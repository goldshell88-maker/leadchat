#!/usr/bin/env bash
# ============================================================================
# Выкатка на прод с этой машины — без реестра образов.
#
# ЗАЧЕМ ОТДЕЛЬНЫЙ СКРИПТ. `deploy/deploy.sh` тянет готовые образы из GHCR,
# которые собирает CI. Реестра пока нет и GitHub не заведён (блок 9.1 ждёт
# решения), поэтому образы собираются прямо на сервере, а исходники туда
# приезжают отсюда. До сих пор это делалось руками — и один раз `rsync
# --delete` снёс docker-compose.override.yml, который существовал только на
# сервере (см. шапку того файла). Скрипт нужен ровно затем, чтобы «руками»
# перестало быть способом выкатки.
#
#   ./ship.sh              — выкатить текущий HEAD
#   ./ship.sh --dry-run    — показать, что поедет, и не трогать сервер
#
# ПОРЯДОК (тот же, что у deploy.sh, 05 §5.3):
#   0. Проверки на этой машине: чистое дерево, фронт и бэкенд — прогоном ЗДЕСЬ,
#      а не надеждой на память («уже прогнаны» однажды означало «не прогнаны»).
#   1. Снимок базы ДО миграций — иначе откатывать будет нечего. Снимок
#      помечен (db_…_deploy.dump): без офсайта, хранятся последние три.
#   2. Синхронизация исходников (без --delete: рантайм на сервере не наш).
#   3. Сборка образов на сервере.
#   4. `alembic upgrade head` — ДО подмены кода (expand-contract).
#   4б. Снимок журналов контейнеров на диск хоста — ПОСЛЕДНИЙ момент, когда
#      они ещё существуют: шаг 5 пересоздаёт контейнеры и стирает их.
#   5. Перезапуск по одному: worker -> scheduler -> api -> nginx, каждый
#      шаг ждёт healthy.
#   6. Smoke снаружи. Провал — откат образов на предыдущие.
#   8. Уборка: висячие образы и кэш сборки — только после зелёной регрессии.
#
# ПРО ОТКАТ. Откатываются ТОЛЬКО образы. Вниз-миграции в проде запрещены
# (05 §5.3): работоспособность старого кода на новой схеме обеспечивает
# правило expand-contract, а не откат схемы.
#
# КАК именно откатываются — важно, потому что раньше не откатывались никак.
# `deploy/rollback.sh` рассчитан на путь через CI: он деплоит предыдущий
# тег-SHA из реестра. Здесь реестра нет, тега нет, и вызов того скрипта был
# заведомо мёртвым (см. шаг 3а). Точка возврата у выкатки без реестра одна:
# пометить работающие образы `…:rollback` ДО сборки и вернуть теги на них.
# ============================================================================
set -uo pipefail

HOST="${SHIP_HOST:-leadchat}"          # алиас из ~/.ssh/config: сам выберет
                                       # прямой путь или переход через Амстердам
REMOTE_DIR="${SHIP_REMOTE_DIR:-/srv/leadchat}"
COMPOSE="docker compose -f ${REMOTE_DIR}/docker-compose.prod.yml -f ${REMOTE_DIR}/docker-compose.override.yml"

# Окружение для скриптов, которые лежат в репозитории и по умолчанию считают,
# что система развёрнута в /opt/leadchat (так задумано для пути через CI). Этот
# сервер стоит в /srv/leadchat, и ночной cron передаёт им путь сам — здесь
# передаём ровно то же. Без этого backup.sh уходит в /opt, не находит каталог и
# честно падает, не сняв снимок.
REMOTE_ENV="DEPLOY_DIR=${REMOTE_DIR} COMPOSE_FILE=${REMOTE_DIR}/docker-compose.prod.yml:${REMOTE_DIR}/docker-compose.override.yml"
HEALTH_URL="${SHIP_HEALTH_URL:-https://188-225-34-82.sslip.io/api/health}"
REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"

DRY=0
[ "${1:-}" = "--dry-run" ] && DRY=1

say()  { printf '\n\033[1m%s\033[0m\n' "$*"; }
ok()   { printf '  \033[32m✓\033[0m %s\n' "$*"; }
die()  { printf '  \033[31m✗ %s\033[0m\n' "$*" >&2; exit 1; }

# Общие ключи ssh для всех вызовов ниже.
#
# ⚠ KEEPALIVE ОБЯЗАТЕЛЕН, И ВОТ ПОЧЕМУ. Путь до Петербурга выбирается сам
# (см. ~/.ssh/config): сначала пробуется прямой, и только если он молчит —
# транзит через Амстердам и дальше по мосту WireGuard на 10.10.0.1. Прямой
# путь пропадает всякий раз, когда сплит-туннель VPN забирает российские
# адреса себе, — то есть обходной путь не редкость, а обычное дело.
#
# А на обходном между командами бывают паузы в минуту и больше: сборка
# образов, `compose up`, ожидание healthy. Без keepalive соединение умирает
# в тишине, и шаг падает не потому, что команда не удалась, а потому, что
# оборвался канал. 29 августа так оборвались три выкатки подряд, одна —
# посреди перезапуска контейнеров.
SSH_OPTS="-o BatchMode=yes -o ConnectTimeout=20 -o ServerAliveInterval=15 -o ServerAliveCountMax=8"

on_server() {
    if [ "$DRY" = "1" ]; then printf '  [dry-run] ssh %s: %s\n' "$HOST" "$1"; return 0; fi
    # shellcheck disable=SC2086 — SSH_OPTS обязан разбиться на отдельные слова.
    ssh $SSH_OPTS "$HOST" "$1"
    rc=$?
    # ⚠ ПОВТОРЯЕМ ТОЛЬКО ОБРЫВ СВЯЗИ, А НЕ ОТКАЗ КОМАНДЫ. 255 — это код самого
    # ssh: не смог соединиться или потерял канал. Любой другой код принадлежит
    # команде на сервере, и повторять её нельзя — мы бы молча пересдавали
    # проваленный шаг, пока он случайно не пройдёт.
    #
    # Повтор безопасен: всё, что здесь выполняется, идемпотентно —
    # `compose up -d`, `alembic upgrade head`, rsync. Обрыв 29 августа как раз
    # и случился ПОСЛЕ того, как команда на сервере отработала: контейнер уже
    # пересоздался, а выкатка об этом не узнала.
    if [ "$rc" = "255" ]; then
        printf '  \033[33m⚠ связь оборвалась, повтор шага\033[0m\n' >&2
        sleep 3
        # shellcheck disable=SC2086
        ssh $SSH_OPTS "$HOST" "$1"
        rc=$?
    fi
    return "$rc"
}

# --- 0. проверки здесь ------------------------------------------------------
say "0. Проверки на этой машине"

cd "$REPO_ROOT" || die "не найден корень репозитория"

# Выкатывать незакоммиченное — верный способ перестать понимать, что работает
# на проде. Разбираться в этом приходится в тот момент, когда что-то сломалось.
[ -n "$(git status --porcelain)" ] && die "рабочее дерево грязное — закоммитьте или спрячьте изменения"
COMMIT="$(git rev-parse --short HEAD)"
ok "выкатываем $COMMIT: $(git log -1 --format=%s | head -c 60)"

ssh -o BatchMode=yes -o ConnectTimeout=20 "$HOST" true 2>/dev/null \
    || die "сервер недоступен. Если это только с этой машины — sudo ./fix-routes.sh"
ok "сервер отвечает"

LOCAL_HEAD="$(ls app/db/migrations/versions/ | sed -n 's/^\([0-9]\{4\}\).*/\1/p' | sort | tail -1)"
REMOTE_HEAD="$(on_server "docker exec leadchat-postgres-1 psql -U leadchat -d leadchat -tAc 'select version_num from alembic_version'" 2>/dev/null | tr -d '[:space:]')"
# КАНАЛЫ В needs_reauth ДО ВЫКАТКИ — для регрессии SM-10 (проверка 24.09).
# Она ищет выкатку, убившую обновление токенов, но падала и на канале,
# выпавшем раньше и по внешней причине, — и откатывала исправный код. Снимок
# снимается здесь, до сборки, и уезжает в smoke.sh (`SMOKE_REAUTH_BEFORE`):
# провал — только на каналах, выпавших после выкатки (deploy/reauth_diff.py).
REAUTH_BEFORE="$(on_server "docker exec leadchat-postgres-1 psql -U leadchat -d leadchat -tAc \"select coalesce(string_agg(id::text, ',' order by id), '') from avito_accounts where status = 'needs_reauth'\"" 2>/dev/null | tr -d '[:space:]')"
if [ "$DRY" = "1" ]; then REMOTE_HEAD="?"; fi
ok "миграции: на сервере ${REMOTE_HEAD:-?}, в репозитории $LOCAL_HEAD"

# --- 0в. проверки фронта ----------------------------------------------------
#
# ⚠ ПОЛОВИНА СИСТЕМЫ ВЫКАТЫВАЛАСЬ БЕЗ ЕДИНОЙ ПРОВЕРКИ (аудит 19.08, L-015).
# Выкатка гоняла серверные наборы и регрессию на проде, а фронт — тот самый,
# который весь день видят тринадцать диспетчеров, — не проверялся ничем: ни
# типами, ни линтером, ни тестами. Обнаружилось это просто: за весь аудит
# фронтовый набор ни разу не запускали, а когда запустили, линтер оказался
# красным. Красное на сервере ловится, красное на экране — нет.
#
# Нет зависимостей — говорим об этом ГРОМКО и продолжаем: `npm ci` посреди
# срочной выкатки хуже, чем честное «эта половина не проверена».
say "0в. Проверки фронта"
if [ ! -d frontend/node_modules ]; then
    printf '  \033[33m! frontend/node_modules нет — типы, линтер и тесты фронта НЕ проверены\033[0m\n'
    printf '  \033[33m  чтобы проверялись: cd frontend && npm ci\033[0m\n'
elif [ "$DRY" = "1" ]; then
    printf '  [dry-run] npm run typecheck / lint / test\n'
else
    # ⚠ ПРИЧИНУ ПОКАЗЫВАЕМ, А НЕ ГЛОТАЕМ (правка 19.08). Первая редакция гнала
    # вывод в /dev/null, и падение читалось как «тесты фронта красные» — без
    # единой строки о том, ЧТО красное. Тот же прогон руками при этом проходил,
    # и разобраться было нечем. Протокол проекта требует обратного: ошибка
    # обязана называть место и причину.
    _fe_log="$(mktemp -t leadchat-front)"
    _fe() {  # $1 — что запускаем, $2 — как называется в отчёте
        if ! ( cd frontend && eval "$1" ) >"$_fe_log" 2>&1; then
            printf '  \033[31m✗ %s — вот последние строки:\033[0m\n' "$2" >&2
            tail -n 25 "$_fe_log" | sed 's/^/    /' >&2
            die "$2 (полный вывод: $_fe_log)"
        fi
        ok "$2"
    }
    _fe "npm run typecheck" "типы"
    _fe "npm run lint" "линтер"
    _fe "npx vitest run src/test" "тесты фронта"
    rm -f "$_fe_log"
fi

# --- 0г. наборы бэкенда -----------------------------------------------------
#
# ⚠ ЗДЕСЬ НЕ ПРОВЕРЯЛОСЬ НИЧЕГО, И ЭТО НЕ ЗАБЫВЧИВОСТЬ, А ДЫРА В ОДНО ЛИЦО.
# Шапка скрипта обещала «зелёные тесты уже прогнаны» — то есть надеялась на
# память человека. Фронт проверяется здесь ровно потому, что такая надежда уже
# однажды не сработала (аудит 19.08, L-015); у бэкенда было то же самое.
#
# ИНТЕГРАЦИОННЫЙ НАБОР ВООБЩЕ НЕ ЗАПУСКАЛСЯ НИКОГДА И НИГДЕ. Он написан
# (266 проверок: доставка, очередь, права, схема) и в `.github/workflows/ci.yml`
# честно вызывается — но у этого репозитория НЕТ УДАЛЁННОГО РЕПОЗИТОРИЯ, то
# есть ни один workflow не выполняется ни разу. Единственный способ его
# запустить — руками, и он требует Docker. Поэтому: есть Docker — гоняем,
# нет — говорим об этом ЖЁЛТЫМ, а не молчим. Пропущенная проверка — это
# непроверенное место, а не пройденное (тот же довод, что у smoke).
say "0г. Наборы бэкенда"
if [ "$DRY" = "1" ]; then
    printf '  [dry-run] pytest tests/unit + gateway/tests + tests/integration\n'
else
    _be_log="$(mktemp -t leadchat-back)"
    _be() {  # $1 — что запускаем, $2 — как называется в отчёте
        if ! eval "$1" >"$_be_log" 2>&1; then
            printf '  \033[31m✗ %s — вот последние строки:\033[0m\n' "$2" >&2
            tail -n 25 "$_be_log" | sed 's/^/    /' >&2
            die "$2 (полный вывод: $_be_log)"
        fi
        ok "$2"
    }
    # ⚠ ЛИНТЕР И ТИПЫ БЭКЕНДА — ТА ЖЕ ДЫРА, ЧТО БЫЛА У ТЕСТОВ (05.09).
    #
    # Фронт здесь проверяется тремя шагами: типы, линтер, тесты. У бэкенда до
    # сегодня был ОДИН — тесты. То есть зелёная выкатка не означала чистый код:
    # `ruff` и `mypy` держались на памяти человека, который запускает их руками.
    # Ровно про такую надежду в шапке этого раздела написано, что она уже
    # однажды не сработала.
    #
    # Цена промаха несимметрична: тесты ловят поведение, а `mypy` —
    # рассогласование типов между слоями, которое в асинхронном коде выстреливает
    # в бою, а не на прогоне. Проверка стоит секунды, поэтому идёт ПЕРЕД
    # тестами: незачем ждать восемь минут прогона, чтобы узнать про опечатку в
    # имени поля.
    _be "uv run ruff check app tests gateway" "линтер бэкенда и шлюза"
    _be "uv run mypy app gateway" "типы бэкенда и шлюза"
    _be "uv run pytest tests/unit -q" "тесты бэкенда"
    # Шлюз внешних API (docs/46) едет на Амстердам своим gateway/deploy.sh,
    # но его код живёт в этом же дереве — сломанный шлюз не должен доехать
    # даже до `git commit`.
    _be "uv run pytest gateway/tests -q" "тесты шлюза"
    if docker info >/dev/null 2>&1; then
        # CI=1 — не украшение: с ним набор ОТКАЗЫВАЕТСЯ пропускаться молча
        # (правило живёт в tests/integration/conftest.py). Закрывает щель
        # между нашей проверкой Docker и самим прогоном: пропади демон в
        # эту секунду — увидим отказ, а не зелёный шаг без единой проверки.
        _be "CI=1 uv run pytest tests/integration -q" "интеграционные тесты"
    else
        printf '  \033[33m! Docker не запущен — интеграционный набор НЕ проверен\033[0m\n'
        printf '  \033[33m  чтобы проверялся: запустите Docker Desktop и повторите\033[0m\n'
    fi
    rm -f "$_be_log"
fi

# --- 0б. секреты на сервере -------------------------------------------------
#
# ЧТО ЗДЕСЬ ПРОВЕРЯЕТСЯ И ПОЧЕМУ ИМЕННО ЗДЕСЬ.
#
# MEDIA_SIGN_KEY подписывает ссылки на вложения. Раздача файлов идёт БЕЗ входа
# по паролю — пропуском служит подпись. Значит известный ключ равносилен
# открытому доступу: любой человек с адресом скачает переписку клиентов.
#
# А в образце окружения репозитория на этом месте лежит строка CHANGE_ME. То
# есть путь, которым прод получает заглушку, — не небрежность, а поведение по
# умолчанию: скопировал образец, заполнил половину полей, выкатил. Подстановка
# в docker-compose (`${MEDIA_SIGN_KEY:?…}`) ловит только пустое и незаданное;
# непустую заглушку она пропускает насквозь.
#
# Проверка стоит ДО снимка базы: падение здесь не стоит ничего, а после снимка
# и rsync это уже не гейт, а уборка последствий.
#
# ЗНАЧЕНИЕ КЛЮЧА НИКОГДА НЕ ПЕЧАТАЕТСЯ — ни в успехе, ни в ошибке. Секрет,
# уехавший в терминал, уезжает и в историю оболочки.
#
# Проверяем ИМЕНОВАННЫЙ список, а не слепой grep по всему .env: AVITO_CLIENT_ID
# и AVITO_CLIENT_SECRET на этом сервере законно стоят заглушками — боевые ключи
# Авито ещё не выданы, канал работает на имитаторе (docs/22). Слепой grep
# заблокировал бы выкатку из-за состояния, которое сегодня в порядке вещей.
say "0б. Секреты на сервере"
# GATEWAY_TOKEN (16.09): без него все помощники адреса и ответы ботов молчат —
# шлюз Амстердама отвечает 401 (docs/46).
REQUIRED_SECRETS="MEDIA_SIGN_KEY TOKEN_ENC_KEY JWT_SECRET GATEWAY_TOKEN"
if [ "$DRY" = "1" ]; then
    printf '  [dry-run] пропущено: проверка секретов в %s/.env\n' "$REMOTE_DIR"
else
    for NAME in $REQUIRED_SECRETS; do
        # Три исхода различаются намеренно. Молчаливое «проверка прошла» при
        # недоступном файле — это сторож, который зеленеет, ничего не увидев;
        # такой хуже отсутствующего.
        VERDICT="$(ssh -o BatchMode=yes -o ConnectTimeout=20 "$HOST" \
            "if [ ! -r ${REMOTE_DIR}/.env ]; then echo NOFILE; else
                 V=\$(grep -m1 \"^${NAME}=\" ${REMOTE_DIR}/.env | cut -d= -f2- | tr -d '\\\"' | tr -d \"'\" | xargs);
                 if [ -z \"\$V\" ]; then echo EMPTY;
                 elif echo \"\$V\" | grep -qiE '^(CHANGE_ME|changeme|dev-.*|test-.*|devOnly.*|ciOnly.*)\$'; then echo PLACEHOLDER;
                 else echo OK; fi
             fi" 2>&1)"
        case "$VERDICT" in
            OK)          ok "${NAME}: задан" ;;
            EMPTY)       die "${NAME} в ${REMOTE_DIR}/.env пуст. Задайте настоящий: openssl rand -hex 32" ;;
            PLACEHOLDER) die "${NAME} в ${REMOTE_DIR}/.env — строка-заглушка из репозитория. Её значение известно всем, у кого есть доступ к коду. Задайте настоящий: openssl rand -hex 32" ;;
            NOFILE)      die "не читается ${REMOTE_DIR}/.env — проверить секреты нечем, выкатка остановлена" ;;
            *)           die "не удалось проверить ${NAME}: ${VERDICT}" ;;
        esac
    done
fi

# --- 0д. расписание cron -----------------------------------------------------
say "0д. Расписание cron на сервере"
# ⚠ ВЫКАТКА CRONTAB НЕ СТАВИТ — И ОБЯЗАНА СКАЗАТЬ, ЕСЛИ ОН РАЗОШЁЛСЯ (24.09).
# Строку снимка журналов добавили в репозиторий 08.09, на сервер её не поставил
# никто, и около двух суток журналов api и nginx пропали вместе с кольцевым
# буфером. Ставить молча нельзя — это настройка сервера, а не код; поэтому
# предупреждение, а не остановка. Сверяются теги «# leadchat-*» рабочих строк.
if [ "$DRY" = "1" ]; then
    printf '  [dry-run] пропущено: сверка crontab\n'
else
    WANT_CRON="$(grep -v '^[[:space:]]*#' deploy/crontab.leadchat | grep -o '# leadchat-[a-z-]*' | sort -u)"
    HAVE_CRON="$(ssh -o BatchMode=yes -o ConnectTimeout=20 "$HOST" 'crontab -l 2>/dev/null' \
        | grep -v '^[[:space:]]*#' | grep -o '# leadchat-[a-z-]*' | sort -u || true)"
    MISSING_CRON="$(comm -23 <(printf '%s\n' "$WANT_CRON") <(printf '%s\n' "$HAVE_CRON") \
        | sed 's/^# //' | tr '\n' ' ')"
    if [ -n "${MISSING_CRON// /}" ]; then
        printf '  \033[33m! в crontab сервера нет строк: %s\033[0m\n' "$MISSING_CRON"
        printf '  \033[33m  поставить на сервере: crontab %s/deploy/crontab.leadchat\033[0m\n' "$REMOTE_DIR"
    else
        ok "crontab сервера совпадает с deploy/crontab.leadchat"
    fi
fi

# --- 1. снимок базы ---------------------------------------------------------
say "1. Снимок базы до миграций"
# BACKUP_LABEL=deploy: снимок остаётся на хосте (без офсайта) и хранится в
# числе последних трёх — иначе каждая выкатка лежала бы 14 суток, как ночная
# копия (12.09: 165 снимков, 10 ГБ, диск 83 %).
on_server "${REMOTE_ENV} BACKUP_LABEL=deploy bash ${REMOTE_DIR}/deploy/backup.sh" && ok "снимок снят" \
    || die "снимок не снят — дальше нельзя: откатывать будет нечего"

# --- 2. исходники -----------------------------------------------------------
say "2. Исходники на сервер"
#
# ЕДЕТ РОВНО ТО, ЧТО ЗАКОММИЧЕНО. Список берём у git, а не обходим каталог.
# Причины две, и обе не теоретические:
#
#   * рядом лежит 8 ГБ сборочного мусора Rust (desktop/src-tauri/target). Он в
#     .gitignore, но обход каталога о .gitignore не знает — писать руками
#     список исключений значит однажды его не дописать;
#   * «что закоммичено» — единственный ответ на вопрос «что сейчас на проде»,
#     который можно проверить через полгода. Отсюда же отказ на грязном дереве
#     выше: два конца одного правила.
#
# БЕЗ --delete. На сервере лежит то, чего в репозитории нет и быть не должно:
# .env с секретами, сертификаты, снимки базы. Один раз --delete уже снёс
# docker-compose.override.yml, и прод поднялся на образах из несуществующего
# реестра.
FILES_COUNT="$(git ls-files | wc -l | tr -d ' ')"
RSYNC_ARGS=(-az --files-from=- --from0 -e "ssh -o BatchMode=yes -o ConnectTimeout=20" --timeout=120)
if [ "$DRY" = "1" ]; then
    printf '  поедет файлов: %s (только отслеживаемые git)\n' "$FILES_COUNT"
    git ls-files -z | rsync "${RSYNC_ARGS[@]}" --dry-run --stats ./ "${HOST}:${REMOTE_DIR}/" 2>&1 | tail -6
else
    git ls-files -z | rsync "${RSYNC_ARGS[@]}" ./ "${HOST}:${REMOTE_DIR}/" \
        || die "не удалось скопировать исходники"
    ok "синхронизировано файлов: ${FILES_COUNT}"
fi

# --- 2б. УДАЛЁННОЕ В РЕПОЗИТОРИИ УДАЛЯЕТСЯ И НА СЕРВЕРЕ ----------------------
#
# ЗАЧЕМ, ЕСЛИ ВЫШЕ НАПИСАНО «БЕЗ --delete». Оба правила верны и не спорят.
# Общий --delete снёс бы .env, сертификаты и docker-compose.override.yml —
# это уже случалось. Но и обратная крайность стоила выкатки: 11 августа из
# репозитория убрали разгрузку очереди, файл `UnloadQueueDialog.tsx` остался
# лежать на сервере, компилятор увидел его импорты к удалённым хукам и уронил
# сборку фронта. Локально всё зелёное, на сервере — красное, и причина не в
# коде вовсе.
#
# Поэтому удаляем ТОЧЕЧНО: только внутри каталогов, которые целиком
# принадлежат репозиторию, и только те файлы, которых нет в списке git.
# Рантайм живёт в корне (.env, docker-compose.override.yml) и в своих
# каталогах (media, backups) — сюда не попадает ни один из них.
OWNED_DIRS=(app frontend/src docker deploy tests docs alembic)
# ⚠ `-z`, А НЕ ПРОСТОЙ `ls-files` (поймано выкаткой 12 августа).
#
# `git ls-files` по умолчанию ЭКРАНИРУЕТ не-ASCII имена: `docs/43-ОДИН-ЧАТ.md`
# печатается как `"docs/43-\320\236\320\224..."`. Такая строка не совпадает
# ни с чем из `find`, и файл с русским именем попадал в список «нет в
# репозитории» — то есть выкатка МОЛЧА УДАЛЯЛА его с сервера. В тот раз это
# были два документа, но `OWNED_DIRS` включает `app`, `tests` и `deploy`:
# первый же файл с русским именем в коде уехал бы с прода тем же путём.
#
# `-z` отдаёт имена как есть, разделяя нулём, — экранирования нет вовсе.
TRACKED_LIST="$(git ls-files -z | tr '\0' '|')"
# Поиск идёт ПО-НАСТОЯЩЕМУ даже вхолостую: он только читает, а холостой прогон
# обязан честно показывать, что именно будет удалено. Через on_server нельзя —
# та вхолостую печатает команду вместо выполнения, и печать попала бы в список
# «лишних файлов» (поймано на первом же прогоне).
STALE="$(ssh -o BatchMode=yes -o ConnectTimeout=20 "$HOST" \
    "cd ${REMOTE_DIR} && find ${OWNED_DIRS[*]} -type f 2>/dev/null" || true)"
DROP=""
while IFS= read -r f; do
    [ -z "$f" ] && continue
    case "|${TRACKED_LIST}" in *"|${f}|"*) continue ;; esac
    DROP="${DROP}${f}"$'\n'
done <<< "$STALE"
DROP="$(printf '%s' "$DROP" | grep -vE '(^|/)__pycache__/|\.pyc$' || true)"
if [ -n "$DROP" ]; then
    DROP_COUNT="$(printf '%s\n' "$DROP" | wc -l | tr -d ' ')"
    printf '%s\n' "$DROP" | sed 's/^/    − /' | head -20
    if [ "$DRY" = "1" ]; then
        printf '  [dry-run] удалить на сервере: %s файл(ов)\n' "$DROP_COUNT"
    else
        # Список едет СТАНДАРТНЫМ ВВОДОМ, а не внутри строки команды: имена
        # файлов с пробелами и кавычками в собранной строке разъехались бы, а
        # ошибка здесь означает `rm -f` не по тому пути.
        printf '%s\n' "$DROP" \
            | ssh -o BatchMode=yes -o ConnectTimeout=20 "$HOST" \
                "cd ${REMOTE_DIR} && xargs -r -d '\n' rm -f --" \
            || die "не удалось убрать файлы, удалённые из репозитория"
        ok "убрано файлов, которых больше нет в репозитории: ${DROP_COUNT}"
    fi
else
    ok "лишних файлов на сервере нет"
fi

# --- 3. сборка --------------------------------------------------------------
say "3. Сборка образов на сервере"

# ВСЕ образы, которые собираются локально, а не берутся из реестра.
#
# Здесь собирались ровно два — api и web, — и это стоило владельцу дня работы.
# Имитатор Авито (`fake-avito`) на любые ключи отдавал один и тот же выдуманный
# аккаунт; в репозитории это починили, выкатка прошла зелёной, контейнер
# перезапустился — но ИЗ СТАРОГО ОБРАЗА, потому что его никто не пересобирал.
# Снаружи всё выглядело исправным, а владелец писал «ничего не привязывается».
#
# Формат элемента: <тег>|<аргументы docker build>.
# ⚠ ВЕРСИЯ ОБЯЗАНА ПОПАСТЬ В БАНДЛ ВЕБА (аудит 22.08). Без --build-arg vite
# инлайнит умолчание «dev» из Dockerfile.web, а isStaleTab() на заглушке молчит
# по построению (frontend/src/platform/buildVersion.ts). То есть предупреждение
# «вкладка работает на старой сборке» было написано, покрыто тестом и выключено
# одной недостающей строкой ЗДЕСЬ. Цена не косметическая: /assets/ отдаётся с
# immutable и try_files =404, после выкатки старые чанки исчезают с сервера, и
# вкладка, открытая до неё, ломается на первом переходе в ленивый раздел.
# Передаём тот же COMMIT, что уходит в APP_VERSION контейнеров, — иначе номера
# разойдутся и баннер начнёт врать в другую сторону.
BUILD_IMAGES=(
    "local/leadchat-api:prod|-f docker/Dockerfile.api ."
    "local/leadchat-web:prod|--build-arg VITE_APP_VERSION=${COMMIT} -f docker/Dockerfile.web ."
    "local/fake-avito:prod|./fake_avito"
)

# Страж от повторения той же ошибки: если в compose появится образ local/…,
# которого нет в списке выше, выкатка обязана упасть ЗДЕСЬ — до перезапуска.
# Иначе система поднимется на образе, которого никто не собирал, и расхождение
# с репозиторием опять будет невидимым.
DECLARED="$(on_server "cd ${REMOTE_DIR} && ${COMPOSE} config" 2>/dev/null \
    | tr -d '\r' | sed -n 's/^ *image: *\(local\/[^ ]*\)$/\1/p' | sort -u)"
for img in ${DECLARED}; do
    known=0
    for entry in "${BUILD_IMAGES[@]}"; do
        [ "${entry%%|*}" = "${img}" ] && known=1
    done
    [ "${known}" = "1" ] \
        || die "образ ${img} объявлен в compose, но выкатка его не собирает — допишите в BUILD_IMAGES"
done

# --- 3а. ТОЧКА ВОЗВРАТА: помечаем то, что работает СЕЙЧАС --------------------
#
# ЧЕГО НЕ БЫЛО И ЧЕМ ЭТО ГРОЗИЛО. Ниже, на красном smoke, выкатка звала
# `deploy/rollback.sh` — а тот тонкая обёртка над `deploy.sh`, который ТЯНЕТ
# ОБРАЗЫ ИЗ РЕЕСТРА. Реестра у этого сервера нет вовсе: образы собираются
# прямо на нём (см. docker-compose.override.yml), тега-SHA не существует, файла
# `.state/previous_tag` тоже. То есть автооткат не «иногда не срабатывал» — он
# не мог сработать ни разу. Первая же красная выкатка оставляла прод лежать со
# свежесобранным сломанным кодом, а в терминале печаталось «откат тоже не
# прошёл — нужен человек на сервере».
#
# Откатывать здесь по-настоящему можно только на предыдущие ОБРАЗЫ, и
# существуют они ровно до следующей строки: `docker build -t …:prod`
# переставляет тег на новый слой, и старый остаётся безымянным. Поэтому метку
# ставим ДО сборки — это и есть вся точка возврата.
#
# Первая выкатка после этой правки метки не найдёт (её не с чего было
# поставить) — откат честно скажет об этом и позовёт человека, вместо того
# чтобы делать вид, что откатился.
say "3а. Метка отката на текущие образы"
for entry in "${BUILD_IMAGES[@]}"; do
    tag="${entry%%|*}"
    on_server "docker image inspect ${tag} >/dev/null 2>&1 && docker tag ${tag} ${tag%:*}:rollback || true" \
        || die "не удалось пометить ${tag} — без точки возврата выкатка не начинается"
done
# Версия, которая работает СЕЙЧАС, — она же версия образов :rollback. Нужна
# откату: без неё compose поднимал контейнеры с APP_VERSION по умолчанию
# («prod»), /api/health отвечал словом вместо номера, и полоса «Вышло
# обновление» у всех горела вечно — перезагрузка приносила то же слово (30.08).
PREV_VERSION="$(curl -skm 10 "$HEALTH_URL" | sed -n 's/.*"version":"\([^"]*\)".*/\1/p')"
ok "точка возврата: ${BUILD_IMAGES[*]%%|*} → :rollback (версия ${PREV_VERSION:-неизвестна})"

# Возврат на помеченные образы. Возвращает 0, только если откат СОСТОЯЛСЯ:
# «откатились» без образов — это то же самое враньё, что и раньше.
rollback_images() {
    local entry tag base missing=""
    for entry in "${BUILD_IMAGES[@]}"; do
        tag="${entry%%|*}"; base="${tag%:*}"
        ssh -n -o BatchMode=yes -o ConnectTimeout=20 "$HOST" \
            "docker image inspect ${base}:rollback >/dev/null 2>&1" \
            || missing="${missing} ${base}:rollback"
    done
    if [ -n "$missing" ]; then
        printf '  \033[31mоткатывать не на что: нет образов%s\033[0m\n' "$missing" >&2
        return 1
    fi
    for entry in "${BUILD_IMAGES[@]}"; do
        tag="${entry%%|*}"; base="${tag%:*}"
        on_server "docker tag ${base}:rollback ${tag}" || return 1
    done
    # --force-recreate: тег переставлен на прежний слой, и контейнер обязан
    # подняться заново. Без него compose может счесть, что менять нечего, —
    # и «откат» оставит работать ровно тот код, из-за которого он и случился.
    # APP_VERSION обязана быть и здесь: откат без неё поднимал контейнеры со
    # словом «prod» вместо номера — и вешал всем вечную полосу обновления.
    on_server "cd ${REMOTE_DIR} && APP_VERSION=${PREV_VERSION:-prod} ${COMPOSE} up -d --no-deps --force-recreate worker scheduler api nginx ${EXTRA_SVCS:-}" \
        || return 1
    return 0
}

for entry in "${BUILD_IMAGES[@]}"; do
    tag="${entry%%|*}"
    on_server "cd ${REMOTE_DIR} && docker build -q -t ${tag} ${entry#*|}" >/dev/null \
        || die "не собрался образ ${tag} — прод не тронут"
done
ok "образы собраны: ${BUILD_IMAGES[*]%%|*}"

# --- 4. миграции ------------------------------------------------------------
say "4. Миграции"
on_server "cd ${REMOTE_DIR} && ${COMPOSE} run --rm api alembic upgrade head" \
    && ok "схема на head" || die "миграции не прошли — код не подменяли, прод работает на прежнем"

# --- 4б. журналы ДО пересоздания --------------------------------------------
say "4б. Снимок журналов контейнеров"
#
# ⚠ ПОСЛЕДНИЙ МОМЕНТ, КОГДА ЖУРНАЛ ЕЩЁ СУЩЕСТВУЕТ. Шаг 5 пересоздаёт
# контейнеры, docker удаляет каталог журнала вместе со старым контейнером —
# и после инцидента смотреть будет нечего. Разбор «почему поехала вёрстка» и
# разбор пропажи реплик бота уже упирались ровно в это.
#
# ⚠ ЭТОТ ШАГ НЕ ИМЕЕТ ПРАВА ОСТАНОВИТЬ ВЫКАТКУ. Не сняли журнал — плохо, но
# оставлять прод на старом коде из-за этого нельзя, поэтому здесь нет `die`.
# Зато и молчания нет: строки скрипта печатаются как есть, а «!!» в них
# превращается в жёлтое предупреждение — иначе тихий отказ снова обнаружился
# бы в тот единственный день, когда журнал понадобится.
if [ "$DRY" = "1" ]; then
    printf '  [dry-run] ssh %s: bash %s/deploy/archive-logs.sh\n' "$HOST" "$REMOTE_DIR"
else
    LOG_OUT="$(on_server "${REMOTE_ENV} bash ${REMOTE_DIR}/deploy/archive-logs.sh" 2>&1)"
    LOG_RC=$?
    [ -n "$LOG_OUT" ] && printf '%s\n' "$LOG_OUT" | sed 's/^/  /'
    # Три признака провала, а не один. Код возврата ловит обрыв канала (ssh 255),
    # пустой ответ — его же в том случае, когда ssh промолчал совсем, «!!» —
    # отказ самого скрипта. Проверка только по «!!» уже отвечала «журналы сняты»
    # на оборванной связи, не получив от сервера ни строки: зелёная строка при
    # несделанной работе вреднее её отсутствия.
    if [ "$LOG_RC" -ne 0 ] || [ -z "$LOG_OUT" ] || printf '%s' "$LOG_OUT" | grep -q '!!'; then
        printf '  \033[33m⚠ журналы сняты не полностью — выкатка продолжается\033[0m\n' >&2
    else
        ok "журналы сняты в /var/leadchat/logs"
    fi
fi

# --- 5. перезапуск ----------------------------------------------------------
say "5. Перезапуск по одному"
# ВСЕ сервисы, а не только четыре главных. Перечисление «worker scheduler api
# nginx» молча пропускало остальных: правка их описания в compose уезжала на
# сервер и там лежала без дела до ручного вмешательства. Поймано на имитаторе
# Авито — ему добавили сеть, выкатка прошла зелёной, а страница согласия
# продолжала отвечать 502, потому что контейнер никто не пересоздал.
#
# Порядок сохранён: сначала фоновые, потом api, потом nginx — он последний,
# чтобы наружу не открылся вход в ещё не готовую систему. Всё, чего нет в
# списке, поднимается перед ними: это вспомогательные сервисы, и ждать их
# отдельно незачем.
# ⚠ В ПРОБНОМ РЕЖИМЕ СПИСОК НЕ СПРАШИВАЕМ. `on_server` при `--dry-run` печатает
# команду вместо выполнения, и эта печать попадала В ПЕРЕМЕННУЮ: список
# «вспомогательных сервисов» превращался в строку «[dry-run] ssh leadchat: cd …»,
# после чего условие ниже срабатывало и скрипт бодро сообщал, что перезапустил
# сервис с таким именем. Пробный прогон, который в одном месте печатает
# бессмыслицу, стоит доверия меньше, чем нужно, — а смотрят на него именно затем,
# чтобы решиться на боевой.
if [ "$DRY" = "1" ]; then
    EXTRA_SVCS=""
    printf '  [dry-run] список вспомогательных сервисов спрашивается на сервере\n'
else
    EXTRA_SVCS="$(on_server "cd ${REMOTE_DIR} && ${COMPOSE} config --services" 2>/dev/null \
        | tr -d '\r' | grep -vxE 'worker|scheduler|api|nginx|postgres|redis|certbot' | tr '\n' ' ')"
fi
if [ -n "${EXTRA_SVCS// /}" ]; then
    on_server "cd ${REMOTE_DIR} && ${COMPOSE} up -d --no-deps ${EXTRA_SVCS}" \
        || die "не перезапустились вспомогательные сервисы: ${EXTRA_SVCS}"
    ok "вспомогательные: ${EXTRA_SVCS}"
fi

for svc in worker scheduler api nginx; do
    # APP_VERSION — коммит, который выкатываем: с ним `/api/health` начинает
    # говорить правду о том, ЧТО отвечает снаружи, и SM-1 ниже это сверяет.
    on_server "cd ${REMOTE_DIR} && APP_VERSION=${COMMIT} ${COMPOSE} up -d --no-deps ${svc}" \
        || die "не перезапустился: ${svc}"
    if [ "$DRY" = "1" ]; then
        # В пробном режиме ждать нечего: `on_server` ничего не выполняет, и
        # цикл ниже крутил бы двадцать четыре пятисекундных паузы на каждый
        # сервис — восемь минут «проверки», за которые ничего не проверяется.
        printf '  [dry-run] дальше ожидание healthy\n'
        continue
    fi
    # Ждём healthy, а не «поднялся»: контейнер стартует раньше, чем начинает
    # отвечать, и следующий сервис пошёл бы к ещё не готовому соседу.
    state=""
    for _ in $(seq 1 24); do
        # shellcheck disable=SC2086 — SSH_OPTS обязан разбиться на слова.
        # Пустой ответ здесь не беда: это просто ещё один заход цикла, а
        # обрыв на опросе не должен ронять выкатку — контейнер поднимается
        # своим ходом и без нашего наблюдения.
        state="$(ssh -n $SSH_OPTS "$HOST" "docker inspect --format '{{.State.Health.Status}}' leadchat-${svc}-1 2>/dev/null || echo none" | tr -d '[:space:]')"
        [ "$state" = "healthy" ] && break
        [ "$state" = "none" ] && break   # у сервиса нет healthcheck — не ждём
        sleep 5
    done
    [ "$state" = "healthy" ] || [ "$state" = "none" ] \
        || die "${svc} не стал healthy за две минуты (последнее состояние: ${state:-нет ответа})"
    ok "${svc}: ${state}"
done

# --- 6. проверка снаружи ----------------------------------------------------
say "6. Проверка снаружи"
if [ "$DRY" = "1" ]; then
    printf '  [dry-run] smoke против %s\n' "$HEALTH_URL"
    exit 0
fi

# Ходим НЕ с этой машины: маршрут до Петербурга отсюда бывает мёртв (см.
# fix-routes.sh), и «сервер не отвечает» означало бы проблему у нас, а не на
# проде. Проверяем оттуда, откуда ходят пользователи.
HEALTH="$(on_server "curl -sS --max-time 15 ${HEALTH_URL}" 2>&1)"
case "$HEALTH" in
    *'"status":"ok"'*) ok "health: $HEALTH" ;;
    *)
        printf '  \033[31m✗ health не ok: %s\033[0m\n' "$HEALTH" >&2
        say "ОТКАТ образов на помеченные перед выкаткой"
        rollback_images \
            && printf '  откат выполнен. ВНИМАНИЕ: схема осталась новой (вниз-миграции запрещены)\n' \
            || printf '  \033[31mоткат тоже не прошёл — нужен человек на сервере\033[0m\n'
        exit 1
        ;;
esac

# --- 7. регрессия -----------------------------------------------------------
#
# ВЫКАТКА ЕЁ НЕ ГОНЯЛА ВООБЩЕ. Здесь заканчивался скрипт: пинг `/api/health`
# — и «готово». А health отвечает «ok», пока живы процесс, база и Redis; он
# ничего не знает ни про вход в систему, ни про то, разбирает ли воркер
# очередь, ни про то, отдаётся ли статика. Набор проверок для этого написан
# (deploy/smoke.sh, SM-1…SM-10) и лежал в репозитории неиспользованным.
#
# Запускаем С СЕРВЕРА по той же причине, что и health: маршрут до Петербурга
# с рабочей машины бывает мёртв, и «регрессия не прошла» означало бы беду у
# нас, а не на проде.
#
# ПРОПУСКИ НЕ МОЛЧАТ. Половина набора требует служебной учётки, которой на
# сервере нет, — и её проверки помечаются SKIP. Строка «5 pass, 0 fail,
# 5 skip» выглядит зелёной, и именно так это и осталось незамеченным. Теперь
# число пропусков печатается отдельной жёлтой строкой: пропущенная проверка —
# это непроверенное место, а не пройденное.
say "7. Регрессия на проде"
# УЧЁТКА ДЛЯ ПРОВЕРОК БЕРЁТСЯ ИЗ .env СЕРВЕРА — САМ smoke.sh ЕГО НЕ ЧИТАЕТ.
#
# 11 августа выяснилось, что совет «задайте SMOKE_EMAIL и SMOKE_PASSWORD в .env»
# не сработал бы: `bash deploy/smoke.sh` по ssh стартует с пустым окружением, а
# скрипт читает переменные и только. То есть учётку можно было завести, вписать
# всё правильно — и по-прежнему получать пять SKIP, не понимая почему.
# Подставляем .env явно; grep по именам, чтобы в окружение не уехало лишнее.
SMOKE_ENV='set -a; eval "$(grep -E "^SMOKE_[A-Z_]+=" .env 2>/dev/null || true)"; set +a;'
# ⚠ СТРОГИЙ РЕЖИМ И СВЕРКА ВЕРСИИ (аудит 19.08, находка L-011).
#
# Было: `bash deploy/smoke.sh` без флагов. Пропущенная проверка (SKIP) не
# роняла выкатку, а без EXPECTED_VERSION проверка SM-1 не сверяла НИЧЕГО —
# наружу мог отвечать старый контейнер, и выкатка всё равно объявляла успех.
#
# Стало: версию передаём всегда — она бесплатна и ловит самый дорогой случай.
# Строгий режим включаем, только если на сервере заданы учётки проверок:
# иначе выкатка падала бы на пяти SKIP, которых человек не может закрыть
# прямо сейчас, и правка гейта стала бы капканом вместо страховки. Нет
# учёток — говорим об этом громко и продолжаем, как раньше.
if on_server "grep -q '^SMOKE_EMAIL=.' ${REMOTE_DIR}/.env" 2>/dev/null; then
    SMOKE_STRICT="--strict"
    ok "регрессия пойдёт в строгом режиме: пропуск = провал"
else
    SMOKE_STRICT=""
    printf '  \033[33m! учётки проверок (SMOKE_EMAIL/SMOKE_PASSWORD) не заданы:\033[0m\n'
    printf '  \033[33m  вход, список диалогов и отправка при выкатке НЕ проверяются\033[0m\n'
fi
# ⚠⚠ ВЕРСИЮ СПРАШИВАЕМ, ТОЛЬКО ЕСЛИ СЕРВЕР УМЕЕТ ЕЁ НАЗЫВАТЬ (правка 19.08).
#
# ЧТО СЛУЧИЛОСЬ. Сверку версии выкатили раньше, чем то, что её питает: на диске
# у владельца `ship.sh` уже требовал версию, а на сервер уезжают только
# ЗАКОММИЧЕННЫЕ файлы, и там лежал прежний `docker-compose.override.yml` — без
# передачи APP_VERSION в контейнеры. Здоровье честно ответило старое `prod`,
# SM-1 сказал «снаружи старый контейнер», и выкатка ОТКАТИЛА совершенно
# исправный образ. Проверка сработала правильно по букве и навредила по делу.
#
# ПОЧЕМУ ЭТО НЕ РАЗОВЫЙ СЛУЧАЙ. Та же ловушка ждёт любого, кто выкатит СТАРЫЙ
# коммит: у него в compose ещё нет APP_VERSION, а скрипт на диске новый.
# Поэтому спрашиваем не «умеет ли скрипт», а «умеет ли ТО, ЧТО ТОЛЬКО ЧТО
# УЕХАЛО на сервер»: строки APP_VERSION в синхронизированном compose.
if on_server "grep -q 'APP_VERSION' ${REMOTE_DIR}/docker-compose.override.yml" 2>/dev/null; then
    SMOKE_VERSION="EXPECTED_VERSION=${COMMIT}"
else
    SMOKE_VERSION=""
    printf '  \033[33m! выкачен код без передачи APP_VERSION — версия снаружи не сверяется\033[0m\n'
    printf '  \033[33m  (так и должно быть при выкатке коммита старее 19.08)\033[0m\n'
fi
SMOKE_OUT="$(on_server "cd ${REMOTE_DIR} && ${SMOKE_ENV} ${SMOKE_VERSION} SMOKE_REAUTH_BEFORE='${REAUTH_BEFORE}' bash deploy/smoke.sh ${SMOKE_STRICT}" 2>&1)"
SMOKE_CODE=$?
printf '%s\n' "$SMOKE_OUT" | sed -n 's/^  /    /p'
if [ "$SMOKE_CODE" != "0" ]; then
    printf '  \033[31m✗ регрессия не прошла — образы откатываются\033[0m\n' >&2
    rollback_images \
        && printf '  откат выполнен. ВНИМАНИЕ: схема осталась новой (вниз-миграции запрещены)\n' \
        || printf '  \033[31mоткат тоже не прошёл — нужен человек на сервере\033[0m\n'
    exit 1
fi
SKIPPED_N="$(printf '%s' "$SMOKE_OUT" | sed -n 's/.*\([0-9][0-9]*\) skip.*/\1/p' | tail -1)"
if [ -n "${SKIPPED_N:-}" ] && [ "$SKIPPED_N" != "0" ]; then
    printf '  \033[33m! пропущено проверок: %s — это НЕПРОВЕРЕННЫЕ места, а не пройденные\033[0m\n' \
        "$SKIPPED_N"
else
    ok "регрессия: пропусков нет"
fi

# --- 8. уборка --------------------------------------------------------------
# ЗАЧЕМ. Каждая выкатка оставляет прежние образы без тега (кроме `:rollback`)
# и слой кэша сборки; ни то, ни другое само не уходит. 12.09: 166 висячих
# образов на 18 ГБ и 28 ГБ кэша — диск боя 83 %. Убираем ТОЛЬКО после
# зелёной регрессии: до неё старые образы — точка отката. Помеченные
# `:rollback` образы висячими не считаются и остаются; кэш режем до 4 ГБ
# самых свежих слоёв, чтобы следующая сборка не шла с нуля.
say "8. Уборка на сервере"
on_server "sudo docker image prune -f >/dev/null && sudo docker buildx prune -af --reserved-space 4GB >/dev/null" \
    && ok "висячие образы убраны, кэш сборки ужат до 4 ГБ" \
    || printf '  \033[33m! уборка не прошла — на выкатку не влияет, диск смотреть руками\033[0m\n'

say "Готово: на проде $COMMIT"
