#!/usr/bin/env bash
# ============================================================================
# LeadChat — внешний наблюдатель (план 5.2, 14 §6).
#
# ЖИВЁТ НЕ НА ПРОДЕ. Ставится на нидерландский сервер и раз в минуту смотрит
# на петербургский снаружи.
#
#   */1 * * * * /srv/leadchat-watchdog/watchdog-offsite.sh >> /var/log/leadchat-watchdog.log 2>&1
#
# ЗАЧЕМ. Всё, что система знает о себе, она знает изнутри — и ровно поэтому не
# может заметить собственную смерть. Сторож в приложении (14 §6) видит
# молчащий вебхук, вставший планировщик и переполненную очередь, но если
# упал весь сервер, докладывать о падении некому и нечем.
#
# ЧЕСТНО О ПРЕДЕЛАХ (это главное в файле)
# ---------------------------------------
# Наблюдатель НЕ РАЗБУДИТ никого ночью. Уведомление он кладёт в центр
# уведомлений, а центр живёт на том самом сервере, который лежит: пока прод
# мёртв, доставить сообщение физически некуда. Чтобы кого-то будить, нужен
# внешний канал — почта или мессенджер, — а от них заказчик отказался
# сознательно (14 §1). Поэтому наблюдатель делает две вещи, которые РЕАЛЬНО
# работают без внешнего канала:
#
#   1. ЗАПИСЫВАЕТ ПРОСТОЙ и докладывает о нём, КОГДА СИСТЕМА ВЕРНУЛАСЬ.
#      Утром администратор видит в центре: «система была недоступна 14 минут,
#      с 03:12 до 03:26». Без этого ночная авария не оставляет вообще никакого
#      следа: логи внутри упавшей машины никто не читает, а к утру всё уже
#      работает и выглядит так, будто ничего не было.
#
#   2. ЛОВИТ ЧАСТИЧНЫЕ ОТКАЗЫ СРАЗУ. Сервер жив, отвечает, но планировщик
#      умер, или nginx отдаёт 502, или сертификат протух. Такие поводы
#      доставляются немедленно — адресат-то на месте. А заметить их изнутри
#      нельзя как раз потому, что умерло то, что должно было заметить.
#
# Иными словами: он превращает «ничего не знаем» в «знаем и записали».
# Полноценное «разбудить человека» остаётся отдельным решением заказчика.
#
# Связь идёт по приватному мосту WireGuard (10.10.0.1), а не через публичный
# адрес: служебная ручка наружу закрыта, и открывать её в интернет ради
# наблюдателя означало бы завести мишень ровно там, где принимают токен.
# ============================================================================
set -euo pipefail

PROD_URL="${PROD_URL:-https://188-225-34-82.sslip.io}"
NOTIFY_URL="${NOTIFY_URL:-http://10.10.0.1/api/v1/internal/notify}"
TOKEN_FILE="${TOKEN_FILE:-/srv/leadchat-watchdog/token}"
STATE_FILE="${STATE_FILE:-/var/lib/leadchat-watchdog/state}"
CURL_TIMEOUT="${CURL_TIMEOUT:-15}"

# Сколько подряд неудачных проверок считать простоем. Три минуты, а не одна:
# единичный таймаут ловится на любой сети и означает «моргнуло», а не
# «система лежит». Ложная тревога здесь дороже минутной задержки — она
# приучает не верить наблюдателю.
FAIL_THRESHOLD="${FAIL_THRESHOLD:-3}"

mkdir -p "$(dirname "$STATE_FILE")"
log() { printf '%s  сторож: %s\n' "$(date -u +%FT%TZ)" "$*"; }

[ -r "$TOKEN_FILE" ] || { log "!! нет файла с токеном $TOKEN_FILE"; exit 1; }
TOKEN="$(tr -d '[:space:]' < "$TOKEN_FILE")"

# --- отправка в центр уведомлений -------------------------------------------
notify() {  # $1 — вид события, $2 — подробность
    local code
    code=$(curl -s -o /dev/null -w '%{http_code}' --max-time 10 \
        -X POST "$NOTIFY_URL" \
        -H 'Content-Type: application/json' \
        -H "X-Internal-Token: ${TOKEN}" \
        -d "$(printf '{"kind":"%s","source":"наблюдатель (Амстердам)","detail":"%s"}' "$1" "${2//\"/}")" \
        2>/dev/null) || true
    code="${code:-000}"
    if [ "$code" = "202" ]; then
        log "доложено: $1 — $2"
        return 0
    fi
    # Не смогли доложить — это ОЖИДАЕМО, когда прод лежит. Пишем в лог и
    # оставляем состояние нетронутым: доложим, когда система вернётся.
    log "!! доложить не удалось ($1), код $code — прод недоступен?"
    return 1
}

# --- состояние --------------------------------------------------------------
# формат: <подряд_неудач> <unixtime_начала_простоя> <был_ли_доклад_о_простое>
read -r FAILS DOWN_SINCE REPORTED < <(cat "$STATE_FILE" 2>/dev/null || echo "0 0 0")
FAILS="${FAILS:-0}"; DOWN_SINCE="${DOWN_SINCE:-0}"; REPORTED="${REPORTED:-0}"
NOW=$(date +%s)

save() { printf '%s %s %s\n' "$1" "$2" "$3" > "$STATE_FILE"; }

# --- проверка ---------------------------------------------------------------
# Без `|| echo 000`: curl и при отказе соединения САМ печатает 000 в
# %{http_code}, а запасной echo дописывал второй — в логе получалось «000000».
HTTP=$(curl -s -o /tmp/wd-health.$$ -w '%{http_code}' --max-time "$CURL_TIMEOUT" \
    "${PROD_URL}/api/health" 2>/dev/null) || true
HTTP="${HTTP:-000}"
BODY=$(cat /tmp/wd-health.$$ 2>/dev/null || true)
rm -f /tmp/wd-health.$$

ALIVE=0
if [ "$HTTP" = "200" ] && printf '%s' "$BODY" | grep -q '"status":"ok"'; then
    ALIVE=1
fi

if [ "$ALIVE" = "0" ]; then
    FAILS=$((FAILS + 1))
    [ "$DOWN_SINCE" = "0" ] && DOWN_SINCE=$NOW
    log "не отвечает (${FAILS}/${FAIL_THRESHOLD}), код ${HTTP}"
    save "$FAILS" "$DOWN_SINCE" "$REPORTED"

    # Попытка доложить сразу — вдруг лежит не весь сервер, а только часть
    # (например, nginx отдаёт 502, а api с базой живы и доступны по мосту).
    if [ "$FAILS" -ge "$FAIL_THRESHOLD" ] && [ "$REPORTED" = "0" ]; then
        if notify "system.unreachable" \
            "снаружи не отвечает $((FAILS)) мин подряд, последний код HTTP ${HTTP}"; then
            save "$FAILS" "$DOWN_SINCE" "1"
        fi
    fi
    exit 0
fi

# --- система отвечает -------------------------------------------------------
if [ "$FAILS" -ge "$FAIL_THRESHOLD" ]; then
    MINUTES=$(( (NOW - DOWN_SINCE) / 60 ))
    FROM=$(date -u -d "@${DOWN_SINCE}" +%H:%M 2>/dev/null || date -u -r "${DOWN_SINCE}" +%H:%M)
    TO=$(date -u +%H:%M)
    # ВОЗВРАТ ДОКЛАДЫВАЕТСЯ ОТДЕЛЬНЫМ ВИДОМ, а не тем же `system.unreachable`.
    #
    # Раньше обе новости ехали одним видом, а вид — это ключ склейки повторов в
    # центре уведомлений. То есть доклад «система вернулась» попадал В ТУ ЖЕ
    # СТРОКУ, что и тревога о падении: счётчик повторов рос, строка снова
    # становилась непрочитанной, красная плашка «Система не отвечает снаружи»
    # всплывала поверх экрана — и всплывала она ровно в тот момент, когда всё
    # уже работало. Администратор утром видел критичную тревогу о недоступности
    # системы, открывал её и обнаруживал внутри текст про возврат.
    #
    # Цена двойная. Человек бежит чинить работающую систему — это раз. И, что
    # хуже, он привыкает, что красная плашка про недоступность врёт: следующую,
    # настоящую, он закроет не глядя. Ровно так на этой системе уже утонули два
    # настоящих провала бэкапа среди ста ложных тревог.
    #
    # `system.recovered` — свой вид (значит и свой ключ склейки), важность
    # «обычное»: возврат это не авария, будить им нельзя. Тревогу о падении он
    # не гасит и не подменяет — она остаётся следом того, что случилось ночью.
    if [ "$REPORTED" = "1" ]; then
        # О простое уже доложили в момент падения — теперь сообщаем, что всё.
        notify "system.recovered" \
            "система вернулась: была недоступна ${MINUTES} мин, с ${FROM} до ${TO} UTC" || true
    else
        # Доложить в момент падения не вышло (прод лежал целиком) — докладываем
        # сейчас. Это и есть тот самый след, которого иначе не остаётся.
        notify "system.recovered" \
            "была недоступна ${MINUTES} мин, с ${FROM} до ${TO} UTC — доклад задержан, пока сервер не отвечал" || true
    fi
    log "восстановилась после ${MINUTES} мин простоя"
elif [ "$FAILS" -gt 0 ]; then
    log "моргнуло ${FAILS} раз, до порога не дошло — молчим"
fi

save 0 0 0

# --- частичные отказы: их адресат жив, докладываем немедленно ---------------
DEEP=$(curl -s --max-time "$CURL_TIMEOUT" "${PROD_URL}/api/health/deep" 2>/dev/null || true)

if printf '%s' "$DEEP" | grep -q '"alive":false'; then
    notify "scheduler.dead" "внешняя проверка: планировщик не отвечает" || true
fi

log "ок"
