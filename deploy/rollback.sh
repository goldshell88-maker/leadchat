#!/usr/bin/env bash
# ============================================================================
# LeadChat — ручной откат на предыдущий тег (docs/05-DEPLOY-OPS.md §5.3,
# docs/07-TESTING-SECURITY.md §6 — этот скрипт дёргает шаг smoke в CI).
#
#   rollback.sh            # на тег, который работал до последнего деплоя
#   rollback.sh <tag>      # на конкретный тег
#
# Это тонкая обёртка над deploy.sh: образы в GHCR иммутабельны (тег = SHA),
# поэтому «откат» — это обычный деплой старого тега.
#
# РАБОТАЕТ ТОЛЬКО ТАМ, ГДЕ ЕСТЬ РЕЕСТР. Боевой сервер сегодня собирает образы
# у себя (docker-compose.override.yml), тегов-SHA и файла .state/previous_tag
# на нём нет — этот скрипт там честно выйдет с кодом 2. Выкатка с рабочей
# машины (deploy/workstation/ship.sh) поэтому его НЕ ЗОВЁТ: она метит рабочие
# образы `…:rollback` перед сборкой и возвращает теги на них. Раньше звала — и
# автооткат при красной выкатке не мог сработать в принципе.
#
# СХЕМУ БД НЕ ОТКАТЫВАЕМ: вниз-миграции в проде запрещены. Старый код обязан
# работать на новой схеме — это и есть смысл правила expand-contract (05 §5.3).
# Если откат нужен из-за миграции, которая ломает старый код, — это баг
# процесса, чинить накатом вперёд (fix-forward), а не вниз.
# ============================================================================
set -euo pipefail

DEPLOY_DIR="${DEPLOY_DIR:-/srv/leadchat}"
PREV_TAG_FILE="${DEPLOY_DIR}/.state/previous_tag"
SELF_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

TAG="${1:-}"
if [ -z "$TAG" ]; then
    [ -f "$PREV_TAG_FILE" ] || {
        echo "!! не знаю предыдущий тег (нет ${PREV_TAG_FILE}) — укажите явно: rollback.sh <tag>" >&2
        exit 2
    }
    TAG="$(cat "$PREV_TAG_FILE")"
fi

echo "== откат на ${TAG} =="
# LEADCHAT_ROLLBACK=1 запрещает deploy.sh откатываться ещё раз при неудаче:
# два отката подряд — это уже ситуация «нужны руки», а не автоматика.
LEADCHAT_ROLLBACK=1 exec "${SELF_DIR}/deploy.sh" "$TAG"
