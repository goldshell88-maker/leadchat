#!/usr/bin/env bash
# ============================================================================
# LeadChat — снимок журналов контейнеров на диск хоста.
#
# ЗАЧЕМ. Журнал json-file лежит в /var/lib/docker/containers/<id>/, где <id> —
# id КОНТЕЙНЕРА. Выкатка пересоздаёт контейнеры, docker удаляет старый каталог
# вместе с журналом — и после инцидента смотреть нечего. Настройкой драйвера
# это не чинится: путь не задаётся, том туда не подставляется. Единственный
# способ пережить пересоздание — вынести строки наружу ДО него.
#
# Запускается дважды и обе точки нужны:
#   * ship.sh, шаг 5 — прямо перед пересозданием (иначе строки этого дня уйдут);
#   * cron 04:00 — чтобы журнал не терялся и в дни без выкатки (кольцевой буфер
#     json-file на nginx — около 2,8 суток, замер 08.09).
#
# ИНКРЕМЕНТ, А НЕ ПОЛНЫЙ СНИМОК. На сервис хранится отметка времени прошлого
# прогона, следующий снимает `docker logs --since <отметка>`. Отметка берётся
# ДО чтения: на границе может продублироваться несколько строк — это дешевле
# дырки, а дырку в журнале за нужный час заметить нельзя.
#
# ОБЪЁМ (замер боя 08.09). Все контейнеры дают 198 МБ строк в сутки, gzip
# сжимает их в 11,8 раза (nginx) и 12,1 (api) — 16 МБ в сутки. При хранении
# 30 суток это ~0,5 ГБ; потолок LOG_ARCHIVE_MAX_MB=3072 срабатывает, только
# если поток вырастет вшестеро.
#
# ⚠ СКРИПТ НЕ ИМЕЕТ ПРАВА ПОМЕШАТЬ ВЫКАТКЕ. Любая беда здесь — предупреждение
# и код 0: ship.sh зовёт его перед перезапуском, и «не сняли журнал» не повод
# оставить прод на старом коде. Молчать при этом тоже нельзя — каждая причина
# отказа печатается строкой «!!».
# ============================================================================
set -uo pipefail

ARCHIVE_DIR="${LOG_ARCHIVE_DIR:-/var/leadchat/logs}"
KEEP_DAYS="${LOG_ARCHIVE_KEEP_DAYS:-30}"
MAX_MB="${LOG_ARCHIVE_MAX_MB:-3072}"
MIN_FREE_PCT="${LOG_ARCHIVE_MIN_FREE_PCT:-10}"
PROJECT="${LOG_ARCHIVE_PROJECT:-leadchat}"

log() { printf '%s  %s\n' "$(date -u +%FT%TZ)" "$*"; }
warn() { log "!! $*"; }

# Разойтись, а не наложиться: cron в 04:00 и выкатка могут совпасть, а два
# прогона на одной отметке времени сняли бы один и тот же кусок дважды.
# Ждать нечего — второй просто уходит: его работу уже делает первый.
# ⚠ Перенаправление в `exec` без команды меняет дескриптор ВСЕГО скрипта,
# поэтому здесь только открытие файла: приписать сюда `2>/dev/null` значит
# заглушить stderr до конца прогона — и предупреждения ниже никто не увидит.
LOCK="${TMPDIR:-/tmp}/leadchat-archive-logs.lock"
if exec 9>"$LOCK" && command -v flock >/dev/null 2>&1; then
    flock -n 9 || { log "уже выполняется другим процессом — пропуск"; exit 0; }
fi

# --- каталог ----------------------------------------------------------------
#
# ⚠ ЗДЕСЬ НЕТ ЛОВУШКИ ПРАВ, И ЭТО СДЕЛАНО НАРОЧНО. Соседний том
# /var/leadchat/whisper показал, чем кончается bind-mount от root в контейнер,
# который работает не от root: первая запись падает молча. Каталог журналов в
# контейнер НЕ монтируется вовсе — в него пишет пользователь деплоя на хосте,
# тот же, что запускает cron и принимает ssh выкатки. Проверять права одного
# пользователя проще, чем сводить uid хоста с uid образа.
#
# /var/leadchat принадлежит root, поэтому подкаталог заводится один раз.
# Пробуем сами (вдруг уже отдан), иначе через sudo -n — БЕЗ пароля: с `-n`
# sudo при запрете возвращает ошибку сразу и не может подвесить выкатку
# ожиданием ввода на канале без терминала.
if [ ! -d "$ARCHIVE_DIR" ]; then
    if ! mkdir -p "$ARCHIVE_DIR" 2>/dev/null; then
        sudo -n mkdir -p "$ARCHIVE_DIR" 2>/dev/null \
            && sudo -n chown "$(id -u):$(id -g)" "$ARCHIVE_DIR" 2>/dev/null
    fi
fi
if [ ! -w "$ARCHIVE_DIR" ]; then
    warn "каталог ${ARCHIVE_DIR} недоступен на запись — журналы НЕ снимаются."
    warn "   один раз на сервере: sudo mkdir -p ${ARCHIVE_DIR} && sudo chown $(id -un):$(id -gn) ${ARCHIVE_DIR}"
    exit 0
fi

# Никаких «внутрь» из архива: в строках nginx видны адреса диалогов, а сам
# каталог рядом с /var/leadchat/download, который nginx раздаёт наружу.
chmod 750 "$ARCHIVE_DIR" 2>/dev/null || true

# --- место на диске ---------------------------------------------------------
# Архив журналов не имеет права стать тем, что добило раздел во время разбора
# аварии. Порог ниже, чем у бэкапа (15%): дамп базы важнее строк лога.
FREE_PCT=$(df -P "$ARCHIVE_DIR" | awk 'NR==2 {gsub("%","",$5); print 100-$5}')
if [ "${FREE_PCT:-100}" -lt "$MIN_FREE_PCT" ]; then
    warn "свободно ${FREE_PCT}% (порог ${MIN_FREE_PCT}%) — снимок пропущен, старое не трогаю"
    exit 0
fi

# --- снимок по сервисам -----------------------------------------------------
# Контейнеры ищем по метке compose, а не по списку имён: список сервисов уже
# один раз разошёлся с действительностью (ship.sh перезапускал четыре из шести,
# и правка описания имитатора Авито лежала невыкаченной).
# Список читаем циклом, а не `mapfile`: его нет в bash 3.2, а скрипт хочется
# уметь прогонять и на рабочей машине — проверка, которая идёт только на бою,
# проверкой не является.
CIDS=()
while IFS= read -r _cid; do
    [ -n "$_cid" ] && CIDS+=("$_cid")
# Одноразовые `docker compose run` (миграции, консольные команды) не снимаем:
# они делили с боевым контейнером отметку сервиса и сдвигали её, и журнал
# боевого за весь период пропадал (проверка 24.09).
done < <(docker ps -q --filter "label=com.docker.compose.project=${PROJECT}" \
             --filter "label=com.docker.compose.oneoff=False" 2>/dev/null)
if [ "${#CIDS[@]}" -eq 0 ]; then
    warn "не нашёл ни одного контейнера проекта ${PROJECT} — снимать нечего"
    exit 0
fi

NOW=$(date -u +%Y-%m-%dT%H:%M:%SZ)
TOTAL_BYTES=0
TAKEN=0

for cid in "${CIDS[@]}"; do
    read -r svc num < <(docker inspect --format \
        '{{index .Config.Labels "com.docker.compose.service"}} {{index .Config.Labels "com.docker.compose.container-number"}}' \
        "$cid" 2>/dev/null) || true
    [ -n "${svc:-}" ] || continue

    # Отметка — у каждой реплики своя (--scale worker=3): общая на сервис
    # сдвигалась первой репликой, и следующая снималась «с этой секунды» —
    # всё написанное ею с прошлого снимка пропадало (проверка 24.09). Первой
    # реплике достаётся прежняя отметка сервиса, чтобы переход не снял буфер
    # заново.
    stamp_file="${ARCHIVE_DIR}/.since-${svc}${num:+-${num}}"
    if [ ! -e "$stamp_file" ] && [ "${num:-1}" = "1" ] && [ -e "${ARCHIVE_DIR}/.since-${svc}" ]; then
        cp "${ARCHIVE_DIR}/.since-${svc}" "$stamp_file"
    fi
    # Первый прогон снимает всё, что есть в кольцевом буфере: там уже лежит
    # история за несколько суток, и терять её из-за отсутствия отметки глупо.
    since=$(cat "$stamp_file" 2>/dev/null || echo "")

    mkdir -p "${ARCHIVE_DIR}/${svc}" || { warn "не создался ${ARCHIVE_DIR}/${svc}"; continue; }
    out="${ARCHIVE_DIR}/${svc}/${NOW//:/-}.log.gz"
    # ⚠ ДВА ПРОГОНА В ОДНУ СЕКУНДУ ПИСАЛИ БЫ В ОДИН ФАЙЛ. Имя снимка — время с
    # точностью до секунды, и выкатка, начатая сразу после ночного cron, затирала
    # снимок предыдущего контейнера своим. Поймано сторожем
    # (tests/unit/test_log_archive_0809.py): строка прежнего контейнера
    # исчезала при живых зелёных логах. Берём первое свободное имя.
    n=0
    while [ -e "$out" ]; do
        n=$((n + 1))
        out="${ARCHIVE_DIR}/${svc}/${NOW//:/-}-${n}.log.gz"
    done

    # --timestamps обязателен: без метки времени строки из разных контейнеров
    # не выстроить в один ряд, а разбор аварии — это именно порядок событий.
    # stderr контейнера сливаем в stdout: приложение пишет туда traceback'и.
    if [ -n "$since" ]; then
        docker logs --timestamps --since "$since" "$cid" >"${out}.tmp" 2>&1
    else
        docker logs --timestamps "$cid" >"${out}.tmp" 2>&1
    fi
    rc=$?
    if [ "$rc" -ne 0 ]; then
        warn "docker logs ${svc} вернул ${rc} — сервис пропущен, отметка не сдвинута"
        rm -f "${out}.tmp"
        continue
    fi

    if [ ! -s "${out}.tmp" ]; then
        # Пустой кусок — не беда (сервис молчал), но и файла плодить незачем.
        rm -f "${out}.tmp"
        printf '%s' "$NOW" >"$stamp_file"
        continue
    fi

    gzip -6 -c "${out}.tmp" >"$out" && rm -f "${out}.tmp" || {
        warn "не сжался снимок ${svc} — отметка не сдвинута"
        rm -f "${out}.tmp" "$out"
        continue
    }

    # Отметку двигаем ТОЛЬКО после удачной записи: иначе неудачный прогон
    # объявил бы снятым то, чего на диске нет, и дыра осталась бы навсегда.
    printf '%s' "$NOW" >"$stamp_file"

    sz=$(stat -c%s "$out" 2>/dev/null || stat -f%z "$out")
    TOTAL_BYTES=$((TOTAL_BYTES + sz))
    TAKEN=$((TAKEN + 1))
done

log "снято сервисов: ${TAKEN}, объём: $((TOTAL_BYTES / 1024)) КБ, каталог ${ARCHIVE_DIR}"

# --- чистка: сначала по сроку, потом по объёму -------------------------------
# Два предела, а не один. Срок отвечает на вопрос «за какой день можно
# посмотреть» (30 суток), объём — на вопрос «сколько это займёт в худшем
# случае» (3 ГБ). Без второго один болтливый traceback в цикле переполнил бы
# раздел задолго до тридцатого дня.
find "$ARCHIVE_DIR" -type f -name '*.log.gz' -mtime "+${KEEP_DAYS}" -delete 2>/dev/null

used_mb() { du -sm "$ARCHIVE_DIR" 2>/dev/null | cut -f1; }
USED=$(used_mb)
if [ "${USED:-0}" -gt "$MAX_MB" ]; then
    warn "архив ${USED} МБ > потолка ${MAX_MB} МБ — удаляю самые старые снимки"
    # Сортируем по ИМЕНИ файла, а не по времени правки: имя — это метка времени
    # снимка в ISO (2026-09-08T04-00-00Z.log.gz), и лексикографический порядок
    # для неё совпадает с хронологическим. Путь для сортировки не годится —
    # он начинается с имени сервиса и перемешал бы дни разных контейнеров.
    # `find -printf` и `sort -z` здесь были бы точнее, но они есть только в
    # GNU: на рабочей машине чистка молча не срабатывала бы, а проверить это
    # было бы негде.
    while IFS= read -r f; do
        USED=$(used_mb)
        [ "${USED:-0}" -le "$MAX_MB" ] && break
        rm -f "$f"
    done < <(find "$ARCHIVE_DIR" -type f -name '*.log.gz' 2>/dev/null \
             | awk -F/ '{print $NF "\t" $0}' | sort | cut -f2-)
    log "после чистки: $(used_mb) МБ"
fi

exit 0
