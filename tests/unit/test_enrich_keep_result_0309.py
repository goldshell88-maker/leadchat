"""Отказ обогащения не гасит карточку клиента на час (03.09).

⚠ ЧТО БЫЛО. Задача подстановки имени ставится под ПОСТОЯННЫМ именем
`enrich:{conversation_id}` — и это правильно: без имени поход в чужой API
случался бы на каждое входящее сообщение.

Но ARQ хранит под тем же именем РЕЗУЛЬТАТ задачи. После неудачной попытки
повторная постановка молча отбрасывалась, пока результат не истечёт — час по
умолчанию. Имя клиента не появлялось в карточке до следующего часа, и не было
видно ничего: ни ошибки, ни следа.

⚠ ПОЧЕМУ НЕ ОКНО В ИМЕНИ. Первая редакция правки добавляла в имя пятиминутное
окно (`enrich:{id}:{минута // 5}`). Она лечила блокировку, но ломала главное:
два сообщения по разные стороны границы окна дали бы ДВА похода в Авито. Тест
`test_enrich_enqueued_once_per_client` в соседнем файле это и поймал.

`keep_result=0` решает ровно нужное: пока задача стоит в очереди или
выполняется, её ключ существует и дедупликация работает; кончилась — неважно,
успехом или отказом — повтор возможен.
"""

from __future__ import annotations

from arq.worker import Function

from app.workers.main import WorkerSettings


def _зарегистрирована(имя: str) -> Function:
    для_имени = [
        f
        for f in WorkerSettings.functions
        if getattr(f, "name", None) == имя or getattr(f, "__name__", None) == имя
    ]
    assert для_имени, f"задача {имя} не зарегистрирована в воркере"
    return для_имени[0]


def test_результат_обогащения_не_хранится() -> None:
    """⚠ ГЛАВНАЯ ПРОВЕРКА: иначе один отказ гасит имя клиента на час."""
    задача = _зарегистрирована("enrich_client")
    assert isinstance(задача, Function), (
        "задача зарегистрирована как обычная корутина — значит keep_result "
        "остался по умолчанию, и отказ снова заблокирует повтор на час"
    )
    assert задача.keep_result_s == 0, (
        f"keep_result={задача.keep_result_s}: после неудачной попытки повторная "
        "постановка будет молча отбрасываться всё это время"
    )


def test_имя_задачи_осталось_постоянным() -> None:
    """⚠ ВТОРАЯ ПОЛОВИНА: без постоянного имени вернётся поход в Авито на КАЖДОЕ
    входящее сообщение — ровно то, от чего дедупликация и заведена."""
    import inspect

    from app.services import client_enrich

    тело = inspect.getsource(client_enrich)
    assert '_job_id=f"enrich:{conversation_id}"' in тело, (
        "в имя задачи добавили что-то переменное — дедупликация сломается на "
        "границе, и два сообщения подряд дадут два похода в чужой API"
    )
