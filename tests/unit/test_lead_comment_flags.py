"""Комментарий заявки и галочки: что уезжает мастеру и почему.

Каждое свойство здесь стоит денег или репутации. Потерянная озвучка — спор с
клиентом на пороге, который мастер проиграет. Лишняя галочка «Прозвон» — звонок,
которого клиент не просил, а это нарушение регламента. Пропущенный «Отзыв» —
не полученный отзыв, ради которого партнёров и просят.
"""

from __future__ import annotations

import pytest

from app.services.lead_comment import build, find_offers
from app.services.lead_flags import detect_calls, normalize_partner, wants_review

СПИСОК = ["007", "723", "7", "740", "340", "748"]


# ------------------------------------------------------------ что озвучили


def test_comment_repeats_the_shape_of_a_real_request() -> None:
    """Порядок строк — как в живой заявке КП №1234567, плюс «Создана с чата».

    Образец разобран 13 августа; строка «Создана с чата» обязательна для заявок
    без звонка по регламенту 15.08 (п. 5) — все наши заявки такие.
    """
    текст = build(
        problem="перестал работать интернет , роутер горит красным",
        outgoing=["Выезд и диагностика 1000 рублей, в случае ремонта бесплатно"],
        review_url="https://clc.li/AbCdE",
    )
    assert текст.split("\n") == [
        "перестал работать интернет , роутер горит красным",
        "Выезд и диагностика 1000 рублей, в случае ремонта бесплатно",
        "Создана с чата",
        "https://clc.li/AbCdE",
    ]


def test_white_723_comment_carries_the_mandatory_marks() -> None:
    """Партнёр 723: ссылка подписана «Белый акк», в конце — «БЕЛАЯ ЗАЯВКА».

    Регламент 15.08, п. 3. За отсутствие подписи — штраф, поэтому форма
    зафиксирована дословно.
    """
    текст = build(
        problem="не включается ноутбук",
        outgoing=[],
        review_url="https://clc.li/FgHiJ",
        white=True,
    )
    assert текст.split("\n") == [
        "не включается ноутбук",
        "Создана с чата",
        "Белый акк https://clc.li/FgHiJ",
        "БЕЛАЯ ЗАЯВКА",
    ]


@pytest.mark.parametrize(
    "фраза",
    [
        "Выезд и диагностика 1000 рублей, в случае ремонта бесплатно",
        "Ремонт от 800 рублей, точнее скажет мастер",
        "Выезд бесплатный",
        "Диагностика бесплатно при ремонте",
        "Работаем без предоплаты",
        "Замена платы 8 900 ₽",
    ],
)
def test_promises_to_the_client_are_kept(фраза: str) -> None:
    """Цена и условия из наших реплик попадают в комментарий.

    Это защита мастера: он приезжает и называет цену. Разойдись она с тем, что
    клиенту сказали в переписке, — спор будет на пороге, и мастер его проиграет,
    потому что клиент помнит цифру, а мастер её не видел.
    """
    assert find_offers([фраза]) == [фраза]


@pytest.mark.parametrize(
    "фраза",
    [
        "Роутер TP-Link 841 меняли?",
        "Мастер приедет завтра с 10 до 13",
        "Какая модель 2019 года?",
        "Квартира 145, второй этаж",
        "Здравствуйте! Ремонт роутеров делаем.",
    ],
)
def test_numbers_that_are_not_prices_stay_out(фраза: str) -> None:
    """Цифры в переписке про ремонт повсюду — модель, этаж, год, время.

    Возьми любое число за цену — и в комментарий уедет «TP-Link 841» как
    обещанная сумма. Мастер прочтёт это как названную клиенту цену.
    """
    assert find_offers([фраза]) == []


def test_the_same_promise_is_not_repeated() -> None:
    """Оператор часто шлёт одну фразу дважды — в комментарии она одна."""
    фраза = "Выезд бесплатный"
    assert find_offers([фраза, "Добрый день", фраза]) == [фраза]


def test_missing_parts_do_not_break_the_comment() -> None:
    """Нет ссылки или озвучек — комментарий короче, а не заявка несозданная.

    «Создана с чата» остаётся и в самом пустом комментарии: она про способ
    создания заявки, а не про содержание переписки (регламент 15.08, п. 5).
    """
    assert build(problem="не морозит", outgoing=[], review_url=None) == (
        "не морозит\nСоздана с чата"
    )
    assert build(problem=None, outgoing=[], review_url=None) == "Создана с чата"


# ------------------------------------------------------------------ прозвон


@pytest.mark.parametrize(
    "реплика",
    [
        "Перезвоните мне вечером, обсудим время",
        "Свяжитесь со мной, пожалуйста",
        "Пока не знаю, когда смогу принять мастера",
        "Уточню время позже",
        "Наберите меня как освобожусь",
    ],
)
def test_call_is_set_only_when_the_client_asked(реплика: str) -> None:
    """«Прозвон» — по словам КЛИЕНТА, и только."""
    прозвон, перед = detect_calls([реплика])
    assert (прозвон, перед) == (True, False)


@pytest.mark.parametrize(
    "реплика",
    [
        "Давайте завтра в 14:00. Позвоните перед выездом, пожалуйста",
        "Предупредите когда выедете",
        "Наберите за полчаса до приезда",
    ],
)
def test_before_visit_wins_over_plain_call(реплика: str) -> None:
    """⚠ ДВЕ ГАЛОЧКИ ОДНОВРЕМЕННО — ЭТО ПРОТИВОРЕЧИЕ, А НЕ ПОДРОБНОСТЬ.

    «Прозвон» значит «времени ещё нет, надо подобрать»; «перед выездом» —
    «время есть, предупредите». Поставь обе — и лид-центру сказано, что время
    одновременно назначено и не назначено. Разбирать это будет человек по
    телефону, у клиента.

    Побеждает «перед выездом»: она конкретнее, а её формулировка содержит слово
    «позвоните», по которому срабатывает и первая.
    """
    прозвон, перед = detect_calls([реплика])
    assert (прозвон, перед) == (False, True)


@pytest.mark.parametrize(
    "реплика",
    [
        "Завтра в 14:00 удобно",
        "Хорошо, договорились",
        "Адрес: Ленина 5, квартира 12",
        "Не морозит холодильник",
    ],
)
def test_nothing_is_set_when_the_client_did_not_ask(реплика: str) -> None:
    """⚠ САМИМ ПРЕДЛАГАТЬ ЗВОНОК РЕГЛАМЕНТ ЗАПРЕЩАЕТ.

    Если время назначено и клиент ни о чём не просил — обе галочки пусты.
    Поставить «Прозвон» здесь значит нарушить прямое правило владельца.
    """
    assert detect_calls([реплика]) == (False, False)


def test_our_own_words_never_set_the_call_flags() -> None:
    """Разбирается ВХОДЯЩИЙ поток. Наши фразы — не основание.

    Иначе «давайте созвонимся» из уст оператора ставило бы галочку — то есть
    ровно в том случае, который запрещён.
    """
    наши = ["Давайте созвонимся и подберём время", "Перезвоним вам завтра"]
    # Функция принимает только клиентские реплики; проверка в том, что вызывающий
    # обязан передать именно их, а на пустом входе флаги не ставятся.
    assert detect_calls([]) == (False, False)
    # А если бы наши слова попали внутрь — это уже дефект вызывающего,
    # и он виден: флаг встанет. Фиксируем поведение явно.
    assert detect_calls(наши)[0] is True


# -------------------------------------------------------------------- отзыв


@pytest.mark.parametrize("номер", ["007", "7", " 7 ", "723", "340"])
def test_review_is_set_for_listed_partners(номер: str) -> None:
    assert wants_review(номер, СПИСОК) is True


@pytest.mark.parametrize("номер", ["999", "1", "", None])
def test_review_is_not_set_for_others(номер: str | None) -> None:
    assert wants_review(номер, СПИСОК) is False


def test_leading_zeros_are_the_same_partner() -> None:
    """«007» в списке владельца и «7» на карточке канала — один человек.

    Не сведи их — и партнёр из списка останется без отзывов, причём молча:
    заявки создаются, галочки нет, никто не замечает.
    """
    assert normalize_partner("007") == normalize_partner("7") == "7"
    assert wants_review("7", ["007"]) is True


# ------------------------------------------------- «Отзыв» по направлению


def test_review_for_partner_7_skips_kp() -> None:
    """Регламент 15.08, п. 2: у партнёра 7 «Отзыв» — на БТ/МНЧ, но не на КП."""
    allowed = ["007", "340", "723"]
    assert wants_review("7", allowed, src_key="bt") is True
    assert wants_review("007", allowed, src_key="mnc") is True
    assert wants_review("7", allowed, src_key="kp") is False
    # у остальных партнёров направление роли не играет
    assert wants_review("723", allowed, src_key="kp") is True
    assert wants_review("340", allowed, src_key="kp") is True
