"""Формы улицы, на которых разбор терял адрес (скриншоты владельца 25.09).

Данные вымышлены, формы — те же, что у клиентов.

1. «ул. Ольховское шоссе 17» — два типа: общее «ул.» спорило с собственным типом
   имени, в запрос уходило «улица … шоссе», а вердикт сверял тип «улица» с
   «шоссе» карты и отвечал «улица не та».
2. «89001112241,5-я Сиреневая д.3» — порядковое после запятой терялось: сторож
   приставки считал любой знак перед числом продолжением числа («12,5»,
   «10:30»), после погашенного телефона оставалась «Сиреневая» — а у карты их
   четыре (2-я, 5-я, 6-я, 9-я).
3. «Пгт Ольховое Сиреневая 12к3 подъезд 2» — улица без типа прилагательным с
   заглавной сливалась с именем пункта («Ольховое Сиреневая»).
4. «С. Ольхово город мечты 14» — сокращение села с точкой ворота не поднимало
   (в отличие от разбора места), а «город …» после имени считалось его хвостом.
5. «Николая-Ольхова 31» — дефис между именем и фамилией: вердикт сравнивал слово
   «николая-ольхова» с двумя словами карты и не сходился.
6. «Поселок Ольховый» отдельной репликой — разбор места его берёт (закреплено
   ниже); теряется он дальше, у карты, это не слой разбора.

ДИВЕРСИИ: убрать `_без_общего_типа` из `parse` — краснеют тесты 1; вернуть
сторож приставки `(?<![\\d.,:])` без исключения для порядкового — тесты 2; убрать
из `_хвост_имени_это_улица` правило улицы женского рода — тесты 3; правило
«город» там же, «с./д.» с точкой или имя без «город …» в `_место_названо` —
тесты 4; убрать повтор сравнения по частям составного слова в
`geocode._улица_не_шире` — тесты 5.
"""

from __future__ import annotations

import pytest

from app.integrations.avito.listing_url import City
from app.services import address_parse as ap
from app.services import geocode as g

МОСКВА = City("Москва", "Москва", "Europe/Moscow")
ЧИТА = City("Чита", "Забайкальский край", "Asia/Chita")
КОМСОМОЛЬСК = City("Комсомольск-на-Амуре", "Хабаровский край", "Asia/Vladivostok")


def _дом(street: str, house: str, city: City, **kw: object) -> g.GeoHit:
    return g.GeoHit(
        street=street,
        house=house,
        settlement=kw.get("settlement"),  # type: ignore[arg-type]
        city=city.name,
        region=city.region,
        lat=float(kw.get("lat", 50.0)),  # type: ignore[arg-type]
        lon=40.0,
        house_level=True,
    )


def _разбор(text: str, **kw: object) -> ap.Found:
    f = ap.parse(text, **kw)  # type: ignore[arg-type]
    assert f is not None, text
    assert ap.quote_holds(f, text), (text, f.street, f.raw)
    return f


# --- 1. общий тип «ул.» при своём типе имени ----------------------------------


@pytest.mark.parametrize(
    ("text", "street", "house"),
    [
        ("ул. Ольховское шоссе 17", "Ольховское шоссе", "17"),
        ("улица Липецкий проспект 5", "Липецкий проспект", "5"),
        ("ул Сиреневый переулок 3", "Сиреневый переулок", "3"),
        ("ул. 7-я линия 12", "7-я линия", "12"),
        ("ул. Ольховая площадь 4", "Ольховая площадь", "4"),
        # Винительный выпрямляется по типу впереди — и лишь потом тип уходит.
        ("на ул. Ольховскую площадь 4", "Ольховская площадь", "4"),
        ("Ул.Ольховское шоссе,д.17 кв 5", "Ольховское шоссе", "17"),
        # Сокращение своего типа — тот же тип: карта получит «шоссе».
        ("ул. Ольховое ш. 17", "Ольховое ш.", "17"),
    ],
)
def test_общий_тип_уступает_своему_типу_имени(text: str, street: str, house: str) -> None:
    f = _разбор(text)
    assert (f.street, f.house) == (street, house)
    # Запрос к карте без «улица» впереди, и вердикт сходится с улицей карты.
    запрос = g.build_query(g.Parsed(street=f.street, house=f.house), МОСКВА)
    assert запрос is not None
    assert not запрос.street_for_map.lower().startswith("улица")
    карта = g.expand_street(street).replace(".", "")
    статус, _ = g.verdict(
        g.Parsed(street=f.street, house=f.house), МОСКВА, [_дом(карта, house, МОСКВА)]
    )
    assert статус == g.GEO_EXACT


@pytest.mark.parametrize(
    ("text", "street"),
    [
        # Тип и есть имя: «улица Набережная» — настоящая улица, тип остаётся.
        ("ул. Набережная 5", "ул. Набережная"),
        ("ул. Ольховая 5", "ул. Ольховая"),
        # Прилагательное от типа — не тип: «Шоссейная» остаётся улицей.
        ("ул. Шоссейная 5", "ул. Шоссейная"),
        ("Ольховское шоссе 17", "Ольховское шоссе"),
    ],
)
def test_общий_тип_остаётся_без_своего_типа(text: str, street: str) -> None:
    assert _разбор(text).street == street


# --- 2. порядковое после знака -------------------------------------------------


@pytest.mark.parametrize(
    ("text", "street", "house", "raw"),
    [
        ("89001112241,5-я Сиреневая д.3", "5-я Сиреневая", "3", "5-я Сиреневая д.3"),
        ("+7 900 111-22-42,5-я Сиреневая д.3", "5-я Сиреневая", "3", "5-я Сиреневая д.3"),
        ("ул.5-я Сиреневая д.3", "ул. 5-я Сиреневая", "3", "ул.5-я Сиреневая д.3"),
        ("Хорошо,3-й Ольховый 5", "3-й Ольховый", "5", "3-й Ольховый 5"),
    ],
)
def test_порядковое_после_знака_остаётся_в_имени(
    text: str, street: str, house: str, raw: str
) -> None:
    f = _разбор(text)
    assert (f.street, f.house, f.raw) == (street, house, raw)


def test_порядковое_выбирает_одну_улицу_из_тёзок() -> None:
    """Карта знает 2-ю, 5-ю, 6-ю и 9-ю Сиреневую с домом 3: без «5-я» это
    «несколько адресов», с ним — один."""
    тёзки = [
        _дом(f"{n}-я Сиреневая улица", "3", КОМСОМОЛЬСК, lat=50.0 + n / 100) for n in (2, 5, 6, 9)
    ]
    f = _разбор("89001112243,5-я Сиреневая д.3")
    статус, дом = g.verdict(g.Parsed(street=f.street, house=f.house), КОМСОМОЛЬСК, тёзки)
    assert статус == g.GEO_EXACT and дом is not None and дом.street == "5-я Сиреневая улица"
    без_порядка = g.verdict(g.Parsed(street="Сиреневая", house="3"), КОМСОМОЛЬСК, тёзки)
    assert без_порядка[0] == g.GEO_AMBIGUOUS


@pytest.mark.parametrize(
    "text",
    [
        # Число после цифры и знака — продолжение числа, а не приставка.
        "12,5 Сиреневая 7",
        # Голое число после знака приставкой не становится: «кв,5» — квартира.
        "кв,5 Сиреневая 7",
    ],
)
def test_число_после_знака_без_порядка_не_приставка(text: str) -> None:
    f = _разбор(text)
    assert (f.street, f.house) == ("Сиреневая", "7")


# --- 3. пункт и улица прилагательным с заглавной -------------------------------


def test_пгт_имя_улица_с_заглавной_корпус_и_подъезд() -> None:
    f = _разбор("Пгт Ольховое Сиреневая 12к3 подъезд 2")
    assert (f.level, f.street, f.house) == ("A", "Сиреневая", "12к3")
    assert (f.settlement, f.settlement_type) == ("Ольховое", "посёлок")
    assert f.parts == {"entrance": "2"}
    assert f.value == "Сиреневая, 12к3"


@pytest.mark.parametrize(
    ("text", "street", "house", "settlement", "stype"),
    [
        ("с. Ольховое Садовая 7", "Садовая", "7", "Ольховое", "село"),
        ("посёлок Сосновый Бор Сиреневая 7", "Сиреневая", "7", "Сосновый Бор", "посёлок"),
        ("д. Горки Сиреневая 3", "Сиреневая", "3", "Горки", "деревня"),
    ],
)
def test_улица_прилагательным_не_сливается_с_именем_пункта(
    text: str, street: str, house: str, settlement: str, stype: str
) -> None:
    f = _разбор(text)
    assert (f.street, f.house, f.settlement, f.settlement_type) == (
        street,
        house,
        settlement,
        stype,
    )


@pytest.mark.parametrize(
    ("text", "settlement"),
    [
        # Прилагательное с существительным одного рода — одно имя пункта.
        ("пгт Красная Горка 5", "Красная Горка"),
        ("посёлок Сосновый Бор 7", "Сосновый Бор"),
        # Строчная улица — по-старому (стенд 15.09).
        ("пгт Ольховое майская 4", "Ольховое"),
    ],
)
def test_двусловное_имя_пункта_не_режется(text: str, settlement: str) -> None:
    assert _разбор(text).settlement == settlement


# --- 4. село сокращением и комплекс без «ЖК» -----------------------------------


def test_село_с_точкой_и_комплекс_после_имени() -> None:
    f = _разбор("С. Ольхово город мечты 14")
    assert (f.level, f.street, f.house) == ("B", "город мечты", "14")
    assert (f.settlement, f.settlement_type) == ("Ольхово", "село")
    assert f.raw == "С. Ольхово город мечты 14"


def test_село_с_точкой_это_разговор_об_адресе() -> None:
    assert ap.gate("С. Ольхово 14") == ap.LEVEL_B
    assert ap.gate("Д. Ольховка 7") == ap.LEVEL_B
    # Без точки «с» — предлог, «д 5» — дом: уровень по-прежнему по неводу.
    assert ap.gate("с Ольхово 14") == ap.LEVEL_C
    assert ap.gate("Приеду с Мужем 14") == ap.LEVEL_C


@pytest.mark.parametrize(
    ("text", "street", "settlement"),
    [
        # «город» после прилагательного — часть имени (ЖК «Солнечный город»).
        ("Солнечный город 27", "Солнечный город", None),
        ("пгт Солнечный город 5", "пгт Солнечный город", "Солнечный город"),
    ],
)
def test_город_после_прилагательного_остаётся_в_имени(
    text: str, street: str, settlement: str | None
) -> None:
    f = _разбор(text)
    assert (f.street, f.settlement) == (street, settlement)


# --- 5. имя и фамилия через дефис ----------------------------------------------


def test_имя_фамилия_через_дефис_разбирается_и_во_второй_строке_время() -> None:
    f = _разбор("Николая-Ольхова 31\nЕсли получится, завтра с 10-11")
    assert (f.street, f.house, f.raw) == ("Николая-Ольхова", "31", "Николая-Ольхова 31")


@pytest.mark.parametrize(
    ("клиент", "карта"),
    [
        ("Николая-Ольхова", "улица Николая Ольхова"),
        ("ул Николая-Ольхова", "улица Николая Ольхова"),
        # Порядок через дефис без «-я» — те же два слова, что у карты.
        ("3-ольховый", "3-й Ольховый проезд"),
    ],
)
def test_дефис_у_клиента_пробел_у_карты_та_же_улица(клиент: str, карта: str) -> None:
    статус, _ = g.verdict(g.Parsed(street=клиент, house="31"), ЧИТА, [_дом(карта, "31", ЧИТА)])
    assert статус == g.GEO_EXACT


@pytest.mark.parametrize(
    ("клиент", "карта", "статус"),
    [
        # Составное имя — другая улица: «Ново-Ольховая» не «Ольховая».
        ("Ново-Ольховая", "улица Ольховая", g.GEO_STREET_MISMATCH),
        ("Николая-Ольхова", "улица Ольхова", g.GEO_STREET_MISMATCH),
        # Как было: дефис у обоих, слитно у клиента.
        ("Ново-Ольховая", "Ново-Ольховая улица", g.GEO_EXACT),
        ("Новоольховая", "Ново-Ольховая улица", g.GEO_EXACT),
        ("Бонч-Ольхова", "улица Бонч-Ольхова", g.GEO_EXACT),
        # Тип, как прежде: не назван клиентом — не спорит, назван — сверяется.
        ("Николая-Ольхова", "проспект Николая Ольхова", g.GEO_EXACT),
        ("пр Николая-Ольхова", "улица Николая Ольхова", g.GEO_STREET_MISMATCH),
    ],
)
def test_дефис_не_делает_чужую_улицу_своей(клиент: str, карта: str, статус: str) -> None:
    assert (
        g.verdict(g.Parsed(street=клиент, house="31"), ЧИТА, [_дом(карта, "31", ЧИТА)])[0] == статус
    )


# --- 6. пункт отдельной репликой — слой разбора его берёт ----------------------


@pytest.mark.parametrize("text", ["Поселок Ольховый", "поселок Ольховый", "Посёлок Ольховый."])
def test_посёлок_отдельной_репликой_это_место(text: str) -> None:
    f = ap.parse_place(text)
    assert f is not None
    assert (f.kind, f.settlement, f.settlement_type) == (ap.KIND_PLACE, "Ольховый", "посёлок")
    assert ap.place_stated_as_address(text, f)
