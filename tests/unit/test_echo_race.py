"""Эхо собственной отправки не должно задваивать ленту и глушить бота.

ЧТО СЛУЧИЛОСЬ 26.08. Бот отправил клиенту реплику в 10:31:29.753, а в 10:31:30 то же
самое вернулось вебхуком Авито — с ТЕМ ЖЕ `external_message_id`. Защита от эха ищет
именно по нему, но `external_message_id` проставляется в ТРЕТЬЕЙ фазе доставки
(`workers/deliver.py`), уже ПОСЛЕ ответа Авито. Эхо успело раньше записи, проверка
ничего не нашла, и наше же сообщение легло второй строкой — как «оператор».

Дальше сработало правило «ответили из другого приложения»: бот выключил сам себя,
приняв за оператора собственное эхо. Владелец подтвердил: «при этом я не отвечал».

⚠ ЧАСТОТА ЧЕСТНАЯ. Из 119 выключений бота за две недели по этой причине случилось
РОВНО ОДНО; остальные 118 — живые операторы в приложении Авито. Клиенту дубль при
этом не уходил: Авито доставляет сообщение один раз, задваивалась только наша лента.

⚠ УНИКАЛЬНЫЙ ИНДЕКС ЗДЕСЬ НЕ СПАСАЕТ, и это не упущение. Таблица `messages` разбита
по `created_at`, поэтому ключ обязан его включать: `(conversation_id,
external_message_id, created_at)`. У бота и у эха время РАЗНОЕ — база пропускает обе
строки на законных основаниях. Значит защита может быть только в коде.
"""

from __future__ import annotations

import ast
import pathlib

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[2]
ИСХОДНИК = (КОРЕНЬ / "app" / "services" / "inbound.py").read_text(encoding="utf-8")


def _тело_зеркала() -> str:
    """Исходник функции, которая кладёт в ленту исходящее из вебхука."""
    дерево = ast.parse(ИСХОДНИК)
    for узел in ast.walk(дерево):
        if isinstance(узел, ast.AsyncFunctionDef) and узел.name == "_apply_external_outgoing":
            return ast.get_source_segment(ИСХОДНИК, узел) or ""
    raise AssertionError("функция _apply_external_outgoing не найдена")


def test_эхо_ловится_не_только_по_внешнему_id() -> None:
    """Одной проверки по external_message_id мало — она проигрывает гонку."""
    тело = _тело_зеркала()
    assert "Message.external_message_id == str(event.message_id)" in тело, (
        "исчезла проверка по внешнему id — основная защита от эха"
    )
    assert "Message.body == event.text" in тело, (
        "нет запасной проверки по тексту: эхо, обогнавшее запись внешнего id, "
        "снова ляжет в ленту второй строкой и выключит бота"
    )


def test_запасная_проверка_ограничена_по_времени() -> None:
    """Без окна она склеивала бы повторы, разнесённые на часы."""
    тело = _тело_зеркала()
    assert "_ЭХО_ОКНО" in тело, "запасная проверка без временного окна"
    assert "Message.created_at >=" in тело and "Message.created_at <=" in тело


def test_окно_разумного_размера() -> None:
    """Секунды мало (очередь доставки), часы много (склеит живые повторы)."""
    from datetime import timedelta

    from app.services.inbound import _ЭХО_ОКНО

    assert timedelta(seconds=30) <= _ЭХО_ОКНО <= timedelta(minutes=10)


def test_внешний_id_доставляется_нашей_строке() -> None:
    """Иначе сверка истории приедет с тем же эхом ещё раз и снова задвоит ленту."""
    тело = _тело_зеркала()
    assert "свой.external_message_id = str(event.message_id)" in тело, (
        "внешний id не проставляется нашему сообщению — reconciliation задвоит его снова"
    )


def test_запасная_проверка_смотрит_только_свои_исходящие() -> None:
    """Входящее клиента с тем же текстом эхом не считается."""
    тело = _тело_зеркала()
    assert 'Message.direction == "out"' in тело
