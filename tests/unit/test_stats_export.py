"""Лист «Диалоги»: заголовки и значения обязаны сходиться по счёту.

ПОЧЕМУ ЭТОТ ФАЙЛ ПОЯВИЛСЯ 12 АВГУСТА. При снятии результата обращения из
выгрузки убирались ДВА независимых места: пара подписей в `CONV_HEADERS`
(«Результат», «Сумма, ₽») и пара значений в разборе строки. Проверить, что
тронуты оба, было НЕЧЕМ — ни один тест не смотрел на согласие этих списков.

Цена рассогласования выше, чем кажется. Лишний заголовок не роняет ни выгрузку,
ни запись файла: `csv.writer` и генератор XLSX печатают ровно то, что им дали,
и файл получается валидным. Просто со следующего столбца всё уезжает на одну
клетку, и владелец читает дату закрытия под подписью «Результат». Ошибки нет,
данные есть, отчёт неверен целиком — и заметить это можно только сверив файл с
перепиской вручную.

Проверка стоит одного вызова чистой функции ровно потому, что разбор строки
вынесен из генератора в `stats.conv_row` (см. её докстринг).
"""

import inspect
import re
from datetime import timedelta

from app.services import stats
from app.services import stats as st


def _sql_without_comments(sql: str) -> str:
    """SQL без строк-комментариев `--`.

    Иначе проверки ниже читали бы объяснения, а не запрос: в этом проекте
    комментарии длинные и НАЗЫВАЮТ то, что убрали, — то есть слово `outcome`
    в тексте есть и должно там быть. Тест, спотыкающийся о собственный
    комментарий, заставляет объяснение вычищать, а объяснение здесь дороже.
    """
    return re.sub(r"--[^\n]*", "", sql)


#: Строка выборки со ВСЕМИ ключами, которые читает `conv_row`. Значения не
#: важны — важен состав: пропущенный ключ здесь даст KeyError, то есть тест
#: заодно ловит рассогласование разбора с SQL.
FAKE_ROW = {
    "first_client_at_msk": "2026-08-12 09:00",
    "account_title": "Ремонт техники СПб",
    "client_name": "Иван",
    "client_phone": "+79990000000",
    "item_title": "Ремонт холодильника",
    "status": "closed",
    "assignee_name": "Пётр Ковалёв",
    "first_operator_name": "Пётр Ковалёв",
    "frt_operator_sec": 42,
    "frt_operator_biz_sec": 42,
    "frt_bot_sec": None,
    "msgs_in": 3,
    "msgs_out_operator": 2,
    "msgs_out_bot": 0,
    "closed_by": "operator",
    "closed_at_msk": "2026-08-12 10:00",
    "conversation_id": "11111111-1111-1111-1111-111111111111",
}


def test_every_header_has_a_value_under_it() -> None:
    """Столько же значений, сколько подписей. Иначе отчёт уезжает на клетку."""
    assert len(stats.conv_row(FAKE_ROW)) == len(stats.CONV_HEADERS), (
        "заголовки листа «Диалоги» и разбор строки разошлись: "
        f"{len(stats.CONV_HEADERS)} подписей против {len(stats.conv_row(FAKE_ROW))} значений. "
        "Правьте оба места — `CONV_HEADERS` и `conv_row`"
    )


def test_the_row_reads_only_columns_the_query_provides() -> None:
    """Каждый ключ разбора есть в выборке.

    Третье место той же правки: колонки убирались ещё и из `_CONV_ROWS_SQL`.
    Ключ, оставшийся в разборе без столбца в запросе, — это KeyError на первой
    же строке боевой выгрузки, то есть отчёт, который не собрался вовсе.

    Проверяется ИМЕННО ЭТО НАПРАВЛЕНИЕ. Обратное («в запросе нет лишнего»)
    заманчиво, но надёжно не проверяется текстом: часть столбцов идёт без
    `AS`, часть с приведением типа, и разбор SQL регуляркой давал бы ложные
    падения на ровном месте — тест, которому не верят, хуже отсутствующего.
    А цена лишнего столбца — лишний трафик из курсора, не сломанный отчёт.
    """
    sql = _sql_without_comments(stats._CONV_ROWS_SQL)
    missing = sorted(key for key in FAKE_ROW if key not in sql)
    assert not missing, f"разбор строки читает столбцы, которых нет в выборке: {missing}"


def test_the_fake_row_stays_in_step_with_the_real_one() -> None:
    """`FAKE_ROW` описывает РОВНО то, что читает разбор, — без запаса.

    Без этой проверки соседние тесты тихо слабеют: лишний ключ в образце не
    мешает `conv_row` отработать, и «столбец есть в SQL» продолжает
    проверяться для колонки, которую разбор давно не читает.
    """
    read_keys = set(re.findall(r'row\["(\w+)"\]', inspect.getsource(stats.conv_row)))
    assert read_keys == set(FAKE_ROW), "образец строки разошёлся с разбором — поправьте FAKE_ROW"


def test_the_outcome_columns_are_gone_from_the_export() -> None:
    """Ни исхода, ни суммы — ни в подписях, ни в выборке.

    ОХРАНА РЕШЕНИЯ ВЛАДЕЛЬЦА ОТ 12 АВГУСТА и одновременно запись его цены:
    «Сумма, ₽» была единственным столбцом всей выгрузки, где стояли деньги.
    Пока её нет, отчёт не отвечает на вопрос «какой канал окупается».
    """
    assert "Результат" not in stats.CONV_HEADERS
    assert not [h for h in stats.CONV_HEADERS if "Сумма" in h]
    assert "outcome" not in _sql_without_comments(stats._CONV_ROWS_SQL)


def test_the_snoozed_card_is_gone_from_the_summary_export() -> None:
    """Строки «Отложено сейчас» в сводке нет, а сумма группы по-прежнему сходится.

    Карточка «Отложено» стояла пятым числом группы «прямо сейчас». Группа
    заводилась с обещанием, что её числа в сумме дают все открытые диалоги, —
    и это обещание переживает снятие карточки только потому, что вместе с ней
    ушёл и сам статус.
    """
    assert "snoozed" not in _sql_without_comments(stats._MY_TODAY_SQL)


