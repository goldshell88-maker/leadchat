class TestПодписиСвежести:
    """Файл обязан объяснять сам себя (аудит 30.08).

    ⚠ ЧТО БЫЛО. Подпись обещала «Диалоги и FRT — по данным на HH:05», но после
    STATS-04 (29.08) сводка периода, захватывающего сегодня, считается ЖИВЬЁМ:
    и «Диалогов новых», и FRT здесь свежие, а старым остаётся только лист
    «Диалоги». Владелец фильтровал лист «Диалоги» по сегодняшней дате, получал
    36 строк против 41 в «Сводке» ТОГО ЖЕ файла — и не имел ничего, чем это
    объяснить.

    Разница настоящая: сегодняшний хвост в витрину ещё не попал. Убрать её
    можно только живым близнецом листа — пересчётом всех предрассчитанных
    колонок на каждую выгрузку. Пока честнее назвать вещи своими именами.
    """

    @staticmethod
    def _пары(период: st.Period) -> dict[str, object]:
        пары = st.summary_pairs(_payload(), период, st.Filters(), refreshed_at=None)
        return {строка[0]: строка[1] for строка in пары}

    def test_период_с_сегодня_подписан_живым(self) -> None:
        сегодня = st.today_msk()
        пары = self._пары(st.Period(сегодня - timedelta(days=6), сегодня))
        assert пары["Сводка посчитана"] == "на момент выгрузки", (
            "живая сводка снова подписана витриной — числа файла нечем объяснить"
        )

    def test_прошлый_период_подписан_витриной(self) -> None:
        вчера = st.today_msk() - timedelta(days=1)
        пары = self._пары(st.Period(вчера - timedelta(days=6), вчера))
        assert пары["Сводка посчитана"] == "по витрине"

    def test_лист_диалогов_подписан_отдельно(self) -> None:
        """Раньше одна подпись стояла на обе половины файла."""
        сегодня = st.today_msk()
        пары = self._пары(st.Period(сегодня, сегодня))
        assert "Лист «Диалоги» — по данным на" in пары, (
            "витринный лист снова без собственной отметки возраста"
        )
