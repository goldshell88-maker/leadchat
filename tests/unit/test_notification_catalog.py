"""Каталог уведомлений на сервере и в интерфейсе не должен расходиться (#32).

ЧТО СЛУЧИЛОСЬ. Четыре вида уведомлений завели на сервере и не завели во
фронтенде: «клиент ждёт вашего ответа», «диалог никто не принял», «ответ не
дошёл до клиента», «очередь разгружена». Все четыре — из последних правок, то
есть расхождение появлялось раз за разом и каждый раз незаметно.

ПОЧЕМУ ЭТОГО НЕ БЫЛО ВИДНО. Каталог в интерфейсе не падает на незнакомом виде —
у него есть запасной вариант: колокольчик и слово «Уведомление». Тем он и
опасен. Самое личное и самое срочное уведомление оператора — «клиент ждёт
вашего ответа» — выглядело в колокольчике как любое другое, а в фильтре
журнала вместо русской подписи стояло машинное `conversation.awaiting_you`.
Ни один тест этого не проверял: с точки зрения кода всё работало.

ПОЧЕМУ ПРОВЕРКА ЖИВЁТ В PYTHON, А НЕ В ТЕСТАХ ФРОНТЕНДА. Источник правды —
сервер: он решает, какие уведомления вообще бывают. Проверять надо в ту
сторону, откуда приходит новое: добавил вид в `KINDS` — тест упал и назвал
недостающую строку. Обратная проверка (в тестах интерфейса) сработала бы
только если кто-то не забудет её обновить, то есть ровно там же, где уже
забывали.

Файл разбирается текстом, а не импортом: тащить в питоновские тесты сборщик
TypeScript ради одного словаря — цена, несопоставимая с задачей.
"""

from __future__ import annotations

import re
from pathlib import Path

from app.services.notifications import KINDS

CATALOG = (
    Path(__file__).resolve().parents[2]
    / "frontend"
    / "src"
    / "features"
    / "notifications"
    / "catalog.ts"
)


def _frontend_kinds() -> set[str]:
    source = CATALOG.read_text(encoding="utf-8")
    # Берём только тело KIND_CATALOG: за его пределами те же строки встречаются
    # в комментариях и типах, и они дали бы ложное «всё на месте».
    body = source.split("KIND_CATALOG", 1)[1].split("const FALLBACK", 1)[0]
    return set(re.findall(r'"([a-z_]+\.[a-z_]+)"\s*:\s*\{', body))


def test_every_server_notification_has_a_face_in_the_interface() -> None:
    missing = sorted(set(KINDS) - _frontend_kinds())
    assert not missing, (
        "Эти виды уведомлений сервер шлёт, а интерфейс не знает — человек увидит "
        "колокольчик и слово «Уведомление» вместо иконки и подписи: "
        f"{missing}. Добавьте их в frontend/src/features/notifications/catalog.ts"
    )


def test_the_interface_does_not_invent_kinds_the_server_never_sends() -> None:
    """Обратная сторона: подпись для несуществующего вида — мёртвый код.

    Он не вреден сам по себе, но врёт при чтении: из каталога кажется, что
    такое уведомление бывает, и его ищут в журнале.
    """
    extra = sorted(_frontend_kinds() - set(KINDS))
    assert not extra, (
        f"Интерфейс знает виды, которых сервер не шлёт: {extra}. "
        "Либо их забыли завести в app/services/notifications.py, либо это остаток."
    )


def test_every_kind_used_in_code_exists_in_the_catalog() -> None:
    """Вид, который код СОЗДАЁТ, обязан быть в каталоге центра.

    ⚠ ЭТА ДЫРА СТОИЛА НАСТОЯЩЕЙ ТРЕВОГИ (аудит 19.08). Соседний страж проверяет
    каталог → интерфейс: у каждого объявленного вида есть иконка и подпись. А
    обратную сторону — код → каталог — не проверял никто, и `leadbot.down` жил
    так с 18 августа: сторож его заводил, каталог о нём не знал, уведомление
    приезжало без кнопки, с запасной иконкой и записью `notification.unknown_kind`
    в журнал на каждую тревогу. Нашли это руками при разборе, а не проверкой.

    Читаем константы `KIND_* = "точка.в.имени"` по всему `app/` — именно так их
    объявляют все зоны, которые заводят уведомления.
    """
    корень = Path(__file__).resolve().parents[2] / "app"
    объявлены: dict[str, str] = {}
    for файл in корень.rglob("*.py"):
        for имя, значение in re.findall(
            r'^(KIND_[A-Z_]+)\s*[:=]\s*(?:str\s*=\s*)?["\']([a-z_]+\.[a-z_]+)["\']',
            файл.read_text(encoding="utf-8"),
            re.M,
        ):
            объявлены[значение] = f"{файл.relative_to(корень.parent)}:{имя}"

    # Виды, которые НЕ порождают уведомления, — с причиной, а не молча.
    # Список намеренно крошечный: каждая новая строка здесь означает «этот вид
    # человеку не показывается», и написать почему обязан тот, кто её добавил.
    НЕ_УВЕДОМЛЕНИЯ = {
        "backup.ok": (
            "сигнал успешного бэкапа: ставит отметку в Redis, чтобы сторож заметил "
            "ТИШИНУ. Уведомлять об успехе нечего (см. internal.py)"
        ),
    }
    чужие = sorted(вид for вид in объявлены if вид not in KINDS and вид not in НЕ_УВЕДОМЛЕНИЯ)
    assert not чужие, (
        "код заводит виды, которых нет в каталоге центра: "
        + ", ".join(f"{в} ({объявлены[в]})" for в in чужие)
        + ". Такое уведомление приедет человеку без кнопки и с запасной иконкой, "
        "а в журнал на каждую тревогу ляжет notification.unknown_kind. "
        "Допишите вид в app/services/notifications.py::KINDS."
    )


def test_every_kind_in_the_catalog_is_actually_produced_by_someone() -> None:
    """Обратная сторона соседней проверки: каталог → код.

    ⚠ ТРИ ВИДА ОБЕЩАЛИ И НЕ ДЕЛАЛИ (аудит 19.08, находка L-012). Каталог
    объявлял «Сообщения не уходят клиентам», «AI временно недоступен» и «Клиент
    недоволен» — с подписью, иконкой и фильтром в журнале, — а создавать их было
    некому: ни одной боевой строки. Владелец рассчитывал на тревогу, которой не
    существует, и это хуже, чем её отсутствие: на неё расчитывают.

    Соседний страж ловит обратное направление (код заводит вид, которого нет в
    каталоге), и он бы этого не увидел никогда. Нашли руками, машинным разбором
    всего `app/`; здесь та же работа закреплена проверкой.

    Ищем упоминание вида в ЛЮБОМ файле `app/`, кроме самого каталога: виды
    заводят и литералом (`kind="queue.backlog"`), и через константу
    (`KIND_DROPPED_DISABLED = "inbound.dropped_disabled"`). Проверка нарочно
    грубая — она отвечает на один вопрос: «этот вид вообще где-нибудь живёт,
    кроме объявления?»

    Проверка ломанием: заведите в KINDS вид `test.never` — тест краснеет.
    """
    корень = Path(__file__).resolve().parents[2] / "app"
    каталог = корень / "services" / "notifications.py"
    тексты = [файл.read_text(encoding="utf-8") for файл in корень.rglob("*.py") if файл != каталог]

    # Вид, который объявлен намеренно без источника, — со строкой «почему».
    # Пустой словарь здесь и должен оставаться: «объявлен и никем не создаётся»
    # — это и есть та беда, ради которой проверка написана.
    БЕЗ_ИСТОЧНИКА: dict[str, str] = {}

    немые = sorted(
        вид
        for вид in KINDS
        if вид not in БЕЗ_ИСТОЧНИКА
        and not any(f'"{вид}"' in текст or f"'{вид}'" in текст for текст in тексты)
    )
    assert not немые, (
        "каталог объявляет виды, которых не создаёт никто: "
        + ", ".join(немые)
        + ". Человек видит подпись и фильтр в журнале и ждёт тревогу, которой не "
        "существует. Либо заведите источник, либо уберите вид из KINDS."
    )


def test_every_queue_frame_carries_its_channel_audience() -> None:
    """Кадр очереди обязан нести список допущенных — иначе фильтр каналов мёртв.

    ⚠ МЕХАНИЗМ БЫЛ НАПИСАН, ПОКРЫТ ТЕСТАМИ И НЕ РАБОТАЛ (аудит 19.08). Фильтр
    `_channel_allows` в хабе честно проверяет список операторов канала, но
    список этот проставлял РОВНО ОДИН публикатор из семи. Пустой список по
    правилу совместимости означает «канал открыт всем» — значит кадр очереди
    чужого канала уезжал каждому менеджеру: звук на чужого клиента, чужая
    строка в очереди, 403 при попытке взять. На двух каналах терпимо, на
    девяти — то самое смешение аккаунтов, которого владелец не хочет.

    Держим свойство текстом, а не памятью: публикация `inbox:new` идёт либо
    через `publish_inbox_new` (там список — именованный параметр), либо через
    кадр из `inbox_frame_addressed`, либо адресно одному человеку
    (`only_user=`). Голый `publish_event(..., INBOX_NEW, ...)` без адреса —
    это возврат мёртвого фильтра.
    """
    корень = Path(__file__).resolve().parents[2] / "app"
    нарушители: list[str] = []
    for файл in корень.rglob("*.py"):
        if файл.name == "hub.py":  # дом самого механизма
            continue
        текст = файл.read_text(encoding="utf-8")
        for номер, строка in enumerate(текст.splitlines(), 1):
            if "publish_event(" not in строка or "INBOX_NEW" not in строка:
                continue
            хвост = "\n".join(текст.splitlines()[номер - 1 : номер + 6])
            if "only_user" in хвост or "INBOX_ELIGIBLE_KEY" in хвост:
                continue
            нарушители.append(f"{файл.relative_to(корень.parent)}:{номер}")
    assert not нарушители, (
        "кадр очереди публикуется без адреса — он уедет операторам ЧУЖИХ каналов: "
        + ", ".join(нарушители)
        + ". Используйте publish_inbox_new(..., eligible_operator_ids=...) или "
        "inbox.inbox_frame_addressed()."
    )
