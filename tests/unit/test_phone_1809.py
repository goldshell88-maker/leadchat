"""Телефоны по скринам владельца 18.09: невидимые разделители и хвост словом.

СЛУЧАЙ 12 — на экране номер вида «7900 111-22-43», в карточке «телефона нет».
Перепечатанная руками строка разбиралась и до правки, значит в бою между «7900»
и «111» стоит символ, которого на скрине не видно: табуляция, тонкий пробел,
длинное тире или знак минуса с клавиатуры iOS. Список разделителей был закрытым —
любой такой символ рвал цепочку на «7900» и «111-22-43», 4 и 6 цифр.

СЛУЧАЙ 15 — «+790011122 сорок»: последние цифры продиктованы словом. Девять
цифр номером не считались. Правило узкое: цифр 9–10, слова дополняют РОВНО до
одиннадцати, результат — мобильный; точка и скобки между словами кончают номер;
слово-единица за числительным («две тысячи», «два дня») делает его количеством.

ДИВЕРСИИ (каждая обязана краснеть): вернуть закрытый список разделителей →
табуляция и тире снова рвут цепочку; убрать проверку «ровно 11» → «три ноль
ноль» станет номером; убрать сторож «ещё число за словами» → «тридцать, два»
даст …30; включить перевод строки в разделители → два номера на двух строках
пропадут оба; вернуть `_SEP` между словами → «сорок. Два этажа» даст …42;
убрать `_единица_за_словами` → «две тысячи рублей» даст …2; вернуть
`_SEP*[,;]?_SEP*` в `_ЗА_СЛОВАМИ_ЧИСЛО` → пять тысяч пробелов за словом
разбираются три секунды.

НОМЕРА ЗДЕСЬ ВЫМЫШЛЕННЫЕ, серия +7 900. На скринах владельца стояли номера живых
клиентов, и в тесты они не попадают — форма записи сохранена как на скринах,
цифры нет; :func:`test_в_файле_только_вымышленные_номера` это сторожит.
"""

import re
