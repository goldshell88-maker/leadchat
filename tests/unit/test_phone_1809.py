# --- сторож: в этом файле нет номеров живых людей --------------------------------

#: `\uXXXX`, `\t`, `\n` в исходнике — текст с обратной косой, а не символ; без
#: подстановки «7900 111-22-43» выглядит для разбора как «7900» и мусор.
_ЭКРАНИРОВАНИЕ = re.compile(r"\\(?:u[0-9a-fA-F]{4}|[tnr])")


def test_в_файле_только_вымышленные_номера() -> None:
    """На скринах владельца стояли номера живых клиентов; сюда они не попадают.

    Всё, что разбор находит в тексте этого файла, обязано быть из вымышленной
    серии +7 900. Диверсия: любой номер другой серии в любом тесте выше.
    """
    исходник = Path(__file__).read_text(encoding="utf-8")
    текст = _ЭКРАНИРОВАНИЕ.sub(lambda m: "\n" if m.group(0) in ("\\n", "\\r") else " ", исходник)
    чужие = sorted({f.raw for f in phone_parse.find_all(текст) if not f.value.startswith("+7900")})
    assert чужие == []


