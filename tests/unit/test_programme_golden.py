"""Золотой корпус программы «автоматически и точно» (21.09, пакет 6.0б, I-6).

Синтетические контрпримеры по образцу `test_address_corpus_1209`: реплики
вымышленные, чисел из боя нет, имён и телефонов нет. Боевой золотой корпус
живёт в контейнере (`address-reparse --golden`, программа §0.2 С-6); здесь —
то, что обязано держаться в git при любой починке разбора и сторожа карты.

Две части:

* ВЫЖИВАЮТ — контрпримеры, которые починки §3.1 (месяцы, числовой префикс,
  род прилагательного) трогать не вправе: падеж — не род («Первомайской 12»),
  тип улицы, названный клиентом, — единственная защита от «Комсомольская ↔
  Комсомольский проспект» (§3.5 Q12: нынешнее поведение закреплено фактом,
  чтобы Q12 не считался защитой от него), места «с. Новое Заозерье» и
  «пос. Майский» читаются как места. Ожидания сняты ПРОГОНОМ 21.09
  (`uv run python`), не выдуманы.
* ПАДАЮТ ДО ПОЧИНКИ — контрпримеры §3.1, на которых код сегодня даёт
  неверный ответ: `_улица_не_шире("улица 40 лет Октября", "Октября") is True`,
  `("улица 8 Марта", "Марта") is True`, `("улица Юбилейная", "Юбилейный") is
  True`, `("улица Майская", "Майский") is True`; разбор поднимает «Марта 12»
  и «Октября 5» целой репликой до B. Они помечены `xfail(strict=True)`:
  починка §3.1 обязана снять xfail осознанно, а не пройти мимо.
* ВЫЖИВАЮТ ПОД СТОП (пакет 7a, Q16) — контрпримеры стоп-классов речи при
  ВСЕХ одиннадцати правилах `STOP_*=on` разом: разбор тот же, что без правил.
  Ожидания сняты прогоном 21.09.

ДИВЕРСИИ (каждая прогнана 21.09 «правка → тест → откат», хеш файла сверен):
`_основа_совпала` → только равенство слов — краснеет
`test_улица_карты_выживает[улица Первомайская]` (падеж) и
`…[Комсомольский проспект-Комсомольская]`, а оба xfail рода проходят и роняют
прогон как XPASS(strict) — так корпус ловит слишком широкую починку; убрать сверку типа в
хвосте `_улица_не_шире` — краснеет `…[Комсомольский проспект-Комсомольская
улица]`; убрать `house_key` из `same_address` — краснеет
`test_один_адрес[Ленина-5-Ленина-5а]`; убрать сверку типов из `same_address`
— краснеет `test_один_адрес[ул Ленина-5-проспект Ленина-5]`; в `parse_place`
не пускать «с.» с точкой и заглавной — краснеет `test_место[с. Новое
Заозерье]`; научить `_улица_не_шире` отвергать месяц одним словом
(починка §3.1) — `test_карта_месяц_и_префикс_до_починки[улица 8 Марта]`
проходит и strict-xfail роняет прогон: так и задумано.
"""

