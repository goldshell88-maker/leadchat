"""ОБЩИЕ БЫСТРЫЕ ОТВЕТЫ ПОЯВЛЯЮТСЯ У ВСЕХ САМИ.

⚠ ПРОСЬБА ВЛАДЕЛЬЦА 28.08: «быстрые ответы должны автоматически появляться у
людей, чтобы им не обязательно было самому их вручную прописывать».

ЧТО БЫЛО. Правило видимости давно верное — человек видит СВОИ личные плюс ВСЕ
общие (`owner_id IS NULL`). Только общих в базе было РОВНО НОЛЬ: замер 28.08 дал
двадцать заготовок, все личные, восемнадцать из них у одного человека.
Остальные двенадцать диспетчеров открывали пустую полосу и набирали
«Здравствуйте» руками — шесть с половиной тысяч раз за месяц.

Завести общие через интерфейс менеджер не мог: право `templates:shared` есть
только у администратора и руководителя. То есть у большинства не было ни
заготовок, ни способа их получить.

⚠ ФРАЗЫ ИЗМЕРЕНЫ, А НЕ ПРИДУМАНЫ. Все двенадцать взяты из боевых исходящих и
повторяются от сотни раз. Заготовка, сочинённая за столом, ложится мимо того,
как разговаривают на самом деле, и ею не пользуются.
"""

import pytest
import sqlalchemy as sa

from app.data.base_templates import БАЗОВЫЕ_ЗАГОТОВКИ
from app.models.template import Template

pytestmark = pytest.mark.anyio


def test_the_set_is_not_empty_and_has_no_duplicate_titles() -> None:
    имена = [t for _, t, _, _ in БАЗОВЫЕ_ЗАГОТОВКИ]
    assert len(имена) >= 30, "набор подозрительно мал для выборки из истории"
    assert len(set(имена)) == len(имена), "два одинаковых заголовка — вторая заготовка недостижима"


def test_no_title_is_a_prefix_of_another() -> None:
    """Заголовок не должен быть НАЧАЛОМ другого заголовка.

    ⚠ ПРАВИЛО СМЕНИЛОСЬ ВМЕСТЕ С РАЗМЕРОМ НАБОРА (28.08, вечер). У первых
    двенадцати заготовок стояло «первые три буквы у всех разные», и это было
    посильно. На тридцати девяти такое правило заставляло бы выдумывать
    заголовки ради самого правила — а заголовок должен называть смысл, а не
    занимать свободную букву.

    Что действительно мешает выбору, так это заголовок, целиком совпадающий с
    началом другого: набрав его, человек не может отделить один от другого.
    Совпадение первых букв у «Записал» и «Занимаюсь таким» помехой не является:
    список показывает оба, и третья буква их разводит.
    """
    имена = [t for _, t, _, _ in БАЗОВЫЕ_ЗАГОТОВКИ]
    for a in имена:
        for b in имена:
            if a is b or a == b:
                continue
            assert not b.lower().startswith(a.lower()), (
                f"«{a}» — начало «{b}»: набрав первый, человек не отделит его от второго"
            )


def test_bodies_are_ready_to_send() -> None:
    """Тело — готовая фраза, а не заготовка заготовки.

    Пустое или однословное тело означает, что человеку всё равно дописывать
    руками, — то есть ровно то, от чего просьба и уводит.
    """
    for _, имя, тело, _ in БАЗОВЫЕ_ЗАГОТОВКИ:
        assert len(тело.strip()) >= 10, f"«{имя}»: тело слишком короткое, дописывать придётся"
        assert not тело.strip().endswith(","), f"«{имя}»: тело обрывается на запятой"


def test_the_strongest_measured_phrase_is_in_the_set() -> None:
    """«Запишу вас» — самый сильный приём в тексте по отдельному замеру.

    +35,9 процентного пункта к доле дошедших до заявки. Набор без него был бы
    набором вежливых фраз, а не рабочим инструментом.
    """
    все = " ".join(тело.lower() for _, _, тело, _ in БАЗОВЫЕ_ЗАГОТОВКИ)
    assert "запишу вас" in все


async def test_seeding_creates_shared_templates_visible_to_everyone(db_sessionmaker) -> None:
    """Созданные заготовки — ОБЩИЕ: `owner_id` пуст, значит видят все."""
    набор = БАЗОВЫЕ_ЗАГОТОВКИ

    async with db_sessionmaker() as db:
        for папка, имя, тело, _ in набор:
            db.add(Template(owner_id=None, title=имя, body=тело, folder=папка))
        await db.commit()

    async with db_sessionmaker() as db:
        rows = (await db.execute(sa.select(Template))).scalars().all()
        assert len(rows) == len(набор)
        assert all(r.owner_id is None for r in rows), (
            "заготовка досталась одному человеку — остальные снова увидят пустую полосу"
        )


async def test_seeding_twice_adds_nothing(db_sessionmaker) -> None:
    """Повтор ничего не задваивает — отбор идёт по заголовку.

    И, что важнее, не переписывает текст: общая заготовка после создания
    принадлежит команде, и возвращать её к исходной при каждой выкатке значило
    бы молча отменять чужую правку.
    """
    async with db_sessionmaker() as db:
        db.add(Template(owner_id=None, title="Здравствуйте", body="Свой текст", folder=None))
        await db.commit()

    async with db_sessionmaker() as db:
        существуют = {
            имя
            for (имя,) in (
                await db.execute(sa.select(Template.title).where(Template.owner_id.is_(None)))
            ).all()
        }
        нехватает = [z for z in БАЗОВЫЕ_ЗАГОТОВКИ if z[1] not in существуют]
        assert "Здравствуйте" not in [t for _, t, _, _ in нехватает]

        for папка, имя, тело, _ in нехватает:
            db.add(Template(owner_id=None, title=имя, body=тело, folder=папка))
        await db.commit()

    async with db_sessionmaker() as db:
        свой = (
            (await db.execute(sa.select(Template).where(Template.title == "Здравствуйте")))
            .scalars()
            .all()
        )
        assert len(свой) == 1, "заголовок задвоился"
        assert свой[0].body == "Свой текст", "повтор переписал текст, поправленный командой"


def test_no_prices_in_the_shared_set() -> None:
    """ЦЕН В ОБЩЕМ НАБОРЕ НЕТ, И ЭТО НЕ ЗАБЫВЧИВОСТЬ.

    В личных заготовках одного человека лежат «Выезд и диагностика 1000 рублей»,
    «Диагностика 500 рублей» и «Выезд бесплатный» — условия РАЗНЫХ каналов.
    Сделай их общими на все девять, и оператор однажды назовёт клиенту чужую
    цену; отозвать это нечем.

    Проверка ищет цифры: любая сумма в общей заготовке — это обещание от имени
    канала, которого мы не знаем.
    """
    import re

    с_ценой = [имя for _, имя, тело, _ in БАЗОВЫЕ_ЗАГОТОВКИ if re.search(r"\d", тело)]
    assert с_ценой == [], (
        f"в общих заготовках появились числа: {с_ценой}. Условия у каналов разные, "
        "и общая заготовка назовёт клиенту чужую цену"
    )


def test_every_phrase_is_earned() -> None:
    """У каждой заготовки записано, сколько раз её набрали руками.

    Число — это доказательство, что фраза не выдумана за столом. Ноль означает,
    что кто-то дописал строку от себя, и её место в наборе ничем не подтверждено.
    """
    for _, имя, _, раз in БАЗОВЫЕ_ЗАГОТОВКИ:
        assert раз >= 30, f"«{имя}»: набрано {раз} раз — этого мало, чтобы звать фразу общей"


def test_folders_group_the_set() -> None:
    """Папки — не украшение: тридцать девять строк списком не читаются.

    Порядок папок отвечает порядку разговора: открытие, диагностика, где и
    когда, контакты, цена, отказ, закрытие.
    """
    папки = [f for f, _, _, _ in БАЗОВЫЕ_ЗАГОТОВКИ]
    assert all(папки), "у заготовки нет папки — в списке из сорока строк её не найти"
    assert len(set(папки)) >= 5
