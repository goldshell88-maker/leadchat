"""Дожим молчащему клиенту в дефолтном сценарии — по живым, а не через 5 минут.

ИЗМЕРЕНО (свежий корпус Jivo, 27 786 диалогов, 3202 настоящих дожима — пауза
оператора дольше двух минут без ответа клиента):

    p25 = 11.3 мин · медиана = 25.2 мин · p75 = 45.5 мин
    быстрее пяти минут — 11% дожимов

Сценарий «Первичный приём» пинговал ровно через 5 минут, то есть быстрее 89%
живых операторов. Регламент прямо связывает настырность с жалобами на Авито и
блокировкой аккаунта партнёра, так что это не косметика.

Число закреплено тестом намеренно: в JSON комментария не поставить, а голое «20m»
через полгода прочтут как случайное и «подкрутят».
"""

from __future__ import annotations

from app.bots.scenarios import default_scenario

ПИНГУЕМЫЕ_ШАГИ = ("ask_problem", "ask_phone")


def _step(scenario, sid):
    return next(s for s in scenario["steps"] if s["id"] == sid)


def test_дожим_не_раньше_живых():
    сценарий = default_scenario()
    for sid in ПИНГУЕМЫЕ_ШАГИ:
        шаг = _step(сценарий, sid)
        assert шаг["params"]["timeout"] == "20m", (
            f"{sid}: дожим быстрее 20 минут обгоняет 89% живых операторов"
        )
        assert шаг["on_timeout"], f"{sid}: ветка таймаута обязана вести на пинг"


def test_долгое_ожидание_не_тронуто():
    """Сутки на второй заход и ночные 12 часов — другие величины, их не двигали."""
    сценарий = default_scenario()
    assert _step(сценарий, "ask_problem_2")["params"]["timeout"] == "24h"
    assert _step(сценарий, "ask_phone_2")["params"]["timeout"] == "12h"
