"""Дефолт ожидания клиента — десятки минут, а не сутки.

ПОВОД. Разбор боевой базы 28.08: из 155 передач диалога человеку 84 (54 %) судья
признал лишними, и самая частая причина — молчание клиента. Боевой сценарий
лид-бота задаёт шаг `wait_client` БЕЗ поля `timeout`, а дефолт в движке был «24h»:
напоминание уходило через сутки, передача человеку — через двое.

ДВА ЗАМЕРА СХОДЯТСЯ НА ДЕСЯТКАХ МИНУТ.
  · живые дожимы (27 786 диалогов, 3202 напоминания): p25 = 11 мин, медиана 25 мин,
    p75 = 46 мин — те же числа держит test_default_scenario_ping;
  · отдача напоминания (5 269 случаев, архив Jivo): через 1–15 мин клиент отвечает
    в 43,1 %, через 15–60 мин — 27,6 %, через 1–4 ч — 18,5 %, через 4–12 ч — 12,2 %.

Взята медиана живых — 25 минут. Быстрее нельзя: регламент Авито связывает
настырность с жалобами и блокировкой аккаунта партнёра.
"""

from __future__ import annotations

from datetime import timedelta

from app.bots.steps import parse_timeout


def _дефолт():
    """Ровно то выражение, что стоит в движке: шаг без своего timeout."""
    return parse_timeout({}.get("timeout", "25m"))


def test_дефолт_не_сутки() -> None:
    assert _дефолт() == timedelta(minutes=25)
    assert _дефолт() < timedelta(hours=1), "сутки ожидания — клиента к тому времени нет"


def test_дефолт_не_настырный() -> None:
    """⚠ Быстрее пяти минут пинговать нельзя — так делают 11 % живых, а регламент
    Авито связывает настырность с жалобами и блокировкой аккаунта."""
    assert _дефолт() >= timedelta(minutes=10)


def test_движок_берёт_именно_этот_дефолт() -> None:
    """Проводка: значение должно стоять в самом движке, а не только здесь."""
    import inspect

    from app.bots import engine

    src = inspect.getsource(engine)
    assert 'params.get("timeout", "25m")' in src, "движок ждёт по другому дефолту"
    assert 'params.get("timeout", "24h")' not in src


def test_явный_таймаут_шага_сильнее_дефолта() -> None:
    """Шагу, которому нужны сутки, никто не мешает их задать."""
    assert parse_timeout({"timeout": "24h"}.get("timeout", "25m")) == timedelta(hours=24)
    assert parse_timeout({"timeout": "5m"}.get("timeout", "25m")) == timedelta(minutes=5)
