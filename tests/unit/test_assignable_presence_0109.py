"""СПИСОК «КОМУ ПЕРЕДАТЬ» ОБЯЗАН ОТЛИЧАТЬ РАБОТАЮЩЕГО ОТ ОТОШЕДШЕГО.

⚠ ЖАЛОБА ВЛАДЕЛЬЦА 01.09 со скриншотом этого самого окна: «показывается, что
люди онлайн в работе, а у кого-то просто вкладка открыта, у кого-то просто ПК
включён».

ПРИЧИНА БЫЛА ЗДЕСЬ, А НЕ В МЕХАНИЗМЕ. Ручка отдавала одно поле `is_online`, а
считалось оно через `presence_map`, то есть `bool(значение_ключа)`: ключ
присутствия существует — значит «в сети». Но у ОТОШЕДШЕГО ключ тоже существует,
в нём просто лежит строка «away». Авто-«отошёл» исправно писал статус — замер на
бою 01.09 показал троих `away` и двоих `online`, — а окно передачи красило всех
пятерых одинаково зелёными.

⚠ ОТОШЕДШЕГО НЕ ПРЯЧЕМ И СТРОКУ НЕ УБИРАЕМ. Он за столом: видит диалоги,
отвечает, и сервер такую передачу принимает (`test_away_counts_as_present` в
соседнем файле). Убрать его из списка значило бы соврать в другую сторону —
руководитель перестал бы ему передавать вовсе. Врёт не наличие строки, а её цвет.

⚠ `is_online` СОХРАНЯЕТ ПРЕЖНИЙ СМЫСЛ. Его читают и другие места; сузить его
тихо значило бы поменять смысл поля под теми, кто о правке не знает. Поэтому
добавлено отдельное поле `presence` — ровно как у списка сотрудников, который
различал состояния с самого начала.
"""

import pytest

pytestmark = pytest.mark.anyio


def auth(tokens) -> dict[str, str]:  # noqa: ANN001
    return {"Authorization": f"Bearer {tokens['admin']}"}


async def _строки(client, tokens) -> dict[str, dict]:  # noqa: ANN001
    r = await client.get("/api/v1/users/assignable", headers=auth(tokens))
    assert r.status_code == 200, r.text
    return {row["full_name"]: row for row in r.json()["items"]}


async def test_отошедший_отличим_от_работающего(client, tokens, make_user, в_сети) -> None:
    работает = await make_user("work@leadchat.test", role="manager", full_name="Пётр Ковалёв")
    обедает = await make_user("lunch@leadchat.test", role="manager", full_name="Анна Петрова")
    await в_сети(работает, "online")
    await в_сети(обедает, "away")

    строки = await _строки(client, tokens)

    assert строки["Анна Петрова"]["presence"] == "away", (
        "отошедший неотличим от работающего — руководитель отдаёт диалог тому, кого нет за столом"
    )
    assert строки["Пётр Ковалёв"]["presence"] == "online", (
        "работающему приписали другое состояние — врём в другую сторону"
    )


async def test_отошедший_остаётся_в_сети(client, tokens, make_user, в_сети) -> None:
    """`is_online` у отошедшего по-прежнему true — и это не оплошность.

    Отошедший на обед сидит за столом, приложение открыто, передачу сервер
    примет. Сузь здесь `is_online` — и окно передачи, отсеивающее офлайн, молча
    перестало бы показывать обедающих, то есть отменило бы решение владельца от
    28.08 правкой, задуманной совсем про другое.
    """
    обедает = await make_user("lunch2@leadchat.test", role="manager", full_name="Анна Петрова")
    await в_сети(обедает, "away")

    строки = await _строки(client, tokens)

    assert строки["Анна Петрова"]["is_online"] is True, (
        "отошедший выпал из «в сети» — окно передачи перестало его показывать"
    )


async def test_не_в_сети_даёт_пустое_состояние(client, tokens, make_user) -> None:
    """Ключа нет — состояния нет. Третьего значения на сервере не заводим."""
    ушёл = await make_user("gone@leadchat.test", role="manager", full_name="Олег Иванов")
    assert ушёл is not None

    строки = await _строки(client, tokens)

    assert строки["Олег Иванов"]["presence"] is None
    assert строки["Олег Иванов"]["is_online"] is False


async def test_подтверждение_отошёл_не_шумит_в_ленте(redis) -> None:
    """Повтор «отошёл» продлевает TTL, но кадр шлёт только на СМЕНУ значения.

    ⚠ ЭТО РЕГРЕССИЯ, КОТОРУЮ ВНОСИТ САМА ПРАВКА, И ОНА НАЙДЕНА ДО ВЫКАТКИ.

    Авто-«отошёл» с 01.09 ПОДТВЕРЖДАЕТ статус раз в две минуты: без этого его
    затирает `presence_connected` после любого обрыва — в том числе после нашей
    же выкатки, которая рвёт все сокеты разом. Но `set_presence` публиковала
    кадр на КАЖДЫЙ вызов. Тринадцать отсутствующих за ночь дают тысячи кадров, а
    лента событий держит 300 строк и повторы не склеивает: к утру в ней не
    осталось бы ничего, кроме «Пётр Ковалёв — отошёл», и настоящие события
    вытеснились бы у администратора и руководителя.

    TTL продлевается всегда — в этом весь смысл подтверждения. Молчит только
    публикация.
    """
    from app.ws import presence as presence_module
    from tests.unit.conftest import drain_events

    uid = "11111111-1111-1111-1111-111111111111"
    pubsub = redis.pubsub()
    await pubsub.subscribe("events")

    await presence_module.set_presence(redis, uid, "away")
    первый = await drain_events(pubsub)
    assert any(e.get("type") == "presence:online" for e in первый), (
        "смена состояния перестала доезжать до коллег"
    )

    # Три подтверждения подряд — ровно то, что делает вкладка ночью.
    for _ in range(3):
        await presence_module.set_presence(redis, uid, "away")
    повторы = await drain_events(pubsub)

    assert повторы == [], (
        "подтверждение «отошёл» шлёт кадр каждый раз — за ночь лента событий забьётся ими"
    )
    assert await redis.ttl(f"presence:{uid}") > 0, (
        "подтверждение перестало продлевать TTL — человек выпадет из сети, пока сидит за столом"
    )
