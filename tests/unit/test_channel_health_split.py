"""Фраза здоровья канала делится на заголовок и деталь — и ни одна ветка не забыта.

ЧТО БЫЛО. Разбор интерфейса 13.08: «янтарный абзац сократить до одной фразы, детали
под раскрытие». Замер на живом экране: 190 знаков у `silence_abnormal`, 157 у
`refresh_failed` — пять-шесть строк в колонке карточки шириной 280. Читают такую
строку боковым зрением, а прочитать её так нельзя.

ПОЧЕМУ ДЕЛИТ СЕРВЕР. Фронту разбирать `message` запрещено прямо (ChannelHealth.tsx):
возьмёт оттуда хоть одно число — и заведёт по нему своё правило, то самое, из-за
которого экран горел жёлтым круглосуточно. Резать регуляркой — то же нарушение
другим способом.

⚠ ПОЧЕМУ `message` ПРИ ЭТОМ НЕ ТРОНУТ. Сервер и фронт выкатываются порознь. Укороти
`message` — и в окно между выкатками человек на старой сборке теряет вторую половину
фразы насовсем. Поэтому заведены ДВА НОВЫХ поля, а `message` остался букву в букву:
старая сборка не заметит ничего, новая при старом сервере увидит пустой `headline` и
нарисует `message` целиком.

⚠ ЧТО ИМЕННО СТЕРЕЖЁТ ЭТОТ ФАЙЛ — НЕ ТЕКСТЫ, А ПОЛНОТУ. Ветка, добавленная завтра без
`headline`, не уронит ни один тест тут или в соседних файлах: поле необязательное,
фронт молча откатится на длинный `message`, и абзац вернётся на пять строк ровно в том
состоянии, которое заведут последним. Поймать это иначе нечем — экран отрисуется без
единой ошибки.
"""

from __future__ import annotations

import inspect
import re

from app.services import channel_health

#: Все ветки, возвращающие строку здоровья. Имя ветки — её `reason`; `None` у штатной.
ВЕТКИ_ТОКЕНА = {
    "service_stub",
    "disabled",
    "unknown",
    "expired",
    "refresh_broken",
    "refresh_failed",
    "expiring",
    None,
}
ВЕТКИ_ПОДПИСКИ = {
    "service_stub",
    "unregister_failed",
    "disabled",
    # ⚠ ОДНА ветка, а не две: `reason=f"subscription_{audit.result}"` даёт и
    # `subscription_foreign`, и `subscription_none` из одного `return`. Первая
    # редакция этого списка развела их — сторож ниже поймал ошибку в самом себе.
    "subscription_lost",
    "register_failed",
    "not_registered",
    "no_events_yet",
    "silence_abnormal",
    "quiet_but_normal",
    "quiet_unknown_rhythm",
    None,
}


def _исходник(имя: str) -> str:
    return inspect.getsource(getattr(channel_health, имя))


def _ветки(исходник: str) -> list[str]:
    """Куски исходника от `return XHealth(` до закрывающей скобки — по одному на ветку."""
    куски = []
    for м in re.finditer(r"return (?:Token|Webhook)Health\(", исходник):
        хвост = исходник[м.end() :]
        глубина = 1
        for i, ч in enumerate(хвост):
            if ч == "(":
                глубина += 1
            elif ч == ")":
                глубина -= 1
                if глубина == 0:
                    куски.append(хвост[:i])
                    break
    return куски


def test_у_каждой_ветки_есть_заголовок():
    """Ни одного `return` без `headline` — иначе фронт тихо откатится на длинный текст."""
    забыли = []
    for имя in ("token_health", "webhook_health"):
        for кусок in _ветки(_исходник(имя)):
            if "headline=" in кусок:
                continue
            повод = re.search(r'reason=(f?"[^"]*"|None)', кусок)
            забыли.append(f"{имя}: reason={повод.group(1) if повод else '?'}")
    assert not забыли, (
        f"ветки без `headline` — экран покажет у них длинный `message` и никто не заметит: {забыли}"
    )


def _длина(литерал: str) -> int:
    """Длина текста, который реально увидит человек.

    ⚠ ПРИБОР ПРИШЛОСЬ ЧИНИТЬ ДВАЖДЫ, И ОБА РАЗА КРАСНЕЛ ОН, А НЕ КОД.
    Первая редакция мерила сырой кусок исходника — и обвинила `unregister_failed`,
    где заголовок законно РАВЕН фразе: одна и та же фраза, разбитая переносом на два
    литерала, «длиннее» себя же в одну строку. Вторая склеивала все литералы подряд —
    и обвинила `silence_abnormal`, у которого заголовок тернарный: две взаимно
    исключающие ветки сложились в одну несуществующую строку.

    Поэтому: склеенные куски внутри ветки складываем, ветки тернарника сравниваем
    порознь и берём самую длинную — человек увидит ровно одну из них.
    """
    ветки = re.split(r"\n\s*(?:if|else)\b", литерал)
    return max((len("".join(re.findall(r'"([^"]*)"', в))) for в in ветки), default=0)


def test_заголовок_не_длиннее_фразы():
    """Заголовок не длиннее `message` — иначе делить было незачем.

    Ловит правку, которая завела поле для галочки. Равенство РАЗРЕШЕНО: у коротких
    состояний (заглушка, выключенный канал, незарегистрированная подписка) делить
    нечего, и заголовок там законно совпадает с фразой.
    """
    длиннее = []
    for имя in ("token_health", "webhook_health"):
        for кусок in _ветки(_исходник(имя)):
            заг = re.search(
                r"headline=\(?\s*(.*?)\s*\)?,\n(?=\s*(?:#|detail=|action=))", кусок, re.S
            )
            соо = re.search(
                r"message=\(?\s*(.*?)\s*\)?,\n(?=\s*(?:#|headline=|action=))", кусок, re.S
            )
            if not заг or not соо:
                continue
            if _длина(заг.group(1)) > _длина(соо.group(1)):
                повод = re.search(r'reason=(f?"[^"]*"|None)', кусок)
                длиннее.append(повод.group(1) if повод else "?")
    assert not длиннее, f"заголовок длиннее самой фразы: {длиннее}"


def test_message_остался_страховкой_на_время_выкатки():
    """`message` есть у КАЖДОЙ ветки — на нём держится старая сборка фронта."""
    без_фразы = []
    for имя in ("token_health", "webhook_health"):
        for кусок in _ветки(_исходник(имя)):
            if "message=" not in кусок:
                без_фразы.append(имя)
    assert not без_фразы, (
        f"ветка без `message`: старая сборка фронта покажет пустую строку здоровья — {без_фразы}"
    )


def test_разбор_знает_про_все_ветки():
    """⚠ Сторож самого сторожа: список веток выше не должен отстать от кода.

    Без этой проверки добавленная ветка просто не попала бы в разбор, и файл
    остался бы зелёным, охраняя на одну ветку меньше.
    """
    для = {"token_health": ВЕТКИ_ТОКЕНА, "webhook_health": ВЕТКИ_ПОДПИСКИ}
    for имя, ожидаемые in для.items():
        куски = _ветки(_исходник(имя))
        assert len(куски) == len(ожидаемые), (
            f"{имя}: веток в коде {len(куски)}, в разборе {len(ожидаемые)} — "
            "список в этом файле отстал"
        )
