def test_пояснение_в_скобках_у_карты_не_мешает_улице() -> None:
    """«ДОС 64» ↔ «ДОС квартал (Большой Аэродром)» (Хабаровск, 12.09).
    ⚠ ДИВЕРСИЯ: убрать `_без_скобок` из `_норм` — краснеет."""
    assert g._улица_не_шире("ДОС квартал (Большой Аэродром)", "ДОС")
    hit = g.GeoHit(
        street="ДОС квартал (Большой Аэродром)",
        house="64",
        settlement=None,
        city="Хабаровск",
        region="Хабаровский край",
        lat=48.47,
        lon=135.13,
        house_level=True,
    )
    assert g.format_address(hit, g.Parsed(street="ДОС", house="64")) == "ДОС квартал, 64, Хабаровск"
