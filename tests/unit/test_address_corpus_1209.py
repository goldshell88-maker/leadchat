@pytest.mark.parametrize(
    ("текст", "ожидание"), ОТВЕТЫ_НА_ВОПРОС, ids=[t for t, _ in ОТВЕТЫ_НА_ВОПРОС]
)
def test_ответ_на_вопрос_оператора(текст: str, ожидание) -> None:
    f = ap.parse(текст, про_адрес=True)
    if ожидание is None:
        assert f is None, (f.level, f.street, f.house)
        return
    уровень, улица, дом, части = ожидание
    assert f is not None, "адрес не разобран"
    assert (f.level, f.street, f.house) == (уровень, улица, дом)
    for k, v in части.items():
        assert f.parts.get(k) == v, (k, f.parts)


