@pytest.mark.asyncio
async def test_пустые_заметки_не_едут():
    """Заметка из одного префикса смысла не несёт и место в контексте занимать не должна."""
    подсказки, _ = await _engine([_Row("Подсказка бота: ", "note")]).load_bot_context(10)
    assert подсказки == []


