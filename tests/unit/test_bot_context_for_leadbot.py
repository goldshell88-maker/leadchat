"""Лид-бот получает то, чего нет в переписке: свои подсказки и звонки клиента (24.08).

ЧТО БЫЛО ВИДНО НА БОЕВОЙ. В режиме подсказки ответ бота уходит в `add_note`, а
`load_dialog_for_ai` собирает только `in`/`out` — то есть своих слов бот не получал
вовсе, и все его анти-повторные правила считали по репликам ОПЕРАТОРА. Замер на
двадцати его гардах: тринадцать меняют поведение, стоит вернуть ему свои реплики.
Отсюда три просьбы номера подряд при собственном правиле «максимум две» и одна
фраза дословно три хода подряд.

Звонок хранится служебной записью (`direction='system'`) и в переписку не входит по
построению. В живом диалоге клиент набирал номер трижды, а чат в это время просил у
него телефон и подталкивал «Ну что, подскажете?».

ПОЧЕМУ ОТДЕЛЬНЫМ ПОЛЕМ, А НЕ ЧАСТЬЮ `dialog`. Клиент подсказок НЕ ВИДЕЛ: оператор
мог их проигнорировать и написать своё. Подмешать их в переписку значит убедить
бота, что он уже поздоровался, и срезать приветствие, которого клиент не получал.
Поэтому у бота два разных вопроса и два разных источника: «что клиент слышал» —
переписка, «что я уже предлагал» — заметки.
"""

from __future__ import annotations

import uuid

import pytest

from app.bots.engine import ScenarioEngine


class _Row:
    def __init__(self, body: str, direction: str, sender: str = "bot"):
        self.body = body
        self.direction = direction
        self.sender_type = sender
        self.id = uuid.uuid4()
        self.created_at = None
        self.attachments = None


class _Scalars(list):
    pass


class _Result:
    def __init__(self, rows):
        self._rows = rows

    def scalars(self):
        return _Scalars(self._rows)

    def scalar_one_or_none(self):
        return self._rows[0] if self._rows else None


class _Db:
    def __init__(self, rows):
        self.rows = rows

    async def execute(self, *_a, **_k):
        return _Result(self.rows)


class _Conv:
    def __init__(self):
        self.id = uuid.uuid4()


def _engine(rows):
    eng = ScenarioEngine.__new__(ScenarioEngine)
    eng.db = _Db(rows)
    eng.conv = _Conv()
    return eng


# ⚠ ПОРЯДОК СТРОК — КАК ИЗ БАЗЫ: запрос идёт `created_at DESC`, метод разворачивает.
_ЛЕНТА = [
    _Row("Подсказка бота: И номер ваш подскажите, пожалуйста", "note"),
    _Row("Клиент звонил через приложение Авито", "system", "avito"),
    _Row("Подсказка бота: Понял, ждём результат. И номер ваш подскажите", "note"),
    _Row("Клиент звонил через приложение Авито", "system", "avito"),
]


@pytest.mark.asyncio
async def test_свои_подсказки_возвращаются_без_префикса():
    подсказки, _ = await _engine(_ЛЕНТА).load_bot_context(10)
    assert подсказки == [
        "Понял, ждём результат. И номер ваш подскажите",
        "И номер ваш подскажите, пожалуйста",
    ]


@pytest.mark.asyncio
async def test_звонки_посчитаны():
    _, звонков = await _engine(_ЛЕНТА).load_bot_context(10)
    assert звонков == 2


@pytest.mark.asyncio
async def test_прочие_служебные_записи_звонком_не_считаются():
    """Служебных записей у Авито много; звонок — только тот, где сказано «звонил»."""
    лента = [
        _Row("Пользователь создал чат, но пока ничего не написал", "system", "avito"),
        _Row("Объявление снято с публикации", "system", "avito"),
        _Row("Клиент звонил через приложение Авито", "system", "avito"),
    ]
    подсказки, звонков = await _engine(лента).load_bot_context(10)
    assert звонков == 1
    assert подсказки == []


@pytest.mark.asyncio
async def test_своя_запись_о_передаче_звонком_не_считается():
    """Слово «звонил» стоит и в НАШЕМ словаре причин передачи.

    `HANDOFF_REASONS["call_made"]` — «клиент звонил, о чём говорили, знает
    только оператор». Передав диалог по этой причине, бот писал свою же строку
    в ленту и на следующем тике считал её ТРЕТЬИМ звонком: два настоящих плюс
    собственная запись. Диалог уходил с ярлыком «клиент просит позвонить», и
    диспетчер звонил тому, кто звонка не просил. Обнуляет счётчик только
    исходящее, а в режиме подсказки бот исходящих не шлёт — само не проходило.

    Берём НАСТОЯЩИЙ текст передачи, а не выдуманный: разъедься формулировка со
    словарём причин — и тест начнёт стеречь фразу, которой в бою нет.
    """
    from app.bots.handoff import handoff_system_text

    своя = handoff_system_text("call_made")
    assert "звонил" in своя.lower(), "словарь причин изменился — проверять стало нечего"
    лента = [
        _Row("Клиент звонил через приложение Авито", "system", "avito"),
        _Row("Клиент звонил через приложение Авито", "system", "avito"),
        _Row(своя, "system", "system"),  # наша запись: sender_type='system'
    ]
    _, звонков = await _engine(лента).load_bot_context(10)
    assert звонков == 2, "бот посчитал звонком собственную запись о передаче"


