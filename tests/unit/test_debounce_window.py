"""Окно серии — три минуты с разбросом, и это замер, а не вкус.

СНИМОК ВЛАДЕЛЬЦА 26.08: клиент пишет в 03:10 и в 03:11, бот отвечает дважды и почти
одним текстом. Окно подсказки было 15 секунд — минутную паузу оно не накрывало.

ЗАМЕР ПО БОЕВОЙ БАЗЕ (19 077 пар подряд идущих реплик клиента): пауза внутри серии
p50 = 13 с, p75 = 32 с, p90 = 88 с, p95 = 214 с. Сколько продолжений ловит окно:

    15 с → 56 %    35 с → 77 %    60 с → 86 %
    90 с → 90 %   120 с → 92 %   180 с → 94 %

После 90 секунд отдача падает до 1–2 пунктов за полминуты. Серия — не редкость:
34 % реплик клиента приходят пачкой из двух и больше.

⚠ 26.08, ВТОРОЙ ПЕРЕСМОТР ЗА ДЕНЬ. Владелец: «бот слишком быстро пишет ответы, ещё
замедли его». Окно теперь служит двум делам: дождаться конца серии И выдержать
человеческую паузу. Замер по боевой базе (13 464 пары «реплика клиента → ответ
оператора» за 30 дней): p50 = 205 секунд. Живой мастер думает 3,4 минуты, а бот на
90 секундах отвечал быстрее большинства людей.

Цена проверена, а не предположена. Доля диалогов, где клиент оставил телефон, по
скорости первого ответа: быстрее минуты 30,7 %, 1-3 мин 23,9 %, 3-10 мин 24,1 %,
10-60 мин 21,4 %, больше часа 22,5 %. Между «1-3» и «3-10» разницы нет.

Разброс обязателен: фиксированное окно означает ответ РОВНО через N секунд каждый раз,
и по такому метроному бота видно не хуже, чем по мгновенному ответу.

⚠ 26.08, ТРЕТИЙ ПЕРЕСМОТР. Владелец: «мне не нравится таймаут 90 секунд, сделай его
гибридным от 30 до 90». Плоское число ушло совсем: окно выбирает ФОРМА последнего
сообщения клиента. Замер по боевой базе (19 806 пар «сообщение клиента → следующее
событие» в пределах 10 минут) показал, что продолжит ли клиент серию — зависит от того,
чем он закончил, и очень сильно:

    форма                        пар    продолжат    p50     p90
    вложение (фото без текста)   1522     65,9 %      5 с    40 с
    обрывок (до 3 слов)          5869     43,5 %     13 с    67 с
    без знака в конце            6807     41,5 %     13 с    67 с
    кончается точкой             1740     38,7 %     19 с   108 с
    кончается вопросом           3868     29,5 %     10 с   104 с

Берётся p90 формы — та же доля пойманных продолжений (90 %), что давало плоское окно, —
и зажимается в полосу владельца 30–90. Фото ждали 90 секунд впустую: после него клиент
дописывает почти наверняка (66 %), но в течение сорока секунд.

⚠ 27.08, ЧЕТВЁРТЫЙ ПЕРЕСМОТР — И ПЕРВЫЙ, ГДЕ ПОСЧИТАНА ЦЕНА ОЖИДАНИЯ. Всё, что выше,
считало одно: как поймать больше дописок. Сколько стоит само ожидание, не считал никто.
Замер по 28 159 диалогам архива Jivo с отметками времени, исход от паузы до ПЕРВОГО
ответа мастера:

    пауза       вернулся   заявка          пауза      заявка (сообщение-вопрос)
    0–10 с       67,6 %    19,3 %          ≤30 с      20,1 %
    10–30 с      68,0 %    18,7 %          30–90 с    15,5 %
    30–60 с      63,7 %    17,3 %          > 90 с      9,5 %
    60–90 с      62,5 %    14,1 %
    1–3 часа     28,4 %     4,6 %

Скорость — сильнейший фактор из всех замеренных: ни один приём В ТЕКСТЕ реплики не давал
больше +10 п.п., а разница «до минуты» против «через час» — 37 п.п. по возврату. При этом
мгновенность ничего НЕ добавляет: 0–10 с не лучше 10–30 с. Замер боевой базы LeadChat из
шапки выше говорит то же самое с другой стороны: быстрее минуты 30,7 %, дальше плато
21–24 %; наши 90 секунд лежали в этом плато.

⚠ ЧТО МЫ СОЗНАТЕЛЬНО ТЕРЯЕМ. Полоса 15–30 минутную паузу внутри серии НЕ накрывает —
для «обрывка» ловим около 72 % продолжений вместо прежних 90 %. Это тот самый случай со
снимка 26.08 (клиент писал в 03:10 и в 03:11), и он снова станет возможен. Размен принят
владельцем 27.08 по замеру выше: в потерянных случаях бот отвечает на неполное сообщение
и получает дописку следующим ходом, а вторую реплику подряд держит защита от повтора
в engine (`last_bot_text` и сравнение первой фразы) — она для этого и делалась.
"""

from __future__ import annotations

from datetime import timedelta

from app.bots.runtime import DEBOUNCE_AUTO, DEBOUNCE_SUGGEST, debounce_window


class _Bot:
    def __init__(self, mode: str) -> None:
        self.mode = mode


def test_окно_не_растёт_за_полминуты() -> None:
    """Обратная сторона снимка 26.08, и она посчитана 27.08.

    Прежде тут стояло требование НАКРЫТЬ минутную паузу (окно ≥ 61 с). Замер цены ожидания
    развернул его: ответ за ≤30 с даёт заявку в 20,1 % против 15,5 % за 30–90 с. Минутные
    паузы внутри серии мы теперь сознательно НЕ ждём — двойную реплику подряд держит
    защита от повтора в engine, а секунды стоят заявок.
    """
    for текст in ("Сколько будет стоить ремонт?", "Телевизор не включается.", "🖼 фото", None):
        assert debounce_window(_Bot("auto"), текст=текст) <= timedelta(seconds=30), текст


def test_пауза_не_мгновенная() -> None:
    """Владелец: «бот секунда в секунду отвечает». Полминуты — нижняя граница любой формы.

    ⚠ ПОЛОСУ 15–30 ВЫБРАЛ ВЛАДЕЛЕЦ 27.08, увидев цену ожидания (шапка файла). До этого
    полоса была 30–90 — тоже его решение, принятое до того, как эту цену посчитали.
    Нижняя граница осталась защитой от мгновенного ответа. Ни одна форма сообщения не
    имеет права выпасть из этой полосы — ни вниз (мгновенный ответ выдаёт автомат), ни
    вверх (лишние секунды прямо стоят заявок).
    """
    import uuid

    формы = (None, "🖼 фото", "да", "Иии дальше не загружается", "Не включается.", "Сколько стоит?")
    for текст in формы:
        for _ in range(200):
            окно = debounce_window(_Bot("auto"), uuid.uuid4(), текст=текст)
            assert timedelta(seconds=15) <= окно <= timedelta(seconds=30), (текст, окно)


def test_фото_не_ждёт_как_текст() -> None:
    """Смысл гибрида: 66 % фото продолжаются, но медиана паузы 5 секунд. Ждать 30 не за чем.

    Без этой проверки «гибрид» выродится обратно в одно число — достаточно свести таблицу
    форм к одному значению, и все остальные проверки останутся зелёными.
    """
    import uuid

    диалоги = [uuid.uuid4() for _ in range(80)]
    фото = max(debounce_window(_Bot("auto"), d, текст="🖼 фото") for d in диалоги)
    вопрос = min(debounce_window(_Bot("auto"), d, текст="Сколько стоит?") for d in диалоги)
    assert фото < вопрос, "фото и вопрос ждут одинаково — форма сообщения перестала влиять на окно"
    assert фото <= timedelta(seconds=17), "после фото клиент дописывает за 5 секунд (p50)"


def test_разброс_есть_и_он_постоянен_внутри_диалога() -> None:
    """Метроном выдаёт бота: одинаковые диалоги не должны отвечать через равные сроки."""
    import uuid

    from app.bots.runtime import DEBOUNCE_JITTER_S, DEBOUNCE_ПО_ФОРМЕ

    бот = _Bot("auto")
    диалоги = [uuid.uuid4() for _ in range(60)]
    текст = "Иии дальше не загружается"
    окна = {debounce_window(бот, d, текст=текст) for d in диалоги}
    assert len(окна) > 1, "разброса нет — все диалоги отвечают через одно и то же время"
    for d in диалоги:
        одно = debounce_window(бот, d, текст=текст)
        assert одно == debounce_window(бот, d, текст=текст), "окно скачет внутри одной серии"
        assert одно <= timedelta(seconds=DEBOUNCE_ПО_ФОРМЕ["без знака"])
        assert одно >= timedelta(seconds=DEBOUNCE_ПО_ФОРМЕ["без знака"] - DEBOUNCE_JITTER_S)


def test_режим_неизвестен_окно_всё_равно_есть() -> None:
    """Режим бота на окно не влияет, но пауза обязана быть при любом режиме."""
    текст = "Сколько будет стоить ремонт?"
    assert debounce_window(None, текст=текст) >= timedelta(seconds=15)
    assert debounce_window(_Bot("suggest"), текст=текст) == debounce_window(
        _Bot("auto"), текст=текст
    )
    assert DEBOUNCE_SUGGEST == DEBOUNCE_AUTO == timedelta(seconds=30), (
        "имена оставлены как потолок полосы — если они разъедутся, разъедется и смысл"
    )


def test_форма_читается_по_концовке() -> None:
    """Классификация — вся суть гибрида: ошибись в ней, и окно уедет вдвое."""
    from app.bots.runtime import МАРКЕР_ВЛОЖЕНИЯ, форма_сообщения

    assert форма_сообщения(None) == "вложение"
    assert форма_сообщения("") == "вложение"
