"""Сторож тишины не рвёт живые соединения (27.08).

⚠ ЗАМЕР БОЯ, РАДИ КОТОРОГО ЭТО НАПИСАНО. За сутки 357 подключений на 24
человек; медиана жизни соединения — 298 секунд, у одного диспетчера 166
переподключений. Гистограмма длительностей даёт пики, кратные шестидесяти
секундам, — рвал прикладной сторож `ws_heartbeat_timeout_seconds = 60`.

Соединение при этом было ЖИВЫМ: uvicorn шлёт штатный ping протокола каждые 20
секунд, браузер отвечает pong сам, без участия страницы. Но pong — управляющий
кадр, до `ws.receive_text()` он не доходит, и сторож его не видит. А наш
прикладной ping раз в 25 секунд в фоновой вкладке тормозится браузером до раза
в минуту и дольше.

Цена не в разрыве, а в догоне после него: полный список диалогов и лента
открытого через REST. Отсюда 955 запросов `/conversations` за сутки при 24
работающих — на мобильном это и читается как «сайт грузит интернет».
"""

from app.core.config import settings

#: Как часто страница шлёт прикладной ping (frontend/src/shared/realtime/WsClient.ts).
КЛИЕНТСКИЙ_PING_S = 25
#: Во сколько раз браузер способен растянуть таймер фоновой вкладки. Chrome
#: ограничивает фоновые таймеры примерно до одного срабатывания в минуту.
ЗАПАС_НА_ФОН = 2.5


def test_heartbeat_survives_a_throttled_background_tab():
    """Сторож обязан пережить фоновую вкладку, иначе рвёт живых."""
    предел_в_фоне = 60  # в фоне ping приходит раз в минуту вместо раза в 25 с
    assert settings.ws_heartbeat_timeout_seconds >= предел_в_фоне * ЗАПАС_НА_ФОН, (
        f"таймаут {settings.ws_heartbeat_timeout_seconds} с рвёт соединение, "
        "как только браузер придержит таймер фоновой вкладки"
    )


def test_presence_outlives_the_socket_watchdog():
    """⚠ ОДНО РЕШЕНИЕ ТЯНЕТ ВТОРОЕ. «На месте» продлевает ТОТ ЖЕ ping. Если
    присутствие гаснет раньше, чем сторож рвёт сокет, человек уходит «не в
    сеть» с живым соединением: коллеги видят серую точку у работающего, а
    автораздача обходит его стороной."""
    assert settings.ws_presence_ttl_seconds > settings.ws_heartbeat_timeout_seconds, (
        f"присутствие {settings.ws_presence_ttl_seconds} с гаснет раньше сторожа "
        f"{settings.ws_heartbeat_timeout_seconds} с"
    )


def test_client_ping_is_still_frequent_enough():
    """Клиентский ping должен укладываться в бюджет с большим запасом даже без
    торможения — иначе правка выше лечит следствие, а не причину."""
    assert КЛИЕНТСКИЙ_PING_S * 3 < settings.ws_heartbeat_timeout_seconds
