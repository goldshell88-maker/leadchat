"""Каждая ручка API требует токен — проверка ПОВЕДЕНИЕМ (аудит 22.08, шаг 6).

ЗАЧЕМ ИМЕННО ПОВЕДЕНИЕМ. Я дважды пробовал сосчитать защищённые ручки по коду —
регулярками по `Depends(...)` — и оба раза получил разный неверный ответ: сперва
«49 без защиты», потом «120 без защиты». Обе цифры были враньём: права висят на
именованных зависимостях (`manage_accounts`, `read_perm`, `write_perm` и других),
и перечислить их текстом надёжно не выходит. Спросить у самого приложения —
единственный способ, который нельзя обмануть опечаткой в шаблоне.

Ручка, добавленная завтра без зависимости прав, провалит этот тест в тот же день,
а не в день, когда кто-то найдёт её снаружи.

ПУБЛИЧНЫЕ ПЕРЕЧИСЛЕНЫ ПОИМЁННО и это намеренно: список — часть договора, а не
удобство. Расширять его можно только осознанно, и каждая строка объясняет себя.

Раздача вложений (`/media/{relpath}`) в списке не нужна: она закрыта не токеном,
а подписью с TTL, которую API выдаёт уже ПОСЛЕ проверки прав на диалог
(`app/api/routes/media.py`). Проверено отдельно: без подписи и с поддельной
подписью файл не отдаётся.
"""

from __future__ import annotations

import pytest

#: Ручки, которым токен не нужен по замыслу. Каждая — со своей причиной.
ПУБЛИЧНЫЕ = {
    ("POST", "/api/v1/auth/login"),  # вход: токена ещё нет
    ("POST", "/api/v1/auth/refresh"),  # обновление по refresh-куке
    ("POST", "/api/v1/auth/logout"),  # выход обязан работать всегда
    ("GET", "/api/v1/auth/invite/{token}"),  # приглашение: пропуск — сам token
    ("POST", "/api/v1/auth/invite/accept"),  # приём приглашения
    ("POST", "/api/v1/support/password-reset"),  # сброс пароля
    ("GET", "/api/health"),  # проба живости для балансировщика
    ("GET", "/api/health/deep"),  # глубокая проба
    ("POST", "/api/hooks/avito/{account_id}"),  # вебхук: пропуск — секрет в адресе
    ("GET", "/api/v1/avito/connect/{token}"),  # OAuth-переход Авито
    ("POST", "/api/v1/avito/callback"),  # OAuth-возврат Авито
    ("GET", "/api/openapi.json"),
    ("GET", "/api/docs"),
    ("GET", "/api/v1/media/{relpath}"),  # закрыта подписью, не токеном
}

ПОДСТАНОВКА = {
    "{conversation_id}": "11111111-1111-1111-1111-111111111111",
    "{account_id}": "11111111-1111-1111-1111-111111111111",
    "{client_id}": "11111111-1111-1111-1111-111111111111",
    "{message_id}": "11111111-1111-1111-1111-111111111111",
    "{bot_id}": "11111111-1111-1111-1111-111111111111",
    "{user_id}": "11111111-1111-1111-1111-111111111111",
    "{notification_id}": "11111111-1111-1111-1111-111111111111",
    "{template_id}": "11111111-1111-1111-1111-111111111111",
    "{candidate_id}": "11111111-1111-1111-1111-111111111111",
    "{session_id}": "s1",
    "{token}": "t1",
    "{relpath:path}": "a/b.jpg",
    "{relpath}": "a/b.jpg",
}


@pytest.mark.asyncio
async def test_kazhdaya_ruchka_trebuet_tokena(client, app):
    схема = app.openapi()
    голые: list[str] = []
    всего = 0
    for путь, методы in схема["paths"].items():
        for метод in методы:
            m = метод.upper()
            if m not in ("GET", "POST", "PUT", "PATCH", "DELETE"):
                continue
            if (m, путь) in ПУБЛИЧНЫЕ:
                continue
            всего += 1
            реальный = путь
            for шаблон, значение in ПОДСТАНОВКА.items():
                реальный = реальный.replace(шаблон, значение)
            ответ = await client.request(m, реальный, json={})
            if ответ.status_code not in (401, 403):
                голые.append(f"{m:6} {путь:52} -> {ответ.status_code}")
    assert всего > 100, f"проверено всего {всего} ручек — схема не собралась?"
    assert not голые, "ручки отвечают без токена:\n" + "\n".join(голые)
