"""Бот не повторяет заметки и не врёт в журнале (27.08).

Две находки обхода кода, обе про одно: система сообщает не тот исход, который
случился.
"""

import inspect

from app.bots import engine


def test_notes_pass_a_repeat_guard():
    """⚠ СЛУЖЕБНАЯ ЗАМЕТКА ЛОЖИЛАСЬ НА КАЖДОЕ СООБЩЕНИЕ КЛИЕНТА.

    Гард повторов стоит в `send_bot_message` и смотрит на подсказки и исходящие
    бота. Заметки идут мимо него, через `add_note`, где проверок не было вовсе.
    Пока лид-бот недоступен, заметка «ИИ недоступен» пишется ДО передачи и вне
    её идемпотентности — а сама передача при повторе выходит сразу. Диалог
    зарастал одинаковыми строками, и настоящие заметки в них тонули.
    """
    тело = inspect.getsource(engine.ScenarioEngine.add_note)
    assert "_заметка_уже_есть" in тело, "заметки снова пойдут мимо гарда повторов"


def test_the_note_guard_stops_at_the_client_reply():
    """Ответил человек — обстоятельства изменились, и та же заметка снова
    осмысленна. Иначе гард молчал бы навсегда."""
    тело = inspect.getsource(engine.ScenarioEngine._заметка_уже_есть)
    assert 'sender_type", "") == "client"' in тело and "return False" in тело


def test_journal_does_not_claim_a_suppressed_reply_was_sent():
    """⚠ ЖУРНАЛ ПИСАЛ «ОТВЕТ УШЁЛ КЛИЕНТУ», КОГДА НИЧЕГО НЕ УШЛО.

    `send_bot_message` возвращает None по двум разным поводам: пустой текст
    (тихое удержание) и сработавший гард повторов. Различался только первый —
    и на погашенном повторе выполнение шло дальше, записывая в `leadbot_calls`
    исход «ответ ушёл клиенту» при том, что в базе нет ни сообщения, ни заметки.
    По этому журналу владелец считает работу бота.
    """
    тело = inspect.getsource(engine.ScenarioEngine.exec_ai_answer)
    ветка = тело[тело.index("отправлено = await self.send_bot_message") :]
    запись = ветка.index("_record_leadbot")
    выход = ветка.index("return")
    assert выход < запись, (
        "погашенный повтор доходит до записи исхода — журнал соврёт, что ответ ушёл клиенту"
    )
    assert "bot.reply_suppressed" in ветка, "погашенный ответ должен быть виден в логах"
