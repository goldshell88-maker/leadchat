"""Разбор причин передачи по видам сбоя (docs/45 §4.3).

Экран «Диалоги бота» стоит на реестре `HANDOFF_REASONS`: тридцать две причины,
которые бот записывает, отдавая диалог человеку. Плитки — это группы из этого
реестра. Разъедутся они молча: причину переименуют или уберут, группа продолжит
искать старое имя и станет вечным нулём. Ноль на экране надзора читается как
«всё хорошо» — то есть отказ будет выглядеть исправностью.
"""

from app.bots import handoff


class TestГруппыСбоев:
    def test_каждая_причина_группы_есть_в_реестре(self) -> None:
        """Группа не может ссылаться на причину, которой бот не записывает.

        Это ровно тот отказ, который не выглядит отказом: плитка молча
        показывает ноль, а администратор делает вывод, что бот не ошибается.
        """
        for группа in handoff.OUTCOME_ORDER:
            for причина in handoff.reasons_of(группа):
                assert причина in handoff.HANDOFF_REASONS, (
                    f"группа «{handoff.outcome_label(группа)}» ищет причину "
                    f"«{причина}», которой нет в реестре"
                )

    def test_причина_не_попадает_в_две_группы(self) -> None:
        """Иначе один диалог считался бы дважды и сумма плиток врала бы."""
        встречалась: dict[str, str] = {}
        for группа in handoff.OUTCOME_ORDER:
            for причина in handoff.reasons_of(группа):
                assert причина not in встречалась, (
                    f"причина «{причина}» стоит и в «{встречалась.get(причина)}», и в «{группа}»"
                )
                встречалась[причина] = группа

    def test_порядок_перечисляет_все_группы(self) -> None:
        """Порядок задаётся руками (не по величине счётчика), и забыть в нём
        группу значит убрать плитку с экрана, не убрав её из словаря."""
        assert set(handoff.ALL_OUTCOMES) == set(handoff.OUTCOME_GROUPS)

    def test_ёмкость_не_лежит_среди_сбоев(self) -> None:
        """«Не смог сам» — 210 передач из 325 на боевом трафике, и это НЕ сбой:
        бот честно зовёт человека вместо того, чтобы гадать.

        Попади эта группа в ряд сбоев — экран сказал бы «210 сбоев» про самое
        здоровое поведение бота, и единственный настоящий отказ по регламенту
        потерялся бы на её фоне совсем.
        """
        assert set(handoff.CAPACITY_ORDER) & set(handoff.OUTCOME_ORDER) == set()
        assert "ai_low_confidence" in handoff.reasons_of("not_capable")
        for группа in handoff.OUTCOME_ORDER:
            assert "ai_low_confidence" not in handoff.reasons_of(группа)

    def test_завис_не_имеет_причин(self) -> None:
        """«Бот завис» — не причина передачи, а отдельное событие журнала
        (`conversation.bot_stuck_released`). Причины ему взять неоткуда, и
        появление их здесь означало бы, что кто-то перепутал два источника."""
        assert handoff.reasons_of("stuck") == ()

    def test_штатные_причины_в_плитки_не_попадают(self) -> None:
        """Экран отвечает на вопрос «где бот навредил», а не «сколько раз он
        передавал диалог». Клиент попросил человека — это работа по плану, и
        считать её сбоем значит утопить настоящие сбои в шуме."""
        штатные = {"client_request", "scenario", "call_made", "call_request", "not_primary"}
        # ⚠ Сюда НЕ входят `ai_low_confidence` и `model_handoff`: они лежат в
        # «ёмкости» — отдельной группе, которая на экране стоит вне ряда сбоев.
        все_в_плитках = {п for г in handoff.OUTCOME_ORDER for п in handoff.reasons_of(г)}
        лишние = штатные & все_в_плитках
        assert not лишние, f"штатная работа попала в плитки сбоев: {sorted(лишние)}"
