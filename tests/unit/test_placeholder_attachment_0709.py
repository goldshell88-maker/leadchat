class _Строка:
    """Строка `messages` ровно в том объёме, в каком её читает движок бота."""

    def __init__(
        self,
        body: str | None,
        attachments: list[dict[str, Any]],
        *,
        direction: str = "in",
        sender_type: str = "client",
    ) -> None:
        self.body = body
        self.attachments = attachments
        self.direction = direction
        self.sender_type = sender_type
        self.id = uuid.uuid4()


class _Курсор:
    def __init__(self, rows: list[_Строка]) -> None:
        self._rows = rows

    def scalars(self) -> Any:
        return iter(self._rows)


class _База:
    def __init__(self, rows: list[_Строка]) -> None:
        self._rows = rows

    async def execute(self, *_a: Any, **_k: Any) -> _Курсор:
        # Движок просит по убыванию времени и разворачивает сам.
        return _Курсор(list(reversed(self._rows)))


class _Диалог:
    def __init__(self) -> None:
        self.id = uuid.uuid4()


def _движок(rows: list[_Строка]) -> ScenarioEngine:
    eng = ScenarioEngine.__new__(ScenarioEngine)
    eng.db = _База(rows)  # type: ignore[assignment]
    eng.conv = _Диалог()  # type: ignore[assignment]
    return eng


