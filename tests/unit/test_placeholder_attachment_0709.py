# ------------------------------------------------- серая запись Авито остаётся с телом


def test_звонок_остаётся_телом_серой_записи() -> None:
    """⚠ ЗВОНОК СОЗНАТЕЛЬНО НЕ ПЕРЕЕХАЛ ВО ВЛОЖЕНИЕ, И ЭТО РЕШЕНИЕ, А НЕ ЗАБЫВЧИВОСТЬ.

    `appCall` не ложится пузырём клиента: адаптер метит его `is_system`, а
    конвейер пишет серой записью Авито (`direction='system'`,
    `sender_type='avito'`). Три причины оставить подпись телом:

    * серый чип рисуется строкой `{body} · время` и вложений не показывает вовсе
      (`MessageBubble.tsx`, ветка `kind === "system"`), а пишет его вставка, где
      `attachments=[]` стоит константой (`inbound._store_avito_system_message`).
      Перенеси подпись — на месте звонка окажется пустой чип;
    * бот считает звонки по слову в ТЕЛЕ такой записи
      (`bots/engine.py::load_bot_context`), а запись с пустым телом пропускает.
      Счётчик молча обнулился бы, и передача «клиент просит позвонить» перестала
      бы срабатывать: за этим стоит 2834 записи о звонках;
    * жалоба владельца не про него: серая запись подписана «Сообщение Авито» и
      словами клиента не выглядит.

    ⚠ ДИВЕРСИЯ. В `_подпись_пустому` ветка `if служебная:` убрана (звонок поехал
    вложением), `__pycache__` снесён. Тест покраснел: `text` стал `None`, а
    вложение — единственным носителем слова «звонил». Восстановлено, зелёный.
    """
    событие = _parse(type="appCall", content={})

    assert событие.is_system is True
    assert событие.text == "Клиент звонил через приложение Авито"
    assert событие.attachments == []
    assert "звонил" in (событие.text or "").lower(), "по этому слову бот считает звонки"


