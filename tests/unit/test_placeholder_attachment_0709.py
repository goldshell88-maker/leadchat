    событие = _parse(type=source_type, content={})

    assert событие.text is None, "подпись в теле читается как речь клиента — ради этого правка"
    (вложение,) = событие.attachments
    assert вложение["name"] == имя
    assert вложение["url"] is None, "ссылки нет и не будет: content пуст, метода у Авито нет"
    assert вложение["size"] is None
    assert вложение["kind"] == "file"
    assert вложение["avito_type"] == source_type, "вид Авито обязан доехать до записи"


