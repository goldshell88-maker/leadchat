"""Поиск похожих карточек не читает таблицу целиком (аудит 22.08, шаг 4).

ЧТО ИЗМЕРЕНО НА БОЮ. У `clients` было три индекса — первичный ключ,
`UNIQUE(channel, external_id)` и крошечный `ix_clients_blocked`. А блок
«Возможно, это тот же человек» ищет по phone, external_id и name, и каждый
поиск шёл последовательным чтением всей таблицы:

    phone       → Seq Scan, 17 518 строк отброшено фильтром, 10.8 мс
    external_id → Seq Scan, 17 518 строк отброшено фильтром, 10.9 мс
    name        → Seq Scan, 17 518 строк отброшено фильтром,  4.9 мс

По счётчикам базы: 88 450 последовательных чтений `clients`, 146 401 343
прочитанные строки. Стоимость растёт линейно с числом карточек.

ЗДЕСЬ ПРОВЕРЯЕТСЯ ДОГОВОР, А НЕ ПЛАН ЗАПРОСА: что индексы объявлены в модели
(иначе следующий autogenerate предложит их удалить), что они частичные по
`merged_into_id IS NULL` — все три запроса всегда несут это условие, — и что
поиск по `external_id` по-прежнему идёт БЕЗ канала. Последнее не придирка:
добавить `channel` в условие значило бы «починить» план ценой смысла — этот
поиск ищет того же человека на ДРУГОМ канале.
"""

from __future__ import annotations

import inspect
import pathlib
import re

from sqlalchemy import Index

from app.models.client import Client
from app.services import clients as clients_svc

ОЖИДАЕМЫЕ = {
    "ix_clients_phone_active": "phone",
    "ix_clients_external_id_active": "external_id",
}

#: Имя ищется через `lower(name)`, поэтому и индекс по выражению — проверять его
#: как обычную колонку нельзя, у выражения нет имени колонки.
ИМЕННОЙ = "ix_clients_name_active"


def _индексы() -> dict[str, Index]:
    return {a.name: a for a in Client.__table_args__ if isinstance(a, Index)}


def test_три_индекса_объявлены_в_модели():
    найдены = _индексы()
    for имя, колонка in ОЖИДАЕМЫЕ.items():
        assert имя in найдены, f"{имя} нет в модели — autogenerate предложит его удалить"
        колонки = [c.name for c in найдены[имя].columns]
        assert колонки == [колонка], f"{имя} построен по {колонки}, а искали по {колонка}"
    assert ИМЕННОЙ in найдены, "индекса по имени нет в модели"
    выражение = str(найдены[ИМЕННОЙ].expressions[0]).lower()
    assert "lower(" in выражение, (
        "индекс по имени построен по колонке, а код ищет через lower(name) — "
        "планировщик такой индекс не возьмёт, он будет мёртвым грузом"
    )


#: Индексы ПОИСКА ПОХОЖИХ — те, ради которых написан этот файл.
#:
#: Перечислены поимённо, а не «все индексы clients»: 28.08 рядом появился
#: `ix_clients_merged_into`, у которого условие ОБРАТНОЕ (`IS NOT NULL`) — он
#: отвечает на другой вопрос, «в эту карточку кого-нибудь объединяли». Правило
#: «объединённую не предлагать» относится к подбору кандидатов, а не к любому
#: индексу на таблице, и перебор по словарю это правило подменял.
ПОИСКОВЫЕ = ("ix_clients_phone_active", "ix_clients_external_id_active", ИМЕННОЙ)


def test_индексы_частичные_по_объединённым():
    """Объединённую карточку предлагать нельзя — условие обязано быть в индексе."""
    for имя in ПОИСКОВЫЕ:
        условие = str(_индексы()[имя].dialect_options["postgresql"]["where"])
        assert "merged_into_id IS NULL" in условие, f"{имя}: нет отсечения объединённых"
    for имя in ("ix_clients_phone_active", "ix_clients_name_active"):
        условие = str(_индексы()[имя].dialect_options["postgresql"]["where"])
        assert "IS NOT NULL" in условие, f"{имя}: пустые значения незачем держать в индексе"


def test_поиск_по_external_id_остался_без_канала():
    """Смысл важнее плана: это поиск того же человека на ДРУГОМ канале."""
    исходник = inspect.getsource(clients_svc)
    i = исходник.index("Client.external_id == client.external_id")
    кусок = исходник[i - 200 : i + 200]
    assert "Client.channel" not in кусок, (
        "в поиск однофамильцев добавили канал — это ломает смысл сквозного клиента"
    )


def test_миграция_на_месте_и_последняя():
    каталог = pathlib.Path(__file__).resolve().parents[2] / "app/db/migrations/versions"
    файл = каталог / "0051_clients_lookup_indexes.py"
    assert файл.exists(), "миграция 0051 не найдена"
    текст = файл.read_text(encoding="utf-8")
    assert 'down_revision = "0050"' in текст
    for имя in ОЖИДАЕМЫЕ:
        assert имя in текст, f"{имя} не создаётся миграцией"
    # ревизий с одним и тем же down_revision быть не должно
    ветки = [
        f
        for f in каталог.glob("*.py")
        if re.search(r'^down_revision = "0050"', f.read_text(encoding="utf-8"), re.M)
    ]
    assert len(ветки) == 1, f"ветвление истории миграций: {[f.name for f in ветки]}"


# ------------------------------------- обратный вопрос: «в меня объединяли?»


def test_обратная_связь_объединения_тоже_под_индексом() -> None:
    """«В ЭТУ карточку кого-нибудь объединяли?» — четыре места и один предикат.

    Три индекса выше держат `merged_into_id` только условием `IS NULL` и на
    такой поиск не годятся ни один: ведущей колонки нет. А спрашивают об этом
    `services/leads.py` (перед выдачей телефона в заявку) и трижды
    `services/clients.py` («Разъединить» и счётчик в карточке).

    Больнее всего в лидах: вопрос стоит ВНУТРИ цикла по выдаваемой пачке, а
    пачка — до 200 строк. Каждый опрос расширения Chrome стоил до двухсот полных
    проходов по `clients`, и цена росла вместе с базой. Ни ошибки, ни строчки в
    журнале — только время.
    """
    индекс = _индексы().get("ix_clients_merged_into")
    assert индекс is not None, (
        "индекс по merged_into_id снят — счёт объединённых снова пойдёт полным проходом, "
        "а в выдаче лидов это до 200 проходов на опрос"
    )
    assert [c.name for c in индекс.expressions] == ["merged_into_id"]
    # Частичный: все четыре запроса сравнивают колонку с конкретным id, то есть
    # заведомо ищут NOT NULL. Объединений единицы — индекс остаётся крошечным.
    условие = индекс.dialect_options["postgresql"].get("where")
    assert условие is not None and "NOT NULL" in str(условие)


