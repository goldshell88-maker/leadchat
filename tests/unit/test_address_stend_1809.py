"""Стенд 18.09: двадцать один скрин владельца по адресам — разбор текста.

Каждый случай — реплика клиента КАК НАПИСАНА и ожидаемый разбор. Классы:

1. Ложные кандидаты: деньги («1т.р.»), цена («500 стоит»), время («19:30»),
   умножение («3*2.5»), глагол или наречие на месте имени («взял», «туда»),
   мебель («купе 2»).
2. Набережные Челны: «38/07» — 38-й комплекс, дом 7 (по городу объявления).
3. «микрорайон авиаторов Сидорова 9» — микрорайон и улица без типа.
4. «В Сукко, на ул. Солнечную» — пункт после «в», винительный падеж улицы.
5. «Ялга ул Мичурина д 3» — пункт без типа вплотную перед улицей с типом.
6. «Строителей 42, к 1» — корпус через запятую.
7. «Октябрьская 18 г первый корпус» — литера через пробел, корпус словом.
8. «КП Новое Заречье, 54» — коттеджный посёлок как массив.
9. «Хутор Садков улица степная 4 пожъезд 2 этаж 1 кв 9» — хутор, опечатка.
10. Ангарск: «92/93квартал,дом 6», «Квартал 92/93, дом 14», «93 кв,31».
11. «Люберцы Д. Петрово Снт Заречное Д. 38» — деревня, массив, дом.
12. «3 подъезд, квартира 52.» — части без улицы.
"""

from __future__ import annotations

import pytest

from app.services import address_parse as ap


def _разбор(text: str, **kw):  # noqa: ANN003, ANN202
    f = ap.parse(text, **kw)
    return f and (f.level, f.street, f.house, f.settlement, f.settlement_type, f.locality, f.parts)


# --- 1. ложные кандидаты -------------------------------------------------------

ЛОЖНЫЕ = [
    # Деньги: «1т.р.» — тысяча рублей, «т» не литера дома; «взял» — глагол.
    "К нам приезжал ваш специалист взял 1т.р. за выезд и диагностику",
    "Специалист Ремонтов взял 1т.р. за выезд",
    "взял 1т",
    # Цена: число перед «стоит».
    "Смысл 500 стоит",
    # Время ЧЧ:ММ — не дом; «позже» — наречие.
    "Если можно не позже 19:30",
    "ДоДо пицца Ленинск кузнецкий 14:26 Есть виды работ",
    # Сечение кабеля: число перед знаком умножения.
    "силовые. для розеток 3*2.5 и освещение 3*1,5",
    "освещение 3х1,5",
    # Наречие места и мебель.
    "Мне нужны туда 4 двери купе 2",
    "Купе 2",
    # Глаголы на месте имени.
    "приезжайте 16",
    "сможете приехать 45",
]


@pytest.mark.parametrize("text", ЛОЖНЫЕ)
def test_ложный_кандидат_не_адрес(text: str) -> None:
    assert ap.parse(text) is None, text
    # …и в ответ на вопрос оператора об адресе тоже: строчные головы без
    # контекста и так не берутся, ловушка — именно контекст.
    assert ap.parse(text, про_адрес=True) is None, text


@pytest.mark.parametrize(
    ("text", "expected"),
    [
        # Класс глаголов не задевает имена улиц строчными с похожим хвостом.
        ("карла маркса 5", ("B", "карла маркса", "5")),
        ("руставели 5", ("B", "руставели", "5")),
        ("юности 5", ("B", "юности", "5")),
        ("Я вам только звонил юность 3", ("B", "юность", "3")),
        ("40 лет октября 5", ("B", "40 лет октября", "5")),
        # «стоит» после дома, но через запятую — речь дальше, дом на месте.
        ("Ленина 5, стоит шлагбаум", ("B", "Ленина", "5")),
        # Тип улицы кончается на «-л», но типом и остаётся.
        ("93-й квартал 31", ("A", "93-й квартал", "31")),
    ],
)
def test_класс_речи_не_режет_имена(text: str, expected: tuple) -> None:
    f = ap.parse(text, про_адрес=True)
    assert f is not None and (f.level, f.street, f.house) == expected


def test_речь_строчными_класс_а_не_словарь() -> None:
    assert ap._РЕЧЬ_СТРОЧНЫМИ.match("взял")
    assert ap._РЕЧЬ_СТРОЧНЫМИ.match("приехать")
    assert ap._РЕЧЬ_СТРОЧНЫМИ.match("позже")
    assert ap._РЕЧЬ_СТРОЧНЫМИ.match("пишите")
    # Существительные на «-сть», родительный «-ла»/«-ли», винительный «-ую».
    assert ap._РЕЧЬ_СТРОЧНЫМИ.match("юность") is None
    assert ap._РЕЧЬ_СТРОЧНЫМИ.match("карла") is None
    assert ap._РЕЧЬ_СТРОЧНЫМИ.match("руставели") is None
    assert ap._РЕЧЬ_СТРОЧНЫМИ.match("ленинградскую") is None


# --- 2. Набережные Челны: «38/07» ----------------------------------------------


def test_комплекс_дом_в_челнах() -> None:
    f = ap.parse_by_city("38/07", "Набережные Челны")
    assert f is not None
    assert (f.level, f.street, f.house, f.parts, f.raw) == ("B", "38-й комплекс", "7", {}, "38/07")
    assert ap.quote_holds(f, "38/07")
    # Части адреса и время вокруг пары: подъезд и квартира — части, «10:00» — нет.
    text = "Завтра сможете приехать 38/07 17 подъезд 286 кв В 10:00 или в 11:00?"
    assert ap.parse(text) is None
    f = ap.parse_by_city(text, "Набережные Челны")
    assert f is not None
    assert (f.street, f.house, f.parts) == (
        "38-й комплекс",
        "7",
        {"entrance": "17", "office": "286"},
    )
    assert ap.quote_holds(f, text)
    assert ap.complex_pair_present(text)
    assert not ap.complex_pair_present("В 10:00 или в 11:00?")


