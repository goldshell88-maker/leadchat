def test_17_сторож_цитаты_держит_склейку_с_пунктом_из_соседней_реплики() -> None:
    """Клиент назвал пункт одной репликой, а квартальную форму — следующей:
    цитата склеивается «пункт; адрес» (`inbound.с_пунктом_контекста`), и
    сторож цитаты обязан её пропустить — иначе строка терялась вовсе
    (ревью 20.09, #11). Формы города сверяются по хвосту склейки."""
    from app.services import inbound

    def склейка(f: ap.Found, пункт: str) -> ap.Found:
        return inbound.с_пунктом_контекста(
            f, inbound.ПунктКонтекста(пункт, None, пункт, inbound.ФОРМА_РЕПЛИКА)
        )

    случаи = [
        (ap.parse_by_city("7.10.34", "Нефтеюганск"), "Каркатеевы"),
        (ap.parse_by_city("86-11", "Ангарск"), "Мегет"),
        (ap.parse_by_city("93 кв,31", "Ангарск"), "Мегет"),
        (ap.parse("14а-76-21"), "Мегет"),
        (ap.parse_by_city("К.418, 1 под, 7 эт, кв.52", "Зеленоград"), "Крюково"),
        (ap.parse_by_city("38/07", "Набережные Челны"), "Орловка"),
    ]
    for f, пункт in случаи:
        assert f is not None and ap.quote_holds(f, f.raw), (f, пункт)
        g = склейка(f, пункт)
        assert g.raw == f"{пункт}; {f.raw}" and g.settlement == пункт
        assert ap.quote_holds(g, g.raw), g
    # Подмена дома в склейке по-прежнему ловится: сторож не ослаб.
    f = ap.parse_by_city("7.10.34", "Нефтеюганск")
    assert f is not None
    g = склейка(f, "Каркатеевы")
    assert not ap.quote_holds(g, "Каркатеевы; 7.11.34")


