"""Разбор телефона в свободном тексте: каждый формат и каждый контрпример.

ОТКУДА ВЗЯТЫ ДАННЫЕ. Всё, что проверяется ниже, — по образцу одного боевого
диалога (здесь a1b2c3d4-0000-4000-8000-000000000001, Анна Сергеевна, 12 августа).
В нём рядом лежат телефон, код от домофона, модель телевизора и адрес с
номером квартиры — то есть и то, что обязано распознаваться, и то, что обязано
НЕ распознаваться. Форма записи — как в бою; имя, цифры и адрес вымышленные.

ПОЧЕМУ ЭТОТ ФАЙЛ ВАЖНЕЕ ОСТАЛЬНЫХ. Номер из карточки набирают и диктуют мастеру
вслух. Ошибка разбора — это звонок постороннему человеку и потерянный настоящий
клиент; поймать её после выкатки можно только по жалобе. Здесь она ловится за
секунду и без базы.
"""

import pytest

from app.services import phone_parse
from app.services.clients import normalize_phone
from app.services.inbound import extract_phone

#: Живое сообщение с боевой системы, входящее 16:35.
АННА = (
    "В любое время в течении дня. Прошу сообщить о времени прихода за 1 час "
    "в СМС по номеру : +7(900)1112240."
)


# --- форматы, которые ОБЯЗАНЫ распознаваться --------------------------------


@pytest.mark.parametrize(
    "text",
    [
        pytest.param("+7(900)1112240", id="плюс-скобки-слитно"),
        pytest.param("8 900 111-22-40", id="восьмёрка-пробелы-дефисы"),
        pytest.param("+7 900 111 22 40", id="плюс-пробелы"),
        pytest.param("79001112240", id="одиннадцать-цифр-подряд"),
        pytest.param("8(900)111-22-40", id="восьмёрка-скобки-дефисы"),
        pytest.param("9001112240", id="десять-цифр-с-девятки"),
        pytest.param("8.900.111.22.40", id="точки-разделителями"),
        # Неразрывный пробел приезжает копипастой из объявления Авито и из
        # мобильного приложения. На глаз он неотличим от обычного, и в
        # прежнем разборе держался только на `\\s` в регулярке — то есть на
        # случайности.
        pytest.param("8 900 111 22 40", id="неразрывный-пробел"),
        pytest.param("8 900 111 22 40", id="узкий-неразрывный"),
        pytest.param("8–900–111–22–40", id="типографское-тире"),
    ],
)
def test_every_way_a_client_writes_a_number(text: str):
    """Один и тот же телефон, десять написаний — одна строка в базе.

    Разойдись хоть одно, и поиск по телефону перестал бы находить диалог, а
    объединение карточек по номеру — срабатывать.
    """
    assert extract_phone(text) == "+79001112240"


def test_the_live_message_that_started_all_this():
    """Диалог Анны Сергеевны: номер внутри фразы, с хвостовой точкой."""
    found = phone_parse.find_first(АННА)
    assert found is not None
    assert found.value == "+79001112240"
    # Точка в конец номера не попала — иначе оператор увидел бы предложение
    # «распознан телефон +7(900)1112240.» и не понял бы, чему верить.
    assert found.raw == "+7(900)1112240"
    assert АННА[found.start : found.end] == found.raw


@pytest.mark.parametrize(
    ("text", "expected"),
    [
        ("тел.89001112240", "+79001112240"),  # точка — разделитель, а не буква
        ("Мой:89001112240", "+79001112240"),  # двоеточие цепочку не продолжает
        ("звоните 8 900 111 22 51", "+79001112251"),
        ("наберите 8 900 111 22 51 после 18", "+79001112251"),  # цифры дальше — через слова
        ("8 (495) 123-45-67", "+74951234567"),  # городской с кодом города — законный
    ],
)
def test_a_number_surrounded_by_words(text: str, expected: str):
    assert extract_phone(text) == expected


def test_two_numbers_in_one_message_are_both_seen():
    """«Мой …, жены …» — второй номер не теряется.

    Запятая цепочку разрывает намеренно: склей мы их в одну, длина вышла бы за
    норму и пропали бы ОБА.
    """
    values = [f.value for f in phone_parse.find_all("мой 8 900 111 22 40, жены +7 900 111 22 52")]
    assert values == ["+79001112240", "+79001112252"]
    # Первым — тот, по которому звонить: его назвали первым.
    first = phone_parse.find_first("мой 8 900 111 22 40, жены +7 900 111 22 52")
    assert first is not None and first.value == "+79001112240"


# --- контрпримеры: обязаны ОСТАТЬСЯ нераспознанными -------------------------


@pytest.mark.parametrize(
    "text",
    [
        # Три строки из того же боевого диалога — критерии приёмки владельца.
        pytest.param("Код входной двери в дом: 37ключ2580", id="код-домофона"),
        pytest.param("Телевизор Samsung QLED Q70A 55cm", id="модель-телевизора"),
        pytest.param("Заречное шоссе дом 7 кв.84 (12 этаж)", id="адрес-с-квартирой"),
        # Цифры вплотную к буквам с любой стороны.
        pytest.param("Телефон 89001112240abc", id="буквы-справа"),
        # «тел89001112240» здесь БЫЛО (буквы слева = не телефон). Корпус 45 дней
        # 12.09: «Ее телефон89001112247.», «89001112247Елена» — 11 живых номеров,
        # приклеенных к кириллическому слову. Целый мобильный (11 цифр с 8/7 или
        # 10 с девятки) у кириллицы — телефон; латиница по-прежнему модель.
        pytest.param("тел8900111224", id="буквы-слева-не-целый"),
        # Знак номера слева: «заказ №…» — это порядковый номер, а не телефон,
        # хотя по цифрам он неотличим (одиннадцать штук, начинается с восьмёрки).
        pytest.param("заказ№89001112240", id="знак-номера"),
        # «#89001112240» отдельным словом — ТЕЛЕФОН с 19.09 (владелец:
        # «#<номер> напишите мне в макс»); знак заказа — только вплотную к слову.
        # Цепочка длиннее нормы: где в ней начинается номер, не знает никто.
        pytest.param("Артикул 8-900-111-22-40-77", id="тринадцать-цифр"),
        pytest.param("1234567890123", id="тринадцать-цифр-подряд"),
        # Короче нормы.
        pytest.param("8900111224", id="десять-цифр-с-восьмёрки"),
        pytest.param("завтра в 10:30, цена 1500", id="время-и-цена"),
        # Десять цифр НЕ с девятки: неотличимо от мобильного с потерянной
        # первой цифрой, и дописать +7 значило бы показать не тот номер.
        pytest.param("4951234567", id="десять-цифр-не-с-девятки"),
        pytest.param("+380671234567", id="иностранный"),
        pytest.param("", id="пусто"),
        pytest.param(None, id="none"),
    ],
)
def test_what_must_never_become_a_phone(text: str | None):
    assert extract_phone(text) is None
    assert phone_parse.find_all(text) == []


def test_the_price_of_the_length_rule_is_paid_no_more():
    """Размен пересмотрен 01.09 — и этот тест сделал ровно то, ради чего стоял.

    ⚠ ЧТО ЗДЕСЬ БЫЛО. Тест закреплял принятую потерю: «с 9 до 21 8 900 111 22 40»
    — одна цепочка в 14 цифр, номер оттуда не доставался. В его собственном
    описании было обещано: «если завтра правило смягчат, он покраснеет и
    заставит перечитать шапку». Так и вышло — он покраснел, шапка перечитана,
    и вот довод.

    ⚠ ПОЧЕМУ РАЗМЕН ПЕРЕСМОТРЕН. Владелец пожаловался: «есть номера, которые
    скрипт не распознал». Замер по боевому корпусу за 60 дней: найдено 5067
    телефонов, пропущено 207 похожих. Прогон нового правила по тому же корпусу
    вернул 104 из них, НЕ ИЗМЕНИВ НИ ОДНОГО прежнего ответа. В контекстах у всех
    возвращённых стоял адрес, после которого человек пишет телефон.

    То есть потеря оказалась не редким краем, а частым случаем: люди пишут
    «Садовая д 12 89001112240» постоянно.

    ⚠ ЧТО НЕ ИЗМЕНИЛОСЬ. Принцип «лучше пропустить, чем придумать» на месте.
    Отрезать разрешено ТОЛЬКО слева и только короткое число: сам
    `8-900-111-22-40-77`, названный автором модуля по имени, по-прежнему молчит
    — см. `test_the_tail_rule_does_not_invent_numbers`.
    """
    assert extract_phone("звоните с 9 до 21 8 900 111 22 40") == "+79001112240"
    # Запятая как разделитель цепочек работала и раньше — проверяем, что не сломали.
    assert extract_phone("звоните с 9 до 21, 8 900 111 22 40") == "+79001112240"


# --- одна нормализация на всю систему ----------------------------------------


@pytest.mark.parametrize(
    "raw",
    ["+7 900 111-22-53", "89001112253", "9001112253", "8 (900) 111 22 53"],
)
def test_manual_input_and_message_parsing_agree(raw: str):
    """Ручной ввод и разбор переписки обязаны давать ОДНУ строку.

    Разойдись они — номер, вычитанный из сообщения, и тот же номер, введённый
    руками, легли бы в базу двумя разными значениями и перестали бы совпадать
    при поиске двойников.
    """
    assert normalize_phone(raw) == extract_phone(raw) == "+79001112253"


@pytest.mark.parametrize(
    "raw",
    [
        "89001112253 или 89001112254",  # два номера в одном поле
        "8 (900) 111-22-53 доб. 5",
        "не знаю",
        "   ",
    ],
)
def test_the_input_field_refuses_what_it_cannot_read_whole(raw: str):
    """В поле ввода «первый попавшийся номер» хуже отказа.

    Оператор увидел бы сохранённое значение, решил, что система его поняла, и
    позвонил по половине введённого. Разбор ПЕРЕПИСКИ ведёт себя иначе — и это
    правильно: там номер и должен стоять среди слов.
    """
    assert normalize_phone(raw) is None


