@pytest.mark.parametrize(
    ("text", "expected"),
    [
        # Случай, который автор модуля назвал вслух как принятую потерю.
        ("Звоните с 9 до 21 8 900 111 22 40", "+79001112240"),
        # Формы из боевого корпуса: человек пишет адрес, следом телефон.
        ("ул Садовая д 12. 89001112240", "+79001112240"),
        ("Школьная 15 89001112240", "+79001112240"),
        ("подъезд 2 квартира 45 89001112240", "+79001112240"),
        ("Луговая 5 89001112240", "+79001112240"),
        ("31.08 89001112240", "+79001112240"),
        # Десятизначный с девятки — тот же путь.
        ("кв 12 9001112240", "+79001112240"),
    ],
)
def test_phone_after_an_address_is_found(text: str, expected: str):
    """Номер, стоящий ПОСЛЕ короткого числа, обязан находиться.

    ⚠ ЗАМЕР БОЯ 01.09, ПОВОД — ЖАЛОБА ВЛАДЕЛЬЦА «есть номера, которые скрипт не
    распознал». Правило длины берёт цепочку цифр и разделителей ЦЕЛИКОМ, и
    «Садовая д 12 89001112240» — это тринадцать цифр, то есть мимо нормы.

    Сколько это стоило: за шестьдесят дней разбор нашёл 5067 телефонов и
    пропустил 207 похожих на телефон. Прогон нового правила по тому же корпусу
    вернул 104 из них — и в контекстах у всех оказался адрес, после которого
    человек пишет номер. Ни одного изменённого ответа на прежних находках.
    """
    found = phone_parse.find_first(text)
    assert found is not None, "номер после адреса снова теряется"
    assert found.value == expected


def test_the_offer_shows_the_number_itself_not_the_whole_chain():
    """`raw` — это номер, а не «адрес и номер» одной строкой.

    Оператор сверяет предложение системы с тем, что человек написал. Покажи мы
    ему «12. 89001112240» как «распознан телефон», сверка сломалась бы ровно там,
    где она нужна.
    """
    found = phone_parse.find_first("ул Садовая д 12. 89001112240")
    assert found is not None
    assert found.raw == "89001112240"


@pytest.mark.parametrize(
    "text",
    [
        # ⚠ ГЛАВНЫЙ КОНТРПРИМЕР, названный автором модуля по имени. Отрежь мы
        # номер СЛЕВА (а не справа), здесь получился бы «+79001112240» из строки,
        # про которую прямо сказано: где в ней начинается номер, не знает никто.
        "8-900-111-22-40-77",
        # Обратная сторона того же: номер слева, мусор справа. Тоже не берём.
        "89001112240 77",
        # Слева слишком много цифр — это не «контекст и номер», а неизвестно что.
        "12345 67890 12345 89001112240",
        "1234567 89001112240",
        # Прежние контрпримеры обязаны продолжать молчать.
        "Заречное шоссе дом 7 кв.84 (12 этаж)",
        "заказ№89001112240",
        "37ключ2580",
    ],
)
def test_the_tail_rule_does_not_invent_numbers(text: str):
    """Правило хвоста НЕ ослабляет главный принцип модуля.

    «Лучше пропустить, чем придумать»: номер из карточки набирают и диктуют
    мастеру вслух. Поэтому отрезать разрешено ТОЛЬКО слева и только короткое
    число — всё остальное молчит, как молчало.
    """
    assert phone_parse.find_first(text) is None


@pytest.mark.parametrize(
    "text",
    [
        "89001112247Елена",
        "Ее телефон89001112247. Позвоните ей",
        "подьезд89001112247, а во сколько сможете?",
        "+79001112247Анна",
    ],
)
def test_целый_номер_приклеенный_к_слову_это_телефон(text: str) -> None:
    """Корпус 45 дней (12.09): 11 из 84 нераспознанных — номер без пробела у слова.
    ⚠ ДИВЕРСИЯ: убрать исключение «целый» в `_glued_to_a_word` — краснеет."""
    assert [f.value for f in phone_parse.find_all(text)] == ["+79001112247"]


def test_надстрочные_цифры_это_тоже_номер() -> None:
    """Бой 12.09: «⁷⁹00 ¹¹12 ²⁵⁹» — клавиатура телефона пишет «маленькие» цифры;
    номер узнаётся, а `raw` остаётся как написано."""
    found = phone_parse.find_all("⁷⁹00 ¹¹12 ²⁵⁹")
    assert [f.value for f in found] == ["+79001112259"]
    assert found[0].raw == "⁷⁹00 ¹¹12 ²⁵⁹"
    assert phone_parse.find_all("На 17⁰⁰") == []
