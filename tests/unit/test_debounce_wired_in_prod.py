"""Пауза бота обязана стоять на БОЕВОМ пути, а не только в функции-обёртке.

ЧТО СЛУЧИЛОСЬ. Окно серии и пауза жили в `runtime.maybe_enqueue_bot_step`, и все
проверки дёргали именно её. А боевой путь — вебхук Авито, `services.inbound.
apply_inbound_event` — звал `enqueue_bot_step` НАПРЯМУЮ, без окна и без отсрочки.
То есть в бою бот отвечал мгновенно, а окно серии не работало НИКОГДА.

Цена: владелец 26.08 прислал снимок «клиент пишет в 03:10 и в 03:11, бот отвечает
дважды почти одним текстом» — гасить серию было нечем. В тот день окно подняли с 15
до 90 секунд, замерив 19 077 пар реплик; на бой это не повлияло ни на секунду, потому
что код с окном в бою не исполнялся. Тем же вечером владелец сказал прямо: «бот
секунда в секунду отвечает».

⚠ ПРОВЕРЯЕМ ПРАВИЛО, А НЕ ОДНО МЕСТО. Обёртку легко обойти снова — достаточно позвать
`enqueue_bot_step` из нового места и забыть про отсрочку. Поэтому проверка обходит ВСЕ
вызовы в `app/` и требует у каждого `defer_by`.
"""

from __future__ import annotations

import ast
import pathlib

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[2]
ПРИЛОЖЕНИЕ = КОРЕНЬ / "app"


def _вызовы_постановки() -> list[tuple[str, int, ast.Call]]:
    """Все вызовы `enqueue_bot_step` в приложении, кроме её собственного определения."""
    найдено: list[tuple[str, int, ast.Call]] = []
    for путь in ПРИЛОЖЕНИЕ.rglob("*.py"):
        дерево = ast.parse(путь.read_text(encoding="utf-8"), filename=str(путь))
        for узел in ast.walk(дерево):
            if not isinstance(узел, ast.Call):
                continue
            имя = (
                узел.func.id
                if isinstance(узел.func, ast.Name)
                else (узел.func.attr if isinstance(узел.func, ast.Attribute) else "")
            )
            if имя == "enqueue_bot_step":
                найдено.append((str(путь.relative_to(КОРЕНЬ)), узел.lineno, узел))
    return найдено


def test_ход_бота_нигде_не_ставится_без_отсрочки() -> None:
    """Мгновенная постановка = бот отвечает секунда в секунду. Так нельзя нигде."""
    вызовы = _вызовы_постановки()
    assert вызовы, "вызовов enqueue_bot_step не найдено вовсе — проверка ослепла"
    без_отсрочки = [
        f"{файл}:{строка}"
        for файл, строка, узел in вызовы
        if not any(kw.arg == "defer_by" for kw in узел.keywords)
    ]
    assert not без_отсрочки, (
        "ход бота ставится без задержки в: "
        + ", ".join(без_отсрочки)
        + ". Мгновенный ответ выдаёт автомат, а окно серии при этом не работает вовсе."
    )


def test_боевой_путь_заводит_окно_серии() -> None:
    """Без `debounce_claim` вторая реплика клиента родит ВТОРОЙ ответ на ту же мысль."""
    исходник = (ПРИЛОЖЕНИЕ / "services" / "inbound.py").read_text(encoding="utf-8")
    assert "debounce_claim(" in исходник, (
        "боевой путь входящих не заводит окно серии — вернулась поломка 26.08, "
        "когда бот отвечал дважды на две реплики клиента подряд"
    )
    assert "debounce_window(" in исходник, "боевой путь ставит ход бота без паузы"


def test_окно_серии_считается_один_раз_и_уходит_в_обе_стороны() -> None:
    """Срок ключа в Redis и отсрочка задачи ОБЯЗАНЫ быть одним и тем же числом.

    ⚠ 26.08, ПОСЛЕ ПЕРЕХОДА НА ГИБРИД: окно теперь зависит от формы сообщения клиента
    (фото 40 с, вопрос 90 с). Пока число зависело только от диалога, два отдельных вызова
    `debounce_window` давали одинаковый ответ и расхождение было невозможно. Теперь
    достаточно во втором вызове забыть `текст=` — и ключ протухнет раньше задачи (бот
    ответит дважды) или позже неё (тик проснётся внутри живого окна). Поэтому проверяем
    не наличие вызова, а ТОЖДЕСТВО: обе стороны получают одну и ту же переменную.
    """
    дерево = ast.parse((ПРИЛОЖЕНИЕ / "services" / "inbound.py").read_text(encoding="utf-8"))
    имена_окна = {
        цель.id
        for узел in ast.walk(дерево)
        if isinstance(узел, ast.Assign)
        and isinstance(узел.value, ast.Call)
        and getattr(узел.value.func, "id", "") == "debounce_window"
        for цель in узел.targets
        if isinstance(цель, ast.Name)
    }
    assert имена_окна, "боевой путь не заводит переменную окна — считать его дважды нельзя"

    def _аргумент(имя_вызова: str, имя_ключа: str) -> set[str]:
        значения = set()
        for узел in ast.walk(дерево):
            if not isinstance(узел, ast.Call):
                continue
            имя = getattr(узел.func, "id", "") or getattr(узел.func, "attr", "")
            if имя != имя_вызова:
                continue
            for kw in узел.keywords:
                if kw.arg == имя_ключа and isinstance(kw.value, ast.Name):
                    значения.add(kw.value.id)
        return значения

    окно_ключа = _аргумент("debounce_claim", "окно")
    окно_задачи = _аргумент("enqueue_bot_step", "defer_by")
    assert окно_ключа & имена_окна, (
        "срок ключа Redis считается отдельно от окна — он разъедется с отсрочкой задачи"
    )
    assert окно_задачи & имена_окна, (
        "отсрочка задачи считается отдельно от окна — тик проснётся не тогда, когда истечёт ключ"
    )
    assert окно_ключа == окно_задачи, (
        f"ключ ждёт {окно_ключа}, а задача {окно_задачи} — это разные числа"
    )


def test_обёртка_и_боевой_путь_берут_окно_из_одного_места() -> None:
    """Два разных числа в двух путях разъедутся при первой же правке."""
    inbound = (ПРИЛОЖЕНИЕ / "services" / "inbound.py").read_text(encoding="utf-8")
    runtime = (ПРИЛОЖЕНИЕ / "bots" / "runtime.py").read_text(encoding="utf-8")
    assert "debounce_window(" in inbound and "debounce_window(" in runtime
    # ⚠ ЧИСЛО ЖИВЁТ ТОЛЬКО В runtime: в боевом пути его быть не должно
    assert "timedelta(seconds=" not in inbound.split("if not backfill:")[-1][:2000], (
        "в боевом пути завелось своё число паузы — оно разъедется с runtime"
    )
