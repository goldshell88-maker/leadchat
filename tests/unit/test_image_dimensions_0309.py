"""Пропорции снимка доезжают до фронта — чтобы лента не прыгала (03.09).

⚠ ЧИСЛА. Строка с фотографией занимает 57 px до загрузки и 210–332 px после:
4:3 даёт +205, 9:16 +275, 16:9 +153. Всё, что ниже, уезжает под курсором ровно
в тот момент, когда человек читает. Вложения у 7,5 % входящих сообщений.

Пропорции у Авито ЕСТЬ и всегда были: версии фотографии приходят словарём вида
`{"140x105": url, "640x480": url}`, и разбор их СЧИТАЛ — чтобы выбрать самую
крупную, — после чего выбрасывал.
"""

from __future__ import annotations

from app.integrations.avito.adapter import _biggest_image_url, _extract_attachments


def test_размеры_возвращаются_вместе_с_адресом() -> None:
    url, w, h = _biggest_image_url({"sizes": {"140x105": "a", "1280x960": "b"}})
    assert (url, w, h) == ("b", 1280, 960), "берётся самая крупная версия и ЕЁ размеры"


def test_размеры_доезжают_до_вложения() -> None:
    (вложение,) = _extract_attachments({"image": {"sizes": {"140x105": "a", "640x480": "b"}}})
    assert вложение["url"] == "b"
    assert (вложение["width"], вложение["height"]) == (640, 480), (
        "без этих двух чисел фронту нечем зарезервировать место под снимок"
    )


def test_неразобранные_размеры_не_выдумываются() -> None:
    """⚠ ПОЛОВИНЧАТЫЕ ПРОПОРЦИИ ХУЖЕ ОТСУТСТВУЮЩИХ: по одному числу высоту не
    посчитать, а выдуманная пропорция резервирует НЕ ТО место."""
    # Ключ без «ШИРИНАxВЫСОТА» не даёт ни площади для сравнения, ни размеров —
    # поведение прежнее, разбор просто уходит на запасной адрес ниже.
    assert _biggest_image_url({"sizes": {"original": "a"}}) == (None, None, None)

    # Снимок с прямым адресом и без словаря размеров — обычный случай старых
    # сообщений: место под него резервировать нечем, и полей быть не должно.
    (вложение,) = _extract_attachments({"image": {"url": "u"}})
    assert вложение["url"] == "u"
    assert "width" not in вложение and "height" not in вложение, (
        "поля появились без значений — фронт построит по ним неверную пропорцию"
    )


def test_файлы_кроме_картинок_размеров_не_получают() -> None:
    (вложение,) = _extract_attachments({"file": {"url": "u", "name": "акт.pdf"}})
    assert "width" not in вложение
