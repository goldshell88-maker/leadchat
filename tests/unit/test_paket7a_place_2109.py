@pytest.mark.parametrize("текст", КОНТРПРИМЕРЫ)
def test_контрпримеры_при_on_как_сегодня(текст: str) -> None:
    старый = ap.parse_place(текст)
    assert старый is not None, "стенд: сегодня это место"
    assert ap.parse_place(текст, rules=ON) == старый
    тень = ap.parse_place(текст, rules=SHADOW)
    assert тень == старый and тень is not None and тень.trace is None


def test_имя_в_реестре_умолчание_off() -> None:
    """Имя заведено в реестре с умолчанием `off`: без записи `rule_state` отдавал
    бы `off`, что бы ни лежало в словаре, и `on` из настройки не включался бы."""
    assert ap.PARSE_RULES[ИМЯ] == ap.PARSE_OFF
    assert ap.rule_state(None, ИМЯ) == ap.PARSE_OFF
    assert ap.rule_state(ON, ИМЯ) == ap.PARSE_ON
    assert ap.rules_from_setting(f"{ИМЯ}=on")[ИМЯ] == ap.PARSE_ON


def test_форма_имени_напрямую() -> None:
    """Помощник по формам: (б) больше двух слов без заглавных — речь (через
    `_МЕСТО_ПУНКТ` такое имя не приходит: первое слово там заглавное — форма
    заведена по договору и держится тестом помощника); (в) хвост-глагол
    отрезан, судится остаток; короткое и справочное — имя."""
    assert ap._имя_пункта_речь("новое заозерье три") is True
    assert ap._имя_пункта_речь("Новое Заозерье") is False
    assert ap._имя_пункта_речь("новое заозерье") is False
    assert ap._имя_пункта_речь("Сколько работаете") is True
    assert ap._имя_пункта_речь("Падун работаете") is False
    assert ap._имя_пункта_речь("Кемерово выезжаете") is False
    assert ap._имя_пункта_речь("Напишу") is True
    assert ap._имя_пункта_речь("Баку") is False  # четыре буквы — не глагол
    assert ap._имя_пункта_речь("Сургут") is False  # справочник городов
    assert ap._имя_пункта_речь("Ангарск") is False  # квартальные города
    assert ap._имя_пункта_речь("Юность") is False  # «-сть» — существительное
