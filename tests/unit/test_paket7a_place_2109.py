"""Пакет 7a, раздел B (21.09): класс 12 `STOP_TYPED_PLACE_SPEECH` — пункт с
типом, чьё имя — речь (программа §2, контракт `contract_7a.md` §B.1).

Тип пункта с заглавным словом за ним — сильная форма, и «город Напишу», «село
Сколько», «посёлок выезжаете» рождали строку места уровня A (корзина
P_only_place). Класс живёт в `parse_place` и судит имя, которое ушло бы в
`settlement`, по ФОРМЕ: (а) единственное слово — глагол (`-у/-ю/-ешь/-ете/…`
от пяти букв, не из справочника городов), наречие (`-тельно/-ично/-ально`) или
слово речи из закрытого списка; (б) больше двух слов и ни одного с заглавной;
(в) глагол вторым-третьим словом отрезается ПЕРЕД судом, остаток судится как
(а)/(б) — обрезать имя в строке класс не вправе (это Q17): «посёлок Падун
работаете» при `on` остаётся как сегодня. Итог — `under_rule(rules,
"STOP_TYPED_PLACE_SPEECH", old=found, new=None)`: `on` — формы нет, `off` —
как сегодня байт в байт, `shadow` — та же строка со следом `stop_shadow`.

Отступление от договора (в отчёте): голое «-о» как наречие не взято — по нему
легли бы «мешково», «Иваново», «Мурино», «Тосно», «Ровно», самые частые
окончания пунктов; вместо него — частые наречия закрытым списком.

ДИВЕРСИИ (каждая прогнана 21.09 «правка → тест → откат», хеш файла сверен):
вернуть `found` из `parse_place` без `under_rule` (всегда старый разбор) —
`test_ложная_форма_on_off_shadow`; убрать `PARSE_RULES[STOP_TYPED_PLACE_SPEECH]
= PARSE_OFF` — тот же тест и `test_имя_в_реестре_умолчание_off`; убрать
исключение справочника городов в `_слово_пункта_речь` —
`test_контрпримеры_при_on_как_сегодня` («город Сургут», «город Барнаул»);
взять голое «-о» наречием — тот же тест («Деревня мешково», «посёлок Тосно»);
убрать обрезку хвоста в `_имя_пункта_речь` — `test_ложная_форма_on_off_shadow`
(«село Сколько работаете»); снимать форму после обрезки, когда остаток — имя
— `test_контрпримеры_при_on_как_сегодня` («посёлок Падун работаете»);
`under_rule(old=found, new=found)` вместо `new=None` — тень без следа,
`test_ложная_форма_on_off_shadow`.

Реплики вымышленные и маскированные, телефонов и имён нет.
"""

from __future__ import annotations

import pytest

from app.services import address_parse as ap

ИМЯ = ap.STOP_TYPED_PLACE_SPEECH
ON = {ИМЯ: ap.PARSE_ON}
OFF = {ИМЯ: ap.PARSE_OFF}
SHADOW = {ИМЯ: ap.PARSE_SHADOW}

# ── ложные формы: текст → (тип, пункт, ключ) как сегодня ─────────────────────
# Снято прогоном 21.09 (карта `map7a_q16.md` §5, строка 12): все — A/place.

ЛОЖНЫЕ = [
    # (а) глагол одним словом
    ("город Напишу", ("город", "Напишу", "город Напишу")),
    ("город Выключился", ("город", "Выключился", "город Выключился")),
    ("город Позвоню", ("город", "Позвоню", "город Позвоню")),
    ("посёлок выезжаете", ("посёлок", "выезжаете", "посёлок выезжаете")),
    ("деревня Работаете", ("деревня", "Работаете", "деревня Работаете")),
    ("пгт Приедете", ("посёлок", "Приедете", "посёлок Приедете")),
    # (а) наречие
    ("город Приблизительно", ("город", "Приблизительно", "город Приблизительно")),
    ("посёлок Реально", ("посёлок", "Реально", "посёлок Реально")),
    ("посёлок Максимально", ("посёлок", "Максимально", "посёлок Максимально")),
    # (а) слово речи
    ("село Сколько", ("село", "Сколько", "село Сколько")),
    ("село Сколько стоит", ("село", "Сколько", "село Сколько")),
    ("село Быстро", ("село", "Быстро", "село Быстро")),
    # (в) → (а): глагол вторым словом отрезан, остаток — речь
    ("село Сколько работаете", ("село", "Сколько работаете", "село Сколько работаете")),
    # Массив рядом форму не спасает: снимается целиком (договор §B.1, `new=None`).
    ("город Напишу, СНТ Ромашка", ("город", "Напишу", "город Напишу, СНТ Ромашка")),
]


@pytest.mark.parametrize(("текст", "сегодня"), ЛОЖНЫЕ, ids=[t for t, _ in ЛОЖНЫЕ])
def test_ложная_форма_on_off_shadow(текст: str, сегодня: tuple[str, str, str]) -> None:
    """`off`/без правила — как сегодня (снимок); `on` — формы нет; `shadow` —
    та же строка, след `stop_shadow`; строк класс не заводит нигде."""
    старый = ap.parse_place(текст)
    assert старый is not None and старый.kind == ap.KIND_PLACE and старый.level == ap.LEVEL_A
    assert (старый.settlement_type, старый.settlement, старый.value) == сегодня
    assert старый.trace is None
    assert ap.parse_place(текст, rules=OFF) == старый
    assert ap.parse_place(текст, rules={}) == старый
    assert ap.parse_place(текст, rules=ON) is None
    тень = ap.parse_place(текст, rules=SHADOW)
    assert тень is not None and тень is not старый
    assert (тень.settlement_type, тень.settlement, тень.value) == сегодня
    assert тень.trace == {"stop_shadow": ИМЯ}


