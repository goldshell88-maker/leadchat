"""Документы про телефоны лид-бота говорят то же, что делает код.

ПОЧЕМУ ЭТО ОТДЕЛЬНЫЙ СТОРОЖ. 16 августа маскировку телефонов для лид-бота сняли
коммитом `906a6e8`. Коммит тронул код, сценарий и тесты — и не тронул ни одного
документа. В итоге одиннадцать дней подряд три места подряд утверждали
обратное живому поведению:

* `docs/42-TZ-LEADBOT.md` §7.1 — «маскировка оставлена, решение за владельцем»;
* шапка модуля `app/bots/leadbot.py` — «⚠ ТЕЛЕФОНЫ УХОДЯТ ЗАМАСКИРОВАННЫМИ»;
* комментарий в `app/bots/engine.py` у самой записи журнала — «телефоны здесь
  уже замаскированы».

Причём последний стоял ровно в том месте, где человек решает, безопасно ли
трогать журнал. Нашлось это только когда построили карту знаний и она столкнула
лбами два утверждения из разных концов корпуса.

Поведение стережёт `test_бот_видит_телефон_сырым` в `test_bot_leadbot.py`. Здесь
стережём ВТОРУЮ половину договора: что написанное про приватность совпадает с
сделанным. Сторож текстовый и потому грубый — он не понимает смысла, он ловит
ровно те формулировки, которые уже один раз соврали. Этого достаточно: врут не
случайные слова, врёт снятое и не переписанное утверждение.
"""

from pathlib import Path

import pytest

from app.bots.engine import ScenarioEngine
from app.bots.provider import LEADBOT

КОРЕНЬ = Path(__file__).resolve().parents[2]

# Формулировки, которые ОДИН РАЗ уже пережили снятие маски и остались врать.
# Список закрытый и растёт только вместе с новым случаем такой же лжи.
СНЯТЫЕ_УТВЕРЖДЕНИЯ = (
    "ТЕЛЕФОНЫ УХОДЯТ ЗАМАСКИРОВАННЫМИ",
    "маскировка оставлена",
    "Телефоны здесь уже замаскированы",
)


def _текст(путь: str) -> str:
    return (КОРЕНЬ / путь).read_text(encoding="utf-8")


@pytest.mark.parametrize(
    "путь",
    ["app/bots/leadbot.py", "app/bots/engine.py", "docs/42-TZ-LEADBOT.md"],
)
def test_ни_одно_место_не_обещает_снятой_маскировки(путь: str) -> None:
    текст = _текст(путь)
    найдено = [ф for ф in СНЯТЫЕ_УТВЕРЖДЕНИЯ if ф in текст]
    assert not найдено, (
        f"{путь} снова обещает маскировку телефонов для лид-бота: {найдено}. "
        "Либо код вернул маску — тогда поправьте и этот список, и "
        "test_лид_бот_видит_телефон_сырым; либо документ отстал от кода снова."
    )


def test_развилка_маскировки_на_месте_и_названа_в_коде() -> None:
    """Ветка `mask=False` для лид-бота — то самое место, о котором пишут документы.

    Если её переименуют или уберут, тексты выше станут описывать несуществующий
    механизм — и сторож обязан упасть здесь, а не через одиннадцать дней.
    """
    движок = _текст("app/bots/engine.py")
    assert "mask=provider_of(self.bot) != LEADBOT" in движок, (
        "Развилка маскировки в `_ai_request` изменилась. Приведите в "
        "соответствие шапку app/bots/leadbot.py и docs/42-TZ-LEADBOT.md §7.1."
    )
    # Значение провайдера читаем из кода, а не из строки: переименование
    # константы обязано ломать сторож, а не проходить мимо него.
    assert LEADBOT, "Провайдер лид-бота исчез — документы про него потеряли предмет"
    assert hasattr(ScenarioEngine, "load_dialog_for_ai")


def test_журнал_маскируется_отдельным_вызовом() -> None:
    """Защита журнала не должна зависеть от того, что диалог уже чистый.

    Для лид-бота он НЕ чистый. Маскировку при записи делает `_record_leadbot`
    своим вызовом `mask_phones`; убрать его — значит положить телефон клиента в
    нашу собственную таблицу `leadbot_calls`.
    """
    движок = _текст("app/bots/engine.py")
    начало = движок.index("async def _record_leadbot")
    тело = движок[начало : начало + 2500]
    assert "mask_phones(" in тело, (
        "В `_record_leadbot` пропал вызов mask_phones — телефон клиента поедет "
        "в журнал leadbot_calls открытым текстом."
    )
