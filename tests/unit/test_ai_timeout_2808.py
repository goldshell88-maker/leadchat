"""Запас по таймауту вызова лид-бота — на сеть, а не на модель.

ЗАМЕР 28.08 по 1 760 боевым ответам лид-бота (журнал systemd, поле `ms`):
    медиана 2 128 мс · p75 3 183 · p90 4 167 · p95 4 659 · p99 5 488 · максимум 8 588

Дольше десяти секунд бот не ответил НИ РАЗУ. Значит прежние 10 с обрезали не
медленную модель, а сетевые обрывы: канал до бота идёт через wg0, и его падения
уже стоили «Failed to fetch» расширению CRM.

В боевой базе панели 38 записей «AI недоступен», и в одном диалоге их доходило до
четырёх подряд — при том что клиент за это время успел сказать «Да, хочу», дать
номер и написать «Спасибо, жду!». Заявка не собралась.

Ретраев по-прежнему нет (02 §3.3): один заход, дальше человек.
"""

from __future__ import annotations

from app.core.config import settings


def test_запас_на_сеть() -> None:
    assert settings.ai_timeout_seconds >= 15, (
        "p99 ответа 5,5 с; меньше пятнадцати — запас на сеть меньше десяти секунд"
    )


def test_не_бесконечное_ожидание() -> None:
    """⚠ Клиент ждёт ответа: таймаут складывается с паузой дебаунса (15–30 с)."""
    assert settings.ai_timeout_seconds <= 20, "клиент не должен ждать ответа полминуты"


def test_заметка_о_недоступности_не_дублируется() -> None:
    """Передача защищена handoff_done, а заметка раньше — нет: в ленту падало
    «AI недоступен» на каждую попытку (14 диалогов, до шести записей, 29 лишних)."""
    import inspect

    from app.bots import engine

    src = inspect.getsource(engine)
    i = src.index("AI_UNAVAILABLE_NOTE)")
    окно = src[max(0, i - 400) : i]
    assert "if not self.state.handoff_done():" in окно, (
        "заметка о недоступности пишется без проверки, что диалог уже передан"
    )
