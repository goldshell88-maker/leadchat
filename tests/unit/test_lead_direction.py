"""Направление заявки решает объявление, а не канал.

Владелец 14 августа, дословно: «у аккаунта нет конкретно направления, сам бот должен
решать, на какое направление создавать заявку». Он прав по устройству: в один канал
Авито пишут и про телевизор, и про принтер, объявлений у аккаунта много, а
`lead_src_key` один.

⚠ ЭТО ВЫВОД, А НЕ ДОГАДКА. Клиент выбрал направление САМ, написав в конкретное
объявление. Слова переписки для этого не годятся: «не включается» одинаково подходит
телевизору и компьютеру.

НАЗВАНИЯ ВЗЯТЫ ИЗ БОЯ, а не придуманы — все шесть объявлений заказчика на 14 августа,
49 диалогов из 50. Отнесение подтверждено владельцем: принтеры и МФУ — компьютерная
помощь вместе с Windows.
"""

from __future__ import annotations

import pytest

from app.services.lead_direction import BT, KP, MNC, detect, detect_from_problem

#: Ровно то, что лежит в боевой базе. Числа — сколько диалогов на каждом объявлении.
БОЕВЫЕ = [
    (
        "Ремонт телевизоров и настройка каналов с выездом / Замена подсветки / "
        "Подключение приставки",
        BT,
        19,
    ),
    ("Настройка телевизора / Каналы, SMART TV, Wi-Fi и приложения", BT, 9),
    (
        "Ремонт принтеров и мфу / Полная настройка / Подключение к устройству / "
        "Выезд по городу / Гарантия",
        KP,
        7,
    ),
    ("Ремонт телевизоров с выездом на дом / Диагностика / Гарантия", BT, 7),
    ("Ремонт принтеров и мфу / Не печатает, зажёвывает бумагу", KP, 6),
    ("Установка Windows и ос / Драйверы, программы и настройка", KP, 1),
]


@pytest.mark.parametrize(("название", "ожидание", "диалогов"), БОЕВЫЕ)
def test_боевые_объявления_разбираются_верно(название, ожидание, диалогов):
    assert detect(название) == ожидание, (
        f"объявление с {диалогов} диалогами уедет не в тот лид-центр"
    )


def test_принтер_с_настройкой_не_уезжает_к_телевизорам():
    """⚠ ПОРЯДОК ПРАВИЛ ВАЖЕН, и этот тест его стережёт.

    «Ремонт принтеров и мфу / Полная настройка / …» содержит слово «настройка», а
    правило телевизоров ловит «каналов/каналы». Стоит поменять правила местами или
    расширить телевизорное слишком широко — тринадцать диалогов про принтеры поедут
    к мастеру по бытовой технике.
    """
    assert detect("Ремонт принтеров и мфу / Полная настройка / Подключение") == KP


def test_неизвестное_объявление_не_выдумывает_направление():
    """⚠ САМЫЙ ВАЖНЫЙ ТЕСТ ФАЙЛА.

    Соблазн «если не поняли — пусть будет БТ» выглядит безобидно ровно до первого
    принтера, уехавшего к мастеру по технике. Незнание обязано дойти до вызывающего,
    чтобы тот взял настройку канала или придержал заявку — оба ответа честнее
    выдуманного.
    """
    assert detect("Услуга без узнаваемых слов") is None
    assert detect("") is None
    assert detect(None) is None


def test_регистр_и_склонения_не_мешают():
    assert detect("РЕМОНТ ТЕЛЕВИЗОРА") == BT
    assert detect("ремонт Принтеров") == KP


# ── направление по ПРОБЛЕМЕ КЛИЕНТА (решение владельца 15.08) ─────────────────────


def test_проблема_перебивает_объявление_на_уровне_вызова():
    """Сам детект по словам клиента: пишут про стиралку в чат про компьютеры."""
    assert detect_from_problem("Здравствуйте, стиральная машина не сливает воду") == BT
    assert detect_from_problem("не печатает принтер, полосит") == KP
    assert detect_from_problem("нужно собрать шкаф и повесить полку") == MNC


def test_проблема_без_слов_техники_направления_не_даёт():
    """«Не включается, приезжайте» подходит и телевизору, и компьютеру — None,
    дальше решает объявление."""
    assert detect_from_problem("не включается, приезжайте скорее") is None
    assert detect_from_problem("") is None
    assert detect_from_problem(None) is None


def test_две_техники_побеждает_первая_названная():
    """Клиент начинает с главной проблемы — она и есть заявка."""
    assert detect_from_problem("стиралка гудит, и комп потом гляньте") == BT
    assert detect_from_problem("комп сгорел, заодно стиралку посмотрите") == KP


def test_плитка_не_уезжает_к_газовым_плитам():
    """«Положить плитку» — муж на час; подстрока «плит» тянула бы в БТ,
    побеждает более длинное совпадение."""
    assert detect_from_problem("нужно положить плитку в ванной") == MNC
    assert detect_from_problem("не зажигается плита") == BT
