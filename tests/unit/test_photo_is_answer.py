"""Фото — это ответ клиента, а не молчание.

СНИМОК ВЛАДЕЛЬЦА 26.08. Бот спросил модель ноутбука, клиент в 21:12 прислал фотографию
блока питания, а в 21:14 диалог ушёл менеджеру с причиной «клиент не ответил в отведённое
время (ask_timeout)». Владелец: «бот передал, хотя клиент выдал фото».

ДВЕ ПРИЧИНЫ, И ОБЕ ЗАКРЫТЫ ЗДЕСЬ.

1. В ШАГ БОТА УЕЗЖАЛ ТОЛЬКО ТЕКСТ. У сообщения с одной картинкой текст пустой, а для
   движка пустая строка означает «клиент промолчал»: `validate_answer` такой ответ не
   принимает, ожидание не снимается. Теперь сообщение без текста, но с вложением уходит
   маркером «🖼 фото» — ответ непустой, ожидание снимается, разговор идёт к шагу ИИ,
   который картинку как раз читать умеет.

2. ДЕДЛАЙН СПОРИЛ С УЖЕ ПРИШЕДШИМ ОТВЕТОМ. `waiting` снимает шаг бота, а он отложен
   окном серии на полторы-две с половиной минуты. Всё это время сообщение клиента уже
   в базе, а `waiting` ещё стоит — и дедлайн, сработав первым, объявляет молчание.
   ⚠ ЭТО ПОБОЧНЫЙ ЭФФЕКТ МОЕЙ ЖЕ ПРАВКИ ТОГО ЖЕ ДНЯ: до подключения паузы шаг бота
   исполнялся сразу и успевал снять ожидание. Теперь дедлайн сперва смотрит, чьё в
   ленте последнее слово, и на слове клиента не срабатывает вовсе.
"""

from __future__ import annotations

import ast
import pathlib

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[2]


def _исходник(*части: str) -> str:
    return (КОРЕНЬ.joinpath(*части)).read_text(encoding="utf-8")


def _функция(текст: str, имя: str) -> str:
    дерево = ast.parse(текст)
    for узел in ast.walk(дерево):
        if isinstance(узел, ast.AsyncFunctionDef | ast.FunctionDef) and узел.name == имя:
            return ast.get_source_segment(текст, узел) or ""
    raise AssertionError(f"функция {имя} не найдена")


def test_сообщение_с_вложением_не_пустое() -> None:
    """Иначе движок примет фото за молчание."""
    from app.services.inbound import _текст_для_бота

    class _Соб:
        def __init__(self, text, attachments):
            self.text = text
            self.attachments = attachments

    assert _текст_для_бота(_Соб("", [{"url": "u"}])) == "🖼 фото"
    assert _текст_для_бота(_Соб("   ", [{"url": "u"}])) == "🖼 фото"
    assert _текст_для_бота(_Соб("Lenovo G50", [{"url": "u"}])) == "Lenovo G50"
    assert _текст_для_бота(_Соб("", [])) == ""


def test_маркер_проходит_валидацию_ответа() -> None:
    """«🖼 фото» обязано считаться ответом на обычном шаге ask."""
    from app.bots.steps import validate_answer

    ok, value = validate_answer({}, "🖼 фото")
    assert ok is True and value == "🖼 фото"


def test_фото_не_считается_телефоном() -> None:
    """А вот на шаге с проверкой номера картинка ответом быть не должна."""
    from app.bots.steps import validate_answer

    ok, _ = validate_answer({"validate": "phone"}, "🖼 фото")
    assert ok is False


def test_маркер_подключён_к_постановке_шага() -> None:
    """Проверка выше зелёная и с вырезанным вызовом — ловим само подключение."""
    исх = _исходник("app", "services", "inbound.py")
    assert "_текст_для_бота(event)" in исх, (
        "маркер вложения не доезжает до шага бота — фото снова станет молчанием"
    )


def test_дедлайн_не_срабатывает_на_ответе_клиента() -> None:
    """Последнее слово клиента — значит он ответил, молчанием это звать нельзя."""
    тело = _функция(_исходник("app", "bots", "runtime.py"), "bot_ask_timeout")
    assert "Message.direction" in тело, "дедлайн не смотрит, чьё последнее слово"
    assert '"answered"' in тело, "нет ветки «клиент ответил» — дедлайн выстрелит вхолостую"
