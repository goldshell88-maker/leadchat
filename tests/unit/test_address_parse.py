def test_сторож_цитаты_держится_на_петербургских_формах() -> None:
    """⚠ СТОРОЖ ЛОМАЛСЯ РОВНО ТАМ, РАДИ ЧЕГО МОДУЛЬ И ПИСАЛСЯ.

    Район («В.О.», «П.С.») стоит МЕЖДУ улицей и домом, и первая редакция
    вырезала его перед разбором — вместе со сдвигом всех смещений. `raw` и
    `start`/`end` начинали указывать в другой текст, и сторож не сходился на
    «12-я линия В.О., д. 7» и «Большой проспект П.С. 40». То есть боевой замер
    «не сошёлся 3 раза из 6 529» был получен сторожем, который на боевом городе
    не работал.

    Теперь район гасится ПРОБЕЛАМИ той же длины: смещения на месте, цитата
    находится в сообщении дословно.

    ⚠ И ПРОВЕРЯЕТСЯ ЗДЕСЬ НЕ `raw == текст[start:end]`. Такое сравнение
    ТАВТОЛОГИЧНО: `raw` этим срезом и определён, и не может разойтись с ним ни
    при какой поломке. Первая редакция этой проверки именно так и была
    написана — и оставалась зелёной под диверсией. Настоящий признак: в
    вырезанном куске обязаны найтись И улица, И номер дома. При сдвинутых
    смещениях кусок кончается на районе, и дома в нём нет.

    ДИВЕРСИЯ: вернуть `_РАЙОН_СПБ.sub(" ", ...)` — обе проверки краснеют.
    """
    for текст in ("12-я линия В.О., д. 7", "Большой проспект П.С. 40"):
        f = ap.parse(текст)
        assert f is not None, текст
        assert ap.quote_holds(f, текст), текст
        assert f.raw == текст[f.start : f.end]
        assert f.house in f.raw, f"дом {f.house!r} вне куска {f.raw!r} ({текст})"
        assert f.street.split()[-1] in f.raw, f"улица вне куска {f.raw!r} ({текст})"


def test_сторож_цитаты_ловит_подмену_в_названии_улицы() -> None:
    """Самая дорогая ошибка — подмена буквы в НАЗВАНИИ, а не в доме.

    Первая редакция сверяла только цифры дома по одной, то есть подмену улицы
    пропускала: «Кировградская» вместо «Кировоградской» ведёт мастера на другую
    улицу с тем же номером дома.

    ДИВЕРСИЯ: вернуть сверку по цифрам дома — проверка краснеет.
    """
    f = ap.parse("ул. Кировоградская 5")
    assert f is not None
    assert not ap.quote_holds(f, "ул. Кировградская 5")
    подменённый = dataclasses.replace(f, house="7")
    assert not ap.quote_holds(подменённый, "ул. Кировоградская 5")


