"""Лид-бот обязан знать, чья реплика — его собственная или живого оператора.

ЧТО СЛУЧИЛОСЬ. `load_dialog_for_ai` ставила роль `assistant` и на ответ бота, и на
сообщение человека: для истории это одно и то же — «наша сторона». Но у лид-бота есть
заслон «диалог уже ведёт человек, не вмешиваюсь», и считает он именно ходы нашей
стороны. Не различая автора, бот доходил до третьей СВОЕЙ реплики и объявлял, что
разговор ведёт оператор, — сам себя.

ЦЕНА. Снимок владельца 26.08 (Оксана, Чита): бот собрал телефон, адрес и согласовал
время «завтра к 10:00-10:30», клиент ответил «Хорошо» — и вместо заявки диалог ушёл
человеку. Владелец: «почему он не создал, он ведь договорился». Заявка создаётся ходом
бота, а хода не было вовсе. Боевой журнал того же мгновения:

    {"layer": "локальный роутер (не наш диалог)", "confidence": 0.0,
     "flag": {"kind": "not_primary",
              "reason": "не первичный: оператор уже ведёт разговор (3 ходов)"}}

Тех трёх «ходов оператора» не существовало: это три реплики бота.

МАСШТАБ: за 7 дней 311 ходов из 1436 (21,7 %) ушли человеку с причиной `not_primary`, а
диалогов, где бот написал 3+ раза и человек не написал ни разу, — 517 из 518.

ВТОРАЯ ПОЛОВИНА ТОГО ЖЕ СНИМКА. В ленте у диспетчера стояло «Причина: AI не уверен в
ответе (ai_low_confidence)», а рядом заметкой — правильное «диалог уже ведёт человек».
`exec_ai_answer` умеет брать настоящую причину из `meta.escalation.reason`, но данные до
неё не доезжали: `_normalize_answer` собирала ответ из трёх полей и `meta` не клала
никогда. Очередь сортируют по причине передачи — значит она обязана быть правдой.
"""

from __future__ import annotations

import ast
import pathlib

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[2]
ДВИЖОК = КОРЕНЬ / "app" / "bots" / "engine.py"
МОСТ = КОРЕНЬ / "app" / "bots" / "leadbot.py"


def test_история_помечает_автора_нашей_стороны() -> None:
    """Без пометки лид-бот считает свои же ответы чужими и замолкает."""
    исходник = ДВИЖОК.read_text(encoding="utf-8")
    assert '"by"' in исходник, (
        "история уходит в лид-бот без автора реплики — вернётся поломка 26.08, "
        "когда бот глушил сам себя на третьей своей реплике"
    )
    assert 'msg.sender_type == "bot"' in исходник, (
        "автор определяется не по типу отправителя — а различить бота и человека больше нечем"
    )


def test_пометка_стоит_только_на_нашей_стороне() -> None:
    """У реплики клиента автора нашей стороны нет и быть не может."""
    исходник = ДВИЖОК.read_text(encoding="utf-8")
    ветка = исходник.split('if role == "assistant":', 1)
    assert len(ветка) == 2, "пометка автора перестала быть привязана к нашей стороне"
    assert '"by"' in ветка[1][:200]


def test_meta_доезжает_до_движка() -> None:
    """Иначе причина передачи в очереди — заглушка «AI не уверен» на каждый случай."""
    дерево = ast.parse(МОСТ.read_text(encoding="utf-8"))
    кладут_meta = any(
        isinstance(узел, ast.Assign)
        and any(
            isinstance(ц, ast.Subscript)
            and getattr(ц.value, "id", "") == "answer"
            and getattr(getattr(ц, "slice", None), "value", None) == "meta"
            for ц in узел.targets
        )
        for узел in ast.walk(дерево)
    )
    assert кладут_meta, (
        "`meta` не попадает в ответ движку — `exec_ai_answer` не сможет назвать настоящую "
        "причину передачи и напишет в очередь ai_low_confidence на каждый случай"
    )


def test_наружу_уходит_только_причина_без_данных_клиента() -> None:
    """В `meta` лежит `lead` с телефоном и адресом — целиком её отдавать нельзя.

    Ответ шага уходит дальше по движку и попадает в записи, которые читают шире, чем
    переписку. Правило то же, что у `_log_meta`: имена полей — можно, значения — нет.
    """
    import app.bots.leadbot as leadbot

    ответ = leadbot._parse(
        {
            "reply": "",
            "confidence": 0.0,
            "needs_operator": True,
            "meta": {
                "escalation": {"reason": "not_primary", "deadline_min": 30},
                "lead": {"phone": "+79001234567", "address": "Ленина 5"},
                "layer": "локальный роутер",
            },
        }
    )
    assert ответ["meta"] == {"escalation": {"reason": "not_primary"}}, (
        "наружу ушло больше причины передачи — вместе с данными клиента"
    )
    выгрузка = repr(ответ)
    assert "79001234567" not in выгрузка and "Ленина" not in выгрузка


def test_движок_берёт_причину_из_meta() -> None:
    """Вторая половина той же проводки: данные есть, а читать их некому."""
    исходник = ДВИЖОК.read_text(encoding="utf-8")
    assert '(result.get("meta") or {}).get("escalation")' in исходник, (
        "движок перестал читать причину передачи от бэкенда"
    )
