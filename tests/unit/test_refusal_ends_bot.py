# --- Сквозная проводка признака (27.08) --------------------------------------


def test_признак_отказа_доживает_до_движка() -> None:
    """⚠ ПЯТЬ ПРОВЕРОК ВЫШЕ СМОТРЕЛИ ТОЛЬКО НА ДВИЖОК — И ПРОПУСТИЛИ РЕГРЕССИЮ.

    Движок ищет `meta.flag.kind == "refuse"` в ответе шага. Ответ этот собирает
    `leadbot._parse`, и 27.08 он был сужен до одного поля — причины эскалации:
    правка защищала `meta.lead` с телефоном и адресом клиента от утечки в ленту.
    Вместе с адресом исчез и флаг, движок перестал его видеть, и бот снова начал
    дожимать клиента после собственного «не помогу» — ровно то, на что владелец
    жаловался 26.08.

    Проверки движка при этом остались зелёными: он-то умеет читать флаг, просто
    получать его перестал. Поэтому здесь — сквозной путь, от ответа чужого
    сервиса до того, что уходит в шаг.
    """
    from app.bots.leadbot import _parse

    ответ = _parse(
        {
            "reply": "С битой матрицей не помогу",
            # `needs_operator` и `confidence` обязательны: без них `_parse`
            # честно возвращает None — форма ответа чужого сервиса проверяется
            # строго, и это правильно.
            "needs_operator": False,
            "confidence": 0.9,
            "meta": {
                "flag": {"kind": "refuse", "why": "матрица"},
                "escalation": {"reason": "не наш профиль"},
                # ⚠ Личные данные обязаны остаться за бортом: ради этого правка
                # и делалась, и ослаблять её нельзя.
                "lead": {"phone": "+79001234567", "address": "Ленина 5"},
            },
        }
    )

    assert ответ["meta"]["flag"]["kind"] == "refuse", "движку нечего будет прочитать"
    assert ответ["meta"]["escalation"]["reason"] == "не наш профиль"
    # Ни телефона, ни адреса — ни на одном уровне ответа.
    как_текст = repr(ответ)
    assert "79001234567" not in как_текст, как_текст
    assert "Ленина" not in как_текст, как_текст
    assert "lead" not in ответ["meta"], ответ["meta"]


def test_без_флага_мета_не_выдумывается() -> None:
    """Ответ без флага и без причины не должен обзаводиться пустым `meta`:
    движок отличает «признака нет» от «признак пустой»."""
    from app.bots.leadbot import _parse

    ответ = _parse(
        {
            "reply": "Подъеду сегодня к 18:00",
            "needs_operator": False,
            "confidence": 0.9,
            "meta": {"lead": {"phone": "+79001234567"}},
        }
    )
    assert "meta" not in ответ, ответ
