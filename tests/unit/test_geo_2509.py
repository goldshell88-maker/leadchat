async def test_гаражный_кооператив_в_воркере_не_ложится_а_жилой_дом_пригорода_да(
    seed_conversation: Any,
    db_sessionmaker: Any,
    redis: Any,
    dadata_отвечает: dict[str, Any],
    osm_пусто: Any,
    точка_города: dict[str, Any],
) -> None:
    """Воркер целиком: по городу DaData знает только кооператив с тем же
    номером; по области рядом — он же и жилой дом в посёлке за 7 км. Раньше
    в карточку ложился кооператив с приблизительной точкой; теперь город
    отказывает, а пригород даёт жилой дом."""
    await _режим(db_sessionmaker, "nominatim")
    точка_города["точка"] = ТОЧКА_ТАМБОВА
    dadata_отвечает["ответы"] = [_тамбов(_гск()), _тамбов(_гск(), ЖИЛОЙ_В_ПОСЁЛКЕ)]
    found = _found("лесной", "27", raw="лесной 27")
    cid = await _строка(seed_conversation, db_sessionmaker, "tambov", found)
    assert await worker.geocode_candidate(ctx(db_sessionmaker, redis), cid) == g.GEO_EXACT
    row = await _row(db_sessionmaker, cid)
    assert row.geo_formatted == "мкр Лесной, 27, Садовый"
    assert row.geo_provider == "dadata" and not row.geo_variants
    assert "кооператив" not in (row.geo_formatted or "")


# ── район клиента и город объявления (Тверь): сторожа, правки нет ─────────────


def test_дом_деревни_не_подписывается_городом_объявления() -> None:
    """Деревня области печатается своим именем и городом объявления не
    становится: без слов клиента о месте это «другой город», не exact в
    Твери. Строка «…, Тверь, <район> район» в карточке владельца — не
    подмена имени деревни, а дом-тёзка в самом городе и район словами
    клиента (`address_text`); район клиента вердикт пока не читает — правка
    вне этого пакета, и сторож здесь её не запирает."""
    деревня = _dadata(
        {
            "suggestions": [
                _подсказка(
                    {
                        "region_with_type": "Тверская обл",
                        "area_with_type": "Озёрный р-н",
                        "city": None,
                        "settlement": "Сосновка",
                        "settlement_with_type": "д Сосновка",
                        "street_with_type": "ул Полевая",
                        "house": "12",
                        "geo_lat": "56.61",
                        "geo_lon": "36.52",
                        "qc_geo": "3",
                        "fias_level": "8",
                    }
                )
            ]
        }
    )
    parsed = g.Parsed(street="Полевая", house="12", level="B")
    assert (деревня[0].settlement, деревня[0].city) == (None, "Сосновка")
    assert g.format_address(деревня[0], parsed) == "ул Полевая, 12, Сосновка"
    статус, hit = g.verdict(parsed, ТВЕРЬ, деревня)
    assert статус == g.GEO_CITY_MISMATCH and hit is None
    # Вариантом «в другом месте» деревня идёт тоже своим именем.
    assert [v["formatted"] for v in g.variants(parsed, ТВЕРЬ, деревня)] == [
        "ул Полевая, 12, Сосновка"
    ]
