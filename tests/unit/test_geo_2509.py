"""Вердикт карты 25.09: СНТ улицей у карты, гаражный кооператив, район клиента.

Случаи владельца 25.09 (настоящие строки клиентов в репозиторий не идут —
здесь вымышленные той же формы, города оставлены: у каждого своя раскладка
DaData).

* Ангарск: «Снт <имя> дом <N>» уходил в «в городе объявления такого дома нет,
  но он есть в области» с вариантом «тер. СНТ <имя>, <N>, <квартал>, Ангарск»
  — дом в самом городе объявления. DaData пишет такое СНТ элементом улицы
  внутри квартала: массив лежит в `street`, а в `settlement` — номер квартала.
  Сторож пункта (`_годные_дома`) смотрел в пункт, город и массив ответа, но не
  в улицу — СНТ клиента «не находилось».
* Тамбов: «<имя> <N>» лёг в карточку «тер гаражно-строительный кооператив
  <Имя>-<k>, <N>, Тамбов» с приблизительной точкой, а клиент живёт в
  микрорайоне соседнего посёлка. `_улица_не_шире` прощает слова карты ПЕРЕД
  первым совпавшим — имя и звание («Феликса Дзержинского») — и так же прощала
  вид нежилого объекта.
* Тверь: «ул <улица>, <N>, Тверь, <район> район» — дом-тёзка в самом городе
  объявления, а район дописан к строке карты словами клиента
  (`address_text`). Правки здесь нет: район клиента вердикт не читает, а
  района карты у `GeoHit` нет. Сторож ниже — деревня городом объявления не
  подписывается.

ДИВЕРСИИ (каждая обязана краснеть): убрать массив-улицу из `_места_ответа` →
краснеют СНТ Ангарска (чистый вердикт и воркер); убрать сторож гаражного
кооператива из `_улица_не_шире` → краснеют кооператив Тамбова, «жилой дом
выигрывает» и воркер; дать точке второй карты массив-улицу → краснеет сторож
точки тёзки-СНТ.
"""

