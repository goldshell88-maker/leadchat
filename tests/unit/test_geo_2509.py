УЛАН_УДЭ = City("Улан-Удэ", "Республика Бурятия", "Asia/Irkutsk")


def _dadata(ответ: dict[str, Any]) -> list[g.GeoHit]:
    """Разбор живёт в шлюзе; вердикту нужны dataclass-ы LeadChat."""
    return [g.GeoHit(**h.model_dump()) for h in gw_dadata.parse_response(ответ)]


def _подсказка(data: dict[str, Any]) -> dict[str, Any]:
    return {"value": "…", "data": data}


# ── СНТ улицей у карты (Ангарск) ─────────────────────────────────────────────


def _снт_улицей(улица: str = "тер. СНТ Зарница", дом: str = "118") -> list[g.GeoHit]:
    """Раскладка DaData, которую показал экран владельца: массив — элемент
    улицы, пункт — квартал города, город — Ангарск; точка — массива."""
    return _dadata(
        {
            "suggestions": [
                _подсказка(
                    {
                        "region_with_type": "Иркутская обл",
                        "city": "Ангарск",
                        "settlement": "207",
                        "settlement_with_type": "кв-л 207",
                        "street_with_type": улица,
                        "house": дом,
                        "geo_lat": "52.531",
                        "geo_lon": "103.884",
                        "qc_geo": "3",
                        "fias_level": "8",
                    }
                )
            ]
        }
    )


#: Разбор «Снт Зарница дом 118» сегодня: массив — и улица, и пункт с типом.
ЗАРНИЦА = g.Parsed(
    street="Снт Зарница", house="118", settlement="Зарница", settlement_type="СНТ", level="A"
)


def test_снт_у_разбора_и_улица_и_пункт() -> None:
    """Предпосылка: форма разбора та же, что у строки владельца."""
    found = address_parse.parse("Снт Зарница дом 118")
    assert found is not None
    assert (found.street, found.house, found.settlement, found.settlement_type) == (
        ЗАРНИЦА.street,
        ЗАРНИЦА.house,
        ЗАРНИЦА.settlement,
        ЗАРНИЦА.settlement_type,
    )


def test_снт_улицей_у_карты_это_пункт_клиента() -> None:
    """Дом в названном СНТ и в самом городе объявления — exact, а не «есть в
    области»: массив-улица карты называет пункт клиента."""
    hits = _снт_улицей()
    assert (hits[0].street, hits[0].settlement, hits[0].city) == (
        "тер. СНТ Зарница",
        "207",
        "Ангарск",
    )
    статус, hit = g.verdict(ЗАРНИЦА, АНГАРСК, hits)
    assert статус == g.GEO_EXACT and hit is hits[0]
    assert g.format_address(hit, ЗАРНИЦА) == "тер. СНТ Зарница, 118, 207, Ангарск"
    # Те же сторожа у правил области и строки улицы: пункт клиента назван.
    assert g.street_in_settlement(ЗАРНИЦА, АНГАРСК, hits) is hits[0]
    assert g.known_street(ЗАРНИЦА, АНГАРСК, hits) is hits[0]


