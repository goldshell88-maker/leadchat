"""СПРАВОЧНИК ГОРОДОВ ПРОВЕРЯЕТСЯ ПРОТИВ БОЕВЫХ ДАННЫХ, А НЕ ПРОТИВ ВЫДУМКИ.

⚠ ЖАЛОБА ВЛАДЕЛЬЦА 28.08: «некоторые города пишутся по-английски, и он не
понимает, из-за этого не знает время».

ЗАМЕР В ТОТ ЖЕ ДЕНЬ по всей боевой базе: 211 разных слагов, из них 56 не были в
справочнике. Это 1370 диалогов — 7% всех, у кого город вообще известен. На
карточке клиента вместо города стоял голый слаг («malahovka»), а часы клиента не
показывались НИКАК: пояс берётся из того же справочника, и без него показывать
нечего.

Все 56 оказались спутниками крупных центров — подмосковные, питерские, пермские.
Ни одного случая со спорным поясом: соврать про время клиента хуже, чем
промолчать, и такой город остался бы нераспознанным намеренно.

ПОЧЕМУ ФАЙЛОМ, А НЕ СПИСКОМ В КОДЕ. Это снимок боя, а не наша выдумка о том,
какие города бывают. Справочник обязан проверяться против того, что приходит на
самом деле, — иначе следующие полсотни спутников снова обнаружатся жалобой.
"""

from pathlib import Path

import pytest

from app.integrations.avito.listing_url import city_by_slug

ФАЙЛ = Path(__file__).resolve().parents[1] / "data" / "prod_city_slugs.txt"


def _боевые() -> list[tuple[str, int]]:
    пары: list[tuple[str, int]] = []
    for строка in ФАЙЛ.read_text(encoding="utf-8").splitlines():
        строка = строка.strip()
        if not строка or строка.startswith("#"):
            continue
        слаг, _, число = строка.rpartition(" ")
        пары.append((слаг, int(число)))
    return пары


def test_snapshot_is_not_empty() -> None:
    """Пустой снимок превратил бы проверку ниже в вечнозелёную."""
    пары = _боевые()
    assert len(пары) > 150, f"снимок боя подозрительно мал: {len(пары)} слагов"


def test_every_city_from_production_is_known() -> None:
    """Каждый слаг из боя опознаётся справочником.

    Не опознан — значит на карточке будет латиница вместо города и пустое место
    вместо часов клиента. Оператор звонит человеку в Хабаровск в его два часа
    ночи, потому что времени на экране нет.
    """
    незнакомые = [(с, n) for с, n in _боевые() if city_by_slug(с) is None]
    потеряно = sum(n for _, n in незнакомые)
    assert not незнакомые, (
        f"справочник не знает {len(незнакомые)} городов из боя "
        f"({потеряно} диалогов): " + ", ".join(f"{с} ({n})" for с, n in незнакомые[:10])
    )


@pytest.mark.parametrize(
    ("слаг", "имя"),
    [
        ("malahovka", "Малаховка"),
        ("kudrovo", "Кудрово"),
        ("verhnyaya_pyshma", "Верхняя Пышма"),
        ("slavyansk-na-kubani", "Славянск-на-Кубани"),
    ],
)
def test_added_cities_are_named_in_russian(слаг: str, имя: str) -> None:
    """Имя по-русски, а не слаг с большой буквы.

    Ради этого всё и делалось: «malahovka» на карточке — это не название города,
    а строка из ссылки, и читать её оператору незачем.
    """
    город = city_by_slug(слаг)
    assert город is not None and город.name == имя


@pytest.mark.parametrize(
    ("слаг", "пояс"),
    [
        ("malahovka", "Europe/Moscow"),
        ("verhnyaya_pyshma", "Asia/Yekaterinburg"),
        ("chernogorsk", "Asia/Krasnoyarsk"),
        ("novoaltaysk", "Asia/Barnaul"),
    ],
)
def test_added_cities_carry_a_real_timezone(слаг: str, пояс: str) -> None:
    """Пояс — IANA-имя, а не смещение.

    Смещение соврало бы в день перевода часов, причём молча: довод записан в
    шапке `listing_url`.
    """
    город = city_by_slug(слаг)
    assert город is not None and город.tz == пояс
