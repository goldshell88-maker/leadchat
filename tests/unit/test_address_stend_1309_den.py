    ("По адресу 7а 3/2 квартира 118 ( 2 подъезд )", {"office": "118", "entrance": "2"}),
    ("Шостаковича 3-418 4 подьезд 6 этаж", {"office": "418", "entrance": "4", "floor": "6"}),
