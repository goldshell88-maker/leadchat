ТРЕТИЙ_КРУГ_ДОМ = [
    # Корпус с точкой перед «кв.» — корпус, а не квартира без числа.
    ("Ленина д. 5 к. 2 кв. 7", "5 к. 2", {"office": "7"}),
    ("Ленина 5 корпус 2 кв.7", "5 корпус 2", {"office": "7"}),
    ("Ленина 5 к 2 кв. 7", "5 к 2", {"office": "7"}),
    # «с 9 до 18», «к 15 часам» — время, не строение и не корпус.
    ("Ленина 5 с 9 до 18 кв 7", "5", {"office": "7"}),
    ("Ленина 5 к 15 часам, кв 7", "5", {"office": "7"}),
    # Корпус словом не теряется перед «подъезд со двора»; голая литера — да.
    ("Ленина 5 корпус 2 подъезд со двора", "5 корпус 2", {}),
    ("Ленина 5к 2 подъезд", "5к", {"entrance": "2"}),
    ("ул Мира 12с 2 этаж", "12с", {"floor": "2"}),
    # Порядок через дефис и словом.
    ("Ленина 5, 3-й подъезд, 4-й этаж", "5", {"entrance": "3", "floor": "4"}),
    ("Ленина 5 кв 7 на 3-м этаже", "5", {"office": "7", "floor": "3"}),
    ("Ленина 5 кв 7 на третьем этаже", "5", {"office": "7", "floor": "3"}),
    ("Ленина 5, третья парадная, 4 этаж", "5", {"entrance": "3", "floor": "4"}),
    # Висячее число после цепочки числом вперёд — не переворачивает её.
    ("Ленина 5, 2 подъезд 4 этаж 2 телевизора", "5", {"entrance": "2", "floor": "4"}),
    ("Ленина 5, 1 подъезд 2 этаж 15 сентября", "5", {"entrance": "1", "floor": "2"}),
    # Площадь — не квартира.
    ("кухня 20 кв.м, Ленина 5 кв 7", "5", {"office": "7"}),
    # Сокращения перед числом и после.
    ("Ленина 5, кв. 7, 3 эт., 2 под.", "5", {"office": "7", "floor": "3", "entrance": "2"}),
    ("Ленина 5, 3 п. 4 эт. кв 12", "5", {"entrance": "3", "floor": "4", "office": "12"}),
    # Время перед «кв» — не квартира; предлог с косвенным падежом — часть.
    ("Ленина 5 в 14 кв 7 подъезд со двора", "5", {"office": "7"}),
    ("Ленина 5, подъезжайте к 3 подъезду", "5", {"entrance": "3"}),
    ("Ленина 5, вход с 2 подъезда, 3 этаж", "5", {"entrance": "2", "floor": "3"}),
    # Этажность дома — не этаж клиента; комнатность — не квартира.
    ("живу в 9 этажке на 3 этаже, Ленина 5", "5", {"floor": "3"}),
    ("квартира 3 комнатная, 5 этаж, Ленина 5", "5", {"floor": "5"}),
    ("у нас 9 этажный дом, лифт не работает, 7 этаж, Ленина 5", "5", {"floor": "7"}),
    ("ул Парадная 5", "5", {}),
]


@pytest.mark.parametrize(
    ("текст", "дом", "части"), ТРЕТИЙ_КРУГ_ДОМ, ids=[t for t, *_ in ТРЕТИЙ_КРУГ_ДОМ]
)
def test_третий_круг_дом(текст: str, дом: str, части: dict[str, str]) -> None:
    f = ap.parse(текст)
    assert f is not None, текст
    assert (f.house, f.parts) == (дом, части)


