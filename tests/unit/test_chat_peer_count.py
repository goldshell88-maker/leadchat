"""Разбор чата сообщает, СКОЛЬКО в нём участников, а не только «вот собеседник».

ЗАЧЕМ ЭТО ЧИСЛО. Раскрытие карточек-заглушек `chat:<id>` строится на утверждении
«у этого чата один собеседник, и вот он». Утверждение обязано быть ВЫВОДОМ, а не
догадкой — иначе оно того же рода, что и допущение про сквозной `author_id`, из-за
которого система молча склеивает людей с первого дня.

Выводом оно становится ровно при двух участниках. Разбор же берёт ПЕРВОГО не-нашего
и обрывает цикл: в чате на троих «первый не наш» — случайный человек, и заглушка
раскроется чужой личностью. Отсюда и число: при любом значении, кроме двух,
автоматика обязана промолчать.

⚠ ПОЧЕМУ СТОРОЖ ОТДЕЛЬНЫМ ФАЙЛОМ. Поле необязательное, с умолчанием `None`. Убери
его из разбора — ни один из 2822 тестов не покраснеет: `client_external_id`
по-прежнему заполняется, чат по-прежнему разбирается, а «не знаем участников» тихо
станет вечным состоянием. Раскрытие заглушек при этом просто перестанет работать —
молча, без единой ошибки в логах.
"""

from __future__ import annotations

from app.integrations.avito.adapter import AvitoAdapter

НАШ = 111222333
ЧУЖОЙ = 987654


def _чат(users: list[dict] | None) -> dict:
    сырое: dict = {"id": "u2i-abc", "users": users}
    if users is None:
        сырое.pop("users")
    return сырое


def test_двое_в_чате_это_и_есть_вывод():
    info = AvitoAdapter.parse_chat(
        _чат([{"id": НАШ, "name": "Мы"}, {"id": ЧУЖОЙ, "name": "Клиент"}]),
        account_user_id=НАШ,
    )
    assert info.peer_count == 2
    assert info.client_external_id == str(ЧУЖОЙ)


def test_трое_в_чате_считаются_честно():
    """⚠ Собеседник ВСЁ РАВНО заполнен — и в этом вся опасность.

    Разбор берёт первого не-нашего и обрывается, поэтому `client_external_id` тут
    есть и выглядит как ответ. Отличить этот случай от честного можно ТОЛЬКО по
    числу участников — ради него поле и заведено.
    """
    info = AvitoAdapter.parse_chat(
        _чат(
            [
                {"id": НАШ, "name": "Мы"},
                {"id": ЧУЖОЙ, "name": "Клиент"},
                {"id": 555000, "name": "Кто-то третий"},
            ]
        ),
        account_user_id=НАШ,
    )
    assert info.peer_count == 3
    assert info.client_external_id == str(ЧУЖОЙ), (
        "разбор перестал заполнять собеседника — тогда и опасности нет, "
        "но тест надо переписать осознанно"
    )


def test_участников_нет_в_ответе_значит_не_знаем():
    """Незнание — не вывод. `None`, а не ноль и не единица."""
    info = AvitoAdapter.parse_chat(_чат(None), account_user_id=НАШ)
    assert info.peer_count is None
    assert info.client_external_id is None


def test_один_участник_это_мы_сами():
    """Чат, где кроме нас никого: собеседника нет, и выдумывать его нечем."""
    info = AvitoAdapter.parse_chat(_чат([{"id": НАШ, "name": "Мы"}]), account_user_id=НАШ)
    assert info.peer_count == 1
    assert info.client_external_id is None
