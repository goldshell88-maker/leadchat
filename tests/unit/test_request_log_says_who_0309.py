"""Журнал запросов и обрывов обязан отвечать на вопрос «у КОГО было медленно».

⚠ РАЗБОР 03.09. Сотрудник сообщил: «3 сентября в 20:46 по Владивостоку сайт
работал в пять раз медленнее». Сервер в ту минуту отвечал за 25 мс по медиане
и 89 мс по p95 — то есть жалоба была про конкретного человека, а не про
службу. Проверить это по журналу оказалось нечем:

* в строке `http.request` есть маршрут, код и миллисекунды — и ни слова о том,
  чей это запрос. «Медленно у меня» ничем не отличалось от «медленно у всех»;
* в строке `ws.disconnected` не было ни причины, ни времени жизни соединения,
  поэтому «связь рвётся» отличалось от «человек закрыл вкладку» только
  догадкой, а считать пары «подключился/отключился» пришлось руками.

Три часа разбора вместо двух минут, и ответ дала случайность: ротированный
файл лога ещё не успел затереться.
"""

import structlog


def auth(tokens, role="manager"):
    return {"Authorization": f"Bearer {tokens[role]}"}


async def test_request_log_names_the_user(client, tokens):
    """Кто сделал запрос — видно в строке журнала."""
    with structlog.testing.capture_logs() as записи:
        r = await client.get("/api/v1/conversations", headers=auth(tokens))
    assert r.status_code == 200, r.text

    строки = [z for z in записи if z.get("event") == "http.request"]
    assert строки, "строки http.request нет вовсе"
    assert строки[-1].get("user_id"), "в журнале запросов не сказано, чей это запрос"


async def test_request_without_a_token_carries_no_user(client):
    """Запрос без токена не уносит чужое имя.

    ⚠ ЭТО НЕ ПРИДИРКА К ЧИСТОТЕ. Переменная контекста живёт в задаче, а задачи
    в asyncio переиспользуются. Забудь мы сбросить её на входе — здоровье,
    вебхук и экран входа приезжали бы в журнал с именем того, кто работал в
    этой задаче до них, и разбор винил бы невиновного.
    """
    with structlog.testing.capture_logs() as записи:
        await client.get("/api/v1/conversations")  # 401

    строки = [z for z in записи if z.get("event") == "http.request"]
    assert строки, "строки http.request нет вовсе"
    assert строки[-1].get("user_id") is None


async def test_the_name_does_not_leak_into_the_next_request(client, tokens):
    """Имя не протекает из запроса в запрос.

    Сначала запрос с токеном (имя есть), сразу следом — без токена. Второй
    обязан приехать пустым: иначе разбор винил бы человека, который к этому
    запросу отношения не имеет.
    """
    with structlog.testing.capture_logs() as записи:
        await client.get("/api/v1/conversations", headers=auth(tokens))
        await client.get("/api/health")

    строки = [z for z in записи if z.get("event") == "http.request"]
    assert len(строки) >= 2
    assert строки[-2].get("user_id"), "запрос с токеном приехал без имени"
    assert строки[-1].get("user_id") is None, "имя протекло в следующий запрос"


