#: КОРОТКИЕ ФОРМЫ ПРИСТАВОК, КОТОРЫЕ АВИТО ПРИСЫЛАЕТ НА САМОМ ДЕЛЕ.
#:
#: ⚠ ОТДЕЛЬНОЙ ТАБЛИЦЕЙ, А НЕ ВТОРОЙ СТРОКОЙ В ОСНОВНОЙ (28.08). В основной
#: действует правило «одна приставка на регион» — его стережёт
#: `test_region_prefixes_point_at_regions_that_exist`, и правило верное: две
#: равноправные записи на один регион читаются как выбор, которого нет.
#:
#: Но площадка присылает и короткую форму: замер боя дал `bashkortostan_oktyabrskiy`
#: без «respublika_». Признать её надо, а равноправной делать нельзя — вот она и
#: живёт псевдонимом: каноническое имя региона одно, написаний у него два.
_REGION_PREFIX_ALIASES: dict[str, str] = {
    "bashkortostan": "Республика Башкортостан",
}


def region_by_prefix(head: str) -> str | None:
    """Регион по приставке слага — с учётом коротких форм площадки."""
    return _REGION_PREFIXES.get(head) or _REGION_PREFIX_ALIASES.get(head)


#: Слова, которыми в слаге оканчивается НАЗВАНИЕ РЕГИОНА, а не района. Хвост с
#: таким словом (``zheleznogorsk_kurskaya_oblast``) — это уточнение области при
#: одноимённых городах, и принимать его за район нельзя: у курского и
#: красноярского Железногорсков разница в четыре часа.
_REGION_WORDS = frozenset({"oblast", "obl", "kray", "respublika", "ao", "okrug", "avtonomnyy"})

#: Больше стольких слов в слаге города не бывает: самая длинная известная
#: приставка — ``respublika_saha_yakutiya`` (три слова) плюс город из двух, итого
#: пять. Потолок тут не ради красоты, а ради времени: разбор ссылки зовётся
#: полсотни раз на одну выдачу списка диалогов, а первым сегментом пути может
#: прийти чужая строка на две тысячи знаков из одних подчёркиваний. Без потолка
#: это перебор всех её разрезов со склейкой строк на каждом — квадрат на ровном
#: месте, в самом горячем месте выдачи.
_MAX_SLUG_WORDS = 8


def _looks_like_district(tail: str) -> bool:
    """Похож ли хвост составного слага на район, а не на что-то ещё.

    Четыре отказа, каждый закрывает свой способ ошибиться:
    * хвост пуст (``moskva_``): оборванный слаг — не город с районом;
    * хвост — сам известный город (``moskva_kazan``): это не район, а два
      города, и который из них клиентский — неизвестно;
    * хвост — известная приставка региона (``zheleznogorsk_kurskaya_oblast``);
    * в хвосте есть слово-признак региона — на случай области, которой в
      ``_REGION_PREFIXES`` ещё нет.
    """
    if not tail or tail in CITIES or tail in _REGION_PREFIXES:
        return False
    return not any(word in _REGION_WORDS for word in tail.split("_"))


def _city_from_compound_slug(slug: str) -> City | None:
    """Город из составного слага: «область_город» или «город_район».

    Голову режем от САМОЙ ДЛИННОЙ к самой короткой, потому что и город, и
    область бывают из двух слов: у ``nizhniy_novgorod_avtozavodskiy`` короткая
    голова ``nizhniy`` не значит ничего, а длинная ``nizhniy_novgorod`` — город.
    """
    parts = slug.split("_")
    if len(parts) > _MAX_SLUG_WORDS:
        return None
    for cut in range(len(parts) - 1, 0, -1):
        head = "_".join(parts[:cut])
        tail = "_".join(parts[cut:])

        region = region_by_prefix(head)
        if region is not None:
            # «область_город». Регион приставки обязан совпасть с регионом
            # города — иначе это одноимённый город из другой области, и его
            # время нам неизвестно.
            city = CITIES.get(tail)
            if city is not None and city.region == region:
                return city
            continue

        # «город_район». Отдаём РОДИТЕЛЬСКИЙ город: как называется район, мы не
        # знаем и выдумывать не станем, а часовой пояс у района тот же — ради
        # пояса всё и затевалось.
        city = CITIES.get(head)
        if city is not None and _looks_like_district(tail):
            return city
    return None


def _норм_имени(name: str) -> str:
    """Имя города для сравнения: строчные, ё→е, дефис — пробел, пробелы
    схлопнуты. «Горно Алтайск», «горно-алтайск», «Горно — Алтайск» — одно имя
    (пакет 5, 20.09). ОДНА нормализация на справочник и разбор
    (`address_parse._имена_городов`) — иначе два пути считали бы одно поле
    по-разному."""
    return " ".join(_ДЕФИСЫ.sub(" ", name.lower().replace("ё", "е")).split())


#: Дефис и тире любого вида: «Горно — Алтайск» с телефона.
_ДЕФИСЫ = re.compile(r"[-‐‑–—]")


@cache
def _по_имени() -> dict[str, City]:
    """Именительный → город; составные записи «А и область» — не города."""
    return {_норм_имени(c.name): c for c in CITIES.values() if " и " not in c.name}


#: Слова имени, которые правила ниже склонили бы не так (ревью 20.09, C6):
#: «Уренгой» — существительное на «-ой», а не прилагательное («в Новом
#: Уренгое», не «Уренгом»); «Луки» — множественное короче пяти букв, и общий
#: порог (он бережёт «Сочи») его не пускал («в Великих Луках»). Явный список
#: вместо ослабления правил: каждое ослабление ловит и чужие слова.
_ПРЕДЛОЖНЫЙ_ИСКЛЮЧЕНИЯ: dict[str, frozenset[str]] = {
    "уренгой": frozenset({"уренгое"}),
    "луки": frozenset({"луках"}),
}


def _предложные_формы(слово: str) -> set[str]:
    """Формы ОДНОГО слова имени в предложном падеже — и только в нём: вызывающие
    знают падеж из контекста («в …», «г. …»), а творительный «-ом» у
    существительных на «-ск» совпал бы с предложным прилагательного района
    («в Подольском районе» → Подольск — ревью 20.09). Беглая гласная (Орёл →
    Орле, Елец → Ельце) и «-о/-е» (Иваново, Кемерово) вне пакета: точное имя."""
    if len(слово) < 3:
        return set()
    if слово in _ПРЕДЛОЖНЫЙ_ИСКЛЮЧЕНИЯ:
        return set(_ПРЕДЛОЖНЫЙ_ИСКЛЮЧЕНИЯ[слово])
    if слово.endswith(("ый", "ий", "ой")):
        # Прилагательное: Грозный → Грозном, Нижний → Нижнем, Дзержинский → Дзержинском.
        основа = слово[:-2]
        return {основа + "ом", основа + "ем"}
    if слово.endswith(("ая", "яя")):
        return {слово[:-2] + ("ой" if слово.endswith("ая") else "ей")}
    if слово.endswith(("ые", "ие")):
        # Набережные → Набережных, Вятские → Вятских, Минеральные → Минеральных.
        return {слово[:-2] + ("ых" if слово.endswith("ые") else "их")}
    if слово.endswith(("ое", "ее")):
        # Средний род прилагательного: Раменское → Раменском, Видное → Видном,
        # Новое → Новом (ревью 20.09, C6). Творительного у них нет — «в
        # Раменском районе» страхует сторож следующего слова в `inbound`.
        return {слово[:-2] + ("ом" if слово.endswith("ое") else "ем")}
    if слово.endswith("ия"):
        return {слово[:-1] + "и"}
    if слово.endswith(("а", "я")):
        return {слово[:-1] + "е"}
    if слово.endswith("ь"):
        # Мягкий знак — оба рода: женский «-и» (Твери, Казани), мужской «-е»
        # (Ярославле, Ставрополе, Анадыре). Род слова неизвестен, форм две;
        # сторож инъективности по справочнику держит их от чужих имён.
        return {слово[:-1] + "и", слово[:-1] + "е"}
    if слово.endswith("й"):
        return {слово[:-1] + "е"}
    if слово.endswith(("и", "ы")):
        # Множественное число (Химки, Мытищи, Челны, Люберцы) — «-ах»; короткие
        # («Сочи») не склоняются.
        return {слово[:-1] + "ах"} if len(слово) >= 5 else set()
    if слово[-1] in "оеуэю":
        return set()
    return {слово + "е", слово + "у"}


@cache
def _по_форме() -> dict[str, City | None]:
    """Предложная форма имени → город; форма двух городов или форма, равная
    именительному другого города, → None (неоднозначность — не совпадение).
    Каждое слово многословного имени склоняется независимо: «Нижнем
    Новгороде», «Набережных Челнах», «Ростове на Дону»."""
    формы: dict[str, City | None] = {}
    именительные = _по_имени()
    for имя, город in именительные.items():
        слова = имя.split()
        for сочетание in product(*[{w, *_предложные_формы(w)} for w in слова]):
            форма = " ".join(сочетание)
            if форма == имя:
                continue
            прежний = формы.get(форма, город)
            формы[форма] = None if (форма in именительные or прежний is not город) else город
    return формы


def city_by_name(name: str | None, *, declined: bool = False) -> City | None:
    """Город по имени, как его написал клиент («Геленджик») — когда у
    объявления города нет, а клиент его назвал (бой 13.09). Дефис и ё не
    важны (пакет 5). `declined=True` — имя может стоять в ПРЕДЛОЖНОМ падеже
    («Салавате», «Твери», «Грозном»): включает только вызывающий, у которого
    падеж известен из контекста («в …», «г. …»); в остальных местах родительный
    города равен фамилии улицы («Кирова»), и склонение вредно."""
    if not name:
        return None
    ключ = _норм_имени(name)
    город = _по_имени().get(ключ)
    if город is not None or not declined:
        return город
    return _по_форме().get(ключ)


def city_by_slug(slug: str | None) -> City | None:
    """Город по слагу из ссылки. Нет в справочнике — None, и это нормально.

    Точное совпадение проверяется ПЕРВЫМ и всегда бьёт правила разбора: иначе
    ``moskva_i_mo`` разобрался бы как «Москва + район mo» и превратился в
    «Москву», потеряв область. Правила — только для того, чего в таблице нет.
    """
    if not slug:
        return None
    city = CITIES.get(slug)
    if city is not None:
        return city
    if "_" not in slug:
        return None
    return _city_from_compound_slug(slug)


def city_fields(slug: str | None) -> dict[str, Any]:
    """Город в том виде, в каком он уезжает наружу — В API И В WS-ПАТЧ.

    Одна функция на оба места намеренно: разойдись они хоть на один ключ, фронт
    получал бы разный набор полей при загрузке страницы и при живом обновлении,
    и город то появлялся бы, то исчезал. Такое в проекте уже было с ценой.

    ``city_slug`` едет наружу даже когда города нет в справочнике: интерфейс
    показывает сам слаг («kerch-2»), и сразу видно, что справочник надо
    пополнить. Времени при этом нет — ``city_tz`` пуст, и время не рисуется.
    """
    city = city_by_slug(slug)
    return {
        "city_slug": slug,
        "city_name": city.name if city else None,
        "city_region": city.region if city else None,
        "city_tz": city.tz if city else None,
    }


def parse_listing_url(raw: str | None) -> ListingUrlParts:
    """Разобрать ссылку на объявление Авито. НИКОГДА не бросает.

    Чистая функция: ни сети, ни базы, ни логов. Любой мусор на входе — это
    ``ListingUrlParts`` с ``ok=False``, а не исключение: разбор ссылки не имеет
    права уронить приём сообщения от клиента.
    """
    if not raw or len(raw) > _MAX_URL:
        return _EMPTY
    s = raw.strip()
    if not s:
        return _EMPTY
    # Ссылки из Авито приходят и без схемы («avito.ru/moskva/...»). Без этого
    # urlsplit посчитал бы весь адрес путём, и хоста не было бы вовсе.
    if not s.startswith(("http://", "https://")):
        s = "https://" + s

    try:
        parsed = urlsplit(s)
        host = parsed.hostname  # свойство разбирает порт и IPv6 — тоже может бросить
    except ValueError:
        return _EMPTY
    if not host:
        return _EMPTY

    host = host.lower()
    for prefix in _HOST_PREFIXES:
        if host.startswith(prefix):
            host = host[len(prefix) :]
    if host not in AVITO_HOSTS:
        # ЧУЖОЙ ДОМЕН. Именно здесь ловится «avito.ru.evil.com»: hostname
        # разобран, сравнение полное, вхождение подстроки ни при чём.
        return ListingUrlParts(kind="foreign")

    # `parsed.query` и `parsed.fragment` не читаются вовсе: в query у Авито
    # ходят рекламные метки и base64-контексты, доверять оттуда нечему.
    #
    # unquote — ПОСЕГМЕНТНО, а не по всему пути сразу (в псевдокоде docs/32 §3
    # наоборот). Иначе закодированный «%2F» внутри имени превратился бы в
    # разделитель и разъехался на два сегмента, сдвинув и город, и категорию.
    segments = [unquote(x) for x in parsed.path.split("/") if x]
    if not segments:
        return _EMPTY

    # --- номер объявления --------------------------------------------------
    # ПОСЛЕДНЯЯ группа цифр в ПОСЛЕДНЕМ сегменте, а не «сегмент по счёту»: у
    # /kerch/predlozheniya_uslug/slug_8213779975 номер третий, у /items/306…
    # второй, у короткой ссылки — первый.
    digits = _DIGITS.findall(segments[-1])
    item_id: int | None = int(digits[-1]) if digits else None
    if item_id is not None and item_id > _BIGINT_MAX:
        # Не влезает в bigint — значит это не номер, а цифры из пути.
        item_id = None

    # --- что это за страница вообще ----------------------------------------
    first = segments[0]
    kind: UrlKind
    if first == "brands":
        kind = "brand"
    elif first in ("user", "company", "agencies", "profile"):
        # Страница ПРОФИЛЯ, а не объявления. Номер обнуляем: иначе хеш профиля
        # с цифрами уехал бы в базу как item_id и склеил бы разные объявления.
        kind, item_id = "user", None
    elif len(segments) == 1 and first.isdigit():
        kind = "short"
    elif item_id is not None:
        kind = "item"
    else:
        kind = "garbage"

    # --- город: ТОЛЬКО по справочнику, никакой транслитерации ---------------
    # Обратная транслитерация дала бы «Ростов На Дону» и «Москва И Мо» — мусор
    # в отчёте владельца. Нет в справочнике — нет названия, слаг сохраняем.
    # Сегмент места стоит первым и у города («/kerch/…»), и у «всей России»
    # («/all/…»): категория идёт за ним в обоих случаях, слаг города — только
    # у города (COUNTRY_SEGMENTS).
    location: str | None = None
    city_slug: str | None = None
    city: City | None = None
    if kind in ("item", "brand") and len(segments) >= 2 and first not in _SERVICE_FIRST_SEGMENTS:
        location = first
        if first not in COUNTRY_SEGMENTS:
            city_slug = first
            city = city_by_slug(city_slug)

    category_slug = segments[1] if location and len(segments) >= 3 else None

    # --- заголовок из слага: сырьё для вызывающего, когда API названия не дал
    title_slug: str | None = None
    if kind == "item":
        tail = segments[-1]
        if item_id is not None:
            tail = tail.removesuffix(str(item_id)).rstrip("_-")
        title_slug = tail or None

    return ListingUrlParts(
        item_id=item_id,
        city_slug=city_slug,
        city_name=city.name if city else None,
        city_region=city.region if city else None,
        city_tz=city.tz if city else None,
        category_slug=category_slug,
        title_slug=title_slug,
        kind=kind,
        ok=item_id is not None,
    )
