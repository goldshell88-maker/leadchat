@dataclass(slots=True)
class InboundEvent:
    """Нормализованное входящее событие канала (единый вход apply_inbound_event)."""

    external_chat_id: str | None
    external_message_id: str | None
    author_id: int | None
    account_user_id: int | None
    text: str | None
    created_at: datetime
    item_title: str | None = None
    item_url: str | None = None
    item_price: str | None = None
    client_name: str | None = None
    attachments: list[dict[str, Any]] = field(default_factory=list)
    # `kind` — ВОРОТА КОНВЕЙЕРА, а не вид события. Воркер (`app/workers/inbound.py`,
    # строка «kind != "message" -> игнор») пропускает дальше только `KIND_MESSAGE`;
    # всё остальное ack'ается и умирает, оставив после себя лишь сырец в
    # `webhook_raw_log`. Поэтому служебная запись Авито, которую НАДО сохранить,
    # тоже едет с `kind=KIND_MESSAGE` — а то, что она служебная, несёт `is_system`.
    # Ворота воркера в этой задаче править нельзя (чужая зона), иначе признак был
    # бы один. Когда до воркера дойдут руки — читать надо `is_system`, а `kind`
    # оставить тем, чем он и является: «нести ли это дальше».
    kind: str = KIND_MESSAGE
    #: Сырой вид от Авито, КАК ПРИШЁЛ, без интерпретации: `value["type"]` у
    #: сообщения, `payload["type"]` у конвертного события.
    #:
    #: ЗАЧЕМ ХРАНИТЬ ТО, ЧЕГО НЕ ПОНИМАЕМ. Словарь значений `value.type` нам
    #: неизвестен: в разобранной спецификации (docs/26, 238 путей) не
    #: зафиксировано НИ ОДНОГО значения кроме "text", а имитатор шлёт "text"
    #: потому, что мы сами его таким написали. Классифицировать по угаданному
    #: перечню запрещено — этот приём в проекте дважды дал зелёные тесты и 4xx
    #: на боевом (docs/30 §«Чего мы не знаем»). Поэтому вид едет сырым: пусть
    #: система сама расскажет, что бывает, а решать будем по данным.
    source_type: str | None = None
    #: «Это служебная запись Авито, а не переписка с клиентом».
    #:
    #: Ставится ТОЛЬКО там, где Авито сказал это сам — конвертом
    #: `payload.type != "message"`. У сообщений (`payload.type == "message"`)
    #: всегда False: отличить служебное от клиентского внутри ленты сегодня
    #: нечем, а ошибка тут самая дорогая — настоящее обращение, спрятанное в
    #: серый чип, не звенит, не встаёт в очередь и теряется совсем.
    is_system: bool = False

    # Алиасы-поля под протокол InboundEventLike зоны конвейера
    # (services/inbound.py, 08 §2.4/§2.5): chat_id/message_id/author_name/item_info.
    chat_id: str | None = field(init=False, default=None)
    message_id: str | None = field(init=False, default=None)
    author_name: str | None = field(init=False, default=None)
    item_info: dict[str, str | None] | None = field(init=False, default=None)

    def __post_init__(self) -> None:
        self.chat_id = self.external_chat_id
        self.message_id = self.external_message_id
        self.author_name = self.client_name
        if self.item_title or self.item_url or self.item_price:
            self.item_info = {
                "title": self.item_title,
                "url": self.item_url,
                "price": self.item_price,
            }


