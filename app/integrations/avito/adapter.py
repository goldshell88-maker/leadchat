def _require_dict(value: Any, what: str) -> dict[str, Any]:
    if not isinstance(value, dict):
        raise WebhookParseError(f"{what}: ожидался объект, получено {type(value).__name__}")
    return value


def _parse_created(value: Any, what: str) -> datetime:
    """unix-секунды (int/float) или ISO-строка -> aware UTC datetime."""
    if isinstance(value, bool):  # bool — подкласс int, отсекаем явно
        raise WebhookParseError(f"{what}: поле 'created' не время")
    if isinstance(value, int | float):
        try:
            return datetime.fromtimestamp(value, UTC)
        except (OverflowError, OSError, ValueError) as exc:
            raise WebhookParseError(f"{what}: 'created' вне диапазона времени") from exc
    if isinstance(value, str):
        try:
            parsed = datetime.fromisoformat(value.replace("Z", "+00:00"))
        except ValueError as exc:
            raise WebhookParseError(f"{what}: 'created' не ISO-время: {value!r}") from exc
        return parsed if parsed.tzinfo else parsed.replace(tzinfo=UTC)
    raise WebhookParseError(f"{what}: отсутствует или нечитаемо поле 'created'")


def _parse_int(value: Any, fieldname: str, what: str) -> int:
    if isinstance(value, bool) or not isinstance(value, int):
        raise WebhookParseError(f"{what}: поле {fieldname!r} должно быть числом")
    return value


def _parse_str(value: Any, fieldname: str, what: str) -> str:
    if not isinstance(value, str) or not value:
        raise WebhookParseError(f"{what}: поле {fieldname!r} должно быть непустой строкой")
    return value


def _price_str(value: Any) -> str | None:
    if value is None:
        return None
    return value if isinstance(value, str) else str(value)


def _extract_item(value: dict[str, Any]) -> tuple[str | None, str | None, str | None]:
    """item из value.item либо value.context{type=item}.value; нет объявления -> None."""
    item = value.get("item")
    if not isinstance(item, dict):
        context = value.get("context")
        if isinstance(context, dict) and context.get("type") == "item":
            ctx_value = context.get("value")
            item = ctx_value if isinstance(ctx_value, dict) else None
        else:
            item = None
    if item is None:
        return None, None, None
    title = item.get("title") if isinstance(item.get("title"), str) else None
    url = item.get("url") if isinstance(item.get("url"), str) else None
    price = _price_str(item.get("price_string") or item.get("price"))
    return title, url, price


