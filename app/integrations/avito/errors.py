"""Типизированные ошибки интеграции с Авито.

Единый словарь исключений для клиента (HTTP-уровень) и адаптера
(парсинг payload'ов). Воркеры/сервисы ловят их по типу и решают:
ретраить, рефрешить токен, спать Retry-After или писать в DLQ.
"""

from __future__ import annotations


class AvitoApiError(Exception):
    """Базовая ошибка вызова API Авито (любой не-2xx, кроме частных случаев ниже)."""

    def __init__(self, message: str, *, status: int | None = None) -> None:
        self.status = status
        super().__init__(message)


class AvitoAuthError(AvitoApiError):
    """Токен не принят — вызывающий контур делает ровно один авто-рефреш и
    повторяет (DESIGN §8.2, 07 §2.3).

    СЮДА ВХОДИТ И 403, А НЕ ТОЛЬКО 401. Мы исходили из того, что истёкший
    токен даёт 401, как принято. У Авито это не так: на истёкший access-токен
    он отвечает **403 Forbidden**. Проверено по двум независимым источникам, в
    том числе по чужой рабочей интеграции, где ради этого заведена отдельная
    настройка `tokenExpiredStatusCode: 403`.

    Цена ошибки была высокой и незаметной: 403 попадал в общую ветку, рефреш
    не запускался, и КАЖДЫЙ следующий запрос к Авито падал — до планового
    обновления токена за два часа до истечения. То есть отправка сообщений
    могла молча встать на часы, а причина выглядела бы как «Авито не отвечает».

    Обратная сторона решения названа честно: 403 у Авито может означать и
    «нет прав на этот метод». Тогда лишний рефреш пройдёт впустую и запрос
    упадёт с тем же 403 — цена одна лишняя выдача токена, и повтор ровно один
    (`_avito_call`), так что зациклиться нельзя.
    """

    def __init__(self, message: str | None = None, *, status: int = 401) -> None:
        super().__init__(message or f"Авито: токен не принят ({status})", status=status)


class AvitoUnavailable(AvitoApiError):
    """До Авито не достучались: сеть, DNS, таймаут, отказ соединения.

    ЗАЧЕМ ОТДЕЛЬНЫЙ ТИП, А НЕ ГОЛЫЙ httpx. Исключения httpx НЕ НАСЛЕДУЮТСЯ ОТ
    ``OSError`` — проверено на нашей версии: у ``ConnectError`` цепочка идёт
    ``NetworkError -> TransportError -> RequestError -> HTTPError -> Exception``.
    А половина вызывающего кода ловила именно ``OSError``, рассчитывая поймать
    «Авито недоступен». Не ловила: исключение пролетало мимо и превращалось в
    HTTP 500 «Внутренняя ошибка сервера».

    Для человека это выглядело так: он вводит ключи, видит красный тост без
    объяснения, жмёт ещё раз, ещё раз. При этом аккаунт мог быть уже создан и
    закоммичен — он обнаруживался только после перезагрузки страницы. Та же
    дыра была в кнопке «Проверить связь», то есть ровно там, где отказ обязан
    объяснять причину.

    Теперь превращение живёт в ОДНОМ месте — ``AvitoClient._request``, — и
    наружу из клиента не выходит ни одного нетипизированного исключения.
    """

    #: Оборвалось ли ПОСЛЕ отправки запроса (аудит 19.08, находка L-007).
    #: Таймаут чтения означает «запрос ушёл, ответа не дождались» — а значит
    #: Авито могло его принять, и слепой повтор даст клиенту второе сообщение.
    #: Отказ соединения и ошибка имени — наоборот, «не ушло вовсе», и повтор
    #: там безопасен. Разница видна только здесь, в месте превращения.
    after_send: bool = False

    def __init__(
        self, message: str = "Не удалось связаться с Авито", *, after_send: bool = False
    ) -> None:
        self.after_send = after_send
        super().__init__(message, status=None)


class TokenRevokedError(AvitoApiError):
    """400 на grant_type=refresh_token — refresh сгорел (одноразовость) или
    пользователь отозвал доступ (DESIGN §1.5)."""

    def __init__(self, message: str = "Авито: refresh-токен не принят (400)") -> None:
        super().__init__(message, status=400)


class RateLimited(AvitoApiError):
    """429 — превышение квоты. Retry-After — истина (08 §4.3)."""

    def __init__(self, retry_after: int) -> None:
        self.retry_after = retry_after
        super().__init__(f"Авито: rate limit, retry after {retry_after}s", status=429)


