async def _известить(
    redis: Any,
    *,
    conversation_id: uuid.UUID,
    message_id: uuid.UUID,
    состояние: str | None,
    текст: str | None,
) -> None:
    """Кадр ``message:transcript`` на экран. Зовётся строго после commit'а.

    Не бросает: текст уже в базе, и приедет со следующим открытием диалога;
    ронять из-за отказа Redis задачу, которая только что отработала минуты
    счёта, значило бы считать её заново (тот же довод, что у
    `voice.enqueue_transcribe`).
    """
    try:
        await publish_transcript(
            redis,
            conversation_id=conversation_id,
            message_id=message_id,
            voice_transcript=текст,
            voice_transcript_status=состояние,
        )
    except Exception as exc:  # noqa: BLE001 — кадр это удобство, текст уже в базе
        log.warning(
            "voice.publish_failed",
            message_id=str(message_id),
            status=состояние,
            reason=repr(exc),
        )


async def _записать_исход(
    factory: Any,
    redis: Any,
    message_id: uuid.UUID,
    created_at: datetime,
    *,
    состояние: str | None,
    текст: str | None = None,
) -> bool:
    """Записать исход и известить экран. Возвращает, найдена ли строка и
    закоммичен ли исход: фаза 3 ставит разбор карточки только по True —
    ставить его на сообщение, которого уже нет, незачем."""
    async with factory() as db:
        msg = await load_message(db, message_id, created_at)
        if msg is None:
            log.warning("voice.message_gone", message_id=str(message_id))
            return False
        msg.voice_transcript_status = состояние
        if текст is not None:
            msg.voice_transcript = текст
        conversation_id = msg.conversation_id
        await db.commit()
    # ⚠ СТРОГО ПОСЛЕ COMMIT'А И ВНЕ СЕССИИ (08 §8.1). Кадр до commit'а заставил
    # бы экран перечитать ещё старую строку — «появляется только после F5».
    await _известить(
        redis,
        conversation_id=conversation_id,
        message_id=message_id,
        состояние=состояние,
        текст=текст,
    )
    return True


@with_job_scope
async def transcribe_voice(
    ctx: dict[str, Any], message_id: uuid.UUID, created_at: datetime
) -> None:
    """Расшифровать голосовое входящего сообщения и положить текст в колонку."""
    if not settings.whisper_enabled:
        return
    factory = ctx["db_session_factory"]
    попытка = int(ctx.get("job_try") or 1)

    # --- фаза 1: решить и занять состояние -----------------------------------
    async with factory() as db:
        msg = await load_message(db, message_id, created_at)
        if msg is None:
            log.warning("voice.message_not_found", message_id=str(message_id))
            return
        voice_id = voice.voice_id_of(msg.attachments)
        if voice_id is None or msg.direction != "in":
            # Расшифровываем только то, что сказал КЛИЕНТ: своё исходящее мы и
            # так знаем текстом, а служебная запись Авито голоса не несёт.
            return
        if msg.voice_transcript_status in voice.ЗАКОНЧЕННЫЕ:
            # Уже посчитано — задача идемпотентна к повторной постановке.
            if msg.voice_transcript_status == voice.СОСТОЯНИЕ_ГОТОВО:
                # ⚠ САМОПОЧИНКА РАЗБОРА. Сюда приходит повтор ТОЙ ЖЕ задачи
                # после ГОТОВО — то есть воркер умер между commit'ом фазы 3 и
                # постановкой разбора. Расшифровка есть, а номер из неё без
                # этих строк не попал бы в карточку никогда. Разбор
                # идемпотентен, лишняя постановка безвредна. Писать здесь
                # нечего, транзакция только читала — Redis не ждёт commit'а.
                await voice.enqueue_voice_card(ctx["redis"], message_id, created_at)
            return
        if msg.voice_transcript_status == voice.СОСТОЯНИЕ_В_РАБОТЕ and попытка == 1:
            # ⚠ ЧУЖОЕ «В РАБОТЕ» УВАЖАЕМ, СВОЁ — НЕТ. Первая попытка, увидев
            # `running`, отступает: считает кто-то другой. А вот ПОВТОР той же
            # задачи (job_try > 1) обязан войти: `running` там оставила её же
            # прошлая попытка, убитая потолком в 300 с или падением воркера, и
            # без этого исключения запись осталась бы «в работе» навсегда — то
            # есть в работе без единого работающего.
            log.info("voice.already_running", message_id=str(message_id))
            return
        conv = await db.get(Conversation, msg.conversation_id)
        account = await db.get(AvitoAccount, conv.account_id) if conv else None
        if account is None or not account.access_token_enc:
            msg.voice_transcript_status = voice.СОСТОЯНИЕ_НЕ_ВЫШЛО
            await db.commit()
            log.warning(
                "voice.no_account",
                message_id=str(message_id),
                conversation_id=str(msg.conversation_id),
            )
            # Подпись «готовится» обязана смениться и здесь: исход в базе уже
            # есть, а без кадра экран узнал бы о нём только после F5.
            await _известить(
                ctx["redis"],
                conversation_id=msg.conversation_id,
                message_id=message_id,
                состояние=voice.СОСТОЯНИЕ_НЕ_ВЫШЛО,
                текст=None,
            )
            return
        msg.voice_transcript_status = voice.СОСТОЯНИЕ_В_РАБОТЕ
        conversation_id = msg.conversation_id
        канал = Канал(
            account_id=str(account.id),
            avito_user_id=account.avito_user_id,
            token_enc=account.access_token_enc,
        )
        await db.commit()

    # --- фаза 2: очередь, Авито, счёт (вне транзакции) ------------------------
    global _желающих
    _желающих += 1
    try:
        try:
            await asyncio.wait_for(_замок.acquire(), timeout=ЖДАТЬ_ОЧЕРЕДЬ_СЕК)
        except TimeoutError as exc:
            # Впереди длинная запись. Место в воркере не держим: задача
            # вернётся через минуту и спросит у Авито ссылку заново — это
            # дешевле, чем держать слот воркера минуту впустую (подписанная
            # ссылка при этом живёт ≥30 минут по замеру 06.09, дело не в ней).
            log.info("voice.queue_busy", message_id=str(message_id), attempt=попытка)
            if попытка < settings.whisper_max_tries:
                raise Retry(defer=ОТЛОЖИТЬ_СЕК) from exc
            # ⚠ ПОТОЛОК НУЖЕН: без него очередь выбрала бы попытки ARQ (их
            # пять), задача умерла бы совсем, а состояние осталось бы `running`
            # НАВСЕГДА — вечное «готовится» на экране, и починить нечем.
            #
            # ⚠ НО ИСХОД — «НЕ НАЧИНАЛИ», А НЕ «НЕ ВЫШЛО» (06.09). К записи ни
            # разу не приступали: она просто не дождалась замка за соседями.
            # `failed` здесь врал бы дважды: диспетчер видел бы «расшифровать
            # не удалось» у записи, которую никто не пробовал, а через десять
            # минут досчёт снова ставил бы её в очередь — мигание «не удалось /
            # готовится» в живом диалоге. NULL честен, и досчёт берёт его сам.
            await _записать_исход(factory, ctx["redis"], message_id, created_at, состояние=None)
            return
        try:
            итог = await _посчитать(ctx, канал, voice_id)
        except РасшифровкаНеВышла as exc:
            повтор_возможен = exc.повторять and попытка < settings.whisper_max_tries
            log.warning(
                "voice.failed",
                message_id=str(message_id),
                conversation_id=str(conversation_id),
                voice_id=voice_id,
                reason=exc.причина,
                attempt=попытка,
                will_retry=повтор_возможен,
            )
            if повтор_возможен:
                # Состояние остаётся `running` намеренно: это ТА ЖЕ задача, и
                # её следующая попытка войдёт по условию `job_try > 1`.
                raise Retry(defer=ОТЛОЖИТЬ_СЕК * попытка) from exc
            await _записать_исход(
                factory, ctx["redis"], message_id, created_at, состояние=voice.СОСТОЯНИЕ_НЕ_ВЫШЛО
            )
            return
        finally:
            if _желающих == 1:
                _выгрузить_модель()
            _замок.release()
    finally:
        _желающих -= 1

    # --- фаза 3: записать исход ----------------------------------------------
    if итог is None:
        log.info(
            "voice.too_long",
            message_id=str(message_id),
            limit_seconds=settings.whisper_max_audio_seconds,
        )
        await _записать_исход(
            factory,
            ctx["redis"],
            message_id,
            created_at,
            состояние=voice.СОСТОЯНИЕ_СЛИШКОМ_ДЛИННАЯ,
        )
        return
    текст, _длительность = итог
    записано = await _записать_исход(
        factory,
        ctx["redis"],
        message_id,
        created_at,
        состояние=voice.СОСТОЯНИЕ_ГОТОВО,
        текст=текст,
    )
    # ⚠ РАЗБОР КАРТОЧКИ — ОТДЕЛЬНОЙ ЗАДАЧЕЙ, А НЕ ЗДЕСЬ, И СТРОГО ПОСЛЕ
    # COMMIT'А. Упади разбор внутри этой задачи — ARQ повторил бы ЕЁ, а фаза 1
    # вышла бы на `done` (ЗАКОНЧЕННЫЕ): расшифровка есть, а номер в карточку не
    # попал бы никогда. У своей задачи — свои попытки, своя область Sentry и
    # своя дедупликация по имени. Постановка до commit'а дала бы разбору
    # прочитать ещё пустую колонку — ровно та слепота, которую он лечит.
    if записано:
        await voice.enqueue_voice_card(ctx["redis"], message_id, created_at)
