async def _скачать(url: str, куда: str) -> int:
    """Запись во временный файл. Возвращает размер; потолок — жёсткий."""
    размер = 0
    try:
        async with httpx.AsyncClient(timeout=ТАЙМАУТ_СКАЧИВАНИЯ) as клиент:
            async with клиент.stream("GET", url) as ответ:
                if ответ.status_code >= 400:
                    # Подписанная ссылка живёт минуты: 403/404 здесь означают
                    # «уже протухла», а не «записи нет» — запись у Авито живёт
                    # недели. Повторять стоит — следующая попытка спросит у
                    # Авито НОВУЮ ссылку, а не постучится в эту же.
                    raise РасшифровкаНеВышла(
                        f"CDN Авито ответил {ответ.status_code}", повторять=True
                    )
                with open(куда, "wb") as файл:
                    async for кусок in ответ.aiter_bytes(64 * 1024):
                        размер += len(кусок)
                        if размер > СКАЧАТЬ_НЕ_БОЛЬШЕ:
                            raise РасшифровкаНеВышла(
                                f"запись больше {СКАЧАТЬ_НЕ_БОЛЬШЕ // 1024 // 1024} МБ",
                                повторять=False,
                            )
                        файл.write(кусок)
    except httpx.HTTPError as exc:
        raise РасшифровкаНеВышла(f"не скачалась: {exc!r}", повторять=True) from exc
    if размер == 0:
        raise РасшифровкаНеВышла("Авито отдал пустой файл", повторять=False)
    return размер


async def _ссылка_на_запись(ctx: dict[str, Any], канал: Канал, voice_id: str) -> str:
    """Свежая ссылка у Авито. Ведро `bulk`: живые ответы клиентам не трогаем."""
    from app.integrations.avito.client import AvitoClient
    from app.integrations.avito.ratelimit import AvitoRateLimiter
    from app.services import crypto

    # ⚠ БЮДЖЕТ БЕРЁМ ПЕРЕД ОБРАЩЕНИЕМ. Окно запросов к Авито у аккаунта одно на
    # всех, и делит его с нами доставка ответов клиентам (08 §4.3). Ведро
    # `bulk`, а не `interactive`: интерактивная доля — это ответы живым людям,
    # и фоновой расшифровке её есть нельзя.
    await AvitoRateLimiter(ctx["redis"]).acquire(канал.account_id, bucket="bulk")
    токен = crypto.decrypt_token(канал.token_enc)
    try:
        ссылки = await AvitoClient().get_voice_urls(токен, канал.avito_user_id, [voice_id])
    except AvitoAuthError as exc:
        # Канал требует переподключения — это делает человек, и до тех пор
        # повторы бессмысленны.
        raise РасшифровкаНеВышла("канал требует переподключения", повторять=False) from exc
    except (AvitoUnavailable, AvitoApiError) as exc:
        raise РасшифровкаНеВышла(f"Авито не отдал ссылку: {exc}", повторять=True) from exc
    ссылка = ссылки.get(voice_id)
    if not ссылка:
        # Авито ответило, но записи не дало: она у него удалена. По замеру
        # 06.09 в первые ~29 дней такого не бывает — ссылка выдана на все
        # возрасты; сюда попадает то, что старше, или удалённое самим Авито.
        raise РасшифровкаНеВышла("Авито не знает такой записи", повторять=False)
    return ссылка


async def _посчитать(ctx: dict[str, Any], канал: Канал, voice_id: str) -> tuple[str, float] | None:
    """Ссылка -> файл -> текст. Файл удаляется в ``finally``, всегда."""
    ссылка = await _ссылка_на_запись(ctx, канал, voice_id)

    # Временный файл, а не наш том с вложениями: хранить чужой голос мы не
    # собираемся ни секунды дольше нужного, и попадать под уборку тома он не
    # должен. Расширение не нужно — формат определяет сам разбор (PyAV).
    дескриптор, путь = tempfile.mkstemp(prefix="leadchat-voice-")
    os.close(дескриптор)
    try:
        байт = await _скачать(ссылка, путь)
        # ⚠ МОДЕЛЬ ГРУЗИМ ОТДЕЛЬНОЙ СТРОКОЙ, ХОТЯ `_расшифровать` СДЕЛАЛ БЫ ЭТО
        # САМ. Иначе первая задача серии приписывала бы к времени счёта две
        # секунды загрузки, и `spent_seconds` в журнале перестал бы годиться
        # для главного, ради чего он там есть, — узнать НАСТОЯЩЕЕ отношение
        # счёта к длительности на боевом ядре и по нему править порог.
        await asyncio.to_thread(_загрузить_модель)
        начало = time.monotonic()
        итог = await asyncio.to_thread(_расшифровать, путь)
        if итог is None:
            return None
        текст, длительность = итог
        log.info(
            "voice.transcribed",
            voice_id=voice_id,
            bytes=байт,
            audio_seconds=round(длительность, 1),
            spent_seconds=round(time.monotonic() - начало, 1),
            chars=len(текст),
        )
        return текст, длительность
    except РасшифровкаНеВышла:
        raise
    except Exception as exc:  # noqa: BLE001 — битый файл/кодек: разбирать нечего
        raise РасшифровкаНеВышла(f"разбор записи не удался: {exc!r}", повторять=False) from exc
    finally:
        # ⚠ ПРЯМАЯ ПРОСЬБА ВЛАДЕЛЬЦА: «пусть он потом их удаляет». В `finally`,
        # а не после успеха: отказ на середине — самый частый путь, и именно он
        # копил бы мусор молча.
        try:
            os.unlink(путь)
        except FileNotFoundError:
            pass
        except OSError:
            # Молча глотать нельзя: неудалённые записи — это и чужой голос на
            # диске, и медленно кончающееся место.
            log.exception("voice.tempfile_not_removed", path=путь)


