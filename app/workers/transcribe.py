class РасшифровкаНеВышла(Exception):
    """Отказ с решением, стоит ли повторять.

    Разделение не косметическое: недоступный на минуту Авито и удалённая у
    Авито запись выглядят одинаково («текста нет»), но лечатся
    противоположно — первое повтором, второе только тем, чтобы перестать
    ходить. Гонять по кругу заведомо безнадёжное — это ровный поток ошибок в
    журнале, в котором перестают замечать настоящие.
    """

    def __init__(self, причина: str, *, повторять: bool) -> None:
        super().__init__(причина)
        self.причина = причина
        self.повторять = повторять


