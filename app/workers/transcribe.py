_желающих = 0


def _домашний_каталог_hugging_face() -> str:
    """Увести домашний каталог HuggingFace на том с весами. Вернуть путь.

    ⚠ ЭТА ФУНКЦИЯ — ЕДИНСТВЕННАЯ ПРИЧИНА, ПО КОТОРОЙ РАСШИФРОВКА ВООБЩЕ
    РАБОТАЕТ В БОЮ. Без неё она не работала НИ РАЗУ: 1 голосовое из 1 в бою
    закончилось `failed`, и вот почему.

    `download_root` ниже уводит на том только САМИ ВЕСА. А библиотека качает их
    своим движком (`hf_xet`), и тот пишет свой кэш и свой журнал в
    `$HOME/.cache/huggingface/xet/` — путь, о котором `download_root` не знает
    ничего. В образе же `useradd -d /srv/app`, а `/srv/app` принадлежит root:
    контейнер работает от uid 999 и писать туда не может. Отсюда в бою
    `OSError('I/O error: Permission denied (os error 13)')` на КАЖДОЙ попытке.

    Замер на боевом сервере 05.09: `test -w $HOME` → нет, `test -w
    /var/leadchat/whisper` → да. То есть том был в порядке ровно всё это время
    — предупреждение в docker-compose.prod.yml про «том приехал от root»
    указывало не туда, и починка по нему не дала бы ничего.

    ⚠ ПОЧЕМУ В КОДЕ, А НЕ ПЕРЕМЕННОЙ ОКРУЖЕНИЯ В COMPOSE. Где лежат веса, знает
    `settings.whisper_model_dir`. Пропиши путь второй раз в compose — и он
    разойдётся с настройкой при первой же её правке, причём молча: расшифровка
    снова начнёт падать на правах, а виноватого не будет видно нигде. Знание о
    каталоге весов обязано жить в одном месте.

    ⚠ `setdefault`, А НЕ ПРИСВОЕНИЕ: заданное снаружи HF_HOME уважаем. Это
    единственный способ увести кэш в другое место, не трогая код, — например
    на машине разработчика, где тома `/var/leadchat` нет вовсе.
    """
    путь = os.path.join(settings.whisper_model_dir, "hf")
    os.environ.setdefault("HF_HOME", путь)
    return os.environ["HF_HOME"]


def _загрузить_модель() -> Any:
    """Модель в память (синхронно, зовётся из потока).

    ⚠ ВЕСА КАЧАЮТСЯ В ТОМ, А НЕ ЛЕЖАТ В ОБРАЗЕ. 464 МБ в слое означали бы
    464 МБ через тоннель на КАЖДОЙ выкатке — а тоннель до сервера уже рвался на
    середине. Здесь первая расшифровка после чистой установки будет дольше на
    время скачивания, и это единственная плата.

    Импорт внутри функции намеренно: CTranslate2 и onnxruntime не должны
    оказаться в памяти api и планировщика, которым они не нужны никогда.
    """
    global _модель
    if _модель is None:
        # ⚠ СТРОГО ДО ИМПОРТА. `huggingface_hub` читает HF_HOME на своём импорте
        # и замораживает путь в константах модуля; выставь мы переменную после,
        # она уже ни на что не повлияла бы — и это было бы «написано, но не
        # подключено» в самом коварном виде: код на месте, а толку ноль.
        каталог = _домашний_каталог_hugging_face()

        from faster_whisper import WhisperModel

        начало = time.monotonic()
        try:
            _модель = WhisperModel(
                settings.whisper_model,
                device="cpu",
                compute_type=РЕЖИМ,
                cpu_threads=settings.whisper_cpu_threads,
                download_root=settings.whisper_model_dir,
            )
        except Exception as exc:
            # ⚠ ПОВТОРЯТЬ СТОИТ, И ЭТО НЕ ПЕРЕСТРАХОВКА. Сюда приходят ровно
            # две беды, и обе временные чаще, чем вечные: первая расшифровка
            # после чистой установки качает 464 МБ (оборвалась сеть — второй
            # заход докачает) и каталог тома оказался не наш по правам (том
            # приехал от root — чинится одной командой на хосте, и после неё
            # повтор пройдёт). Хоронить запись из-за этого нельзя: причина не в
            # ней.
            raise РасшифровкаНеВышла(f"модель не загрузилась: {exc!r}", повторять=True) from exc
        log.info(
            "voice.model_loaded",
            model=settings.whisper_model,
            threads=settings.whisper_cpu_threads,
            hf_home=каталог,
            seconds=round(time.monotonic() - начало, 1),
        )
    return _модель


def _выгрузить_модель() -> None:
    global _модель
    if _модель is not None:
        _модель = None
        log.info("voice.model_unloaded")


def _расшифровать(путь: str) -> tuple[str, float] | None:
    """Текст записи или None, если она длиннее порога. Синхронно, в потоке.

    ⚠ ДЛИТЕЛЬНОСТЬ ИЗВЕСТНА ДО СЧЁТА, И ЭТИМ МЫ ПОЛЬЗУЕМСЯ. ``transcribe``
    возвращает разбор ленивым перебором, а сведения о записи — сразу. Значит
    длинную запись видно ДО того, как на неё потрачена хоть одна секунда
    процессора: перебор просто не начинаем.
    """
    модель = _загрузить_модель()
    отрезки, сведения = модель.transcribe(
        путь,
        language=ЯЗЫК,
        beam_size=ШИРИНА_ЛУЧА,
        # Отсев тишины. Без него Whisper на паузах и шуме дописывает от себя
        # целые фразы (известное свойство модели), и диспетчер читал бы
        # выдумку как слова клиента.
        vad_filter=True,
        # Не опираться на уже разобранное. С опорой модель, раз сбившись,
        # повторяет одну и ту же фразу до конца записи — а голосовое из
        # мессенджера как раз шумное.
        condition_on_previous_text=False,
    )
    if сведения.duration > settings.whisper_max_audio_seconds:
        return None
    текст = " ".join(отрезок.text.strip() for отрезок in отрезки).strip()
    return текст, float(сведения.duration)


