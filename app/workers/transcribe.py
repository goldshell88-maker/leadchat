# исходных 82. Остальное держит аллокатор, и отдаст он это только процессу,
# которому память понадобится. Обещать «после расшифровки как не бывало»
# нельзя — обещаем ровно то, что видно замером.
_модель: Any = None
_замок = asyncio.Lock()
