    #: Цена разрыва не в самом разрыве: после переподключения идёт догон через
    #: REST — полный список диалогов и лента открытого. Отсюда 955 запросов
    #: `/conversations` за сутки при 24 работающих; на мобильном интернете это и
    #: читается как «сайт грузит интернет».
    #:
    #: Три минуты переживают торможение таймеров с запасом, а действительно
    #: мёртвое соединение закроет штатный ping/pong за ~40 секунд — раньше, чем
    #: этот сторож, и по признаку надёжнее.
