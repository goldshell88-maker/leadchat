    @model_validator(mode="after")
    def _refuse_placeholder_secrets(self) -> "Settings":
        """На проде секрет-заглушка из репозитория — это отсутствие секрета.

        ОБЯЗАТЕЛЬНОСТЬ ПОЛЯ ЗАКРЫВАЕТ ТОЛЬКО «ПЕРЕМЕННОЙ НЕТ». Осталось
        «переменная есть, но это строка, которую видно на GitHub». Именно она
        и лежит в образце окружения (.env.prod.example) — то есть путь, по
        которому прод получает заглушку, это не небрежность, а поведение по
        умолчанию: скопировал образец, заполнил половину полей, выкатил.

        Единственным барьером до сих пор была подстановка в docker-compose
        (`${MEDIA_SIGN_KEY:?…}`). Она валит рендер файла, когда переменная
        пуста или не задана, и пропускает непустую заглушку насквозь.

        ПОЧЕМУ ПРОВЕРКА ЖИВЁТ ЗДЕСЬ, А НЕ ТОЛЬКО В ВЫКАТКЕ. Гейт выкатки
        срабатывает один раз, а `.env` на сервере правят и после неё —
        руками, в спешке, при разборе аварии. Валидатор же отрабатывает на
        КАЖДОМ старте контейнера: подсунуть заглушку и не заметить нельзя.

        Только при `ENV=production`: в разработке и в CI заглушки — норма и
        единственный разумный вариант, а сторож, роняющий собственный CI,
        живёт до первого разбирательства.

        ТРИ СЕКРЕТА, А НЕ ОДИН (25.09). Сторож знал только MEDIA_SIGN_KEY, а
        ключ шифрования в .env.example был случайной строкой настоящего вида:
        скопировал образец на сервер — и токены Авито шифруются ключом из
        репозитория, а ни выкатка, ни этот валидатор ничего не замечают.
        Называем все заглушки разом: чинить по одной за перезапуск — ночь.
        """
        if self.env != "production":
            return self
        offenders = [
            f"{name.upper()} на проде равен строке-заглушке из репозитория. "
            f"{stake} Задайте настоящий: {command}"
            for name, (stake, command) in _GUARDED_SECRETS.items()
            if getattr(self, name).strip() in PLACEHOLDER_SECRETS
        ]
        if offenders:
            raise ValueError("\n".join(offenders))
        return self


