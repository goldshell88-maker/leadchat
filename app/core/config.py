# --- служебные пользователи (07 §6) ------------------------------------------
# Домен `.local` зарезервирован под сущности smoke-набора: такие пользователи
# существуют в БД (им нужен логин и права manager), но в UI-списках сотрудников,
# статистике и выборе исполнителя их быть не должно. Проверка по домену, а не по
# конкретному адресу: адрес настраивается (SMOKE_USER_EMAIL), правило — нет.
SERVICE_EMAIL_SUFFIX = ".local"


def is_service_email(email: str | None) -> bool:
    """Служебный (smoke) пользователь — скрывается из UI-списков (07 §6)."""
    if not email:
        return False
    return email.strip().lower().endswith(SERVICE_EMAIL_SUFFIX)
