"""Подробный след пути сообщения — включается на время, а не навсегда.

ЗАЧЕМ. Владелец: «сделай подробное логирование, чтобы было всё видно». Видно
должно быть, что случилось с КОНКРЕТНЫМ сообщением: пришло по вебхуку — легло в
базу — разбудило бота — бот ответил — ответ встал в очередь доставки — Авито
его принял. Сегодня каждый из этих шагов пишет своё, но связать их между собой
нельзя: сквозного идентификатора нет, и разбор одного случая превращается в
чтение всего потока по времени.

ПОЧЕМУ ПО ТРЕБОВАНИЮ, А НЕ ВСЕГДА (решение владельца от 12 августа). На боевом
идут десятки тысяч сообщений в сутки. Постоянный подробный след — это журналы
на порядок больше и переписка клиентов, лежащая в логах дольше, чем нужно.
Поэтому: в обычной работе — как раньше, а когда что-то пошло не так, след
включается на час-другой, не трогая выкатку.

ПОЧЕМУ СО СРОКОМ, А НЕ ПРОСТО ПЕРЕКЛЮЧАТЕЛЕМ. Включённый «на посмотреть» и
забытый след — это ровно тот случай, ради которого его и не сделали постоянным:
через неделю никто не помнит, что он включён, а журналы растут. Поэтому у
включения есть срок, и по его истечении след гаснет сам.

⚠ ЧТО В СЛЕД НЕ ПОПАДАЕТ. Тексты сообщений, телефоны, токены. След отвечает на
вопрос «где остановилось», а не «что написал клиент»: переписка есть в базе, и
класть её копию в логи ради удобства разбора — это то же самое, от чего
отказались в журнале лид-бота.
"""

from __future__ import annotations

import time
from typing import Any

import structlog

log = structlog.get_logger("app.trace")

#: Сколько секунд помним ответ на «включён ли след». Читается он на КАЖДОМ шаге
#: пути, то есть десятки тысяч раз в сутки; ходить за ним в базу каждый раз —
#: это лишний запрос на каждое сообщение ради настройки, которая меняется раз в
#: месяц. Пять секунд достаточно, чтобы включение подхватилось «сразу» по
#: человеческим меркам.
CACHE_TTL_SECONDS = 5.0

#: Максимум, на сколько можно включить. Сутки — заведомо больше любого разбора
#: и заведомо меньше срока, за который забытый след успеет надуть журналы.
MAX_HOURS = 24

#: (когда прочитали, до какого момента включён). `None` — ещё не читали.
_cache: tuple[float, float] | None = None


def _now() -> float:
    return time.time()


def set_until(until_ts: float) -> None:
    """Запомнить срок в процессе. Зовётся после чтения настройки и из тестов."""
    global _cache
    _cache = (time.monotonic(), until_ts)


def drop_cache() -> None:
    global _cache
    _cache = None


def is_on() -> bool:
    """Включён ли подробный след ПРЯМО СЕЙЧАС.

    Синхронно и без обращения к базе: зовётся из середины конвейера, где своей
    сессии для настроек нет, а тик уже держит транзакцию. Свежесть обеспечивает
    :func:`refresh` — его зовут воркер и ручки перед работой.
    """
    if _cache is None:
        return False
    read_at, until = _cache
    if time.monotonic() - read_at > CACHE_TTL_SECONDS:
        return False  # протухло — до обновления считаем выключенным
    return until > _now()


def step(event: str, **fields: Any) -> None:
    """Одна отметка на пути сообщения. Молчит, пока след не включён.

    ИМЕНА СОБЫТИЙ — ЕДИНЫЕ, и это главное в этой функции. Разбор одного случая
    сводится к `grep` по `message_id`, а не к чтению всего потока: каждая
    отметка несёт идентификатор сообщения, и по нему видна вся его жизнь.
    """
    if not is_on():
        return
    # `trace=True` — метка для отбора: `jq 'select(.trace)'` отделяет след от
    # обычного потока, не гадая по именам событий.
    log.info(event, trace=True, **fields)


async def refresh(db: Any) -> bool:
    """Перечитать срок из настроек, ОСТАВИВ СЕССИЮ КАК БЫЛА.

    ⚠ ГЛАВНОЕ В ЭТОЙ ФУНКЦИИ — ПОСЛЕДНИЕ ЧЕТЫРЕ СТРОКИ, А НЕ ЧТЕНИЕ.
    Любой запрос открывает транзакцию неявно. Позови эту функцию перед кодом,
    который начинает СВОЮ (`async with db.begin()` — так работает и приём
    входящего, и тик бота), — и он упадёт с «A transaction is already begun».
    Цена: перестаёт доезжать КАЖДОЕ входящее сообщение клиента.

    Ловушка сработала уже трижды за день: в тике бота, в посеве стенда и в
    конвейере воркера, куда её внесли вместе с этим самым следом. Каждый раз
    код читался правильно.

    Поэтому чинится СВОЙСТВО, а не место вызова: если транзакцию открыли мы,
    мы её и закрываем. Тогда функцию можно звать откуда угодно, и следующий
    `db.begin()` работает. Место однажды переставят — свойство останется.

    Импорт локальный: `app.services.app_settings` тянет модели, а этот модуль
    зовут из середины конвейера — верхнеуровневый импорт замкнул бы круг.

    СВЕЖИЙ ОТВЕТ — БЕЗ БАЗЫ (проверка 24.09). Зовут её на КАЖДОМ вебхуке, и
    до правки каждый вызов шёл в базу: соединение из общего пула API на
    каждый приём, хотя комментарий шлюза и сторож обещали обратное. Ответ
    моложе `CACHE_TTL_SECONDS` отдаётся из памяти процесса — ровно тот срок,
    которым `is_on` и так ограничивает его жизнь.
    """
    if _cache is not None and time.monotonic() - _cache[0] <= CACHE_TTL_SECONDS:
        return is_on()
    from app.services import app_settings

    # `in_transaction` есть у AsyncSession; на всякой другой заглушке считаем,
    # что транзакция уже была, — тогда мы точно ничего не закроем чужого.
    was_open = bool(getattr(db, "in_transaction", lambda: True)())
    try:
        values = await app_settings.get_all(db)
    except Exception:  # noqa: BLE001 — след не имеет права уронить работу
        return is_on()
    finally:
        if not was_open and bool(getattr(db, "in_transaction", lambda: False)()):
            # Только читали — откатывать нечего, но транзакцию надо закрыть.
            await db.rollback()
    raw = values.get(app_settings.TRACE_UNTIL)
    set_until(float(raw) if raw else 0.0)
    return is_on()
