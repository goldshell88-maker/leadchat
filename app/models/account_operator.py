"""account_operators — «кто работает на этом канале» (план 7.2, разбор Jivo 15 §2.2).

Зачем таблица. У заказчика девять каналов Авито и тринадцать операторов, и у
каждого канала СВОЙ набор людей: в Jivo это экран «Назначить операторов на
! Парт - 7 / Ист - В43 МНЧ !» со списком сотрудников и галочками. Без этой
связи очередь «Входящие» (7.1) показывает всем всё — оператор листает чужие
обращения и берёт не свои.

ПОЧЕМУ ОТДЕЛЬНАЯ ТАБЛИЦА, А НЕ КОЛОНКА
--------------------------------------
Просилось поле-массив у ``avito_accounts`` (``operator_ids uuid[]``) — по
образцу ``conversations.tags``. Отказались: связь читается в ОБЕ стороны и
обе стороны горячие. «Кто на канале» нужно экрану назначения, а «какие каналы
у меня» — фильтру очереди, который выполняется на каждом кадре ``inbox:new``
у тринадцати человек. Массив умеет только первое; второе превратилось бы в
``= ANY(operator_ids)`` по всем аккаунтам, то есть в перебор.

Второе: массив id не знает внешнего ключа. Удалили сотрудника — и в колонке
остаётся мусорный uuid, который потом всплывёт как «канал назначен кому-то»
и молча спрячет очередь от всех живых. Здесь это невозможно: обе стороны —
``ON DELETE CASCADE``.

ПЕРВИЧНЫЙ КЛЮЧ — СОСТАВНОЙ
--------------------------
``(account_id, user_id)``. Суррогатный ``id`` здесь не нужен ничему: строка
не редактируется и не адресуется по одному id — она либо есть, либо нет.
Зато составной ключ бесплатно даёт то, ради чего в такие таблицы обычно
добавляют уникальный индекс: одного человека нельзя назначить на канал
дважды, а значит «полная замена набора» (галочки экрана) не может оставить
дублей даже при гонке двух администраторов.

ИНДЕКСЫ В ОБЕ СТОРОНЫ
---------------------
* PK ``(account_id, user_id)`` — сторона канала: список операторов для экрана
  назначения и предикат «есть ли у канала назначенные» в фильтре очереди
  (``EXISTS ... WHERE account_id = ?``) — это префикс ключа.
* ``ix_account_operators_user`` ``(user_id, account_id)`` — сторона оператора:
  «мои каналы» в профиле и вариант плана, когда PostgreSQL решает вести
  соединение от оператора, а не от диалога. Второй столбец в индексе делает
  его покрывающим: список каналов оператора читается, не заглядывая в кучу.

``created_at`` — не украшение: экран назначения показывает «назначен 5
августа», а разбор «почему обращение висело» упирается ровно в вопрос, когда
человека сняли с канала.
"""

import uuid
from datetime import datetime

from sqlalchemy import DateTime, ForeignKey, Index, PrimaryKeyConstraint, Uuid, func
from sqlalchemy.orm import Mapped, mapped_column

from app.models.base import Base


class AccountOperator(Base):
    __tablename__ = "account_operators"
    __table_args__ = (
        PrimaryKeyConstraint("account_id", "user_id", name="pk_account_operators"),
        Index("ix_account_operators_user", "user_id", "account_id"),
    )

    account_id: Mapped[uuid.UUID] = mapped_column(
        Uuid,
        # CASCADE, а не RESTRICT: отключённый канал удаляют вместе с его
        # назначениями — держать «назначения на несуществующий канал» значит
        # ловить их потом в фильтре очереди.
        ForeignKey("avito_accounts.id", ondelete="CASCADE"),
        nullable=False,
    )
    user_id: Mapped[uuid.UUID] = mapped_column(
        Uuid,
        # CASCADE — та же причина с другой стороны: строка уволенного не
        # должна оставлять канал «назначенным призраку», иначе правило
        # «канал без операторов доступен всем» перестанет срабатывать и
        # очередь этого канала не увидит никто.
        ForeignKey("users.id", ondelete="CASCADE"),
        nullable=False,
    )
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), nullable=False, server_default=func.now()
    )
