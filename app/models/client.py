#: Уверенность в том, что карточка, собравшая диалоги с РАЗНЫХ аккаунтов
#: Авито, — это один человек.
#:
#: `assumed` — держится на одном лишь `author_id` Авито. Это ПРЕДПОЛОЖЕНИЕ:
#: см. длинный комментарий у `cross_account_since` ниже.
#: `confirmed` — с другого канала пришёл ТОТ ЖЕ номер телефона, что уже был
#: известен по первому. Совпадение идентификатора И номера у двух разных
#: людей неправдоподобно, поэтому это уже факт, а не догадка.
LINK_ASSUMED = "assumed"
LINK_CONFIRMED = "confirmed"


class Client(Base):
    __tablename__ = "clients"
    __table_args__ = (
        UniqueConstraint("channel", "external_id"),
        # Значение колонки — из закрытого словаря. Без CHECK'а первая же опечатка
        # («assumed » с пробелом) даёт строку, которую интерфейс не покажет ни
        # предположением, ни фактом: карточка молча теряет предупреждение.
        # Имя — БЕЗ приставки `ck_clients_`: её добавляет соглашение об именах
        # (`app/models/base.py`, ключ "ck" = `ck_%(table_name)s_%(constraint_name)s`).
        # С приставкой в имени ограничение приезжало в базу как
        # `ck_clients_ck_clients_link_confidence` — проверено на Postgres. Само
        # оно при этом работает, но найти его в базе по имени из кода нельзя, а
        # именно так его и будут искать, когда в три ночи ляжет приём сообщений.
        CheckConstraint(
            "link_confidence IS NULL OR link_confidence IN ('assumed', 'confirmed')",
            name="link_confidence",
        ),
        # ⚠ БЛОК «ВОЗМОЖНО, ЭТО ТОТ ЖЕ ЧЕЛОВЕК» ЧИТАЛ ТАБЛИЦУ ЦЕЛИКОМ (аудит 22.08).
        # Он ищет по phone, external_id и name — ни одного индекса по ним не было,
        # и каждый поиск шёл Seq Scan'ом: 17 518 строк отброшено фильтром, 10.8 мс
        # на телефон, 10.9 на external_id, 4.9 на имя. По счётчикам базы —
        # 88 450 последовательных чтений и 146 401 343 прочитанные строки.
        # Составной UNIQUE(channel, external_id) тут не работает и не должен:
        # однофамильцев по external_id ищут НАМЕРЕННО без канала — это поиск того
        # же человека на другом канале.
        # Частичные, потому что все три запроса всегда несут merged_into_id IS NULL:
        # объединённую карточку предлагать нельзя. Миграция — 0051.
        Index(
            "ix_clients_phone_active",
            "phone",
            postgresql_where=text("phone IS NOT NULL AND merged_into_id IS NULL"),
        ),
        Index(
            "ix_clients_external_id_active",
            "external_id",
            postgresql_where=text("merged_into_id IS NULL"),
        ),
        # ⚠ А ЭТОТ — ПРО ОБРАТНЫЙ ВОПРОС: «в ЭТУ карточку кого-нибудь объединяли?»
        # (миграция 0056). Три индекса выше держат `merged_into_id` только
        # условием `IS NULL` и на такой поиск не годятся ни один — ведущей
        # колонки нет. А спрашивают об этом четыре места, и одно из них —
        # `services/leads.py` — внутри цикла по выдаваемой пачке лидов (до 200
        # строк): каждый опрос расширения стоил до двухсот полных проходов по
        # `clients`. Частичный, потому что все четыре запроса сравнивают колонку
        # с конкретным идентификатором, то есть заведомо ищут NOT NULL;
        # объединений в базе единицы, и индекс получается крошечным.
        Index(
            "ix_clients_merged_into",
            "merged_into_id",
            postgresql_where=text("merged_into_id IS NOT NULL"),
        ),
        # ⚠ ПО ВЫРАЖЕНИЮ, А НЕ ПО КОЛОНКЕ. Поиск однофамильцев идёт через
        # `sa.func.lower(Client.name) == …` (services/clients.py), и индекс по
        # голому `name` планировщик для него НЕ возьмёт. Проверено на боевой
        # базе в транзакции с откатом: с индексом по колонке запрос остаётся
        # Seq Scan (17 700 строк отброшено, 4.7 мс), с индексом по lower(name) —
        # Bitmap Index Scan, 0.3 мс. Индекс по колонке был бы мёртвым грузом:
        # занимал бы диск, замедлял записи и не использовался никогда.
        Index(
            "ix_clients_name_active",
            text("lower(name)"),
            postgresql_where=text("name IS NOT NULL AND merged_into_id IS NULL"),
        ),
        # ⚠ ДОЧЕРНЯЯ СТОРОНА ВНЕШНЕГО КЛЮЧА. PostgreSQL не заводит такие
        # индексы сам, а проверять внешний ключ при удалении диалога обязан —
        # и без индекса проверка каждый раз читает `clients` целиком. Замер
        # боя 05.09: «Seq Scan on clients, Rows Removed by Filter: 61 364,
        # 11,1 мс» на каждое из 11 738 удалений за месяц. Чистка истории
        # канала на 2 700 диалогов — это полминуты сплошных проходов ПОД
        # БЛОКИРОВКАМИ, во время которых ждут все.
        Index(
            "ix_clients_phone_conversation",
            "phone_conversation_id",
            postgresql_where=text("phone_conversation_id IS NOT NULL"),
        ),
        # Та же беда у адреса (0086, 24.09): колонки заведены 11.09 без индекса,
        # и стирание истории канала на 2 244 диалога (медиана) упиралось в
        # потолок запроса API — уже после того, как подписка у Авито снята.
        Index(
            "ix_clients_address_conversation",
            "address_conversation_id",
            postgresql_where=text("address_conversation_id IS NOT NULL"),
        ),
        Index(
            "ix_clients_address_candidate",
            "address_candidate_id",
            postgresql_where=text("address_candidate_id IS NOT NULL"),
        ),
        # ⚠ ПОИСК ПО МЕРЕ НАБОРА ЧИТАЛ ТАБЛИЦУ ЦЕЛИКОМ ДВАЖДЫ НА КАЖДУЮ КЛАВИШУ
        # (замер боя 06.09): `count(*)` 43,7–102 мс и страница 33–77 мс, в обоих
        # «Seq Scan on clients, 62 264 строки» по `name ILIKE '%…%'` и
        # `phone LIKE '%…%'`. Два B-tree выше (по `lower(name)` и по `phone`)
        # тут бессильны: ведущий `%` в шаблоне — это поиск подстроки, а не
        # начала строки. GIN по триграммам (pg_trgm, миграция 0068) отвечает на
        # `LIKE '%…%'` из индекса.
        #
        # ⚠ ВЫРАЖЕНИЕ ИНДЕКСА И ВЫРАЖЕНИЕ В ЗАПРОСЕ ОБЯЗАНЫ СОВПАДАТЬ БУКВАЛЬНО.
        # Индекс по `lower(name)` планировщик возьмёт только для
        # `lower(name) LIKE …` — так и написано в `conversations._search_condition`.
        # Верни туда `name ILIKE …` — индекс останется на диске мёртвым грузом,
        # а замер вернётся к прежнему. Совпадение стережёт
        # `tests/unit/test_search_trgm_0609.py`.
        #
        # Метка `name_lower` — ключ для `postgresql_ops`: SQLAlchemy ищет класс
        # операторов по `.key` элемента, а у голого `text("lower(name)")` ключа
        # нет. На SQLite (тесты) оба ложатся обычными индексами: `postgresql_*`
        # там просто не читаются.
        Index(
            "ix_clients_name_trgm",
            func.lower(text("name")).label("name_lower"),
            postgresql_using="gin",
            postgresql_ops={"name_lower": "gin_trgm_ops"},
        ),
        Index(
            "ix_clients_phone_trgm",
            "phone",
            postgresql_using="gin",
            postgresql_ops={"phone": "gin_trgm_ops"},
        ),
    )

    id: Mapped[uuid.UUID] = mapped_column(Uuid, primary_key=True, default=uuid.uuid4)
    channel: Mapped[str] = mapped_column(Text, nullable=False, default="avito")
    external_id: Mapped[str] = mapped_column(Text, nullable=False)  # avito user id of the client
    name: Mapped[str | None] = mapped_column(Text)
    phone: Mapped[str | None] = mapped_column(Text)
    avito_rating: Mapped[Decimal | None] = mapped_column(Numeric)
    # Аватар клиента — ссылка на CDN Авито (128×128 из карточки чата).
    #
    # ХРАНИМ ССЫЛКУ, А НЕ ФАЙЛ, и это решение: скачивать чужие картинки к себе
    # значило бы завести хранилище, ротацию и вопрос «что показывать, когда
    # клиент сменил фото». Ссылка Авито живёт на их CDN и обновляется у них;
    # протухнет — интерфейс сам откатится на инициалы (обработчик ошибки img).
    avatar_url: Mapped[str | None] = mapped_column(Text)
    # Публичный профиль клиента на Авито — адрес, по которому диспетчер уходит
    # смотреть, с кем разговаривает (просьба владельца 02.09).
    #
    # ⚠ ХРАНИМ, ПОТОМУ ЧТО ВЫВЕСТИ НЕ ИЗ ЧЕГО. `external_id` — числовой
    # `author_id` Мессенджера, а публичная страница живёт по другому,
    # непрозрачному ключу; преобразования между ними нет (разбор в
    # `client_enrich.client_profile_url`). Адрес приходит от Авито в том же
    # блоке `public_user_profile`, откуда берётся аватар, и запоминается здесь.
    #
    # `None` означает «ещё не спрашивали или Авито не дал», и карточка в этом
    # случае показывает номер клиента вместо ссылки. Пустота честнее адреса,
    # собранного догадкой: по такой ссылке жмут при клиенте.
    profile_url: Mapped[str | None] = mapped_column(Text)
    #: Когда мы В ПОСЛЕДНИЙ РАЗ СПРАШИВАЛИ Авито про профиль этого клиента.
    #:
    #: ⚠ ОТДЕЛЬНО ОТ САМОЙ ССЫЛКИ, ПОТОМУ ЧТО ПУСТОЙ ОТВЕТ — ТОЖЕ ЗНАНИЕ.
    #: Без этой отметки условие «ссылки нет — сходи спроси» означало бы поход в
    #: чужой API на каждое входящее сообщение, вечно, если Авито ссылку не даёт.
    #: С ней цена конечная: один вопрос на клиента.
    profile_checked_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))

    # --- один клиент на разных каналах (требование владельца 6 от 11 августа) --
    #
    # ЧТО ЗДЕСЬ УЖЕ ПРОИСХОДИТ БЕЗ ЭТИХ КОЛОНОК. Ограничение выше —
    # `UNIQUE(channel, external_id)` — БЕЗ аккаунта. Значит один и тот же
    # `author_id` Авито, пришедший с двух разных наших аккаунтов, попадает в
    # ОДНУ строку клиента (`app/services/inbound.py::_upsert_client` ищет
    # строку по `channel + external_id` и ничего не знает про аккаунт), и
    # диалоги обоих аккаунтов встают под один `client_id`. То есть склейка
    # клиентов между каналами в системе включена с первого дня и работает
    # молча.
    #
    # ПОЧЕМУ ЭТО ОПАСНО. Допущение «author_id одинаков во всех аккаунтах»
    # никогда не проверялось. В каталоге методов (docs/26) такого утверждения
    # нет; в спецификации Авито у `Chat.users[].id` стоит ровно «Обратите
    # внимание на хэширование» — предупреждение без объяснения. Если
    # идентификатор на самом деле СВОЙ у каждого аккаунта, то совпадение
    # чисел с двух каналов означает не одного человека, а столкновение двух
    # разных, и в одну карточку съезжаются чужая переписка и чужой телефон.
    # Проверить это на живых данных сегодня нельзя: на 11 августа в боевой
    # базе 52 клиента и ни один не писал больше чем на один аккаунт — механизм
    # включён и ни разу не срабатывал.
    #
    # ЧТО ДЕЛАЮТ ЭТИ КОЛОНКИ. Они не включают и не выключают склейку — они
    # делают её ВИДИМОЙ и датируют. Пока значения пусты, поведение системы
    # ровно прежнее.
    #
    #: Момент обращения, с которого карточка стала межканальной: когда у клиента
    #: впервые появился диалог на аккаунте, отличном от того, где он уже был.
    #: NULL — клиент писал только на один канал (сегодня это все 52).
    cross_account_since: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))
    #: `assumed` | `confirmed` (см. LINK_ASSUMED/LINK_CONFIRMED). NULL, пока
    #: склейки нет. Интерфейс обязан читать именно это поле: выдать `assumed`
    #: за факт — значит показать диспетчеру чужую историю как свою.
    link_confidence: Mapped[str | None] = mapped_column(Text)
    #: Когда с ДРУГОГО канала пришёл номер, не совпавший с уже известным.
    #: Это единственный сигнал ложной склейки, который у нас сегодня есть:
    #: столкнувшиеся по `author_id` посторонние люди почти наверняка назовут
    #: разные телефоны. NULL — противоречия не видели (в том числе потому, что
    #: телефона нет вовсе).
    link_phone_conflict_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))
    #: С какого аккаунта пришёл номер, лежащий в `phone`. Без этой колонки
    #: «телефон совпал» ничего не доказывает: совпадение с номером, взятым с
    #: ТОГО ЖЕ канала, — это не подтверждение межканальной склейки, а
    #: тавтология. NULL — происхождение номера неизвестно (строки до этой
    #: миграции и второй писатель телефона, `app/bots/engine.py::capture_phone`);
    #: неизвестное происхождение подтверждением не считается.
    phone_account_id: Mapped[uuid.UUID | None] = mapped_column(
        Uuid, ForeignKey("avito_accounts.id", ondelete="SET NULL")
    )
    #: КАКИМ ДИАЛОГОМ ДОКАЗАН НОМЕР В `phone`.
    #:
    #: Заявка в лид-центр собирается из карточки (`app/services/leads.py`), и пока
    #: карточка описывает одного человека, `phone` для неё верен. После объединения —
    #: уже нет: в карточке может лежать номер, названный в СОСЕДНЕМ диалоге, и мастер
    #: поедет к другому человеку. Это худшее последствие ошибочной склейки: показ
    #: лишней истории неприятен, выезд к постороннему — нет.
    #:
    #: NULL значит «происхождение неизвестно» — так у всех строк до этой миграции и у
    #: номеров, записанных ботом. Неизвестное происхождение НЕ считается доказательством
    #: (`leads.lead_phone`), но и не отменяет номер: для карточки, которая никогда не
    #: объединялась, путать нечего.
    phone_conversation_id: Mapped[uuid.UUID | None] = mapped_column(
        Uuid, ForeignKey("conversations.id", ondelete="SET NULL")
    )

    # --- РУЧНОЕ ОБЪЕДИНЕНИЕ КАРТОЧЕК (правка 9 от 12 августа) ---------------
    #
    # ЗАЧЕМ ВООБЩЕ РУКИ. Автоматика склеивает карточки по `author_id` Авито и
    # подтверждает телефоном — но телефон есть у 3 обращений из 37, а
    # `author_id` Авито не обещает быть общим для разных аккаунтов (см.
    # длинный комментарий у `cross_account_since`). То есть у автоматики нет
    # данных, чтобы быть правой, и единственный, кто видит, что «Ольга с
    # ноутбуком» и «Ольга со стиралкой» — один человек, — это диспетчер,
    # читающий переписку.
    #
    # ПОЧЕМУ ПРОИГРАВШАЯ СТРОКА НЕ УДАЛЯЕТСЯ, А ПОМЕЧАЕТСЯ. Три причины, и
    # каждая одна была бы достаточной.
    #
    # 1. `UNIQUE(channel, external_id)` — по нему `_upsert_client` находит
    #    клиента на каждом входящем. Удали строку — и следующее сообщение с
    #    того же `author_id` заведёт её заново, пустую и без телефона; то
    #    есть объединение «разваливалось» бы само собой через минуту.
    # 2. Идентификаторов Авито у человека законно НЕСКОЛЬКО — по одному на
    #    каждый наш аккаунт. Список идентификаторов карточки — это и есть
    #    набор сохранённых строк; отдельная таблица «ещё идентификаторы»
    #    хранила бы то же самое во втором месте.
    # 3. «Разъединить» обязано возвращать ТОЧНО исходное состояние. Вернуть
    #    удалённую строку с тем же uuid можно только из журнала, а восстановить
    #    сохранённую — это один UPDATE.
    #
    # ЧЕГО ЭТИ КОЛОНКИ НЕ ДЕЛАЮТ. Они не перенаправляют приём сообщений:
    # `_upsert_client` про них не знает и знать не будет (чужая зона). Диалоги
    # переезжают на победителя ОДИН раз, в момент объединения; входящие в них
    # находятся по `external_chat_id` (`_upsert_conversation`) и клиента у
    # существующего диалога не переписывают — то есть объединённое остаётся
    # объединённым. Единственный шов: СОВСЕМ НОВЫЙ чат на проигравший
    # идентификатор заведёт диалог под проигравшей карточкой. Это видно и
    # чинится тем же объединением — `merge_candidates` покажет такую карточку
    # подсказкой, потому что идентификатор совпал.
    #
    #: Куда объединена эта карточка. NULL — карточка самостоятельная.
    #: Ссылка на свою же таблицу; ON DELETE SET NULL, потому что удаление
    #: победителя не должно уносить с собой историю проигравшего.
    merged_into_id: Mapped[uuid.UUID | None] = mapped_column(
        Uuid, ForeignKey("clients.id", ondelete="SET NULL")
    )
    #: Когда объединили. Нужна не для красоты: «Разъединить» показывается
    #: рядом с датой, а без даты оператор не отличит вчерашнее объединение от
    #: сделанного полгода назад и не поймёт, что именно он сейчас откатит.
    merged_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))

    # --- телефон, введённый руками -----------------------------------------
    #
    # ЗАЧЕМ ОТДЕЛЬНЫЕ КОЛОНКИ, А НЕ ПРОСТО ЗАПИСЬ В `phone`. Карточка подписывает
    # номер словами «(из диалога)» — это правда ровно до первого ручного ввода.
    # Без этих двух колонок номер, набранный диспетчером со слов клиента по
    # телефону, показывался бы как вычитанный из переписки, то есть карточка
    # ручалась бы за него чужим авторитетом. Кто и когда — единственное, что
    # позволяет через месяц спросить с человека, а не с системы.
    #
    #: Кто ввёл номер руками. NULL — номер добыт из переписки автоматикой
    #: (`_maybe_extract_phone`) или пришёл из бота.
    phone_set_by_id: Mapped[uuid.UUID | None] = mapped_column(
        Uuid, ForeignKey("users.id", ondelete="SET NULL")
    )
    #: Когда ввели руками. NULL вместе с `phone_set_by_id`.
    phone_set_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))

    #: Адрес выезда. С 18.09 пишет автоматика по степени строки
    #: (`clients.candidate_grade`: точка дома, приблизительная точка, текст
    #: без точки); человек только меняет («изменить», PUT) или отказывает
    #: строке («Не адрес»), и его правку автоматика не трогает.
    address: Mapped[str | None] = mapped_column(Text)
    #: Каким диалогом адрес доказан. Тот же смысл, что у `phone_conversation_id`:
    #: заявке нужно уметь ответить «откуда это взято», а разбирать журнал аудита
    #: по всей истории она не может.
    address_conversation_id: Mapped[uuid.UUID | None] = mapped_column(
        Uuid, ForeignKey("conversations.id", ondelete="SET NULL")
    )
    #: Кто набрал адрес с клавиатуры. NULL — подтверждено разобранное из
    #: переписки. По этим двум колонкам карточка выбирает подпись
    #: происхождения, ровно как у телефона.
    #:
    #: ⚠ ПАРНОГО `address_account_id` ЗДЕСЬ НЕТ, И ЭТО НЕ ПРОПУСК. У телефона
    #: такая колонка отвечает на вопрос «с какого нашего канала пришёл номер», и
    #: на ней стоит межканальная сверка: один и тот же номер в двух каналах —
    #: довод склеить карточки. Адрес такой сверке не служит: два человека
    #: законно живут по одному адресу (соседи, коммуналка, офис), и склеивать
    #: их было бы прямым вредом.
    address_set_by_id: Mapped[uuid.UUID | None] = mapped_column(
        Uuid, ForeignKey("users.id", ondelete="SET NULL")
    )
    address_set_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))
    #: Строка распознавания, ИЗ КОТОРОЙ адрес попал в карточку (11.09). Это
    #: единственный ответ на вопрос «откуда адрес»: по ней карточка находит
    #: цитату клиента, координаты и вердикт карты. Сравнивать текст поля со
    #: строками кандидатов больше нельзя — в поле лежит строка карты («…улица,
    #: 12, посёлок Заречный, Орск»), а в кандидате — «улица, дом» клиента.
    #: NULL — адрес набран руками либо записан до этой правки.
    address_candidate_id: Mapped[uuid.UUID | None] = mapped_column(
        Uuid, ForeignKey("client_address_candidates.id", ondelete="SET NULL", use_alter=True)
    )
    #: Ключ «улица, дом» строки, из которой записан адрес. Дублирует строку
    #: намеренно: она уходит каскадом вместе с диалогом (отключение канала
    #: чистит историю), а «этот адрес уже в карточке» обязано узнаваться и
    #: после этого. NULL — адрес руками.
    address_value: Mapped[str | None] = mapped_column(Text)

    # --- имя, введённое человеком (требование заказчика 13 августа) ---------
    #
    # ⚠ ЗАЧЕМ ОТМЕТКА, А НЕ ПРОСТО ЗАПИСЬ В `name`. Без неё правка диспетчера
    # молча теряется в трёх местах обычной работы: объединение карточек берёт
    # имя по правилу «у кого есть, того и берём» (рассчитано на два имени из
    # Авито); разъединение восстанавливает снимок и обязано вернуть ТОЧНО
    # исходное состояние; дозагрузка из Авито решает «писать или нет» по
    # пустоте поля — и очищенное человеком имя вернулось бы само.
    #
    # Все три различаются одним признаком: имя ввёл человек. Приём тот же, что
    # у телефона выше, и это не совпадение — задача та же самая.
    #
    #: Кто ввёл имя руками. NULL — имя пришло из профиля Авито.
    name_set_by_id: Mapped[uuid.UUID | None] = mapped_column(
        Uuid, ForeignKey("users.id", ondelete="SET NULL")
    )
    #: Когда ввели руками. NULL вместе с `name_set_by_id`.
    name_set_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))

    # --- чёрный список (аудит 7 августа, docs/19) --------------------------
    #
    # ЗАЧЕМ. Есть люди, которые пишут каждый день и клиентами не являются:
    # спам, «а сколько стоит» без намерения, скандалист, с которым решили не
    # работать. Сейчас их обращения неотличимы от новых: диалог встаёт в
    # очередь, звенит у тринадцати человек, кто-то его открывает, тратит
    # минуту и закрывает. Каждый день.
    #
    # ЧТО ДЕЛАЕТ ПОМЕТКА, А ЧТО НЕТ. Сообщения помеченного НЕ ТЕРЯЮТСЯ: они
    # приходят, сохраняются, диалог виден и доступен поиском. Пометка убирает
    # ровно одно — требование внимания: диалог не встаёт в очередь и не
    # звенит. Клиент об этом не знает и ничего не замечает, а команда
    # перестаёт разбирать одно и то же по кругу.
    #
    # Именно поэтому не «удалить» и не «заблокировать отправку»: и то и
    # другое означало бы потерянные сообщения, а среди них однажды окажется
    # настоящий заказ от человека, который в прошлый раз был не в духе.
    blocked_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))
    blocked_by_id: Mapped[uuid.UUID | None] = mapped_column(Uuid, ForeignKey("users.id"))
    #: Почему помечен — видно в карточке. «Пишет каждый день, ничего не
    #: заказывает» объясняет пометку тому, кто наткнётся на неё через месяц.
    blocked_reason: Mapped[str | None] = mapped_column(Text)


#: Состояния распознанного номера. Закрытый словарь, за ним следит CHECK ниже.
#:
#: `pending` — номер вычитан из переписки и ЖДЁТ решения оператора. Это
#: состояние по умолчанию: тихая запись чужого номера в карточку хуже, чем
#: несделанная работа (решение владельца от 12 августа).
#: `accepted` — оператор согласился: номер принадлежит этому человеку. Он
#: показывается в списке телефонов карточки и, если оператор выбрал «заменить»,
#: стоит в `clients.phone`.
#: `rejected` — оператор сказал «это не его телефон». Строка остаётся, и это
#: важнее, чем кажется: без неё тот же номер из того же сообщения предлагался бы
#: заново после каждого пересчёта по истории.
CANDIDATE_PENDING = "pending"
CANDIDATE_ACCEPTED = "accepted"
CANDIDATE_REJECTED = "rejected"

#: Откуда взялась строка кандидата. `inbound` — распознали на живом входящем,
#: `rescan` — разовый пересчёт по накопленной истории (`app/cli.py scan-phones`).
#: Разница нужна оператору: предложение по свежему сообщению он проверит по
#: памяти, а предложение по переписке трёхмесячной давности — только чтением.
CANDIDATE_SOURCE_INBOUND = "inbound"
CANDIDATE_SOURCE_RESCAN = "rescan"
#: `swap` — номер СНЯТ С ОСНОВНОГО, когда оператор сделал основным другой
#: (09.09). Строка заводится не распознаванием, а перестановкой, и `message_id`
#: у неё пуст: сообщения, из которого её вычитали, не существует. Отдельное
#: значение нужно, чтобы карточка не врала происхождением — «распознан в
#: переписке» и «был основным до обмена» это разные ответы на вопрос
#: «откуда мы это знаем». CHECK'а на колонке нет, миграция не требуется.
CANDIDATE_SOURCE_SWAP = "swap"
#: Адрес прочитан бесплатной моделью (13.09) — тот же путь проверки, свой источник для замера.
CANDIDATE_SOURCE_LLM = "llm"
#: Номер или адрес вычитан из РАСШИФРОВКИ голосового (19.09): доказательство
#: машинное, оператор сверяет со звуком. Отдельное значение — ради подписи на
#: карточке («из голосового», а не «из диалога») и замера доверия через две
