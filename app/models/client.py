CANDIDATE_SOURCE_VOICE = "voice"


class ClientPhoneCandidate(Base):
    """Телефон, вычитанный из ТЕКСТА сообщения, до решения оператора.

    ЗАЧЕМ ОТДЕЛЬНАЯ ТАБЛИЦА, А НЕ ПАРА КОЛОНОК В `clients`. Три причины, и
    первой одной хватило бы.

    1. Кандидатов у человека законно НЕСКОЛЬКО: он пишет свой номер, потом
       номер жены, потом рабочий. Пара колонок вместила бы последний и молча
       забыла остальные — то есть повторила бы ровно ту беду, ради которой всё
       это заведено (номер лежит в переписке, а карточка о нём не знает).
    2. Отклонённое обязано ПОМНИТЬСЯ. Оператор один раз сказал «это код от
       домофона, а не телефон»; спрашивать его об этом ещё раз после каждого
       пересчёта по истории — способ научить людей не читать подсказки.
    3. У кандидата есть происхождение: из какого сообщения и когда. В `clients`
       это были бы четыре колонки на каждый кандидат.

    ПОЧЕМУ У `message_id` НЕТ ВНЕШНЕГО КЛЮЧА. `messages` в Postgres
    секционирована по `created_at`, и первичный ключ у неё составной
    (`id, created_at`) — сослаться на одну колонку такой таблицы нельзя. Отсюда
    же соседняя `message_at`: без неё найти сообщение в боевой базе значит
    просканировать все секции, а с ней — ровно одну. Пара «идентификатор и
    время» и есть настоящая ссылка на сообщение в секционированной таблице.

    СТРОКА — ЭТО НЕ ТЕЛЕФОН КЛИЕНТА. Пока `status='pending'`, карточка ничего
    не утверждает и никого ни с кем не склеивает: распознанный номер даёт
    ПОДСКАЗКУ в блоке «Возможно, это тот же человек» и ничего больше. Молчаливая
    склейка 11 августа собрала под одним именем восемь человек из разных
    городов, и повторять это нечем.
    """

    __tablename__ = "client_phone_candidates"
    __table_args__ = (
        # ОДИН НОМЕР — ОДНА СТРОКА НА КАРТОЧКУ. Клиент пишет свой телефон в
        # каждом втором сообщении («жду по номеру …», «наберите на …»), и без
        # этого ограничения карточка обросла бы десятком одинаковых
        # предложений, а отклонённое возвращалось бы следующим же сообщением.
        # Ограничение же даёт и дешёвый отбор «кандидаты этой карточки»: его
        # индекс начинается с `client_id`, отдельный индекс не нужен.
        UniqueConstraint("client_id", "phone"),
        # Значение из закрытого словаря. Без CHECK'а первая опечатка даёт
        # строку, которую экран не покажет ни ожидающей решения, ни
        # отклонённой: предложение исчезает молча.
        # Имя — БЕЗ приставки `ck_client_phone_candidates_`: её добавляет
        # соглашение об именах (`app/models/base.py`).
        CheckConstraint(
            "status IN ('pending', 'accepted', 'rejected')",
            name="status",
        ),
        # ⚠ ДИАЛОГ ОБЯЗАТЕЛЕН ВСЕМ, КРОМЕ ОБМЕНА (миграция 0070). Довод — у
        # самой колонки `conversation_id` ниже. CHECK, а не соглашение в коде:
        # правило про доказательство слишком легко забыть, заводя третий
        # источник строк.
        CheckConstraint(
            "conversation_id IS NOT NULL OR source = 'swap'",
            name="conversation_unless_swap",
        ),
        # ИНДЕКС ПО `phone` — GIN ПО ТРИГРАММАМ, И ТОЛЬКО ТАКОЙ (миграция 0068).
        #
        # Здесь стояло «отдельного индекса по phone нет, и это проверено»: поиск
        # по телефону из переписки (критерий приёмки: и «1112240», и
        # «+7 900 111-22-40» находят диалог Анны Сергеевны) шёл тогда
        # коррелированным EXISTS от диалога, где первым срабатывал `client_id`
        # из уникального ограничения выше, а B-tree по `phone` при ведущем `%`
        # не помог бы ничем. Оба довода устарели 02.09: поиск переписан в
        # объединение, и эта ветка идёт ОТ КАНДИДАТОВ — `phone LIKE '%хвост%'`
        # по всей таблице, потом соединение с диалогами по `client_id`. Про
        # B-tree довод верен по-прежнему, поэтому индекс триграммный: он
        # единственный отвечает на подстроку.
        #
        # Таблица маленькая (6 414 строк, 1,6 мс перебором на бою 07.09), и
        # выигрыш здесь скромный. Индекс стоит ради единообразия трёх веток
        # одного поиска: две по `clients` идут триграммами, и третья обязана
        # быть устроена так же, иначе следующий читатель будет искать, чем она
        # особенная.
        Index(
            "ix_client_phone_candidates_phone_trgm",
            "phone",
            postgresql_using="gin",
            postgresql_ops={"phone": "gin_trgm_ops"},
        ),
        # А ВОТ ПО `conversation_id` ИНДЕКС НУЖЕН ПО ДРУГОЙ ПРИЧИНЕ: это
        # дочерняя сторона внешнего ключа с ON DELETE CASCADE. Удаление
        # диалога обязано найти здесь свои строки, и без индекса ищет их
        # перебором всей таблицы. Довод «отбор по client_id закрыт уникальным
        # ограничением» сюда не переносится: то ограничение начинается с
        # `client_id`, а каскад приходит от диалога.
        Index("ix_client_phone_candidates_conversation", "conversation_id"),
    )

    id: Mapped[uuid.UUID] = mapped_column(Uuid, primary_key=True, default=uuid.uuid4)
    client_id: Mapped[uuid.UUID] = mapped_column(
        Uuid, ForeignKey("clients.id", ondelete="CASCADE"), nullable=False
    )
    #: Диалог, в котором номер написан. У РАСПОЗНАННОГО номера обязателен:
    #: предложение без «где это было» оператор проверить не может, а
    #: непроверяемое предложение он либо примет не глядя, либо перестанет
    #: замечать.
    #:
    #: ⚠ NULL ДОПУСКАЕТСЯ РОВНО ДЛЯ `source = 'swap'` (миграция 0070). У номера,
    #: снятого с основного при обмене, доказательства из переписки нет вовсе: он
    #: утверждает «этот номер человека, он был у него основным». Поставить туда
    #: диалог нажатия было неправдой дважды — и по смыслу, и по последствию:
    #: внешний ключ ниже уносит строку вместе с диалогом, а `clients.phone`
    #: чистка канала щадит намеренно, то есть обмен ПЕРЕНОСИЛ БЫ номер из
    #: долговечного места в недолговечное. Правило держит CHECK
    #: `conversation_unless_swap`, а не память читателя.
    conversation_id: Mapped[uuid.UUID | None] = mapped_column(
        Uuid, ForeignKey("conversations.id", ondelete="CASCADE"), nullable=True
    )
    #: Сообщение, из которого вычитан номер (см. про отсутствие внешнего ключа
    #: в докстринге класса). NULL быть не должно, но допускается: разовый
    #: пересчёт по истории теоретически может встретить строку без пары.
    message_id: Mapped[uuid.UUID | None] = mapped_column(Uuid)
    #: Время ЭТОГО сообщения — ключ секции `messages` и заодно ответ на вопрос
    #: «когда клиент это написал».
    message_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))
    #: Канонический вид, +7XXXXXXXXXX (`app/services/phone_parse.py`).
    phone: Mapped[str] = mapped_column(Text, nullable=False)
    #: Как номер написан в сообщении: «+7(900)1112240». Оператор обязан иметь
    #: возможность сверить нашу догадку с тем, что человек написал на самом деле.
    raw: Mapped[str] = mapped_column(Text, nullable=False)
    source: Mapped[str] = mapped_column(Text, nullable=False, default=CANDIDATE_SOURCE_INBOUND)
    status: Mapped[str] = mapped_column(Text, nullable=False, default=CANDIDATE_PENDING)
    #: Когда РАСПОЗНАЛИ (не когда написали — это `message_at`). У живого
    #: входящего они совпадают, у пересчёта по истории различаются на месяцы.
    detected_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), nullable=False)
    resolved_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))
    resolved_by_id: Mapped[uuid.UUID | None] = mapped_column(
        Uuid, ForeignKey("users.id", ondelete="SET NULL")
    )
    #: Слово рядом с номером в сообщении («жена», «мастер», «второй») —
    #: `phone_rules.hint_word`. ТОЛЬКО ПОДПИСЬ НА ЭКРАНЕ, НИКОГДА НЕ РЕШЕНИЕ:
    #: ошибка словаря стоит неверной подписи у номера, а не звонка не тому.
    hint: Mapped[str | None] = mapped_column(Text)


class ClientMergeVeto(Base):
    """«Эту пару человек разъединил» — память для автоматического объединения.

    Автообъединение по телефону (`workers/client_merge.py`) обязано помнить
    отказ человека: без этой строки пара, которую оператор разъединил,
    удовлетворяла бы правилу снова и склеивалась бы обратно первым же
    входящим. Пара хранится упорядоченной (`a_id < b_id`, CHECK), чтобы у одной
    пары была ровно одна строка независимо от того, кто был победителем.

    Снимается ручным «Объединить» той же пары: человек переиграл свой откат.
    """

    __tablename__ = "client_merge_vetoes"
    __table_args__ = (
        CheckConstraint("a_id < b_id", name="ordered"),
        Index("ix_client_merge_vetoes_b", "b_id"),
    )

    a_id: Mapped[uuid.UUID] = mapped_column(
        Uuid, ForeignKey("clients.id", ondelete="CASCADE"), primary_key=True
    )
    b_id: Mapped[uuid.UUID] = mapped_column(
        Uuid, ForeignKey("clients.id", ondelete="CASCADE"), primary_key=True
    )
    created_by_id: Mapped[uuid.UUID | None] = mapped_column(
        Uuid, ForeignKey("users.id", ondelete="SET NULL")
    )
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), nullable=False)
    #: Строка журнала `client.merged`, которую откатили, — чтобы отчёт различал
