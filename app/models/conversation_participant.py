"""conversation_participants — кого позвали в диалог, не отдавая его (docs/19).

ЧЕМ ЭТО ОТЛИЧАЕТСЯ ОТ ПЕРЕДАЧИ
-------------------------------
Передача меняет ОТВЕТСТВЕННОГО: диалог уходит целиком, спрос переходит на
принявшего. Приглашение не меняет ничего — ответственный прежний, и отвечает
за клиента он же. Позвали просто затем, что нужен второй человек: мастер по
холодильникам скажет, чинится ли эта модель; старший подскажет, что делать
со скандалом.

«ЗАЧЕМ, ЕСЛИ ДИАЛОГИ И ТАК ВИДНЫ ВСЕМ»
---------------------------------------
Вопрос правильный: вкладка «Все» показывает любой диалог любому оператору.
Но «может открыть, если знает адрес» и «увидит» — разные вещи, особенно
когда диалогов четыреста тысяч. Приглашение делает две вещи, которых не
даёт общая видимость:

* коллега УЗНАЁТ, что его зовут, — приходит уведомление с причиной;
* диалог появляется в его «Моих» — то есть в списке, который он смотрит
  каждый день, а не в общем потоке, куда он заглядывает по поиску.

Без первого приглашение бессмысленно (позвали в пустоту), без второго —
бесполезно на второй день (диалог утонул).

ПОЧЕМУ ОТДЕЛЬНАЯ ТАБЛИЦА, А НЕ ПОЛЕ В `conversations`
------------------------------------------------------
Позвать можно нескольких: диспетчер зовёт мастера, мастер — старшего. Поле
вместило бы одного, и второй вызов молча вытеснил бы первого.
"""

import uuid
from datetime import datetime

from sqlalchemy import DateTime, ForeignKey, Index, Text, Uuid, func
from sqlalchemy.orm import Mapped, mapped_column

from app.models.base import Base


class ConversationParticipant(Base):
    __tablename__ = "conversation_participants"
    __table_args__ = (
        # Сторона человека: «какие диалоги, куда меня позвали» — это его
        # рабочий список, читается на каждое открытие «Моих».
        Index("ix_conversation_participants_user", "user_id", "conversation_id"),
    )

    # Составной ключ вместо суррогатного: строка не редактируется и не
    # адресуется по одному id, а ключ бесплатно запрещает позвать одного и
    # того же дважды — включая гонку двух операторов, нажавших одновременно.
    conversation_id: Mapped[uuid.UUID] = mapped_column(
        Uuid, ForeignKey("conversations.id", ondelete="CASCADE"), primary_key=True
    )
    user_id: Mapped[uuid.UUID] = mapped_column(
        Uuid, ForeignKey("users.id", ondelete="CASCADE"), primary_key=True
    )
    invited_by_id: Mapped[uuid.UUID | None] = mapped_column(
        Uuid, ForeignKey("users.id", ondelete="SET NULL")
    )
    invited_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), nullable=False, server_default=func.now()
    )
    #: Зачем позвали. Без этого приглашение читается как «посмотри зачем-то»,
    #: и человек открывает диалог, чтобы выяснить, что от него хотели.
    reason: Mapped[str | None] = mapped_column(Text)
    #: Как человек здесь оказался: `invited` — позвали, `self` — зашёл сам.
    #:
    #: ⚠ МАШИННОЕ ПОЛЕ, А НЕ ОТТЕНОК СМЫСЛА В `reason`. От этого различия
    #: зависят три РАЗНЫХ решения, и все три уже написаны в коде:
    #:
    #: * права. Участие даёт закрепить чужой диалог (`services/pins.py`).
    #:   «Позвали помочь» — законная причина; «зашёл посмотреть» — нет;
    #: * долг. Число «ждут вашего ответа» обязано считать то, за что человек
    #:   отвечает, а не то, что он сегодня открывал;
    #: * срок жизни. Приглашение снимает человек, а зашедший уходит сам —
    #:   вместе с возвратом диалога в очередь.
    #:
    #: Умолчание `invited`: все строки, заведённые до этого поля, — настоящие
    #: приглашения, и трактовать их иначе значило бы задним числом отнять
    #: у позванных права.
    kind: Mapped[str] = mapped_column(
        Text, nullable=False, default="invited", server_default="invited"
    )
