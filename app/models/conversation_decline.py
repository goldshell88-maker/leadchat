"""Отказ от диалога — С МОМЕНТОМ, а не навсегда (требование заказчика от 13 августа).

«При нажатии „Отклонить“ диалог возвращался в течение 3 минут назад во входящие, и
работало под каждого пользователя отдельно: у того, кто нажал, вернётся в очередь;
тот, кто не нажимал, так и останется».

ПОЧЕМУ ОТДЕЛЬНАЯ ТАБЛИЦА, А НЕ ВРЕМЯ В МАССИВЕ. Отказы жили в
``conversations.declined_by`` — массиве строк-идентификаторов. Момента отказа там нет и
приделать его некуда: «id|время» в той же строке пришлось бы разбирать в SQL, а фильтр
очереди обязан быть именно в SQL (очередь длинная, постфильтрация страницы отдала бы
неполную страницу и неверный счётчик — см. ``inbox.visible_queue_condition``).

ПОЧЕМУ ``declined_by`` ОСТАЛСЯ И НЕ УДАЛЁН. Он отвечает на ДРУГОЙ вопрос. Здесь — «чей
отказ ещё действует» (живёт три минуты). Там — «кто вообще отказывался», и по нему
считается эскалация «отказались ВСЕ, кому диалог доступен» (14 §2.3): администраторов
зовут по факту круга отказов, а не по тому, у кого именно сейчас спрятана строка. Сделай
их одним источником — и через три минуты после последнего отказа «круг» рассыпался бы
сам собой, а эскалация перестала бы срабатывать вовсе.

Плюс регламент выкатки (RUNBOOK-DEPLOY §13): одна миграция — только добавляющие
изменения, удаление колонки разрешено минимум через релиз. Снеси ``declined_by`` сейчас —
и автоматический откат на предыдущий тег (шаг 6 деплоя) перестанет работать навсегда:
старый код пишет в эту колонку на каждом ``enter_queue``.

ПОЧЕМУ БЕЗ ПЕРЕНОСА СТАРЫХ ОТКАЗОВ. Переносить нечего. Отказ теперь живёт три минуты, а
всё, что лежит в ``declined_by`` на момент выкатки, старше этого срока по определению —
такие отказы обязаны считаться истёкшими, и именно это происходит само, если ничего не
переносить. Заодно снимается вопрос, что делать с отменёнными отказами и с отказами,
которые система намеренно стирала при возврате диалога в очередь.

СОСТАВНОЙ КЛЮЧ. Строка не адресуется по одному идентификатору, а ключ
``(conversation_id, user_id)`` бесплатно запрещает два отказа одного человека по одному
диалогу: повторное нажатие — это обновление момента, а не второй ряд.
"""

import uuid
from datetime import datetime

from sqlalchemy import DateTime, ForeignKey, Index, PrimaryKeyConstraint, func
from sqlalchemy.dialects.postgresql import UUID as PgUUID
from sqlalchemy.orm import Mapped, mapped_column

from app.models.base import Base


class ConversationDecline(Base):
    """Один отказ одного человека от одного диалога — с моментом нажатия."""

    __tablename__ = "conversation_declines"
    __table_args__ = (
        PrimaryKeyConstraint("conversation_id", "user_id", name="pk_conversation_declines"),
        # Сторона времени: фоновая задача раз в минуту ищет отказы, которые только что
        # истекли, чтобы толкнуть диалог обратно в очередь тому, кто отказывался. Без
        # индекса это был бы полный проход по таблице на каждом такте планировщика.
        Index("ix_conversation_declines_expiry", "declined_at"),
    )

    conversation_id: Mapped[uuid.UUID] = mapped_column(
        PgUUID(as_uuid=True), ForeignKey("conversations.id", ondelete="CASCADE"), nullable=False
    )
    user_id: Mapped[uuid.UUID] = mapped_column(
        PgUUID(as_uuid=True), ForeignKey("users.id", ondelete="CASCADE"), nullable=False
    )
    #: Когда нажали «Отклонить». Отсюда считается, действует ли отказ ещё.
    declined_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), nullable=False, server_default=func.now()
    )
