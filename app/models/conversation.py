"""conversations — DESIGN §4.4."""

import uuid
from datetime import datetime
from typing import Any

from sqlalchemy import (
    BigInteger,
    Boolean,
    CheckConstraint,
    DateTime,
    ForeignKey,
    Index,
    Integer,
    Text,
    UniqueConstraint,
    Uuid,
    func,
    text,
)
from sqlalchemy.orm import Mapped, mapped_column

from app.models.base import Base
from app.models.types import JSONB, TextArray


class Conversation(Base):
    __tablename__ = "conversations"
    __table_args__ = (
        UniqueConstraint("channel", "external_chat_id"),
        Index("ix_conversations_tags", "tags", postgresql_using="gin"),
        Index(
            "ix_conversations_origin_client",
            "origin_client_id",
            postgresql_where=text("origin_client_id IS NOT NULL"),
        ),
        # ОГРАНИЧЕНИЕ НА СЛОВАРЬ СТАТУСОВ (docs/38 §2, миграция 0026).
        #
        # До 0026 его не было вовсе: в колонку писали тринадцать мест кода, и
        # ни одно не проверялось базой — физически туда можно было записать
        # что угодно, а охраняли её три независимые python-проверки, ни одна
        # из которых не была выведена из двух других.
        #
        # Значения выписаны ЛИТЕРАЛАМИ, а не подставлены из
        # `services.conversation_status.STATUSES`: ограничение попадает в
        # миграцию текстом SQL, и собранное из кода оно означало бы, что
        # содержимое уже применённой миграции зависит от версии приложения.
        # Разъезд литералов со словарём ловит охранный тест
        # `tests/unit/test_conversation_status.py`.
        #
        # Объявлено В МОДЕЛИ, а не только в миграции, потому что юнит-тесты
        # строят схему из метаданных (`Base.metadata.create_all` на SQLite):
        # иначе запрет работал бы на проде и молчал в тестах. Прецедент —
        # `users.role` (app/models/user.py).
        #
        # ЗНАЧЕНИЙ ЧЕТЫРЕ С 12 АВГУСТА (миграция 0033). `snoozed` снят вместе со
        # всей отложкой — решением владельца. Ограничение приведено в
        # соответствие, а не оставлено «широким»: разрешать значение, которого
        # в продукте больше нет, значит держать открытой дверь, за которой
        # ничего нет, — и первый же чужой UPDATE поставит диалог в статус, для
        # которого не осталось ни подписи, ни фильтра, ни экрана.
        CheckConstraint(
            "status IN ('new','in_progress','waiting_client','closed')",
            name="status",
        ),
        # ОГРАНИЧЕНИЕ НА СПРАВОЧНИК РЕЗУЛЬТАТОВ (FUNC-32, миграция 0032).
        #
        # Комментарий у самой колонки обещал закрытый справочник и ссылался на
        # «`OUTCOMES` ниже» — константы с таким именем в этом файле нет и
        # никогда не было: она живёт в `services/conversations.py`. То есть
        # единственной охраной колонки была одна проверка на Python в одной
        # ручке закрытия диалога, а обещание в модели было ложным.
        #
        # Чем это опасно именно здесь: по результату считаются ДЕНЬГИ — сколько
        # обращений стали выездами, какой канал окупается (services/stats.py
        # группирует по этой колонке). Значение мимо справочника не падает и не
        # подсвечивается, оно просто добавляет в сводку строку, которой никто
        # не заказывал: перенос данных, ручной UPDATE при разборе, будущая
        # массовая правка — и квартальный отчёт разъезжается молча.
        #
        # Значения выписаны ЛИТЕРАЛАМИ по той же причине, что и у `status`
        # выше: ограничение уезжает в миграцию текстом SQL, и собранное из кода
        # оно означало бы, что содержимое уже применённой миграции зависит от
        # версии приложения. Разъезд со справочником ловит охранный тест
        # `tests/unit/test_conversation_outcome.py`.
        #
        # NULL законен и означает «не проставили»: результат обязателен не
        # везде, а принуждать диспетчера к цифре, которой он не знает, значит
        # получить выдуманную.
        CheckConstraint(
            "outcome IS NULL OR outcome IN "
            "('visit','declined','not_our_profile','spam','no_reply')",
            name="outcome",
        ),
        # Индекс под сторож отложки. Сторожа не стало 12 августа, и читателей у
        # индекса теперь ноль — но он ОСТАЁТСЯ, как остаются и сами колонки:
        # `snoozed_until` заполнена только у диалогов, отложенных до выката, то
        # есть индекс почти пустой (он частичный) и не стоит ничего ни на
        # вставке, ни на месте. Снести его — минутное дело, а собрать обратно
        # вместе с функцией — ещё одна миграция и ещё одно окно выката.
        Index(
            "ix_conversations_snoozed_until",
            "snoozed_until",
            postgresql_where=text("snoozed_until IS NOT NULL"),
        ),
    )

    id: Mapped[uuid.UUID] = mapped_column(Uuid, primary_key=True, default=uuid.uuid4)
    channel: Mapped[str] = mapped_column(Text, nullable=False, default="avito")
    external_chat_id: Mapped[str] = mapped_column(Text, nullable=False)
    account_id: Mapped[uuid.UUID] = mapped_column(
        Uuid, ForeignKey("avito_accounts.id"), nullable=False
    )
    client_id: Mapped[uuid.UUID] = mapped_column(Uuid, ForeignKey("clients.id"), nullable=False)
    #: Карточка, под которую диалог встал бы, не будь она объединена в другую
    #: (`inbound._upsert_client` ведёт к победителю по цепочке `merged_into_id`).
    #: Пусто у диалогов, заведённых прямо под свою карточку. Читает только
    #: «Разъединить»: диалоги, появившиеся ПОСЛЕ объединения, в снимке журнала
    #: нет, и без этой колонки они оставались у победителя навсегда.
    origin_client_id: Mapped[uuid.UUID | None] = mapped_column(
        Uuid, ForeignKey("clients.id", ondelete="SET NULL")
    )
    assignee_id: Mapped[uuid.UUID | None] = mapped_column(Uuid, ForeignKey("users.id"))
    # Состав словаря — `app/services/conversation_status.py`, он же в CHECK
    # выше. Здесь его НЕТ намеренно: комментарий с перечислением значений
    # прожил в этой строке до 0026 и всё это время был единственным местом,
    # где состав вообще был записан на уровне модели, — то есть ровно тем
    # видом документации, который расходится с кодом молча.
    status: Mapped[str] = mapped_column(Text, nullable=False, default="new")

    # --- когда диалог вошёл в НЫНЕШНИЙ статус (docs/38 §2) -------------------
    #
    # Нужно строке контекста в карточке: «В работе у Иванова · 12 мин».
    #
    # ПОЧЕМУ НЕ `updated_at`. Тот двигается от ЛЮБОГО изменения строки
    # (ORM onupdate, см. ниже): каждое сообщение, каждая заметка, каждое
    # обогащение карточки клиента. Строка «в работе 12 мин», построенная на
    # нём, показывала бы время с последнего сообщения — другую величину, и
    # показывала бы правдоподобно. Это и есть худший вид ошибки: заметить её
    # можно только сверив с журналом.
    #
    # Пишется РОВНО В ОДНОМ месте — `services.conversations._set_status`.
    # Прямое присваивание `conv.status = ...` после docs/38 считается ошибкой
    # ревью: оно оставит колонку со временем прошлого статуса.
    #
    # NULL законен только у строк, созданных до 0026 и с тех пор не менявших
    # статуса: миграция проставила им приблизительное значение, а совсем
    # старым — то, что нашлось. Интерфейс на NULL показывает статус без
    # длительности; прочерк честнее выдуманного нуля.
    status_since: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))

    # --- отложенный диалог (docs/38 §7) --------------------------------------
    #
    # «Отложен» — единственный статус, который снимается сам. Срок лежит В
    # БАЗЕ, а не отложенным заданием ARQ, и это решение: задание с задержкой
    # живёт в Redis, и перезапуск Redis без persistence теряет его вместе с
    # обещанием вернуться к клиенту. Правда в колонке переживает перезапуск
    # чего угодно, а сторож раз в минуту стоит одного индексного чтения.
    #
    # Три поля, а не одно: «до какого времени», «кто отложил» и «почему».
    # Второе нужно строке контекста и разбору («кто спрятал диалог на сутки»),
    # третье — тому, кто откроет диалог вместо автора отложки.
    snoozed_until: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))
    snoozed_by_id: Mapped[uuid.UUID | None] = mapped_column(Uuid, ForeignKey("users.id"))
    snooze_reason: Mapped[str | None] = mapped_column(Text)
    bot_active: Mapped[bool] = mapped_column(Boolean, nullable=False, default=False)
    bot_vars: Mapped[dict[str, Any]] = mapped_column(JSONB, nullable=False, default=dict)
    tags: Mapped[list[str]] = mapped_column(TextArray, nullable=False, default=list)
    item_title: Mapped[str | None] = mapped_column(Text)
    item_url: Mapped[str | None] = mapped_column(Text)
    item_price: Mapped[str | None] = mapped_column(Text)
    # --- город объявления (требование владельца от 11 августа) --------------
    #
    # СНИМОК НА МОМЕНТ ОБРАЩЕНИЯ, а не текущее состояние объявления. Пишется
    # один раз, при первом разборе ссылки, и не переписывается: перенос
    # объявления в другой город не должен задним числом переписать отчёт за
    # прошлый квартал (docs/32, крайний случай «объявление перенесено»).
    #
    # ХРАНИТСЯ ТОЛЬКО СЛАГ, хотя docs/32 §1 предлагал ещё и название с
    # регионом. Название и часовой пояс — производные от слага по справочнику
    # `integrations/avito/listing_url.CITIES`, и считаются на выдаче. Причина
    # ровно одна и она практическая: справочник будет пополняться по факту
    # встреченных слагов, и при хранении названия каждое пополнение требовало
    # бы прогона по всей таблице, чтобы старые строки перестали быть
    # прочерками. Со слагом они чинятся сами, в тот же миг.
    #
    # NULL значит «города не знаем»: ссылки не было, домен чужой или слаг не
    # похож на город. Это законное состояние, а не сбой.
    item_city_slug: Mapped[str | None] = mapped_column(Text)
    # Sprint-2 owner decision: a plain per-conversation counter is enough for
    # now (per-user Redis read-markers из 01 §5.1 — позже). Incremented by
    # apply_inbound_event, reset by POST /conversations/{id}/read.
    unread_count: Mapped[int] = mapped_column(
        Integer, nullable=False, default=0, server_default="0"
    )
    last_message_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))
    # Any row change (ORM onupdate) — backs the ?updated_since= API filter.
    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        nullable=False,
        server_default=func.now(),
        onupdate=func.now(),
    )

    # --- очередь «Входящие» (план 7.1, 15 §2.1) -----------------------------
    #
    # Состояние «ждёт принятия» выражено ПОЛЯМИ ОЧЕРЕДИ, а не пятым статусом.
    # Разбор альтернативы — в шапке миграции 0007; коротко: `status` читают
    # вкладки списка (01 §5.1), статистика (06), боты и inbound-конвейер, и
    # новое значение в нём означало бы правку каждого из них. Поля очереди
    # ортогональны статусу: пока `claimed_by_id IS NULL`, диалог ждёт хозяина,
    # каким бы ни был его статус.
    #
    # `offered_at` — когда диалог встал в очередь. По нему очередь сортируется
    # («дольше всех ждущий — первым») и считается время ожидания принятия.
    # NULL значит «в очереди никогда не стоял»: ровно так после миграции
    # выглядят диалоги, заведённые до 7.1, — они не всплывут во «Входящих».
    offered_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))
    # `claimed_by_id` — ЕДИНСТВЕННЫЙ арбитр гонки: принятие делается одним
    # `UPDATE ... WHERE claimed_by_id IS NULL` (app/services/inbox.claim).
    # Это не дубль `assignee_id`: ответственный меняется передачей (01 §5.5),
    # а «кто вынул диалог из очереди» — факт, который передача не переписывает.
    claimed_by_id: Mapped[uuid.UUID | None] = mapped_column(Uuid, ForeignKey("users.id"))
    claimed_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))
    # Кто отказался вести диалог: id сотрудников строками (тот же приём, что
    # `tags`, — портируется на SQLite юнит-тестов). Отклонившему диалог больше
    # не показывается, иначе он будет натыкаться на него в очереди снова.
    declined_by: Mapped[list[str]] = mapped_column(TextArray, nullable=False, default=list)
    # Пометка «отказались все, кому диалог доступен» (эскалация 7.1): диалог
    # остаётся в очереди, но администраторы уже позваны (14 §2.3).
    escalated_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))
    # Когда диалог отдала СИСТЕМА, а не человек (план 7.6). Заполнено — значит
    # оператор его ещё не подтвердил ни одним действием: не ответил, не закрыл,
    # не передал. Ровно такие диалоги возвращаются в очередь, если получатель
    # ушёл из сети (7.7): клиент, лежащий «у оператора», которого нет за
    # столом, не ждёт никого конкретно и не виден остальным двенадцати.
    #
    # ПОЧЕМУ ОТДЕЛЬНОЕ ПОЛЕ, А НЕ ВЫВОД ИЗ ДРУГИХ
    # Соблазн вывести признак из `claimed_by_id IS NULL AND assignee_id IS NOT
    # NULL` — «никто не нажимал принять, но ответственный есть». Так нельзя:
    # под это же условие попадает передача руководителем (01 §5.5), где
    # решение принял человек и отбирать диалог обратно нельзя. Отличать
    # решение системы от решения человека обязано поле, которое ставит сама
    # система.
    auto_assigned_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))

    # --- клиент ждёт ответа (требование заказчика от 7 августа) --------------
    #
    # «Если диалог в работе, то должно как-то сигнализировать, что клиент
    # написал сообщение».
    #
    # Момент, когда клиент написал и ему ещё не ответили. Ставится на входящем,
    # если поле пусто; снимается ответом оператора, закрытием и возвратом в
    # очередь. По нему рисуется «ждёт 12 мин» в списке и работает сторож,
    # который сначала напоминает оператору, потом руководителю.
    #
    # ПОЧЕМУ ПОЛЕ, А НЕ ВЫЧИСЛЕНИЕ. Признак «последнее сообщение от клиента»
    # выводится запросом (так делает статистика), но каждый такой вывод — это
    # LATERAL по таблице сообщений на КАЖДЫЙ диалог. Раз в минуту по всем
    # активным диалогам это неприемлемо: на четырёхстах тысячах строк сторож
    # превратился бы в самую тяжёлую операцию системы. Поле пишется один раз
    # там, где событие и происходит.
    #
    # ПОЧЕМУ «ЕСЛИ ПУСТО», А НЕ КАЖДОЕ ВХОДЯЩЕЕ. Клиент, написавший подряд
    # пять сообщений, ждёт с ПЕРВОГО. Обновляй мы отметку на каждом, самый
    # настойчивый клиент выглядел бы самым свежим — ровно наоборот.
    awaiting_since: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))

    # --- ответ оператора не ушёл клиенту (план работ 21, этап 2) -------------
    #
    # Момент САМОГО РАННЕГО исходящего в состоянии `failed`. Пусто — всё, что
    # писал оператор, доставлено.
    #
    # ЗАЧЕМ ПОЛЕ В ДИАЛОГЕ, ЕСЛИ СТАТУС ЕСТЬ У СООБЩЕНИЯ. Красный крест видно
    # только в открытой ленте, а решение «идти дальше или вернуться» человек
    # принимает по левому списку. Там строка выглядела успешно отвеченной:
    # «Вы: перезвоню в течение часа» и ничего красного. Оператор уходил к
    # следующему клиенту, а этот оставался без ответа.
    #
    # ПОЧЕМУ НЕ СЧИТАТЬ НА ЧТЕНИИ. Тот же довод, что у `awaiting_since` выше:
    # список диалогов — самый частый запрос системы, и подзапрос по `messages`
    # означал бы поход в таблицу сообщений на каждую строку каждого списка.
    # Поле пишется на редких путях — провал доставки, повтор, удаление, — и
    # всегда пересчитывается одним запросом (`services.messages.refresh_
    # undelivered`), а не правится «плюс один / минус один»: счётчик, который
    # чинят инкрементами, рано или поздно расходится с правдой.
    #
    # ПОЧЕМУ МОМЕНТ, А НЕ «ДА/НЕТ». По нему видно, сколько ответ уже висит
    # неотправленным, и это же значение можно показать человеку. Само
    # булево — `undelivered_at is not None`.
    undelivered_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))

    # --- система спросила адрес (владелец 18.09) ---------------------------
    #
    # Момент, когда `workers/address_ask.py` отправил клиенту вопрос об адресе.
    # Пусто — не спрашивала. Пишется ОДИН раз под FOR UPDATE и никогда не
    # сбрасывается: «раз на диалог навсегда». Не в `bot_vars`: тот JSONB —
    # карман движка бота, а скаляр верхнего уровня уезжает в сводку передачи
    # (`bots/state.py::from_dict` считает его собранной переменной).
    address_asked_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))

    # --- чем закончилось обращение (план работ 21, C1) -----------------------
    #
    # ЭТИ ЧЕТЫРЕ КОЛОНКИ БОЛЬШЕ НИКТО НЕ ЗАПОЛНЯЕТ И НЕ ПОКАЗЫВАЕТ. Окно «Чем
    # закончилось обращение?» снято 12 августа решением владельца, закрытие
    # диалога стало одношаговым. Колонки и накопленные значения ОСТАВЛЕНЫ
    # намеренно: снос необратим, а решение может измениться — вернуть функцию
    # должно быть можно правкой кода. Ограничение `ck_conversations_outcome`
    # (0032) тоже осталось: оно разрешает NULL и потому ничему не мешает.
    #
    # ЦЕНА РЕШЕНИЯ, ЗАПИСАННАЯ ЗДЕСЬ НАМЕРЕННО: `outcome_amount` была
    # ЕДИНСТВЕННЫМ местом во всей системе, где появлялась сумма. Пока её не
    # заполняют, продукт не может ответить, какой канал окупается, — считаются
    # обращения и скорость, но не деньги.
    #
    # Всё, что ниже, — доводы времён живой функции; они сохранены, потому что
    # решают тот же вопрос, если функцию будут возвращать.
    #
    # Единственная величина в системе, которую нельзя восстановить задним
    # числом. Переписка отвечает на вопрос «о чём говорили», но не на вопрос
    # «чем кончилось»: выехал мастер или человек передумал, видно только со
    # слов того, кто вёл диалог, — и только пока он помнит.
    #
    # СПРАВОЧНИК ЗАКРЫТЫЙ, и с миграции 0032 его держит база — `CheckConstraint`
    # в `__table_args__` выше. Свободный текст через месяц превращается в
    # двести написаний одного и того же, и сводку по нему не построить;
    # расширить список проще, чем разобрать свалку.
    #
    # ЗДЕСЬ СТОЯЛО «(`OUTCOMES` ниже)». Константы с таким именем в этом файле
    # нет: справочник живёт в `app/services/conversations.py`. Ссылка на
    # несуществующее место читалась как «ограничение рядом, всё под охраной» —
    # и ровно поэтому отсутствие ограничения в базе никто не замечал.
    outcome: Mapped[str | None] = mapped_column(Text)

    # Сумма — В КОПЕЙКАХ и целым числом. Дробные рубли в плавающей точке дают
    # «1999.9999999» в отчёте за квартал. Необязательна и заполняется только
    # там, где известна: принуждать диспетчера к цифре, которой он не знает,
    # значит получить выдуманную.
    outcome_amount: Mapped[int | None] = mapped_column(BigInteger)

    # Кто и когда проставил. Нужны не для отчёта, а для разбора: «почему этот
    # выезд помечен отказом» — вопрос к человеку, а не к системе.
    outcome_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))
    outcome_by_id: Mapped[uuid.UUID | None] = mapped_column(Uuid, ForeignKey("users.id"))

    # --- передача с подтверждением (требование заказчика от 7 августа) -------
    #
    # «Диалог не считается переданным, если другой сотрудник его не принял».
    #
    # До этого передача была мгновенной: нажал «Передать» — и ответственность
    # ушла, даже если коллега в этот момент обедал, был не в сети или просто не
    # заметил. Клиент при этом оставался без ответа, а спросить было не с кого:
    # передавший считал, что дело сделано, принимающий — что ему ничего не
    # давали.
    #
    # Поэтому передача двухфазная. Пока `transfer_to_id` заполнен, диалог ЕЩЁ
    # ЧИСЛИТСЯ ЗА ПЕРЕДАЮЩИМ (`assignee_id` не меняется) — он и отвечает
    # клиенту, если тот написал. Принял получатель — ответственный меняется;
    # отказался или промолчал слишком долго — предложение снимается, и диалог
    # остаётся там, где был.
    #
    # ПОЧЕМУ НЕ ЧЕРЕЗ ОЧЕРЕДЬ «ВХОДЯЩИЕ». Соблазн велик: там уже есть и
    # принятие, и отказ, и эскалация. Но очередь — это «диалог ничей, возьмите
    # кто-нибудь», а передача адресная: она предложена ОДНОМУ человеку и
    # означает «прошу тебя, потому что ты в теме». Свали их в одно — и
    # адресность потеряется: диалог, который передавали конкретному мастеру по
    # холодильникам, заберёт первый освободившийся.
    transfer_to_id: Mapped[uuid.UUID | None] = mapped_column(Uuid, ForeignKey("users.id"))
    transfer_by_id: Mapped[uuid.UUID | None] = mapped_column(Uuid, ForeignKey("users.id"))
    #: Владелец в момент предложения. Предлагать может и не он (администратор,
    #: руководитель), а принятие сверяет владельца именно с ним.
    transfer_from_id: Mapped[uuid.UUID | None] = mapped_column(Uuid, ForeignKey("users.id"))
    transfer_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))
    #: Сопроводительная фраза «почему передаю» — её пишут в момент передачи, и
    #: получателю она нужна больше, чем сам факт: «клиент из Балашихи, это твой
    #: район» объясняет предложение, а голое «вам передан диалог» — нет.
    transfer_comment: Mapped[str | None] = mapped_column(Text)
