"""users — DESIGN §4.4."""

import uuid
from datetime import datetime

from sqlalchemy import Boolean, CheckConstraint, DateTime, Text, Uuid, func
from sqlalchemy.orm import Mapped, mapped_column

from app.models.base import Base
from app.models.types import JSONB, CIText


class User(Base):
    __tablename__ = "users"
    __table_args__ = (
        CheckConstraint("role IN ('admin','head','manager','observer')", name="users_role"),
    )

    id: Mapped[uuid.UUID] = mapped_column(Uuid, primary_key=True, default=uuid.uuid4)
    email: Mapped[str] = mapped_column(CIText, unique=True, nullable=False)
    password_hash: Mapped[str] = mapped_column(Text, nullable=False)  # argon2id
    full_name: Mapped[str] = mapped_column(Text, nullable=False)
    #: Личный цвет сотрудника (17.08): #RRGGBB, задаёт админ в «Команде» —
    #: люди разных отделов различимы в списках с одного взгляда.
    color: Mapped[str | None] = mapped_column(Text)
    role: Mapped[str] = mapped_column(Text, nullable=False)
    is_active: Mapped[bool] = mapped_column(Boolean, nullable=False, default=True)

    # Служебная запись, а не человек (07 §6): пользователь-робот регрессионного
    # smoke. Его заводит `app/cli.py seed-smoke` на каждом деплое.
    #
    # ЗАЧЕМ ОТДЕЛЬНАЯ КОЛОНКА, ЕСЛИ СЛУЖЕБНОСТЬ «ВИДНО ПО ПОЧТЕ». Раньше её и
    # выводили из адреса — `config.is_service_email` прячет всё, что кончается
    # на `.local`. Правило дешёвое и ровно поэтому неверное: домен `.local` —
    # обычный внутренний домен, и на боевой базе на нём живут НАСТОЯЩИЕ люди
    # (замер 12 августа: `admin@leadpartner.local` и `dev-admin@leadchat.local`
    # — два действующих администратора, которых список сотрудников не
    # показывает вовсе). Признак обязан СТАВИТЬСЯ тем, кто запись создал, а не
    # угадываться по строке.
    #
    # Ставится в одном месте (seed-smoke), читается там, где строится отчёт.
    is_service: Mapped[bool] = mapped_column(
        Boolean, nullable=False, default=False, server_default="false"
    )

    # Сотрудник удалён (требование заказчика от 7 августа).
    #
    # ПОЧЕМУ ОТМЕТКА, А НЕ DELETE. Настоящее удаление снесло бы вместе с
    # человеком его сообщения — а это переписка с клиентами. Годовой отчёт
    # стал бы анонимным, а в старых диалогах вместо имени появилось бы
    # «Сотрудник»: клиент видит подпись, и она обязана остаться правдой.
    #
    # ЧЕМ ОТЛИЧАЕТСЯ ОТ `is_active = False`. Отключённый — временное
    # состояние: человек в отпуске, разбираемся с доступом, вернётся.
    # Он виден в списке под галочкой «показывать отключённых», его можно
    # включить обратно одной кнопкой. Удалённый не виден нигде и не
    # включается: он ушёл. Оставь мы только «отключён», список за год
    # зарастает уволенными, и найти работающего становится задачей.
    deleted_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))
    # Работает ли человек с диалогами — ОТДЕЛЬНО от роли (план 7.4).
    #
    # ЗАЧЕМ. У заказчика в Jivo так настроен отдел «СТАРШИЕ - ЧАТЫ»:
    # администрируют систему, но обращения не ведут. До этого поля роль
    # означала сразу две вещи — «что человеку позволено» и «грузить ли его
    # диалогами», — и развести их было нечем: любой администратор
    # автоматически попадал в очередь и в автораздачу.
    #
    # Флаг убирает человека из РАЗДАЧИ (очередь, автораспределение, список
    # «кому передать»), но не отнимает право отвечать. Разница существенная:
    # администратор, вмешавшийся в конкретный диалог, должен иметь возможность
    # написать клиенту — просто система не должна назначать ему новые сама.
    #
    # По умолчанию `true`: до 7.4 диалоги вели все, кто умеет отвечать, и
    # миграция не должна менять это ни для кого.
    handles_conversations: Mapped[bool] = mapped_column(
        Boolean, nullable=False, default=True, server_default="true"
    )
    # Отдел — свободная строка, а не справочник. У заказчика их семь с лишним
    # (Дисп 1–7, Клининг, АВИТО ОТДЕЛ, ОКК, СТАРШИЕ - ЧАТЫ), состав меняется
    # чаще, чем стоило бы гонять миграцию, а никакой логики на отделе не
    # висит: он нужен, чтобы в списке из тринадцати человек находить нужного
    # глазом, а не вычитыванием строк.
    department: Mapped[str | None] = mapped_column(Text)
    # Когда системе в последний раз пришлось отдать этому человеку диалог (#35).
    #
    # Нужно автораздаче для тай-брейка: при равной нагрузке диалог достаётся
    # тому, кому дольше не доставалось. Раньше это выводили запросом
    # `max(updated_at)` по всем диалогам человека — без фильтра по статусу и
    # без границы по времени, то есть перебирая всю его историю на каждое
    # новое обращение. И считало оно не то: `updated_at` меняется от любой
    # правки, так что активно отвечающий оператор выглядел «только что
    # получившим диалог» и уступал очередь тому, кто сидит без дела.
    #
    # Ставится ровно в момент выдачи (`inbox.assign_by_distribution`). Пусто —
    # «системой не получал ни разу», и такой человек идёт первым: у него точно
    # есть место.
    last_assigned_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))
    # --- личные настройки интерфейса (требование заказчика 13 августа) ------
    #
    # Пока здесь одно: переназначенные горячие клавиши, `{"hotkeys": {"claim":
    # ["Mod+KeyY"]}}`. Чего в объекте нет — берётся из реестра по умолчанию, поэтому
    # запись хранит ТОЛЬКО отличия: так обновление умолчаний доезжает до всех, кто
    # это действие не трогал, а не застревает у каждого своей копией.
    #
    # ⚠ ХРАНИТСЯ У ЧЕЛОВЕКА, А НЕ В БРАУЗЕРЕ, И ЭТО СУТЬ. Настройка — про мышечную
    # память, и подводит она ровно тогда, когда человек сел за подменный компьютер
    # или открыл десктопную сборку: то есть в единственный день, когда привычка и
    # нужна больше всего.
    ui_settings: Mapped[dict | None] = mapped_column(JSONB, nullable=True)
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), nullable=False, server_default=func.now()
    )
