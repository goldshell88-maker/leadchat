"""Готовые сценарии, поставляемые с продуктом.

Сейчас он один — «Первичный приём» (DESIGN §4.2, разложенный по формату
02 §1). Его копию получает каждый новый бот: `POST /bots` без `scenario`
и кнопка «Создать бота» в списке (02 §5.1, 11 §5.1).

**Срок дожима — 20 минут, и это измеренная величина (21.08).** Было 5 минут.
По свежему корпусу Jivo (27 786 диалогов, 3202 настоящих дожима — пауза оператора
дольше двух минут без ответа клиента) живые ждут p25 = 11.3 мин, медиана 25.2 мин,
p75 = 45.5 мин; быстрее пяти минут пингуют только 11%. То есть бот обгонял 89%
операторов, а регламент прямо связывает настырность с жалобами на Авито и
блокировкой аккаунта партнёра. Число закреплено тестом
``tests/unit/test_default_scenario_ping.py``: в JSON комментария не поставить.

**Отличие от примера 02 §1.5 — одно и осознанное.** В примере документа
`ask_problem.on_timeout` ведёт на шаг `close_silent`, то есть через 24 часа
молчания клиента бот закрывает диалог. Решение владельца: автоматического
закрытия по таймауту НЕТ — диалог живёт, пока менеджер не закроет его руками.
Поэтому ветка таймаута ведёт на `handoff_no_reply`: диалог возвращается в
общую очередь со статусом `new` и остаётся там. Шаг типа `close` в дефолтном
сценарии не используется вовсе (сам тип шага поддержан — админ может собрать
им свой сценарий осознанно).
"""

import json
from pathlib import Path
from typing import Any

_DIR = Path(__file__).parent

DEFAULT_SCENARIO_FILE = "primary_intake.json"
DEFAULT_BOT_NAME = "Первичный приём"

# База знаний по умолчанию пустая: цены и сроки у каждого сервиса свои,
# выдумывать их за владельца нельзя (02 §3.1 запрещает модели фантазировать,
# а валидатор предупредит `ai_without_kb` — это ровно то напоминание,
# которое админ должен увидеть перед включением бота).
DEFAULT_KNOWLEDGE_BASE = ""

# Круглосуточно (02 §2.5, дефолт DDL).
DEFAULT_SCHEDULE: dict[str, Any] = {"always": True}


def load_scenario(name: str = DEFAULT_SCENARIO_FILE) -> dict[str, Any]:
    """Прочитать сценарий из каталога. Каждый вызов — свежая копия."""
    data: dict[str, Any] = json.loads((_DIR / name).read_text(encoding="utf-8"))
    return data


def default_scenario() -> dict[str, Any]:
    """Копия «Первичного приёма» — заготовка для нового бота."""
    return load_scenario()
