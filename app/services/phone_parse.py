"""Российский телефон, написанный внутри обычной фразы.

ЖИВОЙ ПОВОД. Диалог a1b2c3d4 (Анна Сергеевна), входящее 12 августа 16:35:
«В любое время в течении дня. Прошу сообщить о времени прихода за 1 час в СМС
по номеру : +7(900)1112240.» В карточке при этом пусто и стоит кнопка «указать
телефон»: лид с готовым контактом лежит в переписке, а поиск по телефону его не
находит. Номер попадал в карточку ровно двумя путями — шагом бота «Вопрос» с
валидатором «телефон» и ответом ассистенту Авито, — и оба требуют, чтобы
человек ответил на прямой вопрос. Люди так не пишут. (Идентификатор, имя и
цифры здесь и ниже вымышленные, форма записи — как в бою.)

ПОЧЕМУ ОТДЕЛЬНЫЙ МОДУЛЬ И ПОЧЕМУ БЕЗ БАЗЫ. Здесь только чистые функции: текст
на входе, номер на выходе. Ни сессии, ни сети, ни настроек. Из-за этого разбор
покрывается тестами построчно (каждый формат и каждый контрпример —
`tests/unit/test_phone_parse.py`), и одна и та же реализация обслуживает три
разных места: приём входящих, поле ввода в карточке и разовый пересчёт по
истории. До этого нормализация жила в двух копиях — в `inbound.extract_phone` и
в `clients.normalize_phone`, — и обе сопровождались комментарием «разойтись им
нельзя». Одна копия расходиться не умеет.

ГЛАВНОЕ ПРАВИЛО: ЛУЧШЕ ПРОПУСТИТЬ, ЧЕМ ПРИДУМАТЬ. Номер из карточки набирают и
диктуют мастеру вслух. Ошибочно распознанная строка — это звонок постороннему
человеку и потерянный настоящий клиент, а нераспознанная — всего лишь работа,
которую сделает оператор руками. Отсюда три ограничения ниже; каждое взято из
того же боевого диалога, где рядом с настоящим номером лежат строки, номером не
являющиеся.

1. ЦИФРЫ, ПРИКЛЕЕННЫЕ К СЛОВУ, — НЕ НОМЕР. «Код входной двери в дом:
   37ключ2580», «Телевизор Samsung QLED Q70A 55cm». Человек, диктующий телефон,
   отделяет его от слов хотя бы пробелом; «тел.89001112240» проходит, потому что
   точка — разделитель, а не буква. Знак номера слева считается тем же
   приклеиванием: «заказ№89001112240» — одиннадцать цифр с восьмёрки, то есть по
   всем остальным признакам телефон, и спасает только этот знак.
2. ДЛИНА РОВНО ПО НОРМЕ. Непрерывная цепочка цифр и разделителей берётся
   ЦЕЛИКОМ, и в ней должно быть 10 или 11 цифр. «Заречное шоссе дом 7 кв.84
   (12 этаж)» даёт цепочки в одну и четыре цифры; «8-900-111-22-40-77» — в
   тринадцать, и это не телефон с лишним хвостом, а неизвестно что: где в такой
   цепочке начинается номер, не знает никто, и угадывать нельзя.
   ЦЕНА ЭТОГО ПРАВИЛА. «Звоните с 9 до 21 8 900 111 22 40» — одна цепочка в 14
   цифр, и номер оттуда не достанется. Это осознанный размен: молчание здесь
   стоит одного ручного ввода, а угадывание — звонка чужому человеку.
3. ХВОСТОВАЯ ПУНКТУАЦИЯ ОТБРАСЫВАЕТСЯ САМА. Цепочка обязана кончаться цифрой,
   поэтому «…1112240.» разбирается без единой оговорки в коде.

ЧЕГО ЗДЕСЬ НЕТ. Ни отсечения служебных сообщений Авито, ни исходящих оператора,
ни настроек «распознавать или нет» — это решения о том, КОГДА звать разбор, и
живут они на стороне вызывающего (`app/services/inbound.py`). Модуль отвечает
на один вопрос: есть ли в этой строке телефон. Единственное исключение —
номер кусками в репликах подряд (:func:`from_fragments`, 25.09): склейку делает
модуль, а какие реплики идут подряд, по-прежнему решает вызывающий.
"""

from __future__ import annotations

import re
from collections.abc import Sequence
from dataclasses import dataclass

#: Разделители, которые человек ставит ВНУТРИ номера. Список закрытый и
#: составлен по тому, что реально приезжает из Авито: обычный пробел,
#: неразрывный и узкий неразрывный (копипаста из объявления, из Word, из
#: мобильного приложения), четыре вида чёрточек (клавиатурный дефис-минус и три
#: типографских, которые подставляет автозамена), скобки вокруг кода и точка.
#:
#: Запятой здесь НЕТ намеренно: «мой 8 900 111 22 40, жены 8 900 111 22 55» —
#: это два номера, и склеить их в одну цепочку значило бы потерять оба (по
#: правилу длины).
#:
#: Записаны кодами, а не символами: неразрывный пробел и типографские чёрточки
#: неотличимы на глаз от обычных, и «поправленный» кем-то из них символ молча
#: выключил бы разбор ровно у тех сообщений, ради которых всё это написано.
#:
#: ⚠ ПЕРЕВОДА СТРОКИ ЗДЕСЬ НЕТ И НЕ БУДЕТ. «89001112240⏎89001112255» — два
#: номера на двух строках; склей их перенос в одну цепочку, вышло бы 22 цифры
#: и пропали бы оба (правило длины). Внутри одного номера человек строку не
#: рвёт.
_SEPARATOR_CHARS = (
    "\u0020"  # пробел
    "\u00a0"  # неразрывный пробел — копипаста из Авито, из Word, из телефона
    "\u202f"  # узкий неразрывный пробел — то же самое, другой редактор
    # Скрин владельца 18.09: номер вида «7900 111-22-40» на экране — и
    # «телефона нет» (здесь и ниже номера вымышленные, форма записи — как в
    # бою). Перепечатанная руками строка разбирается, значит в бою между «7900»
    # и «111» стоит что-то, чего на скрине не видно. Список был закрытым: любой
    # другой пробел или чёрточка рвал цепочку на «7900» и «111-22-40» — 4 и 6
    # цифр, не номер. Ниже всё, что клавиатура, Word и копипаста подставляют
    # вместо обычных пробела и дефиса, а глаз не отличает.
    "\u0009"  # табуляция — вставка из таблицы
    "\u1680\u2000\u2001\u2002\u2003\u2004\u2005\u2006\u2007\u2008\u2009\u200a"
    "\u205f\u3000"  # математический и идеографический пробелы
    "\u200b\u200c\u200d\u2060\ufeff"  # нулевой ширины: пробел, соединители, BOM
    "\u00ad"  # мягкий перенос — Word ставит его внутри «длинных слов»
    # Метки направления письма: iOS оборачивает ими номер, скопированный из
    # «Контактов» (U+202A…U+202C), мессенджеры ставят U+200E/U+200F.
    "\u200e\u200f\u202a\u202b\u202c\u202d\u202e\u2066\u2067\u2068\u2069"
    "\u002d"  # дефис-минус с клавиатуры
    # Бой 25.09: «номер900-111_22 48» (слово и цифры вымышленные) — подчёркивание
    # вместо дефиса, на телефонной раскладке символов они в одном ряду. Цепочка
    # рвалась на «900-111» и «22 48», шесть и четыре цифры, — номера не было.
    "\u005f"  # подчёркивание
    "\u2010\u2011\u2012\u2013"  # дефис, неразрывный дефис, цифровое и короткое тире
    "\u2014\u2015"  # длинное тире и горизонтальная черта — автозамена «--» в Word и Заметках
    "\u2212\u2796"  # знак минуса (iOS по долгому нажатию) и эмодзи-минус
    "\u2043\u2e3a\u2e3b\u2e40"  # дефис-маркер, двойное/тройное тире, двойной дефис
    "\ufe58\ufe63\uff0d"  # малые и полноширинная чёрточки — азиатские раскладки
    "\u207b\u208b"  # надстрочный и подстрочный минус — рядом с «маленькими» цифрами
    "()."
    # Эмодзи-цифры «8️⃣9️⃣1️⃣…» (бой 13.09): за каждой цифрой стоят невидимые
    # знак вариации и обводка клавиши — внутри номера это разделители.
    "\ufe0f\u20e3"
)
_SEP = "[" + re.escape(_SEPARATOR_CHARS) + "]"

#: Цепочка «цифра, дальше цифры через разделители». Начинается с необязательного
#: плюса и ЗАКАНЧИВАЕТСЯ ЦИФРОЙ — отсюда даром получается правило 3 (хвостовая
#: точка в цепочку не входит).
#:
#: `[0-9]`, а не `\d`: в Python `\d` — это все десятичные цифры Юникода, включая
#: арабо-индийские. Такая «цифра» прошла бы длину и упёрлась бы в сравнение с
#: «78» уже после того, как мы решили, что нашли номер.
_RUN = re.compile(rf"[+]?[0-9](?:{_SEP}*[0-9])*")

#: Всё, что не цифра, — для подсчёта длины цепочки.
_NOT_DIGIT = re.compile(r"[^0-9]")

#: Шум в ОДНОЙ строке, введённой руками: те же разделители плюс любой пробельный
#: символ (перенос строки из буфера обмена). Здесь можно быть щедрее, чем в
#: `_SEP`: строка целиком обязана оказаться номером, и лишнее не с чем спутать.
#:
#: Собирается из `_SEPARATOR_CHARS`, а не переписывается рядом: ручной ввод и
#: разбор переписки обязаны давать одну строку (`test_phone_parse`), и второй
#: список чёрточек разошёлся бы с первым при первой же правке.
_NOISE = re.compile(rf"(?:\s|{_SEP})+")

_ONLY_DIGITS = re.compile(r"[0-9]+")


@dataclass(frozen=True)
class Found:
    """Один найденный номер: что показать оператору и где это было в тексте.

    `raw` нужен не для красоты. Экран показывает предложение «распознан телефон
    +7 900 111-22-40», и оператор обязан иметь возможность сверить его с тем,
    что человек написал на самом деле: «+7(900)1112240». Без исходной записи
    проверить нашу же догадку нечем.
    """

    #: Канонический вид, +7XXXXXXXXXX.
    value: str
    #: Ровно как написано в сообщении.
    raw: str
    #: Границы `raw` в исходном тексте — чтобы экран мог подсветить место.
    start: int
    end: int


def _from_digits(digits: str) -> str | None:
    """Цифры цепочки → ``+7XXXXXXXXXX``. Непохожее на номер — ``None``.

    ПРИНИМАЕМ РОВНО ДВЕ ФОРМЫ. Одиннадцать цифр с 7 или 8 — это и мобильный, и
    городской с кодом города: клиент, дающий рабочий телефон, имеет на это
    полное право. Десять цифр — только с девятки: «4951234567» неотличимо от
    мобильного, у которого потеряли первую цифру, и дописать к нему `+7`
    значило бы ПОКАЗАТЬ НЕ ТОТ НОМЕР.

    Иностранные номера не принимаются: у них другая длина, и приведение их к
    русской маске — тот же показ не того номера.
    """
    if len(digits) == 11 and digits[0] in "78":
        return "+7" + digits[1:]
    if len(digits) == 10 and digits[0] == "9":
        return "+7" + digits
    return None


#: Знаки, которые ПЕРЕД цепочкой означают «это порядковый номер чего-то»:
#: заказа, дома, квартиры, детали. «заказ№89001112240» — одиннадцать цифр,
#: начинающихся с восьмёрки, то есть по всем остальным признакам телефон;
#: спасает только этот знак. Найдено тестом, а не рассуждением.
#:
#: Сзади они ничего не значат («8 900 111 22 40 №2» — это телефон и номер
#: чего-то), поэтому проверяются только слева.
#:
#: Множество, а не строка: `"" in "№#"` в Python — ИСТИНА, и с строкой проверка
#: отвергала бы каждый номер, стоящий в самом начале текста. Поймано тестом на
#: «+7(900)1112240» ровно в тот момент, когда знак номера сюда добавили.
_NUMBER_SIGNS = frozenset("№#")


#: Сколько цифр разрешено ОСТАВИТЬ СЛЕВА, отрезая номер от хвоста цепочки.
#:
#: Четыре — это «31.08», «с 9 до 21», «кв 12». Пять и больше слева означает, что
#: перед нами не «контекст и номер», а неизвестно что, и трогать это нельзя.
_MAX_PREFIX_DIGITS = 4


def _phone_at_the_tail(run: str) -> tuple[str, int] | None:
    """Номер как ХВОСТ цепочки, если слева осталось короткое число.

    ⚠ ЗАЧЕМ ЭТО ВООБЩЕ ЕСТЬ (замер боевого корпуса 01.09). Правило длины берёт
    цепочку цифр и разделителей ЦЕЛИКОМ, и на этом теряются настоящие номера:
    «Звоните с 9 до 21 8 900 111 22 40» — четырнадцать цифр в одной цепочке.
    Автор модуля этот размен назвал вслух и принял осознанно.

    Замер показал его цену: за шестьдесят дней разбор нашёл 5067 телефонов и
    пропустил 207 похожих. У большинства пропусков форма одна и та же — маленькое
    число, разделитель, нормальный одиннадцатизначный номер: «21 8912…»,
    «31.08 8912…», «2. 8912…».

    ⚠ ТОЛЬКО СПРАВА, И ЭТО ГЛАВНОЕ ОГРАНИЧЕНИЕ. Брать номер как НАЧАЛО цепочки
    нельзя ни при каких условиях: «8-900-111-22-40-77» — тринадцать цифр, и
    отрезав справа «77», мы получили бы ровно тот номер, который автор модуля
    отказался угадывать по имени. Слева же отрезается контекст — время, дата,
    количество, — и он по природе короткий.

    ⚠ ОДИННАДЦАТЬ ЦИФР — ТОЖЕ «КОНТЕКСТ И НОМЕР» (бой 25.09). «кв 1 9001112246»:
    одна цифра квартиры и десятизначный мобильный — целиком не номер (не с 7/8),
    а хвост — номер. Здесь стояло «до одиннадцати включительно — вызывающий уже
    решил», и такие цепочки молчали.

    Возвращает канонический номер и смещение его начала внутри цепочки.
    """
    цифр_всего = len(_NOT_DIGIT.sub("", run))
    if цифр_всего <= 10:
        return None  # хвост за контекстом короче десяти цифр — не номер
    # Идём по позициям ПОСЛЕ разделителя: номер начинается с цифры, а слева от
    # него обязан стоять разделитель, а не цифра — иначе мы режем число пополам.
    for i in range(1, len(run)):
        if not run[i].isdigit() or run[i - 1].isdigit():
            continue
        слева = len(_NOT_DIGIT.sub("", run[:i]))
        if слева > _MAX_PREFIX_DIGITS:
            # Дальше слева только больше. `continue` здесь пересчитывал префикс
            # на каждой позиции: «12 12 12 …» в 60 тысяч знаков — шестнадцать
            # секунд на одно входящее (замер 25.09; подчёркивание в разделителях
            # сделало такую цепочку ещё и из «12_12_12…»).
            break
        if слева == 0:
            continue
        хвост = _NOT_DIGIT.sub("", run[i:])
        # Плюс открывает код страны: «+1 917 …», «+91 98…» — это чужой номер
        # целиком, и десять цифр за кодом — не наш мобильный без восьмёрки.
        # Отрезать код и дописать +7 значило бы показать не тот номер.
        if run.startswith("+") and len(хвост) == 10:
            continue
        value = _from_digits(хвост)
        if value is not None:
            return value, i
    return None


_СЛОВО_ДАЛЬШЕ = re.compile(r"\s*[-–]?\s*[А-ЯЁа-яё]")


def _phone_at_the_head(run: str) -> tuple[str, int] | None:
    """Номер как НАЧАЛО цепочки, если справа через ПРОБЕЛ осталось короткое число.

    ⚠ РАЗМЕН, КОТОРЫЙ АВТОР МОДУЛЯ ОТКАЗАЛСЯ ДЕЛАТЬ, — сделан в узком виде по
    корпусу 45 дней (12.09): «89001112247 25 лет», «89001112248 2 -я садовая
    14», «89001112247 5 этаж кв 12» — телефон, за ним ПРОБЕЛ, короткое число
    и СЛОВО (дом, этаж, возраст; слово проверяет вызывающий). Опасные случаи
    «8-900-111-22-40-77» (хвост дефисом) и «89001112240 77» (хвост в конце
    строки) остаются нерешаемыми — их мы по-прежнему не трогаем. Хвост — не
    длиннее :data:`_MAX_PREFIX_DIGITS` цифр, как и префикс у хвостового правила.

    Возвращает канонический номер и длину его записи внутри цепочки.
    """
    if len(_NOT_DIGIT.sub("", run)) <= 11:
        return None
    цифр = 0
    for i, ch in enumerate(run):
        if ch.isdigit():
            цифр += 1
        if цифр not in (10, 11) or not ch.isdigit():
            continue
        # «…79-85. 1 этаж» (бой 13.09): точка конца фразы перед пробелом — тоже
        # граница номера; сама точка в номер не входит.
        после = i + 1
        if после < len(run) and run[после] == ".":
            после += 1
        if после >= len(run) or not run[после].isspace():
            continue
        хвост_цифр = len(_NOT_DIGIT.sub("", run[после:]))
        if хвост_цифр == 0 or хвост_цифр > _MAX_PREFIX_DIGITS:
            continue
        value = _from_digits(_NOT_DIGIT.sub("", run[: i + 1]))
        if value is not None:
            return value, i + 1
    return None


def _looks_mobile(digits: str) -> bool:
    """Целый мобильный: одиннадцать цифр с 7/8 и девяткой или десять с девятки.

    Признак для мест, где сигнал слабее обычного (номер вплотную к слову, хвост
    словом): код или модель («37ключ2580», «Q70A») такой формы не бывает.
    """
    return (len(digits) == 11 and digits[0] in "78" and digits[1] == "9") or (
        len(digits) == 10 and digits[0] == "9"
    )


#: Числительные 0–99 словом: «+790011122 сорок» (скрин владельца 18.09) —
#: человек продиктовал хвост номера словом, как говорят вслух. Только именительный
#: падеж: «тридцати», «пятью» — это уже про что-то другое (минуты, рубли).
