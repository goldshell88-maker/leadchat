#: Слова-числа СРАЗУ за цепочкой цифр, на той же строке. Каждое слово обязано
#: кончаться там, где кончается (иначе «три» откусилось бы от «тридцати»);
#: между словами — пробелы и чёрточки, поэтому «сорок-два» и «сорок два» — одно
#: и то же 42, а «сорок, два» — нет: запятая, как и у цифр, рвёт цепочку.
#: Длинные слова в перечислении первыми — регулярка берёт первое подошедшее.
#:
#: ⚠ ТОЧКА И СКОБКИ МЕЖДУ СЛОВАМИ — НЕ РАЗДЕЛИТЕЛИ, хотя внутри цифровой
#: цепочки они разделители («8.900.111.22.40»). Цифры через точку люди пишут,
#: числительные — нет: «тридцать. Два этажа», «+7900111224. Два мастера» — это
#: конец предложения и начало следующего, и «Два» — не цифра номера. Взять её
#: значило бы придумать номер из первого слова следующей фразы. «тридцать
#: (два)» — вставка, и она оставляет вопрос «30 или 32?» без ответа: слово в
#: скобках увидит сторож :data:`_ЗА_СЛОВАМИ_ЧИСЛО` и промолчит.
_ЗНАКИ_МЕЖДУ_СЛОВАМИ = "".join(ch for ch in _SEPARATOR_CHARS if ch not in "().")
_МЕЖДУ_СЛОВАМИ = "[" + re.escape(_ЗНАКИ_МЕЖДУ_СЛОВАМИ) + "]"
_СЛОВО = "(?:" + "|".join(sorted(_ЧИСЛА_СЛОВОМ, key=len, reverse=True)) + ")(?![а-яё])"
_СЛОВА_ЗА_ЦИФРАМИ = re.compile(
    rf"{_МЕЖДУ_СЛОВАМИ}*({_СЛОВО}(?:{_МЕЖДУ_СЛОВАМИ}+{_СЛОВО})*)", re.IGNORECASE
)
_РАЗБИТЬ_НА_СЛОВА = re.compile(rf"{_МЕЖДУ_СЛОВАМИ}+")

#: Группа цифр СРАЗУ за числами словом — через пробел или чёрточку, как слово за
#: словом: «…двадцать два 45». Внутри группы — те же пробелы и чёрточки, без
#: точки и скобок: «…двадцать два 45. 3 этаж» — точка кончила номер, и «3» —
#: этаж, а не его цифра.
_ЦИФРЫ_ЗА_СЛОВАМИ = re.compile(rf"{_МЕЖДУ_СЛОВАМИ}+[0-9](?:{_МЕЖДУ_СЛОВАМИ}*[0-9])*")

#: Код страны словом впереди продиктованного номера: «Восемь 900 111 …».
_КОД_СЛОВОМ = frozenset({"семь", "восемь"})

#: Ещё число сразу ЗА словами — цифрой или словом, хоть через запятую: «тридцать,
#: два», «тридцать 5». Где кончается номер — 30 или 32? — не знает никто, и это
#: тот же вопрос, на который цифровая цепочка «…-77» отвечает молчанием.
#:
#: Запятая — ВНУТРИ необязательной группы вместе с разделителями за ней, а не
#: между двумя `_SEP*`: две соседние «звёздочки» вокруг необязательного знака
#: делят полосу разделителей всеми способами, и на 5000 пробелов за словом это
#: три секунды перебора, на 20000 — полминуты, в потоке входящих Авито (длина
#: сообщения не ограничена). С однозначным разбиением — миллисекунды.
_ЗА_СЛОВАМИ_ЧИСЛО = re.compile(rf"{_SEP}*(?:[,;]{_SEP}*)?(?:([0-9]+)|{_СЛОВО})", re.IGNORECASE)

#: Слово сразу за числительными, которое делает их КОЛИЧЕСТВОМ, а не цифрами
#: номера. Множитель меняет само число («две тысячи» — 2000, не 2), единица
#: счёта говорит, что считали не цифры: «два дня не отвечает», «три раза
#: звонил», «семь вечера», «тридцать пять человек». На цепочке в 9–10 цифр
#: (опечатка в номере) такое слово-число — обычное продолжение фразы, и взять
#: его цифрой значило бы позвонить постороннему. Список закрытый и по формам,
#: а не по основам: «раз» — единица, «разбитый» — нет.
_ЕДИНИЦЫ_СЧЁТА = frozenset(
    # множители
    "тысяча тысячи тысячу тысяч тыс сотня сотни сотню сотен сто сот "
    "миллион миллиона миллионов млн "
    # деньги
    "рубль рубля рублей руб "
    # время
    "секунда секунды секунду секунд минута минуты минуту минут мин час часа часов "
    "сутки суток день дня дней неделя недели неделю недель месяц месяца месяцев "
    "год года лет утра вечера ночи "
    # счёт
    "раз раза штука штуки штуку штук шт человек человека чел процент процента процентов "
    # расстояние, площадь, дом
    "метр метра метров км кв этаж этажа этажей подъезд подъезда".split()
)
_СЛОВО_ЗА_СЛОВАМИ = re.compile(rf"{_МЕЖДУ_СЛОВАМИ}+([а-яё]+)", re.IGNORECASE)


def _spoken_digits(words: str) -> str:
    """«тридцать два» → ``"32"``, «ноль три» → ``"03"``, «двадцать» → ``"20"``.

    Десятки с единицами за ними — одно двузначное число: «сорок два» — это 42,
    а не 402. Всё остальное — каждое слово само по себе, как его произносят
    цифрами: «ноль» — 0, «пять» — 5, «пятнадцать» — 15.
    """
    числа = [_ЧИСЛА_СЛОВОМ[w.lower()] for w in _РАЗБИТЬ_НА_СЛОВА.split(words)]
    out: list[str] = []
    i = 0
    while i < len(числа):
        n = числа[i]
        if n >= 20 and i + 1 < len(числа) and 1 <= числа[i + 1] <= 9:
            n += числа[i + 1]
            i += 1
        out.append(str(n))
        i += 1
    return "".join(out)


def _phone_with_spoken_tail(text: str, digits: str, end: int) -> tuple[str, int] | None:
    """Хвост номера словом: «+790011122 сорок» → +7 900 111-22-40.

    Скрин владельца 18.09: человек продиктовал последние цифры числительным, и
    цепочка из девяти цифр номером не считалась. Правило узкое намеренно:

    * в цепочке 9 или 10 цифр — то есть номер почти целый, недостаёт хвоста;
    * слова дополняют его РОВНО до одиннадцати — «+790011122 три ноль ноль»
      даёт двенадцать, и где там номер, не знает никто;
    * результат — мобильный (7/8 и девятка): у городского с продиктованным
      хвостом сигнал слишком слабый, а цена — звонок постороннему.

    «стоит 5000 тридцать» сюда не попадает: цифр четыре, не девять.
    Возвращает канонический номер и конец записи (со словами) в тексте.
    """
    if len(digits) not in (9, 10):
        return None
    m = _СЛОВА_ЗА_ЦИФРАМИ.match(text, end)
    if m is None:
        return None
    всего = digits + _spoken_digits(m.group(1))
    if (
        len(всего) != 11
        or not _looks_mobile(всего)
        or _ещё_число_за_словами(text, m.end())
        or _единица_за_словами(text, m.end())
    ):
        return None
    value = _from_digits(всего)
    return (value, m.end()) if value is not None else None


def _единица_за_словами(text: str, end: int) -> bool:
    """«две тысячи», «два дня», «тридцать пять человек» — количество, не номер.

    Смотрим только через пробел или чёрточку: «тридцать. Минут через пять» —
    точка кончила предложение, и «Минут» к числительному не относится.
    """
    m = _СЛОВО_ЗА_СЛОВАМИ.match(text, end)
    return m is not None and m.group(1).lower() in _ЕДИНИЦЫ_СЧЁТА


def _ещё_число_за_словами(text: str, end: int) -> bool:
    """«тридцать, два», «тридцать 5» — хвост сомнителен; «тридцать. 2 этаж» — нет.

    Та же граница, что у цифровой цепочки в :func:`_phone_at_the_head`: короткое
    число, за которым идёт СЛОВО, — это этаж, подъезд, возраст, и номер оно не
    продолжает. Число без слова или длиннее :data:`_MAX_PREFIX_DIGITS` цифр
    оставляет вопрос «где кончается номер» без ответа — молчим.
    """
    m = _ЗА_СЛОВАМИ_ЧИСЛО.match(text, end)
    if m is None:
        return False
    цифры = m.group(1)
    if цифры is not None and len(цифры) > _MAX_PREFIX_DIGITS:
        return True
    return not _СЛОВО_ДАЛЬШЕ.match(text, m.end())


def _что_перед(text: str, конец: int) -> tuple[int, str]:
    """Что стоит перед `конец` через пробелы и чёрточки: слово целиком или один
    знак (цифра, точка, запятая); в начале текста — пустая строка. И где оно
    начинается."""
    i = конец
    while i > 0 and text[i - 1] in _ЗНАКИ_МЕЖДУ_СЛОВАМИ:
        i -= 1
    j = i
    while j > 0 and text[j - 1].isalpha():
        j -= 1
    if j == i and i > 0:
        j -= 1
    return j, text[j:i]


def _phone_dictated(text: str, start: int, end: int) -> tuple[str, int, int] | None:
    """Номер цифрами вперемешку со словами: «Восемь 900 111 двадцать два 45».

    Бой 25.09 (цифры здесь вымышленные): первая цифра и середина номера
    продиктованы словами, как говорят вслух. :func:`_phone_with_spoken_tail`
    берёт слова только ХВОСТОМ за почти целой цепочкой; здесь они стоят и МЕЖДУ
    группами цифр, а цепочка — шесть цифр. Правила те же, что у хвоста словом, и
    по той же причине — звонок постороннему:

    * от цепочки вправо чередуются числа словом и группы цифр — через пробел или
      чёрточку; точка, запятая и перевод строки кончают номер;
    * итог — РОВНО одиннадцать цифр, мобильный с 7/8. Десять со словами не берём
      («900111224 ноль», 18.09): дописать +7 значило бы угадать ещё и потерянную
      семёрку. Кроме одного случая — семёрку или восьмёрку назвали словом
      впереди («Восемь 900 …»), и перед этим словом нет ни цифры, ни другого
      числительного: «сорок восемь» — это 48, «5 восемь» — неизвестно что;
    * за номером — ни числа без слова, ни единицы счёта (сторожа хвоста
      словом), и последняя группа цифр не приклеена к слову.

    Возвращает канонический номер и границы записи (со словами) в тексте.
    """
    цифры = _NOT_DIGIT.sub("", text[start:end])
    конец = end
    слов = 0
    while len(цифры) < 11:
        слова = _СЛОВА_ЗА_ЦИФРАМИ.match(text, конец)
        if слова is None:
            break
        цифры += _spoken_digits(слова.group(1))
        конец = слова.end()
        слов += 1
        if len(цифры) >= 11:
            break
        группа = _ЦИФРЫ_ЗА_СЛОВАМИ.match(text, конец)
        if группа is None:
            break
        цифры += _NOT_DIGIT.sub("", группа.group())
        конец = группа.end()
    начало = start
    if слов and len(цифры) == 10:
        начало_слова, слово = _что_перед(text, start)
        _, прежнее = _что_перед(text, начало_слова)
        if (
            слово.lower() in _КОД_СЛОВОМ
            and начало_слова + len(слово) < start
            and not прежнее.isdigit()
            and прежнее.lower() not in _ЧИСЛА_СЛОВОМ
        ):
            цифры = str(_ЧИСЛА_СЛОВОМ[слово.lower()]) + цифры
            начало = начало_слова
    if (
        not слов
        or len(цифры) != 11
        or not _looks_mobile(цифры)
        or (конец < len(text) and text[конец].isalnum())
        or _ещё_число_за_словами(text, конец)
        or _единица_за_словами(text, конец)
    ):
        return None
    value = _from_digits(цифры)
    return (value, начало, конец) if value is not None else None


def _знак_стоит_отдельно(ch: str) -> bool:
    return ch.isspace() or ch in ",;:()[]"


def _glued_to_a_word(text: str, start: int, end: int) -> bool:
    """Цепочка приклеена к слову или к знаку номера — значит это не телефон.

    Правило 1 из шапки модуля. Буква с любой стороны («37ключ2580», «Q70A»,
    «89001112240abc») и знак номера слева («заказ№89001112240») означают, что
    цифры описывают что-то другое: код, модель, порядковый номер.
    """
    before = text[start - 1] if start > 0 else ""
    after = text[end] if end < len(text) else ""
    if before in _NUMBER_SIGNS:
        # «#<номер> напишите мне в макс» (владелец 19.09): решётка как метка
        # перед ЦЕЛЫМ мобильным — телефон. Знак заказа стоит вплотную к слову
        # («заказ№89001112240») — тот по-прежнему отвергается: перед знаком
        # буква, а не начало текста или пробел.
        перед_знаком = text[start - 2] if start > 1 else ""
        отдельный_знак = перед_знаком == "" or _знак_стоит_отдельно(перед_знаком)
        return not (отдельный_знак and _looks_mobile(_NOT_DIGIT.sub("", text[start:end])))
    if not (before.isalpha() or after.isalpha()):
        return False
    # ⚠ ЦЕЛЫЙ ТЕЛЕФОН, ПРИКЛЕЕННЫЙ К СЛОВУ, — ВСЁ-ТАКИ ТЕЛЕФОН (корпус 45 дней,
    # 12.09): «89001112247Елена», «телефон89001112247.», «подьезд89001112247,»
    # — 11 из 84 нераспознанных. Код или модель («37ключ2580», «Q70A») таким
    # не бывает: у них цифр не одиннадцать и не десять с девятки.
    # Только кириллица: латиница за цифрами — модель («89001112240abc»).
    кириллица = all(
        not ch.isalpha() or ("а" <= ch.lower() <= "я" or ch.lower() == "ё")
        for ch in (before, after)
    )
    return not (_looks_mobile(_NOT_DIGIT.sub("", text[start:end])) and кириллица)


def _phone_after_a_glued_number(text: str, start: int, end: int) -> tuple[str, int] | None:
    """«кв1 9001112246»: к слову приклеен номер квартиры, а не телефон за ним.

    Бой 25.09 (цифры здесь вымышленные): цепочка «1 9001112246» приклеена слева
    к «кв», и правило 1 из шапки отвергало её ЦЕЛИКОМ — вместе с мобильным,
    отделённым пробелом. Приклеено здесь только первое число (квартира, дом —
    «д5»), а телефон — хвост цепочки, и отрезается он тем же правилом, что в
    «кв 12 9001112240».

    Узко, потому что сигнал слабее обычного: слева кириллица (латиница — это
    модель, «Q70 …»; знак номера «№1 …» по-прежнему отвергает всё), хвост —
    целый мобильный и сам ни к чему не приклеен.

    Возвращает канонический номер и смещение его начала внутри цепочки.
    """
    перед = text[start - 1].lower() if start > 0 else ""
    if not ("а" <= перед <= "я" or перед == "ё"):
        return None
    хвост = _phone_at_the_tail(text[start:end])
    if хвост is None:
        return None
    начало = start + хвост[1]
    if not _looks_mobile(_NOT_DIGIT.sub("", text[начало:end])) or _glued_to_a_word(
        text, начало, end
    ):
        return None
    return хвост


def normalize(raw: str | None) -> str | None:
    """ОДНА строка целиком → ``+7XXXXXXXXXX``. Непохожее на номер — ``None``.

    Это разбор ПОЛЯ ВВОДА, а не текста сообщения, и разница принципиальная. В
    поле человек вводит один номер; если он ввёл «89001112256 или 89001112257»,
    честный ответ — «не понимаю», а не молча взятый первый. Оператор увидел бы
    сохранённое значение, решил, что система его поняла, и позвонил по половине
    введённого. Поэтому здесь нет поиска внутри строки: всё, что осталось после
    снятия разделителей, обязано быть цифрами.
    """
    if raw is None:
        return None
    # Сначала шум, потом плюс: номер, скопированный из «Контактов» iOS, приходит
    # как «\u202a+7 915…\u202c», и плюс в нём стоит не первым символом.
    text = _NOISE.sub("", raw)
    if text.startswith("+"):
        text = text[1:]
    if not _ONLY_DIGITS.fullmatch(text):
        return None
    return _from_digits(text)


#: Надстрочные, подстрочные и полноширинные цифры → обычные. Бой 12.09: «⁷⁹00
#: ¹¹12 ²⁵⁹» (клавиатура телефона так пишет «маленькие» цифры) номером не
#: считалось; в 60 днях таких сообщений 17. Таблица — один символ в один,
#: поэтому смещения `raw` в исходном тексте не сдвигаются.
_ОБЫЧНЫЕ_ЦИФРЫ = str.maketrans("⁰¹²³⁴⁵⁶⁷⁸⁹₀₁₂₃₄₅₆₇₈₉０１２３４５６７８９", "0123456789" * 3)


def find_all(text: str | None) -> list[Found]:
    """Все российские номера в свободном тексте, в порядке появления.

    Пустой список — это ответ «номера здесь нет», а не «не смогли»: все три
    правила из шапки модуля отсекают молча и намеренно.
    """
    if not text:
        return []
    исходный = text
    text = text.translate(_ОБЫЧНЫЕ_ЦИФРЫ)
    out: list[Found] = []
    for match in _RUN.finditer(text):
        run = match.group()
        цифры = _NOT_DIGIT.sub("", run)
        начало = match.start()
        if not _glued_to_a_word(text, match.start(), match.end()):
            value = _from_digits(цифры)
        else:
            # Приклеенная цепочка — не номер, кроме мобильного ЗА приклеенным
            # числом: «кв1 9001112246» (бой 25.09).
            отдельно = _phone_after_a_glued_number(text, match.start(), match.end())
            if отдельно is None:
                continue
            value, сдвиг = отдельно
            run = run[сдвиг:]
            начало += сдвиг
        if value is None:
            хвост = _phone_at_the_tail(run)
            словом = _phone_with_spoken_tail(text, цифры, match.end()) if хвост is None else None
            if хвост is not None:
                value, сдвиг = хвост
                # `raw` обязан показывать ИМЕННО НОМЕР, а не всю цепочку: оператор
                # сверяет предложение системы с тем, что человек написал, и «21 8 900
                # 111 22 45» в качестве «как написано» сбивало бы эту сверку.
                run = run[сдвиг:]
                начало = match.start() + сдвиг
            elif словом is not None:
                # `raw` — вместе со словами: оператор сверяет «+7 900 111-22-40»
                # с тем, что написано, а написано «+790011122 сорок».
                value, конец = словом
                run = text[начало:конец]
            else:
                # Хвостовое число обязано продолжаться СЛОВОМ («25 лет», «5 этаж»,
                # «2 -я садовая»): «89001112240 77» в конце строки по-прежнему
                # не угадываем — там никто не знает, где кончается номер.
                голова = _phone_at_the_head(run)
                if голова is not None and _СЛОВО_ДАЛЬШЕ.match(text, match.end()):
                    value, длина = голова
                    run = run[:длина]
                else:
                    # «Восемь 900 111 двадцать два 45» (бой 25.09): слова между
                    # группами цифр; `raw` — со словами, как у хвоста словом.
                    диктовка = _phone_dictated(text, match.start(), match.end())
                    if диктовка is None:
                        continue
                    value, начало, конец = диктовка
                    run = text[начало:конец]
        # `raw` — из исходного текста: оператор сверяет с тем, что написано.
        out.append(
            Found(
                value=value,
                raw=исходный[начало : начало + len(run)],
                start=начало,
                end=начало + len(run),
            )
        )
    return out


def find_first(text: str | None) -> Found | None:
    """Первый номер в тексте — или ``None``.

    ПЕРВЫЙ, А НЕ «САМЫЙ ПОХОЖИЙ»: в «мой 8 915 …, жены 8 916 …» первым назван
    тот, по которому звонить. Второй не теряется — его видит :func:`find_all`,
    и он попадает в список кандидатов карточки.
    """
    found = find_all(text)
    return found[0] if found else None


#: Склейка реплик-кусков в `raw`: оператор видит, что номер собран из нескольких
#: сообщений, а не написан одним, — как цитата «пункт; адрес» у адреса.
_МЕЖДУ_РЕПЛИКАМИ = "; "


def is_fragment(text: str | None) -> bool:
    """Реплика целиком — кусок номера: «8900», «111-22», «+7 900».

    Только цифры и разделители номера (плюс — первым), и цифр меньше десяти:
    реплика с целым номером разбирается сама, и приклеить к ней соседнюю значило
    бы угадывать, где у двух чисел кончается номер.
    """
    if text is None:
        return False
    цифры = _NOISE.sub("", text).removeprefix("+")
    return bool(_ONLY_DIGITS.fullmatch(цифры)) and len(цифры) < 10


def from_fragments(parts: Sequence[str | None]) -> Found | None:
    """Номер, разорванный на реплики подряд: «8900» → «111» → «2247».

    Бой 25.09 (цифры здесь вымышленные): клиент отправил номер тремя
    сообщениями, и в каждом — обрывок короче номера, то есть по отдельности не
    номер ни один. `parts` — речь реплик клиента ПОДРЯД, от старой к текущей;
    какие реплики считать подряд (без ответа оператора между ними, в коротком
    окне), решает вызывающий (`inbound._номер_по_кускам`).

    Склеиваем с конца: текущая реплика обязана быть куском, первая же реплика
    не-кусок кончает склейку. Номер — РОВНО целый мобильный (десять цифр с
    девятки или одиннадцать с 7/8 и девяткой), без правил хвоста, головы и слов:
    сигнал здесь слабее, чем в одной реплике, а лишняя цифра — звонок
    постороннему. Нашли на десяти цифрах — дальше назад не смотрим; перебрали за
    одиннадцать — молчим.

    `raw` — куски через «; », `start`/`end` — границы в этой склейке.
    """
    куски: list[str] = []
    for часть in reversed(parts):
        if часть is None or not is_fragment(часть):
            break
        куски.insert(0, часть.strip())
        цифры = _NOT_DIGIT.sub("", "".join(куски))
        if len(цифры) > 11:
            return None
        value = normalize(" ".join(куски))
        if len(куски) > 1 and value is not None and _looks_mobile(цифры):
            raw = _МЕЖДУ_РЕПЛИКАМИ.join(куски)
            return Found(value=value, raw=raw, start=0, end=len(raw))
    return None
