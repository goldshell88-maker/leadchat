#: Имя ARQ-задачи. Живёт здесь, а не в воркере: ставит задачу конвейер приёма
#: (`services/inbound.py`), а импортировать ради имени модуль с моделью значило
#: бы тащить CTranslate2 в процесс api.
TRANSCRIBE_JOB = "transcribe_voice"
#: Разбор карточки по расшифровке (`workers/voice_card.py`) — отдельная задача,
#: а не хвост `transcribe_voice`: упади разбор внутри расшифровки, ARQ повторил
#: бы ЕЁ, а фаза 1 вышла бы на `done` — текст есть, номер в карточку не попал
#: бы никогда. У своей задачи свои попытки, своя область Sentry и своё имя.
VOICE_CARD_JOB = "voice_card_extract"
#: Имя задачи разбора по сообщению. Живёт рядом с :func:`transcribe_job_ids`
#: намеренно: замок `transcribing` в `workers/address_ask.py` спрашивает у ARQ
#: «в полёте ли расшифровка или её разбор» ПО ИМЕНАМ, и рожать их руками в
#: двух местах значило бы однажды разойтись — замок молчал бы, вопрос об адресе
#: ушёл бы тому, кто только что наговорил адрес.
VOICE_CARD_JOB_ID = "voicecard:{}"


def transcribe_job_ids(message_id: uuid.UUID) -> tuple[str, str]:
    """Имена задачи расшифровки: (живая постановка, ремонтная постановка).

    Ремонтное имя отдельное обязательно: под исходным ремонт наткнулся бы на
    дедупликацию с ещё живой первой задачей и тихо ничего не сделал.
    """
    return f"voice:{message_id}", f"voice:{message_id}:repair"


# --- состояния расшифровки ---------------------------------------------------
#
# ⚠ ПОЧЕМУ ПРИЗНАК СОСТОЯНИЯ НУЖЕН ОТДЕЛЬНО ОТ ТЕКСТА. Пустой текст сам по себе
# не отличает «ещё не начинали» от «расшифровали, а там тишина» и от «не
# вышло». Без этого различия повторный запуск невозможен: непонятно, чего ждать
# и что перезапускать, а диспетчер видит одинаковое ничто во всех трёх случаях.
#
# NULL в колонке — «не начинали». Отдельного значения под это нет намеренно:
# так у 317 тысяч уже лежащих строк состояние верное без переписывания таблицы.
СОСТОЯНИЕ_В_РАБОТЕ = "running"
СОСТОЯНИЕ_ГОТОВО = "done"
СОСТОЯНИЕ_НЕ_ВЫШЛО = "failed"
#: Запись длиннее порога: расшифровки не будет НИКОГДА, и это не отказ.
#: Отдельно от `failed`, потому что «попробуйте ещё раз» здесь — ложный совет:
#: повтор упрётся в тот же порог и потратит те же минуты процессора.
СОСТОЯНИЕ_СЛИШКОМ_ДЛИННАЯ = "too_long"

#: Состояния, из которых работу начинать не надо. `running` сюда НЕ входит:
#: разбор в `transcribe.py` — задачу мог убить таймаут ARQ, и тогда взяться за
#: неё снова обязана её же повторная попытка.
ЗАКОНЧЕННЫЕ = frozenset({СОСТОЯНИЕ_ГОТОВО, СОСТОЯНИЕ_СЛИШКОМ_ДЛИННАЯ})

# --- речь клиента: тело или расшифровка -------------------------------------
#
# ⚠ ОДИН ИСТОЧНИК НА ВСЮ ЦЕПОЧКУ РАЗБОРА КАРТОЧКИ. У голосового `body = None`,
# а разбор телефона и адреса читал только тело: расшифровка приезжала минуты
# спустя в `voice_transcript`, и её не читал никто (замер 19.09 за 30 дней: 708
# расшифровок `done`, строк адреса от них — 0; владелец: «не распознал номер из
# аудио»). Правило «что считать речью клиента» живёт здесь в двух видах —
# Python для одной реплики и SQL для выборок соседних реплик — и расходиться
# им нельзя: соседи читали бы одно, сама реплика — другое (класс
# dva-puti-raznyi-schet). Сторож пары — `test_voice_card_1909`.


@dataclass(frozen=True, slots=True)
class Speech:
    """Речь клиента в одной реплике — то, что читают правила карточки."""

    #: Текст как есть, без обрезки: `phone_parse.find_all` отдаёт смещения по
    #: переданной строке, и подсказка `hint_word` ищет по ТОЙ ЖЕ строке.
    #: None — речи нет (пустое тело, расшифровки нет или не вышла).
    text: str | None
    #: Текст взят из расшифровки, а не из тела. По нему разбор подписывает
    #: строку источником `voice`: доказательство машинное, оператор сверяет со
    #: звуком.
    spoken: bool


def speech_of(body: str | None, transcript: str | None, status: str | None) -> Speech:
    """Тело, иначе расшифровка голосового в состоянии ГОТОВО, иначе ничего.

    Тело побеждает: Авито не присылает голосовое с текстом, а если пришлёт —
    написанное человеком надёжнее машинного. Расшифровка берётся ТОЛЬКО при
    `done`: у `running`/`failed`/`too_long` текста в колонке нет по контракту
    `transcribe._записать_исход`, и проверка состояния держит этот контракт
    явно, а не надеется на него.
    """
    if body is not None and body.strip():
        return Speech(body, False)
    if status == СОСТОЯНИЕ_ГОТОВО and transcript is not None and transcript.strip():
        return Speech(transcript, True)
    return Speech(None, False)


def speech_sql() -> sa.ColumnElement[str | None]:
    """То же, что :func:`speech_of`, условием SQL — для выборок соседних реплик.

    Пробелы проверяются только в УСЛОВИИ (как `.strip()` в `speech_of`), наружу
    идёт исходная строка. `trim`, не `btrim`: стенд тестов — SQLite, там
    `btrim` нет; в Postgres `trim(x)` = `btrim(x)`. У исходящих расшифровки не
    бывает — для них первая ветвь `case` отдаёт тело.
    """
    from app.models import Message

    def непустое(col: Any) -> sa.ColumnElement[bool]:
        return sa.func.nullif(sa.func.trim(col), "").is_not(None)

    return sa.case(
        (непустое(Message.body), Message.body),
        (
            (Message.voice_transcript_status == СОСТОЯНИЕ_ГОТОВО)
            & непустое(Message.voice_transcript),
            Message.voice_transcript,
        ),
    )


#: ⚠ ОКНО ВМЕСТО РАВЕНСТВА ПО ДАТЕ. Дата едет в задаче ради ОДНОГО — чтобы
#: PostgreSQL искал строку в одной партиции из 28, а не во всех. Для этого
#: годится и диапазон, а он вдобавок переживает любое округление на пути
#: «объект -> pickle -> драйвер -> хранилище».
ОКНО_ПОИСКА = timedelta(seconds=1)


async def load_message(
    db: AsyncSession, message_id: uuid.UUID, created_at: datetime
) -> Message | None:
    """Сообщение по `(id, created_at ± ОКНО_ПОИСКА)` — так его ищут обе задачи
    голоса (расшифровка и разбор карточки). `db.get(Message, id)` по одному id
    падает: первичный ключ секционированной таблицы составной."""
    from app.models import Message

    return (
        await db.execute(
            sa.select(Message)
            .where(
                Message.id == message_id,
                Message.created_at >= created_at - ОКНО_ПОИСКА,
                Message.created_at <= created_at + ОКНО_ПОИСКА,
            )
            .limit(1)
        )
    ).scalar_one_or_none()


#: Приставка, которой конвейер приёма помечает идентификатор записи
#: (`adapter._attachment_id`): в `media_id` лежит `avito_voice_<id>`, а Авито
#: ждёт голый `<id>`.
_ПРИСТАВКА = "avito_voice_"


def voice_id_of(attachments: list[Any] | None) -> str | None:
    """Идентификатор записи из вложений сообщения или None.

    ⚠ ОДНО МЕСТО НА ВСЮ СИСТЕМУ. Такой же разбор был написан внутри ручки
    `GET /messages/{id}/voice`; теперь оттуда зовётся эта функция. Знание о том,
    как голосовое лежит в `attachments` (вид `voice`, приставка в `media_id`),
    обязано жить в одном месте: разойдись эти два разбора — ручка отдавала бы
    запись, а расшифровка молчала бы, и виноватого не было бы видно нигде.

    Первое голосовое, а не все: Авито кладёт в сообщение одну запись, и
    складывать несколько расшифровок в одну колонку было бы враньём о том,
    какая из них чья.
    """
    for item in attachments or []:
        if not isinstance(item, dict) or item.get("avito_type") != "voice":
            continue
        сырой = str(item.get("media_id") or "")
        ид = сырой.removeprefix(_ПРИСТАВКА)
        if ид:
            return ид
    return None


def has_voice(attachments: list[Any] | None) -> bool:
    """Есть ли в сообщении голосовое — без разбора идентификатора."""
    return voice_id_of(attachments) is not None


def has_voice_sql(db: AsyncSession) -> sa.ColumnElement[bool]:
    """То же, что :func:`has_voice`, но условием SQL — для отбора по таблице.

    ⚠ ЗАЧЕМ ВООБЩЕ УСЛОВИЕ В SQL. Состояние расшифровки NULL стоит у КАЖДОЙ
    строки, к которой не приступали, — у всех 317 тысяч текстовых тоже. Отбери
    досчёт «NULL не старше месяца» и проверь вложение уже в Python — порция из
    двадцати уходила бы на пустышки, а до голосовых очередь не доходила бы
    никогда.

    Живёт здесь, рядом с :func:`voice_id_of`, по той же причине: знание о
    том, как голосовое лежит в `attachments` (`avito_type='voice'`), обязано
    быть в одном месте. Разойдись SQL и разбор — досчёт брал бы одно, а задача
    расшифровки отказывалась бы от него как «не голосовое», и виноватого не
    было бы видно нигде.

    На PostgreSQL — вхождение `@>` по jsonb (как `_has_tag` в `conversations`
    для тегов); на SQLite юнит-тестов jsonb нет, и условие вырождается в
    поиск подстроки по сериализованному JSON. Оба грубее :func:`voice_id_of`
    (пустой `media_id` они пропустят), и это намеренно: точный разбор делает
    сама задача, а здесь достаточно отсечь текстовые.
    """
    from sqlalchemy.dialects.postgresql import JSONB

    from app.models import Message

    if db.get_bind().dialect.name == "postgresql":
        return sa.cast(Message.attachments, JSONB).contains([{"avito_type": "voice"}])
    # SQLite хранит JSON строкой через `json.dumps`: двоеточие с пробелом.
    return sa.cast(Message.attachments, sa.Text).like('%"avito_type": "voice"%')


async def enqueue_transcribe(
    redis: Redis,
    message_id: uuid.UUID,
    created_at: datetime,
    *,
    повтор: bool = False,
    отложить: timedelta | None = None,
) -> bool:
    """Поставить расшифровку в очередь. Строго после commit'а (08 §8.1).

    ⚠ ДАТА ЕДЕТ ВМЕСТЕ С ИДЕНТИФИКАТОРОМ. `messages` разбита на помесячные
    партиции, первичный ключ составной `(id, created_at)`. Без даты задача
    искала бы строку во всех 28 партициях; с датой — ровно в одной.

    ⚠ ИМЯ ЗАДАЧИ ДЕДУПЛИЦИРУЕТ ПОСТАНОВКУ. Один и тот же вебхук Авито доставляет
    повторно (at-least-once), а сверка истории перечитывает канал; без имени
    одна запись расшифровывалась бы столько раз, сколько её увидели, и каждый
    раз занимала бы единственное место в очереди расшифровок.

    Не бросает: расшифровка — удобство, и терять из-за неё живой вебхук клиента
    нельзя. Отказ виден строкой в журнале, сообщение при этом уже в базе.

    ⚠ ВОЗВРАЩАЕТ, ВСТАЛА ЛИ ЗАДАЧА НА САМОМ ДЕЛЕ. ARQ отказывает молча — при
    занятом имени `enqueue_job` отдаёт None, не бросая ничего. Ремонтному
    прогону этого различия не хватало бы: он рапортовал бы «перезапустил
    двадцать», не перезапустив ни одной.

    :param повтор: ремонтная постановка. Меняет имя задачи, и это обязательно:
        под исходным именем ремонт наткнулся бы на дедупликацию с ещё живой
        первой задачей и тихо ничего не сделал.
    :param отложить: через сколько задаче стартовать. Досчёт ставит порцию
        сразу, а считает воркер по одной за замком: стартуй все двадцать разом —
        и хвост порции не дождался бы замка ни за одну из трёх попыток
        (120 с ожидания каждая) и лёг бы обратно в очередь. Разнос по времени
        убирает саму давку, а не её последствия.
    """
    from arq.connections import ArqRedis

    from app.services.messages import as_arq

    живое, ремонтное = transcribe_job_ids(message_id)
    имя = ремонтное if повтор else живое
    try:
        job = await ArqRedis.enqueue_job(
            as_arq(redis),
            TRANSCRIBE_JOB,
            message_id,
            created_at,
            _job_id=имя,
            _defer_by=отложить,
        )
    except Exception:  # noqa: BLE001 — расшифровка не стоит упавшего вебхука
        log.warning("voice.enqueue_failed", message_id=str(message_id))
        return False
    return job is not None


async def enqueue_voice_card(redis: Redis, message_id: uuid.UUID, created_at: datetime) -> bool:
    """Поставить разбор карточки по расшифровке. Строго после commit'а ГОТОВО.

    Тот же образец, что у :func:`enqueue_transcribe`: дата едет ради одной
    партиции; имя `voicecard:{id}` дедуплицирует постановку (повтор задачи
    расшифровки после ГОТОВО перепоставляет разбор — второй не нужен); не
    бросает — упади здесь Redis, задача расшифровки повторилась бы впустую
    (фаза 1 → `done` → выход), а текст уже в базе. Отказ виден строкой
    `voice.card_enqueue_failed`; сеть под ним — `cli backfill-cards`.

    Возвращает, встала ли задача на самом деле (при занятом имени ARQ отдаёт
    None молча).
    """
    from arq.connections import ArqRedis

    from app.services.messages import as_arq

    try:
        job = await ArqRedis.enqueue_job(
            as_arq(redis),
            VOICE_CARD_JOB,
            message_id,
            created_at,
            _job_id=VOICE_CARD_JOB_ID.format(message_id),
        )
    except Exception:  # noqa: BLE001 — разбор карточки не стоит повторной расшифровки
        log.warning("voice.card_enqueue_failed", message_id=str(message_id))
        return False
    return job is not None
