"""Комментарий заявки: проблема + что озвучили клиенту + ссылка на отзыв.

ОБРАЗЕЦ ЖИВОЙ ЗАЯВКИ (КП №1234567, разобрана 13 августа), три строки; номер КП и
ссылка здесь вымышленные:

    перестал работать интернет , роутер горит красным
    Выезд и диагностика 1000 рублей, в случае ремонта бесплатно
    https://clc.li/AbCdE

Первая — что случилось у клиента, его словами. Вторая — ЧТО МЫ ЕМУ ПООБЕЩАЛИ:
цену выезда, «диагностика бесплатно», «от 800». Третья — ссылка, по которой
просим оставить отзыв.

ПОЧЕМУ ВТОРАЯ СТРОКА ВАЖНЕЕ ПЕРВОЙ. Мастер приезжает и называет цену. Если она
разойдётся с тем, что клиенту сказали в переписке, спор будет на пороге, и
проиграет его мастер: клиент помнит цифру, а мастер её не видел. Озвучка в
комментарии — это то, чем мастер защищён.

ПОЧЕМУ ИЗВЛЕЧЕНИЕ, А НЕ ПОЛЕ ДЛЯ ОПЕРАТОРА. Владелец выбрал автоматический
сбор: лишнее поле на каждую заявку заполняют первую неделю, а потом перестают, и
комментарий становится пустым у всех. Здесь же цена уже сказана в переписке —
её достаточно найти.

⚠ ЭТО ПОДСКАЗКА, А НЕ ИСТИНА. Разбор текста ошибается: цена бывает в вопросе
клиента («а если дороже 2000?»), в отказе («дешевле 1500 не берёмся»), в чужой
цитате. Поэтому собранное показывается человеку до отправки заявки и правится —
так решил владелец, и так же сделано с распознаванием телефонов.
"""

from __future__ import annotations

import re

#: Признаки того, что в реплике НАЗВАНА цена или условие выезда.
#:
#: Ищем не «любое число», а число рядом со словом о деньгах или о выезде: в
#: переписке про ремонт цифры повсюду — модель техники, год, этаж, время. Без
#: этой привязки в озвучку попало бы «роутер TP-Link 841» как цена.
_ЦЕНА = re.compile(
    r"""
    (?:
        \d[\d\s]{2,}\s*(?:р\b|руб|₽)        # 1000 руб / 8 900 ₽
      | (?:от|до)\s+\d[\d\s]{2,}            # от 800 / до 2500
    )
    """,
    re.IGNORECASE | re.VERBOSE,
)

#: Условия, которые звучат без цифр и всё равно являются обещанием.
_УСЛОВИЯ = re.compile(
    r"(выезд\w*\s+бесплатн\w*"
    r"|диагностик\w*\s+бесплатн\w*"
    r"|бесплатн\w*\s+(?:выезд|диагностик)\w*"
    r"|в\s+случае\s+ремонта\s+бесплатн\w*"
    r"|без\s+предоплат\w*)",
    re.IGNORECASE,
)

#: Слова, после которых цифра почти наверняка НЕ цена. Проверяются в той же
#: реплике: «перезвоню после 800» — это время, а не рубли.
_НЕ_ЦЕНА = re.compile(r"(этаж|подъезд|кварти|модель|год\w*\s+выпуск|серийн)", re.IGNORECASE)

#: Потолок длины строки озвучек. Комментарий читает мастер в машине с телефона;
#: три экрана текста он не прочтёт, а нужное потеряется.
MAX_OFFERS = 400
MAX_PROBLEM = 400


def _clean(text: str) -> str:
    """Схлопнуть переносы и лишние пробелы: комментарий — строка, а не абзац."""
    return re.sub(r"\s+", " ", (text or "").replace(" ", " ")).strip()


def find_offers(outgoing: list[str]) -> list[str]:
    """Реплики НАШЕЙ стороны, в которых названа цена или условие.

    Порядок сохраняется: клиенту называли цены по ходу разговора, и последняя
    не отменяет первую — мастеру нужны все, чтобы понимать, о чём договорились.
    Повторы убираются: одну и ту же фразу оператор часто шлёт дважды.
    """
    found: list[str] = []
    seen: set[str] = set()
    for raw in outgoing:
        line = _clean(raw)
        if not line:
            continue
        имеет_цену = bool(_ЦЕНА.search(line)) and not _НЕ_ЦЕНА.search(line)
        if not (имеет_цену or _УСЛОВИЯ.search(line)):
            continue
        key = line.lower()
        if key in seen:
            continue
        seen.add(key)
        found.append(line)
    return found


def build(
    *,
    problem: str | None,
    outgoing: list[str],
    review_url: str | None,
    white: bool = False,
) -> str:
    """Собрать комментарий заявки — ровно тем же порядком, что в живой заявке.

    Пустые части просто пропускаются: комментарий без ссылки лучше, чем заявка,
    не созданная из-за отсутствия ссылки.

    ⚠ Две добавки — требования регламента заявок (пакет владельца 15.08):
    «Создана с чата» обязательна для заявок без звонка — все наши такие
    (п. 5 регламента), а у партнёра 723 ссылка подписывается «Белый акк …»
    и в конец идёт строка «БЕЛАЯ ЗАЯВКА» (п. 3). За отсутствие — штрафы.
    """
    lines: list[str] = []

    problem_line = _clean(problem or "")
    if problem_line:
        lines.append(problem_line[:MAX_PROBLEM])

    offers = find_offers(outgoing)
    if offers:
        # Через «; », а не с новой строки на каждую: у мастера в списке заявок
        # видно две-три первые строки, и цена обязана попасть в них.
        joined = "; ".join(offers)
        lines.append(joined[:MAX_OFFERS])

    lines.append("Создана с чата")

    url = (review_url or "").strip()
    if url:
        lines.append(("Белый акк " + url) if white else url)
    if white:
        lines.append("БЕЛАЯ ЗАЯВКА")

    return "\n".join(lines)
