def format_place(hit: PlaceHit, place: Place) -> str:
    """«массив Южный, деревня Большая Дубрава, Гатчинский район»."""
    куски: list[str] = []
    if hit.kind == "street":
        # «ул Горького, Королёв»: улица, пункт, город — без района, он лишний.
        куски.append(hit.name)
        if hit.settlement:
            куски.append(hit.settlement)
        if hit.city and _норм(hit.city) != _норм(hit.settlement):
            куски.append(hit.city)
        return ", ".join(к for к in куски if к)
    if hit.kind == "area":
        куски.append(hit.name)
        if hit.settlement:
            тип = place.settlement_type if place.settlement else None
            куски.append(f"{тип} {hit.settlement}" if тип else hit.settlement)
    else:
        куски.append(hit.name)
    if (
        hit.city
        and _норм(hit.city) not in {_норм(к) for к in куски}
        and not (hit.settlement and _норм(hit.city) == _норм(hit.settlement))
    ):
        куски.append(hit.city)
    if hit.district:
        куски.append(hit.district)
    return ", ".join(к for к in куски if к)


class GeocodeError(Exception):
    """Карта не ответила по-человечески. Без URL и тела ответа — в них адрес.

    `kind`: `network` — таймаут/обрыв, повтор уместен; `blocked` — 403/429 или
    HTML вместо JSON, повторять бесполезно и вредно (политика OSM);
    `bad_response` — JSON не той формы; `limit` — НАШ суточный потолок выбран
    (воркер занимает место до похода), провайдер ни при чём.
    """

    def __init__(self, provider: str, kind: str, status: int | None = None) -> None:
        super().__init__(f"{provider}: {kind}" + (f" ({status})" if status else ""))
        self.provider = provider
        self.kind = kind
        self.status = status


