#: Слова строки карты, не различающие дом: «г»/«д» перед именем и тип
#: пункта — Яндекс пишет «посёлок Заречный», DaData — «Заречный».
_ШУМ_СТРОКИ_КАРТЫ = frozenset(
    "г город д дом поселок посёлок пос пгт рп село деревня дер станица хутор аул".split()
)
#: Кусок строки карты с таким словом — страна или регион: «Хабаровский край»,
#: «Московская обл», «Россия» — в ключ не входит целиком.
_РЕГИОН_В_СТРОКЕ_КАРТЫ = frozenset(
    "россия рф край область обл респ республика ао округ городской муниципальный район р-н".split()
)


def formatted_key(formatted: str | None) -> frozenset[str]:
    """Ключ дома по строке карты, одинаковый у разных карт.

    Яндекс пишет «Луговая улица, 14, Хабаровск», DaData — «ул Луговая, 14,
    Хабаровск» (бой 14.09: два предложения одного дома в карточке). Тип улицы
    сводится к полному слову, порядок слов в куске не важен, страна и регион
    отбрасываются; «улица Ленина, 5» и «проспект Ленина, 5» остаются разными.
    """
    куски: set[str] = set()
    for кусок in (formatted or "").split(","):
        кусок = кусок.strip()
        if кусок[:1].isdigit():
            # Дом — ключом дома: «12Е» ≠ «12» (ревью 14.09: `_слова` срезала
            # литеру «е» как порядковое окончание), «5к2» = «5 к 2».
            куски.add(house_key(re.sub(r"^(?:д|дом)\.?\s*", "", кусок.lower())))
            continue
        слова_куска = _слова(кусок)
        if any(w in _РЕГИОН_В_СТРОКЕ_КАРТЫ for w in слова_куска):
            continue
        слова = sorted(_ТИПЫ_УЛИЦ.get(w, w) for w in слова_куска if w not in _ШУМ_СТРОКИ_КАРТЫ)
        if слова:
            куски.add(" ".join(слова))
    return frozenset(куски)


def _основа(слово: str) -> str:
    for окончание in _ОКОНЧАНИЯ:
        if слово.endswith(окончание) and len(слово) - len(окончание) >= 4:
            return слово[: -len(окончание)]
    return слово


def _основа_совпала(а: str, б: str) -> bool:
    """Одно слово в двух ФОРМАХ — не однокоренные слова.

    «Первомайской» и «Первомайская» — да; «Советов» и «Советская», «Пушкина» и
    «Пушкинская», «Октября» и «Октябрьская» — нет: это разные улицы (находка
    ревью 11.09; первая редакция сравнивала пять первых букв и пускала их).
    Срезается только окончание, основа обязана совпасть целиком.
    """
    if а == б:
        return True
    if len(а) < 4 or len(б) < 4:
        return False
    оа, об = _основа(а), _основа(б)
    if оа == об:
        return True
    # ⚠ ОПЕЧАТКА И СОКРАЩЕНИЕ (просьба владельца 11.09: «люди пишут адреса
    # сокращённо или с ошибками»). Одна буква не там в длинном слове
    # («Звенигародская») и обрубок от шести букв («Звенигор») — то же слово.
    # Короткие слова опечаток не получают: «Мира»/«Миру», «Ленин»/«Ленина»
    # против «Ленинградская» — по-прежнему только целиком.
    # Пропущенная буква («Презжая» → «Проезжая», стенд 13.09): короче основа
    # на одну, но обе не короче пяти.
    # Две правки — только в длинных основах: от десяти букв любые, от восьми —
    # при равной длине (перестановка и замена: «Амнудсина» → «Амундсена», бой
    # 13.09), чтобы «Строителей» и «Строительная» не стали одной улицей.
    длинные = min(len(оа), len(об)) >= 10 or (min(len(оа), len(об)) >= 8 and len(оа) == len(об))
    if (
        len(оа) >= 5
        and len(об) >= 5
        and max(len(оа), len(об)) >= 6
        and _расстояние(оа, об) <= (2 if длинные else 1)
    ):
        return True
    короче, длиннее = sorted((а, б), key=len)
    return len(короче) >= 6 and длиннее.startswith(короче)


def _расстояние(а: str, б: str) -> int:
    """Расстояние Дамерау—Левенштейна: правок между словами, перестановка
    соседних букв («Амнудсена» ← «Амундсена») — одна правка, как в жизни."""
    if а == б:
        return 0
    d = [[0] * (len(б) + 1) for _ in range(len(а) + 1)]
    for i in range(len(а) + 1):
        d[i][0] = i
    for j in range(len(б) + 1):
        d[0][j] = j
    for i in range(1, len(а) + 1):
        for j in range(1, len(б) + 1):
            цена = 0 if а[i - 1] == б[j - 1] else 1
            d[i][j] = min(d[i - 1][j] + 1, d[i][j - 1] + 1, d[i - 1][j - 1] + цена)
            if i > 1 and j > 1 and а[i - 1] == б[j - 2] and а[i - 2] == б[j - 1]:
                d[i][j] = min(d[i][j], d[i - 2][j - 2] + 1)
    return d[len(а)][len(б)]


def _слово_есть(слово: str, среди: list[str]) -> bool:
    return any(_основа_совпала(слово, w) for w in среди)


def settlement_seen(settlement: str, hits: list[GeoHit]) -> bool:
    """Хоть один ответ карты называет пункт клиента — в поле пункта, города
    или массива."""
    пункт = _норм(settlement)
    return any(_пункт_назван(пункт, _места_ответа(h)) for h in hits)


def _места_ответа(h: GeoHit, *, с_массивом_улицей: bool = True) -> list[str]:
    """Слова всех мест ответа карты: пункт, город, массив. Названный клиентом
    пункт может лежать в любом из них: «Гурульба» — город, «ДНТ Лесная-Поляна»
    — массив, «Ивняково» — пункт (18.09).

    Массив с участками бывает у карты и УЛИЦЕЙ (25.09, Ангарск: DaData пишет
    «тер. СНТ …» элементом улицы внутри квартала, а в пункте ответа — номер
    квартала). Такая улица — тоже место: без неё СНТ клиента «не находилось»,
    и дом в самом городе объявления уходил вариантом «есть в области».
    `с_массивом_улицей=False` — у точки второй карты (`precise_point`): СНТ
    одного имени в области десятки, и участок-тёзка, названный второй картой
    только улицей, дал бы чужую точку с пометкой «точная»."""
    места = _слова(h.settlement) + _слова(h.city) + _слова(h.area)
    улица = _слова(h.street) if с_массивом_улицей else []
    if any(w in _ТИПЫ_МАССИВА_С_УЧАСТКАМИ for w in улица):
        места += улица
    return места


def _без_дефисов(слова: list[str]) -> list[str]:
    """«Лесная-Поляна» ↔ «Лесная поляна» (18.09, Улан-Удэ): дефис у карты, пробел у
    клиента — те же два слова."""
    return [ч for w in слова for ч in w.split("-") if ч]


def _пункт_назван(пункт: str, среди: list[str]) -> bool:
    """«Новое Заозерье» против слов карты: каждое слово пункта есть среди них.
    Сравнение целой фразой с одним словом не сходилось никогда — пункты из
    двух слов (бой 12.09) карта «не подтверждала».

    Тип массива в имени («СНТ Светлый», «ДНТ Лесная поляна») — не слово имени:
    карта пишет его по-своему («тер. СНТ», «днп ДНТ») или не пишет вовсе.
    """
    слова = _без_дефисов([w for w in пункт.split() if w and w not in _ТИПЫ_МАССИВА])
    if not слова:
        return False
    среди = _без_дефисов(среди)
    if all(_слово_есть(w, среди) for w in слова):
        return True
    # «ЖК Большое Путилково» против «Путилково» (бой 13.09): имя комплекса —
    # пункт плюс слово; хватает совпадения последнего длинного слова.
    return len(слова) >= 2 and len(слова[-1]) >= 5 and _слово_есть(слова[-1], среди)


