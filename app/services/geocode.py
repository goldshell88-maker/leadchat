def _без_скобок(s: str | None) -> str:
    return _В_СКОБКАХ.sub("", s or "").strip()


def _норм(s: str | None) -> str:
    """Нижний регистр, ё→е, знаки — в пробелы, пробелы схлопнуты; скобки — вон."""
    т = _без_скобок(s).lower().replace("ё", "е")
    т = re.sub(r"[^0-9a-zа-я\-]+", " ", т)
    return re.sub(r"\s+", " ", т).strip()


#: «42-й квартал», «3-я линия», «1-ая Советская»: числительное с окончанием —
#: то же число. Бой 12.09 (Ангарск): клиент писал «42 квартал 7», карта
#: отвечала «42-й квартал», и улица «не подтверждалась».
_ПОРЯДКОВОЕ = re.compile(r"^(\d+)-?(?:й|я|ая|ый|ой|ий|ое|е|го|му)$")


def _слова(s: str | None) -> list[str]:
    out: list[str] = []
    for w in _норм(s).split():
        w = w.strip("-")
        if not w:
            continue
        m = _ПОРЯДКОВОЕ.match(w)
        out.append(m.group(1) if m else w)
    return out


def expand_street(street: str) -> str:
    """«ул звенигородская» → «улица звенигородская»: карте нужен полный тип."""
    слова = [w for w in re.split(r"\s+", (street or "").strip()) if w]
    out: list[str] = []
    for w in слова:
        ключ = w.lower().replace("ё", "е").rstrip(".")
        out.append(_ТИПЫ_УЛИЦ.get(ключ, w.rstrip(".") if ключ in _ТИПЫ_УЛИЦ else w))
    return " ".join(out)


def house_key(house: str | None) -> str:
    """Ключ сравнения дома: «12 корпус 2», «12 к 2», «12к2» — одно и то же.

    ⚠ ЛИТЕРА И КОРПУС ВХОДЯТ В КЛЮЧ. Именно их разбор терял до 11.09, и карта
    подтверждала СОСЕДНИЙ дом — подтверждение выглядело безупречно.
    """
    т = (house or "").lower().replace("ё", "е")
    # «23/4» и «23к4» — один дом: дробь в чате означает корпус (Комсомольск,
    # 12.09: карта отдаёт «23 к 4», клиент пишет «23/4»).
    т = re.sub(r"\s*/\s*(?=\d)", "к", т)
    т = re.sub(r"\b(?:корпус|корп|кор|к)\.?\s*", "к", т)
    т = re.sub(r"\b(?:строение|стр|с)\.?\s*(?=\d)", "с", т)
    т = re.sub(r"\b(?:литера|лит)\.?\s*", "", т)
    т = re.sub(r"[\s.]+", "", т)
    # «07» и «7» — один дом (18.09, Набережные Челны: «31/07» — комплекс 31,
    # дом 7; карта нулей впереди не пишет).
    return re.sub(r"^0+(?=\d)", "", т)


