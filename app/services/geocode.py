@dataclass(frozen=True, slots=True)
class Evidence:
    """Всё, что воркер собрал по строке до решения. Сеть сюда не входит."""

    status: str
    parsed: Parsed
    city: City | None
    #: Ответы, по которым вынесен `status` (для правил про неоднозначность).
    hits: list[GeoHit]
    #: Все ответы по городу с именем карты, DaData первой (`по_городу` воркера):
    #: улица у DaData при `house_missing` до `hits` не доходит. Это и улика
    #: спора города об улице (`city_disputes_street`).
    city_hits: list[tuple[list[GeoHit], str]]
    #: Всё, что ответила область; пусто — не искали. Имя карты области —
    #: `region_provider` (DaData, реже Яндекс).
    region_hits: list[GeoHit]
    variants: list[dict[str, Any]]
    city_point: tuple[float, float] | None
    #: Пункты из соседних реплик (`settlement_hints`).
    hints: list[str]
    hit: GeoHit | None = None
    #: `status`/`hit` — поиском по стране.
    country: bool = False
    region_provider: str | None = None
    #: Сетевой ответ на дом «N» для «N/M» с именем карты; None — не спрашивали.
    fraction_hits: tuple[list[GeoHit], str] | None = None
    #: Место массива (участок в СНТ) и ответ `search_place`; None — не спрашивали.
    place: Place | None = None
    place_hits: list[PlaceHit] | None = None
    #: Ответ `search_place` на НАЗВАННЫЙ клиентом пункт (`settlement_place`) —
    #: улика правила `neighbour_settlement`; None — не спрашивали (кандидата
    #: нет, область не искали, уровень C, DaData нет).
    settlement_place_hits: list[PlaceHit] | None = None
    #: Ответ `search_place` на ПЕРВОЕ СЛОВО улицы без типа («Кола» из «Кола
    #: садовая») — улика правила `settlement_in_street`; None — не спрашивали
    #: (форма не та, уровень C, слово есть в улицах карт, DaData нет).
    street_place_hits: list[PlaceHit] | None = None


@dataclass(frozen=True, slots=True)
class Decision:
    rule: str
    hit: GeoHit
    #: Выбор среди нескольких или дом взят не из справочника: воркер ставит
    #: `~approx` ПОСЛЕ уточнения точки, независимо от точки.
    approx: bool
    parsed: Parsed
    #: Карта, давшая `hit`, если не та, чьё имя уже в `provider` воркера
    #: (улица DaData при `not_found` от OSM); None — оставить как есть.
    provider: str | None = None
    #: Квартира из хвоста дроби («10/77» → кв 77) — в строку, если пусто.
    office: str | None = None
    #: Расстояние, которым решено (км): у `neighbour_settlement` — от дома до
    #: точки названного пункта. В журнал (`rule_km`) и в `trace.km` — по нему
    #: копится замер для радиуса.
    km: float | None = None
    #: Политика правила в момент суда (пакет 6.0а): `suggest` — воркер ставит
    #: хвост `~suggest`; `approx` — `approx` уже True; `exact` — как написано.
    #: `off`/`shadow` решением не бывают: у них правило возвращает None.
    policy: str = POLICY_EXACT


@dataclass(frozen=True, slots=True)
class Shadow:
    """Что решило бы правило в тени (`shadow`) и чем кончился боевой суд без
    него — в `trace.shadow` и журнал `geocode.rule_shadow`. Без ПД: имя
    правила, статус, ключ дома по карте (`format_address` — то же, что легло
    бы в `geo_formatted`), расстояние и имя боевого правила (None — боевой суд
    промолчал)."""

    rule: str
    status: str
    key: str
    km: float | None
    instead: str | None

    def as_trace(self) -> dict[str, Any]:
        return {
            "rule": self.rule,
            "status": self.status,
            "key": self.key,
            "km": round(self.km, 2) if self.km is not None else None,
            "instead": self.instead,
        }


#: Ключи `trace` строки, принадлежащие СУДУ (пакет 6.0а, I-1): при каждом
#: новом вердикте они собираются заново, а прежние уходят в `trace.prev`
#: (один уровень — аудит читает «чем решено сейчас» и «чем было решено до
#: пересуда»). Остальные ключи — слоя разбора (`parse_form`, `level_reason`,
#: `locality_form`, `form`, `parse_shadow`, `stop_shadow`), судьи (`judge`)
#: и отката (`unfilled_at`) — суд не трогает.
TRACE_VERDICT_KEYS: tuple[str, ...] = (
    "rule",
    "policy",
    "km",
    "region",
    "hit_city",
    "query_form",
    "settlement_read",
    "shadow",
    "suggest",
)
#: Форма запроса, которым вынесен вердикт (`trace.query_form`).
QUERY_FORM_HOUSE = "house"  # улица и дом по городу/области
QUERY_FORM_COUNTRY = "country"  # дом найден поиском по стране
QUERY_FORM_PLACE = "place"  # место без улицы (`_geocode_place`)


def verdict_trace(
    base: Mapping[str, Any] | None,
    *,
    rule: str | None,
    policy: str | None,
    km: float | None,
    hit: GeoHit | None,
    query_form: str,
    settlement_read: str | None = None,
    shadow: Shadow | None = None,
) -> dict[str, Any]:
    """След суда поверх прежнего `trace` строки: ключи разбора остаются,
    ключи суда собираются заново, прежний суд — в `prev`. `base` — снимок
    `row.trace` фазы 1 воркера (строка читается один раз; запись — условный
    UPDATE без чтения, как у `geo_prev`). Пустые значения не пишутся: аудит
    фильтрует «ключ есть/нет» (`trace["k"].as_string() == v`), и `None` там
    только мешал бы."""
    прежний = dict(base or {})
    был_суд = {k: прежний[k] for k in TRACE_VERDICT_KEYS if k in прежний}
    след = {k: v for k, v in прежний.items() if k not in TRACE_VERDICT_KEYS and k != "prev"}
    новое: dict[str, Any] = {
        "rule": rule,
        "policy": policy if rule is not None else None,
        "km": round(km, 2) if km is not None else None,
        "region": hit.region if hit is not None else None,
        "hit_city": (hit.city or hit.settlement) if hit is not None else None,
        "query_form": query_form,
        "settlement_read": settlement_read,
        "shadow": shadow.as_trace() if shadow is not None else None,
        "suggest": True if policy == POLICY_SUGGEST and rule is not None else None,
    }
    след.update({k: v for k, v in новое.items() if v is not None})
    prev = был_суд or прежний.get("prev")
    if prev:
        след["prev"] = prev
    return след


def trace_after_reset(base: Mapping[str, Any] | None) -> dict[str, Any] | None:
    """`trace` при возврате строки в очередь карты (`сброс_вердикта`): суд
    уходит в `prev`, ключи разбора остаются; аудит после пересуда не читает
    прошлый `rule` как нынешний. None — следа не было и нет."""
    if not base:
        return None
    был_суд = {k: base[k] for k in TRACE_VERDICT_KEYS if k in base}
    след = {k: v for k, v in base.items() if k not in TRACE_VERDICT_KEYS and k != "prev"}
    prev = был_суд or base.get("prev")
    if prev:
        след["prev"] = prev
    return след or None


def trace_restored(base: Mapping[str, Any] | None) -> dict[str, Any] | None:
    """`trace` при УДЕРЖАНИИ прежнего вердикта (`keeps_previous`): суд, ушедший
    в `prev` при сбросе, возвращается наверх — строка снова несёт тот вердикт.
    Если суд и не уходил (сброс без следа), след остаётся как есть."""
    if not base:
        return None
    if any(k in base for k in TRACE_VERDICT_KEYS) or not isinstance(base.get("prev"), dict):
        return dict(base)
    след = {k: v for k, v in base.items() if k != "prev"}
    след.update(base["prev"])
    return след


def _решение(
    pol: Policy,
    rule: str,
    hit: GeoHit,
    approx: bool,
    parsed: Parsed,
    *,
    provider: str | None = None,
    office: str | None = None,
    km: float | None = None,
) -> Decision | None:
    """ЕДИНСТВЕННОЕ место, где правило становится решением, — здесь же
    применяется его политика: `off` (и `shadow` в боевом суде) — None, и
    `or`-цепочка идёт к следующему правилу; `suggest` — решение с хвостом
    для воркера; `approx` — `approx=True` независимо от написанного; `exact`
    — как написано."""
    return _под_политикой(
        Decision(rule, hit, approx, parsed, provider=provider, office=office, km=km), pol.of(rule)
    )


def _под_политикой(d: Decision | None, p: str) -> Decision | None:
    """Наложить политику `p` на готовое решение — строже из двух (ворота
    ветки поверх правила: `in_named_city=suggest` делает предложением и
    `best_of`, решивший внутри ветки)."""
    if d is None:
        return None
    if _СТРОГОСТЬ[p] > _СТРОГОСТЬ[d.policy]:
        return d
    if p in (POLICY_OFF, POLICY_SHADOW):
        return None
    if p == POLICY_SUGGEST:
        return dataclasses.replace(d, policy=POLICY_SUGGEST)
    if p == POLICY_APPROX:
        return dataclasses.replace(d, approx=True, policy=POLICY_APPROX)
    return d


def policy_decision(
    policy: Mapping[str, str] | None,
    rule: str,
    hit: GeoHit,
    approx: bool,
    parsed: Parsed,
    *,
    provider: str | None = None,
    km: float | None = None,
    shadow_as: str = POLICY_OFF,
) -> Decision | None:
    """Решение правила, живущего вне `auto_decide` (пригород воркера), под той
    же политикой: боевой суд — `shadow_as=off`, теневой — `exact`."""
    return _решение(
        Policy(policy or {}, shadow_as), rule, hit, approx, parsed, provider=provider, km=km
    )


def shadow_of(
    боевое: Decision | None, тень: Decision | None, *, city_point: tuple[float, float] | None
) -> Shadow | None:
    """Разница боевого и теневого суда → `Shadow`; None — тень ничего не
    добавила (то же правило, та же строка карты и та же точка — или тень
    промолчала). Сравнение не по одной строке карты: точка улицы и дом-голова
    печатают номер клиента одинаково («ул Ленина, 13/38»), а стоят в разных
    точках и решены разными правилами."""
    if тень is None:
        return None
    ключ = format_address(тень.hit, тень.parsed)
    if боевое is not None and (
        боевое.rule,
        format_address(боевое.hit, боевое.parsed),
        боевое.hit.lat,
        боевое.hit.lon,
    ) == (тень.rule, ключ, тень.hit.lat, тень.hit.lon):
        return None
    km = тень.km
    if km is None and city_point is not None:
        km = distance_km(city_point, (тень.hit.lat, тень.hit.lon))
    return Shadow(
        rule=тень.rule,
        status=GEO_EXACT,
        key=ключ,
        km=km,
        instead=боевое.rule if боевое is not None else None,
    )


def shadow_decide(e: Evidence, policy: Mapping[str, str] | None) -> Shadow | None:
    """Теневой суд (§0.3 `shadow`): `auto_decide` зовётся дважды — боевой
    (тень выключена) и с тенью как `exact`; разница — `Shadow`. Сети нет,
    строк не заводит: только `trace.shadow` и журнал у воркера. Второй суд
    идёт всегда, а не «если есть правила в тени»: правило без записи в
    реестре — тень по умолчанию, и перечислить такие имена заранее нельзя;
    суд чистый и дешёвый, без тени разницы не будет."""
    боевое = auto_decide(e, policy)
    тень = _decide(e, Policy(policy or {}, POLICY_EXACT))
    return shadow_of(боевое, тень, city_point=e.city_point)


def auto_decide(e: Evidence, policy: Mapping[str, str] | None = None) -> Decision | None:
    """Боевой суд: политика — ВХОД (§0.3, К-4). `policy` — настройка поверх
    `RULE_DEFAULT_POLICY` (`parse_rule_policy`); None и `{}` — одни умолчания:
    правила 18–20.09 как написаны, правило без записи в реестре — `shadow`, а
    в боевом суде тень равна `off`. Тень судит `shadow_decide`."""
    return _decide(e, Policy(policy or {}, POLICY_OFF))


def _decide(e: Evidence, pol: Policy) -> Decision | None:
    """Решить сама после всей цепочки (карты, подсказчики, область, пригород,
    уступка пункта). None — оставить вердикт как есть: строка улицы
    (`card_grade`=text, если карта знает улицу) или ничего.

    Каждое правило — именованный сторож; без признака решения нет (защита от
    тавтологии из шапки модуля: «город совпал» решением не является).

    Спор города об улице (`city_disputes_street`) — ОДИН сторож на все отказы,
    до правил: при споре решения нет ни для какого статуса. Улики спора — все
    ответы по городу — не зависят от того, какая карта отдала спорный дом, а
    какая улицу без дома; статус же зависит (по карте вердикта —
    `street_mismatch`, `house_missing`, `not_found`, `house_mismatch`), и
    сторож на одной ветке при тех же уликах давал точку улицы против прочтения
    справочника (ревью C1, 19.09). Не зовутся при споре и `_fraction_head` с
    `_house_family`: они тоже выбирают одно из двух прочтений — дом «N» или
    семью дома на улице клиента против дома с номером клиента на улице той же
    основы чужого типа, — а такой выбор при споре за оператором. `elsewhere`
    при споре — то же (A8): единственный дом в радиусе — не решение.
    `street_mismatch` уровней A/B без спора — как `house_missing` (N24);
    уровень — `street_mismatch_continues`.

    `elsewhere` — единственный вход соседа за забором (9): дом-сосед попадает
    в улики только вариантом области (`variants` пункт не сверяет), а улика
    «улица в названном пункте есть» — эхо DaData уровня 7 — живёт только в
    ответах области (`seen`); `settlement_mismatch` итогом значит «область не
    ходила», и там сторож слеп (скептик 20.09).

    Прочтение первого слова улицы пунктом (10, `street_head_reading`) стоит
    ПЕРЕД ветками отказов и закрывает их: установлено — решает только
    `_settlement_in_street`, а без дома в пункте решения нет вовсе. Иначе
    строка падала бы в `_fraction_head`/`_only_in_radius`/`_street_point` по
    сырому разбору, где `_улица_не_шире` прощает клиенту лишнее слово — и дом
    «Садовая, 4» в самом Мурманске или «4/27» в Североморске за 18 км побеждал
    бы слово «Кола» (скептик 20.09, Б-2).
    """
    if e.status == GEO_EXACT:
        if e.country and e.hit is not None:
            return _решение(pol, RULE_COUNTRY, e.hit, True, e.parsed, provider="dadata")
        return None
    if e.city is None:
        return None
    if city_disputes_street(e.parsed, e.city, e.city_hits):
        return None
    if e.status in STREET_HEAD_STATUSES or street_mismatch_continues(e.status, e.parsed.level):
        прочтение = street_head_reading(e)
        if прочтение is not None:
            return _settlement_in_street(e, прочтение, pol)
    if e.status == GEO_ELSEWHERE:
        # Единственный в 40 км среди нескольких — сначала (клиент пункта не
        # называл); назвал, и в нём дома нет — сосед за забором.
        return _only_in_radius(e, pol) or _neighbour_settlement(e, pol)
    if e.status == GEO_AMBIGUOUS:
        return _ambiguous(e, _groups(e), pol)
    if e.status == GEO_OTHER_CITY:
        return _in_named_city(e, pol)
    if e.status in (
        GEO_HOUSE_MISSING,
        GEO_HOUSE_MISMATCH,
        GEO_NOT_FOUND,
    ) or street_mismatch_continues(e.status, e.parsed.level):
        return (
            _fraction_head(e, pol)
            or _house_family(e, pol)
            or _street_point(e, pol)
            or _area_point(e, pol)
        )
    return None


def _дома_области(e: Evidence) -> list[GeoHit]:
    """Дома клиента по области (ответы области, а без них — `hits`) с теми
    же сторожами, что у `suburb_hit`: номер, регион, улица, слова клиента о
    месте; один дом на адрес."""
    if e.city is None:
        return []
    пул = e.region_hits if e.region_hits else e.hits
    return distinct_addresses(_дома_клиента(e.parsed, e.city, пул))


def _дома_клиента(parsed: Parsed, city: City, hits: list[GeoHit]) -> list[GeoHit]:
    """Дома клиента среди ответов карт — сторожа `suburb_hit`: дом справочника
    (`house_level`, не интерполяция), номер ключом, регион, улица без «верю
    пункту», слова клиента о месте. Точность точки состав НЕ меняет (урок
    `_дома_по_стране`: неточный соперник — соперник). Один фильтр на правила
    области (`_дома_области`) и соседа за забором (`neighbour_candidates`)."""
    ключ = house_key(parsed.house)
    return [
        h
        for h in hits
        if h.house_level
        and h.house
        and not h.interpolated
        and house_key(h.house) == ключ
        and region_matches(city.region, h.region)
        and _улица_сошлась(parsed, h, без_улицы=False)
        and _место_клиента_названо(parsed, h)
    ]


def fraction_head_in_hits(parsed: Parsed, city: City | None, hits: list[GeoHit]) -> bool:
    """Дом-голова дроби клиента («4» для «4/27») уже лежит среди ответов —
    сторожами `_дома_клиента` (номер ключом, регион, улица, слова клиента о
    месте). Воркер по нему не тратит поход головой по области: DaData на
    «4/27» могла отдать «д 4» соседом сама."""
    дробь = fraction_head(parsed)
    if дробь is None or city is None:
        return False
    return bool(_дома_клиента(dataclasses.replace(parsed, house=дробь[0]), city, hits))


def _groups(e: Evidence) -> list[GeoHit]:
    """Группы неоднозначного вердикта — ровно те, что видел `verdict`
    (сторожа места уже применены им)."""
    _, по_улице = _годные_дома(e.parsed, e.city, e.hits)
    return distinct_addresses(по_улице)


def _only_in_radius(e: Evidence, pol: Policy) -> Decision | None:
    """(1) Из нескольких домов области ровно один в `SUBURB_KM` от точки
    города объявления, остальные дальше. Одиночку решает пригород воркера;
    два в радиусе (Дядьково 5 км / Агро-Пустынь 14 км) — монета, None."""
    if e.city_point is None:
        return None
    группы = _дома_области(e)
    if len(группы) < 2:
        return None
    в_радиусе = [h for h in группы if distance_km(e.city_point, (h.lat, h.lon)) <= SUBURB_KM]
    if len(в_радиусе) != 1:
        return None
    return _решение(pol, RULE_ONLY_IN_RADIUS, в_радиусе[0], True, e.parsed)


def _ambiguous(e: Evidence, группы: list[GeoHit], pol: Policy) -> Decision | None:
    return _fullest_street(e, группы, pol) or _one_spot(e, группы, pol) or _best_of(e, группы, pol)


def _fullest_street(e: Evidence, группы: list[GeoHit], pol: Policy) -> Decision | None:
    """(2a) Одна группа содержит ВСЕ значимые слова улицы клиента, остальные —
    подмножество: «Красная Керчь» > «Красная». Одно слово у клиента — правило
    молчит: «Победы» и «30-летия Победы» им не различить."""
    слова_клиента = {w for w in _слова(e.parsed.street) if w not in _СЛОВА_ТИПА and len(w) > 1}
    if len(слова_клиента) < 2 or len(группы) < 2:
        return None
    полные = [h for h in группы if all(_слово_есть(w, _слова(h.street)) for w in слова_клиента)]
    if len(полные) != 1:
        return None
    return _решение(pol, RULE_FULLEST_STREET, полные[0], True, e.parsed)


def _one_spot(e: Evidence, группы: list[GeoHit], pol: Policy) -> Decision | None:
    """(2b) Все группы — точные точки домов, и все попарно в `ONE_SPOT_KM`:
    дубли ГАР одного дома (`_одно_пятно`). Точка любого приблизительная."""
    if len(группы) < 2 or not _одно_пятно(группы):
        return None
    return _решение(pol, RULE_ONE_SPOT, группы[0], True, e.parsed)


def _best_of(e: Evidence, группы: list[GeoHit], pol: Policy) -> Decision | None:
    """(2c) Именованный признак ровно у одной группы: пункт из соседней
    реплики назван в ответе (`hints`) — или клиент пункта не называл и ровно
    один дом стоит в самом городе объявления, а не в его пунктах. Два дома с
    признаком — None: точность точки и близость к городу решением не
    являются."""
    if e.city is None or len(группы) < 2:
        return None
    с_подсказкой: list[tuple[GeoHit, str]] = []
    for h in группы:
        подсказка = next((п for п in e.hints if _пункт_назван(_норм(п), _места_ответа(h))), None)
        if подсказка is not None:
            с_подсказкой.append((h, подсказка))
    if len(с_подсказкой) == 1:
        h, подсказка = с_подсказкой[0]
        return _решение(
            pol, RULE_BEST_OF, h, True, dataclasses.replace(e.parsed, settlement=подсказка)
        )
    if e.parsed.settlement is None and not _регион_вместо_города(e.city):
        в_городе = [h for h in группы if _в_самом_городе(e.city.name, h)]
        if len(в_городе) == 1:
            return _решение(pol, RULE_BEST_OF, в_городе[0], True, e.parsed)
    return None


def _in_named_city(e: Evidence, pol: Policy) -> Decision | None:
    """`other_city_in_text`: дома в названном клиентом городе (сторожа слов
    `_дома_области`) — от двух решают правила неоднозначности. Одна группа
    недостижима (любой дом в названном городе вердикт делает `exact`);
    расстояния до города объявления для чужого города не считаются. Политика
    ворот `in_named_city` ложится поверх политики решившего правила — строже
    из двух (`_под_политикой`)."""
    if pol.of(RULE_IN_NAMED_CITY) in (POLICY_OFF, POLICY_SHADOW):
        return None
    группы = _дома_области(e)
    if len(группы) < 2:
        return None
    return _под_политикой(_ambiguous(e, группы, pol), pol.of(RULE_IN_NAMED_CITY))


def _fraction_head(e: Evidence, pol: Policy) -> Decision | None:
    """(3, дробь) «N/M» не найден ни дробью, ни корпусом — дом «N» есть у
    карты: сначала без сети из ответов по городу (DaData на «13/38» уже отдала
    дом «13» — `house_mismatch`), потом из сетевого ответа воркера, потом из
    ответов области (голова по области, 20.09). Хвост — квартира по
    `flat_from_fraction`, кроме улиц с угловой нумерацией (`corner_numbering`);
    строка карты печатает номер клиента.

    Прочтения — как у `_вердикт_с_подсказками`: сначала слова клиента как
    есть, потом с пунктом из соседней реплики («Кола, садовая 4/27» — подсказка
    «Кола» иначе не доходила до головы, а без запятой та же строка решалась
    правилом (10); скептик 20.09, А-4). Решение с подсказкой несёт её в
    `parsed`, как `_best_of`.

    Радиусная ветка (А2, 20.09): ни один источник не подтвердил «N» ни в
    городе, ни в названном пункте, а среди домов-голов ОБЛАСТИ ровно один
    стоит в `SUBURB_KM` от точки города объявления — признак `suburb_hit` и
    `only_in_radius` под головой. Сторожа: уровень A/B (вывод из геометрии
    неводу C не положен), город объявления улицы клиента НЕ знает
    (`known_street` по всем ответам — иначе «Полярная 3/14» в Сызрани получала
    бы дом-голову в посёлке за 30 км вместо точки своей улицы; скептик А-1),
    дубли одного дома у двух карт склеены (`_без_дублей_пятна`, А-5), карта —
    по объекту (А-7). `office` эта ветка не пишет: геометрия и посылка о
    квартире — два вывода подряд, в карточку идёт только дом (А-2).
    """
    дробь = fraction_head(e.parsed)
    if дробь is None or e.city is None:
        return None
    голова, хвост = дробь
    источники = list(e.city_hits)
    if e.fraction_hits is not None:
        источники.append(e.fraction_hits)
    if e.region_hits:
        источники.append((e.region_hits, e.region_provider or ""))
    пул = [h for hs, _ in источники for h in hs]
    квартира = _квартира_дроби(e.parsed, e.city, пул, хвост)
    прочтения = [e.parsed]
    if e.parsed.settlement is None:
        прочтения += [dataclasses.replace(e.parsed, settlement=п) for п in e.hints]
    for прочтение in прочтения:
        с_головой = dataclasses.replace(прочтение, house=голова)
        for hs, карта in источники:
            статус, hit = verdict(с_головой, e.city, hs)
            if статус != GEO_EXACT or hit is None:
                continue
            return _дробь_решена(e, hit, прочтение, карта, pol, office=квартира)
    if (
        e.city_point is None
        or not e.region_hits
        or e.parsed.level not in STREET_EVIDENCE_LEVELS
        or known_street(e.parsed, e.city, пул) is not None
    ):
        return None
    с_головой = dataclasses.replace(e.parsed, house=голова)
    группы = _дома_области(dataclasses.replace(e, parsed=с_головой))
    в_радиусе = _без_дублей_пятна(
        [h for h in группы if distance_km(e.city_point, (h.lat, h.lon)) <= SUBURB_KM]
    )
    if len(в_радиусе) != 1:
        return None
    (hit,) = в_радиусе
    return _дробь_решена(
        e,
        hit,
        e.parsed,
        _карта_ответа(источники, hit),
        pol,
        office=None,
        km=distance_km(e.city_point, (hit.lat, hit.lon)),
    )


def _квартира_дроби(parsed: Parsed, city: City, пул: list[GeoHit], хвост: str) -> str | None:
    """Квартира из хвоста дроби для решения правила дроби: по
    `flat_from_fraction`, кроме улиц с угловой нумерацией (`corner_numbering`
    по всем ответам в уликах). Одно определение на городскую ветку
    `_fraction_head` и на ветку (ii) прочтения (10)."""
    return None if corner_numbering(parsed, city, пул) else flat_from_fraction(хвост)


def _дробь_решена(
    e: Evidence,
    hit: GeoHit,
    прочтение: Parsed,
    карта: str | None,
    pol: Policy,
    *,
    office: str | None,
    km: float | None = None,
) -> Decision | None:
    """Решение правила дроби: строка карты печатает номер КЛИЕНТА («4/27» по
    дому «4»), квартира — в `office`, прочтение (подсказка, пункт из первого
    слова) — в `parsed`. Одна сборка на подтверждение вердиктом, радиусную
    ветку и ветку (ii) правила (10). Политика — правила дроби: ветка (ii)
    правила (10) решает ИМЕНЕМ дроби, и выключенная дробь молчит и там; поверх
    неё в ветке (ii) — ворота правила (10), строже из двух (`_под_политикой`
    в `_settlement_in_street`): выключенное прочтение молчит и при живой
    дроби."""
    return _решение(
        pol,
        RULE_FRACTION_HEAD,
        dataclasses.replace(hit, house=e.parsed.house),
        True,
        прочтение,
        provider=карта or None,
        office=office,
        km=km,
    )


def _карта_ответа(источники: list[tuple[list[GeoHit], str]], hit: GeoHit) -> str | None:
    """Имя карты, чей это ответ, — по объекту, а не по `region_provider`
    (область — общий пул DaData и Яндекса; скептик 20.09, А-7). Пустое имя
    (область без провайдера) — None, как везде у `Decision.provider`."""
    return next((к for hs, к in источники if any(h is hit for h in hs)), None) or None


def _house_family(e: Evidence, pol: Policy) -> Decision | None:
    """(8) Только `house_mismatch`: первая карта, знающая семью дома
    («29» ↔ «29А»), решает вердиктом с семьёй; семья из двух («29А» и «29Б»)
    — `ambiguous` → None, дальше строка улицы."""
    if e.status != GEO_HOUSE_MISMATCH:
        return None
    for hs, карта in e.city_hits:
        _, по_улице = _годные_дома(e.parsed, e.city, hs, family=True)
        if not по_улице:
            continue
        статус, hit = verdict(e.parsed, e.city, hs, family=True)
        if статус == GEO_EXACT and hit is not None:
            return _решение(pol, RULE_HOUSE_FAMILY, hit, True, e.parsed, provider=карта)
        return None
    return None


def _street_point(e: Evidence, pol: Policy) -> Decision | None:
    """(3, улица) Улица есть, дома нет: точка улицы с номером клиента — из
    ответов УРОВНЯ УЛИЦЫ (точка дома соседа — не точка улицы; сосед даёт
    только строку без точки). `precise=False` ведёт воркер к Яндексу за
    точкой дома; не даст — `~approx`.

    Улика уровня улицы годится только уровням `STREET_EVIDENCE_LEVELS` — тот
    же сторож, что у строки улицы без точки в воркере. Улицы всех карт (город
    и область) судятся ОДНИМ вызовом `known_street`: перебор карт до первой
    давшей улицу пропускал бы неоднозначность DaData через слабую карту с
    единственной догадкой; имя карты — у выбранного ответа."""
    if e.parsed.level not in STREET_EVIDENCE_LEVELS:
        return None
    # `street_mismatch` — с N24: уровень проверен в `auto_decide`
    # (`street_mismatch_continues`), спор города — там же, одним сторожем на
    # все отказы, до правил; `house_mismatch` по-прежнему исключён (дом
    # соседа — строка без точки).
    if e.status not in (GEO_HOUSE_MISSING, GEO_NOT_FOUND, GEO_STREET_MISMATCH):
        return None
    источники = [(hs, карта) for hs, карта in e.city_hits]
    if e.region_hits:
        источники.append((e.region_hits, e.region_provider or ""))
    улицы = [(h, карта) for hs, карта in источники for h in hs if not h.house_level]
    улица = known_street(e.parsed, e.city, [h for h, _ in улицы])
    if улица is None or not _похож_на_дом(e.parsed.house):
        return None
    карта = next(к for h, к in улицы if h is улица)
    return _решение(
        pol,
        RULE_STREET_POINT,
        dataclasses.replace(улица, house=e.parsed.house, house_level=False, precise=False),
        False,
        e.parsed,
        provider=карта or None,
    )


def _похож_на_дом(house: str | None) -> bool:
    """Номер клиента — дом по НЫНЕШНЕМУ разбору (владелец 19.09: «Камера 4G»
    — дом «4G» старого разбора лёг в карточку точкой улицы; сегодняшний невод
    латинскую букву за литеру не берёт). Точка улицы и массива ставится не по
    справочнику домов, а по слову клиента — и слово обязано быть домом.
    Определение «что такое дом» одно на проект — `address_parse.is_house_number`:
    обе головы разбора (невод и «дом N») и форма модели; первая редакция
    сверяла только с головой невода и отбирала точку у настоящих домов из
    реплики «дом 12, корпус 2» (ревью 19.09)."""
    return address_parse.is_house_number(house)


def _area_point(e: Evidence, pol: Policy) -> Decision | None:
    """(7) Участок массива («СНТ Светлый 23»): дома у ФИАС нет, а массив
    карта знает один — точка массива. `kind == "area"` обязателен: с
    массивом в роли пункта карта отдала бы посёлок-тёзку. Уровень — как у
    точки улицы: только `STREET_EVIDENCE_LEVELS`."""
    if e.parsed.level not in STREET_EVIDENCE_LEVELS:
        return None
    if e.place is None or e.place_hits is None or not _похож_на_дом(e.parsed.house):
        return None
    статус, место = place_verdict(e.place, e.city, e.place_hits)
    if статус != GEO_EXACT or место is None or место.kind != "area":
        return None
    return _решение(
        pol,
        RULE_AREA_POINT,
        GeoHit(
            street=место.name,
            house=e.parsed.house,
            settlement=место.settlement,
            city=место.city,
            region=место.region,
            lat=место.lat,
            lon=место.lon,
            house_level=False,
            precise=False,
            area=место.name,
        ),
        False,
        e.parsed,
        provider="dadata",
    )


# --- сосед за забором (9) ---------------------------------------------------------


def settlement_place(parsed: Parsed) -> Place | None:
    """Названный клиентом пункт как место — за его точкой для правила
    `neighbour_settlement`; None — правило заведомо молчит: пункта нет, улицы
    нет или пункт — массив (у СНТ/КП улицы внутренние, тёзок вокруг десятки,
    а участок массива ведёт своё правило `area_point`). Улица и район в запрос
    не идут — точка нужна самого пункта."""
    if not parsed.settlement or not parsed.street.strip():
        return None
    if _норм(parsed.settlement_type or "") in _ТИПЫ_МАССИВА:
        return None
    return Place(
        settlement=parsed.settlement,
        settlement_type=parsed.settlement_type,
        area=None,
        district=None,
        level=parsed.level,
    )


def neighbour_candidates(parsed: Parsed, city: City | None, pool: list[GeoHit]) -> list[GeoHit]:
    """Дома-соседи: у них сошлось всё, кроме пункта, — один на адрес. Пусто,
    когда решать нечего или нельзя:

    * названный пункт улицу клиента ЗНАЕТ — домом, улицей без дома, эхом
      DaData уровня 7 (`street_in_settlement` без типа): тогда спор не о
      соседе, а о доме на своей улице — за оператором (`street_point` /
      `house_missing`, N24). Дом «23» без улицы в пункте и дом 23 на другой
      улице пункта сторож не задевают: улица у такого ответа — не улица клиента;
    * дом стоит в самом городе объявления: клиент назвал деревню — он не в
      городе, а тёзки «Садовая/Лесная» на окраине есть почти всегда;
    * дом стоит в массиве с участками (СНТ/ДНТ/КП в любом месте ответа —
      `_дом_в_массиве_с_участками`) — улицы там внутренние, тот же довод, что
      у названного пункта-массива;
    * клиент типа улицы не назвал, а у карты тип не «улица» («вишнёвая» ↔
      «пер Вишнёвый»): терпимость вердикта к типу здесь перебивала бы слово
      клиента о пункте словом карты о переулке.

    Точность точки состав не меняет (`_дома_клиента`): дом с точкой пункта —
    такой же соперник в круге, и отбросить его до подсчёта значит выдать
    единственный точный за единственный (урок `_дома_по_стране`, ревью 19.09).
    """
    if city is None or not parsed.settlement or not parsed.street.strip():
        return []
    if street_in_settlement(parsed, city, pool, с_типом=False) is not None:
        return []
    без_пункта = dataclasses.replace(parsed, settlement=None, settlement_type=None)
    годные = [
        h
        for h in _дома_клиента(без_пункта, city, pool)
        if not _в_самом_городе(city.name, h)
        and not _дом_в_массиве_с_участками(h)
        and _тип_улицы_не_чужой(parsed.street, h.street)
    ]
    return distinct_addresses(годные)


def _дом_в_массиве_с_участками(h: GeoHit) -> bool:
    """В местах ответа карты — тип массива с участками («тер. СНТ Луч», «КП
    Лесной»). Смотрятся ВСЕ места (`_места_ответа`), а не одна структура:
    DaData кладёт массив в `area`, Яндекс структуру не пишет никогда и второй
    пункт («СНТ Луч» рядом с городом) отдаёт в `settlement` (шлюз
    `yandex_geocoder`) — дом из СНТ, пришедший Яндексом, иначе проходил
    кандидатом (ревью 20.09, C3). Микрорайон и квартал (мягкие типы) массивом
    здесь не считаются: дом в «мкр Восточный» соседнего посёлка — обычный дом."""
    return any(w in _ТИПЫ_МАССИВА_С_УЧАСТКАМИ for w in _места_ответа(h))


def _тип_улицы_не_чужой(улица_клиента: str, улица_карты: str | None) -> bool:
    """Клиент назвал тип — его сверил `_улица_сошлась`; не назвал — у карты
    либо «улица», либо типа нет вовсе."""
    if _тип_улицы(улица_клиента) is not None:
        return True
    return _тип_улицы(улица_карты) in (None, "улица")


def _то_же_имя_пункта(пункт: str, имя: str | None) -> bool:
    """Имя места карты равно имени пункта клиента ЦЕЛИКОМ после `_норм`
    (регистр, ё→е, дефис ≡ пробел). Не `_пункт_назван`: его терпимость к
    опечатке и обрубку нужна, чтобы сверить ответ с клиентом, а здесь место
    ВЫБИРАЕТСЯ по минимуму расстояния среди похожих — «Жуково» ловило бы
    Жуковку в 2 км, «Горки» — Горки-2 (скептик 20.09)."""
    return bool(имя) and _норм(имя).replace("-", " ") == _норм(пункт).replace("-", " ")


def _имя_пункта(p: PlaceHit) -> str | None:
    """Имя места как ПУНКТА: деревня/посёлок (уровень 6) или город (уровень 4).
    Массив («тер. СНТ Липки») и улица («ул Липки») пунктом не являются
    — у них имени пункта нет."""
    if p.kind == "settlement":
        return p.settlement
    if p.kind == "city":
        return p.city
    return None


def _места_с_именем(имя: str, city: City, места: list[PlaceHit]) -> list[PlaceHit]:
    """Места карты, которые и есть пункт с этим именем: в области объявления,
    пункт (не улица и не массив), имя ЦЕЛИКОМ. Одно определение «место =
    слово клиента» для соседа за забором (9) и прочтения (10)."""
    return [
        p
        for p in места
        if region_matches(city.region, p.region) and _то_же_имя_пункта(имя, _имя_пункта(p))
    ]


def _neighbour_settlement(e: Evidence, pol: Policy) -> Decision | None:
    """(9) Сосед за забором (владелец 20.09: «деревня Липки, вишнёвая 23»
    при объявлении в Одинцове — «Дубки, ул Вишнёвая, 23» за общим забором;
    HEAD оставлял `elsewhere` с одним вариантом и пустой карточкой).

    Сторожа, все именованные: область искали (`region_hits` — там и эхо
    улицы пункта); уровень A/B; пункт назван и не массив (`settlement_place`);
    номер — дом; точка названного пункта спрошена (`settlement_place_hits`);
    кандидаты (`neighbour_candidates`) по всем ответам города и области, и
    только в `SUBURB_KM` от точки города объявления (якорь: тёзок пункта
    `search_place` отдаёт до десяти по всей области, а Яндекс по городу и
    область без круга отдают дома по всему региону — без якоря дом в 147 км
    решался бы, стоило тёзке пункта стоять рядом с НИМ, а не с клиентом; нет
    точки города — молчание; ревью 20.09, C2); место — `kind` settlement/city
    в регионе объявления с ТЕМ ЖЕ именем; в `NEIGHBOUR_KM` от ближайшей тёзки
    — РОВНО ОДИН кандидат (двое — монета, None); у него точка самого дома
    (`precise`: точка пункта соседа расстояния не доказывает). Решение — с
    `~approx`: пункт установлен выводом из геометрии, а не подтверждением, и
    аудит видит каждое."""
    if e.city is None or e.city_point is None or not e.region_hits:
        return None
    if e.settlement_place_hits is None:
        return None
    if e.parsed.level not in STREET_EVIDENCE_LEVELS or settlement_place(e.parsed) is None:
        return None
    if not _похож_на_дом(e.parsed.house):
        return None
    источники = [(hs, карта) for hs, карта in e.city_hits]
    источники.append((e.region_hits, e.region_provider or ""))
    пул = [h for hs, _ in источники for h in hs]
    точка_города = e.city_point
    кандидаты = [
        h
        for h in neighbour_candidates(e.parsed, e.city, пул)
        if distance_km(точка_города, (h.lat, h.lon)) <= SUBURB_KM
    ]
    if not кандидаты:
        return None
    места = _места_с_именем(e.parsed.settlement or "", e.city, e.settlement_place_hits)
    if not места:
        return None
    рядом: list[tuple[GeoHit, float]] = []
    for h in кандидаты:
        km = min(distance_km((p.lat, p.lon), (h.lat, h.lon)) for p in места)
        if km <= NEIGHBOUR_KM:
            рядом.append((h, km))
    без_дублей = _без_дублей_пятна([h for h, _ in рядом])
    рядом = [(h, km) for h, km in рядом if any(h is d for d in без_дублей)]
    if len(рядом) != 1:
        return None
    ((hit, km),) = рядом
    if not hit.precise:
        return None
    карта = _карта_ответа(источники, hit)
    return _решение(
        pol, RULE_NEIGHBOUR_SETTLEMENT, hit, True, e.parsed, provider=карта or None, km=km
    )


def _одно_пятно(дома: list[GeoHit]) -> bool:
    """Все дома — точные точки, попарно в `ONE_SPOT_KM`: дубли одного дома
    (признак правила `_one_spot`, вынесен для соседа за забором)."""
    if not all(h.precise and h.house_level for h in дома):
        return False
    return all(
        distance_km((a.lat, a.lon), (b.lat, b.lon)) <= ONE_SPOT_KM for a in дома for b in дома
    )


def _без_дублей_пятна(дома: list[GeoHit]) -> list[GeoHit]:
    """Тот же дом у двух карт («ул Вишнёвая» DaData и «Вишнёвая улица»
    Яндекса, точки в десятках метров) — `distinct_addresses` их не склеивает
    (улицы разными словами), а соперниками они не являются: признак — тот же,
    что у (2b) `_one_spot`; остаётся первый (DaData — она в уликах первой).
    Одна склейка на соседа за забором и радиусную ветку дроби (скептик 20.09,
    А-5): два определения «один дом» дали бы монету в одном правиле и решение
    в другом."""
    if len(дома) > 1 and _одно_пятно(дома):
        return дома[:1]
    return дома


# --- пункт из первого слова улицы (10) ----------------------------------------------

#: Отказы, после которых первое слово улицы без типа читается пунктом области:
#: пустота, улица без дома, другой дом, дом в другом месте; «улица не та» у
#: уровней A/B — через `street_mismatch_continues` (N24). Одна константа на
#: диспетчер `auto_decide` и на гейт запроса места в воркере. Отказы со словом
#: клиента о месте (`settlement_mismatch`, `other_city_in_text`) сюда не входят
#: — там читать нечего, место уже названо.
STREET_HEAD_STATUSES = frozenset(
    {GEO_NOT_FOUND, GEO_HOUSE_MISSING, GEO_HOUSE_MISMATCH, GEO_ELSEWHERE}
)

_СЛОВО_БУКВАМИ = re.compile(r"[А-Яа-яЁё]+(?:-[А-Яа-яЁё]+)*")


def street_head_as_settlement(parsed: Parsed, city: City | None) -> tuple[str, str] | None:
    """(а) Форма слов клиента, при которой первое слово улицы МОЖЕТ быть
    пунктом: место не названо; улица без типа («Красная площадь» — площадь)
    ровно из двух слов буквами (дефис внутри допустим — «Усть-Кут победы»;
    «40 лет Октября» — три слова с числом); первое — от трёх букв, не тип, не
    фамилия улицы («Толстого Победы»), не речь (`is_place_name` — то же
    определение имени пункта, что у разбора и подсказок), не город
    объявления и не город справочника Авито (это `locality`, край Б0). Регистр
    не улика: «кола садовая» пишут строчными, а заглавная у «Красная Пресня»
    ничего не доказывает — улику даёт карта (место с тем же именем), не форма.
    Возвращает (первое, остаток улицы)."""
    if parsed.settlement or parsed.locality or parsed.area:
        return None
    if _тип_улицы(parsed.street) is not None:
        return None
    слова = parsed.street.split()
    if len(слова) != 2 or not all(_СЛОВО_БУКВАМИ.fullmatch(w) for w in слова):
        return None
    первое, остаток = слова
    имя = _норм(первое)
    if len(имя.replace("-", "")) < 3 or имя in _СЛОВА_ТИПА:
        return None
    if address_parse.is_street_surname(первое) or not address_parse.is_place_name(первое):
        return None
    if city_by_name(первое) is not None or (city is not None and _норм(city.name) == имя):
        return None
    return первое, остаток


def street_names_word(слово: str, пул: list[GeoHit]) -> bool:
    """(в) Хоть одна карта знает улицу, в имени которой есть это слово:
    «Красная Пресня 5» — карты отдают «улица Красная Пресня», и «Красная»
    пунктом не читается. Дефис карты снимается («Стара Загора» ↔ «ул
    Стара-Загора», скептик 20.09, Б-3) — той же `_без_дефисов`, что у
    `_пункт_назван`; «Кола» против «Кольский проспект» не сходится
    (`_основа_совпала` требует основу целиком)."""
    части = _без_дефисов([_норм(слово)])
    if not части:
        return False
    return any(
        all(_слово_есть(ч, _без_дефисов(_слова(h.street))) for ч in части) for h in пул if h.street
    )


def _все_ответы(e: Evidence) -> list[GeoHit]:
    """Все ответы карт в уликах: город, голова дроби, область — один пул для
    сторожа (в) в воркере и в правиле (скептик 20.09, Б-4)."""
    пул = [h for hs, _ in e.city_hits for h in hs]
    if e.fraction_hits is not None:
        пул += e.fraction_hits[0]
    return пул + list(e.region_hits)


def street_head_candidate(e: Evidence) -> tuple[str, str] | None:
    """Сторожа (а)–(в) прочтения на уликах — ДО сети: форма слов
    (`street_head_as_settlement`), уровень A/B (невод C — самая шумная масса;
    та же константа, что у точки улицы), ни одна карта не знает улицы с первым
    словом (`street_names_word` по всем ответам). Воркер зовёт её же перед
    запросом места: второго набора сторожей нет."""
    if e.city is None or e.parsed.level not in STREET_EVIDENCE_LEVELS:
        return None
    разбор = street_head_as_settlement(e.parsed, e.city)
    if разбор is None or street_names_word(разбор[0], _все_ответы(e)):
        return None
    return разбор


def street_head_reading(e: Evidence) -> tuple[str, str] | None:
    """Прочтение УСТАНОВЛЕНО: сторожа (а)–(в) прошли, место спрошено
    (`street_place_hits`) и среди мест есть пункт области с тем же именем
    ЦЕЛИКОМ (`_места_с_именем` — те же сторожа, что у соседа за забором; «Колла»,
    «им. Ленина», улица «ул Кольская», массив «тер. СНТ Кола» — нет). С этого
    момента слово клиента о пункте сильнее любого прочтения «лишнее слово
    улицы»: `auto_decide` дальше правила (10) не идёт, воркер строку улицы без
    точки не пишет."""
    разбор = street_head_candidate(e)
    if разбор is None or e.city is None or e.street_place_hits is None:
        return None
    if not _места_с_именем(разбор[0], e.city, e.street_place_hits):
        return None
    return разбор


def _settlement_in_street(e: Evidence, прочтение: tuple[str, str], pol: Policy) -> Decision | None:
    """(10) «Кола садовая 4/27» при объявлении в Мурманске (владелец 20.09):
    разбор такую улику дать не может (пункт без типа он берёт только перед
    типом улицы), её дала карта — `street_head_reading`. Судятся УЖЕ собранные
    ответы, суженные до домов в пункте с тем же именем ЦЕЛИКОМ (`settlement`
    или `city` ответа — та же `_то_же_имя_пункта`, что выбрала место; дом в
    «Новая Кола» за 183 км сюда не входит — скептик 20.09, Б-1) и не дальше
    `SUBURB_KM` от точки города объявления: пункт назначили мы по форме слова,
    и без геометрического якоря это гадание (Апатиты → Кола за 170 км молчат
    честно). Один фильтр на обе ветки:

    (i) дом клиента в пункте — сторожами вердикта «пункт назван клиентом»
    (`_дома_клиента`: номер ключом, регион, улица, слово о пункте);
    (ii) дом-голова дроби в пункте — решением правила дроби (`_дробь_решена`:
    `rule=fraction_head`, `office` по `_квартира_дроби`), прочтение — наше
    (`Decision.parsed`), в журнале воркера `settlement_read`.

    Соперники в обеих ветках считаются по ОБЪЕДИНЁННОМУ пулу источников
    (город, голова, область), склеенному `distinct_addresses` и
    `_без_дублей_пятна`: ровно один дом — решение, двое — None. Перебор
    источников порознь (`verdict` по каждому) делал бы невидимым дом-соперник
    из другого источника: два одноимённых пункта области с тем же домом на
    той же улице (DaData отдала один, Яндекс — другой) решались бы первым
    (ревью 20.09, D1). Карта решения — по объекту (`_карта_ответа`).

    Степень `approx` в обеих: прочтение — вывод, аудит `--degree approx` видит
    каждое срабатывание; `km` — расстояние до города объявления, в журнал.
    Без дома в пункте — None, и это окончательный ответ диспетчера (Б-2).
    """
    if e.city is None or e.city_point is None:
        return None
    первое, остаток = прочтение
    точка_города = e.city_point

    def в_пункте(h: GeoHit) -> bool:
        return (
            _то_же_имя_пункта(первое, h.settlement) or _то_же_имя_пункта(первое, h.city)
        ) and distance_km(точка_города, (h.lat, h.lon)) <= SUBURB_KM

    читаем = dataclasses.replace(e.parsed, settlement=первое, settlement_type=None, street=остаток)
    источники = [([h for h in hs if в_пункте(h)], к) for hs, к in e.city_hits]
    if e.fraction_hits is not None:
        источники.append(([h for h in e.fraction_hits[0] if в_пункте(h)], e.fraction_hits[1]))
    if e.region_hits:
        источники.append(([h for h in e.region_hits if в_пункте(h)], e.region_provider or ""))
    все = [h for hs, _ in источники for h in hs]
    дома = _без_дублей_пятна(distinct_addresses(_дома_клиента(читаем, e.city, все)))
    if len(дома) > 1:
        return None
    if дома:
        (hit,) = дома
        return _решение(
            pol,
            RULE_SETTLEMENT_IN_STREET,
            hit,
            True,
            читаем,
            provider=_карта_ответа(источники, hit),
            km=distance_km(точка_города, (hit.lat, hit.lon)),
        )
    дробь = fraction_head(читаем)
    if дробь is None:
        return None
    голова, хвост = дробь
    головы = _без_дублей_пятна(
        distinct_addresses(_дома_клиента(dataclasses.replace(читаем, house=голова), e.city, все))
    )
    if len(головы) != 1:
        return None
    (hit,) = головы
    # Ветка (ii) решает именем дроби, но живёт внутри правила (10): политика
    # его ворот ложится поверх политики дроби — строже из двух, как у
    # `_in_named_city`. Иначе `settlement_in_street=off` (или тень) не
    # выключало бы прочтение ровно на том классе, ради которого правило
    # заведено, — дробном доме владельца (ревью 20.09, #1). None отсюда —
    # по-прежнему окончательный ответ диспетчера (Б-2).
    return _под_политикой(
        _дробь_решена(
            e,
            hit,
            читаем,
            _карта_ответа(источники, hit),
            pol,
            office=_квартира_дроби(читаем, e.city, все, хвост),
            km=distance_km(точка_города, (hit.lat, hit.lon)),
        ),
        pol.of(RULE_SETTLEMENT_IN_STREET),
    )


def _улица_сошлась(
    parsed: Parsed, h: GeoHit, *, без_улицы: bool = True, с_типом: bool = True
) -> bool:
    """Улица клиента сошлась с ответом карты; без улицы улицей служит массив,
    а без того и другого («посёлок Каменка, 9») — `без_улицы`: вердикт
    верит пункту, варианты — нет (дом «9» есть в каждом посёлке области).

    Улица клиента — микрорайон у карты (владелец 19.09, Старый Оскол:
    «Пугачева 9» — Яндекс и OSM отдают дом с `settlement` «микрорайон
    Пугачёва» и пустой улицей; DaData пишет «мкр Пугачева» улицей и
    проходит выше): улицы у ответа нет, а место ответа — массив мягкого типа
    с теми же словами — та же «улица», названная по-своему. Пункт с твёрдым
    типом («посёлок Каменка») улицей не служит: дом «9» в посёлке — не
    «Каменка, 9» на улице Каменка.
    """
    if parsed.street.strip():
        if _улица_не_шире(h.street, parsed.street, с_типом=с_типом):
            return True
        return not (h.street or "").strip() and _улица_как_массив(parsed.street, h)
    if parsed.area:
        return _массив_назван(parsed.area, h)
    return без_улицы


def _улица_как_массив(улица: str, h: GeoHit) -> bool:
    """Пункт или массив ответа назван словом мягкого типа массива (мкр,
    микрорайон, квартал, массив), и все значимые слова улицы клиента среди его
    слов: «Пугачева» ↔ «микрорайон Пугачёва»."""
    return _место_улицей(улица, h) is not None


def _место_улицей(улица: str, h: GeoHit) -> str | None:
    """Место ответа карты (пункт или массив), которое и есть улица клиента:
    массив мягкого типа с её словами. None — такого нет.

    Слова сверяются СТРОГО, после `_норм` (регистр, ё→е): «Пугачева» ↔
    «микрорайон Пугачёва» — да. Терпимость к форме слова и опечаткам
    (`_основа_совпала`) задумана для склонений ОДНОЙ улицы; между разными
    видами объектов прилагательное в другом роде — другой объект: «ул
    Северная» и «мкр Северный», «ул Строителей» и «мкр Строитель» живут в
    одном городе рядом (ревью 19.09)."""
    свои = [w for w in _слова(улица) if w not in _СЛОВА_ТИПА and w not in _ТИПЫ_МАССИВА_МЯГКИЕ]
    if not свои:
        return None
    for место in (h.settlement, h.area):
        слова = _слова(место)
        if not any(w in _ТИПЫ_МАССИВА_МЯГКИЕ for w in слова):
            continue
        if all(w in слова for w in свои):
            return (место or "").strip() or None
    return None


def _массив_назван(массив: str, h: GeoHit) -> bool:
    """Массив клиента («СНТ Рассвет») есть в ответе карты — улицей, массивом
    или пунктом; слова типа не считаются."""
    слова = [w for w in _слова(массив) if w not in _ТИПЫ_МАССИВА and w not in _СЛОВА_ТИПА]
    if not слова:
        return False
    среди = _без_дефисов(_слова(h.street) + _места_ответа(h))
    return all(_слово_есть(w, среди) for w in _без_дефисов(слова))


def _город_назван(лок: str, среди: list[str]) -> bool:
    """«Орске», «Уфе», «Гае» против «Орск», «Уфа», «Гай»: падеж короткого имени.

    Короткие города словоформой не сравнить (основа короче четырёх букв), а
    отказать своему же городу — значит запереть автоматику там, где клиент
    просто написал «в городе Орске» (находка ревью 11.09).
    """
    for w in среди:
        if _основа_совпала(лок, w):
            return True
        if len(w) >= 3 and (лок[:-1] == w or лок[:-2] == w or лок[:-1] == w[:-1]):
            return True
    return False


def _город_совпал(город: str, hit: GeoHit) -> bool:
    ожидаем = _слова(город)
    есть = _слова(hit.city)
    return bool(ожидаем) and all(_слово_есть(w, есть) for w in ожидаем)


def _улица_не_шире(улица_карты: str | None, улица_клиента: str, *, с_типом: bool = True) -> bool:
    """Каждое значимое слово улицы карты есть в словах клиента.

    Именно в эту сторону: клиент написал «Октября 5», карта нашла «улица 40
    лет Октября» — слов «40» и «лет» клиент не писал, значит это не его улица.
    Обратное направление («слова клиента есть у карты») такой подмены не
    ловит. `с_типом=False` — тип улицы не сверяется (`city_disputes_street`:
    та же улица без спора о типе); все сторожа слов остаются.
    """
    # ⚠ ВИД НЕЖИЛОГО ОБЪЕКТА — НЕ ИМЯ И НЕ ЗВАНИЕ (25.09, Тамбов: «<имя> N» лёг
    # в карточку «тер гаражно-строительный кооператив <Имя>-k, N, Тамбов» с
    # приблизительной точкой, а клиент живёт в микрорайоне соседнего посёлка).
    # Ниже слова карты перед совпавшим прощаются как опущенные имя и звание, и
    # «гаражно-строительный кооператив» прощался так же. Гараж клиент назвал
    # бы сам; не назвал — это не его улица, и жилой дом с тем же именем её не
    # делит.
    if _гаражный(улица_карты) and not _гаражный(улица_клиента):
        return False
    свои = [w for w in _слова(улица_клиента) if w not in _СЛОВА_ТИПА]
    чужие = [
        w
        for w in _слова(улица_карты)
        if w not in _СЛОВА_ТИПА and (len(w) > 1 or w.isdigit()) and w not in _СЛОВА_РАЙОНА_СПБ
    ]
    if not свои and not чужие:
        # «Набережная 7» ↔ «Набережная улица» (стенд 13.09): тип и есть имя;
        # без типов сравнивать нечего — сравниваем сами слова.
        свои = _слова(улица_клиента)
        чужие = [w for w in _слова(улица_карты) if w not in {"улица", "ул"}]
    if not _слова_не_шире(чужие, свои) and not _составное_частями(чужие, свои):
        return False
    # `city_disputes_street`: та же улица без спора о типе.
    if not с_типом:
        return True
    # Тип улицы, если клиент его назвал, обязан совпасть с типом карты:
    # «Комсомольский проспект» и «Комсомольская улица» — разные улицы с одной
    # основой, и по словам их не различить.
    свой_тип = _тип_улицы(улица_клиента)
    # У карты типов может быть два («ул Николаевский проспект» у DaData, Самара,
    # стенд 13.09): годится любой из них.
    чужие_типы = _типы_улицы(улица_карты)
    return свой_тип is None or not чужие_типы or свой_тип in чужие_типы


def _составное_частями(чужие: list[str], свои: list[str]) -> bool:
    """«Николая-Ольхова 31» (владелец 25.09, Чита): имя и фамилия через дефис
    у клиента, «улица Николая Ольхова» у карты — одно слово против двух, и
    вердикт отвечал «улица не та», хотя карта нашла тот самый дом. Составное
    слово клиента читается частями, но только когда КАЖДАЯ часть есть у
    карты: «Ново-Садовая» — не «Садовая» (разные улицы одного города), и
    лишнее слово клиента здесь не прощается, как прощается отдельное."""
    составные = [w for w in свои if "-" in w]
    if not составные or not all(_слово_есть(ч, чужие) for ч in _без_дефисов(составные)):
        return False
    return _слова_не_шире(чужие, _без_дефисов(свои))


def _слова_не_шире(чужие: list[str], свои: list[str]) -> bool:
    """Слова улицы карты против слов клиента, типы уже сняты: ядро
    `_улица_не_шире` без сверки типа."""
    if not чужие or not свои:
        return False
    # Инициал у клиента («С.Перовской») закрывает слово карты с той же буквы
    # («Софьи»): человек назвал имя, только коротко.
    инициалы = {w for w in свои if len(w) == 1 and w.isalpha()}
    # ⚠ ИМЯ, ЗВАНИЕ И ПОРЯДКОВЫЙ НОМЕР ЛЮДИ ОПУСКАЮТ (владелец 12.09: «люди очень
    # часто сокращают названия»; замер по 60 отказам боя: «Дзержинского» ↔
    # «улица Феликса Дзержинского», «Лебедя» ↔ «улица Генерала А.И.Лебедя»,
    # «Гайнуллина» ↔ «улица Рифката Гайнуллина», «Правда» ↔ «улица им. газеты
    # «Правда»», «Павла Морозова» ↔ «улица Морозова Павла Леонтьевича»).
    # Лишние слова карты допустимы, если хотя бы одно слово клиента совпало и
    # каждое лишнее — либо стоит ПЕРЕД первым совпавшим (имя, звание, «1-й»,
    # «им. газеты»), либо имя/звание из словаря, либо отчество. Слово ПОСЛЕ
    # совпавшего, которое не отчество, — другая улица. Две улицы, подошедшие
    # так обе («1-й» и «2-й Красноармейский»), дадут «неоднозначно» и варианты.
    совпавшие = [i for i, w in enumerate(чужие) if _слово_есть(w, свои) or w[0] in инициалы]
    if not совпавшие:
        return False
    # Число, которое клиент НАЗВАЛ, обязано быть у карты: «31-й комплекс» и
    # «32-й комплекс» (Набережные Челны, 18.09) — разные адреса, а число перед
    # именем иначе прощалось как опущенный «2-й» у «Красноармейского».
    if any(w.isdigit() and w not in чужие for w in свои):
        return False
    первое = совпавшие[0]
    for i, w in enumerate(чужие):
        if i in совпавшие:
            continue
        if i < первое or w in _ИМЯ_ИЛИ_ЗВАНИЕ or _ОТЧЕСТВО.search(w):
            continue
        return False
    return True


#: Имена в родительном падеже и звания, которые стоят ПЕРЕД фамилией в названии
#: улицы и которые клиент опускает: «Феликса Дзержинского» → «Дзержинского»,
#: «Академика Сахарова» → «Сахарова». Список — самые частые имена улиц-персон
#: и титулы; фамилию без имени клиент пишет всегда, а вот имя — почти никогда.
_ИМЯ_ИЛИ_ЗВАНИЕ = frozenset(
    """феликса карла розы клары софьи веры максима гавриила александра алексея андрея антона
бориса вадима валентина валерия василия виктора виталия владимира владислава вячеслава
геннадия георгия григория даниила дмитрия евгения егора ивана игоря ильи иосифа кирилла
константина леонида льва михаила николая олега павла петра романа семена сергея степана
федора юрия якова аркадия ефима емельяна лазаря самуила исаака моисея матвея тараса богдана
анны марии ольги елены татьяны натальи зои любови надежды валентины ульяны марины ларисы
галины тамары лидии ирины светланы полины юлии екатерины александры анатолия артема
вениамина всеволода глеба давида демьяна ерофея захара зиновия иннокентия исидора клима
кузьмы макара марка мирона назара никиты нестора платона прокопия ростислава савелия
тимофея тихона трофима фомы харитона юлиана
имени им академика маршала генерала адмирала полковника майора капитана лейтенанта
сержанта космонавта героя героев братьев сестер профессора доктора святого святой князя
писателя поэта композитора художника архитектора летчика партизана комиссара""".split()
)

#: Отчество в названии улицы у карты («Морозова Павла Леонтьевича»).
_ОТЧЕСТВО = re.compile(r"(?:вич|вича|вичем|вна|вны|вной|ич|ича|ична|ичны)$")

#: Сокращения гаражного кооператива в имени улицы («тер ГСК …», «тер. ГК …»);
#: полные слова («гаражно-строительный», «гаражный», «гаражи») — по началу.
_ГАРАЖНЫЕ_СОКРАЩЕНИЯ = frozenset({"гск", "гк", "гпк", "пгк", "гспк", "гэк"})


def _гаражный(улица: str | None) -> bool:
    """В имени улицы — гаражный кооператив (сторож `_улица_не_шире`)."""
    return any(w.startswith("гараж") or w in _ГАРАЖНЫЕ_СОКРАЩЕНИЯ for w in _слова(улица))


#: Ориентиры петербуржцев внутри названия улицы у карты: «12-я линия В.О.»,
#: «Большой проспект Петроградской стороны». Разбор их гасит, карта возвращает.
_СЛОВА_РАЙОНА_СПБ = frozenset({"васильевского", "острова", "петроградской", "стороны", "во", "пс"})


def _тип_улицы(улица: str | None) -> str | None:
    for w in _слова(улица):
        if w in _ТИПЫ_УЛИЦ:
            return _ТИПЫ_УЛИЦ[w]
    return None


def _типы_улицы(улица: str | None) -> set[str]:
    return {_ТИПЫ_УЛИЦ[w] for w in _слова(улица) if w in _ТИПЫ_УЛИЦ}


# --- строка в формате карт ---------------------------------------------------


def format_address(hit: GeoHit, parsed: Parsed, *, with_settlement: bool = False) -> str:
    """«Звенигородская улица, 1, посёлок Заречный, Орск» — как в картах.

    ``with_settlement`` — пункт печатается всегда: у ВАРИАНТОВ он и есть то,
    чем адреса различаются («Ленина 5» в Кречевицах и в Панковке).

    Тип населённого пункта берётся из слов клиента («п» → «посёлок»), потому
    что карта OSM отдаёт «Заречный» без типа, а тот же `suburb` у неё бывает
    и городским районом («Форштадт»): выдумывать «посёлок Форштадт» нельзя.
    Без типа от клиента пункт идёт голым именем — это правда, а не догадка.
    Яндекс тип отдаёт сам, и он остаётся как есть.
    """
    куски: list[str] = []
    # Улица клиента — микрорайон у карты (19.09, «Пугачева 9» ↔ «микрорайон
    # Пугачёва», улицы у ответа нет): место печатается на месте улицы, а не
    # после дома («микрорайон Пугачёва, 9, Старый Оскол»), и второй раз
    # пунктом не идёт.
    место_улицей = (
        _место_улицей(parsed.street, hit) if not hit.street and parsed.street.strip() else None
    )
    if hit.street:
        куски.append(_без_скобок(hit.street))
    elif место_улицей:
        куски.append(_без_скобок(место_улицей))
    if hit.house:
        куски.append(hit.house)
    массив = (hit.area or "").strip()
    if (
        массив
        and _норм(массив) not in _норм(hit.street)
        and _норм(массив) != _норм(hit.settlement)
        and _норм(массив) != _норм(место_улицей)
        and any(
            _пункт_назван(_норм(своё), _слова(массив))
            for своё in (parsed.settlement, parsed.area)
            if своё
        )
    ):
        # Массив, который клиент назвал сам («ДНТ Лесная поляна, ул Прямая
        # 3»): мастеру он нужен не меньше улицы — по нему въезд и шлагбаум.
        куски.append(массив)
    пункт = (hit.settlement or "").strip()
    назван_клиентом = bool(
        parsed.settlement and пункт and _пункт_назван(_норм(parsed.settlement), _слова(пункт))
    )
    if (
        пункт
        and _норм(пункт) != _норм(hit.city)
        and _норм(пункт) not in _норм(hit.street)
        and _норм(пункт) != _норм(место_улицей)
    ):
        if (
            назван_клиентом
            and parsed.settlement_type
            and not _норм(пункт).startswith(_норм(parsed.settlement_type))
        ):
            куски.append(f"{parsed.settlement_type} {пункт}")
        elif назван_клиентом or hit.settlement_kind == "place" or with_settlement:
            куски.append(пункт)
        # Городской район, которого клиент не называл, в адрес не идёт.
    if hit.city:
        куски.append(hit.city)
    return ", ".join(к for к in куски if к)


def address_text(
    *,
    geo_formatted: str | None,
    geo_status: str | None,
    value: str,
    parts: dict[str, str | None],
    district: str | None = None,
    area: str | None = None,
) -> str:
    """Текст, который ложится в `clients.address` из строки-кандидата.

    ⚠ ОДИН СБОРЩИК НА «ПОДТВЕРДИТЬ» И НА АВТОЗАПИСЬ. Строка карты — когда
    она есть, иначе «улица, дом» клиента; части (квартира, подъезд, этаж,
    домофон) — всегда, потому что мастеру они нужны не меньше улицы, а до
    11.09 кнопка «Подтвердить» их теряла.

    Строка карты (`geo_formatted`) записывается ровно в двух случаях: дом
    подтверждён (`exact`, все семь мест записи) и — с 18.09 — отказ по
    содержанию, при котором карта знает улицу клиента (строка улицы с номером
    клиента, степень `text`, пишет только воркер под сторожем STREET_KNOWN);
    сброс вердикта её стирает. Поэтому сборщик верит самой строке, а не
    статусу: у прежних строк это то же «строка карты только при exact».
    `geo_status` остаётся в подписи ради журнала и старых вызовов.
    """
    основа = geo_formatted or value
    хвост: list[str] = []
    if parts.get("office"):
        хвост.append(f"кв {parts['office']}")
    if parts.get("entrance"):
        хвост.append(f"подъезд {parts['entrance']}")
    if parts.get("floor"):
        хвост.append(f"этаж {parts['floor']}")
    if parts.get("intercom"):
        хвост.append(f"домофон {parts['intercom']}")
    # Район словами клиента («район Бугор») — мастеру ориентир; строка карты
    # его не знает, а сам клиент назвал не зря.
    if district and _норм(district) not in _норм(основа):
        хвост.append(district)
    # Микрорайон/квартал словами клиента («микрорайон 9», владелец 19.09,
    # Волжский): строка карты его не пишет, а в микрорайонных городах мастер
    # едет по нему — не меньше, чем по улице.
    if area and _норм(area) not in _норм(основа) and _норм(area) != _норм(district or ""):
        хвост.append(area)
    return ", ".join([основа, *хвост])
