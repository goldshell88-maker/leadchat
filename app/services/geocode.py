#: Слова, которые в имени места — тип, а не имя: «ЖК», «село», «жилой
#: комплекс», «район». Сверяются только имена.
_ТИПЫ_МЕСТА = frozenset({"жк", "жилой", "комплекс", "район", "р-н", "округ", "тер", "территория"})


def yandex_place_hit(place: Place, city: City | None, hits: list[GeoHit]) -> PlaceHit | None:
    """Место у Яндекс-геокодера после отказа DaData (владелец 18.09: «ЖК
    Дубровино» при объявлении в Москве — DaData `not_found`, Яндекс на «Москва,
    ЖК Дубровино» отдаёт первым `settlement='ЖК Дубровино', city='село
    Дубровино', region='Москва'`, дальше мусор вплоть до Ташкентской области).

    Два обязательных сторожа: РЕГИОН (`region_matches`) и СЛОВА МЕСТА — все
    значимые слова места клиента есть в settlement/city ответа. Город, названный
    клиентом (`locality`), — тоже словами. Город объявления не сверяется:
    пункт-спутник («ЖК Дубровино» у Москвы) в черте города не лежит — потому
    и названный клиентом город объявления или регион ответа («Москва, ЖК
    Дубровино»: `city='село Дубровино', region='Москва'`) словами места не
    сверяется, регион за него уже проверен (ревью 19.09). Первый прошедший
    ответ — место со степенью «приблизительно» (`card_grade`, `kind=place`).
    """
    if city is None:
        return None
    слова = _без_дефисов(
        [
            w
            for w in _слова(place.query_text)
            if len(w) >= 3
            and w not in _ТИПЫ_МАССИВА
            and w not in _ТИПЫ_МЕСТА
            and w not in _ШУМ_СТРОКИ_КАРТЫ
        ]
    )
    if not слова:
        return None
    for h in hits:
        if not region_matches(city.region, h.region):
            continue
        места = _без_дефисов(_слова(h.settlement) + _слова(h.city))
        if not all(_слово_есть(w, места) for w in слова):
            continue
        if (
            place.locality
            and not _регион_вместо_города(city)
            and not _город_места_назван(place.locality, city, h, места)
        ):
            continue
        имя = h.settlement or h.city or ""
        массив = bool(place.area and not place.settlement)
        # Раскладка — как у разбора DaData на шлюзе: у массива имя лежит в
        # `area`, у пункта — в `settlement`; иначе `format_place` напечатал бы
        # имя дважды («ЖК Дубровино, ЖК Дубровино, село Дубровино»). Пункт
        # Яндекса — сам массив, родитель у него в `city`.
        return PlaceHit(
            name=имя,
            kind="area" if массив else "settlement",
            settlement=None if массив else имя,
            area=имя if массив else None,
            city=h.city if _норм(h.city) != _норм(имя) else None,
            district=None,
            region=h.region,
            lat=h.lat,
            lon=h.lon,
        )
    return None


def _город_места_назван(locality: str, city: City, h: GeoHit, места: list[str]) -> bool:
    """Город, названный клиентом рядом с местом, есть в ответе Яндекса —
    словами пункта/города, либо это город самого объявления или регион
    ответа: у пункта-спутника («ЖК Дубровино», `city='село Дубровино'`,
    `region='Москва'`) слова «Москва» в пункте и городе нет, и сторож слов
    гасил бы случай владельца, стоит клиенту написать «Москва, ЖК Дубровино».
    Чужой город («Подольск») ни тем, ни другим не проходит."""
    ожидаем_город = _норм(locality).split()
    if all(_город_назван(w, места) for w in ожидаем_город):
        return True
    return _норм(locality) == _норм(city.name) or region_matches(locality, h.region)


