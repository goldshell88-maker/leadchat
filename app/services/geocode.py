def build_query(parsed: Parsed, city: City | None) -> Query | None:
    """Запрос к карте из разбора и города объявления. Без города — None.

    Слаг-регион («Москва и МО») городом не является: в запрос уходит только
    регион, а город результата не проверяется — проверяется регион.
    """
    if city is None:
        return None
    город = None if _регион_вместо_города(city) else city.name
    return Query(
        region=city.region,
        city=город,
        settlement=_пункт_для_карты(parsed),
        street=_улица_для_карты(parsed),
        house=parsed.house,
    )


def _пункт_для_карты(parsed: Parsed) -> str | None:
    """Пункт клиента для запроса. Массив с участками — с типом (18.09:
    «Светлый 23» по Бурятии карта примет за село или улицу Светлую, «СНТ
    Светлый 23» — за участок массива). Микрорайон и квартал так не помечаем:
    без типа их карта находила и раньше, а лишнее слово в запросе меняет её
    ответ."""
    пункт = parsed.settlement.strip().title() if parsed.settlement else None
    тип = _ТИПЫ_МАССИВА_С_УЧАСТКАМИ.get(_норм(parsed.settlement_type or ""))
    if пункт and тип:
        return f"{тип} {пункт}"
    return пункт


def _улица_для_карты(parsed: Parsed) -> str:
    """Дом без улицы в массиве («СНТ Рассвет, 17» внутри деревни): массив и
    есть улица — так его и спрашиваем у карты."""
    return parsed.street.strip() or (parsed.area or "")


def build_country_query(parsed: Parsed) -> Query | None:
    """Запрос без области — поиск по стране (владелец 18.09: «поиск по стране
    при неизвестном городе — да»).

    Город назвал клиент — `city=locality` (DaData `locations=[{city}]`); не
    назвал — `city=None`, и `locations` пустой: вся страна (шлюз,
    `locations_for(region=None, city=None)`). Пункт — как у `build_query`
    (тип массива с участками — префиксом). Без дома или без улицы/массива —
    None: место по стране не ищем (у мест свой путь), а голый номер по стране
    — шум.
    """
    if not parsed.house.strip() or not (parsed.street.strip() or parsed.area):
        return None
    город = (parsed.locality or "").strip() or None
    return Query(
        region=None,
        city=город,
        settlement=_пункт_для_карты(parsed),
        street=_улица_для_карты(parsed),
        house=parsed.house,
    )


def _регион_вместо_города(city: City) -> bool:
    return "и мо" in _норм(city.name) or "и область" in _норм(city.name)


def verdict(
    parsed: Parsed, city: City | None, hits: list[GeoHit], *, family: bool = False
) -> tuple[str, GeoHit | None]:
    """Вердикт по ответам карты: статус и выбранный дом (только при `exact`).

    Порядок сторожей — от «карта вообще не нашла» к «нашла, но не то». Первый
    несошедшийся даёт имя отказу. `ambiguous` — все сошлись, а домов несколько:
    «Ленина 5» в двух посёлках одного округа.

    `family=True` — когда точного ключа нет, дом ищется и семьёй («29» ↔
    «29А», `house_family_match`): правило (8) автопривязки, только с пометкой
    «приблизительно» у вызывающего. При точном ключе в ответах вердикт с
    семьёй и без неё один и тот же.
    """
    статус, по_улице = _годные_дома(parsed, city, hits, family=family)
    if статус is not None:
        return статус, None
    # ⚠ РАЗНЫЕ ТОЧКИ ОДНОГО АДРЕСА — ЭТО ОДИН АДРЕС (бой 12.09: «Большая
    # Санкт-Петербургская, 27» в Великом Новгороде — четыре строения OSM
    # с одним номером, и карта просила «уточните посёлок»). Неоднозначность —
    # только когда РАЗНЫЕ адреса: другой посёлок, другая улица того же названия.
    группы = distinct_addresses(по_улице)
    if len(группы) > 1:
        return GEO_AMBIGUOUS, None
    return GEO_EXACT, группы[0]


def _годные_дома(
    parsed: Parsed,
    city: City | None,
    hits: list[GeoHit],
    *,
    family: bool = False,
    с_типом: bool = True,
) -> tuple[str | None, list[GeoHit]]:
    """Сторожа вердикта по порядку; первый несошедшийся — именем отказа и
    пустым списком. Все сошлись — `None` и дома клиента (ещё не сведённые к
    разным адресам): по ним `verdict` решает exact/ambiguous, а правила
    автопривязки (`_groups`) выбирают среди неоднозначных. `с_типом=False` —
    улицы сравниваются без хвоста типа (только `city_disputes_street`)."""
    if city is None:
        return GEO_NO_CITY, []
    if not hits:
        return GEO_NOT_FOUND, []
    дома = [h for h in hits if h.house_level and h.house and not h.interpolated]
    if not дома:
        return GEO_HOUSE_MISSING, []

    ключ = house_key(parsed.house)
    тот_дом = [h for h in дома if house_key(h.house) == ключ]
    if not тот_дом and family:
        тот_дом = [h for h in дома if house_family_match(h.house, parsed.house)]
    if not тот_дом:
        return GEO_HOUSE_MISMATCH, []

    в_регионе = [h for h in тот_дом if region_matches(city.region, h.region)]
    if not в_регионе:
        return GEO_REGION_MISMATCH, []

    # Город, названный клиентом словами, обязан быть в ответе — иначе он
    # пишет из другого города, и город объявления карте подсказал не то.
    # А если он в ответе — ГОРОД КЛИЕНТА ВАЖНЕЕ ГОРОДА ОБЪЯВЛЕНИЯ (владелец
    # 14.09: «Город Щёлково … 14 корпус 3» при объявлении в Ивантеевке —
    # дом в Щёлкове и есть тот дом, а не «есть в области, проверьте вариант»).
    if parsed.locality:
        # Каждое слово города обязано быть в ответе: «Верхняя Пышма» ≠
        # «Верхняя Салда» (ревью 14.09: сторож по одному слову делал точным
        # дом-тёзку по первому слову двухсловного города).
        слова_города = _норм(parsed.locality).split()
        в_городе = [
            h
            for h in в_регионе
            if all(_город_назван(w, _слова(h.city) + _слова(h.settlement)) for w in слова_города)
        ]
        if not в_городе:
            return GEO_OTHER_CITY, []
    elif not _регион_вместо_города(city):
        в_городе = [h for h in в_регионе if _город_совпал(city.name, h)]
    else:
        в_городе = в_регионе

    if parsed.settlement:
        # ПУНКТ, НАЗВАННЫЙ КЛИЕНТОМ, ВАЖНЕЕ ГОРОДА ОБЪЯВЛЕНИЯ (бой 12.09:
        # «Малиновка, пер Тихий 2» при объявлении в Костроме — деревня
        # Костромского района, и дом там найден; карта предлагала выбирать
        # из двух переулков). Ищем среди домов ОБЛАСТИ, не города. Не нашёлся —
        # отказ, а не дом в городе объявления: клиент назвал другое место.
        # Пункт клиента у карты бывает и массивом («ДНТ Лесная поляна» —
        # `area`, 18.09): смотрим во все места ответа.
        пункт = _норм(parsed.settlement)
        с_пунктом = [h for h in в_регионе if _пункт_назван(пункт, _места_ответа(h))]
        if с_пунктом:
            в_городе = с_пунктом
        elif _норм(parsed.settlement_type or "") not in _ТИПЫ_МАССИВА_МЯГКИЕ:
            return GEO_SETTLEMENT_MISMATCH, []
        # Микрорайон, ЖК, квартал города («Калуга, мкр Кошелев, ул Андрея
        # Сидорова 3» — владелец 15.09) карта в адресе дома пишет редко: это
        # уточнение внутри города, а не другой пункт — дом в городе годится.
    if not в_городе:
        return GEO_CITY_MISMATCH, []

    # Дом по пункту без улицы («посёлок Каменка, 9», бой 13.09): улицы нет
    # ни у клиента, ни у карты — пункт уже сверен выше. Массив без улицы
    # («д. Ивняково, СНТ Рассвет, 17», 18.09) — улицей служит массив: карта
    # пишет его улицей («тер. СНТ Рассвет»), массивом или пунктом.
    по_улице = [h for h in в_городе if _улица_сошлась(parsed, h, с_типом=с_типом)]
    if not по_улице:
        return GEO_STREET_MISMATCH, []
    return None, по_улице


def city_disputes_street(
    parsed: Parsed, city: City | None, city_hits: list[tuple[list[GeoHit], str]]
) -> bool:
    """Город объявления сам спорит об улице (ревью N24, 19.09): карты ПО ГОРОДУ
    вместе не нашли дом клиента на улице его типа, но нашли дом с его номером,
    в его городе/пункте, на улице с ТОЙ ЖЕ основой и чужим типом («ул Ленина 5»
    ↔ «пр-кт Ленина, д 5»). Люди пишут «ул» ко всему, и такой дом — самое
    вероятное прочтение; спор о типе решается внутри города (очередь N6), а не
    областью: одноимённая улица нужного типа в пригороде здесь — подмена.

    Сторожа — ровно те, что у вердикта (`_годные_дома`: номер, регион,
    город/пункт клиента, слова `locality`), только сравнение улиц без хвоста
    типа. Отказ по основе («ул Мира, 5» при «ул Ленина 5») спором не
    считается; другой номер — `house_mismatch`, другой город — `city_mismatch`,
    клиент без типа — вердикт `exact`. Ответы всех карт города судятся ВМЕСТЕ:
    нашла хоть одна улицу нужного типа с домом — спора нет (вердикт и не был бы
    «улица не та»)."""
    hits = [h for hs, _ in city_hits for h in hs]
    статус, _ = _годные_дома(parsed, city, hits)
    if статус != GEO_STREET_MISMATCH:
        return False
    статус_без_типа, _ = _годные_дома(parsed, city, hits, с_типом=False)
    return статус_без_типа is None


def house_family_match(a: str | None, b: str | None) -> bool:
    """«29» ↔ «29А», «12» ↔ «12 к 2» — одна семья дома: ведущее число равно,
    ключи разные, один из ключей — голое число (чистая версия
    `clients._одна_семья_дома` по номерам, без строк карты). «29А» ↔ «29Б» —
    два дома, не семья; `formatted_key` («12Е» ≠ «12») не трогается."""
    номер_a = re.match(r"\d+", (a or "").strip())
    номер_b = re.match(r"\d+", (b or "").strip())
    if not номер_a or not номер_b:
        return False
    число_a = re.sub(r"^0+(?=\d)", "", номер_a.group(0))
    число_b = re.sub(r"^0+(?=\d)", "", номер_b.group(0))
    if число_a != число_b:
        return False
    ключ_a, ключ_b = house_key(a), house_key(b)
    return ключ_a != ключ_b and число_a in (ключ_a, ключ_b)


def fraction_head(parsed: Parsed) -> tuple[str, str] | None:
    """«13/38» → («13», «38»): голова и хвост дроби, обе непустые; «13/»,
    «/38», без дроби — None. «1/2/3» → («1», «2/3»): хвост не число, квартира
    из него не берётся."""
    if "/" not in parsed.house:
        return None
    голова, хвост = parsed.house.split("/", 1)
    голова, хвост = голова.strip(), хвост.strip()
    if not голова or not хвост:
        return None
    return голова, хвост


def flat_from_fraction(хвост: str) -> str | None:
    """Хвост дроби — квартира, если это число от 10 («4/27» → кв 27); «14/2»,
    «1/2/3», «09» — нет: корпус или дробь дома. ОДНО определение на правило
    (`_fraction_head`) и на сетевые походы головой (воркер: тратить ли вторую
    карту и область на «N»); число — посылка правила 18.09, корпусом 20.09 она
    подтверждается слабо (скептик: среди отказов с M ≥ 10 дома-дроби и квартиры
    поровну), поэтому она живёт в одном месте, а не в трёх."""
    return хвост if хвост.isdigit() and int(хвост) >= 10 else None


def corner_numbering(parsed: Parsed, city: City | None, hits: list[GeoHit]) -> bool:
    """На улице клиента у карты есть ДРУГОЙ дом с дробью в номере («28/7»,
    «32/3» на Казачьей в Новочеркасске) — угловая нумерация: «30/95» здесь
    дом, а не дом 30 с квартирой 95. Улика лежит прямо в ответах (DaData
    отдаёт соседей по улице), сети не стоит; при ней хвост квартирой не
    пишется и голову у карт не спрашивают (скептик 20.09, А-2).

    Считаются только дома на улице клиента В ЕГО МЕСТЕ — теми же сторожами,
    что у `known_street` (`_улица_клиента`: регион, улица, названный пункт или
    город, иначе сам город объявления): в пул попадают ответы Яндекса по
    городу и области — дома других городов региона, а «Ленина, 24/7» на
    одноимённой улице в соседнем городе (корпус ФИАС пишет дробью) о нумерации
    улицы клиента не говорит ничего; он гасил квартиру у городской ветки дроби
    и походы головой А1/А2 (ревью 20.09, C4)."""
    if city is None:
        return False
    ключ = house_key(parsed.house)
    return any(
        h.house
        and "/" in h.house
        and house_key(h.house) != ключ
        and _улица_клиента(parsed, city, h)
        for h in hits
    )


#: Две точки ближе этого — один дом (≈70 м): «ул Горького, 12Б, Королёв» и
#: «…, 12Б, Первомайский, Королёв» у DaData — одна и та же «двенадцать Б»
#: (стенд 13.09), микрорайон в одном ответе назван, в другом нет.
_ОДИН_ДОМ_ГРАДУСОВ = 0.0007


def distinct_addresses(hits: list[GeoHit]) -> list[GeoHit]:
    """Первый дом каждого РАЗЛИЧНОГО адреса: улица + дом + пункт + город;
    дома с тем же номером на той же улице, стоящие в одной точке, — один."""
    видели: set[tuple[str, str, str, str]] = set()
    out: list[GeoHit] = []
    for h in hits:
        ключ = (_норм(h.street), house_key(h.house), _норм(h.settlement), _ядро_города(h.city))
        if ключ in видели:
            continue
        if any(
            house_key(o.house) == ключ[1]
            and _норм(o.street) == ключ[0]
            and abs(o.lat - h.lat) < _ОДИН_ДОМ_ГРАДУСОВ
            and abs(o.lon - h.lon) < _ОДИН_ДОМ_ГРАДУСОВ * 2
            for o in out
        ):
            continue
        видели.add(ключ)
        out.append(h)
    return out


_АДМИНИСТРАТИВНОЕ = re.compile(r"\b(?:городской|муниципальн\w*|округ|район)\b")


def _ядро_города(s: str | None) -> str:
    """«городской округ Великий Новгород» и «Великий Новгород» — один город."""
    return " ".join(_АДМИНИСТРАТИВНОЕ.sub(" ", _норм(s)).split())


# --- точка дома ----------------------------------------------------------------

#: Хвост имени провайдера в строке, у которой вердикт `exact`, а точка —
#: приблизительная: улицы или пункта, не дома (DaData `qc_geo` 2/3, и вторая
#: карта точку дома не дала). Экран читает хвост и пишет «точка
#: приблизительная»; сторожа по имени карты (`endswith("nominatim")`,
#: `startswith("speller+")`) его не задевают.
POINT_APPROX_SUFFIX = "~approx"


def mark_approx(provider: str) -> str:
    return provider if POINT_APPROX_SUFFIX in provider else provider + POINT_APPROX_SUFFIX


def point_is_approx(provider: str | None) -> bool:
    """Хвост читается подстрокой, не концом строки (контракт 18.09): за ним
    может стоять ещё пометка («dadata~approx~picked»), и `endswith` её бы
    не увидел."""
    return bool(provider) and POINT_APPROX_SUFFIX in str(provider)


#: Хвост политики `suggest` (пакет 6.0а): решение правила лежит в строке
#: (статус, точка, строка карты), но в карточку не идёт — `card_grade` → None
#: одной строкой в единственном судье. Принятие оператором снимает хвост
#: (`strip_suggest`), и степень строки становится той, что записана правилом.
POINT_SUGGEST_SUFFIX = "~suggest"


def mark_suggest(provider: str) -> str:
    return provider if POINT_SUGGEST_SUFFIX in provider else provider + POINT_SUGGEST_SUFFIX


def point_is_suggest(provider: str | None) -> bool:
    return bool(provider) and POINT_SUGGEST_SUFFIX in str(provider)


def strip_suggest(provider: str | None) -> str | None:
    """Снять хвост предложения — при принятии человеком; `~approx` остаётся."""
    if provider is None:
        return None
    return provider.replace(POINT_SUGGEST_SUFFIX, "") or None


def card_grade(
    kind: str | None,
    geo_status: str | None,
    geo_provider: str | None,
    geo_lat: float | None,
    geo_lon: float | None,
    geo_formatted: str | None,
) -> str | None:
    """ЕДИНСТВЕННЫЙ судья «что идёт в карточку» (контракт 18.09, п. 3).

    `exact` — дом с точкой дома; `approx` — точка есть, но приблизительная:
    хвост `~approx` у провайдера (точка улицы/массива/пункта, выбор среди
    нескольких, город от карты) или МЕСТО (`kind=place`) — точка пункта или
    массива всегда центр, хотя `_geocode_place` хвоста не ставит; `text` —
    отказ по содержанию (`REFUSAL_STATUSES`), у которого воркер записал
    строку улицы (сторож STREET_KNOWN, `known_street`) — адрес без точки;
    `None` — в карточку не идёт: ещё проверяется, выбор из нескольких, отказ
    без строки улицы, а также `exact` без координат (инвариант нарушен —
    такой строке верить нельзя).

    Ворота воркера, автозаписи и карточки читают только эту функцию; участок
    карточки зовёт её через `clients.candidate_grade(row)`.

    Хвост `~suggest` (политика правила `suggest`, §0.3) — не степень: решение
    ждёт нажатия оператора, и в карточку само не идёт ни точкой, ни текстом.
    """
    if point_is_suggest(geo_provider):
        return None
    if geo_status == GEO_EXACT:
        if geo_lat is None or geo_lon is None:
            return None
        if kind == KIND_PLACE or point_is_approx(geo_provider):
            return GRADE_APPROX
        return GRADE_EXACT
    if geo_status in REFUSAL_STATUSES and geo_formatted:
        return GRADE_TEXT
    return None


#: Ранги силы вердикта (пакет 5, 20.09) — для сравнения при пересуде. Больше
#: — сильнее. Ранги 0 и 1 в карточку не идут оба; различие — слово оператору.
RANK_NONE = 0
RANK_NAMED_REFUSAL = 1
RANK_VARIANTS = 2
RANK_TEXT = 3
RANK_APPROX = 4
RANK_EXACT = 5


def verdict_rank(
    kind: str | None,
    geo_status: str | None,
    geo_provider: str | None,
    geo_lat: float | None,
    geo_lon: float | None,
    geo_formatted: str | None,
    geo_variants: list[dict[str, Any]] | None,
) -> int:
    """Сила вердикта по УЛИКАМ в строке, не по имени статуса (пакет 5, 20.09).

    Улика — то, что видит карточка (`card_grade`: точка дома, приблизительная
    точка, строка улицы) или оператор (варианты, слово о причине отказа).
    Считается через `card_grade` — второго определения «что такое улика» не
    появляется (контракт 18.09, п. 3). Варианты — ранг 2 при ЛЮБОМ статусе
    (`other_city_in_text` с вариантами по стране — тоже выбор оператору), а не
    только у `REQUEUE_STATUSES` (ревью 20.09). Ранг 1 — именованный отказ без
    улик: `other_city_in_text`/`settlement_mismatch` несут оператору причину,
    переписать их пустым `not_found` — потеря. Ранг 0 — `not_found`, `no_city`,
    `pending`, `error`, `blocked`, `ambiguous` без вариантов, `exact` без точки.
    """
    степень = card_grade(kind, geo_status, geo_provider, geo_lat, geo_lon, geo_formatted)
    if степень == GRADE_EXACT:
        return RANK_EXACT
    if степень == GRADE_APPROX:
        return RANK_APPROX
    if степень == GRADE_TEXT:
        return RANK_TEXT
    if geo_variants:
        return RANK_VARIANTS
    if geo_status in REFUSAL_STATUSES and geo_status != GEO_NOT_FOUND:
        return RANK_NAMED_REFUSAL
    return RANK_NONE


def keeps_previous(rank_new: int, rank_prev: int, maps_incomplete: bool) -> bool:
    """Монотонность пересуда (решение владельца 20.09: «точность должна только
    расти»): прежний вердикт удерживается, когда новый СЛАБЕЕ и вынесен НЕ ВСЕМ
    настроенным набором карт. Все карты в деле и вердикт всё равно слабее — это
    новая информация (карта поправила справочник), и она записывается: правило
    запрещает ухудшение от слепоты, а не ухудшение вообще. Равные ранги не
    удерживают: новый вердикт той же силы свежее."""
    return rank_new < rank_prev and maps_incomplete


def point_precision(
    kind: str | None,
    geo_status: str | None,
    geo_provider: str | None,
    geo_lat: float | None,
    geo_lon: float | None,
) -> str:
    """Степень ТОЧКИ для экрана — тот же судья: exact/approx как у карточки,
    text и «не годна» — `none` (точки нет). Экран хвост провайдера для этого
    не разбирает. Хвост `~suggest` здесь снят: точка предложения на экране —
    настоящая точка правила (exact/approx), а «в карточку не идёт» экран
    читает по `suggest` в `geo_view`, не по степени точки."""
    степень = card_grade(kind, geo_status, strip_suggest(geo_provider), geo_lat, geo_lon, None)
    if степень in (GRADE_EXACT, GRADE_APPROX):
        return степень
    return PRECISION_NONE


def settlement_inside_street(settlement: str, street: str) -> bool:
    """Пункт, все значимые слова которого уже есть в «улице» — микрорайон,
    который карта отдала и пунктом, и улицей («Кедровка» ⊂ «мкр Кедровка»)."""
    слова = [w for w in _слова(settlement) if w not in _СЛОВА_ТИПА and w not in _ТИПЫ_МАССИВА]
    улица = set(_слова(street))
    return bool(слова) and all(w in улица for w in слова)


def precise_point(hit: GeoHit, region: str | None, others: list[GeoHit]) -> GeoHit | None:
    """Тот же дом с точной точкой у другой карты — или None.

    DaData знает дом ФИАС, но точку ставит в центр улицы или пункта (18.09:
    «Лучистая 7к3» — центр мкр Чёрная Речка, 1,4 км от дома; «КП Новая
    Слобода 12» — центр села). Яндекс тот же дом отдаёт с `precision=exact`.
    Берём его координаты, только если это тот же дом: номер, улица и место
    сходятся, регион тот же. Улица массива («тер. СНТ Светлый») у второй
    карты обычно другая («10-я улица») — тогда достаточно, чтобы вторая карта
    назвала сам массив.
    """
    for o in others:
        if not (o.house_level and o.precise and not o.interpolated and o.house):
            continue
        if house_key(o.house) != house_key(hit.house):
            continue
        if region and not region_matches(region, o.region):
            continue
        места = _места_ответа(o, с_массивом_улицей=False)
        то_же_место = any(_пункт_назван(_норм(м), места) for м in (hit.settlement, hit.city) if м)
        if not то_же_место:
            continue
        улица = hit.street or ""
        if not улица:
            continue
        та_же_улица = bool(o.street) and (
            _улица_не_шире(o.street, улица) or _улица_не_шире(улица, o.street or "")
        )
        if та_же_улица or _массив_у_карты(улица, o):
            return dataclasses.replace(hit, lat=o.lat, lon=o.lon, precise=True)
    return None


def _массив_у_карты(улица: str, o: GeoHit) -> bool:
    """«Улица» DaData — массив («тер. СНТ Светлый»), и вторая карта назвала
    его местом (пунктом, массивом или городом)."""
    слова = _слова(улица)
    if not any(w in _ТИПЫ_МАССИВА for w in слова):
        return False
    имя = " ".join(w for w in слова if w not in _ТИПЫ_МАССИВА and w not in _СЛОВА_ТИПА)
    return bool(имя) and _пункт_назван(имя, _места_ответа(o, с_массивом_улицей=False))


def variants(parsed: Parsed, city: City | None, hits: list[GeoHit]) -> list[dict[str, Any]]:
    """Варианты для оператора, когда вердикт не `exact`: дома с нужным номером
    в области, разные адреса — по одному на адрес, не больше :data:`MAX_VARIANTS`.

    Город здесь НЕ обязателен: именно так находится дом в соседнем городе той же
    области (`elsewhere`). Регион обязателен — «Ленина 5» есть в каждой области.
    """
    if city is None:
        return []
    ключ = house_key(parsed.house)
    годные = [
        h
        for h in hits
        if h.house_level
        and h.house
        and not h.interpolated
        and house_key(h.house) == ключ
        and region_matches(city.region, h.region)
        and _улица_сошлась(parsed, h, без_улицы=False)
    ]
    return [
        {
            "formatted": format_address(h, parsed, with_settlement=True),
            "lat": h.lat,
            "lon": h.lon,
            "city": h.city,
        }
        for h in distinct_addresses(годные)[:MAX_VARIANTS]
    ]


#: Пригород (владелец 18.09): единственный дом области не дальше этого от
#: точки города объявления — тот самый дом. Замер месяца: у 49 % строк «в
#: другом месте» единственный найденный дом стоял в 2–19 км от центра города
#: объявления (Реутов → Москва, Мурино → Петербург, Смышляевка → Самара).
SUBURB_KM = 40.0

#: Сосед за забором (владелец 20.09, Липки/Дубки): дом на улице клиента,
#: точный по номеру и улице, стоит не дальше этого от точки НАЗВАННОГО пункта —
#: а самой улицы в названном пункте карта не знает. Не 40 км пригорода: там
#: клиент пункта не называл, здесь мы перебиваем его слово, и круг обязан быть
#: кругом забора. Число — до замера: по OSM дом владельца стоит в 0,6 км от
#: центра Липок, а в круге 3 км вокруг него восемь пунктов и две разные
#: «Новая улица» (скептик 20.09) — «тёзки начинаются с 4–5 км» не подтвердилось.
#: 1,5 км накрывают деревню (радиус ≤ 1 км) и ближний край соседа; дальний край
#: большого посёлка — промах в сторону молчания. Поднимать — только с
#: распределением `rule_km` по живым срабатываниям, не навскидку.
NEIGHBOUR_KM = 1.5


def distance_km(a: tuple[float, float], b: tuple[float, float]) -> float:
    """Расстояние по дуге между двумя точками (широта, долгота), км."""
    la1, lo1, la2, lo2 = (math.radians(x) for x in (*a, *b))
    h = (
        math.sin((la2 - la1) / 2) ** 2
        + math.cos(la1) * math.cos(la2) * math.sin((lo2 - lo1) / 2) ** 2
    )
    return 2 * 6371.0 * math.asin(math.sqrt(h))


def suburb_hit(
    parsed: Parsed,
    city: City | None,
    hits: list[GeoHit],
    city_point: tuple[float, float] | None,
    *,
    radius_km: float = SUBURB_KM,
) -> GeoHit | None:
    """Единственный дом области в пригороде города объявления — или None.

    Тот же отбор, что у `variants` (номер дома, регион, улица): домов с таким
    адресом по области ровно один, и он не дальше `radius_km` от точки города
    объявления. Точки города нет — правило не применяется. Клиент назвал
    другой город (`locality`) или пункт (`settlement`) — дом обязан быть в
    нём: пригород не заменяет слов клиента.
    """
    if city is None or city_point is None:
        return None
    ключ = house_key(parsed.house)
    годные = [
        h
        for h in hits
        if h.house_level
        and h.house
        and not h.interpolated
        and house_key(h.house) == ключ
        and region_matches(city.region, h.region)
        and _улица_сошлась(parsed, h, без_улицы=False)
    ]
    группы = distinct_addresses(годные)
    if len(группы) != 1:
        return None
    (h,) = группы
    if parsed.locality:
        слова_города = _норм(parsed.locality).split()
        if not all(_город_назван(w, _слова(h.city) + _слова(h.settlement)) for w in слова_города):
            return None
    if parsed.settlement and not _пункт_назван(_норм(parsed.settlement), _места_ответа(h)):
        return None
    if distance_km(city_point, (h.lat, h.lon)) > radius_km:
        return None
    return h


def street_in_settlement(
    parsed: Parsed, city: City | None, hits: list[GeoHit], *, с_типом: bool = True
) -> GeoHit | None:
    """Улица клиента в НАЗВАННОМ им пункте — ответ карты без дома (владелец
    16.09, Псков: «деревня Ольхово, ул Кленовая 8» — у ФИАС на этой
    улице дома 1–6, восьмого нет; вместо этого карта предлагала Кленовую, 8
    в Пскове). Точка улицы в деревне — в сотнях метров от дома; чужой дом в
    городе — в сорока километрах. `с_типом=False` — улица считается и при
    чужом типе (сторож соседа за забором: «пер Вишнёвый» в названном пункте
    — уже спор о доме на своей улице, а не о соседе)."""
    if city is None or not parsed.settlement or not parsed.street.strip():
        return None
    пункт = _норм(parsed.settlement)
    for h in hits:
        if (
            h.street
            and region_matches(city.region, h.region)
            and _пункт_назван(пункт, _места_ответа(h))
            and _улица_не_шире(h.street, parsed.street, с_типом=с_типом)
        ):
            return h
    return None


def street_variant(hit: GeoHit, parsed: Parsed) -> dict[str, Any]:
    """Вариант «улица в пункте, дом клиента»: точка — улицы, номер — клиента."""
    с_домом = dataclasses.replace(hit, house=parsed.house, house_level=False)
    return {
        "formatted": format_address(с_домом, parsed, with_settlement=True),
        "lat": hit.lat,
        "lon": hit.lon,
        "city": hit.settlement or hit.city,
    }


def variants_name_settlement(settlement: str, варианты: list[dict[str, Any]]) -> bool:
    """Хоть один вариант — в пункте клиента."""
    пункт = _норм(settlement)
    return any(
        _пункт_назван(
            пункт, _слова(str(v.get("city") or "")) + _слова(str(v.get("formatted") or ""))
        )
        for v in варианты
    )


def known_street(parsed: Parsed, city: City | None, hits: list[GeoHit]) -> GeoHit | None:
    """Сторож STREET_KNOWN: улица (или массив) клиента у карты — в месте
    клиента, в области объявления, и ОДНА: первый подходящий ответ любого
    уровня (дом соседа тоже доказывает улицу) — или None.

    Без него треть «текстов» уровней A/B — не адреса (замер 18.09 по 88
    отказам: «ГГц, 6», «сама стена, 6м», «инвалид, 2», «кабелем СИП, 4»).
    Сторожа те же, что у `suburb_hit`: регион; улица (`_улица_сошлась`,
    без «верю пункту»); слова `locality` клиента в city+settlement ответа;
    `settlement` через `_пункт_назван`; без слов клиента о месте — город
    объявления (`_город_совпал`) или слаг-регион. Улица без дома у карты — не
    подтверждение адреса, а улика: строка улицы в карточку без точки (степень
    `text`) и точка улицы (правило `street_point`).

    Одноимённые улицы в разных пунктах одного города («ул Молодёжная» в
    Красной Глинке и в самой Самаре, ревью 19.09) — та же неоднозначность, что
    у домов (`verdict` → `ambiguous`), и решается тем же признаком, что у
    `_best_of`: клиент пункта не называл — единственная группа в самом городе;
    иначе None, а не первая по порядку карты.
    """
    if city is None or not (parsed.street.strip() or parsed.area):
        return None
    группы = _группы_улиц([h for h in hits if _улица_клиента(parsed, city, h)])
    if not группы:
        return None
    if len(группы) == 1:
        return группы[0][0]
    if parsed.settlement is None and not _регион_вместо_города(city):
        в_городе = [гр for гр in группы if _в_самом_городе(city.name, гр[0])]
        if len(в_городе) == 1:
            return в_городе[0][0]
    return None


def _улица_клиента(parsed: Parsed, city: City, h: GeoHit) -> bool:
    """Ответ карты — улица клиента в его месте (сторожа `known_street`)."""
    if not region_matches(city.region, h.region):
        return False
    if not _улица_сошлась(parsed, h, без_улицы=False):
        return False
    if not _место_клиента_названо(parsed, h):
        return False
    return bool(
        parsed.locality
        or parsed.settlement
        or _регион_вместо_города(city)
        or _город_совпал(city.name, h)
    )


#: Две точки одной улицы у карт дальше этого не лежат: улица с микрорайоном и
#: без него у DaData («ул Горького, Первомайский, Королёв» и «ул Горького,
#: Королёв», стенд 13.09) — один объект ФИАС; одноимённые улицы в пунктах
#: одного города стоят за десятки километров (Красная Глинка — 25 км от
#: центра Самары).
_ОДНА_УЛИЦА_KM = 2.0

_КлючУлицы = tuple[tuple[str, ...], str, str]


def _ключ_улицы(h: GeoHit) -> _КлючУлицы:
    """Улица без слов типа («ул Молодёжная» DaData = «Молодёжная улица»
    Яндекса), пункт — только отдельный (`place`; район внутри города у OSM и
    Яндекса улицу не делит), город без административной обёртки."""
    слова = tuple(sorted(w for w in _слова(h.street) if w not in _СЛОВА_ТИПА))
    пункт = _норм(h.settlement) if h.settlement_kind == "place" else ""
    return слова, пункт, _ядро_города(h.city)


def _группы_улиц(hits: list[GeoHit]) -> list[list[GeoHit]]:
    """Ответы карт по РАЗНЫМ улицам, в порядке первого появления; внутри
    группы — порядок карт (DaData первой). Группа с пунктом, стоящая ближе
    `_ОДНА_УЛИЦА_KM` к такой же без пункта, — та же улица (микрорайон DaData,
    см. `distinct_addresses`)."""
    по_ключу: dict[_КлючУлицы, list[GeoHit]] = {}
    for h in hits:
        по_ключу.setdefault(_ключ_улицы(h), []).append(h)
    for ключ in list(по_ключу):
        слова, пункт, город = ключ
        без_пункта = по_ключу.get((слова, "", город)) if пункт else None
        if без_пункта is None:
            continue
        a, b = по_ключу[ключ][0], без_пункта[0]
        if distance_km((a.lat, a.lon), (b.lat, b.lon)) <= _ОДНА_УЛИЦА_KM:
            без_пункта += по_ключу.pop(ключ)
    return [sorted(гр, key=hits.index) for гр in по_ключу.values()]


def _в_самом_городе(город: str, h: GeoHit) -> bool:
    """Ответ карты стоит в самом городе объявления, а не в его пункте — общий
    признак `_best_of` (дома) и `known_street` (улицы)."""
    return _город_совпал(город, h) and (
        h.settlement is None or _норм(h.settlement) == _норм(h.city)
    )


def _место_клиента_названо(parsed: Parsed, h: GeoHit) -> bool:
    """Город (`locality`) и пункт (`settlement`), названные клиентом, есть в
    ответе карты — те же сторожа, что у `suburb_hit`. Не назвал — правда."""
    if parsed.locality:
        слова_города = _норм(parsed.locality).split()
        if not all(_город_назван(w, _слова(h.city) + _слова(h.settlement)) for w in слова_города):
            return False
    if parsed.settlement and not _пункт_назван(_норм(parsed.settlement), _места_ответа(h)):
        return False
    return True


# --- страна --------------------------------------------------------------------


def _дома_по_стране(parsed: Parsed, hits: list[GeoHit]) -> list[GeoHit]:
    """Отбор строже вердикта: дом `house_level and not interpolated` — улица-
    тёзка по стране единственна редко, и подтверждать её точкой улицы нельзя.
    Точность точки (`precise`) состав не меняет: дом-тёзка с точкой пункта
    (qc_geo 3, обычное дело у деревень) — такой же соперник, и отбросить его
    до подсчёта значит выдать единственный точный за единственный (ревью
    19.09: «ул Центральная, 15» в двух Ивановках и Бузулуке → `exact`
    Бузулука). Точность решает только `exact` у единственной группы
    (`country_verdict`). Региона нет и сверять его нечем; город — только
    словами клиента, пункт — `_пункт_назван`."""
    ключ = house_key(parsed.house)
    return [
        h
        for h in hits
        if h.house_level
        and not h.interpolated
        and h.house
        and house_key(h.house) == ключ
        and _улица_сошлась(parsed, h, без_улицы=False)
        and _место_клиента_названо(parsed, h)
    ]


#: Дома с одним ключом адреса по стране (улица, номер, пункт, город, область)
#: дальше этого — тёзки в разных районах одной области («д. Ивановка» в
#: Оренбургской не одна), а не разные точки одного дома: ключ района не знает.
#: Ближе — один дом: неточный дубль (точка пункта) и точный DaData отдаёт рядом.
_ОДНО_МЕСТО_KM = 1.0


def _тот_же_адрес_по_стране(a: GeoHit, b: GeoHit) -> bool:
    """Как `distinct_addresses`, но с областью и с расстоянием у одного ключа."""
    if _норм(a.region) != _норм(b.region):
        return False
    if _норм(a.street) != _норм(b.street) or house_key(a.house) != house_key(b.house):
        return False
    if abs(a.lat - b.lat) < _ОДИН_ДОМ_ГРАДУСОВ and abs(a.lon - b.lon) < _ОДИН_ДОМ_ГРАДУСОВ * 2:
        return True
    if (_норм(a.settlement), _ядро_города(a.city)) != (_норм(b.settlement), _ядро_города(b.city)):
        return False
    return distance_km((a.lat, a.lon), (b.lat, b.lon)) <= _ОДНО_МЕСТО_KM


def _группы_по_стране(parsed: Parsed, hits: list[GeoHit]) -> list[GeoHit]:
    """Разные адреса по стране — представитель каждого. Ключ
    `distinct_addresses` область не различает (в одной области она лишняя), а
    по стране «с. Поляны, ул Колхозная, 4» стоит и в Рязанской, и в Кировской;
    район он не знает тоже, а «д. Ивановка» в одной области бывает в
    нескольких — один ключ, точки за десятки километров
    (`_тот_же_адрес_по_стране`). Точные дома идут первыми: представитель
    группы — точный, если он в ней есть, иначе `distinct_addresses` оставил бы
    первый по порядку карты, и единственный точный дом ушёл бы в `not_found`."""
    годные = sorted(_дома_по_стране(parsed, hits), key=lambda h: not h.precise)
    out: list[GeoHit] = []
    for h in годные:
        if not any(_тот_же_адрес_по_стране(o, h) for o in out):
            out.append(h)
    return out


def country_verdict(parsed: Parsed, hits: list[GeoHit]) -> tuple[str, GeoHit | None]:
    """Вердикт по стране: ровно одна группа (`_группы_по_стране`) с точной
    точкой → `exact` (воркер помечает `~approx`: город определён картой, не
    человеком); одна, но с точкой пункта → `not_found` (подтверждать
    улицу-тёзку по стране точкой пункта нельзя); несколько → `ambiguous`; ни
    одной → `not_found`."""
    группы = _группы_по_стране(parsed, hits)
    if not группы:
        return GEO_NOT_FOUND, None
    if len(группы) > 1:
        return GEO_AMBIGUOUS, None
    if not группы[0].precise:
        return GEO_NOT_FOUND, None
    return GEO_EXACT, группы[0]


def country_variants(parsed: Parsed, hits: list[GeoHit]) -> list[dict[str, Any]]:
    """Варианты по стране — тот же отбор, что у `country_verdict`; в строке —
    область: `format_address` регион не печатает, а два «с. Поляны, ул
    Колхозная, 4» в разных областях иначе неразличимы."""
    out: list[dict[str, Any]] = []
    for h in _группы_по_стране(parsed, hits)[:MAX_VARIANTS]:
        строка = format_address(h, parsed, with_settlement=True)
        if h.region and _норм(h.region) not in _норм(строка):
            строка = f"{строка}, {h.region}"
        out.append(
            {"formatted": строка, "lat": h.lat, "lon": h.lon, "city": h.city, "region": h.region}
        )
    return out


def ask_reason(
    *, geo_status: str | None, city_known: bool, locality: str | None, variants: Any
) -> str | None:
    """Чистый признак для участка C — единственной точки, где решают
    «спросить клиента». Единственная причина — `ASK_CITY`: город неизвестен
    и слага объявления нет. Слаг есть, но не в справочнике, — город известен
    человеку, это повод пополнить справочник (`listing.unknown_city_slug`),
    не вопрос. Клиент город назвал, а по стране ничего — вопроса нет
    (переспрашивать сказанное нельзя); назвал, а городов-тёзок несколько
    (варианты) — «уточните город и область»."""
    if geo_status != GEO_NO_CITY or city_known:
        return None
    if locality and not variants:
        return None
    return ASK_CITY


