def place_verdict(
    place: Place, city: City | None, hits: list[PlaceHit]
) -> tuple[str, PlaceHit | None]:
    """Вердикт по месту: регион объявления, названный пункт, названный массив.

    Точка — у самого мелкого названного уровня: массив, если клиент назвал
    массив и карта его знает; иначе пункт. Массив без пункта — только если
    карта знает его в этом регионе один.
    """
    if city is None:
        return GEO_NO_CITY, None
    if not hits:
        return GEO_NOT_FOUND, None
    в_регионе = [h for h in hits if region_matches(city.region, h.region)]
    if not в_регионе:
        return GEO_REGION_MISMATCH, None
    годные = в_регионе
    if place.locality and not _регион_вместо_города(city):
        ожидаем_город = _слова(place.locality)
        годные = [
            h
            for h in годные
            if all(_слово_есть(w, _слова(h.city) + _слова(h.settlement)) for w in ожидаем_город)
        ]
        if not годные:
            return GEO_CITY_MISMATCH, None
    if place.street:
        # Улица без дома: только улицы с тем же названием; без пункта и массива
        # — в городе объявления (улиц Ленина в области десятки, точка нужна одна).
        годные = [h for h in годные if h.kind == "street" and _улица_не_шире(h.name, place.street)]
        if not годные:
            return GEO_STREET_MISMATCH, None
        if not place.settlement and not place.area and not _регион_вместо_города(city):
            ожидаем = _слова(city.name)
            годные = [h for h in годные if all(_слово_есть(w, _слова(h.city)) for w in ожидаем)]
            if not годные:
                return GEO_CITY_MISMATCH, None
    if place.settlement:
        # Пункт клиента бывает и массивом карты («мкр Индустриальный» на
        # «Индустриальный» — бой 13.09): массив тоже среди слов.
        пункт = _норм(place.settlement)
        годные = [
            h
            for h in годные
            if _пункт_назван(пункт, _слова(h.settlement) + _слова(h.city) + _слова(h.area))
        ]
        if not годные:
            return GEO_SETTLEMENT_MISMATCH, None
    if place.area:
        массив = _норм(place.area)
        слова_массива = [w for w in массив.split() if w not in _ТИПЫ_МАССИВА]
        # У улицы внутри микрорайона DaData кладёт микрорайон в `settlement`
        # (ревью 13.09: «мкр Центральный, ул Ленина» уходил в not_found).
        с_массивом = [
            h
            for h in годные
            if all(_слово_есть(w, _слова(h.area) + _слова(h.settlement)) for w in слова_массива)
        ]
        if с_массивом:
            годные = с_массивом
        elif not place.settlement and not place.street:
            return GEO_NOT_FOUND, None
    # Точка: улица < массив < пункт < город — что назвал клиент, то и точка.
    порядок = (
        {"area": 0, "settlement": 1, "city": 2}
        if place.area
        else {"settlement": 0, "city": 1, "area": 2}
    )
    if place.street:
        порядок = {"street": 0}
    годные = sorted(годные, key=lambda h: порядок.get(h.kind, 3))
    лучшие = [h for h in годные if h.kind == годные[0].kind]
    if len({_ключ_места(h) for h in лучшие}) > 1:
        return GEO_AMBIGUOUS, None
    return GEO_EXACT, годные[0]


def _ключ_места(h: PlaceHit) -> tuple[str, str, str]:
    """Что считать «тем же местом» при выборе между находками.

    Улица в городе — одна и та же с микрорайоном в `settlement` и без него:
    в ГАР у бывших посёлков, влитых в город, улица заведена дважды (Королёв,
    «ул Горького» с «мкр Первомайский» и без — стенд 13.09). Без города
    различаем по району: две Сосновки в разных районах области — разные.
    """
    if h.kind == "street" and h.city:
        return _норм(h.name), _норм(h.city), ""
    return _норм(h.name), _норм(h.city) or _норм(h.district), _норм(h.settlement)


