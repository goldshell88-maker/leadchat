@dataclass(frozen=True, slots=True)
class Query:
    """Что спрашиваем у карты. Собирается ТОЛЬКО из компонентов разбора.

    ⚠ НИКОГДА ИЗ `raw` И НЕ ИЗ ТЕКСТА СООБЩЕНИЯ: рядом с адресом клиент пишет
    телефон, имя, код домофона — это персональные данные, и наружу они не
    уходят. В запросе — улица, дом, пункт и город, больше ничего.
    """

    region: str | None
    city: str | None
    settlement: str | None
    street: str
    house: str

    @property
    def street_for_map(self) -> str:
        return expand_street(self.street)

    @property
    def free_text(self) -> str:
        """Свободная строка для карт, которые не умеют структурный запрос."""
        # Место без дома (Яндекс за местом, 18.09): хвост без пробела на конце.
        куски = [
            self.region,
            self.city,
            self.settlement,
            f"{self.street_for_map} {self.house}".strip(),
        ]
        return ", ".join(к for к in куски if к)


