def parse_rule_policy(text: str | None, *, strict: bool = True) -> dict[str, str]:
    """Настройка «имя=значение,…» → словарь; пусто — `{}` (одни умолчания).

    Проверяет и имя (только известные `RULE_*`), и значение (`POLICIES`):
    опечатка в настройке молча выключала бы или, хуже, включала не то правило.

    Строгость — по стороне (ревью 20.09, #5/#14). `strict=True` — ЗАПИСЬ:
    ошибка — `ValueError` с текстом для человека, ручка настроек и задача
    лестницы получают 400 (`app_settings.Spec.check`). `strict=False` —
    ЧТЕНИЕ в бою (воркер карты, задача, экран): плохая пара пропускается с
    предупреждением, остальные сохраняются. Иначе одно имя, снятое или
    переименованное следующей выкаткой, обнуляло бы ВСЮ строку — и правило,
    выключенное владельцем за ложные адреса, молча вернулось бы к `exact`."""
    из: dict[str, str] = {}
    известные = set(RULE_DEFAULT_POLICY)
    for кусок in (text or "").replace(";", ",").replace("\n", ",").split(","):
        кусок = кусок.strip()
        if not кусок:
            continue
        имя, знак, значение = кусок.partition("=")
        имя, значение = имя.strip(), значение.strip().lower()
        if not знак or not имя or not значение:
            ошибка = f"ожидается «правило=политика», получено «{кусок}»"
        elif имя not in известные:
            ошибка = f"неизвестное правило «{имя}»; известны: {', '.join(sorted(известные))}"
        elif значение not in POLICIES:
            ошибка = (
                f"неизвестная политика «{значение}» у «{имя}»; допустимы: {', '.join(POLICIES)}"
            )
        else:
            из[имя] = значение
            continue
        if strict:
            raise ValueError(ошибка)
        # Читается на каждую задачу карты: одна устаревшая пара дала бы тысячи
        # одинаковых строк в сутки — называем каждую пару один раз на процесс.
        if кусок not in _ПРЕДУПРЕЖДЕНО:
            _ПРЕДУПРЕЖДЕНО.add(кусок)
            log.warning(
                "rule_policy.unknown_rule", layer="geo", rule=имя, value=значение, error=ошибка
            )
    return из


#: Пары настройки `address_geo.rule_policy`, о которых нестрогий читатель уже
#: предупредил (на процесс).
_ПРЕДУПРЕЖДЕНО: set[str] = set()


def rule_policy(policy: Mapping[str, str] | None, rule: str) -> str:
    """Политика правила: настройка поверх умолчаний, неизвестное имя — `shadow`."""
    if policy and rule in policy:
        return policy[rule]
    return RULE_DEFAULT_POLICY.get(rule, POLICY_SHADOW)


