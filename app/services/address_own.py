"""Свои адреса — мастерская, офис, пункт приёма, — которые в переписке называем
МЫ, а клиент повторяет (пакет 7а, Q24; программа §2.2).

ЗАЧЕМ. «Привезу сам, куда?» → оператор: «ул. Невская 7а» → клиент: «подъеду на
Невскую 7а». Разбор входящего честно находит дом — но это не адрес клиента, а
наш; карта его подтвердит, и автопривязка положит в карточку клиента адрес
мастерской (бой, корзина H_house_missing_mismatch #49). Отличить эхо по словам
нельзя — ключ тот же; отличить можно по ИСТОЧНИКУ: адрес есть в списке своих
(владелец пишет руками — `address_own_addresses`; задача выводит из исходящих
за 90 дней — `address_geo.own_addresses_auto`) или он прозвучал в исходящих
этого диалога РАНЬШЕ первого упоминания клиентом (`inbound`).

ЧТО ЗДЕСЬ. Только чистые функции — ключ адреса и сравнение с ним, чтобы
сторож входящего, задача и проверка настройки считали «тот же адрес» одной
меркой: ядро улицы (`address_parse.street_core`) + ключ дома
(`geocode.house_key`) — то же, чем `same_address` склеивает строки одной
карточки («ул. Ленина 5», «Ленина, 5», «ленина 5» — один ключ). Ни базы, ни
настроек — их читают вызывающие.
"""

from __future__ import annotations

import re

from app.services import address_parse
from app.services.address_parse import Found
from app.services.geocode import house_key

#: Ключ своего адреса: (ядро улицы, ключ дома). Тип улицы в ключ не входит —
#: список владельца пишется как удобно («Ленина 5»), а клиент повторяет как
#: услышал («ул Ленина, 5»); ложная склейка «ул.» с «пр.» на адресах компании
#: (их единицы) дешевле пропущенного эха.
Key = tuple[tuple[str, ...], str]

#: Часть списка, состоящая из одного дома («5», «7а», «5 к 2», «17/2»): такая
#: часть — не отдельный адрес, а хвост предыдущей, отрезанный запятой
#: («ул. Ленина, 5» — самая естественная запись адреса, и запятая внутри неё
#: не разделитель). Тем же пишет задача: «улица, дом; улица, дом».
_ТОЛЬКО_ДОМ = re.compile(
    r"^\d+\s*[а-яёa-z]?(?:\s*(?:/|к\.?|корп\.?|корпус|стр\.?|с\.?)\s*\d+\s*[а-яё]?)?$",
    re.IGNORECASE,
)
#: Дом в свободном тексте клиента — для реплик, которые разбор не взял
#: («да это дом 5 по ленина»): сравнивается через `house_key`, чтобы «5 к 2»,
#: «5/2» и «5к2» сошлись.
#: Корпус — раньше литеры: «5к2» иначе читался бы как литера «к» и дом «5».
_ДОМ_В_ТЕКСТЕ = re.compile(
    r"(?<![\d])\d{1,4}"
    r"(?:\s*(?:/|к\.?|корп\.?|корпус|стр\.?)\s*\d{1,3}|[а-яёa-z](?![а-яёa-z]))?"
    r"(?![\d])",
    re.IGNORECASE,
)


def split_list(text: str | None) -> list[str]:
    """Части списка адресов: через `,`, `;` и перевод строки, как список своих
    номеров (`phone_rules.parse_own_numbers`), но часть из одного дома
    приклеивается к предыдущей (см. `_ТОЛЬКО_ДОМ`)."""
    части: list[str] = []
    for кусок in re.split(r"[,;\n]", text or ""):
        кусок = " ".join(кусок.split())
        if not кусок:
            continue
        if части and _ТОЛЬКО_ДОМ.match(кусок):
            части[-1] = f"{части[-1]} {кусок}"
        else:
            части.append(кусок)
    return части


def key_of(found: Found | None) -> Key | None:
    """Ключ разобранного адреса или `None`: не дом, либо улицы нет («посёлок
    Сосново, 9» — дом по пункту без улицы: ядра нет, сравнивать нечем, как и
    у `same_address`)."""
    if found is None or found.kind != address_parse.KIND_HOUSE:
        return None
    ядро = address_parse.street_core(found.street)
    if not ядро or not (found.house or "").strip():
        return None
    return (ядро, house_key(found.house))


def parse_part(part: str) -> Found | None:
    """Разбор одной части списка — ОДИН читатель у проверки настройки, у
    ключей рантайма и у задачи. `про_адрес=True`: список пишется как ответ на
    вопрос «где вы находитесь» — «Ленина 5» без типа улицы годится."""
    return address_parse.parse(part, про_адрес=True)


def check_list(text: str) -> None:
    """Проверка настройки владельца до записи (`Spec.check`): каждая непустая
    часть обязана разбираться домом, иначе `ValueError` с текстом этой части —
    человек видит, какую строку исправить. Базы не трогает."""
    for часть in split_list(text):
        if key_of(parse_part(часть)) is None:
            raise ValueError(f"не разобрано как «улица дом»: «{часть}»")


def own_keys(text_owner: str | None, text_auto: str | None) -> frozenset[Key]:
    """Ключи своих адресов из обеих настроек — список владельца и вывод задачи.
    Мусорная часть пропускается молча (запись уже проверена; вывод задачи —
    её же строки), как у списка своих номеров."""
    ключи: set[Key] = set()
    for текст in (text_owner, text_auto):
        for часть in split_list(текст):
            ключ = key_of(parse_part(часть))
            if ключ is not None:
                ключи.add(ключ)
    return frozenset(ключи)


def is_own(found: Found | None, keys: frozenset[Key]) -> bool:
    """Разобранный адрес — из списка своих?"""
    ключ = key_of(found)
    return ключ is not None and ключ in keys


def text_mentions(text: str | None, key: Key) -> bool:
    """Упоминает ли реплика адрес с этим ключом — по ТЕКСТУ, не по строкам:
    разбор берёт не всякую реплику клиента («да это дом 5 по ленина» — `None`),
    а для порядка «кто назвал адрес первым» неразобранное упоминание считается.
    Правило: в тексте есть каждое слово ядра улицы (как слово, без учёта
    регистра и «ё») и число с ключом дома."""
    if not text:
        return False
    ядро, дом = key
    т = text.lower().replace("ё", "е")
    for слово in ядро:
        if re.search(rf"(?<![0-9a-zа-я]){re.escape(слово)}(?![0-9a-zа-я])", т) is None:
            return False
    return any(house_key(m.group(0)) == дом for m in _ДОМ_В_ТЕКСТЕ.finditer(т))
