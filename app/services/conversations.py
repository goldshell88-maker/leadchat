#: Сколько символов цитаты уезжает в ленту.
#:
#: Цитата — напоминание «о чём речь», а не второй экземпляр сообщения. Сто
#: символов хватает узнать вопрос («Сколько будет стоить замена экрана на
#: iPhone 13, если…»), и при этом пузырь ответа не превращается в пересказ.
ЦИТАТА_СИМВОЛОВ = 100


def quote_out(msg: Message | None) -> dict[str, Any] | None:
    """Снимок цитируемого сообщения для ленты — короткий и без вложений.

    ⚠ СОБИРАЕТСЯ НА ВЫДАЧЕ, А НЕ ХРАНИТСЯ. Хранимый снимок замерзает: оператор
    удалил заметку или исправил текст, а в цитате навсегда осталось прежнее.
    Здесь цитата всегда показывает то, что в ленте лежит СЕЙЧАС.

    `None` законен и означает «сообщение удалили»: связь остаётся, показывать
    нечего. Лента в этом случае рисует «сообщение удалено», а не пустоту —
    иначе ответ выглядел бы обращённым в никуда.
    """
    if msg is None:
        return None
    тело = (msg.body or "").strip()
    return {
        "id": str(msg.id),
        "direction": msg.direction,
        # Обрезка со стороны сервера: длина цитаты — свойство продукта, а не
        # вкус каждого экрана. Иначе десктоп и браузер обрежут по-разному.
        "body": тело[:ЦИТАТА_СИМВОЛОВ],
        "truncated": len(тело) > ЦИТАТА_СИМВОЛОВ,
        # Вложения не копируем: цитата это напоминание, а не второй показ
        # фотографии. Есть ли там вложение — говорим признаком.
        "has_attachments": bool(msg.attachments),
    }


def message_out(
    msg: Message, sender: User | None = None, *, quoted: Message | None = None
) -> dict[str, Any]:
    """MessageOut (01 §6.1) — same shape in REST and in WS message:new."""
    return {
        "id": str(msg.id),
        "conversation_id": str(msg.conversation_id),
        "direction": msg.direction,
        "sender_type": msg.sender_type,
        # Автор — единой сборкой (`user_ref`): в пузыре исходящего рядом с
        # именем показывается отдел, и собираться он обязан там же, где у
        # ответственного, иначе один и тот же человек подпишется в ленте и в
        # списке по-разному.
        "sender": user_ref(sender),
        "body": msg.body,
        # Свежая подпись на каждый ответ: ссылка живёт 1 ч (01 §6.1), сырые
        # метаданные из БД без неё не откроются. Вложения входящих из Авито
        # (без ключа ``path``) sign_attachments отдаёт как есть.
        "attachments": sign_attachments(msg.attachments),
        "delivery_status": msg.delivery_status,
        "client_message_id": getattr(msg, "client_message_id", None),
        "created_at": iso(msg.created_at),
        # На какое сообщение это ответ (просьба владельца 02.09). Наша
        # собственная связь: у Авито цитирования в API нет, поэтому у входящих
        # она пуста ВСЕГДА — на что ответил клиент, нам не сообщают.
        "reply_to_id": str(msg.reply_to_id) if getattr(msg, "reply_to_id", None) else None,
        # Снимок цитируемого. Заполняется только там, где вызывающий его
        # ПОДГОТОВИЛ: собирать здесь значило бы запрос на каждое сообщение
        # страницы, то есть N+1 по 28 партициям.
        "reply_to": quote_out(quoted),
        # Машинная расшифровка голосового — считает наш Whisper в воркере.
        #
        # ⚠ ЕДЕТ У ВСЕХ СООБЩЕНИЙ, А НЕ ТОЛЬКО У ГОЛОСОВЫХ, И ЭТО НАМЕРЕННО:
        # форма ответа одна на все сообщения ленты, а `null` читается однозначно
        # («расшифровки нет»). Отдельная форма для голосовых заставила бы каждого
        # читателя знать, у каких сообщений поле бывает.
        #
        # ⚠ ТЕКСТ И СОСТОЯНИЕ — ПАРА, И ВТОРОЕ НЕ ЛИШНЕЕ. По одному тексту
        # «пусто» означало бы сразу три разных вещи: ещё считаем, посчитали и
        # там тишина, не вышло. Экран обязан их различать: под записью, которую
        # ещё считают, место молчит, а под неудавшейся честно написано, что
        # расшифровки не будет.
        "voice_transcript": getattr(msg, "voice_transcript", None),
        "voice_transcript_status": getattr(msg, "voice_transcript_status", None),
    }


def _first_attachment_name(msg: Any) -> str | None:
    """Имя первого вложения сообщения — для строки списка.

    ⚠ ТОЛЬКО ЧТЕНИЕ ГОТОВОГО ПОЛЯ, НИКАКОГО ВТОРОГО СЛОВАРЯ. Имена придумывает
    разбор (`integrations/avito/adapter.py`), здесь мы их лишь достаём: заведи
    список слов ещё и тут — и он разъедется с тем на первой же правке
    формулировки, а разъехавшись, покажет в списке не то, что в ленте.

    Первое, а не все: у сообщения с непоказуемым содержимым вложение ровно
    одно, а перечисление в строке шириной в треть экрана всё равно не помещается.
    """
    вложения = msg.attachments or []
    for a in вложения:
        if isinstance(a, dict):
            имя = a.get("name")
            if isinstance(имя, str) and имя.strip():
                return имя
    return None


class _СОбъявлением(Protocol):
    """Чем город объявления считается у диалога: колонка слага и ссылка.

    Протокол, а не `Conversation`: город нужен и там, где из диалога читают
    только эти две колонки (`other_conversation_cities`, ревью 19.09, D4) —
    один путь разбора на строку и на пару колонок.
    """

    @property
    def item_city_slug(self) -> str | None: ...

    @property
    def item_url(self) -> str | None: ...


class _Объявление(NamedTuple):
    """Две колонки диалога вместо целой строки — для `conversation_city`."""

    item_city_slug: str | None
    item_url: str | None


def conversation_city_slug(conv: _СОбъявлением) -> str | None:
    """Слаг города объявления: колонка, а без неё — ссылка. ОДИН путь на всех.

    ⚠ ЗАЧЕМ ОТДЕЛЬНАЯ ФУНКЦИЯ (11.09). Это же выражение стояло в `item_out`
    строкой, и проверка адреса по карте завела бы второе такое же — а потом
    третье. Чип «город Орск» в шапке диалога и город, с которым идут к карте,
    обязаны быть ОДНИМ городом: иначе оператор видит один город, а под адресом
    читает «найден в другом».
    """
    return conv.item_city_slug or parse_listing_url(conv.item_url).city_slug


def conversation_city(conv: _СОбъявлением) -> City | None:
    """Город объявления справочником `listing_url` — с регионом.

    Не `avito_cities.city_by_slug`: тот словарь короче на 65 слагов и в
    нескольких местах расходится с этим (Петергоф против Санкт-Петербурга), а
    региона у него нет вовсе. Регион карте нужен как обязательный сторож.
    """
    return city_by_slug(conversation_city_slug(conv))


#: Сколько других диалогов клиента смотрим за городом — у одного человека их
#: единицы, двадцать покрывают любую карточку с запасом.
_ДРУГИХ_ДИАЛОГОВ = 20


async def other_conversation_cities(
    db: AsyncSession, client_id: uuid.UUID, conversation_id: uuid.UUID
) -> list[City]:
    """Города объявлений ДРУГИХ диалогов того же клиента — свежие первыми, без
    повторов. ОДИН источник для всех, кто спрашивает «откуда пишет клиент»:
    город для карты без слага (воркер, стенд 15.09), пара «квартал-дом» в
    чужом городе (владелец 19.09: «по адресу 12б-73» при объявлении в Саранске
    от клиента из Нефтеюганска) и город клиента из другого региона (там же).

    Город — только через `conversation_city`, то есть по справочнику: слаг,
    которого справочник не знает, — не «города нет» и не чужой город (ревью
    15.09), такой диалог просто пропускается.
    """
    # Две колонки, а не строка целиком: сюда ходят с любой пары «N-M» в речи
    # («2-3 дня», «10-12»), и тащить ради имени города теги и JSONB каждого
    # из 20 диалогов незачем (ревью 19.09, D4). Город — тем же
    # `conversation_city`, что и у строки.
    rows = (
        await db.execute(
            select(Conversation.item_city_slug, Conversation.item_url)
            .where(
                Conversation.client_id == client_id,
                Conversation.id != conversation_id,
                sa.or_(
                    Conversation.item_city_slug.is_not(None), Conversation.item_url.is_not(None)
                ),
            )
            .order_by(Conversation.last_message_at.desc().nulls_last())
            .limit(_ДРУГИХ_ДИАЛОГОВ)
        )
    ).all()
    города: list[City] = []
    for слаг, ссылка in rows:
        city = conversation_city(_Объявление(слаг, ссылка))
        if city is not None and all(c.name != city.name for c in города):
            города.append(city)
    return города


def item_out(conv: Conversation) -> dict[str, Any] | None:
    """Объявление диалога — с городом и часовым поясом (требование 11 августа).

    ГОРОД БЕРЁТСЯ ИЗ КОЛОНКИ, А НЕ ИЗ ССЫЛКИ — но если колонка пуста, ссылка
    разбирается прямо здесь. Это не перестраховка: колонку заполняет задача
    обогащения, и у всего, что накопилось ДО этой выкатки, она пуста, а
    ремонтного прогона по базе задача не предполагает. Ровно на этом месте
    аудит нашёл «дефект 2» (docs/32 §10.1): поле, которое пишется одним путём,
    у половины строк остаётся пустым навсегда. Разбор ссылки чист и дёшев —
    регулярка и словарь на строку выборки, — и он гарантирует, что город
    виден ВСЕГДА, когда в ссылке он есть.

    Часовой пояс уезжает IANA-именем (``Europe/Moscow``), а не временем и не
    смещением: время считает браузер, поэтому оно ИДЁТ, а не замирает на
    момент ответа сервера, и переход на другое смещение случится сам.
    """
    if not (conv.item_title or conv.item_url or conv.item_price):
        return None
    slug = conversation_city_slug(conv)
    return {
        "title": conv.item_title,
        "url": conv.item_url,
        "price": conv.item_price,
        **city_fields(slug),
    }


