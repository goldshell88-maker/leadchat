def encode_cursor(created_at: datetime, message_id: uuid.UUID) -> str:
    """Opaque keyset cursor: base64url(created_at_iso + "|" + message_id) — 01 §1.4.

    Время кодируем с МИКРОсекундами, а не через `iso()`: в WS-кадрах округление
    до миллисекунд намеренное, но здесь это точность ключа пагинации. У
    PostgreSQL `created_at` почти всегда с микросекундами, а сравнение в ветке
    `after` строгое (`key > (created_at, id)`) — округлённый вниз курсор
    возвращает пограничное сообщение ЕЩЁ РАЗ, и догрузка после обрыва WS
    дублирует последнее известное клиенту сообщение.

    `decode_cursor` обратно совместим: `fromisoformat` читает обе точности,
    поэтому курсоры, выданные до этой правки, продолжают работать.
    """
    at = created_at.replace(tzinfo=UTC) if created_at.tzinfo is None else created_at
    stamp = at.astimezone(UTC).isoformat(timespec="microseconds").replace("+00:00", "Z")
    raw = f"{stamp}|{message_id}"
    return base64.urlsafe_b64encode(raw.encode()).decode()


def decode_cursor(cursor: str) -> tuple[datetime, uuid.UUID]:
    try:
        raw = base64.urlsafe_b64decode(cursor.encode()).decode()
        created_str, id_str = raw.split("|", 1)
        created = datetime.fromisoformat(created_str.replace("Z", "+00:00"))
        if created.tzinfo is None:
            created = created.replace(tzinfo=UTC)
        return created, uuid.UUID(id_str)
    except (ValueError, binascii.Error) as exc:
        raise ApiError(
            "validation_error",
            "Невалидный курсор",
            status=400,
            details={"fields": [{"field": "cursor", "rule": "format", "message": str(exc)}]},
        ) from exc


#: Приставка, которой сам Авито помечает служебные записи ВНУТРИ переписки.
#:
#: Признака служебности у таких записей нет: `is_system` выставляется только по
#: конверту (`payload.type != "message"`), а внутри ленты Авито его не ставит. Они
#: приезжают обычными сообщениями клиента — «Ассистент Авито ответил…»,
#: «Пользователь создал чат, но пока ничего не написал», — и выдаёт их только эта
#: приставка. Взята из боевых данных владельца (снимки от 14 августа), а не угадана.
AVITO_SYSTEM_PREFIX = "[Системное сообщение]"


async def _quoted_for(db: AsyncSession, rows: Sequence[Message]) -> dict[uuid.UUID, Message]:
    """Цитируемые сообщения страницы — ОДНИМ запросом, а не по одному на строку.

    ⚠ ЗАЧЕМ ЭТО ОТДЕЛЬНОЙ ФУНКЦИЕЙ, А НЕ ВНУТРИ `message_out`. Собери цитату там
    — и получится запрос на КАЖДОЕ сообщение страницы: пятьдесят запросов вместо
    одного, и каждый по партиционированной таблице, где планирование само по
    себе стоит десятки миллисекунд (замер 02.09: 28 партиций, планирование
    85-100 мс на холодном соединении). Это ровно тот N+1, за который в этом
    проекте уже платили.

    ⚠ ЗАПРАШИВАЕМ ПАРОЙ `(id, created_at)`. Ключ у `messages` составной, и без
    даты выборка обошла бы все партиции вместо одной. Пары уже лежат в строках —
    их записали при отправке, специально ради этого места.

    Цитируемое может лежать ЗА пределами страницы (ответ на сообщение недельной
    давности) — поэтому отдельная выборка, а не поиск среди `rows`.
    """
    пары = [(m.reply_to_id, m.reply_to_created_at) for m in rows if m.reply_to_id]
    if not пары:
        return {}
    найденные = (
        await db.execute(
            select(Message).where(
                sa.tuple_(Message.id, Message.created_at).in_([(i, t) for i, t in пары])
            )
        )
    ).scalars()
    return {m.id: m for m in найденные}


async def list_messages(
    db: AsyncSession,
    conv: Conversation,
    *,
    before: str | None = None,
    after: str | None = None,
    limit: int = 50,
    include_notes: bool = True,
    include_avito_system: bool = True,
) -> dict[str, Any]:
    """GET /conversations/{id}/messages (01 §6.1): items ASC + ready cursors."""
    if before and after:
        raise ApiError(
            "validation_error",
            "before и after одновременно нельзя",
            status=400,
            details={"fields": [{"field": "before/after", "rule": "exclusive", "message": ""}]},
        )
    limit = max(1, min(limit, MAX_MESSAGES_LIMIT))

    def _base_conds() -> list[sa.ColumnElement[bool]]:
        conds: list[sa.ColumnElement[bool]] = [Message.conversation_id == conv.id]
        if not include_notes:  # observer: лента без заметок (01 §6.1)
            conds.append(Message.direction != "note")
        if not include_avito_system:
            # СЛУЖЕБНЫЕ ЗАПИСИ АВИТО СКРЫТЫ (требование владельца от 14 августа:
            # «в самой Jivo их нет»).
            #
            # ⚠ СКРЫТЫ, А НЕ УДАЛЕНЫ. Фильтр стоит в запросе ленты и только в нём:
            # сообщения остаются в базе, приезжают в выгрузку и в разбор, и
            # выключатель возвращает их целиком. Терять чужие слова из-за настройки
            # показа нельзя — за некоторыми из них стоит действие клиента.
            #
            # ДВА ВИДА, И ЛОВИТЬ НАДО ОБА. Первый система уже различает сама:
            # `sender_type='avito'` — Авито сказал о служебности КОНВЕРТОМ, и лента
            # рисует такой пузырь серым чипом «Сообщение Авито».
            #
            # Второй приезжает ОБЫЧНЫМ СООБЩЕНИЕМ КЛИЕНТА, и признака служебности у
            # него нет вовсе: `is_system` ставится только по конверту, а внутри
            # переписки Авито его не выставляет никогда. Такие записи и видно на
            # снимках владельца — «Ассистент Авито ответил…», «Пользователь создал
            # чат, но пока ничего не написал». Единственное, чем они себя выдают, —
            # приставка, которую пишет сам Авито.
            #
            # Сравнение по приставке — не наша догадка о чужом формате, а буквальный
            # текст площадки, увиденный в боевых данных. Но и не признак: если Авито
            # её сменит, записи вернутся в ленту, а не исчезнут — то есть ошибка
            # здесь безопасна по направлению.
            conds.append(Message.sender_type != "avito")
            conds.append(
                sa.or_(
                    Message.body.is_(None),
                    sa.not_(Message.body.startswith(AVITO_SYSTEM_PREFIX)),
                )
            )
        return conds

    stmt = select(Message).where(*_base_conds())
    key = sa.tuple_(Message.created_at, Message.id)

    # ⚠ «ЕСТЬ ЛИ ЕЩЁ» В СТОРОНУ ЛИСТАНИЯ — ЭТО `LIMIT + 1`, А НЕ EXISTS.
    #
    # Здесь стояли два EXISTS ради двух флагов, и каждый планировался по 28
    # партициям `messages` — 1,4–16 мс на штуку (замер боя 06.09), причём на
    # первом открытии диалога, то есть на каждом клике по строке списка. Берём
    # на одну строку больше, чем отдадим: лишняя строка и есть ответ «дальше
    # есть», её отбрасываем. Первое открытие обходится ОДНИМ запросом: в сторону
    # «новее» там ничего быть не может — мы взяли самые новые.
    #
    # ⚠ НА СТРАНИЦАХ ПО КУРСОРУ ФЛАГ В ПРОТИВОПОЛОЖНУЮ СТОРОНУ ПО-ПРЕЖНЕМУ
    # СЧИТАЕТ EXISTS. Из взятых строк его не вывести: листая вверх от курсора,
    # мы не видим, что осталось ниже него. Фронт этот флаг на таких страницах
    # не читает (вверх — `has_more_before`, догон — `has_more_after`), но
    # контракт ручки обещает точные флаги, а не «скорее всего». Один EXISTS
    # вместо двух, и только на страницах по курсору.
    ещё = limit + 1
    has_more_before = has_more_after = False
    if before:
        c, i = decode_cursor(before)
        rows = (
            (
                await db.execute(
                    stmt.where(key < sa.tuple_(sa.literal(c), sa.literal(i)))
                    .order_by(Message.created_at.desc(), Message.id.desc())
                    .limit(ещё)
                )
            )
            .scalars()
            .all()
        )
        has_more_before = len(rows) > limit
        rows = list(reversed(rows[:limit]))
    elif after:
        c, i = decode_cursor(after)
        rows = (
            (
                await db.execute(
                    stmt.where(key > sa.tuple_(sa.literal(c), sa.literal(i)))
                    .order_by(Message.created_at.asc(), Message.id.asc())
                    .limit(ещё)
                )
            )
            .scalars()
            .all()
        )
        has_more_after = len(rows) > limit
        rows = rows[:limit]
    else:  # first open: the last `limit` messages
        rows = (
            (
                await db.execute(
                    stmt.order_by(Message.created_at.desc(), Message.id.desc()).limit(ещё)
                )
            )
            .scalars()
            .all()
        )
        has_more_before = len(rows) > limit
        rows = list(reversed(rows[:limit]))

    sender_ids = {m.sender_user_id for m in rows if m.sender_user_id}
    senders = (
        {u.id: u for u in (await db.execute(select(User).where(User.id.in_(sender_ids)))).scalars()}
        if sender_ids
        else {}
    )

    prev_cursor: str | None
    next_cursor: str | None
    if rows:
        oldest, newest = rows[0], rows[-1]
        prev_cursor = encode_cursor(oldest.created_at, oldest.id)
        next_cursor = encode_cursor(newest.created_at, newest.id)
        if before:
            has_more_after = bool(
                (
                    await db.execute(
                        select(
                            sa.exists(
                                select(sa.literal(1)).where(
                                    *_base_conds(),
                                    key
                                    > sa.tuple_(
                                        sa.literal(newest.created_at), sa.literal(newest.id)
                                    ),
                                )
                            )
                        )
                    )
                ).scalar_one()
            )
        elif after:
            has_more_before = bool(
                (
                    await db.execute(
                        select(
                            sa.exists(
                                select(sa.literal(1)).where(
                                    *_base_conds(),
                                    key
                                    < sa.tuple_(
                                        sa.literal(oldest.created_at), sa.literal(oldest.id)
                                    ),
                                )
                            )
                        )
                    )
                ).scalar_one()
            )
    else:
        prev_cursor = next_cursor = None
        has_more_before = has_more_after = False

    цитаты = await _quoted_for(db, rows)

    return {
        "items": [
            message_out(
                m,
                senders.get(m.sender_user_id) if m.sender_user_id else None,
                quoted=цитаты.get(m.reply_to_id) if m.reply_to_id else None,
            )
            for m in rows
        ],
        "page": {
            "prev_cursor": prev_cursor,
            "next_cursor": next_cursor,
            "has_more_before": bool(has_more_before),
            "has_more_after": bool(has_more_after),
        },
    }
