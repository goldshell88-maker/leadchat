async def _has_operator_reply(db: AsyncSession, conv: Conversation) -> bool:
    """Отвечал ли клиенту хоть кто-то из сотрудников — для запрета `no_reply_yet`.

    Условие ровно то же, что у первого ответа оператора в витрине статистики
    (`conversation_table._first_operator_at`): исходящее, автор — оператор,
    доставка не провалилась. Третье слагаемое здесь главное: неотправленный
    ответ — это не ответ, и разрешать по нему «Ждёт клиента» значило бы
    объявить, что ход за клиентом, который наших слов не видел.

    Ответ БОТА тоже не считается: бот не договаривается о выезде, он собирает
    контакт. «Ждём клиента» после реплики бота означало бы, что мы ждём ответа
    на автоответчик.

    Точечный проход по индексу `(conversation_id, created_at)` c `LIMIT 1` —
    правило партиций 06 §0.2 соблюдено.
    """
    return bool(
        (
            await db.execute(
                sa.select(sa.literal(1))
                .select_from(Message)
                .where(
                    Message.conversation_id == conv.id,
                    Message.direction == "out",
                    Message.sender_type == "operator",
                    Message.delivery_status != "failed",
                )
                .limit(1)
            )
        ).first()
    )


