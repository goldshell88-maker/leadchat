def _aw[T](result: Awaitable[T] | T) -> Awaitable[T]:
    """Сужение типа команд redis-py.

    Один класс `Redis` обслуживает и sync-, и async-клиент, поэтому часть
    команд объявлена как `Awaitable[T] | T`. Клиент в приложении всегда
    асинхронный — сужаем в одном месте, а не `# type: ignore` на каждой строке.
    """
    return cast(Awaitable[T], result)


async def mark_transferred(redis: Redis, user_id: uuid.UUID, conv_id: uuid.UUID) -> None:
    key = TRANSFERRED_KEY.format(user_id=user_id)
    await _aw(redis.sadd(key, str(conv_id)))
    await redis.expire(key, TRANSFERRED_TTL_SECONDS)


async def clear_transferred(redis: Redis, user_id: uuid.UUID, conv_id: uuid.UUID) -> None:
    """Флажок гаснет, как только человек открыл диалог (11 §2.1)."""
    await _aw(redis.srem(TRANSFERRED_KEY.format(user_id=user_id), str(conv_id)))


async def transferred_ids(redis: Redis, user_id: uuid.UUID) -> set[str]:
    """Множество мало по определению — это непросмотренные передачи одного юзера."""
    members: set[str | bytes] = await _aw(redis.smembers(TRANSFERRED_KEY.format(user_id=user_id)))
    return {m if isinstance(m, str) else m.decode() for m in members}


def own_condition(user_id: uuid.UUID) -> sa.ColumnElement[bool]:
    """За что человек ОТВЕЧАЕТ — уже, чем «Мои».

    ⚠ ЗАЧЕМ ОТДЕЛЬНО ОТ «МОИХ» (03.09). «Мои» с сегодняшнего дня включают и
    диалоги, в которые человек просто зашёл: владелец просил, чтобы чужой
    рабочий диалог появлялся в списке у обоих. Но ОТВЕЧАТЬ за клиента
    по-прежнему может только один, и число «ждут вашего ответа» обязано
    считать именно это. Иначе один чужой ждущий диалог зачёлся бы в долг и
    хозяину, и каждому заглянувшему, а пилюля «ждут ВАШЕГО ответа»
    выродилась бы в «сколько диалогов я сегодня открыл».
    """
    from app.models import Conversation as _C

    return sa.or_(_C.assignee_id == user_id, _C.transfer_to_id == user_id)


def _waiting_condition() -> sa.ColumnElement[bool]:
    """SQL-предикат «клиент ждёт нашего ответа». ОДИН на весь бэкенд.

    Зеркало `conversation_status.waiting_since`: та функция отвечает на тот же
    вопрос про ОДНУ строку в питоне, эта — про выборку в базе. Обе собраны из
    одних и тех же двух условий и из одной и той же константы, потому что
    расходиться им нельзя: по этому предикату считается число «не отвечено» на
    вкладке, по нему же отбираются строки, когда на это число нажимают. Разъедься
    они — человек нажал бы на «8» и увидел шесть строк.

    Почему `status` проверяется отдельно, хотя сегодня незакрытые статусы и
    `STATUS_SHOWS_WAIT` совпадают: совпадение это случайное, держится на том, что
    статусов ровно четыре. Появится пятый — и условие останется верным само,
    потому что берёт готовое множество, а не перечисляет статусы заново.
    """
    return sa.and_(
        Conversation.status.in_(sorted(status_dict.STATUS_SHOWS_WAIT)),
        Conversation.awaiting_since.is_not(None),
    )


async def tab_counts(db: AsyncSession, viewer: User) -> dict[str, int]:
    """Сколько у смотрящего диалогов на руках и сколько из них не отвечено.

    ⚠ ЗАЧЕМ (жалоба владельца 02.09): «нет интуитивно понятной навигации,
    сколько у меня диалогов взято, сколько диалогов не отвечено».

    ⚠ ПОЧЕМУ СЧИТАЕТ СЕРВЕР, А НЕ СПИСОК НА КЛИЕНТЕ. Бейдж у «Моих» когда-то
    был и его СНЯЛИ — он считался по загруженным строкам, а список приходит
    страницами по 50: у диспетчера с четырьмя сотнями диалогов «Мои 3»
    превращалось в «Мои 17» просто от прокрутки колеса. Неверный счётчик хуже
    отсутствующего, потому что по нему решают, идти ли в раздел. Довод записан
    на месте снятого бейджа в `ChatListPane.tsx`, и вернуть бейдж он разрешал
    ровно одним способом — этой ручкой.

    ⚠ ПРЕДИКАТЫ БЕРУТСЯ У ТЕХ ЖЕ ФУНКЦИЙ, ЧТО И У СПИСКА, И ЭТО ГЛАВНОЕ В ЭТОМ
    МЕСТЕ. Область вкладки — `_tab_condition`, ровно та, по которой выбираются
    строки. Ожидание — `status_dict.STATUS_SHOWS_WAIT` и `awaiting_since`, ровно те, из
    которых `conversation_status.waiting_since` считает предикат «ждёт».
    Написать здесь второе, «такое же» условие значило бы завести пару, которая
    расходится молча: на экране рядом встали бы число «ждут 8» и восемь строк,
    из которых ждут шесть. Этот проект на такой паре попадался много раз.

    ⚠ ПОЧЕМУ ЧИСЛА ТОЛЬКО ПРО «МОИ», ХОТЯ ВКЛАДКИ ДВЕ. Вкладка «Все» на клиенте
    уходит на сервер как `tab=any` — по решению владельца от 17.08 она ВСЕГДА
    включает закрытые и залитый архив Авито (`frontend/src/features/chats/api.ts`).
    Это сотни тысяч строк, и число над ней означало бы не то, что вкладка
    показывает: «Все 66» рядом со списком из четырёхсот тысяч — это не счётчик,
    а второй источник правды. Спрошено же ровно про своё: «сколько у меня
    диалогов взято, сколько не отвечено».

    Область — `_tab_condition("mine")`, то есть буквально условие вкладки «Мои»
    вместе с её умолчанием «кроме закрытых».
    """
    # Долг считается по СВОЕМУ, а список «Моих» — шире (см. `own_condition`).
    ждут = sa.and_(_waiting_condition(), own_condition(viewer.id))
    строка = (
        await db.execute(
            select(
                sa.func.count().label("mine"),
                sa.func.count().filter(ждут).label("mine_waiting"),
            )
            .select_from(Conversation)
            .where(_tab_condition("mine", viewer))
        )
    ).one()
    return {"mine": int(строка.mine), "mine_waiting": int(строка.mine_waiting)}


async def list_conversations(
    db: AsyncSession,
    viewer: User,
    *,
    tab: str = "all",
    q: str | None = None,
    status: str | None = None,
    account_id: uuid.UUID | None = None,
    assignee_id: uuid.UUID | None = None,
    unassigned: bool = False,
    unread_only: bool = False,
    waiting_only: bool = False,
    tag: str | None = None,
    updated_since: datetime | None = None,
    limit: int = 50,
    offset: int = 0,
    transferred: set[str] | None = None,
) -> tuple[list[dict[str, Any]], int]:
    """Items + total for GET /conversations.

    ПОРЯДОК ФИКСИРОВАННЫЙ И СОСТОИТ ИЗ ТРЁХ КЛЮЧЕЙ (разбор от 12 августа):
    закреплённые смотрящим → `last_message_at` убывающе → `id`.
    Параметров сортировки у ручки нет: порядок списка — часть работы
    тринадцати диспетчеров, а не настройка каждого.

    ЧТО ОТСЮДА УБРАЛИ И ПОЧЕМУ. До этой правки первыми ключами стояли
    `unread_count > 0`, «негатив» среди непрочитанных и «кто дольше ждёт» —
    всё производное от колонки `conversations.unread_count`. Колонка
    ГЛОБАЛЬНАЯ: она осталась с тех пор, когда непрочитанное считалось у
    диалога. Сегодня в ответ уезжает ПЕР-ЮЗЕРНОЕ число — сразу после этой
    выборки `read_markers.apply_unread_counts` переписывает `unread_count` в
    каждой строке по маркерам чтения смотрящего.

    То есть сортировали по одному числу, а показывали другое. На боевом
    стенде это видно голыми глазами: диалог с `unread_count: 0` в ответе
    стоял выше диалога, который на два часа свежее, — потому что в колонке у
    него единица от чужого непрочитанного. Со стороны оператора список
    выглядел неотсортированным вовсе, и внешний разбор так его и описал.

    Починить «на месте», сохранив ключ, нельзя: пер-юзерный счётчик считается
    ПОСЛЕ выборки, поверх готовой страницы, а ORDER BY обязан отработать ДО
    LIMIT. Сортировать по нему значило бы тянуть из базы всё и резать
    страницы в памяти — на 454 тысячах диалогов это не вариант. Поэтому
    порядок собран ровно из того, что запрос видит и что выдача показывает.

    ПОСЛЕДНИЙ КЛЮЧ ОБЯЗАТЕЛЕН. Служебные события Авито приходят пачками с
    одинаковой секундой, и без `id` порядок внутри пачки задавала бы база —
    он вправе меняться от запроса к запросу, а значит вторая страница теряла
    бы одни диалоги и дублировала другие. Тот же ORDER BY, что и на первой
    странице, — единственное, что делает offset-пагинацию честной.

    У ЭТОГО ПОРЯДКА ЕСТЬ ЗЕРКАЛО НА КЛИЕНТЕ, и оно обязано меняться вместе с
    этим местом: `frontend/src/shared/lib/conversationOrder.ts`. Фронт
    пересортировывает кэш списка на каждое событие (новое сообщение, патч
    строки, закрепление) — разъедься эти два правила, и список после первого
    же входящего перестроился бы в другой порядок. Индекс под запрос —
    миграция 0028 (`ix_conversations_open_last_message`).
    """
    conds: list[sa.ColumnElement[bool]] = [_tab_condition(tab, viewer, status_given=bool(status))]
    if status:
        # Состояние диалога — ОТДЕЛЬНОЕ измерение от вкладки, а не ещё одна
        # вкладка (UX, замечание заказчика 7 августа).
        #
        # Вкладки отвечают на вопрос «чей диалог» (в очереди / мой / общий), а
        # статус — «в каком он состоянии». Раньше оба признака стояли в одном
        # ряду кнопок: «Мои · Все · Новые · Закрытые». Ряд читался как набор
        # взаимоисключающих режимов, хотя «Новые» и «Закрытые» — это срезы
        # ВНУТРИ «Всех», и половина кнопок выглядела повторяющей соседей.
        # Развести их — единственный способ убрать это ощущение, не отнимая
        # ни одной возможности: «Все + статус Закрытые» даёт ровно то же, что
        # давала вкладка «Закрытые».
        conds.append(Conversation.status == status)
    if q:
        conds.append(_search_condition(db, q))
    if account_id:
        conds.append(Conversation.account_id == account_id)
    if assignee_id:
        conds.append(Conversation.assignee_id == assignee_id)
    if unassigned:
        # Пункт «Без ответственного» фильтра «Менеджер ▾» (11 §2.5.2). Отдельный
        # флаг, а не спецзначение в `assignee_id`: тип поля остаётся uuid, и
        # любая опечатка по-прежнему даёт честный 422, а не «показал всё».
        # Это НЕ вкладка «Новые»: закрытый ботом диалог тоже может быть без
        # ответственного.
        conds.append(Conversation.assignee_id.is_(None))
    if unread_only:
        conds.append(Conversation.unread_count > 0)
    if waiting_only:
        # ⚠ «Ждут ответа» — фильтр, ПАРНЫЙ счётчику на вкладке (жалоба 02.09).
        #
        # Число «не отвечено» бесполезно, если по нему нельзя перейти: у
        # диспетчера 66 диалогов, из них ждут трое, и искать их прокруткой —
        # ровно та работа, которую число должно было отменить.
        #
        # Предикат тот же самый, не «такой же»: см. `_waiting_condition`.
        #
        # ⚠ И ТА ЖЕ ПАРА С «СВОИМ», ЧТО У СЧЁТЧИКА — НО ТОЛЬКО НА «МОИХ».
        #
        # Число на вкладке «Мои» и строки, которые по нему открываются, обязаны
        # сходиться: нажал на «8» — увидел восемь. Считай счётчик своё, а фильтр
        # всё подряд — человек нажимал бы на восемь и получал двадцать.
        #
        # На «Всех» же фильтр значит буквально «клиент ждёт ответа», без
        # оглядки на то, чей это диалог: там нет ни счётчика, ни обещания
        # сходимости, а есть вопрос «где вообще кого-то заждались».
        conds.append(
            sa.and_(_waiting_condition(), own_condition(viewer.id))
            if tab in ("my", "mine")
            else _waiting_condition()
        )
    if tag:
        conds.append(_has_tag(db, tag))
    if updated_since:
        conds.append(Conversation.updated_at >= updated_since)

    # ⚠ СОЕДИНЕНИЯ С `clients` ЗДЕСЬ БОЛЬШЕ НЕТ, И ЭТО НЕ ПОТЕРЯ, А ЗАМЕР.
    #
    # Оно стояло ради поиска по имени клиента — единственного условия, которому
    # нужна была вторая таблица. С 02.09 поиск носит свои соединения внутри
    # веток объединения (`_search_condition`), и снаружи оно не нужно НИКОМУ.
    #
    # Выдачи это не меняет: `conversations.client_id` объявлен NOT NULL и
    # защищён внешним ключом, диалогов без клиента в бою ноль (проверено
    # запросом), то есть внутреннее соединение не отсекало ни одной строки.
    #
    # Цена, которую оно брало на САМОЙ ЧАСТОЙ ручке системы (замер боя 02.09):
    #     count(*) с соединением — 193,9 мс, хэш на 3164 kB по 56 574 клиентам
    #     count(*) без него      —  13,3 мс
    # В 14,6 раза, и это на каждой странице каждого списка у каждого из
    # тринадцати. Тот же приём давно стоит в соседнем модуле
    # (`conversation_table._select_narrowed`).
    base = select(Conversation).where(*conds)

    # ⚠ ПРИ ПОИСКЕ ИТОГ НЕ СЧИТАЕТСЯ ОТДЕЛЬНЫМ count(*) — ОН ЕДЕТ В ТОЙ ЖЕ
    # ВЫБОРКЕ, ЧТО И СТРАНИЦА (`count(*) OVER ()`).
    #
    # Число нужно: фронт рисует по нему «Найдено: N» и решает, есть ли ещё
    # страницы (`ChatListPane`, `loaded < page.total`), так что заменить его
    # приближением нельзя — контракт требует ровно размер выборки. Но платить
    # за него вторым проходом по тем же условиям незачем: при поиске условие
    # `id IN (объединение)` и так собирает ВСЁ множество подходящих диалогов,
    # прежде чем отсортировать и отрезать страницу, — окно просто читает его
    # размер по дороге. Замер боя 06.09: два запроса — это два одинаковых
    # прохода по `clients` (43,7–102 мс + 33–77 мс) на каждое нажатие клавиши.
    #
    # ⚠ БЕЗ ПОИСКА — ПО-ПРЕЖНЕМУ ОТДЕЛЬНЫЙ count(*), И ЭТО НАМЕРЕННО. Страница
    # без поиска идёт по индексу миграции 0028 и останавливается на пятидесятой
    # строке; окно заставило бы её дочитать вкладку до конца. Тот же довод, что
    # у закреплённых ниже: выражение поверх выборки ломает ранний выход.
    #
    # ⚠ ОКНО МОЛЧИТ, КОГДА СТРОК НЕТ. Пустая страница при `offset=0` значит
    # пустую выборку — итог ноль без запроса. Пустая страница при сдвиге (фронт
    # спросил дальше конца по устаревшему итогу) и голова закреплённых, целиком
    # заполнившая страницу, — редкие случаи, там честный count(*).
    итог_окном = bool(q)
    total: int | None = (
        None
        if итог_окном
        else (
            await db.execute(select(sa.func.count()).select_from(Conversation).where(*conds))
        ).scalar_one()
    )

    # Закреплённые — ОДНИМ запросом, до выборки, а не по одному на строку.
    #
    # Раньше этот же набор брался после выборки (только чтобы проставить
    # `pinned` в ответе), а первым ключом сортировки стоял коррелированный
    # EXISTS по `conversation_pins`. Набор нужен обоим местам, и взять его
    # заранее выгоднее вдвойне: у большинства диспетчеров закреплённых нет
    # вовсе, и тогда ключ сортировки просто не появляется — ORDER BY остаётся
    # ровно тем, под который заведён индекс (миграция 0028).
    pinned = await pins.pinned_ids(db, viewer.id)

    # Полный ключ — против дрожания порядка на одинаковых секундах и, как
    # следствие, против дублей и пропусков между страницами. Подробности —
    # в докстринге функции. Ключ ОДИН на обе половины ниже.
    порядок = [Conversation.last_message_at.desc().nulls_last(), Conversation.id]

    всего_окном: int | None = None
    if not pinned:
        # Путь 54 человек из 56 — один запрос, ровно под индекс миграции 0028.
        rows, всего_окном = await _страница(
            db, base.order_by(*порядок).limit(limit).offset(offset), с_итогом=итог_окном
        )
    else:
        # ⚠ ЗАКРЕПЛЁННЫЕ БЕРУТСЯ ОТДЕЛЬНОЙ ВЫБОРКОЙ, А НЕ КЛЮЧОМ СОРТИРОВКИ.
        #
        # ЧТО БЫЛО. Первым ключом стоял `sa.case((id.in_(pinned), 0), else_=1)`.
        # Выражение в ORDER BY делает индексный порядок непригодным: планировщик
        # обязан отсортировать ВСЮ выборку. Замер на боевой базе, вкладка «Все»
        # (там не действует частичный индекс по открытым): 50,1 -> 0,27 мс на
        # выборке строк, 3037 -> 48 буферов; ручка целиком 86,5 -> 28,1 мс.
        #
        # Закрепления сегодня у двоих из 56, и это не довод «можно не чинить»:
        # закрепление задумано как ежедневный инструмент, и как только им
        # начнут пользоваться, каждый получит перебор 44 тысяч строк на КАЖДЫЙ
        # опрос списка.
        #
        # ⚠ ТРИ МЕСТА, ГДЕ ОШИБКА СТОИТ ПОТЕРЯННОГО ДИАЛОГА.
        #
        # 1. У головы НЕТ `limit`. Потолок числа закреплений держит `pins.pin`,
        #    а не эта выборка. Поставь здесь LIMIT MAX_PINS — и если у человека
        #    почему-то окажется восьмое закрепление, оно исчезнет из списка
        #    СОВСЕМ: из хвоста его выбросит `NOT IN`.
        # 2. `np` считается по ФАКТИЧЕСКИ прошедшим фильтр, а не по длине
        #    `pinned`. Закреплённый диалог может не подойти под вкладку, поиск,
        #    «ждут ответа», канал или тег — тогда он в списке не стоит и позиций
        #    не занимает, а смещение хвоста уехало бы ровно на столько диалогов.
        # 3. Обе половины строятся от ОДНОГО `base`. Собирать условия заново
        #    нельзя: пара разъедется молча, и закреплённые полезут в результаты
        #    поиска, которому они не отвечают.
        #
        # Побочная выгода: `pin_ids` — один и тот же питоновский набор в обеих
        # половинах. Даже если человек закрепит или открепит диалог МЕЖДУ двумя
        # запросами, состав страницы останется согласованным. Перечитывать
        # `pinned` между запросами НЕЛЬЗЯ — вот это как раз потеряло бы строку.
        pin_ids = list(pinned)
        голова = list(
            (
                await db.execute(base.where(Conversation.id.in_(pin_ids)).order_by(*порядок))
            ).scalars()
        )
        np = len(голова)
        страница_головы = голова[offset : offset + limit]
        нужно_ещё = limit - len(страница_головы)
        хвост: list[Conversation] = []
        всего_хвоста: int | None = None
        if нужно_ещё > 0:
            # Смещение хвоста считает ТОЛЬКО незакреплённые строки: закреплённые
            # выброшены условием `NOT IN`, и первые `np` позиций полного списка
            # уже съедены головой.
            хвост, всего_хвоста = await _страница(
                db,
                base.where(Conversation.id.notin_(pin_ids))
                .order_by(*порядок)
                .limit(нужно_ещё)
                .offset(max(0, offset - np)),
                с_итогом=итог_окном,
            )
        rows = страница_головы + хвост
        # Голова взята без LIMIT и прошла те же условия, что и хвост: итог —
        # это вся голова плюс размер хвоста, который окно и посчитало.
        if всего_хвоста is not None:
            всего_окном = np + всего_хвоста

    if total is None:
        if всего_окном is not None:
            total = всего_окном
        elif offset == 0 and not rows:
            total = 0
        else:
            total = (
                await db.execute(select(sa.func.count()).select_from(Conversation).where(*conds))
            ).scalar_one()

    related = await _load_related(db, rows)
    flagged = transferred or set()
    items = [
        conversation_out(
            conv,
            account=related["accounts"].get(conv.account_id),
            client=related["clients"].get(conv.client_id),
            assignee=related["users"].get(conv.assignee_id),
            users=related["users"],
            last_message=related["last_messages"].get(conv.id),
            transferred_to_me=str(conv.id) in flagged,
            pinned=conv.id in pinned,
        )
        for conv in rows
    ]
    return items, total


async def _страница(
    db: AsyncSession, stmt: Select[Any], *, с_итогом: bool
) -> tuple[list[Conversation], int | None]:
    """Строки страницы и, если просили, размер всей выборки тем же запросом.

    `count(*) OVER ()` считается ДО `LIMIT`/`OFFSET` — по всему множеству,
    прошедшему `WHERE`, — поэтому число в каждой строке одно и то же и равно
    тому, что дал бы отдельный `count(*)` по тем же условиям. Когда строк нет,
    окну не на чем ехать — тогда `None`, и решает вызывающий (см.
    `list_conversations`).
    """
    if not с_итогом:
        return list((await db.execute(stmt)).scalars()), None
    rows: list[Conversation] = []
    всего: int | None = None
    for conv, n in (await db.execute(stmt.add_columns(sa.func.count().over()))).all():
        rows.append(conv)
        всего = int(n)
    return rows, всего


async def _load_related(db: AsyncSession, convs: list[Conversation]) -> dict[str, dict]:
    """Batch-load accounts/clients/assignees/last messages for a page.

    Служебные записи Авито в превью — по той же настройке, что и в ленте
    (17.08): тумблер «Не показывать…» скрывал их в открытом диалоге, а строка
    списка продолжала показывать «[Системное сообщение]…» — владелец читал
    это как «уведомления всё равно приходят».
    """
    if not convs:
        return {"accounts": {}, "clients": {}, "users": {}, "last_messages": {}}
    account_ids = {c.account_id for c in convs}
    client_ids = {c.client_id for c in convs}
    # Ответственный, а также обе стороны предложенной передачи: их имена
    # показываются в диалоге («Борис ждёт вашего подтверждения»), и подгружать
    # их отдельным запросом на каждую строку значило бы полсотни походов в
    # базу на открытие списка.
    user_ids = {c.assignee_id for c in convs if c.assignee_id}
    user_ids |= {c.transfer_to_id for c in convs if c.transfer_to_id}
    user_ids |= {c.transfer_by_id for c in convs if c.transfer_by_id}
    # Здесь же грузился `snoozed_by_id` — автор отложки. Отложку сняли
    # 12 августа; колонка в базе осталась, но её никто не показывает, и грузить
    # ради неё лишние строки `users` больше незачем.
    conv_ids = [c.id for c in convs]

    accounts = {
        a.id: a
        for a in (
            await db.execute(select(AvitoAccount).where(AvitoAccount.id.in_(account_ids)))
        ).scalars()
    }
    clients = {
        c.id: c
        for c in (await db.execute(select(Client).where(Client.id.in_(client_ids)))).scalars()
    }
    users = (
        {u.id: u for u in (await db.execute(select(User).where(User.id.in_(user_ids)))).scalars()}
        if user_ids
        else {}
    )

    from app.services import app_settings as _app_settings

    _avito_hidden = bool(await _app_settings.get(db, _app_settings.AVITO_SYSTEM_HIDDEN))
    _preview_cond = (
        Message.direction.in_(("in", "out")) if _avito_hidden else PREVIEW_MESSAGE_CONDITION
    )
    last_messages = {
        m.conversation_id: m
        for m in (
            await db.execute(_last_message_stmt(_dialect(db), conv_ids, _preview_cond))
        ).scalars()
    }
    return {
        "accounts": accounts,
        "clients": clients,
        "users": users,
        "last_messages": last_messages,
    }


def _last_message_stmt(
    dialect: str, conv_ids: Sequence[uuid.UUID], допуск: sa.ColumnElement[bool]
) -> Select[Any]:
    """Последнее допущенное в превью сообщение каждого диалога страницы.

    ⚠ НА POSTGRES — `CROSS JOIN LATERAL (… ORDER BY created_at DESC, id DESC
    LIMIT 1)`, А НЕ ОКНО `row_number()`. Оба дают одни и те же строки (сверено
    на бою 07.09: 50 диалогов, одинаковый дайджест выдачи), но платят за них
    по-разному. Окно ОБЯЗАНО прочитать все сообщения пятидесяти диалогов
    (581 строка по 28 партициям), отсортировать их и выбросить всё, кроме
    первого в каждой группе. LATERAL для каждого диалога делает один шаг по
    индексу `(conversation_id, created_at)` назад и останавливается на первой
    строке. Замер боя 07.09, свежее соединение: буферы 3 067 → 512 (−83 %),
    исполнение 8,7 → 2,9 мс; аудит 06.09 на прогретом соединении:
    планирование 11–62 мс → 4,7 мс, исполнение 8–24 → 1,2 мс.

    Ведущая выборка — `SELECT id FROM conversations WHERE id IN (…)`, а не
    список литералов: пятьдесят обращений по первичному ключу стоят пятьдесят
    буферов, зато у столбца есть тип, и LATERAL привязывается к нему без
    приведений.

    ⚠ ЗАПАСНАЯ ВЕТКА — ДЛЯ SQLite, где LATERAL нет вовсе. Это прежняя форма с
    окном; по ней идут юнит-тесты, а форму Postgres стережёт компиляция в
    `test_list_preview_lateral_0609.py` и сравнение двух форм на настоящем
    Postgres в `tests/integration/test_perf_0609_pg.py`.

    Порядок внутри диалога — `(created_at DESC, id DESC)`, тот же, что в ленте:
    служебные события Авито приходят пачками с одной секундой, и без второго
    ключа «последнее» дрожало бы от запроса к запросу.
    """
    if dialect == "postgresql":
        страница = select(Conversation.id).where(Conversation.id.in_(conv_ids)).subquery("page")
        последнее = (
            select(Message)
            .where(Message.conversation_id == страница.c.id, допуск)
            .order_by(Message.created_at.desc(), Message.id.desc())
            .limit(1)
            .lateral("last")
        )
        latest = sa.orm.aliased(Message, последнее)
        return select(latest).select_from(страница.join(последнее, sa.true()))

    rn = (
        sa.func.row_number()
        .over(
            partition_by=Message.conversation_id,
            order_by=(Message.created_at.desc(), Message.id.desc()),
        )
        .label("rn")
    )
    sub = (
        select(Message, rn)
        .where(
            Message.conversation_id.in_(conv_ids),
            допуск,  # см. `PREVIEW_MESSAGE_CONDITION`: кто и почему сюда допущен
        )
        .subquery()
    )
    latest = sa.orm.aliased(Message, sub)
    return select(latest).where(sub.c.rn == 1)


