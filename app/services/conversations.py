def add_system_message(db: AsyncSession, conv: Conversation, body: str) -> Message:
    """Системная запись в ленту (01 §5.4/§5.5): видна сотрудникам, клиенту не уходит.

    `last_message_at` НЕ двигаем: это метка активности переписки, по ней
    сортируется список (01 §5.1) — служебная запись не должна выталкивать
    диалог наверх.
    """
    msg = Message(
        id=uuid.uuid4(),
        conversation_id=conv.id,
        external_message_id=None,
        direction="system",
        sender_type="system",
        sender_user_id=None,
        body=body,
        attachments=[],
        delivery_status="delivered",
        created_at=datetime.now(UTC),
    )
    db.add(msg)
    return msg


