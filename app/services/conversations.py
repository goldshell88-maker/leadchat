async def ensure_in_progress(
    db: AsyncSession,
    conv: Conversation,
    *,
    source: str,
    actor_id: uuid.UUID | None,
    now: datetime | None = None,
) -> bool:
    """«Кто-то взялся за диалог» — один вход для всех АВТОМАТИЧЕСКИХ переходов.

    Возвращает True, если статус изменился (вызывающему это нужно, чтобы
    решить, публиковать ли кадр и писать ли системную запись).

    ПОЧЕМУ ОДНА ФУНКЦИЯ. До docs/38 это был один и тот же `if` в четырёх
    местах — первый ответ оператора (`messages`), автораздача и принятие из
    очереди (`inbox`), принятие передачи (`transfer`), — и каждая копия знала
    СВОЙ набор исходных статусов. Пока значений было три, разница не всплывала;
    стоило добавить четвёртое — и каждая копия пропустила бы своё подмножество.

    ЧТО ИМЕННО БУДИТСЯ. Только `new`. Здесь же был `snoozed` со снятием срока;
    отложку убрали 12 августа решением владельца.

    А ВОТ `waiting_client` НЕ СБРАСЫВАЕТСЯ, И ЭТО ГЛАВНОЕ РЕШЕНИЕ ЗДЕСЬ. Мы
    ждём клиента и написали ему ещё раз («напоминаю про завтра») — ход
    по-прежнему за клиентом. Сбрасывай мы статус на любом нашем сообщении,
    любое напоминание возвращало бы диалог в «В работе», и значение обесценилось
    бы за один день: в «Ждёт клиента» не осталось бы ничего, кроме диалогов, в
    которые никто не заходил. Разбудить его может только сам клиент
    (`inbound.apply_inbound_event`) или человек руками.
    """
    if conv.status != "new":
        return False
    previous = conv.status
    status_dict.set_status(conv, "in_progress", now=now)
    await write_audit(
        db,
        user_id=actor_id,
        action="conversation.status_changed",
        entity="conversation",
        entity_id=str(conv.id),
        details={
            "from": previous,
            "to": "in_progress",
            # `by` различает решение человека и решение системы: по нему
            # считается «закрыто ботом» в статистике и читается журнал.
            "by": "operator" if actor_id is not None else "system",
            "source": source,
            "assignee_id": str(conv.assignee_id) if conv.assignee_id else None,
        },
    )
    # ⚠ ТРЕВОГИ «ИМ НИКТО НЕ ЗАНЯТ» ГАСНУТ ЗДЕСЬ ТОЖЕ (жалоба владельца 28.08:
    # «сделай, чтобы история уведомлений чистилась, а то приходят все за всё
    # время»).
    #
    # Механизм гашения написан давно и позван из трёх мест: принятия из очереди,
    # смены статуса руками и назначения ответственного. А эта функция — вход для
    # всех АВТОМАТИЧЕСКИХ переходов «кто-то взялся за диалог», и среди них тот,
    # которым сегодня отвечают чаще всего: ответ, написанный в приложении Авито.
    # Мимо гашения проходила ровно та дорога, по которой идёт большинство.
    #
    # Замер боя 28.08: 2466 непрочитанных «Диалог никто не принял» из 2650
    # непрочитанных вообще — 93% колокольчика составляли тревоги о диалогах,
    # которыми давно занялись. Цена записана рядом, в `cli.dismiss-stale-alerts`:
    # «пока завал не разобран, колокольчик бесполезен — его перестают открывать,
    # и следующая настоящая тревога опоздает ровно настолько, насколько человек
    # привык не смотреть».
    await notifications.resolve_conversation(db, conv.id)
    return True


async def clean_up_closed(db: AsyncSession, conv: Conversation, *, by_user: User | None) -> None:
    """Уборка, без которой закрытый диалог продолжает жить: одна на все пути
    закрытия — руками и сторожем освобождения.

    * ожидание и непрочитанное — иначе сторож напоминал бы о закрытом вечно,
      а шкала «ждёт 3 ч» и бейдж трея считали бы его живым;
    * висящее предложение передачи — у получателя осталась бы рабочая
      «Принять» на закрытом обращении;
    * закрепления у всех — невидимые закладки на закрытых съедали предел семи;
    * метки очереди `offered_at`/`claimed_at`/`escalated_at` — под обещание
      «у закрытого их нет» построены частичные индексы очереди, а путь возврата
      без `enter_queue` втаскивал недельное ожидание первым в очередь;
    * бот замолкает (`mute`, а не `bot_active = False`): иначе отложенный
      дожим писал бы клиенту закрытого диалога, а вернувшийся клиент попал бы
      на второй круг сценария.
    """
    from app.bots.runtime import mute_bot

    await clear_closed_marks(db, conv)
    await mute_bot(db, conv, by_user=by_user, audit=False)


async def clear_closed_marks(db: AsyncSession, conv: Conversation) -> None:
    """Полевая часть уборки закрытия — общая с закрытием ботом (проверка 24.09).

    Бот закрывал диалог, оставляя `offered_at`, ожидание, непрочитанное и чужие
    закрепления: переоткрытый руководителем такой диалог вставал в очередь
    первым с «ждёт N дней», а вернувшийся клиент сразу эскалировался. Бота
    здесь не глушим: шаг `close` по 02 §1.3 этого не делает.
    """
    from app.services import transfer as transfer_svc
    from app.services.inbox import clear_awaiting

    clear_awaiting(conv)
    conv.unread_count = 0
    if transfer_svc.is_pending(conv):
        transfer_svc.clear(conv)
    await db.execute(sa.delete(ConversationPin).where(ConversationPin.conversation_id == conv.id))
    conv.offered_at = None
    conv.claimed_at = None
    conv.escalated_at = None


async def change_status(
    db: AsyncSession,
    conv: Conversation,
    *,
    new_status: str,
    actor: User,
) -> Message:
    """PATCH /conversations/{id}/status (01 §5.4). Возвращает системную запись.

    Транзакцию и публикацию событий держит endpoint (08 §8.1).

    ЗАКРЫТИЕ ОДНОШАГОВОЕ. У функции были ещё четыре параметра — `outcome`,
    `outcome_amount`, `snooze_until`, `snooze_reason`, — и вместе с ними вопрос
    «чем закончилось» на каждом закрытии и целая ветка отложки. Всё снято
    12 августа решением владельца.

    Разрешённое живёт матрицей в `services.conversation_status.TRANSITIONS`, а
    не двумя `if`-ами подряд, как было до docs/38. Разница не в опрятности:
    пока правило было размазано по телу функции, «что можно» приходилось
    выводить чтением — и вывод «всё, кроме closed → new» оказался верным, хотя
    ни в одном комментарии записан не был.
    """
    if new_status not in STATUSES:
        raise ApiError(
            "validation_error",
            "Недопустимый статус",
            status=400,
            details={
                "fields": [
                    {"field": "status", "rule": "enum", "message": "|".join(STATUSES)},
                ]
            },
        )
    previous = conv.status
    if previous == new_status:
        # ГОНКА «ДВОЕ ВЗЯЛИ ОДНОВРЕМЕННО» ОТВЕЧАЕТ ЗДЕСЬ, И ОТВЕЧАЕТ ЧЕСТНО.
        #
        # Раньше второй оператор получал 422 «Диалог уже в этом статусе» —
        # сообщение, верное по букве и бесполезное по смыслу: человек не
        # узнавал, что диалог забрал коллега, и жал кнопку снова. Путь очереди
        # (`inbox.claim`) на ту же гонку отвечает 409 `already_claimed` с
        # именем победителя; теперь оба пути отвечают одинаково, и в интерфейсе
        # у них один обработчик.
        #
        # Условие узкое НАМЕРЕННО — только «взять в работу» и только когда
        # диалог уже у кого-то другого. Руководитель, который переводит в «В
        # работе» чужой диалог, гонку не проигрывает: его перевод состоялся бы
        # и без нас, а `previous == new_status` у него означает ровно то, что
        # написано.
        if new_status == "in_progress" and conv.assignee_id not in (None, actor.id):
            holder = await db.get(User, conv.assignee_id)
            name = holder.full_name if holder else "коллега"
            raise ApiError(
                "already_claimed",
                f"Диалог уже взял {name}",
                status=409,
                details={
                    "reason": "already_claimed",
                    "claimed_by": user_ref(holder),
                    "mine": False,
                },
            )
        raise ApiError(
            "unprocessable",
            "Диалог уже в этом статусе",
            status=422,
            details={"reason": "same_status"},
        )
    # ⚠ ОБРАЩЕНИЕ ИЗ ОЧЕРЕДИ ХОРОНИТ ТОЛЬКО АДМИНИСТРАТОР (владелец, 22.08).
    #
    # Диалог во «Входящих» никто ещё не взял, а закрытие убирает его из очереди
    # НАСОВСЕМ: `inbox.queue_condition` требует `status != closed`. Один
    # случайный «Закрыть» — и обращение, которому не ответили, исчезает у всех,
    # а клиент ждёт. Оператору для «я сейчас занят» есть «Отклонить»: диалог
    # уходит с его глаз на три минуты и возвращается в общую очередь.
    #
    # ПРОВЕРКА НА СЕРВЕРЕ, а не только спрятанной кнопкой: кнопка защищает от
    # случайного нажатия, но не от горячей клавиши, повторного запроса и чужого
    # клиента.
    from app.services import inbox as inbox_mod  # круг импортов: inbox тянет нас

    if (
        new_status == "closed"
        and inbox_mod.is_waiting(conv)
        and ("conversations:close_queued" not in ROLE_PERMISSIONS.get(actor.role, frozenset()))
    ):
        raise ApiError(
            "forbidden",
            "Обращение ещё никто не взял. Нажмите «Отклонить» — оно вернётся в очередь "
            "к коллегам. Закрыть необработанное может только администратор",
            status=403,
            details={"reason": "queued_close_forbidden"},
        )
    # ⚠ ЗАШЁДШИЙ САМ ЧУЖОЙ ДИАЛОГ НЕ ЗАКРЫВАЕТ (жалоба владельца 04.09:
    # «я закрываю диалог у себя — он закрывается и у Петрова Ивана»).
    #
    # ЧТО БЫЛО. Открытие чужого рабочего диалога записывало человека в
    # участники само, и диалог вставал в его «Мои» рядом с собственными. Дальше
    # «Закрыть» означало для него «убрать у себя» — а означало на деле «закрыть
    # клиенту». В бою это стоило живого разговора: администратор закрыл диалог
    # в 14:38, клиент написал в 14:42, и хозяину пришлось принимать его заново.
    # Все три записи «зашёл сам», какие были в базе, оказались такими.
    #
    # ЧТО ТЕПЕРЬ. Вход стал нажатием («Войти в диалог»), а выход — «Выйти»:
    # именно он убирает диалог из «Моих» и никого не трогает. Закрытие
    # остаётся тем, чем было, — общим действием хозяина.
    #
    # ПОЧЕМУ ОТКАЗ, А НЕ ТИХАЯ ЗАМЕНА НА ВЫХОД. Администратор иногда закрывает
    # чужой диалог по делу (9 раз за 30 дней). Подмени мы ему действие молча —
    # он ушёл бы, считая диалог закрытым. Пусть лучше скажем прямо.
    #
    # ПОЗВАННОГО ЭТО НЕ КАСАЕТСЯ: его позвали помогать, и права он получил
    # осознанно (см. `participants.invited_ids`).
    from app.services import participants as participants_mod  # noqa: PLC0415 — как выше

    if (
        new_status == "closed"
        and conv.assignee_id is not None
        and conv.assignee_id != actor.id
        and await participants_mod.is_guest(db, conv.id, actor.id)
    ):
        holder = await db.get(User, conv.assignee_id)
        имя = holder.full_name if holder else "коллега"
        raise ApiError(
            "forbidden",
            f"Диалог ведёт {имя}, а вы в нём гость. Закрытие закроет его и у хозяина — "
            "чтобы убрать диалог из своих, нажмите «Выйти»",
            status=403,
            details={"reason": "guest_cannot_close"},
        )
    if not status_dict.can_transition(previous, new_status):
        # Причина у каждого запрета своя и объяснена словами: «нельзя» без
        # объяснения оператор читает как поломку и идёт к администратору.
        reason, message = status_dict.denial(previous, new_status)
        raise ApiError("unprocessable", message, status=422, details={"reason": reason})

    if new_status == "waiting_client" and not await _has_operator_reply(db, conv):
        # «Ждёт клиента» означает «ход за клиентом», а ход не может быть за
        # тем, кому ещё ничего не сказали. Матрица одна этого не ловит:
        # `in_progress → waiting_client` разрешён, а взять диалог в работу
        # можно и не написав ни слова (руководитель, кнопка «Взять в работу»).
        raise ApiError(
            "unprocessable",
            "Клиенту ещё никто не ответил — ждать ему нечего",
            status=422,
            details={"reason": "no_reply_yet"},
        )

    status_dict.set_status(conv, new_status)
    # Сменил статус — значит диалог в руках у человека, а не просто выдан.
    from app.services.inbox import clear_auto_assignment

    clear_auto_assignment(conv)
    if new_status == "closed":
        await clean_up_closed(db, conv, by_user=actor)
    took_over = False
    прежний_хозяин = conv.assignee_id
    # ⚠ ЗАКРЫТЫЙ ДИАЛОГ НИЧЕЙ, И ВОЗВРАТ В РАБОТУ ОТДАЁТ ЕГО НАЖАВШЕМУ.
    #
    # Слова владельца (03.09), две жалобы подряд: «когда диалог закрыт, то он по
    # факту не чей… сейчас из-за этого себе в работу нельзя забрать диалог» и,
    # после первой правки, «взял в работу и снова так же в „Мои" диалог не
    # появился».
    #
    # ЧТО БЫЛО. Владелец менялся ровно у НИЧЕЙНОГО диалога, а закрытие
    # ответственного не снимает. Значит переоткрытие чужого закрытого диалога
    # возвращало его ПРЕЖНЕМУ хозяину — тот на месте, тот и ведёт, — а нажавший
    # оставался ни с чем и своей строки в «Моих» не видел.
    #
    # Тупик был полный, а не «неудобно»: в «Мои» диалог не попадал (там свои и
    # не закрытые), во «Входящие» тоже — очередь требует `offered_at`, а
    # закрытие его чистит; «Принять» такой диалог не берёт; ответ клиенту
    # владельца не меняет; POST /assign на закрытом отвечает «сначала
    # переоткройте» — подсказка вела в круг.
    #
    # ЗАМЕР БОЯ ЗА 30 СУТОК: 115 переоткрытий, из них 21 — чужого диалога
    # (17 раз жал диспетчер, 4 — администратор). Ни одного случая «диалог
    # ничей»: ветка «кто взял, тот и ведёт» на переоткрытии не срабатывала
    # никогда.
    #
    # ⚠ ПОЧЕМУ ЭТО НЕ ОТЪЁМ ЧУЖОЙ РАБОТЫ. Закрытого диалога нет ни в чьих
    # «Моих» — вкладка исключает закрытые. То есть у прежнего хозяина ничего не
    # отнимается: диалог ушёл из его списка в момент ЗАКРЫТИЯ, а не сейчас. Сам
    # переход виден в ленте и в аудите: системная запись называет и того, кто
    # взял, и того, кто вёл.
    #
    # ⚠ ПОЛИТИКА НЕ НОВАЯ. Когда закрытый диалог переоткрывает КЛИЕНТ своим
    # сообщением, ответственный снимается явно и диалог уходит в очередь
    # (`inbound.apply_inbound_event`). Ручной путь делал ровно обратное — две
    # двери в одно состояние вели к разным хозяевам.
    #
    # ⚠ ТОЛЬКО ИЗ «ЗАКРЫТ». `previous == "closed"` здесь обязательно: у живого
    # диалога смена статуса ответственного не трогает и трогать не должна —
    # иначе перевод коллеги в «Ждёт клиента» и обратно менял бы хозяина.
    #
    # ⚠ head/observer СЕБЕ ВЗЯТЬ НЕ МОГУТ (`can_answer_clients`), и у них
    # поведение остаётся прежним: диалог возвращается к тому, кто его вёл.
    # Отправить его вместо этого в общую очередь заманчиво, но это отдельная
    # ветка с собственными краями (заблокированный клиент, повторное нажатие,
    # метка ожидания), а в бою за месяц её не позвали ни разу: руководитель
    # среди нажимавших не встретился. Пустой ветки, которую нечем проверить на
    # живых данных, здесь не будет.
    #
    берёт_себе = conv.assignee_id is None or previous == "closed"
    if new_status == "in_progress" and берёт_себе and can_answer_clients(actor.role):
        # «кто взял — тот и ведёт» (01 §6.2)
        conv.assignee_id = actor.id
        # Держателем очереди диалог считает `claimed_by_id or assignee_id`: без
        # этой строки новый хозяин не смог бы вернуть в очередь свой же диалог —
        # сервер ответил бы «не держатель», имея в виду прежнего.
        conv.claimed_by_id = actor.id
        conv.claimed_at = datetime.now(UTC)
        took_over = прежний_хозяин != actor.id

    body = f"Статус: {_status_label(previous)} → {_status_label(new_status)}. {actor.full_name}"
    if took_over:
        body = f"{body} — взял(а) в работу"
        if прежний_хозяин is not None:
            # Переход владения обязан быть виден в ленте, а не только в аудите:
            # прежний хозяин открывает диалог и читает, куда делась его работа.
            прежний = await db.get(User, прежний_хозяин)
            if прежний is not None:
                body = f"{body} (вёл(а) {прежний.full_name})"
    msg = add_system_message(db, conv, body)

    await write_audit(
        db,
        user_id=actor.id,
        action="conversation.status_changed",
        entity="conversation",
        entity_id=str(conv.id),
        details={
            "from": previous,
            "to": new_status,
            "by": "operator",
            "assignee_id": str(conv.assignee_id) if conv.assignee_id else None,
        },
    )
    if took_over:
        await write_audit(
            db,
            user_id=actor.id,
            action="conversation.assigned",
            entity="conversation",
            entity_id=str(conv.id),
            details={
                "assignee_id": str(actor.id),
                # Здесь стоял литерал `None`, и он был правдой ровно пока
                # владелец менялся только у ничейного диалога. С переоткрытием
                # он стал бы враньём в единственном поле, ради которого запись
                # и заводили.
                "prev_assignee_id": str(прежний_хозяин) if прежний_хозяин else None,
                "by": "self",
            },
        )
    # Состояние диалога изменилось руками человека — значит тревоги про то, что
    # им никто не занят, устарели. Самая заметная из них: «Диалог никто не
    # принял» продолжала висеть у администраторов при уже ЗАКРЫТОМ диалоге и
    # звала «взять его во Входящих», где его давно нет.
    await notifications.resolve_conversation(db, conv.id)
    return msg


async def resolve_assignee(
    db: AsyncSession,
    assignee_id: uuid.UUID | None,
    *,
    redis: Redis | None = None,
    require_online: bool = False,
    actor_id: uuid.UUID | None = None,
) -> User | None:
    """Проверки получателя из 01 §5.5 (422 с машиночитаемым reason).

    ``require_online`` — правило владельца от 28.08: «сделай так, чтобы не было
    возможности передать диалог человеку в офлайн». Проверка живёт ЗДЕСЬ, рядом
    с остальными проверками получателя, а не в интерфейсе: список сотрудников
    грузится один раз при открытии окна, и человек в нём успевает уйти домой,
    пока оператор дописывает комментарий. Отсеивать только в списке значит
    договориться, а не запретить.

    ``actor_id`` — сам себе диалог можно забрать всегда. Он в сети по факту
    запроса, а отметка присутствия принадлежит WS-хабу и живёт с TTL: подвисшее
    соединение не повод отказать человеку в его же диалоге.
    """
    if assignee_id is None:
        return None
    assignee = await db.get(User, assignee_id)
    if assignee is None:
        raise ApiError(
            "unprocessable",
            "Сотрудник не найден",
            status=422,
            details={"reason": "assignee_not_found"},
        )
    if not assignee.is_active:
        raise ApiError(
            "unprocessable",
            "Сотрудник отключён",
            status=422,
            details={"reason": "assignee_inactive"},
        )
    if not can_answer_clients(assignee.role):
        raise ApiError(
            "unprocessable",
            "Этому сотруднику нельзя передать диалог — он не отвечает клиентам",
            status=422,
            details={"reason": "assignee_cannot_chat"},
        )
    if require_online and redis is not None and assignee.id != actor_id:
        # ⚠ ПЕРЕДАВАТЬ В ОФЛАЙН НЕЛЬЗЯ (решение владельца 28.08).
        #
        # Переданный диалог не появляется ни в очереди, ни в «Моих» получателя,
        # пока тот не примет передачу, — то есть отданный ушедшему домой человеку
        # он не виден НИКОМУ и ждёт молча. Отдающий при этом уверен, что дело
        # сделано.
        #
        # Ключ присутствия читаем тем же хелпером, что и список сотрудников
        # (`ws.presence`), — чтобы окно и запрет говорили об одном и том же.
        from app.ws.presence import presence_map  # noqa: PLC0415 — зона WS

        online = await presence_map(redis, [assignee.id])
        if not online.get(assignee.id, False):
            raise ApiError(
                "unprocessable",
                f"{assignee.full_name} сейчас не в сети — передать диалог некому",
                status=422,
                details={"reason": "assignee_offline"},
            )
    return assignee


def _assignment_kind(actor: User, new_assignee_id: uuid.UUID | None) -> str:
    """`details.by` для `conversation.assigned` — словарь 06 §0.3.

    `auto` пишет не эта ручка, а автоназначение по первому ответу (01 §6.2).
    """
    if new_assignee_id is not None and new_assignee_id == actor.id:
        return "self"
    return "head" if actor.role == "head" else "transfer"


async def assign_conversation(
    db: AsyncSession,
    conv: Conversation,
    *,
    assignee: User | None,
    actor: User,
    comment: str | None = None,
) -> Message:
    """POST /conversations/{id}/assign (01 §5.5). Возвращает системную запись."""
    previous_id = conv.assignee_id
    new_id = assignee.id if assignee else None
    if previous_id == new_id:
        raise ApiError(
            "unprocessable",
            "Диалог уже назначен на этого сотрудника"
            if new_id
            else "У диалога и так нет ответственного",
            status=422,
            details={"reason": "same_assignee"},
        )

    # Закрытый диалог ни предлагать, ни назначать нельзя: у получателя он не
    # появится ни в «Моих», ни в очереди, а снятие ответственного воскресило бы
    # его в очередь в обход матрицы статусов. Сначала переоткрывают.
    if conv.status == "closed":
        raise ApiError(
            "conversation_closed",
            "Диалог закрыт. Сначала переоткройте его, потом назначайте",
            status=422,
        )

    from app.services import transfer as transfer_svc

    # ПЕРЕДАЧА ДРУГОМУ ЧЕЛОВЕКУ — ПРЕДЛОЖЕНИЕ, А НЕ ДЕЙСТВИЕ (требование
    # заказчика от 7 августа: «диалог не считается переданным, если другой
    # сотрудник его не принял»). Ответственный не меняется, пока получатель не
    # согласится; подробности — в шапке `services/transfer.py`.
    #
    # Мгновенными остаются три случая, и каждый по своей причине: взять себе
    # (принимать нечего), снять ответственного (диалог уходит в очередь, у неё
    # своё принятие) и назначить диалог, у которого ответственного НЕТ — это
    # раздача, а не передача: отнимать не у кого, и ждать подтверждения значило
    # бы оставить клиента без ответа ради формальности.
    if assignee is not None and previous_id is not None and assignee.id != actor.id:
        transfer_svc.offer(conv, to=assignee, actor=actor, comment=comment)
        body = f"Диалог предложен: {actor.full_name} → {assignee.full_name}"
        if comment:
            body = f"{body}. Комментарий: {comment}"
        msg = add_system_message(db, conv, body)
        await write_audit(
            db,
            user_id=actor.id,
            action="conversation.transfer_offered",
            entity="conversation",
            entity_id=str(conv.id),
            details={
                "to_id": str(assignee.id),
                "from_id": str(previous_id),
                "comment": bool(comment),
            },
        )
        return msg

    previous_status = conv.status
    conv.assignee_id = new_id
    # Назначение решает судьбу диалога напрямую: висящее предложение устарело.
    # Весть его получателю отправляет ручка — она видит, кому предлагали.
    if transfer_svc.is_pending(conv):
        transfer_svc.clear(conv)
    # Передача — решение человека. Отметку автораздачи снимаем, иначе система
    # отобрала бы у нового ответственного диалог, который ему отдали руками.
    from app.services.inbox import clear_auto_assignment

    clear_auto_assignment(conv)
    if new_id is not None:
        # Назначили — «никто не берёт» больше не правда.
        conv.escalated_at = None
        if conv.bot_active:
            # Назначили человеку диалог, который вёл бот, — бот отходит тем же
            # движением (проверка 24.09). Иначе дедлайн `ask` через полчаса
            # дожимал клиента у назначенного оператора, а у того висел баннер
            # «Диалог ведёт бот». Не `mute`: вернут в очередь — ворота решат.
            from app.bots.state import BotState

            state = BotState.from_conv(conv)
            state.stop_waiting()
            conv.bot_vars = state.dump()
            conv.bot_active = False
    # 01 §5.5: назначили — «в работе»; сняли назначение — обратно в «Новые».
    #
    # Отложка снимается в ОБЕ стороны. Диалог, отложенный до завтра и отданный
    # коллеге, у коллеги отложенным быть не должен: он его не откладывал и про
    # срок не знает. Диалог, у которого сняли ответственного, уезжает в
    # очередь — там отложке тем более не место, иначе сторож разбудит ничей
    # диалог и назначит его тому, кто уже не при чём.
    status_dict.clear_snooze(conv)
    status_dict.set_status(conv, "in_progress" if new_id else "new")
    if new_id is None:
        # Снять ответственного — значит вернуть диалог В ОЧЕРЕДЬ, а не просто
        # обнулить поле (7.1). Без этого у диалога остаётся `claimed_by_id`
        # принявшего, предикат очереди его не пускает, и диалог зависает в
        # «Новых» невидимым для «Входящих» — то есть ровно в том состоянии, от
        # которого 7.1 и спасает: он есть, он ничей, и его никто не берёт.
        # Прошлые отказы сохраняются (`keep_declines`): руководитель разбирает
        # затор, а не даёт отказавшимся второй круг.
        # Импорт внутри функции — inbox импортирует этот модуль сверху (цикл).
        from app.services.inbox import return_to_queue

        return_to_queue(conv)

    if assignee is None:
        body = f"Диалог возвращён в «Новые». {actor.full_name}"
    elif assignee.id == actor.id:
        body = f"Диалог взят в работу: {actor.full_name}"
    else:
        body = f"Диалог передан: {actor.full_name} → {assignee.full_name}"
    if comment:
        # 01 §5.5: комментарий коллеге едет в ленту той же системной записью —
        # клиенту он не уходит никогда.
        body = f"{body}. Комментарий: {comment}"
    msg = add_system_message(db, conv, body)

    await write_audit(
        db,
        user_id=actor.id,
        action="conversation.assigned",
        entity="conversation",
        entity_id=str(conv.id),
        details={
            "assignee_id": str(new_id) if new_id else None,
            "prev_assignee_id": str(previous_id) if previous_id else None,
            # 06 §0.3: self | transfer | head | auto. Переназначение чужого
            # диалога руководителем — это `head`, иначе журнал показывает
            # «Диалог передан коллеге» вместо «переназначен руководителем».
            "by": _assignment_kind(actor, new_id),
            "comment": bool(comment),
        },
    )
    if conv.status != previous_status:
        await write_audit(
            db,
            user_id=actor.id,
            action="conversation.status_changed",
            entity="conversation",
            entity_id=str(conv.id),
            details={
                "from": previous_status,
                "to": conv.status,
                "by": "operator",
                "assignee_id": str(new_id) if new_id else None,
            },
        )
    # Тот же довод, что у смены статуса, — но ТОЛЬКО когда ответственный
    # появился. Снятие ответственного возвращает диалог В ОЧЕРЕДЬ (см.
    # `return_to_queue` выше), то есть «его никто не принял» снова становится
    # правдой, и гасить тревогу здесь значило бы прятать живую.
    if new_id is not None:
        await notifications.resolve_conversation(db, conv.id)
    return msg


