# Телефон ищем только по достаточно длинному куску цифр: «iPhone 13» не должен
# превращаться в LIKE '%13%' по всем телефонам базы.
PHONE_QUERY_MIN_DIGITS = 5


def normalize_phone_query(q: str) -> str | None:
    """Цифры запроса, приведённые к хвосту номера (01 §5.1).

    В базе телефон лежит канонично `+7XXXXXXXXXX` (`app/services/phone_parse.py`),
    а человек ищет как придётся: «8 900 111-22-45», «+7 (900) 1112245»,
    «9001112245», «111-22-45». Снимаем разделители и отрезаем национальный
    префикс 7/8 — остаток одинаково находится подстрокой в канонической записи.
    """
    digits = re.sub(r"\D", "", q)
    if len(digits) < PHONE_QUERY_MIN_DIGITS:
        return None
    if len(digits) == 11 and digits[0] in "78":
        digits = digits[1:]
    return digits


def _search_condition(db: AsyncSession, q: str) -> sa.ColumnElement[bool]:
    """q= (01 §5.1): имя клиента, телефон и текст переписки — одним поиском.

    ⚠ ЗДЕСЬ БЫЛО `OR` ИЗ ЧЕТЫРЁХ ПРОВЕРОК, И ОНО СТОИЛО ДО ПОЛУТОРА МИНУТ
    ЗАВИСАНИЯ (замер боя 02.09). Условие читалось естественно — «имя ИЛИ телефон
    ИЛИ кандидат ИЛИ текст», — но планировщику `OR` запрещает зайти со стороны
    индекса: он обязан проверить ВЕСЬ предикат на каждой строке. План на боевых
    данных: Nested Loop по всем 42 686 диалогам, и внутри — Append по 28
    партициям `messages` на каждый диалог. Больше миллиона обращений на один
    поиск.

    ЧТО ЭТО ЗНАЧИЛО ДЛЯ ЧЕЛОВЕКА (замер 02.09, боевая база):
        слово «телевизор» — 1,5-1,8 с
        имя «Иван»        — 2,9-4,6 с
        короткое «ре»     — 3,0-11,2 с
        ТЕЛЕФОН           — 27,6 с, худший случай 93 с
    Поиск идёт по мере набора, то есть на номер из десяти цифр уходило несколько
    таких запросов подряд. Со стороны диспетчера это «приложение зависло».

    ⚠ ПОЧЕМУ `UNION` БЫСТРЕЕ, ХОТЯ ЗАПРОСОВ СТАЛО БОЛЬШЕ. Потому что каждая ветка
    получает СВОЙ вход. Главное — ветка по тексту: она идёт от `ix_messages_search`
    (GIN по tsvector) и сразу находит те несколько сообщений, что подходят, вместо
    того чтобы спрашивать про каждый диалог отдельно. Остальные ветки бьют по
    `clients` — 56 тысяч строк, это десятки миллисекунд даже перебором.

    Замер того же телефона после правки: 318 мс против 27 600 мс. В 87 раз.

    ⚠ ВЫДАЧА ОБЯЗАНА ОСТАТЬСЯ ТОЙ ЖЕ. `A OR B OR C` по строкам одного соединения
    и объединение тех же трёх выборок — это одно и то же множество; соединение с
    `clients` идёт по первичному ключу и кратности не меняет. Совпадение выдачи
    сверено на боевых данных по пяти запросам и закреплено тестом
    `test_search_union_matches_or`.

    ⚠ ЧЕГО ЗДЕСЬ НАМЕРЕННО НЕТ. Поиск по-прежнему ищет ВЕЗДЕ, включая закрытые и
    чужие диалоги (UX-аудит, docs/17 §Т3): сужать его вкладкой нельзя, иначе
    оператор снова скажет клиенту «вы к нам не обращались» при 42 тысячах
    диалогов истории. Правка про скорость, а не про охват.
    """
    q = q.strip()
    like = f"%{q}%"

    def по_клиенту(условие: sa.ColumnElement[bool]) -> Select[Any]:
        return (
            select(Conversation.id).join(Client, Client.id == Conversation.client_id).where(условие)
        )

    # ⚠ `lower(name) LIKE lower(:q)`, А НЕ `name ILIKE :q` — РАДИ ИНДЕКСА, И ЭТО
    # НЕ ВКУСОВЩИНА (замер боя 06.09). Обе ветки по `clients` шли Seq Scan по
    # 62 264 строкам на каждое нажатие клавиши: count 43,7–102 мс + страница
    # 33–77 мс, 9,7 % вызовов списка, около 5 000 запросов в день. Миграция
    # 0068 заводит GIN по триграммам на `lower(name)` и на `phone`, но индекс
    # по выражению планировщик берёт только для ТОГО ЖЕ выражения: `ILIKE` —
    # другой оператор над голым `name`, и для него индекс мёртв. Смысл прежний:
    # ILIKE в Postgres и есть «lower с обеих сторон». На SQLite (тесты) `ilike`
    # и так компилировался в эту же форму, так что там не меняется ничего.
    # Совпадение выражения с индексом стережёт `test_search_trgm_0609.py`.
    ветки: list[Select[Any]] = [по_клиенту(sa.func.lower(Client.name).like(sa.func.lower(like)))]

    phone = normalize_phone_query(q)
    if phone:
        ветки.append(по_клиенту(Client.phone.like(f"%{phone}%")))
        # Кандидаты в телефоны — отдельной веткой от своего индекса по клиенту,
        # а не коррелированным EXISTS на каждый диалог.
        ветки.append(
            select(Conversation.id)
            .join(
                ClientPhoneCandidate,
                ClientPhoneCandidate.client_id == Conversation.client_id,
            )
            .where(ClientPhoneCandidate.phone.like(f"%{phone}%"))
        )

    text_match: sa.ColumnElement[bool] | sa.TextClause
    if _dialect(db) == "postgresql":
        text_match = sa.text(
            "messages.search @@ websearch_to_tsquery('russian', :fts_q)"
        ).bindparams(fts_q=q)
    else:
        text_match = Message.body.ilike(like)
    # ⚠ ВЕТКА ПО ТЕКСТУ ИДЁТ ОТ СООБЩЕНИЙ, А НЕ ОТ ДИАЛОГОВ, И В ЭТОМ ВСЯ ПРАВКА.
    # Так GIN-индекс по `search` работает входом: находим подходящие сообщения и
    # берём их диалоги. Прежняя форма спрашивала «а есть ли в ЭТОМ диалоге такое
    # сообщение» — и повторяла вопрос 42 тысячи раз по 28 партициям.
    ветки.append(
        select(Message.conversation_id).where(
            Message.direction.in_(("in", "out")),
            text_match,
        )
    )

    объединение = sa.union(*ветки).subquery()
    return Conversation.id.in_(select(объединение.c[0]))


def _tab_condition(tab: str, viewer: User, *, status_given: bool = False) -> sa.ColumnElement[bool]:
    """Вкладки списка (01 §5.1). «Входящие» здесь НЕТ намеренно.

    Очередь — это не фильтр по строкам этого списка: у неё свой порядок
    («дольше всех ждущий первым»), свой состав элемента (время ожидания, число
    отказов, пометка «никто не берёт») и своя судьба строки — приняли, и она
    исчезла у всех тринадцати. Поэтому `?tab=inbox` уходит целиком в
    `services.inbox.list_inbox` (развилка в `routes/conversations.py`), а не
    заводит здесь ветку, которая отдавала бы те же диалоги в другой форме и в
    другом порядке. Две выборки очереди рано или поздно разъехались бы, и
    разъезд означал бы «принял верхний, а взял не того, кто ждёт дольше всех».
    """
    # `status_given` снимает умолчание «кроме закрытых» у вкладок «Мои» и
    # «Все». Без этого «Мои + статус Закрытые» давало бы пустой список: два
    # условия про один столбец противоречили бы друг другу. Явно выбранный
    # человеком статус обязан побеждать умолчание вкладки — он его как раз и
    # переопределяет, а не дополняет.
    if tab in ("my", "mine"):
        # «Мои» — это мои как ответственного И те, куда меня позвали (docs/19).
        # Без второй половины приглашение бесполезно на второй день: диалог
        # тонет в общем потоке, и позванный про него забывает.
        from app.services.participants import mine_condition

        mine = mine_condition(viewer.id)
        return mine if status_given else sa.and_(mine, Conversation.status != "closed")
    if tab == "new":
        return Conversation.status == "new"
    if tab == "closed":
        return Conversation.status == "closed"
    if tab == "all":
        return sa.true() if status_given else Conversation.status != "closed"
    if tab == "any":
        # «Везде, включая закрытые» — область ПОИСКА (UX-аудит, docs/17 §Т3).
        #
        # Существующие вкладки для поиска не годятся ни одна: `all` исключает
        # закрытые, `mine` — чужие. У менеджера вкладка по умолчанию «Мои»,
        # и он получал честное «ничего не найдено» про клиента, который в
        # системе есть, — при 454 тысячах диалогов истории.
        #
        # Отдельным значением, а не «игнорируем tab, когда задан q»: сочетание
        # вкладки с запросом — законная возможность (поиск внутри закрытых
        # проверяется отдельным тестом), и отнимать её ради умолчания нельзя.
        # Здесь интерфейс просто получает способ сказать то, что он и так
        # обещает, приглушая вкладки на время поиска.
        return sa.true()
    raise ApiError(
        "validation_error",
        "Недопустимое значение tab",
        status=400,
        details={"fields": [{"field": "tab", "rule": "enum", "message": "my|all|new|closed|any"}]},
    )


