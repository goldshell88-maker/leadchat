async def get_conversation(db: AsyncSession, conv_id: uuid.UUID) -> Conversation:
    conv = await db.get(Conversation, conv_id)
    if conv is None:
        raise ApiError("not_found", "Диалог не найден", status=404)
    return conv


async def get_conversation_for_update(db: AsyncSession, conv_id: uuid.UUID) -> Conversation:
    """То же, но со строчным локом (08 §8.4: статус/назначение/отправка).

    Порядок захвата зафиксирован: сначала `conversations`, потом `messages`.
    На SQLite (юнит-тесты) `FOR UPDATE` компилируется в пустоту — это ок,
    конкурентности там нет.
    """
    conv = (
        await db.execute(select(Conversation).where(Conversation.id == conv_id).with_for_update())
    ).scalar_one_or_none()
    if conv is None:
        raise ApiError("not_found", "Диалог не найден", status=404)
    return conv


async def conversation_detail(
    db: AsyncSession,
    conv: Conversation,
    *,
    transferred_to_me: bool = False,
    viewer: User | None = None,
) -> dict[str, Any]:
    """GET /conversations/{id} (01 §5.2): list element + detail-only fields.

    ``viewer`` нужен ради закрепления: оно ЛИЧНОЕ, и без «кто смотрит» деталь
    отдавала бы `pinned: false` всем подряд. Кнопка в шапке при этом
    возвращалась бы в исходное состояние сразу после нажатия — закрепление
    сработало, а выглядит как будто нет.
    """
    related = await _load_related(db, [conv])
    pinned = False
    if viewer is not None:
        pinned = conv.id in await pins.pinned_ids(db, viewer.id)
    out = conversation_out(
        conv,
        account=related["accounts"].get(conv.account_id),
        client=related["clients"].get(conv.client_id),
        assignee=related["users"].get(conv.assignee_id),
        users=related["users"],
        last_message=related["last_messages"].get(conv.id),
        transferred_to_me=transferred_to_me,
        pinned=pinned,
    )
    first_client_at = (
        await db.execute(
            select(sa.func.min(Message.created_at)).where(
                Message.conversation_id == conv.id, Message.direction == "in"
            )
        )
    ).scalar()
    conv_count = (
        await db.execute(
            select(sa.func.count())
            .select_from(Conversation)
            .where(Conversation.client_id == conv.client_id)
        )
    ).scalar_one()
    # Кого позвали в диалог (docs/19). В детали, а не в строке списка: имена
    # нужны при открытии («кто ещё здесь»), а в списке из пятидесяти строк это
    # был бы отдельный запрос на каждую.
    from app.services.participants import view as participants_view

    out.update(
        {
            "bot_vars": conv.bot_vars or {},
            "external_chat_id": conv.external_chat_id,
            "first_client_at": iso(first_client_at),
            "client_conversations_count": conv_count,
            "participants": await participants_view(db, conv.id),
            # Отсюда ушли `snoozed_by` и `snooze_reason` — кто отложил и почему.
            # Показывать их было негде после снятия отложки 12 августа, а поле
            # в ответе, которое никто не читает, — это обещание, что оно живое.
        }
    )
    return out


async def _client_channels(db: AsyncSession, client_id: uuid.UUID) -> list[dict[str, Any]]:
    """Каналы, на которые этот клиент писал, — от самого раннего обращения.

    Порядок именно такой, а не по алфавиту: первым стоит канал, с которого
    человек пришёл, и строка «каналы: Тимофей, Дамир» читается как история, а
    не как список. Текущий диалог сюда входит наравне с прошлыми — иначе у
    клиента с двумя обращениями на одном канале и одним на текущем список
    молча терял бы канал, который открыт прямо сейчас.

    Дата берётся по `conversations`, а не по `messages`: «когда начался диалог
    на этом канале» нужно с точностью до порядка, а не до минуты, и лезть за
    ней в партиционированную таблицу сообщений ради сортировки трёх строк
    незачем.

    `offered_at` пуст у всего, что залито импортом истории (решение владельца
    №3: история в очередь не идёт), поэтому запасной ключ — `last_message_at`.
    Без него импортированный канал выглядел бы «без даты» и уезжал в конец,
    хотя он-то как раз самый ранний.

    ЧЕСТНО ПРО ТОЧНОСТЬ ЭТОГО ПОРЯДКА. Обе даты ПОДВИЖНЫ: `offered_at`
    переставляется вперёд, когда клиент вернулся в закрытый диалог
    (`inbox.enter_queue` в `apply_inbound_event`), а `last_message_at` — на
    каждом сообщении. Значит «первым пришёл» здесь означает «первым по самой
    ранней из подвижных дат», и у клиента, у которого ВСЕ диалоги на канале
    переоткрывались, порядок может разъехаться с настоящим. Настоящую дату
    первого обращения знает только `messages.created_at`, а туда на каждое
    открытие карточки не ходят: `messages` партиционирована, и правило 06 §0.2
    разрешает по ней только точечный проход. Цена ошибки — переставленные
    местами два названия в строке «Писал ещё на каналы»; цена точности —
    проход по всем партициям на каждой карточке. Выбран порядок, а не точность,
    и это записано здесь, чтобы никто не принял его за гарантию.
    """
    rows = (
        await db.execute(
            select(
                AvitoAccount.id,
                AvitoAccount.title,
                sa.func.min(
                    sa.func.coalesce(Conversation.offered_at, Conversation.last_message_at)
                ).label("since"),
            )
            .join(Conversation, Conversation.account_id == AvitoAccount.id)
            .where(Conversation.client_id == client_id)
            .group_by(AvitoAccount.id, AvitoAccount.title)
        )
    ).all()
    # Каналы без единой даты (диалог заведён, сообщений ещё нет) — в конец, а
    # не в начало: `None` значит «не знаем», и подставлять вместо него ноль
    # значило бы объявить такой канал самым ранним. Списки разделены, а не
    # склеены ключом сортировки, чтобы дата и `None` нигде не сравнивались
    # между собой: на SQLite (юнит-тесты) время приходит без зоны, и такое
    # сравнение падало бы только в одном из двух диалектов.
    dated = sorted((r for r in rows if r.since is not None), key=lambda r: r.since)
    undated = [r for r in rows if r.since is None]
    return [{"id": str(r.id), "title": r.title} for r in (*dated, *undated)]


async def client_history(db: AsyncSession, conv: Conversation) -> dict[str, Any]:
    """GET /conversations/{id}/client-history (01 §5.6).

    Прошлые диалоги того же клиента, кроме текущего, `last_message_at DESC`,
    без пагинации — их единицы. `messages_count` считается одним GROUP BY по
    `conversation_id IN (...)`: правило партиций 06 §0.2 соблюдено (точечный
    проход по индексу `(conversation_id, created_at)`), N+1 нет.

    КАНАЛ У КАЖДОГО ОБРАЩЕНИЯ И СВОДКА ПО КАНАЛАМ (требование владельца 6 от
    11 августа). Сервер отдавал `account.title` в каждой строке и до этой
    правки — его просто никто не показывал. Теперь рядом едет `summary`: все
    каналы клиента и мера доверия к тому, что это один человек. Без второго
    первое опасно: «писал ещё и на канал Дамир» звучит как факт, а держится
    оно на одном лишь `author_id` (`app/models/client.py`).
    """
    client = await db.get(Client, conv.client_id)
    rows = list(
        (
            await db.execute(
                select(Conversation)
                .where(Conversation.client_id == conv.client_id, Conversation.id != conv.id)
                .order_by(Conversation.last_message_at.desc().nulls_last(), Conversation.id)
            )
        ).scalars()
    )
    related = await _load_related(db, rows)
    counts: dict[uuid.UUID, int] = {}
    if rows:
        counts = {
            row.conversation_id: row.cnt
            for row in (
                await db.execute(
                    select(
                        Message.conversation_id.label("conversation_id"),
                        sa.func.count().label("cnt"),
                    )
                    .where(
                        Message.conversation_id.in_([c.id for c in rows]),
                        Message.direction.in_(("in", "out")),  # служебные записи не считаем
                    )
                    .group_by(Message.conversation_id)
                )
            )
        }
    items = []
    for row in rows:
        account = related["accounts"].get(row.account_id)
        assignee = related["users"].get(row.assignee_id)
        items.append(
            {
                "id": str(row.id),
                "status": row.status,
                "item": {"title": row.item_title} if row.item_title else None,
                # `id` рядом с названием: интерфейс отличает «тот же канал, что
                # открыт сейчас» от чужого не сравнением названий (они у
                # заказчика человеческие — «Тимофей», «Дамир» — и повторяются),
                # а сравнением идентификаторов.
                "account": {"id": str(account.id), "title": account.title} if account else None,
                "assignee": user_ref(assignee),
                "last_message_at": iso(row.last_message_at),
                "messages_count": counts.get(row.id, 0),
            }
        )
    return {
        "client": (
            {"id": str(client.id), "name": client.name}
            if client
            else {"id": str(conv.client_id), "name": None}
        ),
        "items": items,
        # Числа обращений здесь НЕТ намеренно, хотя в макете оно есть: его уже
        # считает `conversation_detail` (`client_conversations_count`), и второе
        # имя тому же числу — это два поля с одним смыслом и разными значениями
        # в тот день, когда одно из них забудут обновить.
        "summary": {
            "channels": await _client_channels(db, conv.client_id),
            "link_confidence": client.link_confidence if client else None,
            "link_phone_conflict": bool(client and client.link_phone_conflict_at is not None),
            "cross_account_since": iso(client.cross_account_since) if client else None,
        },
    }


