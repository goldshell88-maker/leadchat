def can_answer_clients(role: str) -> bool:
    """Может ли роль отвечать клиенту.

    ВНИМАНИЕ: это НЕ то же, что «кому раздавать диалоги» (7.4). Право отвечать
    даёт роль, а участие в раздаче — отдельный признак `handles_conversations`.
    Для выборок «кому дать диалог» есть :func:`operator_pool_conditions`.
    """
    return role in ASSIGNABLE_ROLES


def operator_pool_conditions(*, include_inactive: bool = False) -> list[sa.ColumnElement[bool]]:
    """Кому система вправе ДАВАТЬ диалоги — одно условие на четыре выборки.

    Их ровно четыре, и раньше каждая держала свою копию: список «кому
    передать» (`/users/assignable`), кандидаты автораздачи, операторы канала и
    эскалация «отказались все». Копии сходились, пока условие было простым
    («активен и роль умеет отвечать»), но 7.4 добавляет третью составляющую —
    и разъехаться им теперь есть на чём. Цена разъезда несимметрична:
    забудешь признак в эскалации — администратора позовут за отдел, который
    диалогов не ведёт; забудешь в автораздаче — ему же диалог и отдадут.

    Три условия:

    1. **Активен.** Отключённый сотрудник не работает вовсе.
    2. **Роль умеет отвечать.** head читает всё и так, но писать клиенту не
       может; observer тем более.
    3. **Участвует в работе с диалогами.** Это и есть 7.4: у заказчика в Jivo
       так настроен отдел «СТАРШИЕ - ЧАТЫ» — администрируют систему, обращения
       не ведут. Признак снимает человека с раздачи, но НЕ отнимает право
       отвечать: администратор, вмешавшийся в конкретный диалог, должен уметь
       написать клиенту.

    `include_inactive` снимает ТОЛЬКО первое условие — для сценария «покажи
    отключённых», где руководитель ищет осиротевшие диалоги уволенного.
    Участие в работе с диалогами при этом остаётся: сотрудник, который их
    никогда не вёл, осиротевших диалогов не оставил.
    """
    conds: list[sa.ColumnElement[bool]] = [
        User.role.in_(ASSIGNABLE_ROLES),
        User.handles_conversations.is_(True),
        # Удалённому диалог не отдаст никто и никогда — ни автораздача, ни
        # список «кому передать». Проверка здесь, в общем условии, а не в
        # каждой из четырёх выборок: пропущенная означала бы диалог, уехавший
        # человеку, которого в системе больше нет.
        User.deleted_at.is_(None),
        # ⚠ СЛУЖЕБНОГО РОБОТА В ПУЛЕ НЕ БЫЛО ВИДНО, А ОН В НЁМ БЫЛ. Найдено
        # разбором трёх списков операторов 15 августа: smoke-пользователь —
        # manager, активен, ведёт диалоги, то есть проходил ВСЕ условия выше.
        # Из списка «кому передать» его убирал фильтр по домену почты в самой
        # ручке — а автораздачу, операторов канала и эскалацию не прикрывало
        # ничто: включи владелец автораздачу, и клиентский диалог мог уехать
        # роботу. Признак читается из колонки (её ставит `seed-smoke`), а не
        # угадывается по строке адреса — довод записан у самой колонки.
        User.is_service.is_(False),
    ]
    if not include_inactive:
        conds.insert(0, User.is_active.is_(True))
    return conds


