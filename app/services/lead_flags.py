"""Галочки заявки: «Отзыв», «Прозвон», «Прозвон перед выездом».

ПРАВИЛА ВЛАДЕЛЬЦА, дословно и без смягчений:

  «Прозвон» — если с клиентом есть договорённость созвониться в промежутке
  времени, чтобы подобрать удобное время встречи. Нажимаем ТОЛЬКО если клиент
  сам попросил либо не знает точного времени, когда сможет принять мастера.
  Если договорённость на точное время есть — **самостоятельно предлагать
  созвониться запрещено**.

  «Прозвон перед выездом» — если договорённость на конкретное время есть, но
  клиента надо предупредить о выезде мастера. Предлагать это клиенту не нужно;
  нажимаем ТОЛЬКО если клиент сам попросил.

⚠ ИЗ ЧЕГО СЛЕДУЕТ ГЛАВНОЕ ОГРАНИЧЕНИЕ ЭТОГО ФАЙЛА: обе галочки ставятся по
словам КЛИЕНТА, а не по нашим. Поэтому разбирается только входящий поток. Наши
собственные фразы («давайте созвонимся») сюда не попадают вовсе — иначе
галочка вставала бы ровно в том случае, который владелец запретил.

⚠ И ВТОРОЕ: это подсказка человеку, а не решение за него. Ошибка здесь стоит
звонка, которого клиент не просил, — а по регламенту это нарушение. Поэтому
найденное показывается перед отправкой заявки и снимается одним нажатием.
"""

from __future__ import annotations

import re

#: Клиент ПРОСИТ созвониться, чтобы договориться о времени.
#:
#: «Перезвоните» здесь ключевое слово, но одного его мало: «перезвоните, когда
#: мастер выедет» — это уже другая галочка. Поэтому просьба о звонке отделяется
#: от привязки к выезду ниже, и при совпадении обеих побеждает вторая.
_ПРОСИТ_ЗВОНОК = re.compile(
    r"(перезвон\w*"
    r"|позвон\w+\s+(?:мне|пожалуйста|потом|позже|вечером|завтра)"
    r"|наберите\s+меня"
    r"|свяжитесь\s+со\s+мной"
    r"|созвон\w*"
    r"|лучше\s+по\s+телефону)",
    re.IGNORECASE,
)

#: Клиент НЕ ЗНАЕТ точного времени — второе основание для «Прозвона».
_НЕ_ЗНАЕТ_ВРЕМЕНИ = re.compile(
    r"(не\s+знаю,?\s+(?:когда|во\s+сколько)"
    r"|пока\s+не\s+знаю"
    r"|не\s+могу\s+сказать,?\s+когда"
    r"|уточню\s+(?:время|позже)"
    r"|как\s+освобожусь"
    r"|по\s+ситуации)",
    re.IGNORECASE,
)

#: Просьба предупредить именно ПЕРЕД ВЫЕЗДОМ мастера.
_ПЕРЕД_ВЫЕЗДОМ = re.compile(
    r"("
    r"(?:предупред\w+|позвон\w+|наберите|сообщите|напиш\w+)"
    r"[^.!?]{0,40}"
    r"(?:перед\s+(?:выезд\w*|приезд\w*)|когда\s+(?:выед\w+|поед\w+|буд\w+\s+выезжать)"
    r"|за\s+\w+\s+(?:до|минут|час\w*))"
    r"|(?:перед\s+(?:выезд\w*|приезд\w*))[^.!?]{0,40}(?:позвон\w+|предупред\w+|наберите)"
    r")",
    re.IGNORECASE,
)


def _any(texts: list[str], pattern: re.Pattern[str]) -> bool:
    return any(pattern.search(t or "") for t in texts)


def detect_calls(incoming: list[str]) -> tuple[bool, bool]:
    """(«Прозвон», «Прозвон перед выездом») по репликам КЛИЕНТА.

    ВЗАИМОИСКЛЮЧАЮЩИЕ, И ЭТО НЕ УПРОЩЕНИЕ. Смысл у них разный: первая означает
    «времени ещё нет, надо подобрать», вторая — «время есть, предупредите
    перед выездом». Поставить обе значит сказать лид-центру одновременно, что
    время назначено и что его нет; разбирать это придётся человеку по телефону,
    у клиента.

    При совпадении обеих побеждает «перед выездом»: она конкретнее, и её
    формулировка («позвоните перед выездом») содержит слово «позвоните», по
    которому срабатывает и первая.
    """
    before_visit = _any(incoming, _ПЕРЕД_ВЫЕЗДОМ)
    if before_visit:
        return False, True
    call = _any(incoming, _ПРОСИТ_ЗВОНОК) or _any(incoming, _НЕ_ЗНАЕТ_ВРЕМЕНИ)
    return call, False


def wants_review(
    partner_number: str | None, allowed: list[str], src_key: str | None = None
) -> bool:
    """Ставить ли «Отзыв» — по номеру партнёра канала.

    Список задаётся настройкой и пополняется («возможно будут добавляться»),
    поэтому он не вшит в код. Сравнение по очищенной строке: партнёра пишут и
    «007», и «7», и с пробелами, а это один и тот же человек.

    ⚠ Единственное вшитое исключение — регламент 15.08, п. 2: у партнёра 7
    «Отзыв» ставится на БТ и МНЧ, но НЕ на КП. Это правило направления, а не
    списка, поэтому настройкой его не выразить.
    """
    number = normalize_partner(partner_number)
    if not number:
        return False
    if number not in {normalize_partner(x) for x in allowed if normalize_partner(x)}:
        return False
    if number == "7" and (src_key or "") == "kp":
        return False
    return True


def normalize_partner(value: str | None) -> str:
    """«007», « 7 », «7» → «7».

    Ведущие нули срезаются намеренно: в списке владельца стоит «007», а на
    карточке канала человек напишет «7» — и это должен быть один партнёр.
    Нечисловые номера остаются как есть, просто очищенными.
    """
    raw = (value or "").strip()
    if not raw:
        return ""
    return raw.lstrip("0") or "0" if raw.isdigit() else raw
