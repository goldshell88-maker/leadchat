"""Принудительный обрыв сессии сотрудника — ОТПРАВИТЕЛЬ сигнала (01 §1.2,
§3.4–3.5, 08 §5.4–5.5).

Потребитель этого сигнала написан давно: `app/ws/hub.py` слушает
`control:revoked` и закрывает сокеты пользователя. Отправителя не было —
и это ровно та дыра, которую поймала приёмка: сотрудника отключили, его окно
продолжало получать ленту переписки (сокет никто не закрывал), а вместе с ней
и переписку клиентов. Модуль закрывает дыру с трёх сторон сразу, потому что
одной мало:

1. **refresh-токены** (`user_refresh:{id}` в Redis) — иначе браузер молча
   выпишет себе новый access через `POST /auth/refresh` и вернётся в систему.
2. **пометка `revoked_users:{id}`** — access-токен живёт 15 минут и подписан
   верно; без пометки он остаётся годным до истечения. Проверку делает
   `get_current_user` в `app/api/deps.py`.
3. **`control:revoked` в Pub/Sub `events`** — открытый сокет аутентифицирован
   тикетом на всю свою жизнь (01 §11.1) и протухание access'а его не рвёт.
   Закрыть его может только явная команда хабу.

Пропусти любой из трёх — и отключение станет косметическим: (1) вернёт вход
через минуту, (2) оставит REST открытым на 15 минут, (3) оставит открытым
поток сообщений навсегда.

**Коды закрытия сокета** (01 §11.7, 08 §5.4): `4403` — «уйти на /login»
(деактивация, сброс пароля), `4401` — «взять новый тикет и переподключиться»
(смена роли: человек продолжает работать, но сессия хаба несёт снимок роли,
сделанный на connect'е, и его надо обновить).
"""

import time
import uuid
from typing import Final, cast

import structlog
from redis.asyncio import Redis

from app.core.config import settings
from app.core.security import revoke_all_user_refresh
from app.ws.events import publish_event

log = structlog.get_logger("app.sessions")

# Ключ денилиста access-токенов. Формат знает этот модуль и `api/deps.py`.
REVOKED_KEY_PREFIX: Final = "revoked_users:"

WS_CLOSE_LOGOUT: Final = 4403  # деактивация/сброс пароля → фронт уходит на /login
WS_CLOSE_RELOGIN: Final = 4401  # смена роли → новый тикет и reconnect


def revoked_key(user_id: uuid.UUID | str) -> str:
    return f"{REVOKED_KEY_PREFIX}{user_id}"


async def revoke_sessions(
    redis: Redis,
    user_id: uuid.UUID | str,
    *,
    reason: str,
    close_code: int = WS_CLOSE_LOGOUT,
    block_access: bool = True,
) -> None:
    """Оборвать все сессии пользователя: refresh, access и открытые сокеты.

    Зовётся ТОЛЬКО после commit'а транзакции, которая изменила пользователя
    (08 §8.1): иначе хаб успеет закрыть сокет по событию, которое потом
    откатится, и сотрудник окажется выкинут без причины.

    ``block_access=False`` — сессии рвём, но действующий access-токен не
    хороним. Нужно смене роли (01 §3.4): роль на бэкенде и так читается из
    строки БД на каждом запросе, а пометка `revoked_users` с TTL 15 минут
    не различает старый токен и новый — сотрудник, честно перезашедший через
    минуту, упирался бы в 401 до конца окна. См. заметку про `api/deps.py`:
    после сверки по `iat` этот флаг можно будет включить и для роли.

    Значение пометки — unix-время отзыва. Сегодняшняя проверка в `deps.py`
    смотрит только на существование ключа; время кладём, чтобы проверку можно
    было ужесточить до «токены, выписанные ДО отзыва» без миграции данных.
    """
    uid = str(user_id)
    await revoke_all_user_refresh(redis, uid)
    if block_access:
        await redis.set(
            revoked_key(uid),
            str(int(time.time() * 1000)),
            ex=settings.jwt_access_ttl_seconds,
        )
    # Хаб живёт в каждом процессе uvicorn и слушает общий канал: публикация —
    # единственный способ дотянуться до сокета, открытого в соседнем процессе.
    await publish_event(redis, "control:revoked", {"user_id": uid, "code": close_code})
    log.info(
        "session.revoked",
        user_id=uid,
        reason=reason,
        close_code=close_code,
        access_blocked=block_access,
    )


async def clear_revocation(redis: Redis, user_id: uuid.UUID | str) -> None:
    """Снять денилист access-токенов (включение сотрудника обратно, 01 §3.5).

    Без этого включённый в ту же минуту сотрудник получал бы 401 до конца
    15-минутного окна — «включили, а войти не могу».
    """
    await redis.delete(revoked_key(user_id))


#: Числа меньше — секунды (пометки прежнего формата), больше — миллисекунды.
_MS_THRESHOLD = 10**11


async def access_revoked_at(redis: Redis, user_id: uuid.UUID | str) -> int | None:
    """Unix-время отзыва access-токенов в миллисекундах или None, если отзыва не было.

    Зовётся из `api/deps.py` на КАЖДОМ запросе: по этому времени решается,
    выписан ли предъявленный токен до отзыва (тогда 401) или после (тогда это
    честный перезаход, и доступ есть).

    ⚠ НЕРАЗБИРАЕМАЯ ПОМЕТКА ЗНАЧИТ «ОТОЗВАНО ТОЛЬКО ЧТО», А НЕ «ДАВНО».
    Здесь возвращался 0 с пояснением «старое значение без метки времени —
    считаем отозвано давно», и это пускало любой токен: 0 меньше любого `iat`.
    Но пометка живёт ровно `jwt_access_ttl_seconds` — пятнадцать минут: раз она
    в Redis есть, отзыв случился в этом окне, а не когда-то. Значение без
    времени — это формат прошлых версий, и единственное, чего мы о нём НЕ
    знаем, — был ли токен выписан после. Пустить по недостающим данным дороже,
    чем попросить перезайти.
    """
    raw = cast(str | None, await redis.get(revoked_key(user_id)))
    if raw is None:
        return None
    try:
        value = int(raw)
    except ValueError:
        return int(time.time() * 1000)
    # Пометки прежнего формата — в секундах. Отзыв случился где-то внутри той
    # секунды; считаем концом её, то есть отказываем при сомнении.
    return value * 1000 + 999 if value < _MS_THRESHOLD else value


def выписан_после(payload: dict[str, object], отозвано_мс: int) -> bool:
    """Выписан ли токен после отзыва сессий. При сомнении — нет.

    Новые токены несут `iat_ms`. У токенов прежнего формата есть только `iat`
    в секундах: выписанный в ту же секунду, что и отзыв, мог быть и до него.
    """
    мс = payload.get("iat_ms")
    if isinstance(мс, int):
        return мс > отозвано_мс
    iat = payload.get("iat")
    return isinstance(iat, int) and iat * 1000 > отозвано_мс
