"""Направление заявки решает ПРОБЛЕМА КЛИЕНТА, потом объявление, потом канал.

⚠ ПОРЯДОК ПЕРЕВЁРНУТ 15.08 РЕШЕНИЕМ ВЛАДЕЛЬЦА: «бот должен определять направление
исходя из проблемы клиента». Прежний довод «клиент выбрал направление сам, когда
написал в объявление» разбился о живые диалоги: пишут про стиральную машину в чат
про компьютеры — в ближайший открытый канал, не выбирая объявление по теме. Слова
переписки оказались честнее названия объявления; объявление осталось вторым
источником (текст без слов техники — «не включается, приезжайте» — направления не
даёт), настройка канала — третьим.

Ниже — историческое обоснование правил слов (актуально: слова те же).


ЗАЧЕМ. Лид-центров три — `bt` (бытовая техника), `kp` (компьютерная помощь),
`mnc` («муж на час»), — и до 14 августа направление было свойством КАНАЛА:
`avito_accounts.lead_src_key`, один выбор на аккаунт. Владелец назвал это ошибкой
дословно: «у аккаунта нет конкретно направления, сам бот должен решать, на какое
направление создавать заявку».

Он прав по устройству. В один канал Авито пишут и про телевизор, и про принтер:
объявлений у аккаунта много, направлений в них — разные. Замер на бою 14 августа: 50
диалогов, 49 с известным объявлением, и среди них обе группы сразу.

ПОЧЕМУ ЭТО ВЫВОД, А НЕ ДОГАДКА. Клиент выбрал направление САМ, когда написал в
конкретное объявление. Мы не угадываем по словам переписки («не включается» одинаково
подходит телевизору и компьютеру) — мы читаем то, что он уже выбрал.

ЧТО ЗДЕСЬ НЕ РЕШАЕТСЯ. Если объявление неизвестно (1 диалог из 50) или его слова ни на
что не похожи — направление НЕ выдумывается. Возвращается ``None``, и заявка берёт
настройку канала как запасной вариант; нет и её — заявка придерживается, как и раньше.
Ошибка направления уводит заявку в чужой лид-центр, то есть к мастеру, который не
приедет; молчание дешевле.

СЛОВА ВЗЯТЫ ИЗ БОЕВЫХ НАЗВАНИЙ, А НЕ ПРИДУМАНЫ. Все шесть объявлений заказчика на
14 августа:

    Ремонт телевизоров и настройка каналов с выездом / Замена подсветки / …   19
    Настройка телевизора / Каналы, SMART TV, Wi-Fi и приложения                9
    Ремонт принтеров и мфу / Полная настройка / Подключение к устройству / …   7
    Ремонт телевизоров с выездом на дом / Диагностика / Гарантия               7
    Ремонт принтеров и мфу / Не печатает, зажёвывает бумагу                    6
    Установка Windows и ос / Драйверы, программы и настройка                   1

Отнесение подтверждено владельцем 14 августа: принтеры и МФУ — компьютерная помощь
вместе с Windows; «настройка телевизора» может идти в любое направление, поэтому
ведётся вместе с телевизорами и отдельного правила не требует.
"""

from __future__ import annotations

#: Направления, они же коды лид-центров (`avito_accounts.lead_src_key`).
#: Значения — те же, что понимает расширение: по ним оно выбирает домен.
BT = "bt"
KP = "kp"
MNC = "mnc"

#: Слова объявления → направление. Порядок ВАЖЕН: первое совпадение выигрывает,
#: поэтому более узкие слова стоят выше более широких.
#:
#: Сравнение по вхождению подстроки в нижнем регистре, без морфологии: названия
#: пишет сам заказчик, и склонения в них предсказуемы («телевизор», «телевизоров»).
#: Корни выбраны так, чтобы покрыть падежи, не цепляя чужого.
ПРАВИЛА: tuple[tuple[tuple[str, ...], str], ...] = (
    # Компьютерная помощь — ставится ПЕРВОЙ намеренно: «принтер … настройка» иначе
    # поймалось бы правилом телевизора по слову «настройка», если оно там появится.
    (("принтер", "мфу", "windows", "виндовс", "драйвер", "компьютер", "ноутбук", "пк "), KP),
    (
        (
            # Телевизоры — 26 диалогов из 49 на бою, самая большая группа.
            "телевизор",
            " тв",
            "тв ",
            "smart tv",
            "приставк",
            "подсветк",
            "каналов",
            "каналы",
            # ⚠ ОСТАЛЬНАЯ БЫТОВАЯ ТЕХНИКА — ЕЁ НЕ БЫЛО В ПЕРВОЙ РЕДАКЦИИ, И ЭТО
            # НАШЁЛ СТОРОЖ. Правила писались строго по шести объявлениям, которые
            # висели 14 августа, а бизнес заказчика — ремонт бытовой техники
            # целиком. Заготовка тестов («Ремонт холодильников на дому») не
            # определялась вовсе и молча падала на настройку канала: пока канал
            # стоит на БТ, разницы не видно — до первого канала на КП.
            "холодильник",
            "морозильн",
            "стиральн",
            "посудомоеч",
            "микроволнов",
            "мультиварк",
            "плит",
            "духов",
            "варочн",
            "вытяжк",
            "кондиционер",
            "сплит",
            "водонагрев",
            "бойлер",
            "пылесос",
            "кофемашин",
        ),
        BT,
    ),
    (("муж на час", "мелкий ремонт", "сантех", "электрик", "мебел"), MNC),
)


#: Уточнения ТОЛЬКО для текста переписки: в названиях объявлений владельца этих
#: коллизий нет, а в живой речи есть. «Положить плитку» — муж на час, но подстрока
#: «плит» утащила бы её к газовым плитам (БТ); побеждает более длинное совпадение.
ПРАВИЛА_РЕЧИ: tuple[tuple[tuple[str, ...], str], ...] = ПРАВИЛА + (
    (("плитк", "кафел"), MNC),
    # Разговорные имена техники — в названиях объявлений их не бывает, в репликах
    # только они и есть. Подстроки выбраны без ложных вложений: «кран» сюда НЕ
    # вошёл нарочно — он подстрока «экрана», и жалоба на телевизор уезжала бы к
    # сантехнику; «комп» — только с разделителем, иначе ловит «компанию».
    (("стиралк", "посудомойк", "микроволновк", "телек ", "телик", "холодос"), BT),
    (("комп ", "комп,", "комп.", "ноут "), KP),
    (
        (
            "шкаф",
            "гардин",
            "карниз",
            "смесител",
            "унитаз",
            "люстр",
            "розетк",
            "выключател",
            "полку",
            "полки",
            "полочк",
        ),
        MNC,
    ),
)


def detect_from_problem(client_text: str | None) -> str | None:
    """Направление по словам КЛИЕНТА. ``None`` — слов техники нет, и это законно.

    Побеждает самое РАННЕЕ вхождение в тексте: клиент начинает с главной проблемы
    («стиралка не сливает… и комп потом гляньте» — заявка про стиралку). При равной
    позиции побеждает более длинное слово — оно специфичнее («плитк» против «плит»).
    """
    t = (client_text or "").lower()
    if not t.strip():
        return None
    best: tuple[int, int, str] | None = None
    for words, key in ПРАВИЛА_РЕЧИ:
        for w in words:
            i = t.find(w)
            if i >= 0 and (best is None or (i, -len(w)) < (best[0], best[1])):
                best = (i, -len(w), key)
    return best[2] if best else None


def detect(item_title: str | None) -> str | None:
    """Направление по названию объявления. ``None`` — не определяется, и это законно.

    ⚠ ВОЗВРАЩАТЬ УМОЛЧАНИЕ ЗДЕСЬ НЕЛЬЗЯ. Соблазн «если не поняли — пусть будет БТ»
    выглядит безобидно ровно до первого принтера, уехавшего к мастеру по технике.
    Незнание обязано дойти до вызывающего, чтобы тот взял настройку канала или
    придержал заявку — оба ответа честнее выдуманного.
    """
    if not item_title:
        return None
    текст = item_title.lower()
    for слова, направление in ПРАВИЛА:
        if any(слово in текст for слово in слова):
            return направление
    return None
