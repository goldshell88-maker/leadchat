def _validate(spec: Spec, value: Any, *, content: bool = True) -> Any:
    """Тип и границы значения; `content=False` — чтение из таблицы: содержимое
    текстовой настройки (`Spec.check`) не проверяется, строка отдаётся как есть
    (см. докстринг `Spec`)."""
    if spec.kind == "text":
        # Свободная строка. Длину ограничиваем: настройка едет в каждый ответ
        # экрана, и мегабайт сюда попасть не должен даже случайно.
        if value is None:
            return ""
        if not isinstance(value, str):
            raise ApiError(
                "validation_error",
                "Нужна строка",
                status=400,
                details={"fields": [{"field": spec.key, "rule": "type", "message": "str"}]},
            )
        текст = value.strip()
        if len(текст) > spec.max_length:
            if content:
                raise ApiError(
                    "validation_error",
                    f"Слишком длинно: не больше {spec.max_length} символов",
                    status=400,
                    details={
                        "fields": [
                            {
                                "field": spec.key,
                                "rule": "string_too_long",
                                "message": str(spec.max_length),
                            }
                        ]
                    },
                )
            текст = текст[: spec.max_length]
        if content and spec.check is not None:
            try:
                spec.check(текст)
            except ValueError as exc:
                raise ApiError(
                    "validation_error",
                    f"{spec.key}: {exc}",
                    status=400,
                    details={
                        "fields": [{"field": spec.key, "rule": "content", "message": str(exc)}]
                    },
                ) from exc
        return текст

    if spec.kind == "ts":
        # Метка времени в секундах: «до какого момента» (сегодня — срок жизни
        # подробного следа). `None` — «никогда», штатное значение.
        #
        # ОТДЕЛЬНЫЙ ТИП, А НЕ `int_or_null`, И ЭТО НЕ ПЕДАНТИЗМ. Тот тип в этом
        # реестре означает «потолок диалогов на сотрудника» и проверяет 1..100 —
        # то есть отверг бы любую настоящую метку времени с сообщением про
        # диалоги. Ровно так и вышло при первой попытке: понятная настройка
        # отказывалась включаться с текстом не про себя.
        if value is None:
            return None
        if isinstance(value, bool) or not isinstance(value, int):
            raise ApiError(
                "validation_error",
                "Нужно время в секундах или пусто",
                status=400,
                details={"fields": [{"field": spec.key, "rule": "type", "message": "int|null"}]},
            )
        return max(0, value)

    if spec.kind == "hour":
        return _validate_hour(spec, value)

    if spec.kind == "count_or_null":
        # Счётчик с потолком: `None` — «без потолка» (платный тариф), ноль —
        # «не спрашивать вовсе». ОТДЕЛЬНЫЙ ТИП, а не `int_or_null`: тот
        # проверяет 1..100 про диалоги на сотрудника и отверг бы тысячу.
        if value is None:
            return None
        if isinstance(value, bool) or not isinstance(value, int):
            raise ApiError(
                "validation_error",
                "Нужно целое число или пусто",
                status=400,
                details={"fields": [{"field": spec.key, "rule": "type", "message": "int|null"}]},
            )
        if value < 0 or value > 1_000_000:
            raise ApiError(
                "validation_error",
                "Потолок — от 0 до 1 000 000 либо пусто",
                status=400,
                details={"fields": [{"field": spec.key, "rule": "range", "message": "0..1000000"}]},
            )
        return value

    if spec.kind == "bool":
        if not isinstance(value, bool):
            raise ApiError(
                "validation_error",
                "Нужно «да» или «нет»",
                status=400,
                details={"fields": [{"field": spec.key, "rule": "type", "message": "bool"}]},
            )
        return value

    # int_or_null: None — «без ограничения», и это осмысленное значение, а не
    # отсутствие ответа.
    if value is None:
        return None
    if isinstance(value, bool) or not isinstance(value, int):
        raise ApiError(
            "validation_error",
            "Укажите целое число или снимите ограничение",
            status=400,
            details={"fields": [{"field": spec.key, "rule": "type", "message": "int|null"}]},
        )
    if value < 1 or value > MAX_ACTIVE_LIMIT:
        raise ApiError(
            "validation_error",
            f"Одновременных диалогов на сотрудника — от 1 до {MAX_ACTIVE_LIMIT} "
            "либо без ограничения",
            status=400,
            details={"fields": [{"field": spec.key, "rule": "range", "message": "1..100"}]},
        )
    return value


def _validate_hour(spec: Spec, value: Any) -> int:
    """Час суток. Начало окна 0..23, конец 0..24. Проверяет ОДИН конец, не пару.

    ⚠ ПОЧЕМУ У КОНЦА ЕСТЬ 24 (правка владельца 22.08). Пара валидируется как
    «начало < конец», и при потолке 23 у обоих концов максимум, что удавалось
    выставить, — 0:00–23:00, то есть двадцать три часа: последний час суток
    выпадал из расчёта всегда. Круглосуточно не выставлялось вовсе — 0–0 и
    23–0 отвергаются как вырожденное окно, и правильно отвергаются: такое окно
    на боевой системе уже давало ноль рабочих секунд у ВСЕХ менеджеров.
    24 значит «до конца суток»: `day + 24 часа` — это полночь следующего дня и
    в Python, и в SQL (`make_interval` час не обрезает, миграция не нужна).

    НАЧАЛУ 24 НЕ РАЗРЕШЕНО. «С 24:00» не значит ничего, а пара 24–24 снова
    вырожденная — то есть ровно та ловушка, из которой эта правка выводит.

    Соотношение концов здесь и не может проверяться: функция видит одно
    значение и не знает, с чем его сравнивать. Пару проверяет
    :func:`_assert_work_window` — уже после того, как присланное сведено с
    сохранённым. Раньше пару не проверял никто, и вот чем это кончилось:
    см. историю там же.
    """
    if isinstance(value, bool) or not isinstance(value, int):
        raise ApiError(
            "validation_error",
            "Укажите час целым числом",
            status=400,
            details={"fields": [{"field": spec.key, "rule": "type", "message": "int"}]},
        )
    потолок = 24 if spec.key == STATS_WORK_END_HOUR else 23
    if value < 0 or value > потолок:
        raise ApiError(
            "validation_error",
            f"Час — от 0 до {потолок}",
            status=400,
            details={"fields": [{"field": spec.key, "rule": "range", "message": f"0..{потолок}"}]},
        )
    return value


def work_window_is_set(start_hour: Any, end_hour: Any) -> bool:
    """Задано ли окно рабочих часов вообще.

    Одно определение на две стороны: проверку сохранения здесь и запасной
    расчёт метрик (`stats.business_seconds_between`, SQL-функция
    `business_seconds_between`). Разъедься они — появилось бы окно, которое
    сохранить нельзя, но которое метрики считают вырожденным, или наоборот.
    """
    try:
        return int(start_hour) < int(end_hour)
    except (TypeError, ValueError):
        return False


async def _assert_work_window(db: AsyncSession, checked: dict[str, Any]) -> None:
    """Окно рабочих часов должно быть НЕПУСТЫМ. Проверка парная, а не по полю.

    ЧТО БЫЛО. На боевой системе окно сохранено как 0:00–0:00. Интерфейс
    подсвечивал это красным, но сохранить позволял, а сервер не возражал
    вовсе: проверка была только «час от 0 до 23», каждый конец отдельно.
    Дальше вырожденное окно даёт ноль рабочих секунд на любом интервале —
    и медиана «первый ответ в рабочее время» стала нулём у ВСЕХ менеджеров.
    Отчёт, по которому оценивают людей, показывал ноль независимо от их
    работы, и выглядел при этом совершенно обычно.

    ПОЧЕМУ ПРОВЕРКА ПАРНАЯ И ПОЧЕМУ ЭТО НИЧЕГО НЕ ЛОМАЕТ. Прежнее объяснение
    «настройки меняют по одной, запрет не дал бы поменять 10–20 на 8–22»
    было неправдой дважды. Во-первых, сравнивается не «присланное с
    присланным», а ИТОГОВАЯ пара: недосланный конец берётся из сохранённого,
    поэтому 10–20 → (start=8) → 8–20 → (end=22) → 8–22 проходит целиком.
    Во-вторых, экран настроек и так шлёт оба поля разом
    (`frontend/.../WorkHoursBlock.tsx`), так что «по одной» их не менял никто.

    ЗАПРЕЩАЕМ НЕ ТОЛЬКО РАВЕНСТВО. Перевёрнутое окно (конец раньше начала)
    даёт ровно тот же ноль: SQL-функция считает окно внутри КАЛЕНДАРНЫХ
    суток и через полночь не переходит, поэтому «с 20 до 8» — это не ночная
    смена, а те же ноль секунд. Разрешить его значило бы оставить второй вход
    в ту же беду.
    """
    keys = {STATS_WORK_START_HOUR, STATS_WORK_END_HOUR}
    if not keys & set(checked):
        return
    current = await get_all(db)
    start = checked.get(STATS_WORK_START_HOUR, current[STATS_WORK_START_HOUR])
    end = checked.get(STATS_WORK_END_HOUR, current[STATS_WORK_END_HOUR])
    if work_window_is_set(start, end):
        return
    raise ApiError(
        "validation_error",
        f"Конец рабочего дня должен быть позже начала — получилось {int(start)}:00–{int(end)}:00. "
        "В таком окне рабочих часов ноль, и скорость первого ответа обнулится у всех",
        status=400,
        details={
            "fields": [
                {"field": STATS_WORK_END_HOUR, "rule": "range", "message": "end_hour > start_hour"}
            ],
            "start_hour": int(start),
            "end_hour": int(end),
        },
    )


class _Pass:
    """Коробка под снимок настроек одного прохода. ``None`` — ещё не читали."""

    __slots__ = ("values",)

    def __init__(self) -> None:
        self.values: dict[str, Any] | None = None


#: Снимок текущего прохода; ``None`` — прохода нет, читаем как раньше.
_pass: ContextVar[_Pass | None] = ContextVar("app_settings_pass", default=None)


@asynccontextmanager
async def one_pass() -> AsyncIterator[None]:
    """Настройки читаются ОДИН РАЗ на проход, а не каждым слоем по отдельности.

    ЗАЧЕМ. Обработка одного входящего сообщения проходит через четыре
    независимых слоя, и каждый ходил за настройками сам: подробный след
    (`app/core/trace.py`), разбор телефона (`inbound._maybe_extract_phone`),
    автораздача (`distribution.is_enabled`) и строка очереди «Входящие»
    (`conversations._load_related`). Четыре обращения к `app_settings` на
    сообщение, а на боевом идут десятки тысяч сообщений в сутки.

    Слои про друг друга не знают и знать не должны, поэтому сложить их чтения
    в одно можно было двумя способами: протащить словарь настроек через шесть
    подписей в четырёх модулях — ради одного вызывающего, у которого этот
    словарь есть, — или объявить границу прохода в одном месте. Здесь второе.

    ⚠ ЭТО НЕ КЭШ, И РАЗНИЦА ПРИНЦИПИАЛЬНАЯ. Снимок живёт ровно столько, сколько
    обработка ОДНОЙ записи стрима, — миллисекунды. Следующее сообщение читает
    настройки заново. Оба обещания на этом пути остаются буквальными:
    «выключил раздачу — она выключилась немедленно» (`distribution.is_enabled`
    прямо отказывается от кэша на пять секунд именно поэтому) и «включил след —
    он подхватился сразу по человеческим меркам» (`trace.CACHE_TTL_SECONDS`).
    Между сообщениями снимка нет.

    ПОБОЧНО СНИМОК УБИРАЕТ РАСХОЖДЕНИЕ. Четыре чтения — это четыре момента
    времени: автораздача могла увидеть настройку, записанную уже после того,
    как её прочитал разбор телефона. Теперь решения по одному сообщению
    принимаются по одному состоянию настроек.

    Запись настроек снимок сбрасывает (см. :func:`set_many`): вернуть человеку
    то, что он только что сохранил, важнее сэкономленного запроса.
    """
    token = _pass.set(_Pass())
    try:
        yield
    finally:
        _pass.reset(token)


def _forget_pass() -> None:
    """Снимок протух — настройки только что записали."""
    box = _pass.get()
    if box is not None:
        box.values = None


def repair_share_pct(value: Any) -> int:
    """Доля починки Яндекса в процентах — как её читают воркер и обход.

    `None`, мусор и всё вне 0…100 → умолчание (`REPAIR_SHARE_YANDEX_DEFAULT`)
    с предупреждением в журнале: настройка правится редко, а починка молчать
    из-за опечатки в ней не должна. Границу держит читатель, не реестр
    (прецедент `ADDRESS_ASK_DELAY_SEC`).
    """
    if isinstance(value, bool) or not isinstance(value, int) or not 0 <= value <= REPAIR_SHARE_MAX:
        if value is not None:
            log.warning("geocode.repair_share_invalid", value=value)
        return REPAIR_SHARE_YANDEX_DEFAULT
    return int(value)


def judge_agreement_pct(value: Any) -> int | None:
    """Согласие судьи с человеком, процентов, — как его читает лестница.

    `None` — калибровки не было; мусор и всё вне 0…100 → тоже `None` с
    предупреждением: судья без честной калибровки воротами быть не может, а
    умолчания «сколько-то процентов» у согласия нет по смыслу.
    """
    if value is None:
        return None
    if isinstance(value, bool) or not isinstance(value, int) or not 0 <= value <= 100:
        log.warning("address_judge.agreement_invalid", value=value)
        return None
    return int(value)


async def get(db: AsyncSession, key: str) -> Any:
    """Значение настройки; нет строки — значение из окружения."""
    spec = SPECS[key]
    if _pass.get() is not None:
        # Внутри прохода дешевле прочитать таблицу целиком один раз, чем ходить
        # за каждым ключом отдельно: строк в ней меньше десятка, а читателей на
        # одно сообщение — четыре (см. :func:`one_pass`).
        return (await get_all(db))[key]
    row = await db.get(AppSetting, key)
    if row is None:
        return spec.default
    try:
        return _validate(spec, row.value, content=False)
    except ApiError as exc:
        # В таблице лежит мусор (правили руками, откатили формат). Падать на
        # каждом входящем сообщении из-за этого нельзя: возвращаемся к
        # значению из окружения — оно заведомо корректно. Но не молча: до
        # 20.09 подмена не оставляла ни строки в журнале, и настройка «жила»
        # неделями не тем значением, что на экране.
        log.warning("app_settings.stored_invalid", key=key, error=str(exc))
        return spec.default


def parse_exempt_ids(raw: str | None) -> set[uuid.UUID]:
    """Строка настройки → множество идентификаторов.

    ⚠ РАЗБОР ОДИН НА ВСЕХ, И ЭТО НЕ ОПРЯТНОСТЬ. Читают список двое: сторож
    освобождения (решает, кого не трогать) и экран настроек (показывает, кто
    в списке). Разойдись они хоть в одном пробеле — на экране будет один
    состав, а в работе другой, и заметит это только человек, у которого диалог
    уехал вопреки исключению.

    Мусор молча пропускаем: идентификатор, который перестал быть
    идентификатором (сотрудника удалили, строку правили руками), не повод
    уронить сторожа и оставить смену без освобождения вовсе.
    """
    из: set[uuid.UUID] = set()
    for кусок in (raw or "").replace(";", ",").split(","):
        кусок = кусок.strip()
        if not кусок:
            continue
        try:
            из.add(uuid.UUID(кусок))
        except ValueError:
            continue
    return из


async def get_all(db: AsyncSession) -> dict[str, Any]:
    """Все объявленные настройки разом — для экрана и для ответа API.

    Внутри прохода (:func:`one_pass`) таблица читается один раз на всех, но
    отдаётся КОПИЯ: снимок общий, и правка словаря одним читателем меняла бы
    настройки у всех следующих в том же проходе.
    """
    box = _pass.get()
    if box is None:
        return await _read_all(db)
    if box.values is None:
        box.values = await _read_all(db)
    return dict(box.values)


async def _read_all(db: AsyncSession) -> dict[str, Any]:
    """Настройки из таблицы, без оглядки на снимок прохода."""
    rows = (await db.execute(sa.select(AppSetting))).scalars().all()
    stored = {r.key: r.value for r in rows}
    out: dict[str, Any] = {}
    for key, spec in SPECS.items():
        if key not in stored:
            out[key] = spec.default
            continue
        try:
            out[key] = _validate(spec, stored[key], content=False)
        except ApiError as exc:
            log.warning("app_settings.stored_invalid", key=key, error=str(exc))
            out[key] = spec.default
    return out


async def set_many(
    db: AsyncSession, values: dict[str, Any], *, user_id: uuid.UUID | None
) -> dict[str, Any]:
    """Записать настройки. Проверка — до записи, вся пачка целиком.

    Целиком намеренно: половина применённых изменений хуже отказа. Человек,
    включивший раздачу и получивший отказ на потолке, будет уверен, что не
    сработало НИЧЕГО, — а раздача уже пошла.
    """
    # Проверка сверяется с СОХРАНЁННЫМ (`_assert_work_window` читает пару
    # целиком), а ответ обязан показать записанное. Снимок прохода здесь —
    # ровно тот случай, когда человек нажимает «сохранить» и видит старое.
    _forget_pass()
    unknown = set(values) - set(SPECS)
    if unknown:
        raise ApiError(
            "validation_error",
            f"Неизвестная настройка: {', '.join(sorted(unknown))}",
            status=400,
            details={"unknown": sorted(unknown)},
        )
    checked = {key: _validate(SPECS[key], value) for key, value in values.items()}
    # Парные проверки — после поштучных и тоже ДО записи: половина применённых
    # изменений хуже отказа (см. докстринг).
    await _assert_work_window(db, checked)

    for key, value in checked.items():
        row = await db.get(AppSetting, key)
        if row is None:
            db.add(AppSetting(key=key, value=value, updated_by_id=user_id))
        else:
            row.value = value
            row.updated_by_id = user_id
    await db.flush()
    _forget_pass()
    return await get_all(db)
