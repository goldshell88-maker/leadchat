"""Единственный словарь статусов диалога на сервере (docs/38 §0–§3).

ПОЧЕМУ ЭТОТ ФАЙЛ ВООБЩЕ ЕСТЬ. К одиннадцатому августа состав словаря был
записан в продукте девять раз: кортеж в `services.conversations`, три словаря
подписей (`conversations`, `audit`, `conversation_table`), «открытые» в
`distribution`, три константы в `inbox`, `Literal` и регулярка в ручках — и
ни одна из копий не была выведена из остальных. Расползание стоило продукту
трёх подтверждённых дефектов: «Все» вместо «Все, кроме закрытых», латиница
`in_progress` в отчёте владельца и три разных смысла слова «ждёт».

ПРАВИЛО СОПРОВОЖДЕНИЯ. Новое значение статуса — правка ДВУХ файлов
(этого и `frontend/src/shared/lib/conversationStatus.ts`) и двух тестов.
Пришлось тронуть третий — значит где-то осталась копия, и её надо убрать, а
не дополнить. Разъезд серверного `STATUSES` с фронтовым `STATUS_ORDER`
охраняет `tests/unit/test_conversation_status.py`.

ЗАЧЕМ ОТДЕЛЬНЫЙ МОДУЛЬ, А НЕ ВЕРХ `services/conversations.py`. Этот словарь
нужен `inbox`, `distribution`, `stats`, `audit`, `conversation_table`, `transfer`,
ручкам, ботам и планировщику. `services.conversations` тянет за собой половину
сервисного слоя и сам импортируется теми же местами — верхнеуровневый импорт
словаря оттуда дал бы круг (`inbox` уже обходит его локальными импортами).
Здесь зависимость ровно одна — модель, а модели сервисов не знают никогда.

ЗДЕСЬ ЖЕ ЖИВЁТ ЗАПИСЬ СТАТУСА (:func:`set_status`). Она обязана быть рядом со
словарём и в модуле, доступном всем тринадцати точкам смены: разложи её по
сервисам — и `status_since` начнёт проставляться в двенадцати местах из
тринадцати, а тринадцатое найдётся через месяц по строке контекста, которая
показывает не то время.

И ЗДЕСЬ ЖЕ — ЕДИНСТВЕННЫЙ РАСЧЁТ ОЖИДАНИЯ (:func:`waiting_since`). По тому же
доводу и по свежему счёту: 12 августа на одном экране «сколько клиент ждёт»
было показано ПЯТЬЮ способами и тремя разными числами сразу — «ждёт 2 ч» в
шапке, «7ч» шкалой в списке, «в очереди 7 ч 11 мин» в карточке, «Диалог ждёт в
очереди» внизу и «Ждал 6 ч 41 мин» в системной записи. Два часа и семь часов
про один диалог — это уже не дубль, а подорванное доверие ко всем числам
продукта разом. Модуль подходит месту расчёта ровно потому же, почему подошёл
записи статуса: его импортируют все — `inbox`, `stats`, `conversation_table`,
сторож ожидания, — а он не импортирует никого, кроме модели.
"""

from datetime import UTC, datetime
from typing import Final

from app.models import Conversation

#: Все значения `conversations.status`. Порядок — жизненный путь диалога, он же
#: порядок пунктов во всех фильтрах; алфавит здесь был бы случайным.
#:
#: Это ЖЕ значение перечислено в `CheckConstraint` модели `Conversation`
#: (app/models/conversation.py) — вручную, литералами: SQLAlchemy требует в
#: ограничении текст SQL, и подставлять его из этого кортежа значило бы
#: получить миграцию, содержимое которой зависит от версии кода. Расхождение
#: ловит тест `test_check_constraint_lists_the_same_statuses`.
#:
#: ЗНАЧЕНИЙ ЧЕТЫРЕ, А НЕ ПЯТЬ: `snoozed` снят 12 августа решением владельца
#: («„Отложить диалог“ и „Чем закончилось обращение?“ — эти функции не нужны»).
#: Колонки отложки (`snoozed_until`, `snoozed_by_id`, `snooze_reason`) в базе
#: ОСТАЛИСЬ вместе с накопленными значениями — снос колонок необратим, а
#: решение владельца может измениться; вернуть функцию должно быть можно
#: правкой кода, а не восстановлением из копии. Поэтому здесь нет и следа
#: отложки, а в базе она есть и молчит.
STATUSES: Final[tuple[str, ...]] = (
    "new",
    "in_progress",
    "waiting_client",
    "closed",
)

#: Диалог ещё не завершён. Ровно дополнение к `closed` — и считается из него,
#: а не выписывается вторым списком: пропущенное значение здесь означало бы
#: диалог, который никто не видит во вкладке «Все».
OPEN_STATUSES: Final[tuple[str, ...]] = tuple(s for s in STATUSES if s != "closed")

#: Диалог требует внимания оператора ПРЯМО СЕЙЧАС.
#:
#: Это НЕ то же самое, что «не закрыт», и разница здесь стоит денег. По этому
#: кортежу считается нагрузка автораздачи (`services/distribution.py`):
#: «Ждёт клиента» — не нагрузка, ход не за нами, и человек с двадцатью такими
#: диалогами обязан считаться свободным.
ACTIVE_STATUSES: Final[tuple[str, ...]] = ("new", "in_progress")

#: Диалог кто-то ВЕДЁТ прямо сейчас — то есть взят.
#:
#: Третье множество, и оно не совпадает ни с одним из двух выше. `new` сюда не
#: входит: его никто не взял. По нему считаются «Мои активные» в виджете
#: оператора и карточка «Ждут ответа» в статистике: обе величины про работу,
#: которая идёт, а не про очередь.
#:
#: ЭТО ВАЖНО НЕ ПЕРЕПУТАТЬ С `OPEN_STATUSES`. Карточка «Ждут ответа» считает
#: `awaiting_since` ИМЕННО по этому множеству; возьми она все открытые — в неё
#: попали бы диалоги очереди, и вернулся бы дефект STATS-01, из-за которого
#: руководитель принимал неразобранную очередь за невыполненную работу.
WORKED_STATUSES: Final[tuple[str, ...]] = ("in_progress", "waiting_client")

#: Статусы, при которых на экране показывается счётчик «клиент ждёт N мин».
#:
#: `closed` ожидание ГАСИТ (см. `clear_awaiting` в change_status). Без этого
#: списка закрытый диалог с непрочитанным продолжал показывать «ждёт 3 ч» и в
#: шапке ленты, и шкалой в строке списка — дефект №3 аудита (docs/33 §3).
#: Фронтовая половина правила лежит в `conversationStatus.ts`
#: (`STATUS_SHOWS_WAIT`) и сверяется тем же тестом.
STATUS_SHOWS_WAIT: Final[frozenset[str]] = frozenset({"new", "in_progress", "waiting_client"})

#: Подписи в единственном числе — для системных записей в ленте, журнала
#: аудита, выгрузок и поля «Статус» в карточке.
LABELS: Final[dict[str, str]] = {
    "new": "Новый",
    "in_progress": "В работе",
    "waiting_client": "Ждёт клиента",
    "closed": "Закрыт",
}

#: Подписи срезом (множественное число) — для фильтров и вкладок: там пункт
#: означает не один диалог, а их множество. «Статус: Новые» и «Статус: Новый»
#: читаются по-разному, и до этой правки в списке чатов стояло первое, а в
#: разборе диалогов — второе.
LABELS_PLURAL: Final[dict[str, str]] = {
    "new": "Новые",
    "in_progress": "В работе",
    "waiting_client": "Ждут клиента",
    "closed": "Закрытые",
}

#: Что во что можно перевести РУКАМИ (`PATCH /conversations/{id}/status`).
#:
#: Объектом, а не двумя `if`-ами подряд, как было до docs/38: пока правило
#: жило в коде функции, добавление значения требовало прочитать её целиком и
#: догадаться, какие сочетания она молча разрешает. Сейчас разрешённое видно
#: списком, а запреты объяснены в `TRANSITION_DENIALS`.
#:
#: АВТОМАТИКА ЭТУ МАТРИЦУ НЕ СПРАШИВАЕТ. Клиент, написавший в закрытый диалог,
#: переоткрывает его независимо от того, что разрешено человеку: система
#: реагирует на факт, а не на решение. Матрица охраняет ручной путь — тот, где
#: ошибку делает человек и где ему надо объяснить причину отказа.
TRANSITIONS: Final[dict[str, frozenset[str]]] = {
    "new": frozenset({"in_progress", "closed"}),
    "in_progress": frozenset({"new", "waiting_client", "closed"}),
    "waiting_client": frozenset({"in_progress", "closed"}),
    # `new` отсюда убран намеренно: закрытый диалог в «Новые» возвращает
    # только воркер входящих, когда клиент написал сам (01 §5.4).
    "closed": frozenset({"in_progress"}),
}

#: Почему нельзя — по паре (откуда, куда). Машинный `reason` + текст человеку.
#:
#: «Нельзя» без объяснения оператор читает как поломку и идёт к администратору;
#: администратор идёт в код. Каждый запрет здесь стоит одной строки и экономит
#: этот путь.
TRANSITION_DENIALS: Final[dict[tuple[str, str], tuple[str, str]]] = {
    ("closed", "new"): (
        "manual_reopen_forbidden",
        "Закрытый диалог возвращается только в работу — или сам, когда клиент напишет",
    ),
    ("closed", "waiting_client"): (
        "reopen_to_progress_only",
        "Закрытый диалог сначала возвращают в работу — и уже потом решают, чего ждать",
    ),
    ("new", "waiting_client"): (
        "no_reply_yet",
        "Клиенту ещё никто не ответил — ждать ему нечего",
    ),
}

#: Универсальный отказ для сочетаний, которых нет ни в матрице, ни в списке
#: причин. Такое возможно только у пары «новый → новый вид», добавленный без
#: правки `TRANSITIONS`, — то есть у ошибки сопровождения.
DEFAULT_DENIAL: Final[tuple[str, str]] = (
    "transition_forbidden",
    "Такой переход статуса не предусмотрен",
)


def label(status: str) -> str:
    """Подпись в единственном числе; незнакомое значение отдаём как есть.

    Фолбэк не украшение: в базе до миграции 0026 не было ограничения вовсе, и
    строка с чужим значением обязана печататься собой, а не пустотой. Потерять
    строку отчёта хуже, чем показать в ней машинный код.
    """
    return LABELS.get(status, status)


def can_transition(previous: str, new_status: str) -> bool:
    """Разрешён ли РУЧНОЙ перевод. Тавтологию (`X → X`) не рассматривает —
    у неё свой ответ (`same_status`) и своя причина: это не запрет, а «вы уже
    там»."""
    return new_status in TRANSITIONS.get(previous, frozenset())


def denial(previous: str, new_status: str) -> tuple[str, str]:
    """`(reason, текст)` для 422. Вызывается только когда переход запрещён."""
    return TRANSITION_DENIALS.get((previous, new_status), DEFAULT_DENIAL)


# ------------------------------------------------------------------ запись статуса


def set_status(conv: Conversation, new_status: str, *, now: datetime | None = None) -> None:
    """ЕДИНСТВЕННОЕ место, где меняется `conversations.status`.

    Присваивание `conv.status = ...` где-либо ещё после docs/38 — ошибка ревью
    и ловится грепом: оно оставит `status_since` со временем ПРОШЛОГО статуса,
    и строка «В работе у Иванова · 12 мин» покажет двенадцать минут с момента,
    когда диалог был новым. Такую ошибку не видно ничем, кроме сверки с
    журналом, — а именно этого рода правдоподобных чисел в продукте за два дня
    аудита нашлось шесть штук.

    Повторный вызов с тем же значением отметку НЕ двигает. Это не экономия, а
    смысл поля: «когда вошёл в статус», а не «когда последний раз про него
    вспомнили». Иначе безобидный `ensure_in_progress` на каждом сообщении
    оператора обнулял бы длительность работы над диалогом.
    """
    if conv.status == new_status:
        return
    conv.status = new_status
    conv.status_since = now or datetime.now(UTC)


