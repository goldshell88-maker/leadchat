    # с точкой и ДВУЗНАЧНЫМ месяцем за ним — дата визита, не дом; невод B такое
    # режет (`_НЕ_ДРОБЬ_ЗА_ДОМОМ`), голова с типом улицы — нет, и «17» шло в
    # карточку. Одна цифра за точкой — часть адреса, а не месяц: «Шевченко 3.2
