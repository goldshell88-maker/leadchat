#: Единицы измерения и прочее, после чего число домом не бывает. Стоит
#: опережающей проверкой сразу за числом.
#:
#: ⚠ ВОЗРАСТ И ДИАГОНАЛЬ (замер лид-бота 25.08): «Самсунг 12 лет», «Тошиба 32
#: диагональ» — это ответ про технику, а не дом. Улицам вроде «50 лет Октября»
#: это не мешает: там числом кончается ДОМ («Октября 167»), а «лет» стоит внутри
#: названия, до него.
#: ⚠ КАЖДАЯ ЕДИНИЦА — ЦЕЛЫМ СЛОВОМ. «час» без границы ловил «частный»:
#: «Улица Гоголя дом 15 частный дом» не разбиралось вовсе (стенд 13.09, 976
#: невзятых сообщений с признаками адреса, «частный дом» — самое частое).
_ЕДИНИЦЫ_ПОСЛЕ_ДОМА = (
    r"(?:мм|см|м2|м²|кв\.?\s*м|метр\w*|мет|кг|гр|литр\w*|л|дюйм\w*|"
    # «взял 1т.р. за выезд», «1 тр», «1 т р» (владелец 18.09): тысячи рублей
    # сокращением — деньги, как «тыс» и «руб».
    r"т\.?\s?р\.?|тр\.?|"
    # «Смысл 500 стоит» (владелец 18.09): число перед «стоит/стоило» — цена.
    # Только в смысле цены — когда за словом конец, знак, число или валюта:
    # «ул Ленина 5 стоит шлагбаум», «Победы 10 стоят машины» — «стоит» это
    # «находится», дом на месте (ревью 18.09).
    r"(?:стои[тл]\w*|стоят)(?=\s*(?:$|[.,;!?)]|\d|руб|₽|р(?![а-яё])|ли(?![а-яё])))|"
    r"тыс\w*|тыщ\w*|руб\w*|₽|р|мин|минут\w*|сек|секунд\w*|час|часа|часов|шт|штук|канал\w*|"
    r"градус\w*|процент\w*|сантиметр\w*|дн|дня|дней|числ\w*|го|раз|раза|"
    # ⚠ «МЕСЯЦ» ДОПИСАН ПОСЛЕ РАЗБОРА. В списке были «мин», «час», «лет», «год»
    # — а «Гарантия 12 месяцев» разбиралась как улица «Гарантия», дом 12.
    # Отрицательная проверка на этот случай до правки зеленела из-за строчной
    # буквы («гарантия»), то есть держала регистр, а не правило.
    r"месяц\w*|недел\w*|"
    # «580 км от Читы» — расстояние, не дом (стенд 13.09).
    r"км|лет|год\w*|диагонал\w*|%|"
    # «улица 8 марта», «9 мая» без дома — дата в названии улицы, не дом (ревью 13.09).
    r"января|февраля|марта|апреля|мая|июня|июля|августа|сентября|октября|ноября|декабря"
    r")(?![а-яёa-z0-9])"
)
_НЕ_ДОМ_ЕДИНИЦА = (
    r"(?!\s*" + _ЕДИНИЦЫ_ПОСЛЕ_ДОМА + r")"
    # «не позже 19:30», «пицца Ленинск кузнецкий 14:26» (владелец 18.09):
    # время ЧЧ:ММ домом не бывает — двоеточие с цифрой сразу за числом.
    r"(?!:\d)"
    # «для розеток 3*2.5», «освещение 3х1,5» (владелец 18.09): число перед
    # знаком умножения — сечение кабеля, габарит, а не дом.
    r"(?!\s*[*×xх]\s*\d)"
    # «Ангарск 11 микрорайон дом квартира 92» (владелец 14.09): число перед
    # типом массива — номер микрорайона, а не дом; голова «Ангарск 11» не годится.
    # Но «Ленина 5 мкр Заря», «Гагарина 7 мкр 3» — за типом своё имя или номер,
    # дом на месте (ревью 14.09).
    # `_ПОСЛЕ_ДОМА` компилируется с IGNORECASE — заглавная задана явно (?-i:…),
    # иначе «дом»/«кв» за типом сходили за имя (ревью 14.09). «мкр.» с точкой и
    # «мкр-н» — те же сокращения.
    # «ленина 5 мкр северный» — имя массива и строчными, если это прилагательное.
    r"(?!\s*-?\s*(?:й|я|ый|ой|го)?\s*(?:мкр-н|мкр(?!-н)|мкрн|микрорайон|микр|квартал)(?![а-яё])"
    r"(?![.\s]*(?:(?-i:[А-ЯЁ])|\d|№|"
    r"(?!(?:какой|который|такой|любой|другой|первый|второй|третий|целый|каждый|нужный)(?![а-яё]))"
    r"[а-яё]+(?:ый|ий|ой|ая|яя|ое|ее)(?![а-яё]))))"
)

#: ⚠ ПРАВАЯ ГРАНИЦА `(?![а-яё])` ОБЯЗАТЕЛЬНА, И БЕЗ НЕЁ ТИП ОТКУСЫВАЕТ НАЧАЛО
#: НАЗВАНИЯ. Первая редакция этого модуля границу потеряла при переносе, и
#: `пер\.?` съедал первые три буквы «Первомайской», `ул` — «Ульянова», `ш\.?` —
#: «Шкапиной». В источнике рядом с этой границей записан замер: 186 обрубков на
#: 3355 адресных реплик корпуса, 61 из них — полный адрес с домом, то есть
#: готовая карточка с несуществующей улицей. Разбор боя LeadChat подтвердил тот
#: же порядок: 105 обрубков уровня A за 30 дней.
#:
#: ⚠ ВАРИАНТЫ ТОЧНЫЕ, А НЕ `\w*`. `наб\w*` и `бул\w*` без границы совпадали бы с
#: любым словом на эти буквы; в источнике перечислены обе формы поимённо
#: (`набережн\w*` и `наб\.?`), и это не многословие, а единственный способ
#: отличить сокращение от начала чужого слова.
#:
#: ⚠ ТИПЫ НАСЕЛЁННОГО ПУНКТА ЗДЕСЬ НАМЕРЕННО. Отдельной ветки «пункт без улицы»
#: в этом модуле нет (в источнике она опирается на карту, которой у нас не
#: будет), но «деревня Васильково, д. 58» и «СНТ Рассвет 2» мастеру нужны так же,
#: как городской адрес. Тип уезжает в `тип1`, название остаётся названием — и
#: адрес разбирается, просто без пометки «это не город».
_ТИП = (
    r"(?:улиц\w*|ул\.?|пр-?кт\.?|пр-т\.?|просп\w*|проспект\w*|пр\.?|пер\.?|переул\w*|ш\.?|шоссе|"
    # «микрарайон» — опечатка через «а» (стенд 13.09, Чита).
    r"б-р|бул\.?|бульвар\w*|набережн\w*|наб\.?|микр[оа]?р?айон\w*|мк?р-н|мкр\.?|мик\.?|пос[её]л\w*|пос\.?|"
    # «КП Новое Заречье, 54» (владелец 18.09, Домодедово): коттеджный посёлок
    # — массив, как СНТ/ДНТ; дома в нём нумеруют по посёлку. Только перед
    # именем с заглавной: в переписке о ремонте «КП» — коммерческое
    # предложение, и «Пришлите КП», «Сделайте КП 3 позиции» поднимали уровень
    # до A и будили модель-читателя (ревью 18.09).
    r"деревн\w*|дер\.?|снт|днт|днп|тсн|кп(?=\.?\s+(?-i:[А-ЯЁ]))|проезд\w*|лини[яи]|тракт\w*|квартал\w*|аллея|тупик|туп\.?)"
    r"(?![а-яё])"
)
#: ⚠ ТРИ ЦИФРЫ, А НЕ ЧЕТЫРЕ — И ЭТО ОТЛИЧИЕ ОТ ИСТОЧНИКА С ДОВОДОМ. Там голова
#: применяется к УЖЕ ВЫРЕЗАННОМУ куску адреса, и четвёртая цифра ничем не
#: грозит. Здесь она применяется ко всему сообщению, и «Ванна 1500 на 3 этаже»
#: давало дом 1500: разбор боя нашёл 94 таких за 30 дней. Дом длиннее трёх цифр
#: в наших городах не встречается, а цена и телефон — сплошь.
#: ⚠ ЛИТЕРА ЧЕРЕЗ ПРОБЕЛ И «КОРПУС» СЛОВОМ — ПРАВКА 11.09 ПОСЛЕ РАЗБОРА.
#: «ул Ленина д 2 В», «Ленина 5 а», «12 корпус 2» давали дом «2», «5», «12» —
#: и цитата в карточке тоже обрывалась до пробела, то есть литеру не показывал
#: никто. Для проверки по карте это хуже, чем кажется: карта подтверждала
#: СОСЕДНИЙ дом «12» вместо «12к2», и подтверждение выглядело безупречно.
#:
#: Литера через пробел ловится только когда за ней конец фразы, знак или часть
#: адреса (кв, подъезд, этаж): иначе «Ленина 5 в квартире 3» дало бы дом «5 в».
#: Сразу слово части адреса, у которого нет своего числа: «5 подъезд», «3
#: этаж, кв 7» — число перед ним принадлежит части. Слово — целиком (без
#: отката на «квартир» + «а»), иначе «квартира 5» считалось бы частью без числа.
_ЧАСТЬ_БЕЗ_СВОЕГО_ЧИСЛА = (
    r"\s*(?:по[дж][ъь]?езд|под\.|этаж|кв(?![а-яё])|квартир)[а-яё]*(?![а-яё])(?![.\s]*\d)"
)
#: Хвост дроби, который на деле часть: «дом 64/5 подъезд» — дом 64, подъезд 5
#: (владелец 18.09); «10/2 этаж», «10/12 кв». Подъезд — до 12 (в доме их
#: больше не бывает: «15/36 подъезд» остаётся угловым домом 15/36 без подъезда),
#: этаж и квартира — до двух цифр. Одно определение на голову дома (`_ДОМ` дробь
#: тут не берёт) и на части (`_ЗВЕНО`, `num_slash` берёт число), иначе два пути
#: прочли бы одну реплику по-разному.
_ХВОСТ_ДРОБИ_ЧАСТЬ = (
    r"(?:(?:\d|1[0-2])(?![\d])(?=\s*(?:по[дж][ъь]?езд|под\.)[а-яё]*(?![а-яё])(?![.\s]*\d))"
    r"|\d{1,2}(?![\d])(?=\s*(?:этаж|кв(?![а-яё])|квартир)[а-яё]*(?![а-яё])(?![.\s]*\d)))"
)
_ДОМ = (
    r"(?:(?:стр|ст|строение)\.?\s*(?=\d))?"
    # «72к 2» (стенд 13.09, Тюмень): «к» вплотную к дому, а за ней число —
    # корпус, не литера; литеру «к» тут не берём, корпус ловит хвост ниже.
    # «Камера 4G», «телевизор 4K», «принтер 3D» (владелец 19.09): цифра с
    # ЛАТИНСКОЙ g/k/d вплотную — техника, не литера дома; кириллические «4к»,
    # «4д» остаются домом.
    r"(?![2-8][gkd](?![а-яёa-z\d]))"
    r"\d{1,3}(?:(?![кс]\s*\d(?!\s*(?:по[дж][ъь]?езд|под\.|этаж|кв(?![а-яё])|квартир)[а-яё]*(?![а-яё])(?![.\s]*\d)))"
    # «1т.р.», «1т р» (владелец 18.09): «т» перед «р» — тысячи рублей, не литера.
    r"(?!т\.?\s?р(?![а-яё]))"
    # «18дк4» (стенд 15.09, Дмитров): литера, а сразу за ней корпус.
    r"[а-яa-z](?:(?![а-яё])|(?=[кс]\d)))?"
    # Перед концом фразы или знаком литерой может быть любая буква; перед
    # частью адреса без запятой — только та, что не бывает предлогом: «5 в
    # квартире 3» — это «в квартире», а не дом «5 в».
    # Буква перед «. 2» — сокращение («к. 2» корпус, «п. 2» подъезд), не литера
    # (находка ревью 11.09: «5 к. 2» давало дом «5 к», корпус терялся). Но
    # только буква, которая бывает сокращением: «Дом 118 б. 4 подьез» (стенд
    # 13.09) — литера «б», а «4» — подъезд.
    r"(?:\s(?:(?![кпсдэ]\.?\s*\d)[а-яa-z](?![а-яё\w])(?=\s*(?:$|[,.;)!?]))|"
    r"[абгд-же-йл-нп-тф-я](?![а-яё\w])(?=\s*(?:кв\b|квартир|по[дж][ъь]езд|под\.|этаж|домофон))"
    # «Октябрьская 18 г первый корпус» (владелец 18.09): литера через пробел
    # и сразу корпус с числом («первый корпус» → «корпус 1» в `_нормализовать`).
    # «22 г Орск» — не литера: за буквой имя, а не корпус.
    r"|[абгд-же-йл-нп-тф-я](?![а-яё\w])(?=\s*(?:корпус|корп|кор)\.?\s*\d)))?"
    # «15/ 3й подъезд» (стенд 14.09, Щёлково): за косой чертой — подъезд, а не
    # корпус, если дальше хвост порядка. «дом 64/5 подъезд» (владелец 18.09):
    # слово части без своего числа — число части (`_ХВОСТ_ДРОБИ_ЧАСТЬ`);
    # «64/5 подъезд 3» — у подъезда число своё, дробь цела.
    r"(?:\s*/\s*(?!" + _ХВОСТ_ДРОБИ_ЧАСТЬ + r")\d{1,3}(?![\d])"
    r"(?!\s*-?\s*(?:й|ой|ый|ий)(?![а-яё])))?"
    # Точка перед корпусом — «7.кор4» (бой 12.09, Казань): без неё корпус
    # терялся, и карта не находила «дом 7», которого без корпуса нет.
    # Корпус словом — всегда; голые «к»/«с» — только вплотную к дому («5к 2»,
    # «12с2») или с точкой («5 к.2»): «5 с 9 до 18», «к 15 часам» — время.
    # «5к 2 подъезд» — 2 это подъезд, не корпус (часть без своего числа);
    # «к.2 кв. 7» — корпус 2, у квартиры число своё (ревью 13.09).
    r"(?:\s*\.?\s*(?:(?:корпус|корп|кор|строение|стр)\.?\s*\d{1,3}(?![а-яё\d])"
    r"|(?:(?<=\d)[кс]\.?\s*|(?<=\d[а-я])[кс](?=\d)|\s?[кс]\.\s*|[\s.][кс](?=\d)"
    r"|\sк\s+(?=\d{1,2}(?![\d])(?!\s*(?:час|утра|вечера|дня|мин|:))))"
    r"\d{1,3}(?![а-яё\d])"
    r"(?!\s*(?:по[дж][ъь]?езд|под\.|этаж|кв(?![а-яё])|квартир)[а-яё]*(?![а-яё])(?![.\s]*\d))))?"
)
#: Та же опережающая проверка, но применяемая ПОСЛЕ головы: за домом не должно
#: стоять единицы измерения. Компилируется один раз — внутри невода она живёт
#: строкой-вставкой, а здесь нужна отдельно.
_ПОСЛЕ_ДОМА = re.compile(_НЕ_ДОМ_ЕДИНИЦА, re.IGNORECASE)

#: Уровень A: слово-тип названо прямо.
#:
#: ⚠ СОБИРАЕТСЯ ИЗ `_ТИП`, А НЕ ПЕРЕЧИСЛЯЕТСЯ ЗАНОВО. Первая редакция держала
#: два независимых списка типов — один для ворот, другой для головы, — и они
#: разошлись немедленно: «ш. Шкапина 15» ворота уровнем A не считали (в их
#: списке было «шоссе», но не «ш.»), а голова разбирала. Это ровно класс «два
#: пути считают одно поле по-разному», от которого в этом проекте страдали уже
#: трижды. Определение теперь одно, и разойтись ему не на чем.
#:
#: ⚠ «ЛИНИЯ» — ОСНОВНОЙ ТИП УЛИЦЫ НА ВАСИЛЬЕВСКОМ ОСТРОВЕ, а Петербург у нас
#: боевой город. Но «линия» бывает и не улицей: «телефонная линия не работает»,
#: «горячая линия» — в ремонте техники это частые фразы. Отсекаются они не
#: словарём, а ФОРМОЙ: нумерованная линия («12-я линия») — всегда улица, а
#: именованная берётся только с заглавной и с номером дома следом («Кадетская
#: линия 21»). Словарь запретов в лид-боте пробовали и убрали: диверсия
#: показала, что он мёртвый — без него все запретные формы и так не проходят.
_ТИП_НАЗВАН = re.compile(
    r"\b" + _ТИП + r"|\bдом\.?\s*\d{1,3}\b|"
    r"(?:\d{1,2}\s*-?\s*(?:я|й|ой|ая)?\s*лини(?:я|и|ю|ей)\b|"
    r"(?-i:[А-ЯЁ][а-яё]{2,})\s+лини(?:я|и|ю|ей)\s+\d{1,3})",
    re.IGNORECASE,
)

#: Части адреса, которые сами по себе улицей не являются, но говорят, что речь
#: об адресе: квартира, подъезд, этаж, домофон, частный дом.
#: «подьезд», «подьез», «подезд» — опечатки боя (стенд 14.09: «Заречная 6,1
#: подьезд» без признака шла в невод и гасилась как дробь «6,1»); «пожъезд» —
#: владелец 18.09 (Шахты): подъезд везде пишется `по[дж][ъь]?езд`, одним
#: образцом, чтобы голова, части и признак уровня читали его одинаково.
_ЧАСТИ_АДРЕСА = re.compile(
    r"кв\.?\s?\d+|кварти|по[дж][ъь]?езд?(?![а-яё])|по[дж][ъь]?езд|этаж|домофон|частн\w*\s+дом|"
    r"свой\s+дом|таунхаус|\bснт\b|коттедж|офис\s?\d",
    re.IGNORECASE,
)

#: Широкий невод «Название Число» — уровни B и C.
#:
#: ⚠ ЧЕТЫРЁХЗНАЧНОЕ И ДЛИННЕЕ — НЕ ДОМ. Хвост ``(?!\d)`` обязателен: без него
#: «Наберите 89001112248» и «Ванна 1500» становились адресом — невод откусывал
#: первые три цифры телефона и цены.
#: ⚠ ЛАТИНИЦА СРАЗУ ЗА ЧИСЛОМ — МОДЕЛЬ, А НЕ ДОМ: «Хайсонс 50E7Q». Литера
#: корпуса у нас кириллическая («8а», «26к1»).
#: ⚠ ДРОБНОЕ ЧИСЛО — НЕ ДОМ: «Завтра 13.30», «Высота 2.50», «после 17.00».
#: ⚠ «ПЕТРЕНКО, 20,33» — ДОМ И КВАРТИРА ЧЕРЕЗ ЗАПЯТУЮ (бой 13.09, Тамбов):
#: запятая ПЕРЕД номером говорит, что это перечисление «улица, дом, квартира»,
#: а не дробное число; без неё «20,33» по-прежнему цена.
_КВАРТИРА_ЗАПЯТОЙ = r"(?:,\d{1,4}(?![\d,.]))?"
_ДЕФИС_ЧИСЛО_В_ИМЕНИ = r"(?:-\d{1,2}(?=[\s,]+\d))?"
#: «19,14» после названия — дом и квартира без пробела («Дорожная 19,14»,
#: владелец 15.09), как «19-14»; «1,5 метра», «2,5» с единицей или второй
#: дробью — число, не дом.
_НЕ_ДРОБЬ_ЗА_ДОМОМ = r"(?!\.\d)(?!,\d+[.,]\d)(?!,\d{1,4}\s*" + _ЕДИНИЦЫ_ПОСЛЕ_ДОМА + r")(?!,\d{5})"
_ШИРОКИЙ_НЕВОД = re.compile(
    r"(?-i:([А-ЯЁ](?:[а-яё]{2,}|[А-ЯЁ]{2,})))"
    + _ДЕФИС_ЧИСЛО_В_ИМЕНИ
    + r"(?:\s*,\s*(?:д\.?\s*)?\d{1,3}"
    + _КВАРТИРА_ЗАПЯТОЙ
    + r"|"
    r"[\s,\-]+(?:(?-i:([а-яё]{3,}))\s+)?(?:д\.?\s*)?\d{1,3})"
    r"(?![\dA-Za-z])" + _НЕ_ДОМ_ЕДИНИЦА + _НЕ_ДРОБЬ_ЗА_ДОМОМ
)
#: Тот же невод БЕЗ ЗАГЛАВНОЙ — только в ответ на вопрос оператора об адресе.
#: Корпус 45 дней (12.09): «вилюйская 12», «белорусская 5», «щорса 12» после
#: «куда подъехать?» — люди в чате пишут строчными, и заглавная буква как
#: сторож шума здесь отсекала настоящие адреса. Без контекста строчные не
#: берутся: там заглавная — единственное, что отличает адрес от «диагональ 55».
#: Строчное слово — только с окончанием названия (ая/ская/ова/ина/ой/ий/ых/ей/а/я/и/ы/ь):
#: «сделать 130», «буду 5», «утром 9», «подъеду 3» после вопроса оператора
#: становились улицей уровня B (ревью 14.09); «анисимова», «победы», «юность»
#: проходят.
_ШИРОКИЙ_НЕВОД_ПОСЛЕ_ВОПРОСА = re.compile(
    r"(?-i:([А-ЯЁ](?:[а-яё]{2,}|[А-ЯЁ]{2,})|[а-яё]{2,}"
    # «ь» — у существительных («юность», «сирень»), не у глаголов («сделать»).
    r"(?:ая|яя|ская|ого|ова|ева|ина|ой|ий|ый|ых|ей|ев|ое|ее|а|я|и|ы|о|е|(?<!т)ь|(?<=ст)ь)"
    # «1микр 12дом 34кв» — микрорайон числом.
    r"|\d{1,3}\s?(?:микрорайон|микр|мкрн|мкр|мик|квартал)))"
    + _ДЕФИС_ЧИСЛО_В_ИМЕНИ
    + r"(?:\s*,\s*(?:д\.?\s*)?\d{1,3}"
    + _КВАРТИРА_ЗАПЯТОЙ
    + r"|"
    r"[\s,\-]+(?:(?-i:([а-яё]{3,}))\s+)?(?:д\.?\s*)?\d{1,3})"
    r"(?![\dA-Za-z])" + _НЕ_ДОМ_ЕДИНИЦА + _НЕ_ДРОБЬ_ЗА_ДОМОМ
)

