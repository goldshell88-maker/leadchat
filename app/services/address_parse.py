def _стоп_классы_головы(г: _Голова, *, уровень: str) -> tuple[str, ...]:
    """Все классы, снимающие эту голову на этом уровне, — в порядке договора."""
    return tuple(
        имя for имя, (признак, уровни) in _КЛАССЫ.items() if уровень in уровни and признак(г)
    )


_СЛОВО_ГОЛОВЫ = re.compile(r"[А-ЯЁа-яёA-Za-z][А-ЯЁа-яёA-Za-z-]*")
_ЧИСЛО_НЕВОДА = re.compile(r"(\d{1,3})(?:,\d{1,4})?$")
#: Слово перед головой — через пробелы в той же строке: перенос строки —
#: граница реплики («Купил Танк⏎Ленина 5» — марка к улице не относится).
_СЛОВО_ПЕРЕД_ГОЛОВОЙ = re.compile(r"([А-ЯЁа-яёA-Za-z][А-ЯЁа-яёA-Za-z-]*)[ \t]+$")


def _голова_невода(text: str, m: re.Match[str]) -> _Голова | None:
    """Голова совпадения невода для стоп-классов.

    Слова — с начала ТОКЕНА, а не совпадения: «ЛДжи 126» невод берёт с «Джи»,
    а марка — «ЛДжи». Служебные слова слева срезаются, как в `_годные_головы`
    («Замена выключателя 3» → «выключателя»). Слева достраивается до трёх
    слов тем, что стоит через пробел и не служебное: невод берёт второе слово
    только строчными, а «Откройте Настройки 3», «Хуавей Нова 13» судятся по
    первому. Пусто — судить нечего (`None`, голова считается чистой).
    """
    число = _ЧИСЛО_НЕВОДА.search(m.group(0))
    if число is None:
        return None
    начало_числа = m.start() + число.start(1)
    конец_числа = начало_числа + len(число.group(1))
    начало = m.start() - len(re.search(r"\S*$", text[: m.start()]).group(0))  # type: ignore[union-attr]
    слова = [w for w in _СЛОВО_ГОЛОВЫ.findall(text[начало:начало_числа]) if w.lower() != "д"]
    if not слова:
        return None
    # Голова из одних служебных слов («Обычно 2», «Хочу 10») судится как есть:
    # разбор её и так отбросит, а ворота для модели закрывает только класс.
    без_служебных = list(слова)
    while без_служебных and без_служебных[0].lower() in _НЕ_НАЗВАНИЕ_УЛИЦЫ:
        без_служебных.pop(0)
    слова = без_служебных or слова
    while len(слова) < 3:
        пред = _СЛОВО_ПЕРЕД_ГОЛОВОЙ.search(text[:начало])
        if пред is None:
            break
        w = пред.group(1).lower()
        if (
            w in _НЕ_НАЗВАНИЕ_УЛИЦЫ
            or w in _НЕ_УЛИЦА
            or w in _ТИПЫ_УЛИЦЫ
            or re.fullmatch(_ТИП, w, re.IGNORECASE) is not None
        ):
            break
        слова.insert(0, пред.group(1))
        начало = пред.start(1)
    return _Голова(tuple(слова), число.group(1), text[конец_числа:], text[:начало])


def _стоп_классы_невода(text: str, m: re.Match[str], *, уровень: str) -> tuple[str, ...]:
    г = _голова_невода(text, m)
    return () if г is None else _стоп_классы_головы(г, уровень=уровень)


def _голова_разбора(text: str, m: re.Match[str], слова: list[str]) -> _Голова | None:
    """Голова, выбранная разбором (`_выбрать_голову`), глазами стоп-классов."""
    цифры = re.search(r"\d{1,3}", m.group("bld"))
    if цифры is None:
        return None
    конец = m.start("bld") + цифры.end()
    return _Голова(
        tuple(слова),
        цифры.group(0),
        text[конец:],
        text[: m.start()],
        bool(m.group("тип1") or m.group("тип2")),
    )


_РАНГ_ПОЛИТИКИ = {PARSE_ON: 2, PARSE_SHADOW: 1, PARSE_OFF: 0}


def _класс_под_политикой(классы_голов: list[tuple[str, ...]], rules: Rules) -> str | None:
    """Имя класса, которым реплика судится под политикой, или `None`.

    Голова без единого класса — чистая: снимать нечего, что бы ни сработало
    у соседних («Все 4 розетки, Ленина 5»). Иначе реплику держит самая слабая
    политика по головам (все головы под `on` — снята; хоть одна только под
    `shadow` — тень; хоть одна только под `off` — как сегодня): имя — первый
    класс этого ранга в порядке договора. Так каждый класс включается и
    меряется отдельно: `off` соседа впереди по списку не заслоняет его `on`.
    """
    if not классы_голов or any(not классы for классы in классы_голов):
        return None
    ранг = {имя: _РАНГ_ПОЛИТИКИ.get(rule_state(rules, имя), 0) for имя in СТОП_КЛАССЫ}
    итог = min(max(ранг[имя] for имя in классы) for классы in классы_голов)
    return next(имя for классы in классы_голов for имя in классы if ранг[имя] == итог)


def speech_stop_class(text: str, *, после_вопроса: bool, уровень: str) -> str | None:
    """Стоп-класс речи для текста без оглядки на политику — первый по порядку
    договора, снимающий каждую голову невода; `None` — хоть одна голова чистая
    или голов нет (пути A строчными невод не видит — их судит `parse` по
    своей голове). Чистая функция для стенда и суда, разбор ходит через
    :func:`_gate`."""
    т = _нормализовать(text or "")[0]
    классы = [
        _стоп_классы_невода(т, m, уровень=уровень)
        for m in _головы_невода(т, после_вопроса=после_вопроса)
    ]
    return _класс_под_политикой(классы, dict.fromkeys(СТОП_КЛАССЫ, PARSE_ON))


def stopped_by(text: str, rules: Rules, *, про_адрес: bool = False) -> str | None:
    """Имя стоп-класса в `on`, снявшего строку из `text`, или `None` — для
    журнала `address.stop_class` в `inbound` (один раз на реплику; в `parse`
    не пишется: он зовётся ≥ 5 раз на входящее). Ворота закрыл класс — его
    имя; ворота открыты, но класс снял голову разбора («обычная 2х комнатная
    квартира» строчными на A) — имя из следа тени тех же классов. Без
    единого класса в `on` — сразу `None`, ни одного разбора."""
    включённые = [имя for имя in СТОП_КЛАССЫ if rule_state(rules, имя) == PARSE_ON]
    if not включённые:
        return None
    уровень, имя = _gate(text, про_адрес=про_адрес, rules=rules)
    if уровень is None:
        return имя
    тенью: dict[str, str] = {
        **dict(rules or {}),
        **dict.fromkeys(СТОП_КЛАССЫ, PARSE_OFF),
        **dict.fromkeys(включённые, PARSE_SHADOW),
    }
    тень = parse(text, про_адрес=про_адрес, rules=тенью)
    след = (тень.trace or {}) if тень is not None else {}
    return след.get("stop_shadow")


#: Заявка из анкеты Авито («Вот подробности 👇 … ✨Задача составлена по ответам
#: клиента в анкете»): адрес бывает только в «Комментарий» и «Где находится
#: объект»; остальное — «Когда нужна услуга: вторник 25 августа», «Что
#: сделать: сделать короб на стены 244» — давало дома «вторник, 25», «стены,
#: 244» (стенд 15.09, 30 дней).
_АНКЕТА_АВИТО = re.compile(r"Вот подробности|Задача составлена по\s+ответам клиента")
#: Поле анкеты: «Имя поля:» и значение до следующего поля («Слово…:» в
#: конце строки) или подписи анкеты. Пустые строки внутри значения — его
#: абзацы («Ленина 12\n\nкв 5, домофон 55»); пустое поле не тянет за собой
#: следующее (ревью 15.09).
_ПОЛЕ_АНКЕТЫ = re.compile(
    r"(?im)^(комментарий|где находится объект|где нужна услуга|адрес)[ \t]*:[ \t]*\n?"
    r"(?P<v>.*?)(?=\n[^\n]{3,60}:[ \t]*\n|\n✨?\s*Задача составлена|\Z)",
    re.DOTALL,
)
_ЛЮБОЕ_ПОЛЕ_АНКЕТЫ = re.compile(r"(?m)^[^\n]{3,60}:[ \t]*\n")


def address_text(body: str | None) -> str:
    """Что из сообщения читать разбору адреса: анкета Авито — только её поля с
    адресом, обычная реплика — как есть. Анкета без единого поля «Имя:» —
    не анкета, а речь со словами «Вот подробности» — как есть."""
    т = body or ""
    if not _АНКЕТА_АВИТО.search(т) or _ЛЮБОЕ_ПОЛЕ_АНКЕТЫ.search(т) is None:
        return т
    return "\n".join(m.group("v").strip() for m in _ПОЛЕ_АНКЕТЫ.finditer(т) if m.group("v").strip())


#: «Ленина; 37», «14 мкр; 37» — «;» клиента перед номером дома (с «д.»/«дом» или
#: без): один знак, длина не меняется. Число до трёх цифр — дом, не телефон.
_ТОЧКА_С_ЗАПЯТОЙ_ПЕРЕД_ДОМОМ = re.compile(
    r"(?<=[а-яёa-z\d.])\s?;(?=\s*(?:дом\s*|д\.?\s*)?\d{1,3}(?![\d]))", re.IGNORECASE
)


def parse(
    text: str, *, про_адрес: bool = False, _без_города: bool = False, rules: Rules = None
) -> Found | None:
    """Адрес из текста — или ``None``.

    ``rules`` — политика правил разбора из настройки `address_parse.rules`
    (`rules_from_setting`; вызывающий читает её один раз на входящее и передаёт
    во все разборы реплики). Пусто — умолчания реестра `PARSE_RULES`; пока
    реестр пуст, разбор от неё не зависит. Правило под политикой применяется
    через :func:`under_rule` — там же рождается след тени.

    ⚠ ГОЛОВА ИЩЕТСЯ ТАМ, ГДЕ ДАН УРОВЕНЬ, А НЕ С НАЧАЛА СООБЩЕНИЯ. Первая
    редакция брала ПЕРВОЕ совпадение головы во всём тексте, и на уровне A это
    давало чужой ответ: «Телевизор Самсунг 55, привезите на Ленина 5» — уровень
    дан типом рядом с «Ленина», а голова возвращала «Самсунг 55». Разбор боя
    нашёл 118 таких за 30 дней. Теперь из подходящих голов берётся та, что
    ПЕРЕСЕКАЕТСЯ с признаком уровня; нет пересечения — первая подходящая.

    ⚠ И ЭТО ЖЕ ОБЪЯСНЯЕТ, ПОЧЕМУ ЗДЕСЬ СТРОЖЕ, ЧЕМ В ИСТОЧНИКЕ. В лид-боте
    `_parse_addr` получает УЖЕ ВЫРЕЗАННЫЙ кусок адреса, и голове внутри него
    ошибиться почти нечем. Здесь она применяется ко всему сообщению — значит
    все запреты невода (марки, габариты, единицы измерения) обязаны действовать
    и на пути A, а не только внутри широкого невода.
    """
    # «14а- 76-21» (бой 13.09, Нефтеюганск): реплика целиком из трёх чисел через
    # дефис — микрорайон, дом, квартира (так пишут в городах с нумерованными
    # микрорайонами). Невод такое не ловит; уровень C — покажется, только если
    # карта подтвердит дом.
    тройка = _МКР_ДОМ_КВ.match(text or "")
    if тройка is None and про_адрес:
        # «12 -58-37. Там где устанавливать шведскую стенку…» (владелец 19.09,
        # Нефтеюганск): тройка в начале реплики, дальше точка и речь — после
        # вопроса об адресе это адрес, а не дата.
        тройка = _МКР_ДОМ_КВ_В_НАЧАЛЕ.match(text or "")
    if тройка is not None:
        return Found(
            street=f"{тройка.group('mkr').lower()} мкр",
            house=тройка.group("bld"),
            raw=(text or "")[тройка.start() : тройка.end()].strip(),
            start=тройка.start(),
            end=тройка.end(),
            level=LEVEL_C,
            parts={"office": тройка.group("kv")},
        )
    уровень, стоп_класс = _gate(text, про_адрес=про_адрес, rules=rules)
    if уровень is None:
        return None
    исходный = text or ""
    # ⚠ РАЙОН ГАСИМ ПРОБЕЛАМИ, А НЕ ВЫРЕЗАЕМ. «12-я линия В.О., д. 7» без этого
    # не разбирается: между улицей и домом стоит сокращение, и голова
    # обрывается на нём. Но вырезание СДВИГАЛО БЫ смещения: `start`/`end`
    # указывали бы в другой текст, а `raw` перестал бы находиться в исходном
    # сообщении — то есть сторож цитаты ломался бы ровно на тех петербургских
    # формах, ради которых правило и написано. Замена на пробелы той же длины
    # оставляет все смещения на месте.
    рабочий = _РАЙОН_СПБ.sub(lambda m: " " * len(m.group(0)), исходный)
    # «С. Июньское Воткинский район. Советская 64» (владелец 14.09, Ижевск):
    # район между пунктом и улицей — тем же способом пробелами, а сам район —
    # в строку словами клиента; иначе пункт стоял не вплотную к голове и
    # терялся, а карта предлагала четыре Советских, 64 по области.
    район_словами = _МЕСТО_РАЙОН.search(рабочий)
    if район_словами is not None:
        s0, e0 = район_словами.span()
        рабочий = рабочий[:s0] + " " * (e0 - s0) + рабочий[e0:]
    # Кавычки вокруг названия («Островок», "Ромашка") — тоже пробелами.
    рабочий = re.sub(r"[«»\"„“”]", " ", рабочий)
    # «14 мкр; 37» (владелец 19.09, Нефтеюганск): точка с запятой между именем
    # и номером дома — та же запятая (той же длины, смещения на месте). Ниже
    # «;» служит границей головы — только для скобок, которые мы сами так
    # гасим, поэтому замена идёт до них.
    рабочий = _ТОЧКА_С_ЗАПЯТОЙ_ПЕРЕД_ДОМОМ.sub(",", рабочий)
    # Скобки с уточнением — целиком: «9 проезд (Октябрьский пос. Заречье), дом
    # 47» (стенд 15.09, Тула) — иначе голова уезжала в речь за скобкой.
    # Пробелами — только когда за скобкой явный дом («, дом 47», «, 47, кв 3»,
    # но не «, 4 крепления» — анкета Авито из корпуса Jivo);
    # иначе точкой с запятой — границей и головы, и цепочки частей: «Анна
    # (квартирантка) Южная 3г» без неё давало улицу «Анна Южная», а
    # «в квартире (…) 2.» — квартиру 2 (корпус Jivo, 15.09).
    рабочий = re.sub(
        r"\((?=[^()\d]{0,60}\))[^()]*\)(?=[\s,]*(?:д\.?|дом\.?|№)\s*\d"
        r"|\s*,\s*\d{1,3}\s?[а-яё]?(?:\s*(?:[,.;!?]|$|(?i:кв|квартир|под|этаж))))",
        lambda m: " " * len(m.group(0)),
        рабочий,
    )
    # Скобки со словом части («(второй подъезд)») остаются: части в них
    # читаются словами (ревью 15.09).
    рабочий = re.sub(
        r"\((?=[^()\d]{0,60}\))(?![^()]*(?:по[дж][ъь]?езд|этаж|парадн|домофон))[^()]*\)",
        lambda m: ";" + " " * (len(m.group(0)) - 1),
        рабочий,
    )
    # ТЕЛЕФОН ГАСИМ ТАК ЖЕ (стенд 13.09): «…111 22 41 Липовая аллея, 615» давал
    # улицу «41 Липовая аллея», «открою ворота 900 111 22 45» — дом «900».
    # Разбор номера — свой, его цифры адресу не принадлежат.
    from app.services import phone_parse

    for номер in phone_parse.find_all(рабочий):
        # Крестиками, а не пробелами: «Тургенева 58 т 8950…» (бой 13.09) — «т»
        # перед погашенным номером выглядела литерой дома перед концом фразы.
        рабочий = рабочий[: номер.start] + "X" * (номер.end - номер.start) + рабочий[номер.end :]
    # «Город Щёлково территория комплекса дубково 14 корпус 3» (владелец
    # 14.09): город, названный словом «г./город», — тоже пробелами, иначе имя
    # города прилипало к улице («Щёлково дубково», «Гай ленина»). Сам город —
    # в `locality` ниже. ПОСЛЕ телефона и кавычек (ревью 14.09): «89001234567
    # г. Гай …» — цифра номера перед «г.» выглядела годом «2015 г.».
    город_словом = _город_клиента_где(рабочий)
    if город_словом is not None:
        s0, e0 = город_словом.start(), город_словом.end("city")
        # Разделитель перед «г.» — не часть города: «, г. Гай» → запятая остаётся.
        s0 = s0 + 1 if рабочий[s0] in " ,.(" else s0
        рабочий = рабочий[:s0] + " " * (e0 - s0) + рабочий[e0:]
    # ГОРОД ОБЪЯВЛЕНИЙ БЕЗ «г.» (бой 13.09, Бердск): «Бердск микрорайон 23 кв6»
    # давало улицу «Бердск». Имя из списка городов Авито в начале реплики (или
    # своим пунктом перечисления) гасится и становится городом клиента — но
    # только если без него адрес всё ещё разбирается: «Октябрьский 5» — улица.
    город_объявлений = None if _без_города else _город_объявлений(рабочий)
    if город_объявлений is not None:
        имя_города = город_объявлений.group("city")
        как_есть = parse(text, про_адрес=про_адрес, _без_города=True, rules=rules)
        if как_есть is not None and имя_города in (как_есть.settlement, как_есть.locality):
            # «Нижний Тагил, ул Мира 3»: разбор и так видит в городе пункт.
            return как_есть
        s0, e0 = город_объявлений.span("city")
        без = рабочий[:s0] + " " * (e0 - s0) + рабочий[e0:]
        # «Губкин 2 фабричная 36а» (стенд 15.09): за городом улица числом
        # и строчными — разговор об адресе, без этого давало «Губкин, 2».
        # Только для такой формы: «Тула, чистка 2 кондиционеров» — не адрес
        # (ревью 15.09).
        улица_числом_за_городом = _УЛИЦА_ЧИСЛОМ_СТРОЧНЫМИ.match(без[e0:]) is not None
        found = parse(
            без, про_адрес=про_адрес or улица_числом_за_городом, _без_города=True, rules=rules
        )
        if found is not None:
            found.raw = исходный[found.start : found.end]
            found.locality = found.locality or имя_города
            if found.district is None and район_словами is not None:
                # «Тула, Зареченский район, ул Пушкина 47»: район погашен
                # здесь, внутренний разбор его не видит (ревью 14.09).
                found.district = " ".join(район_словами.group(0).split())
            if found.level == LEVEL_C:
                # Город перед «название число» — уже разговор об адресе.
                found.level = LEVEL_B
            return found
        if (
            как_есть is not None
            and как_есть.level != LEVEL_C
            and как_есть.street.lower().replace("ё", "е") == имя_города.lower().replace("ё", "е")
            and not _ГОРОД_ПРИЛАГАТЕЛЬНОЕ.search(имя_города.lower())
        ):
            # «Ангарск 86-11, кв 5», «Бердск 23 кв 6» (ревью 14.09): без города
            # адреса нет, а с ним город стал бы улицей. Город-прилагательное
            # («Октябрьский 5 кв 3», «Московский 220 кв 15») — проспект без
            # типа, как писали и раньше.
            return None
    рабочий, обратно = _нормализовать(рабочий)
    знак = _ТИП_НАЗВАН.search(рабочий) or _ЧАСТИ_АДРЕСА.search(рабочий)
    m, слова = _выбрать_голову(рабочий, знак)
    if m is None:
        return None
    # Стоп-класс и по ГОЛОВЕ РАЗБОРА, не только по неводу ворот (пакет 7a):
    # на уровне A невод уровень не решал, и «обычная 2х комнатная квартира»
    # строчными, «Хочу 10 … офис 2024» через часть адреса до ворот не
    # доходили. Итог — ниже, через `under_rule`, когда строка собрана.
    голова = _голова_разбора(рабочий, m, слова)
    if голова is not None:
        стоп_класс = _класс_под_политикой(
            [((стоп_класс,) if стоп_класс else ()) + _стоп_классы_головы(голова, уровень=уровень)],
            rules,
        )

    street = " ".join(filter(None, (m.group("тип1"), " ".join(слова), m.group("тип2"))))
    # ПУНКТ ВМЕСТО УЛИЦЫ (бой 13.09, Щёлково): «Поселок Сосново дом 9» — в
    # посёлке улиц нет, дома нумеруют по посёлку; карта ищет дом по пункту.
    пункт_вместо_улицы = _ПУНКТ_КАК_УЛИЦА.match(street)
    # «Ольхово днт Ромашка 5», «Выселки улица Тверская 37» (стенд 13.09):
    # имя с заглавной ПЕРЕД типом — пункт, улица начинается с типа.
    имя_перед_типом = _ИМЯ_ПЕРЕД_ТИПОМ.match(street) if not m.group("тип1") else None
    пункт_из_головы: str | None = None
    тип_из_головы: str | None = None
    начало_пункта: int | None = None
    if имя_перед_типом is not None and _годное_имя_пункта(имя_перед_типом.group("sname")):
        пункт_из_головы = имя_перед_типом.group("sname")
        if имя_перед_типом.group("stype"):
            тип_из_головы = _ПУНКТ_КАНОН.get(имя_перед_типом.group("stype").lower().rstrip("."))
        else:
            # «Хутор Садков улица степная 4» (владелец 18.09): голова
            # начинается с имени, а слово типа стоит перед ней — тип и цитата
            # берутся оттуда, иначе пункт шёл на карту без типа.
            тип_перед = _ТИП_ПУНКТА_ПЕРЕД.search(рабочий[: m.start()])
            if тип_перед is not None and (
                тип_перед.group("stype").lower().rstrip(".") not in ("с", "д", "п")
                or пункт_из_головы[0].isupper()
            ):
                тип_из_головы = _ПУНКТ_КАНОН[тип_перед.group("stype").lower().rstrip(".")]
                начало_пункта = тип_перед.start("stype")
        street = " ".join(filter(None, (имя_перед_типом.group("rest"), m.group("тип2"))))
    тип1 = (m.group("тип1") or "").lower().rstrip(".")
    if тип1 in _ПУНКТ_КАНОН:
        # «Деревня Сорокино улица советская 31» (стенд 13.09): тип пункта, имя
        # пункта, а улица — с её типа; иначе пункт съедал улицу целиком.
        # После полного слова типа («Деревня подлесниково улица кленовая» —
        # владелец 16.09) имя бывает и строчными; после «д»/«с»/«п» — нет.
        # «д» тоже: перед именем и улицей с типом иным словом не бывает;
        # «с»/«п» — предлоги, им нужна заглавная.
        образец = _ИМЯ_СТРОЧНЫМИ_ПЕРЕД_ТИПОМ if len(тип1) >= 3 or тип1 == "д" else _ИМЯ_ПЕРЕД_ТИПОМ
        внутри = образец.match(" ".join(слова))
        if внутри is not None and _годное_имя_пункта(внутри.group("sname")):
            пункт_из_головы, тип_из_головы = внутри.group("sname"), _ПУНКТ_КАНОН[тип1]
            # Тип в конце («Улица калининградское шоссе») — часть улицы.
            street = " ".join(filter(None, (внутри.group("rest"), m.group("тип2"))))
        elif _ПУНКТ_КАНОН[тип1] == "микрорайон" and not m.group("тип2"):
            # «Балашиха микрорайон авиаторов Сидорова 9кв 4» (владелец 18.09):
            # после «микрорайон <Имя>» слово с заглавной перед номером — улица
            # без типа; карта улицу «микрорайон авиаторов Сидорова» не знала.
            хвост = _улица_после_имени_массива(слова)
            if хвост:
                пункт_из_головы, тип_из_головы = " ".join(слова[:-хвост]), "микрорайон"
                street = " ".join(слова[-хвост:])
    # ⚠ ХВОСТ ИЩЕТСЯ В ОСТАТКЕ, А НЕ ВО ВСЁМ ТЕКСТЕ. «Горная 9 подъезд 1»:
    # правило подъезда умеет форму «9 подъезд», и во всём тексте оно откусывало
    # НОМЕР ДОМА, объявляя его подъездом. Разбор боя: 140 случаев за 30 дней.
    # Источник вырезает пролёт головы перед разбором хвоста — делаем так же.
    остаток = рабочий[: m.start()] + " " + рабочий[m.end() :]
    parts = _части(остаток)
    квартира_рядом = m.group("kv") or m.group("kv2")
    if квартира_рядом and "office" not in parts:
        # «Ленина 5-12» и «Петренко 20,33» (бой 13.09, Тамбов): через дефис или
        # запятую сразу после дома пишут квартиру, а не корпус. Явное «кв 12»
        # из остатка своё место занимает: угадыванием не перебиваем.
        parts["office"] = квартира_рядом
    start, end = m.start(), m.end()
    house = m.group("bld").strip()
    корпус_за_частями = _КОРПУС_ЗАПЯТОЙ.match(рабочий[end:]) or _КОРПУС_ЗА_ЧАСТЯМИ.match(
        рабочий[end:]
    )
    if корпус_за_частями is not None and not re.search(r"[кс]\s*\d|корп|стр|/", house.lower()):
        gd = корпус_за_частями.groupdict()
        номер_корпуса = gd.get("n") or gd.get("nk") or gd.get("n2")
        house = f"{house} корпус {номер_корпуса}"
        end += корпус_за_частями.end()
    пункт, тип_пункта, start, end = _пункт_рядом(
        рабочий,
        start,
        end,
        # Голое имя перед запятой берётся пунктом при улице с типом ИЛИ при
        # частях адреса рядом («Кохма , текстильная 16 ,1 кв 1 подьезд»,
        # бой 13.09): квартира и подъезд — та же страховка, что «ул».
        # …и при явном «дом N» («д. Черёмухово д. 2В», стенд 13.09).
        улица_с_типом=m.group("тип1") is not None
        or bool(parts)
        or _ЯВНЫЙ_ДОМ.search(m.group(0)) is not None,
        тип_в_голове=m.group("тип1") is not None and пункт_из_головы is None,
    )
    if пункт_из_головы is not None and пункт is None:
        пункт, тип_пункта = пункт_из_головы, тип_из_головы
        if начало_пункта is not None:
            start = min(start, начало_пункта)
    if пункт is None and not m.group("тип1") and not m.group("тип2") and len(слова) in (1, 2):
        # «д. Черёмухово д. 2В» (стенд 13.09): перед головой — только тип
        # пункта, имя — сама «улица»: дом по пункту без улицы. «Ст. Романовская
        # школьная 128 а» (стенд 15.09): имя — первое слово, улица строчными —
        # второе.
        тип_перед = _ТИП_ПУНКТА_ПЕРЕД.search(рабочий[:start])
        if (
            тип_перед is not None
            and слова[0][0].isupper()
            and _годное_имя_пункта(слова[0])
            and (len(слова) == 1 or _хвост_имени_это_улица(слова) == 1)
        ):
            пункт = слова[0]
            тип_пункта = _ПУНКТ_КАНОН[тип_перед.group("stype").lower().rstrip(".")]
            start = тип_перед.start("stype")
            if len(слова) == 2:
                street = слова[1]
    if пункт_вместо_улицы is not None and пункт is None:
        # Улица остаётся как написана — ключ старых строк («деревня Васильково,
        # 58») не меняется; пункт дописывается рядом, чтобы карта искала дом по
        # нему и в другом городе области (правило «названный пункт важнее»).
        тип = (
            (пункт_вместо_улицы.group("stype") or пункт_вместо_улицы.group("stype2"))
            .lower()
            .rstrip(".")
        )
        имя_пункта_ = (
            пункт_вместо_улицы.group("sname") or пункт_вместо_улицы.group("sname2")
        ).strip()
        # «пгт Отрадное майская 4» (стенд 15.09): хвост имени, похожий на
        # улицу, — улица, а не часть имени пункта. У СНТ/ДНТ/ЖК имена
        # двусловные сплошь и рядом («Солнечная поляна») — их не режем.
        слова_имени = имя_пункта_.split()
        хвост = (
            _хвост_имени_это_улица(слова_имени)
            if _ПУНКТ_КАНОН[тип] in ("посёлок", "село", "деревня", "станица", "хутор", "аул")
            else 0
        )
        if хвост:
            street = " ".join(слова_имени[-хвост:])
            имя_пункта_ = " ".join(слова_имени[:-хвост])
        пункт, тип_пункта = имя_пункта_, _ПУНКТ_КАНОН[тип]
    город = _канон_города(город_словом.group("city")) if город_словом is not None else None
    # «…, район Бугор» после дома (бой 13.09, Елец): уточнение для мастера,
    # в ключ не входит, в карточку дописывается словами клиента.
    район_города = _РАЙОН_ПОСЛЕ.search(остаток)
    район = " ".join(район_города.group("d").split()) if район_города is not None else None
    if район is None and район_словами is not None:
        район = " ".join(район_словами.group(0).split())
    # Смещения — обратно в координаты исходного текста (см. `_нормализовать`).
    start, end = обратно[start], обратно[end - 1] + 1
    street = _винительный_в_именительный(street.strip())
    if город_объявлений is not None and город is None:
        # «Бердск Каштановая 63»: без города улица уровня C и не берётся, а с
        # ним город прилип к названию — отделяем, раз название остаётся.
        имя_города = город_объявлений.group("city")
        if street.lower().startswith(имя_города.lower() + " "):
            street, город = street[len(имя_города) :].strip(), имя_города
    # «Люберцы Д. Петрово Снт Заречное Д. 38» (владелец 18.09): массив под
    # пунктом — улицей остаётся как написан (ключ старых строк «Снт Заречное,
    # 38» не меняется), а в `area` уходит для карты: массив у карты —
    # планировочная структура, а не улица, и по нему же въезд для мастера.
    # «Снт Солнечный 47» без пункта выше — массив и есть пункт, `area` пусто.
    массив_улицей = _МАССИВ_УЛИЦЕЙ.match(street)
    area = (
        " ".join(street.split())
        if массив_улицей is not None and пункт is not None and тип_пункта not in _ТИПЫ_МАССИВА
        else None
    )
    found = Found(
        street=street,
        house=house,
        # `raw` берётся из ИСХОДНОГО текста по тем же смещениям: в него входит и
        # погашенный район, то есть цитата находится в сообщении дословно.
        # С 11.09 в неё входит и населённый пункт, названный рядом.
        raw=исходный[start:end],
        start=start,
        end=end,
        level=уровень,
        parts=parts,
        settlement=пункт,
        settlement_type=тип_пункта,
        locality=город,
        district=район,
        area=area,
    )
    if стоп_класс is None:
        return found
    # Стоп-класс речи под политикой: `on` сюда не доходит (ворота закрыты) —
    # кроме класса по голове разбора; `shadow` — строка со следом
    # `stop_shadow`; `off` — как без класса.
    return under_rule(rules, стоп_класс, old=found, new=None)


#: Улица, которая на самом деле массив: «Снт Заречное», «ДНТ Ромашка», «КП
#: Новое Заречье» — тип массива первым словом.
_МАССИВ_УЛИЦЕЙ = re.compile(r"^(?:снт|днт|днп|тсн|кп|жк)\.?\s+\S", re.IGNORECASE)
#: Канонические типы массива у пункта: пункт с таким типом — сам массив.
_ТИПЫ_МАССИВА = frozenset({"СНТ", "ДНТ", "ДНП", "ТСН", "КП", "ЖК"})
#: «район Бугор», «р-н Засосна» в остатке сообщения — своим пунктом
#: перечисления (в начале или после запятой), иначе «район» из речи.
_РАЙОН_ПОСЛЕ = re.compile(
    r"(?:^|,)\s*(?P<d>(?:район|р-н)\s+"
    r"[А-ЯЁа-яё][а-яё-]{2,}(?:\s+[А-ЯЁа-яё][а-яё-]{2,})?)(?![а-яё])",
    re.IGNORECASE,
)


def _имена_городов() -> frozenset[str]:
    """Имена справочника в нормализации `listing_url._норм_имени` (пакет 5):
    дефис — пробел, ё → е. Сравнивать с ней — только через `_норм_города`."""
    from app.integrations.avito.listing_url import CITIES, _норм_имени

    return frozenset(_норм_имени(c.name) for c in CITIES.values() if " и " not in c.name)


def _норм_города(имя: str) -> str:
    from app.integrations.avito.listing_url import _норм_имени

    return _норм_имени(имя)


def _канон_города(имя: str) -> str:
    """Имя города после «г»/«город» — как в справочнике, когда клиент написал
    его в предложном падеже или без дефиса («г Салавате», «г Горно Алтайск»,
    пакет 5): в `locality` идёт «Салават», карта и сторож другого города
    находят город; `raw`/`value` строки — как написал клиент (ключи старых
    строк не меняются). Не из справочника — как написано."""
    from app.integrations.avito.listing_url import city_by_name

    город = city_by_name(имя, declined=True)
    return город.name if город is not None else имя


_ГОРОД_ВНАЧАЛЕ = re.compile(
    r"(?:^|[,.;!\n])\s*(?P<city>[А-ЯЁ][а-яё]+(?:[ -][А-ЯЁ][а-яё]+)?)(?=[\s,.]|$)"
)
_ГОРОД_ВНАЧАЛЕ_СЛОВО = re.compile(r"(?:^|[,.;!\n])\s*(?P<city>[А-ЯЁ][а-яё]+)(?=[\s,.]|$)")


#: «Московский проспект 5», «Октябрьский мкр 3»: город-прилагательное перед
#: типом улицы или массива, за которым сразу дом, конец или запятая, — это
#: название, не город. «Бердск ул Ленина 5» (за типом имя улицы) и «Мурино
#: бульвар Менделеева» (город не прилагательное) — по-прежнему город (ревью 14.09).
_ТИП_ЗА_ГОРОДОМ_ПРИЛАГАТЕЛЬНЫМ = re.compile(
    r"\s+(?:улица|ул\.?|пр-?кт\.?|проспект|пр\.?|пер\.?|переулок|ш\.?|шоссе|б-р|бульвар|"
    r"набережная|наб\.?|проезд|линия|тракт|аллея|тупик|туп\.?|мкр-н|мкр|мкрн|микрорайон|квартал)"
    r"(?![а-яё])\.?\s*(?:$|[,.;]|\d|д\.?\s*\d|дом(?![а-яё]))",
    re.IGNORECASE,
)
_ГОРОД_ПРИЛАГАТЕЛЬНОЕ = re.compile(r"(?:ский|цкий|ной|ный|ый|ий|ой|ая|яя|ое|ее)$")


def _город_объявлений(text: str) -> re.Match[str] | None:
    """«Бердск, …», «Здравствуйте. Бердск микрорайон 23» — город из списка Авито."""
    имена = _имена_городов()
    # Сначала два слова («Нижний Тагил»), потом одно («Бердск Каштановая»).
    for образец in (_ГОРОД_ВНАЧАЛЕ, _ГОРОД_ВНАЧАЛЕ_СЛОВО):
        for m in образец.finditer(text):
            if _норм_города(m.group("city")) not in имена:
                continue
            # «Московский проспект», «Свердловский проспект» (ревью 14.09):
            # город-прилагательное перед типом улицы — название улицы, не город.
            if _ГОРОД_ПРИЛАГАТЕЛЬНОЕ.search(
                m.group("city").lower()
            ) and _ТИП_ЗА_ГОРОДОМ_ПРИЛАГАТЕЛЬНЫМ.match(text, m.end()):
                continue
            # «Солнечный город 27» (стенд 15.09, Хабаровск — ЖК): прилагательное
            # с «город/парк/бор/квартал» следом — составное имя, не город.
            if _ГОРОД_ПРИЛАГАТЕЛЬНОЕ.search(m.group("city").lower()) and re.match(
                r"\s+(?:город|городок|парк|бор|квартал|берег)(?![а-яё])", text[m.end() :], re.I
            ):
                continue
            return m
    return None


def _город_клиента(text: str) -> str | None:
    """«г Гай», «город Орск» — но не «2015 г. выпуска» и не «в городе нет»."""
    m = _город_клиента_где(text)
    return m.group("city") if m is not None else None


def _город_клиента_где(text: str) -> re.Match[str] | None:
    """Совпадение с группой ``city``; два слова — только у города из списка
    Авито («г. Нижний Новгород»), иначе второе слово — улица («г Гай Ленина 5»)."""
    for m in _ГОРОД_КЛИЕНТА.finditer(text):
        # Число перед «г» проверяется ещё раз с учётом пробела: «2015 г.».
        перед = text[: m.start()].rstrip()
        if перед and перед[-1].isdigit():
            continue
        имя = m.group("city")
        if m.group("city2") and _норм_города(имя) not in _имена_городов():
            m = _ГОРОД_КЛИЕНТА_КОРОТКО.match(text, m.start()) or m
            имя = m.group("city")
        if имя.lower() in _НЕ_НАЗВАНИЕ_УЛИЦЫ or имя.lower() in _НЕ_УЛИЦА:
            continue
        return m
    return None


def _пункт_рядом(
    text: str, start: int, end: int, *, улица_с_типом: bool, тип_в_голове: bool = False
) -> tuple[str | None, str | None, int, int]:
    """Населённый пункт вплотную к голове — перед ней или сразу за ней.

    Возвращает название, канонический тип и РАСШИРЕННЫЕ границы цитаты: пункт
    входит в `raw`, иначе сторож цитаты не смог бы его сверить.

    ⚠ ПЕРЕД ГОЛОВОЙ — ТОЛЬКО ВПЛОТНУЮ. «п Урожай ул Луговая 1» —
    да; «посёлок красивый, а живу на ул Ленина 5» — между ними речь, и это не
    пункт адреса. Голое «п» требует улицы с типом: «п. 2» — это подъезд.
    """
    перед = _ПУНКТ_ПЕРЕД.search(text[:start])
    if перед is not None and _годный_пункт(перед, улица_с_типом=улица_с_типом):
        тип = перед.group("stype").lower().rstrip(".")
        return перед.group("sname").strip(), _ПУНКТ_КАНОН[тип], перед.start("stype"), end
    после = _ПУНКТ_ПОСЛЕ.search(text[end:])
    if после is not None and _годный_пункт(после, улица_с_типом=True):
        тип = после.group("stype").lower().rstrip(".")
        return после.group("sname").strip(), _ПУНКТ_КАНОН[тип], start, end + после.end("sname")
    имя = _ПУНКТ_ИМЯ_ПЕРЕД.search(text[:start]) if улица_с_типом else None
    if имя is not None and _годное_имя_пункта(имя.group("sname")) and _имя_после_в_годится(имя):
        return имя.group("sname").strip(), None, имя.start("sname"), end
    # «Ялга ул Мичурина д 3»: голое имя без запятой — только перед типом
    # улицы в самой голове; квартиры и «дом» такой страховкой не считаются.
    имя = _ПУНКТ_ИМЯ_ВПЛОТНУЮ.search(text[:start]) if тип_в_голове else None
    if (
        имя is not None
        and _годное_имя_пункта(имя.group("sname"))
        and _РЕЧЬ_СТРОЧНЫМИ.match(имя.group("sname").lower()) is None
        and re.fullmatch(_ТИП, имя.group("sname").lower(), re.IGNORECASE) is None
        # «Бердск ул Ленина 5» — город объявления, он идёт в `locality`.
        # Сравнение — той же нормализацией, что у справочника (`_норм_города`):
        # с 20.09 имена там без дефиса, и «Санкт-Петербург» с дефисом в
        # наборе не находился — уходил пунктом (ревью 20.09, C5).
        and _норм_города(имя.group("sname")) not in _имена_городов()
    ):
        return имя.group("sname").strip(), None, имя.start("sname"), end
    return None, None, start, end


#: Тип улицы в косвенном падеже на месте имени пункта: «улице кленовой 17»,
#: «Приедете на проспекте …» — не пункт «улице». В именительном падеже типы
#: ловит `_ТИП`; косвенные формы ни в одном стоп-списке не лежали, и первое
#: слово улицы без типа проходило именем пункта (скептик 20.09, Б-5).
_ТИП_УЛИЦЫ_В_ПАДЕЖЕ = frozenset(
    """улице улицу улицей улицею проспекте проспекту проспектом переулке переулку переулком
бульваре бульвару бульваром набережную проезде проезду проездом площади площадью аллее аллею
аллеей линию тупике тупику""".split()
)


def _годное_имя_пункта(имя: str) -> bool:
    """«Малиновка», «Нижний Тагил» — да; «Здравствуйте», «Мой адрес», «улице» —
    речь."""
    слова = имя.lower().split()
    return all(
        w not in _НЕ_НАЗВАНИЕ_УЛИЦЫ and w not in _НЕ_УЛИЦА and w not in _ТИП_УЛИЦЫ_В_ПАДЕЖЕ
        for w in слова
    )


def is_place_name(name: str) -> bool:
    """Слово может быть именем пункта: не приветствие, не речь, не служебная
    часть адреса, не тип улицы в падеже. ОДНО определение на пункт разбора
    (`_ПУНКТ_ИМЯ_ВПЛОТНУЮ`), подсказки карте (:func:`settlement_hints`) и
    прочтение первого слова улицы пунктом (`geocode.street_head_as_settlement`)."""
    return _годное_имя_пункта(name)


# --- класс 12 `STOP_TYPED_PLACE_SPEECH` (пакет 7a, Q16) --------------------------
#
# Тип пункта с заглавным словом за ним — сильная форма, и стоп-списки её не
# держат: «город Напишу», «село Сколько», «посёлок выезжаете» рождали строку
# места уровня A (корзина P_only_place, стенд 21.09). Класс судит по ФОРМЕ
# слова, а не по словарю: словарь речи бесконечен, формы глагола — нет.

#: Глагольная форма одним словом имени: «Напишу», «Выключился», «выезжаете».
#: Только от пяти букв: «Баку», «Орёл», «Тула» короче. «-сть» — существительное
#: («Юность»), как у `_РЕЧЬ_СТРОЧНЫМИ`.
_РЕЧЬ_ГЛАГОЛ_ПУНКТА = re.compile(
    r"^(?=[а-яё-]{5,}$)(?![а-яё-]*сть$)"
    r"[а-яё-]*(?:у|ю|ешь|ете|ите|ет|ут|ют|ат|ят|л|ла|ло|ли|лся|лась|лось|лись|ть|ся)$"
)
#: Наречие одним словом имени: «Приблизительно», «Реально», «Отлично».
#: Голое «-о» договор тоже называл, но по нему легли бы «мешково», «Иваново»,
#: «Мурино», «Тосно», «Ровно» — самые частые окончания русских пунктов; форма
#: их от наречия не отличает, поэтому «-о» здесь — только закрытым списком ниже.
_РЕЧЬ_НАРЕЧИЕ_ПУНКТА = re.compile(r"^(?=[а-яё]{6,}$)[а-яё]*(?:тельно|ично|ально)$")
#: Слова речи, которые не глагол и не наречие по окончанию, но именем пункта
#: не бывают: вопросительные, частицы, время, обещания «напишу/позвоню».
_РЕЧЬ_СЛОВО_ПУНКТА = frozenset(
    """сколько когда где куда откуда почему можно нужно надо есть нет да уже ещё еще тоже
также сейчас завтра сегодня напишу напишите позвоню позвоните приедете выезжаете работаете
ездите делаете точно быстро срочно далеко близко""".split()
)
#: Глагол вторым/третьим словом имени («Падун работаете», «Таежное выезжаете»):
#: имя обрезается ДО него — что осталось, то и судится. Обрезка самого имени
#: в строке — Q17, не этот класс.
_РЕЧЬ_ХВОСТ_ИМЕНИ = re.compile(r"^[а-яё]{4,}(?:ете|ите|ают|яют)$")


def _слово_пункта_речь(слово: str) -> bool:
    w = слово.lower()
    if _норм_города(w) in _имена_городов() or слово in КВАРТАЛЬНЫЕ_ГОРОДА:
        # «Сургут», «Салават», «Барнаул», «Махачкала»: окончание глагольное,
        # имя — из справочника.
        return False
    return (
        w in _РЕЧЬ_СЛОВО_ПУНКТА
        or _РЕЧЬ_ГЛАГОЛ_ПУНКТА.match(w) is not None
        or _РЕЧЬ_НАРЕЧИЕ_ПУНКТА.match(w) is not None
    )


def _имя_пункта_речь(имя: str) -> bool:
    """Имя пункта с типом — речь, а не название (класс 12): единственное слово —
    глагол/наречие/слово речи; больше двух слов и ни одного с заглавной. Глагол
    вторым-третьим словом отрезается перед судом: «Сколько работаете» → «Сколько»
    — речь; «Падун работаете» → «Падун» — имя, форма остаётся как есть."""
    слова = имя.split()
    for i, w in enumerate(слова[1:], start=1):
        if _РЕЧЬ_ХВОСТ_ИМЕНИ.match(w.lower()) is not None:
            слова = слова[:i]
            break
    if len(слова) == 1:
        return _слово_пункта_речь(слова[0])
    return len(слова) > 2 and not any(w[:1].isupper() for w in слова)


#: Реплика клиента, которая целиком — название места: «Новое Заозерье»,
#: «п. Ударник», «деревня Ивановка». Бой 12.09 (Череповец): клиент назвал
#: посёлок одним сообщением, а «Рябиновая 8» — следующим; карта нашла три
#: Рябиновых, 8 по области, и среди них ту самую. Это ПОДСКАЗКА для карты, а
#: не пункт строки: годится, только когда карта подтвердила дом именно там.
_РЕПЛИКА_ПУНКТ = re.compile(
    r"^\s*(?:(?:" + _ПУНКТ_ТИПЫ + r")\.?\s+)?"
    r"(?P<name>[А-ЯЁ][а-яё]+(?:[ -][А-ЯЁа-яё][а-яё]+){0,2})\s*[.!]?\s*$"
)


#: Одно слово в родительном падеже: «Буденного», «Толстого», «Достоевского» —
#: так кончаются фамилии улиц; пункты («Ялга», «Кедровка») и улицы вроде
#: «Гагарина» (не -ого/-его) — нет.
_РОДИТЕЛЬНЫЙ = re.compile(r"^[а-яё]+(?:ого|его)$")


def is_street_surname(name: str) -> bool:
    """Голое слово в родительном падеже — фамилия улицы, не пункт (владелец
    19.09, Старый Оскол: «Буденного» → вопрос оператора → «Буденного 7 кв 54»
    — пункт «Буденного» пристал к строке, и карта отказала «пункт не тот»).
    Пункты в родительном падеже не называют, а улицы-фамилии — сплошь: чиним
    одним окончанием, без словаря фамилий. ПРАВИЛО ОДНО на пункт строки
    (`inbound._пункт_в_реплике`) и на подсказки карте
    (:func:`settlement_hints`); с типом («п. Буденного») пункт остаётся
    пунктом — тип назвал сам клиент."""
    return _РОДИТЕЛЬНЫЙ.match(name.strip().lower().replace("ё", "е")) is not None


def settlement_hints(texts: list[str | None]) -> list[str]:
    """Названия мест из коротких реплик, по порядку и без повторов.

    Реплика-место с типом («Гатчинский р-н. Д. Малая Сосновка, массив
    Южный») даёт пункт из :func:`parse_place`; голое название — как есть,
    кроме фамилии улицы (:func:`is_street_surname`): «Буденного» отдельной
    репликой — улица, и подсказкой карте она вела бы запрос по области с
    пунктом, которого нет (ревью 19.09).
    """
    out: list[str] = []
    for t in texts:
        имя: str | None = None
        m = _РЕПЛИКА_ПУНКТ.match(t or "")
        if m is not None and _годное_имя_пункта(m.group("name")):
            имя = m.group("name").strip()
            без_типа = not (t or "")[: m.start("name")].strip()
            if без_типа and is_street_surname(имя):
                continue
        else:
            место = parse_place(t or "")
            if место is not None and место.settlement:
                имя = место.settlement
        if имя is None:
            # «Пашковка, Ореховая 317/1» — имя перед запятой в самом сообщении с
            # адресом, когда улица без типа и без частей: подсказкой, не
            # сторожем («Ольга, Ореховая 317/1» — имя человека, карта его не
            # найдёт и не помешает).
            m = _ИМЯ_ПЕРЕД_ЗАПЯТОЙ.match(t or "")
            if m is not None and _годное_имя_пункта(m.group("name")):
                имя = m.group("name").strip()
        if имя and имя not in out:
            out.append(имя)
    return out


_ИМЯ_ПЕРЕД_ЗАПЯТОЙ = re.compile(r"^\s*(?P<name>[А-ЯЁ][а-яё]{2,}(?:[ -][А-ЯЁ][а-яё]{2,})?)\s*,\s*\S")


_СТАНЦИЯ_ПЕРЕД = re.compile(r"(?i)(?:жд|ж/д|ж\.\s?д\.?|метро|м\.)\s*$")


def _годный_пункт(m: re.Match[str], *, улица_с_типом: bool) -> bool:
    тип = m.group("stype").lower().rstrip(".")
    имя = m.group("sname").split()[0].lower()
    if not _годное_имя_пункта(m.group("sname")):
        # Второе слово имени — речь («деревня Ивановка приезжайте»): не пункт.
        return False
    if тип == "п" and not улица_с_типом:
        return False
    if (
        тип == "ст"
        and (
            not (m.group("sdot") and m.group("sname")[0].isupper())
            # «жд ст. Удельная», «метро ст. Автово» (ревью 15.09) — ориентир, не пункт.
            or _СТАНЦИЯ_ПЕРЕД.search(m.string[: m.start("stype")]) is not None
        )
    ):
        # «Ст. Романовская» — станица (стенд 15.09); «ст» без точки — «ст 5» строение.
        return False
    if тип in ("с", "д") and not (
        (m.group("sdot") and m.group("sname")[0].isupper())
        # «д Сорокино ул Полевая», «Д новая мельница ул Нахимова д 15» (стенд
        # 15.09): «д» перед именем и улицей с типом — деревня, и строчными тоже.
        or (тип == "д" and улица_с_типом)
    ):
        # «с.»/«д.» — только с точкой и заглавной; «д Сорокино ул Полевая»
        # без точки годится: «д» перед Именем и улицей с типом — деревня, а
        # предлог «с» («с Мужем») точки требует по-прежнему. Точка и заглавная
        # вместе — уже сокращение, улица с типом не нужна: «С. Июньское
        # Воткинский район. Советская 64» (владелец 14.09).
        return False
    # «п Ударник» — да; «пос. этот» и «п меня» — речь, а не название.
    return имя not in _НЕ_НАЗВАНИЕ_УЛИЦЫ and имя not in _НЕ_УЛИЦА


def _выбрать_голову(
    text: str, знак: re.Match[str] | None
) -> tuple[re.Match[str] | None, list[str]]:
    """Из подходящих голов — та, что пересекается с признаком уровня.

    Пересечение важнее порядка: признак уровня («ул.», «кв 5») стоит РЯДОМ с
    настоящим адресом, а первое совпадение головы может оказаться где угодно —
    в описании техники, в габаритах, в цене.
    """
    подходящие = list(_годные_головы(text))
    if not подходящие:
        return None, []
    if знак is not None:
        # Признаков может быть несколько («днт Ромашка 5 ул дом 148» — бой
        # 13.09, Бурятия): среди голов у признаков — та, где дом назван явно
        # словом «дом/д.»; голое число рядом с типом пункта — не дом.
        признаки = [знак, *_ТИП_НАЗВАН.finditer(text)]
        у_признаков = [
            (m, слова)
            for m, слова in подходящие
            if any(m.start() <= з.end() and з.start() <= m.end() for з in признаки)
            # «снт Ромашка, 3 линия, 12»: «3» перед типом улицы с числом дальше
            # — имя улицы, а не дом.
            and not _ТИП_И_ДОМ_ДАЛЬШЕ.match(text, m.end())
        ]
        for m, слова in у_признаков:
            if _ЯВНЫЙ_ДОМ.search(m.group(0)):
                return m, слова
        if у_признаков:
            # «частный дом 3 этажа, котёл на 1 этаже, Ленина 5» (ревью 13.09):
            # среди голов у признака — та, что с типом улицы или именем с
            # заглавной; одно строчное слово речи перед числом — последней.
            return max(у_признаков, key=lambda г: _вес_головы(*г))
    return подходящие[0]


def _вес_головы(m: re.Match[str], слова: list[str]) -> int:
    """Порядок голов сохраняется («Ольхово днт Ромашка 5» раньше «днт
    Ромашка 5»); назад уходит только голова из одного строчного слова без
    типа — речь перед числом («частный 3», «без лифта, 4»)."""
    if m.group("тип1") or m.group("тип2"):
        return 1
    if len(слова) == 1 and слова[0][:1].islower():
        return 0
    return 1


def _все_головы(text: str) -> Iterator[re.Match[str]]:
    """Голова с КАЖДОГО слова, а не только непересекающиеся совпадения.

    «Новые липки 50 лет Победы дом 14» (стенд 13.09): первое совпадение —
    «Новые липки 50» — отбрасывается («50 лет» — срок), а `finditer` дальше
    начинает с «лет» и настоящую голову «50 лет Победы дом 14» не видит.
    """
    видели: set[tuple[int, int]] = set()
    for начало in [0, *(m.end() for m in re.finditer(r"\s+|[,.;:!?()]", text))]:
        m = _ГОЛОВА.match(text, начало)
        if m is None or m.span() in видели or not m.group("street").strip():
            continue
        видели.add(m.span())
        yield m


def _годные_головы(text: str) -> Iterator[tuple[re.Match[str], list[str]]]:
    """Головы, у которых название — действительно название.

    ⚠ СЛУЖЕБНЫЕ СЛОВА СРЕЗАЮТСЯ СЛЕВА, А ОСТАЛЬНОЕ ОТБРАСЫВАЕТ ГОЛОВУ ЦЕЛИКОМ.
    «Мой адрес Чехова 6» — «адрес» слева, срезаем, остаётся «Чехова». А вот
    служебное слово ВНУТРИ названия означает, что голова захватила чужую речь,
    и чинить её отрезанием нельзя.

    ⚠ ТИП УЛИЦЫ ИСКЛЮЧЁН ИЗ ЗАПРЕТА, И ЭТО СЛЕД НАСТОЯЩЕГО ДЕФЕКТА ЛИД-БОТА
    (28.08). Стоп-список содержит «улица», «проспект» и прочие типы — они и
    правда не название. Но правило отбрасывало голову целиком, стоило типу
    оказаться среди слов, и «Вокзальная улица 3» не разбиралось вовсе: дальше
    разбор брал следующее совпадение и отдавал обрывок вроде «ица».

    ⚠ ЗАПРЕТЫ НЕВОДА ДЕЙСТВУЮТ И ЗДЕСЬ (правка после разбора). `_НЕ_УЛИЦА` и
    `_НЕ_ДОМ_ЕДИНИЦА` жили только внутри широкого невода, то есть на уровнях B
    и C. На уровне A они не проверялись вовсе, и «Ванна 1500 на 3 этаже»,
    «Самсунг 55, кв 12», «Гарантия 12 месяцев» становились адресами. Замер боя
    за 30 дней: 144 марки и габарита, 74 единицы измерения.
    """
    for m in _все_головы(text):
        название = _ПОРЯДОК_С_ПРОБЕЛАМИ.sub(_порядок_слитно, m.group("street").strip())
        слова = [w for w in re.split(r"\s+", название) if w]
        # «Ленинский район Муравьева 14»: служебное слово («район», «город») с
        # тем, что перед ним, — уточнение, а название улицы — то, что ПОСЛЕ
        # него (корпус 12.09). Срезаем до последнего служебного слова; если
        # после него ничего нет — голова захватила чужую речь целиком.
        # «2 парадная 5 этаж» — подъезд по-петербургски, а «ул Парадная 5» —
        # улица: слово из _ИМЯ_ПРИ_ТИПЕ служебное только без типа перед ним.
        служебные = [
            i
            for i, w in enumerate(слова)
            if (
                w.lower().strip(".,") in _НЕ_НАЗВАНИЕ_УЛИЦЫ
                # Глагол или сравнительная степень строчными — речь (владелец
                # 18.09: «Иван взял 1т»); тип улицы («квартал») — нет.
                # Только у головы БЕЗ типа: класс — по окончанию, и «ул сокол
                # 5», «ул карл маркса 5», «пер. орел 3» (ревью 18.09) он резал
                # до «ул маркса» или выбрасывал целиком, а типовая голова —
                # самая сильная улика, глагол за «ул» не пишут.
                or (
                    not m.group("тип1")
                    and not m.group("тип2")
                    and w[:1].islower()
                    and _РЕЧЬ_СТРОЧНЫМИ.match(w.lower().strip(".,")) is not None
                    and re.fullmatch(_ТИП, w.lower().strip(".,"), re.IGNORECASE) is None
                )
            )
            and w.lower().strip(".,") not in _ТИПЫ_УЛИЦЫ
            and not (m.group("тип1") and w.lower().strip(".,") in _ИМЯ_ПРИ_ТИПЕ)
            # «Солнечный город 27» (стенд 15.09, Хабаровск — ЖК): «город» после
            # прилагательного с заглавной — часть имени, не речь.
            and not (
                w.lower() == "город"
                and i >= 1
                and слова[i - 1][0].isupper()
                and re.search(r"(?:ый|ий|ой)$", слова[i - 1].lower())
            )
        ]
        # «Лесной поселок 14а», «Мой адрес поселок Ударник 7» — пункт на месте
        # улицы: «поселок» здесь не речь, а тип пункта, его оставляем (стенд 13.09).
        if служебные and _ПУНКТ_КАК_УЛИЦА.match(" ".join(слова)) is not None:
            служебные = []
        if служебные:
            j = служебные[-1]
            оставить_тип = слова[j].lower().strip(".,") in _ПУНКТ_КАНОН
            слова = слова[j:] if оставить_тип else слова[j + 1 :]
        if not слова:
            continue
        # Марка, габарит, речь — та же проверка, что у невода, и по тем же
        # словам: смысловая голова у «Повесить зеркало 130» — второе слово.
        # Исключение — «40 лет Октября», «50 лет ВЛКСМ»: «лет» после числа и
        # перед словом — часть названия, а не срок.
        лет_в_названии = len(слова) >= 3 and слова[0].isdigit() and слова[1].lower() == "лет"
        if any(
            w.lower().strip(".,") in _НЕ_УЛИЦА and not (лет_в_названии and w.lower() == "лет")
            for w in слова
        ):
            continue
        # За домом стоит единица измерения — значит это не дом («55 дюймов»,
        # «12 месяцев», «2 метра»).
        if _ПОСЛЕ_ДОМА.match(text, m.end()) is None:
            continue
        # «Домофон не работает, 5 подъезд», «Понял, 5 этаж» (ревью 13.09):
        # одно слово, запятая, число и сразу слово части без своего числа —
        # это число части, а не дом. «112 мкр , 26 Подъезд 1» и «Вокзальная,
        # 33 подъезд 2» — у части своё число, дом на месте; «Ул. Грибоедова,
        # д.36 подъезд 6» — дом назван словом.
        if (
            m.group("зпт")
            and not m.group("дм")
            and len(слова) == 1
            and _ЧАСТЬ_БЕЗ_ЧИСЛА_ЗА_ДОМОМ.match(text, m.end())
        ):
            continue
        # «Ла Мур 1 этаж отдельный вход» (владелец 14.09, Новосибирск): без
        # типа улицы и слова «дом» голое число перед частью без своего числа —
        # этаж магазина, а не дом; «Ленина 5 этаж 3», «ул Ленина 5 этаж» и
        # дом с дробью/корпусом («Ленина 17/4 подъезд») остаются.
        if (
            not m.group("тип1")
            and not m.group("тип2")
            and not m.group("дм")
            and m.group("bld").strip().isdigit()
            and _ЧАСТЬ_БЕЗ_ЧИСЛА_ЗА_ДОМОМ.match(text, m.end())
        ):
            continue
        yield m, слова


#: Города, где адрес пишут двумя числами: «86-11» в Ангарске — 86-й квартал,
#: дом 11 (владелец 14.09); в Нефтеюганске — микрорайон и дом. Слово типа
#: клиент не пишет — его подставляет разбор по городу объявления.
КВАРТАЛЬНЫЕ_ГОРОДА: dict[str, str] = {
    "Ангарск": "квартал",
    "Шелехов": "квартал",
    "Нефтеюганск": "мкр",
    "Пыть-Ях": "мкр",
}
_ПАРА_КВАРТАЛ = re.compile(
    r"(?<![\d\-/:])(?<![\d][.,])(?P<q>[1-9]\d{0,2}[а-я]?)\s*-\s*(?P<bld>[1-9]\d{0,2}[а-я]?)"
    r"(?![\d\-/:а-яё])(?![.,]\d)",
    re.IGNORECASE,
)
#: «93 кв,31», «93 кв. 31», «93кв 31» (владелец 18.09, Ангарск): в квартальном
#: городе «кв» ПОСЛЕ числа — квартал, а не квартира («кв 31» — квартира, число
#: за словом). Само «кв» — улика: пара с ним берётся без проверок на время.
#: «31 подъезд» за парой — подъезд без своего числа, дом тогда не назван.
_ПАРА_КВАРТАЛ_КВ = re.compile(
    r"(?<![\d\-/:])(?<![\d][.,])(?P<q>[1-9]\d{0,2})\s*кв(?:-л|артал)?\.?\s*[,\s]\s*"
    r"(?P<bld>[1-9]\d{0,2}[а-я]?)(?![\d\-/:а-яё])(?![.,]\d)"
    r"(?!" + _ЧАСТЬ_БЕЗ_СВОЕГО_ЧИСЛА + r")",
    re.IGNORECASE,
)
#: «80 кв, 3 комнаты», «82 кв 5 м», «15 кв 3 комнатная» — площадь и комнаты,
#: а не квартал с домом (ревью 18.09).
_КОМНАТЫ_ЗА_ПАРОЙ = re.compile(r"\s*,?\s*(?:комнат|м(?![а-яё])|кв\.?\s*м(?![а-яё]))", re.IGNORECASE)
#: Время перед парой чисел: «с 9-13», «в 10-12», «к 14-15», «в 9-30» — не адрес.
_ВРЕМЯ_ПЕРЕД_ПАРОЙ = re.compile(
    r"(?:^|\s)(?:в|с|к|до|после|около|часов|часа|утра|вечера|дня)\s*$", re.IGNORECASE
)
#: Слово вплотную перед парой, после которого пара — не адрес: диапазон
#: («через 30-40», «за 300-500», «до 60-70»), часть адреса со своими номерами
#: («подъезд 2-3»), латиница марки (но не маска телефона «XXXXXXXXXXX»).
_НЕ_АДРЕС_ВПЛОТНУЮ_К_ПАРЕ = re.compile(
    r"(?:^|\s)(?:через|за|до|около|примерно|где-то|по|или|этаж\w*|по[дж][ъь]?езд\w*|кв|"
    r"квартир\w*|домофон|(?!x+(?![a-z0-9]))[a-z][a-z0-9]*)\W*$",
    re.IGNORECASE,
)
#: Слово цены, техники, модели, срока среди трёх слов перед парой: «Телевизор
#: диагональ примерно 40-43», «Самсунг 40-43», «Мне 65-70», «Скидка 30-40».
_НЕ_АДРЕС_ПЕРЕД_ПАРОЙ = re.compile(
    r"(?:^|\s)(?:цена|стоимость|стоит|бюджет|скидк\w*|диагональ\w*|дюйм\w*|размер\w*|"
    r"модель|ошибк\w*|код|телевизор\w*|телек\w*|тв|экран\w*|матриц\w*|яркост\w*|"
    r"монитор\w*|ноутбук\w*|планшет\w*|температур\w*|греется|весом|вес|"
    r"самсунг\w*|филипс\w*|сони|тошиба|панасоник\w*|хайер|хисенс|элджи|"
    r"минут\w*|секунд\w*|часов|рублей|тысяч\w*|тыщ\w*|лет|года|возраст\w*|мне|серия)"
    r"(?:\W+[а-яё\-]+){0,2}\W*$",
    re.IGNORECASE,
)
#: Части адреса сразу за парой («86-11, 1 подъезд, кв 5») — сильный признак.
_ЧАСТИ_ЗА_ПАРОЙ = re.compile(
    r"^\W*(?:\d{1,3}\s*)?(?:по[дж][ъь]?езд|кв(?![а-яё])|квартир|этаж|домофон|парадн)", re.IGNORECASE
)
#: Слова, которые не мешают паре быть «всей репликой»: «Адрес: 86-11.», «Ок 86-11».
_ВОКРУГ_ПАРЫ = re.compile(
    r"(?:здравствуйте|добрый\s+день|добрый\s+вечер|доброе\s+утро|привет|адрес|ок|окей|"
    r"хорошо|да|это|мой|наш|у\s+нас|пишите|записывайте)",
    re.IGNORECASE,
)


#: Города, где адрес — номер корпуса без улицы: «Зеленоград, к317», «К.418, 1
#: под, 7 эт, кв.52» (стенд 15.09). Карта понимает «Зеленоград, корпус 418».
КОРПУСНЫЕ_ГОРОДА = frozenset({"Зеленоград"})
#: Голая «к» — только с точкой или вплотную («К.418», «к317»): «к 2000 рублей»,
#: «приеду к 1200» — предлог (ревью 15.09). Полные «корп»/«корпус» — и через пробел.
_КОРПУС_ГОРОДА = re.compile(
    r"(?<![а-яё\d])(?:к\.\s?|к(?=\d)|(?:корп|корпус)\.?\s?)(?P<bld>\d{3,4}[а-яА-Я]?)(?![\d])(?![.,]\d)",
    re.IGNORECASE,
)


def parse_corpus(text: str, *, rules: Rules = None) -> Found | None:
    """«К.418, 1 под, 7 эт, кв.52» в корпусном городе → улица «корпус», дом 418."""
    from app.services import phone_parse

    рабочий = text or ""
    for номер in phone_parse.find_all(рабочий):
        рабочий = рабочий[: номер.start] + "X" * (номер.end - номер.start) + рабочий[номер.end :]
    if parse(рабочий, rules=rules) is not None:
        return None
    m = _КОРПУС_ГОРОДА.search(рабочий)
    if m is None:
        return None
    return Found(
        street="корпус",
        house=m.group("bld"),
        raw=(text or "")[m.start() : m.end()],
        start=m.start(),
        end=m.end(),
        level=LEVEL_B,
        parts=parts_only(рабочий[: m.start()] + " " + рабочий[m.end() :], rules=rules),
    )


#: Города, где адрес — «комплекс/дом»: «38/07» в Набережных Челнах — 38-й
#: комплекс, дом 7 (владелец 18.09; карта: «38-й комплекс, 7»). Слово
#: «комплекс» клиент не пишет, ноль впереди дома — их манера («07»).
КОМПЛЕКСНЫЕ_ГОРОДА = frozenset({"Набережные Челны"})
#: Пара через дробь, сама по себе: «17/4» ПОСЛЕ улицы — дом с корпусом, его
#: берёт :func:`parse` раньше; здесь только реплика без головы.
_ПАРА_КОМПЛЕКС = re.compile(
    r"(?<![\d\-/:.,])(?P<c>[1-9]\d{0,2})\s*/\s*(?P<bld>\d{1,3}[а-я]?)(?![\d\-/:а-яё])(?![.,]\d)",
    re.IGNORECASE,
)


def complex_pair_present(text: str) -> bool:
    """Есть ли в реплике пара «N/M» вообще — стоит ли идти в ленту за вопросом."""
    return _ПАРА_КОМПЛЕКС.search(text or "") is not None


def parse_complex_pair(text: str, *, про_адрес: bool = False, rules: Rules = None) -> Found | None:
    """«38/07» в комплексном городе → улица «38-й комплекс», дом 7.

    Улики те же, что у квартальной пары (:func:`parse_quarter_pair`): за
    парой нет единицы, перед ней нет слова цены, техники или части адреса,
    пара одна. Пара «как дата» (день до 31, месяц до 12: «18/09», «1/10») и
    «как дробь» (оба числа до 4: «1/2», «3/4») берётся ТОЛЬКО с частями
    адреса за ней, словом «адрес» перед ней или всей репликой в ответ на
    вопрос оператора об адресе (``про_адрес``); «38/07» — датой не бывает.
    Нули впереди дома отбрасываются: «07» → «7», как пишет карта.
    """
    from app.services import phone_parse

    рабочий = text or ""
    for номер in phone_parse.find_all(рабочий):
        рабочий = рабочий[: номер.start] + "X" * (номер.end - номер.start) + рабочий[номер.end :]
    город = _город_объявлений(рабочий)
    if город is not None:
        s0, e0 = город.span("city")
        рабочий = рабочий[:s0] + " " * (e0 - s0) + рабочий[e0:]
    if parse(рабочий, rules=rules) is not None:
        return None
    пары = list(_ПАРА_КОМПЛЕКС.finditer(рабочий))
    if len(пары) != 1:
        return None
    m = пары[0]
    перед, после = рабочий[: m.start()], рабочий[m.end() :]
    if (
        _ПОСЛЕ_ДОМА.match(рабочий, m.end()) is None
        or _НЕ_АДРЕС_ВПЛОТНУЮ_К_ПАРЕ.search(перед)
        or _НЕ_АДРЕС_ПЕРЕД_ПАРОЙ.search(перед)
    ):
        return None
    дом = m.group("bld").lstrip("0")
    if not дом or дом[0].isalpha():
        return None
    числа = (int(m.group("c")), int(re.sub(r"\D", "", дом)))
    if числа[0] >= 100 or числа[1] >= 100:
        # «220/380 вольт», «12/345» — напряжение, номер заявки; комплексов в
        # Челнах около семидесяти, домов в комплексе — десятки (ревью 18.09).
        return None
    части_рядом = _ЧАСТИ_ЗА_ПАРОЙ.match(после) is not None
    слово_адрес = re.search(r"адрес\w*\W*$", перед, re.IGNORECASE) is not None
    остаток = _ВОКРУГ_ПАРЫ.sub(" ", перед + " " + после)
    целиком = not re.search(r"[а-яёa-z0-9]", остаток, re.IGNORECASE)
    как_дата = числа[0] <= 31 and числа[1] <= 12
    как_дробь = числа[0] <= 4 and числа[1] <= 4
    if (как_дата or как_дробь) and not (части_рядом or слово_адрес or (целиком and про_адрес)):
        return None
    return Found(
        street=f"{m.group('c')}-й комплекс",
        house=дом,
        raw=(text or "")[m.start() : m.end()],
        start=m.start(),
        end=m.end(),
        level=LEVEL_B,
        parts=parts_only(перед + " " + после, rules=rules),
    )


def parse_by_city(
    text: str, город: str | None, *, про_адрес: bool = False, rules: Rules = None
) -> Found | None:
    """Формы адреса, свойственные городу объявления: «86-11» в квартальных,
    «к317» в корпусных, «38/07» в комплексных. Пусто — когда город не из
    таких или форм нет."""
    if not город:
        return None
    тип = КВАРТАЛЬНЫЕ_ГОРОДА.get(город)
    if тип:
        return parse_quarter_pair(text, тип, про_адрес=про_адрес, rules=rules)
    if город in КОРПУСНЫЕ_ГОРОДА:
        return parse_corpus(text, rules=rules)
    if город in КОМПЛЕКСНЫЕ_ГОРОДА:
        return parse_complex_pair(text, про_адрес=про_адрес, rules=rules)
    return None


def _без_телефона_и_города(text: str) -> str:
    """Реплика для поиска квартальной формы: телефон погашен крестиками, город
    объявления впереди («Нефтеюганск 7.10.34», «Ангарск, 86-11») и знаки за
    ним — пробелами. Длина не меняется: смещения найденного годятся для среза
    из исходного текста. Один помощник на разбор и на ворота
    (`quarter_pair_present`): иначе ворота живого пути не пускали бы к разбору
    форму, которую тот умеет (ревью 20.09, #10)."""
    from app.services import phone_parse

    рабочий = text or ""
    for номер in phone_parse.find_all(рабочий):
        рабочий = рабочий[: номер.start] + "X" * (номер.end - номер.start) + рабочий[номер.end :]
    город = _город_объявлений(рабочий)
    if город is not None:
        s0, e0 = город.span("city")
        # Запятая за городом гасится вместе с ним: точечная тройка привязана к
        # началу строки, и «Нефтеюганск, 7.10.34» иначе упиралась бы в неё.
        за_городом = re.match(r"[\s,]*", рабочий[e0:])
        e0 += за_городом.end() if за_городом is not None else 0
        рабочий = рабочий[:s0] + " " * (e0 - s0) + рабочий[e0:]
    return рабочий


def quarter_pair_present(text: str) -> bool:
    """Есть ли в реплике пара «N-M», «N кв M» или тройка «N.M.K» вообще —
    стоит ли идти в ленту за вопросом. Смотрит ту же форму текста, что и
    разбор: город объявления впереди погашен."""
    т = _без_телефона_и_города(text)
    return (
        _ПАРА_КВАРТАЛ.search(т) is not None
        or _ПАРА_КВАРТАЛ_КВ.search(т) is not None
        or _МКР_ДОМ_КВ_ТОЧКИ.match(т) is not None
    )


def parse_quarter_pair(
    text: str, тип: str, *, про_адрес: bool = False, rules: Rules = None
) -> Found | None:
    """«86-11» в квартальном городе → улица «86 квартал», дом 11.

    Пара чисел через дефис — форма адреса только в городах из
    :data:`КВАРТАЛЬНЫЕ_ГОРОДА`, и даже там ей нужны улики (ревью 14.09: без
    них «завтра 10-12», «2-3 дня», «500-700 рублей» становились адресами):

    - за парой нет единицы («минут», «рублей», «дюймов», «сентября») и перед
      ней нет слова цены, техники, модели или части адреса; пара одна —
      «с 10-12 или 15-17» это два окна времени;
    - пара «как время» (первое число до 24, второе до 59: «10-12», «9-30»,
      «18-15») берётся ТОЛЬКО с частями адреса за ней («9-13, кв 5»),
      словом «адрес» перед ней или всей репликой в ответ на вопрос оператора
      об адресе (``про_адрес``);
    - иначе пара, где первое число больше 24, — адрес и в речи («Через час
      86-11», владелец 14.09): временем так не пишут, а квартал 86 — пишут.

    Уровень B. Телефон гасится крестиками до поиска, как в :func:`parse`;
    город объявления перед парой («Ангарск 86-11») — тоже
    (`_без_телефона_и_города`).
    """
    рабочий = _без_телефона_и_города(text)
    # «7.10.34» целиком репликой (или в начале после вопроса об адресе) —
    # микрорайон, дом, квартира через точки: местная запись в квартальных
    # городах. Дефисная тройка живёт в `parse` для любого города; точечная —
    # только здесь, чтобы вне таких городов дата не стала адресом. Тройка
    # «как дата» («5.10.26», `_точки_как_дата`) — как пара «как время»: только
    # после вопроса оператора об адресе или со словом «адрес» впереди («Адрес:
    # 5.10.26» — улика наравне с вопросом, как у пар). Ищется в тексте с
    # погашенным городом («Нефтеюганск 7.10.34»), а срез — из исходного, от
    # микрорайона до квартиры: слово «адрес» впереди в цитату не входит.
    точки = _МКР_ДОМ_КВ_ТОЧКИ.match(рабочий)
    if точки is not None and (
        про_адрес
        or (
            точки.group("хвост") is None
            and (
                not _точки_как_дата(точки)
                or re.search(r"адрес\w*\W*$", рабочий[: точки.start("mkr")], re.IGNORECASE)
                is not None
            )
        )
    ):
        начало, конец = точки.start("mkr"), точки.end("kv")
        return Found(
            street=f"{точки.group('mkr').lower()} {тип}",
            house=точки.group("bld"),
            raw=(text or "")[начало:конец],
            start=начало,
            end=конец,
            level=LEVEL_B,
            parts={"office": точки.group("kv")},
        )
    if parse(рабочий, rules=rules) is not None:
        return None
    # «93 кв,31» (владелец 18.09): квартал назван словом «кв» — пара с уликой
    # внутри, проверки на время и диапазон ей не нужны. Но «кв» — это ещё
    # квартира и квадратные метры, поэтому (ревью 18.09): только там, где
    # массив и есть квартал («93 кв» микрорайоном в Нефтеюганске не бывает);
    # за парой нет единицы и комнат («80 кв, 3 комнаты», «82 кв 5 м»); перед
    # ней нет предлога времени и слова цены или техники («в 14 кв 7»).
    с_кв = _ПАРА_КВАРТАЛ_КВ.search(рабочий) if тип == "квартал" else None
    if с_кв is not None and (
        _ПОСЛЕ_ДОМА.match(рабочий, с_кв.end()) is None
        or _ВРЕМЯ_ПЕРЕД_ПАРОЙ.search(рабочий[: с_кв.start()])
        or _НЕ_АДРЕС_ПЕРЕД_ПАРОЙ.search(рабочий[: с_кв.start()])
        or _КОМНАТЫ_ЗА_ПАРОЙ.match(рабочий, с_кв.end())
    ):
        с_кв = None
    if с_кв is not None:
        return Found(
            street=f"{с_кв.group('q')} {тип}",
            house=с_кв.group("bld"),
            raw=(text or "")[с_кв.start() : с_кв.end()],
            start=с_кв.start(),
            end=с_кв.end(),
            level=LEVEL_B,
            parts=parts_only(рабочий[: с_кв.start()] + " " + рабочий[с_кв.end() :], rules=rules),
        )
    пары = list(_ПАРА_КВАРТАЛ.finditer(рабочий))
    if len(пары) != 1:
        return None
    m = пары[0]
    q, bld = m.group("q"), m.group("bld")
    перед, после = рабочий[: m.start()], рабочий[m.end() :]
    if (
        _ПОСЛЕ_ДОМА.match(рабочий, m.end()) is None
        or _НЕ_АДРЕС_ВПЛОТНУЮ_К_ПАРЕ.search(перед)
        or _НЕ_АДРЕС_ПЕРЕД_ПАРОЙ.search(перед)
    ):
        return None
    числа = (int(re.sub(r"\D", "", q)), int(re.sub(r"\D", "", bld)))
    if числа[1] >= 100:
        # «300-500», «500-700» — цена; дома в квартале трёхзначными не бывают.
        return None
    if числа[0] <= 24 and _ВРЕМЯ_ПЕРЕД_ПАРОЙ.search(перед):
        return None
    части_рядом = _ЧАСТИ_ЗА_ПАРОЙ.match(после) is not None
    слово_адрес = re.search(r"адрес\w*\W*$", перед, re.IGNORECASE) is not None
    остаток = _ВОКРУГ_ПАРЫ.sub(" ", перед + " " + после)
    целиком = not re.search(r"[а-яёa-z0-9]", остаток, re.IGNORECASE)
    # «18-15», «12-12» — тоже время: минут меньше часа (ревью 14.09). «27-28»,
    # «28-29» — дни месяца, «30-40», «40-50» — «примерно столько»: соседние
    # числа и круглые десятки без улик — не адрес (третий круг ревью).
    как_время = числа[0] <= 24 and числа[1] <= 59
    как_диапазон = числа[1] == числа[0] + 1 or (числа[0] % 10 == 0 and числа[1] % 10 == 0)
    if (как_время or как_диапазон) and not (части_рядом or слово_адрес or (целиком and про_адрес)):
        return None
    return Found(
        street=f"{q.lower()} {тип}",
        house=bld,
        raw=(text or "")[m.start() : m.end()],
        start=m.start(),
        end=m.end(),
        level=LEVEL_B,
        parts=parts_only(перед + " " + после, rules=rules),
    )


#: Дом в строке карты: «40», «12а», «5 к 2», «17/2», «3 стр 1».
_ДОМ_ГЕОТОЧКИ = re.compile(
    r"^\d{1,4}[а-яa-z]?(?:\s*(?:/|к|корп\.?|корпус|с|стр\.?|строение)\s*\d{1,3}[а-я]?)?$",
    re.IGNORECASE,
)
_ТИП_ПУНКТА_ГЕОТОЧКИ = re.compile(
    r"^(?P<тип>пос[её]лок|деревня|село|станица|хутор|аул|пгт|рабочий пос[её]лок|"
    r"дачный пос[её]лок|садовое товарищество|город)\s+(?P<имя>.+)$",
    re.IGNORECASE,
)
_РЕГИОН_ГЕОТОЧКИ = re.compile(
    r"(?<![а-яё])(?:область|край|республика|округ|район|россия|автономн)", re.IGNORECASE
)


def parse_geopoint(address: str) -> Found | None:
    """Адрес из геоточки Авито («Московская область, городской округ Химки,
    посёлок Берёзово, садоводческое некоммерческое товарищество Берёзово, 27»,
    владелец 15.09) — строка карты, а не речь: куски через запятую, дом
    последним, перед ним улица или массив, выше — пункт, город, регион.
    Точку выбрал сам клиент, поэтому уровень A; координаты берёт вызывающий.
    """
    куски = [к.strip() for к in (address or "").split(",") if к.strip()]
    if len(куски) < 2:
        return None
    дом = куски[-1] if _ДОМ_ГЕОТОЧКИ.match(куски[-1]) else ""
    остальное = куски[:-1] if дом else куски
    улица = ""
    пункт = тип_пункта = город = район = None
    for кусок in остальное:
        if _РЕГИОН_ГЕОТОЧКИ.search(кусок) and не_пункт(кусок):
            if район is None and re.search(r"район|округ", кусок, re.IGNORECASE):
                район = кусок
            continue
        m = _ТИП_ПУНКТА_ГЕОТОЧКИ.match(кусок)
        if m is not None:
            if m.group("тип").lower() == "город":
                город = m.group("имя")
            else:
                пункт, тип_пункта = (
                    m.group("имя"),
                    _ПУНКТ_КАНОН.get(m.group("тип").lower(), m.group("тип").lower()),
                )
            continue
        # Та же нормализация, что у справочника: «Санкт-Петербург, 5» иначе
        # рождало строку дома с улицей «Санкт-Петербург» (ревью 20.09, C5).
        if _норм_города(кусок) in _имена_городов():
            город = кусок
            continue
        # Как написано у карты: сторож цитаты сверяет улицу с текстом точки.
        улица = кусок
    if not улица and not пункт:
        return None
    return Found(
        street=улица,
        house=дом,
        raw=address.strip(),
        start=0,
        end=len(address),
        level=LEVEL_A,
        kind=KIND_HOUSE if дом else KIND_PLACE,
        settlement=пункт,
        settlement_type=тип_пункта,
        locality=город,
        district=район,
    )


def не_пункт(кусок: str) -> bool:
    """«городской округ Химки» — регион, «посёлок Берёзово» с «район» в имени — нет."""
    return _ТИП_ПУНКТА_ГЕОТОЧКИ.match(кусок) is None


def parts_only(text: str, *, rules: Rules = None) -> dict[str, str]:
    """Части адреса из сообщения, В КОТОРОМ УЛИЦЫ И ДОМА НЕТ.

    ⚠ ЗАЧЕМ ОТДЕЛЬНАЯ ФУНКЦИЯ. Адрес люди называют по частям: «Ленина 5», а
    следом «кв 3, второй подъезд». Замер боя: так устроены 23,5 % адресных
    диалогов. Обычный `parse` такое сообщение не берёт вовсе — у него нет
    головы, — и без этой функции квартира терялась бы у каждого четвёртого
    адреса, то есть мастер приезжал бы к подъезду и звонил уточнять.

    ⚠ ЭТО НЕ АДРЕС И НЕ ПРЕТЕНДУЕТ ИМ БЫТЬ. Функция возвращает только части и
    ровно поэтому безопасна: сама по себе она ничего в карточку не кладёт,
    вызывающий дописывает их в УЖЕ НАЙДЕННЫЙ адрес того же диалога. «Квартира
    53» без улицы адресом для выезда не является — это записано и в шапке
    `_ПРО_АДРЕС`.

    ⚠ ЦЕНА РЕШЕНИЯ НАЗВАНА ВСЛУХ. «Телевизор на 5 этаже» в диалоге, где адрес
    уже назван, добавит этаж 5. Ошибка видна оператору — части показаны рядом с
    цитатой, — и она дешевле потерянной квартиры: во втором случае мастер
    приезжает и не может войти.
    """
    т = text or ""
    if _ГОЛОВА.search(т) and parse(т, rules=rules) is not None:
        return {}  # это полноценный адрес, у него свой путь
    return _части(т)


# --- место без улицы -------------------------------------------------------------
#
# ВЛАДЕЛЕЦ 13.09: «клиент написал „Гатчинский р-н. Д. Малая Сосновка, массив
# Южный“ — мне бы в картах перейти быстро; как укажет улицу — обновить».
# Адрес называют по частям: сначала место, улица и дом позже (или никогда —
# в деревне мастер найдёт по массиву). Место — отдельная строка-кандидат
# (`kind=place`): карта даёт ему точку, карточка — ссылку на карту.

#: Между именем и «район» — пробел обязателен: «Микрорайон 3» — не район
#: «Микро» (стенд 1409).
_МЕСТО_РАЙОН = re.compile(
    r"(?<![А-ЯЁа-яё])(?P<district>[А-ЯЁ][а-яё]+(?:-[А-ЯЁ][а-яё]+)?)\s+"
    r"(?:р-н|р-он|район[аеу]?|муниципальн\w*\s+округ[аеу]?)(?![а-яё])",
)
#: Слово имени пункта — не тип улицы: «п. Сосновка ул. Лесная» — пункт
#: «Сосновка», а не «Сосновка ул» (ревью 13.09).
_НЕ_ТИП_УЛИЦЫ = (
    r"(?!(?i:улиц\w*|ул\.?|просп\w*|пр-?кт\.?|пр\.?|пер\.?|переул\w*|ш\.?|шоссе|б-р|бульвар\w*|"
    r"набережн\w*|наб\.?|проезд\w*|лини[яи]|тракт|аллея|тупик|туп\.?)(?![а-яё]))"
)
#: Слово речи, которым название не кончается: «ул союзная рядом тц» → «ул союзная».
_НЕ_ХВОСТ_НАЗВАНИЯ = (
    r"(?!(?:рядом|около|возле|напротив|дальше|ближе|потом|сейчас|сегодня|завтра|нужна|"
    r"нужно|нужен|можно|надо|будет|есть|тоже|также|ремонт|установка|замена|подскажите|"
    r"сколько|стоит|работает|нету)(?![а-яё]))"
)
_МЕСТО_ПУНКТ = re.compile(
    r"(?<![А-ЯЁа-яё])(?P<stype>(?i:" + _ПУНКТ_ТИПЫ + r"|г|город))\.?\s*"
    # «посёлок Росва нужен ремонт» → «Росва»: слово речи в имя не входит.
    r"(?P<sname>[А-ЯЁ][а-яё]+(?:[ -]"
    + _НЕ_ТИП_УЛИЦЫ
    + _НЕ_ХВОСТ_НАЗВАНИЯ
    + r"[А-ЯЁа-яё][а-яё]+){0,2})(?![а-яё])"
    # «Деревня мешково», «село Репное» — после полного слова типа имя и строчными.
    # «я пос новомихайловский» (стенд 13.09) — и после «пос»: в речи такого
    # слова нет, а имя от пяти букв.
    r"|(?<![А-ЯЁа-яё])(?:(?P<stype3>(?i:пос[её]лок|деревня|село|станица|хутор))\s+"
    r"(?P<sname3>[а-яё]{3,})|(?P<stype4>(?i:пос)\.?)\s+(?P<sname4>[а-яё]{5,}))(?![а-яё])",
)
_МЕСТО_МАССИВ = re.compile(
    r"(?<![А-ЯЁа-яё])(?:(?P<atype>массив|мкр-н|мкр|мкрн|микрорайон|квартал|снт|днп|днт|тсн|жк|"
    # Граница после типа: «тер+ять» из «время не терять» было массивом (бой 13.09).
    r"садоводство|кп|коттеджный\s+пос[её]лок|территория|тер)(?![а-яё])\.?\s*"
    # «квартал 92/93» (владелец 18.09, Ангарск): сдвоенный номер — один массив.
    r"(?P<aname>[А-ЯЁ][а-яё]+(?:[ -][А-ЯЁа-яё][а-яё]+){0,2}|№?\s?\d{1,3}(?:/\d{1,3})?)"
    # «10 мкр», «5 микрорайон», «49 квартал» — номер перед типом.
    r"|(?<![\d])(?P<anum>\d{1,3}(?:/\d{1,3})?[а-яё]?)\s*-?(?:й|я|ый|ой)?\s*"
    r"(?P<atype2>мкр|мкрн|микрорайон|квартал))"
    r"(?![а-яё\d])",
    re.IGNORECASE,
)
#: Слов речи вокруг места: с пунктом с типом («посёлок Киссолово, 15 км от
#: Парнаса…») речь не отменяет места — до 12; массив без пункта («в 17 мкр
#: как скоро сможете») — до 8; одинокий район местом не считается.
_МЕСТО_ЛИШНИХ_СЛОВ = 12
_МЕСТО_ЛИШНИХ_СЛОВ_МАССИВ = 8
_МЕСТО_ЛИШНИХ_СЛОВ_УЛИЦА = 16


def parse_place(text: str, *, rules: Rules = None) -> Found | None:
    """Место без улицы и дома: район, пункт с типом, массив/СНТ.

    Нужен хотя бы пункт с типом («д. Малая Сосновка») или массив/СНТ с
    названием; один район («Гатчинский р-н») местом не считается — карта дала
    бы точку райцентра, и мастер поехал бы не туда. Сообщение, где есть
    улица с домом, разбирает :func:`parse` — сюда оно не попадает.
    ``rules`` — политика правил разбора, та же, что у :func:`parse`.
    """
    if not text or parse(text, rules=rules) is not None:
        return None
    рабочий = text.replace("\n", " ")
    район = _МЕСТО_РАЙОН.search(рабочий)
    # «С. Июньское Воткинский район»: район — не хвост имени пункта.
    без_района = рабочий
    if район is not None:
        без_района = рабочий[: район.start()] + " " * len(район.group(0)) + рабочий[район.end() :]
    # «Ангарск 11 микрорайон …» (владелец 14.09): город объявления без «г.» —
    # город клиента, а не слово речи вокруг места. Кусок — сам город, без
    # разделителя перед ним: иначе цитата начиналась бы с точки (ревью 14.09).
    город_объявлений = _город_объявлений(рабочий)
    if город_объявлений is not None:
        город_объявлений = re.compile(
            "(?P<city>" + re.escape(город_объявлений.group("city")) + ")"
        ).match(рабочий, город_объявлений.start("city"))
    пункт = None
    город_словами: re.Match[str] | None = None
    for m in _МЕСТО_ПУНКТ.finditer(без_района):
        тип = (m.group("stype") or m.group("stype3") or m.group("stype4")).lower().rstrip(".")
        имя = m.group("sname") or m.group("sname3") or m.group("sname4")
        # Голые «с», «д», «г» — только с точкой и заглавной, как у пункта рядом
        # с улицей: «с мужем», «д 5», «г вечера» — не место.
        if тип in ("с", "д", "г", "п", "ст") and not (
            рабочий[m.start("stype") + len(тип) : m.start("stype") + len(тип) + 1] == "."
            and имя[0].isupper()
        ):
            continue
        if not _годное_имя_пункта(имя):
            continue
        # «г. Белгород, пгт Северный»: город — город клиента, пункт — пгт
        # (ревью 13.09); в `parse` то же: город уходит в `locality`.
        if тип in ("г", "город") and город_словами is None:
            город_словами = m
            continue
        пункт = m
        break
    массив = _МЕСТО_МАССИВ.search(рабочий)
    if (
        пункт is not None
        and массив is not None
        and пункт.start() < массив.end()
        and массив.start() < пункт.end()
    ):
        # «СНТ Ромашка» — и тип пункта, и массив: одно место, не два.
        пункт = None
    if пункт is None and город_словами is not None:
        # Город без другого пункта — сам пункт («г. Гатчина, мкр Аэродром»).
        пункт, город_словами = город_словами, None
    # УЛИЦА БЕЗ ДОМА (владелец 13.09: «находить почти всё»): «Калуга, улица 65
    # лет Победы», «в Королёве ул. Горького» — место с точкой улицы; дом
    # придёт следующей репликой и заменит его. Только с типом улицы: голое
    # «Горького» без дома — слово, не адрес.
    улица = _УЛИЦА_БЕЗ_ДОМА.search(рабочий)
    for другое in (пункт, массив):
        if (
            улица is not None
            and другое is not None
            and другое.start() < улица.end()
            and улица.start() < другое.end()
        ):
            улица = None
    пункт_без_типа: re.Match[str] | None = None
    if пункт is None and улица is not None:
        # «В Сукко, на ул. Солнечную» (владелец 18.09): имя перед улицей с
        # типом — пункт без типа, как «Малиновка, пер Тополиный» у дома.
        перед = _ПУНКТ_ИМЯ_ПЕРЕД.search(рабочий[: улица.start()])
        if (
            перед is not None
            and _годное_имя_пункта(перед.group("sname"))
            and _имя_после_в_годится(перед)
            and (город_объявлений is None or перед.start("sname") != город_объявлений.start())
        ):
            пункт_без_типа = re.compile("(?P<sname>" + re.escape(перед.group("sname")) + ")").match(
                рабочий, перед.start("sname")
            )
    if пункт is None and массив is None and улица is None:
        return None
    if город_объявлений is not None and any(
        m is not None and m.start() < город_объявлений.end() and город_объявлений.start() < m.end()
        for m in (район, город_словами, пункт, массив, улица)
    ):
        # «Московский проспект» в Петербурге: город внутри названия — не город.
        город_объявлений = None
    if массив is not None and пункт is None and массив.group("atype") is None:
        # «10 мкр» без пункта — микрорайон города объявления: карта ищет его в
        # городе (`search_place(city=…)`), клиент «в 10-м мкр» — уже место.
        pass
    куски = [
        m
        for m in (район, город_словами, пункт, пункт_без_типа, массив, улица, город_объявлений)
        if m is not None
    ]
    # Речь вокруг: всё, что не попало в куски, обязано быть коротким.
    остаток = рабочий
    for m in sorted(куски, key=lambda m: m.start(), reverse=True):
        остаток = остаток[: m.start()] + " " + остаток[m.end() :]
    лишних = [w for w in re.split(r"[^0-9a-zA-Zа-яёА-ЯЁ]+", остаток) if w]
    предел = _МЕСТО_ЛИШНИХ_СЛОВ if пункт is not None else _МЕСТО_ЛИШНИХ_СЛОВ_МАССИВ
    if улица is not None:
        # Улица с типом в речи («в Королёве ул. Горького, поменять лампочку…»):
        # улица города объявления — место без риска, речь вокруг не мешает.
        предел = _МЕСТО_ЛИШНИХ_СЛОВ_УЛИЦА
    if len(лишних) > предел:
        return None
    имя_улицы = " ".join(улица.group(0).split()) if улица is not None else ""
    if имя_улицы:
        слова_улицы = [w for w in re.split(r"[\s.]+", имя_улицы) if w]
        # «65 лет Победы»: «лет» после числа — часть названия.
        лет_в_названии = len(слова_улицы) >= 3 and any(
            w.lower() == "лет" and слова_улицы[i - 1].isdigit()
            for i, w in enumerate(слова_улицы)
            if i > 0
        )
        if any(
            (w.lower() in _НЕ_УЛИЦА and not (лет_в_названии and w.lower() == "лет"))
            or (w.lower() in _НЕ_НАЗВАНИЕ_УЛИЦЫ and w.lower() not in _ТИПЫ_УЛИЦЫ)
            for w in слова_улицы
        ):
            return None
    start = min(m.start() for m in куски)
    end = max(m.end() for m in куски)
    # «11 микрорайон дом квартира 92»: квартира названа вместе с местом —
    # едет с ним, а оттуда к дому (`_дом_к_месту`), как и части между репликами.
    части = _части(остаток)
    тип_пункта = None
    имя_пункта = пункт_без_типа.group("sname") if пункт_без_типа is not None else None
    имя_улицы = _винительный_в_именительный(имя_улицы)
    if пункт is not None:
        тип = (
            (пункт.group("stype") or пункт.group("stype3") or пункт.group("stype4"))
            .lower()
            .rstrip(".")
        )
        тип_пункта = _ПУНКТ_КАНОН.get(тип, "город" if тип in ("г", "город") else тип)
        имя_пункта = (
            пункт.group("sname") or пункт.group("sname3") or пункт.group("sname4")
        ).strip()
        # «п. Сосновка ул Лесная»: имя пункта захватило улицу — режем на типе.
        внутри = re.search(r"\s(" + _ТИП_УЛИЦЫ_ТОЛЬКО + r".*)$", имя_пункта, re.IGNORECASE)
        if внутри is not None and not имя_улицы:
            имя_улицы = " ".join(внутри.group(1).split())
            имя_пункта = имя_пункта[: внутри.start()].strip()
    found = Found(
        street=имя_улицы,
        house="",
        raw=text[start:end] if "\n" not in text[start:end] else рабочий[start:end],
        start=start,
        end=end,
        level=LEVEL_A,
        kind=KIND_PLACE,
        parts=части,
        settlement=имя_пункта,
        settlement_type=тип_пункта,
        locality=(
            город_словами.group("sname").strip()
            if город_словами is not None
            else город_объявлений.group("city")
            if город_объявлений is not None
            else None
        ),
        district=район.group(0).strip() if район is not None else None,
        area=_массив_словами(массив) if массив is not None else None,
    )
    # Класс 12: судится имя, которое ушло бы в `settlement`, — уже без улицы
    # («п. Сосновка ул Лесная») и после выбора между городом и пунктом. Форма
    # снимается целиком (договор 7a §B.1), не пересобирается без пункта.
    if пункт is not None and имя_пункта and _имя_пункта_речь(имя_пункта):
        return under_rule(rules, STOP_TYPED_PLACE_SPEECH, old=found, new=None)
    return found


#: Тип пункта, как его пишут В АДРЕСЕ: именительный падеж и сокращения.
#: «деревни», «станицы» регэксп `_ПУНКТ_ТИПЫ` принимает ради «ул Ленина 5,
#: деревни Малиновка» рядом с улицей; отдельной репликой это речь: «еду из
#: деревни Малиновка». Положительный список, а не «кроме родительного».
_ТИП_ПУНКТА_ИМЕНИТЕЛЬНЫЙ = frozenset(
    "деревня дер д село с посёлок поселок пос п пгт станица ст хутор аул г город".split()
)
#: Предлог, после которого пункт — откуда/докуда/возле, а не где живёт клиент:
#: «из д. Малиновка», «до п. Ударник», «около д. Малиновка». «в» намеренно НЕ
#: здесь: «живу в д. Малиновка» — это и есть адрес.
_ПРЕДЛОГ_НЕ_АДРЕСА = frozenset("из до от мимо около возле у с со за через после".split())


def place_stated_as_address(text: str, found: Found) -> bool:
    """Пункт с типом назван КАК АДРЕС, а не в речи (N13, 19.09): тип в
    именительном падеже («деревня Малиновка», «д. Малиновка», «С. Поселье»),
    перед ним нет предлога движения/положения («из д. Малиновка») и частицы
    «не» в двух ближайших словах («это не посёлок Ударник»). Для `found` от
    :func:`parse_place` с `settlement`; пункт без типа (имя перед улицей) — False.
    Контрпримеры, которые ОБЯЗАНЫ проходить: «нет, деревня Малиновка» (частица
    «нет», не «не»), «деревня Малиновка, а не Ударник» («не» после, не перед),
    «живу в д. Малиновка», «в посёлок Ударник»."""
    if not found.settlement:
        return False
    рабочий = (text or "").replace("\n", " ")
    for m in _МЕСТО_ПУНКТ.finditer(рабочий):
        имя = (m.group("sname") or m.group("sname3") or m.group("sname4") or "").strip()
        if имя != found.settlement:
            continue  # район и город словами имени пункта не дают
        тип = (m.group("stype") or m.group("stype3") or m.group("stype4") or "").lower().rstrip(".")
        if тип not in _ТИП_ПУНКТА_ИМЕНИТЕЛЬНЫЙ:
            return False
        перед = re.findall(r"[а-яё]+", рабочий[: m.start()].lower())[-2:]
        if "не" in перед:
            return False
        return not (перед and перед[-1] in _ПРЕДЛОГ_НЕ_АДРЕСА)
    return False


#: Улица с типом без дома: «улица 65 лет Победы», «ул. Горького», «Проспект
#: 70 лет октября», «2 бульварный проезд» — тип спереди или сзади.
#: Только типы УЛИЦ (без пунктов и товариществ — те ловит массив/пункт).
#: ⚠ ТОЛЬКО ИМЕНИТЕЛЬНЫЙ ПАДЕЖ И СОКРАЩЕНИЯ, БЕЗ `\w*` (ревью 13.09): «на улице
#: дождь», «перейти улицу», «трактор», «проспали», «телефонная линия» — речь.
#: В адресе без дома тип стоит в именительном: «улица Зеленогорская», «ул.
#: Горького», «Невский проспект».
_ТИП_УЛИЦЫ_ТОЛЬКО = (
    r"(?:улица|ул\.?|пр-?кт\.?|проспект|пр\.?|пер\.?|переулок|ш\.?|шоссе|"
    r"б-р|бульвар|набережная|наб\.?|проезд|линия|тракт|аллея|тупик|туп\.?)(?![а-яё])"
)
_ТИП_УЛИЦЫ_СЛОВОМ = (
    r"(?:улица|проспект|переулок|шоссе|бульвар|набережная|проезд|аллея|тупик|тракт)(?![а-яё])"
)
#: Сокращения, которых в речи не бывает («ул.», «пр.», «пер.», «б-р», «наб.»):
#: после них название берётся и строчными — «на пр юрия гагарина», «балашиха,
#: ул. карла маркса» (стенд 13.09). Полное слово («улица какая») — нет.
#: «и пр. мелочи» — «прочее», не проспект: после «и» сокращение не тип. «пр»
#: без точки — только с названием из двух слов и больше: «пр подключени»,
#: «пр нтер» (стенд 13.09, 7 дней) — обрывки речи, «пр юрия гагарина» — проспект.
#: «2 ш. ножки» — штуки, не шоссе: «ш.» после числа не тип. «пр.» с точкой —
#: тоже «прочее» («выключатели, пр. мелочи»): идёт по ветке с окончанием имени.
_ТИП_УЛИЦЫ_СОКРАЩЁННО = (
    r"(?<![иИ]\s)(?:ул\.?|пр-?кт\.?|пер\.?|б-р|наб\.?|(?<!\d)(?<!\d\s)ш\.)(?![а-яё])"
)
#: …и только там, где стоит адрес: в начале, после запятой, «на», «по»,
#: «адрес» — «цена пр замене платы», «пр включении гудит» (ревью 13.09) —
#: обрубки «при».
#: «пр» без точки — только после «на/по/адрес» и с двумя словами имени
#: («на пр юрия гагарина»); «пр этой цене», «пр большой нагрузке» — обрубки
#: «при» (ревью 13.09). «пр.» с точкой — по ветке с окончанием имени.
_ПР_БЕЗ_ТОЧКИ = r"(?<![иИ]\s)пр\.(?![а-яё])|(?<=\bна )пр(?=\s+[а-яё]{4,}\s+[а-яё]{2,})(?![а-яё.])"
#: Окончание имени у последнего слова («гагарина», «строителей», «науки»,
#: «ленинский»); «ул ыбка», «ул етела» — обрывки: слово не начинается с ы/ь/ъ/й.
_ОКОНЧАНИЕ_ИМЕНИ = r"(?:а|я|ой|ого|его|ых|их|ый|ий|ая|ое|ей|ов|ев|и|ы)(?![а-яё])"
#: Строчное название после сокращения: до трёх слов от четырёх букв, последнее
#: — с окончанием имени; «пр включении гудит», «пр. мелочи» — речь (ревью 13.09).
_НАЗВАНИЕ_СТРОЧНЫМИ = (
    r"(?![ыьъй])(?:[а-яё]{4,}\s+" + _НЕ_ХВОСТ_НАЗВАНИЯ + r"){0,2}"
    r"(?![ыьъй])[а-яё]{2,}" + _ОКОНЧАНИЕ_ИМЕНИ
)
_НАЗВАНИЕ_СТРОЧНЫМИ_ДВА = _НАЗВАНИЕ_СТРОЧНЫМИ
#: Название улицы без дома: первое слово с заглавной (или число: «65 лет
#: Победы», «8 марта»), следующие — тоже с заглавной или «лет/года/имени»:
#: «Горького она сама встретит» → «Горького»; «улица какая» — не улица.
_НАЗВАНИЕ_УЛИЦЫ = (
    r"(?:(?:\d{1,3}(?:\s?-?[еяй])?\s*(?:лет\s+|года\s+)?)?"
    r"(?-i:[А-ЯЁ])[а-яё]+(?:-(?-i:[А-ЯЁ])?[а-яё]+)?"
    # «спасо-тушинский бульвар» (стенд 13.09): составное через дефис —
    # название и строчными; «где-то», «кое-что» короче трёх букв с краю.
    r"|[а-яё]{3,}-(?!нибудь|либо|таки|(?:то)(?![а-яё]))[а-яё]{3,}"
    r"|\d{1,3}\s+[а-яё]{3,})"
    r"(?:\s+(?:лет|года|имени|им\.?|(?-i:[А-ЯЁ])[а-яё]+(?:-[А-ЯЁа-яё][а-яё]+)?)){0,2}"
)
#: Тип сзади — только полным словом («8 марта улица», «Невский проспект»):
#: «Королёве ул.» с «ул» сзади — город и обрывок, не улица.
_УЛИЦА_БЕЗ_ДОМА = re.compile(
    r"(?<![А-ЯЁа-яё])(?:"
    + r"(?P<порядок>\d{1,3}-?[еяй]\s+)?(?P<тип1>"
    + _ТИП_УЛИЦЫ_ТОЛЬКО
    + r")\s*\.?\s*"
    + _НАЗВАНИЕ_УЛИЦЫ
    # «в Хабаровске улица Чкалова» (стенд 14.09): слово после предлога — не
    # имя перед типом; поиск идёт дальше и берёт «улица Чкалова».
    + r"|(?<!\bв )(?<!\bво )(?<!\bна )(?<!\bиз )(?<!\bпо )"
    + _НАЗВАНИЕ_УЛИЦЫ
    + r"\s+(?P<тип2>"
    + _ТИП_УЛИЦЫ_СЛОВОМ
    + r")"
    + r"|(?P<тип3>"
    + _ТИП_УЛИЦЫ_СОКРАЩЁННО
    + r")\s*\.?\s*(?-i:"
    + _НАЗВАНИЕ_СТРОЧНЫМИ
    + r")"
    + r"|(?P<тип4>"
    + _ПР_БЕЗ_ТОЧКИ
    + r")\s*(?-i:"
    + _НАЗВАНИЕ_СТРОЧНЫМИ_ДВА
    + r")"
    + r")(?![а-яё])(?![\s,.\-]*(?:д\.?|дом\.?)?\s*№?\s*\d)",
    re.IGNORECASE,
)


def house_only(text: str) -> str | None:
    """Реплика, которая целиком — номер дома: «дом 17», «д.16», «17 дом»,
    «номер 8», «Улицы нет дом 226». Продолжение места, названного раньше
    (владелец 13.09: «адрес постепенно»)."""
    m = _ТОЛЬКО_ДОМ.match(text or "")
    if m is None:
        return None
    return " ".join((m.group("bld") or m.group("bld2") or m.group("bld3")).split())


def house_phrase(text: str) -> str | None:
    """Кусок реплики с домом как написан: «д.16», «дом номер 12» — для цитаты."""
    m = _ТОЛЬКО_ДОМ.match(text or "")
    return m.group("head").strip() if m is not None else None


def area_as_street(area: str) -> str:
    """Массив как улица дома: «мкр 10» → «10 мкр», как пишет `parse` для
    «мкр 10 д 15» — иначе один дом получал бы два ключа (ревью 13.09)."""
    m = re.fullmatch(r"(?i)(мкр|мкрн|микрорайон|квартал)\.?\s*№?\s*(\d{1,3})", area.strip())
    return f"{m.group(2)} {m.group(1).lower()}" if m else area.strip()


_НОМЕР_ДОМА = (
    r"\d{1,3}(?:\s?[а-я](?![а-яё]))?(?:\s*/\s*\d{1,3}[а-я]?)?"
    r"(?:[\s,]*(?:к|корп\.?|корпус|стр\.?|строение)\s*\d{1,2})?"
)
_ТОЛЬКО_ДОМ = re.compile(
    r"^\s*(?:улицы\s+нет[\s,]*)?(?:это\s+)?(?P<head>"
    # «дом 17», «д.16», «дом номер 12», «дом №12», «дом 12/2», «дом 12, корпус 2».
    r"(?:дом|д\.?)(?:\s*(?:номер|№))?\s*(?P<bld>" + _НОМЕР_ДОМА + r")"
    r"|(?P<bld2>\d{1,3}(?:\s?[а-я](?![а-яё]))?)\s*(?:-?й|-?ый)?\s+дом"
    # «номер 8» — только сама по себе: «номер 2 подъезд» — ответ про подъезд (ревью 13.09).
    r"|(?:номер|№)\s*(?P<bld3>" + _НОМЕР_ДОМА + r")(?=\s*[.!]?\s*$))"
    # «дом 17, кв 36, подъезд 4» — части после дома не мешают; «дом 120 кв м» — площадь.
    r"\s*[.!]?(?:[\s,;]+(?:кв\.?(?!\s*\.?\s*м(?![а-яё]))|квартира|под\.?|подъезд|эт\.?|этаж|"
    r"домофон|код)(?![а-яё]).*)?\s*$",
    re.IGNORECASE | re.DOTALL,
)

#: ЧТО ТАКОЕ ДОМ — ОДНИМ СЛОВОМ НА ВЕСЬ ПРОЕКТ (ревью 19.09). Дом рождается
#: двумя головами: `_ДОМ` у невода («5», «5а», «17/2», «5к2», «3 стр 1») и
#: `_НОМЕР_ДОМА` у реплики «дом N» («12, корпус 2», «12/2а», «12, стр 3»);
#: модель-читатель пишет дом в тех же формах. Сторож «слово клиента — дом»
#: (точка улицы и массива в `geocode`, ответ модели) обязан принимать ОБЕ
#: головы, иначе дом, законно рождённый одной, режется сторожем по другой:
#: «12, корпус 2» из `house_only` не проходил `_ДОМ`, и строка теряла точку.
#: Латинская техника («4G», «4K», «3D») и числа от четырёх цифр («1000») —
#: не дом ни по одной голове.
_НОМЕР_ДОМА_ЛЮБОЙ_ГОЛОВОЙ = re.compile(r"(?:" + _ДОМ + r")|(?:" + _НОМЕР_ДОМА + r")", re.IGNORECASE)


def is_house_number(text: str | None) -> bool:
    """Слово клиента — номер дома в одной из канонических форм проекта
    (:data:`_НОМЕР_ДОМА_ЛЮБОЙ_ГОЛОВОЙ`); пробелы схлопываются, как у
    :func:`house_only`. Пусто — не дом."""
    return _НОМЕР_ДОМА_ЛЮБОЙ_ГОЛОВОЙ.fullmatch(" ".join((text or "").split())) is not None


def _массив_словами(m: re.Match[str]) -> str:
    """«10 мкр» → «мкр 10»: как пишет карта; остальное — как написано."""
    if m.group("anum"):
        return f"{m.group('atype2').lower()} {m.group('anum')}"
    return " ".join(m.group(0).split())


def street_core(street: str | None) -> tuple[str, ...]:
    """Слова улицы без типа, служебных слов и регистра — то, что делает улицу
    ЭТОЙ улицей: «ул. Некрасова», «Некрасова», «сектор Улица Лесная» →
    («некрасова»,), («лесная»,). Один адрес — одна строка (бой 13.09:
    по две строки на карточку из-за «ул.», регистра и «сектор»)."""
    слова = [
        w.lower().replace("ё", "е") for w in re.split(r"[^0-9a-zа-яёA-ZА-ЯЁ]+", street or "") if w
    ]
    ядро = tuple(
        w
        for w in слова
        if w not in _ТИПЫ_УЛИЦЫ and w not in _НЕ_НАЗВАНИЕ_УЛИЦЫ and w not in _НЕ_УЛИЦА
    )
    # У улицы из одного типа («микрорайон», «Набережная 7») тип и есть имя.
    return ядро or tuple(
        w for w in слова if w in _ТИПЫ_УЛИЦЫ or w in ("микрорайон", "мкр", "квартал")
    )


def street_type(street: str | None) -> str | None:
    """Полный тип улицы, если он назван: «ул. Ленина» → «улица», «пр Мира» →
    «проспект»; без типа — None."""
    from app.services.geocode import _ТИПЫ_УЛИЦ

    for w in re.split(r"[^0-9a-zа-яёA-ZА-ЯЁ-]+", street or ""):
        ключ = w.lower().replace("ё", "е").rstrip(".")
        if ключ in _ТИПЫ_УЛИЦ:
            return _ТИПЫ_УЛИЦ[ключ]
    return None


def same_address(
    a_street: str | None, a_house: str | None, b_street: str | None, b_house: str | None
) -> bool:
    """Одно место, написанное по-разному: ядро улицы и ключ дома совпали, а
    тип, если назван у обеих, — один («ул Ленина» и «проспект Ленина» — разные)."""
    from app.services.geocode import house_key

    ядро = street_core(a_street)
    if not ядро or ядро != street_core(b_street) or house_key(a_house) != house_key(b_house):
        return False
    тип_a, тип_b = street_type(a_street), street_type(b_street)
    return тип_a is None or тип_b is None or тип_a == тип_b


def quote_holds(found: Found, text: str) -> bool:
    """Сторож цитаты: разбор обязан находиться в исходном тексте.

    ⚠ СВЕРЯЕМ ПО СЛОВАМ ВНУТРИ ВЫРЕЗАННОГО КУСКА, А НЕ УЛИЦУ ПОДСТРОКОЙ. Улица
    ПЕРЕСОБИРАЕТСЯ из трёх групп («тип + название + тип»), и знаки препинания
    по дороге теряются: из «ул.Ленина 5» получается улица «ул Ленина», которой
    в тексте нет ни одной подстрокой. Первая редакция сверяла именно так — и
    боевой перезамер дал 118 несовпадений из 6 396 на совершенно правильных
    разборах. Кусок `raw` — литеральный срез сообщения, и слова в нём лежат
    ровно так, как их написал человек.

    ⚠ ПРОВЕРЯЕТСЯ И УЛИЦА, И ДОМ. Первая редакция сверяла лишь цифры дома по
    одной, то есть подмену В НАЗВАНИИ пропускала, — а именно она и есть самая
    дорогая ошибка: «Кировградская» вместо «Кировоградской» ведёт мастера на
    другую улицу с тем же номером дома.

    ⚠ ЗАЧЕМ ОН НУЖЕН, ЕСЛИ ПРАВИЛА НЕ ВЫДУМЫВАЮТ. Правила действительно не
    выдумывают по построению. Сторож стоит на будущее — на тот случай, если
    разбор станут дополнять языковой моделью: та подставляет букву с
    уверенностью единица, и её собственная проверка этого не ловит.
    """
    if found.kind == KIND_PLACE:
        return bool(found.raw) and re.sub(r"\s+", " ", found.raw) in re.sub(r"\s+", " ", text or "")
    if (not found.street and not found.settlement) or not found.house or not found.raw:
        return False
    # Кусок обязан находиться в переданном тексте. Для исходного сообщения это
    # верно по построению, а вот для ЧУЖОГО текста — уже проверка: ею и ловится
    # разбор, приложенный не к тому сообщению.
    ровно = re.sub(r"\s+", " ", text or "")
    if re.sub(r"\s+", " ", found.raw) not in ровно:
        return False
    кусок = found.raw.lower()
    # Пункт из соседней реплики склеивается с адресом через «; » («Каркатеевы;
    # 7.10.34», `inbound.с_пунктом_контекста`): формы города, привязанные к
    # началу или всей строке, сверяются по хвосту склейки — иначе клиент,
    # назвавший сначала пункт, терял строку вовсе (ревью 20.09, #11).
    хвост = found.raw.rsplit("; ", 1)[-1]
    слова = [w for w in re.split(r"[^0-9a-zа-яё]+", found.street.lower()) if w]
    if found.street == "корпус" and re.match(r"(?i)\s*(?:к\.?|корп\.?|корпус)\s?\d", хвост):
        # Зеленоград: «К.418», «к317» — слово «корпус» дописано разбором по
        # городу, клиент писал «к.» (ревью 15.09: без этого строка не
        # проходила сторож цитаты и на живом пути не заводилась).
        слова = []
    if (found.street.endswith(" мкр") and _МКР_ДОМ_КВ.match(хвост)) or (
        found.street.endswith((" мкр", " квартал"))
        and (
            _ПАРА_КВАРТАЛ.fullmatch(хвост)
            or _ПАРА_КВАРТАЛ_КВ.fullmatch(хвост)
            or _МКР_ДОМ_КВ_ТОЧКИ.match(хвост)
        )
    ):
        # «14а- 76-21», «86-11», «93 кв,31», «7.10.34»: слово «мкр»/«квартал»
        # дописано разбором по городу, клиент его не писал.
        слова = [w for w in слова if w not in ("мкр", "квартал")]
    if found.street.endswith(" комплекс") and _ПАРА_КОМПЛЕКС.fullmatch(хвост):
        # «38/07» (Набережные Челны): «38-й комплекс» дописан разбором по
        # городу, клиент писал только пару; дом «7» — из «07».
        слова = []
    # «ул. Солнечную» → «ул. Солнечная»: имя выпрямлено из винительного
    # (`_винительный_в_именительный`), в цитате оно стоит как написано.
    if not all(w in кусок or _в_винительном(w) in кусок for w in слова):
        return False
    # Пункт живёт в цитате: он вошёл в `raw` при разборе, и подменить его
    # молча нельзя — по нему карта выбирает между четырьмя улицами Ленина.
    if found.settlement and found.settlement.lower() not in кусок:
        return False
    # Город клиента в цитату не входит (он может стоять далеко от адреса),
    # но обязан быть в самом тексте.
    if found.locality and found.locality.lower() not in ровно.lower():
        return False
    дом = found.house.replace(" ", "").lower()
    if дом in кусок.replace(" ", ""):
        return True
    # Корпус за частями («7, кв 41, 1 корпус», «5, подъезд 2, корпус 3»): в
    # цитате он стоит отдельно от дома, а в доме — как «7 корпус 1».
    корпус_отдельно = re.fullmatch(r"(?P<h>.+?)корпус(?P<n>\d{1,2})", дом)
    if корпус_отдельно is None or корпус_отдельно.group("h") not in кусок.replace(" ", ""):
        return False
    n = корпус_отдельно.group("n")
    # «42, к 1» — корпус через запятую голой «к»; «первый корпус» — словом
    # (владелец 18.09): в цитате число стоит не цифрой.
    словом = next((k for k, v in _ПОРЯДОК.items() if v == n), None)
    return (
        re.search(rf"(?<!\d){n}\s*корп", кусок) is not None
        or re.search(rf"(?:корп[а-яё.]*|(?<![а-яё])к\.?)\s*{n}(?!\d)", кусок) is not None
        or (
            словом is not None
            and re.search(rf"(?<![а-яё]){словом}[а-яё]*\s*корп", кусок) is not None
        )
    )
