_ЯВНЫЙ_ДОМ = re.compile(r"(?:^|[\s,.\-])(?:д\.?|дом\.?)\s*№?\s*\d", re.IGNORECASE)
#: Слово строчными после имени пункта с заглавной — улица, если оно выглядит
#: улицей: прилагательное («центральная», «парковая», «молодежая») или тип
#: улицы («проезд», «дорога»). «Крамный холм», «Солнечная поляна», «Клеверная
#: бухта» — двусловные имена пунктов, их второе слово улицей не бывает
#: (корпус Jivo, 15.09).
_УЛИЦА_ПРИЛАГАТЕЛЬНЫМ = re.compile(r"^[а-яё-]{3,}(?:ая|яя|ое|ее|ый|ий|ой)$")


def _хвост_имени_это_улица(слова: list[str]) -> int:
    """Сколько последних слов имени пункта — улица: 0, 1 («Отрадное майская»)
    или 2 («Голубово Южный проезд», «Кембридж Шотландский бульвар»)."""
    if len(слова) < 2 or not слова[0][0].isupper():
        return 0
    if any(w.lower().rstrip(".") in _ПУНКТ_КАНОН for w in слова[1:-1]):
        # «Посёлок Строитель микрорайон центральный» — тип внутри имени:
        # хвост принадлежит ему, а не улице.
        return 0
    последнее = слова[-1].lower()
    if последнее in _ТИПЫ_УЛИЦЫ or последнее == "дорога":
        if len(слова) >= 3 and _УЛИЦА_ПРИЛАГАТЕЛЬНЫМ.match(слова[-2].lower()):
            return 2
        return 0
    if слова[-1][0].islower() and _УЛИЦА_ПРИЛАГАТЕЛЬНЫМ.match(последнее):
        return 1
    return 0


#: Прилагательное с существительным одного рода — одно двусловное имя
#: («Красная Горка», «Новое Павлино», «Зелёная Роща»), а не имя и улица.
#: Множественное число — тоже («Белые Росы», «Новые Черёмушки», «Зелёные
#: Горки»): без него «мкр Белые Росы 5» резалось на микрорайон «Белые» и
#: улицу «Росы» (ревью 18.09). Родительный («Первого Мая») сюда не берём: он
#: неотличим от «Дзержинского Ленина» — микрорайон и улица.
_ИМЯ_ИЗ_ДВУХ_СЛОВ = (
    (re.compile(r"(?:ая|яя)$"), re.compile(r"[ая]$|ь$")),
    (re.compile(r"(?:ый|ий|ой)$"), re.compile(r"[бвгджзклмнпрстфхцчшщ]$|й$|ь$")),
    (re.compile(r"(?:ое|ее)$"), re.compile(r"[ое]$")),
    (re.compile(r"(?:ые|ие)$"), re.compile(r"[ыиа]$")),
)


def _улица_после_имени_массива(слова: list[str]) -> int:
    """Сколько последних слов имени микрорайона — улица без типа: «авиаторов
    Сидорова» → 1, «Северный Карла Маркса» → 2, «Красная Горка» → 0.

    Имя микрорайона — одно слово или прилагательное с существительным
    («Красная Горка»); всё, что после него с заглавной, — улица. «Гагарина
    Ленина» (два родительных подряд) — микрорайон Гагарина, улица Ленина.
    """
    if len(слова) < 2 or not слова[-1][0].isupper():
        return 0
    первое, второе = слова[0].lower(), слова[1].lower()
    согласованы = any(adj.search(первое) and noun.search(второе) for adj, noun in _ИМЯ_ИЗ_ДВУХ_СЛОВ)
    имя = 2 if согласованы and len(слова) >= 3 else 1
    if согласованы and len(слова) == 2:
        return 0
    return len(слова) - имя


