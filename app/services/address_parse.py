"""Разбор адреса из текста сообщения — без базы, без сети, без настроек.

Устроен как соседний :mod:`app.services.phone_parse` и по той же причине: одна
реализация обслуживает три места (приём входящего, поле карточки, пересчёт по
истории). Разъехавшись, копии дают карточке два разных ответа на вопрос «что мы
вычитали», и разница видна не сразу.

⚠ ГЛАВНОЕ ПРАВИЛО ТО ЖЕ, ЧТО У ТЕЛЕФОНА: ЛУЧШЕ ПРОПУСТИТЬ, ЧЕМ ПРИДУМАТЬ. Цена
ошибки здесь даже выше: неверно распознанный номер стоит звонка постороннему, а
неверно распознанный адрес — выезда мастера не туда, то есть потерянного дня
бригады и клиента, который ждал. Поэтому распознанное НИКОГДА не пишется в
карточку молча (решение владельца от 12 августа) и показывается как ЦИТАТА
клиента, а не как проверенный факт: проверять «существует ли такой дом» нам
нечем (разбор — в решении по ГАР от 09.09).

⚠ ПРАВИЛА ВЗЯТЫ ИЗ ЛИД-БОТА, А НЕ ПРИДУМАНЫ ЗАНОВО. Там они обкатаны на живом
трафике той же компании и той же предметной области (выездной ремонт техники), и
каждый запрет в них — след настоящего промаха: «шкаф 90/90/208» становился
адресом, «Самсунг 12 лет» тоже, а «12-я линия В.О.» адресом не считалась.
Переписывать это с нуля значило бы пройти тот же путь ошибок второй раз.
Источник: ``brain/server.py`` лид-бота, строки 1433–1601 и 3460–3760.

⚠ ТРИ УРОВНЯ УВЕРЕННОСТИ, И ЭТО НЕ УКРАШЕНИЕ. У лид-бота широкий невод
«Название Число» работает только рядом с вопросом бота об адресе: без контекста
он даёт половину ложных («Диагональ 55», «Виндоус 10», «Хайер 32»), с контекстом
— 5 %. В LeadChat бота-спрашивающего нет, поэтому контекст другой, и уровни
разведены явно:

* ``A`` — в тексте есть слово-тип («ул.», «проспект», «дом 12»). Контекст не
  нужен: на корпусе лид-бота это 94,5 % точности само по себе;
* ``B`` — широкий невод И признак разговора об адресе: клиент сам сказал
  «адрес», «живу», «нахожусь», либо оператор спросил;
* ``C`` — широкий невод без всякого контекста. Тот самый случай с половиной
  ложных.

⚠ ЗАМЕР НА БОЮ 09.09 ПЕРЕВЕРНУЛ ОЖИДАНИЕ ОТ УРОВНЯ B. За 30 дней: 107 828
входящих от клиентов, разбор сработал 6 396 раз (5 %). Из них уровень A — 3 613
находок в 3 355 диалогах, уровень C — 2 619, а уровень **B всего 164**, то есть
2,6 % находок. Причина видна, стоит её назвать: у лид-бота контекст даёт почти
всё, потому что бот спрашивает адрес САМ и по скрипту; в LeadChat адрес никто
по скрипту не спрашивает, и признак «разговор об адресе» просто не встречается.

Отсюда решение: показываем уровень A, он один стоит 3 355 диалогов в месяц.
Уровни B и C остаются за настройкой и по умолчанию молчат — городить вокруг 164
находок отдельную оговорку на экране незачем.

Вместе с адресом разбор приносит его части: квартира 1 888 раз, подъезд 871,
этаж 649, домофон 108.

Сторож цитаты на этом прогоне не сошёлся НИ РАЗУ из 6 396 — правила выдумывать
не умеют по построению.

⚠ ПЕРВЫЕ ЧИСЛА ЭТОГО ЗАМЕРА БЫЛИ ПОЛУЧЕНЫ СЛОМАННЫМ РАЗБОРОМ, и это стоит
помнить, читая любой замер. Разбор своей же правки нашёл семь потерянных при
переносе правил (правая граница типа, стоп-списки на пути A, выбор головы, хвост
по остатку и три помельче). До их починки числа были 6 529 / 3 668 / 174 / 2 687
при трёх несовпадениях цитаты — то есть похожими настолько, что подмены в них
было не разглядеть. Замер подтверждает объём работы, но не её правильность.

⚠ МОДУЛЬ ПОКА НИКЕМ НЕ ЗОВЁТСЯ, И ЭТО ОСОЗНАННЫЙ ШАГ, А НЕ ЗАБЫТЫЙ ХВОСТ.
В этом проекте есть беда «написано, но не подключено», поэтому сказано прямо:
здесь закончен ПЕРВЫЙ шаг плана (чистый разбор плюс замер, которым решают,
стоит ли продолжать). Дальше по плану — модель и миграция, приём входящего,
ручка, поле карточки. Пока их нет, разбор ничего не меняет ни на одном экране.
"""

