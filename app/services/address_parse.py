#: 13.09 по 30 дням боя: 132 реплики с перепутанными подъездом и этажом).
#: Люди пишут в одном из двух порядков — «подъезд 3, этаж 4» (слово, число)
#: или «3 подъезд, 4 этаж» (число, слово) — и внутри одной цепочки порядок не
#: меняют. Образец «слово число» на «3 подъезд 17 этаж 314 кв» брал подъезд
#: «17», а образец «число слово» на «квартира 12 подъезд 3» — подъезд «12».
#:
#: Цепочка — ряд, где слова частей и числа чередуются: «кв 58» и «2 подъезд
#: 9 этаж» в «кв 58, 2 подъезд, 9 этаж» — две цепочки (два числа подряд
#: рвут ряд), и у каждой свой порядок: начинается со слова — число ПОСЛЕ
#: слова, начинается с числа — число ПЕРЕД словом. Чужое слово («со стороны
#: двора») тоже рвёт цепочку. «дом»/«д.» и «корпус»/«к.» участвуют в ряду —
#: их число принадлежит дому, а не части, — но части не дают.
#: Граница слова части — по буквам, а не `\b`: «2подьезд», «5подьезд», «9кв»
#: пишут слитно, и между цифрой и буквой границы слова нет. Хвост слова —
#: буквы, а не `\w`: «подъезд3» — слово и число, не одно слово. Чужое слово
#: забирает приросшие цифры («Янино1», «ст1», «э21», «l210») — это не числа
#: частей. Время («12:00», «13.00», «часов 11», «до 12», «к 16») — не число.
#: Число ПОСЛЕ предлога — часть, только если слово части стоит в косвенном
#: падеже: «в 3 подъезде», «к 3 подъезду», «с 2 подъезда», «на 5 этаже»;
#: «на 3 этаж», «в 3 подъезд» — полным словом; «в 14 кв 7» — время (ревью 13.09).
_ЧАСТЬ_В_ПАДЕЖЕ = (
    r"(?=\s*(?:по[дж][ъь]?езд[аеу]?|этаж[аеу]?|квартир[аеуы]|парадн(?:ой|ую|ая))(?![а-яё]))"
)
_ЗВЕНО = re.compile(
    r"(?P<time>(?<![\d])\d{1,2}[:.]\d{2}(?![\d]))"
    # «6 кв м», «20 кв.м» — площадь, не квартира; «квартира 3 комнатная» —
    # комнаты, не номер (ревью 13.09).
    r"|(?P<office>(?<![а-яё])(?:кв(?:\.(?!\s?м(?![а-яё]))|(?![а-яё.]))(?!\s?м(?![а-яё]))"
    r"|квартир[а-яё]{0,2}(?![а-яё])|офис[а-яё]{0,2}(?![а-яё])|оф\.?(?=\s?\d)|пом\.(?=\s?\d))"
    r"(?!\s*\d{1,2}(?:\s*-?\s*х)?\s*комнатн))"
    # «подьезд», «подьез», «подез» — опечатки боя; «п6», «п. 2» — подъезд числом,
    # «3 п.» — числом перед; «т.п.» — не подъезд. Только существительное:
    # «подъезжайте», «подъезжать» — речь о времени.
    r"|(?P<entrance>(?<![а-яё])(?:по[дж][ъь]?езд[а-яё]{0,2}(?![а-яё])|под[ъь]?ез(?![а-яё])"
    r"|под\.|(?<!т\.)(?<!т\. )п\.?(?=\s?\d)|п\.(?=\s*(?:$|[,;]))|парадн[а-яё]{0,2}(?![а-яё])"
    # «1 под, 7 эт, кв.52» (Зеленоград, стенд 15.09): «под» и «эт» без точки —
    # часть, когда за ними знак или конец (предлог «под окном» так не стоит).
    r"|под(?=\s*(?:$|[,;]))))"
    # «этажка», «этажный», «этажерка» — не этаж.
    r"|(?P<floor>(?<![а-яё])(?:этаж(?:а|е|ом|у|и|ей|ах)?(?![а-яё])|эт\.(?![а-яё])|эт(?=\s?\d)"
    r"|эт(?=\s*(?:$|[,;]))))"
    r"|(?P<intercom>(?<![а-яё])домофон[а-яё]*)"
    r"|(?P<house>(?<![а-яё])(?:дом(?![а-яё])|д\.?(?=\s?\d)|корпус|корп\.?|к\.(?=\s*\d)"
    r"|стр\.?(?=\s*\d)))"
    # «третий подъезд», «на третьем этаже» — порядок словом (только подъезд и
    # этаж: «во второй квартире» — не номер квартиры).
    r"|(?P<ordinal>(?<![а-яё])(?:(?:перв|втор|четв[её]рт|пят|шест|седьм|восьм|девят|десят)"
    r"(?:ый|ой|ий|ая|ое|ом|ем|ого|его|ую|ые|ых|ым)|трет(?:ий|ья|ье|ьем|ьей|ьего|ьим|ью|ьи))"
    r"(?![а-яё])(?=\s*(?:по[дж][ъь]?езд|парадн|этаж)))"
    # Число после предлога — часть в косвенном падеже (см. _ЧАСТЬ_В_ПАДЕЖЕ).
    r"|(?P<num_p>(?<=\b[вкс] )\d{1,2}(?![\d])(?:\s?-\s?(?:м|ом|ем|й|ой|ый|ий)(?![а-яё]))?"
    + _ЧАСТЬ_В_ПАДЕЖЕ
    + r")"
    r"|(?P<num_na>(?<=\bна )\d{1,2}(?![\d])(?:\s?-\s?(?:м|ом|ем|й|ой|ый|ий)(?![а-яё]))?"
    + _ЧАСТЬ_В_ПАДЕЖЕ
    + r")"
    # «дом 64/5 подъезд» (владелец 18.09): хвост дроби перед словом части без
    # своего числа — это число части (голова дома дробь тут уже не берёт).
    r"|(?P<num_slash>(?<=/)" + _ХВОСТ_ДРОБИ_ЧАСТЬ + r")"
    # Число — не хвост дроби и дефиса («4/2», «93-97» — дом), не время («в 14»,
    # «к 15», «с 9 до 18»). Хвост порядка («2-й», «3-ий», «5-м») — часть числа.
    # Литера квартиры — одна буква, не начало слова: «кв41домофон» → 41.
    r"|(?P<num>(?<![\d/:])(?<!\d-)(?<!\bчас )(?<!\bчаса )(?<!\bчасов )(?<!\bчасам )(?<!\bдо )"
    r"(?<!\bпосле )(?<!\bоколо )(?<!\bк )(?<!\bс )(?<!\bв )(?<!\bна )\d{1,4}(?![\d/:])(?!-\d)"
    r"(?:\s?-\s?(?:й|ой|ый|ий|ем|ом|м|ая|я|го|е)(?![а-яё])|[а-яa-z](?![а-яё\w]))?)"
    # Запятая, точка с пробелом, скобка — граница цепочки: «кв 5, 2 подъезд,
    # 4 этаж» — три цепочки по паре, каждая читается однозначно. Точка внутри
    # («кв .15», «50.7») границей не считается.
    r"|(?P<other>[^\W\d_]+\d*|[,;()]|\.(?=\s|$))",
    re.IGNORECASE,
)
_ПОРЯДОК = {
    "перв": "1",
    "втор": "2",
    "трет": "3",
    "четв": "4",
    "пят": "5",
    "шест": "6",
    "седьм": "7",
    "восьм": "8",
    "девят": "9",
    "десят": "10",
}


def _звенья(текст: str) -> list[tuple[str, str]]:
    """Ряд из (вид, значение): вид — имя части, `house`, `num` или `other`."""
    ряд: list[tuple[str, str]] = []
    for m in _ЗВЕНО.finditer(текст):
        вид = m.lastgroup or "other"
        значение = m.group(0)
        if вид == "time":
            вид = "other"
        elif вид in ("num_p", "num_na", "num_slash"):
            вид = "num"
        elif вид == "ordinal":
            вид = "num"
            значение = next(v for k, v in _ПОРЯДОК.items() if значение.lower().startswith(k))
        ряд.append((вид, значение))
    return ряд


def _цепочки(ряд: list[tuple[str, str]]) -> list[list[tuple[str, str]]]:
    """Разбить ряд на цепочки чередования «слово части ↔ число»."""
    цепочки: list[list[tuple[str, str]]] = []
    текущая: list[tuple[str, str]] = []
    for вид, значение in ряд:
        if вид == "other":
            if текущая:
                цепочки.append(текущая)
            текущая = []
            continue
        число = вид == "num"
        if текущая and (текущая[-1][0] == "num") == число:
            # Два числа или два слова подряд — новая цепочка.
            цепочки.append(текущая)
            текущая = []
        текущая.append((вид, значение))
    if текущая:
        цепочки.append(текущая)
    return цепочки


#: Сколько цифр бывает у части: подъезд и этаж — до двух, квартира — до четырёх.
_ЦИФР_У_ЧАСТИ = {"entrance": 2, "floor": 2, "office": 4}


def _прочитать(цепочка: list[tuple[str, str]], *, число_после: bool) -> dict[str, str] | None:
    """Пары «слово ↔ число» в одном порядке; `None` — так читать нельзя
    (этаж «140», подъезд «314»: число не того размера)."""
    parts: dict[str, str] = {}
    пары = range(len(цепочка) - 1)
    for i in пары:
        слово, число = (цепочка[i], цепочка[i + 1]) if число_после else (цепочка[i + 1], цепочка[i])
        if слово[0] == "num" or число[0] != "num":
            continue
        if слово[0] in ("house", "intercom") or слово[0] in parts:
            continue
        значение = число[1]
        if слово[0] != "office":
            значение = re.sub(r"[^\d]", "", значение)
        else:
            значение = re.sub(r"\s?-\s?[а-яё]+$", "", значение)  # «12-й» → 12
        if not значение or len(re.sub(r"[^\d]", "", значение)) > _ЦИФР_У_ЧАСТИ[слово[0]]:
            return None
        parts[слово[0]] = значение
    return parts


def _части(текст: str) -> dict[str, str]:
    parts: dict[str, str] = {}
    for цепочка in _цепочки(_звенья(текст)):
        if len(цепочка) < 2:
            continue
        # Порядок цепочки — по первому звену. Нечётная цепочка с числа и ОДНИМ
        # словом («2 кВ 29», «43 подъезд 10») — сначала как «слово число» без
        # первого числа: висячее число перед одной частью обычнее, чем после.
        # С двумя и больше словами («2 подъезд 4 этаж 2 телевизора») — числом
        # вперёд; чтение, где число не того размера (этаж «140» в «140А этаж 4
        # кв 29»), отбрасывается в пользу второго (ревью 13.09).
        со_слова = цепочка[0][0] != "num"
        слов = sum(1 for вид, _ in цепочка if вид != "num")
        одно_слово_с_числа = not со_слова and len(цепочка) % 2 == 1 and слов == 1
        порядок = [со_слова or одно_слово_с_числа, not (со_слова or одно_слово_с_числа)]
        for число_после in порядок:
            прочитано = _прочитать(цепочка, число_после=число_после)
            if прочитано is not None:
                for k, v in прочитано.items():
                    parts.setdefault(k, v)
                break
    м = _ДОМОФОН.search(текст)
    if м is not None:
        parts["intercom"] = м.group(1)
    return parts


