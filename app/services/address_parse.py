#: ⚠ «дом» СЛОВОМ УЛИЦЫ НЕ БЫВАЕТ. Без запрета «112 микрорайон дом 17» давало
#: улицу «112 микрорайон дом» и дом без номера.
#: Слово названия: обычное («Ленина») или АББРЕВИАТУРА заглавными («ДОС», «ЖБИ»,
#: «СНТ Заря») — кварталы военных городков и садоводства пишут так (12.09).
_БУКВЫ = (
    # Инициал — ТОЛЬКО заглавная (голова компилируется без учёта регистра):
    # «пр.Победы» давало улицу «р.Победы», «этаж.домофон» — «ж.домофон».
    # Слово части адреса названием не бывает и с заглавной: «Бульварная 14
    # Подъезд 2 Этаж 5» (стенд 13.09) давало тип «бульвар», улицу «14 Подъезд»
    # и дом 2 — а короткую голову «Бульварная 14» регекс уже не пробовал.
    # Только формы существительного: «Подъездная», «Этажная», «Парадная»,
    # «Литературная» — улицы (ревью 13.09).
    r"(?!(?:дом|дома|участок|стр|строение|по[дж][ъь]?езд?[а-яё]{0,2}|этаж[а-яё]{0,2}|кв|"
    r"квартир[а-яё]{0,2}|корпус|корп|код|домофон[а-яё]{0,2}|офис)\b)(?:(?-i:[А-ЯЁ])[.\s]\s?){0,2}"
    r"(?:[А-ЯЁа-яё][а-яё]{2,}|[А-ЯЁ]{3,}(?![а-яё]))"
    # «Машиностроитель-2», «ТЭЦ-3» — число через дефис часть названия, только
    # когда дальше стоит ещё число (дом); «Лермонтова-20» — дом (стенд 13.09).
    r"(?:-(?:[А-ЯЁа-яё][а-яё]+|\d{1,2}(?![\d])(?=[\s,.]*(?:д\.?|дом\.?|участок|уч\.?)?\s*№?\s*\d)))?"
)
#: «5ягодная» — число вплотную к названию (стенд 13.09): пробел не обязателен,
#: когда дальше слово от трёх букв (единицы «18м» — одна буква, не пройдут).
#: Голое число ПЕРЕД полным типом улицы — не приставка: «часов 11 улица
#: Зеленогорская 17/3» давало улицу «11 улица Зеленогорская» (бой 13.09,
#: Благовещенск). Приставка перед типом бывает только порядковой: «2-я улица
#: Строителей»; «11 линия», «5 Кольцевая», «2 Советская улица» — не трогаем.
#: Голое число (без «-я») — приставка только перед Именем с заглавной или
#: «лет/года» («5 Кольцевая», «50 лет Октября»); «к 11 звягинцева 7/2» (бой
#: 13.09) — время, и после «к/в/до/после/около/часов» число приставкой не бывает.
_ЧИСЛОВАЯ_ПРИСТАВКА = (
    # «квартира 12 ленина 5», «кв. 5 садовая 7» (ревью 14.09): число после слова
    # части — её номер, не приставка.
    r"(?:(?<![\d.,:])(?<![кКвВ]\s)(?<!до\s)(?<!после\s)(?<!около\s)(?<!часов\s)(?<!часам\s)"
    r"(?<!\bкв\s)(?<!\bкв\.\s)(?<!\bкв\.)(?<!квартира\s)(?<!\bэтаж\s)(?<!по[дж][ъь]езд\s)"
    r"(?<!домофон\s)(?<!\bкод\s)"
    r"\d{1,3}"
    r"(?:\s?-?[еяй]\s*(?=[А-ЯЁа-яё][а-яё]{2})"
    # «Ул 1 - Тихая , 43» (владелец 19.09, Астрахань): порядок через дефис С
    # ПРОБЕЛАМИ — без «-я» («1 - Тихая»), с отдельным «я» («2 - я Садовая»)
    # или «го» («3 - го Интернационала», «3-го Интернационала»). Без него
    # улицей становилась «Тихая», а в городе четыре Тихих, 43 — карта
    # отвечала «несколько». Только перед Именем с заглавной или строчным
    # прилагательным улицы: «10 - я дома» и «5-го числа» именем не бывают.
    # Время «с 10 - Ленина 7» отсекается предлогом перед числом.
    r"|(?<!\bс\s\d)(?<!\bс\s\d{2})(?<!\bс\s\d{3})(?<!\bсо\s\d)(?<!\bсо\s\d{2})"
    r"\s*-\s*(?:(?:[еяй]|го|ой|ый|ий|ая)(?![а-яё])\s*)?"
    r"(?=(?-i:[А-ЯЁ])[а-яё]{2}|[а-яё]{3,}(?:ая|яя|ская|ого|ова|ева|ина|ой|ий|ых)\s+\d)"
    # «5ягодная» — число вплотную к названию (стенд 13.09).
    r"|(?=[А-ЯЁа-яё][а-яё]{2})"
    # «3-луговой 26» — порядок через дефис без «-й» (стенд 13.09);
    # «2-комнатная 60», «3-х» — не улица.
    # Только «число-слово ДОМ»: «2-спальная кровать 160» — техника (ревью 13.09).
    r"|-(?!комнатн|этажн|местн|фазн|ярусн|канальн|скоростн|секционн|камерн|литров|"
    r"дюйм|метров|полосн|цветн|контурн|ступенч|тактн|ядерн|струйн|рядн|створч|дверн|"
    r"конфор|кратн|зонн|жильн|проводн|клавишн|кнопочн|программн|режимн|уровнев|слойн|"
    r"позиционн|сторонн|плит|спальн|полюсн|тарифн|х(?![а-яё]))"
    r"(?=[А-ЯЁа-яё][а-яё]{2,}[\s,.\-]*(?:д\.?|дом\.?)?\s*№?\s*\d)"
    r"|(?!\s*(?:улиц|просп|пр-кт|переул|шоссе|бульвар|набережн|площад|тракт|"
    r"проезд|аллея|тупик|б-р|(?:пер|наб|пл|ш)\.?(?![а-яё])))"
    r"\s+(?=(?-i:[А-ЯЁ])[а-яё]{2}|лет\s|года\s|лини[яи](?![а-яё])|квартал|просека|"
    r"микрорайон|микр(?![а-яё])|мкрн|мкр(?![а-яё])|мик(?![а-яё])"
    # «2 молодежная 36», «2 сормовская 59» (стенд 14.09): строчное имя с
    # окончанием улицы и дом следом — приставка и без заглавной.
    r"|[а-яё]{3,}(?:ая|яя|ская|ого|ова|ева|ина|ой|ий|ых)\s+\d"
    # «ул 9 мая 10», «пер 1 мая 5», «ул 3 интернационала 5» (проверка 24.09):
    # после ЯВНОГО типа улицы число с любым строчным словом — имя улицы. Так
    # пишут почти все, а без этой ветки тип и число терялись, улицей
    # становилось «мая», и карта ставила в карточку «ул 1 Мая» — чужой дом.
    # Ссылка на группу типа: приставка живёт только внутри `_ГОЛОВА`.
    r"|(?(тип1)[а-яё]{3,}))"
    # «16а мкр дом 5», «178а квартал 5» (ревью 18.09): номер массива с литерой
    # — приставка только перед типом массива, литера у улицы числом не бывает.
    r"|[а-яё](?![а-яё])\s+(?=квартал|микрорайон|микр(?![а-яё])|мкрн|мкр(?![а-яё])|мик(?![а-яё]))))?"
)

#: «5 ул дом 148», «3 линия д 12» (бой 13.09, Бурятия): число — имя улицы
#: («5-я улица»), когда за типом сразу явный «дом N». Без «дом» число перед
#: типом — время или чужое («часов 11 улица Зеленогорская»).
#: «13 проезд 6А» (стенд 15.09, Иваново): число перед типом — улица и без
#: слова «дом», если дальше сразу номер.
#: «92/93квартал,дом 6» (владелец 18.09, Ангарск): сдвоенный номер квартала
#: через дробь — имя, а не дом с корпусом.
_УЛИЦА_ЧИСЛОМ = (
    r"\d{1,3}(?:/\d{1,3})?\s*(?:-?[еяй])?\s*"
    r"(?:ул\.?|улица|лини[яи]|проезд|пер\.?|переулок|квартал|просека)"
    r"(?![а-яё])(?=[\s,.\-]*(?:д\.?|дом\.?)?\s*№?\s*\d)"
)
#: «2 фабричная 36а» сразу за городом объявления: число, слово строчными
#: от четырёх букв, дом.
_УЛИЦА_ЧИСЛОМ_СТРОЧНЫМИ = re.compile(
    r"[\s,.]*\d{1,2}(?:\s*-?\s*[яйе])?\s+[а-яё]{4,}(?:\s+[а-яё]{3,})?\s+\d{1,3}[а-яё]?(?![\d])"
)
#: Порядок с пробелами В ОБЕ СТОРОНЫ от дефиса в начале названия — одним
#: словом: «1 - Тихая» → «1-я Тихая», «2 - я Садовая» → «2-я Садовая»,
#: «3 - го Интернационала» → «3-го Интернационала». Иначе отдельное «я»
#: попадало в стоп-список речи и срезало всё до себя, а карта получала
#: «1 - Тихая» как есть. Без окончания у клиента род берётся у прилагательного
#: улицы; у существительного («Интернационала») окончание не выдумываем —
#: «3 Интернационала». Формы без пробелов («3-луговой», «1-я») и с одним
#: пробелом («3 -я») не трогаем: это ключи старых строк (стенд 13.09, корпус 12.09).
_ПОРЯДОК_С_ПРОБЕЛАМИ = re.compile(
    r"^(?P<n>\d{1,3})\s+-\s+(?:(?P<suf>я|й|е|го|ой|ый|ий|ая)(?![а-яё])\s*)?(?=[А-ЯЁа-яё])",
    re.IGNORECASE,
)


def _порядок_слитно(m: re.Match[str]) -> str:
    suf = (m.group("suf") or "").lower()
    if not suf:
        слово = m.string[m.end() :].split()[0].lower()
        if re.search(r"(?:ая|яя)$", слово):
            suf = "я"
        elif re.search(r"(?:ый|ий|ой)$", слово):
            suf = "й"
        elif re.search(r"(?:ое|ее)$", слово):
            suf = "е"
    return f"{m.group('n')}-{suf} " if suf else f"{m.group('n')} "


