# --- политика правил разбора (пакет 6.0а, 20.09; программа §0.3) ---------------
#: Реестр правил СЛОЯ РАЗБОРА (стоп-классы речи Q16, формы Q17–Q23, Z F1–F4):
#: имя → умолчание `on|off|shadow`. Пока пуст — правила добавляет пакет 7
#: (исполнитель B), контракт `contract_60a.md`: новое имя рождается здесь с
#: умолчанием `off`; `shadow` для разбора = старый разбор в бой, новый — только
#: `trace.parse_shadow={key_old, key_new}` (или `trace.stop_shadow=имя`).
#: Настройка `address_parse.rules` («имя=значение,…») перекрывает поимённо;
#: её проверяет `rules_from_setting` (400 при неизвестном имени).
PARSE_ON = "on"
PARSE_OFF = "off"
PARSE_SHADOW = "shadow"
PARSE_POLICIES: tuple[str, ...] = (PARSE_ON, PARSE_OFF, PARSE_SHADOW)
PARSE_RULES: dict[str, str] = {}
#: Класс 12 (пакет 7a, Q16): пункт с типом, чьё имя — речь («город Напишу»,
#: «село Сколько»); живёт в :func:`parse_place`. Заводится отдельной строкой,
#: а не в литерале выше: реестр в пакете 7a правят три исполнителя разом.
