def rules_from_setting(text: str | None, *, strict: bool = True) -> dict[str, str]:
    """`address_parse.rules` → действующая политика разбора: умолчания
    `PARSE_RULES` поверх перекрытий настройки. Пусто — одни умолчания.

    Неизвестное имя или значение: при `strict=True` (ЗАПИСЬ — `Spec.check`
    реестра настроек, 400 ручки) — `ValueError`: опечатка в настройке не имеет
    права молча включить или выключить не то правило. При `strict=False`
    (ЧТЕНИЕ в бою, `inbound.parse_rules`) плохая пара пропускается с
    предупреждением, остальные действуют: имя, снятое из реестра следующей
    выкаткой, не должно обнулять перекрытия соседних правил (ревью 20.09,
    #5/#14 — тот же договор, что у `geocode.parse_rule_policy`)."""
    из = dict(PARSE_RULES)
    for кусок in (text or "").replace(";", ",").replace("\n", ",").split(","):
        кусок = кусок.strip()
        if not кусок:
            continue
        имя, знак, значение = кусок.partition("=")
        имя, значение = имя.strip(), значение.strip().lower()
        if not знак or not имя or not значение:
            ошибка = f"ожидается «правило=значение», получено «{кусок}»"
        elif имя not in PARSE_RULES:
            известны = ", ".join(sorted(PARSE_RULES)) or "(реестр пуст)"
            ошибка = f"неизвестное правило разбора «{имя}»; известны: {известны}"
        elif значение not in PARSE_POLICIES:
            допустимы = ", ".join(PARSE_POLICIES)
            ошибка = f"неизвестное значение «{значение}» у «{имя}»; допустимы: {допустимы}"
        else:
            из[имя] = значение
            continue
        if strict:
            raise ValueError(ошибка)
        # Читается на каждое входящее: одна устаревшая пара дала бы тысячи
        # одинаковых строк в сутки и заслонила бы настоящие предупреждения —
        # называем каждую пару один раз на процесс.
        if кусок not in _ПРЕДУПРЕЖДЕНО:
            _ПРЕДУПРЕЖДЕНО.add(кусок)
            log.warning(
                "rule_policy.unknown_rule", layer="parse", rule=имя, value=значение, error=ошибка
            )
    return из


#: Пары настройки `address_parse.rules`, о которых нестрогий читатель уже
#: предупредил (на процесс).
_ПРЕДУПРЕЖДЕНО: set[str] = set()


#: Тип политики разбора, как её получают `parse(..., rules=…)` и правила:
#: словарь `rules_from_setting` (или пусто — одни умолчания реестра).
Rules = Mapping[str, str] | None


def rule_state(rules: Rules, name: str) -> str:
    """Политика правила разбора в ЭТОМ разборе: перекрытие настройки →
    умолчание реестра. Имя вне реестра — `off`, что бы ни лежало в словаре:
    включить его настройкой нельзя (`rules_from_setting` отвергнет), а правило,
    которое забыли записать в `PARSE_RULES`, в бою молчит, а не решает —
    словарь, собранный руками (сухой прогон, тест), этого не обходит."""
    if name not in PARSE_RULES:
        return PARSE_OFF
    if rules is not None and name in rules:
        return rules[name]
    return PARSE_RULES[name]


def under_rule(rules: Rules, name: str, *, old: Found | None, new: Found | None) -> Found | None:
    """Итог правила разбора под его политикой — ЕДИНСТВЕННОЕ место, где политика
    слоя разбора превращается в поведение (пакет 6.0а, программа §0.3).

    `old` — разбор без правила (сегодняшний), `new` — с ним. `on` — новый;
    `off` — старый, как будто правила нет; `shadow` — в бой идёт СТАРЫЙ, а
    разница остаётся следом на строке, которую он заводит:
    `trace.parse_shadow={rule, key_old, key_new, changed}` — правило прочитало
    бы иначе (ключ — «улица, дом», уже лежащий в самой строке, ПД сверх неё
    нет; `changed` — какие поля строки разошлись: ключ, пункт, город, район,
    уровень…), `trace.stop_shadow=имя` — стоп-класс снял бы строку вовсе.
    Правило, которое в тени НАШЛО бы адрес там, где старый разбор молчит,
    строки не заводит (К-5: тень без строк) — только журнал
    `address.parse_shadow` без слов клиента; объём считает сухой прогон.
    Одинаковые поля строки — не разница, следа нет.
    """
    политика = rule_state(rules, name)
    if политика == PARSE_ON:
        return new
    if политика != PARSE_SHADOW:
        return old
    if old is None:
        if new is not None:
            log.info("address.parse_shadow", rule=name, status="would_add", level=new.level)
        return None
    след: dict[str, Any]
    if new is None:
        след = {"stop_shadow": name}
    else:
        разошлись = [поле for поле in _ПОЛЯ_СТРОКИ if getattr(old, поле) != getattr(new, поле)]
        if not разошлись:
            return old
        след = {
            "parse_shadow": {
                "rule": name,
                "key_old": old.value,
                "key_new": new.value,
                "changed": разошлись,
            }
        }
    # Копия, а не правка на месте: `old` может быть общим с другим путём разбора
    # (тот же объект возвращают ветки города), и след одного правила не должен
    # всплыть у соседа.
    return _с_следом(old, след)


#: Поля `Found`, из которых собирается строка-кандидат (ключ, пункт, город,
#: район, массив, регион, вид, уровень): тень правила разбора сравнивает их —
#: одинаковый ключ при другом пункте (Q17, расклейка) — тоже разница.
_ПОЛЯ_СТРОКИ: tuple[str, ...] = (
    "value",
    "kind",
    "level",
    "settlement",
    "settlement_type",
    "locality",
    "district",
    "area",
    "region",
)


def _с_следом(found: Found, след: dict[str, Any]) -> Found:
    """`found` с дописанным следом (`Found.trace`), поверх прежних ключей."""
    return dataclasses.replace(found, trace={**(found.trace or {}), **след})


@dataclass
class Found:
    """Разобранный адрес: что показать, откуда взято и насколько уверены.

    ``raw`` — кусок сообщения РОВНО как написан. Он не для красоты: оператор
    обязан сверить нашу догадку с тем, что человек набрал, а буквы клиента мы
    не переписываем никогда — видимую опечатку человек ловит, отполированную
    нет.
    """

    street: str
    house: str
    raw: str
    start: int
    end: int
    level: str
    parts: dict[str, str] = field(default_factory=dict)
    #: Населённый пункт рядом с улицей — название и канонический тип
    #: («Урожай», «посёлок»). Пусто — не назван. В `value` не входит.
    settlement: str | None = None
    settlement_type: str | None = None
    #: Город, названный клиентом словами «г./город». Пусто — не назван.
    locality: str | None = None
    #: «house» — улица и дом; «place» — только место: район, пункт, массив
    #: (владелец 13.09: «адрес постепенно — сначала место, потом улица»).
    kind: str = KIND_HOUSE
    #: Район («Гатчинский р-н») и массив/СНТ/микрорайон («массив Южный») —
    #: как написаны; у «house» пусто.
    district: str | None = None
    area: str | None = None
    #: Регион словами клиента («Московская область») — колонка `region`
    #: строки; пусто — не назван (пакет 6.0а, заполняет пакет 7).
    region: str | None = None
    #: СЛЕД РАЗБОРА (`trace` строки, пакет 6.0а, I-1; пишет
    #: `record_address_candidate`, заполняет пакет 7): какой формой разобрано
    #: (`parse_form`), почему такой уровень (`level_reason`), в какой форме
    #: назван город (`locality_form`: «г. X», «в X», анкета…), какой пункт
    #: прочитан из контекста, а не из слов рядом с улицей (`settlement_read`).
    #: Пусто — след не оставлен; ключ в `trace` тогда не пишется.
    parse_form: str | None = None
    level_reason: str | None = None
    locality_form: str | None = None
    settlement_read: str | None = None
    #: Прочие ключи следа разбора для `trace` строки, поверх именованных выше:
    #: `parse_shadow`/`stop_shadow` (тень правила разбора, `under_rule`), `form`
    #: (форма места F1–F4, пакет 8). Пусто — ключей нет. Доносит
    #: `clients.след_разбора`; суд их не трогает.
    trace: dict[str, Any] | None = None

    @property
    def value(self) -> str:
        """Каноническая строка «улица, дом» — ключ уникальности БЕЗ квартиры.

        ⚠ КВАРТИРА В КЛЮЧ НЕ ВХОДИТ, И ЭТО РЕШЕНИЕ 09.09. В 23,5 % адресных
        диалогов адрес размазан по нескольким репликам: «Ленина 5» → «кв 3,
        второй подъезд». С квартирой в ключе каждый обрывок стал бы отдельным
        вопросом оператору. Цена названа вслух: «Ленина 5 кв 3» и «кв 7» у
        одного клиента станут одной строкой — оператор увидит обе цитаты и
        выберет.
        """
        if self.kind == KIND_PLACE:
            место = place_value(
                settlement=self.settlement,
                settlement_type=self.settlement_type,
                area=self.area,
                district=self.district,
            )
            if self.street.strip():
                return ", ".join(к for к in (self.street.strip(), место) if к)
            return место
        if not self.street.strip() and self.settlement:
            # Дом по пункту без улицы: «посёлок Сосново, 9».
            пункт = f"{self.settlement_type or ''} {self.settlement}".strip()
            return f"{пункт}, {self.house.strip()}"
        return f"{self.street.strip()}, {self.house.strip()}"


def place_value(
    *,
    settlement: str | None,
    settlement_type: str | None,
    area: str | None,
    district: str | None,
) -> str:
    """«деревня Малая Сосновка, массив Южный, Гатчинский р-н» — ключ места."""
    куски: list[str] = []
    if settlement:
        куски.append(f"{settlement_type} {settlement}".strip() if settlement_type else settlement)
    if area:
        куски.append(area)
    if district:
        куски.append(district)
    return ", ".join(к for к in куски if к)


#: «мкр15», «мкр. 15», «микрорайон №15» — номер ПОСЛЕ типа. В голове разбора
#: число стоит ПЕРЕД типом («15 мкр д 15»), иначе «мкр15 д.15» давало улицу
#: «мкр» и дом «15» — номер микрорайона вместо дома (бой 12.09). Число уже
#: перед типом — не трогаем: там второе число и есть дом.
#: «Квартал 92/93, дом 14», «квартал 93 дом 31» (владелец 18.09, Ангарск):
#: квартал — тот же нумерованный массив, и номер у него бывает сдвоенным
#: («92/93» — два квартала одним двором). «в квартале 5» не трогаем: за типом
#: буква, а не число.
#: Литера — часть номера: «мкр 16а дом 5», «квартал 178а 5» (Ангарск: 6а,
#: 17а — микрорайоны, 85а — квартал). Без неё переставлялось голое число, и
#: литера приклеивалась к типу — улица «мкра», «178 квартала» (ревью 18.09).
_МКР_ПОСЛЕ = re.compile(
    r"(?<![\d])\b(мкр|мкрн|микр|мик|микрорайон|м-н|квартал|кв-л)\.?\s*№?\s*"
    r"(\d{1,3}(?:/\d{1,3})?[а-яё]?)(?![\d/а-яё])",
    re.IGNORECASE,
)
#: «1микр», «3мкр», «9мик» — число прилипло к типу слева: тот же микрорайон.
_МКР_ПРИЛИП = re.compile(
    r"(?<![\d:.,])(\d{1,3})(мкр|мкрн|микр|мик|микрорайон|линия|проезд|улица|квартал)(?![а-яё])",
    re.IGNORECASE,
)
#: «14а- 76-21», «14а-76-21», «5 - 12 - 3»: микрорайон (число, часто с
#: литерой), дом, квартира — вся реплика целиком, иначе это дата или размер.
#: «Адрес 3-24-71», «14А-76-118 3 подъезд» (стенд 14.09): после слова «адрес»
#: и с хвостом частей — та же тройка; телефон «8-912-…» не пройдёт: у него
#: первое число «8» без второго, а группы длиннее.
_МКР_ДОМ_КВ = re.compile(
    r"^\s*(?:адрес[:\s]+)?(?![78]\s*-\s*\d{3})(?P<mkr>[1-9]\d?[а-яa-z]?)\s*-\s*(?P<bld>[1-9]\d{0,2}[а-я]?)\s*-\s*"
    r"(?P<kv>[1-9]\d{0,2})(?![\d\-])\s*[.!,]?\s*"
    r"(?:$|(?=\d|по[дж][ъь]?езд|этаж|кв(?![а-яё])|квартир|парадн|домофон|код(?![а-яё])|"
    r"перв|втор|трет|четв|пят|шест|седьм|восьм|девят|десят))",
    re.IGNORECASE,
)
#: Та же тройка в НАЧАЛЕ реплики, за которой точка/восклицание и любой текст
#: («12 -58-37. Там где…», владелец 19.09) — только после вопроса об адресе.
_МКР_ДОМ_КВ_В_НАЧАЛЕ = re.compile(
    r"^\s*(?:адрес[:\s]+)?(?![78]\s*-\s*\d{3})(?P<mkr>[1-9]\d?[а-яa-z]?)\s*-\s*(?P<bld>[1-9]\d{0,2}[а-я]?)\s*-\s*"
    r"(?P<kv>[1-9]\d{0,2})(?![\d\-])\s*[.!]\s+(?=\S)",
    re.IGNORECASE,
)
#: «первый корпус», «второй корп.» — корпус порядковым словом (владелец
#: 18.09). Только именительный: «во втором корпусе» — речь о месте, не номер.
#: Та же тройка ЧЕРЕЗ ТОЧКИ — «7.10.34» (владелец 20.09, Нефтеюганск: первая
#: реплика диалога). Только в квартальных городах (`parse_quarter_pair`): вне
#: их «7.10.26» — скорее дата. Без ведущих нулей («07.10.34» — дата), третье
#: число до трёх цифр, дальше не цифра и не точка («7.10.34.1» — версия).
#: Одиночная точка перед концом («7.10.34.») — конец предложения, как у
#: дефисной тройки (ревью 20.09, #9); точка с текстом дальше — `хвост`.
_МКР_ДОМ_КВ_ТОЧКИ = re.compile(
    r"^\s*(?:адрес[:\s]+)?(?P<mkr>[1-9]\d?[а-яa-z]?)\s*\.\s*(?P<bld>[1-9]\d{0,2}[а-я]?)\s*\.\s*"
    r"(?P<kv>[1-9]\d{0,2})(?!\d)(?!\.\d)\s*[!,]?\s*(?:\.?\s*$|(?P<хвост>[.!]\s+(?=\S)))",
    re.IGNORECASE,
)
#: Годы «ближнего» календаря двумя цифрами: «5.10.26» — 5 октября 2026-го,
#: такое клиент пишет о дне визита. Дальше «30» такой записью не бывает.
_БЛИЖНИЕ_ГОДЫ = range(24, 31)


def _точки_как_дата(m: re.Match[str]) -> bool:
    """Точечная тройка похожа на короткую дату «д.м.гг»: день до 31, месяц
    1…12, год из `_БЛИЖНИХ_ГОДОВ`. Такая тройка целиком репликой без вопроса
    оператора — скорее дата визита, чем адрес; после вопроса — адрес (решение
    20.09). «7.10.34» — 34-й год так не пишут, читается адресом и без вопроса;
    литера в номере («7а.10.26») — дата с буквой не бывает."""
    mkr, bld, kv = m.group("mkr"), m.group("bld"), m.group("kv")
    if not (mkr.isdigit() and bld.isdigit()):
        return False
    return int(mkr) <= 31 and 1 <= int(bld) <= 12 and int(kv) in _БЛИЖНИЕ_ГОДЫ


_КОРПУС_СЛОВОМ = re.compile(
    r"(?<![а-яё])(?P<n>перв|втор|трет|четв[её]рт|пят|шест|седьм|восьм|девят|десят)"
    r"(?:ый|ой|ий)\s+(?P<k>корпус|корп\.?)(?![а-яё])",
    re.IGNORECASE,
)
#: Число (дома, с литерой или без) перед корпусом словом: «18 г первый
#: корпус», «7, кв 41, первый корпус» — между ними только знаки.
_ЧИСЛО_ДОМА_ПЕРЕД = re.compile(r"\d\s*[а-яё]?[\s,;.]*$", re.IGNORECASE)
#: Число перед типом — уже номер микрорайона («15 мкр 15»): вторая цифра — дом.
#: «93-й квартал 31», «5-й мкр 12» (владелец 18.09): порядковое перед типом —
#: тоже число перед типом; без хвоста «-й» разбор переставлял «31 квартал» и
#: терял дом. Дробь и литера — те же, что умеет `_МКР_ПОСЛЕ`: «92/93 квартал
#: 6» без них переставлялось в «92/93 6 квартал» и не разбиралось вовсе, «16а
#: мкр 5» — в «16а 5 мкр» (ревью 18.09).
_ЧИСЛО_ПЕРЕД = re.compile(
    r"(?:^|[\s,])(\d{1,3}(?:/\d{1,3})?[а-яё]?)(?:\s*-?\s*(?:й|я|ый|ой|ий|ая|го))?\s*$"
)
#: После «мкр 18» сразу квартира/подъезд/этаж — значит 18 это дом.
#: «Юбилейный мкр 3» — имя микрорайона перед типом, число за ним — дом.
#: Только прилагательное с заглавной: «Здравствуйте мкр 15», «Живу мкр 15» —
#: речь, и «мкр 15» в них по-прежнему микрорайон.
_ИМЯ_ПЕРЕД_МКР = re.compile(r"(?P<w>[А-ЯЁ][а-яё]+(?:ый|ий|ой|ая|яя|ое|ее))\s*$")
_ДОМ_ПОСЛЕ_МКР = re.compile(r"[\s,]*(?:дом|д\.?)\s*№?\s*\d", re.IGNORECASE)
_ЧАСТИ_ПОСЛЕ_МКР = re.compile(
    r"[\s,.\-]*(?:кв\.?|квартира|под\.?|подъезд|эт\.?|этаж|домофон)(?![а-яё])", re.IGNORECASE
)


#: Сокращение типа улицы, прилипшее к имени дефисом: «пр-мира», «ул-Ленина»,
#: «бул-Мира» — дефис становится пробелом, дальше тип читает `_ТИП` как
#: обычно (слово типа не разворачиваем: сторож цитаты сверяет слова строки с
#: текстом клиента). «Б-мира» — отдельно: «Б-» это и бульвар, и «Большая»
#: («Б-Морская»), и «Богдана» («Б-Хмельницкого»), поэтому буква снимается, а
#: решает карта: «мира 17а» находит и ул., и б-р Мира — дом 17а есть только на
#: бульваре; при доме на обеих — честные варианты. Только перед буквами имени
#: (не «б-р», не «пр-кт», не «пр-т», не «мкр-н» — у них своя запись в `_ТИП`)
#: и только в начале слова.
_ТИП_ПРИЛИП = re.compile(
    r"(?<![а-яёa-z\d])(?P<t>б|пр|ул|пер|бул)-(?=[а-яё]{3,})(?!р(?![а-яё]))(?!кт(?![а-яё]))(?!т(?![а-яё]))",
    re.IGNORECASE,
)


def _нормализовать(text: str) -> tuple[str, list[int]]:
    """Текст для разбора и карта «индекс в нём → индекс в исходном».

    Переписанный кусок весь указывает на свой исходный диапазон: начало — на
    его начало, конец — на его конец, поэтому `raw` режется по исходному тексту
    и остаётся тем, что написал человек.
    """
    out: list[str] = []
    обратно: list[int] = []
    pos = 0
    замены: list[tuple[int, int, str]] = [
        (m.start(), m.end(), f"{m.group(1)} {m.group(2)}") for m in _МКР_ПРИЛИП.finditer(text)
    ]
    # «Б-мира 17а» (владелец 20.09, Невинномысск): сокращение типа вплотную к
    # имени через дефис — тип терялся, в запрос уходила «Мира», карта находила
    # улицу Мира вместо бульвара и дом не подтверждала. Полное слово типа
    # ставится сюда же, в нормализацию: разбор дальше видит обычную голову с типом.
    for m in _ТИП_ПРИЛИП.finditer(text):
        # «Б-» — один пробел (замена нулевой длины сломала бы карту смещений
        # `обратно` ниже); остальные — тип и пробел вместо дефиса.
        тип = m.group("t")
        замены.append((m.start(), m.end(), " " if тип.lower() == "б" else f"{тип} "))
    # «Октябрьская 18 г первый корпус» (владелец 18.09): корпус порядковым
    # словом — числом, как «5 подъезд» у частей; хвост `_ДОМ` умеет только цифры.
    # В замену идёт канон «корпус N», а не тип как написан: «второй корп.»
    # давало дом «5 корп. 2», и сторож цитаты, ждущий слово «корпус», его
    # гасил (ревью 18.09). И только ПОСЛЕ числа дома: «второй корпус Ленина
    # 5» с заменой впереди давало улицу «2 Ленина».
    for m in _КОРПУС_СЛОВОМ.finditer(text):
        if _ЧИСЛО_ДОМА_ПЕРЕД.search(text[: m.start()]) is None:
            continue
        номер = next(v for k, v in _ПОРЯДОК.items() if m.group("n").lower().startswith(k))
        замены.append((m.start(), m.end(), f"корпус {номер}"))
    for m in _МКР_ПОСЛЕ.finditer(text):
        if _ЧИСЛО_ПЕРЕД.search(text[: m.start()]):
            continue
        # «микрорайон 23 кв6» (бой 13.09, Бердск): сразу квартира — «23» и
        # есть дом, а «Микрорайон» — улица без названия; переставлять нечего.
        # Голое «мкр 15» — по-прежнему микрорайон (место).
        if _ЧАСТИ_ПОСЛЕ_МКР.match(text[m.end() :]):
            continue
        # «Юбилейный мкр 3» (ревью 14.09): имя перед типом — микрорайон
        # Юбилейный, дом 3; переставив, получили бы «3-й микрорайон».
        # …но «Октябрьский мкр 35 дом 3» — микрорайон 35, дом 3: явный «дом»
        # за числом сильнее имени перед типом (ревью 14.09).
        имя = _ИМЯ_ПЕРЕД_МКР.search(text[: m.start()])
        if (
            имя is not None
            and имя.group("w").lower() not in _НЕ_НАЗВАНИЕ_УЛИЦЫ | _НЕ_УЛИЦА
            and not _ДОМ_ПОСЛЕ_МКР.match(text, m.end())
        ):
            continue
        замены.append((m.start(), m.end(), f"{m.group(2)} {m.group(1)}"))
    for start, end, замена in sorted(замены):
        if start < pos:
            continue
        for i in range(pos, start):
            out.append(text[i])
            обратно.append(i)
        for j, ch in enumerate(замена):
            out.append(ch)
            обратно.append(start if j < len(замена) - 1 else end - 1)
        pos = end
    for i in range(pos, len(text)):
        out.append(text[i])
        обратно.append(i)
    обратно.append(len(text))  # индекс «за концом» — для end
    return "".join(out), обратно


def gate(text: str, *, про_адрес: bool = False, rules: Rules = None) -> str | None:
    """Уровень уверенности для текста — или ``None``, если адресом не пахнет.

    ``про_адрес`` — признак разговора об адресе снаружи: оператор спросил в
    предыдущей реплике. Клиента, назвавшего свою реплику адресом сам, ловим
    здесь же. ``rules`` — политика правил разбора (`rules_from_setting`):
    стоп-классы речи (пакет 7a) читают её здесь, и здесь же её читают ворота
    модели (`address_llm.looks_like_address`) — один невод на оба пути.
    Обёртка над :func:`_gate`: имя сработавшего класса нужно только разбору
    (след тени), сигнатура ворот для остальных читателей прежняя.
    """
    return _gate(text, про_адрес=про_адрес, rules=rules)[0]


def _gate(
    text: str, *, про_адрес: bool = False, rules: Rules = None
) -> tuple[str | None, str | None]:
    """Уровень ворот и имя стоп-класса речи (пакет 7a, Q16): `(уровень, имя)`.

    Уровень считается как всегда; затем головы невода судят стоп-классы
    (:func:`_класс_под_политикой`). Класс в `on` закрывает ворота — уровень
    `None`, имя остаётся: разбор молчит, а модель-читатель не будится (М-10 —
    `looks_like_address` ходит через те же ворота). Класс в `shadow`/`off`
    уровня не трогает, имя уезжает в `parse` → `under_rule` (след тени или
    ничего). Ворота закрываются, только когда речью оказалась КАЖДАЯ голова:
    «Все 4 розетки, Ленина 5» — «Ленина 5» чистая, реплика адресная.
    """
    # «7мкр-д64» (бой 13.09, Ангарск): тип прилип к числу — уровень смотрим по
    # тексту после той же нормализации, что и голова.
    т = _нормализовать(text or "")[0]
    if _ТИП_НАЗВАН.search(т) or _ЧАСТИ_АДРЕСА.search(т):
        уровень = LEVEL_A
        # На уровне A невод уровень не решает, но головы для классов «2-х» и
        # местоимения (единственных, что судят при названном типе) — те же.
        головы = list(_головы_невода(т, после_вопроса=про_адрес))
    else:
        # «Город Щёлково …», «г. Гай …» — клиент сам назвал город: это разговор об
        # адресе, как и после вопроса оператора (владелец 14.09). «ольховая
        # 164 жк восток новостройка» (владелец 15.09): ЖК, СНТ, микрорайон или
        # пункт с типом рядом — тоже; без этого строчная улица с домом ждала
        # следующей реплики с заглавной.
        про_адрес = про_адрес or _город_клиента(т) is not None or _место_названо(т)
        головы = list(_головы_невода(т, после_вопроса=про_адрес))
        if not головы:
            return None, None
        уровень = LEVEL_B if (про_адрес or _ПРО_АДРЕС.search(т)) else LEVEL_C
    имя = _класс_под_политикой([_стоп_классы_невода(т, m, уровень=уровень) for m in головы], rules)
    if имя is not None and rule_state(rules, имя) == PARSE_ON:
        return None, имя
    return уровень, имя


def _место_названо(text: str) -> bool:
    """Массив с типом («жк восток», «СНТ Заря», «13 мкр») или пункт с типом и
    именем с заглавной («посёлок Сосново») — клиент говорит об адресе."""
    if _МЕСТО_МАССИВ.search(text) is not None:
        return True
    return any(
        _годное_имя_пункта(m.group("sname") or m.group("sname3") or m.group("sname4") or "")
        and (m.group("stype") or "").lower().rstrip(".") not in ("с", "д", "г", "п")
        # «Ст Ленина 5» — строение, не станица: «ст» только с точкой (ревью 15.09).
        and not (
            (m.group("stype") or "").lower() == "ст"
            and text[m.end("stype") : m.end("stype") + 1] != "."
        )
        for m in _МЕСТО_ПУНКТ.finditer(text)
    )


def _невод_сработал(text: str, *, после_вопроса: bool = False) -> bool:
    """Широкий невод со стоп-списком голов: хоть одна голова прошла."""
    return next(_головы_невода(text, после_вопроса=после_вопроса), None) is not None


def _головы_невода(text: str, *, после_вопроса: bool = False) -> Iterator[re.Match[str]]:
    """Совпадения широкого невода, прошедшие стоп-список голов.

    Проверяются ОБА слова названия: смысловая голова у «Повесить зеркало 130» —
    именно второе, и без этой проверки габарит стал бы домом.
    """
    невод = _ШИРОКИЙ_НЕВОД_ПОСЛЕ_ВОПРОСА if после_вопроса else _ШИРОКИЙ_НЕВОД
    for m in невод.finditer(text):
        первое, второе = ((g or "").lower() for g in m.groups())
        if первое not in _НЕ_УЛИЦА and второе not in _НЕ_УЛИЦА:
            yield m
        # «Нет, белорусская 5»: служебное слово слева, название — второе;
        # голова его отрежет сама (`_годные_головы`).
        elif после_вопроса and второе and второе not in _НЕ_УЛИЦА and первое in _НЕ_НАЗВАНИЕ_УЛИЦЫ:
            yield m


# --- стоп-классы речи по форме (пакет 7a, Q16; программа §2.1) -----------------
#
# Невод «Название Число» берёт и речь с заглавной: «Метра 4», «Хонор 8х»,
# «Наберите 2гис», «Хочу 10» — стоп-списки (`_НЕ_УЛИЦА`, `_НЕ_НАЗВАНИЕ_УЛИЦЫ`)
# держат слова, а речь бесконечна (стенд 21.09: ≈390 ложных строк в месяц).
# Классы судят ФОРМУ головы перед числом и хвост сразу за ним, а не словарь.
# Каждый — своё имя в реестре `PARSE_RULES` с умолчанием `off` (§0.3):
# включается по одному, после замера `address-reparse --golden --scope all
# --rules STOP_X=on`, через `shadow`. Порядок кортежа — порядок договора:
# при нескольких сработавших имя даёт первый (среди равных по политике).
STOP_UNIT_BEFORE_NUMBER = "STOP_UNIT_BEFORE_NUMBER"
STOP_BARE_METRE = "STOP_BARE_METRE"
STOP_LATIN_BRAND = "STOP_LATIN_BRAND"
STOP_ORDINAL_SUFFIX = "STOP_ORDINAL_SUFFIX"
STOP_LIST_MARKERS = "STOP_LIST_MARKERS"
STOP_DATE_DOT = "STOP_DATE_DOT"
STOP_DIGITS_WORD = "STOP_DIGITS_WORD"
STOP_C_ONE_WORD_FORM = "STOP_C_ONE_WORD_FORM"
STOP_IMPERATIVE = "STOP_IMPERATIVE"
STOP_ADVERB = "STOP_ADVERB"
STOP_PRONOUN = "STOP_PRONOUN"


class _Голова(NamedTuple):
    """Голова перед числом глазами стоп-классов: слова как написаны (служебные
    слева уже срезаны), цифры дома, хвост сразу за цифрами, текст до головы
    и признак типа улицы в голове (голова разбора уровня A)."""

    слова: tuple[str, ...]
    число: str
    хвост: str
    перед: str
    с_типом: bool = False


#: (1) Единица, срок, числительное словом перед числом: «Метра 4», «Раза 4»,
#: «Числа 23», «Квадратов 80». Список — формы слов меры, а не техники.
_ЕДИНИЦА_ГОЛОВОЙ = re.compile(
    r"^(?:метр(?:а|ов)?|год(?:а|ов)?|месяц(?:а|ев)?|числ(?:а|о)|раз(?:а)?|секунд(?:а|ы)?|"
    r"дн(?:я|ей)|мин(?:ут|уты|уту)?|штук(?:а|и)?|литр(?:а|ов)?|киловатт\w*|квадрат\w*|"
    r"час(?:а|ов)?|недел(?:я|и|ь)|сут(?:ки|ок)|тонн(?:а|ы)?|килограмм\w*|грамм(?:а|ов)?|"
    r"рубл(?:ь|я|ей)|тысяч\w*|процент(?:а|ов)?|сантиметр\w*|миллиметр\w*|километр\w*|"
    r"дюйм\w*|кг|см|мм|км)$"
)
#: …и инфинитив: «Обжать 3 провода», «Просверлить 10». «-сть/-сти» —
#: существительное («Юность»), как у `_РЕЧЬ_СТРОЧНЫМИ`; существительные на
#: «-ть/-чь» — закрытым списком: «Млечный Путь 5» — улица.
_ИНФИНИТИВ = re.compile(r"^[а-яё]{2,}(?:(?<!с)ть|(?<!с)ти|чь)$")
_НЕ_ГЛАГОЛ_НА_ТЬ = frozenset(
    "путь пути мать сеть сети нить нити ртуть треть трети речь печь ночь дочь память дичь".split()
)
#: (2) Слово-величина перед числом: «Расстояние 5 м», «Стена 4м», «Бетон 3
#: м3», «Площадь 60 квадратов». Голый метр за числом сам по себе дом не
#: снимает — «Ленина 6 м» это литера через пробел (решает `_ДОМ`).
_ВЕЛИЧИНА_ГОЛОВОЙ = frozenset(
    """расстояние верх низ стена стены стену площадь высота высоту ширина ширину длина
длину глубина глубину комнату комнаты бетон бетона прокладка прокладки периметр толщина
толщину диаметр метраж квадратура объём объем""".split()
)
_ГОЛЫЙ_МЕТР = re.compile(r"^\s*(?:м(?![а-яё])|м3|м²|квадрат\w*|кв(?!\s*\.?\s*\d)(?![а-яё]))")
#: (3) Марка техники транслитом перед числом («Хонор 8х», «Танк 581», «Эпсон
#: 412»), латиница словом, латинская буква через пробел за числом («4 g»).
#: Кириллическая «х» через пробел — литера: «Октября 85 х» остаётся домом.
_МАРКИ = frozenset(
    """хонор хуавей асус эпсон лджи элджи танк смарт реалми редми ксиоми сяоми леново делл
асер канон кэнон бош индезит аристон хайсенс хисенсе дексп бибикью техно инфиникс виво оппо
поко""".split()
)
_ЛАТИНСКОЕ_СЛОВО = re.compile(r"^[A-Za-z][A-Za-z-]*$")
_ЛАТИНИЦА_ЗА_ЧИСЛОМ = re.compile(r"^\s+[A-Za-z](?![A-Za-zа-яё])")
#: (4) Порядковый хвост сразу за числом: «2-х створчатый», «4-х ств», «2х
#: комнатная». Числовой префикс ПЕРЕД именем («20-летия Октября») — Q20.
_ПОРЯДКОВЫЙ_ХВОСТ = re.compile(r"^-?(?:х|ти|ми|мя)(?=\s|$|[,.;!?)])")
#: (5) Нумерованный список: маркер «N. » или «N) » до головы, а число головы —
#: следующий маркер («…2. Замена выключателя 3. Установка…»).
_МАРКЕР_СПИСКА = re.compile(r"(?:^|\s)\d{1,2}[.)]\s")
_ЧИСЛО_МАРКЕР = re.compile(r"^[.)](?:\s|$)")
#: (6) Дата «д.ММ» за числом — тот же сторож, что у `_ГОЛОВА`; невод B/C
#: дробь за числом и так не берёт, имя живёт ради реестра и следа.
_ДАТА_ЗА_ЧИСЛОМ = re.compile(
    r"^\.(?:0[1-9]|1[0-2])(?!\d)(?!\s*(?:по[дж]|под\.|кв|квартир|этаж|эт\.|корп|к\.|домофон))"
)
#: (7) «Последние цифры 20-84», «Цифры 12»: клиент диктует номер, не дом.
_СЛОВО_ЦИФР = re.compile(r"^(?:цифр(?:ы|а)|последние|номер(?:а)?|код)$")
#: (8) Форма названия: прилагательное улицы («Ясная», «Вольская», «Майский»,
#: «Разумное») или существительное в родительном («Мира», «Победы», «Октября»,
#: «Гагарина», «Строителей») либо пункт на «-о»/«-ье» («Иваново», «Заречье»)
#: — одно такое слово с числом на C остаётся адресом; без формы («Танк 581»,
#: «Даже 21», «Память 128») — речь.
_ФОРМА_НАЗВАНИЯ = re.compile(r"(?:ая|яя|ой|ий|ый|ых|их|ое|ее|ье|ов|ев|ей|а|я|ы|и|о)$")
#: (9) Повелительное наклонение первым словом: «Наберите 2гис», «Откройте
#: Настройки 3», «Скиньте 2 фото». За глаголом улица в форме прилагательного
#: («Приезжайте Ленина 5») — адрес, класс не берёт.
_ПОВЕЛИТЕЛЬНОЕ = re.compile(r"^[а-яё]{2,}(?:ите|йте|ай|уй|ьте)$")
_ФОРМА_УЛИЦЫ = re.compile(r"(?:ая|яя|ой|ий|ый|ых|их|ова|ева|ёва|ина|ская)$")
#: (10) Наречие перед числом: «Приблизительно 75», «Реально 3», «Обычно 2».
#: «Центральная 5» — «-альная», не «-ально».
_НАРЕЧИЕ = re.compile(r"^[а-яё]{2,}(?:тельно|ально|енно|ерно|чно)$")
#: (11) Местоимение или квантор перед числом — закрытый список: «Все 4»,
#: «Хочу 10», «Ему 26», «Каждый 3».
_МЕСТОИМЕНИЕ = frozenset(
    """все всё хочу ему ей им нам другие другой остальные каждый каждая любой любая оба обе
всего много мало несколько такие такой таких этих эти этот эта""".split()
)


def _слово(г: _Голова, i: int) -> str:
    return г.слова[i].lower().strip(".,")


def _стоп_единица_перед_числом(г: _Голова) -> bool:
    w = _слово(г, -1)
    if _ЕДИНИЦА_ГОЛОВОЙ.match(w) is not None:
        return True
    return _ИНФИНИТИВ.match(w) is not None and w not in _НЕ_ГЛАГОЛ_НА_ТЬ


def _стоп_голый_метр(г: _Голова) -> bool:
    w = _слово(г, -1)
    if w in _ВЕЛИЧИНА_ГОЛОВОЙ or w.startswith("квадрат"):
        return True
    return _ГОЛЫЙ_МЕТР.match(г.хвост) is not None and _ЕДИНИЦА_ГОЛОВОЙ.match(w) is not None


def _стоп_марка(г: _Голова) -> bool:
    if any(_слово(г, i) in _МАРКИ or _ЛАТИНСКОЕ_СЛОВО.match(w) for i, w in enumerate(г.слова)):
        return True
    return _ЛАТИНИЦА_ЗА_ЧИСЛОМ.match(г.хвост) is not None


def _стоп_порядковый_хвост(г: _Голова) -> bool:
    return _ПОРЯДКОВЫЙ_ХВОСТ.match(г.хвост) is not None


def _стоп_маркеры_списка(г: _Голова) -> bool:
    return _МАРКЕР_СПИСКА.search(г.перед) is not None and _ЧИСЛО_МАРКЕР.match(г.хвост) is not None


def _стоп_дата_точкой(г: _Голова) -> bool:
    return _ДАТА_ЗА_ЧИСЛОМ.match(г.хвост) is not None


def _стоп_слово_цифр(г: _Голова) -> bool:
    return _СЛОВО_ЦИФР.match(_слово(г, -1)) is not None


def _стоп_одно_слово_без_формы(г: _Голова) -> bool:
    if len(г.слова) != 1 or len(г.число) < 2 or г.с_типом:
        return False
    w = г.слова[0]
    if w[:1].isdigit() or _ФОРМА_НАЗВАНИЯ.search(w.lower()) is not None:
        return False
    # «Ангарск 86», «Тверь 10»: город справочника — пункт с домом (Q9), не речь.
    return _норм_города(w) not in _имена_городов() and w not in КВАРТАЛЬНЫЕ_ГОРОДА


def _стоп_повелительное(г: _Голова) -> bool:
    w = _слово(г, 0)
    if len(w) < 5 or _ПОВЕЛИТЕЛЬНОЕ.match(w) is None:
        return False
    if _норм_города(w) in _имена_городов():
        return False  # «Алтай», «Валдай»: окончание глагольное, имя — из справочника
    return all(_ФОРМА_УЛИЦЫ.search(_слово(г, i)) is None for i in range(1, len(г.слова)))


def _стоп_наречие(г: _Голова) -> bool:
    return _НАРЕЧИЕ.match(_слово(г, -1)) is not None


def _стоп_местоимение(г: _Голова) -> bool:
    return _слово(г, -1) in _МЕСТОИМЕНИЕ


