"""Ячейка CSV для Excel: текст остаётся текстом (проверка 24.09).

Excel разбирает ячейки CSV сам. Телефон «+79161234567» становится числом без
плюса, а в стандартной ширине колонки ещё и «7,92E+10». Имя клиента «=1+1»
становится формулой, и хуже всего формула вида `=HYPERLINK("…"&D2;…)`: щелчок
по ней отправляет соседнюю ячейку с телефоном наружу. Текст в выгрузках идёт
из полей, которые пишет не наш продукт (имя клиента на Авито, название
объявления), поэтому экранируется каждая строковая ячейка.

XLSX защищён отдельно (`stats._text_stays_text`): там ячейке можно прямо
сказать «это текст», у CSV такого способа нет.
"""

import re
from typing import Any

#: Начала, с которых Excel, LibreOffice и Google Sheets читают формулу.
_FORMULA_START = ("=", "+", "-", "@", "\t", "\r")

#: Номер телефона целиком: плюс по желанию и 10–15 цифр.
_PHONE = re.compile(r"\+?\d{10,15}")


def csv_cell(value: Any) -> Any:
    """Строку — в вид, который табличный редактор покажет как есть.

    Номер пишется формулой-строкой `="+79161234567"`: так Excel показывает его
    текстом с плюсом, без числового формата. Прочий текст, начинающийся со
    знака формулы, получает апостроф впереди — редактор покажет его, но
    вычислять ячейку не станет. Остальное, включая числа, уходит без изменений.
    """
    if not isinstance(value, str) or not value:
        return value
    if _PHONE.fullmatch(value):
        return f'="{value}"'
    if value.startswith(_FORMULA_START):
        return "'" + value
    return value
