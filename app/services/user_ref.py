"""Ссылка на человека для интерфейса: имя и отдел собираются одним местом.

ПРОСЬБА ВЛАДЕЛЬЦА 04.09, ДОСЛОВНО: «нужно сделать так, чтобы везде аккуратно
в скобочках подписывались (Чатер) (ОКК) и т.д.» — рядом с именем виден отдел:
«Петров Иван (Чатер)». Отдел уже лежит в `users.department` (7.4), но
наружу до сих пор не выходил нигде, кроме вкладки «Команда»: во всех
остальных местах человек приезжал парой `{id, full_name}`.

⚠ ПОЧЕМУ ОТДЕЛЬНЫЙ МОДУЛЬ, А НЕ ПОЛЕ, ДОПИСАННОЕ В ДВАДЦАТИ МЕСТАХ. Пара
`{"id": ..., "full_name": ...}` собиралась руками в двух десятках точек:
`conversations` (лента, список, история клиента), `inbox`, `messages`,
`transfer`, `participants`, `inbound`, `account_operators`, плюс ручки
`routes/conversations`, `routes/inbox`, `routes/clients`. Дописать поле в
каждую значило бы завести двадцать независимых копий правила — и точка,
которую добавят через месяц, отдела не получит. Тогда в одном окне человек
станет «Иванов (ОКК)», а в соседнем останется «Иванов», и это прочтётся как
ДВА РАЗНЫХ ИВАНОВА. Ровно этим здесь уже ловились: см. `dva-puti-raznyi-schet`
— два пути считали одно поле по-разному.

⚠ ОТДЕЛ ЧИСТИТСЯ ЗДЕСЬ, А НЕ НА ЭКРАНЕ. Замер боя: поле свободное (справочника
нет, см. `models/user.py`), заполнено НЕ У ВСЕХ, и значения разной
аккуратности — «Диспетчер МНЧ» и «Диспетчер  МНЧ» с двумя пробелами человек
читает как один отдел, а строки сравниваются как разные. Поэтому:

* пробелы по краям снимаются, внутренние схлопываются в один;
* пустой отдел (пусто, пробелы, `null`) отдаётся как `null` — скобки не
  рисуются вовсе: «Иванов ()» хуже, чем просто «Иванов».

Фронт нормализует ещё раз, и это не дубль по недосмотру: у отдела есть второй
путь наружу (`department` в строке «Команды» и в кандидате на канал), а фронт
и бэкенд выкатываются порознь — старая сборка сервера про эту чистку не знает.
"""

from typing import Any, overload
from uuid import UUID

from app.models import User

__all__ = ["normalize_department", "user_ref", "user_ref_parts"]


def normalize_department(department: str | None) -> str | None:
    """«Диспетчер  МНЧ» → «Диспетчер МНЧ», «   » → None.

    Отдельным именем, потому что то же правило нужно строкам, которые ссылкой
    на человека не являются: кандидат на канал (`account_operators`) и строка
    «Команды» везут отдел собственным полем.
    """
    if not department:
        return None
    # `split()` без аргумента режет по любым пробельным (в том числе по
    # неразрывному, который приезжает из копипасты в поле ввода).
    сжатый = " ".join(department.split())
    return сжатый or None


def user_ref_parts(
    user_id: UUID | str | None,
    full_name: str,
    department: str | None = None,
) -> dict[str, Any]:
    """Та же ссылка, но из отдельных значений — для строк без объекта `User`.

    Нужна ровно там, где объекта нет и не будет: выборка колонками
    (`account_operators.operators_summary`) и синтетический автор
    «Автораздача» у распределения (`inbound`), у которого учётной записи не
    существует.
    """
    return {
        "id": str(user_id) if user_id is not None else "",
        "full_name": full_name,
        "department": normalize_department(department),
    }


# Перегрузки нужны вызывающим, которые РАСКРЫВАЮТ ссылку в свой словарь
# (`{**user_ref(u), "reason": ...}` в `participants`): без них проверка типов
# видит `dict | None` и запрещает распаковку там, где `None` невозможен.
@overload
def user_ref(user: User) -> dict[str, Any]: ...
@overload
def user_ref(user: None) -> None: ...
@overload
def user_ref(user: User | None) -> dict[str, Any] | None: ...
def user_ref(user: User | None) -> dict[str, Any] | None:
    """Как человек выглядит в любом ответе API: `{id, full_name, department}`.

    `None` на входе — `None` на выходе: «ответственного нет» и «ответственный
    без отдела» это разные новости, и склеивать их пустым объектом нельзя.
    """
    if user is None:
        return None
    return user_ref_parts(user.id, user.full_name, user.department)
