def msk_day_range(
    date_from: date | None, date_to: date | None
) -> tuple[datetime | None, datetime | None]:
    """Даты по Москве (обе включительно) → полуинтервал UTC ``[ts_from, ts_to)``.

    ``date_to`` включительный: правая граница — полночь следующего дня по МСК.
    """
    ts_from = (
        datetime.combine(date_from, time.min, tzinfo=MSK).astimezone(UTC) if date_from else None
    )
    ts_to = (
        datetime.combine(date_to + timedelta(days=1), time.min, tzinfo=MSK).astimezone(UTC)
        if date_to
        else None
    )
    return ts_from, ts_to
