def _label(mapping: dict[str, str], value: Any) -> str | None:
    return mapping.get(value) if isinstance(value, str) else None


#: Подписи полей заявки канала в описании строки журнала.
_LEAD_FIELD_LABELS = {
    "lead_origin": "источник",
    "lead_partner_number": "партнёр",
    "review_url": "ссылка на отзыв",
}


def describe(action: str, details: Mapping[str, Any] | None = None) -> str:
    """Человекочитаемое описание строки журнала (01 §9.7, экран 11 §4.2).

    Неизвестное действие возвращается как есть: журнал показывает правду, а не
    «—», даже если кто-то записал событие мимо реестра.
    """
    d: Mapping[str, Any] = details or {}
    base = AUDIT_ACTIONS.get(action)
    if base is None:
        return action

    if action == "auth.login" and d.get("result") == "failure":
        return "Неудачная попытка входа"
    if action == "conversation.status_changed":
        frm = _label(_STATUS_LABELS, d.get("from")) or d.get("from") or "?"
        to = _label(_STATUS_LABELS, d.get("to")) or d.get("to") or "?"
        by = _label(_BY_LABELS, d.get("by"))
        text = f"Статус диалога: {frm} → {to}"
        return f"{text} ({by})" if by else text
    if action == "conversation.assigned":
        if d.get("assignee_id") is None:
            # Возврат в очередь и снятие ответственного — разные события для
            # разбора смены: первое сделал сам оператор, второе — руководитель.
            return (
                "Диалог возвращён во «Входящие»"
                if d.get("source") == "inbox"
                else "С диалога снят ответственный"
            )
        if d.get("source") == "inbox" and d.get("by") == "self":
            return "Диалог принят из очереди"
        return _label(_ASSIGN_LABELS, d.get("by")) or base
    if action == "conversation.declined":
        reason = d.get("reason")
        return f"{base} (причина: {reason})" if reason else base
    if action in ("client.phone_captured", "client.address_captured"):
        # Словарь один на телефон и адрес: значения `source` пишутся теми же
        # тремя словами, и второй словарь с теми же ключами разошёлся бы с
        # первым при первой же правке.
        source = _label(_PHONE_SOURCES, d.get("source"))
        return f"{base} ({source})" if source else base
    if action in ("client.merged", "client.unmerged"):
        # Число перенесённых диалогов — единственное, что отличает безобидное
        # объединение пустой карточки от переезда девяти чужих переписок.
        moved = d.get("conversation_ids")
        count = len(moved) if isinstance(moved, list) else 0
        if action == "client.merged" and d.get("auto"):
            # Автоматику видно словом, а не только по пустому сотруднику.
            base = "Карточки клиента объединены автоматически по телефону"
        return f"{base} (перенесено диалогов: {count})" if count else base
    if action == "client.phone_candidate_accepted" and d.get("auto"):
        return "Номер из переписки добавлен в карточку автоматически"
    if action in ("user.invited", "user.role_changed"):
        frm, to = _label(_ROLE_LABELS, d.get("from")), _label(_ROLE_LABELS, d.get("to"))
        if action == "user.role_changed" and frm and to:
            return f"{base}: {frm} → {to}"
        role = _label(_ROLE_LABELS, d.get("role"))
        return f"{base} ({role})" if role else base
    if action == "user.email_changed":
        frm, to = d.get("from"), d.get("to")
        return f"{base}: {frm} → {to}" if frm and to else base
    if action == "bot.updated" and d.get("revision") is not None:
        return f"{base} (ревизия {d['revision']})"
    if action == "bot.handoff" and d.get("reason"):
        return f"{base} (причина: {d['reason']})"
    if action == "dialogs.exported" and d.get("rows") is not None:
        return f"{base} (строк: {d['rows']})"
    if action == "account.lead_fields_changed" and isinstance(d.get("changes"), Mapping):
        parts = [
            f"{_LEAD_FIELD_LABELS.get(field, field)}: {change.get('from') or '—'} → "
            f"{change.get('to') or '—'}"
            for field, change in d["changes"].items()
            if isinstance(change, Mapping)
        ]
        return f"{base} ({'; '.join(parts)})" if parts else base
    if action == "stats.exported":
        fmt = d.get("format")
        period = " — ".join(str(d[k]) for k in ("date_from", "date_to") if d.get(k))
        tail = ", ".join(part for part in (str(fmt) if fmt else "", period) if part)
        return f"{base} ({tail})" if tail else base
    return base


