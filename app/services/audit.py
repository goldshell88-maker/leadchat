async def write_audit(
    db: AsyncSession,
    *,
    user_id: uuid.UUID | None,
    action: str,
    entity: str | None = None,
    entity_id: str | None = None,
    details: dict[str, Any] | None = None,
) -> AuditLog:
    """Поставить строку журнала в сессию; транзакцией владеет вызывающий.

    ``user_id`` — обязательный именованный параметр и передаётся явно, включая
    ``None``: «действие системы/бота» — это решение автора кода, а не забытый
    аргумент (06 §0.3). Актор передаётся как ``user_id=user.id``.
    """
    if action not in AUDIT_ACTIONS:
        # Опечатка в action не должна ронять бизнес-операцию: строку пишем,
        # но событие видно в логах, а тест реестра валит CI.
        log.warning("audit.unknown_action", action=action, entity=entity)
    row = AuditLog(
        user_id=user_id,
        action=action,
        entity=entity,
        entity_id=entity_id,
        details=details,
    )
    db.add(row)
    return row


