"""Ручное объединение карточек клиента и телефон, введённый руками (правка 9 от 12 августа).

ЗАЧЕМ. Автоматическая склейка карточек держится на двух опорах, и обе шатаются.
Первая — `author_id` Авито: `UNIQUE(channel, external_id)` без аккаунта уже
сводит в одну карточку одинаковые идентификаторы с разных наших аккаунтов, но
Авито нигде не обещает, что идентификатор общий (у `Chat.users[].id` в
спецификации стоит ровно «Обратите внимание на хэширование»). Вторая — телефон:
он и подтверждает склейку, и опровергает её. Замер боевой базы 12 августа: 37
обращений, телефон известен у ТРЁХ. То есть в 34 случаях из 37 автоматике
опереться не на что, и решить, один это человек или двое, может только
диспетчер, читающий переписку.

Обратное тоже верно и стоило дороже: молчаливая склейка по совпавшему
идентификатору 11 августа собрала под одним именем восемь человек из разных
городов. Поэтому подсказка по идентификатору или имени остаётся ПОДСКАЗКОЙ с
кнопкой, а руками сведённое обязано разъединяться обратно — точно в исходное
состояние, иначе первое же ошибочное объединение необратимо.

ЧТО ДЕЛАЕТ МИГРАЦИЯ. Четыре nullable-колонки в `clients`, ни одного индекса,
ни одного изменения существующих данных. Пока колонки пусты, система ведёт
себя ровно как вчера: ни приём сообщений, ни выдача диалогов их не читают.

`merged_into_id` / `merged_at` — карточка объединена в другую. Проигравшая
строка НЕ УДАЛЯЕТСЯ (разбор — в `app/models/client.py`): её держит
`UNIQUE(channel, external_id)`, по которому `_upsert_client` находит клиента на
каждом входящем, и она же хранит второй идентификатор Авито и второй телефон
того же человека — у него их законно несколько, по одному на каждый наш
аккаунт.

`phone_set_by_id` / `phone_set_at` — номер введён руками. Карточка подписывает
номер словами «(из диалога)»; без этих колонок номер, записанный со слов
клиента, показывался бы как вычитанный из переписки, то есть карточка ручалась
бы за него чужим авторитетом.

ССЫЛКА `clients.merged_into_id -> clients.id` — НА СВОЮ ЖЕ ТАБЛИЦУ, и это
осознанно: «объединено в» — отношение между карточками, а не сущность.
`ON DELETE SET NULL`, потому что удаление победителя не должно уносить с собой
историю проигравшего; на цикл (A -> B -> A) внешний ключ не проверяет, поэтому
цикл запрещает код (`app/services/clients.py::merge_clients` отказывается
объединять уже объединённое и объединять карточку саму в себя).

ИНДЕКСОВ НЕТ, И ЭТО ПРОВЕРЕНО, А НЕ ЗАБЫТО. Оба новых запроса — «кто объединён
в эту карточку» (`WHERE merged_into_id = ?`) и «нет ли этого номера у другой
карточки» (`WHERE phone = ?`) — идут по `clients`, где 52 строки на бою и
десятки тысяч в худшем будущем; они выполняются на открытии карточки и на
ручном вводе номера, то есть считанные разы в минуту. Индекса нет и у
существующего `conversations.client_id`, которым читают `client_history` и
`conversation_detail` (проверено по 0001/0002: индексы только `tags`,
`(assignee_id, status)`, `updated_at`, `account_id`). Заводить индексы надо
будет сразу всем троим и отдельной миграцией, а не тайком внутри этой.

ОБЪЁМ И ВРЕМЯ. `ADD COLUMN` с NULL-умолчанием в Postgres 11+ — операция на
метаданных, таблица не переписывается. Данные не трогаются вовсе.

ОБРАТИМОСТЬ. `downgrade` снимает внешние ключи и колонки. Потери есть, и о них
честно: откат СТИРАЕТ факт объединения — карточки останутся раздельными, а
диалоги, переехавшие на победителя, обратно не вернутся (их переезд — это
`conversations.client_id`, и он не в этой миграции). Восстановить состояние
после отката можно только по журналу аудита (`client.merged` хранит обе
исходные карточки и список переехавших диалогов). Поэтому откат — dev-only
(08 §1.4 правило 5), как и у всех предыдущих.
"""

