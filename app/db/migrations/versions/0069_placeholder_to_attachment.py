def вложение(подпись: str) -> dict[str, Any]:
    """Вложение-заглушка для накопленной подписи — в форме живого разбора.

    Поля повторяют `adapter::_placeholder_attachment` для того же вида, и
    сторож в юнит-наборе сверяет их полем к полю. Отличие ровно одно и оно
    намеренное: `name` берётся из ТЕЛА, а не пересчитывается разбором. Иначе 348
    записей «Видео» переписались бы сегодняшней формулировкой «Видео —
    посмотреть можно только в приложении Авито», то есть миграция переписала бы
    ленту вместо того, чтобы перенести её. Переносим слова, не сочиняем.
    """
    вид = ПОДПИСИ[подпись]
    return {
        # Ключ строки в ленте (React key). Считать нечего — содержимого нет, а
        # заглушка у сообщения ровно одна: вид плюс слово-метка.
        "media_id": f"avito_{вид}_placeholder",
        # Не «image» даже у фотографии: `kind="image"` для ленты означает «рисуй
        # картинку», а рисовать нечем.
        "kind": "file",
        "name": подпись,
        # `None` написан явно, а не опущен, как в `_extract_attachments`: там
        # отсутствие ключа значит «ссылку не нашли», здесь мы знаем больше —
        # ссылки нет и не будет.
        "url": None,
        "size": None,
        "avito_type": вид,
    }


def отбор() -> sa.ColumnElement[bool]:
    """Условие переноса — ОДНО на все стороны: и на правку, и на её проверки.

    Пять условий, и каждое отвечает за свою границу: дата — за партиции (а),
    пара `in`/`client` — за то, что мы не трогаем ни серый чип Авито, ни
    исходящие, точный список — за отбор без «похоже на служебное» (е), пустой
    массив — за уже имеющиеся вложения (д).
    """
    return sa.and_(
        messages.c.created_at >= ГРАНИЦА,
        messages.c.direction == "in",
        messages.c.sender_type == "client",
        messages.c.body.in_(tuple(ПОДПИСИ)),
        messages.c.attachments == [],
    )


def отбор_отката() -> sa.ColumnElement[bool]:
    """Строки, лежащие ровно в той форме, которую кладёт `вложение()`.

    Сравнение ПОЛНЫМ массивом, а не по одному полю: заглушка не содержит ничего
    от самой строки, поэтому равенство здесь — точный и единственный признак.
    """
    return sa.and_(
        messages.c.created_at >= ГРАНИЦА,
        messages.c.direction == "in",
        messages.c.sender_type == "client",
        messages.c.body.is_(None),
        sa.or_(*[messages.c.attachments == [вложение(п)] for п in ПОДПИСИ]),
    )


def перенести(conn: sa.Connection) -> int:
    """Подпись из тела -> вложение. Возвращает число тронутых строк."""
    выбор = sa.case(*[(messages.c.body == п, sa.literal([вложение(п)], JSONB)) for п in ПОДПИСИ])
    return conn.execute(
        sa.update(messages).where(отбор()).values(body=sa.null(), attachments=выбор)
    ).rowcount


def вернуть(conn: sa.Connection) -> int:
    """Вложение -> подпись в теле. Возвращает число тронутых строк."""
    выбор = sa.case(*[(messages.c.attachments == [вложение(п)], п) for п in ПОДПИСИ])
    return conn.execute(
        sa.update(messages).where(отбор_отката()).values(body=выбор, attachments=[])
    ).rowcount


