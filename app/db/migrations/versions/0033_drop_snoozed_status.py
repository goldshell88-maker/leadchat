"""Статус «Отложен» снят: словарь статусов сводится к четырём значениям.

ПОЧЕМУ ЭТА МИГРАЦИЯ ВООБЩЕ ЕСТЬ, ЕСЛИ КОЛОНКИ НЕ ТРОГАЕМ. Решение владельца от
12 августа — «„Отложить диалог“ и „Чем закончилось обращение?“ — эти функции не
нужны» — снимает интерфейс и поток работы, а не данные. Никаких `DROP COLUMN`
здесь нет и быть не должно: снос колонки необратим, а решение может измениться.

Но `conversations.status` охраняет `CHECK`, который перечисляет значения
ЯВНЫМИ ЛИТЕРАЛАМИ (заведён миграцией 0027). Оставить в нём `snoozed` значило бы
держать в базе разрешение на значение, которого в продукте больше нет: ни
подписи, ни фильтра, ни экрана, ни перехода. Первый же UPDATE мимо приложения —
перенос данных, ручная правка при разборе, откат кода — поставил бы диалог в
статус, из которого его нечем достать: `TRANSITIONS` такого источника не знает,
и в интерфейсе у строки не будет ни одной рабочей кнопки. Ограничение обязано
описывать то, что есть, иначе оно не ограничение, а комментарий.

ЧТО ДЕЛАЕТСЯ С УЖЕ ОТЛОЖЕННЫМИ ДИАЛОГАМИ. Переводятся в «В работе» — ДО смены
ограничения, отдельным запросом.

Именно в «В работе», а не в «Новые», и это не произвол: отложить можно было
ТОЛЬКО свой диалог (проверка `snooze_requires_owner` в прежнем `change_status`),
значит у каждой такой строки есть ответственный. Ровно так же поступал сторож
возврата (`scheduler/jobs/snooze.py`, ветка «есть владелец»), когда срок
истекал. То есть миграция делает то же, что сделала бы система сама, просто
раньше срока: диалог возвращается человеку, который его вёл. Отправить их в
«Новые» значило бы отобрать работу у того, кто сам же её отложил, и вывалить
пачку чужих диалогов в общую очередь на тринадцать человек.

СРОКИ ОТЛОЖКИ НЕ ЗАТИРАЮТСЯ, И ЭТО НАМЕРЕННО. `snoozed_until`, `snoozed_by_id`
и `snooze_reason` остаются как есть — это единственный след того, что и на
какое время было отложено. Обнулить их значило бы потерять данные ради
опрятности; вернуть функцию после этого можно было бы только из резервной
копии. Гасятся они сами, по одной строке, при первом же осмысленном действии
над диалогом (`conversation_status.clear_snooze`, шесть точек вызова).
Частичный индекс `ix_conversations_snoozed_until` тоже остаётся: читателей у
него теперь нет, но он почти пустой и не стоит ничего.

ПЕРЕД ВЫКАТКОЙ ОБЯЗАТЕЛЕН ЗАПРОС (тот же порядок, что у 0027 и 0032, шаг 0):

    SELECT status, count(*) FROM conversations GROUP BY status ORDER BY 2 DESC;

Он отвечает на два вопроса сразу. Первый: сколько диалогов сейчас отложено —
то есть скольким людям в начале смены прилетит вернувшийся диалог без
объяснения (замер dev-стенда 12 августа: 0 отложенных из 37; на бою может быть
иначе). Второй: нет ли в колонке значения ВНЕ четырёх — тогда `ADD CONSTRAINT`
упадёт, и узнать об этом надо до окна выката, а не в нём.

ЕСЛИ ОТЛОЖЕННЫЕ ЕСТЬ — СКАЗАТЬ ЛЮДЯМ. Диалог вернётся раньше обещанного срока
и без уведомления: вид `conversation.snooze_due` снят этим же релизом. Список
для рассылки берётся ДО миграции:

    SELECT c.id, u.full_name, c.snoozed_until, c.snooze_reason
      FROM conversations c LEFT JOIN users u ON u.id = c.snoozed_by_id
     WHERE c.status = 'snoozed' ORDER BY c.snoozed_until;

ОБЪЁМ И БЛОКИРОВКИ. `ADD CONSTRAINT ... CHECK` без `NOT VALID` сканирует
таблицу под ACCESS EXCLUSIVE, а в `conversations` непрерывно пишет
inbound-конвейер. На нынешнем объёме (боевая база 11 августа — 37 диалогов на
двух живых каналах плюс импортированная история) это доли секунды. ЕСЛИ ЭТА
ПРАВКА КОГДА-НИБУДЬ ПОЕДЕТ НА БАЗУ В СОТНИ ТЫСЯЧ СТРОК — разбить на
`ADD CONSTRAINT ... NOT VALID` и `VALIDATE CONSTRAINT` двумя транзакциями.

ПОРЯДОК ВЫКАТА — СНАЧАЛА СХЕМА, ПОТОМ КОД. Обратный порядок безопасен здесь
только на первый взгляд: старый код умеет писать `snoozed`, и если он поработает
после `ADD CONSTRAINT`, отложка упадёт `IntegrityError` прямо в лицо диспетчеру.
Новый код после миграции корректен полностью — он про `snoozed` не знает.

НОМЕР РЕВИЗИИ ПРИ СЛИЯНИИ НАДО ПЕРЕПРОВЕРИТЬ. На 12 августа над этим деревом
идут четыре параллельные работы, и номер `0033` мог занять кто-то ещё. Две
ревизии с одним `down_revision` дают alembic ДВЕ головы, и `upgrade head` на
такой базе не поднимется вовсе. Тот, кто сливает вторым, переставляет
`down_revision` на ту ревизию, что легла первой, и переименовывает файл.
"""

from collections.abc import Sequence

from alembic import op

revision: str = "0033"
down_revision: str = "0032"
branch_labels: str | Sequence[str] | None = None
depends_on: str | Sequence[str] | None = None

#: КОРОТКОЕ имя ограничения — то, что подставляется в `naming_convention`
#: (`ck_%(table_name)s_%(constraint_name)s` из app/models/base.py). В базе оно
#: превращается в `ck_conversations_status`. Полное имя писать здесь нельзя:
#: `create_check_constraint` и `drop_constraint` ОБА прогоняют аргумент через
#: соглашение, и получилось бы `ck_conversations_ck_conversations_status` —
#: `DROP CONSTRAINT`, не находящий цели (на этом уже падала 0027).
CK_STATUS = "status"

FOUR = "status IN ('new','in_progress','waiting_client','closed')"
FIVE = "status IN ('new','in_progress','waiting_client','snoozed','closed')"


def upgrade() -> None:
    # ДАННЫЕ ПЕРВЫМИ, ограничение вторым. Обратный порядок уронил бы миграцию
    # на первой же отложенной строке — `DROP` старого и `ADD` нового идут в
    # одной транзакции, и между ними значение `snoozed` уже запрещено.
    #
    # `WHERE` обязателен: без него это переписывание всей таблицы и потеря
    # закрытых. `status_since` двигаем вместе со статусом — иначе строка
    # контекста скажет «В работе · 4 дня», считая от входа в отложку, а на
    # деле диалог вернулся к человеку только что (docs/38 §2: поле означает
    # «когда вошёл в НЫНЕШНИЙ статус»).
    op.execute(
        "UPDATE conversations SET status = 'in_progress', status_since = now() "
        "WHERE status = 'snoozed'"
    )
    op.drop_constraint(CK_STATUS, "conversations", type_="check")
    op.create_check_constraint(CK_STATUS, "conversations", FOUR)


def downgrade() -> None:
    # dev-only (08 §1.4 правило 5: в проде downgrade не применяется).
    #
    # Возвращается только ограничение. Статусы обратно НЕ переводятся, и это
    # честнее, чем угадывать: «в работе» после отката неотличимо от «в работе»,
    # которое было там всегда. След при этом сохранён — сроки отложки upgrade
    # не затирал, поэтому вернуть состояние можно точным запросом, руками и
    # осознанно:
    #
    #     UPDATE conversations SET status = 'snoozed'
    #      WHERE status = 'in_progress' AND snoozed_until > now();
    op.drop_constraint(CK_STATUS, "conversations", type_="check")
    op.create_check_constraint(CK_STATUS, "conversations", FIVE)
