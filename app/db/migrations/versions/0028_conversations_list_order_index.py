"""Индекс под порядок списка диалогов: «кроме закрытых», свежее сверху, полный ключ.

ЧТО ПОДДЕРЖИВАЕТ ЭТОТ ИНДЕКС. Ровно один запрос — `GET /conversations`
(`services.conversations.list_conversations`). После правки от 12 августа его
порядок состоит из трёх ключей:

    ORDER BY <закреплённые смотрящим>, last_message_at DESC NULLS LAST, id

Умолчание обеих вкладок («Мои», «Все») добавляет к нему `status <> 'closed'`:
закрытые в список не попадают, пока человек не выберет их фильтром «Статус».
Именно эта пара — фильтр плюс порядок — здесь и покрывается.

ПОЧЕМУ ПРЕЖНИХ ИНДЕКСОВ НЕ ХВАТАЕТ. Их два, и оба мимо:

* `ix_conversations_last_message_at` — `(last_message_at DESC NULLS LAST)` без
  второго столбца. Он даёт порядок, но не даёт ПОЛНОГО ключа: на строках с
  одинаковой секундой (служебные события Авито приходят пачками) порядок
  внутри пачки индекс не задаёт, и досортировка остаётся за планировщиком.
  Плюс он не знает про «кроме закрытых» — а закрытых в базе большинство.
* `ix_conversations_status_last_message` — `(status, last_message_at DESC)`.
  Ведущий столбец под `status <> 'closed'` не работает: неравенство по первому
  столбцу btree превращает поиск в проход по всему индексу, а не в диапазон.

ПОЧЕМУ ЧАСТИЧНЫЙ, А НЕ СОСТАВНОЙ ПО `status`. Условие у нас не «какой-то
статус», а «любой, кроме одного», и оно одинаково для всех вкладок и всех
тринадцати человек. Частичный индекс это условие ЗНАЕТ: планировщик сверяет
его с `WHERE` и берёт индекс целиком, а сам индекс не хранит закрытые строки
вовсе — на боевой базе это основная её часть (454 тысячи диалогов истории
против десятков открытых).

ПРО ЗАКРЕПЛЁННЫХ. Первым ключом порядка стоит закрепление, и по индексу оно не
идёт — это личная отметка в отдельной таблице. Поэтому `list_conversations`
берёт набор закреплённых ОТДЕЛЬНЫМ дешёвым запросом ДО выборки и добавляет
ключ, только если он непуст. У большинства диспетчеров закреплённых нет, и для
них `ORDER BY` совпадает с этим индексом столбец в столбец. У остальных
закреплённых не больше семи (`services.pins.MAX_PINS`) — досортировка идёт по
странице, а не по таблице.

ОБЪЁМ И БЛОКИРОВКИ. `CREATE INDEX` без `CONCURRENTLY` держит на таблице
SHARE-блокировку: чтения проходят, записи ждут. В `conversations` непрерывно
пишет inbound-конвейер, поэтому на большой базе строить надо `CONCURRENTLY` и
ВНЕ транзакции миграции. На нынешнем объёме (замер боевой базы 11 августа — 37
живых диалогов плюс импортированная история) это доли секунды, и усложнять
выкатку незачем. ЕСЛИ ЭТА МИГРАЦИЯ ПОЕДЕТ НА БАЗУ В СОТНИ ТЫСЯЧ СТРОК —
переписать на `op.execute("CREATE INDEX CONCURRENTLY …")` с
`autocommit_block()`.

В МОДЕЛИ ИНДЕКС НЕ ОБЪЯВЛЕН НАМЕРЕННО. Юнит-набор строит схему из метаданных
на SQLite, и частичный индекс там не проверяет ничего: планировщика Postgres в
нём нет, а порядок задаёт `ORDER BY`, а не индекс. Правильность порядка держат
`tests/unit/test_conversations_order.py`, скорость — этот индекс.

НОМЕР РЕВИЗИИ ПРИ СЛИЯНИИ НАДО ПЕРЕПРОВЕРИТЬ. 12 августа над этим деревом
работают несколько параллельных веток, и `0028` может оказаться занят. Две
ревизии с одним `down_revision` дают alembic ДВЕ головы, и `upgrade head` на
такой базе не поднимется вовсе. Тот, кто сливает вторым, переставляет
`down_revision` на ту ревизию, что легла первой, и переименовывает файл.
"""

