"""Межканальная склейка клиента становится видимой (требование владельца 6 от 11 августа).

ЧТО БЫЛО. «У меня так и не связываются клиенты, если один и тот же клиент
пишет на разные аккаунты» — дословно. Проверка по коду дала обратное:
связывание УЖЕ работает и всегда работало. У таблицы `clients` ограничение
`UNIQUE(channel, external_id)` без аккаунта (`0001_init.py`), а
`app/services/inbound.py::_upsert_client` ищет клиента по паре
`channel + external_id` и про аккаунт не знает вовсе. Один и тот же
`author_id`, пришедший с двух наших аккаунтов, попадает в ОДНУ карточку.

То есть жалоба владельца — не про отсутствие механизма, а про то, что его
работы НЕ ВИДНО: число обращений клиента считалось
(`client_conversations_count`) и не выводилось ни в одном компоненте (дефект
аудита SCEN-14), а канал прошлого обращения не показывался нигде.

(В том же ряду обычно называют `first_client_at` — не называйте: проверено по
`conversation_detail`, это `min(messages.created_at)` по ЭТОМУ диалогу, опора
для времени первого ответа. К истории клиента поле отношения не имеет, и
показать его как «клиент у нас с …» значит выдать дату сегодняшнего диалога
за дату знакомства.)

ПОЧЕМУ НЕЛЬЗЯ ПРОСТО ПОКАЗАТЬ. Допущение «author_id Авито одинаков во всех
аккаунтах» никогда не проверялось. В каталоге методов (docs/26) такого
утверждения нет, в спецификации у `Chat.users[].id` стоит ровно «Обратите
внимание на хэширование» — предупреждение без пояснений. Если идентификатор
свой у каждого аккаунта, то совпадение чисел с двух каналов — это не один
человек, а столкновение двух разных; в одну карточку съедутся чужая
переписка и чужой телефон, и диспетчер прочитает их как историю клиента,
который сейчас пишет. Замер боевой базы 11 августа: 52 клиента, ни один не
писал более чем на один аккаунт. Механизм включён и НИ РАЗУ не срабатывал —
проверить его на живых данных сегодня нечем.

ЧТО ДЕЛАЕТ МИГРАЦИЯ. Четыре nullable-колонки и один CHECK, ни одного индекса
(почему — в теле). Склейку она не включает и не выключает: пока колонки пусты,
система ведёт себя ровно как вчера. Колонки отвечают на три вопроса, на которые
сегодня ответить нечем: когда карточка стала межканальной, насколько мы
уверены, что это один человек, и не спорит ли с этим телефон.

ПОЧЕМУ `phone_account_id` — ОТДЕЛЬНАЯ КОЛОНКА, А НЕ ВЫВОД ИЗ ДАННЫХ.
Подтверждение склейки — это «тот же номер пришёл с ДРУГОГО канала». Без
записи о том, с какого канала взят номер в `clients.phone`, совпадение
доказывает лишь то, что клиент дважды написал один и тот же номер на одном
и том же канале. Вывести это задним числом нельзя: у `clients.phone` нет ни
ссылки на сообщение, ни на диалог (аудит `client.phone_captured` хранит
`conversation_id` в `details`, но это JSON журнала, а не ключ).

БЭКФИЛЛ — ОДИН UPDATE, И ОН ЖЕ ИЗМЕРЕНИЕ. Клиентам, у которых диалоги УЖЕ
лежат на разных аккаунтах, проставляется `cross_account_since` (самое раннее
сообщение такого клиента) и `link_confidence='assumed'`. На боевой базе это
ноль строк — и ровно это нужно знать: если после выкатки строки появились,
значит склейка уже случалась и её просто никто не видел. Ничего, кроме новых
колонок, бэкфилл не трогает, поэтому повторный запуск безопасен.

`link_confidence` бэкфилл ставит ТОЛЬКО `assumed`, даже когда телефон у
карточки есть: происхождение старого номера неизвестно (`phone_account_id` у
исторических строк NULL), а подтверждать склейку номером неизвестного
происхождения — это выдать предположение за факт задним числом. Такие
карточки получат `confirmed` сами, когда номер придёт с другого канала.

ОБЪЁМ И ВРЕМЯ. `clients` — десятки строк на бою (52 на 11 августа) и десятки
тысяч в худшем будущем. `ADD COLUMN` с NULL-умолчанием в Postgres 11+ —
операция на метаданных. `ADD CONSTRAINT ... CHECK` проверяет существующие
строки, но все четыре колонки только что созданы и содержат NULL, а NULL
CHECK проходит. Бэкфилл — один `UPDATE ... FROM (GROUP BY)` по `conversations`.

ИНДЕКСА ПО `conversations.client_id` В БАЗЕ НЕТ, И БЭКФИЛЛУ ОН НЕ НУЖЕН.
Проверено по списку индексов (`0001_init.py`, `0002_inbound.py`: только `tags`,
`(assignee_id, status)`, `updated_at`, `account_id`). Внешняя выборка всё равно
`GROUP BY client_id` по всей таблице — индекс её не ускорил бы; запрос
одноразовый и идёт на миграции. Тем же неиндексированным столбцом читают и
существующие `client_history` с `conversation_detail`, так что заводить индекс
именно здесь значило бы решать чужую задачу внутри чужой миграции. Сегодня это
десятки строк; когда перестанет быть — индекс заводится отдельно и сразу для
всех троих.

ОБРАТИМОСТЬ ПОЛНАЯ И ЧЕСТНАЯ. `downgrade` снимает CHECK и четыре
колонки. Терять нечего: их не заполнял никто, кроме этой миграции и кода,
который поедет вместе с ней; `UNIQUE(channel, external_id)` не трогается
вовсе, поэтому ни один клиент не распадётся и ни одна карточка не изменится.
Это осознанное отличие от плана в docs/31 §1, который снимал ограничение
сразу: снятое ограничение ломает `ON CONFLICT (channel, external_id)` в
`_upsert_client` (PostgreSQL 42P10) — то есть каждый вебхук от нового
клиента давал бы 500 в окне между миграцией и релизом кода (разбор в docs/30,
раздел B2). Разделение на «сначала видимость, потом схема ключа» —
следствие именно этого разбора.
"""

