"""Ботам — поле «кто отвечает»: наш Claude или лид-бот владельца.

ЧТО ПРОИСХОДИТ. Лид-бот — отдельный продукт владельца на своём сервере, до сих
пор работавший через Jivo с человеком в контуре. Владелец подключает его к
LeadChat автоответом: на шаге `ai_answer` бот отвечает сам, LeadChat отправляет,
и всё остальное — замолкание при менеджере, расписание, передача человеку —
остаётся прежним. Технически подмена сводится к одной развилке
(`app/bots/provider.py`), а этой колонкой она включается.

ПОЧЕМУ КОЛОНКА У БОТА, А НЕ У КАНАЛА. Всё, что определяет ответ, уже лежит на
боте: сценарий с шагом `ai_answer`, база знаний, расписание. Канал (аккаунт
Авито) отвечает за доставку и сам ссылается на бота. Поставь переключатель на
канал — и два аккаунта с одним ботом отвечали бы разными мозгами по одной базе
знаний, причём в редакторе бота эта разница не видна ВООБЩЕ: человек правит
базу знаний и не понимает, почему на одном аккаунте правки работают, а на
другом нет. Разбор целиком — в шапке `app/bots/provider.py`.

ПОЧЕМУ ЗНАЧЕНИЕ ПО УМОЛЧАНИЮ `claude`, А НЕ «ЧТО НАСТРОЕНО». Существующие боты
обязаны продолжить работать ровно как вчера. Автоответ по чужому регламенту —
другие цены, другие формулировки, другая ценовая лестница; включить его молча
всем сразу значило бы обнаружить подмену по ответам клиентам, а не по
настройке. Поэтому `server_default` жёстко прибит к `claude`, и лид-бот
включается боту за ботом, руками.

CHECK, А НЕ ENUM. Значений два, и добавление третьего (если появится ещё один
внешний мозг) в enum'е Postgres стоит отдельного `ALTER TYPE` с блокировкой, а
в CHECK — одной строки. Имя ограничения короткое: `create_check_constraint` и
`drop_constraint` оба прогоняют аргумент через `naming_convention` из
`app/models/base.py`, и полное имя превратилось бы в
`ck_bots_ck_bots_ai_provider` — то есть в `DROP CONSTRAINT`, не находящий цели
(на этом уже падала 0027).

ЗАМЕР ПЕРЕД ВЫКАТКОЙ НЕ НУЖЕН, И ЭТО РЕДКИЙ СЛУЧАЙ. Колонка новая, значений
вне списка в ней взяться неоткуда, `ADD CONSTRAINT` проверяет только что
проставленный `server_default`. Таблица `bots` на 12 августа — единицы строк,
блокировка на доли секунды.

НОМЕР РЕВИЗИИ ПРИ СЛИЯНИИ НАДО ПЕРЕПРОВЕРИТЬ. Над этим деревом идут
параллельные работы, и номер `0035` мог занять кто-то ещё. Две ревизии с одним
`down_revision` дают alembic ДВЕ головы, и `upgrade head` на такой базе не
поднимется вовсе. Тот, кто сливает вторым, переставляет `down_revision` на ту
ревизию, что легла первой, и переименовывает файл.
"""

