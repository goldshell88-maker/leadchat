"""Результат обращения: закрытый справочник теперь держит база (FUNC-32).

ЧТО БЫЛО. У `conversations.outcome` не было в базе ни одного ограничения, а
комментарий модели обещал «закрытый справочник (`OUTCOMES` ниже)» и ссылался на
константу, которой в том файле нет — она живёт в `app/services/conversations.py`.
Единственной охраной колонки была одна проверка на Python в ручке закрытия
диалога: всё, что попадает в колонку мимо неё (перенос данных, ручной UPDATE
при разборе, будущая массовая правка), проходило молча.

ПОЧЕМУ ЭТО НЕ КОСМЕТИКА. По этой колонке считаются ДЕНЬГИ: сколько обращений
стали выездами и какой канал окупается (`app/services/stats.py` группирует по
ней). Лишнее значение не падает и не подсвечивается — оно просто добавляет в
квартальный отчёт строку, которой никто не заказывал, и заметить это можно
только сверив отчёт с перепиской вручную.

ПЕРЕД ВЫКАТКОЙ ОБЯЗАТЕЛЕН ЗАПРОС (тот же порядок, что у 0027, шаг 0):

    SELECT outcome, count(*) FROM conversations
     WHERE outcome IS NOT NULL GROUP BY outcome ORDER BY 2 DESC;

Ограничения в колонке не было никогда — если в выдаче окажется значение вне
пяти, `ADD CONSTRAINT` упадёт на боевом. Это правильное поведение (падение
миграции лучше падения трафика), но узнать об этом надо ДО окна выката. Лечится
одним `UPDATE` заведомо неверных строк в NULL: пустой результат честнее
выдуманного.

ОБЪЁМ И БЛОКИРОВКИ. `ADD CONSTRAINT ... CHECK` без `NOT VALID` сканирует
таблицу под ACCESS EXCLUSIVE, а в `conversations` непрерывно пишет
inbound-конвейер. На нынешнем объёме (боевая база 11 августа — 37 диалогов на
двух живых каналах плюс импортированная история) это доли секунды. ЕСЛИ ЭТА
ПРАВКА КОГДА-НИБУДЬ ПОЕДЕТ НА БАЗУ В СОТНИ ТЫСЯЧ СТРОК — разбить на
`ADD CONSTRAINT ... NOT VALID` и `VALIDATE CONSTRAINT` двумя транзакциями.

NULL РАЗРЕШЁН ЯВНО. Результат обязателен не везде: принуждать диспетчера к
значению, которого он не знает, значит получить выдуманное. Поэтому условие
начинается с `outcome IS NULL OR` — без этой половины миграция запретила бы
все незакрытые диалоги разом.

НОМЕР РЕВИЗИИ ПРИ СЛИЯНИИ НАДО ПЕРЕПРОВЕРИТЬ. На 12 августа над этим деревом
идут шесть параллельных работ, и номер `0032` мог занять кто-то ещё. Две
ревизии с одним `down_revision` дают alembic ДВЕ головы, и `upgrade head` на
такой базе не поднимется вовсе. Тот, кто сливает вторым, переставляет
`down_revision` на ту ревизию, что легла первой, и переименовывает файл.
"""

from collections.abc import Sequence

from alembic import op

revision: str = "0032"
down_revision: str = "0031"
branch_labels: str | Sequence[str] | None = None
depends_on: str | Sequence[str] | None = None

#: КОРОТКОЕ имя ограничения — то, что подставляется в `naming_convention`
#: (`ck_%(table_name)s_%(constraint_name)s` из app/models/base.py). В базе оно
#: превращается в `ck_conversations_outcome`. Полное имя писать здесь нельзя:
#: `create_check_constraint` и `drop_constraint` ОБА прогоняют аргумент через
#: соглашение, и получилось бы `ck_conversations_ck_conversations_outcome` —
#: `DROP CONSTRAINT`, не находящий цели (на этом уже падала 0027).
CK_OUTCOME = "outcome"

CONDITION = "outcome IS NULL OR outcome IN ('visit','declined','not_our_profile','spam','no_reply')"


def upgrade() -> None:
    op.create_check_constraint(CK_OUTCOME, "conversations", CONDITION)


def downgrade() -> None:
    # dev-only (08 §1.4 правило 5: в проде downgrade не применяется).
    # Данные трогать не надо: снятие ограничения ничего не ломает — код
    # откатившейся версии умеет писать ровно те же пять значений.
    op.drop_constraint(CK_OUTCOME, "conversations", type_="check")
