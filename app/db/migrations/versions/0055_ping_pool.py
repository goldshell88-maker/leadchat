def _починить(узел: Any) -> tuple[Any, int]:
    """Заменяем ЗНАЧЕНИЕ ключа `text`, а не любую похожую строку в сценарии."""
    if isinstance(узел, list):
        всего = 0
        новый: list[Any] = []
        for э in узел:
            э2, n = _починить(э)
            новый.append(э2)
            всего += n
        return новый, всего
    if isinstance(узел, dict):
        всего = 0
        новый_d: dict[str, Any] = {}
        for k, v in узел.items():
            if k == "text" and isinstance(v, str) and v.strip() in ОДИНОЧКИ:
                новый_d[k] = list(ПУЛ)
                всего += 1
                continue
            v2, n = _починить(v)
            новый_d[k] = v2
            всего += n
        return новый_d, всего
    return узел, 0


