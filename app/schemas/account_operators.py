"""Схемы назначения операторов на каналы Авито (15 §2.2, план 7.2).

Зачем это существует. У заказчика девять каналов Авито и тринадцать
операторов, и у каждого канала СВОЙ набор людей — в Jivo это отдельный экран
«Назначить операторов на „! Парт - 7 / Ист - В43 МНЧ !"» со списком сотрудников
и галочками. Без такой привязки очередь «Входящие» (план 7.1) показывает всем
всё: оператор видит чужие обращения и берёт не свои.

**Правило совместимости, ради которого форма ответов именно такая.** Пустой
набор означает «канал доступен ВСЕМ операторам», а не «никому». Поэтому нигде
ниже нет поля вида ``is_closed``, а на карточке канала едет
:class:`ChannelOperatorsSummary` с ``count``: ноль читается экраном как
«открыт всем» — тем же правилом, что исполняют ``visible_queue_condition`` и
``eligible_operator_ids`` (app/services/inbox.py). Обратное прочтение стоило бы
одного деплоя: фильтрация включается, очередь у всех тринадцати пустеет,
обращения виснут молча.

Три решения, которые видно прямо в форме схем:

* **Экран назначения приезжает одним ответом** (:class:`ChannelOperatorsOut`):
  кто назначен (``assigned_ids``) плюс ВЕСЬ список сотрудников с пометкой
  ``can_be_operator``. Двумя запросами галочки и список разъезжаются: в Jivo
  несотрудники показаны серым и требуют сначала «стать оператором», и
  ``can_be_operator=false`` — ровно этот серый цвет.
* **Правило «кого можно назначить» считает сервер.** Фронт его не повторяет:
  в 7.4 «оператор» станет отдельным переключателем, независимым от роли, и
  повторённое на клиенте правило разъехалось бы с настоящим.
* **Тело PUT — полный набор, а не дельта.** Экран с галочками по своей природе
  отдаёт итоговое состояние; «добавь одного» и «убери одного» на тринадцати
  строках дали бы гонку двух открытых вкладок с непредсказуемым исходом.

Email сотрудника здесь намеренно нет: список сотрудников с адресами отдаёт
только `GET /users` (право `users:manage`, admin), а экран назначения открыт
на чтение ещё и руководителю (`accounts:read`).
"""

import uuid
from typing import Literal

from pydantic import BaseModel, Field, field_validator

# Потолок набора на один канал. Тринадцать операторов сегодня, сотни — запас
# на вырост; смысл лимита не в бизнес-правиле, а в защите от тела на мегабайт.
MAX_OPERATORS = 200


class OperatorRefOut(BaseModel):
    """Сотрудник в аватарке карточки канала (тип ``UserRef`` фронта)."""

    id: uuid.UUID
    full_name: str
    #: Отдел — подписью «(ОКК)» в подсказке над аватарками (04.09).
    #:
    #: Поле обязано быть ЗДЕСЬ, а не только в словаре сервиса: ответ едет
    #: через `response_model`, и Pydantic молча срезает всё, чего нет в
    #: модели, — отдел уехал бы из сервиса и не доехал до экрана.
    department: str | None = None


class ChannelOperatorsSummary(BaseModel):
    """Свод по каналу для карточки в `/settings/accounts` (11 §4.1).

    ``count == 0`` — канал открыт всем операторам (правило совместимости),
    а не «на канале никого». Так эту цифру и подписывает экран.
    """

    # Ноль по умолчанию — та же безопасная сторона правила: канал, про который
    # свод не собран, читается как «открыт всем», а не «закрыт для всех».
    count: int = 0
    # Первые несколько — аватарками, остальные прячутся за «+N», как в Jivo.
    preview: list[OperatorRefOut] = Field(default_factory=list)


class ChannelOperatorCandidateOut(BaseModel):
    """Строка списка на экране назначения: сотрудник и можно ли его назначить.

    ``can_be_operator`` — активен и отвечает клиентам (право `messages:send`,
    01 §12). Руководитель и наблюдатель приезжают с ``false`` и рисуются
    серым; ``reason`` объясняет человеку, почему галочка не ставится.
    """

    id: uuid.UUID
    full_name: str
    role: str
    is_active: bool
    is_online: bool = False
    can_be_operator: bool
    reason: str | None = None
    department: str | None = None  # отделы — 7.4


class ChannelOperatorsOut(BaseModel):
    """`GET /avito-accounts/{id}/operators` — всё, что нужно экрану назначения.

    Пустой ``assigned_ids`` — канал открыт всем операторам.
    """

    assigned_ids: list[uuid.UUID] = Field(default_factory=list)
    candidates: list[ChannelOperatorCandidateOut] = Field(default_factory=list)


class ChannelOperatorsWrite(BaseModel):
    """Тело `PUT /avito-accounts/{id}/operators` — полная замена набора.

    Пустой список разрешён и означает «канал общий»: все операторы снова видят
    его обращения. Это осознанная операция, а не ошибка формы. Дубликаты
    схлопываются здесь, а не в SQL, — иначе ответ «назначен один» на список из
    пяти одинаковых id выглядел бы ошибкой сохранения.
    """

    operator_ids: list[uuid.UUID] = Field(default_factory=list, max_length=MAX_OPERATORS)

    @field_validator("operator_ids")
    @classmethod
    def _dedupe(cls, value: list[uuid.UUID]) -> list[uuid.UUID]:
        return list(dict.fromkeys(value))


class ChannelOperatorsSaved(BaseModel):
    """Ответ PUT — свод, которым карточка канала перерисовывается сразу.

    Не весь экран назначения: модалка после сохранения закрывается, а обновить
    надо строку «Операторы: N» под карточкой (03 §2.1 — без второго GET).
    """

    operators: ChannelOperatorsSummary


class MyChannelOut(BaseModel):
    """Канал в блоке «Мои каналы» профиля.

    ``access`` отвечает оператору на вопрос «почему я вижу одни обращения и не
    вижу другие»: ``assigned`` — меня назначили, ``open`` — на канал не
    назначен никто, поэтому он открыт всем. Разница видна человеку, и при
    разборе смены вопрос снимается без похода к администратору.
    """

    id: uuid.UUID
    title: str
    access: Literal["assigned", "open"]
    #: Источник канала («В95») — та же пометка, что в шапке чата и в списках
    #: выбора (просьба владельца 03.09: «нужно, чтобы источник также
    #: прописывался рядом с аккаунтами»). Названия каналов различаются одним
    #: словом («Александр КП» / «Александр МНЧ»), а отвечает диспетчер именно
    #: от источника. `None` — не заполнен, и тогда подпись остаётся прежней.
    lead_origin: str | None = None


class MyChannelsOut(BaseModel):
    """`GET /me/channels` и `GET /users/{id}/accounts` — каналы одного человека."""

    items: list[MyChannelOut] = Field(default_factory=list)
