"""Схемы очереди «Входящие» (15 §2.1, план 7.1).

Очередь — это ответ на масштаб: тринадцать операторов на девяти каналах не
могут работать по правилу «кто первым ответил, тот и ведёт». Диалог сначала
ждёт в очереди, оператор жмёт «Принять» либо «Отклонить», и только принятый
уходит в «Мои».

Форма ответов подчинена одному требованию: **после каждого действия фронт
должен уметь перерисовать и открытый диалог, и бейдж вкладки, не делая
второго запроса.** Поэтому диалог едет целиком, а рядом с ним — свежий
счётчик очереди того, кто позвал ручку.

Счётчик здесь всегда персональный. «Отклонить» — решение одного оператора
(диалог остаётся свободным для остальных), поэтому глобального «размера
очереди» в системе не существует, и поле ``count`` во всех схемах ниже
означает ровно «сколько диалогов ждёт ЛИЧНО вас».
"""

import uuid
from typing import Any

from pydantic import BaseModel, Field, field_validator

# Причина отклонения — короткая строка для журнала и статистики («не мой
# канал», «занят»), а не переписка. Лимит держим здесь: и ручка, и будущая
# форма фронта берут его отсюда, а не из двух разных магических чисел.
MAX_DECLINE_REASON_LEN = 500


class InboxCountOut(BaseModel):
    """`GET /inbox/count` — бейдж вкладки «Входящие» (11 §2.1).

    Два числа, а не одно: `escalated` — сколько диалогов уже отказались вести
    все, кому они доступны. Такой диалог не исчезает из очереди (это был бы
    брошенный клиент), но бейдж обязан выглядеть иначе — иначе «никто не
    берёт» неотличимо от «просто очередь».
    """

    count: int
    escalated: int


class ClaimOut(InboxCountOut):
    """`POST /conversations/{id}/claim`.

    ``conversation`` — полный объект 01 §5.2 (как у `GET /conversations/{id}`):
    фронт открывает принятый диалог сразу, не дожидаясь второго round-trip.
    Вложенный объект, а не поля вперемешку со счётчиком — иначе `count`
    выглядел бы полем диалога и рано или поздно уехал бы в стор диалогов.
    """

    conversation: dict[str, Any]


class DeclineRequest(BaseModel):
    """Тело `POST /conversations/{id}/decline`. Причина необязательна."""

    reason: str | None = Field(default=None, max_length=MAX_DECLINE_REASON_LEN)

    @field_validator("reason")
    @classmethod
    def _strip(cls, v: str | None) -> str | None:
        # Пустая строка из формы — это «причины нет», а не причина из пробелов.
        if v is None:
            return None
        return v.strip() or None


class DeclineOut(InboxCountOut):
    """Подтверждение отказа + новый размер СВОЕЙ очереди.

    Диалог не возвращается: он и не открывался у отказавшегося. Возвращается
    счётчик — ради него ручка и отвечает телом, а не 204.

    ``already_declined`` — повтор (двойной клик, «Отклонить» из двух вкладок).
    Ответ на него намеренно 200, а не ошибка: результат ровно тот, которого
    человек добивался, и красная плашка тут ввела бы в заблуждение. Но фронту
    флаг нужен, чтобы не рисовать вторую строку в ленте.

    ``escalated_now`` — этим отказом закрылся круг: диалог отклонили ВСЕ, кому
    он доступен. Он остаётся в очереди с пометкой, администраторы уведомлены.
    Имя с суффиксом намеренно: унаследованное ``escalated`` — это СКОЛЬКО
    брошенных диалогов в очереди сейчас, а здесь речь о ЭТОМ диалоге. Два
    разных смысла под одним именем — готовая ошибка на стороне фронта.
    """

    conversation_id: uuid.UUID
    declined: bool
    already_declined: bool = False
    reason: str | None
    escalated_now: bool = False


class ReleaseOut(InboxCountOut):
    """`POST /conversations/{id}/release` — вернуть принятый диалог в очередь.

    ``conversation`` едет целиком по той же причине, что и у claim, только
    наоборот: строка списка должна перерисоваться из «мой» в «свободен».
    """

    conversation: dict[str, Any]
