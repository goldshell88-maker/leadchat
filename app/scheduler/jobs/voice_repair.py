"""Досчёт расшифровок голосовых: и тех, что не вышли, и тех, что не начинали.

ЗАЧЕМ. Расшифровка не работала в бою ни разу до 05.09: домом пользователя
контейнера был каталог кода, принадлежащий root, и движок загрузки весов
падал на правах записи в `$HOME`. Причину чинит `workers/transcribe.py`. Но
одной починкой дело не закрывается, и вот почему — поставить расшифровку
умеет ровно один путь, конвейер приёма, а он срабатывает в момент прихода
сообщения и второй раз не срабатывает никогда. Значит без этого прогона:

* записи, сгоревшие до починки, остались бы `failed` навсегда;
* всё, что пришло ДО включения расшифровки, осталось бы без текста навсегда.
  Замер 06.09: входящих голосовых без расшифровки за 30 дней — 458 (до суток
  3, 1–2 дня 31, 2–7 дней 97, 7–30 дней 327). Скриншот владельца — закрытый
  диалог с двумя голосовыми и ни строчки текста, оператор пишет клиенту
  «аудио не грузит, можете написать пожалуйста».

⚠ ДВА СРОКА, КОТОРЫЕ ЗДЕСЬ ПУТАЛИ. Ссылка на запись и сама запись живут
по-разному, и до 06.09 в этом файле (и в трёх соседних) они были склеены в
одно «ссылка живёт минуты — старое расшифровать нечем». Это неверно:

* ПОДПИСАННАЯ ССЫЛКА (`files.avito.ru`, параметры `id` и `token`) — короткая,
  считаем «минуты»; её срок меряется отдельно. Поэтому ссылку спрашивают
  прямо перед скачиванием, а не хранят.
* САМА ЗАПИСЬ у Авито живёт долго. Замер 06.09 через `getVoiceFiles`:
  сообщения возрастом 0,3 ч, 10,8 ч, 24 ч, 48 ч, 98 ч, ~7, ~14, ~21 и ~29 дней
  — ссылка выдана на ВСЕ. Старше 45 дней сообщений в базе нет, проверить
  нечем; граница между 29 и 45 днями не измерена.

ПОЧЕМУ СТОРОЖ, А НЕ РАЗОВЫЙ СКРИПТ. Разовый скрипт закрыл бы вчерашнюю беду и
ничего не сказал бы о завтрашней. Отказ здесь по своей природе средовой —
кончилось место, том приехал не с теми правами, оборвалась сеть на 464 МБ
весов — и лечится он не правкой записи, а починкой среды. Значит нужна
регулярная попытка: среду починили — и тексты появляются сами.

ГРАНИЦЫ. Каждая отвечает своему способу навредить:

* НЕ СТАРШЕ 30 СУТОК (:data:`НЕ_СТАРШЕ`) — по замеру записи, а не по ссылке.
* ТОЛЬКО ПОРЦИЯ (:data:`ПОРЦИЯ`). Расшифровка идёт по одной на весь процесс
  (в том же процессе живёт приём вебхуков), и вываливать в очередь сотни
  задач значит занять её на часы. Не успели за проход — доберём следующим.
* ТОЛЬКО ВХОДЯЩИЕ С ГОЛОСОВЫМ, И ЭТО В SQL. Состояние NULL стоит у КАЖДОЙ
  строки без расшифровки — у всех 317 тысяч текстовых тоже. Отбирай мы «NULL
  не старше месяца» и проверяй вложение уже в Python — порция из двадцати
  уходила бы на пустышки, а голосовые не доходили бы до очереди никогда.
* ТОЛЬКО ЖИВЫЕ КАНАЛЫ. По сообщениям канала в `needs_reauth`/`disabled`
  расшифровка кончается отказом «канал требует переподключения», а раз
  счётчика попыток нет — она повторялась бы каждые десять минут по каждому
  голосовому месяц подряд. Отсечено в SQL соединением с аккаунтом.
* `too_long` и `done` не берём: первое упрётся в тот же порог, второе готово.

ПОРЯДОК — НОВЫЕ ВПЕРЁД. Наоборот было бы правильно, живи запись минуты:
тогда старые ближе к порогу и их надо спасать первыми. Но запись живёт ≥29
дней, старым спешить некуда, — а новые принадлежат диалогам, в которых прямо
сейчас работает человек (тот самый скриншот). Хвост из 458 при порции 20 раз
в 10 минут добирается за ~4 часа; месячный закрытый диалог столько подождёт.

ЧЕГО ЗДЕСЬ НЕТ, И ЧЕМ ЭТО ГРОЗИТ. Счётчика попыток у записи нет — колонка
потребовала бы миграции на таблице в 317 тысяч строк. Границу держит возраст:
пока сообщение моложе порога, попытки идут. Значит безнадёжная запись (Авито
её удалил, битый кодек, пустой файл) повторяется каждые 10 минут до
30-дневной границы — до 4 тысяч заходов. Замер 06.09 таких не показал (ссылка
выдана на все возрасты, 7 из 7 новых — `done`); появятся — нужна колонка
попыток или конечное состояние «безнадёжно», и это отдельное решение.
"""

from datetime import UTC, datetime, timedelta
from typing import Any

import sqlalchemy as sa
import structlog
from apscheduler.triggers.interval import IntervalTrigger

from app.core import redis as redis_mod
from app.db import session as db_mod
from app.models import AvitoAccount, Conversation, Message
from app.services import voice

log = structlog.get_logger("app.voice_repair")

#: До какого возраста сообщения имеет смысл пытаться.
#:
#: 30 суток — по замеру самой ЗАПИСИ у Авито, а не подписанной ссылки: 06.09
#: `getVoiceFiles` отдал ссылку на голосовые возрастом от 0,3 ч до ~29 дней, все
#: до единого. Старше 45 дней сообщений в базе не было — где именно между 29 и
#: 45 днями запись пропадает, не измерено, и 30 взято как «измеренное плюс
#: день». Двое суток, стоявшие здесь раньше, были про ссылку — и не про то.
НЕ_СТАРШЕ = timedelta(days=30)

#: Сколько записей ставим в очередь за один проход.
ПОРЦИЯ = 20

#: Через сколько секунд после предыдущей стартует следующая задача порции.
#:
#: ⚠ БЕЗ РАЗНОСА ПОРЦИЯ ДАВИЛА БЫ САМА СЕБЯ (ревью 06.09). Воркер берёт до
#: `arq_max_jobs` (50) задач разом: все двадцать стартовали бы сразу и встали
#: за одним замком `transcribe._замок`. Задача ждёт замок 120 с, потом
#: откладывается на 60 с, и так три попытки — хвост порции не дождался бы ни
#: одной и лёг бы «не начинали» обратно, чтобы через десять минут повторить то
#: же самое. Работа шла бы, но кругами.
#:
#: Двадцать секунд — по замеру боя 05.09: 15,3 с и 11,6 с на задачу вместе со
#: ссылкой, скачиванием и счётом (записи 19 и 14 с речи). Порция из двадцати
#: растягивается на 380 с и целиком укладывается в десятиминутный интервал:
#: каждая находит замок свободным, ни одна не ждёт соседей. Длинные записи
#: (до 5 минут) счёт замедлят — тогда следующая подождёт у замка, что и
#: предусмотрено, но уже не двадцать разом.
ШАГ_СЕК = 20

#: Как часто ходим. 458 записей в хвосте при порции 20 — около четырёх часов;
#: чаще незачем (расшифровка всё равно идёт по одной), реже — хвост тянулся
#: бы сутки, а новые голосовые живого диалога ждали бы своей очереди с ними.
ИНТЕРВАЛ = timedelta(minutes=10)


async def repair_transcripts() -> int:
    """Точка входа планировщика: своя сессия, свой Redis.

    Возвращает число задач, ВСТАВШИХ В ОЧЕРЕДЬ, — не число найденных. Разница
    существенная: ARQ отказывает молча, и без этого различия прогон рапортовал
    бы об успехе, ничего не сделав.
    """
    redis = redis_mod.get_client()
    async with db_mod.session_scope() as db:
        кандидаты = await найти_нерасшифрованные(db)

    поставлено = 0
    for номер, (message_id, created_at) in enumerate(кандидаты):
        # Разнос по времени: i-я задача стартует через i × ШАГ. Первая — сразу.
        задержка = timedelta(seconds=номер * ШАГ_СЕК) if номер else None
        if await voice.enqueue_transcribe(
            redis, message_id, created_at, повтор=True, отложить=задержка
        ):
            поставлено += 1

    if кандидаты:
        # Пишем всегда, когда нашли хоть что-то, и обе величины: расхождение
        # между ними — единственный признак того, что очередь отказывает.
        log.info(
            "voice.repair",
            found=len(кандидаты),
            enqueued=поставлено,
            newest=кандидаты[0][1].isoformat(),
            oldest=кандидаты[-1][1].isoformat(),
        )
    return поставлено


async def найти_нерасшифрованные(
    db: Any, *, now: datetime | None = None
) -> list[tuple[Any, datetime]]:
    """Входящие голосовые не старше порога, у которых текста нет. Ничего не меняет.

    Отдельно от :func:`repair_transcripts` намеренно: отбор — это набор
    решений «брать / не брать», и проверять их надо на обычной сессии теста, а
    не через глобальные соединения процесса.

    ⚠ ГРАНИЦА ПО ДАТЕ НУЖНА ДВАЖДЫ. Она не только отсекает то, чего у Авито
    уже нет: таблица `messages` разбита на помесячные партиции, и без условия
    на `created_at` этот отбор читал бы все 28 партиций целиком каждые десять
    минут. С условием — одну, максимум две.

    ЦЕНА ЗАПРОСА (оценка, не замер — PostgreSQL под рукой нет). Раз в 10
    минут: партиций по дате остаётся 1–2; в них пара `direction='in' AND
    sender_type='client'` вместе с диапазоном по `created_at` ложится на
    частичный индекс `idx_messages_client_in` (миграция 0004), то есть
    читаются только входящие клиентов за месяц — тысячи строк, не сотни
    тысяч; остаток (состояние, вложение) — фильтр по прочитанному. Соединение
    с диалогом и аккаунтом — по первичным ключам, и только для того, что
    прошло фильтр. Порядок с `LIMIT` — по тому же индексу. Ни `OR` по
    состоянию, ни `@>` по вложению индекса не лишают: на этих колонках его и
    нет.
    """
    порог = (now or datetime.now(UTC)) - НЕ_СТАРШЕ
    rows = await db.execute(
        sa.select(Message.id, Message.created_at)
        .join(Conversation, Conversation.id == Message.conversation_id)
        .join(AvitoAccount, AvitoAccount.id == Conversation.account_id)
        .where(
            Message.created_at >= порог,
            # Только сказанное КЛИЕНТОМ: своё исходящее мы и так знаем текстом.
            # `sender_type` рядом с `direction` не для смысла (у входящих он
            # всегда `client`), а ради частичного индекса — см. цену выше.
            Message.direction == "in",
            Message.sender_type == "client",
            voice.has_voice_sql(db),
            sa.or_(
                Message.voice_transcript_status.is_(None),
                Message.voice_transcript_status == voice.СОСТОЯНИЕ_НЕ_ВЫШЛО,
            ),
            AvitoAccount.status == "active",
        )
        .order_by(Message.created_at.desc())
        .limit(ПОРЦИЯ)
    )
    return [(r[0], r[1]) for r in rows.all()]


DEFAULTS: dict[str, Any] = {"coalesce": True, "max_instances": 1, "misfire_grace_time": 300}

JOB_ID = "voice_repair"


#: Через сколько после подъёма процесса пройти в первый раз.
#:
#: ⚠ БЕЗ ЭТОГО ПРОГОН МОГ БЫ НЕ ВЫПОЛНИТЬСЯ ПОЧТИ НИКОГДА. `IntervalTrigger`
#: отсчитывает первый заход от старта, то есть через :data:`ИНТЕРВАЛ`, — а
#: планировщик перезапускается КАЖДОЙ выкаткой, и выкаток по замеру бывает
#: 9–22 в сутки. В плотный день отсчёт сбрасывался бы раньше, чем добегал до
#: конца.
#:
#: И это не только про частоту. Выкатка — ровно тот момент, когда среду
#: чинят: если расшифровка падала на правах или на месте, то первое, что
#: обязано случиться после подъёма, — повторная попытка.
#:
#: Две минуты, а не ноль: дать процессу дойти до рабочего состояния и не
#: соревноваться за пул соединений с миграциями и первой волной запросов.
ПЕРВЫЙ_ЗАХОД = timedelta(minutes=2)


def register(scheduler: Any) -> None:
    """Раз в :data:`ИНТЕРВАЛ`, и один раз вскоре после подъёма."""
    scheduler.add_job(
        repair_transcripts,
        IntervalTrigger(
            seconds=int(ИНТЕРВАЛ.total_seconds()),
            start_date=datetime.now(UTC) + ПЕРВЫЙ_ЗАХОД,
        ),
        id=JOB_ID,
        **DEFAULTS,
    )
