/* global self */
/*
 * ============================================================================
 * Сервис-воркер LeadChat — кнопки «Принять»/«Отклонить» ВНУТРИ уведомления.
 *
 * ЗАЧЕМ ОН ВООБЩЕ НУЖЕН. У `new Notification(...)`, которым веб-мост показывал
 * уведомления до 07.09, кнопок не бывает в принципе: поле `actions` существует
 * только у `registration.showNotification` — то есть только у воркера. Это не
 * особенность браузера, а разделение в самом стандарте, и обойти его нечем.
 * Всё остальное, что этот файл делает, — следствие: раз уж уведомление рисует
 * воркер, то и нажатие приходит к нему.
 *
 * Файл лежит в `public/` и едет в сборку КАК ЕСТЬ: Vite его не трогает, TS тут
 * нет, синтаксис — тот, что понимает браузер сам. В бою 100 % Chromium
 * (журнал nginx: Chrome 4576 запросов, Yandex Browser 484, Firefox и Safari —
 * ноль), поэтому `??` и шаблонные строки безопасны.
 *
 * ⚠ ЗДЕСЬ НАМЕРЕННО НЕТ ОБРАБОТЧИКА СЕТЕВЫХ ЗАПРОСОВ, И ЭТО ГЛАВНОЕ РЕШЕНИЕ
 * ВСЕГО ФАЙЛА. Стоит воркеру подписаться на событие сети, как он встаёт на путь
 * КАЖДОГО запроса вкладки и получает право отвечать своей копией. Тогда он
 * может: закэшировать бандл и отдавать вчерашний код после выкатки; пережить
 * откат образа и остаться единственным носителем сломанной версии; молча
 * подменить ответ API. Ни одна из этих бед нам не нужна ради кнопок в
 * уведомлении — а цена ошибки высока: воркер живёт в браузере человека дольше,
 * чем наш контейнер на сервере.
 *
 * Без такого обработчика воркер не участвует в загрузке вообще ничем: он спит,
 * пока браузер не разбудит его уведомлением. Ровно этого и хотим.
 * Сторож `ServiceWorker0709` следит, чтобы обработчик не завёлся «попутно».
 * ============================================================================
 */

/** Метка отправителя: `platform/serviceWorker.ts` отбирает сообщения по ней. */
const КАНАЛ = "leadchat-sw";

/** Нажали по телу уведомления, а не по кнопке: `event.action` тогда пуст. */
const ОТКРЫТЬ = "open";

self.addEventListener("install", () => {
  /*
   * Без `skipWaiting` новая версия воркера ждёт, пока закроются ВСЕ вкладки со
   * старой. У диспетчера их 11–13 за смену, и закрываются они не все сразу —
   * правка доехала бы в лучшем случае к следующему дню. Ждать нечего: воркер
   * не держит состояния и не стоит на пути запросов (см. шапку).
   */
  self.skipWaiting();
});

self.addEventListener("activate", (event) => {
  // `claim` забирает уже открытые вкладки под свежую версию, не дожидаясь
  // перезагрузки. Для вкладки это ничем не пахнет — воркер ей ничего не отдаёт.
  event.waitUntil(self.clients.claim());
});

self.addEventListener("notificationclick", (event) => {
  // Закрываем ПЕРВЫМ делом: дальше идёт ожидание вкладки, и всё это время
  // уведомление висело бы на экране уже нажатым.
  event.notification.close();

  const данные = event.notification.data ?? {};
  const conversationId = typeof данные.conversationId === "string" ? данные.conversationId : null;

  event.waitUntil(доставитьВоВкладку(event.action || ОТКРЫТЬ, conversationId));
});

/**
 * Передать нажатие вкладке — и ничего не делать самому.
 *
 * ⚠ ПОЧЕМУ ВОРКЕР НЕ ЗОВЁТ СЕРВЕР САМ. Соблазн есть: «Принять» — это один POST
 * на /conversations/{id}/claim, и воркер мог бы сходить туда напрямую. Не может:
 * токен доступа живёт В ПАМЯТИ ВКЛАДКИ, а не в куке — у воркера его нет и взять
 * негде. Обходить это (класть токен в общее хранилище, слать его сюда заранее)
 * значило бы размножить секрет ради удобства. Вкладка сделает тот же запрос
 * своей сессией: и проще, и один владелец у токена.
 *
 * Есть и вторая причина, продуктовая. Ответ сервера бывает 409 — «диалог уже
 * забрал коллега». Это норма при 30–33 операторах на канал, а не ошибка, и
 * показать её человеку способна только вкладка: у уведомления для этого нет ни
 * места, ни языка.
 */
async function доставитьВоВкладку(action, conversationId) {
  const вкладки = await self.clients.matchAll({ type: "window", includeUncontrolled: true });

  /*
   * Куда именно доставлять. У человека открыто несколько вкладок LeadChat, и
   * попасть надо в ту, на которую он смотрит, — иначе действие уедет в
   * свёрнутое окно, а перед глазами останется прежний экран. Порядок выбора:
   * вкладка в фокусе → просто видимая → любая. `includeUncontrolled` обязателен:
   * вкладка, открытая ДО установки воркера, им не управляется, и без этого
   * флага её здесь не видно вовсе.
   */
  const цель =
    вкладки.find((c) => c.focused) ?? вкладки.find((c) => c.visibilityState === "visible") ?? вкладки[0];

  if (цель) {
    цель.postMessage({ source: КАНАЛ, action, conversationId });
    // Право поднять окно даётся ровно на время обработки нажатия — но браузер
    // всё равно вправе отказать (окно на другом рабочем столе). Отказ не должен
    // отменять доставку: сообщение уже ушло строкой выше.
    if (typeof цель.focus === "function") await цель.focus().catch(() => {});
    return;
  }

  /*
   * Вкладок нет вовсе — уведомление пережило закрытие браузера. Открываем
   * диалог адресом.
   *
   * ⚠ САМО ДЕЙСТВИЕ ПРИ ЭТОМ ТЕРЯЕТСЯ, И ЭТО ВЫБОР, А НЕ НЕДОДЕЛКА. Свежей
   * вкладке нечего отправить: она ещё грузится, и `postMessage` в неё уходит в
   * никуда. Выполнить «Принять» вслепую в незагруженной вкладке хуже, чем не
   * выполнить: человек не увидел бы ни подтверждения, ни 409 от коллеги,
   * который забрал диалог раньше. Открытый диалог — честный ответ на нажатие:
   * кнопка «Принять» ждёт его на экране.
   */
  const адрес = conversationId ? `/chats/${encodeURIComponent(conversationId)}` : "/";
  await self.clients.openWindow(адрес);
}
