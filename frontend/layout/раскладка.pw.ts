/* ───────────────────────── сама проверка экранов ─────────────────────── */

for (const экран of ЭКРАНЫ) {
  const ключ = ключЭкрана(экран);
  test(`раскладка: ${ключ} — ${экран.что}`, async ({ page }) => {
    const м = манифест();
    const снимок = м.снимки[ключ];
    test.skip(
      !снимок?.есть || !снимок.свежий,
      `снимок протух или отсутствует — про это падает отдельный тест (чинить ${экран.снимает})`,
    );

    await page.goto(`/pw-${ключ}.html`);
    // Шрифт задаёт ширину каждой строки: померить до его загрузки — значит
    // померить чужие метрики и получить то придуманную обрезку, то пропуск.
    await page.evaluate(() => document.fonts.ready);

    const найдено: Array<{ ширина: number; рельса: number; беда: Беда }> = [];
    for (const ширина of ширины(экран)) {
      const высота = РАЗМЕРЫ.get(ширина) ?? 800;
      for (const рельса of рельсы(экран, ширина)) {
        await поставить(page, ширина, высота, рельса);
        const итог = await page.evaluate(померить);
        /*
         * ⚠ У ЭКРАНА ПОД ПОЛОСОЙ СПРАШИВАЕМ ТОЛЬКО ПРО НАКРЫТИЕ. Разметка под
         * полосой та же самая, значит те же обрезки и наезды всплыли бы
         * вторым разом под другим именем — и каждую пришлось бы заводить в
         * `известные.ts` дважды. Две записи об одной беде расходятся при
         * первой же починке: одну удалили, вторая осталась сторожить пустоту.
         *
         * Полоса добавляет ровно один новый вопрос — до чего теперь не
         * докликнуться, — и его здесь и задаём. Всё остальное про эту разметку
         * уже спрошено у исходного экрана.
         */
        const беды = экран.полоса
          ? итог.беды.filter((б) => б.признак === "накрыто")
          : экран.срез
            ? итог.беды.filter((б) => б.признак !== "рваный ряд")
            : итог.беды;
        for (const беда of беды) найдено.push({ ширина, рельса, беда });
      }
    }

    const записи = ОТКЛОНЕНИЯ.filter((о) => о.экран === ключ);
    const задетые = new Set<number>();
    const новые: string[] = [];
    const выросли: string[] = [];

    for (const { ширина, рельса, беда } of найдено) {
      const i = записи.findIndex((о) => совпало(о, ключ, ширина, рельса, беда));
      if (i === -1) {
        новые.push(
          `${ширина}px, рельса ${рельса}: ${беда.признак} на ${беда.сколько}px — ` +
            `${беда.узел}${беда.видно ? ` — «${беда.видно}»` : ""}`,
        );
        continue;
      }
      задетые.add(i);
      const о = записи[i];
      if (беда.сколько - о.сколько > ДОПУСК) {
        выросли.push(
          `${подпись(о)} — а намеряно ${беда.сколько}px при ${ширина}px, рельса ${рельса}: ` +
            `беда выросла, число в записи устарело`,
        );
      }
    }

    const починились = записи
      .filter((_, i) => !задетые.has(i))
      .map((о) => `${подпись(о)} — не воспроизводится, удалите строку (${о.чинится})`);

    expect(
      [...новые, ...выросли, ...починились],
      `экран «${экран.что}» (стенд ${ключ})`,
    ).toEqual([]);
  });
}

/* ─────────── политика возможностей: браузер её принимает ─────────────── */

test("политика возможностей не ругается в консоль", async ({ page }) => {
  /*
   * ⚠ ЭТА ПРОВЕРКА РОДИЛАСЬ ИЗ ЖАЛОБЫ ДИСПЕТЧЕРА В ТОТ ЖЕ ВЕЧЕР, ЧТО И ПРАВКА.
   * Расширяя Permissions-Policy 08.09, я написал рядом «браузер молча
   * пропускает незнакомые имена». Это неправда: на `ambient-light-sensor`
   * Chrome пишет «Error with Permissions-Policy header: Unrecognized feature»
   * при КАЖДОЙ загрузке страницы, у каждого человека, весь день. Работе не
   * мешает, но красная строка в консоли выглядит поломкой — и разбираться с
   * ней пришла смена.
   *
   * Стенд отдаёт БОЕВОЙ заголовок, прочитанный из того же сниппета, что
   * уезжает на сервер (`layout/сервер.js`), поэтому здесь проверяется не
   * копия списка, а он сам. Список имён при этом не перечисляется: сторож,
   * повторяющий список, устареет вместе с браузером, а этот спрашивает у
   * самого браузера.
   */
  const жалобы: string[] = [];
  page.on("console", (m) => {
    if (m.type() !== "error" && m.type() !== "warning") return;
    if (/permissions-policy/i.test(m.text())) жалобы.push(m.text());
  });

  await page.goto("/pw-markup.html");
  await page.evaluate(() => document.fonts.ready);

  expect(
    жалобы,
    "браузер не принял часть политики возможностей — эта строка появится в " +
      "консоли у каждого диспетчера при каждой загрузке",
  ).toEqual([]);
});

