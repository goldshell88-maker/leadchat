/**
 * СТОРОЖ РАСКЛАДКИ: единственная проверка в проекте, которая видит РЕЗУЛЬТАТ.
 *
 * ⚠ ЗАЧЕМ ОН ВООБЩЕ ПОЯВИЛСЯ. Остальные 338 сторожей проверяют НАМЕРЕНИЕ:
 * какое свойство выставлено, какой класс навешен, какое число лежит в токене.
 * jsdom вёрстку не считает вовсе — ни ширин, ни переносов, ни переполнений.
 * Поэтому редизайн уехал в бой при зелёном прогоне из 2564 тестов, а двадцать
 * бед адаптива прожили в продукте незамеченными: «съехало» — это результат, а
 * результат до сегодняшнего дня не мерил никто.
 *
 * ЧТО ЗДЕСЬ ПРОВЕРЯЕТСЯ (по одному тесту на экран):
 *   • МОЛЧА РЕЖЕТСЯ  — текст не влезает, а многоточия и прокрутки нет;
 *   • НАЕЗД ПО ВЫСОТЕ — содержимое легло поверх соседа снизу;
 *   • ВЫЛЕЗ ЗА РОДИТЕЛЯ ВПРАВО — родитель не прокручивается;
 *   • ПОЛОСА У СТРАНИЦЫ — горизонтальная полоса у всего окна.
 *
 * ЧЕГО ОН НЕ ВИДИТ — честно, чтобы не считали закрытым:
 *   1. Положение выпадающих панелей. Координаты им считает floating-ui по
 *      настоящим размерам якоря; в снимке из jsdom размеры нулевые, и панель
 *      стоит у левого верхнего угла. Меряется её собственная ширина и текст
 *      внутри — не то, вылезет ли она за край окна.
 *   2. Цвет и читаемость. Это `src/test/tokenContrast.test.ts`.
 *   3. Поведение: наведение, фокус, анимации. Снимок — это один кадр покоя.
 *   4. Светлую тему. Обоснование — в тесте «темы не двигают раскладку» ниже:
 *      он падает, если в теме появится хоть один размерный токен.
 */
import { expect, test } from "@playwright/test";
import { readFileSync } from "node:fs";

import { ЭКРАНЫ, РАЗМЕРЫ, ключЭкрана, рельсы, ширины } from "./экраны";
import { померить, type Беда } from "./мерка";
import { ДОПУСК, НЕ_СНИМАЮТСЯ, ОТКЛОНЕНИЯ, подпись, совпало } from "./известные";
import { ПУТЬ_МАНИФЕСТА, type Манифест } from "./подготовка";

function манифест(): Манифест {
  return JSON.parse(readFileSync(ПУТЬ_МАНИФЕСТА, "utf8")) as Манифест;
}

/**
 * Ставит окно, рельсу и даёт браузеру пересчитать раскладку.
 *
 * ⚠ ДВА КАДРА ОЖИДАНИЯ, А НЕ НОЛЬ И НЕ ТАЙМЕР. Смена вьюпорта пересчитывает
 * контейнерные запросы асинхронно: померить сразу — значит померить прошлую
 * ширину. Таймер на 200мс сделал бы то же самое, но медленнее и без гарантии;
 * два кадра — это ровно «раскладка применена и отрисована».
 */
async function поставить(
  страница: import("@playwright/test").Page,
  ширина: number,
  высота: number,
  рельса: number,
): Promise<void> {
  await страница.setViewportSize({ width: ширина, height: высота });
  await страница.evaluate((px: number) => {
    document.documentElement.style.setProperty("--lc-rail-w", `${px}px`);
  }, рельса);
  await страница.evaluate(
    () => new Promise<void>((r) => requestAnimationFrame(() => requestAnimationFrame(() => r()))),
  );
}

/* ─────────────────────── свежесть снимков разметки ───────────────────── */

test("снимки разметки свежие — иначе стенд мерит вчерашний день", () => {
  const м = манифест();
  const мёртвые = Object.entries(м.снимки).filter(([, с]) => !с.есть || !с.свежий);
  const принятые = new Set(НЕ_СНИМАЮТСЯ.map((н) => н.экран));

  const неожиданные = мёртвые
    .filter(([имя]) => !принятые.has(имя))
    .map(([имя, с]) => `${имя}: ${с.есть ? "снимок не обновился" : "снимка нет"} — чинить ${с.снимает}`);

  // Обратная сторона: снималка снова работает, а строка про неё осталась.
  const ожили = НЕ_СНИМАЮТСЯ.filter((н) => м.снимки[н.экран]?.свежий).map(
    (н) => `${н.экран}: снимок снова снимается, удалите строку из НЕ_СНИМАЮТСЯ (${н.чинится})`,
  );

  expect(
    [...неожиданные, ...ожили],
    "снимок разметки протух: стенд померил бы разметку, которой в продукте уже нет",
  ).toEqual([]);
});

/* ─────────────── обоснование того, что меряем одну тему ──────────────── */

test("темы не двигают раскладку — иначе одной темы мало", () => {
  /*
   * Стенд меряет ТЁМНУЮ тему. Это законно ровно до тех пор, пока тема меняет
   * цвета и тени, но не размеры: тень места не занимает, цвет тоже. Появится
   * в теме `--lc-space-*`, ширина колонки или кегль — и половина замеров
   * ослепнет МОЛЧА. Поэтому запрет записан явно и проверяется арифметикой.
   */
  const css = readFileSync("src/app/lc-vars.css", "utf8").replace(/\/\*[\s\S]*?\*\//g, "");
  const плохие: string[] = [];
  for (const [, селектор, тело] of css.matchAll(/([^{}]+)\{([^{}]*)\}/g)) {
    /*
     * ⚠ БАЗОВЫЙ БЛОК СЮДА НЕ ВХОДИТ. Он записан как
     * `:root, :root[data-mantine-color-scheme="dark"]` — то есть умолчание, а
     * не переопределение темы, и размерам в нём место: `--lc-row-time-w: 48px`
     * живёт именно там. Проверяем ПЕРЕОПРЕДЕЛЕНИЯ: светлую схему и пресеты.
     */
    const тематический =
      селектор.includes('color-scheme="light"') || селектор.includes("data-lc-preset");
    if (!тематический) continue;
    for (const [, имя, значение] of тело.matchAll(/(--[\w-]+)\s*:\s*([^;]+);/g)) {
      // Тени — единственная законная длина в теме: они не занимают места.
      if (/shadow/.test(имя)) continue;
      if (/\d+(px|rem|em|vh|vw|%)/.test(значение)) плохие.push(`${селектор.trim()} → ${имя}: ${значение.trim()}`);
    }
  }
  expect(
    плохие,
    "в теме появился размерный токен: раскладка стала зависеть от темы, и мерить одну тёмную больше нельзя",
  ).toEqual([]);
});

