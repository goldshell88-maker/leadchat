/**
 * МЕРКА: признаки беды, посчитанные в настоящем браузере.
 *
 * ⚠ ФУНКЦИЯ ЕДЕТ В СТРАНИЦУ ЦЕЛИКОМ (`page.evaluate`), поэтому она обязана
 * быть самодостаточной: никаких импортов, никаких внешних имён. Всё, чем она
 * пользуется, объявлено внутри неё. Отсюда её длина — это не небрежность, это
 * условие работы.
 *
 * ПОЧЕМУ ВООБЩЕ БРАУЗЕР. В проекте 338 сторожей, и все они проверяют
 * НАМЕРЕНИЕ: какое свойство выставлено, какой класс навешен. jsdom вёрстку не
 * считает вовсе — ни ширин, ни переносов, ни переполнений. А «съехало» — это
 * РЕЗУЛЬТАТ. Поэтому двадцать бед адаптива прожили в бою при зелёном прогоне
 * из 2564 тестов, и поэтому меряем здесь, а не там.
 *
 * ⚠ ГЛАВНОЕ ПРО ПОРОГИ НИЖЕ. Каждое условие здесь стоит не для красоты, а
 * потому что без него первый прогон 08.09 выдал сотни ложных находок. Убирая
 * условие, приготовьтесь разбирать их заново — история каждого записана рядом.
 */

/** Одна найденная беда. */
export interface Беда {
  признак:
    | "режется"
    | "вылез вправо"
    | "наезд по высоте"
    | "полоса у страницы"
    | "накрыто"
    | "рваный ряд";
  /** Короткий путь до узла — чтобы беду можно было найти в исходниках. */
  узел: string;
  /** На сколько пикселей. */
  сколько: number;
  /** Что в этом узле написано — по тексту место узнаётся быстрее, чем по классу. */
  видно: string;
}

export interface Итог {
  беды: Беда[];
  /** Сколько бед было ДО схлопывания одинаковых — для отчёта. */
  всего: number;
}

/**
 * Считает беды на текущей странице.
 *
 * ⚠ ЧЕГО ЗДЕСЬ НАМЕРЕННО НЕТ. Длинная страница — норма, а не беда: журнал
 * уведомлений на сорок строк обязан быть выше окна, и документ его
 * прокручивает. Ловится НАЕЗД — когда содержимое ложится ПОВЕРХ соседа снизу
 * или молча обрезается, — а не сам факт, что содержимого много.
 */
export function померить(): Итог {
  const корень = document.getElementById("стенд") ?? document.body;
  const беды: Беда[] = [];

  /** Короткий путь до узла: четыре колена от него вверх, без служебных классов. */
  function путь(el: Element): string {
    const части: string[] = [];
    for (let n: Element | null = el; n && n.id !== "стенд" && части.length < 4; n = n.parentElement) {
      const cls = (typeof n.className === "string" ? n.className : "")
        .split(" ")
        .filter((c) => c && !/^m_[0-9a-f]+$/.test(c) && !/^mantine-/.test(c))[0];
      части.unshift(cls ? n.tagName.toLowerCase() + "." + cls : n.tagName.toLowerCase());
    }
    return части.join(" > ");
  }

  function класс(el: Element): string {
    return typeof el.className === "string" ? el.className : "";
  }

  /** Видно ли узел вообще: невидимое мерить незачем. */
  function виден(el: Element): boolean {
    const cs = getComputedStyle(el);
    if (cs.display === "none" || cs.visibility === "hidden") return false;
    const r = el.getBoundingClientRect();
    return r.width >= 4 && r.height >= 4;
  }

  /**
   * Спрятан ли узел приёмом «1×1 + clip-path» (`lc-table--cards thead`,
   * `lc-visually-hidden`, Mantine VisuallyHidden).
   *
   * ⚠ БЕЗ ЭТОГО ОТСЕВА СТЕНД ВРЁТ. Первый ручной прогон 08.09 объявил бедой
   * строку подписей колонок в карточном режиме: сама шапка 1×1 и отсеивалась
   * по размеру, а её `tr` внутри — 26×78 и «обрезан на 462px». Человек не
   * видит ни того, ни другого: предок режет всё clip-path'ом.
   */
  function подКлипом(el: Element): boolean {
    for (let p = el.parentElement; p; p = p.parentElement) {
      const cs = getComputedStyle(p);
      if (cs.clipPath !== "none") return true;
      const r = p.getBoundingClientRect();
      if ((r.width <= 2 || r.height <= 2) && cs.overflow === "hidden") return true;
    }
    return false;
  }

  /**
   * Прокручивается ли по горизонтали хоть один предок: тогда вылезание вправо
   * законно — человек доедет до содержимого колесом или полосой.
   */
  function подПрокруткой(el: Element): boolean {
    for (let p = el.parentElement; p; p = p.parentElement) {
      const o = getComputedStyle(p).overflowX;
      if (o === "auto" || o === "scroll") return true;
    }
    return false;
  }

  /**
   * Видно ли узел ИМЕННО В ЭТОЙ ТОЧКЕ — то есть не срезан ли он прокруткой.
   *
   * ⚠ БЕЗ ЭТОГО ПРОВЕРКА ТОЧКОЙ ВРЁТ, И ПЕРВЫЙ ЖЕ ПРОГОН ЭТО ПОКАЗАЛ. В
   * журнале уведомлений последняя строка таблицы уехала за нижний край своего
   * прокручиваемого блока (`.lc-journal__scroll`: содержимое 588, окно 469).
   * Коробка у кнопки «Открыть диалог» осталась там, где она БЫЛА БЫ, — на
   * 660-м пикселе, — а нарисована кнопка не была вовсе: предок её срезал. В
   * той точке лежит «Вперёд» из подвала, и мерка объявила, что подвал накрыл
   * кнопку. Накрывать нечего: до кнопки доезжают колесом, и это норма.
   */
  function виденВТочке(el: Element, x: number, y: number): boolean {
    for (let n = el.parentElement; n && n.id !== "стенд"; n = n.parentElement) {
      const cs = getComputedStyle(n);
      if (cs.overflowX === "visible" && cs.overflowY === "visible") continue;
      const r = n.getBoundingClientRect();
      if (x < r.left || x > r.right || y < r.top || y > r.bottom) return false;
    }
    return true;
  }

  /**
   * Лежит ли узел внутри НАМЕРЕННОГО слоя: меню, окна, всплывашки, ящика.
   *
   * ⚠ ОПОЗНАЁМ ПО РОЛИ И ПО РОДНОМУ КЛАССУ MANTINE, А НЕ ПО ПУТИ. `путь`
   * вычищает служебные классы (`m_1b7284a3`, `mantine-…`), поэтому в отчёте
   * слой выглядит безымянным `div > div > div > div` — по такому следу его не
   * узнать ни человеку, ни коду.
   */
  function слой(el: Element): boolean {
    for (let n: Element | null = el; n && n.id !== "стенд"; n = n.parentElement) {
      const роль = n.getAttribute("role");
      if (роль === "dialog" || роль === "menu" || роль === "listbox" || роль === "tooltip") {
        return true;
      }
      if (n.hasAttribute("aria-modal")) return true;
      if (/mantine-(Overlay|Modal|Menu|Popover|Drawer|Tooltip|Combobox|Select)/.test(класс(n))) {
        return true;
      }
      /*
       * Свои слои проекта. У карточки клиента в узкой раскладке роли нет и
       * быть не должно — это панель, а не окно, — зато есть две приметы,
       * которыми приложение объявляет намерение накрыть: модификатор
       * `--overlay` у самой панели (`client-card--overlay`, chats-page.css) и
       * подложка `…-backdrop`, которая для того и нарисована, чтобы перехватить
       * нажатие мимо панели.
       *
       * ⚠ ПРИМЕТА ПО ИМЕНИ КЛАССА — ЗДЕСЬ ЭТО ВЕРНО, А НЕ СЛАБО. Новый оверлей
       * без этих примет мерка объявит бедой, и разбираться придётся глазами.
       * Ошибаться в эту сторону и надо: оверлей, накрывающий управление, —
       * решение, которое кто-то обязан принять вслух.
       */
      const кл = класс(n);
      if (/--overlay(\s|$)/.test(кл) || /-backdrop(\s|$)/.test(кл)) return true;
    }
    return false;
  }

  const режет = (o: string) => o === "hidden" || o === "clip";
  const крутит = (o: string) => o === "auto" || o === "scroll";

  for (const el of Array.from(корень.querySelectorAll("*"))) {
    if (!виден(el)) continue;
    const кл = класс(el);
    if (/VisuallyHidden|lc-visually-hidden/.test(кл)) continue;
    if (подКлипом(el)) continue;

    const cs = getComputedStyle(el);
    const r = el.getBoundingClientRect();
    const тег = el.tagName.toLowerCase();
    const текст = (el.textContent || "").trim().replace(/\s+/g, " ").slice(0, 60);
    /*
     * Внутренние классы Mantine (`m_1b7284a3`) на 2–4px — шум измерения:
     * округление рамок, теней и строчных боксов. Отсеиваем ТОЛЬКО у них: у
     * своих классов четыре пикселя — это четыре пикселя.
     * ⚠ СМОТРИМ КЛАСС САМОГО УЗЛА, А НЕ ЕГО ПУТЬ. Путь служебные классы
     * ВЫЧИЩАЕТ (см. `путь` выше), и отсев по пути не сработал ни разу: в
     * первом прогоне 08.09 он пропустил 4-пиксельный шум переключателей
     * Mantine на девяти экранах настроек разом.
     */
    const шумныйУзел = /(^|\s)(m_[0-9a-f]+|mantine-)/.test(кл);
    const мелочь = (сколько: number) => шумныйУзел && сколько <= 4;

    /*
     * 1. МОЛЧА РЕЖЕТСЯ. Текст не влез, и его ОБРЕЗАЛИ: ни многоточия, ни
     *    прокрутки. Человек не знает, что чего-то не видит.
     *
     * ⚠ ТРЕБУЕМ ИМЕННО ОБРЕЗКУ (`hidden`/`clip`), И ЭТО НЕ ОСЛАБЛЕНИЕ.
     * `scrollWidth > clientWidth` при `overflow: visible` значит, что
     * содержимое ТОРЧИТ, а не исчезло — его видно, и ловит его признак 3
     * («вылез вправо») вместе с полосой у страницы. Без этого условия первый
     * прогон 08.09 выдал 4-пиксельные «обрезки» у каждого переключателя,
     * каждого аватара и каждой подписи: у строчного бокса высота строки чуть
     * больше своей коробки, и это видно ровно никак.
     */
    const дельта = el.scrollWidth - el.clientWidth;
    if (
      дельта > 1 &&
      режет(cs.overflowX) &&
      cs.textOverflow !== "ellipsis" &&
      тег !== "textarea" &&
      !мелочь(дельта)
    ) {
      беды.push({ признак: "режется", узел: путь(el), сколько: дельта, видно: текст });
    }

    /*
     * 2. НАЕЗД ПО ВЫСОТЕ: содержимое вылезло за нижний край своего блока.
     *
     * ⚠ ЗАЧЕМ ВООБЩЕ МЕРИТЬ ВЫСОТУ. Самая дорогая беда третьего захода была
     * именно вертикальной: флекс-колонка отняла высоту у шапки ленты (у
     * флекс-элемента умолчание `flex-shrink: 1`), содержимому шапки нужно
     * было 210px, нарисована она 64px — 147 пикселей строк легли ПОВЕРХ
     * полосы «Диалог ведёт бот» и надписи «В работе у вас». По горизонтали
     * при этом всё было ровно, и проверка одних ширин её не увидела бы.
     *
     * ⚠ ДВА УСЛОВИЯ, БЕЗ КОТОРЫХ ЭТО ПРЕВРАЩАЕТСЯ В ШУМ.
     *   а) БЛОК РЕЖЕТ содержимое (`hidden`/`clip`) ИЛИ у блока есть СЛЕДУЮЩИЙ
     *      ВИДИМЫЙ БРАТ. Если брата нет и блок не режет — содержимое просто
     *      продолжается вниз, и документ его прокручивает: так устроен любой
     *      длинный экран, и «Что нового» честно давал 2426px «наезда»,
     *      которого человек не видит вовсе.
     *   б) СЧИТАЕМ ПО ДЕТЯМ-ЭЛЕМЕНТАМ, а не по `scrollHeight`. `scrollHeight`
     *      прибавляет и строчный бокс текста, который выступает СИММЕТРИЧНО
     *      вверх и вниз (аватар рельса: коробка 36, строка 39) — наезда там
     *      нет, а число есть.
     */
    if (!крутит(cs.overflowY)) {
      let низДетей = -Infinity;
      for (const ребёнок of Array.from(el.children)) {
        const дcs = getComputedStyle(ребёнок);
        if (дcs.position === "absolute" || дcs.position === "fixed") continue;
        if (!виден(ребёнок)) continue;
        низДетей = Math.max(низДетей, ребёнок.getBoundingClientRect().bottom);
      }
      let братСнизу = false;
      for (let б = el.nextElementSibling; б; б = б.nextElementSibling) {
        if (виден(б)) {
          братСнизу = true;
          break;
        }
      }
      const наезд = Math.round((низДетей - r.bottom) * 10) / 10;
      if (
        низДетей > -Infinity &&
        наезд > 1.5 &&
        (режет(cs.overflowY) || братСнизу) &&
        !мелочь(наезд)
      ) {
        беды.push({ признак: "наезд по высоте", узел: путь(el), сколько: наезд, видно: текст });
      }
    }

    /*
     * 3. ВЫЛЕЗ ЗА РОДИТЕЛЯ ВПРАВО. Прокручивается родитель или любой предок —
     *    вылезание законно: до содержимого можно доехать.
     */
    const p = el.parentElement;
    if (p && p !== корень && cs.position !== "fixed" && cs.position !== "absolute") {
      const pr = p.getBoundingClientRect();
      const вправо = Math.round((r.right - pr.right) * 10) / 10;
      if (вправо > 1.5 && !подПрокруткой(el) && !мелочь(вправо)) {
        беды.push({ признак: "вылез вправо", узел: путь(el), сколько: вправо, видно: текст });
      }
    }
  }

  /*
   * 4. ПОЛОСА У СТРАНИЦЫ по горизонтали. Рабочее место занимает окно целиком;
   *    горизонтальная полоса здесь значит, что вправо уехало что-то, чего у
   *    человека нет способа увидеть, не сдвинув весь экран.
   */
  const de = document.documentElement;
  const полоса = de.scrollWidth - de.clientWidth;
  if (полоса > 1) {
    беды.push({ признак: "полоса у страницы", узел: "html", сколько: полоса, видно: "" });
  }

  /*
   * 5. НАКРЫТО — до управления не докликнуться.
   *
   * ⚠ ЗАЧЕМ ОТДЕЛЬНЫЙ ПРИЗНАК. Первые четыре ловят содержимое, которое НЕ
   * ПОМЕСТИЛОСЬ. Здесь беда обратная: помещается всё, коробки на своих местах,
   * ни одного переполнения — а нажать нельзя, потому что сверху лежит оверлей.
   * Ровно так прожил дефект H-04: полоса «вышло обновление» накрывала
   * «Выгрузить CSV» на «Диалогах» и пункт «Аккаунты Авито» в настройках, и
   * все прежние мерки показывали чистый экран.
   *
   * ⚠ ПРОБА ТОЧКОЙ, А НЕ РАЗБОР `z-index`. Кто окажется сверху, решают слой,
   * контекст наложения, порядок в документе и `pointer-events` — четыре
   * правила, которые в сумме не считаются на бумаге. `elementFromPoint`
   * отвечает тем же способом, что и настоящее нажатие: браузер сам говорит,
   * во что попадёт палец.
   *
   * Мерим ЦЕНТР: край управления может быть накрыт законно (соседняя панель
   * с тенью, скруглённый угол), а центр — это то место, куда целятся.
   */
  const УПРАВЛЕНИЕ =
    'button, a[href], input, select, textarea, [role="button"], [role="tab"], [role="switch"], [role="menuitem"], [role="option"]';
  const окноШ = document.documentElement.clientWidth;
  const окноВ = document.documentElement.clientHeight;
  for (const el of Array.from(корень.querySelectorAll(УПРАВЛЕНИЕ))) {
    if (!виден(el) || подКлипом(el)) continue;
    if (/VisuallyHidden|lc-visually-hidden/.test(класс(el))) continue;
    const r = el.getBoundingClientRect();
    const x = Math.round(r.left + r.width / 2);
    const y = Math.round(r.top + r.height / 2);
    /*
     * За краем экрана `elementFromPoint` возвращает null на любой причине —
     * и на «уехало вниз», и на «накрыто». Это чужая беда: её ловят признаки
     * выше, а здесь она дала бы ложное имя.
     */
    if (x < 0 || y < 0 || x >= окноШ || y >= окноВ) continue;
    if (!виденВТочке(el, x, y)) continue;
    const сверху = document.elementFromPoint(x, y);
    if (!сверху || el.contains(сверху) || сверху.contains(el)) continue;
    /*
     * ⚠ ЗАКОННОЕ НАКРЫТИЕ НЕ БЕДА, И БЕЗ ЭТОГО ОТСЕВА ПРИЗНАК БЕСПОЛЕЗЕН.
     * Первый прогон 08.09 выдал 60 «бед» на восьми экранах: открытое меню
     * «Статус диалога», окна «Передать диалог» и «Позвать коллегу», панель
     * быстрых ответов, карточка клиента оверлеем. Все они накрывают работу
     * НАРОЧНО — в этом их смысл, и человек знает, что нажать надо сперва в
     * них. Беда — только та, о которой человек не просил.
     */
    if (слой(сверху)) continue;
    /*
     * Насколько накрыто — по вертикали: полоса ложится сверху, и глубина
     * наложения сразу говорит, на сколько её отодвигать.
     */
    const cr = сверху.getBoundingClientRect();
    const глубина =
      Math.round((Math.min(r.bottom, cr.bottom) - Math.max(r.top, cr.top)) * 10) / 10;
    /*
     * ⚠ УЗЕЛ — ТОЛЬКО НАКРЫТЫЙ, НАКРЫВАЮЩИЙ УХОДИТ В ЧЕЛОВЕЧЕСКОЕ ПОЛЕ. Сперва
     * я склеивал оба пути в `узел`, и одна беда рассыпалась на четыре записи:
     * у кнопки «Отказаться» сверху оказывался то `kbd` подсказки, то
     * переключатель режима, то само поле ввода — смотря какая ширина. Сверка с
     * известными отклонениями идёт по `узел` дословно, то есть на одну беду
     * пришлось бы четыре строки списка, и починка гасила бы их поодиночке.
     */
    беды.push({
      признак: "накрыто",
      узел: путь(el),
      сколько: Math.max(глубина, 1),
      видно:
        ((el.textContent || "").trim().replace(/\s+/g, " ").slice(0, 40) || "без подписи") +
        " ← накрывает " +
        путь(сверху),
    });
  }

  /*
   * 6. РВАНЫЙ РЯД — обрамлённые панели одного ряда кончаются на разной высоте.
   *
   * ⚠ ЭТО НЕ ПЕРЕПОЛНЕНИЕ И НЕ НЕДОСТУПНОСТЬ, А ТРЕТИЙ РОД БЕДЫ: всё влезло,
   * всё нажимается, но ряд не читается рядом. Найдено глазами на «Статистике»
   * 08.09: `.stats-page__row` стоял на `align-items: start` без единого слова о
   * причине, и график с тепловой картой кончались на 320 и 286 пикселях —
   * рваный край в 34 пикселя между двумя карточками с рамками.
   *
   * ⚠ СУДИМ ТОЛЬКО ПО ОБРАМЛЁННЫМ СОСЕДЯМ, И ЭТО ГЛАВНОЕ ОГРАНИЧЕНИЕ. У
   * безрамочных блоков разная высота — норма: их край не виден. Рамка же край
   * рисует, и глаз сравнивает его с соседним. Плюс требуем общий верх: панели
   * разных рядов сравнивать не за что.
   */
  for (const родитель of Array.from(корень.querySelectorAll("*"))) {
    const дети = Array.from(родитель.children).filter((el) => {
      if (!виден(el)) return false;
      const cs = getComputedStyle(el);
      if (cs.position === "absolute" || cs.position === "fixed") return false;
      return parseFloat(cs.borderTopWidth) > 0 && cs.borderTopStyle !== "none";
    });
    if (дети.length < 2) continue;
    const коробки = дети.map((el) => el.getBoundingClientRect());
    const верх = Math.min(...коробки.map((r) => r.top));
    /* Один ряд: все начинаются на одной высоте. Иначе это стопка, а не ряд. */
    if (коробки.some((r) => Math.abs(r.top - верх) > 2)) continue;
    const низы = коробки.map((r) => r.bottom);
    const разброс = Math.round((Math.max(...низы) - Math.min(...низы)) * 10) / 10;
    if (разброс > 2) {
      беды.push({
        признак: "рваный ряд",
        узел: путь(родитель),
        сколько: разброс,
        видно: `панелей в ряду ${дети.length}`,
      });
    }
  }

  /* Одинаковые строки списка дают одну и ту же беду десять раз подряд. */
  const виденРаньше = new Set<string>();
  const уник = беды.filter((б) => {
    const k = б.признак + "|" + б.узел + "|" + б.сколько;
    if (виденРаньше.has(k)) return false;
    виденРаньше.add(k);
    return true;
  });
  уник.sort((a, b) => b.сколько - a.сколько);

  return { беды: уник, всего: беды.length };
}
