/**
 * ЧТО МЕРЯЕМ: список экранов стенда адаптива и размеров, на которых их гоняем.
 *
 * ⚠ ГЛАВНОЕ ПРО ЭТОТ ФАЙЛ. Снимок разметки снят в jsdom при ОДНОЙ ширине окна
 * (`ширинаОкна(...)` в соответствующем `src/test/*.dump.tsx`), и React в нём
 * уже принял решения, которые от ширины зависят: рисовать карточку клиента
 * оверлеем или колонкой, показывать список или ленту, ставить кнопку «Назад».
 * Поэтому у каждого снимка есть ДИАПАЗОН ширин, на котором он честен, и мерить
 * его вне диапазона — значит мерить состояние, которого у человека не бывает.
 * Диапазоны ниже повторяют пороги из `src/shared/lib/breakpoints.ts`:
 * MOBILE_MAX = 767 (окно), NARROW_MAX = 1359 (рабочее место).
 *
 * ⚠ ВТОРОЕ ГЛАВНОЕ. Рельса приложения развёрнута по умолчанию и занимает
 * 218px (`railStore.ts`), а в CSS лежит запасное `--lc-rail-w: 72px`. Разница
 * 146px — из-за неё пороги, написанные по ширине ОКНА, срабатывали не там, где
 * их ждали. Каждый экран рабочего места гоняется при ОБЕИХ рельсах.
 */

/** Как стенд обрамляет снимок — см. layout/подготовка.ts. */
export type Каркас =
  /** Рельса слева + колонка `.lc-main` (в ней объявлен контейнер lc-workspace). */
  | "место"
  /** Экран во всё окно без рельсы: вход, «забыли пароль». */
  | "страница"
  /** Сам снимок и есть рельса: обрамляем колонкой её ширины. */
  | "рельса";

export interface Экран {
  /** Имя снимка в `.dump` без `.html`. */
  имя: string;
  /**
   * Имя ПРОВЕРКИ, если оно отличается от имени снимка: один и тот же снимок
   * меряется в двух положениях (без полосы и с полосой). По нему зовётся файл
   * стенда, называется тест и сверяются известные отклонения.
   */
  ключ?: string;
  /**
   * Снимок — СРЕЗ страницы, а не вся она: в него попала лишь часть колонок или
   * лента без виртуализованных сообщений. Признак «рваный ряд» на таких не
   * считается: он сравнивает высоты соседних панелей, а у среза высота
   * ненастоящая.
   *
   * ⚠ ЗАМЕР, КОТОРЫМ ЭТО УСТАНОВЛЕНО (08.09). В полном снимке `markup` обе
   * панели чатов равны на всех пяти проверенных ширинах (902 и 902 при
   * 1920×950). В срезе `sloi-note-mode` лента 334 против списка 857 —
   * `react-virtual` в jsdom считает высоту от измеренной, а она ноль, и лента
   * схлопывается. Это свойство снимка, а не продукта.
   */
  срез?: true;
  /**
   * Поставить над экраном стопку полос — ровно так, как это делает `AppLayout`.
   * Разметку даёт снимок `polosa.html` (`src/test/polosa-снимок.dump.tsx`).
   */
  полоса?: true;
  каркас: Каркас;
  /** [мин, макс] ширины окна, на которых снимок соответствует бою. */
  диапазон: [number, number];
  /** Плотная сетка ширин (у экранов со своими порогами) или редкая. */
  сетка?: "плотно" | "редко";
  /** Ровно эти ширины, если снимок снят под конкретную (матрица графика). */
  ширины?: number[];
  /** Ровно эти рельсы, если снимок снят под конкретную. */
  рельсы?: number[];
  /** Какой снимающий тест его делает — куда идти, если снимок протух. */
  снимает: string;
  /** Что это за экран человеческими словами (попадает в текст падения). */
  что: string;
}

