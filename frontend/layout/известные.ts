/** Совпадает ли найденная беда с записью. */
export function совпало(
  о: Отклонение,
  экран: string,
  ширина: number,
  рельса: number,
  б: Беда,
): boolean {
  return (
    о.экран === экран &&
    о.признак === б.признак &&
    о.узел === б.узел &&
    (о.ширина === undefined || о.ширина === ширина) &&
    (о.рельса === undefined || о.рельса === рельса)
  );
}

/** Как запись выглядит в тексте падения. */
export function подпись(о: Отклонение): string {
  const где = [о.ширина ? `${о.ширина}px` : null, о.рельса ? `рельса ${о.рельса}` : null]
    .filter(Boolean)
    .join(", ");
  return `${о.экран}: ${о.признак} у ${о.узел}${где ? ` (${где})` : ""} — ${о.сколько}px`;
}
