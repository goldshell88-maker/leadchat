/**
 * Конфиг проверки раскладки. НЕ ЧАСТЬ ПРОДУКТА и НЕ ЧАСТЬ ОБЩЕГО ПРОГОНА.
 *
 * Запуск: npm run layout
 *
 * ⚠ ТОЛЬКО CHROMIUM, И ЭТО СЧИТАНО, А НЕ ПРИКИНУТО. В журнале nginx боевого
 * сервера за смену: Chrome 4576 запросов, Yandex 484 (тот же Blink), Firefox 0,
 * Safari 0. Тянуть три браузера ради нулей — это +400 МБ на каждую машину и
 * втрое дольше прогон.
 *
 * ⚠ НИ ОДНОГО ПОВТОРА. `retries: 0` намеренно: мигающий сторож хуже
 * отсутствующего — его начинают перезапускать вместо того, чтобы читать. Если
 * проверка замигает, чинить надо проверку, а не добавлять повтор.
 */
import { defineConfig, devices } from "@playwright/test";

const ПОРТ = Number(process.env.LAYOUT_PORT ?? 8742);

export default defineConfig({
  testDir: ".",
  /*
   * ⚠ РАСШИРЕНИЕ `.pw.ts`, А НЕ `.spec.ts`. У vitest в этом проекте include по
   * умолчанию (`**\/*.{test,spec}.*`), и файл с именем `*.spec.ts` попал бы в
   * ОБЩИЙ прогон: `npm test` попытался бы выполнить его в jsdom и упал бы на
   * импорте @playwright/test. Имя — это и есть замок.
   */
  testMatch: /.*\.pw\.ts$/,
  globalSetup: "./подготовка.ts",
  // Браузер медленный, а экранов много: полный прогон ~2 минуты на четырёх
  // рабочих. Один тест — один экран, поэтому таймаут щедрый.
  timeout: 120_000,
  expect: { timeout: 10_000 },
  fullyParallel: true,
  workers: 4,
  retries: 0,
  forbidOnly: !!process.env.CI,
  reporter: [["list", { printSteps: false }]],
  /*
   * Следы падений — в `.dump`, а не в `frontend/test-results`. `.dump` уже
   * лежит в `.gitignore` (там же стенды), а каталог по умолчанию оказался бы
   * непрослеженным мусором в корне фронта после первого же красного прогона.
   */
  outputDir: "../.dump/pw-следы",
  use: {
    baseURL: `http://127.0.0.1:${ПОРТ}`,
    // Ширину и высоту задаёт сам тест по матрице размеров.
    viewport: { width: 1440, height: 800 },
    /*
     * Ровно 1 — иначе округление рамок и теней даёт дробные пиксели, и
     * пороги «больше 1.5px» начинают срабатывать от масштаба, а не от беды.
     */
    deviceScaleFactor: 1,
  },
  projects: [{ name: "chromium", use: { ...devices["Desktop Chrome"] } }],
  /*
   * Ждём ПОРТ, а не файл: сервер поднимается раньше `globalSetup`, а манифест
   * появляется только после него — проверка по адресу файла не прошла бы
   * никогда.
   */
  webServer: {
    command: "node layout/сервер.js",
    port: ПОРТ,
    cwd: "..",
    reuseExistingServer: true,
    timeout: 20_000,
  },
});
