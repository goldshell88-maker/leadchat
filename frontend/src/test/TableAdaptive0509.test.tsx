/**
 * «РАЗБОР ДИАЛОГОВ» НА ЛЮБОМ ЭКРАНЕ (правка 05.09).
 *
 * ⚠ ПОЧЕМУ СТОРОЖ ЧИТАЕТ ИСХОДНИК CSS. В vitest стоит `css: false`: стилей в
 * jsdom нет вовсе, ширины и высоты нулевые, и НИ ОДИН рендер-тест возврата
 * медиазапроса не заметит. Числа ниже померены в браузере на статическом
 * стенде, подключающем настоящие css-файлы, и записаны рядом с проверками.
 *
 * Файл читается с диска, а не импортируется с `?raw`: на `?raw` Vite при
 * `css: false` отдал бы пустую строку, и проверка молча позеленела бы.
 */

const CSS = readFileSync("src/features/table/table.css", "utf-8") as string;
const TSX = readFileSync("src/features/table/TablePage.tsx", "utf-8") as string;

/** CSS без комментариев: в них старые значения разбираются как БЫВШИЕ. */
const КОД = CSS.replace(/\/\*[\s\S]*?\*\//g, " ");

/** Тело правила по селектору. Ищем именно объявление, а не упоминание. */
function правило(селектор: string): string {
  const at = КОД.indexOf(`${селектор} {`);
  expect(at, `правило ${селектор} не найдено`).toBeGreaterThan(-1);
  return КОД.slice(at, КОД.indexOf("}", at));
}

/** Тело медиазапроса по его условию (со вложенными правилами). */
function медиа(условие: string): string {
  const at = КОД.indexOf(`@media ${условие} {`);
  expect(at, `медиазапрос ${условие} пропал`).toBeGreaterThan(-1);
  // Блок кончается на строке с одинокой закрывающей скобкой в нулевой колонке.
  const конец = КОД.indexOf("\n}", at);
  expect(конец, `медиазапрос ${условие} не закрыт`).toBeGreaterThan(at);
  return КОД.slice(at, конец);
}

describe("Карточка на узком экране не наследует табличную высоту строки", () => {
  /*
   * ⚠ ГЛАВНАЯ НАХОДКА ПРАВКИ, И САМАЯ ТИХАЯ.
   *
   * 04.09 строке таблицы задали высоту числом (`height: 60px` у ячейки), чтобы
   * колонка имён перестала ехать. В таблице `height` у ячейки — это МИНИМУМ. В
   * карточном режиме та же ячейка становится `display: flex`, и там `height` —
   * это ТОЧНАЯ высота каждой строчки карточки.
   *
   * Замер на 375×812: карточка 566 пикселей, девять строчек по 60 — на телефон
   * помещался один диалог из пятидесяти. Правило `padding: var(--lc-space-2) 0`
   * из общего `lc-table-cards.css` при этом стояло на месте и не работало: вес
   * (0,1,2) против (0,2,0) у табличного.
   *
   * После правки: 420 пикселей.
   */
  const карточки = медиа("(max-width: 900px)");

  it("высота ячейки в карточке отпущена", () => {
    expect(карточки, "карточка снова получит девять строчек по 60 пикселей").toMatch(
      /\.dt__scroll \.lc-table--cards tr td\s*\{[^}]*height:\s*auto/,
    );
  });

  it("горизонтальный отступ ячейки в карточке снят", () => {
    // Иначе к 12 пикселям поля самой карточки прибавляются 12 отступа ячейки,
    // и название канала переносится на вторую строку там, где помещалось в одну.
    expect(карточки, "табличный отступ снова приезжает внутрь карточки").toMatch(
      /\.dt__scroll \.lc-table--cards tr td\s*\{[^}]*padding:\s*var\(--lc-space-2\) 0/,
    );
  });

  it("отмена написана селектором не слабее того, что отменяет", () => {
    /*
     * ⚠ ЭТО НЕ ПРИДИРКА К ФОРМЕ ЗАПИСИ, А СУТЬ ДЕФЕКТА. Ровно на этом сгорело
     * правило в общем файле: `.lc-table--cards tr td` (0,1,2) проигрывает
     * `.dt__scroll .mantine-Table-td` (0,2,0) и не применяется вовсе. Отмена
     * обязана нести те же два класса, иначе она такая же немая.
     */
    const классов = (с: string) => (с.match(/\./g) ?? []).length;
    expect(классов(".dt__scroll .lc-table--cards tr td")).toBeGreaterThanOrEqual(
      классов(".dt__scroll .mantine-Table-td"),
    );
    expect(карточки).toContain(".dt__scroll .lc-table--cards tr td");
  });

  it("табличная высота при этом на месте — отменяется только в карточке", () => {
    // Отрицательная половина: убери `height: 60px` из таблицы совсем — и
    // колонка имён поедет снова (tableRowLine0409.test.ts про то же).
    expect(правило(".dt__scroll .mantine-Table-td")).toMatch(/height:\s*60px/);
  });

  it("имя клиента в карточке дотягивает до нормы мишени", () => {
    // Строчный текст даёт 21 пиксель высоты, а по имени открывают диалог
    // пальцем. 24 — нижняя граница нормы.
    expect(карточки, "мишень имени в карточке снова ниже 24 пикселей").toMatch(
      /\.dt \.dt__open\s*\{[^}]*min-height:\s*24px/,
    );
  });
});

describe("Ширина экрана используется, а не игнорируется", () => {
  it("таблица занимает всю ширину своей карточки", () => {
    /*
     * Замер 2560×1200: обёртка 2446, таблица 1496 — 950 пикселей карточки
     * пустовали, подсветка строки обрывалась на середине.
     */
    expect(правило(".dt__scroll table"), "таблица снова ужимается по содержимому").toMatch(
      /width:\s*100%/,
    );
  });

  it("потолок обрезки — вилка от ширины окна, а не одно число", () => {
    /*
     * 15 знаков подбирались, когда таблица не помещалась в ноутбук, и стояли
     * одни на все ширины: на мониторе 27" название канала обрезалось до 142
     * пикселей при 950 пустых рядом. Каналы у заказчика различаются ХВОСТОМ
     * («Север-2» против «Север-3»), а видно было начало.
     */
    for (const [селектор, пол] of [
      [".dt__ell", "15ch"],
      [".dt__ell--wide", "22ch"],
    ] as const) {
      const тело = правило(селектор);
      const m = /max-width:\s*clamp\(\s*([^,]+),\s*([^,]+),\s*([^)]+)\)/.exec(тело);
      expect(m, `${селектор}: потолок обрезки снова задан одним числом`).toBeTruthy();
      expect(m![1].trim(), `${селектор}: пол вилки уехал — узкий экран изменится`).toBe(пол);
      expect(m![2], `${селектор}: середина вилки не зависит от окна`).toContain("vw");
    }
  });

  it("рост начинается ПОСЛЕ запаса, а не до него", () => {
    /*
     * ⚠ САМОЕ ЛЁГКОЕ МЕСТО ДЛЯ ПОРЧИ: поднять коэффициент, «чтобы шире». 9vw
     * догоняет пол 15ch около 1475 пикселей окна, а таблица целиком влезает в
     * обёртку начиная примерно с 1450. Возьми больше — и на ходовом 1440
     * колонки начнут расти раньше, чем появилось место, то есть вернётся
     * горизонтальная прокрутка, ради снятия которой потолок и заводили.
     */
    const vw = (селектор: string) =>
      Number(/clamp\([^,]+,\s*([\d.]+)vw/.exec(правило(селектор))![1]);
    expect(vw(".dt__ell"), "узкая колонка начнёт расти раньше времени").toBeLessThanOrEqual(9);
    expect(vw(".dt__ell--wide"), "широкая колонка начнёт расти раньше времени").toBeLessThanOrEqual(
      13,
    );
  });

  it("поля экрана на телефоне уже, чем на ноутбуке", () => {
    // 24 пикселя с каждой стороны — это 48 из 375, тринадцать процентов ширины.
    expect(медиа("(max-width: 767px)"), "телефон снова платит 48 пикселей за поля").toMatch(
      /\.dt\s*\{[^}]*padding:\s*var\(--lc-space-4\)/,
    );
  });
});

describe("Отступ ячейки живёт в одном месте", () => {
  /*
   * Его читают три правила: шапка, ячейка и растянутая на всю ячейку кнопка
   * сортировки (у неё он стоит в ОТРИЦАТЕЛЬНОМ поле). Пока число было написано
   * в каждом своей рукой, комментарий просил «числа обязаны совпадать» — то
   * есть держал правило уговором. Разъезд не виден на глаз: кнопка либо не
   * дотягивается до края ячейки, либо вылезает за него.
   */
  it("объявлен один раз", () => {
    expect(правило(".dt"), "переменная отступа ячейки пропала").toMatch(/--dt-cell-x:\s*var\(/);
  });

  for (const селектор of [
    ".dt__scroll .mantine-Table-th",
    ".dt__scroll .mantine-Table-td",
    ".dt__sort",
  ]) {
    it(`${селектор} берёт отступ оттуда же`, () => {
      /*
       * ⚠ ПРОВЕРЯЕТСЯ ИМЕННО СТРОКА `padding`, А НЕ НАЛИЧИЕ ИМЕНИ В ПРАВИЛЕ.
       * Первая редакция искала `var(--dt-cell-x)` где угодно в теле — и
       * диверсия «вернуть в padding кнопки прежний --lc-space-4» прошла её
       * насквозь: имя оставалось в соседней строке `margin`, и проверка
       * зеленела на своём же дефекте.
       */
      expect(правило(селектор), `${селектор}: свой отступ мимо общего числа`).toMatch(
        /padding:\s*var\(--lc-space-3\) var\(--dt-cell-x\)/,
      );
    });
  }

  it("кнопка сортировки вытянута ровно на тот же отступ", () => {
    // Отрицательное поле обязано быть той же величины: меньше — кнопка не
    // дотянется до края столбца, больше — вылезет в соседний.
    expect(правило(".dt__sort")).toMatch(/margin:[^;]*calc\(var\(--dt-cell-x\) \* -1\)/);
  });
});

describe("Движение объясняет и слушает «меньше движения»", () => {
  it("длительностей числом в файле нет", () => {
    // 120ms были единственным временем в файле и разъехались бы со шкалой
    // первыми. Общая шкала — --lc-dur-* (150/200/250/300).
    const числом = [...КОД.matchAll(/(?:transition|animation):[^;]*?\b\d+m?s\b/g)].map((m) => m[0]);
    expect(числом, `длительность мимо шкалы:\n${числом.join("\n")}`).toEqual([]);
  });

  it("переход приглушения гасится при «меньше движения»", () => {
    /*
     * ⚠ ОБЩЕЕ ПРАВИЛО СЮДА НЕ ДОСТАЁТ. `lc-vars.css` гасит АНИМАЦИИ и
     * намеренно не трогает переходы (без них состояния кнопок мигают).
     * Приглушение таблицы при догрузке — переход, и человеку, попросившему
     * меньше движения, страница по-прежнему плавно тускнела на каждый фильтр.
     */
    const тише = медиа("(prefers-reduced-motion: reduce)");
    expect(тише, "переход приглушения снова играет при «меньше движения»").toMatch(
      /\.dt__scroll\[data-stale\]\s*\{[^}]*transition:\s*none/,
    );
  });
});

describe("Иерархия: число крупнее подписи, имя крупнее ряда", () => {
  it("«Найдено» набрано ступенью показателя, а подпись — самой мелкой", () => {
    const значение = правило(".dt__found-value");
    const подпись = правило(".dt__found-label");
    expect(значение, "число найденного снова одного кегля с соседями").toContain(
      "var(--lc-fz-metric)",
    );
    expect(подпись, "подпись под числом набрана не мельче него").toContain("var(--lc-fz-micro)");
    expect(значение).not.toContain("var(--lc-fz-micro)");
  });

  it("имя клиента крупнее и жирнее остального ряда", () => {
    /*
     * Ряд из девяти равнозначных значений не читается: по нему приходится идти
     * слева направо целиком, хотя ищут в нём всегда одно — кого открыть.
     */
    expect(правило(".dt__scroll table"), "тело таблицы съехало со ступени плотных таблиц").toContain(
      "var(--lc-fz-note)",
    );
    const имя = правило(".dt__open");
    expect(имя, "имя клиента сравнялось кеглем с остальным рядом").toContain("var(--lc-fz-body)");
    expect(имя, "имя клиента сравнялось начертанием с остальным рядом").toContain(
      "var(--lc-fw-semibold)",
    );
  });

  it("панель «Ещё» отделена поверхностью, а не одним зазором", () => {
    const тело = правило(".dt__more");
    expect(тело, "панель снова читается как продолжение ряда фильтров").toContain(
      "background: var(--lc-surface)",
    );
    expect(тело, "радиус панели разошёлся с рецептом крупной поверхности").toContain(
      "var(--lc-radius-lg)",
    );
  });
});

/*
 * ЖИВАЯ ПОЛОВИНА: то, что доезжает до разметки. Класс, забытый в TSX, делает
 * любое правило выше мёртвым, а на глаз это неотличимо от «правило не сработало».
 */
const ROWS: TableRow[] = [
  {
    id: "c-1",
    status: "new",
    client_name: "Павел Ушаков",
    client_phone: null,
    assignee_id: null,
    assignee_name: null,
    item_title: null,
    account_id: "acc-1",
    account_title: "Бригада Андрея Владиславовича КП · Б6",
    tags: [],
    bot_active: false,
    unread_count: 0,
    last_message_at: "2026-08-06T14:24:00Z",
    messages_count: 1,
    first_response_sec: null,
    duration_sec: 0,
  },
];

describe("Разметка отдаёт то, за что держатся правила", () => {
  let fetchMock: ReturnType<typeof vi.fn>;

  beforeEach(() => {
    queryClient.clear();
    resetSessionStore({
      user: { ...fakeUser, role: "head" },
      permissions: ["conversations:read", "stats:all", "accounts:read"],
      accessToken: "t",
      bootstrapped: true,
    });
    fetchMock = vi.fn(async (input: RequestInfo | URL) => {
      const url = new URL(String(input), "http://localhost");
      if (url.pathname.endsWith("/conversations/table")) {
        return jsonResponse(200, { items: ROWS, page: { limit: 50, offset: 0, total: 1248 } });
      }
      if (url.pathname.endsWith("/users/assignable")) return jsonResponse(200, { items: [] });
      if (url.pathname.endsWith("/avito-accounts")) {
        return jsonResponse(200, { items: [], page: { limit: 50, offset: 0, total: 0 } });
      }
      return jsonResponse(404, { error: { code: "not_found", message: "нет" } });
    });
    vi.stubGlobal("fetch", fetchMock);
  });

  afterEach(() => {
    vi.unstubAllGlobals();
    vi.restoreAllMocks();
  });

  it("число и его подпись — разные узлы, разряды разделены", () => {
    const { container } = renderWithProviders(<TablePage />, { route: "/dialogs" });
    return screen.findByText("Павел Ушаков").then(() => {
      const значение = container.querySelector(".dt__found-value");
      const подпись = container.querySelector(".dt__found-label");
      expect(значение, "число найденного не отделено от подписи — крупным его не набрать").toBeTruthy();
      expect(подпись?.textContent).toBe("Найдено");
      // Пробел разрядов — неразрывный (Intl, ru-RU): «1248» читается посимвольно.
      expect(значение?.textContent?.replace(/\u00a0|\u202f/g, " ")).toBe("1 248");
    });
  });

  it("у крестика чипа есть класс, которым растёт мишень", async () => {
    // Без класса правило `.dt__chip-x::after` мёртвое, а мишень так и остаётся
    // 14×14 при норме 24×24 — и это не видно ни на одном скриншоте.
    const { container } = renderWithProviders(<TablePage />, { route: "/dialogs?status=new" });
    await screen.findByText("Павел Ушаков");
    const крестик = container.querySelector(".dt__chips .dt__chip-x");
    expect(крестик, "крестик чипа потерял класс — мишень снова 14 пикселей").toBeTruthy();
    expect(крестик?.getAttribute("aria-label")).toMatch(/^Снять сужение:/);
  });

  it("TSX не задаёт кегль числа руками — он живёт в CSS", () => {
    // Иначе шкала снова разъедется: правило в CSS и стиль в разметке.
    const счётчик = TSX.slice(TSX.indexOf('className="dt__found"'));
    expect(счётчик.slice(0, 400), "кегль числа задан в разметке мимо шкалы").not.toMatch(/fz=/);
  });
});
