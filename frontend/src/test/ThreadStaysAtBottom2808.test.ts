import { describe, expect, it } from "vitest";
// @ts-expect-error — типов Node в проекте нет (tsconfig types: ["vite/client"]).
import { readFileSync } from "node:fs";

/**
 * ЛЕНТА ОТКРЫВАЕТСЯ НА ПОСЛЕДНЕМ СООБЩЕНИИ И ОСТАЁТСЯ ТАМ, ПОКА РАСТЁТ.
 *
 * ⚠ ЖАЛОБА ВЛАДЕЛЬЦА 28.08: «когда заходишь в чат, он открывает не с самого
 * последнего сообщения и приходится листать вниз».
 *
 * Цикл прижимания рассчитан на полсекунды: тридцать заходов по 16 мс, и он
 * кончается, как только высота трижды подряд совпала. Этого хватает на текст и
 * НЕ хватает на вложения: у картинки нет заранее известной высоты, приходит она
 * по сети и рисуется через секунду-полторы после выхода из цикла. Лента растёт
 * под уже поставленной прокруткой — и человек видит середину переписки.
 *
 * Проверка по исходнику: поведение живёт в `useLayoutEffect` и завязано на
 * настоящую раскладку, которой в jsdom нет (там все высоты нулевые, и
 * «прижались» не отличить от «не прижались»). Сторож здесь честнее
 * псевдо-проверки в среде без раскладки.
 */
const src = (readFileSync(
  "src/features/chats/components/thread/ChatThreadPane.tsx",
  "utf-8",
) as string).replace(/\/\*[\s\S]*?\*\//g, " ").replace(/\/\/[^\n]*/g, " ");

describe("Прижимание ленты к низу", () => {
  it("за ростом содержимого следит наблюдатель размера", () => {
    /*
     * Именно он ловит догрузку картинок: срабатывает на каждое изменение
     * высоты, а не через отмеренные полсекунды.
     */
    expect(src, "ленту снова держит только таймер — вложения опять уронят её вниз").toContain(
      "new ResizeObserver",
    );
  });

  it("наблюдают за СОДЕРЖИМЫМ, а не за самим скроллером", () => {
    /*
     * У скроллера высота постоянная — он наблюдал бы сам за собой и не
     * срабатывал бы никогда. Растёт то, что внутри.
     */
    expect(src).toMatch(/ro\.observe\(child\)/);
  });

  it("прижимание слушается «прилипания» и не воюет с человеком", () => {
    /*
     * Прокрутил вверх читать старое — обработчик прокрутки сбрасывает
     * `stickToBottom`, и лента обязана оставить человека в покое. Без этого
     * условия каждая догруженная картинка дёргала бы его вниз.
     */
    const i = src.indexOf("new ResizeObserver");
    expect(i).toBeGreaterThan(-1);
    const тело = src.slice(i, i + 320);
    expect(тело, "наблюдатель тянет вниз даже того, кто читает старое").toContain(
      "if (!stickToBottom.current) return;",
    );
  });

  it("наблюдатель отключается вместе с диалогом", () => {
    /*
     * Без отписки каждый открытый диалог оставлял бы за собой живого
     * наблюдателя, а их за смену сотни.
     */
    expect(src).toMatch(/ro\?\.disconnect\(\)/);
  });
});
