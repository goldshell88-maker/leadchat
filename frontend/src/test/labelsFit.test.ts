// @ts-expect-error — типов Node в проекте нет (tsconfig types: ["vite/client"]),
// как в buttonCanon.test.ts: сторож только читает файл.
import { readFileSync } from "node:fs";
import { describe, expect, it } from "vitest";

/**
 * ПОДПИСИ ОБЯЗАНЫ ПОМЕЩАТЬСЯ В СВОИ ПОЛЯ.
 *
 * 29 августа владелец сказал про интерфейс «всё едет» и попросил пройти
 * каждую вкладку и каждое поле. Обход с замерами в живом браузере нашёл
 * четыре места, где текст обрывался на полуслове. Все числа ниже — не
 * прикидки: ширины сняты с боевой страницы холстом тем же шрифтом, каким
 * поле рисует текст.
 *
 * ⚠ ЗАЧЕМ ТЕСТ, ЕСЛИ ШИРИНЫ УЖЕ ПОПРАВЛЕНЫ. Затем, что обратная правка не
 * выглядит поломкой. Уменьшить `w` на тридцать пикселей ради того, чтобы ряд
 * фильтров встал в одну строку, — соблазнительно и совершенно незаметно на
 * экране разработчика, где выбран короткий вариант. Дефект проявится у
 * диспетчера, на длинном значении, и связать его с той правкой будет уже
 * нечем.
 *
 * ⚠ ПОЧЕМУ ЭТО НЕ ЗАМЕР, А СРАВНЕНИЕ ЧИСЕЛ. jsdom не считает раскладку:
 * ширины в нём нулевые, мерить нечего. Поэтому здесь сверяются объявленные
 * числа с записанными результатами настоящего замера. Тест не поймает смену
 * шрифта или удлинение подписи — он держит ровно то, что держит: чтобы
 * однажды измеренный запас не отобрали обратно.
 */

const читать = (путь: string): string => readFileSync(путь, "utf8");

describe("Подписи помещаются в свои поля", () => {
  it("фильтр «Тип события» вмещает самое длинное название", () => {
    const src = читать("src/features/notifications/NotificationsPage.tsx");

    /*
     * ⚠ СНАЧАЛА ВЫРЕЗАЕМ НУЖНЫЙ <Select>, ПОТОМ ИЩЕМ В НЁМ ШИРИНУ.
     *
     * `(?:(?!<Select)[\s\S])*?` вместо простого `[\s\S]*?` — не украшение.
     * Ленивый поиск начинает с ПЕРВОГО `<Select` в файле и тянется до первой
     * подходящей подписи, проглатывая соседние поля целиком; ширина тогда
     * берётся у чужого поля. Первая версия этого теста так и сделала: нашла
     * 170 у соседа вместо 345 у нужного.
     * Поиск `/w=\{(\d+)\}/` по всему файлу однажды уже поймал `fw={600}` в
     * заголовке соседней секции и зеленел на диверсии насквозь.
     */
    const поле = /<Select(?:(?!<Select)[\s\S])*?aria-label="Тип события"(?:(?!<Select)[\s\S])*?\/>/.exec(src);
    expect(поле, "поле «Тип события» пропало из NotificationsPage").not.toBeNull();
    const w = /\bw=\{(\d+)\}/.exec(поле?.[0] ?? "");
    expect(w, "у поля «Тип события» пропала ширина").not.toBeNull();

    /*
     * Замер 29.08: «Канал отобрали: подписка на события пропала» — 279 px
     * при шрифте поля (12px Inter). Обвес поля (отступы + галочка) съедает
     * 43 px: при w=260 под текст оставалось 217.
     */
    expect(
      Number(w?.[1]),
      "ширина снова меньше самого длинного названия события",
    ).toBeGreaterThanOrEqual(279 + 43);
  });

  it("колонка названий быстрых ответов вмещает самое длинное название", () => {
    const css = читать("src/features/chats/components/composer/template-picker.css");
    const правило = /^\.tpl-row__title\s*\{([^}]*)\}/m.exec(css);
    expect(правило, "правило .tpl-row__title пропало из template-picker.css").not.toBeNull();

    const w = /width:\s*(\d+)px/.exec(правило?.[1] ?? "");
    expect(w, "у колонки названий пропала ширина").not.toBeNull();
    // Замер 29.08: «Наберу через пару минут» — 180 px (14px Inter, вес 600).
    expect(Number(w?.[1]), "колонка снова уже самого длинного названия").toBeGreaterThanOrEqual(180);

    /*
     * Колонка обязана остаться ЖЁСТКОЙ. `flex: 1` здесь читается как
     * улучшение («пусть растёт»), а на деле рассыпает выравнивание: ширина
     * названия начинает зависеть от длины ответа в той же строке, и список
     * перестаёт читаться сверху вниз одним движением глаза.
     */
    expect(правило?.[1], "колонка названий стала резиновой — выравнивание рассыплется").toMatch(
      /flex:\s*none/,
    );
  });

  it("название быстрого ответа целиком доступно по наведению", () => {
    const src = читать("src/features/chats/components/composer/TemplatePickerPopover.tsx");
    /*
     * Страховка на будущее: колонка жёсткая, и заготовку с более длинным
     * названием заведут рано или поздно. Без `title` выбор пойдёт вслепую.
     */
    expect(src, "у названия заготовки пропала подсказка при наведении").toMatch(
      /className="tpl-row__title"\s+title=\{t\.title\}/,
    );
  });

  it("подпись поиска по диалогам помещается в колонку", () => {
    const src = читать("src/features/chats/components/list/ChatListPane.tsx");
    const поле = /<TextInput(?:(?!<TextInput)[\s\S])*?aria-label="Поиск по диалогам"(?:(?!<TextInput)[\s\S])*?\/>/.exec(src);
    expect(поле, "поле поиска пропало из ChatListPane").not.toBeNull();

    const подпись = /placeholder="([^"]*)"/.exec(поле?.[0] ?? "");
    expect(подпись, "у поиска пропала подпись").not.toBeNull();

    /*
     * ⚠ ЗДЕСЬ СТОРОЖИТСЯ ДЛИНА, А НЕ БУКВА. Колонка списка жёстко 340 px,
     * под текст в поле остаётся 212 (отступ слева 38 + бронь под значок
     * сочетания 62).
     *
     * ⚠ С 08.09 БРОНЬ УСЛОВНАЯ: значок рисуется, только когда сочетание
     * действительно привязано (по умолчанию поиск выключен — аудит H-06,
     * см. Sochetanie0809.test.tsx). Считаем по худшему случаю — с бронью:
     * без неё места только больше, и подпись, влезшая в 212, влезет и в 274. Замер 29.08: прежняя подпись «Поиск по имени, телефону или
     * сообщению…» просила 287 px и не помещалась НИКОГДА — ни на широком
     * мониторе, ни на телефоне. Слово «сообщению» не видел ни один человек.
     *
     * 26 символов — это ~180 px при 13px Inter, с запасом к 212. Точную
     * фразу не проверяем: её вправе переписать, лишь бы влезала.
     */
    expect(
      подпись?.[1].length,
      "подпись поиска снова длиннее, чем помещается в колонку 340 px",
    ).toBeLessThanOrEqual(30);

    // И подпись обязана остаться правдивой: поле ищет и по тексту реплик.
    expect(подпись?.[1].toLowerCase()).toMatch(/текст/);
  });

  it("выбор вида условия в ботах вмещает самую длинную подпись", () => {
    const форма = читать(
      "src/features/settings/bots/components/StepForms/ConditionForm.tsx",
    );
    const поле = /<Select(?:(?!<Select)[\s\S])*?data=\{CONDITION_KINDS\}(?:(?!<Select)[\s\S])*?\/>/.exec(форма);
    expect(поле, "выбор вида условия пропал из ConditionForm").not.toBeNull();
    const w = /\bw=\{(\d+)\}/.exec(поле?.[0] ?? "");
    expect(w, "у выбора вида условия пропала ширина").not.toBeNull();

    /*
     * Замер 29.08: «переменная существует» — 141 px (14px Inter), обвес
     * поля ~42. В отличие от остальных четырёх мест, это НЕ проверено на
     * живом экране: в бою нет ни одного бота, форму условия открыть негде.
     */
    const самая = читать("src/features/settings/bots/scenario.ts");
    expect(самая, "подписи видов условия переехали из scenario.ts").toMatch(
      /переменная существует/,
    );
    expect(
      Number(w?.[1]),
      "ширина снова меньше самой длинной подписи вида условия",
    ).toBeGreaterThanOrEqual(141 + 42);
  });
});
