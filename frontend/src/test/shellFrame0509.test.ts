describe("Скелет входа обещает ту же рамку, что рабочее место", () => {
  it("третья колонка есть и в стилях, и в разметке", () => {
    expect(
      безКомментариев(LAYOUT_CSS),
      "правило .lc-boot__pane--card пропало — скелет снова обещает две колонки",
    ).toMatch(/\.lc-boot__pane--card\s*\{/);
    expect(LAYOUT).toContain('className="lc-boot__pane lc-boot__pane--card"');
  });

  it("пороги скелета совпадают с порогами рабочего места", () => {
    const рабочие = пороги(CHATS_CSS);
    // Пустой список означал бы, что разбор перестал находить медиазапросы, —
    // и сторож молча позеленел бы, ничего не сверяя.
    expect(рабочие.length).toBeGreaterThan(3);
    const скелет = пороги(LAYOUT_CSS);
    const пропущены = рабочие.filter((п) => !скелет.includes(п));
    expect(
      пропущены,
      `скелет не знает про ступени рабочего места: ${пропущены.join(", ")}`,
    ).toEqual([]);
  });

  it("ширины колонок у скелета те же, что у рабочего места", () => {
    const списокРабочий = ширины(CHATS_CSS, ".chats-page > .chat-list-pane");
    const списокСкелет = ширины(LAYOUT_CSS, ".lc-boot__pane--list");
    expect(списокРабочий.length, "перестали находиться ширины списка").toBeGreaterThan(1);
    expect(списокСкелет, "колонка списка у скелета разошлась с рабочим местом").toEqual(
      списокРабочий,
    );

    const картаРабочая = ширины(CHATS_CSS, ".chats-page > .client-card:not(.client-card--overlay)");
    const картаСкелет = ширины(LAYOUT_CSS, ".lc-boot__pane--card");
    expect(картаРабочая.length, "перестали находиться ширины карточки").toBeGreaterThan(1);
    expect(картаСкелет, "карточка клиента у скелета разошлась с рабочим местом").toEqual(
      картаРабочая,
    );
  });

  it("рельс скелета берёт ширину оттуда же, откуда каркас", () => {
    const скелет = LAYOUT.slice(
      LAYOUT.indexOf("export function AppChromeSkeleton"),
      LAYOUT.indexOf("export function AppLayout"),
    );
    expect(скелет.length, "AppChromeSkeleton пропал из файла").toBeGreaterThan(200);
    expect(
      скелет,
      "скелет снова полагается на запасное значение --lc-rail-w, то есть на 72",
    ).toContain("useRailExpanded()");
    expect(скелет).toContain('"--lc-rail-w"');
    expect(скелет).toContain("RAIL_WIDTH_EXPANDED");
    expect(скелет).toContain("RAIL_WIDTH_COLLAPSED");
  });
});

/**
 * ═══ 2. НА КОРОТКОМ ОКНЕ НИЗ РЕЛЬСА ДОСТАЁТСЯ ═══
 *
 * НАЙДЕНО ЗАМЕРОМ на стенде при 667×375 — телефон, повёрнутый набок.
 * Свёрнутому рельсу администратора нужно 619 пикселей высоты (девять строк по
 * 44, разделитель, знак и кнопка «это я»); прокрутки у него не было вовсе, и
 * колокольчик с кнопкой сотрудника оказывались на 244 пикселя НИЖЕ края
 * экрана. Достать их было нечем: ни уведомлений, ни «отошёл», ни выхода.
 *
 * ⚠ ПОЧЕМУ ПОРОГ СТОРОЖИТСЯ С ДВУХ СТОРОН. Снизу — требуемой высотой: порог
 * ниже 619 не спасает, беда остаётся. Сверху — типовым ноутбуком 1366×768, где
 * на окно приходится 660–700 пикселей: там рельс помещается, и отбирать
 * подсказки (а `overflow-y: auto` вычисляет `overflow-x` тоже в `auto` и
 * срезает их) не за что.
 */
describe("Свёрнутый рельс на коротком окне прокручивается", () => {
  const ТРЕБУЕТ_АДМИНУ = 619; // замер на стенде 05.09
  const ОКНО_НОУТБУКА = 700; // 1366×768 за вычетом обвеса браузера

  it("правило есть и включает прокрутку именно свёрнутому", () => {
    const блок = медиа(RAIL_CSS, /max-height/);
    expect(блок, "медиазапрос по высоте пропал — низ рельса снова недостижим").not.toBe("");
    expect(блок).toMatch(/\.lc-rail:not\(\[data-expanded\]\)/);
    expect(блок).toMatch(/overflow-y:\s*auto/);
  });

  it("порог покрывает требуемую высоту и не трогает ноутбук", () => {
    const m = /@media[^{]*max-height:\s*(\d+)px/.exec(безКомментариев(RAIL_CSS));
    expect(m, "порог по высоте пропал").not.toBeNull();
    const порог = Number(m?.[1]);
    expect(порог, "порог ниже требуемых рельсу 619 — низ панели снова не достать").toBeGreaterThanOrEqual(
      ТРЕБУЕТ_АДМИНУ,
    );
    expect(порог, "порог залез на окно ноутбука — у диспетчера пропадут подсказки").toBeLessThanOrEqual(
      ОКНО_НОУТБУКА,
    );
  });
});

/**
 * ═══ 3. ПОДСКАЗКА СВЁРНУТОГО РЕЛЬСА ПОМЕЩАЕТСЯ В СВОЙ ПОТОЛОК ═══
 *
 * У подсказки жёсткий потолок 240 пикселей и многоточие (`app-rail.css`), и это
 * правильно: колонка контента начинается там же, где кончается рельс. Но две
 * подписи в него не помещались, и обе теряли многоточием ровно тот хвост, ради
 * которого их читают.
 *
 *   «Поиск по имени, телефону или сообщению — Ctrl+K» — 327 пикселей при
 *   потолке 240: на экране оставалось «…или соо…», сочетание клавиш пропадало.
 *
 *   «Станислав Александрович Гончаренко — на месте» — 323 пикселя: пропадало
 *   состояние, единственное, чего в свёрнутом виде узнать больше неоткуда
 *   (подпись под именем там спрятана `display: none`).
 *
 * ⚠ ЗАМЕР ПЕРЕСЧИТАН В СИМВОЛЫ, потому что мерить в jsdom нечем. 46 символов
 * длинной подписи дали 307 пикселей текста при 12px Inter — 6,7 на символ.
 * Внутри потолка на текст остаётся 220 (240 минус 20 отступов), то есть 33
 * символа. Тот же приём и тот же довод, что в `labelsFit.test.ts`.
 */
describe("Подписи свёрнутого рельса влезают в подсказку", () => {
  const НА_СИМВОЛ = 6.7; // 12px Inter, замер холстом на стенде 05.09
  const ОТСТУПЫ = 20; // padding 10 слева и справа у ::after

  it("потолок подсказки на месте — иначе мерить не с чем", () => {
    const m = /max-width:\s*(\d+)px/.exec(безКомментариев(RAIL_CSS));
    expect(m, "потолок ширины подсказки пропал").not.toBeNull();
    expect(Number(m?.[1])).toBeGreaterThan(0);
  });

  it("ни одна постоянная подпись не длиннее потолка", () => {
    const потолок = Number(/max-width:\s*(\d+)px/.exec(безКомментариев(RAIL_CSS))?.[1]);
    const предел = Math.floor((потолок - ОТСТУПЫ) / НА_СИМВОЛ);

    const подписи = [...RAIL.matchAll(/data-tip="([^"]+)"/g)].map((m) => m[1]);
    // Пустой список означал бы, что разбор перестал находить подписи.
    expect(подписи.length, "постоянные подписи пропали из рельса").toBeGreaterThanOrEqual(6);

    const длинные = подписи.filter((т) => т.length > предел);
    expect(
      длинные,
      `подпись не поместится в подсказку (предел ${предел} символов): ${длинные.join(" | ")}`,
    ).toEqual([]);
  });

  it("у кнопки сотрудника состояние стоит впереди имени", () => {
    /*
     * Имя приходит от администратора и длину его ограничить нельзя, поэтому
     * порядок — единственная защита: многоточие обязано съедать избыточное
     * (имя, которое человек и так знает), а не состояние.
     */
    const подпись = /data-tip=\{`([^`]+)`\}/.exec(RAIL);
    expect(подпись, "подпись кнопки сотрудника пропала").not.toBeNull();
    const шаблон = подпись?.[1] ?? "";
    expect(
      шаблон.indexOf("away ?"),
      "имя снова стоит перед состоянием — многоточие съест именно состояние",
    ).toBeLessThan(шаблон.indexOf("user.full_name"));
  });
});

/**
 * ═══ 4. ПЕРЕНОС ПОЛОСЫ ОБНОВЛЕНИЯ ДЕЙСТВИТЕЛЬНО ПЕРЕНОСИТ ═══
 *
 * В `platform.css` стоял одинокий `flex-wrap: wrap` — правило, написанное под
 * ту раскладку, где текст занимал естественную ширину и вытеснял кнопки на
 * вторую строку. Но у текста рядом `flex: 1; min-width: 0`: он сжимается до
 * нуля и переноса не просит НИКОГДА. Замер на 375: текстовый блок ужимался до
 * 108 пикселей, две строки полосы разъезжались на пять, высота доходила до 117
 * пикселей поверх шапки ленты, а обе кнопки спокойно стояли рядом.
 *
 * Ровно тот класс дефекта, который просили искать первым: медиазапрос правит
 * механизм, которого в базовом правиле давно нет.
 */
describe("Полоса обновления на телефоне переносит текст, а не сжимает его", () => {
  it("в узком медиазапросе есть и перенос, и полная строка под текст", () => {
    const блок = медиа(PLATFORM_CSS, /max-width:\s*767px/);
    expect(блок, "узкий медиазапрос полосы обновления пропал").not.toBe("");
    expect(блок).toMatch(/flex-wrap:\s*wrap/);
    expect(
      блок,
      "перенос снова ничего не делает: текст сжимается до нуля и не просит новой строки",
    ).toMatch(/\.lc-update-banner__text\s*\{[^}]*flex-basis:\s*100%/);
  });
});

/**
 * ═══ 5. ПОЛОСЫ ПОЯВЛЯЮТСЯ ДВИЖЕНИЕМ, И ДВИЖЕНИЕ ГАСИТСЯ ═══
 *
 * Стопка стоит оверлеем поверх работы: полоса возникала одним кадром поверх
 * переписки, которую человек читает. Четверть секунды объясняют, что сверху
 * появилось сообщение, а не что-то мигнуло.
 *
 * Гашение проверяется отдельно и не «на всякий случай»: общее правило в
 * `lc-base.css` снимает ПЕРЕХОДЫ, а здесь именно `animation`.
 */
describe("Появление полос объяснено движением и выключается", () => {
  it("кадры объявлены и надеты на все три полосы", () => {
    const css = безКомментариев(LAYOUT_CSS);
    expect(css).toMatch(/@keyframes lc-banner-in/);
    for (const селектор of [".lc-conn-banner", ".lc-perm-banner"]) {
      const m = new RegExp(`\\${селектор}\\s*\\{[^}]*animation:\\s*lc-banner-in`).exec(css);
      expect(m, `${селектор} появляется рывком`).not.toBeNull();
    }
    expect(безКомментариев(PLATFORM_CSS)).toMatch(
      /\.lc-update-banner\s*\{[^}]*animation:\s*lc-banner-in/,
    );
  });

  it("движение снимается у того, кто его выключил", () => {
    const вЛэйауте = медиа(LAYOUT_CSS, /prefers-reduced-motion:\s*reduce/);
    expect(вЛэйауте).toMatch(/animation:\s*none/);
    expect(вЛэйауте).toMatch(/\.lc-conn-banner/);
    expect(вЛэйауте).toMatch(/\.lc-perm-banner/);
    expect(медиа(PLATFORM_CSS, /prefers-reduced-motion:\s*reduce/)).toMatch(/animation:\s*none/);
  });

  it("длительность взята токеном, а не числом", () => {
    // 250 мс здесь названы `--lc-dur-base`. Число вместо токена отвяжет полосу
    // от общего темпа интерфейса, и заметить это можно только секундомером.
    expect(безКомментариев(LAYOUT_CSS)).toMatch(/animation:\s*lc-banner-in var\(--lc-dur-/);
    expect(безКомментариев(PLATFORM_CSS)).toMatch(/animation:\s*lc-banner-in var\(--lc-dur-/);
  });
});

/**
 * ═══ 6. ИЕРАРХИЯ РЕЛЬСА: ОДИН АКЦЕНТ, ОДНА ГРАНИЦА ГРУППЫ ═══
 *
 * Три правки одного разбора, и все три проверяемы текстом правил:
 *
 *   ТЕКУЩИЙ РАЗДЕЛ отмечен ещё и насыщенностью. Заливка `--lc-selected` на
 *   тёмной теме отличается от фона панели на несколько процентов светлоты, и
 *   боковым зрением — а на рельс смотрят именно так — активная строка сливалась
 *   с соседями.
 *
 *   ЛИНИЯ МЕЖДУ ГРУППАМИ убрана у развёрнутого рельса: там ту же границу уже
 *   держит заголовок «ПОД РУКОЙ», и две границы одной группы читаются как две
 *   группы. В свёрнутом виде заголовки спрятаны, и линия остаётся.
 *
 *   «НА МЕСТЕ» снято с акцентного цвета: им в рельсе отмечен текущий раздел, и
 *   один цвет не может значить сразу «вы здесь» и «вы на месте». «Отошёл»
 *   остаётся янтарным — это отклонение, его и надо видеть.
 */
describe("Иерархия левой панели", () => {
  /*
   * Объявления правил, в СПИСКЕ СЕЛЕКТОРОВ которых есть ровно этот селектор.
   * Регулярка по тексту здесь не годится: `.lc-rail__item` — префикс
   * `.lc-rail__item[data-active]`, и наивный поиск отвечал бы телом соседа.
   */
  const правило = (селектор: string): string => {
    const тела: string[] = [];
    for (const m of безКомментариев(RAIL_CSS).matchAll(/([^{}]+)\{([^{}]*)\}/g)) {
      const список = m[1].split(",").map((s) => s.trim().replace(/\s+/g, " "));
      if (список.includes(селектор)) тела.push(m[2]);
    }
    return тела.join(" ");
  };

  it("текущий раздел отмечен не только цветом", () => {
    const тело = правило(".lc-rail__item[data-active]");
    expect(тело, "правило активной строки пропало").not.toBe("");
    expect(тело, "активная строка снова отличается одним лишь оттенком").toMatch(
      /font-weight:\s*var\(--lc-fw-semibold\)/,
    );
  });

  it("у развёрнутой панели границу группы держит заголовок, а не линия", () => {
    const тело = правило(".lc-rail[data-expanded] .lc-rail__divider");
    expect(тело, "правило разделителя у развёрнутой панели пропало").not.toBe("");
    expect(тело, "линия вернулась туда, где группу уже делит заголовок").toMatch(
      /display:\s*none/,
    );
    // А в свёрнутом виде линия обязана остаться: заголовки там спрятаны.
    expect(правило(".lc-rail__divider")).toMatch(/background:\s*var\(--lc-border\)/);
  });

  it("«На месте» не занимает акцентный цвет", () => {
    const тело = правило(".lc-rail__who em");
    expect(тело, "правило подписи состояния пропало").not.toBe("");
    expect(
      тело,
      "состояние по умолчанию снова красится тем же, чем текущий раздел",
    ).not.toMatch(/--lc-primary/);
  });
});
