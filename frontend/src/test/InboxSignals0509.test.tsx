/**
 * Три сигнала, которых человеку не хватало (замечания владельца и сотрудника 05.09).
 */
// @ts-expect-error — типов Node в проекте нет (tsconfig types: ["vite/client"]).
import { readFileSync } from "node:fs";
import { describe, expect, it } from "vitest";

const PANE = (
  readFileSync("src/features/chats/components/list/ChatListPane.tsx", "utf-8") as string
).replace(/\/\*[\s\S]*?\*\//g, "");
const FOOTER = (
  readFileSync("src/features/chats/components/composer/ThreadFooter.tsx", "utf-8") as string
).replace(/\/\*[\s\S]*?\*\//g, "");

describe("Сигналы в списке и подвале", () => {
  it("счётчик очереди называет точное число, а не «99+»", () => {
    /*
     * «99+» отвечает на вопрос «много ли», а смотрят сюда с вопросом «сколько
     * именно»: по нему решают, хватит ли смены разобрать очередь до конца дня.
     */
    expect(PANE, "потолок «99+» вернулся").not.toMatch(/99\s*\+/);
    expect(PANE).toMatch(/\{inboxCount\}/);
  });

  it("долг «ждут вашего ответа» виден и во «Входящих»", () => {
    /*
     * Человек сидит в очереди подолгу, разбирая её, и всё это время не знал,
     * что написали ему самому. Условие `!inboxOpen` стояло здесь без единого
     * слова довода.
     */
    const условие = PANE.match(/const долгВиден =([^;]*);/s);
    expect(условие, "нет условия видимости чипа долга").toBeTruthy();
    expect(условие![1], "чип снова спрятан во «Входящих»").not.toMatch(/!inboxOpen/);
  });

  it("переданный мне диалог не показывает полосу входа", () => {
    /*
     * ⚠ ОБРАТНАЯ СВЯЗЬ СОТРУДНИКА: «когда тебе передают диалог, нужно сделать
     * 2 действия вместо одного, чтоб его принять». Пока предложение висит,
     * ответственный ещё прежний — формально диалог чужой. Но человека сюда
     * ПОЗВАЛИ: требовать «сначала войди, потом прими» — это спрашивать
     * разрешения войти у того, кто сам открыл дверь.
     *
     * Порядок веток в подвале уже менялся дважды, поэтому правило записано
     * явно, а не держится на том, что ветка предложения стоит выше.
     */
    const условие = FOOTER.match(/const заслон =([^;]*);/s);
    expect(условие, "нет условия заслона").toBeTruthy();
    expect(условие![1], "исключение для переданного мне диалога пропало").toMatch(/мнеПередают/);
    expect(FOOTER).toMatch(/transferred_to_me/);
  });
});

/**
 * Снимок без слов — без пузыря (просьба владельца 05.09: «можно чтобы
 * нормально отображалось и не было лишнего фона»).
 */
describe("Сообщение из одной фотографии", () => {
  const BUBBLE = (
    readFileSync("src/features/chats/components/thread/MessageBubble.tsx", "utf-8") as string
  ).replace(/\/\*[\s\S]*?\*\//g, "");
  const CSS = (
    readFileSync("src/features/chats/components/thread/chat-thread.css", "utf-8") as string
  ).replace(/\/\*[\s\S]*?\*\//g, "");

  it("пузырь помечается признаком «только снимок»", () => {
    expect(BUBBLE).toMatch(/data-media=\{толькоСнимок/);
  });

  it("условие узкое: одна картинка и ни слова текста", () => {
    /*
     * ⚠ ГРАНИЦА ВАЖНЕЕ САМОГО ПРАВИЛА. Появилась подпись — пузырь обязан
     * вернуться: слова на светлой фотографии без подложки не прочесть. Заметка
     * тоже остаётся с подложкой — у неё своя, янтарная, и она несёт смысл.
     */
    const условие = BUBBLE.match(/const толькоСнимок =([^;]*);/s);
    expect(условие, "нет признака «только снимок»").toBeTruthy();
    expect(условие![1]).toMatch(/!msg\.body\?\.trim\(\)/);
    expect(условие![1]).toMatch(/attachments\.length === 1/);
    expect(условие![1]).toMatch(/kind !== "note"/);
  });

  it("у такого пузыря сняты поля, подложка и тень", () => {
    const правило = CSS.match(/\.msg__bubble\[data-media\]\s*\{([^}]*)\}/s);
    expect(правило, "нет правила для пузыря со снимком").toBeTruthy();
    expect(правило![1]).toMatch(/padding:\s*0/);
    expect(правило![1]).toMatch(/background:\s*none/);
    expect(правило![1]).toMatch(/box-shadow:\s*none/);
  });
});

/**
 * Снимок не растягивается на ширину пузыря.
 *
 * ⚠ ТРЕТЬЯ ПОПЫТКА, И ПЕРВЫЕ ДВЕ БИЛИ МИМО. Снимали поля пузыря — полосы
 * остались; чинили пропорцию — она есть лишь у 734 снимков из 4978 за 14 дней.
 * Причина была в другом: `.msg__attachments` — флекс-колонка, дети в ней
 * растягиваются по умолчанию, обёртка снимка занимала всю ширину пузыря, и
 * картинка вписывалась в неё по центру с полями по бокам.
 */
describe("Ширина снимка в пузыре", () => {
  const CSS2 = (
    readFileSync("src/features/chats/components/thread/chat-thread.css", "utf-8") as string
  ).replace(/\/\*[\s\S]*?\*\//g, "");

  it("вложения прижаты к началу, а не растянуты", () => {
    const правило = CSS2.match(/\.msg__attachments\s*\{([^}]*)\}/s);
    expect(правило, "нет правила .msg__attachments").toBeTruthy();
    expect(правило![1], "растяжка вернулась — снимок снова получит поля по бокам").toMatch(
      /align-items:\s*flex-start/,
    );
  });

  it("картинка по-прежнему не обрезается", () => {
    /*
     * Граница правки: прижать к началу — можно, обрезать — нельзя. Клиент
     * присылает доказательство (экран с ошибкой, шильдик), и `cover` срезал бы
     * ровно то, ради чего он его прислал (решение 28.08).
     */
    expect(CSS2).toMatch(/^\.msg__image\s*\{[^}]*object-fit:\s*contain/ms);
  });
});
