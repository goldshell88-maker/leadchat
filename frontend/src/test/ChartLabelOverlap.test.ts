/**
 * Подписи оси X не наезжают друг на друга (жалоба владельца 22.08: «идёт
 * наслоение»).
 *
 * ЧТО БЫЛО. Потолок в восемь подписей стоял независимо от их длины, а зазор
 * проверялся только у ПОСЛЕДНЕЙ подписи с соседкой — равномерная сетка не
 * проверялась вовсе. На неделе по часам это 168 точек: шаг 21, между
 * подписями 83 единицы viewBox, а «16 авг., 06:00» занимает 91. Подписи
 * налезали, и на графике читалось «21:0017 авг., 18:0018 авг.».
 *
 * Вылезло это ровно тогда, когда «по часам» стало доступно с первого нажатия
 * (правка того же дня): раньше режим просто не открывался на длинном периоде.
 *
 * ЧТО СТАЛО. Число подписей считается от ширины подписи и ширины поля: сколько
 * влезает, столько и ставим, но не больше восьми.
 */
import { describe, expect, it } from "vitest";
import {
  EDGE_LABEL_FACTOR,
  labelIndexes,
  labelWidth,
  perPoint,
  PLOT_W,
} from "@/features/stats/lib/axisLabels";

/**
 * Наименьший зазор между соседними подписями, в единицах viewBox.
 *
 * Шаг берётся тем же `perPoint`, по которому график ставит сами подписи
 * (`cx(i) = PAD.left + PLOT_W / n * (i + 0.5)`). Своя формула здесь была
 * `PLOT_W / (count - 1)` — она ЗАВЫШАЕТ зазор и тем сильнее, чем меньше точек:
 * тест мерил расстояния, которых на экране нет, и на коротких рядах зеленел бы
 * при настоящем наложении.
 */
function минимальныйЗазор(count: number, sample: string): number {
  const индексы = [...labelIndexes(count, 8, sample)].sort((a, b) => a - b);
  if (индексы.length < 2) return PLOT_W;
  let min = Infinity;
  for (let i = 1; i < индексы.length; i += 1) {
    min = Math.min(min, (индексы[i] - индексы[i - 1]) * perPoint(count));
  }
  return min;
}

const ЧАС = "16 авг., 06:00";
const ДЕНЬ = "16 авг";

/**
 * Сколько места подписи нужно на самом деле. Полторы ширины, а не одна:
 * крайние подписи прижимаются внутрь поля и съезжают на полширины (см.
 * `EDGE_LABEL_FACTOR`). Множитель берём из кода, а не переписываем числом —
 * иначе проверка начнёт сторожить своё представление о графике.
 */
function нужныйЗазор(sample: string): number {
  return EDGE_LABEL_FACTOR * labelWidth(sample);
}

describe("подписи оси X", () => {
  it("неделя по часам: 168 точек и ни одного наложения", () => {
    expect(минимальныйЗазор(168, ЧАС)).toBeGreaterThanOrEqual(нужныйЗазор(ЧАС));
  });

  it("сутки по часам: 24 точки", () => {
    expect(минимальныйЗазор(24, ЧАС)).toBeGreaterThanOrEqual(нужныйЗазор(ЧАС));
  });

  it("месяц по дням: короткая подпись, подписей больше", () => {
    expect(минимальныйЗазор(30, ДЕНЬ)).toBeGreaterThanOrEqual(нужныйЗазор(ДЕНЬ));
  });

  it("длинная подпись не съедает ось целиком — минимум две остаются", () => {
    const очень = "16 августа 2026 года, 06:00";
    expect(labelIndexes(168, 8, очень).size).toBeGreaterThanOrEqual(2);
  });

  it("правый край подписан всегда — это ответ на «по какой день данные»", () => {
    for (const n of [7, 24, 30, 168]) {
      expect([...labelIndexes(n, 8, ЧАС)]).toContain(n - 1);
    }
  });

  it("подписей не больше восьми даже на коротком периоде", () => {
    expect(labelIndexes(6, 8, ДЕНЬ).size).toBeLessThanOrEqual(8);
  });

  /*
   * Зазор считается по ОДНОМУ образцу на всю ось, поэтому образец обязан быть
   * самой длинной подписью ряда. Возьми мы короткую — «1 мая, 06:00» вместо
   * «16 сент., 06:00», — сетка встанет уже, чем нужно длинным подписям.
   * Период, задевающий май или сентябрь, это не редкость.
   */
  it("сетка, посчитанная по короткому образцу, не выдерживает длинных подписей", () => {
    const короткий = "1 мая, 06:00";
    const длинный = "16 сент., 06:00";
    const индексы = [...labelIndexes(168, 8, короткий)].sort((a, b) => a - b);
    const зазор = (индексы[1] - индексы[0]) * perPoint(168);
    expect(зазор).toBeLessThan(нужныйЗазор(длинный));
    // По длинному образцу тот же ряд размечается без наложения.
    expect(минимальныйЗазор(168, длинный)).toBeGreaterThanOrEqual(нужныйЗазор(длинный));
  });

  it("две точки: зазор считается по настоящей геометрии, а не по завышенной", () => {
    // Колонка при двух точках — половина поля, и подписи стоят в её середине.
    expect(perPoint(2)).toBe(PLOT_W / 2);
    expect(минимальныйЗазор(2, ЧАС)).toBeGreaterThanOrEqual(нужныйЗазор(ЧАС));
  });

  /*
   * ⚠ КРАЙНИЕ ПОДПИСИ ПРИЖАТЫ ВНУТРЬ ПОЛЯ — иначе половина даты уезжает за
   * viewBox и срезается. Прижатая влево первая подпись стоит НЕ по центру
   * своей точки, а вся справа от неё: занимает [cx, cx+W] вместо
   * [cx−W/2, cx+W/2]. Проверка «зазор ≥ одна ширина» этого не ловила, и на
   * стенде первая подпись налезала на вторую на 31 единицу (замер
   * `getComputedTextLength`, неделя по часам).
   *
   * Считаем занятые отрезки честно, с учётом прижатия, — как их считает
   * браузер.
   */
  it("первая и последняя подписи прижаты внутрь и всё равно не задевают соседок", () => {
    for (const n of [24, 48, 168]) {
      const индексы = [...labelIndexes(n, 8, ЧАС)].sort((a, b) => a - b);
      const W = labelWidth(ЧАС);
      const cx = (i: number) => perPoint(n) * (i + 0.5); // от левого края поля
      const отрезки = индексы.map((i, k) => {
        if (k === 0) return [cx(i), cx(i) + W]; // прижата влево
        if (k === индексы.length - 1) return [cx(i) - W, cx(i)]; // прижата вправо
        return [cx(i) - W / 2, cx(i) + W / 2];
      });
      for (let k = 1; k < отрезки.length; k += 1) {
        expect(отрезки[k][0]).toBeGreaterThanOrEqual(отрезки[k - 1][1]);
      }
    }
  });
});
