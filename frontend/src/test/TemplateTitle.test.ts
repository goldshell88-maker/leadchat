import { describe, expect, it } from "vitest";
import { названиеПоТексту } from "@/features/templates/название";

describe("название заготовки по её тексту", () => {
  it("короткий текст становится названием целиком", () => {
    expect(названиеПоТексту("Куда к вам подъехать?")).toBe("Куда к вам подъехать?");
  });

  it("длинный текст режется по границе слова", () => {
    const источник = "Здравствуйте! Подскажите, какая модель телевизора и что именно с ним произошло?";
    const имя = названиеПоТексту(источник);
    expect(имя.endsWith("…")).toBe(true);
    expect(имя.length).toBeLessThanOrEqual(41);
    /*
     * ⚠ ПРОВЕРЯЕМ САМО СВОЙСТВО, А НЕ ПОСЛЕДНЮЮ БУКВУ. Первая редакция
     * запрещала букву перед многоточием — но правильно обрезанное название
     * ровно так и выглядит («…какая модель…»), и тест краснел на верном коде.
     * Настоящее свойство: там, где мы остановились, в источнике кончилось
     * слово — дальше пробел или знак, а не продолжение буквами.
     */
    const без = имя.slice(0, -1);
    expect(источник.startsWith(без)).toBe(true);
    expect(источник[без.length] ?? "").not.toMatch(/[\p{L}\p{N}]/u);
  });

  it("берётся только первая строка", () => {
    expect(названиеПоТексту("Добрый день!\nКогда вам удобно?")).toBe("Добрый день!");
  });

  it("пустой текст названия не даёт", () => {
    expect(названиеПоТексту("   \n  ")).toBe("");
  });

  it("одно слово длиннее предела режется, а не теряется", () => {
    const имя = названиеПоТексту("а".repeat(60));
    expect(имя).toBe("а".repeat(40) + "…");
  });
});
