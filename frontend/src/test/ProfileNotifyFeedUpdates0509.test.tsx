/*
 * ═══ ИЕРАРХИЯ ЗАГОЛОВКОВ ПРОФИЛЯ ═══
 *
 * Шесть блоков назывались `fz={16}` литералом, седьмой — `order={4} fz="sm"`,
 * то есть 13 пикселей: заголовок блока был ТИШЕ собственной подписи под ним
 * (14) и читался как примечание к предыдущему блоку. У соседних вкладок
 * настроек (лид-бот, распределение, заявки) блоки называются
 * `--lc-fz-section`. Заодно h4 без h3 над ним — провал иерархии для
 * программы чтения с экрана.
 */
describe("заголовки блоков профиля одинаковы 0509", () => {
  const БЛОКИ = [
    "AboutAppBlock",
    "AppearanceBlock",
    "BrowserAlertsBlock",
    "ContactAdminForm",
    "HotkeysBlock",
    "MyChannelsBlock",
    "ToastsBlock",
  ];

  for (const имя of БЛОКИ) {
    it(`${имя}: заголовок второго уровня кеглем из токена`, () => {
      const src = readFileSync(
        `src/features/settings/profile/${имя}.tsx`,
        "utf-8",
      ) as string;
      const код = src.replace(/\/\*[\s\S]*?\*\//g, " ").replace(/\{\/\*[\s\S]*?\*\/\}/g, " ");
      const заголовок = /<Title[^>]*>/.exec(код);
      expect(заголовок, `${имя}: заголовок блока пропал`).not.toBeNull();
      const тег = заголовок?.[0] ?? "";
      expect(тег, `${имя}: уровень заголовка разошёлся с соседями`).toContain("order={2}");
      expect(тег, `${имя}: кегль числом — из темы его уже не поправить`).toMatch(
        /fz="var\(--lc-fz-section\)"/,
      );
    });
  }
});

/*
 * ═══ СОСТОЯНИЕ ЛЕНТЫ ВИДНО, А НЕ УГАДЫВАЕТСЯ ═══
 *
 * «Лента идёт» / «Лента остановлена» / «Нет связи» — единственный ответ на
 * вопрос, ради которого экран открыт. Стояли 12 пикселей `--lc-text-3`, то
 * есть тише подписи канала в строке: остановленная лента выглядела просто
 * тихой.
 */
describe("состояние ленты названо и подкрашено 0509", () => {
  beforeEach(() => {
    clearFeed();
    useConnectionStore.setState({ status: "open" });
  });

  it("признак состояния стоит в разметке, а не только в словах", async () => {
    renderWithProviders(<FeedPage />, { route: "/feed" });
    // По тексту, а не по роли: `role="status"` носит и пустое состояние ленты.
    const строка = await screen.findByText("Лента идёт");
    expect(строка).toHaveAttribute("data-state", "running");
  });

  it("пауза меняет тот же признак, что и фразу", async () => {
    useFeedStore.getState().pause();
    renderWithProviders(<FeedPage />, { route: "/feed" });
    const строка = await screen.findByText(/Лента остановлена/);
    expect(строка, "фраза сменилась, а признак нет — цвет разойдётся с текстом").toHaveAttribute(
      "data-state",
      "paused",
    );
  });

  it("обрыв связи виден и в признаке", async () => {
    useConnectionStore.setState({ status: "reconnecting" });
    renderWithProviders(<FeedPage />, { route: "/feed" });
    const строка = await screen.findByText("Нет связи с сервером — лента остановилась");
    expect(строка).toHaveAttribute("data-state", "offline");
  });

  it("тревожные состояния покрашены, а спокойное — нет", () => {
    const текст = css(FEED);
    expect(правило(текст, '.lc-feed__state[data-state="paused"]')).toMatch(
      /color:\s*var\(--lc-warning-text\)/,
    );
    expect(правило(текст, '.lc-feed__state[data-state="offline"]')).toMatch(
      /color:\s*var\(--lc-danger-text\)/,
    );
    // Акцент на экране один, и он занят кнопкой «Продолжить»: строка
    // состояния красится тоном беды, но никогда — акцентом.
    expect(правило(текст, ".lc-feed__state"), "строка состояния забрала акцент экрана").not.toMatch(
      /var\(--lc-primary/,
    );
  });

  it("строка состояния громче подписей", () => {
    const тело = правило(css(FEED), ".lc-feed__state");
    expect(тело, "строка вернулась к кеглю подписи — с полуметра её не видно").not.toMatch(
      /font-size:\s*var\(--lc-fz-caption\)/,
    );
    expect(тело).toMatch(/font-size:\s*var\(--lc-fz-body\)/);
  });
});

