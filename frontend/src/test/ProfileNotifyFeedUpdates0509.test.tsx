/**
 * СТОРОЖА УЧАСТКА «ПРОФИЛЬ · УВЕДОМЛЕНИЯ · ЛЕНТА · ЧТО НОВОГО» (обход 05.09).
 *
 * Обход шёл на статическом стенде с НАСТОЯЩИМИ css участка, на пяти ширинах
 * (375 · 768 · 1024 · 1440 · 2560) в обеих темах. Все числа ниже сняты с
 * браузера, а не прикинуты: сторожа держат ровно тот запас, который однажды
 * померили, — обратная правка ширины на глаз разработчика незаметна, а
 * проявляется у диспетчера с телефона.
 *
 * ⚠ ПОЧЕМУ БОЛЬШИНСТВО ПРОВЕРОК ЧИТАЕТ CSS ТЕКСТОМ. В vitest стоит
 * `css: false`, jsdom раскладку не считает — мерить в тесте нечего. Поэтому
 * здесь сверяется то, что проверяемо: какие правила объявлены и на каком
 * механизме они держатся. Ловушка проекта («медиазапрос правит механизм,
 * которого в базовом правиле уже нет») ловится именно так — и только так.
 */

/** CSS без комментариев: разбор в шапке файла вправе называть что угодно. */
function css(путь: string): string {
  return (readFileSync(путь, "utf-8") as string).replace(/\/\*[\s\S]*?\*\//g, " ");
}

/** Тело правила `селектор { … }` — из указанного куска CSS. */
function правило(текст: string, селектор: string): string {
  const at = текст.indexOf(`${селектор} {`);
  expect(at, `правило ${селектор} не найдено`).toBeGreaterThan(-1);
  return текст.slice(at, текст.indexOf("}", at));
}

/**
 * Тело медиазапроса целиком — со всеми правилами внутри.
 *
 * ⚠ СЧИТАЕМ СКОБКИ, А НЕ ИЩЕМ ПЕРВУЮ ЗАКРЫВАЮЩУЮ. Первая версия резала блок
 * по ближайшей `}` и отдавала ровно одно правило из четырёх — сторож зеленел
 * на диверсии, потому что просто не видел испорченного места.
 */
function медиаВсе(текст: string, условие: string): string[] {
  const блоки: string[] = [];
  let from = 0;
  for (;;) {
    const at = текст.indexOf(`@media ${условие}`, from);
    if (at < 0) break;
    let глубина = 0;
    let конец = -1;
    for (let i = текст.indexOf("{", at); i < текст.length; i += 1) {
      if (текст[i] === "{") глубина += 1;
      if (текст[i] === "}") {
        глубина -= 1;
        if (глубина === 0) {
          конец = i + 1;
          break;
        }
      }
    }
    if (конец < 0) throw new Error(`@media ${условие}: не закрыт`);
    блоки.push(текст.slice(at, конец));
    from = конец;
  }
  expect(блоки.length, `медиазапрос @media ${условие} не найден`).toBeGreaterThan(0);
  return блоки;
}

/**
 * Один блок медиазапроса — тот, в котором есть нужный селектор.
 *
 * ⚠ ОДНО И ТО ЖЕ УСЛОВИЕ ВСТРЕЧАЕТСЯ НЕСКОЛЬКО РАЗ. В `notifications.css` два
 * блока `prefers-reduced-motion`: один гасит пульс скелета, второй — выезд
 * плашки. Первая версия брала первый попавшийся и краснела на живом коде.
 */
function медиа(текст: string, условие: string, содержит = ""): string {
  const блоки = медиаВсе(текст, условие);
  const нужный = блоки.find((б) => б.includes(содержит));
  expect(нужный, `@media ${условие} с «${содержит}» не найден`).toBeDefined();
  return нужный ?? "";
}

const NOTIFY = "src/features/notifications/notifications.css";
