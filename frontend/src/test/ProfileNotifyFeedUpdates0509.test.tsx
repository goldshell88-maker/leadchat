/*
 * ═══ ГЛАВНАЯ ЛОВУШКА УЧАСТКА ═══
 *
 * Свежий пример из бою: в списке каналов узкий экран задавал
 * `flex-direction: column`, а строка к тому времени стала СЕТКОЙ — правило не
 * делало ничего, и название канала на телефоне обрезалось. Медиазапрос
 * пережил механизм, который правил.
 *
 * Все три узких блока этого участка держатся на одном и том же: строка —
 * флекс-контейнер. Переведи её на `grid` — и `flex-wrap`, `flex-basis`,
 * `order` внутри медиазапросов замолчат, не сломав ни одного теста и не
 * подчеркнув ни одной строки. Этот сторож — единственное, что тогда крикнет.
 */
describe("механизм узких правил цел 0509", () => {
  const РЯДЫ: ReadonlyArray<readonly [string, string, string]> = [
    [FEED, ".lc-feed__row", "перенос строки события"],
    [NOTIFY, ".lc-critical__item", "перенос кнопок плашки"],
    [UPDATES, ".updates__item", "метка над текстом записи"],
  ];

  for (const [путь, селектор, зачем] of РЯДЫ) {
    it(`${селектор} — флекс, на нём держится ${зачем}`, () => {
      expect(
        правило(css(путь), селектор),
        `${селектор}: механизм сменился, а медиазапрос про него остался`,
      ).toMatch(/display:\s*flex/);
    });
  }
});

