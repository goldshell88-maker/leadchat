// как в railChrome.test.ts и controlScale.test.ts: сторож только читает файлы.
import { readFileSync, readdirSync, statSync } from "node:fs";
import { describe, expect, it } from "vitest";

/**
 * ПОДПИСЬ КНОПКИ И ЦВЕТ ОПАСНОГО ДЕЙСТВИЯ.
 *
 * НАЙДЕНО ОБХОДОМ 12 августа среди 161 кнопки продукта.
 *
 * ЗНАК «+» СТОЯЛ В ТЕКСТЕ десяти подписей, и регистр после него разошёлся
 * ровно пополам: «+ добавить шаг» и «+ Добавить шаг» на одном экране. Плюс —
 * работа значка, а не буквы: в доступное имя кнопки он не попадает вовсе, то
 * есть для скринридера половина этих кнопок и так называлась без него.
 *
 * ЦВЕТ ОПАСНОГО ДЕЙСТВИЯ БЫЛ ИНВЕРТИРОВАН В ДВУХ МЕСТАХ, и оба нашлись:
 * необратимое «Отключить и стереть» рисовалось нейтральным серым — тем же,
 * что соседние «Переименовать» и «Обновить подписку», — а безобидная на вид,
 * но блокирующая клиента кнопка «Пометить» получила заливку ЦВЕТОМ СОГЛАСИЯ,
 * ту же, что «Принять диалог» и «Сохранить».
 *
 * Сторож читает исходники: в vitest `css: false`, цвет померить нечем, а
 * обойти рендером все экраны с их состояниями дороже, чем прочесть разметку.
 */

const SRC = "src/features";

function tsxFiles(dir: string, out: string[] = []): string[] {
  for (const name of readdirSync(dir) as string[]) {
    const full = `${dir}/${name}`;
    if ((statSync(full) as { isDirectory(): boolean }).isDirectory()) tsxFiles(full, out);
    else if (name.endsWith(".tsx")) out.push(full);
  }
  return out;
}

/** Разметка без комментариев: в них «+ Создать бота» упоминается как БЫВШЕЕ. */
function code(path: string): string {
  return (readFileSync(path, "utf-8") as string)
    .replace(/\{\/\*[\s\S]*?\*\/\}/g, " ")
    .replace(/\/\*[\s\S]*?\*\//g, " ")
    .replace(/^\s*\/\/.*$/gm, " ");
}

describe("Подписи кнопок", () => {
  it("знака «+» в тексте подписей нет", () => {
    const виновные: string[] = [];
    for (const f of tsxFiles(SRC)) {
      for (const m of code(f).matchAll(/>\s*\+\s*[А-Яа-яЁё][^<]*</g)) {
        виновные.push(`${f}: ${m[0].trim().slice(0, 40)}`);
      }
    }
    expect(виновные, `плюс — работа значка, а не буквы:\n${виновные.join("\n")}`).toEqual([]);
  });
});

describe("Цвет опасного действия", () => {
  it("«Отключить и стереть» и «Удалить» — опасные пункты меню, а не кнопки в ряду", () => {
    /*
     * ⚠ СТОРОЖ ПЕРЕУЧЕН 15 АВГУСТА вместе с местом самих действий (п. 22
     * отчёта тестирования). Раньше оба стояли ОБЫЧНЫМИ КНОПКАМИ рядом с
     * «Переименовать»: ряд читается как ряд одинаково безобидных, а на узкой
     * колонке (280px) четыре контрола переносились на вторую строку, ставя
     * «Удалить» туда, куда падает взгляд. Теперь оба живут в меню «…» за
     * чертой от обслуживания, и охраняется именно это: НЕ Button, а
     * Menu.Item с `data-danger` — красный тем же токеном, которым в карточке
     * написано «Требует переподключения» (правка 7695de1 про почти белый
     * `color="red"` в тёмной теме остаётся в силе — токен, а не имя цвета).
     */
    const src = code("src/features/settings/accounts/AccountsPage.tsx");
    for (const действие of ["Отключить и стереть", "Удалить"]) {
      const at = src.indexOf(`${действие}\n`);
      expect(at, `«${действие}» пропало — проверьте сторожа`).toBeGreaterThan(-1);
      const разметка = src.slice(Math.max(0, at - 1600), at);
      const пункт = разметка.lastIndexOf("<Menu.Item");
      expect(пункт, `«${действие}» больше не пункт меню — курок вернулся на стол`).toBeGreaterThan(-1);
      expect(
        разметка.slice(пункт),
        `«${действие}» нарисовано без красноты опасного пункта`,
      ).toContain("data-danger");
      // Кнопкой в ряду действий его быть не должно вовсе.
      expect(разметка.slice(пункт)).not.toContain("<Button");
    }
  });

  it("«Пометить нежелательным» — не цветом согласия", () => {
    const src = code("src/features/chats/components/card/BlockClientButton.tsx");
    const at = src.indexOf(">\n          Пометить\n        <");
    const кнопка = src.slice(Math.max(0, at - 400), at);
    expect(кнопка.slice(кнопка.lastIndexOf("<Button")), "блокировка залита цветом согласия").toContain(
      'color="red"',
    );
  });
});

describe("Одно действие — одно слово", () => {
  it("выгрузка называется одним глаголом на «Разборе» и «Статистике»", () => {
    const разбор = code("src/features/table/TablePage.tsx");
    const статистика = code("src/features/stats/components/StatsFilters.tsx");
    expect(разбор).toContain("Выгрузить CSV");
    // Статистика выгружает XLSX по умолчанию — подпись не обещает CSV (24.09).
    expect(статистика).toContain("Выгрузить отчёт");
    expect(статистика).not.toContain("Выгрузить CSV");
    // «⬇» — эмодзи: его рисует операционная система, и на Windows он выглядит
    // иначе, чем на macOS. Значок обязан быть наш.
    expect(статистика).not.toContain("⬇");
  });

  it("сброс называется одинаково везде", () => {
    const короткий: string[] = [];
    for (const f of tsxFiles(SRC)) {
      if (/>\s*Сбросить\s*</.test(code(f))) короткий.push(f);
    }
    expect(короткий, `«Сбросить» без уточнения — рядом живёт «Сбросить фильтры»`).toEqual([]);
  });
});
