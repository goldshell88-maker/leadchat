/**
 * Строка канала на узком экране складывается в столбик.
 *
 * ⚠ РЕГРЕССИЯ, ПРИСЛАННАЯ СКРИНШОТОМ (05.09): «Бригада Андрея Владиславовича
 * КП …» — название обрезано, строки налезают друг на друга.
 *
 * ПРИЧИНА. Правило для узких экранов писалось, когда свёрнутая строка была
 * ФЛЕКСОМ, и говорило ровно одно: `flex-direction: column`. 04.09 строка стала
 * СЕТКОЙ — шесть колонок с поимённым закреплением, чтобы список не «ехал», — а
 * медиазапрос не тронули. `flex-direction` на сетке не делает НИЧЕГО: строка
 * осталась шестиколоночной с минимумами на 706 пикселей и на телефоне не
 * помещалась.
 *
 * ⚠ КЛАСС ДЕФЕКТА: «сменили механизм раскладки и забыли про её же исключения».
 * Ни один сторож этого не ловил, потому что оба правила по отдельности верны.
 */
// @ts-expect-error — типов Node в проекте нет (tsconfig types: ["vite/client"]).
import { readFileSync } from "node:fs";
import { describe, expect, it } from "vitest";

const CSS = readFileSync("src/features/settings/accounts/accounts.css", "utf-8") as string;

/** Тело медиазапроса для узких экранов. */
function узкий(): string {
  const m = CSS.match(/@media \(max-width:\s*900px\)\s*\{([\s\S]*?)\n\}/);
  expect(m, "нет правил для узких экранов").toBeTruthy();
  return m![1];
}

describe("Список каналов на узком экране", () => {
  it("свёрнутая строка перестаёт быть сеткой", () => {
    /*
     * Проверяем именно СМЕНУ механизма, а не наличие `flex-direction`: она и
     * была на месте всё это время и ничего не делала.
     */
    const тело = узкий();
    expect(тело).toMatch(
      /\.account-card:not\(\[data-open\]\)\s*\{[^}]*display:\s*flex/s,
    );
  });

  it("широкая раскладка — действительно сетка, иначе проверка выше ни о чём", () => {
    // Отрицательная проверка обязана падать по своей причине: если строка
    // перестанет быть сеткой и на широком экране, «перестаёт быть сеткой»
    // станет утверждением ни о чём.
    expect(CSS).toMatch(
      /\.account-card:not\(\[data-open\]\)\s*\{[^}]*display:\s*grid[^}]*grid-template-columns/s,
    );
  });
});
