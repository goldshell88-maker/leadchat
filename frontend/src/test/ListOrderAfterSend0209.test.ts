import { beforeEach, describe, expect, it } from "vitest";
import {
  поПлану,
  пересобратьПорядок,
  подписатьсяНаПорядок,
  поколениеПересборки,
} from "@/features/chats/components/list/listOrder";
import type { ConversationDto } from "@/shared/api/types";

/**
 * СВОЙ ОТВЕТ ПОДНИМАЕТ ДИАЛОГ НАВЕРХ СРАЗУ.
 *
 * ⚠ ЖАЛОБА ВЛАДЕЛЬЦА 02.09: «когда отвечаешь клиенту, не сразу чат уходит вверх».
 *
 * Это оборотная сторона заморозки порядка, заведённой 30.08 по другой боевой
 * жалобе — «целишься в строку, а она уезжает из-под руки». Заморозка держит
 * порядок четыре секунды после наведения на колонку, а диспетчер работает так:
 * щёлкнул диалог в списке, тут же ответил. Отправка попадает ровно в это окно.
 *
 * ⚠ ОБЕ ЖАЛОБЫ ВЕРНЫ, И РАЗНИЦА НЕ В ТОМ, ДВИГАТЬ ЛИ СПИСОК. Разница в том,
 * ЧЬЁ действие его двигает: своё видно сразу, чужое ждёт, пока рука опустится.
 * Поэтому заморозка не снимается, а пересобирается от нынешнего порядка.
 */

function строка(id: string, at: string): ConversationDto {
  return { id, last_message_at: at } as ConversationDto;
}

describe("Порядок списка после своей отправки", () => {
  beforeEach(() => {
    // Счётчик поколений — модульный; тесты не должны зависеть от соседей.
    пересобратьПорядок();
  });

  it("замороженный план держит прежний порядок", () => {
    /* Это защита 30.08, и её ломать нельзя: проверяем, что она жива. */
    const свежие = [строка("б", "13:36"), строка("а", "13:20")];
    expect(поПлану(свежие, ["а", "б"]).map((r) => r.id)).toEqual(["а", "б"]);
  });

  it("новые строки при заморозке встают В КОНЕЦ, а не между", () => {
    const свежие = [строка("новая", "13:40"), строка("а", "13:20"), строка("б", "13:10")];
    expect(поПлану(свежие, ["а", "б"]).map((r) => r.id)).toEqual(["а", "б", "новая"]);
  });

  it("без плана порядок свежий — заморозки нет", () => {
    const свежие = [строка("б", "13:36"), строка("а", "13:20")];
    expect(поПлану(свежие, null).map((r) => r.id)).toEqual(["б", "а"]);
  });

  it("⚠ отправка поднимает поколение — список обязан пересобрать план", () => {
    const было = поколениеПересборки();
    пересобратьПорядок();
    expect(
      поколениеПересборки(),
      "своя отправка не сообщает списку — строка уедет наверх только после заморозки",
    ).toBeGreaterThan(было);
  });

  it("подписчик узнаёт об отправке", () => {
    let вызовов = 0;
    const отписка = подписатьсяНаПорядок(() => {
      вызовов += 1;
    });
    пересобратьПорядок();
    expect(вызовов, "список не подписан — пересборка до него не дойдёт").toBe(1);
    отписка();
    пересобратьПорядок();
    expect(вызовов, "отписка не работает — утечка на размонтировании").toBe(1);
  });

  it("⚠ ПРОВОДКА: взятие диалога тоже пересобирает порядок", async () => {
    /*
     * ⚠ ЖАЛОБА ВЛАДЕЛЬЦА 02.09: «когда берёшь новые диалоги, они сначала все
     * внизу, потом скачут вверх».
     *
     * Та же заморозка, что и у отправки, только с другой стороны: строки,
     * которых в замороженном плане НЕТ, встают в конец — иначе замораживать
     * было бы нечего. Только что взятый из очереди диалог — как раз такая
     * строка. Он появлялся внизу и уезжал наверх, когда заморозка отпускала.
     *
     * Правило одно: своё действие видно сразу. Взять диалог — своё действие.
     */
    // @ts-expect-error — типов Node в проекте нет (tsconfig types: ["vite/client"]).
    const { readFileSync } = await import("node:fs");
    for (const файл of [
      "src/features/chats/inbox/claimFromQueue.ts",
      "src/features/chats/inbox/useInbox.ts",
    ]) {
      const src = readFileSync(файл, "utf-8") as string;
      // Поимённо: одного сброса плана мало — строка приезжает позже, см.
      // `ClaimedRowInPlace0209`.
      expect(src, `${файл}: взятие диалога не пересобирает порядок списка`).toContain(
        "пересобратьПорядок(convId)",
      );
    }
  });

  it("⚠ ПРОВОДКА: отправка зовёт пересборку, а список её слушает", async () => {
    /*
     * Без этого всё остальное зеленеет впустую: сигнал можно написать, покрыть
     * тестами и не позвать ни разу. Этот проект на такой дыре попадался много
     * раз — сегодня дважды.
     */
    // @ts-expect-error — типов Node в проекте нет (tsconfig types: ["vite/client"]).
    const { readFileSync } = await import("node:fs");
    const отправка = readFileSync("src/features/chats/hooks/useSendMessage.ts", "utf-8") as string;
    expect(отправка, "отправка не сообщает списку о своём сообщении").toContain(
      "пересобратьПорядок()",
    );
    const список = readFileSync(
      "src/features/chats/components/list/ChatListPane.tsx",
      "utf-8",
    ) as string;
    expect(список, "список не подписан на пересборку порядка").toContain("подписатьсяНаПорядок");
    expect(
      список,
      "план заморозки не обнуляется по поколению — порядок останется прежним",
    ).toContain("порядокПодКурсором.current = null");
  });
});
