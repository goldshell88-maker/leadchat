/**
 * Строка «Разбора диалогов» держит ОДНУ высоту и ОДНУ первую линию.
 *
 * ⚠ ЖАЛОБА ВЛАДЕЛЬЦА, ПОВТОРЁННАЯ ТРИЖДЫ РАЗНЫМИ СЛОВАМИ: «всё едет». На этом
 * экране причина своя. Ячейка «Клиент» — вертикальная стопка (имя, телефон,
 * метки), а ячейки выравнивались по центру: строка с метками выше соседней, и
 * имя в ней стоит НИЖЕ, чем имя строки без меток. Статус, оператор и числа при
 * этом на своих местах — «едет» только колонка имён, и понять почему, глядя на
 * экран, нельзя.
 *
 * ⚠ ПОЧЕМУ СТОРОЖ, А НЕ ПРОСТО ПРАВКА. Обе строки правила («по верху» и «одна
 * высота») выглядят необязательными: убери любую — экран не сломается, он
 * просто снова начнёт ехать. Ровно такие правила и снимают первыми при
 * следующей переделке.
 */
// @ts-expect-error — типов Node в проекте нет (tsconfig types: ["vite/client"]).
import { readFileSync } from "node:fs";
import { describe, expect, it } from "vitest";

const CSS = readFileSync("src/features/table/table.css", "utf-8") as string;

/** Правило для ячеек таблицы разбора. */
function ячейка(): string {
  const m = CSS.match(/\.dt__scroll \.mantine-Table-td\s*\{([^}]*)\}/s);
  expect(m, "нет правила для ячеек .dt__scroll .mantine-Table-td").toBeTruthy();
  return m![1];
}

describe("Строка разбора диалогов", () => {
  it("ячейки выровнены по верху, а не по центру", () => {
    // По центру — значит первая линия ячейки зависит от высоты САМОЙ ДЛИННОЙ
    // ячейки строки, то есть от того, есть ли у клиента метки.
    expect(ячейка()).toMatch(/vertical-align:\s*top/);
    expect(ячейка(), "выравнивание по центру вернулось").not.toMatch(/vertical-align:\s*middle/);
  });

  it("высота строки задана числом", () => {
    // Без неё строки без телефона и меток были бы ниже соседних, и колонка
    // статусов поехала бы теперь уже в другую сторону.
    expect(ячейка()).toMatch(/height:\s*\d+px/);
  });

  it("ячейка клиента осталась стопкой — телефон и метки свисают вниз", () => {
    /*
     * Это вторая половина правила, и без неё первая бессмысленна: если имя,
     * телефон и метки встанут в РЯД, ячейка снова начнёт распирать колонку —
     * и поедет уже ширина, как это было в списке каналов.
     */
    const m = CSS.match(/\.dt__client\s*\{([^}]*)\}/s);
    expect(m, "нет правила .dt__client").toBeTruthy();
    expect(m![1]).toMatch(/flex-direction:\s*column/);
  });
});
