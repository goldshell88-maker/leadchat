/**
 * ОДИН ЦВЕТ — ОДИН СМЫСЛ. Проверка перцептивной дистанции, а не контраста.
 *
 * ПРАВИЛО, КОТОРОЕ ЭТОТ ФАЙЛ ЗАЩИЩАЕТ (docs/16, «Основания»): «Цвет несёт ровно
 * один смысл — срочность. Янтарь: клиент ждёт. Красный: диалог брошен. Зелёный:
 * действие». Разбор интерфейса 13.08 показал, что продукт его не выполняет: у
 * зелёного насчитали восемнадцать смыслов, у янтарного двадцать девять.
 *
 * ⚠ ПОЧЕМУ НЕ ЛОВИЛОСЬ НИЧЕМ. В проекте три сторожа цвета — tokenContrast (пары
 * «чернила на заливке»), surfaceLadder (ступени поверхностей), buttonCanon (токен
 * опасного действия). Ни один не задаёт вопроса «сколько РАЗНЫХ СМЫСЛОВ у одного
 * hex»: они проверяют читаемость, а не однозначность. Совпадение двух смыслов
 * читаемость не портит — оно портит понимание, и приборов на это не было.
 *
 * ⚠ И ПОЧЕМУ КОНТРАСТ ЗДЕСЬ НЕ ГОДИТСЯ — это стоило мне ошибки по дороге.
 * Контраст WCAG меряет СВЕТЛОТУ. Фиолетовый #a78bfa против янтарного #f59e0b даёт
 * 1.27 — по контрасту «неразличимы», хотя спутать их невозможно. Вопрос «различит
 * ли глаз два кружка рядом» решается перцептивной дистанцией: ΔE в OKLab.
 * Шкала ΔE·100: ~5 едва заметно, ~10 явно, >20 разные цвета.
 */

// @ts-expect-error — типов Node в проекте нет (tsconfig types: ["vite/client"]),
// как в surfaceLadder.test.ts: сторож только читает файлы.
import { readFileSync } from "node:fs";
import { describe, expect, it } from "vitest";

const VARS = readFileSync("src/app/lc-vars.css", "utf-8") as string;

type Scheme = "dark" | "light";

/**
 * Токены схемы — разбором ПО БЛОКАМ, а не срезом файла.
 *
 * ⚠ ПЕРВАЯ РЕДАКЦИЯ РЕЗАЛА ФАЙЛ ПО СТРОКЕ «prefers-color-scheme: light», КОТОРОЙ В
 * НЁМ НЕТ. Темы здесь разделены селектором `:root[data-mantine-color-scheme="light"]`,
 * поэтому `indexOf` возвращал −1, срез отдавал весь файл целиком, и в «тёмную» карту
 * последним значением попадали СВЕТЛЫЕ. Тест при этом краснел — но не на том, на чём
 * думал. Ровно та же ошибка сначала вышла и в разборе на python: одинаковый приём,
 * одинаковый результат.
 *
 * Блоки светлой темы стоят в файле не одним куском, а вперемежку с тёмными, так что
 * двусторонний срез не работает в принципе. Разбираем каждый блок с его селектором.
 */
/*
 * ⚠ ЦВЕТОВЫЕ ПРЕСЕТЫ — ВТОРАЯ ОСЬ (04.09). Разбор ниже читал ЛЮБОЙ блок с
 * `:root`, поэтому блоки пресетов подмешивались и в тёмную карту, и в
 * светлую — а лежат они в конце файла и перезаписывали обе. Роли мерились бы
 * у палитры, которой ни один человек не видит.
 *
 * Список пресетов повторяет `tokenContrast.test.ts`; что они не разъедутся,
 * стережёт `presets0409.test.ts`.
 */
const PRESETS = ["indigo", "amethyst", "copper"] as const;
type Preset = (typeof PRESETS)[number] | null;
type Variant = { preset: Preset; scheme: Scheme };
const VARIANTS: Variant[] = [null, ...PRESETS].flatMap((preset) => [
  { preset, scheme: "dark" as const },
  { preset, scheme: "light" as const },
]);
const имяВарианта = (v: Variant) => `${v.preset ?? "базовая"}/${v.scheme}`;

function tokens(variant: Variant): Map<string, string> {
  const карта = new Map<string, string>();
  const светлаяСхема = variant.scheme === "light";
  // Довод про `:not(...)` — в tokenContrast.test.ts, ловушка та же.
  const безОговорки = (с: string) => с.replace(/:not\([^)]*\)/g, "");
  const применить = (нужен: (селектор: string) => boolean) => {
    for (const м of VARS.matchAll(/([^{}]+)\{([^}]*)\}/g)) {
      const селектор = м[1];
      if (селектор.includes("@media")) continue;
      if (!нужен(безОговорки(селектор))) continue;
      for (const т of м[2].matchAll(/(--lc-[a-z0-9-]+):\s*([^;]+);/g)) карта.set(т[1], т[2].trim());
    }
  };
  // Сперва база: светлая тема наследует тёмные умолчания и кладёт своё сверху.
  применить((селектор) => {
    if (!селектор.includes(":root")) return false;
    if (селектор.includes("data-lc-preset")) return false;
    const светлый = селектор.includes('color-scheme="light"');
    return светлый ? светлаяСхема : true;
  });
  // Потом пресет — у него в CSS выше специфичность, здесь это порядок.
  if (variant.preset) {
    const мой = `data-lc-preset="${variant.preset}"`;
    применить((селектор) => {
      if (!селектор.includes(мой)) return false;
      return селектор.includes('color-scheme="light"') === светлаяСхема;
    });
  }
  return карта;
}

const TOKENS = new Map<string, Map<string, string>>(
  VARIANTS.map((v) => [имяВарианта(v), tokens(v)] as const),
);

type Where = Scheme | Variant;
const ключВарианта = (w: Where) => (typeof w === "string" ? `базовая/${w}` : имяВарианта(w));

function resolve(имя: string, scheme: Where, глубина = 0): string {
  const v =
    TOKENS.get(ключВарианта(scheme))!.get(имя) ?? TOKENS.get("базовая/dark")!.get(имя) ?? "";
  if (глубина > 8) return v;
  const м = /^var\((--lc-[a-z0-9-]+)\)$/.exec(v.trim());
  return м ? resolve(м[1], scheme, глубина + 1) : v.trim();
}

function rgb(hex: string): [number, number, number] {
  const h = hex.replace("#", "");
  return [0, 2, 4].map((i) => parseInt(h.slice(i, i + 2), 16)) as [number, number, number];
}

/** sRGB → OKLab. Формула Björn Ottosson, коэффициенты не округлены намеренно. */
function oklab([R, G, B]: [number, number, number]): [number, number, number] {
  const лин = (c: number) => {
    const x = c / 255;
    return x <= 0.04045 ? x / 12.92 : ((x + 0.055) / 1.055) ** 2.4;
  };
  const [r, g, b] = [лин(R), лин(G), лин(B)];
  const l = Math.cbrt(0.4122214708 * r + 0.5363325363 * g + 0.0514459929 * b);
  const m = Math.cbrt(0.2119034982 * r + 0.6806995451 * g + 0.1073969566 * b);
  const s = Math.cbrt(0.0883024619 * r + 0.2817188376 * g + 0.6299787005 * b);
  return [
    0.2104542553 * l + 0.793617785 * m - 0.0040720468 * s,
    1.9779984951 * l - 2.428592205 * m + 0.4505937099 * s,
    0.0259040371 * l + 0.7827717662 * m - 0.808675766 * s,
  ];
}

/** ΔE·100 в OKLab: «насколько это разные цвета для глаза». */
function deltaE(a: string, b: string): number {
  const [A, B] = [oklab(rgb(a)), oklab(rgb(b))];
  return Math.hypot(A[0] - B[0], A[1] - B[1], A[2] - B[2]) * 100;
}

/**
 * Порог различимости. 15 — «видно боковым зрением», а не «видно, если приглядеться».
 * Ниже брать нельзя: замер показал, что два соседних шага янтаря дают 9-11 и на
 * экране читаются одним пятном — ровно то, ради чего этот файл и заведён.
 */
const РАЗЛИЧИМО = 15;

/**
 * Пары, которые ОБЯЗАНЫ различаться, потому что видны человеку ОДНОВРЕМЕННО.
 * Список короткий намеренно: сюда попадает не «два токена одного цвета», а
 * «два смысла в одном кадре». Совпадение цветов на разных экранах никому не мешает
 * и в сторожа не идёт — иначе он превратится в запрет пользоваться палитрой.
 */
const ПАРЫ: ReadonlyArray<{ a: string; b: string; где: string }> = [
  {
    a: "--lc-conn-ok",
    b: "--lc-presence-online",
    где: "окно «это я» в рельсе: точка связи под точкой присутствия",
  },
  {
    a: "--lc-conn-degraded",
    b: "--lc-presence-away",
    где: "то же окно, когда вы отошли и связь просела",
  },
  {
    a: "--lc-presence-away",
    b: "--lc-presence-online",
    где: "переключатель «На месте / Отошёл» — обе точки в одном контроле",
  },
  {
    a: "--lc-presence-away",
    b: "--lc-warning",
    где: "/chats: полоса «отошёл» на рельсе и полоса срочности строки — обе 3px по левому краю",
  },
];

/**
 * ИЗВЕСТНЫЕ СЛАБОСТИ: тест на них НЕ падает, но печатает список, чтобы про них нельзя
 * было забыть молча. Приём взят у `tokenContrast.test.ts`, где так же вынесены две
 * пары, которые чинятся не значением токена.
 */
const ИЗВЕСТНО: ReadonlyArray<{ a: string; b: string; scheme: Scheme; почему: string }> = [
  {
    a: "--lc-presence-away",
    b: "--lc-warning",
    scheme: "dark",
    почему:
      "ΔE 0 — это один токен: --lc-presence-away объявлен как var(--lc-warn). Видно их " +
      "одновременно на /chats: рельса в состоянии «отошёл» рисует полосу " +
      "`inset 3px 0 0` по левому краю, а строка ждущего диалога — ::before шириной 3px " +
      "по своему левому краю, в 80px правее. Та же ширина, тот же край, тот же hex; " +
      "различаются только длиной (вся высота окна против 54px). Проверено отрисовкой. " +
      "⚠ ЧИНИТСЯ НЕ ЦВЕТОМ, А ФОРМОЙ, и потому не сделано сегодня: у полосы рельсы " +
      "записан довод — «пометка на аватаре одна теряется среди значков», то есть " +
      "полоса существует ради заметности с любого экрана. Перекрасить «отошёл» — " +
      "значит спорить с тем, что away во всех продуктах янтарный; сменить форму — " +
      "отдельная правка рельсы с проверкой, что заметность не потерялась.",
  },
  {
    a: "--lc-presence-away",
    b: "--lc-warning",
    scheme: "light",
    почему: "То же самое и по той же причине: в светлой теме оба #b45309.",
  },
  {
    a: "--lc-conn-degraded",
    b: "--lc-presence-away",
    scheme: "light",
    почему:
      "ΔE 9.1. В светлой теме «отошёл» — это amber-700 #b45309, сам по себе буро-красный, " +
      "и любой красный оказывается к нему близко (red-600 даёт 9.9, red-700 — 9.1). " +
      "Развести можно, только уведя связь в синий целиком — но тогда «просело» перестанет " +
      "отличаться от «в сети» цветом, а подпись на узких экранах скрывается " +
      "(ConnectionIndicator: «цвет точки говорит то же самое»). Выбран размен: общий случай " +
      "(вы отошли, связь цела) разведён полностью — зелёное ушло в синее; совпадение " +
      "остаётся только когда И вы отошли, И сервер просел, и там рядом есть подпись.",
  },
];

/**
 * ⚠ ПАРА, КОТОРУЮ Я ВПИСАЛ ПО АНАЛОГИИ И УБРАЛ, ПРОВЕРИВ.
 * `--lc-conn-lost` против `--lc-presence-offline` — оба серые, ΔE 4.9. Но в один кадр
 * они не попадают: `presence-offline` рисуется только у ЧУЖОГО присутствия (карточка
 * клиента, список команды), а в окне «это я» его нет вовсе — grep по `tone="offline"`
 * это подтверждает. Правило этого файла: сюда идёт «два смысла в одном кадре», а не
 * «два токена одного цвета», иначе сторож превращается в запрет пользоваться палитрой.
 */

describe("Один цвет — один смысл", () => {
  it.each(VARIANTS)("смыслы в одном кадре различимы: $preset/$scheme", (variant) => {
    const scheme = variant;
    /* ⚠ Имена токенов и их значения держим ПОРОЗНЬ. Первая редакция клала hex в те же
       поля `a`/`b` — и список известных слабостей, который сверяется по ИМЕНАМ, после
       этого не находил ничего. Тест краснел на паре, которая тут же была объявлена
       известной: прибор спорил сам с собой. */
    const слабые = ПАРЫ.map((п) => {
      const цветA = resolve(п.a, scheme);
      const цветB = resolve(п.b, scheme);
      return { ...п, цветA, цветB, ΔE: deltaE(цветA, цветB) };
    })
      .filter((п) => п.ΔE < РАЗЛИЧИМО)
      /*
       * ⚠ ИЗВЕСТНЫЕ СЛАБОСТИ ЗАПИСАНЫ ПО СХЕМЕ, А НЕ ПО ВАРИАНТУ, И ЭТО ВЕРНО:
       * они про роли базовой палитры (янтарь «отошёл» = янтарь «тревога»),
       * которые пресеты не трогают. Сравнивать надо со схемой варианта — иначе
       * послабление перестаёт находиться и обвиняет каждый пресет в чужой беде.
       */
      .filter(
        (п) => !ИЗВЕСТНО.some((и) => и.a === п.a && и.b === п.b && и.scheme === variant.scheme),
      );

    expect(
      слабые,
      `цвета сливаются:\n${слабые
        .map((п) => `  ${п.где}\n    ${п.a} ${п.цветA} × ${п.b} ${п.цветB} → ΔE ${п.ΔE.toFixed(1)}`)
        .join("\n")}`,
    ).toEqual([]);
  });

  it("известные слабости всё ещё слабости — иначе строку пора убрать", () => {
    for (const п of ИЗВЕСТНО) {
      const ΔE = deltaE(resolve(п.a, п.scheme), resolve(п.b, п.scheme));
      // Если пару всё-таки развели — строка обязана уйти отсюда, а не висеть вечно.
      expect(ΔE, `${п.a} × ${п.b} (${п.scheme}) развели: ΔE ${ΔE.toFixed(1)}`).toBeLessThan(
        РАЗЛИЧИМО,
      );
      console.info(`известная слабость: ${п.a} × ${п.b} (${п.scheme}) — ΔE ${ΔE.toFixed(1)}`);
    }
  });

  it("⚠ СВЯЗЬ НЕ ЗАНИМАЕТ ТОКЕНЫ ПРИСУТСТВИЯ", () => {
    /*
     * Проверяется не значение, а ССЫЛКА. Значения можно развести и снова свести
     * одной правкой примитива; ссылка же говорит о намерении. Ровно так дефект и
     * прожил: в app-layout.css написали «связь, а не человек», развели одно
     * состояние из трёх, а два других остались на `--lc-presence-*` — и правка
     * цвета присутствия молча меняла бы цвет связи.
     */
    const layout = readFileSync("src/app/app-layout.css", "utf-8") as string;
    const правила = layout.replace(/\/\*[\s\S]*?\*\//g, "");
    const занял = [...правила.matchAll(/\.lc-conn__dot[^{]*\{([^}]*)\}/g)]
      .map((м) => м[1])
      .filter((тело) => /--lc-presence-/.test(тело));
    expect(занял, "индикатор связи снова взял токен присутствия").toEqual([]);
  });

  it("сам расчёт умеет находить слияние — иначе тест зелёный ни о чём", () => {
    // Два соседних шага янтаря: на экране одно пятно, и прибор обязан это видеть.
    expect(deltaE("#f59e0b", "#d97706")).toBeLessThan(РАЗЛИЧИМО);
    // Янтарь против синего — заведомо разные цвета.
    expect(deltaE("#f59e0b", "#60a5fa")).toBeGreaterThan(20);
    // ⚠ И то, на чём я ошибся: по контрасту WCAG эта пара «неразличима» (1.27),
    // а по ΔE — разные цвета. Прибор обязан отвечать на второй вопрос.
    expect(deltaE("#a78bfa", "#f59e0b")).toBeGreaterThan(20);
  });
});
