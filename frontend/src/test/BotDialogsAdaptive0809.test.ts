// как в breakpoints.test.ts и BotsLeadsAdaptiveBold0509.test.ts: сторож читает файлы.
import { readFileSync } from "node:fs";
import { describe, expect, it } from "vitest";

/**
 * СТОРОЖА РАСКЛАДКИ ЭКРАНА «ДИАЛОГИ БОТА» (08.09).
 *
 * ⚠ ЭТОТ СТОРОЖ НАСТОЯЩЕЙ РАСКЛАДКИ НЕ ВИДИТ И ВИДЕТЬ НЕ МОЖЕТ. В конфигурации
 * тестов стоит `css: false` (vite.config.ts), а jsdom не считает ни ширин, ни
 * переносов, ни переполнений: `getBoundingClientRect` там возвращает нули.
 * Ровно поэтому все три беды ниже уехали в бой мимо 300+ проверок проекта — не
 * потому, что их не проверяли, а потому, что проверить их было нечем.
 *
 * Проверено РУКАМИ на стенде адаптива: боевой CSS (`npm run build`, все чанки,
 * включая ленивый BotDialogsPage-*.css), настоящая разметка (снималка
 * `stat-tabl-снимок.dump.tsx` → `.dump/stat-tabl-bot.html`), каркас с рельсой
 * 218px — в бою она РАЗВЁРНУТА по умолчанию (railStore.ts: `expanded: true`,
 * RAIL_WIDTH_EXPANDED = 218). Замер при 72 даёт экрану на 146px больше
 * реальности и половину бед не воспроизводит вовсе. Матрица: 14 размеров
 * (390×780 … 2560×1300), обе ширины рельсы.
 *
 *   ┌──────────────────────────┬──────────── ДО ────────┬──────── ПОСЛЕ ──────┐
 *   │ таблица, срез справа     │ 900: 121px, 768: 253,  │ те же числа, но     │
 *   │ (рельса 218)             │ 390: 461 — БЕЗ ПОЛОСЫ  │ прокруткой (auto)   │
 *   │ имя клиента, наезд       │ 390/р72: 60.9px поверх │ 0px, многоточие     │
 *   │ на соседнюю колонку      │ соседа, в две строки   │ одной строкой       │
 *   │ полоса прокрутки у       │ 1024×700: 195px ниже   │ 0 — прокрутка своя, │
 *   │ ДОКУМЕНТА                │ края, 1280×627: 112    │ у раздела           │
 *   └──────────────────────────┴────────────────────────┴─────────────────────┘
 *
 * Сторожа проверяют ПРИЧИНУ — то, чем эти числа держатся: объявления в CSS и
 * подпись в разметке. Если завтра кто-то вернёт `overflow: hidden` ради углов
 * или снимет многоточие с имени, красным станет здесь, а не в бою.
 */

const CSS = "src/features/bot-dialogs/bot-dialogs.css";
const СТРАНИЦА = "src/features/bot-dialogs/BotDialogsPage.tsx";

/** Соседи, у которых прокрутка раздела сделана раньше и правильно. */
const СОСЕДИ: Array<{ путь: string; селектор: string }> = [
  { путь: "src/features/stats/stats.css", селектор: ".stats-page" },
  { путь: "src/features/settings/accounts/accounts.css", селектор: ".accounts-page" },
  { путь: "src/features/feed/feed.css", селектор: ".lc-feed" },
];

function файл(путь: string): string {
  return readFileSync(путь, "utf-8") as string;
}

/** Текст без комментариев: разбор в шапке правила вправе называть что угодно. */
function безКомментариев(путь: string): string {
  return файл(путь).replace(/\/\*[\s\S]*?\*\//g, " ");
}

/** Все правила файла: список селекторов и тело. Медиазапросы включены. */
function правила(путь: string): Array<{ селекторы: string[]; тело: string }> {
  const css = безКомментариев(путь);
  const out: Array<{ селекторы: string[]; тело: string }> = [];
  const rx = /([^{}@]+)\{([^{}]*)\}/g;
  let m: RegExpExecArray | null;
  while ((m = rx.exec(css)) !== null) {
    const голова = m[1].trim();
    if (!голова || голова.startsWith("@")) continue;
    out.push({ селекторы: голова.split(",").map((s) => s.trim()).filter(Boolean), тело: m[2] });
  }
  return out;
}

/**
 * Все объявления, доезжающие до селектора, одной строкой.
 *
 * ⚠ СКЛЕИВАЮТСЯ ТЕЛА ВСЕХ ПРАВИЛ, ГДЕ ЭТОТ СЕЛЕКТОР УПОМЯНУТ, а не одного:
 * обрезка у `.bot-live__who` объявлена в общем правиле с двумя соседями, а
 * кегль и цвет — в своём. Ищи только точное совпадение — иначе `.bot-live`
 * подберёт объявления `.bot-live__who` и сторож позеленеет не на том.
 */
function объявления(путь: string, селектор: string): string {
  const свои = правила(путь).filter((п) => п.селекторы.includes(селектор));
  // Отрицательная проверка обязана падать по своей причине: не нашлось ни
  // одного правила — значит, селектор переименован или разбор сломался, и
  // молчать об этом нельзя.
  expect(свои.length, `${путь}: правил для «${селектор}» не найдено`).toBeGreaterThan(0);
  return свои.map((п) => п.тело).join(";");
}

function есть(тело: string, свойство: string, значение: RegExp): boolean {
  const rx = new RegExp(`(^|;|\\s)${свойство}\\s*:\\s*([^;}]+)`, "g");
  let m: RegExpExecArray | null;
  let последнее: string | null = null;
  while ((m = rx.exec(тело)) !== null) последнее = m[2].trim();
  return последнее !== null && значение.test(последнее);
}

/* ═══════ 1. Таблица не режет молча: скругление отдельно, обрезка отдельно ═══ */

describe("Таблица бота: столбцы доступны прокруткой, а не срезаны", () => {
  it(".bot-table прокручивается по горизонтали, а не прячет лишнее", () => {
    const тело = объявления(CSS, ".bot-table");
    expect(
      есть(тело, "overflow-x", /^(auto|scroll)$/),
      "у .bot-table нет overflow-x: auto — столбцы «Сообщений» и «Первый ответ» " +
        "исчезнут справа без полосы прокрутки (замер 08.09: срез 121px при 900, 253 при 768)",
    ).toBe(true);
  });

  it(".bot-table не возвращает overflow: hidden ради углов", () => {
    const тело = объявления(CSS, ".bot-table");
    expect(
      есть(тело, "overflow", /hidden|clip/),
      "`overflow: hidden` вернулся. Углы он скругляет, но заодно молча режет: " +
        "именно так столбцы и пропали. Скругление держит border-radius — " +
        "содержимое обрезается по скруглённой границе при ЛЮБОМ overflow, кроме visible",
    ).toBe(false);
  });

  it("скругление углов при этом не потеряно", () => {
    const тело = объявления(CSS, ".bot-table");
    expect(
      есть(тело, "border-radius", /var\(--lc-radius-/),
      "у .bot-table пропал border-radius — прямые углы таблицы вылезут из рамки; " +
        "ради этого здесь когда-то и стоял overflow: hidden",
    ).toBe(true);
  });
});

/* ═════════ 2. Каждая ячейка живой строки умеет обрезаться многоточием ═══════ */

describe("Полоса «Сейчас у бота»: буквы не ложатся поверх букв", () => {
  const ЯЧЕЙКИ = [".bot-live__who", ".bot-live__meta", ".bot-live__said"];

  for (const ячейка of ЯЧЕЙКИ) {
    it(`${ячейка} сжимается и обрезается видимо`, () => {
      const тело = объявления(CSS, ячейка);
      // `min-width: 0` — без него многоточие мёртвое: ячейка сетки не умеет
      // сжиматься ниже своего содержимого, и обрезать нечего. Ровно этот
      // пропуск 29.08 сделал обрезку на «Аккаунтах Авито» немым правилом.
      expect(есть(тело, "min-width", /^0(px)?$/), `${ячейка}: нет min-width: 0`).toBe(true);
      expect(есть(тело, "overflow", /hidden/), `${ячейка}: нет overflow: hidden`).toBe(true);
      expect(есть(тело, "text-overflow", /ellipsis/), `${ячейка}: нет многоточия`).toBe(true);
      expect(есть(тело, "white-space", /nowrap/), `${ячейка}: нет white-space: nowrap`).toBe(true);
    });
  }

  it("имя клиента остаётся читаемым: у .bot-live__who есть title", () => {
    const tsx = файл(СТРАНИЦА);
    expect(
      /className="bot-live__who"\s+title=\{/.test(tsx),
      "у span.bot-live__who пропал title. Имя теперь обрезается многоточием " +
        "(замер 08.09: на 390 колонке достаётся 17px при 151 нужных) — " +
        "обрезка видима, но текст обязан оставаться доступным наведением",
    ).toBe(true);
  });
});

/* ═══════════ 3. Прокрутка у раздела, а не у документа — как у соседей ══════ */

describe("Раздел прокручивается сам, второй полосы у страницы нет", () => {
  it(".bot-dialogs объявляет flex: 1, min-height: 0 и свою прокрутку", () => {
    const тело = объявления(CSS, ".bot-dialogs");
    expect(
      есть(тело, "flex", /^1(\s|$)/),
      ".bot-dialogs не забирает остаток колонки .lc-main (flex: 1)",
    ).toBe(true);
    // ⚠ Пара неразрывна. `flex: 1` без `min-height: 0` не работает вовсе:
    // флекс-ребёнок по умолчанию не сжимается ниже содержимого и выпирает из
    // колонки — прокрутка достаётся документу (замер: 1024×700 → 195px ниже края).
    expect(
      есть(тело, "min-height", /^0(px)?$/),
      ".bot-dialogs без min-height: 0 — flex: 1 рядом бесполезен, содержимое выдавит колонку",
    ).toBe(true);
    expect(
      есть(тело, "overflow-y", /^(auto|scroll)$/),
      ".bot-dialogs без своей прокрутки — полоса появится у документа, " +
        "и заголовок с полосой «Сейчас у бота» уедут наверх (замер: 1280×627 → 112px)",
    ).toBe(true);
  });

  it("рецепт тот же, что у соседних разделов, а не свой", () => {
    // Разойтись здесь с соседями — значит получить экран, где прокрутка
    // ведёт себя иначе, чем на остальных четырёх. Сторож требует не «похоже»,
    // а буквально тот же набор объявлений.
    for (const { путь, селектор } of СОСЕДИ) {
      const тело = объявления(путь, селектор);
      expect(есть(тело, "flex", /^1(\s|$)/), `${селектор}: пропал flex: 1`).toBe(true);
      expect(есть(тело, "min-height", /^0(px)?$/), `${селектор}: пропал min-height: 0`).toBe(true);
    }
  });
});
