// @ts-expect-error — типов Node в проекте нет (tsconfig types: ["vite/client"]);
// ровно так же поступают соседние сторожа surfaceLadder и ChatsAdaptiveBold0509.
import { readFileSync } from "node:fs";
import { describe, expect, it } from "vitest";

const СПИСОК = "src/features/chats/components/list/chat-list.css";
const ШКАЛА = "src/features/chats/components/list/wait-gauge.css";
const РЕЛЬСА = "src/app/app-rail.css";
const ПАНЕЛЬ = "src/features/chats/components/list/ChatListPane.tsx";

/** Текст файла без комментариев: в них разобраны сами дефекты, и наивный поиск
 *  краснел бы на объяснении вместо правила. */
const безКомментариев = (путь: string): string =>
  (readFileSync(путь, "utf-8") as string).replace(/\/\*[\s\S]*?\*\//g, " ");

/** Тело правила по точному селектору. */
function правило(путь: string, селектор: string): string {
  const css = безКомментариев(путь);
  const at = css.indexOf(`\n${селектор} {`);
  expect(at, `${путь}: правило ${селектор} не найдено`).toBeGreaterThan(-1);
  return css.slice(at, css.indexOf("}", at));
}

describe("Огранка: левая вертикаль кадра одна", () => {
  it("шапка списка и строка отсчитывают одни и те же 17px от края колонки", () => {
    /*
     * 1 (рамка панели) + 16 (боковое поле шапки) = 17 — заголовок, поиск, вкладки.
     * 1 (рамка панели) + 8 (вылет карточки) + 8 (поле строки) = 17 — аватар.
     * Рамки у карточки при этом нет вовсе: прозрачный пиксель занимал место
     * всегда и сбивал аватар на 18.
     */
    expect(
      правило(СПИСОК, ".chat-list-pane__header"),
      "боковое поле шапки списка ушло со ступени 16 — вертикаль разъехалась",
    ).toMatch(/padding:\s*var\(--lc-space-4\)\s+var\(--lc-space-4\)\s+var\(--lc-space-3\)/);

    const карточка = правило(СПИСОК, ".conv-card");
    expect(карточка, "вылет карточки перестал быть 8").toMatch(
      /margin:\s*0\s+var\(--lc-space-2\)/,
    );
    expect(карточка, "у строки снова рамка — она занимает место и в невыбранном виде").toMatch(
      /border:\s*none/,
    );

    expect(
      правило(СПИСОК, ".conv-card__main"),
      "внутреннее поле строки: слева ступень 8, справа его нет (см. ячейку времени)",
    ).toMatch(/padding:\s*0\s+0\s+0\s+var\(--lc-space-2\)/);
  });

  it("зелёный контур выбранной строки лежит ПОВЕРХ янтарной ячейки", () => {
    /*
     * `box-shadow: inset` рисуется над фоном, но под детьми, а ячейка времени
     * теперь прижата к правому краю строки во всю её высоту. Контур на самой
     * строке ушёл бы под ячейку и рвался бы на её 48px.
     */
    expect(правило(СПИСОК, ".conv-card[data-active]::after")).toMatch(
      /box-shadow:\s*inset 0 0 0 1px var\(--lc-primary\)/,
    );
    expect(
      правило(СПИСОК, ".conv-card::after"),
      "слой контура обязан быть прозрачным в покое и не ловить нажатия",
    ).toMatch(/pointer-events:\s*none/);
    expect(правило(СПИСОК, ".conv-card[data-active]"), "ореол выбранного пропал").toMatch(
      /box-shadow:\s*var\(--lc-shadow-glow\)/,
    );
  });

  it("ячейка времени скругляется строкой, а не сама собой", () => {
    /*
     * У строки радиус 12, у ячейки стоял собственный «0 4px 4px 0» — янтарная
     * заливка выходила за скруглённый край строки у двух правых углов.
     */
    expect(
      безКомментариев(ШКАЛА),
      "у .wait-gauge снова свой радиус — он разойдётся с радиусом строки",
    ).not.toMatch(/border-radius/);
    expect(
      правило(СПИСОК, ".conv-card"),
      "строка перестала обрезать ячейку времени своим радиусом",
    ).toMatch(/overflow:\s*hidden/);
    /* ⚠ ЗАЩИТА, А НЕ ОФОРМЛЕНИЕ: у импортированных диалогов в ячейке стоит дата
       «01.08.2025» шириной 61px. Без жёсткой ширины она срезается с обеих
       сторон и читается как ДРУГАЯ дата. */
    expect(безКомментариев(ШКАЛА), "жёсткая ширина ячейки времени снята").toMatch(
      /width:\s*var\(--lc-row-time-w\)/,
    );
  });

  it("зазор строк списка назван, а не вписан числом в трёх местах", () => {
    /*
     * 84 (ChatListPane.ROW_HEIGHT) − 78 (высота карточки) = 6. Список
     * виртуализирован: число живёт парой, и в CSS в одиночку его менять нельзя.
     * На шкале --lc-space-* шестёрки нет — это остаток арифметики, а не ступень
     * воздуха, поэтому имя объявлено локально.
     */
    const css = безКомментариев(СПИСОК);
    expect(css, "локальное имя зазора строк исчезло").toMatch(/--lc-row-gap:\s*6px/);
    expect(
      правило(СПИСОК, ".chat-list-pane__scroll"),
      "верхнее поле ленты снова не равно зазору между строками",
    ).toMatch(/padding-top:\s*var\(--lc-row-gap\)/);

    const tsx = readFileSync(ПАНЕЛЬ, "utf-8") as string;
    const m = /const ROW_HEIGHT = (\d+);/.exec(tsx);
    expect(m, "ROW_HEIGHT в ChatListPane.tsx не найден").not.toBeNull();
    const высота = /height:\s*(\d+)px/.exec(правило(СПИСОК, ".conv-card"));
    expect(высота, "высота .conv-card не найдена").not.toBeNull();
    expect(
      Number(m![1]) - Number(высота![1]),
      "шаг виртуализации и высота карточки разошлись с объявленным зазором 6",
    ).toBe(6);
  });

  it("рельса: знак стоит на оси разделов, разделитель — на ступени шкалы", () => {
    /*
     * Было 38 при пунктах 44: знак центрировался по своей ячейке и стоял на
     * (44 − 38) / 2 = 3px выше вертикальной оси значков разделов. Разделитель
     * был 28 — ни ширина пункта (44), ни ширина его значка (20).
     */
    expect(правило(РЕЛЬСА, ".lc-rail__logo"), "ячейка знака снова не равна пункту").toMatch(
      /height:\s*44px/,
    );
    expect(правило(РЕЛЬСА, ".lc-rail__item"), "пункт рельсы перестал быть 44").toMatch(
      /height:\s*44px/,
    );
    expect(правило(РЕЛЬСА, ".lc-rail__divider"), "ширина разделителя ушла со ступени 24").toMatch(
      /width:\s*var\(--lc-space-5\)/,
    );
  });

  it("отступов числом в этих трёх файлах не осталось", () => {
    /*
     * Единственное разрешённое число — `padding: 3px` у обоймы «на месте /
     * отошёл» в рельсе: ровно на него посчитан внутренний радиус вложенной
     * кнопки (`calc(--lc-radius-md - 3px)`). Возьми ступень шкалы — и кнопка
     * отклеится от рамки обоймы.
     */
    const исключения = new Map<string, number>([[РЕЛЬСА, 1]]);
    const плохие: string[] = [];
    for (const файл of [СПИСОК, ШКАЛА, РЕЛЬСА]) {
      const числом = безКомментариев(файл)
        .split("\n")
        .filter((s) => /^\s*(padding|margin|gap|row-gap|column-gap)[a-z-]*:.*\d+(px|em|rem|%)/.test(s));
      const можно = исключения.get(файл) ?? 0;
      if (числом.length > можно) плохие.push(`${файл}: ${числом.join(" | ").trim()}`);
    }
    expect(плохие, `отступ мимо шкалы:\n${плохие.join("\n")}`).toEqual([]);
  });
});
