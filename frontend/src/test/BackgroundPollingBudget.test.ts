import { describe, expect, it } from "vitest";
// @ts-expect-error — типов Node в проекте нет (tsconfig types: ["vite/client"]).
import { readFileSync } from "node:fs";
// @ts-expect-error — тот же случай.
import { readdirSync, statSync } from "node:fs";

/** Запросы, которым фоновый опрос разрешён — с причиной. */
const РАЗРЕШЕНО: Record<string, string> = {};

function файлы(корень: string): string[] {
  const out: string[] = [];
  for (const имя of readdirSync(корень) as string[]) {
    const путь = `${корень}/${имя}`;
    if ((statSync(путь) as { isDirectory(): boolean }).isDirectory()) {
      if (имя === "test" || имя === "node_modules") continue;
      out.push(...файлы(путь));
    } else if (имя.endsWith(".ts") || имя.endsWith(".tsx")) {
      out.push(путь);
    }
  }
  return out;
}

describe("Фоновый опрос", () => {
  it("никто не опрашивает сервер из свёрнутой вкладки без объяснения", () => {
    const виновные: string[] = [];
    for (const путь of файлы("src")) {
      /*
       * ⚠ КОММЕНТАРИИ ВЫРЕЗАЕМ ДО ПОИСКА. Первая редакция сторожа искала слово
       * по всему файлу — и поймала РАЗБОР в комментарии над самой правкой
       * («здесь стояло refetchIntervalInBackground: true»). Проверка, которая
       * не отличает код от рассказа о коде, краснеет на честном файле и
       * зеленеет на закомментированном.
       */
      const текст = (readFileSync(путь, "utf-8") as string)
        .replace(/\/\*[\s\S]*?\*\//g, " ")
        .replace(/\/\/[^\n]*/g, " ");
      // Считаем только ВКЛЮЧЁННЫЙ фоновый опрос: `: true`.
      if (!/refetchIntervalInBackground:\s*true/.test(текст)) continue;
      const ключ = путь.replace(/^src\//, "");
      if (ключ in РАЗРЕШЕНО) continue;
      виновные.push(ключ);
    }
    expect(
      виновные,
      "неучтённый фоновый опрос: такой запрос уходит из свёрнутой вкладки круглосуточно. " +
        "Если он там нужен — впишите файл в РАЗРЕШЕНО с причиной.",
    ).toEqual([]);
  });
});
