import { beforeEach, describe, expect, it } from "vitest";
import {
  забытьСвои,
  поПлану,
  пересобратьПорядок,
  свои,
} from "@/features/chats/components/list/listOrder";
import type { ConversationDto } from "@/shared/api/types";

/**
 * ⚠ ПОВТОРНАЯ ЖАЛОБА ВЛАДЕЛЬЦА 02.09: «снова беру пачку диалогов, они сначала
 * появляются в самом низу списка, потом через пару секунд переезжают наверх».
 *
 * Первая правка того же дня сбрасывала план порядка в момент взятия. Этого мало:
 * строка приезжает с сервера ПОЗЖЕ, а заморозка к тому времени взводится заново
 * и уже без неё — для нового плана она снова незнакомая и снова падает в хвост.
 *
 * Здесь стережём вторую половину правила: строка, которую человек взял сам,
 * встаёт на своё место в любой момент приезда, а чужая новая — по-прежнему в
 * конец, ради чего заморозка и заведена.
 */
const строка = (id: string): ConversationDto => ({ id }) as ConversationDto;

beforeEach(() => {
  забытьСвои(["взятая", "вторая", "чужая", "стар1", "стар2"]);
});

describe("взятый диалог встаёт на своё место, а не в хвост", () => {
  it("приехал позже — всё равно наверху, потому что помечен своим", () => {
    пересобратьПорядок("взятая");
    // Заморозка успела взвестись заново: в плане взятой строки нет.
    const порядок = поПлану(
      [строка("взятая"), строка("стар1"), строка("стар2")],
      ["стар1", "стар2"],
      свои(),
    );
    expect(порядок.map((r) => r.id)).toEqual(["взятая", "стар1", "стар2"]);
  });

  it("пачка диалогов: каждый на своём месте, в порядке сервера", () => {
    пересобратьПорядок("взятая");
    пересобратьПорядок("вторая");
    const порядок = поПлану(
      [строка("взятая"), строка("стар1"), строка("вторая"), строка("стар2")],
      ["стар1", "стар2"],
      свои(),
    );
    expect(порядок.map((r) => r.id)).toEqual(["взятая", "стар1", "вторая", "стар2"]);
  });

  it("чужая новая строка по-прежнему уходит в конец", () => {
    const порядок = поПлану(
      [строка("чужая"), строка("стар1"), строка("стар2")],
      ["стар1", "стар2"],
      свои(),
    );
    expect(порядок.map((r) => r.id)).toEqual(["стар1", "стар2", "чужая"]);
  });

  it("попала в план — перестала быть своей свежей", () => {
    пересобратьПорядок("взятая");
    забытьСвои(["взятая", "стар1"]);
    const порядок = поПлану(
      [строка("взятая"), строка("стар1")],
      ["стар1"],
      свои(),
    );
    expect(порядок.map((r) => r.id)).toEqual(["стар1", "взятая"]);
  });

  it("своя строка ниже всех знакомых — встаёт в конец, а не в середину", () => {
    пересобратьПорядок("взятая");
    const порядок = поПлану(
      [строка("стар1"), строка("стар2"), строка("взятая")],
      ["стар1", "стар2"],
      свои(),
    );
    expect(порядок.map((r) => r.id)).toEqual(["стар1", "стар2", "взятая"]);
  });
});

describe("места взятия называют диалог поимённо", () => {
  it.each([
    "src/features/chats/inbox/claimFromQueue.ts",
    "src/features/chats/inbox/useInbox.ts",
  ])("%s", async (файл) => {
    // @ts-expect-error — типов Node в проекте нет (tsconfig types: ["vite/client"]).
    const { readFileSync } = await import("node:fs");
    const текст = readFileSync(файл, "utf-8") as string;
    expect(текст).toContain("пересобратьПорядок(convId)");
    // Безымянный вызов здесь означал бы возврат жалобы: план сбросится, а
    // строка приедет позже и снова окажется чужой.
    expect(текст).not.toContain("пересобратьПорядок();");
  });

  it("ChatListPane отдаёт свои строки в перестановку и чистит их по плану", async () => {
    // @ts-expect-error — типов Node в проекте нет (tsconfig types: ["vite/client"]).
    const { readFileSync } = await import("node:fs");
    const текст = readFileSync(
      "src/features/chats/components/list/ChatListPane.tsx",
      "utf-8",
    ) as string;
    expect(текст).toContain("свои()");
    expect(текст).toContain("забытьСвои(порядокПодКурсором.current)");
  });
});
