// @ts-expect-error — типов Node в проекте нет (tsconfig types: ["vite/client"]);
// ровно так же поступают соседние сторожа buttonNoShrink и AccountsNarrow0509.
import { readFileSync } from "node:fs";
import { describe, expect, it } from "vitest";

import { NARROW_MAX } from "@/shared/lib/breakpoints";

const ЛЕНТА = "src/features/chats/components/thread/chat-thread.css";
const ПОДВАЛ = "src/features/chats/components/composer/composer.css";
const СПИСОК = "src/features/chats/components/list/chat-list.css";
const КАРТОЧКА = "src/features/chats/components/card/client-card.css";
const БАЗА = "src/app/lc-base.css";

const файл = (путь: string): string => readFileSync(путь, "utf-8") as string;

/** Текст файла без комментариев: в них разобраны сами дефекты, и наивный
 *  поиск краснел бы на объяснении вместо правила. */
const безКомментариев = (путь: string): string =>
  файл(путь).replace(/\/\*[\s\S]*?\*\//g, " ");

/**
 * Тело @-блока целиком, со вложенными правилами. Скобки считаются, а не
 * ищутся первой закрывающей: внутри медиазапроса лежат обычные правила.
 */
function блок(путь: string, заголовок: RegExp): string {
  const css = безКомментариев(путь);
  const m = заголовок.exec(css);
  expect(m, `${путь}: не найден блок ${заголовок}`).not.toBeNull();
  let i = css.indexOf("{", m!.index);
  let глубина = 0;
  const начало = i;
  for (; i < css.length; i++) {
    if (css[i] === "{") глубина++;
    else if (css[i] === "}") {
      глубина--;
      if (глубина === 0) return css.slice(начало + 1, i);
    }
  }
  throw new Error(`${путь}: блок ${заголовок} не закрыт`);
}

/** Тело правила ВНЕ каких-либо @-блоков: они действуют не на всех ширинах. */
function базовое(путь: string, селектор: string): string {
  const css = безКомментариев(путь);
  let вне = "";
  let i = 0;
  while (i < css.length) {
    if (css[i] === "@") {
      let глубина = 0;
      let открыт = false;
      for (; i < css.length; i++) {
        if (css[i] === "{") {
          глубина++;
          открыт = true;
        } else if (css[i] === "}") {
          глубина--;
          if (открыт && глубина === 0) {
            i++;
            break;
          }
        }
      }
      continue;
    }
    вне += css[i];
    i++;
  }
  const at = вне.indexOf(`\n${селектор} {`);
  expect(at, `${путь}: базовое правило ${селектор} не найдено`).toBeGreaterThan(-1);
  return вне.slice(at, вне.indexOf("}", at));
}

/** Число ступени шкалы кегля по имени токена. */
function ступень(имя: string): number {
  const vars = файл("src/app/lc-vars.css");
  const m = new RegExp(`${имя}:\\s*(\\d+)px`).exec(vars);
  expect(m, `в шкале нет ступени ${имя}`).not.toBeNull();
  return Number(m![1]);
}

describe("Чаты: узкий экран не съедает смысл", () => {
  it("метка канала переносится ниже порога, за которым города больше нигде нет", () => {
    /*
     * Порог берётся из общего источника, а не переписывается числом: CSS не
     * умеет читать TypeScript, и разъехавшиеся копии уже давали состояние,
     * которого не бывает (см. shared/lib/breakpoints.ts).
     */
    const тело = блок(
      ЛЕНТА,
      new RegExp(`@media \\(max-width:\\s*${NARROW_MAX}px\\)`, "g"),
    );
    expect(
      /\.thread-header__lead\s*\{[^}]*white-space:\s*normal/s.test(тело),
      "ниже порога метка снова обрезается — вместе с городом, которого на этих ширинах больше негде взять",
    ).toBe(true);
  });

  it("выше порога метка по-прежнему одна строка с многоточием", () => {
    /*
     * Отрицательная проверка обязана падать по своей причине. Сними здесь
     * `nowrap` — и правило выше перестанет что-либо значить: переносить будет
     * нечего, метка станет многострочной на всех ширинах разом, а шапка
     * поедет вверх на каждом длинном названии.
     */
    const база = базовое(ЛЕНТА, ".thread-header__lead");
    expect(база, "базовая метка больше не однострочная").toMatch(/white-space:\s*nowrap/);
    expect(база, "у метки пропало многоточие — обрезка станет немой").toMatch(
      /text-overflow:\s*ellipsis/,
    );
  });

  it("кнопка «Забрать себе» на плашке бота не сжимается", () => {
    // Шестое место дефекта, разобранного у `.card-merge__row .lc-btn`.
    expect(
      базовое(ЛЕНТА, ".thread-bot-banner__take"),
      "подпись кнопки снова рубится посреди буквы",
    ).toMatch(/flex:\s*none/);
  });
});

describe("Чаты: до кнопки достаёт палец, а не только мышь", () => {
  it("«Ответить» видно там, где наведения не бывает", () => {
    const тело = блок(ЛЕНТА, /@media \(hover: none\)/g);
    expect(
      /\.msg__reply-btn\s*\{[^}]*opacity:\s*1/s.test(тело),
      "на тач-экране «Ответить» снова невидимо, то есть его нет",
    ).toBe(true);
  });

  it("в покое кнопка всё-таки спрятана — иначе прятать нечего", () => {
    // Та же отрицательная проверка: без `opacity: 0` в базе правило выше
    // зеленело бы на пустом месте.
    expect(базовое(ЛЕНТА, ".msg__reply-btn")).toMatch(/opacity:\s*0/);
  });

  it("«Ответить», «Повторить» и «История статусов» дорастают до 24px под пальцем", () => {
    const тело = блок(ЛЕНТА, /@media \(pointer: coarse\)/g);
    for (const селектор of [".msg__reply-btn", ".msg__retry", ".thread-events__toggle"]) {
      expect(тело, `${селектор}: цель снова мельче 24px`).toContain(селектор);
    }
    expect((тело.match(/min-height:\s*24px/g) ?? []).length).toBeGreaterThanOrEqual(2);
  });

  it("крестик «убрать из диалога» дорастает до 24×24 под пальцем", () => {
    /*
     * Видимость ему уже вернули (`@media (hover: none)`), а размер — нет:
     * замер 12×20. Промах по нему открывает не то, а само действие убирает
     * человека из диалога и отменяется разговором, а не нажатием.
     */
    const тело = блок(КАРТОЧКА, /@media \(pointer: coarse\)/g);
    expect(/\.card-participant__remove\s*\{[^}]*min-height:\s*24px/s.test(тело)).toBe(true);
    expect(/\.card-participant__remove\s*\{[^}]*min-width:\s*24px/s.test(тело)).toBe(true);
  });

  it("переключатель «Клиенту / Заметка» дорастает до 24px под пальцем", () => {
    // Из всех мелких целей эта дороже прочих: она решает, уйдёт набранное
    // клиенту или останется внутренней заметкой.
    const тело = блок(ПОДВАЛ, /@media \(pointer: coarse\)/g);
    expect(
      /\.composer__mode\s*\{[^}]*min-height:\s*24px/s.test(тело),
      "цель переключателя режима снова 22px",
    ).toBe(true);
  });
});

describe("Чаты: подвал стоит под сообщениями, а не под всей панелью", () => {
  it("потолок колонки чтения объявлен один раз и на самой панели", () => {
    expect(базовое(ЛЕНТА, ".chat-thread-pane"), "мера колонки чтения пропала").toMatch(
      /--thread-col:\s*\d+px/,
    );
  });

  it("сообщения берут ширину из этой меры, а не из своего числа", () => {
    const тело = базовое(ЛЕНТА, ".thread-virtual");
    expect(тело).toMatch(/max-width:\s*var\(--thread-col\)/);
    expect(тело, "вернулся собственный литерал — мера снова в двух местах").not.toMatch(
      /max-width:\s*\d+px/,
    );
  });

  it("поле ввода и ряд под ним держат ту же меру", () => {
    const тело = базовое(ПОДВАЛ, ".composer__field,\n.composer__footer");
    expect(тело, "подвал снова растягивается на всю панель").toMatch(
      /max-width:\s*var\(--thread-col\)/,
    );
    expect(тело, "без ширины 100% правило центрирования ничего не центрирует").toMatch(
      /width:\s*100%/,
    );
    expect(тело).toMatch(/margin-inline:\s*auto/);
  });
});

describe("Чаты: показатель крупнее подписи", () => {
  it("пустой экран ленты говорит в полный голос, а не общим кеглем", () => {
    const css = безКомментариев(ЛЕНТА);
    expect(
      /\.chat-thread-pane--empty \.lc-empty__title\s*\{[^}]*font-size:\s*var\(--lc-fz-section\)/s.test(
        css,
      ),
      "фраза пустого экрана вернулась к общему кеглю",
    ).toBe(true);
  });

  it("общий пустой экран при этом остался прежним — правка адресная", () => {
    /*
     * Отрицательная проверка: подними кегль в общем классе — и «крупнее»
     * перестанет что-либо значить, зато подрастут ещё семь мест, где
     * пустота мелкая по делу («Заметок нет» внутри карточки).
     */
    expect(
      базовое(БАЗА, ".lc-empty__title"),
      "общий заголовок пустого состояния изменили — тогда адресное правило лишнее",
    ).toMatch(/font-size:\s*var\(--lc-fz-card\)/);
  });

  it("число долга крупнее подписи вкладки, рядом с которой стоит", () => {
    const число = базовое(СПИСОК, ".chat-debt__num");
    const вкладка = базовое(СПИСОК, ".chat-tabs__tab");
    const m = /font-size:\s*var\((--lc-fz-[a-z]+)\)/.exec(число);
    const v = /font-size:\s*var\((--lc-fz-[a-z]+)\)/.exec(вкладка);
    expect(m, "у числа долга пропал кегль").not.toBeNull();
    expect(v, "у вкладки пропал кегль").not.toBeNull();
    expect(
      ступень(m![1]),
      "показатель снова набран вровень с подписью — панель, где всё важное, не показывает ничего",
    ).toBeGreaterThan(ступень(v![1]));
  });

  it("телефон клиента крупнее подписи о том, откуда он взялся", () => {
    const значение = базовое(КАРТОЧКА, ".card-phone__value");
    const подпись = базовое(КАРТОЧКА, ".card-phone__source");
    const m = /font-size:\s*var\((--lc-fz-[a-z]+)\)/.exec(значение);
    const v = /font-size:\s*var\((--lc-fz-[a-z]+)\)/.exec(подпись);
    expect(m, "у телефона пропал кегль").not.toBeNull();
    expect(v, "у подписи источника пропал кегль").not.toBeNull();
    expect(
      ступень(m![1]),
      "номер снова одного кегля с подписью — колонку приходится читать вместо взгляда",
    ).toBeGreaterThan(ступень(v![1]));
  });
});
