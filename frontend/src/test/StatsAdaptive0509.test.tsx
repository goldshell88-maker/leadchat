/* ───────────────────── 5. иерархия и подача ────────────────────────────── */

describe("Иерархия читается с полуметра", () => {
  /** Кегль правила, разрешённый до числа по шкале в lc-vars. */
  const кегльПравила = (селектор: string) => {
    const m = /font-size:\s*var\((--lc-fz-[a-z]+)\)/.exec(правило(stats, селектор));
    expect(m, `${селектор}: кегль задан не токеном`).not.toBeNull();
    return кегль(m![1]);
  };

  it("заголовок группы крупнее заголовка панели, а тот — крупнее подписи карточки", () => {
    // Было наоборот в первой паре: «За период» 14 приглушённым, «График» 13, а
    // числа между ними 24. Ступень, которая тише своего содержимого, иерархию
    // не строит.
    const группа = кегльПравила("\\.stats-group__title");
    const панель = кегльПравила("\\.stats-panel__title");
    expect(группа, "заголовок группы не крупнее заголовка панели").toBeGreaterThan(панель);
    expect(панель, "заголовок панели не крупнее подписи").toBeGreaterThan(кегль("--lc-fz-caption"));
  });

  it("заголовок группы переносится целиком, а не ломается посреди словосочетания", () => {
    // При 375 в строку 255 пикселей «За период» с пояснением не влезало, и
    // флексбокс дожимал первый элемент: на экране стояло «За / период».
    expect(правило(stats, "\\.stats-group__title")).toMatch(/flex-wrap:\s*wrap/);
  });

  it("в подвале смены число крупнее слов вокруг", () => {
    // Строка «Сегодня: 12 взято · 8 закрыто» вся шла 12-м кеглем: показатель,
    // ради которого подвал и существует, стоял вровень со служебными словами.
    const число = /font-size:\s*var\((--lc-fz-[a-z]+)\)/.exec(правило(stats, "\\.my-today__num"))![1];
    const строка = /font-size:\s*var\((--lc-fz-[a-z]+)\)/.exec(правило(stats, "\\.my-today__line"))![1];
    expect(кегль(число), "число снова вровень со словами").toBeGreaterThan(кегль(строка));

    // И в разбивке поповера: значение крупнее своей подписи.
    expect(кегль(/font-size:\s*var\((--lc-fz-[a-z]+)\)/.exec(правило(stats, "\\.my-today__row dd"))![1]))
      .toBeGreaterThan(
        кегль(/font-size:\s*var\((--lc-fz-[a-z]+)\)/.exec(правило(stats, "\\.my-today__row dt"))![1]),
      );
  });

  it("проявление групп объяснимое и выключается по просьбе системы", () => {
    // Движение здесь объясняет подмену заготовки настоящими числами и длится
    // один такт токена. Без выключателя оно становится помехой тому, кому от
    // движения плохо.
    expect(правило(stats, "\\.stats-group"), "проявления нет").toMatch(
      /animation:\s*stats-appear\s+var\(--lc-dur-[a-z]+\)/,
    );
    expect(
      правилоВ(медиа(stats, "(prefers-reduced-motion: reduce)"), "\\.stats-group"),
      "движение не выключается",
    ).toMatch(/animation:\s*none/);
  });
});

