const безКомментариев = (css: string) => css.replace(/\/\*[\s\S]*?\*\//g, " ");

/**
 * ВСЕ блоки `@media (...)` с этим условием, склеенные подряд.
 *
 * ⚠ ИМЕННО ВСЕ, А НЕ ПЕРВЫЙ. Условие `(max-width: 900px)` встречается в
 * `stats.css` четырежды — карточки, полоса, таблица, заготовка, — и они стоят
 * рядом со своими правилами, а не свалены в один блок. Первая версия сторожа
 * брала первый блок и не находила в нём правил из остальных трёх: тест
 * КРАСНЕЛ на верном коде, а это хуже, чем не проверять вовсе.
 *
 * Скобки считаются, а не ищется первая закрывающая: внутри лежат вложенные
 * правила, и `indexOf("}")` вернул бы конец первого из них.
 */
function медиа(css: string, условие: string): string {
  const чистый = безКомментариев(css);
  const куски: string[] = [];
  const маркер = `@media ${условие} {`;
  for (let at = чистый.indexOf(маркер); at > -1; at = чистый.indexOf(маркер, at + 1)) {
    let depth = 0;
    for (let i = чистый.indexOf("{", at); i < чистый.length; i += 1) {
      if (чистый[i] === "{") depth += 1;
      else if (чистый[i] === "}") {
        depth -= 1;
        if (depth === 0) {
          куски.push(чистый.slice(at, i));
          break;
        }
      }
    }
  }
  expect(куски.length, `блок @media ${условие} не найден`).toBeGreaterThan(0);
  return куски.join("\n");
}

/**
 * Тело одного правила.
 *
 * Селектор приходит уже как кусок регулярного выражения (точка экранирована
 * вызывающим): ищутся и составные селекторы вроде `.stats-filters > *`, где
 * своё экранирование внутри помощника только мешало бы.
 *
 * `вложенное = false` требует правило БЕЗ отступа, то есть базовое. Без этого
 * `.managers__name` находился внутри медиазапроса, и сторож сравнивал правку
 * саму с собой.
 */
function правило(css: string, селектор: string, вложенное = false): string {
  const чистый = безКомментариев(css);
  const отступ = вложенное ? "[ \\t]*" : "";
  const m = new RegExp(`(?:^|[\\n{])${отступ}${селектор}\\s*\\{`).exec(чистый);
  expect(m, `правило ${селектор} не найдено`).not.toBeNull();
  const at = m!.index + m![0].length;
  return чистый.slice(at, чистый.indexOf("}", at));
}

/** То же правило, но внутри медиазапроса — там оно с отступом. */
const правилоВ = (блок: string, селектор: string) => правило(блок, селектор, true);

/** Число из объявления токена в `:root` — шкала кеглей объявлена там. */
function кегль(токен: string): number {
  const m = new RegExp(`${токен}:\\s*(\\d+)px`).exec(безКомментариев(vars));
  expect(m, `${токен} не объявлен пикселями`).not.toBeNull();
  return Number(m![1]);
}

