/**
 * «СЛЕДУЮЩИЙ ПОСЛЕ ЗАКРЫТИЯ» БЕРЁТСЯ ИЗ ВИДИМОГО СПИСКА.
 *
 * ЧТО БЫЛО. `nextConversationId` перебирал ВСЕ закэшированные варианты
 * фильтров и брал первый кэш, где нашёлся закрытый диалог. Довод в
 * комментарии — «диалог физически находится ровно в одном списке» — неверен:
 * один и тот же диалог лежит и в «Моих», и во «Всех», и в любой прошлой
 * выдаче поиска, а кэши живут по получасу. Побеждал чаще всего САМЫЙ СТАРЫЙ.
 *
 * Как это выглядело у владельца: заходит на «Все» (вкладка по умолчанию для
 * его роли), переключается на «Мои», закрывает свой диалог — и автопереход
 * уносит его к соседу по «Всем», то есть в чужую переписку или в архивный
 * диалог Авито. Слева при этом не подсвечена ни одна строка: в «Моих» её нет.
 *
 * ЧТО СТАЛО. Сосед считается по ключу той выдачи, что сейчас на экране, —
 * ровно так же, как его считают стрелки и J/K (`useChatHotkeys.cachedRows`).
 * Двух ответов на вопрос «кто следующий» на одном экране быть не должно.
 */
import { beforeEach, describe, expect, it } from "vitest";
import { queryClient } from "@/app/queryClient";
import { nextConversationId } from "@/features/chats/api";
import { qk, type ConversationFilters } from "@/shared/api/queryKeys";

const ВСЕ: ConversationFilters = { tab: "all" };
const МОИ: ConversationFilters = { tab: "mine" };

function положить(filters: ConversationFilters, ids: string[]) {
  queryClient.setQueryData(qk.conversations.list(filters), {
    pages: [{ items: ids.map((id) => ({ id })), page: { limit: ids.length, offset: 0, total: ids.length } }],
    pageParams: [0],
  });
}

describe("следующий диалог после закрытия", () => {
  beforeEach(() => queryClient.clear());

  it("сосед снизу — из того списка, что на экране", () => {
    положить(МОИ, ["m-1", "m-2", "m-3"]);
    expect(nextConversationId("m-2", МОИ)).toBe("m-3");
  });

  it("закрыли последний — идём к соседу сверху", () => {
    положить(МОИ, ["m-1", "m-2"]);
    expect(nextConversationId("m-2", МОИ)).toBe("m-1");
  });

  it("в списке он один — идти некуда", () => {
    положить(МОИ, ["m-1"]);
    expect(nextConversationId("m-1", МОИ)).toBeNull();
  });

  /*
   * ГЛАВНАЯ ПРОВЕРКА. Старый кэш «Всех» лежит рядом и содержит тот же диалог с
   * ДРУГИМИ соседями. Прежний перебор уводил именно туда.
   */
  it("старый кэш другой вкладки не перебивает видимый список", () => {
    положить(ВСЕ, ["чужой-1", "m-2", "чужой-2"]);
    положить(МОИ, ["m-1", "m-2", "m-3"]);
    expect(nextConversationId("m-2", МОИ)).toBe("m-3");
    // И наоборот: смотрим «Все» — получаем соседа по «Всем».
    expect(nextConversationId("m-2", ВСЕ)).toBe("чужой-2");
  });

  it("диалога нет в видимом списке — никуда не уводим", () => {
    положить(ВСЕ, ["чужой-1", "из-разбора", "чужой-2"]);
    положить(МОИ, ["m-1", "m-2"]);
    // Открыт из «Разбора диалогов»: в левой колонке его нет вовсе.
    expect(nextConversationId("из-разбора", МОИ)).toBeNull();
  });
});
