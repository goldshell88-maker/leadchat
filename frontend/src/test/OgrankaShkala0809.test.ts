/**
 * ОГРАНКА: КАЖДОЕ ЧИСЛО ОТСТУПА — С ИМЕНЕМ (08.09).
 *
 * ЗАЧЕМ. Замер по всем 60 экранам стенда 08.09 дал 13 различных полей и 10
 * зазоров, из них 3, 5, 6 и 10 пикселей — мимо шкалы токенов
 * (2/4/8/12/16/24/32/40/48/64). Глазом это не читается как решение: у соседних
 * плашек на одном экране отступы отличались на два пикселя, и разница выглядела
 * неаккуратностью, а не смыслом. После правки зазоров осталось 7 значений и все
 * на шкале.
 *
 * ⚠ СТОРОЖ ПРО ЛИТЕРАЛЫ, А НЕ ПРО ПИКСЕЛИ. Мерить пиксели здесь нечем — в jsdom
 * раскладки нет вовсе; их меряет `npm run layout` в настоящем браузере, но он
 * ловит переполнение, а «6 вместо 8» переполнением не является и не станет.
 * Держим ИСТОЧНИК: отступ, написанный числом, а не токеном.
 *
 * ⚠ ИСКЛЮЧЕНИЯ ПОИМЕННЫЕ И С ДОВОДОМ — иначе список станет свалкой.
 */
// @ts-expect-error — типов Node в проекте нет (tsconfig types: ["vite/client"]);
// тот же приём, что в surfaceLadder и OgrankaKolonki.
import { readdirSync, readFileSync, statSync } from "node:fs";
import { describe, expect, it } from "vitest";

/** Значения шкалы `--lc-space-*` из lc-vars.css. */
const ШКАЛА = new Set([0, 1, 2, 4, 8, 12, 16, 24, 32, 40, 48, 64]);

/**
 * Где число в отступе оставлено намеренно.
 *
 * ⚠ КАЖДАЯ СТРОКА — С ДОВОДОМ. Запись без довода означает «мне лень», и через
 * полгода никто не отличит её от настоящего решения.
 */
const НАМЕРЕННО: Array<{ файл: string; довод: string }> = [
  {
    файл: "src/app/lc-base.css",
    довод:
      "переменные полей ввода Mantine (--input-padding-y-*): ими выставляется " +
      "ВЫСОТА поля, а не ритм страницы, и шкала отступов к ним не относится",
  },
  {
    файл: "src/features/settings/accounts/week-bars.css",
    довод:
      "зазор 3px несущий: минимум колонки недели 60px считается из рисунка — " +
      "семь столбиков по 6 плюс шесть зазоров по 3 (сторож AccountsRowTail0809)",
  },
  {
    файл: "src/features/chats/components/list/chat-list.css",
    довод:
      "`--lc-row-gap: 6px` — поимённый зазор строки списка, сверяется на " +
      "парность с ROW_HEIGHT (огранка чатов, KartochkaOgranka0809)",
  },
];

function файлыCSS(корень: string): string[] {
  const из: string[] = [];
  for (const имя of readdirSync(корень)) {
    const путь = `${корень}/${имя}`;
    if (statSync(путь).isDirectory()) из.push(...файлыCSS(путь));
    else if (имя.endsWith(".css")) из.push(путь);
  }
  return из;
}

describe("Огранка: отступы берутся из шкалы, а не пишутся числом", () => {
  it("во всём CSS нет полей и зазоров мимо шкалы", () => {
    const прощено = new Set(НАМЕРЕННО.map((з) => з.файл));
    const плохие: string[] = [];

    for (const путь of файлыCSS("src")) {
      if (прощено.has(путь)) continue;
      const css = (readFileSync(путь, "utf-8") as string).replace(/\/\*[\s\S]*?\*\//g, " ");
      for (const [, свойство, значения] of css.matchAll(
        /(padding|padding-inline|padding-block|gap|row-gap|column-gap)\s*:\s*([^;{}]+);/g,
      )) {
        /* `calc(...)` пропускаем: там число объяснено выражением — например
           `calc(28px + var(--lc-space-2))` выравнивает подпись под значком. */
        if (значения.includes("calc(")) continue;
        for (const [, число] of значения.matchAll(/(?<![\w-])(\d+)px/g)) {
          if (!ШКАЛА.has(Number(число))) {
            плохие.push(`${путь}: ${свойство}: ${значения.trim()} — ${число}px вне шкалы`);
          }
        }
      }
    }

    expect(
      [...new Set(плохие)],
      "отступ написан числом мимо шкалы токенов: на экране это выглядит как " +
        "неаккуратность, а не как решение",
    ).toEqual([]);
  });

  it("каждое исключение объяснено и указывает на существующий файл", () => {
    /* Обратная сторона: список исключений не должен пережить свои файлы. */
    for (const з of НАМЕРЕННО) {
      expect(() => statSync(з.файл), `${з.файл} из списка исключений не существует`).not.toThrow();
      expect(з.довод.length, `${з.файл}: исключение без довода`).toBeGreaterThan(40);
    }
  });
});
