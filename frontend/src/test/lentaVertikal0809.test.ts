import { describe, expect, it } from "vitest";

/**
 * СТОРОЖ ЛЕНТЫ: поле ввода на экране, шапка не поверх соседей, кнопки внутри
 * своих полос (замер стенда 08.09).
 *
 * ⚠ ЧЕСТНО О ТОМ, ЧЕГО ЭТОТ СТОРОЖ НЕ ВИДИТ. Раскладку он не считает — в jsdom
 * её нет вовсе: ширины нулевые, переносов и `overflow` не существует. Поэтому
 * здесь проверяются ПРИЧИНЫ по тексту стилей, а не следствия на экране. Сами
 * следствия померены руками в браузере, на боевом собранном CSS и настоящей
 * разметке (`.dump/stand-lenta-*.html`, снималка `chaty-krome-sloi.dump.tsx`),
 * с рельсой приложения 218px — той, что стоит в бою (railStore `expanded:
 * true`), а не запасной 72 из lc-vars.css.
 *
 * ЧИСЛА ЗАМЕРА, ДО → ПОСЛЕ (окно 768×700, рельса 218, ленте достаётся 174px):
 *   • низ композера относительно окна:      +37 → −13 (при 768×627: +110 → −13)
 *   • содержимое шапки за её блоком:        147 → 0   (при 900×627: 21 → 0)
 *   • блок кнопок правее полосы передачи: +126,6 → −17 (при 880×700: +14,6 → −17)
 *   • переключатель режимов правее подвала: +53,5 → −4 (при 800×700: +21,5 → −4)
 *   • высота ленты:                          32 → 108 (в ноль не сжимается)
 * На 1024 и шире раскладка не изменилась: прокрутки у панели нет, лента 151,5
 * до и после, кнопка передачи 34×144,3 до и после.
 */
declare function require(id: string): { readFileSync(p: string, enc: string): string };

const ФАЙЛЫ = {
  лента: "src/features/chats/components/thread/chat-thread.css",
  полоса: "src/features/chats/components/thread/transfer-bar.css",
  композер: "src/features/chats/components/composer/composer.css",
} as const;

/**
 * Тело правила ВНЕ медиазапросов: они действуют не на всех ширинах, а беды
 * ловились на всех. Разбор тот же, что у сторожа threadHeaderLayout.
 */
function правило(файл: string, селектор: string): string {
  const css: string = require("node:fs").readFileSync(файл, "utf-8");
  let i = 0;
  let out = "";
  while (i < css.length) {
    if (css.startsWith("@media", i) || css.startsWith("@supports", i)) {
      let скобки = 0;
      let начали = false;
      while (i < css.length) {
        if (css[i] === "{") {
          скобки++;
          начали = true;
        } else if (css[i] === "}") {
          скобки--;
          if (начали && скобки === 0) {
            i++;
            break;
          }
        }
        i++;
      }
      continue;
    }
    out += css[i];
    i++;
  }
  // Комментарии вырезаем: в них лежат прежние значения свойств, и проверка
  // «правило есть» зеленела бы от одного упоминания в разборе.
  out = out.replace(/\/\*[\s\S]*?\*\//g, " ");
  const at = out.indexOf(`\n${селектор} {`);
  expect(at, `${файл}: правило ${селектор} не найдено`).toBeGreaterThan(-1);
  return out.slice(at, out.indexOf("}", at));
}

describe("Панель ленты: поле ввода не уезжает под нижний край окна", () => {
  it("панель прокручивается по вертикали, а не глотает низ", () => {
    /*
     * Стояло `overflow: hidden` — обещание, что содержимое влезет всегда. При
     * 768×700 детям панели нужно 826px в 676: композер оказывался на 37px ниже
     * окна, и добраться до него было нечем — ни полосы, ни колеса.
     */
    const панель = правило(ФАЙЛЫ.лента, ".chat-thread-pane");
    expect(панель).toMatch(/overflow-y:\s*auto/);
    expect(панель).not.toMatch(/overflow:\s*hidden/);
    // По горизонтали прокрутке взяться неоткуда — там остаётся `hidden`.
    expect(панель).toMatch(/overflow-x:\s*hidden/);
  });

  it("композер прилипает к низу панели и не сжимается", () => {
    // Одной прокрутки мало: поле ввода не должно ТРЕБОВАТЬ прокрутки.
    const композер = правило(ФАЙЛЫ.композер, ".composer");
    expect(композер).toMatch(/position:\s*sticky/);
    expect(композер).toMatch(/bottom:\s*0/);
    expect(композер).toMatch(/flex:\s*none|flex-shrink:\s*0/);
  });

  it("лента не сжимается в ноль — у неё нижний предел высоты", () => {
    /*
     * Оборотная сторона правок выше: как только шапке и полосам запретили
     * ужиматься, весь дефицит лёг на ленту и замер дал ей 0px. Предел — одна
     * строка ленты (ВЫСОТА_СТРОКИ = 76 из ChatThreadPane.tsx) плюс её поля.
     */
    const лента = правило(ФАЙЛЫ.лента, ".thread-scroll");
    const предел = /min-height:\s*(\d+)px/.exec(лента);
    expect(предел, "у .thread-scroll снят нижний предел высоты").not.toBeNull();
    expect(Number(предел![1])).toBeGreaterThanOrEqual(76);
    // ...но и не больше того, что помещается на рабочем ноутбуке 1366×700:
    // там ленте достаётся 145,5px, и предел 184 заводил прокрутку на ровном
    // месте (проверено замером до записи этого числа в файл).
    expect(Number(предел![1])).toBeLessThanOrEqual(145);
  });
});

describe("Шапка ленты не рисуется поверх соседних полос", () => {
  it("шапке запрещено ужиматься ниже её содержимого", () => {
    /*
     * `min-height` задаёт пол высоты блока, но не запрещает колонке этот блок
     * сжимать: умолчание флекс-элемента — `flex-shrink: 1`. Замер 768×700:
     * содержимому нужно 210px, нарисовано 64 — 147 пикселей строк легли поверх
     * полосы «Диалог ведёт бот» и строки «В работе у вас».
     */
    expect(правило(ФАЙЛЫ.лента, ".thread-header")).toMatch(/flex-shrink:\s*0|flex:\s*none/);
  });

  it("полосы под шапкой тоже не ужимаются по высоте", () => {
    // Та же болезнь: сжатая полоса кладёт свой текст на соседей.
    expect(правило(ФАЙЛЫ.лента, ".thread-bot-banner")).toMatch(/flex:\s*none|flex-shrink:\s*0/);
    expect(правило(ФАЙЛЫ.полоса, ".transfer-bar")).toMatch(/flex:\s*none|flex-shrink:\s*0/);
  });
});

describe("Кнопки передачи диалога — внутри своей полосы", () => {
  it("блок кнопок не шире полосы и переносит кнопки", () => {
    /*
     * `flex-shrink: 0` тут верен и остаётся (Mantine рубит подпись посреди
     * буквы), но запрет сжиматься — не разрешение быть шире родителя: замер
     * 768×700 дал блок на 126,6px правее полосы, «Отказаться» не видно вовсе.
     */
    const блок = правило(ФАЙЛЫ.полоса, ".transfer-bar__actions");
    expect(блок).toMatch(/max-width:\s*100%/);
    expect(блок).toMatch(/flex-wrap:\s*wrap/);
    expect(блок).toMatch(/flex-shrink:\s*0|flex:\s*none/);
  });

  it("подпись кнопки переносится, а не обрезается, и кнопка при этом растёт", () => {
    // На строке 108px «Принять диалог» просит 110: без переноса подписи её
    // срезало бы посреди буквы, без переноса высоты — по нижнему краю кнопки.
    const кнопка = правило(ФАЙЛЫ.полоса, ".transfer-bar__actions .lc-btn");
    expect(кнопка).toMatch(/height:\s*auto/);
    expect(кнопка).toMatch(/min-height:/);
    const подпись = правило(ФАЙЛЫ.полоса, ".transfer-bar__actions .mantine-Button-label");
    expect(подпись).toMatch(/white-space:\s*normal/);
  });
});

describe("Переключатель «Сообщение / Заметка» не обрублен", () => {
  it("переключатель не шире подвала и переносит кнопки", () => {
    /*
     * Подвал переносит переключатель на свою строку, но перенос помогает,
     * только если перенесённому есть куда встать: замер 768×700 дал
     * переключателю 189,5px в подвале 140 — «Заметка» обрывалась посреди буквы.
     */
    const режимы = правило(ФАЙЛЫ.композер, ".composer__modes");
    expect(режимы).toMatch(/max-width:\s*100%/);
    expect(режимы).toMatch(/flex-wrap:\s*wrap/);
    // Без `min-width: 0` потолок не действует: автоминимум флекс-элемента
    // равен его содержимому.
    expect(режимы).toMatch(/min-width:\s*0/);
  });
});
