/**
 * Ширина страницы каналов — под обычный монитор (жалоба владельца 22.08).
 *
 * «Плохое соотношение на стандартных ПК 16:9, 1920 на 1080».
 *
 * СЧИТАЕМ ЧЕСТНО. На 1920 слева стоят полоса разделов и меню настроек — около
 * 215 пикселей. Рабочей области остаётся ~1705, а страница упиралась в 1120:
 * почти шестьсот пикселей простаивали.
 *
 * ⚠ 27.08 КОЛОНОК БОЛЬШЕ НЕТ: каналы стали списком (решение владельца
 * «аккаунты давай не плитками сделаем, а просто списком»). Считать нечего —
 * строка занимает всю ширину. Но сама жалоба никуда не делась: если потолок
 * страницы вернут к 1120, шестьсот пикселей снова будут простаивать, только
 * теперь у строк. Поэтому проверяем то, что осталось осмысленным, — потолок
 * ширины и одноколоночную раскладку.
 */
import { describe, expect, it } from "vitest";
// @ts-expect-error — типов Node в проекте нет (tsconfig types: ["vite/client"]),
// а ставить @types/node ради одного сторожа несоразмерно. Ровно так же
// поступают соседние сторожа actionBusConsumers.test.ts и mantineStyles.test.ts.
import { readFileSync } from "node:fs";

const CSS = readFileSync("src/features/settings/accounts/accounts.css", "utf8");

function число(rx: RegExp): number {
  const m = CSS.match(rx);
  expect(m, `не нашёл в accounts.css: ${rx}`).toBeTruthy();
  return Number(m![1]);
}

/** Слева всегда стоят полоса разделов и меню настроек. */
const МЕНЮ = 215;
/** Внутренние отступы страницы (--lc-space-5 с двух сторон). */
const ОТСТУПЫ = 48;

/** Сколько пикселей достаётся списку на экране такой ширины. */
function рабочая(экран: number, потолок: number): number {
  return Math.min(экран - МЕНЮ, потолок) - ОТСТУПЫ;
}

describe("страница каналов на обычном мониторе", () => {
  const потолок = число(/\.accounts-page\s*\{[^}]*max-width:\s*(\d+)px/s);

  it("на 1920×1080 страница берёт ширину, а не жмётся к 1120", () => {
    // 1490 — это те самые шестьсот пикселей, которые раньше простаивали.
    expect(рабочая(1920, потолок)).toBeGreaterThanOrEqual(1400);
  });

  it("на ноутбучных 1366 ничего не сломано: список занимает всё, что есть", () => {
    expect(рабочая(1366, потолок)).toBeGreaterThan(1000);
  });

  it("каналы выложены списком, а не сеткой плиток", () => {
    // ⚠ Сторож ровно на возврат сетки. Плитки в auto-fill ставили одноимённые
    // поля соседних каналов на разную высоту, и сравнить каналы между собой —
    // «где не проставлен источник», «у кого просрочен токен» — было нельзя.
    const правило = CSS.match(/\n\.accounts-page__grid\s*\{([^}]*)\}/s);
    expect(правило, "не нашёл правило .accounts-page__grid").toBeTruthy();
    expect(правило![1]).not.toMatch(/grid-template-columns|minmax\(/);
    expect(правило![1]).toMatch(/flex-direction:\s*column/);
  });
});
