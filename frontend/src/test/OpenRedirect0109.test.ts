import { describe, expect, it } from "vitest";
import { внутреннийАдрес, толькоВнутренний } from "@/shared/lib/внутреннийАдрес";

/**
 * ОТКРЫТЫЙ РЕДИРЕКТ: ПЕРЕХОД ТОЛЬКО ВНУТРЬ ПРИЛОЖЕНИЯ.
 *
 * ⚠ ПОВОД — АУДИТ ЗАВИСИМОСТЕЙ 01.09. В `react-router` 6.x числится открытый
 * редирект: обратный слэш в адресе, переданном в `<Link>` или `navigate()`,
 * уводит браузер на ЧУЖОЙ сайт — браузер читает `\\evil.example` как
 * `//evil.example`. Исправлено только в ветке 7.
 *
 * ⚠ ПОЧЕМУ НЕ ОБНОВИЛИСЬ. Проверено на деле: `7.18.3` ставится, аудит чист,
 * типы и линтер молчат — но два теста показали настоящую перемену поведения.
 * В седьмой ветке ленивому маршруту нужен `HydrateFallback`, иначе при ПЕРВОЙ
 * загрузке роутер не рисует НИЧЕГО. Ленивых маршрутов у нас пятнадцать, и
 * человек, открывший закладку прямо на статистику или настройки, увидел бы
 * белый экран. Это не «обновить версию», а решение о том, что показывать при
 * загрузке, — а от полноэкранных загрузчиков проект отказался осознанно.
 *
 * ⚠ НАСТОЯЩАЯ УЯЗВИМОСТЬ ИЗМЕРЕНА И РАВНА НУЛЮ. Свободный адрес в переход не
 * попадает нигде: все `navigate()` — литералы или `/chats/${uuid}`, серверные
 * ссылки строит `catalog.ts:entityLink` из закрытого списка путей. Эти
 * проверки нужны, чтобы дыра не появилась ЗАВТРА: сегодня безопасность держится
 * на том, что никто не додумался передать в переход чужую строку.
 */
describe("Переход уводит только внутрь приложения", () => {
  it.each([
    "/chats",
    "/chats/2f1c8d0e-0000-4000-8000-000000000000",
    "/settings/accounts",
    "/notifications",
  ])("свой путь пропускается: %s", (to) => {
    expect(внутреннийАдрес(to)).toBe(true);
    expect(толькоВнутренний(to)).toBe(to);
  });

  it.each([
    // ⚠ СОБСТВЕННО ТА САМАЯ БРЕШЬ: браузер читает обратный слэш как прямой.
    ["/\\evil.example", "обратный слэш — это и есть открытый редирект"],
    ["\\\\evil.example", "два обратных слэша"],
    ["//evil.example", "адрес без схемы уводит наружу"],
    ["https://evil.example", "чужой сайт со схемой"],
    ["javascript:alert(1)", "скрипт вместо адреса"],
    ["data:text/html,<script>alert(1)</script>", "страница из адреса"],
    ["chats", "относительный путь — не наш абсолютный"],
  ])("наружу не уводим: %s", (to) => {
    expect(внутреннийАдрес(to), "адрес уводит за пределы приложения").toBe(false);
    expect(толькоВнутренний(to)).toBeNull();
  });

  it("⚠ проверка подключена там, где адрес приходит С СЕРВЕРА", async () => {
    /*
     * Без этой проверки всё остальное зеленеет впустую: функцию можно написать,
     * покрыть тестами и не позвать ни разу. Этот проект на такой дыре попадался
     * много раз — последний раз сегодня, когда кадр про клиента сбрасывал не тот
     * ключ кэша.
     */
    // @ts-expect-error — типов Node в проекте нет (tsconfig types: ["vite/client"]).
    const { readFileSync } = await import("node:fs");
    for (const файл of [
      "src/features/notifications/NotificationPanel.tsx",
      "src/features/notifications/NotificationsPage.tsx",
    ]) {
      const src = readFileSync(файл, "utf-8") as string;
      expect(src, `${файл}: проверка адреса не подключена`).toContain("толькоВнутренний(");
    }
  });
});
