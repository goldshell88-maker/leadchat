import { describe, expect, it } from "vitest";
// @ts-expect-error — типов Node в проекте нет (tsconfig types: ["vite/client"]),
// так же поступают соседние сторожа, читающие исходники.
import { readFileSync } from "node:fs";

/**
 * ПОДВАЛ МОДАЛЬНОГО ОКНА ОБЯЗАН БЫТЬ ВИДЕН НА НЕВЫСОКОМ ЭКРАНЕ.
 *
 * ⚠ ЧЕСТНО О ГРАНИЦЕ ЭТОГО СТОРОЖА: jsdom раскладку не считает вовсе — у него
 * любой прямоугольник нулевой, `position: sticky` он не исполняет, а CSS-файлы
 * в тесты и не подключаются. Проверить ЗДЕСЬ, что кнопка видна, невозможно в
 * принципе. Поэтому сторож стережёт ПРИЧИНУ (правило и класс на месте), а сам
 * замер сделан в настоящем браузере на собранном CSS — стенд
 * `.dump/merka-okon.html` плюс снималка `src/test/okna-снимок.dump.tsx`.
 *
 * ЧИСЛА ЗАМЕРА (08.09, собранный CSS, оба состояния рельса — 218 и 72 — дали
 * одни и те же числа: окно рисуется в портале и ширина рельса ему не
 * достаётся):
 *
 *   окно                     размер     низ кнопки → экран      после
 *   мастер Авито             1440×760   «Подключить» 782 → 760  видна
 *   мастер Авито             1366×700   779 → 700               видна
 *   мастер, чужая подписка   1440×760   «Забрать канал» 859 → 760  видна
 *   назначить операторов     1440×760   «Сохранить» 827.6 → 760 видна
 *   назначить операторов     390×780    916.3 → 780             видна
 *   позвать в диалог         768×627    «Позвать» 678.4 → 627   видна
 *   песочница бота           1280×627   ввод ответа 637.5 → 627 виден
 *
 * Всего было 60 записей о беде на матрице 13 окон × 2 рельса × 9 размеров,
 * стало 10, и ни одной про кнопку окна.
 */

/* Путь от корня фронта — так же читают исходники соседние сторожа. */
const ФАЙЛ = (путь: string) => readFileSync(`src/${путь}`, "utf8") as string;

/** Тело правила по имени класса — без него проверка «есть слово в файле» врала бы. */
function правило(css: string, селектор: string): string {
  const i = css.indexOf(`\n${селектор} {`);
  expect(i, `${селектор}: правила нет вовсе`).toBeGreaterThan(-1);
  return css.slice(i, css.indexOf("}", i));
}

const ПОДВАЛЫ: Array<{ имя: string; css: string; селектор: string; поле: string }> = [
  {
    имя: "мастер подключения канала",
    css: "features/settings/accounts/connect-wizard.css",
    селектор: ".wizard__foot",
    // Поле окна Mantine — `var(--lc-space-5)`; подвал обязан его закрыть.
    поле: "--lc-space-5",
  },
  {
    имя: "назначить операторов",
    css: "features/settings/accounts/accounts.css",
    селектор: ".assign-ops__foot",
    поле: "--lc-space-5",
  },
  {
    имя: "передать / позвать",
    css: "features/chats/components/card/client-card.css",
    селектор: ".card-dialog__foot",
    поле: "--lc-space-5",
  },
  {
    имя: "песочница бота",
    css: "features/settings/bots/bots.css",
    селектор: ".sandbox-composer",
    // У ящика поле своё — `var(--mantine-spacing-md)`, это 16px = --lc-space-4.
    поле: "--lc-space-4",
  },
];

describe("Подвал модального окна виден на невысоком экране", () => {
  for (const п of ПОДВАЛЫ) {
    it(`${п.имя}: подвал прилипает к низу и закрывает поле окна`, () => {
      const тело = правило(ФАЙЛ(п.css), п.селектор);
      expect(тело, `${п.селектор}: не прилипает`).toMatch(/position:\s*sticky/);
      expect(тело, `${п.селектор}: не прижат к низу`).toMatch(/bottom:\s*0/);
      // Без фона содержимое едет ПОД подвалом и читается сквозь него.
      expect(тело, `${п.селектор}: нет фона`).toMatch(/background:\s*var\(--lc-surface\)/);
      // Отрицательное поле снизу плюс равное ему внутреннее: иначе под
      // прилипшим подвалом остаётся щель в поле окна.
      expect(тело, `${п.селектор}: не закрывает поле окна снизу`).toContain(
        `margin-bottom: calc(-1 * var(${п.поле}))`,
      );
      expect(тело, `${п.селектор}: нет внутреннего поля взамен отрицательного`).toContain(
        `padding-bottom: var(${п.поле})`,
      );
    });
  }

  /*
   * Класс из CSS должен стоять на ТОМ САМОМ узле. Правило без разметки —
   * мёртвая буква, и текстовая проверка одного только CSS этого не поймала бы.
   */
  const РАЗМЕТКА: Array<[string, string, string]> = [
    ["features/settings/accounts/AssignOperatorsModal.tsx", "assign-ops__foot", "Сохранить"],
    ["features/chats/components/card/TransferDialog.tsx", "card-dialog__foot", "Передать"],
    ["features/chats/components/card/InviteDialog.tsx", "card-dialog__foot", "Позвать"],
    ["features/settings/bots/SandboxDrawer.tsx", "sandbox-composer", "Ответ клиента"],
  ];

  for (const [путь, класс, подпись] of РАЗМЕТКА) {
    it(`${путь.split("/").pop()}: класс «${класс}» стоит на группе с «${подпись}»`, () => {
      const код = ФАЙЛ(путь);
      const i = код.indexOf(`className="${класс}"`);
      expect(i, `${класс}: класса в разметке нет`).toBeGreaterThan(-1);
      // Подпись действия — в тех же 900 знаках, что и класс: так видно, что
      // класс стоит на подвале, а не уехал на соседний блок.
      expect(код.slice(i, i + 900), `${класс}: рядом нет «${подпись}»`).toContain(подпись);
    });
  }

  /*
   * ⚠ ЗАПАСНОЙ МЕДИАЗАПРОС ПЕСОЧНИЦЫ ОБЯЗАН ЖИТЬ ВНУТРИ `@supports not`.
   *
   * Правила одинаковой силы, и стоящий ниже медиазапрос перебивал контейнерный
   * — тот самый, ради которого приём и заводился. Замер до правки: окно 850 и
   * 899 → ящик 780, контейнер 748 (то есть «широко»), а раскладка выходила
   * `column`, панель состояния 748px вместо 240. После: `row`, панель 240,
   * лента 496 — как на окне 901.
   */
  it("песочница: медиазапрос остаётся запасным, а не перебивает контейнерный", () => {
    const css = ФАЙЛ("features/settings/bots/bots.css");
    const i = css.indexOf("@supports not (container-type: inline-size)");
    expect(i, "нет @supports вокруг запасного запроса").toBeGreaterThan(-1);
    const блок = css.slice(i, i + 400);
    expect(блок, "медиазапрос песочницы не внутри @supports").toContain("@media (max-width: 900px)");
    expect(блок, "внутри @supports не та раскладка").toContain("flex-direction: column");
    /*
     * Второго правила про `.sandbox-body` снаружи `@supports` быть не должно:
     * оно перебило бы контейнерный запрос ровно так же, как перебивало
     * прежнее. В файле есть и другие медиазапросы на 900 (карточка бота,
     * шапка шага) — они про другие блоки и здесь ни при чём, поэтому считаем
     * не медиазапросы, а правила про саму песочницу.
     */
    const песочница = [...css.matchAll(/\.sandbox-body \{/g)];
    // Три правила: обычная раскладка, контейнерный запрос и запасной внутри
    // @supports. Четвёртое означало бы, что кто-то завёл ещё один порог.
    expect(песочница.length, "правил про .sandbox-body стало больше трёх").toBe(3);
    expect(css.slice(0, i), "правило про .sandbox-body осталось и снаружи @supports").not.toMatch(
      /@media[^{]*\{[^}]*\.sandbox-body/,
    );
  });
});
