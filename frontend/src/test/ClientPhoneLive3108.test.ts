import { beforeEach, describe, expect, it } from "vitest";
// @ts-expect-error — типов Node в проекте нет (tsconfig types: ["vite/client"]).
import { readFileSync } from "node:fs";
import { queryClient } from "@/app/queryClient";
import { applyWsEvent } from "@/shared/realtime/applyWsEvent";

/**
 * НОМЕР КЛИЕНТА ПРИВЯЗЫВАЕТСЯ БЕЗ ПЕРЕЗАГРУЗКИ.
 *
 * ⚠ ЖАЛОБА ВЛАДЕЛЬЦА 31.08: «когда клиент скинул номер, то чтобы он
 * привязался, приходится обновлять страницу».
 *
 * ЧТО БЫЛО. Сервер извлекает телефон из текста входящего и записывает его
 * клиенту — и не сообщает наружу НИЧЕГО. Кадр `message:new` несёт заплатку
 * диалога, полей клиента в ней нет. Карточка живёт на своём ключе, который не
 * сверяет ни один кадр, ни тихая сверка (она трогает диалоги, сообщения и
 * очередь), ни возврат на вкладку — перезапрос по фокусу выключен глобально.
 * Данные считаются свежими минуту, а открытая карточка не пересоздаётся
 * вовсе, так что и перезапрос при монтировании не наступает никогда.
 *
 * ЧТО СТАЛО. Сервер шлёт кадр `client:updated`, фронт по нему сбрасывает всё,
 * что знает о клиентах. Самого номера в кадре НЕТ намеренно: это персональные
 * данные, у карточки своя ручка с правами, и рассылать их всем подписчикам
 * ради экономии одного запроса нельзя.
 */

const CLIENT = "cccc3333-0000-0000-0000-000000000003";
const CONV = "dddd4444-0000-0000-0000-000000000004";
const КЛЮЧ = ["clients", "identity", CLIENT] as const;

describe("Кадр «карточка клиента изменилась»", () => {
  beforeEach(() => {
    queryClient.clear();
  });

  it("сбрасывает кэш карточки", () => {
    queryClient.setQueryData(КЛЮЧ, { id: CLIENT, phone: null });
    applyWsEvent({
      type: "client:updated",
      ts: "2026-08-31T10:00:00Z",
      data: { client_id: CLIENT, conversation_id: CONV, reason: "phone_captured" },
    } as never);

    expect(
      queryClient.getQueryCache().find({ queryKey: КЛЮЧ })?.state.isInvalidated,
      "карточка не помечена устаревшей — номер появится только после F5",
    ).toBe(true);
  });

  it("накрывает и историю, и кандидатов на объединение", () => {
    // Телефон меняет не только личность: по нему ищутся двойники.
    queryClient.setQueryData(["clients", "merge-candidates", CLIENT], { items: [] });
    queryClient.setQueryData(["clients", "history", CONV], { items: [] });
    applyWsEvent({
      type: "client:updated",
      ts: "2026-08-31T10:00:00Z",
      data: { client_id: CLIENT, conversation_id: CONV },
    } as never);

    for (const ключ of [
      ["clients", "merge-candidates", CLIENT],
      ["clients", "history", CONV],
    ]) {
      expect(
        queryClient.getQueryCache().find({ queryKey: ключ })?.state.isInvalidated,
        `ключ ${ключ.join("/")} не сброшен`,
      ).toBe(true);
    }
  });

  it("персональных данных в кадре нет", () => {
    /*
     * ⚠ ГРАНИЦА, А НЕ ПРИДИРКА. Кадр широковещательный: его получают все, кто
     * подписан. Положи мы сюда сам номер — и телефон клиента уехал бы людям,
     * которым карточка по правам не отдалась бы.
     */
    const тип = readFileSync("src/shared/realtime/wsEvents.ts", "utf-8") as string;
    const кадр = тип.slice(тип.indexOf('type: "client:updated"'));
    const тело = кадр.slice(0, кадр.indexOf("}"));
    expect(тело, "в кадр о клиенте попали персональные данные").not.toMatch(/phone|name|email/i);
  });

  it("сервер действительно шлёт этот кадр после записи номера", () => {
    /*
     * ⚠ БЕЗ ЭТОГО ПРОВЕРКИ ВЫШЕ СТОРОЖИЛИ БЫ ОБРАБОТЧИК КАДРА, КОТОРЫЙ НИКТО
     * НЕ ШЛЁТ. Механизм, написанный и не подключённый, — самая частая поломка
     * в этом проекте.
     */
    const бэк = readFileSync(
      "../app/services/inbound.py",
      "utf-8",
    ) as string;
    expect(бэк, "сервер не сообщает о записи номера — фронту неоткуда узнать").toMatch(
      /"client:updated"/,
    );
    /*
     * ⚠ ФОРМА ПРОВЕРКИ ОБНОВЛЕНА 02.09 ВМЕСТЕ С ПРИЧИНОЙ, ПО КОТОРОЙ ОНА
     * ОКАЗАЛАСЬ НЕДОСТАТОЧНОЙ.
     *
     * Здесь сверялся точный вид вызова: `_известить_о_клиенте(conv, client,
     * reason=…)` прямо в разборе телефона. Проверка была зелёной — и всё равно
     * пропустила боевую беду: кадр уходил ВНУТРИ транзакции, до commit'а. Экран
     * получал его, перезапрашивал карточку и читал ещё старую строку без
     * телефона; номер появлялся только после F5.
     *
     * То есть «шлёт ли сервер кадр» — не тот вопрос. Правильный: «есть ли что
     * читать к моменту кадра», и ответить на него из фронтового теста нельзя.
     * Настоящая проверка теперь на бэкенде
     * (`test_к_моменту_кадра_о_клиенте_телефон_уже_в_базе`): она читает базу из
     * ДРУГОЙ сессии и видит только закоммиченное.
     *
     * Здесь остаётся то, что этот набор действительно может стеречь: причины
     * кадра никуда не делись, и публикуется он после записи, а не по месту.
     */
    // Причины с 12.09 рождаются в едином писателе номеров (`clients.absorb_phones`),
    // а `inbound` только несёт их до кадра после commit'а.
    const писатель = readFileSync("../app/services/clients.py", "utf-8") as string;
    expect(писатель, "разбор телефона больше не сообщает, что карточка изменилась").toContain(
      '"phone_captured"',
    );
    expect(писатель, "кадр не шлётся, когда номер только предложен").toContain(
      '"phone_suggested"',
    );
    expect(
      бэк,
      "кадр снова уходит из разбора, то есть ДО записи в базу — вернётся «только после F5»",
    ).toContain("причина_кадра_клиента");
  });
});
