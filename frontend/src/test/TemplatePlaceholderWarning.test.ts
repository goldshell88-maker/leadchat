/**
 * Незаменённый плейсхолдер шаблона предупреждает оператора (27.08).
 *
 * ⚠ КАК НАШЛОСЬ. Обход неиспользуемых экспортов фронта: `hasUnresolvedVars`
 * написана, задокументирована ссылкой на требование 11 §3.1 («подсветить
 * менеджеру») и не вызывалась НИ РАЗУ. Мёртвый экспорт здесь оказался не
 * мусором, а недоделкой — ровно как `inboxAhead` у кнопки «Следующий (N)».
 *
 * Что это значит на экране: `applyTemplateVars` подставляет имя клиента,
 * менеджера и объявление, а когда значения нет — оставляет `{объявление}` в
 * тексте. Так и задумано: «менеджер видит, что надо дописать». Видеть-то он
 * видит, но ничто на это не указывало, и шаблон уходил клиенту со скобками.
 */
import { describe, expect, it } from "vitest";
// @ts-expect-error — типов Node в проекте нет (tsconfig types: ["vite/client"]);
// так же поступают соседние сторожа cardRecipe и buttonNoShrink.
import { readFileSync } from "node:fs";
import { applyTemplateVars, hasUnresolvedVars } from "@/features/templates/vars";

describe("Плейсхолдеры шаблона", () => {
  it("без объявления плейсхолдер остаётся в тексте — и это видно проверке", () => {
    const текст = applyTemplateVars("Здравствуйте, {имя}! По {объявление} готов помочь.", {
      clientName: "Пётр",
      managerName: "Иван",
      itemTitle: null,
    });

    expect(текст).toContain("{объявление}");
    expect(hasUnresolvedVars(текст)).toBe(true);
  });

  it("все значения на месте — предупреждать не о чем", () => {
    const текст = applyTemplateVars("Здравствуйте, {имя}! По {объявление} готов помочь.", {
      clientName: "Пётр",
      managerName: "Иван",
      itemTitle: "Ремонт стиральных машин",
    });

    expect(hasUnresolvedVars(текст)).toBe(false);
  });

  it("клиент без имени плейсхолдером НЕ считается — там свой фолбэк", () => {
    // «Клиент» подставляется вместо имени намеренно (10 §7.2): дописывать
    // менеджеру нечего, и предупреждение здесь было бы ложной тревогой.
    const текст = applyTemplateVars("Здравствуйте, {имя}!", { clientName: null });
    expect(текст).toBe("Здравствуйте, Клиент!");
    expect(hasUnresolvedVars(текст)).toBe(false);
  });

  it("обычные фигурные скобки в тексте тревогу не поднимают", () => {
    // Отправку предупреждение не блокирует, но и кричать на каждую скобку
    // нельзя: считаются только известные имена переменных.
    expect(hasUnresolvedVars("код ошибки {E-102}, пришлите фото")).toBe(false);
  });

  it("ПРОВОДКА: композер действительно зовёт проверку", () => {
    // ⚠ Сердце этой находки. Функция была написана и не подключена — и молчала
    // ровно потому, что её никто не звал. Проверка «работает ли функция» такую
    // поломку не ловит вовсе: она зелёная и у мёртвого кода.
    const src = readFileSync("src/features/chats/components/composer/Composer.tsx", "utf-8") as string;
    expect(src).toContain("hasUnresolvedVars(text)");
  });

  it("проверка не зависит от предыдущего вызова", () => {
    // ⚠ У PATTERN стоит флаг `g`, а `RegExp.test` с ним двигает `lastIndex`:
    // без сброса вторая проверка того же текста вернула бы false. Сброс в
    // коде есть — тест держит его на месте.
    const текст = "осталось {менеджер}";
    expect(hasUnresolvedVars(текст)).toBe(true);
    expect(hasUnresolvedVars(текст)).toBe(true);
  });
});
