import { beforeEach, describe, expect, it } from "vitest";
// @ts-expect-error — типов Node в проекте нет (tsconfig types: ["vite/client"]).
import { readFileSync } from "node:fs";
import { useChatUiStore } from "@/shared/stores/chatUiStore";

/**
 * ОБХОД ЭКРАНОВ 31.08 — три самых дорогих находки.
 *
 * Владелец попросил проверить каждую вкладку и каждое действие и найти то,
 * чего он сам не видел. Эти три опаснее прочих: каждая тихо делает не то, что
 * человек заказывал, и последствия необратимы.
 */

const CONV = "ffff0000-0000-0000-0000-00000000000f";

describe("Заметка не превращается в сообщение клиенту", () => {
  beforeEach(() => {
    useChatUiStore.setState({ drafts: {} });
  });

  it("⚠ после отправки заметки поле остаётся в режиме заметки", () => {
    /*
     * САМАЯ ОПАСНАЯ НАХОДКА ОБХОДА. Очистка поля удаляла запись черновика
     * ЦЕЛИКОМ, вместе с признаком «это заметка». Композер, не найдя записи,
     * брал умолчание — жёлтое поле «Заметка» само перекрашивалось в обычное
     * «Сообщение».
     *
     * Оператор этого не заказывал: он пишет для своих («клиенту скидку не
     * обещать, клиент мутный»), жмёт Enter, поле очищается, он продолжает ту
     * же мысль — и вторая строка уходит КЛИЕНТУ в Авито, где отозвать
     * сообщение нельзя.
     */
    useChatUiStore.getState().setDraft(CONV, { text: "клиент мутный", isNote: true });

    useChatUiStore.getState().clearDraft(CONV);

    const после = useChatUiStore.getState().drafts[CONV];
    expect(после?.isNote, "режим заметки потерян — следующая строка уйдёт клиенту").toBe(true);
    expect(после?.text, "текст заметки не очистился").toBe("");
  });

  it("обычное сообщение по-прежнему стирает запись целиком", () => {
    // Черновики лежат в localStorage: держать пустышку на каждый открытый
    // диалог незачем. Пустышка нужна только заметке — там она несёт смысл.
    useChatUiStore.getState().setDraft(CONV, { text: "Здравствуйте", isNote: false });
    useChatUiStore.getState().clearDraft(CONV);
    expect(useChatUiStore.getState().drafts[CONV]).toBeUndefined();
  });
});

describe("Опасные действия спрашивают, клавиши не срабатывают невпопад", () => {
  it("сброс пароля идёт через подтверждение", () => {
    /*
     * Пункт стоит ПЕРВЫМ в меню строки сотрудника, а срабатывал сразу: промах
     * мышью обнулял пароль работающему диспетчеру и выкидывал его из смены
     * посреди разговора. Соседние опасные действия (роль, отключение,
     * удаление) давно спрашивают — это одно почему-то не спрашивало.
     */
    const исходник = readFileSync(
      "src/features/settings/team/TeamMembersTab.tsx",
      "utf-8",
    ) as string;
    expect(исходник, "сброс пароля снова срабатывает сразу").not.toMatch(
      /onClick=\{\(\) => \{\s*setActionError\(null\);\s*reissue\.mutate\(u\);/,
    );
    expect(исходник, "нет ветки подтверждения для сброса пароля").toMatch(
      /setPending\(\{ kind: "reissue", user: u \}\)/,
    );
  });

  it("во время записи сочетания глобальные клавиши молчат", () => {
    /*
     * ⚠ РЕГРЕССИЯ, ВНЕСЁННАЯ МНОЙ ЖЕ 31.08. Заслон клавиши приёма стал
     * глобальным — и переназначение сочетания превратилось в ловушку: человек
     * жмёт «изменить» у строки «Принять диалог», нажимает Ctrl+R, чтобы задать
     * его, — а заслон честно ПРИНИМАЕТ живой диалог и уносит из настроек в
     * чужую переписку.
     */
    const заслон = readFileSync("src/features/hotkeys/useChatHotkeys.ts", "utf-8") as string;
    expect(заслон, "заслон не спрашивает, идёт ли запись сочетания").toMatch(
      /if \(идётЗапись\) return;/,
    );
    const редактор = readFileSync(
      "src/features/settings/profile/HotkeysEditor.tsx",
      "utf-8",
    ) as string;
    expect(редактор, "редактор не сообщает о начале записи").toMatch(
      /записьСочетания\(capturing !== null\)/,
    );
    expect(редактор, "редактор не снимает признак при уходе").toMatch(
      /return \(\) => записьСочетания\(false\)/,
    );
  });
});
