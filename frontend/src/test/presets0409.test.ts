/**
 * Цветовые пресеты объявлены в ЧЕТЫРЁХ местах — и обязаны совпадать.
 *
 * ⚠ ПРОСЬБА ВЛАДЕЛЬЦА 04.09: «сделай несколько пресетов стиля, не только
 * чёрные и белые».
 *
 * ЧЕТЫРЕ МЕСТА, И У КАЖДОГО СВОЯ ПРИЧИНА БЫТЬ:
 *   index.html — ставит атрибут ДО первой отрисовки, иначе страница мигает
 *                базовой палитрой;
 *   preset.ts  — список для переключателя и смена по нажатию;
 *   lc-vars.css — сами палитры, два блока на пресет;
 *   tokenContrast.test.ts — перебор вариантов в проверках контраста.
 *
 * ⚠ ЭТО РОВНО ТОТ КЛАСС ДЕФЕКТА, НА КОТОРОМ ПРОЕКТ УЖЕ ЛОВИЛСЯ: «два пути
 * считают одно поле по-разному». Разъедься списки — и получится пресет,
 * который выбирается в настройках, но не красит; или красит, но не переживает
 * перезагрузку; или живёт в CSS, а проверки контраста о нём не знают. Ни одно
 * из трёх не видно глазами сразу.
 */
// @ts-expect-error — типов Node в проекте нет (tsconfig types: ["vite/client"]).
import { readFileSync } from "node:fs";
import { describe, expect, it } from "vitest";

const БЕЗ_КОММЕНТАРИЕВ = (s: string) => s.replace(/\/\*[\s\S]*?\*\//g, "");

/** Ключи из списка переключателя (без базового — он «отсутствие пресета»). */
function изМодуля(): string[] {
  const src = readFileSync("src/shared/theme/preset.ts", "utf-8") as string;
  const блок = БЕЗ_КОММЕНТАРИЕВ(src).match(/ПРЕСЕТЫ\s*=\s*\[([\s\S]*?)\]\s*as const/);
  expect(блок, "не нашёл список ПРЕСЕТЫ").toBeTruthy();
  return [...блок![1].matchAll(/key:\s*"([\w-]+)"/g)]
    .map((m) => m[1])
    .filter((k) => k !== "base")
    .sort();
}

/** Ключи, которые пропускает встроенный скрипт первой отрисовки. */
function изСкрипта(): string[] {
  const html = readFileSync("index.html", "utf-8") as string;
  /*
   * Берём ровно условие `if (...)`, а не всё до точки с запятой: следом идёт
   * `setAttribute("data-lc-preset", preset)`, и имя атрибута попадало в список
   * ключей четвёртым «пресетом».
   */
  const строка = html.match(/if \(preset === ([^)]*)\)/);
  expect(строка, "во встроенном скрипте нет проверки пресета").toBeTruthy();
  return [...строка![1].matchAll(/"([\w-]+)"/g)].map((m) => m[1]).sort();
}

/** Ключи, для которых в палитре есть блоки. */
function изCss(): string[] {
  const css = БЕЗ_КОММЕНТАРИЕВ(readFileSync("src/app/lc-vars.css", "utf-8") as string);
  return [...new Set([...css.matchAll(/data-lc-preset="([\w-]+)"/g)].map((m) => m[1]))].sort();
}

/** Ключи, которые перебирают проверки контраста. */
function изСторожа(): string[] {
  const src = БЕЗ_КОММЕНТАРИЕВ(
    readFileSync("src/test/tokenContrast.test.ts", "utf-8") as string,
  );
  const блок = src.match(/const PRESETS = \[([^\]]*)\] as const/);
  expect(блок, "в стороже контраста нет списка PRESETS").toBeTruthy();
  return [...блок![1].matchAll(/"([\w-]+)"/g)].map((m) => m[1]).sort();
}

describe("Цветовые пресеты", () => {
  it("переключатель, скрипт первой отрисовки, палитра и сторож знают одно и то же", () => {
    const модуль = изМодуля();
    expect(модуль.length, "пресетов нет вовсе").toBeGreaterThan(0);
    expect(изСкрипта(), "скрипт index.html не пропускает те же ключи").toEqual(модуль);
    expect(изCss(), "в палитре нет блоков под эти ключи").toEqual(модуль);
    expect(изСторожа(), "проверки контраста не перебирают эти пресеты").toEqual(модуль);
  });

  it("у каждого пресета ДВА блока: тёмный и светлый", () => {
    /*
     * Один блок на пресет — самая заманчивая ошибка здесь: кажется, что цвет
     * задан, и он действительно задан — но направление контраста в темах
     * зеркальное. В тёмной графика берёт светлую ступень рампы и заливка носит
     * тёмные чернила; в светлой всё наоборот. Один блок означает нечитаемые
     * заливки в одной из двух тем.
     */
    const css = БЕЗ_КОММЕНТАРИЕВ(readFileSync("src/app/lc-vars.css", "utf-8") as string);
    const пропущено: string[] = [];
    for (const ключ of изМодуля()) {
      const светлый = new RegExp(
        `data-lc-preset="${ключ}"\\]\\[data-mantine-color-scheme="light"`,
      ).test(css);
      const тёмный = new RegExp(
        `data-lc-preset="${ключ}"\\]:not\\(\\[data-mantine-color-scheme="light"\\]\\)`,
      ).test(css);
      if (!тёмный) пропущено.push(`${ключ}: нет тёмного блока с оговоркой :not(...light)`);
      if (!светлый) пропущено.push(`${ключ}: нет светлого блока`);
    }
    expect(пропущено, пропущено.join("\n")).toEqual([]);
  });

  it("пресет красит и заливки Mantine, а не только токены проекта", () => {
    /*
     * ⚠ ИСТОЧНИКОВ ЦВЕТА ДВА, И ВТОРОЙ ПРИХОДИТ ИЗ JS. Заливки кнопок,
     * бейджей, чекбоксов и рамки каркаса берутся из кортежа `lp` в theme.tsx,
     * а не из lc-vars.css. Перекрасить только токены — получить наполовину
     * перекрашенное приложение: строка выбрана новым цветом, а кнопка на ней
     * осталась зелёной. Кортеж статичен и var() содержать не может, поэтому
     * пресет переопределяет переменные Mantine прямо в своём блоке.
     */
    const css = БЕЗ_КОММЕНТАРИЕВ(readFileSync("src/app/lc-vars.css", "utf-8") as string);
    const без: string[] = [];
    for (const ключ of изМодуля()) {
      const блоки = [...css.matchAll(/([^{}]+)\{([^{}]*)\}/g)].filter(([, sel]) =>
        sel.includes(`data-lc-preset="${ключ}"`),
      );
      for (const [, sel, body] of блоки) {
        if (!/--mantine-color-lp-\d/.test(body)) без.push(sel.trim().slice(0, 80));
      }
    }
    expect(без, `блок пресета не переопределяет кортеж Mantine:\n${без.join("\n")}`).toEqual([]);
  });
});
