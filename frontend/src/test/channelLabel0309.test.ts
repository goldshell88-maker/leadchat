import { describe, expect, it } from "vitest";
import { подписьКанала } from "@/shared/lib/channelLabel";

/**
 * ИСТОЧНИК РЯДОМ С НАЗВАНИЕМ КАНАЛА (просьба владельца 03.09).
 *
 * ⚠ ПОЧЕМУ ЭТО НУЖНО. В списках выбора два десятка строк вида «Александр КП»,
 * «Александр МНЧ», «Анатолий БТ» — по ним не отличить, какой источник за каким
 * каналом. А диспетчер отвечает клиенту именно от источника, и в шапке чата
 * тот показан с 19.08 — в списках его не было.
 *
 * ⚠ ПОЧЕМУ ПОДПИСЬ, А НЕ НАЗВАНИЕ. Раньше владелец вписывал источник прямо в
 * название канала («ПАРТ 7 ИСТ С78»). 19 августа поля вынесли из названия: оно
 * уходит в отчёты и уведомления. Источник приписывается ПРИ ОТОБРАЖЕНИИ.
 */
describe("подпись канала", () => {
  it("источник приписывается к названию", () => {
    expect(подписьКанала({ title: "Александр КП", lead_origin: "В84.2" })).toBe(
      "Александр КП · В84.2",
    );
  });

  it("без источника подпись остаётся прежней", () => {
    /*
     * Служебный канал и только что подключённый источника не имеют. Висящая
     * точка без значения хуже её отсутствия.
     */
    expect(подписьКанала({ title: "SMOKE-ACCOUNT", lead_origin: null })).toBe("SMOKE-ACCOUNT");
    expect(подписьКанала({ title: "Новый", lead_origin: undefined })).toBe("Новый");
  });

  it("пробелы вокруг источника не создают пустой хвост", () => {
    /*
     * Поле правится руками в настройках, и пробел там появляется легко.
     * `"Канал · "` выглядел бы как обрезанная строка.
     */
    expect(подписьКанала({ title: "Канал", lead_origin: "   " })).toBe("Канал");
    expect(подписьКанала({ title: "Канал", lead_origin: " В95 " })).toBe("Канал · В95");
  });
});
