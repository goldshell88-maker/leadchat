/**
 * СЕРВИС-ВОРКЕР: КНОПКИ «ПРИНЯТЬ»/«ОТКЛОНИТЬ» ВНУТРИ УВЕДОМЛЕНИЯ (07.09).
 *
 * ⚠ ЖАЛОБА ВЛАДЕЛЬЦА: «не работают уведомления от браузера… чтобы можно было
 * принять диалог или отклонить там же в уведомлении».
 *
 * Кнопки в уведомлении даёт ровно один механизм — `registration.showNotification`
 * сервис-воркера. У `new Notification`, которым веб-мост обходился до сих пор,
 * поля `actions` нет вовсе; это разделение в стандарте, а не пробел браузера.
 *
 * Все проверки здесь про одно: этот путь ломается МОЛЧА. Воркер, отданный с
 * чужим Content-Type, не регистрируется — и приложение продолжает работать,
 * просто без кнопок. Ни экрана ошибки, ни записи в журнале сервера: отказ
 * виден только в консоли вкладки конкретного человека. Поэтому сторожа стоят и
 * на коде, и на тексте конфигов, которые этот код обслуживают.
 */

// ---------------------------------------------------------------------------
// Подделка браузерного `navigator.serviceWorker`: в jsdom его нет вовсе.
// ---------------------------------------------------------------------------

type Слушатель = (e: MessageEvent) => void;

/** Поля показа, которых нет в типах браузера (см. довод в serviceWorker.ts). */
type ОпцииПоказа = {
  body?: string;
  icon?: string;
  tag?: string;
  requireInteraction?: boolean;
  silent?: boolean | null;
  actions?: Array<{ action: string; title: string }>;
  data?: { conversationId: string | null };
};

function поставитьВоркерВБраузере(
  опции: { регистрация?: () => Promise<unknown>; показ?: () => Promise<void> } = {},
) {
  // Тип задан отдельно, а не именами аргументов: имена здесь не нужны ни
  // одной проверке (они читают `mock.calls`), а линтер справедливо ругается на
  // объявленный и неиспользованный аргумент.
  type Показ = (title: string, опции?: ОпцииПоказа) => Promise<void>;
  const showNotification = vi.fn<Показ>(опции.показ ? () => опции.показ!() : async () => {});
  const рег = { showNotification } as unknown as ServiceWorkerRegistration;
  const register = vi.fn(опции.регистрация ?? (async () => рег));
  const слушатели: Слушатель[] = [];

  Object.defineProperty(navigator, "serviceWorker", {
    configurable: true,
    value: {
      register,
      addEventListener: (тип: string, cb: Слушатель) => {
        if (тип === "message") слушатели.push(cb);
      },
      removeEventListener: (_тип: string, cb: Слушатель) => {
        const i = слушатели.indexOf(cb);
        if (i >= 0) слушатели.splice(i, 1);
      },
    },
  });

  return { register, showNotification, слушатели };
}

async function модуль() {
  return await import("@/platform/serviceWorker");
}

async function читать(путь: string): Promise<string> {
  // @ts-expect-error — типов Node в проекте нет (tsconfig types: ["vite/client"]).
  const { readFileSync } = await import("node:fs");
  return readFileSync(путь, "utf-8") as string;
}

