// @ts-expect-error — типов Node в проекте нет (tsconfig types: ["vite/client"]),
// как в breakpoints.test.ts и cssDeadClasses.test.ts: сторож только читает файлы.
import { readFileSync } from "node:fs";
import { describe, expect, it } from "vitest";

/**
 * СТОРОЖА УЧАСТКА «БОТЫ · АВТОЗАЯВКИ» — АДАПТИВНОСТЬ И ИЕРАРХИЯ (05.09).
 *
 * Всё, что здесь проверяется, померено в браузере на статическом стенде с
 * НАСТОЯЩИМИ css этого участка, на пяти ширинах (375, 768, 1024, 1440, 2560) и
 * в обеих темах. Числа в объяснениях — оттуда, а не с потолка.
 *
 * ⚠ ПОЧЕМУ СТОРОЖА ЧИТАЮТ ФАЙЛЫ, А НЕ МЕРЯЮТ. В конфигурации тестов стоит
 * `css: false` (vite.config.ts): в jsdom стилей нет вовсе, ширину мерить нечем,
 * а `import ... ?raw` для .css отдаёт пустую строку — тот же капкан описан в
 * breakpoints.test.ts и mantineStyles.test.ts. Поэтому читаем через `node:fs`
 * и проверяем то, что проверяемо: механизм раскладки объявлен, потолки на
 * месте, ступени кегля разведены.
 */

const BOTS_CSS = "src/features/settings/bots/bots.css";
const LEADS_CSS = "src/features/settings/leads/leads.css";
const VARS_CSS = "src/app/lc-vars.css";

function файл(путь: string): string {
  return readFileSync(путь, "utf-8") as string;
}

/** Текст без комментариев: разбор в шапке правила вправе называть что угодно. */
function безКомментариев(путь: string): string {
  return файл(путь).replace(/\/\*[\s\S]*?\*\//g, " ");
}

/** Все правила файла: селектор (как написан) и тело. Медиазапросы включены. */
function правила(путь: string): Array<{ селектор: string; тело: string; позиция: number }> {
  const css = безКомментариев(путь);
  const out: Array<{ селектор: string; тело: string; позиция: number }> = [];
  const rx = /([^{}@]+)\{([^{}]*)\}/g;
  let m: RegExpExecArray | null;
  while ((m = rx.exec(css)) !== null) {
    const селектор = m[1].trim();
    if (!селектор || селектор.startsWith("@")) continue;
    out.push({ селектор, тело: m[2], позиция: m.index });
  }
  return out;
}

/* ══════════════════ 1. Правило раскладки объявляет свой механизм ══════════ */

/**
 * ⚠ ГЛАВНАЯ ЛОВУШКА УЧАСТКА, И ОНА ЗДЕСЬ УЖЕ СРАБОТАЛА.
 *
 * В `leads.css` лежало ровно одно объявление на строку канала —
 * `justify-content: space-between`, — и не делало НИЧЕГО: `.leads-channel` был
 * обычным `div` (`display: block`), а `justify-content` понимают только
 * флекс и грид. Замерено в браузере: `getComputedStyle(...).display === "block"`.
 * Правило пережило ту раскладку, под которую писалось (имя слева, выбор
 * лид-центра справа одной строкой), и осталось лежать памятником — а пока оно
 * лежало, разъезда никто не искал: на 375 имени канала доставалось 136 px при
 * нужных 279–419, то есть «Бригада Андрея …» у всех трёх бригад подряд.
 *
 * Сторож требует малого: свойство, которое работает только во флексе или
 * гриде, обязано стоять рядом с объявлением этого механизма — в том же правиле
 * или в другом правиле того же файла с тем же селектором (так устроены
 * медиазапросы: базовое правило объявляет `display`, узкое правит направление).
 */
const ТОЛЬКО_ВО_ФЛЕКСЕ = ["justify-content", "flex-direction", "flex-wrap", "align-content"];

describe("Раскладка объявляет механизм, а не правит несуществующий", () => {
  for (const путь of [BOTS_CSS, LEADS_CSS]) {
    it(`${путь}: у каждого правила раскладки есть свой display`, () => {
      const все = правила(путь);
      // Отрицательная проверка обязана падать по своей причине: пустой разбор
      // означал бы, что регексп перестал видеть правила, — и тест зеленел бы
      // всегда, в том числе на диверсии.
      expect(все.length, `${путь}: правила не разобрались`).toBeGreaterThan(5);

      const механизмУ = new Map<string, boolean>();
      for (const { селектор, тело } of все) {
        if (/display:\s*(flex|grid|inline-flex|inline-grid)/.test(тело)) {
          механизмУ.set(селектор, true);
        }
      }

      const мёртвые: string[] = [];
      for (const { селектор, тело } of все) {
        const правит = ТОЛЬКО_ВО_ФЛЕКСЕ.some((имя) => new RegExp(`(^|;|\\s)${имя}:`).test(тело));
        if (!правит) continue;
        const свой = /display:\s*(flex|grid|inline-flex|inline-grid)/.test(тело);
        if (!свой && !механизмУ.get(селектор)) мёртвые.push(селектор);
      }

      expect(
        мёртвые,
        `${путь}: правило раскладки без объявленного display — оно не делает ничего`,
      ).toEqual([]);
    });
  }
});

/* ══════════════════ 2. Ширины из разметки не распирают телефон ════════════ */

describe("Объявленные в разметке ширины имеют потолок на узком экране", () => {
  it("строка канала: поля не шире своей строки", () => {
    /*
     * У выбора лид-центра стоит `w={320}`, и уменьшать его нельзя — это
     * защита от немой обрезки подписи (leadsWording.test.ts, 29.08). Но на 375
     * содержимому раздела остаётся 327 px, и то же число распирало строку:
     * замер до правки — поле 184 px при нужных 308, имя 136 при нужных 279.
     */
    const css = безКомментариев(LEADS_CSS);
    expect(css, "снят потолок с полей строки канала").toMatch(
      /\.leads-channel__head\s*>\s*\*[\s\S]{0,120}max-width:\s*100%/,
    );
  });

  it("строка канала переносится, а не режет имя и выбор одновременно", () => {
    const тело = правила(LEADS_CSS).find((r) => r.селектор === ".leads-channel__head")?.тело ?? "";
    expect(тело, "у ряда «имя + лид-центр» пропал перенос").toMatch(/flex-wrap:\s*wrap/);
  });

  it("переключатель режима бота: потолок И сжимаемая обёртка", () => {
    /*
     * Одного `max-width: 100%` на переключателе мало: процент считается от
     * колонки-обёртки, а у неё как у флекс-элемента `min-width: auto` — она не
     * сжимается ниже max-content своего содержимого, то есть ниже тех же 340.
     * Замер: без `min-width: 0` переключатель оставался 340 в колонке 327.
     */
    const css = безКомментариев(BOTS_CSS);
    const обёртка = правила(BOTS_CSS).find((r) => r.селектор === ".bot-editor__mode")?.тело ?? "";
    expect(обёртка, "обёртка режима снова не сжимается").toMatch(/min-width:\s*0/);
    expect(css, "снят потолок с переключателя режима").toMatch(
      /\.bot-editor__mode\s+\.mantine-SegmentedControl-root\s*\{[^}]*max-width:\s*100%/,
    );
  });
});

/* ══════════════════ 3. Сводка шага не остаётся без ширины ═════════════════ */

describe("Свёрнутая карточка шага показывает текст шага и на телефоне", () => {
  it("узкое правило стоит ПОСЛЕ базового и даёт сводке ненулевой базис", () => {
    /*
     * Замер на 375 до правки: `.step-card__control` получал 16 px при нужных
     * 574 — свёрнутая карточка показывала идентификатор и три кнопки, а текст
     * шага не показывала вовсе.
     *
     * ⚠ ПОРЯДОК ВАЖНЕЕ САМОГО ПРАВИЛА. Оба правила весят (0,1,0), и решает
     * порядок в файле: первая редакция этой правки стояла ВЫШЕ базового
     * `.step-card__control { flex: 1 }` — базис перебивался обратно на 0, и на
     * экране не менялось ничего. Поймано браузером, а не чтением.
     */
    const все = правила(BOTS_CSS).filter((r) => r.селектор === ".step-card__control");
    expect(все.length, "правил для сводки шага стало не два").toBeGreaterThanOrEqual(2);

    const базовое = все[0];
    const узкое = все[все.length - 1];
    expect(узкое.позиция, "узкое правило снова стоит выше базового").toBeGreaterThan(базовое.позиция);

    const базис = /flex:\s*\d+\s+\d+\s+([\d.]+)(%|px)/.exec(узкое.тело);
    expect(базис, "у сводки шага на узком экране пропал явный базис").not.toBeNull();
    expect(Number(базис?.[1]), "базис снова нулевой — переноса не будет").toBeGreaterThan(0);
  });

  it("порог тот же, что у таблиц-карточек, — третьего числа не завелось", () => {
    const пороги = new Set(
      [...безКомментариев(BOTS_CSS).matchAll(/@media[^{]*max-width:\s*(\d+)px/g)].map((m) => m[1]),
    );
    expect([...пороги], "в ботах появился свой порог раскладки").toEqual(["900"]);
  });
});

/* ══════════════════ 4. Таблица ботов на телефоне — карточки ═══════════════ */

describe("Список ботов ничего не прячет за правым краем", () => {
  const src = файл("src/features/settings/bots/BotsPage.tsx");

  it("таблица носит общий карточный режим", () => {
    /*
     * Замер на 375: таблица просила 1018 px при колонке 375 — 643 px уезжали в
     * горизонтальную прокрутку раздела без единого признака, что там что-то
     * есть. За краем оставались аккаунты, расписание, счётчик и обе кнопки.
     *
     * ⚠ ИЩЕМ В `className` ТАБЛИЦЫ, А НЕ В ФАЙЛЕ. Первая редакция проверяла
     * `src.toContain("lc-table--cards")` — и диверсия, снявшая класс с
     * таблицы, прошла её насквозь: рядом стоит объяснение, где это имя
     * названо словами. Сторож читал комментарий и зеленел.
     */
    const тег = /<Table\s[^>]*className="([^"]*)"/.exec(src);
    expect(тег, "у таблицы ботов пропал className").not.toBeNull();
    expect(
      (тег?.[1] ?? "").split(/\s+/),
      "таблица ботов снова без карточного режима",
    ).toContain("lc-table--cards");
  });

  it("у каждого названного столбца есть подпись ячейки", () => {
    /*
     * Подпись в карточном режиме берётся из `data-label`: CSS не умеет читать
     * содержимое `<th>`. Забытая подпись даёт значение без имени — «24/7» само
     * по себе не говорит ничего.
     */
    const заголовки = [...src.matchAll(/<Table\.Th[^>]*>\s*([^<]+?)\s*<\/Table\.Th>/g)].map(
      (m) => m[1].trim(),
    );
    expect(заголовки.length, "столбцы таблицы ботов не разобрались").toBeGreaterThan(4);

    const подписи = new Set(
      [...src.matchAll(/data-label="([^"]+)"/g)].map((m) => m[1]),
    );
    // «Бот» — заголовок карточки, у него подписи нет намеренно (иначе слева
    // встало бы слово «Бот» напротив имени бота).
    for (const имя of заголовки.filter((h) => h !== "Бот")) {
      expect(подписи.has(имя), `столбец «${имя}» остался без data-label`).toBe(true);
    }
  });
});

/* ══════════════════ 5. Иерархия: число крупнее своей подписи ══════════════ */

/** Ступени шкалы кеглей из lc-vars.css: имя → пиксели базовой шкалы. */
function шкала(): Record<string, number> {
  const out: Record<string, number> = {};
  // Берём ПЕРВОЕ объявление каждой ступени: ниже в файле шкала
  // переобъявляется для мониторов от 1800, и там числа другие.
  for (const m of файл(VARS_CSS).matchAll(/--lc-fz-([a-z]+):\s*(\d+)px/g)) {
    if (out[m[1]] === undefined) out[m[1]] = Number(m[2]);
  }
  return out;
}

describe("Показателю — кегль показателя, подписи — кегль подписи", () => {
  const ступени = шкала();

  it("шкала кеглей прочиталась", () => {
    // Иначе проверки ниже сравнивали бы undefined с undefined и молчали.
    expect(Object.keys(ступени).length).toBeGreaterThanOrEqual(8);
  });

  it("числа журнала автозаявок вдвое крупнее своих подписей", () => {
    /*
     * Было наоборот по обоим счетам: подпись стояла первой, а число под ней
     * набиралось `fz="lg"` — 18 px, ступени, которой в шкале нет вовсе (есть 16
     * и 20). Полтора кегля разницы взгляд не ловит: два единственных числа
     * экрана читались как продолжение текста.
     */
    const value = правила(LEADS_CSS).find((r) => r.селектор === ".leads-stat__value")?.тело ?? "";
    const label = правила(LEADS_CSS).find((r) => r.селектор === ".leads-stat__label")?.тело ?? "";
    const токен = (тело: string) => /font-size:\s*var\(--lc-fz-([a-z]+)\)/.exec(тело)?.[1] ?? "";

    const кеглЧисла = ступени[токен(value)];
    const кеглПодписи = ступени[токен(label)];
    expect(кеглЧисла, "у числа пропал кегль из шкалы").toBeGreaterThan(0);
    expect(кеглПодписи, "у подписи пропал кегль из шкалы").toBeGreaterThan(0);
    expect(
      кеглЧисла / кеглПодписи,
      "число и подпись снова почти одного кегля — иерархия схлопнулась",
    ).toBeGreaterThanOrEqual(1.8);
  });

  it("«Диалогов/7д» набрано крупнее соседей по строке", () => {
    const src = файл("src/features/settings/bots/BotsPage.tsx");
    const ячейка = /<Table\.Td[^>]*data-label="Диалогов\/7д"[\s\S]*?<\/Table\.Td>/.exec(src);
    expect(ячейка, "ячейка со счётчиком диалогов пропала").not.toBeNull();
    const токен = /fz="var\(--lc-fz-([a-z]+)\)"/.exec(ячейка?.[0] ?? "")?.[1] ?? "";
    expect(
      ступени[токен],
      "счётчик диалогов снова того же кегля, что расписание рядом",
    ).toBeGreaterThan(ступени.body);
  });

  it("заголовок «Сценарий» — ступень раздела, а не карточки", () => {
    const src = файл("src/features/settings/bots/BotEditor.tsx");
    const заголовок = /<Title order=\{2\}[^>]*>/.exec(src)?.[0] ?? "";
    expect(заголовок, "заголовок сценария пропал").not.toBe("");
    expect(заголовок, "кегль заголовка снова числом или ступенью карточки").toContain(
      "var(--lc-fz-section)",
    );
  });
});

