/* ══════════════════ 8. Движение объяснено и гасится ═══════════════════════ */

describe("Единственное движение экрана уважает «уменьшить движение»", () => {
  it("появление списка ошибок гасится настройкой системы", () => {
    /*
     * Глобальное правило в lc-vars.css гасит `animation`, но НАМЕРЕННО не
     * трогает `transition` — значит своё движение обязано гаситься и своим
     * правилом тоже, иначе следующая правка (перевод на transition) тихо
     * вернёт качание тем, кто его выключил.
     */
    const css = безКомментариев(BOTS_CSS);
    expect(css, "у списка ошибок пропало появление").toMatch(
      /\.bot-editor__issues\s*\{[^}]*animation:\s*bot-issues-in/,
    );
    expect(css, "движение не гасится при prefers-reduced-motion").toMatch(
      /@media\s*\(prefers-reduced-motion:\s*reduce\)\s*\{\s*\.bot-editor__issues\s*\{[^}]*animation:\s*none/,
    );
  });

  it("длительность взята токеном, а не числом", () => {
    const тело = правила(BOTS_CSS).find((r) => r.селектор === ".bot-editor__issues")?.тело ?? "";
    expect(тело, "длительность появления записана числом мимо шкалы").toMatch(
      /animation:[^;]*var\(--lc-dur-[a-z]+\)/,
    );
  });
});
