import { readFileSync } from "node:fs";
import { describe, expect, it } from "vitest";
import { MOBILE_MAX, NARROW_MAX, узкоеМесто } from "@/shared/lib/breakpoints";
import { RAIL_WIDTH_COLLAPSED, RAIL_WIDTH_EXPANDED } from "@/shared/stores/railStore";

/**
 * ПОРОГ РАСКЛАДКИ СЧИТАЕТСЯ ОТ РАБОЧЕГО МЕСТА, А НЕ ОТ ОКНА.
 *
 * ЧТО БЫЛО. Ступени раскладки чатов стояли медиазапросами по ширине ОКНА, а
 * содержимому окно целиком не достаётся: слева рельса приложения, и по
 * умолчанию она РАЗВЁРНУТА на 218 пикселей (`railStore`, «команда переезжает с
 * Jivo, где разделы подписаны словами»). В `lc-vars.css` при этом лежит
 * запасное `--lc-rail-w: 72px`, и расчёты в комментариях велись от него.
 * Разница 146 пикселей — ровно столько, чтобы ступень включилась там, где на
 * неё нет места.
 *
 * ЗАМЕР НА СТЕНДЕ 08.09 (собранный CSS, рельса 218, высота 900) — ДО:
 *
 *     окно 1360 → ленте 398px      окно 1500 → 450 (МЕНЬШЕ, чем на 1440)
 *     окно 1400 → 438              окно 1600 → 550
 *     окно 1440 → 478              окно 1700 → 650 ← только здесь ≥616
 *
 * То есть на полосе окон 1360–1699 показывались три колонки при ленте ниже её
 * собственного объявленного минимума 616. Слои при этом расходились: CSS уже
 * считал раскладку широкой (поле 16, зазор 16), а React по тому же окну ещё
 * держал карточку в потоке — из 14 ширин матрицы при рельсе 218 сходились
 * восемь, расходились шесть.
 *
 * ПОСЛЕ (тот же стенд, те же ширины): все 14 ширин × 2 положения рельсы —
 * сходятся, а лента при трёх колонках нигде не опускается ниже 609 пикселей:
 *
 *     место 1359 → лента 983 (две колонки)   место 1441 → 609
 *     место 1360 → 616                       место 1800 → 928
 *     место 1440 → 696                       место 1921 → 1009
 *
 * ⚠ ЧЕГО ЭТОТ СТОРОЖ НЕ УМЕЕТ. В vitest стоит `css: false`, а jsdom не считает
 * раскладку вовсе: ни медиазапросы, ни контейнерные запросы здесь не
 * применяются, `getBoundingClientRect` отдаёт нули. Ни одну из находок выше
 * рендер-тест не увидел бы НИКОГДА — их и нашли замером в браузере. Здесь
 * проверяется единственное, что проверяемо машиной: правило меряет тот
 * предмет, который решает дело, оба слоя меряют один и тот же предмет, и
 * арифметика ступеней сходится по числам из самих файлов.
 */

/** Пути относительные: vitest запускается из каталога frontend. */
const читать = (путь: string): string => readFileSync(путь, "utf-8") as string;

const LAYOUT_CSS = читать("src/app/app-layout.css");
const CHATS_CSS = читать("src/features/chats/chats-page.css");
const THREAD_CSS = читать("src/features/chats/components/thread/chat-thread.css");
const CHATS_TSX = читать("src/features/chats/ChatsPage.tsx");
const ШИРИНА_TS = читать("src/features/chats/ширинаМеста.ts");

function безКомментариев(css: string): string {
  return css.replace(/\/\*[\s\S]*?\*\//g, " ");
}

/** Тело блока `@…{ … }`, начиная от индекса заголовка. */
function тело(текст: string, отЗаголовка: number): string {
  let глубина = 0;
  for (let i = текст.indexOf("{", отЗаголовка); i < текст.length; i += 1) {
    if (текст[i] === "{") глубина += 1;
    else if (текст[i] === "}") {
      глубина -= 1;
      if (глубина === 0) return текст.slice(текст.indexOf("{", отЗаголовка) + 1, i);
    }
  }
  return "";
}

/** Все блоки файла с таким заголовком (регулярка ищется по «очищенному» CSS). */
function блоки(css: string, заголовок: RegExp): string[] {
  const текст = безКомментариев(css);
  const out: string[] = [];
  const re = new RegExp(заголовок.source, "g");
  for (const m of текст.matchAll(re)) out.push(тело(текст, m.index!));
  return out;
}

/** Значения токенов шкалы: сравнивать ступени можно только в пикселях. */
function токен(имя: string): number {
  const vars = читать("src/app/lc-vars.css");
  const m = new RegExp(`\\${имя}:\\s*(\\d+)px`).exec(vars);
  expect(m, `в токенах нет ${имя}`).not.toBeNull();
  return Number(m![1]);
}

/** `340px` или `var(--lc-col-list)` — в число. */
function впиксели(значение: string): number {
  const v = значение.trim();
  const прямо = /^(\d+)px$/.exec(v);
  if (прямо) return Number(прямо[1]);
  const через = /^var\((--[a-z0-9-]+)\)$/.exec(v);
  expect(через, `непонятное значение ${v}`).not.toBeNull();
  return токен(через![1]);
}

/**
 * Ширина ленты при такой ширине рабочего места — ПО РАЗБОРУ CSS.
 *
 * Каскад повторяется вручную: базовые правила, затем контейнерные блоки файла
 * сверху вниз, чьё условие подходит. Карточка при узком месте из потока
 * уходит — это решает React (`ChatsPage.tsx`), и здесь повторено то же
 * условие: `узкоеМесто`.
 */
function ленте(место: number): number {
  const текст = безКомментариев(CHATS_CSS);
  const состояние = {
    поле: токен("--lc-gutter"),
    зазор: токен("--lc-gutter"),
    список: токен("--lc-col-list"),
    карточка: токен("--lc-col-card"),
  };

  const применить = (блок: string) => {
    for (const m of блок.matchAll(/([^{}]+)\{([^{}]*)\}/g)) {
      const селектор = m[1].trim().replace(/\s+/g, " ");
      const свойства = m[2];
      if (селектор === ".chats-page") {
        const поле = /(?:^|;)\s*padding:\s*([^;]+)/.exec(свойства);
        if (поле) {
          const части = поле[1].trim().split(/\s+/);
          состояние.поле = впиксели(части[части.length - 1]);
        }
        const зазор = /(?:^|;)\s*gap:\s*([^;]+)/.exec(свойства);
        if (зазор) состояние.зазор = впиксели(зазор[1]);
      }
      const ширина = /(?:^|;)\s*width:\s*([^;]+)/.exec(свойства);
      if (!ширина) continue;
      if (селектор === ".chats-page > .chat-list-pane") состояние.список = впиксели(ширина[1]);
      if (селектор === ".chats-page > .client-card:not(.client-card--overlay)") {
        состояние.карточка = впиксели(ширина[1]);
      }
    }
  };

  // Базовые правила — всё, что до первого блока с условием.
  применить(текст.slice(0, текст.indexOf("@")));

  const re = /@container\s+lc-workspace\s*\((max|min)-width:\s*(\d+)px\)/g;
  for (const m of текст.matchAll(re)) {
    const порог = Number(m[2]);
    const подходит = m[1] === "max" ? место <= порог : место >= порог;
    if (подходит) применить(тело(текст, m.index!));
  }

  const колонки = узкоеМесто(место)
    ? состояние.список
    : состояние.список + состояние.карточка + состояние.зазор;
  return место - 2 * состояние.поле - колонки - состояние.зазор;
}

describe("Ступени раскладки меряют рабочее место, а не окно", () => {
  it("контейнер объявлен на `.lc-main` — и у неё нет полей, иначе он мерил бы не то", () => {
    /*
     * Размерный запрос читает CONTENT-BOX контейнера. Появись у `.lc-main`
     * поля — и измеряемая ширина перестала бы совпадать с border-box
     * `.chats-page`, то есть с тем, что наблюдает React. Расхождение вышло бы
     * ровно на сумму полей и жило бы молча.
     */
    const правило = /\.lc-main\s*\{([^}]*)\}/.exec(безКомментариев(LAYOUT_CSS));
    expect(правило, "правило .lc-main пропало").not.toBeNull();
    expect(правило![1], "`.lc-main` перестала быть контейнером запросов").toMatch(
      /container-type:\s*inline-size/,
    );
    expect(правило![1]).toMatch(/container-name:\s*lc-workspace/);
    expect(
      /(^|;)\s*padding/.test(правило![1]),
      "у `.lc-main` появились поля — контейнер стал мерить уже, чем ширина рабочего места",
    ).toBe(false);
  });

  it("контейнером НЕ стала сама `.chats-page` — это замкнуло бы круг", () => {
    /*
     * ⚠ САМАЯ ЗАМАНЧИВАЯ ПРАВКА И САМАЯ НЕВЕРНАЯ. Написать `container-type` на
     * `.chats-page` короче на одну строку и не требует чужого файла. Но поля у
     * неё ступенчатые (24 / 16 / 12), а запрос читает content-box: запрос,
     * который меняет поля своего же контейнера, меняет и то, что измеряет. На
     * ступени 1441 поле прыгает с 16 на 32, то есть измеряемая ширина скачет
     * на 32 пикселя В СТОРОНУ ОБРАТНОГО РЕШЕНИЯ, и на полосе шириной ровно в
     * эту разницу устойчивого ответа не существует вовсе.
     */
    const база = /\.chats-page\s*\{([^}]*)\}/.exec(безКомментариев(CHATS_CSS));
    expect(база, "базовое правило .chats-page пропало").not.toBeNull();
    expect(
      /container-type/.test(база![1]),
      "`.chats-page` объявлена контейнером — она меняет собственные поля, и запрос начнёт спорить сам с собой",
    ).toBe(false);
  });

  it("вся лестница чатов живёт в контейнерных запросах", () => {
    const текст = безКомментариев(CHATS_CSS);
    const контейнерные = [...текст.matchAll(/@container\s+lc-workspace[^{]*?(\d+)px/g)].map((m) =>
      Number(m[1]),
    );
    expect(контейнерные.sort((a, b) => a - b)).toEqual([1359, 1440, 1441, 1800, 1921]);
    expect(
      контейнерные,
      "порог узкой раскладки в CSS разошёлся с NARROW_MAX — карточка окажется и в потоке, и в оверлее",
    ).toContain(NARROW_MAX);
  });

  it("медиазапросы чатов остались только страховкой, под `@supports`", () => {
    /*
     * Отрицательная проверка обязана падать по своей причине: оставь кто-нибудь
     * медиазапрос СНАРУЖИ `@supports`, и он вернёт мерку по окну на верхних
     * ступенях. `min-width: 1800px` по окну ложно срабатывает при развёрнутой
     * рельсе на 218 пикселей раньше — ровно та беда, от которой лечимся.
     */
    const текст = безКомментариев(CHATS_CSS);
    const запас = блоки(CHATS_CSS, /@supports\s+not\s*\(container-type:\s*inline-size\)/);
    expect(запас.length, "страховка для браузеров без контейнерных запросов пропала").toBe(1);

    const всего = (текст.match(/@media[^{]*?(?:max|min)-width/g) ?? []).length;
    const внутриЗапаса = (запас[0].match(/@media[^{]*?(?:max|min)-width/g) ?? []).length;
    expect(
      всего - внутриЗапаса,
      "медиазапрос по ширине окна вернулся в чаты вне страховки — мерка снова не та",
    ).toBe(0);

    // Страховка обязана повторять ту же лестницу: иначе редкий браузер получит
    // экран без ступеней вовсе.
    const числаЗапаса = [...запас[0].matchAll(/(?:max|min)-width:\s*(\d+)px/g)]
      .map((m) => Number(m[1]))
      .sort((a, b) => a - b);
    expect(числаЗапаса).toEqual([1359, 1440, 1441, 1800, 1921]);
  });

  it("шапка ленты переключается по той же мерке, что и карточка", () => {
    /*
     * ⚠ КНОПКА «КЛИЕНТ» — ЕДИНСТВЕННЫЙ ВХОД В КАРТОЧКУ НА УЗКОМ МЕСТЕ. Карточку
     * убирает из потока React по ширине места; покажи кнопку медиазапросом по
     * окну — и при развёрнутой рельсе появится полоса окон 1360–1577, где
     * карточки в потоке уже нет, а кнопки ещё нет. Замер на стенде: при окне
     * 1440 и рельсе 218 кнопка имела `display: none`, хотя месту доставалось
     * 1222 и карточка уже была оверлеем.
     *
     * Здесь ветки НЕ разделены `@supports`: обе говорят «ниже порога —
     * показать», а узкое окно всегда означает узкое место (место = окно −
     * рельса ≤ окно), поэтому их объединение равно выводу контейнерного
     * запроса.
     */
    const вКонтейнере = блоки(
      THREAD_CSS,
      new RegExp(`@container\\s+lc-workspace\\s*\\(max-width:\\s*${NARROW_MAX}px\\)`),
    );
    for (const селектор of [".thread-header__card-toggle", ".thread-header__lead"]) {
      const нашлось = вКонтейнере.some((б) => б.includes(селектор));
      expect(
        нашлось,
        `${селектор} остался только на медиазапросе — переключится по окну, а не по месту`,
      ).toBe(true);
    }
  });

  it("React берёт ширину места замером, а не медиазапросом", () => {
    expect(ШИРИНА_TS, "наблюдатель размера пропал — замер снова стал догадкой").toContain(
      "new ResizeObserver",
    );
    expect(
      ШИРИНА_TS,
      "оценка до замера пропала — первый кадр снова рисуется по ширине окна целиком",
    ).toContain("window.innerWidth - рельса");
    expect(ШИРИНА_TS).toContain("RAIL_WIDTH_EXPANDED");
    expect(ШИРИНА_TS).toContain("RAIL_WIDTH_COLLAPSED");

    expect(CHATS_TSX).toContain("useWorkspaceWidth");
    expect(CHATS_TSX).toContain("узкоеМесто");
    expect(
      /NARROW_QUERY|useMediaQuery\(\s*NARROW/.test(CHATS_TSX),
      "узкая раскладка снова спрашивает медиазапрос — он не умеет вычесть рельсу",
    ).toBe(false);
    // Порог телефона по окну остаётся: по нему сворачивается сама рельса.
    expect(CHATS_TSX).toContain("MOBILE_QUERY");
  });

  it("ленте при трёх колонках остаётся не меньше 600px на каждой ступени", () => {
    /*
     * ⚠ ЧИСЛА РАЗБИРАЮТСЯ ИЗ САМОГО CSS, А НЕ ПЕРЕПИСАНЫ РЯДОМ. Подними
     * кто-нибудь колонку списка до 400 — проверка упадёт здесь, а не у
     * оператора. Порядок применения блоков повторяет каскад: базовое правило,
     * затем блоки файла сверху вниз, чьё условие подходит этой ширине места.
     *
     * Сверено со стендом 08.09 до пикселя: браузер на тех же ширинах места
     * даёт ровно эти же значения ленты, и при рельсе 218, и при 72.
     */
    for (const { место, лента } of [
      { место: NARROW_MAX, лента: 983 }, // две колонки
      { место: NARROW_MAX + 1, лента: 616 },
      { место: 1440, лента: 696 },
      { место: 1441, лента: 609 },
      { место: 1799, лента: 967 },
      { место: 1800, лента: 928 },
      { место: 1920, лента: 1048 },
      { место: 1921, лента: 1009 },
    ]) {
      expect(ленте(место), `на месте ${место} разбор CSS даёт другую ленту`).toBe(лента);
      if (!узкоеМесто(место)) {
        expect(
          ленте(место),
          `при трёх колонках на месте ${место} ленте остаётся ${ленте(место)}px`,
        ).toBeGreaterThanOrEqual(600);
      }
    }
  });

  it("сдвинуть порог по окну вместо смены мерки — это та же беда с другой стороны", () => {
    /*
     * Соблазн был «подвинуть 1359 на 1577» (1359 + 218). Проверка показывает,
     * почему это неверно: при СВЁРНУТОЙ рельсе три колонки перестали бы
     * появляться там, где на них есть место, — окно 1440 даёт месту 1368, и
     * ленте достаётся 624 пикселя.
     */
    const мест = (окно: number, рельса: number) => окно - рельса;

    // Развёрнутая рельса: 1440 — рабочий MacBook смены, месту тесно.
    expect(узкоеМесто(мест(1440, RAIL_WIDTH_EXPANDED))).toBe(true);
    // Свёрнутая рельса на том же окне: место есть, и три колонки обязаны быть.
    expect(узкоеМесто(мест(1440, RAIL_WIDTH_COLLAPSED))).toBe(false);
    // Тот самый «сдвинутый порог» 1577 отнял бы их у свёрнутой рельсы.
    expect(мест(1440, RAIL_WIDTH_COLLAPSED)).toBeGreaterThan(NARROW_MAX);
    expect(1440).toBeLessThan(NARROW_MAX + RAIL_WIDTH_EXPANDED);

    // Порог телефона остался по окну, и это не опечатка: разбор в breakpoints.ts.
    expect(MOBILE_MAX).toBe(767);
  });
});
