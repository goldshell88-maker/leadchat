const безКомментариев = (css: string) => css.replace(/\/\*[\s\S]*?\*\//g, " ");

/**
 * Все блоки `@media`/`@container`/`@supports` с этим условием, склеенные подряд.
 *
 * ⚠ ИМЕННО ВСЕ, А НЕ ПЕРВЫЙ, и скобки считаются, а не ищется первая закрывающая:
 * довод целиком записан у такого же помощника в `StatsAdaptive0509.test.tsx`.
 * Внутри `@supports` лежит вложенный `@media`, и `indexOf("}")` вернул бы конец
 * этого вложенного блока.
 */
function блок(css: string, заголовок: string): string {
  const чистый = безКомментариев(css);
  const куски: string[] = [];
  const маркер = `${заголовок} {`;
  for (let at = чистый.indexOf(маркер); at > -1; at = чистый.indexOf(маркер, at + 1)) {
    let depth = 0;
    for (let i = чистый.indexOf("{", at); i < чистый.length; i += 1) {
      if (чистый[i] === "{") depth += 1;
      else if (чистый[i] === "}") {
        depth -= 1;
        if (depth === 0) {
          куски.push(чистый.slice(at, i));
          break;
        }
      }
    }
  }
  expect(куски.length, `блок ${заголовок} не найден`).toBeGreaterThan(0);
  return куски.join("\n");
}

/** Тело правила. Селектор приходит уже как кусок регулярного выражения. */
function правило(css: string, селектор: string): string {
  const чистый = безКомментариев(css);
  const m = new RegExp(`(?:^|[\\n{])[ \\t]*${селектор}\\s*\\{`).exec(чистый);
  expect(m, `правило ${селектор} не найдено`).not.toBeNull();
  const at = m!.index + m![0].length;
  return чистый.slice(at, чистый.indexOf("}", at));
}

/** Есть ли вообще такое правило (для проверок «правило исчезло»). */
function естьПравило(css: string, селектор: string): boolean {
  return new RegExp(`(?:^|[\\n{])[ \\t]*${селектор}\\s*\\{`).test(безКомментариев(css));
}

/**
 * Тела ВСЕХ правил с этим селектором, склеенные подряд.
 *
 * ⚠ ПЕРВОЕ СОВПАДЕНИЕ ЗДЕСЬ ВРЁТ. `.op-grid__name` встречается в узком блоке
 * дважды: сначала вторым селектором в паре с `.op-grid__corner` (общий потолок
 * ширины), потом своим правилом. Сторож, взявший первое, читал чужое тело и
 * КРАСНЕЛ на верном коде — а это хуже, чем не проверять вовсе.
 */
function всеТела(css: string, селектор: string): string {
  const чистый = безКомментариев(css);
  const re = new RegExp(`(?:^|[\\n{])[ \\t]*${селектор}\\s*\\{`, "g");
  const тела: string[] = [];
  for (let m = re.exec(чистый); m; m = re.exec(чистый)) {
    const at = m.index + m[0].length;
    тела.push(чистый.slice(at, чистый.indexOf("}", at)));
  }
  expect(тела.length, `правило ${селектор} не найдено`).toBeGreaterThan(0);
  return тела.join("\n");
}

/** Тот же файл, но без блока — для проверок «широкий экран не тронут». */
function безБлока(css: string, заголовок: string): string {
  return безКомментариев(css).split(блок(css, заголовок)).join("\n");
}

