/* ═══════════════ 4. имя менеджера в карточном режиме ══════════════════════ */

/**
 * Вес селектора тройкой (id, класс/атрибут/псевдокласс, тег/псевдоэлемент).
 *
 * ⚠ ЭТО НЕ УКРАШЕНИЕ СТОРОЖА, А ЕГО СУТЬ. Прежняя правка карточного режима
 * лежала в файле ВЫШЕ базового правила и имела ту же силу (0,1,0) — при равной
 * силе побеждает последний, и медиазапрос на это не влияет. Сторож
 * `StatsAdaptive0509` сравнивал ТЕКСТ двух правил и потому три дня зеленел на
 * коде, которого в бою не было. Сравнивать надо силу.
 */
function вес(селектор: string): [number, number, number] {
  const чистый = селектор.replace(/\s+/g, " ").trim();
  const id = (чистый.match(/#[\w-]+/g) ?? []).length;
  const класс = (чистый.match(/\.[\w-]+|\[[^\]]+\]|:(?!:)[\w-]+/g) ?? []).length;
  const тег = (чистый.match(/(?:^| |>|\+|~)[a-z][\w-]*/g) ?? []).length;
  return [id, класс, тег];
}

const сильнее = (a: string, b: string) => {
  const [x, y] = [вес(a), вес(b)];
  for (let i = 0; i < 3; i += 1) {
    if (x[i] !== y[i]) return x[i] > y[i];
  }
  return false;
};

describe("Имя менеджера в карточке: правка наконец побеждает базовое правило", () => {
  const карточки = блок(stats, "@media (max-width: 900px)");

  /*
   * ЗАМЕР НА СТЕНДЕ ДО ПРАВКИ: окно 768, рельс 218 — кнопка 219,6 пикселя,
   * правый край 722 при внутреннем крае карточки 714. То же на 390 (356 против
   * 348) и на 900 (854 против 846). ПОСЛЕ: 714, 348 и 846 — край в край.
   * Высота строки-карточки не изменилась (327,5) и высота кнопки тоже (35,5).
   */
  it("правило карточного режима сильнее базового, а не просто раньше", () => {
    const карточное = ".managers.lc-table--cards .managers__name";
    expect(естьПравило(карточки, "\\.managers\\.lc-table--cards \\.managers__name")).toBe(true);
    expect(сильнее(карточное, ".managers__name")).toBe(true);
  });

  it("обнуляет боковые поля и оставляет вертикальные — это цель нажатия", () => {
    const тело = правило(карточки, "\\.managers\\.lc-table--cards \\.managers__name");
    // Первое значение — вертикаль (сохранена), второе — горизонталь (обнулена).
    expect(тело).toMatch(/margin:\s*calc\(var\(--lc-space-2\) \* -1\) 0/);
    expect(тело).toMatch(/padding:\s*var\(--lc-space-2\) 0/);
  });

  it("не оставляет прежнюю слабую копию — она снова проиграла бы молча", () => {
    expect(естьПравило(карточки, "\\.managers__name")).toBe(false);
  });

  it("базовое правило по-прежнему вычитает боковой отступ ячейки таблицы", () => {
    expect(правило(stats, "\\.managers__name")).toMatch(
      /margin:\s*-8px calc\(var\(--lc-space-2\) \* -1\)/,
    );
  });
});

