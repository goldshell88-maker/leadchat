import { describe, expect, it } from "vitest";
// @ts-expect-error — типов Node в проекте нет (tsconfig types: ["vite/client"]).
import { readFileSync } from "node:fs";
import { ПОРОГ_НИЗА, следующаяЗащёлка } from "@/features/chats/components/thread/threadStick";

/**
 * ДЛИННЫЙ ДИАЛОГ ОТКРЫВАЕТСЯ В САМОМ НИЗУ (жалоба владельца 30.08: «чат
 * открывается не в конце, а где-то чуть ниже середины»).
 *
 * ⚠ ПРИЧИНА ОКАЗАЛАСЬ НЕ В КАРТИНКАХ, хотя это первое, что приходит в голову.
 * У догрузки картинки нет события, которым она сбивала бы прижатие; версию
 * проверили и отбросили.
 *
 * Ломала односторонняя защёлка. Прежнее правило было в одну строку — «прижаты,
 * если до низа меньше порога» — и не различало двух разных причин того, что
 * низ отдалился: человек пролистал вверх ИЛИ содержимое выросло вниз при
 * неподвижной прокрутке. Второе случается на каждом открытии длинной ленты:
 * строки виртуализированы с оценкой 64 пикселя, реальные высоты приезжают
 * пачками, и на полусотне строк набегают сотни пикселей.
 *
 * Погаснув, защёлка убивала ОБА заслона разом: цикл прижатия выходил без
 * перепланировки таймера — то есть навсегда, — и наблюдатель размера тоже
 * замолкал. Лента оставалась там, куда успела встать.
 */

const ЭКРАН = 600;

/** Лента, прижатая к низу. */
function уНиза() {
  return { scrollTop: 2400, scrollHeight: 3000, clientHeight: ЭКРАН };
}

describe("Лента держится низа, пока человек её не увёл", () => {
  it("прижаты к низу — держимся", () => {
    expect(следующаяЗащёлка(true, 2400, уНиза())).toBe(true);
  });

  it("⚠ лента выросла вниз при неподвижной прокрутке — ДЕРЖИМСЯ", () => {
    /*
     * ГЛАВНАЯ ПРОВЕРКА ФАЙЛА. Виртуализатор перемерил строки, общая высота
     * выросла на 900 пикселей, прокрутка не двигалась. Прежнее правило здесь
     * гасило защёлку — и диалог замирал ниже середины.
     */
    const выросла = { scrollTop: 2400, scrollHeight: 3900, clientHeight: ЭКРАН };
    expect(
      следующаяЗащёлка(true, 2400, выросла),
      "рост ленты снова считается уходом человека — диалог замрёт не в конце",
    ).toBe(true);
  });

  it("человек пролистал вверх — отпускаем", () => {
    const вверх = { scrollTop: 1200, scrollHeight: 3000, clientHeight: ЭКРАН };
    expect(
      следующаяЗащёлка(true, 2400, вверх),
      "ленту будет дёргать вниз под руками у того, кто читает старое",
    ).toBe(false);
  });

  it("дрожь в пару пикселей уходом не считается", () => {
    const дрожь = { scrollTop: 2398, scrollHeight: 3900, clientHeight: ЭКРАН };
    expect(следующаяЗащёлка(true, 2400, дрожь)).toBe(true);
  });

  it("вернулись к низу — защёлка встаёт сама", () => {
    expect(следующаяЗащёлка(false, 1200, уНиза())).toBe(true);
  });

  it("движение вниз, но ещё далеко от низа — состояние не меняем", () => {
    const ниже = { scrollTop: 1800, scrollHeight: 3900, clientHeight: ЭКРАН };
    expect(следующаяЗащёлка(false, 1200, ниже)).toBe(false);
  });

  it("порог низа не выдуман на месте", () => {
    expect(ПОРОГ_НИЗА).toBeGreaterThan(0);
  });

  it("правило действительно подключено к ленте", () => {
    /*
     * ⚠ БЕЗ ЭТОГО ОСТАЛЬНЫЕ СТОРОЖИЛИ БЫ ЧИСТУЮ ФУНКЦИЮ, КОТОРУЮ НИКТО НЕ
     * ЗОВЁТ. Механизм, написанный и не подключённый, — самая частая поломка в
     * этом проекте.
     */
    const исходник = readFileSync(
      "src/features/chats/components/thread/ChatThreadPane.tsx",
      "utf-8",
    ) as string;
    expect(исходник, "обработчик прокрутки снова считает защёлку сам").toMatch(
      /stickToBottom\.current = следующаяЗащёлка\(/,
    );
    expect(исходник, "цикл прижатия снова умирает от разового «не сейчас»").toMatch(
      /if \(!stickToBottom\.current\) \{\s*\n\s*if \(triesLeft > 0\)/,
    );
  });
});
