// @ts-expect-error — типов Node в проекте нет (tsconfig types: ["vite/client"]),
// так же поступают соседние сторожа, читающие исходники (breakpoints.test.ts).
import { readFileSync } from "node:fs";
import { describe, expect, it } from "vitest";
import { MOBILE_MAX } from "@/shared/lib/breakpoints";
import { RAIL_WIDTH_COLLAPSED, RAIL_WIDTH_EXPANDED } from "@/shared/stores/railStore";
import { SettingsLayout } from "@/features/settings/SettingsLayout";
import { renderWithProviders } from "./render";

/**
 * СТОРОЖ ПОРОГА КОЛОНКИ РАЗДЕЛОВ «НАСТРОЕК» (08.09).
 *
 * БЕДА. Порог был записан как `@media (max-width: 900px)` — по ширине ОКНА.
 * Окну разделу не достаётся: слева стоит рельса приложения, развёрнутая по
 * умолчанию на 218 px, и ещё 220 забирает сама колонка разделов. Замер на
 * стенде (`.dump/мерка-нав.html`, боевой CSS, развёрнутая рельса), ДО:
 *
 *   окно 899 → содержимому 681   окно 901 → 463   ← окно шире на пиксель,
 *   окно 900 → содержимому 682   окно 902 → 464      места на 219 меньше
 *   окно 1024 → 586              окно 1120 → 682  ← только здесь вернулись
 *
 * 463 — меньше, чем раздел получает на самом узком настольном окне (550), и в
 * этой полосе на «Аккаунтах Авито» строка операторов резалась на 14 px, а бед
 * раскладки становилось 7 против 3 на окне 900.
 *
 * ПОСЛЕ (тот же стенд, та же сборка):
 *   рельс 218: 768→550 899→681 900→682 901→683 902→684 1024→806 1120→902
 *              1180→742 1200→762 1280→842 1440→1002
 *   рельс  72: 768→696 899→827 900→828 901→829 902→830 1024→732 1120→828
 *              1180→888 1200→908 1280→988 1440→1148
 * Наименьшее значение при обеих рельсах стоит на левом краю диапазона (550 и
 * 696), провала посередине больше нет.
 *
 * ⚠ ЧЕСТНАЯ ПОМЕТКА: ЭТОТ СТОРОЖ РАСКЛАДКУ НЕ МЕРЯЕТ И МЕРИТЬ НЕ МОЖЕТ.
 * В конфигурации тестов стоит `css: false` (vite.config.ts), а jsdom не считает
 * ни ширин, ни медиазапросов, ни контейнерных: `getBoundingClientRect()` вернёт
 * нули на любом окне. Именно поэтому беда и уехала в бой мимо 300+ сторожей.
 * Здесь проверяется ПРИЧИНА — чем меряется порог и из чего сложено его число, —
 * а результат померен в браузере и записан выше числами.
 */

const SETTINGS_CSS = "src/features/settings/settings.css";

function файл(путь: string): string {
  return readFileSync(путь, "utf-8") as string;
}

/** Текст без комментариев: разбор в шапке правила вправе называть что угодно. */
function безКомментариев(путь: string): string {
  return файл(путь).replace(/\/\*[\s\S]*?\*\//g, " ");
}

/** Тело запроса `@container`/`@media` целиком, со всеми вложенными правилами. */
function телоЗапроса(css: string, начало: number): string {
  const открыт = css.indexOf("{", начало);
  let глубина = 0;
  for (let i = открыт; i < css.length; i++) {
    if (css[i] === "{") глубина++;
    if (css[i] === "}") {
      глубина--;
      if (глубина === 0) return css.slice(открыт + 1, i);
    }
  }
  throw new Error("незакрытый запрос в " + SETTINGS_CSS);
}

/** Объявления одного селектора внутри тела запроса — в порядке написания. */
function объявления(тело: string, селектор: string): string {
  const rx = new RegExp(селектор.replace(/[.*+?^${}()|[\]\\]/g, "\\$&") + "\\s*\\{([^{}]*)\\}");
  return (rx.exec(тело)?.[1] ?? "").replace(/\s+/g, " ").trim();
}

/** Ширина колонки разделов из самого CSS: число подставлять руками нельзя. */
function ширинаКолонки(css: string): number {
  const тело = /\.settings-nav\s*\{([^{}]*)\}/.exec(css)?.[1] ?? "";
  return Number(/width:\s*(\d+)px/.exec(тело)?.[1] ?? NaN);
}

describe("Порог колонки разделов считается по месту, а не по окну (08.09)", () => {
  it("контейнером объявлена обёртка, и она есть в разметке", () => {
    /*
     * `@container` правит ПОТОМКОВ контейнера, а переключать надо направление
     * самой `.settings-page`. Значит контейнер обязан быть снаружи неё — иначе
     * запрос напишется, а сработать ему будет не на чем.
     */
    const css = безКомментариев(SETTINGS_CSS);
    const тело = /\.settings-frame\s*\{([^{}]*)\}/.exec(css)?.[1] ?? "";
    expect(тело, "обёртка перестала быть контейнером — мерить порог нечем").toMatch(
      /container-type:\s*inline-size/,
    );
    expect(тело, "у контейнера пропало имя — запрос ниже станет ничьим").toMatch(
      /container-name:\s*settings-frame/,
    );

    const { container } = renderWithProviders(<SettingsLayout />, { route: "/settings/profile" });
    const обёртка = container.querySelector(".settings-frame");
    expect(обёртка, "класса контейнера нет в разметке").not.toBeNull();
    expect(
      обёртка?.firstElementChild?.className,
      "`.settings-page` больше не лежит прямо внутри контейнера",
    ).toBe("settings-page");
  });

  it("решение принимает контейнерный запрос, а не окно", () => {
    const css = безКомментариев(SETTINGS_CSS);
    expect(css, "раскладка разделов снова решается только по ширине окна").toMatch(
      /@container\s+settings-frame\s*\(max-width:\s*\d+px\)/,
    );
    expect(css, "вернулся прежний порог по окну (900) — тот самый, из-за которого всё").not.toMatch(
      /@media\s*\(max-width:\s*900px\)/,
    );
  });

  it("число порога сложено из ширины рельсы и ширины самой колонки", () => {
    /*
     * ⚠ ПРОВЕРЯЕТСЯ НЕ ЧИСЛО, А ЕГО ВЫВОД. Порог обязан ехать за своими
     * слагаемыми: поменяется ширина рельсы (railStore) или колонки разделов —
     * прежнее число молча станет неверным, как это уже случилось с 900.
     *
     *   MOBILE_MAX + 1 − RAIL_WIDTH_COLLAPSED = 768 − 72 = 696
     *       столько достаётся разделу на самом узком настольном окне;
     *   696 + 220 (колонка) = 916
     *       столько нужно месту, чтобы после появления колонки содержимому
     *       осталось не меньше этих 696.
     */
    const css = безКомментариев(SETTINGS_CSS);
    const порог = Number(/@container\s+settings-frame\s*\(max-width:\s*(\d+)px\)/.exec(css)?.[1]);
    const самоеУзкоеМесто = MOBILE_MAX + 1 - RAIL_WIDTH_COLLAPSED;
    expect(порог + 1, "порог разошёлся с расчётом от рельсы и колонки").toBe(
      самоеУзкоеМесто + ширинаКолонки(css),
    );
    expect(ширинаКолонки(css), "ширина колонки разделов уехала мимо расчёта порога").toBe(220);
  });

  it("страховка по окну уже контейнерного запроса и не спорит с ним", () => {
    /*
     * Оба запроса живут в браузере ОДНОВРЕМЕННО и оба умеют только ВКЛЮЧАТЬ
     * строку. Значит страховка обязана быть подмножеством: сработала она —
     * обязан был сработать и контейнерный. Самая узкая рельса 72, поэтому при
     * окне ≤ порог+72 месту заведомо остаётся не больше порога.
     */
    const css = безКомментариев(SETTINGS_CSS);
    const порог = Number(/@container\s+settings-frame\s*\(max-width:\s*(\d+)px\)/.exec(css)?.[1]);
    const страховка = Number(/@media\s*\(max-width:\s*(\d+)px\)\s*\{\s*\.settings-page/.exec(css)?.[1]);
    expect(страховка, "страховки по окну не осталось вовсе").toBeGreaterThan(0);
    expect(
      страховка,
      "страховка шире контейнерного запроса: положит колонку строкой там, где места хватало",
    ).toBeLessThanOrEqual(порог + RAIL_WIDTH_COLLAPSED);
  });

  it("страховка и контейнерный запрос кладут раскладку ОДИНАКОВО", () => {
    /*
     * Две редакции одного решения расходятся на первой же правке. Здесь они
     * обязаны совпадать объявление в объявление, иначе браузер без поддержки
     * получит не ту строку, что боевой Chromium.
     */
    const css = безКомментариев(SETTINGS_CSS);
    const контейнер = телоЗапроса(css, css.indexOf("@container settings-frame"));
    const медиа = телоЗапроса(css, css.search(/@media\s*\(max-width:\s*\d+px\)\s*\{\s*\.settings-page/));
    for (const селектор of [".settings-page", ".settings-nav", ".settings-nav__item"]) {
      const а = объявления(контейнер, селектор);
      expect(а, `в контейнерном запросе пропало правило ${селектор}`).not.toBe("");
      // Полосу прокрутки страховка не прячет коммментарием, а объявлением —
      // сравниваем сами объявления, а не текст с пояснениями.
      expect(объявления(медиа, селектор), `страховка разошлась с запросом на ${селектор}`).toBe(а);
    }
  });

  it("развёрнутая рельса — та величина, ради которой всё и делалось", () => {
    /*
     * Числа замера в шапке сняты при 218 и 72. Разойдись ширина рельсы с этими
     * числами — и расчёт порога, и весь разбор выше говорят про другой экран.
     */
    expect(RAIL_WIDTH_EXPANDED, "ширина развёрнутой рельсы уехала — замеры выше устарели").toBe(218);
    expect(RAIL_WIDTH_COLLAPSED, "ширина свёрнутой рельсы уехала — расчёт порога устарел").toBe(72);
  });
});
