import { describe, expect, it } from "vitest";

/**
 * СТОРОЖ ОГРАНКИ ЛЕНТЫ И КОМПОЗЕРА (08.09).
 *
 * ЗАЧЕМ ОН. Огранка — это правки в третьем знаке: отступ на четыре пикселя,
 * зазор на восемь, интерлиньяж на два. Ни один существующий сторож их не
 * видит: раскладочный (`layout/`) ловит обрезку и переполнение, а не «стало
 * ли ровно», а jsdom-тесты меряют поведение, а не числа. Значит, любая
 * следующая правка вернёт разнобой молча — как уже возвращала его дважды.
 *
 * ЧТО ИМЕННО СТЕРЕЖЁТСЯ. Только то, что меняли, и только числами, которые
 * посчитаны в браузере на стенде `layout/`. Замеры записаны рядом с каждым
 * утверждением, чтобы правка «а поставлю-ка обратно» стоила разговора с
 * числом, а не с мнением.
 *
 * ⚠ ЗДЕСЬ ЖЕ СТЕРЕЖЁТСЯ ТО, ЧТО ТРОГАТЬ НЕЛЬЗЯ: `min-height` и `flex-shrink`
 * шапки, `sticky` композера, прокрутка ленты. Огранка соседствует с защитой
 * от переполнения, и сносить защиту заодно с разнобоем — самая дешёвая из
 * ошибок, которую тут можно сделать.
 *
 * `?raw` для CSS не годится: в тестовой среде Vite отдаёт по нему пустую
 * строку, и проверка была бы зелёной всегда (тот же довод — в tokenContrast).
 */
declare function require(id: string): { readFileSync(p: string, enc: string): string };

const ЛЕНТА = "src/features/chats/components/thread/chat-thread.css";
const КОМПОЗЕР = "src/features/chats/components/composer/composer.css";

const читать = (путь: string): string => require("node:fs").readFileSync(путь, "utf-8");

const CSS: Record<string, string> = { [ЛЕНТА]: читать(ЛЕНТА), [КОМПОЗЕР]: читать(КОМПОЗЕР) };

/** Текст файла без комментариев — чтобы число из разбора не считалось кодом. */
function безКомментариев(файл: string): string {
  return CSS[файл].replace(/\/\*[\s\S]*?\*\//g, "");
}

/** Тело правила ВНЕ медиазапросов: они действуют не на всех ширинах. */
function правило(файл: string, селектор: string): string {
  const текст = безКомментариев(файл);
  // Вырезаем содержимое @-блоков, оставляя правила верхнего уровня.
  let вне = "";
  let i = 0;
  while (i < текст.length) {
    if (текст.startsWith("@media", i) || текст.startsWith("@supports", i)) {
      let скобки = 0;
      let начали = false;
      while (i < текст.length) {
        if (текст[i] === "{") {
          скобки++;
          начали = true;
        } else if (текст[i] === "}") {
          скобки--;
          if (начали && скобки === 0) {
            i++;
            break;
          }
        }
        i++;
      }
      continue;
    }
    вне += текст[i];
    i++;
  }
  const где = вне.indexOf(`\n${селектор} {`);
  expect(где, `правила ${селектор} нет вовсе`).toBeGreaterThan(-1);
  const открыли = вне.indexOf("{", где);
  return вне.slice(открыли + 1, вне.indexOf("}", открыли));
}

describe("Огранка: числа в полях и зазорах — только со шкалы", () => {
  it.each([ЛЕНТА, КОМПОЗЕР])("в %s не осталось пиксельных литералов в padding/margin/gap", (файл) => {
    /*
     * Было 11 таких объявлений в ленте (2, 3, 1 и −2 пикселя) и 6 в композере
     * (1, 2, 5 пикселей). Ни одно из этих чисел шкале не принадлежит: она
     * идёт 2 / 4 / 8 / 12 / 16 / 24 / 32 (--lc-space-0…6).
     *
     * ДИВЕРСИЯ: вернуть `padding: 5px 8px` строке быстрого ответа — краснеет.
     */
    const литералы = безКомментариев(файл)
      .split("\n")
      .filter((строка) => /(padding|margin|gap)[a-z-]*\s*:[^;]*\d+px/.test(строка));
    expect(литералы, `осталось: ${литералы.join(" | ")}`).toHaveLength(0);
  });
});

describe("Огранка: шапка ленты", () => {
  it("вертикальное поле 12, и минимум высоты перестал быть растяжкой", () => {
    /*
     * Замер стенда (layout/, оба каркаса): при поле 8 натуральная высота
     * двухстрочной шапки — 62 на базовой шкале кегля и 66 на широкой
     * (≥1800px), то есть объявленные 64 были то растяжкой, то мимо. После
     * правки — 65 на ОБЕИХ шкалах (20 + 4 + 16 + 12 + 12 = 64 плюс 1px
     * нижней рамки), и высота шапки перестала зависеть от ширины окна.
     */
    const шапка = правило(ЛЕНТА, ".thread-header");
    expect(шапка).toMatch(/padding:\s*var\(--lc-space-3\)\s+var\(--lc-space-4\)/);

    // ⚠ ЗАЩИТА ОТ ПЕРЕПОЛНЕНИЯ. Замер 768×700 без них: содержимому шапки нужно
    // 210px, а нарисована она 64px — 147 пикселей строк легли поверх соседей.
    expect(шапка, "шапку опять разрешили сжимать").toMatch(/flex-shrink:\s*0/);
    expect(шапка, "минимум высоты снят").toMatch(/min-height:\s*64px/);
    expect(шапка, "перенос строк снят").toMatch(/flex-wrap:\s*wrap/);
  });

  it("обе строки шапки набраны целым интерлиньяжем", () => {
    /*
     * Множитель 1.5 давал имени 24 на базовой шкале и 25,5 на широкой, а
     * строке «канал · объявление» — 18 и 19,5: пол-пикселя, на которых текст
     * садится между растровыми строками и мылится. Замер после: 20 и 16 на
     * обеих шкалах.
     */
    expect(правило(ЛЕНТА, ".thread-header__name")).toMatch(/line-height:\s*20px/);
    expect(правило(ЛЕНТА, ".thread-header__sub")).toMatch(/line-height:\s*16px/);
  });

  it("правая часть шапки стоит на двух зазорах, а не на трёх", () => {
    /*
     * Замер 1920 до: чип статуса → стрелки 12, между стрелками 4, стрелки →
     * «…» 12. Три квадрата 30×30 одной геометрии читались как «пара» и
     * «одиночка». После: 4 внутри группы кнопок, 12 между группами (замер
     * 1920: 1773 и 1807 — стрелки, 1841 — «…»; 768: 533 / 567 / 601).
     *
     * ⚠ САМИХ СТРЕЛОК С 09.09 НЕТ (листание переехало на клавиши), но правило
     * соседства осталось и стережётся по-прежнему: в обёртке `.thread-pager`
     * живёт конвейер очереди «Следующий (N)», и без отрицательного поля «…»
     * отъезжает от него на шапочные 12 ровно как раньше.
     *
     * ДИВЕРСИЯ: снести правило — «…» отъезжает обратно на шапочные 12.
     */
    expect(правило(ЛЕНТА, ".thread-pager")).toMatch(/gap:\s*var\(--lc-space-1\)/);
    expect(правило(ЛЕНТА, ".thread-pager + .thread-actions__more")).toMatch(
      /margin-left:\s*calc\(var\(--lc-space-1\)\s*-\s*var\(--lc-space-3\)\)/,
    );
  });

  it("у обоих чипов шапки одно боковое поле", () => {
    // Было 8 у метки канала и 12 у плашки статуса: при равном тексте плашка
    // выглядела шире соседа. Замер 1440: ширина плашки 76,5 → 68,5.
    expect(правило(ЛЕНТА, ".thread-header__status")).toMatch(/padding:\s*0\s+var\(--lc-space-2\)/);
    expect(правило(ЛЕНТА, ".thread-header__lead")).toMatch(
      /padding:\s*var\(--lc-space-0\)\s+var\(--lc-space-2\)/,
    );

    // ⚠ ЗАЩИТА. Чип с числом внутри («В работе · ждёт 1 ч») не переносится:
    // «ждёт 1» без единицы читается как другое число.
    expect(правило(ЛЕНТА, ".thread-header__status")).toMatch(/white-space:\s*nowrap/);
  });
});

describe("Огранка: композер", () => {
  it("поле панели одно по кругу — 16", () => {
    // Было 12 по вертикали при 16 по горизонтали: подвал стоял на своей паре
    // чисел. Замер 1440: высота композера 142 → 154, поле ввода не двигалось.
    const композер = правило(КОМПОЗЕР, ".composer");
    expect(композер).toMatch(/padding:\s*var\(--lc-space-4\)\s+var\(--lc-space-4\)/);
    expect(композер).toMatch(/calc\(var\(--lc-space-4\)\s*\+\s*env\(safe-area-inset-bottom/);

    // ⚠ ЗАЩИТА. Замер 768×700 без `sticky`: низ композера на 37px ниже окна,
    // поля ввода и кнопки отправки на экране не остаётся вовсе.
    expect(композер, "композер отлепили от низа панели").toMatch(/position:\s*sticky/);
    expect(композер, "композеру вернули сжатие").toMatch(/flex:\s*none/);
  });

  it("поле ввода не перекошено по вертикали", () => {
    // Было 8 / 8 / 4: низ короче верха на шаг, и плашка «Напишите сообщение»
    // сидела выше оптического центра рамки. Замер 1440: высота 79 → 83.
    const поле = правило(КОМПОЗЕР, ".composer__field");
    expect(поле).toMatch(/padding:\s*var\(--lc-space-2\);/);
    expect(поле, "нижний предел высоты поля снят").toMatch(/min-height:\s*56px/);
  });

  it("подвал и поле ввода идут от одной кромки", () => {
    /*
     * Подвал стоял на собственном боковом поле 4 при поле панели 16: замер
     * 1440 до — переключатель начинался на 465, рамка поля на 461; подсказка
     * кончалась на 1403, рамка на 1407. После: 461 и 1407 у обоих.
     */
    expect(правило(КОМПОЗЕР, ".composer__footer")).not.toMatch(/padding:/);
  });

  it("клавиша подсказки — поля со шкалы и общий радиус", () => {
    // Было `padding: 1px 5px` и радиус 6 — оба мимо шкалы, и капсула сидела
    // на пиксель выше строки. Замер 1440: 39,2×18 → 37,2×20.
    const клавиша = правило(КОМПОЗЕР, ".composer__hint kbd");
    expect(клавиша).toMatch(/padding:\s*var\(--lc-space-0\)\s+var\(--lc-space-1\)/);
    expect(клавиша).toMatch(/border-radius:\s*var\(--lc-radius-sm\)/);
  });
});

describe("Огранка: вес и контраст второстепенного текста", () => {
  it("имя автора набрано одним весом во всех трёх местах", () => {
    /*
     * Полужирным в ленте было помечено многое: подпись автора в пузыре, имя в
     * цитате, имя в плашке ответа, чип канала. Когда помечено всё — не
     * помечено ничего. 600 остался там, ради чего на ленту смотрят: имя
     * клиента в шапке, просроченный чип, подсвеченный телефон.
     */
    for (const селектор of [".msg__author", ".msg__quote-who", ".composer__replying-who"]) {
      expect(правило(ЛЕНТА, селектор), селектор).toMatch(/font-weight:\s*var\(--lc-fw-medium\)/);
    }
    expect(правило(ЛЕНТА, ".thread-header__lead")).toMatch(/font-weight:\s*var\(--lc-fw-medium\)/);
    // ...а имя клиента — по-прежнему 600.
    expect(правило(ЛЕНТА, ".thread-header__name")).toMatch(/font-weight:\s*var\(--lc-fw-semibold\)/);
  });

  it("подпись служебного сообщения тише кеглем, а не прозрачностью", () => {
    /*
     * Посчитано на живых токенах: text-3 (#949e97) на bg-2 (#1a221e) — 5.88:1;
     * те же чернила при opacity 0.75 — 3.93:1 в тёмной теме и 3.74:1 в
     * светлой, то есть ниже нормы 4.5:1 у обеих.
     */
    const подпись = правило(ЛЕНТА, ".msg__system-source");
    expect(подпись, "прозрачность вернулась — контраст снова 3.93:1").not.toMatch(/opacity:/);
    expect(подпись).toMatch(/font-size:\s*var\(--lc-fz-micro\)/);
  });

  it("погашенное событие гаснет, но остаётся читаемым", () => {
    /*
     * При 0,55 те же чернила давали 2.75:1 в тёмной теме и 2.47:1 в светлой —
     * вдвое ниже нормы. 0,85 — первая ступень, проходящая 4.5:1 в ОБЕИХ темах
     * (4.64:1 и 4.68:1). Ниже опускать нечего: строка перестаёт читаться.
     */
    const погашенное = правило(ЛЕНТА, '.thread-events__item[data-cancelled="true"]');
    const число = /opacity:\s*([\d.]+)/.exec(погашенное)?.[1];
    expect(число, "прозрачности нет — гаснуть нечему").toBeDefined();
    expect(Number(число)).toBeGreaterThanOrEqual(0.85);
  });
});
