import { describe, expect, it } from "vitest";

/**
 * СТОРОЖ ШАПКИ ЛЕНТЫ: имя клиента и время ожидания не исчезают на узком окне.
 *
 * ЗАЧЕМ ФАЙЛОМ СТИЛЕЙ, А НЕ РЕНДЕРОМ. Оба дефекта нашли ЗАМЕРОМ в браузере,
 * а не чтением кода, и повторить их рендером нельзя: в jsdom раскладки нет
 * вовсе, любые ширины там равны нулю, и тест зеленел бы при любой вёрстке.
 * Поэтому проверяем сами правила — те, отсутствие которых и давало замеры:
 *
 *  * 768px: `.thread-header__info` — ШИРИНА 0 (ни имени клиента, ни аккаунта,
 *    ни ответственного), «Закрыть» — 18×26, то есть зелёный овал без текста,
 *    «Клиент» — x 701–769 при правом крае шапки 755, кнопка за окном. Причина:
 *    перенос строки был включён только медиазапросом «до 767px», ровно на
 *    пиксель мимо; блоку с именем нечего было противопоставить кнопкам.
 *  * 1440px с ответственным: `.thread-header__wait` — 42×36 вместо 42×18,
 *    «ждёт 1 ч» разорвано на «ждёт 1» и «ч», шапка выросла с 64 до 77.
 *
 * `?raw` для CSS не годится: в тестовой среде Vite отдаёт по нему пустую
 * строку, и проверка была бы зелёной всегда (тот же довод — в tokenContrast).
 */
declare function require(id: string): { readFileSync(p: string, enc: string): string };

const CSS = require("node:fs").readFileSync(
  "src/features/chats/components/thread/chat-thread.css",
  "utf-8",
);

/** Разметка шапки — нужна проверке «класс правда надет, а не только описан». */
const TSX = require("node:fs").readFileSync(
  "src/features/chats/components/thread/ChatThreadPane.tsx",
  "utf-8",
);

/** Тело правила ВНЕ медиазапросов: они действуют не на всех ширинах. */
function baseRule(selector: string): string {
  let depth = 0;
  let out = "";
  let i = 0;
  // Вырезаем содержимое всех @-блоков, оставляя только правила верхнего уровня.
  while (i < CSS.length) {
    if (CSS.startsWith("@media", i) || CSS.startsWith("@supports", i)) {
      let braces = 0;
      let started = false;
      while (i < CSS.length) {
        if (CSS[i] === "{") {
          braces++;
          started = true;
        } else if (CSS[i] === "}") {
          braces--;
          if (started && braces === 0) {
            i++;
            break;
          }
        }
        i++;
      }
      continue;
    }
    if (CSS[i] === "{") depth++;
    if (CSS[i] === "}") depth--;
    out += CSS[i];
    i++;
  }
  expect(depth).toBe(0); // разбор не разъехался по скобкам

  const at = out.indexOf(`\n${selector}`);
  if (at === -1) return "";
  const open = out.indexOf("{", at);
  const close = out.indexOf("}", open);
  return out.slice(open + 1, close);
}

describe("Шапка ленты — правила, без которых она ломается на узком окне", () => {
  it("переносится на ЛЮБОЙ ширине, а не только на телефоне", () => {
    // Медиазапрос «до 767px» промахивался мимо 768–1023, где ленте достаётся
    // столько же места, сколько на телефоне: список уже занял свои 340.
    expect(baseRule(".thread-header")).toMatch(/flex-wrap:\s*wrap/);
  });

  it("у блока с именем клиента есть нижний предел ширины", () => {
    const info = baseRule(".thread-header__info");
    // `flex: 1` без базиса сжимается до нуля — именно это и давало width = 0.
    expect(info).toMatch(/flex:\s*1\s+1\s+\d+px/);
    expect(info).not.toMatch(/flex:\s*1\s*;/);
  });

  it("кнопки шапки не сжимаются в овал без текста", () => {
    expect(baseRule(".thread-header__next")).toMatch(/flex:\s*none/);
  });

  it("чип статуса с ожиданием не переносится и не сжимается", () => {
    /*
     * Тот же замер, что был у отдельного «ждёт N»: 42×36 вместо 42×18,
     * «ждёт 1 ч» разорвано на «ждёт 1» и «ч», шапка выросла с 64 до 77.
     * С 12 августа ожидание живёт ВНУТРИ единственного чипа статуса («В
     * работе · ждёт 1 ч»), но опасность прежняя: число, оторванное от
     * единицы измерения, читается как другое число.
     */
    const chip = baseRule(".thread-header__status");
    expect(chip).toMatch(/white-space:\s*nowrap/);
    expect(chip).toMatch(/flex:\s*none/);
  });

  it("цвет статуса берётся из общего словаря, а не пишется здесь шестой копией", () => {
    // docs/38 §1: цвета статуса живут в `.lc-status-chip` (app/lc-base.css).
    // В этом самом файле уже лежал мёртвый `.thread-status` с собственным
    // набором веток — он пережил свою разметку и полгода врал, что пилюля
    // статуса в ленте есть.
    const chip = baseRule(".thread-header__status");
    expect(chip).not.toMatch(/--lc-status-/);
    expect(TSX).toContain("lc-status-chip");
  });

  it("тревожная заливка просрочки весомее цвета статуса, а не вровень с ним", () => {
    /*
     * `.lc-status-chip[data-status="in_progress"]` и
     * `.thread-header__status[data-late="true"]` — одинаковой вескости (класс
     * плюс атрибут). При равенстве спор решает порядок файлов в сборке, а он
     * складывается из порядка импортов и меняется от любой перестановки: чип
     * просроченного диалога переставал бы желтеть молча и не всегда. Поэтому
     * в селекторе стоят ОБА класса.
     */
    expect(CSS).toMatch(/\.thread-header__status\.lc-status-chip\[data-late="true"\]/);
  });

  it("город в метке канала не обрезается — уступает место сосед", () => {
    /*
     * ⚠ ЭТА ПРОВЕРКА РАНЬШЕ ТРЕБОВАЛА ОБРАТНОГО («строка фактов остаётся одной
     * строкой»), и требование было ошибкой — оно и держало дефект.
     *
     * Метку правили дважды, и оба раза меняли одну потерю на другую, потому что
     * делили ОДНУ строку между двумя надписями: 19.08 метка не сжималась и
     * съедала соседа в ноль; 23.08 метку научили сжиматься — и обрезаться стал
     * ГОРОД, он в метке последний. Снимки владельца 25.08: «партнёр 7 · источник
     * В43 · город Од…», на узкой шапке «партнёр 7 · источ…».
     *
     * Решение — вторая строка, а не выбор пострадавшего. Кто уступает, решено по
     * цене ошибки: обрезанный город стоит зря потраченного выезда, а название
     * объявления видно из самой переписки и лежит в `title`.
     */
    const sub = baseRule(".thread-header__sub");
    expect(sub).toMatch(/flex-wrap:\s*wrap/);

    const lead = baseRule(".thread-header__lead");
    // `flex: 0 0 auto` — метка не сжимается НИКОГДА: именно сжатие и резало город.
    expect(lead).toMatch(/flex:\s*0\s+0\s+auto/);
    // ...но и шире шапки не становится: на совсем узком экране обрежется САМА,
    // многоточием, а не будет срезана `overflow` родителя без всякого знака.
    expect(lead).toMatch(/max-width:\s*100%/);
    expect(lead).toMatch(/text-overflow:\s*ellipsis/);

    // Сосед по-прежнему умеет сжиматься — иначе перенос ему не поможет.
    expect(baseRule(".thread-header__sub > *")).toMatch(/min-width:\s*0/);
  });

  it("перенос стоит одной строки, а не рассыпается в столбик", () => {
    /*
     * Разрешив перенос, легко получить шапку, растущую на каждое длинное
     * название. Держит это `.lc-truncate` на строке «канал · объявление»: у неё
     * `white-space: nowrap`, значит она занимает ровно одну строку и обрезается
     * многоточием. Проверяем, что класс правда надет, а не только подразумевается.
     */
    expect(TSX).toContain('className="lc-truncate"');
  });
});
