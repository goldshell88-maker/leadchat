import { describe, expect, it } from "vitest";
import { подогнатьРегистр, продолжаетПредложение } from "@/features/templates/склейка";
import { длясравнения, содержит } from "@/features/templates/поиск";

/**
 * ДВА ДЕФЕКТА БЫСТРЫХ ОТВЕТОВ, КОТОРЫЕ ВИДИТ КЛИЕНТ (замеры боя 03.09).
 */

describe("регистр на стыке", () => {
  /*
   * ⚠ ЗА ТРИДЦАТЬ СУТОК КЛИЕНТАМ УШЛО 386 ТАКИХ СООБЩЕНИЙ, 90 ЗА ОДИН ДЕНЬ.
   * «Хорошо, Когда вам будет удобно меня принять?» отправлено 84 раза против
   * 50 раз правильного варианта. Отозвать сообщение в Авито нечем.
   */
  it("посреди фразы первая буква понижается", () => {
    expect(подогнатьРегистр("Хорошо, ", "Когда вам будет удобно?")).toBe(
      "когда вам будет удобно?",
    );
    expect(подогнатьРегистр("по ", "По цене так сразу не скажу")).toBe(
      "по цене так сразу не скажу",
    );
  });

  it("в начале сообщения заглавная остаётся", () => {
    expect(подогнатьРегистр("", "Здравствуйте")).toBe("Здравствуйте");
    expect(подогнатьРегистр("   ", "Здравствуйте")).toBe("Здравствуйте");
  });

  it("после конца предложения заглавная остаётся", () => {
    expect(подогнатьРегистр("Понял вас. ", "Когда принять?")).toBe("Когда принять?");
    expect(подогнатьРегистр("Готово! ", "Когда принять?")).toBe("Когда принять?");
    expect(подогнатьРегистр("Точно? ", "Когда принять?")).toBe("Когда принять?");
    // Перенос строки — тоже начало.
    expect(подогнатьРегистр("Первая строка\n", "Когда принять?")).toBe("Когда принять?");
  });

  it("аббревиатуру не трогаем", () => {
    /*
     * ⚠ ЕДИНСТВЕННОЕ ИСКЛЮЧЕНИЕ, КОТОРОЕ ОПРЕДЕЛЯЕТСЯ НАДЁЖНО. Имя собственное
     * от начала предложения в тексте не отличить, а аббревиатура видна по
     * форме. «тв не включается» вместо «ТВ не включается» — это уже не
     * вежливость, а ошибка в названии предмета.
     */
    expect(подогнатьРегистр("Скажите, ", "ТВ не включается?")).toBe("ТВ не включается?");
    expect(подогнатьРегистр("Скажите, ", "СМС придёт на телефон")).toBe("СМС придёт на телефон");
  });

  it("не буква — менять нечего", () => {
    expect(подогнатьРегистр("Хорошо, ", "«Ремонт» сделаем")).toBe("«Ремонт» сделаем");
    expect(подогнатьРегистр("Хорошо, ", "1500 рублей")).toBe("1500 рублей");
  });

  it("предикат отличает продолжение от начала", () => {
    expect(продолжаетПредложение("Хорошо, ")).toBe(true);
    expect(продолжаетПредложение("Хорошо ")).toBe(true);
    expect(продолжаетПредложение("Хорошо. ")).toBe(false);
    expect(продолжаетПредложение("")).toBe(false);
  });
});

describe("сравнение букв при поиске", () => {
  /*
   * ⚠ «Ё» ЛОМАЛА ПОДСКАЗКУ МОЛЧА. За тридцать суток в исходящих «еще
   * требуется» 373 раза против «ещё требуется» 73; «все в наличии» — 197
   * против 4. То есть почти всегда человек набирал вариант, по которому
   * подсказка не отвечала.
   */
  it("«еще» находит «ещё» и наоборот", () => {
    expect(содержит("Вам помощь ещё требуется?", "еще")).toBe(true);
    expect(содержит("Вам помощь еще требуется?", "ещё")).toBe(true);
    expect(содержит("У вас всё в наличии уже есть?", "все в наличии")).toBe(true);
  });

  it("регистр и лишние пробелы не мешают", () => {
    expect(содержит("Здравствуйте", "ЗДР")).toBe(true);
    expect(содержит("По  объёму   работы", "по объему работы")).toBe(true);
  });

  it("пустой запрос подходит всему", () => {
    expect(содержит("что угодно", "")).toBe(true);
    expect(содержит("что угодно", "   ")).toBe(true);
  });

  it("нормализация не меняет сам текст заготовки", () => {
    /*
     * Правило про буквы поиска не имеет права менять то, что прочитает
     * клиент: «ё» остаётся в отправляемом тексте.
     */
    expect(длясравнения("Ещё")).toBe("еще");
    expect("Вам помощь ещё требуется?").toContain("ё");
  });
});
