/**
 * Куда ведут стрелки выбора дня и когда «вперёд» гаснет.
 *
 * ЧТО БЫЛО. Шаг считался от конца периода в обе стороны, и из недельного
 * периода «‹» уводило в ПОЗАВЧЕРА, перепрыгнув последний день недели, а «›»
 * упиралось в завтра и молча ничего не делало. Нажатие без последствий человек
 * читает как поломку — и жмёт ещё раз.
 *
 * ЧТО СТАЛО. Из многодневного периода любое нажатие — вход в режим дня на
 * последнем дне периода; дальше стрелки шагают сутками. Дальше сегодняшнего
 * дня не пускаем, и ровно в этом случае кнопка погашена: «куда ведёт» и
 * «горит ли» считает одна функция.
 */
import { describe, expect, it } from "vitest";
import { dayForwardBlocked, dayStepTarget } from "@/features/stats/lib/dayStep";

const СЕГОДНЯ = "2026-08-22";
const НЕДЕЛЯ = { dateFrom: "2026-08-16", dateTo: "2026-08-22" };
const ДЕНЬ = (d: string) => ({ dateFrom: d, dateTo: d });

describe("шаг по суткам на почасовом графике", () => {
  it("из недели «назад» открывает ПОСЛЕДНИЙ день периода, а не позавчера", () => {
    expect(dayStepTarget(НЕДЕЛЯ, -1, СЕГОДНЯ)).toBe("2026-08-22");
  });

  it("из недели «вперёд» тоже открывает последний день — это вход в режим дня", () => {
    expect(dayStepTarget(НЕДЕЛЯ, 1, СЕГОДНЯ)).toBe("2026-08-22");
  });

  it("из одного дня стрелки шагают сутками", () => {
    expect(dayStepTarget(ДЕНЬ("2026-08-20"), -1, СЕГОДНЯ)).toBe("2026-08-19");
    expect(dayStepTarget(ДЕНЬ("2026-08-20"), 1, СЕГОДНЯ)).toBe("2026-08-21");
  });

  it("дальше сегодняшнего дня хода нет", () => {
    expect(dayStepTarget(ДЕНЬ(СЕГОДНЯ), 1, СЕГОДНЯ)).toBeNull();
  });

  it("границу месяца шаг переходит календарно", () => {
    expect(dayStepTarget(ДЕНЬ("2026-09-01"), -1, "2026-09-05")).toBe("2026-08-31");
    expect(dayStepTarget(ДЕНЬ("2026-08-31"), 1, "2026-09-05")).toBe("2026-09-01");
  });

  it("«вперёд» погашено ровно тогда, когда ведёт в никуда", () => {
    expect(dayForwardBlocked(ДЕНЬ(СЕГОДНЯ), СЕГОДНЯ)).toBe(true);
    expect(dayForwardBlocked(ДЕНЬ("2026-08-21"), СЕГОДНЯ)).toBe(false);
    // Из недели вперёд идти ЕСТЬ куда: нажатие открывает последний день.
    expect(dayForwardBlocked(НЕДЕЛЯ, СЕГОДНЯ)).toBe(false);
  });

  it("период, целиком лежащий в прошлом, ходит внутри себя", () => {
    const прошлое = { dateFrom: "2026-07-01", dateTo: "2026-07-07" };
    expect(dayStepTarget(прошлое, 1, СЕГОДНЯ)).toBe("2026-07-07");
    expect(dayStepTarget(ДЕНЬ("2026-07-07"), 1, СЕГОДНЯ)).toBe("2026-07-08");
  });
});
