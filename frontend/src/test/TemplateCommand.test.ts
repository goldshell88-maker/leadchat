import { describe, expect, it } from "vitest";
import { найтиКоманду } from "@/features/templates/команда";

describe("«/команда» в поле ввода", () => {
  it("«/» в начале пустого поля — это команда", () => {
    expect(найтиКоманду("/", 1)).toEqual({ от: 0, запрос: "" });
  });

  it("набранное после «/» и есть запрос", () => {
    expect(найтиКоманду("/цена", 5)).toEqual({ от: 0, запрос: "цена" });
  });

  it("команда открывается и посреди сообщения — после пробела", () => {
    const текст = "Хорошо, /выезд";
    expect(найтиКоманду(текст, текст.length)).toEqual({ от: 8, запрос: "выезд" });
  });

  it("косая посреди слова командой НЕ считается", () => {
    /*
     * ⚠ ЭТО ЖИВЫЕ СЛУЧАИ, А НЕ ПРИДУМАННЫЕ: адреса и часы работы диспетчеры
     * пишут каждый день. Открывайся список на каждой такой косой — он мешал бы
     * ровно тем, кто печатает быстро.
     */
    for (const текст of ["Ленина 5/2", "и/или", "09:00/18:00"]) {
      expect(найтиКоманду(текст, текст.length), текст).toBeNull();
    }
  });

  it("перевод строки команду обрывает", () => {
    const текст = "/цена\nвторая строка";
    expect(найтиКоманду(текст, текст.length)).toBeNull();
  });

  it("смотрим НАЗАД от каретки, а не на весь текст", () => {
    // Каретка стоит перед «/»: команды под ней ещё нет.
    expect(найтиКоманду("текст /цена", 3)).toBeNull();
    // Каретка внутри команды: запрос — только до неё.
    expect(найтиКоманду("/цена", 3)).toEqual({ от: 0, запрос: "це" });
  });

  it("длинный хвост командой не считается", () => {
    // Забытая открытой команда не должна тянуться через всё сообщение.
    const текст = "/" + "я".repeat(80);
    expect(найтиКоманду(текст, текст.length)).toBeNull();
  });

  it("пробелы внутри запроса разрешены — названия из двух слов", () => {
    const текст = "/куда подъехать";
    expect(найтиКоманду(текст, текст.length)).toEqual({ от: 0, запрос: "куда подъехать" });
  });
});
