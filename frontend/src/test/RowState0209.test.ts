import { describe, expect, it } from "vitest";
import { ждётНас, waitingFor } from "@/shared/lib/waiting";

/**
 * ТРИ СОСТОЯНИЯ СТРОКИ, РАЗЛИЧИМЫЕ ГЛАЗОМ (жалоба владельца 02.09):
 * «в какие я просто зашёл посмотреть, в какие ответил — всё сливается».
 *
 * Здесь стережётся ПРЕДИКАТ, из которого состояние выводится. Разница между
 * ним и подписью ожидания стоила боевого дефекта: подпись молчит первую минуту
 * («ждёт 0 мин» — шум), и строка со свежайшим сообщением клиента приглушалась
 * как отвеченная — притом стоя ПЕРВОЙ, список отсортирован по свежести.
 */
const СЕЙЧАС = Date.parse("2026-09-02T12:00:00Z");
const строка = (waiting_since: string | null | undefined, over = {}) => ({
  status: "in_progress",
  waiting_since,
  unread_count: 0,
  last_message_at: "2026-09-02T11:59:40Z",
  ...over,
});

describe("ждёт ли клиент — по полю, а не по подписи", () => {
  it("написал полминуты назад: подписи нет, но ЖДЁТ", () => {
    const свежий = строка("2026-09-02T11:59:40Z");
    expect(waitingFor(свежий, СЕЙЧАС)).toBeNull(); // «ждёт 0 мин» не пишем
    expect(ждётНас(свежий)).toBe(true); // но приглушать строку нельзя
  });

  it("прочитан и не отвечен — по-прежнему ждёт, хотя непрочитанных нет", () => {
    // ⚠ ИМЕННО ЭТОТ СЛУЧАЙ И ЕСТЬ ЖАЛОБА. Замер боя 02.09: у одного
    // диспетчера таких восемь из одиннадцати ждущих.
    expect(ждётНас(строка("2026-09-02T11:00:00Z", { unread_count: 0 }))).toBe(true);
  });

  it("мы ответили — не ждёт", () => {
    expect(ждётНас(строка(null))).toBe(false);
  });

  it("закрытый — не ждёт, что бы ни стояло в поле", () => {
    expect(ждётНас(строка("2026-09-02T11:00:00Z", { status: "closed" }))).toBe(false);
  });

  it("строка из старого кэша без поля — запасной путь по непрочитанным", () => {
    // `undefined` ≠ `null`: первое значит «поля нет», второе — ответ сервера
    // «не ждёт». Подменять отсутствие догадкой нельзя в обе стороны.
    expect(ждётНас(строка(undefined, { unread_count: 2 }))).toBe(true);
    expect(ждётНас(строка(undefined, { unread_count: 0 }))).toBe(false);
  });
});
