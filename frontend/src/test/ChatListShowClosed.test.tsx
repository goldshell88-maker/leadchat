import { beforeEach, describe, expect, it, vi } from "vitest";
import { fetchConversations } from "@/features/chats/api";
import { matchesTab } from "@/platform/warmup";
import { jsonResponse } from "./helpers";

/**
 * «ВСЯ ИСТОРИЯ ЦЕЛИКОМ» ВО ВКЛАДКЕ «ВСЕ» (требование заказчика 13 августа).
 *
 * ЧТО БЫЛО. Вся импортированная история Авито заводится закрытой, а `tab=all` без
 * явного статуса режет закрытые на сервере. Значит «вся история» ≡ архив ≡ ровно то
 * множество, которое вкладка отсекала. Попасть в него из «Чатов» можно было одним
 * способом — кнопкой в ПУСТОМ состоянии, то есть только когда работы не осталось.
 *
 * ⚠ ПОЧЕМУ ВЫКЛЮЧЕНО ПО УМОЛЧАНИЮ. 454 тысячи закрытых против десятков открытых, а
 * «Все» — вкладка по умолчанию у владельца и руководителя. Включи архив всегда — и
 * первый экран после входа станет архивом: список сортируется по последнему
 * сообщению, и закрытое сегодня встанет в верхние строки вперемешку с рабочим.
 * Просили, чтобы историю МОЖНО БЫЛО посмотреть, а не чтобы она заслонила работу.
 */

describe("Показывать закрытые: что уходит на сервер", () => {
  let fetchMock: ReturnType<typeof vi.fn>;

  beforeEach(() => {
    fetchMock = vi.fn(async () => jsonResponse(200, { items: [], total: 0 }));
    vi.stubGlobal("fetch", fetchMock);
  });

  function запрос(): URLSearchParams {
    const url = String(fetchMock.mock.calls[0][0]);
    return new URL(url, "http://x").searchParams;
  }

  it("вкладка «Все» всегда включает архив (решение владельца 17.08)", async () => {
    await fetchConversations({ tab: "all" }, 0);
    expect(запрос().get("tab")).toBe("any");
  });

  it("с переключателем уходит режим «везде, включая закрытые»", async () => {
    /**
     * ⚠ ТОТ ЖЕ `any`, ЧТО У ПОИСКА, а не новый параметр. На сервере `any` уже
     * означает ровно это и покрыт тестами; второй способ сказать одно и то же
     * разъехался бы с первым на первой правке условия вкладок.
     */
    await fetchConversations({ tab: "all", withClosed: true }, 0);
    expect(запрос().get("tab")).toBe("any");
  });

  it("поиск по-прежнему ищет везде — переключатель ему не нужен", async () => {
    await fetchConversations({ tab: "mine", q: "Ольга" }, 0);
    expect(запрос().get("tab")).toBe("any");
  });
});

describe("Показывать закрытые: офлайн-снимок десктопа", () => {
  /**
   * ⚠ ПРАВИЛО ВКЛАДОК ПРОДУБЛИРОВАНО В `warmup.ts` НАМЕРЕННО: снимок рисуется ДО
   * первого ответа сервера. Забудь мы там про переключатель — список моргнул бы и
   * подменился: сперва без архива из кэша, потом с архивом от сервера. Со стороны
   * это выглядит как «интерфейс сам себя переписал».
   */
  const закрытый = { id: "c1", status: "closed" } as never;
  const открытый = { id: "c2", status: "new" } as never;

  it("без переключателя закрытых в снимке нет", () => {
    expect(matchesTab(закрытый, { tab: "all" }, "u1")).toBe(false);
    expect(matchesTab(открытый, { tab: "all" }, "u1")).toBe(true);
  });

  it("с переключателем в снимке есть и закрытые", () => {
    expect(matchesTab(закрытый, { tab: "all", withClosed: true }, "u1")).toBe(true);
    expect(matchesTab(открытый, { tab: "all", withClosed: true }, "u1")).toBe(true);
  });
});
