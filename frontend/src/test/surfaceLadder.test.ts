/** Все .css продукта — для сторожей, проверяющих правило по всему дереву. */
function cssFiles(dir = "src"): string[] {
  const out: string[] = [];
  for (const item of readdirSync(dir, { withFileTypes: true })) {
    const p = `${dir}/${item.name}`;
    if (item.isDirectory()) out.push(...cssFiles(p));
    else if (item.name.endsWith(".css")) out.push(p);
  }
  return out;
}

function rule(path: string, selector: string): string {
  const css = (readFileSync(path, "utf-8") as string).replace(/\/\*[\s\S]*?\*\//g, " ");
  const at = css.indexOf(`\n${selector} {`);
  expect(at, `${path}: правило ${selector} не найдено`).toBeGreaterThan(-1);
  return css.slice(at, css.indexOf("}", at));
}

