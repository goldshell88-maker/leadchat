  it("радиус задаётся только токеном", () => {
    const плохие: string[] = [];
    for (const файл of cssFiles()) {
      const строки = (readFileSync(файл, "utf-8") as string)
        .replace(/\/\*[\s\S]*?\*\//g, "")
        .split("\n");
      for (const [i, стр] of строки.entries()) {
        const m = /border-radius:\s*([^;]+);/.exec(стр);
        if (!m) continue;
        const v = m[1].trim();
        if (v.includes("var(") || v === "50%" || v === "0" || v === "2px") continue;
        if (v === "inherit") continue;
        // Односторонняя полоска: четыре значения, каждое «0» или «Npx».
        // «0 3px 3px 0» — скруглён только правый край, это форма, а не радиус.
        if (/^(0|\d+px)(\s+(0|\d+px)){3}$/.test(v)) continue;
        плохие.push(`${файл}:${i + 1} — ${v}`);
      }
    }
    expect(плохие, `радиус мимо токенов:\n${плохие.join("\n")}`).toEqual([]);
  });
