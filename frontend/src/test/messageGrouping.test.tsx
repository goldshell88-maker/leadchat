import { describe, expect, it } from "vitest";
import { render } from "@testing-library/react";
import { MessageBubble } from "@/features/chats/components/thread/MessageBubble";
import type { MessageDto } from "@/shared/api/types";

/**
 * ПОДРЯД ИДУЩИЕ СООБЩЕНИЯ ОДНОГО АВТОРА СХЛОПЫВАЮТСЯ.
 *
 * ЗАЧЕМ ЭТОТ ФАЙЛ ПОЯВИЛСЯ ПОЗЖЕ САМОЙ ПРАВКИ. Схлопывание сделано 6 августа, и
 * работает, — а сторожа у него не было ни одного: сними условие `!sameAuthor` в
 * `MessageBubble`, и ни один тест из тысячи не покраснеет. Лента тихо вернулась бы к
 * четырём одинаковым подписям подряд, и заметил бы это разбор интерфейса через
 * месяц, а не сборка через минуту.
 *
 * Дыру нашла проверка пункта разбора «убрать имя оператора из каждого пузыря»:
 * сам пункт не подтвердился (всё уже сделано), но выяснилось, что держится это
 * ни на чём.
 *
 * ⚠ ЧТО ИМЕННО ОХРАНЯЕТСЯ — НЕ «КРАСИВО», А ЧЕТЫРЕ ГРАНИЦЫ ГРУППЫ. Серия рвётся
 * сменой автора, сменой типа пузыря, границей суток и паузой больше пяти минут.
 * Каждая из них — отдельное решение с доводом, и молча потерять можно любую.
 */

const ОЛЬГА = { id: "u-1", full_name: "Ольга Никитина" };
const ПЁТР = { id: "u-2", full_name: "Пётр Ковалёв" };

function исходящее(over: Partial<MessageDto> = {}): MessageDto {
  return {
    id: "m-1",
    conversation_id: "c-1",
    direction: "out",
    sender_type: "user",
    sender: ОЛЬГА,
    body: "Здравствуйте, помогу",
    attachments: [],
    delivery_status: "delivered",
    created_at: "2026-08-13T09:00:00Z",
    ...over,
  } as MessageDto;
}

/** Сколько подписей автора отрисовалось у второго сообщения пары. */
function подписейУПродолжения(prev: MessageDto, msg: MessageDto): number {
  const { container } = render(
    <MessageBubble msg={msg} prev={prev} clientId="cl-1" clientName="Иван" />,
  );
  return container.querySelectorAll(".msg__author").length;
}

describe("Схлопывание подписи автора", () => {
  it("второе сообщение подряд идёт без имени", () => {
    const первое = исходящее({ id: "m-1", created_at: "2026-08-13T09:00:00Z" });
    const второе = исходящее({ id: "m-2", created_at: "2026-08-13T09:01:00Z" });
    expect(подписейУПродолжения(первое, второе)).toBe(0);
  });

  it("первое сообщение серии имя показывает", () => {
    const { container } = render(
      <MessageBubble msg={исходящее()} prev={null} clientId="cl-1" clientName="Иван" />,
    );
    expect(container.querySelector(".msg__author")?.textContent).toBe("Ольга Никитина");
  });

  it("⚠ СМЕНА АВТОРА РВЁТ СЕРИЮ", () => {
    /**
     * В диалоге бывает несколько операторов плюс бот. Без этой границы передача
     * диалога читалась бы как продолжение одного человека — а спрашивают потом
     * именно «кто это писал клиенту».
     */
    const ольга = исходящее({ id: "m-1", created_at: "2026-08-13T09:00:00Z" });
    const пётр = исходящее({ id: "m-2", created_at: "2026-08-13T09:01:00Z", sender: ПЁТР });
    expect(подписейУПродолжения(ольга, пётр)).toBe(1);
  });

  it("⚠ ПАУЗА БОЛЬШЕ ПЯТИ МИНУТ РВЁТ СЕРИЮ", () => {
    // Пауза больше — это другой заход в диалог, и напомнить автора уместно.
    const первое = исходящее({ id: "m-1", created_at: "2026-08-13T09:00:00Z" });
    const позже = исходящее({ id: "m-2", created_at: "2026-08-13T09:06:00Z" });
    expect(подписейУПродолжения(первое, позже)).toBe(1);
  });

  it("⚠ ГРАНИЦА СУТОК РВЁТ СЕРИЮ", () => {
    /*
     * Между сообщениями встаёт дата-разделитель, и подпись после него обязана быть:
     * иначе первое сообщение нового дня выглядит продолжением вчерашнего.
     *
     * ⚠ МОМЕНТЫ СЧИТАЮТСЯ ОТ МЕСТНОЙ ПОЛУНОЧИ, А НЕ ВПИСАНЫ СТРОКОЙ UTC.
     *
     * День определяется `localDayKey`, то есть местным временем. Фиксированная пара
     * вроде «23:59Z / 00:01Z» лежит в разных сутках только в UTC: в Москве это одни
     * сутки, и тест проверял бы не границу дня, а пятиминутное окно — то есть был бы
     * зелёным и бессмысленным. Проверено прогоном: с фиксированными строками тест
     * краснеет в UTC и зеленеет в Europe/Moscow, а сторож не имеет права зависеть
     * от того, где его запустили.
     */
    const до = new Date(2026, 7, 12, 23, 59, 0);
    const после = new Date(2026, 7, 13, 0, 1, 0);
    const вчера = исходящее({ id: "m-1", created_at: до.toISOString() });
    const сегодня = исходящее({ id: "m-2", created_at: после.toISOString() });
    expect(подписейУПродолжения(вчера, сегодня)).toBe(1);
  });

  it("⚠ СМЕНА ТИПА ПУЗЫРЯ РВЁТ СЕРИЮ", () => {
    // Входящее между двумя исходящими — уже другой разговор, а не очередь ответов.
    const входящее = исходящее({
      id: "m-1",
      direction: "in",
      sender_type: "client",
      sender: null,
      created_at: "2026-08-13T09:00:00Z",
    });
    const ответ = исходящее({ id: "m-2", created_at: "2026-08-13T09:01:00Z" });
    expect(подписейУПродолжения(входящее, ответ)).toBe(1);
  });
});

/**
 * ГЕОМЕТРИЯ ГРУППЫ (13.08) — вторая половина схлопывания.
 *
 * Подпись и аватар убрали 6 августа, а вертикальный зазор оставили прежним: 6px и
 * внутри серии, и между сериями. Признаки группы сняли, признак группы не дали.
 * Теперь продолжение помечается классом `msg--cont`, и на нём висит уменьшенный
 * отступ.
 *
 * ⚠ ПРОВЕРЯЕТСЯ КЛАСС, А НЕ ОТСТУП, И ЭТО НЕ ЛЕНЬ. Тесты идут с `css: false`:
 * стилей в jsdom нет, `getBoundingClientRect` возвращает нули, и утверждение про
 * «2px против 8px» было бы зелёным при любом CSS — то есть враньём. Класс здесь
 * ровно то, что этот файл в состоянии удержать честно; числа померены в браузере и
 * записаны рядом с правилом в chat-thread.css.
 */
function классыКорня(prev: MessageDto | null, msg: MessageDto): string {
  const { container } = render(
    <MessageBubble msg={msg} prev={prev} clientId="cl-1" clientName="Иван" />,
  );
  return container.querySelector(".msg")?.className ?? "";
}

describe("Отступ внутри группы", () => {
  it("продолжение серии помечено классом", () => {
    const первое = исходящее({ id: "m-1", created_at: "2026-08-13T09:00:00Z" });
    const второе = исходящее({ id: "m-2", created_at: "2026-08-13T09:01:00Z" });
    expect(классыКорня(первое, второе)).toContain("msg--cont");
  });

  it("первое сообщение серии класса не получает", () => {
    expect(классыКорня(null, исходящее())).not.toContain("msg--cont");
  });

  it("⚠ ГРАНИЦА СЕРИИ РАЗЖИМАЕТ ЗАЗОР", () => {
    // Пауза больше пяти минут — новая серия, и отступ обязан вернуться вместе с
    // подписью. Иначе имя появится, а группа продолжит выглядеть слитной.
    const первое = исходящее({ id: "m-1", created_at: "2026-08-13T09:00:00Z" });
    const позже = исходящее({ id: "m-2", created_at: "2026-08-13T09:06:00Z" });
    expect(классыКорня(первое, позже)).not.toContain("msg--cont");
  });

  it("⚠ ЗАМЕТКА НЕ СЖИМАЕТСЯ, ХОТЯ АВТОР ТОТ ЖЕ", () => {
    /*
     * У заметки подпись рисуется ВСЕГДА («Заметка · имя · видно только
     * сотрудникам»), она в серию не схлопывается. Если бы класс шёл от одного
     * `sameAuthor`, две заметки подряд сели бы вплотную, сохранив по полной подписи
     * каждая: плотность группы без признаков группы. Поэтому класс идёт от того,
     * что подпись действительно убрана.
     */
    // Вид пузыря определяется `direction`, а НЕ `sender_type` (kindOf,
    // MessageBubble.tsx:33-38). Первая попытка задала здесь `sender_type: "note"`
    // и получила обычное исходящее — сторож поймал ошибку в самом приборе.
    const заметка = (over: Partial<MessageDto>) =>
      исходящее({ direction: "note", ...over }) as MessageDto;
    const первая = заметка({ id: "m-1", created_at: "2026-08-13T09:00:00Z" });
    const вторая = заметка({ id: "m-2", created_at: "2026-08-13T09:01:00Z" });
    const классы = классыКорня(первая, вторая);
    expect(классы, `заметка получила класс продолжения: ${классы}`).not.toContain("msg--cont");
  });
});
