import { describe, expect, it } from "vitest";
// @ts-expect-error — типов Node в проекте нет (tsconfig types: ["vite/client"]).
import { readFileSync } from "node:fs";

/**
 * ЗАКРЫЛ — СТРОКА УХОДИТ ИЗ «ВХОДЯЩИХ» СРАЗУ.
 *
 * ⚠ ЖАЛОБА ВЛАДЕЛЬЦА 28.08: «не моментально уходит диалог из входящих при
 * принятии и закрытии».
 *
 * Принятие это делало давно (`inbox/useInbox.ts`, `принятоУспешно`), а
 * закрытие — нет. Причина в двух разных кэшах: `applyConversationPatch` правит
 * строку в СПИСКАХ ДИАЛОГОВ, а очередь живёт в своём (`qk.inbox.list`) со
 * своим составом строки, и патч его не трогает вовсе. Закрытый диалог
 * продолжал стоять во «Входящих», а счётчик над вкладкой считал его живым — до
 * следующей полной загрузки списка, то есть до перезахода.
 *
 * Проверка по исходнику: поведение живёт в колбэке мутации, поднимать ради
 * него роутер, очередь и сервер — дороже, чем сам дефект.
 */
function src(путь: string): string {
  return (readFileSync(путь, "utf-8") as string)
    .replace(/\/\*[\s\S]*?\*\//g, " ")
    .replace(/\/\/[^\n]*/g, " ");
}

describe("Закрытие диалога и очередь", () => {
  const хук = src("src/features/chats/hooks/useConversationActions.ts");

  it("закрытие убирает строку из кэша очереди", () => {
    expect(хук, "строка останется во «Входящих» до перезахода").toContain(
      "removeInboxRow(convId)",
    );
  });

  it("и снимает диалог со счётчика очереди", () => {
    /*
     * Счётчик над вкладкой — отдельное состояние (`inboxStore`), и без этой
     * строки он продолжал бы считать закрытый диалог живым: «во Входящих 7», а
     * в списке шесть.
     */
    expect(хук).toMatch(/useInboxStore\.getState\(\)\.remove\(convId\)/);
  });

  it("и перезапрашивает списки СРАЗУ, а не в хвосте чужой пачки", () => {
    /*
     * Схлопывание перезапросов защищает от ЧУЖИХ событий и в живую смену
     * откладывается секундами. Своё нажатие — не чужое событие: его результат
     * человек ждёт глазами. Тот же довод записан у принятия.
     */
    expect(хук).toContain("refetchListsNow()");
  });

  it("всё это — ТОЛЬКО при закрытии, а не на любой смене статуса", () => {
    /*
     * «Ждёт клиента» и «В работе» из очереди диалог не убирают: её условие
     * требует лишь `status != closed`. Убери мы строку на любой смене — диалог
     * пропал бы из «Входящих», оставшись там на сервере, и вернулся бы при
     * следующей загрузке. Хуже, чем задержка: пропажа без причины.
     */
    expect(хук).toMatch(/if \(conv\.status === "closed"\) \{/);
  });

  it("принятие своё удаление не потеряло", () => {
    /* Вторая половина жалобы: обе дороги обязаны вести себя одинаково. */
    const принятие = src("src/features/chats/inbox/useInbox.ts");
    expect(принятие).toContain("removeInboxRow(convId)");
    expect(принятие).toContain("refetchListsNow()");
  });
});
