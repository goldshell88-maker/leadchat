import { describe, expect, it } from "vitest";
import { STATUS_LABEL, STATUS_ORDER, STATUS_SHOWS_CHIP } from "@/shared/lib/conversationStatus";
import { waitingForRow } from "@/shared/lib/waiting";
import { formatMoscow } from "@/shared/lib/moscowTime";

/**
 * Дефект №3 (docs/33 §3) и цена его возврата.
 *
 * Закрытие диалога не трогало `unread_count`, а шкала ожидания в строке
 * списка считается по нему. Закрытый диалог с непрочитанным показывал «ждёт
 * 3 ч»: оператор видел строку, требующую внимания, открывал её и находил
 * закрытое обращение.
 */
describe("ожидание гаснет статусом, а не только счётчиком", () => {
  const NOW = Date.parse("2026-08-12T12:00:00Z");
  const row = (status: string) => ({
    unread_count: 3,
    last_message_at: "2026-08-12T09:00:00Z",
    status,
  });

  it("у закрытого диалога ожидания нет, сколько бы непрочитанных ни лежало", () => {
    expect(waitingForRow(row("closed"), NOW)).toBeNull();
  });

  it("незнакомый статус ожидание всё равно гасит", () => {
    /*
     * Здесь проверялся `snoozed` — статус, снятый 12 августа. Проверка не
     * выброшена, а обобщена, и это важнее прежнего случая: правило «не в
     * `STATUS_SHOWS_WAIT` — значит не ждёт» обязано работать и для значения,
     * которого фронт не знает. Такое приезжает в окне выката (бэкенд поехал
     * раньше) и из офлайн-снимка десктопа.
     */
    expect(waitingForRow(row("snoozed"), NOW)).toBeNull();
    expect(waitingForRow(row("совсем_новый_статус"), NOW)).toBeNull();
  });

  it("у рабочих статусов ожидание считается как раньше", () => {
    for (const status of ["new", "in_progress", "waiting_client"]) {
      expect(waitingForRow(row(status), NOW)?.text).toBe("3 ч");
    }
  });

  it("строка без статуса (кэш прошлой версии) ожидание показывает", () => {
    // Молча погасить тревогу хуже, чем показать лишнюю: в офлайн-снимке
    // десктопа лежат строки, записанные до этой выкатки.
    const legacy = { unread_count: 3, last_message_at: "2026-08-12T09:00:00Z" };
    expect(waitingForRow(legacy, NOW)?.text).toBe("3 ч");
  });
});

describe("чип статуса в списке", () => {
  it("не рисуется у «Новый» и «В работе» — это 95 % строк", () => {
    expect(STATUS_SHOWS_CHIP.has("new")).toBe(false);
    expect(STATUS_SHOWS_CHIP.has("in_progress")).toBe(false);
  });

  it("рисуется ровно у тех двух, что объясняют непривычный вид строки", () => {
    expect([...STATUS_SHOWS_CHIP].sort()).toEqual(["closed", "waiting_client"]);
  });

  it("«Отложен» из словаря убран целиком — ни значения, ни подписи, ни чипа", () => {
    /*
     * ОХРАНА РЕШЕНИЯ ВЛАДЕЛЬЦА ОТ 12 АВГУСТА. Отложка снята, и вернуться она
     * может только осознанной правкой — а не тем, что кто-то дописал строку в
     * словарь, чиня соседний экран.
     *
     * Три проверки, потому что вернуть значение можно тремя независимыми
     * способами: добавить в порядок (появится пункт во всех фильтрах), завести
     * подпись (появится текст в карточке и в отчёте), включить в чипы
     * (появится метка в строке списка). Серверную половину сторожит
     * `tests/unit/test_conversation_status.py`.
     */
    expect(STATUS_ORDER).not.toContain("snoozed");
    expect(STATUS_LABEL).not.toHaveProperty("snoozed");
    expect(STATUS_SHOWS_CHIP.has("snoozed" as never)).toBe(false);
  });

  it("у каждого значения словаря есть подпись", () => {
    for (const code of STATUS_ORDER) {
      expect(STATUS_LABEL[code]).toBeTruthy();
    }
  });
});

/**
 * Московское время в интерфейсе (docs/38 §7).
 *
 * ЗДЕСЬ БЫЛИ ТРИ ПРОВЕРКИ ПРЕСЕТОВ ОТЛОЖКИ — «завтра в 10:00» на пересменке,
 * «в понедельник» из понедельника, разбор своего срока из поля. Они ушли
 * 12 августа вместе с самими пресетами и функциями под ними (`moscowAt`,
 * `daysToNextMonday`, `moscowFromLocalInput`).
 *
 * Осталась одна, и она про живое: `formatMoscow` подписывает дату закрытия в
 * карточке клиента. Настройки часового пояса у пользователя в системе нет, а
 * вся отчётность московская — подпись, посчитанная по часам браузера, у
 * диспетчера в Новосибирске разошлась бы с отчётом владельца на четыре часа.
 */
describe("московское время", () => {
  it("подпись показывается по Москве, а не по часам браузера", () => {
    expect(formatMoscow("2026-08-14T07:00:00Z")).toBe("14 авг, 10:00");
  });
});
