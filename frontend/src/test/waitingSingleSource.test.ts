import { describe, expect, it } from "vitest";
import { waitingFor, waitingForRow, waitingSince } from "@/shared/lib/waiting";

/**
 * ОДНА МЕТРИКА ОЖИДАНИЯ (CHATS-07 / FUNC-14).
 *
 * На боевом экране 12 августа «сколько клиент ждёт» было показано пятью
 * способами и тремя разными числами сразу: «ждёт 2 ч» в шапке ленты, оранжевая
 * шкала «7ч» в строке списка, «в очереди 7 ч 11 мин» в карточке, «Диалог ждёт в
 * очереди» нижней плашкой и «Ждал 6 ч 41 мин» в системной записи. Каждое число
 * выглядело правдоподобно — тем и опасно.
 *
 * Считает теперь сервер (`waiting_since`), интерфейс только оформляет. Тесты
 * ниже держат ровно эту границу: интерфейс не имеет права ни считать сам, ни
 * гасить чужой счёт по своим приметам.
 */

const NOW = Date.parse("2026-08-12T14:27:00Z");
const ago = (min: number) => new Date(NOW - min * 60_000).toISOString();

/** Строка списка с сервера: канонический якорь + всё, чем раньше считали. */
const row = (over: Record<string, unknown> = {}) => ({
  waiting_since: ago(147), // 12:00 — клиент ждёт два с половиной часа
  status: "in_progress",
  unread_count: 1,
  last_message_at: ago(147),
  ...over,
});

describe("ожидание считается в одном месте — на сервере", () => {
  it("число берётся из серверного поля, а не из непрочитанных", () => {
    expect(waitingFor(row(), NOW)?.text).toBe("2 ч");
  });

  it("закрытый диалог не ждёт", () => {
    // Сервер такой строке `waiting_since` и не пришлёт, но проверка статуса на
    // клиенте всё равно первая: кадр `conversation:updated` патчит строку
    // полями, которые изменились, и закрытие приезжает статусом — без якоря.
    expect(waitingFor(row({ status: "closed" }), NOW)).toBeNull();
  });

  it("незнакомый статус тоже не ждёт — правило от обратного", () => {
    // Здесь проверялся `snoozed`, снятый 12 августа. Смысл проверки шире
    // прежнего случая: `waitingFor` пускает ожидание только для статусов из
    // `STATUS_SHOWS_WAIT`, а не отсекает известный список. В окне выката
    // (бэкенд поехал раньше фронта) это единственная защита.
    expect(waitingFor(row({ status: "snoozed" }), NOW)).toBeNull();
    expect(waitingFor(row({ status: "совсем_новый_статус" }), NOW)).toBeNull();
  });

  it("ожидание НЕ гаснет, когда оператор открыл диалог", () => {
    /*
     * ПРЕЖНЯЯ БЕДА. Открытие диалога обнуляет `unread_count` локально, до
     * всякого ответа сервера, а шкала ожидания считалась по этому счётчику.
     * Значит ожидание гасло ровно в ту секунду, когда оператор заглянул в
     * диалог и НИЧЕГО не ответил, — то есть когда оно нужнее всего.
     *
     * Непрочитанное — состояние ОПЕРАТОРА, ожидание — состояние КЛИЕНТА.
     */
    expect(waitingFor(row({ unread_count: 0 }), NOW)?.text).toBe("2 ч");
  });

  it("«не ждёт» от сервера — это null, и клиент его не переспоривает", () => {
    // Мы ответили: клиенту ждать нечего, а непрочитанное у ЭТОГО оператора
    // остаться могло (писал коллега). Прежний расчёт зажёг бы просрочку.
    expect(waitingFor(row({ waiting_since: null, unread_count: 3 }), NOW)).toBeNull();
  });

  it("возврат в очередь ожидание ПЕРЕСЧИТЫВАЕТ, а не тянет из очереди", () => {
    /*
     * РАЗБОР АНАЛИТИКА: диалог вернулся в очередь в 12:08, принят в 14:27, а
     * показывалось «3 ч 43 мин» — от первого сообщения клиента в 10:44, потому
     * что считали от `offered_at`, который возврат намеренно не двигает.
     * Клиент к тому времени успел получить ответ и написать заново в 11:55.
     *
     * Каноническое поле выводится из переписки и от очереди не зависит вовсе.
     */
    const returned = {
      offered_at: ago(223), // 10:44 — первое попадание в очередь
      waiting_since: ago(152), // 11:55 — последнее сообщение клиента
      status: "new",
      unread_count: 1,
      last_message_at: ago(152),
    };
    expect(waitingFor(returned, NOW)?.text).toBe("2 ч");
    // А вот что показывали раньше — и что больше не должно попадаться на глаза.
    expect(waitingSince(returned.offered_at, NOW)?.text).toBe("3 ч");
  });

  it("строка без поля (кэш прошлой версии) считается по-старому", () => {
    // В офлайн-снимке десктопа лежат строки, записанные ДО выкатки. Молча
    // погасить у них тревогу хуже, чем показать лишнюю.
    const legacy = { status: "in_progress", unread_count: 2, last_message_at: ago(147) };
    expect(waitingFor(legacy, NOW)?.text).toBe("2 ч");
  });

  it("старое имя ведёт в ту же функцию — второй логики нет", () => {
    expect(waitingForRow).toBe(waitingFor);
  });
});
