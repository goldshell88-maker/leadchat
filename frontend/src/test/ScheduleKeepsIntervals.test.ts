/**
 * Переключение расписания не стирает настроенные интервалы (27.08).
 *
 * ⚠ ЧТО БЫЛО. Ветка «Круглосуточно» возвращала объект `{ always: true }`
 * ЦЕЛИКОМ — без часового пояса и без интервалов. Человек настраивал «пн–пт
 * 9:00–18:00, сб 10:00–15:00», на минуту переключался на «Круглосуточно»
 * посмотреть, как будет, возвращался обратно — и получал один пустой интервал
 * по умолчанию. Взять настройку было неоткуда: на сервер уходило то же
 * усечённое расписание.
 *
 * «Круглосуточно» — это про то, КОГДА бот работает, а не команда забыть, что
 * было настроено.
 */
import { describe, expect, it } from "vitest";
// @ts-expect-error — типов Node в проекте нет (tsconfig types: ["vite/client"]).
import { readFileSync } from "node:fs";

const ФАЙЛ = "src/features/settings/bots/components/ScheduleEditor.tsx";

function код(путь: string): string {
  return (readFileSync(путь, "utf-8") as string)
    .replace(/\/\*[\s\S]*?\*\//g, " ")
    .replace(/\/\/[^\n]*/g, " ");
}

describe("Переключатель расписания", () => {
  it("«Круглосуточно» сохраняет остальное расписание", () => {
    const src = код(ФАЙЛ);
    // Обе ветки обязаны раскрывать прежнее расписание, а не собирать объект с нуля.
    expect(src).toMatch(/\{\s*\.\.\.schedule,\s*always:\s*true\s*\}/);
  });

  it("«По расписанию» тоже не теряет соседние поля", () => {
    const src = код(ФАЙЛ);
    const at = src.indexOf("always: false");
    expect(at, "ветка «по расписанию» исчезла").toBeGreaterThan(-1);
    // `...schedule` должен стоять ДО `always: false`, иначе он перезатрёт флаг.
    const до = src.slice(Math.max(0, at - 200), at);
    expect(до).toContain("...schedule");
  });
});
