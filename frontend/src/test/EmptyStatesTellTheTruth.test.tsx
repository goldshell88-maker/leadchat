// @ts-expect-error — типов Node в проекте нет (tsconfig types: ["vite/client"]).
import { readFileSync } from "node:fs";
import { describe, expect, it } from "vitest";

/**
 * ПУСТОЙ ЭКРАН НАЗЫВАЕТ НАСТОЯЩУЮ ПРИЧИНУ, А НЕ ПЕРВУЮ ПОПАВШУЮСЯ.
 *
 * Три места, механизм общий: у пустоты несколько причин, а ветка была одна — и
 * человек получал совет, который к его случаю не относится.
 *
 * ⚠ ЖИВАЯ ЛЕНТА. Пауза хранит только НОМЕР, на котором остановились, а запись в
 * буфер продолжается и режет самое старое (предел 300 строк). Через какое-то
 * время ни одной строки «до паузы» в буфере не остаётся — и экран говорил «Под
 * этот отбор ничего не попало… снимите отбор по каналу», которого человек не
 * ставил. Пауза на пустой ленте даёт порог 0: достаточно ОДНОГО события.
 *
 * ⚠ АВТОЗАЯВКИ. Состояния запросов не читались вовсе: при отказе печаталось
 * «Отдано всего 0», «Ждут ответа расширения 0» и «Пока ничего не отдавали» — с
 * объяснением, при каких условиях лид появится. Владелец приходит сюда ровно с
 * вопросом «почему в лид-центрах мало заявок» и уходит с ответом «заявок не
 * было, всё спокойно».
 *
 * ⚠ ЗАСЛОНКА ПРОКРУТКИ. Признак «справа есть ещё» держится на заслонке цветом
 * фона; она обязана СОВПАДАТЬ с фоном блока. Умолчание было `--lc-bg-0`, а все
 * три потребителя покрашены `--lc-surface`, и переменную не переопределял ни
 * один. В тёмной теме растушёвка была видна там, где крутить некуда, и слабела
 * там, где было куда, — признак вёл в обратную сторону.
 *
 * Отрисовкой это не проверить: в jsdom нет раскладки, а состояния запросов
 * пришлось бы поднимать целыми экранами. Проверяем САМИ ПРАВИЛА — тем же
 * приёмом, что `bubbleUnderPressure` и `surfaceLadder`.
 */

const без_комментариев = (t: string) =>
  (t as string).replace(/\/\*[\s\S]*?\*\//g, " ").replace(/\/\/[^\n]*/g, " ");

function файл(путь: string): string {
  return без_комментариев(readFileSync(путь, "utf-8") as string);
}

describe("Пустая живая лента", () => {
  it("«виноват отбор» — проверенное утверждение, а не «в буфере что-то есть»", () => {
    const src = файл("src/features/feed/FeedPage.tsx");
    expect(
      src,
      "ветка про отбор снова показывается по одной лишь длине буфера",
    ).not.toMatch(/\)\s*:\s*entries\.length > 0 \?\s*\(\s*<EmptyState\s+illustration="search"/);
    // Признак спрашивает то, что имели в виду: проходит ли отбор хоть одна строка.
    expect(src).toMatch(/entries\.some\(\(e\) => matchesFilters\(e, filters\)\)/);
  });

  it("у вытеснения строк — своё объяснение и своё действие", () => {
    const src = файл("src/features/feed/FeedPage.tsx");
    expect(src, "остановленная лента снова обвиняет отбор").toContain(
      "вытеснены новыми",
    );
    // Совет — «Продолжить», а не «снимите отбор»: отбора человек не ставил.
    expect(src).toMatch(/Продолжить/);
  });
});

describe("Экран автозаявок", () => {
  it("отказ загрузки не выдаётся за «заявок не было»", () => {
    const src = файл("src/features/settings/leads/LeadsTab.tsx");
    expect(src, "состояние запроса снова не читается").toMatch(
      /handouts\.isError \|\| state\.isError/,
    );
    expect(src).toContain("это сбой связи, а не отсутствие заявок");
  });

  it("числа сводки при отказе не показываются нулями", () => {
    /* Ноль — это утверждение «отдали ноль», а мы его не знаем. */
    const src = файл("src/features/settings/leads/LeadsTab.tsx");
    expect(src).toMatch(/state\.isError \? "—" : \(stats\.total \?\? 0\)/);
    expect(src).toMatch(/state\.isError \? "—" : \(stats\.unacked \?\? 0\)/);
  });
});

describe("Признак «справа есть ещё»", () => {
  it("заслонка красится тем же фоном, что и её потребители", () => {
    const base = файл("src/app/lc-base.css");
    expect(base, "заслонка снова другого цвета — признак покажет наоборот").toMatch(
      /--lc-scroll-shade:\s*var\(--lc-surface\)/,
    );
  });

  it("и потребители действительно покрашены этим фоном", () => {
    /*
     * Сторож бесполезен, если завтра таблицу перекрасят: правило здесь не «пусть
     * будет surface», а «заслонка совпадает с фоном». Проверяем обе стороны.
     */
    const team = файл("src/features/settings/team/team.css");
    const table = файл("src/features/table/table.css");
    expect(team).toMatch(/\.audit__scroll\s*\{[^}]*background-color:\s*var\(--lc-surface\)/);
    expect(table).toMatch(/\.dt__scroll\s*\{[^}]*background-color:\s*var\(--lc-surface\)/);
  });
});
