import { describe, expect, it } from "vitest";

/**
 * CSP: ХЕШ ВСТРОЕННОГО СКРИПТА ОБЯЗАН СОВПАДАТЬ С САМИМ СКРИПТОМ.
 *
 * ⚠ ПРОСЬБА ВЛАДЕЛЬЦА 01.09: «максимально защитить код, который отображается на
 * странице сайта в браузере». Ответ на неё — Content-Security-Policy: она не
 * даёт выполниться ЧУЖОМУ скрипту, даже если тот как-то попал в разметку. Это
 * важно именно здесь: текст сообщений пишет посторонний человек из Авито, и до
 * сих пор от внедрения защищало ровно одно — экранирование React.
 *
 * ⚠ ЧЕМ ОПАСНА ЭТА КОНКРЕТНАЯ СВЯЗКА. В `index.html` есть один встроенный
 * скрипт: он ставит тему до первой отрисовки, чтобы смена не видела вспышку
 * светлого экрана. Разрешать его через 'unsafe-inline' нельзя — это открыло бы
 * заодно и любой чужой скрипт, то есть выключило бы всю защиту. Поэтому он
 * разрешён ПОИМЕННО, по хешу содержимого.
 *
 * Отсюда ловушка: правка этого скрипта меняет хеш, и браузер перестаёт его
 * выполнять. Сайт при этом не падает — он просто открывается в чужой теме и с
 * вспышкой, а в консоли у КАЖДОГО человека появляется отказ. Заметить это
 * можно было бы только глазами, и то не сразу.
 *
 * Этот сторож переводит беду из боя в ворота выкатки: правка скрипта без правки
 * хеша роняет тесты здесь, а не интерфейс у тринадцати человек.
 */

const СНИППЕТ = "../docker/nginx/snippets/security-headers.conf";

async function читать(путь: string): Promise<string> {
  // @ts-expect-error — типов Node в проекте нет (tsconfig types: ["vite/client"]).
  const { readFileSync } = await import("node:fs");
  return readFileSync(путь, "utf-8") as string;
}

async function csp(): Promise<string> {
  const conf = await читать(СНИППЕТ);
  const m = conf.match(/add_header\s+Content-Security-Policy\s+"([^"]+)"/);
  expect(m, "в заголовках больше нет Content-Security-Policy — защита снята целиком").toBeTruthy();
  return m![1];
}

describe("CSP и встроенный скрипт темы", () => {
  it("⚠ хеш в политике совпадает со скриптом в index.html", async () => {
    const html = await читать("index.html");
    const m = html.match(/<script>([\s\S]*?)<\/script>/);
    expect(m, "встроенный скрипт исчез из index.html — хеш в CSP стал мусором").toBeTruthy();

    // @ts-expect-error — типов Node в проекте нет.
    const { createHash } = await import("node:crypto");
    const хеш = createHash("sha256").update(m![1], "utf8").digest("base64") as string;

    expect(
      await csp(),
      `скрипт темы изменился, а хеш в CSP — нет. Браузер откажется его выполнять: ` +
        `у всех откроется чужая тема со вспышкой. Впишите в security-headers.conf ` +
        `'sha256-${хеш}'`,
    ).toContain(`'sha256-${хеш}'`);
  });

  it("⚠ политику не ослабили, чтобы «починить» поломку", async () => {
    /*
     * Самый вероятный способ сломать эту защиту — не убрать её, а смягчить.
     * Когда что-нибудь перестанет работать, первым делом захочется дописать
     * 'unsafe-inline' в script-src: сайт оживёт, а защиты не станет, и никто
     * не заметит. Оба послабления названы здесь поимённо.
     */
    const политика = await csp();
    const скрипты = политика.match(/script-src([^;]*)/)?.[1] ?? "";

    expect(
      скрипты,
      "в script-src вернулся 'unsafe-inline' — чужой скрипт снова выполнится, защиты нет",
    ).not.toContain("unsafe-inline");
    expect(
      скрипты,
      "в script-src появился 'unsafe-eval' — открыт целый класс приёмов внедрения",
    ).not.toContain("unsafe-eval");
    expect(политика, "object-src перестал быть 'none' — вернулись плагины и <object>").toContain(
      "object-src 'none'",
    );
    expect(политика, "frame-ancestors ослаблен — сайт снова можно встроить в чужую страницу").toContain(
      "frame-ancestors 'none'",
    );
  });

  it("⚠ картинки и звук от Авито разрешены — иначе смена слепнет и глохнет", async () => {
    /*
     * ⚠ ЭТО НЕ ПРЕДОСТОРОЖНОСТЬ, А СЛЕД ТРЁХ БОЕВЫХ ПОЛОМОК 01.09, ПОДРЯД.
     *
     * Первая выкатка CSP погасила фотографии. Дофиксили `*.img.avito.st` —
     * оказалось, аватары идут с `static.avito.ru` (21 657 клиентов). Пока
     * чинили аватары — выяснилось, что и голосовые берутся с адреса, который
     * Авито отдаёт на лету и которого в базе нет вовсе.
     *
     * Причина у всех трёх одна: ВСЁ, что диспетчер видит и слышит от клиента,
     * лежит НЕ У НАС. Замер: вложений 11 027, скачанных к себе — ноль.
     *
     * Поэтому сторож проверяет обе директивы сразу. Сузить их до 'self' можно
     * будет только после того, как медиа начнут забираться к себе и отдаваться
     * по подписанной ссылке.
     */
    const политика = await csp();
    for (const директива of ["img-src", "media-src"]) {
      const значение = политика.match(new RegExp(`${директива}([^;]*)`))?.[1] ?? "";
      expect(
        значение,
        `${директива} больше не пускает домены Авито — у диспетчеров пропадут фотографии, аватары и голосовые`,
      ).toContain("avito");
    }
  });

  it("политика включена в тот сниппет, который подключён везде", async () => {
    /*
     * ⚠ ПРОВОДКА. В nginx `add_header` внутри location ПОЛНОСТЬЮ заменяет набор
     * из server — поэтому заголовки живут в сниппете, который включается в
     * каждый location отдельно. Положи CSP мимо сниппета — и она будет
     * действовать на части страниц, а на статике и вложениях исчезнет молча.
     */
    const шаблон = await читать("../docker/nginx/templates/leadchat.conf.template");
    const включений = (шаблон.match(/include\s+\/etc\/nginx\/snippets\/security-headers\.conf/g) ?? [])
      .length;
    expect(включений, "сниппет заголовков перестал подключаться в locations").toBeGreaterThan(3);
    expect(
      шаблон,
      "CSP выписана прямо в шаблоне — на locations со своими заголовками она пропадёт",
    ).not.toContain("Content-Security-Policy");
  });
});
