/**
 * Значки — СВОИ, а не символы шрифта (просьба владельца 04.09: «сделай
 * собственные иконки»).
 *
 * ⚠ ЧТО БЫЛО. Собственный набор в проекте есть с самого начала — 50 фигур на
 * сетке 24 с одной толщиной обводки. Но по экранам вместо них стояли СИМВОЛЫ:
 * «✕» и «×» (два разных креста в одном файле), «▸» у раскрытия строки канала,
 * «▶» у голосового, «↑»/«↓» у перестановки шагов бота, «🔄» у
 * «Переподключить», «🧪» у «Протестировать», «📋» у «Скопировать», «👁» у
 * режима просмотра, «✓» у восстановленной связи.
 *
 * Разница не косметическая. Символ рисуется ШРИФТОМ: его толщина не совпадает
 * с соседним значком, размер зависит от кегля, а эмодзи на Windows и на Маке
 * выглядят по-разному — в одном ряду кнопок это видно сразу. Хуже того, эмодзи
 * попадал в ДОСТУПНОЕ ИМЯ кнопки: читалка с экрана произносила «планшет с
 * зажимом Скопировать».
 *
 * ⚠ ЧТО ЗДЕСЬ НЕ ЗАПРЕЩЕНО. Символы в ДАННЫХ — не значки интерфейса, а
 * содержимое: каталог видов шага бота (`scenario.ts`), каталог уведомлений,
 * подписи, которые приходят с сервера. Они живут в .ts и сюда не попадают.
 */
// @ts-expect-error — типов Node в проекте нет (tsconfig types: ["vite/client"]).
import { readFileSync, readdirSync, statSync } from "node:fs";
import { describe, expect, it } from "vitest";

const КОРЕНЬ = "src";

/** Символы, которыми в этом проекте подменяли значки. */
const ПОДМЕНЫ = ["✕", "×", "▸", "▶", "↑", "↓", "←", "→", "⋮", "✓", "✎", "👁", "🔄", "🧪", "📋"];

function файлы(dir: string): string[] {
  const out: string[] = [];
  for (const имя of readdirSync(dir)) {
    const путь = `${dir}/${имя}`;
    if (statSync(путь).isDirectory()) {
      if (имя === "test") continue; // сами тесты про символы говорят словами
      out.push(...файлы(путь));
    } else if (имя.endsWith(".tsx")) {
      out.push(путь);
    }
  }
  return out;
}

/** Код без комментариев: разбор в шапке файла символы называть вправе. */
function код(путь: string): string {
  return (readFileSync(путь, "utf-8") as string)
    .replace(/\/\*[\s\S]*?\*\//g, "")
    .replace(/^\s*\/\/.*$/gm, "");
}

describe("значки собственные", () => {
  it("символ не стоит вместо значка ни на одном экране", () => {
    /*
     * ⚠ ЛОВИМ СИМВОЛ В НАЧАЛЕ СОДЕРЖИМОГО, А НЕ ТОЛЬКО В ОДИНОЧЕСТВЕ.
     *
     * Первая редакция требовала, чтобы символ был ЕДИНСТВЕННЫМ между тегами
     * (`>✕<`). Диверсия «▶ {name}» прошла её насквозь: там символ стоит первым,
     * а следом идёт подпись — ровно тот случай, ради которого сторож писался.
     *
     * ⚠ И ВТОРАЯ РЕДАКЦИЯ ТОЖЕ ПРОШЛА, ПОТОМУ ЧТО ЧИТАЛА ПОСТРОЧНО. В разметке
     * открывающий тег обычно стоит на своей строке, а содержимое — на
     * следующей; `>` и символ просто не встречались в одной строке. Поэтому
     * ищем по ВСЕМУ файлу, а номер строки считаем по месту совпадения.
     *
     * Позиция важна и в другую сторону: стрелка в КОНЦЕ подписи — не значок, а
     * типографика («далее →», «Открыть на Авито →»), и запрещать её нечего.
     */
    const набор = ПОДМЕНЫ.map((s) => s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")).join("");
    const rx = new RegExp(`>\\s*[${набор}]`, "gu");
    /*
     * ⚠ КЛАВИША — НЕ ЗНАЧОК. `<kbd>↑↓</kbd>` называет клавиши, которые человек
     * ищет глазами на своей клавиатуре: там стрелка нарисована ровно так же.
     * Подменять её нашей фигурой значило бы показать не то, что он нажимает.
     */
    const плохие: string[] = [];
    for (const файл of файлы(КОРЕНЬ)) {
      const текст = код(файл);
      rx.lastIndex = 0;
      let m: RegExpExecArray | null;
      while ((m = rx.exec(текст))) {
        const до = текст.slice(0, m.index);
        // `>` съеден совпадением, поэтому перед ним остаётся именно `<kbd`.
        if (/<kbd$/.test(до)) continue;
        const строка = до.split("\n").length;
        const кусок = текст.slice(m.index, m.index + 60).replace(/\s+/g, " ");
        плохие.push(`${файл}:${строка} — ${кусок}`);
      }
    }
    expect(плохие, `символ вместо значка:\n${плохие.join("\n")}`).toEqual([]);
  });

  it("эмодзи не попадает в подпись кнопки", () => {
    /*
     * Подпись кнопки — это её ИМЯ для читалки с экрана. «📋 Скопировать»
     * произносилось как «планшет с зажимом Скопировать»; значок обязан стоять
     * рядом с подписью и быть помечен aria-hidden, а не входить в неё.
     */
    const эмодзи = /[\u{1F300}-\u{1FAFF}\u{2600}-\u{27BF}]/u;
    const плохие: string[] = [];
    for (const файл of файлы(КОРЕНЬ)) {
      for (const [i, стр] of код(файл).split("\n").entries()) {
        /*
         * ⚠ ВСЕ СТРОКИ В СТРОКЕ, А НЕ ПЕРВАЯ. Здесь стояло одно `.exec`, и
         * диверсия `{copied ? "Скопировано" : "📋 Скопировать"}` прошла: первой
         * кавычкой шла чистая подпись, до второй сторож не добирался.
         */
        for (const m of стр.matchAll(/["'`]([^"'`]*)["'`]/g)) {
          if (!эмодзи.test(m[1])) continue;
          if (!/\p{L}/u.test(m[1])) continue; // одинокий значок в данных — не подпись
          плохие.push(`${файл}:${i + 1} — ${m[1]}`);
        }
      }
    }
    expect(плохие, `эмодзи в подписи:\n${плохие.join("\n")}`).toEqual([]);
  });

  it("набор значков растёт одним файлом", () => {
    // Все фигуры живут в одном месте и на одной сетке — иначе «свой набор»
    // расползётся по компонентам, и толщина линии снова разъедется.
    const icon = readFileSync("src/shared/ui/Icon.tsx", "utf-8") as string;
    const сколько = (icon.match(/^export const Icon/gm) ?? []).length;
    expect(сколько, "значков в наборе стало меньше").toBeGreaterThanOrEqual(50);
    expect(icon).toContain('viewBox="0 0 24 24"');
    expect(icon).toContain("strokeWidth={2}");
  });
});
