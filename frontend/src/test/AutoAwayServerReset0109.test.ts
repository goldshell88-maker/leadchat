import { beforeEach, describe, expect, it, vi } from "vitest";
import { renderHook } from "@testing-library/react";
import { useAutoAway } from "@/features/presence/автоОтошёл";
import { usePresenceStore } from "@/features/presence/usePresence";

/**
 * АВТО-«ОТОШЁЛ» ПЕРЕЖИВАЕТ СБРОС СТАТУСА СЕРВЕРОМ И ВТОРУЮ ВКЛАДКУ.
 *
 * ⚠ ЖАЛОБА ВЛАДЕЛЬЦА 01.09: «показывается, что люди онлайн в работе, а у кого-то
 * просто вкладка открыта, у кого-то просто ПК включён».
 *
 * Механизм был написан 31.08 и подключён — но работал ровно до первой
 * моргнувшей сети. Разбор нашёл две независимые дыры, обе подтверждены чтением
 * кода сервера:
 *
 * 1. СЕРВЕР СБРАСЫВАЕТ СТАТУС САМ. Пропал последний сокет — через 30 секунд
 *    грации запись о статусе УДАЛЯЕТСЯ (`presence_disconnected`). Сокет
 *    вернулся — `presence_connected` не находит, что сохранять, и пишет
 *    «online». Истёк TTL на спящем ноутбуке — первый же пинг воскрешает ключ
 *    строкой `redis.get(...) or "online"`. Сокет пропадает постоянно: сеть,
 *    крышка ноутбука, наша собственная выкатка (она сбрасывает разом всю смену).
 *    Клиент об этом не узнавал — и со сверкой «уже стоит нужное, не шлём»
 *    замолкал НАВСЕГДА.
 *
 * 2. ДВЕ ВКЛАДКИ ВЕЛИ ДВА СЧЁТА. Забытая вкладка молчит порог и честно ставит
 *    «отошёл», хотя человек работает в соседней; а рабочая не возвращает «на
 *    месте», потому что её собственная память говорит, что он и так на месте.
 */

const запросы: { status: string }[] = [];

vi.mock("@/shared/api/http", () => ({
  http: {
    put: async (_url: string, body: { status: string }) => {
      запросы.push(body);
      return body;
    },
  },
}));

const КЛЮЧ_АКТИВНОСТИ = "lc:presence:last-active";
const КЛЮЧ_СТАТУСА = "lc:presence:pushed";
const МИН = 60 * 1000;

describe("Авто-«отошёл» против сброса и второй вкладки", () => {
  beforeEach(() => {
    запросы.length = 0;
    vi.useFakeTimers();
    usePresenceStore.getState().set("online");
    localStorage.clear();
  });

  /*
   * ⚠ ЗДЕСЬ ВРЕМЯ ДВИГАЕТСЯ АСИНХРОННО, И ЭТО НЕ ПРИДИРКА К СТИЛЮ.
   *
   * С обычным `advanceTimersByTime` обещание `pushPresence` не выполняется до
   * конца синхронного тела теста: зеркало статуса остаётся «на месте», сверка
   * «уже стоит нужное» не срабатывает НИКОГДА — и проверка зеленеет, что бы ни
   * стояло в коде. Поймано диверсией: возврат сверки для «отошёл» этот набор
   * не уронил. Асинхронное продвижение доводит обещание до конца, и зеркало
   * становится настоящим.
   */
  it("⚠ повторяет «отошёл»: сервер возвращает «на месте» сам, и молчать нельзя", async () => {
    renderHook(() => useAutoAway());
    await vi.advanceTimersByTimeAsync(31 * МИН);
    expect(запросы.at(-1)?.status).toBe("away");
    const было = запросы.length;

    /*
     * Здесь и происходила беда. Сервер после переподключения молча вернул «на
     * месте»; зеркало клиента по-прежнему говорит «отошёл», значит старая
     * сверка «уже стоит нужное» глушила все дальнейшие попытки. Человека нет за
     * столом, а система до конца смены считает его работающим.
     */
    await vi.advanceTimersByTimeAsync(3 * МИН);

    expect(
      запросы.length,
      "после первого «отошёл» клиент замолчал — любой сброс на сервере теперь навсегда",
    ).toBeGreaterThan(было);
    expect(запросы.at(-1)?.status).toBe("away");
  });

  it("но не шлёт чаще, чем нужно: повтор реже двух минут", async () => {
    // Обратная сторона: сняв сверку, легко получить запрос каждую минуту на
    // каждого из тринадцати диспетчеров всю ночь.
    renderHook(() => useAutoAway());
    await vi.advanceTimersByTimeAsync(30 * МИН);
    const было = запросы.length;

    // За десять минут при шаге в две выходит пять повторов; сняв ограничитель,
    // получили бы десять — по одному на каждый тик.
    await vi.advanceTimersByTimeAsync(10 * МИН);
    const повторов = запросы.length - было;

    expect(повторов, "повтор «отошёл» перестал уходить вовсе — сброс на сервере станет вечным").toBeGreaterThan(0);
    expect(
      повторов,
      "повтор «отошёл» уходит каждую минуту — это шквал на пустом месте",
    ).toBeLessThanOrEqual(5);
  });

  it("активность в СОСЕДНЕЙ вкладке не даёт поставить «отошёл»", () => {
    renderHook(() => useAutoAway());

    // Человек работает в другой вкладке: она отмечает активность каждые десять
    // минут. Эта вкладка своих событий не видит вовсе.
    for (let i = 0; i < 6; i += 1) {
      vi.advanceTimersByTime(10 * МИН);
      localStorage.setItem(КЛЮЧ_АКТИВНОСТИ, String(Date.now()));
    }

    expect(
      запросы,
      "забытая вкладка объявила отошедшим человека, который работает в соседней",
    ).toHaveLength(0);
  });

  it("рабочая вкладка возвращает «на месте», если соседняя поставила «отошёл»", () => {
    renderHook(() => useAutoAway());

    // Соседняя вкладка молчала порог и отправила «отошёл». Общая запись это
    // помнит; память ЭТОЙ вкладки по-прежнему говорит «на месте».
    localStorage.setItem(КЛЮЧ_СТАТУСА, "away");
    usePresenceStore.getState().set("online");

    window.dispatchEvent(new KeyboardEvent("keydown", { key: "a" }));

    expect(
      запросы.at(-1)?.status,
      "человек работает, а числится отошедшим: автораздача его обходит, и никто не понимает почему",
    ).toBe("online");
  });

  it("порог — ровно 30 минут, как просил владелец", () => {
    renderHook(() => useAutoAway());
    vi.advanceTimersByTime(29 * МИН);
    expect(запросы, "порог сработал раньше тридцати минут").toHaveLength(0);
    vi.advanceTimersByTime(2 * МИН);
    expect(запросы.at(-1)?.status, "порог не сработал и после тридцати минут").toBe("away");
  });

  it("недоступное хранилище не ломает работу", () => {
    /*
     * Приватный режим, запрет на хранилище, переполнение. Раз общая запись —
     * новая зависимость, она обязана уметь отсутствовать: иначе правка ради
     * второй вкладки сломает присутствие у того, у кого вкладка одна.
     */
    const было = Storage.prototype.setItem;
    const былоЧтение = Storage.prototype.getItem;
    Storage.prototype.setItem = () => {
      throw new DOMException("QuotaExceededError");
    };
    Storage.prototype.getItem = () => {
      throw new DOMException("SecurityError");
    };
    try {
      renderHook(() => useAutoAway());
      vi.advanceTimersByTime(31 * МИН);
      expect(запросы.at(-1)?.status, "без localStorage авто-«отошёл» перестал работать").toBe(
        "away",
      );
    } finally {
      Storage.prototype.setItem = было;
      Storage.prototype.getItem = былоЧтение;
    }
  });
});
