import { afterEach, beforeEach, describe, expect, it, vi } from "vitest";
import { queryClient } from "@/app/queryClient";
import { CONVERSATIONS_LIST_KEY, qk } from "@/shared/api/queryKeys";
import {
  applyConversationPatch,
  догнатьЕслиОтстали,
  забытьДогоны,
} from "@/shared/realtime/applyWsEvent";
import { useChatUiStore } from "@/shared/stores/chatUiStore";

/**
 * ЖАЛОБА ВЛАДЕЛЬЦА 29.08: «приходит уведомление, а сообщение в чате не
 * появляется — приходится обновлять страницу».
 *
 * ПОЧЕМУ ТАК ВЫХОДИЛО. Низ ленты живёт исключительно на сокете: у запроса
 * стоит `getNextPageParam: () => null`, и ни `refetchInterval`, ни
 * `refetchOnWindowFocus` у него нет. Потерялся кадр `message:new` — лента не
 * узнает о сообщении никогда. А потеряться он может и без обрыва: хаб не
 * буферизирует, кадры «внутри диалога» уходят только подписанным, часть
 * отсекается по правам. Уведомление при этом едет своим маршрутом и доезжает.
 *
 * Тихая сверка чинила это раз в две минуты — но столько никто не ждёт.
 *
 * ЧТО СТОРОЖИМ ЗДЕСЬ. Не текст исходника, а поведение: строка списка ушла
 * вперёд → лента догоняется немедленно; не ушла → не догоняется; и главное —
 * догоняется РОВНО ОДИН РАЗ на метку, иначе экран уйдёт в бесконечный
 * перезапрос, что хуже исходной жалобы.
 */

const CONV = "11111111-1111-1111-1111-111111111111";

/**
 * Шпион отдельной функцией — ради вывода типа.
 *
 * `invalidateQueries` дженерик, и `ReturnType<typeof vi.spyOn>` сужается до
 * безымянной сигнатуры, с которой он не сходится. Через собственную функцию
 * TypeScript выводит тип сам, и объявлять его руками не приходится.
 */
function поставитьШпиона() {
  return vi.spyOn(queryClient, "invalidateQueries").mockResolvedValue(undefined);
}

/** Строка списка с известной меткой последнего сообщения. */
function положитьСтроку(lastMessageAt: string): void {
  queryClient.setQueryData([...CONVERSATIONS_LIST_KEY, "тест"], {
    pages: [
      {
        items: [{ id: CONV, last_message_at: lastMessageAt, unread_count: 0, tags: [] }],
        page: { limit: 50, has_more: false, next_cursor: null },
      },
    ],
    pageParams: [null],
  });
}

/** Лента с одним сообщением заданного времени. */
function положитьЛенту(createdAt: string): void {
  queryClient.setQueryData(qk.messages.list(CONV), {
    pages: [
      {
        items: [{ id: "m1", created_at: createdAt, direction: "in", body: "привет" }],
        page: { has_more_before: false, prev_cursor: null },
      },
    ],
    pageParams: [null],
  });
}

describe("Лента замечает, что отстала, и догоняется сама", () => {
  let догон: ReturnType<typeof поставитьШпиона>;

  beforeEach(() => {
    queryClient.clear();
    забытьДогоны();
    useChatUiStore.setState({ activeConversationId: CONV });
    догон = поставитьШпиона();
  });

  afterEach(() => {
    догон.mockRestore();
    queryClient.clear();
    забытьДогоны();
  });

  it("строка знает о более свежем сообщении — лента перезапрашивается", () => {
    положитьЛенту("2026-08-29T10:00:00Z");
    положитьСтроку("2026-08-29T10:05:00Z"); // на пять минут вперёд

    догнатьЕслиОтстали(CONV);

    expect(догон, "пропажу не заметили — человеку снова остаётся F5").toHaveBeenCalledWith(
      expect.objectContaining({ queryKey: qk.messages.list(CONV) }),
    );
  });

  it("лента не отстала — лишнего запроса нет", () => {
    положитьЛенту("2026-08-29T10:05:00Z");
    положитьСтроку("2026-08-29T10:05:00Z");

    догнатьЕслиОтстали(CONV);

    expect(догон, "перезапрос на ровном месте — это лишний запрос на каждый кадр").not.toHaveBeenCalled();
  });

  it("секундное расхождение перезапросом не считается", () => {
    /*
     * Часы клиента и сервера расходятся, да и порядок записи не гарантирован.
     * Без допуска экран дёргался бы на пустом месте.
     */
    положитьЛенту("2026-08-29T10:00:00Z");
    положитьСтроку("2026-08-29T10:00:01Z");

    догнатьЕслиОтстали(CONV);

    expect(догон).not.toHaveBeenCalled();
  });

  it("догоняем один раз на метку, а не бесконечно", () => {
    /*
     * ⚠ САМАЯ ВАЖНАЯ ПРОВЕРКА. Строку двигают и сообщения, которых в ленте
     * может не оказаться. Без памяти о том, за какой меткой уже гнались,
     * каждый следующий кадр запускал бы новый перезапрос — и экран ушёл бы в
     * бесконечный цикл. Это было бы заметно хуже исходной жалобы.
     */
    положитьЛенту("2026-08-29T10:00:00Z");
    положитьСтроку("2026-08-29T10:05:00Z");

    догнатьЕслиОтстали(CONV);
    догнатьЕслиОтстали(CONV);
    догнатьЕслиОтстали(CONV);

    expect(догон, "догон повторился на ту же метку — это петля").toHaveBeenCalledTimes(1);
  });

  it("чужой диалог не трогаем", () => {
    /*
     * Догонять закрытые ленты значит платить запросом за то, чего никто не
     * видит: тринадцать диспетчеров на утреннем наплыве дали бы шквал.
     */
    useChatUiStore.setState({ activeConversationId: "другой-диалог" });
    положитьЛенту("2026-08-29T10:00:00Z");
    положитьСтроку("2026-08-29T10:05:00Z");

    догнатьЕслиОтстали(CONV);

    expect(догон).not.toHaveBeenCalled();
  });

  it("проверка действительно вызывается из обработчика кадра", () => {
    /*
     * ⚠ БЕЗ ЭТОГО ТЕСТА ОСТАЛЬНЫЕ ПЯТЬ СТОРОЖИЛИ БЫ МЁРТВУЮ ФУНКЦИЮ.
     *
     * Они зовут `догнатьЕслиОтстали` напрямую и остались бы зелёными, даже
     * убери кто-нибудь вызов из `applyConversationPatch`. Механизм, написанный
     * и не подключённый, — самая частая поломка в этом проекте: за один день
     * 29.08 такое ловилось трижды (пауза бота, признак `mine`, `/presence`).
     *
     * Здесь кадр идёт настоящим путём: строка уезжает вперёд патчем, кадра
     * ленты нет вовсе — ровно та жалоба, ради которой всё и делалось.
     */
    положитьЛенту("2026-08-29T10:00:00Z");
    положитьСтроку("2026-08-29T10:00:00Z");

    applyConversationPatch(CONV, { last_message_at: "2026-08-29T10:05:00Z" });

    expect(
      догон,
      "обработчик кадра не зовёт проверку — лента снова узнает о сообщении только с F5",
    ).toHaveBeenCalledWith(expect.objectContaining({ queryKey: qk.messages.list(CONV) }));
  });

  it("лента не открывалась — догонять нечего", () => {
    положитьСтроку("2026-08-29T10:05:00Z"); // ленты в кэше нет вовсе

    догнатьЕслиОтстали(CONV);

    expect(догон, "создали запрос для ленты, которую никто не открывал").not.toHaveBeenCalled();
  });
});
