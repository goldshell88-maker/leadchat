// @ts-expect-error — типов Node в проекте нет (tsconfig types: ["vite/client"]),
// как в buttonCanon.test.ts: сторож только читает файл.
import { readFileSync } from "node:fs";
import { describe, expect, it } from "vitest";

const src = readFileSync("src/features/settings/leads/LeadsTab.tsx", "utf-8");

/**
 * СЛОВА ЭКРАНА «ЗАЯВКИ» — ЧАСТЬ ЛОГИКИ, И ОНИ УЖЕ ОДИН РАЗ СОВРАЛИ.
 *
 * С 14 августа направление заявки решает ОБЪЯВЛЕНИЕ (`lead_direction.detect`),
 * а выбор лид-центра у канала — запасной путь. Экран же продолжал говорить
 * «Не выбран — заявки не уходят», и владелец дважды прочитал его дословно:
 * «у аккаунта нет конкретно направления, сам бот должен решать». Бот решал —
 * экран пугал. Сторож держит слова в согласии с сервером.
 */
describe("Экран «Заявки»: подписи говорят правду про направление", () => {
  it("пустой выбор больше не грозит «заявки не уходят»", () => {
    expect(src).not.toContain("заявки не уходят");
    expect(src).toContain("Не выбран — по проблеме и объявлению");
  });

  it("описание объясняет, что направление решает объявление, а выбор — запасной", () => {
    expect(src).toContain("по проблеме клиента в переписке");
    expect(src).toContain("объявление, в которое написал клиент");
    expect(src).toContain("Выбор здесь");
    // Обещание журнала осталось: несработавшие оба пути видны, а не молчат.
    expect(src).toContain("а не пропадает молча");
  });

  it("селект называется запасным и в имени для скринридера", () => {
    expect(src).toContain("Запасной лид-центр канала");
  });
});

/*
 * ⚠ ОБРЕЗКА ЗНАЧЕНИЯ ОБЯЗАНА БЫТЬ ВИДНА (29.08).
 *
 * Замер на бою: все 31 поле выбора лид-центра были ровно 280 px при нужных
 * 287, и на экране стояло «Не выбран — по проблеме и объявлени». Слово теряло
 * последнюю букву, а браузерное `text-overflow: clip` не оставляло НИКАКОГО
 * признака, что текст обрезан: фраза читалась как целая, с опечаткой.
 *
 * Ширину подняли до 320, но одной ширины мало — подпись могут удлинить.
 * Страховка глобальная, поэтому и проверяется в общем файле стилей.
 */
describe("Поля не врут про своё значение", () => {
  it("значение, не влезшее в поле, обрезается многоточием", () => {
    const css: string = readFileSync("src/app/lc-base.css", "utf8");
    const правило = /\.lc-field input[^{]*\{([^}]*)\}/.exec(css);
    expect(правило, "страховка от немой обрезки пропала из lc-base.css").not.toBeNull();
    expect(правило?.[1]).toMatch(/text-overflow:\s*ellipsis/);
  });

  it("поле выбора лид-центра шире самой длинной подписи", () => {
    const src: string = readFileSync("src/features/settings/leads/LeadsTab.tsx", "utf8");
    /*
     * ⚠ ИЩЕМ ШИРИНУ ИМЕННО ЭТОГО ПОЛЯ, А НЕ ПЕРВУЮ ПОХОЖУЮ. Первая проверка
     * брала `/w=\{(\d+)\}/` по всему файлу и ловила `fw={600}` в заголовке
     * секции: 600 больше 287, тест зеленел всегда — в том числе на диверсии,
     * вернувшей ширину на 280. Границу слова здесь не поставить (`f` — тоже
     * буква), поэтому сначала вырезаем сам `<Select>` по его данным.
     */
    const поле = /<Select[\s\S]*?data=\{ЦЕНТРЫ\}[\s\S]*?\/>/.exec(src);
    expect(поле, "поле выбора лид-центра пропало из LeadsTab").not.toBeNull();
    const w = /\bw=\{(\d+)\}/.exec(поле?.[0] ?? "");
    expect(w, "у поля выбора пропала ширина").not.toBeNull();
    // 287 px — измеренная ширина подписи «Не выбран — по проблеме и объявлению».
    expect(Number(w?.[1]), "ширина снова меньше самой длинной подписи").toBeGreaterThan(287);
  });
});
