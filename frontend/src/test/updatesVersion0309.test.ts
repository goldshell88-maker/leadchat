import { describe, expect, it } from "vitest";
import { RELEASES } from "@/features/updates/changelog";
import { LATEST_VERSION } from "@/features/updates/version";

/**
 * Версия последнего выпуска вынесена в отдельный файл — чтобы стартовый чанк
 * не вёз 17 КБ текстов ради одной строки (разбор 03.09).
 *
 * ⚠ ЦЕНА РАЗВЯЗКИ — ВОЗМОЖНОЕ РАСХОЖДЕНИЕ, И ЭТОТ ТЕСТ ЕСТЬ ИМЕННО ПОЭТОМУ.
 * Разойдись эти два значения — и точка «есть непрочитанное» в меню начнёт
 * врать: либо горит всегда, либо не загорается на новый выпуск. Заметить это
 * глазами почти нельзя.
 */
describe("версия выпуска", () => {
  it("совпадает с первым выпуском журнала", () => {
    expect(
      LATEST_VERSION,
      "version.ts разошёлся с changelog.ts — точка «есть непрочитанное» будет врать",
    ).toBe(RELEASES[0]?.version);
  });
});
