/**
 * Правка на месте выглядит как текст с курсором, а не как коробка.
 *
 * ⚠ ЖАЛОБА ВЛАДЕЛЬЦА 05.09 СО СКРИНШОТОМ: «сделай так, чтобы не было вот таких
 * полей при изменении текста». На снимке — имя канала, превратившееся в поле с
 * рамкой по периметру и зелёным кольцом фокуса во всю коробку.
 *
 * ПОЧЕМУ ЭТО ВАЖНЕЕ, ЧЕМ ВЫГЛЯДИТ. Правка на месте держится на обещании: ты
 * правишь ТО ЖЕ САМОЕ, что читал. Стоит слову сменить кегль, подложку и
 * обрасти рамкой — обещание нарушено, и человек на мгновение ищет, куда делось
 * имя и что это за форма появилась.
 *
 * Признак «сейчас правится» несёт тонкая черта снизу: её хватает и глазу, и
 * требованию видимого фокуса.
 */
// @ts-expect-error — типов Node в проекте нет (tsconfig types: ["vite/client"]).
import { readFileSync } from "node:fs";
import { describe, expect, it } from "vitest";

/*
 * ⚠ КОММЕНТАРИИ ВЫРЕЗАЕМ ДО РАЗБОРА. В них встречается фигурная скобка — здесь
 * это `fw={600}` в объяснении, — и `[^}]*` обрывает блок ровно на ней: правило
 * читалось до половины, а половина не содержала того, что проверяется. Соседние
 * сторожа проекта режут комментарии по той же причине.
 */
const CSS = (readFileSync("src/features/settings/accounts/accounts.css", "utf-8") as string).replace(
  /\/\*[\s\S]*?\*\//g,
  "",
);

function поле(): string {
  const m = CSS.match(
    /^\.account-row__rename-field \.mantine-Input-input\s*\{([^}]*)\}/ms,
  );
  expect(m, "нет правила для поля правки имени канала").toBeTruthy();
  return m![1];
}

describe("Правка имени канала на месте", () => {
  it("у поля нет рамки по периметру и своей подложки", () => {
    const тело = поле();
    expect(тело, "рамка по периметру вернулась").toMatch(/(?:^|\s)border:\s*0/);
    expect(тело, "своя подложка вернулась").toMatch(/background:\s*transparent/);
  });

  it("признак правки — черта снизу, а не кольцо", () => {
    expect(поле()).toMatch(/border-bottom:\s*2px solid/);
    const фокус = CSS.match(
      /\.account-row__rename-field \.mantine-Input-input:focus[^{]*\{([^}]*)\}/s,
    );
    expect(фокус, "нет правила фокуса").toBeTruthy();
    // Кольцо Mantine рисуется box-shadow'ом: вдвоём с чертой они дают коробку.
    expect(фокус![1]).toMatch(/box-shadow:\s*none/);
  });

  it("кегль и насыщенность повторяют само имя — строка не дёргается", () => {
    /*
     * Имя набрано `fw={600} fz="md"`. Разойдись поле хоть на ступень — при
     * переходе к правке строка канала подпрыгнет, и это заметно сильнее, чем
     * кажется: рядом тридцать четыре такие же строки.
     */
    const тело = поле();
    expect(тело).toMatch(/font-size:\s*var\(--lc-fz-card\)/);
    expect(тело).toMatch(/font-weight:\s*var\(--lc-fw-semibold\)/);
  });
});
