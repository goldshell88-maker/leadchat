import { describe, expect, it } from "vitest";
import { подобрать } from "@/features/templates/rankByContext";
import type { TemplateDto } from "@/shared/api/types";

/**
 * БЫСТРЫЕ ОТВЕТЫ ПОДБИРАЮТСЯ ПО ТОМУ, ЧТО ПИШЕТ КЛИЕНТ.
 *
 * Просьба владельца дословно: «он должен понимать, что человек пытается
 * написать, и исходя из его сообщений выдавать варианты». Плоский список этого
 * не делает: у диспетчера полтора десятка заготовок, нужная стоит третьей с
 * конца, и пока её найдёшь глазами — быстрее набрать руками.
 *
 * ⚠ БЕЗ МОДЕЛИ, И ЭТО РЕШЕНИЕ. Полоса живёт над пустым полем, человек смотрит
 * на неё доли секунды. Поход к модели — сотни миллисекунд, деньги за каждый
 * диалог и чужая доступность ради задачи «отсортировать пятнадцать строк».
 * Сравнение слов отвечает мгновенно и ОБЪЯСНИМО: видно, почему заготовка
 * всплыла.
 */

function t(id: string, title: string, body: string, used = 0): TemplateDto {
  return { id, owner_id: "u1", title, body, folder: null, used_count: used };
}

const ЗАГОТОВКИ = [
  t("1", "Работаем без выходных", "Работаем каждый день с 9 до 21"),
  t("2", "Цена замены экрана", "Замена экрана на телевизоре — от 8900 ₽"),
  t("3", "Выезд сегодня", "Мастер приедет сегодня, назовите адрес"),
  t("4", "Про стиральные машины", "Стиральные машины чиним на дому"),
];

describe("Подбор заготовок под слова клиента", () => {
  it("клиент про телевизор — первой идёт заготовка про телевизор", () => {
    const [первая] = подобрать(ЗАГОТОВКИ, ["Разбился экран у телевизора, сколько замена?"]);
    expect(первая.title).toBe("Цена замены экрана");
  });

  it("клиент про стиралку — первой идёт про стиральные машины", () => {
    const [первая] = подобрать(ЗАГОТОВКИ, ["Стиральная машина не сливает воду"]);
    expect(первая.title).toBe("Про стиральные машины");
  });

  it("склонение не мешает: «телевизора» находит «телевизоре»", () => {
    /*
     * Русский склоняет, и точное совпадение слов связь теряет. Сравниваем по
     * общему началу слова — это ловит падежи и число, а словарь лемм на
     * мегабайты в бандл ради сортировки пятнадцати строк не кладём.
     */
    const [первая] = подобрать(ЗАГОТОВКИ, ["чиню телевизоры"]);
    expect(первая.title).toBe("Цена замены экрана");
  });

  it("совпадение в НАЗВАНИИ весит больше, чем в теле", () => {
    /*
     * Название пишут как ярлык темы, и совпадение по нему точнее, чем
     * случайное слово в середине длинного текста.
     */
    const набор = [
      t("a", "Общие условия", "Работаем с выездом, адрес уточним при звонке"),
      t("b", "Выезд сегодня", "Мастер свободен"),
    ];
    const [первая] = подобрать(набор, ["Когда возможен выезд?"]);
    expect(первая.title).toBe("Выезд сегодня");
  });

  it("клиент молчит — порядок остаётся исходным", () => {
    expect(подобрать(ЗАГОТОВКИ, []).map((x) => x.id)).toEqual(["1", "2", "3", "4"]);
  });

  it("ничто не подошло — порядок тоже исходный, а не перетасованный", () => {
    /*
     * Заготовки, ничем не отличающиеся по подходящести, обязаны стоять там же,
     * где стояли: иначе полоса перетасовывается на каждое сообщение клиента, и
     * мышечная память диспетчера перестаёт работать.
     */
    expect(подобрать(ЗАГОТОВКИ, ["ключи от квартиры"]).map((x) => x.id)).toEqual([
      "1",
      "2",
      "3",
      "4",
    ]);
  });

  it("вежливые слова темой не считаются", () => {
    /*
     * «Здравствуйте», «пожалуйста», «сколько» есть в каждом втором сообщении:
     * считай мы их, наверх всплывала бы самая длинная заготовка, а не нужная.
     */
    expect(подобрать(ЗАГОТОВКИ, ["Здравствуйте, пожалуйста скажите"]).map((x) => x.id)).toEqual([
      "1",
      "2",
      "3",
      "4",
    ]);
  });

  it("считаем по НЕСКОЛЬКИМ репликам, а не по одной", () => {
    const порядок = подобрать(ЗАГОТОВКИ, ["Здравствуйте", "Телевизор не включается"]);
    expect(порядок[0].title).toBe("Цена замены экрана");
  });
});

describe("Популярность заготовок", () => {
  /*
   * ⚠ ПРОСЬБА ВЛАДЕЛЬЦА 29.08: «сделай популярность ответов, когда пишешь для
   * быстрых ответов». Общих заготовок 39 плюс личные, а подсказка показывает
   * пять: какие пять, должен решать живой сигнал, а не алфавит.
   */
  it("клиент молчит — первыми идут самые ходовые", () => {
    const набор = [
      t("редкая", "Запчасти", "У вас всё в наличии уже есть?", 46),
      t("ходовая", "Здравствуйте", "Здравствуйте!", 6655),
      t("средняя", "Фото", "Фото есть?", 98),
    ];
    expect(подобрать(набор, []).map((x) => x.id)).toEqual(["ходовая", "средняя", "редкая"]);
  });

  it("СМЫСЛ ВАЖНЕЕ ЧАСТОТЫ, и это главное правило порядка", () => {
    /*
     * Клиент написал про стиральную машину — ответ про неё обязан стоять выше
     * «Здравствуйте», сколько бы раз последнее ни применяли. Иначе самая
     * ходовая заготовка навсегда займёт первую строку, и подсказка перестанет
     * отвечать на вопрос клиента.
     */
    const набор = [
      t("привет", "Здравствуйте", "Здравствуйте!", 6655),
      t("стиралка", "Стиральные машины", "Стиральные машины чиним на дому", 12),
    ];
    const [первая] = подобрать(набор, ["Стиральная машина не сливает воду"]);
    expect(первая.id).toBe("стиралка");
  });

  it("при равном смысле решает частота", () => {
    const набор = [
      t("реже", "Выезд завтра", "Мастер приедет завтра", 10),
      t("чаще", "Выезд сегодня", "Мастер приедет сегодня", 900),
    ];
    const [первая] = подобрать(набор, ["когда приедет мастер"]);
    expect(первая.id).toBe("чаще");
  });

  it("поля нет вовсе — порядок прежний, а не рассыпавшийся", () => {
    /*
     * Сборка фронта переживает сервер, который поля ещё не присылает. В этот
     * промежуток подсказка обязана работать как раньше.
     */
    const без: TemplateDto[] = [
      { id: "1", owner_id: "u1", title: "Первая", body: "Раз", folder: null },
      { id: "2", owner_id: "u1", title: "Вторая", body: "Два", folder: null },
    ];
    expect(подобрать(без, []).map((x) => x.id)).toEqual(["1", "2"]);
  });
});

describe("ПРОВОДКА: применение считается", () => {
  it("вставка шаблона отмечает применение — в единственной точке", async () => {
    /*
     * Через `insertTemplate` идут ОБА пути вставки: полоса подсказок и пикер по
     * «⚡»/«/». Поставь мы отметку на каждом по отдельности, третий путь однажды
     * появился бы мимо, и популярность считалась бы по половине применений —
     * то есть врала бы тем сильнее, чем активнее пользуются вторым способом.
     */
    // @ts-expect-error — типов Node в проекте нет (tsconfig types: ["vite/client"]).
    const { readFileSync } = await import("node:fs");
    const src = (readFileSync(
      "src/features/chats/components/composer/Composer.tsx",
      "utf-8",
    ) as string)
      .replace(/\/\*[\s\S]*?\*\//g, " ")
      .replace(/\/\/[^\n]*/g, " ");
    expect(src, "применение не считается — популярность замрёт на посеве").toContain(
      "отметитьПрименение(t.id)",
    );
  });
});
