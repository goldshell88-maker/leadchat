import { describe, expect, it } from "vitest";
// @ts-expect-error — типов Node в проекте нет (tsconfig types: ["vite/client"]),
// а ставить @types/node ради одного сторожа несоразмерно. Ровно так же
// поступает соседний сторож стилей mantineStyles.test.ts.
import { readFileSync, readdirSync, statSync } from "node:fs";

/**
 * У каждого сочетания клавиш должен быть слушатель (#31).
 *
 * ЧТО СЛУЧИЛОСЬ. Ctrl+T («Передать диалог») стоял в шпаргалке, нажимался,
 * поднимал счётчик в шине действий — и на этом всё: на `transferNonce` не был
 * подписан НИ ОДИН файл во всём интерфейсе. Человек жал клавишу, ничего не
 * происходило, и он решал, что сломалось приложение. Сломана была шпаргалка,
 * обещавшая несуществующее.
 *
 * ПОЧЕМУ ЭТО НЕ ЛОВИЛОСЬ. Ни типы, ни линтер тут ни при чём: счётчик
 * объявлен, функция вызывается, всё «работает». Отсутствует только потребитель
 * — а его отсутствие ничем не отличается от «ещё не написали».
 *
 * ПОЧЕМУ ПРОВЕРКА ТЕКСТОМ, А НЕ ПОВЕДЕНИЕМ. Поведенческий тест на каждое
 * сочетание требует поднять пол-приложения и всё равно проверит только те,
 * про которые вспомнили. Этот же ловит ровно ту болезнь, что была: счётчик
 * есть, слушателя нет. Дёшево и не пропускает.
 */

// Пути относительные, от каталога запуска (frontend) — тем же способом, что и
// соседние тесты, читающие исходники. `node:path` и `node:url` в проекте не
// типизированы (tsconfig тянет только vite/client), и первая версия этого
// файла на них спотыкалась: тесты шли, а typecheck падал.
const ROOT = "src";
const BUS = "src/features/hotkeys/actionBus.ts";

/**
 * Код без комментариев.
 *
 * БЕЗ ЭТОГО СТОРОЖ ЗЕЛЕНЕЛ НА СЛОМАННОМ. Проверено: если убрать слушателя из
 * ленты, но оставить комментарий, В КОТОРОМ УПОМЯНУТ `transferNonce`, поиск по
 * тексту находит имя и считает, что потребитель есть. То есть сторож проверял
 * бы наличие рассказа о коде вместо самого кода — ровно та болезнь, которую он
 * и заведён ловить.
 */
function code(source: string): string {
  return source.replace(/\/\*[\s\S]*?\*\//g, "").replace(/\/\/.*$/gm, "");
}

function sources(dir: string, out: string[] = []): string[] {
  for (const entry of readdirSync(dir)) {
    const path = `${dir}/${entry}`;
    if (statSync(path).isDirectory()) {
      sources(path, out);
    } else if (/\.(ts|tsx)$/.test(entry) && path !== BUS) {
      out.push(path);
    }
  }
  return out;
}

/** Имена счётчиков прямо из объявления шины — список не дублируем. */
function nonces(): string[] {
  const source = readFileSync(BUS, "utf8");
  return [...new Set([...source.matchAll(/\b(\w+Nonce)\b/g)].map((m) => m[1]))];
}

describe("Шина действий: у каждого сочетания есть слушатель", () => {
  const files = sources(ROOT).filter((p) => !p.includes("/test/"));
  const corpus = files.map((p) => code(readFileSync(p, "utf8"))).join("\n");

  it("счётчики вообще объявлены — иначе проверка была бы пустой", () => {
    // Без этого удаление шины сделало бы тест вечно зелёным.
    expect(nonces().length).toBeGreaterThan(3);
  });

  it.each(nonces())("%s кто-то читает", (nonce) => {
    expect(corpus).toContain(nonce);
  });
});
