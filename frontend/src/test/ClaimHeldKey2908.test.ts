// @ts-expect-error — типов Node в проекте нет (tsconfig types: ["vite/client"]).
import { readFileSync } from "node:fs";
import { describe, expect, it } from "vitest";
import { БЕЗ_АВТОПОВТОРА } from "@/features/hotkeys/catalog";

/**
 * СНИМОК ВЛАДЕЛЬЦА 29.08: стопка красных тостов «Не получилось принять диалог —
 * вы уже приняли этот диалог», четыре подряд, «когда зажимаешь кнопку».
 *
 * Дефектов здесь два, и второй хуже первого.
 *
 * ПЕРВЫЙ — АВТОПОВТОР. Браузер шлёт `keydown` десятки раз в секунду, пока
 * клавишу держат. Обработчик сочетаний признак `repeat` не смотрел вовсе, и
 * каждое повторение уходило на сервер отдельным запросом.
 *
 * ВТОРОЙ — ПОВТОР СВОЕГО ЖЕ ПРИНЯТИЯ СЧИТАЛСЯ ОТКАЗОМ. Сервер помечает такой
 * случай признаком `mine` и делает это с самого начала: в `app/services/inbox.py`
 * рядом стоит комментарий «фронту достаточно этого флага, чтобы второй клик по
 * „Принять“ своей же кнопкой не выглядел ошибкой». Но в типе фронта поля не
 * было — то есть поле на проводе существовало, а для кода его не существовало.
 * Система четырежды пожаловалась на действие, которое ей удалось.
 */

const ОБРАБОТЧИК = readFileSync("src/features/hotkeys/useChatHotkeys.ts", "utf-8") as string;
const ТИПЫ = readFileSync("src/shared/api/types.ts", "utf-8") as string;
const ПО_КЛАВИШЕ = readFileSync("src/features/chats/inbox/claimFromQueue.ts", "utf-8") as string;
const ПО_КНОПКЕ = readFileSync("src/features/chats/inbox/useInbox.ts", "utf-8") as string;

describe("Зажатая клавиша не повторяет то, что меняет состояние", () => {
  it("принятие, отклонение, закрытие и передача — без автоповтора", () => {
    for (const действие of ["claim", "decline", "close", "transfer"] as const) {
      expect(
        БЕЗ_АВТОПОВТОРА.has(действие),
        `«${действие}» меняет состояние диалога и повторяться не должно`,
      ).toBe(true);
    }
  });

  it("листание автоповтором пользуется — и остаётся при нём", () => {
    /*
     * ⚠ ОБРАТНАЯ СТОРОНА, И ЕЁ ЛЕГКО СЛОМАТЬ «ЗАОДНО». Запретить повтор всем
     * сочетаниям проще и выглядит аккуратнее, но зажать J и проехать по списку
     * — это ровно то, ради чего сочетания и заводились. Починив спам, легко
     * молча отобрать листание: жалобы не будет, человек просто перестанет
     * пользоваться клавишами.
     */
    for (const действие of ["listNext", "listPrev", "queueNext", "unreadNext"] as const) {
      expect(
        БЕЗ_АВТОПОВТОРА.has(действие),
        `«${действие}» — это листание, автоповтор ему нужен`,
      ).toBe(false);
    }
  });

  it("обработчик действительно смотрит на признак повтора", () => {
    // Список без проверки — мёртвый: он врёт следующему читателю о том, что
    // защита есть.
    expect(ОБРАБОТЧИК, "обработчик сочетаний не проверяет e.repeat").toMatch(
      /e\.repeat\s*&&\s*БЕЗ_АВТОПОВТОРА\.has/,
    );
  });
});

describe("Повторное принятие своего диалога — не ошибка", () => {
  it("признак mine объявлен в типе, а не только на проводе", () => {
    const блок = /export interface AlreadyClaimedDetails \{([\s\S]*?)\}/.exec(ТИПЫ);
    expect(блок, "тип AlreadyClaimedDetails пропал").not.toBeNull();
    expect(блок?.[1], "поле mine снова не доезжает до фронта").toMatch(/\bmine\b/);
  });

  it("путь горячей клавиши уводит свой диалог в успех, а не в тост", () => {
    expect(ПО_КЛАВИШЕ, "claimFromQueue снова не разбирает mine").toMatch(/детали\?\.mine/);
    // И именно в успех: открыть диалог и поставить курсор.
    /*
     * ⚠ КОНЕЦ ВЕТКИ ИЩЕТСЯ ПО ОТСТУПУ, А НЕ ПО ПЕРВОЙ ЖЕ СКОБКЕ. Ленивое
     * `[\s\S]*?\}` обрывалось на `}` внутри `${convId}` — и тест объявил,
     * что фокуса в ветке нет, хотя он там второй строкой.
     */
    const ветка = /if \(детали\?\.mine\) \{([\s\S]*?)\n {6}\}/.exec(ПО_КЛАВИШЕ);
    expect(ветка?.[1]).toMatch(/navigate\(/);
    expect(ветка?.[1]).toMatch(/requestComposerFocus\(/);
    expect(ветка?.[1], "в ветку успеха попал показ тоста").not.toMatch(/showToast/);
  });

  it("путь кнопки не выбрасывает человека из его же диалога", () => {
    /*
     * До правки свой диалог попадал в общую ветку «уже занят»: тост
     * «Диалог принял <вы сами>» И `leaveQueue`, то есть уход на другой диалог.
     * Тост можно проигнорировать, а потерянный диалог надо искать заново.
     */
    expect(ПО_КНОПКЕ, "useClaimConversation снова не разбирает свой случай").toMatch(
      /мойЖеДиалог\(err\)/,
    );
    const ветка = /if \(мойЖеДиалог\(err\)\) \{([\s\S]*?)\n {6}\}/.exec(ПО_КНОПКЕ);
    expect(ветка, "ветка своего диалога пропала").not.toBeNull();
    expect(ветка?.[1], "из своей ветки снова уводят через leaveQueue").not.toMatch(/leaveQueue/);
    expect(ветка?.[1], "на удавшееся действие снова жалуются тостом").not.toMatch(/showToast/);
  });
});
