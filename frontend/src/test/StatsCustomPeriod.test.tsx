import { describe, expect, it, vi } from "vitest";
import { screen } from "@testing-library/react";
import userEvent from "@testing-library/user-event";

import { StatsFilters } from "@/features/stats/components/StatsFilters";
import { renderWithProviders } from "./render";

/**
 * ПРОИЗВОЛЬНЫЙ ПЕРИОД — ВЫБРАТЬ ЕГО БЫЛО НЕЛЬЗЯ ВООБЩЕ.
 *
 * НАЙДЕНО ПРОВЕРКОЙ ИНТЕРФЕЙСА 12 августа, дословно: «клик по дню ничего не
 * делает, день не подсвечивается как начало диапазона, запросов к API нет».
 * Проверяющий грешил на управляемый компонент — и был прав.
 *
 * `DatePickerInput` управляемый: что показать, решает `value`. Оно собиралось
 * ТОЛЬКО из применённого периода, а первый клик приходит как `[дата, null]` —
 * применять нечего, и обработчик выходил ранним `return`. Состояние не
 * менялось, календарь перерисовывался со старым диапазоном, клик пропадал.
 * Второй клик после этого выглядел для календаря снова первым, и так по кругу.
 *
 * ПОЧЕМУ ЭТО ПРОВЕРЯЕТСЯ ТЕСТОМ, А НЕ ГЛАЗАМИ. Дефект жил в продукте
 * незамеченным: экран открывается, календарь рисуется, дни нажимаются,
 * ошибок в консоли нет. Не работает ровно одна вещь — та, ради которой
 * календарь и открыли, — и увидеть это можно только доведя выбор до конца.
 */

const ПЕРИОД = { dateFrom: "2026-07-14", dateTo: "2026-08-12" };

function показать(onCustomPeriod = vi.fn()) {
  renderWithProviders(
    <StatsFilters
      preset="custom"
      period={ПЕРИОД}
      onPresetChange={vi.fn()}
      onCustomPeriod={onCustomPeriod}
      managerIds={[]}
      onManagersChange={vi.fn()}
      onAccountChange={vi.fn()}
      refreshedAt={null}
      onExport={vi.fn()}
    />,
    { route: "/stats" },
  );
  return onCustomPeriod;
}

/**
 * Кнопка дня в открытом календаре.
 *
 * Ищется по ПОЛНОЙ дате («6 июля 2026»), а не по номеру: именно так день назван
 * в дереве доступности, и по одному номеру нашлись бы ещё и дни соседних
 * месяцев, которые календарь дорисовывает по краям.
 */
function день(подпись: string): HTMLElement {
  return screen.getByRole("button", { name: подпись });
}

async function открытьКалендарь() {
  await userEvent.click(screen.getByLabelText("Произвольный период"));
  // Календарь раскрывается не мгновенно — ждём, иначе первый же клик по дню
  // уйдёт в пустоту, и провал будет выглядеть как дефект продукта.
  await screen.findByRole("button", { name: "15 июля 2026" });
}

describe("Статистика — произвольный период", () => {
  it("первый клик по дню подсвечивает его, а не пропадает", async () => {
    показать();
    await открытьКалендарь();

    await userEvent.click(день("6 июля 2026"));

    /*
     * ВОТ ЭТО И БЫЛО СЛОМАНО. Первый клик обязан оставить след на экране:
     * пока он не оставляет, второй клик для календаря — снова первый, и
     * диапазон не собирается никогда.
     */
    expect(день("6 июля 2026")).toHaveAttribute("data-selected", "true");
  });

  it("два клика собирают диапазон и применяют его", async () => {
    const применён = показать();
    await открытьКалендарь();

    await userEvent.click(день("6 июля 2026"));
    await userEvent.click(день("20 июля 2026"));

    expect(применён).toHaveBeenCalledTimes(1);
    expect(применён).toHaveBeenCalledWith({ dateFrom: "2026-07-06", dateTo: "2026-07-20" });
  });

  it("пока вторая дата не выбрана, период не применяется", async () => {
    const применён = показать();
    await открытьКалендарь();

    await userEvent.click(день("6 июля 2026"));

    // Один клик — это ещё не период. Применить его значило бы показать цифры
    // за диапазон, которого человек не задавал.
    expect(применён).not.toHaveBeenCalled();
  });

  /*
   * ПРО СЛИШКОМ ДЛИННЫЙ ДИАПАЗОН ЗДЕСЬ ПРОВЕРКИ НЕТ, И ЭТО РЕШЕНИЕ.
   *
   * Предел — 366 дней; чтобы дотянуться до него кликами, тест листал бы
   * календарь на год назад, то есть проверял бы навигацию Mantine, а не наш
   * код. Само правило живёт в чистой функции `resolveCustomPeriod` и
   * проверяется там, без календаря.
   */
});
