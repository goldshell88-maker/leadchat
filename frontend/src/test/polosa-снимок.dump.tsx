import { expect, it } from "vitest";
// @ts-expect-error — типов Node в проекте нет (tsconfig types: ["vite/client"]),
// так же поступают соседние снималки и сторожа, читающие исходники.
import { writeFileSync } from "node:fs";
import { UpdateBanner } from "@/platform/UpdateBanner";
import { useUpdateStore } from "@/platform/updateStore";
import { renderWithProviders } from "./render";

const КАТАЛОГ = "./.dump";

it("снимает разметку стопки полос", () => {
  /*
   * `announceBuild` — тот же путь, каким полоса появляется в бою: сверка
   * версии сборки (`platform/buildVersion.ts`) увидела на сервере другой
   * коммит. Подставлять состояние в обход стора значило бы снимать положение,
   * которого приложение не умеет достигать.
   */
  useUpdateStore.getState().announceBuild("1f068d3");

  const { container } = renderWithProviders(
    <div className="lc-banners">
      <UpdateBanner />
    </div>,
  );

  const полоса = container.querySelector(".lc-banners > .lc-update-banner");
  expect(полоса, "полоса не нарисовалась — стенд померил бы пустую стопку").toBeTruthy();

  writeFileSync(`${КАТАЛОГ}/polosa.html`, container.innerHTML, "utf8");
});
