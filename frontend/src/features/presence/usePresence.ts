import { useMutation } from "@tanstack/react-query";
import { create } from "zustand";
import { http } from "@/shared/api/http";
import { showToast } from "@/shared/ui/toast";

/**
 * Своё состояние: «на месте» или «отошёл» (#34).
 *
 * ЗАЧЕМ. Диспетчер отходит от стола — обед, перекур, разговор по телефону.
 * Сказать об этом системе было нечем: присутствие двоичное, и единственный
 * способ выпасть из автораздачи — закрыть приложение. То есть перестать
 * видеть собственные диалоги и через три минуты потерять розданные сторожу
 * возврата.
 *
 * ЧТО ЭТО НЕ ЗНАЧИТ. «Отошёл» — не «ушёл»: человек остаётся в сети, видит
 * свои диалоги, отвечает, коллеги видят его в списках. Меняется одно —
 * автораздача перестаёт давать ему НОВЫЕ обращения.
 *
 * СОСТОЯНИЕ ЖИВЁТ НА СЕРВЕРЕ, а здесь только отражается. Хранить его в
 * браузере значило бы потерять при обновлении страницы и разойтись со
 * второй вкладкой; сервер держит его в том же ключе, что и присутствие.
 */

export type PresenceStatus = "online" | "away";

/**
 * ОБЩАЯ НА ВСЕ ВКЛАДКИ ЗАПИСЬ О ПОСЛЕДНЕМ ОТПРАВЛЕННОМ СТАТУСЕ.
 *
 * ⚠ ЗАЧЕМ (найдено 01.09 при разборе жалобы про «онлайн, а их нет»).
 * Хранилище выше живёт в ПАМЯТИ ОДНОЙ ВКЛАДКИ, а авто-«отошёл» решает по нему,
 * нужно ли идти на сервер: «уже стоит нужное — не ходим». У двух вкладок два
 * разных представления об одном человеке, и они расходятся:
 *
 *   • забытая вторая вкладка молчит порог и ставит «отошёл»;
 *   • человек в это время работает в первой — а её хранилище всё ещё говорит
 *     «на месте», значит вернуть «на месте» она НЕ ПЫТАЕТСЯ.
 *
 * Итог: работающий числится отошедшим, и автораздача его обходит. Сервер
 * при этом прав, врут вкладки — каждая по-своему.
 *
 * Общая запись в localStorage делает представление одним на все вкладки. Она
 * не заменяет сервер (истина там), а лишь отвечает на вопрос «мы это уже
 * отправляли?» — и потому переживает перезагрузку без вреда: худшее, что
 * бывает при расхождении, — один лишний PUT.
 */
const КЛЮЧ_СТАТУСА = "lc:presence:pushed";

/** Что мы (любая вкладка) отправили последним. `null` — не знаем. */
export function отправленныйСтатус(): PresenceStatus | null {
  try {
    const v = localStorage.getItem(КЛЮЧ_СТАТУСА);
    return v === "online" || v === "away" ? v : null;
  } catch {
    // Приватный режим, запрет на хранилище, переполнение — не повод ломать
    // работу. Без общей записи поведение откатывается к прежнему, повкладочному.
    return null;
  }
}

function запомнитьСтатус(status: PresenceStatus): void {
  try {
    localStorage.setItem(КЛЮЧ_СТАТУСА, status);
  } catch {
    // см. выше
  }
}

interface PresenceState {
  status: PresenceStatus;
  set(status: PresenceStatus): void;
}

export const usePresenceStore = create<PresenceState>((set) => ({
  // До первого ответа сервера считаем себя на месте: это и есть состояние
  // только что открытого приложения.
  status: "online",
  set: (status) => set({ status }),
}));

/**
 * Сменить состояние ОТКУДА УГОДНО: из переключателя в интерфейсе или из меню
 * трея десктопа.
 *
 * ⚠ ЗАЧЕМ ОБЩАЯ ФУНКЦИЯ (найдено 27.08). Путей к одному состоянию было два, и
 * ни один не доводил дело до конца:
 *
 *   • переключатель в интерфейсе делал PUT и писал в хранилище — но десктоп об
 *     этом не узнавал: тосты продолжали звучать («отошёл» их глушит), а галочка
 *     в меню трея оставалась на прежнем пункте;
 *   • выбор в трее вызывал ровно `setAwayMode` — тосты замолкали, но на сервер
 *     не уходило НИЧЕГО: коллеги по-прежнему видели человека на месте, и
 *     автораздача продолжала слать ему обращения. В интерфейсе значок тоже не
 *     менялся.
 *
 * Замысел был правильный и записан в tray.rs: «статус меняет фронт: он делает
 * PUT и возвращает подтверждённое значение командой set_presence. Rust сам в
 * API не ходит». Не хватало одного — самой этой функции.
 *
 * Возвращает подтверждённое сервером состояние; откат при отказе — на
 * вызывающем (у переключателя он оптимистичный, см. `useSetPresence`).
 */
/**
 * Сервер сообщил моё состояние, выставленное с другого устройства или вкладки.
 * Экран и общая запись «что отправляли» должны это знать: иначе действие здесь
 * не отправило бы «на месте», считая, что оно и так стоит.
 */
export function принятьСвойСтатус(status: PresenceStatus): void {
  usePresenceStore.getState().set(status);
  запомнитьСтатус(status);
}

export async function pushPresence(
  status: PresenceStatus,
  opts: { auto?: boolean } = {},
): Promise<PresenceStatus> {
  // `auto` — «отошёл» поставила вкладка по тишине, а не человек: сервер
  // сверит с активностью на других устройствах и может ответить «на месте».
  const r = await http.put<{ status: PresenceStatus }>("/presence", {
    status,
    ...(opts.auto ? { auto: true } : {}),
  });
  const подтверждено = r.status ?? status;
  usePresenceStore.getState().set(подтверждено);
  // Единственный писатель статуса — здесь же и общая запись. Развести их
  // значило бы снова получить два ответа на один вопрос: ручной «отошёл» из
  // переключателя или трея не попал бы в общую запись, и авто-возврат счёл бы,
  // что человек и так на месте.
  запомнитьСтатус(подтверждено);
  return подтверждено;
}

export function useSetPresence() {
  const apply = usePresenceStore((s) => s.set);
  return useMutation({
    // Тот же запрос, что и у трея: одна реализация на один смысл.
    mutationFn: (status: PresenceStatus) => pushPresence(status),
    /*
     * Оптимистично — и с честным откатом.
     *
     * Переключатель состояния обязан отвечать мгновенно: человек уже встал
     * из-за стола. Но если запрос не прошёл, оставить галку на «отошёл»
     * нельзя ни в коем случае — человек будет уверен, что новых обращений ему
     * не дают, а они пойдут.
     */
    onMutate: (status) => {
      const previous = usePresenceStore.getState().status;
      apply(status);
      return { previous };
    },
    onError: (_err, _status, ctx) => {
      if (ctx) apply(ctx.previous);
      showToast({
        title: "Состояние не сохранилось",
        message: "Попробуйте ещё раз — пока система считает, что вы на месте",
        color: "red",
      });
    },
  });
}
