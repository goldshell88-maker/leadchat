import { useEffect, useRef } from "react";
import { pushPresence, usePresenceStore, отправленныйСтатус } from "./usePresence";
import type { PresenceStatus } from "./usePresence";

/**
 * «Отошёл» ставится САМ, когда человека нет за столом.
 *
 * ⚠ ЖАЛОБА ВЛАДЕЛЬЦА 31.08: «пишется, что два сотрудника онлайн, а их даже нет
 * — просто включены ПК».
 *
 * ПОЧЕМУ ТАК БЫЛО. Присутствие на сервере означает ровно «приложение открыто и
 * отвечает на пинги» (`app/ws/presence.py`): ключ живёт минутами и продлевается
 * каждым пингом сокета. Пинги шлёт вкладка, а не человек — значит включённый
 * компьютер с открытой вкладкой честно докладывал «на месте» хоть всю ночь.
 * Статус «отошёл» в системе есть, но выставлялся ТОЛЬКО руками, а руками его
 * не ставит никто: уходя со смены, человек закрывает не вкладку, а глаза.
 *
 * ЧТО СЧИТАЕТСЯ ПРИСУТСТВИЕМ ТЕПЕРЬ. Не открытая вкладка, а действия человека:
 * нажатия, прокрутка, набор текста, касания. Молчит `ПОРОГ` — ставим «отошёл»;
 * человек вернулся и что-то сделал — возвращаем «на месте».
 *
 * ⚠ ДВИЖЕНИЯ МЫШИ ЗДЕСЬ НЕТ НАМЕРЕННО. Курсор ездит сам: от толчка стола, от
 * чужой руки, от программы удалённого доступа. Считать это присутствием
 * значило бы вернуть ровно ту беду, от которой всё заводилось, — «человека
 * нет, а он на месте». Читающий диалоги прокручивает ленту, и прокрутка тут
 * есть.
 *
 * ⚠ ПОЧЕМУ ВОЗВРАТ ПЕРЕБИВАЕТ И РУЧНОЙ «ОТОШЁЛ». Иначе получилось бы хуже
 * исходного: человек поставил «отошёл», вернулся, работает — а коллеги и
 * автораздача считают, что его нет, и обращения идут мимо. Действие в
 * приложении и есть «я вернулся»; отдельной кнопки для этого не нужно.
 *
 * ⚠ ПОЧЕМУ НЕ ТРОГАЕМ СКРЫТУЮ ВКЛАДКУ ОТДЕЛЬНО. Свёрнутая вкладка не шлёт
 * событий ввода, значит порог сработает сам. Заводить второе правило про
 * `visibilitychange` значило бы получить два ответа на один вопрос — а они
 * разъезжаются: человек может смотреть в Авито в соседнем окне и при этом
 * работать.
 */

/**
 * Сколько тишины считаем отсутствием.
 *
 * ⚠ 30 МИНУТ — РЕШЕНИЕ ВЛАДЕЛЬЦА 01.09 («если нет активности через 30 минут,
 * ставился статус отошёл»). Стояло десять. Тридцать МЯГЧЕ, а не строже, и это
 * сказано вслух: диспетчер, который полчаса ведёт переписку в самом Авито и не
 * трогает нашу вкладку, при десяти минутах числился бы отошедшим зря.
 */
const ПОРОГ_МС = 30 * 60 * 1000;

/**
 * ⚠ ОТМЕТКА АКТИВНОСТИ — ОБЩАЯ НА ВСЕ ВКЛАДКИ (найдено 01.09).
 *
 * Считать тишину в памяти одной вкладки нельзя: у диспетчера их обычно две —
 * рабочая и забытая. Забытая молчит порог и честно ставит «отошёл», хотя
 * человек в это время работает в соседней. Работающий выпадает из автораздачи,
 * и никто не понимает почему.
 *
 * Общая отметка отвечает на вопрос «когда этого ЧЕЛОВЕКА видели последний раз»,
 * а не «когда его видела эта вкладка».
 */
const КЛЮЧ_АКТИВНОСТИ = "lc:presence:last-active";

/**
 * Когда последний раз подтверждали «отошёл» — тоже ОБЩЕЕ на вкладки.
 *
 * Держи это в памяти вкладки — и две забытые вкладки дали бы два независимых
 * повтора: вдвое больше запросов и вдвое больше строк в ленте событий. Ошибка
 * та же самая, что и с отметкой активности, только этажом ниже.
 */
const КЛЮЧ_ПОВТОРА = "lc:presence:away-confirmed";

/**
 * Пауза ПОСЛЕ НЕУДАЧИ, и только после неё.
 *
 * ⚠ ОБЫЧНЫЙ ОГРАНИЧИТЕЛЬ ЧАСТОТЫ ЗДЕСЬ ВРЕДЕН, И ЭТО ПОЙМАЛ ТЕСТ. Сначала
 * стояла задержка на любой запрос — и возврат «на месте» глушился ею сразу
 * после автоматического «отошёл»: человек вернулся, работает, а числится
 * ушедшим, и автораздача обходит его стороной. Это ровно тот вред, от которого
 * всё и заводилось.
 *
 * От шквала защищает не время, а состояние: если в хранилище уже нужный
 * статус, запрос не уходит вовсе. Пауза нужна ровно на один случай — сеть
 * отвечает отказом, и повторять на каждое нажатие бессмысленно.
 */
const ПАУЗА_ПОСЛЕ_ОТКАЗА_МС = 30 * 1000;

/**
 * Как часто ПОВТОРЯТЬ «отошёл», пока человека нет за столом.
 *
 * ⚠ ПОЧЕМУ ПОВТОРЯТЬ ВООБЩЕ, А НЕ СКАЗАТЬ ОДИН РАЗ (разбор 01.09, проверено по
 * коду сервера). Сервер сбрасывает статус в «на месте» САМ, и не по ошибке, а
 * по своему устройству:
 *
 *   • пропал последний сокет — через 30 секунд грации запись о статусе
 *     УДАЛЯЕТСЯ (`app/ws/presence.py:presence_disconnected`);
 *   • сокет вернулся — `presence_connected` не находит, что сохранять, и
 *     пишет «online» (там же, :92-94);
 *   • истёк TTL на спящем ноутбуке — первый же пинг воскрешает ключ строкой
 *     `status = await redis.get(...) or "online"` (:102).
 *
 * А сокет пропадает постоянно: моргнула сеть, закрыли крышку на минуту, мы
 * сами перезапустили сервер выкаткой — последнее сбрасывает разом ВСЮ смену.
 *
 * Клиент об этом не узнаёт: кадр `presence:online` фронт не разбирает, а своё
 * состояние перечитывает только при входе. Со сверкой «уже стоит нужное — не
 * шлём» это значило, что после первого же сброса авто-«отошёл» замолкал
 * НАВСЕГДА, и человек числился на месте до конца смены. Механизм работал ровно
 * до первой моргнувшей сети.
 *
 * Повтор чинит это без единой правки на сервере: любой сброс исправляется не
 * позже, чем через две минуты. Цена — тринадцать запросов раз в две минуты на
 * всю смену, и только пока людей нет за столом.
 */
const ПОВТОР_ОТОШЁЛ_МС = 2 * 60 * 1000;

/**
 * Как часто работающее устройство напоминает серверу «на месте», даже если
 * по своей памяти уже его отправляло. Сервер не даёт авто-«отошёл» с
 * простаивающей вкладки перебить человека, которого видел активным последние
 * 30 минут, — но видел он его только по этому запросу. Без повтора телефон,
 * отправивший «на месте» один раз утром, через полчаса проигрывал
 * простаивающему компьютеру, и сторож освобождения забирал диалоги
 * работающего человека.
 */
const ПОДТВЕРЖДАТЬ_НА_МЕСТЕ_МС = 5 * 60 * 1000;

const СОБЫТИЯ = ["pointerdown", "keydown", "wheel", "touchstart"] as const;

export function useAutoAway(): void {
  /*
   * Запасная отметка на случай, когда общего хранилища нет: приватный режим,
   * запрет на localStorage, переполнение. Тогда поведение откатывается к
   * прежнему, повкладочному, — хуже, но работает.
   */
  const последнее = useRef(Date.now());
  const доКогдаМолчим = useRef(0);
  /** Запасная отметка повтора, когда общего хранилища нет. */
  const подтверждали = useRef(0);
  /** Когда это устройство последний раз сказало серверу «на месте». */
  const наМестеСказали = useRef(0);

  useEffect(() => {
    if (typeof window === "undefined") return;

    const записатьАктивность = () => {
      последнее.current = Date.now();
      try {
        localStorage.setItem(КЛЮЧ_АКТИВНОСТИ, String(последнее.current));
      } catch {
        // Хранилище недоступно — остаётся отметка своей вкладки, см. выше.
      }
    };

    const когдаВиделиЧеловека = (): number => {
      try {
        const v = Number(localStorage.getItem(КЛЮЧ_АКТИВНОСТИ));
        // Берём позднейшее из общего и своего: чужая вкладка могла записать
        // активность только что, а могла и не записать вовсе.
        if (Number.isFinite(v) && v > 0) return Math.max(v, последнее.current);
      } catch {
        // см. выше
      }
      return последнее.current;
    };

    const когдаПодтверждали = (): number => {
      try {
        const v = Number(localStorage.getItem(КЛЮЧ_ПОВТОРА));
        if (Number.isFinite(v) && v > 0) return Math.max(v, подтверждали.current);
      } catch {
        // Хранилище недоступно — остаётся отметка своей вкладки.
      }
      return подтверждали.current;
    };

    const запомнитьПодтверждение = () => {
      подтверждали.current = Date.now();
      try {
        localStorage.setItem(КЛЮЧ_ПОВТОРА, String(подтверждали.current));
      } catch {
        // см. выше
      }
    };

    // Открытая вкладка — это уже действие человека. Без этой строки только что
    // открытое приложение унаследовало бы чужую вчерашнюю отметку и ушло бы в
    // «отошёл» на первом же тике.
    записатьАктивность();

    /**
     * `сверятьЗеркало=true` — не ходить на сервер, если там и так нужное. Это
     * защита от шквала для «на месте»: действий у работающего человека сотни.
     * Для «отошёл» сверка ВЫКЛЮЧЕНА намеренно, см. `ПОВТОР_ОТОШЁЛ_МС`.
     */
    const отправить = (статус: PresenceStatus, сверятьЗеркало: boolean) => {
      /*
       * ⚠ СВЕРЯЕМСЯ С ОБЩЕЙ ЗАПИСЬЮ, А НЕ ТОЛЬКО СО СВОЕЙ ПАМЯТЬЮ.
       *
       * Здесь стояло только хранилище вкладки — и возврат «на месте» ломался
       * ровно тогда, когда был нужнее всего: соседняя вкладка поставила
       * «отошёл», а эта считает, что и так на месте, и запрос не шлёт. Человек
       * работает и при этом числится отошедшим.
       */
      if (сверятьЗеркало) {
        const считаем = отправленныйСтатус() ?? usePresenceStore.getState().status;
        if (считаем === статус) return;
      }
      if (Date.now() < доКогдаМолчим.current) return;
      // Не удалось — не беда: следующее действие или тик попробуют снова.
      // Ронять работу из-за статуса нельзя, но и молчать вечно тоже.
      // «Отошёл» отсюда — догадка вкладки по тишине: помечаем `auto`, чтобы
      // сервер не дал ей перебить человека, работающего с другого устройства
      // (владелец 19.09: телефон в работе, компьютер слал «отошёл»).
      void pushPresence(статус, { auto: статус === "away" }).catch(() => {
        доКогдаМолчим.current = Date.now() + ПАУЗА_ПОСЛЕ_ОТКАЗА_МС;
      });
    };

    const наДействие = () => {
      записатьАктивность();
      const пораНапомнить = Date.now() - наМестеСказали.current > ПОДТВЕРЖДАТЬ_НА_МЕСТЕ_МС;
      if (пораНапомнить) наМестеСказали.current = Date.now();
      отправить("online", !пораНапомнить);
    };

    for (const имя of СОБЫТИЯ) {
      window.addEventListener(имя, наДействие, { passive: true });
    }
    // Тик реже порога: минута точности здесь никому не нужна, а таймер,
    // будящий вкладку каждую секунду, — это расход батареи на пустом месте.
    const таймер = window.setInterval(() => {
      if (Date.now() - когдаВиделиЧеловека() < ПОРОГ_МС) return;
      // Повторяем не чаще, чем нужно, но повторяем: сервер сбрасывает статус сам.
      if (Date.now() - когдаПодтверждали() < ПОВТОР_ОТОШЁЛ_МС) return;
      запомнитьПодтверждение();
      отправить("away", false);
    }, 60_000);

    return () => {
      for (const имя of СОБЫТИЯ) window.removeEventListener(имя, наДействие);
      window.clearInterval(таймер);
    };
  }, []);
}
