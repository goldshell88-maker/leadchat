import { useEffect, useState } from "react";

/**
 * Выложен ли инсталлятор десктопа.
 *
 * ⚠ ЗАЧЕМ ЭТО ВООБЩЕ ПОНАДОБИЛОСЬ. В подвале экрана входа висела ссылка
 * «Скачать приложение для Windows» на `/download`. Ссылку поставили в расчёте
 * на релиз — а релиз ни разу не выпускался: nginx на проде отдаёт по
 * `/download/` редирект на `LeadChat-Setup.exe`, которого там нет, и человек
 * получает 404 (проверено 27.08 на боевом адресе).
 *
 * Это худший вид неработающей ссылки: она обещает то, чего нет, ПЕРЕД входом —
 * то есть первое, что новый сотрудник узнаёт о системе, это что у неё битые
 * ссылки.
 *
 * ⚠ ПОЧЕМУ НЕ ПРОСТО УБРАТЬ ССЫЛКУ. Тогда её пришлось бы возвращать руками в
 * день релиза — и ровно этого не случится: релиз выпускает CI по тегу, а
 * фронт правит человек, и между ними нет ничего, что напомнило бы. Здесь же
 * признак берётся оттуда, куда релиз кладёт файлы: появился манифест —
 * появилась ссылка, сама.
 *
 * Манифест лёгкий (сотни байт) и лежит на том же домене; запрос идёт один раз
 * за монтирование экрана. Любая осечка — сеть, 404, отсутствие сервера в dev —
 * значит «релиза нет»: ошибиться в эту сторону дешевле, чем показать битую
 * ссылку.
 */
export function useDesktopRelease(): boolean {
  const [есть, setЕсть] = useState(false);

  useEffect(() => {
    // AbortController, а не «проверю флаг после await»: экран входа успевают
    // покинуть за время запроса, и setState после размонтирования — это
    // предупреждение React и утечка обработчика.
    const ac = new AbortController();
    fetch("/download/latest.json", { method: "HEAD", signal: ac.signal })
      .then((r) => {
        if (r.ok) setЕсть(true);
      })
      .catch(() => {
        // Сети нет или манифеста нет — ссылку не показываем. Молча: на экране
        // входа человеку нечего делать с этой ошибкой.
      });
    return () => ac.abort();
  }, []);

  return есть;
}
