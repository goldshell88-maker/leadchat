import { useSessionStore } from "@/shared/stores/sessionStore";

/**
 * «Человека выкинуло из работающего приложения» — признак для экрана входа
 * (аудит SHELL-03).
 *
 * ЧТО БЫЛО. Протух refresh-токен (или пришёл кадр 4403 «сотрудник отключён») —
 * сессия обнулялась, страж уводил на `/login`, и человек видел обычную пустую
 * форму. По всему интерфейсу не было НИ ОДНОЙ строки про истёкшую сессию.
 * Диспетчер, набиравший ответ клиенту, оказывался на экране входа и не
 * понимал: он вышел сам, его отключил администратор или упал сервер. В модалке
 * отключения администратору при этом обещано «открытые окна перестанут
 * работать» — то есть про это знают все, кроме того, с кем это случилось.
 *
 * ПОЧЕМУ ПРИЗНАК СОБИРАЕТСЯ ЗДЕСЬ, А НЕ В МЕСТЕ ВЫХОДА. Мест выхода три
 * (`http.ts` при мёртвом refresh, `WsClient` на 4403, кнопка «Выйти»), и все
 * три — в чужих файлах. Но различить их можно снаружи, ничего не трогая:
 *
 *   * этот модуль помнит, БЫЛ ли в этой вкладке вошедший человек;
 *   * `RequireAuth` при выбросе кладёт в state перехода `from` — адрес, с
 *     которого человека сняли; кнопка «Выйти» уходит на `/login` без него.
 *
 * Оба условия вместе означают ровно одно: работал — и выкинуло. Один вход по
 * ссылке на закрытый раздел (`from` есть, сессии не было) под них не подходит,
 * и осознанный выход (сессия была, `from` нет) — тоже.
 *
 * Честное ограничение: память живёт во вкладке. Перезагрузил страницу — и
 * объяснения больше нет. Для сообщения «это только что случилось» этого
 * достаточно; знать причину через сутки незачем.
 */

let hadSession = false;

useSessionStore.subscribe((s) => {
  if (s.user) hadSession = true;
});

/** Был ли в этой вкладке вошедший сотрудник. */
export function hadSessionInThisTab(): boolean {
  return hadSession;
}

/**
 * Человека сняли с рабочего экрана, а не он сам пришёл на форму входа.
 * `fromProtected` — был ли переход сделан стражем (`state.from` у location).
 */
export function wasKickedOut(fromProtected: boolean): boolean {
  return hadSession && fromProtected;
}

/** Только для тестов: забыть, что в этой вкладке кто-то входил. */
export function resetSessionMemory(): void {
  hadSession = false;
}
