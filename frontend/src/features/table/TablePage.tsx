/**
 * Смещение Москвы, написанное числом.
 *
 * Взять его из браузера нельзя — в том и дело: у руководителя во Владивостоке
 * браузер живёт на UTC+10. Раньше границы периода считались именно так
 * (`toISOString()` от локальной полуночи), а время в самой таблице печаталось
 * по Москве. «С 6 августа» у владивостокского руководителя начиналось в 19:00
 * пятого по московскому времени, и строки за вечер пятого попадали в отчёт,
 * которого не просили; у него же и у московского коллеги одна и та же ссылка
 * давала разные наборы строк.
 *
 * Константа безопасна: Москва живёт на UTC+3 круглый год — переходов на летнее
 * время нет с 2014 года.
 */
const MSK_OFFSET = "+03:00";

/** «2026-08-06» → момент начала этих суток по Москве. */
function mskDayStart(date: string): string {
  return `${date}T00:00:00${MSK_OFFSET}`;
}

/**
 * ЧАСОВОЙ ПОЯС В ТАБЛИЦЕ ОБЪЯСНЯЛСЯ ТРИЖДЫ (перекройка, разбор живого экрана).
 *
 * Отчёт печатает московское время — это не прихоть: руководитель в Москве и
 * руководитель во Владивостоке, обсуждая одну строку, обязаны называть одни и
 * те же часы, иначе спор «когда именно ответили клиенту» нечем разрешить.
 * Ровно поэтому же московское время стоит и в выгрузке (сервер,
 * app/services/conversation_table.py).
 *
 * Но сотруднику на UTC+10 московское число само по себе ничего не говорит, и
 * лечили это ДОБАВЛЕНИЕМ ОБЪЯСНЕНИЙ. К августу их стало три штуки на одно и то
 * же: строка в шапке «Время в таблице московское: сейчас в Москве…», подпись
 * «(МСК)» в заголовке колонки и подсказка «21:24 у вас · 14:24 по Москве» по
 * наведению на ячейку. Три текста об одном — это не «надёжнее», это шум: глаз
 * перестаёт читать их все, а вычитать часы в уме человек всё равно
 * продолжает, потому что смотрит-то он на число в ячейке.
 *
 * ЧТО ЗДЕСЬ. Одно место вместо трёх: переключатель над таблицей. Он и
 * ОБЪЯВЛЯЕТ пояс, и МЕНЯЕТ его, поэтому второй раз про пояс сказать негде —
 * значение показано один раз. Умолчание прежнее, московское: отчёт остаётся
 * общим документом, а «у вас» — осознанный выбор того, кому надо сверить
 * колонку со своими часами.
 *
 * Выбор живёт в адресе (`?tz=local`), как и весь остальной срез: ссылку на
 * этот экран пересылают, и она обязана воспроизводить увиденное целиком.
 */
function cellTime(iso: string | null, timeZone: string): string {
  return (iso && formatInZone(iso, timeZone)) || "—";
}

