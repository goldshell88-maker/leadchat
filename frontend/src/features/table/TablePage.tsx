/**
 * Часы сотрудника и московские расходятся?
 *
 * Считается ЧУЖОЙ функцией намеренно: `moscowZoneHint` уже отвечает ровно на
 * этот вопрос (`null` — часы совпали), и своя вторая проверка однажды
 * разошлась бы с ней способом сравнения. Сравнивать надо ПОКАЗАННОЕ время, а
 * не имя зоны: у Симферополя имя своё, а часы московские, и переключатель ему
 * не нужен — обе половины показали бы одно и то же.
 *
 * Саму подпись мы больше не печатаем (см. `cellTime`); от функции нужен
 * только её ответ «есть ли о чём говорить».
 */
function zonesDiffer(): boolean {
  return moscowZoneHint() !== null;
}

/**
 * Секунды → «4 мин», «1 ч 20 м». `null` — прочерк, а не ноль.
 *
 * Нечисло тоже даёт прочерк: пока сервер не отдавал новое поле, ячейка честно
 * показывала «NaN ч NaN м» — отказ, который выглядит как поломка всего отчёта.
 * Прочерк в той же ситуации читается как «данных нет», и это правда.
 */
function duration(sec: number | null | undefined): string {
  if (sec === null || sec === undefined || !Number.isFinite(sec)) return "—";
  if (sec < 60) return `${sec} с`;
  const m = Math.floor(sec / 60);
  if (m < 60) return `${m} мин`;
  const h = Math.floor(m / 60);
  return `${h} ч ${m % 60} м`;
}

