/**
 * Очередь «Входящие» (7.1): загрузка списка и два решения оператора.
 *
 * Запрос очереди живёт, пока у сотрудника есть право отвечать клиентам, —
 * даже когда открыта вкладка «Мои». Счётчик на вкладке должен быть верным до
 * того, как в неё заглянули: иначе очередь молча растёт, и смысл экрана теряется.
 */
export function useInboxQueue(enabled: boolean) {
  return useInfiniteQuery({
    queryKey: qk.inbox.list,
    queryFn: ({ pageParam }) => fetchInboxQueue(pageParam),
    initialPageParam: 0,
    getNextPageParam: (last, all) => {
      const loaded = all.reduce((n, p) => n + p.items.length, 0);
      return loaded < last.page.total ? loaded : undefined; // undefined = конец
    },
    enabled,
    // Как у списка диалогов (06.09): прежние строки держатся, пока едут новые,
    // скелет — только когда очередь ещё ни разу не приезжала.
    placeholderData: keepPreviousData,
  });
}

/**
 * Диалог ушёл из моей очереди — убрать строку и перейти к следующему.
 * Пустой экран после решения недопустим: оператор разбирает очередь потоком,
 * и каждый лишний клик по списку — это секунды ожидания клиента.
 */
function leaveQueue(
  convId: string,
  nextId: string | null,
  navigate: NavigateFunction,
  counters?: InboxCountDto,
): void {
  const inbox = useInboxStore.getState();
  inbox.settle(convId, counters);
  inbox.clearClaimed(convId);
  removeInboxRow(convId);
  navigate(nextId ? `/chats/${nextId}` : "/chats", { replace: true });
}

/** Тост опоздавшему — тем же текстом, что и плашка (7.1 п.4): человек не должен гадать. */
function showAlreadyClaimed(claimedBy: UserRef): void {
  showToast({
    title: "Диалог уже занят",
    message: `Диалог принял ${подписьСотрудника(claimedBy)}`,
    color: "yellow",
  });
}

/** Диалог уже принят — и принят ВАМИ. Это не отказ, а повтор удавшегося. */
function мойЖеДиалог(err: unknown): boolean {
  if (!(err instanceof ApiError) || err.status !== 409) return false;
  return Boolean((err.details as AlreadyClaimedDetails | undefined)?.mine);
}

/** `details` ошибки 409 — кто успел первым; без этого поля тост был бы безымянным. */
function claimedByFrom(err: unknown): UserRef | undefined {
  if (!(err instanceof ApiError) || err.status !== 409) return undefined;
  return (err.details as AlreadyClaimedDetails | undefined)?.claimed_by;
}

/**
 * Что делает УСПЕШНОЕ принятие — одним телом на всех вызывающих.
 *
 * ⚠ ЗАЧЕМ ОТДЕЛЬНО ОТ МУТАЦИИ (28.08). Принять диалог можно двумя путями:
 * кнопкой в очереди и сочетанием клавиш. Кнопка живёт в компоненте открытого
 * диалога, а сочетание обязано работать из ЛЮБОЙ вкладки — то есть для
 * диалога, который сейчас не открыт, и мутации для него нет. Две копии этой
 * обвязки разъехались бы на первой же правке: счётчик очереди, строка списка,
 * перезапрос и фокус — четыре разных места.
 */
export function принятоУспешно(convId: string, res: InboxClaimResponse): void {
  const conv: ConversationDetailDto = res.conversation;
  queryClient.setQueryData<ConversationDetailDto>(qk.conversations.detail(convId), conv);
  const inbox = useInboxStore.getState();
  // Счётчик берём из ответа ручки, а не считаем сами: он персональный, и
  // сервер только что посчитал его точно (01 — ClaimOut наследует счётчики).
  inbox.settle(convId, { count: res.count, escalated: res.escalated });
  inbox.clearClaimed(convId);
  removeInboxRow(convId);
  // Строка списков + перенос между вкладками (обработчик идемпотентен —
  // серверный conversation:updated придёт следом и ничего не сломает).
  applyConversationPatch(convId, {
    status: conv.status,
    assignee: conv.assignee,
    in_inbox: false,
  });
  /*
   * ⚠ СТРОКА В «МОИХ» — ИЗ ОТВЕТА РУЧКИ, А НЕ ИЗ ПЕРЕЗАПРОСА (замер 06.09: 552
   * принятия за смену, p50 43 мс; строка появлялась только после ВТОРОГО круга
   * — список плюс числа, — 3–5 запросов на каждый приём).
   *
   * `applyConversationPatch` правит строку ТАМ, ГДЕ ОНА УЖЕ ЕСТЬ, а взятого
   * диалога в «Моих» нет — он лежал в очереди. Ответ же везёт диалог целиком
   * (`InboxClaimResponse.conversation`): ставим его на место по порядку
   * сервера и двигаем числа над вкладкой на своё действие. Сверка ниже это
   * подтвердит, а не покажет впервые.
   */
  if (conv.assignee && conv.assignee.id === useSessionStore.getState().user?.id) {
    вставитьСтроку(conv, (f) => строкаВходитВМои(conv, f));
    сдвинутьСчёт({ mine: 1, mine_waiting: conv.waiting_since ? 1 : 0 });
  }
  /*
   * ⚠ СПИСКИ ПЕРЕЗАПРАШИВАЕМ СРАЗУ, А НЕ В ХВОСТЕ ЧУЖОЙ ПАЧКИ (28.08).
   *
   * Перезапрос идёт через схлопывание, которое защищает от ЧУЖИХ событий и в
   * живую смену откладывалось минутами. Жалоба дословно: «взял 4 диалога, по
   * статистике в работе 14, а вижу 10; подгрузились спустя 3 минуты».
   *
   * Своё нажатие — не чужое событие. Строка уже стоит (выше), поэтому круг
   * идёт в фоне: он сверяет, а не показывает. Сам `POST /claim` при этом
   * остаётся блокирующим — гонку двух нажатий решает сервер, и показать
   * «взял», чтобы через 200 мс отобрать, хуже ожидания ответа.
   */
  refetchListsNow();
  /*
   * ⚠ И ПОМЕЧАЕМ СТРОКУ СВОЕЙ, ИНАЧЕ ОНА ПРИЕДЕТ В КОНЕЦ СПИСКА (разбор 04.09).
   *
   * Порядок списка заморожен на четыре секунды, пока курсор над колонкой:
   * строки не должны прыгать под рукой. Заморозка отличает знакомые строки от
   * новых — и взятый диалог для неё НОВЫЙ, потому что в «Моих» его до сих пор
   * не было. Без пометки он вставал в хвост и висел там до конца заморозки:
   * человек нажал «Принять», диалог открылся, а в списке его на месте нет.
   *
   * Пометка эта в проекте есть и работает — но стояла только на пути КЛАВИШИ
   * (`claimFromQueue`), а кнопка «Принять» идёт сюда и её не ставила. Один и
   * тот же диалог, взятый двумя способами, вёл себя по-разному.
   */
  пересобратьПорядок(convId);
}

/**
 * «Принять диалог» — `POST /conversations/{id}/claim`.
 * Оптимистичного захвата тут быть не может: принятие атомарно на сервере,
 * и показать «взял», а через 200 мс отобрать — хуже, чем подождать ответ.
 * Успех: диалог мой, он в «Моих», курсор в поле ввода. `409` — значит успел
 * коллега: тост его именем и переход к следующему в очереди.
 */
export function useClaimConversation(convId: string) {
  const navigate = useNavigate();
  return useMutation({
    mutationFn: () => claimConversation(convId),
    onSuccess: (res) => {
      принятоУспешно(convId, res);
      requestComposerFocus(); // 7.1 п.3: принял — сразу пиши
    },
    onError: (err) => {
      /*
       * ⚠ СВОЙ ЖЕ ДИАЛОГ — НЕ ОТКАЗ. Прежде этот случай попадал в ветку ниже
       * вместе с чужими: человек видел «Диалог уже занят: Иван Иванов», где
       * Иван Иванов — он сам, и его ВЫБРАСЫВАЛО из собственного диалога через
       * `leaveQueue`. Второе хуже первого: тост можно проигнорировать, а
       * потерянный диалог надо искать заново.
       */
      if (мойЖеДиалог(err)) {
        requestComposerFocus();
        return;
      }
      const claimedBy = claimedByFrom(err);
      if (claimedBy) {
        showAlreadyClaimed(claimedBy);
        leaveQueue(convId, nextInboxId(convId), navigate);
        return;
      }
      // ⚠ ПРИЧИНУ ОТКАЗА ГОВОРИТ СЕРВЕР, И ВЫБРАСЫВАТЬ ЕЁ НЕЛЬЗЯ.
      //
      // У принятия четыре разных отказа, и все с готовым человеческим текстом:
      // «Диалог канала N ведут другие операторы», «Вы выведены из работы с
      // диалогами», «Принять может только тот, кто отвечает клиентам», «Диалог
      // закрыт». Здесь разбирался ровно один случай — 409 «уже занят», — а
      // остальные превращались в «Попробуйте ещё раз». Совет заведомо ложный:
      // ни одна из этих причин от повтора не меняется. Человек жмёт второй раз,
      // третий, получает то же самое и уходит отвечать в Авито — то есть ровно
      // то, ради чего система и заводилась, обходится стороной.
      const spoken = err instanceof ApiError ? err.message.trim() : "";
      showToast({
        title: "Не получилось принять диалог",
        message: spoken || "Попробуйте ещё раз",
        color: "red",
      });
      // ⚠ ЧУЖОЙ КАНАЛ — УБИРАЕМ СТРОКУ, А НЕ ТОЛЬКО ЖАЛУЕМСЯ (аудит 19.08).
      // Строка чужого канала могла попасть на экран (прямая ссылка, вкладка
      // «Все», старый кадр), и после 403 она ОСТАВАЛАСЬ на месте: жать можно
      // было бесконечно, а своя строка тонула в чужом потоке. Сервер сказал
      // «этот канал ведут другие» — значит в очереди этого человека диалогу
      // не место, и счётчик обязан сойтись с серверным.
      if (err instanceof ApiError && err.details?.reason === "channel_not_assigned") {
        leaveQueue(convId, nextInboxId(convId), navigate);
      }
    },
  });
}

/**
 * «Вернуть в очередь» — `POST /conversations/{id}/release`.
 *
 * ЗАЧЕМ ЭТО НУЖНО ЖИВОМУ ДИСПЕТЧЕРУ. Взять чужой диалог по ошибке — дело
 * одной секунды: очередь обновляется на глазах, строки съезжают, палец уже
 * летит к «Принять». Без возврата ошибка стоила дорого: диалог оседал в
 * «Моих», из очереди у остальных двенадцати исчезал, и клиент ждал человека,
 * который не собирался ему отвечать. Обойти это можно было только через
 * руководителя — то есть отвлечь второго человека ради чужой описки.
 *
 * ПОЧЕМУ БЕЗ ПОДТВЕРЖДЕНИЯ. Действие обратимо в один клик: диалог возвращается
 * в очередь, откуда его можно принять снова, в том числе тем же человеком.
 * Спрашивать «вы уверены?» перед обратимым действием — это учить не читать
 * такие вопросы, а они понадобятся там, где обратного пути нет.
 *
 * Счётчик берём из ответа: очередь выросла на единицу только у меня, и точное
 * значение знает сервер. Остальным её пришлёт `inbox:released`.
 */
export function useReleaseConversation(convId: string) {
  return useMutation({
    mutationFn: () => releaseConversation(convId),
    onSuccess: (res) => {
      const conv: ConversationDetailDto = res.conversation;
      queryClient.setQueryData<ConversationDetailDto>(qk.conversations.detail(convId), conv);
      // restore, не settle: диалог ВЕРНУЛСЯ в очередь, id снова известен —
      // иначе свой же кадр inbox:released делал бейджу +1 (аудит 16.08)
      useInboxStore.getState().restore(convId, { count: res.count, escalated: res.escalated });
      // Строка возвращается в очередь и уходит из «Моих». Серверный
      // `inbox:released` придёт следом — обработчик идемпотентен.
      applyConversationPatch(convId, {
        status: conv.status,
        assignee: conv.assignee,
        in_inbox: true,
      });
      showToast({
        title: "Диалог вернулся в очередь",
        message: "Его снова видят все операторы",
      });
    },
    onError: (err) => {
      // причину говорит сервер (18.08): «Попробуйте ещё раз» на 409/403
      // отправляет человека по кругу вместо объяснения
      showToast({
        title: "Не получилось вернуть диалог",
        message: err instanceof ApiError ? err.message : "Попробуйте ещё раз",
        color: "red",
      });
    },
  });
}

/**
 * Что делает УСПЕШНЫЙ ОТКАЗ — одним телом на всех вызывающих.
 *
 * ⚠ ЗАЧЕМ ОТДЕЛЬНО ОТ МУТАЦИИ (07.09) — довод тот же, что у `принятоУспешно`
 * выше, и появился он по той же причине. Отказаться от диалога теперь можно
 * тремя путями: кнопкой в панели очереди, сочетанием клавиш и кнопкой
 * «Отклонить» в браузерном уведомлении. Мутация живёт в компоненте открытого
 * диалога, а карточка уведомления приходит, когда на экране этого диалога нет
 * вовсе, — позвать хук оттуда нельзя. Своя копия обвязки развела бы четыре
 * места сразу: счётчик очереди, строка списка, переход к следующему и
 * возможность «Вернуть».
 *
 * `nextId` считает ВЫЗЫВАЮЩИЙ и обязательно ДО запроса: после удаления строки
 * соседа по очереди уже не найти.
 */
export function отклоненоУспешно(
  convId: string,
  res: InboxDeclineResponse,
  nextId: string | null,
  navigate: NavigateFunction,
): void {
  leaveQueue(convId, nextId, navigate, {
    count: res.count,
    escalated: res.escalated,
  });
  /*
   * Отказ обратим (UX-аудит, docs/17 §Т7).
   *
   * Отказ теперь делается одним нажатием Ctrl+Backspace — промахнуться
   * легко, а последствие было необратимым: обращение навсегда уходило из
   * очереди отказавшегося. Клиент при этом не брошен (коллегам диалог
   * виден), но конкретный оператор терял то, что собирался взять.
   *
   * ⚠ И РОВНО ПОЭТОМУ «Вернуть» ОБЩЕЕ С УВЕДОМЛЕНИЕМ (07.09). В карточке две
   * кнопки рядом, они мелкие и приходят внезапно поверх чужого окна —
   * промахнуться там не легче, а тяжелее, чем клавишей. Отказ из уведомления
   * без возврата был бы единственным необратимым путём из трёх.
   *
   * Возврат возможен, только пока диалог ещё ждёт: если его успели
   * принять, сервер ответит 409, и мы честно об этом скажем, а не сделаем
   * вид, что получилось.
   */
  showUndoToast({
    title: "Диалог отклонён",
    /*
     * ⚠ ФЛАГ, А НЕ СЧЁТЧИК (аудит 30.08). Сервер шлёт два похожих поля и
     * прямо предупреждает «не путать»: `escalated` — ЧИСЛО брошенных в
     * моей очереди, `escalated_now` — «этим отказом закрылся круг».
     *
     * Здесь стояло число. Пока в очереди висит хоть один брошенный диалог,
     * КАЖДЫЙ отказ от любого другого печатал «От него отказались все» —
     * ложь про только что отклонённый. Обратная сторона хуже: когда круг
     * действительно замыкался, а других брошенных не было, сообщение не
     * появлялось — то есть молчали ровно там, где надо было сказать.
     */
    message: res.escalated_now ? "От него отказались все" : undefined,
    actionLabel: "Вернуть",
    onAction: () => {
      undoDeclineConversation(convId)
        .then((back) => {
          useInboxStore.getState().settle(convId, {
            count: back.count,
            escalated: back.escalated,
          });
          void queryClient.invalidateQueries({ queryKey: qk.inbox.list });
          // Свой же диалог — человек нажал «Принять» именно на него.
          выбралСам(convId);
          // ⚠ ВЗЯТЬ ДИАЛОГ — ТОЖЕ СВОЁ ДЕЙСТВИЕ (жалоба владельца 02.09: «когда берёшь
          // новые диалоги, они сначала все внизу, потом скачут вверх»).
          //
          // Порядок списка заморожен четыре секунды после наведения на колонку, а
          // строки, которых в замороженном плане нет, встают В КОНЕЦ — иначе замораживать
          // было бы нечего. Диалог, только что взятый из очереди, как раз такая строка:
          // он появлялся внизу и уезжал наверх, когда заморозка отпускала.
          //
          // Своё действие видно сразу — то же правило, что и у отправки сообщения.
          //
          // ⚠ ПОЧЕМУ ЭТОГО БЫЛО МАЛО И ЖАЛОБА ПОВТОРИЛАСЬ В ТОТ ЖЕ ДЕНЬ. Сброс плана
          // срабатывает СЕЙЧАС, а строка приезжает с сервера через секунду-две —
          // заморозка к тому времени взводится заново, уже без неё, и строка опять
          // падает в хвост. Поэтому диалог называется поимённо: он помечен как свой и
          // встанет на своё место, когда бы ни доехал.
          пересобратьПорядок(convId);
          navigate(`/chats/${convId}`);
          showToast({ title: "Диалог вернулся в вашу очередь", tone: "success" });
        })
        .catch((err) => {
          // Человеку — короткий вывод, в лог — причина с диалогом: «уже
          // приняли или закрыли» это догадка, а 500 и обрыв сети выглядят
          // на экране так же.
          console.warn("[inbox] вернуть отказ не удалось:", convId, err);
          showToast({
            title: "Вернуть не получилось",
            message: "Диалог уже приняли или закрыли",
            tone: "warning",
          });
        });
    },
  });
}

/**
 * Что сказать человеку, когда отказ НЕ ПРОШЁЛ, — тоже одним телом на всех.
 *
 * ⚠ «ДИАЛОГ ЗАБРАЛ КОЛЛЕГА» — НЕ НЕУДАЧА, И КРАСНЫМ ОБ ЭТОМ ГОВОРИТЬ НЕЛЬЗЯ
 * (решение принято явно, 07.09, вместе с кнопкой «Отклонить» в уведомлении).
 *
 * Замер 05.09: около 2000 постановок в очередь за сутки, каждая адресована
 * трём десяткам операторов. «Пока тянулся к кнопке — забрали» здесь не
 * редкость, а обычный исход, и на него сервер отвечает 409 `already_claimed` с
 * именем занявшего. Человек хотел, чтобы диалог ушёл из его очереди, — диалог
 * ушёл, просто чужими руками; красное «Не получилось отклонить» описывало бы
 * это как поломку и отправляло проверять, что сломалось.
 *
 * Молчать при этом нельзя тем более: нажатие без ответа читается как
 * сломанная кнопка (ровно жалоба 30.08 про клавишу приёма). Поэтому спокойный
 * жёлтый тост — тем же текстом, каким встречают опоздавшего с «Принять»
 * (`showAlreadyClaimed`): случай один, и слова должны быть одни.
 *
 * ⚠ СВОЙ ЖЕ ДИАЛОГ РАЗБИРАЕТСЯ ОТДЕЛЬНО, иначе повторится беда 29.08: тост
 * «Диалог принял Иван Иванов», где Иван Иванов — сам читающий.
 *
 * Остальные отказы (диалог закрыт, не ждёт принятия, нет права) сервер
 * объясняет своими словами — их и показываем красным: они от повтора не
 * меняются, и человеку нужен текст, а не «попробуйте ещё раз».
 */
export function отказНеПрошёл(convId: string, err: unknown): void {
  console.warn("[inbox] отклонить не удалось:", convId, err);
  if (мойЖеДиалог(err)) {
    showToast({
      title: "Диалог уже у вас",
      message: "Вы приняли его раньше — отклонять нечего",
      tone: "warning",
    });
    return;
  }
  const claimedBy = claimedByFrom(err);
  if (claimedBy) {
    showAlreadyClaimed(claimedBy);
    return;
  }
  showToast({
    title: "Не получилось отклонить",
    message:
      err instanceof ApiError ? err.message : "Диалог остался в очереди — попробуйте ещё раз",
    color: "red",
  });
}

/**
 * «Отклонить» — `POST /conversations/{id}/decline`. Диалог остаётся в очереди
 * для остальных, из моей — уходит. Следующего считаем ДО ответа сервера: после
 * удаления строки соседа уже не найти.
 */
export function useDeclineConversation(convId: string) {
  const navigate = useNavigate();
  return useMutation<InboxDeclineResponse, Error, void, { nextId: string | null }>({
    mutationFn: () => declineConversation(convId),
    onMutate: () => ({ nextId: nextInboxId(convId) }),
    onSuccess: (res, _vars, ctx) => отклоненоУспешно(convId, res, ctx?.nextId ?? null, navigate),
    onError: (err) => отказНеПрошёл(convId, err),
  });
}

/** Переход к следующему из плашки «Диалог принял …» — без запросов к серверу. */
export function useGoToNextInQueue(convId: string): () => void {
  const navigate = useNavigate();
  return () => leaveQueue(convId, nextInboxId(convId), navigate);
}

/**
 * Сколько диалогов очереди ещё ждёт, КРОМЕ открытого, — для кнопки
 * «Следующий (N)» в шапке ленты.
 *
 * Подписка на стор, а не разовое чтение: очередь живая (`inbox:new`,
 * `inbox:claimed` у коллег), и число на кнопке обязано меняться вместе с
 * бейджем вкладки, а не застывать на том, что было при открытии диалога.
 *
 * Ноль здесь значит «кнопку показывать не за что»: следующего нет, и
 * `nextInboxId` в этот момент вернёт `null`. Условие показа кнопки — это
 * число, а не общий размер очереди: при единственном ждущем, который сейчас и
 * открыт, размер очереди равен единице, и кнопка вела бы в тот же диалог.
 */
export function useInboxAhead(convId: string): number {
  return useInboxStore((s) => Math.max(0, s.count - (s.ids[convId] ? 1 : 0)));
}

