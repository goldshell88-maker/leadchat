import type { NavigateFunction } from "react-router-dom";
import { requestComposerFocus } from "@/features/hotkeys/focusBus";
import { ApiError } from "@/shared/api/http";
import type { AlreadyClaimedDetails } from "@/shared/api/types";
import { showToast } from "@/shared/ui/toast";
import { claimConversation, declineConversation, fetchInboxQueue, nextInboxId } from "./api";
import { отказНеПрошёл, отклоненоУспешно, принятоУспешно } from "./useInbox";
import { выбралСам } from "../выборДиалога";

/**
 * Принять диалог, КОТОРЫЙ СЕЙЧАС НЕ ОТКРЫТ, и открыть его.
 *
 * ⚠ ЗАЧЕМ ОТДЕЛЬНО ОТ `useClaimConversation` (28.08, просьба операторов).
 * Мутация живёт в компоненте открытого диалога, а сочетание клавиш обязано
 * работать из любой вкладки — то есть для диалога, компонента которого на
 * экране нет. Жалоба дословно: «приходится заходить во входящие, тыкать мышкой
 * на диалог и после нажимать комбинацию». Обвязка успеха при этом ОДНА
 * (`принятоУспешно`): две копии разъехались бы на первой правке.
 *
 * Порядок «сначала принять, потом открыть» намеренный. Открой мы диалог до
 * ответа сервера — человек увидел бы чужой уже принятый диалог с плашкой
 * «Диалог принял Иван» и решил бы, что сочетание сработало неверно. Ответ
 * приходит за десятки миллисекунд, а правда важнее мгновенности.
 */
export async function claimFromQueue(convId: string, navigate: NavigateFunction): Promise<void> {
  try {
    const res = await claimConversation(convId);
    принятоУспешно(convId, res);
    выбралСам(convId);
    // ⚠ ВЗЯТЬ ДИАЛОГ — ТОЖЕ СВОЁ ДЕЙСТВИЕ (жалоба владельца 02.09: «когда берёшь
    // новые диалоги, они сначала все внизу, потом скачут вверх»).
    //
    // Порядок списка заморожен четыре секунды после наведения на колонку, а
    // строки, которых в замороженном плане нет, встают В КОНЕЦ — иначе замораживать
    // было бы нечего. Диалог, только что взятый из очереди, как раз такая строка:
    // он появлялся внизу и уезжал наверх, когда заморозка отпускала.
    //
    // Своё действие видно сразу — то же правило, что и у отправки сообщения.
    //
    // ⚠ ПОЧЕМУ ЭТОГО БЫЛО МАЛО И ЖАЛОБА ПОВТОРИЛАСЬ В ТОТ ЖЕ ДЕНЬ. Сброс плана
    // срабатывает СЕЙЧАС, а строка приезжает с сервера через секунду-две —
    // заморозка к тому времени взводится заново, уже без неё, и строка опять
    // падает в хвост. Поэтому диалог называется поимённо: он помечен как свой и
    // встанет на своё место, когда бы ни доехал.
    пересобратьПорядок(convId);
    navigate(`/chats/${convId}`);
    requestComposerFocus(); // принял — сразу пиши (7.1 п.3)
  } catch (err) {
    /*
     * Причину говорит сервер, и выбрасывать её нельзя: у принятия четыре
     * разных отказа с готовым человеческим текстом («канал ведут другие
     * операторы», «вы выведены из работы с диалогами», «диалог закрыт»), и ни
     * одна из этих причин от повтора не меняется.
     */
    /*
     * ⚠ СВОЙ ЖЕ ДИАЛОГ — ЭТО УСПЕХ, А НЕ ОТКАЗ (снимок владельца 29.08).
     *
     * Оператор придержал клавишу принятия и получил стопку красных тостов
     * «Не получилось принять диалог: вы уже приняли этот диалог». Диалог при
     * этом был принят — то есть система четырежды пожаловалась на то, что
     * сделала. Человек, читающий такое, идёт проверять, что сломалось.
     *
     * Повторное принятие своего диалога ничего не меняет и ничего не портит:
     * оно просто уже случилось. Значит и вести себя надо как при успехе —
     * открыть диалог и поставить курсор в поле ввода.
     */
    if (err instanceof ApiError && err.status === 409) {
      const детали = err.details as AlreadyClaimedDetails | undefined;
      if (детали?.mine) {
        выбралСам(convId);
        // ⚠ ВЗЯТЬ ДИАЛОГ — ТОЖЕ СВОЁ ДЕЙСТВИЕ (жалоба владельца 02.09: «когда берёшь
        // новые диалоги, они сначала все внизу, потом скачут вверх»).
        //
        // Порядок списка заморожен четыре секунды после наведения на колонку, а
        // строки, которых в замороженном плане нет, встают В КОНЕЦ — иначе замораживать
        // было бы нечего. Диалог, только что взятый из очереди, как раз такая строка:
        // он появлялся внизу и уезжал наверх, когда заморозка отпускала.
        //
        // Своё действие видно сразу — то же правило, что и у отправки сообщения.
        //
        // ⚠ ПОЧЕМУ ЭТОГО БЫЛО МАЛО И ЖАЛОБА ПОВТОРИЛАСЬ В ТОТ ЖЕ ДЕНЬ. Сброс плана
        // срабатывает СЕЙЧАС, а строка приезжает с сервера через секунду-две —
        // заморозка к тому времени взводится заново, уже без неё, и строка опять
        // падает в хвост. Поэтому диалог называется поимённо: он помечен как свой и
        // встанет на своё место, когда бы ни доехал.
        пересобратьПорядок(convId);
        navigate(`/chats/${convId}`);
        requestComposerFocus();
        return;
      }
    }
    const сказал = err instanceof ApiError ? err.message.trim() : "";
    showToast({
      title: "Не получилось принять диалог",
      message: сказал || "Попробуйте ещё раз",
      color: "red",
    });
  }
}

/**
 * Отказаться от диалога, КОТОРЫЙ СЕЙЧАС НЕ ОТКРЫТ, — сестра `claimFromQueue`.
 *
 * ⚠ ЗАЧЕМ ОНА ПОЯВИЛАСЬ (07.09). В браузерной карточке очереди рядом с
 * «Принять» встала вторая кнопка — «Отклонить», и нажатие приходит в
 * платформенный слой, где React-хука `useDeclineConversation` не позвать: его
 * компонент на экране не рождался, диалог даже не открыт.
 *
 * ⚠ И ЗАЧЕМ ОНА ТАКАЯ КОРОТКАЯ. Всё, что делает удавшийся и не удавшийся
 * отказ, лежит в `useInbox.ts` (`отклоненоУспешно` / `отказНеПрошёл`) и зовётся
 * ОБОИМИ путями — экранным и уведомлением. Вторая копия обвязки — самый
 * частый класс дефектов этого проекта: два пути считают одно поле по-разному и
 * расходятся молча, на первой же правке счётчика или текста.
 *
 * Следующего в очереди берём ДО запроса — ровно как в мутации: после удаления
 * строки соседа уже не найти.
 */
export async function declineFromQueue(convId: string, navigate: NavigateFunction): Promise<void> {
  const следующий = nextInboxId(convId);
  try {
    const res = await declineConversation(convId);
    отклоненоУспешно(convId, res, следующий, navigate);
  } catch (err) {
    отказНеПрошёл(convId, err);
  }
}

/**
 * Принять ПЕРВОГО ЖДУЩЕГО, спросив очередь у сервера.
 *
 * ⚠ ПОСЛЕДНЕЕ ЗВЕНО ПРОСЬБЫ «принимать без клика мышки и не заходя во
 * Входящие» (владелец, 30.08 — третье возвращение к теме). Клавиша приёма
 * брала первого из КЭША выдачи `/inbox`, а кэш появляется только при открытии
 * вкладки: у диспетчера, работающего из «Моих», клавише было неоткуда узнать,
 * кто ждёт. Кадры очереди кэш не создают намеренно («вкладку не открывали —
 * кэш не создаём»), так что чинить надо не кадрами, а прямым вопросом серверу.
 *
 * Порядок отдаёт сервер — «дольше всех ждёт — тот первый» (offered_at ASC), и
 * это тот же порядок, что видит открытая вкладка. `fetchInboxQueue` заодно
 * сеет стор очереди, так что счётчики не разъезжаются.
 *
 * Нажали двое разом — второй получит от `claimFromQueue` честное «Диалог
 * принял Иван», ровно как при клике; наперегонки со следующим не бежим:
 * серверный текст объясняет, что случилось, а тихий перескок на другого
 * человека — снова «я нажал на одного, открылся другой».
 */
export async function взятьПервогоССервера(navigate: NavigateFunction): Promise<void> {
  let первый: string | undefined;
  try {
    первый = (await fetchInboxQueue(0)).items.find((row) => row.in_inbox !== false)?.id;
  } catch {
    // Причина не важна человеку, важно «не принялось»: сеть/сервер скажут
    // своё в консоль сами, а клавиша не имеет права промолчать.
    showToast({
      title: "Не получилось спросить очередь",
      message: "Проверьте соединение и попробуйте ещё раз",
      color: "red",
    });
    return;
  }
  if (!первый) {
    // Молчание читалось бы как «клавиша сломана» — ровно сегодняшняя жалоба.
    showToast({ title: "Очередь пуста", message: "Сейчас никто не ждёт" });
    return;
  }
  await claimFromQueue(первый, navigate);
}
