import { markConversationRead } from "./api";
import { applyLocalRead } from "@/shared/realtime/applyWsEvent";

/**
 * Отметка «прочитано» с досылкой, если запрос не дошёл.
 *
 * ⚠ ЗАЧЕМ ПОМНИТЬ НЕДОСТАВЛЕННОЕ (аудит 30.08). Эффект открытия диалога слал
 * `POST /read` и глотал ошибку с припиской «маркер доедет при следующем
 * открытии». Не доедет: ретраи транспорта покрывают только 502/503/504 и
 * сетевые сбои в окне около секунды, а обрыв туннеля подольше, 429 от nginx
 * или 500 проходят мимо — и на сервере маркер не сдвинут.
 *
 * Локально бейдж уже погашен, но тихая сверка раз в две минуты перезапрашивает
 * списки, а `seedFromRows` объявлен «сервер — истина» и перезаписывает
 * счётчики целиком. Итог: диалог, В КОТОРЫЙ ОПЕРАТОР СМОТРИТ, снова становится
 * жирным и снова просит внимания. Человек видит непрочитанное там, где читает
 * прямо сейчас, — и перестаёт верить бейджам вообще.
 *
 * Поэтому недоставленное запоминается и досылается: при следующей отметке, из
 * тихой сверки и из догона после обрыва. Множество живёт в памяти вкладки и
 * намеренно не переживает перезагрузку — после неё диалог откроется заново и
 * отметит себя сам.
 */
const недоставленные = new Set<string>();

/** Отметить диалог прочитанным: локально сразу, на сервере — с досылкой. */
export async function отметитьПрочитанным(convId: string): Promise<void> {
  applyLocalRead(convId);
  try {
    await markConversationRead(convId);
    недоставленные.delete(convId);
  } catch {
    // Причина не важна: важно, что сервер не узнал. Молчать нельзя — счётчик
    // вернётся первой же сверкой.
    недоставленные.add(convId);
  }
}

/**
 * Досдать всё, что не дошло.
 *
 * ⚠ ЗОВЁТСЯ ПЕРЕД ПЕРЕЗАПРОСОМ СПИСКОВ, А НЕ ПОСЛЕ. Сверка тянет с сервера
 * счётчики, и если маркер не досдан к этому моменту, она принесёт старое
 * непрочитанное — то есть ровно тот дефект, ради которого всё и заведено.
 */
export async function досдатьМаркеры(): Promise<void> {
  if (недоставленные.size === 0) return;
  for (const convId of [...недоставленные]) {
    try {
      await markConversationRead(convId);
      недоставленные.delete(convId);
      applyLocalRead(convId);
    } catch {
      // Оставляем в очереди: следующая сверка попробует снова.
    }
  }
}

/** Только для тестов и смены пользователя: забыть накопленное. */
export function забытьМаркеры(): void {
  недоставленные.clear();
}

/** Только для тестов: сколько маркеров ждёт досылки. */
export function ждутДосылки(): number {
  return недоставленные.size;
}
