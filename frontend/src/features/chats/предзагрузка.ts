/**
 * Спросить диалог ДО того, как по нему щёлкнули.
 *
 * ⚠ ЗАЧЕМ ЭТО ВООБЩЕ (просьба владельца 05.09: «сделай моментальную подгрузку
 * диалога, есть небольшой тайминг»).
 *
 * Сервер к задержке отношения не имеет — замер боя за шесть часов:
 * `GET /conversations/{id}` n=123, среднее 55 мс, максимум 436;
 * `GET /conversations/{id}/messages` n=130, среднее 42 мс, максимум 283.
 * Оба запроса уходят ПАРАЛЛЕЛЬНО (сторож `ThreadOpenParallel0509`), то есть
 * лента ждёт один круг до сервера, а не два. Но ждёт она его ПОСЛЕ нажатия —
 * и весь этот круг человек смотрит на скелет.
 *
 * Круг никуда не денется, зато его можно сдвинуть в прошлое: человек наводит
 * мышь на строку раньше, чем нажимает, и это время у нас есть даром.
 *
 * ЧЕГО ЗДЕСЬ НЕТ. Предзагрузка ничего не отмечает прочитанным, не двигает
 * фокус и не трогает открытый диалог — она только кладёт в кэш два ответа,
 * которые всё равно были бы запрошены нажатием. Не нажали — ответы протухнут
 * сами (`gcTime` 30 минут) и никому не помешают.
 */

/**
 * Сколько держать мышь на строке, прежде чем спрашивать сервер.
 *
 * ЧИСЛО ВЫБРАНО МЕЖДУ ДВУМЯ ЗАМЕРАМИ, А НЕ НА ГЛАЗ.
 *
 * СНИЗУ его держит проводка мышью. Строка списка — 84 px (`ROW_HEIGHT` в
 * `ChatListPane`), а прицельное движение мыши идёт со скоростью порядка тысячи
 * пикселей в секунду, то есть строку под курсором пересекает за ~84 мс. Порог
 * 150 мс означает: всё, что летит быстрее 560 px/s (84 px за 150 мс), не рождает
 * НИ ОДНОГО запроса — колонку в пятьдесят строк можно проводить мышью насквозь
 * бесплатно. Порог в 30–50 мс превратил бы ту же проводку в полсотни запросов
 * от одного человека, а операторов в смене тринадцать.
 *
 * СВЕРХУ его держит сам смысл затеи. От момента, когда курсор встал на цель,
 * до нажатия проходит порядка 250–400 мс (доводка + решение). Успеть надо в
 * это окно: 150 мс ожидания + 55 мс среднего ответа детали = 205 мс — ответ
 * уже в кэше к нажатию. Порог 400 мс не успевал бы ровно у тех, кто работает
 * быстро, то есть у тех, ради кого всё и делается.
 */
export const ПОРОГ_НАВЕДЕНИЯ_МС = 150;

/**
 * Положить в кэш деталь и первую страницу ленты.
 *
 * ⚠ `prefetch*` МОЛЧА НИЧЕГО НЕ ДЕЛАЕТ, ЕСЛИ ДАННЫЕ СВЕЖИЕ, — и это здесь
 * главное свойство, а не мелочь. Общий `staleTime` 30 секунд
 * (`app/queryClient.ts`) означает, что повторное наведение на ту же строку,
 * возврат к соседу и метание между двумя диалогами не стоят ни одного запроса.
 * Своей проверки «а не спрашивали ли мы это только что» заводить не надо: она
 * была бы вторым ответом на вопрос, у которого уже есть один.
 *
 * Ключи и `queryFn` — ТЕ ЖЕ, что у `useConversationDetail` и
 * `useThreadMessages`. Разойдись они хоть на букву — предзагрузка наполняла бы
 * соседний кэш, а лента по-прежнему ходила бы на сервер, и заметить это можно
 * было бы только замером.
 */
export function предзагрузитьДиалог(convId: string): void {
  if (!convId) return;
  // Открытый диалог спрашивает себя сам — второй заход был бы шумом в логе.
  if (useChatUiStore.getState().activeConversationId === convId) return;

  void queryClient.prefetchQuery({
    queryKey: qk.conversations.detail(convId),
    queryFn: () => fetchConversation(convId),
  });
  /*
   * ⚠ ГРЕЕМ ЛЕНТУ, ТОЛЬКО ЕСЛИ ЕЁ В КЭШЕ НЕТ ВОВСЕ (правка 07.09).
   *
   * `prefetchInfiniteQuery` с `pages: 1` не «догружает первую страницу» — он
   * ПЕРЕСОБИРАЕТ ленту из одной страницы, выбрасывая всё остальное. Пока
   * предзагрузка шла только по наведению, это было почти безвредно: человек
   * наводится на строку, которую собирается открыть. С прогревом соседей
   * (07.09) она пошла САМА, без единого действия, — и у диалога, который
   * человек читал две минуты назад и пролистал вверх, кэш из двух страниц
   * [старое, свежий хвост] превращался в одну [старое]. Свежий хвост
   * исчезал, а вместе с ним и последние сообщения клиента: открыв такой
   * диалог, человек увидел бы старую переписку без её конца.
   *
   * Проверено сквозным зондом ревьюера, поэтому здесь стоит замок, а не
   * оговорка в комментарии: есть данные — не трогаем, пусть их обновляет
   * тот, кто ими владеет (хук ленты при открытии и кадры WS).
   */
  if (queryClient.getQueryData(qk.messages.list(convId)) === undefined) {
    void queryClient.prefetchInfiniteQuery({
      queryKey: qk.messages.list(convId),
      queryFn: ({ pageParam }: { pageParam: string | null }) => fetchMessages(convId, pageParam),
      initialPageParam: null as string | null,
      // Вниз ничего не догружаем — низ живой (WS). Слово в слово как у
      // `useThreadMessages`: разойдись они, и кэш, положенный сюда, читался бы
      // хуком с другими правилами страниц.
      getNextPageParam: () => null,
      // Ровно первая страница: старое подтянет прокрутка вверх, когда и если
      // человек до неё доберётся. Тянуть историю впрок — платить за то, чего
      // никто не просил.
      pages: 1,
    });
  }
  предзагрузитьЛичность(convId);
}

/**
 * Личность клиента — ТРЕТИЙ запрос, и берётся он из строки списка.
 *
 * ⚠ ВОДОПАД, КОТОРЫЙ ЗДЕСЬ СНИМАЕТСЯ. Карточка справа спрашивает
 * `GET /clients/{id}/identity`, а `client.id` узнаёт из ДЕТАЛИ диалога — то
 * есть ждёт круг до сервера, чтобы начать второй. Замер боя за восемь часов:
 * 5 047 вызовов identity при p50 21 мс, почти по одному на каждое открытие
 * карточки. Ждать деталь незачем: `client.id` уже лежит в строке списка,
 * оттуда же его берёт шапка ленты (`ChatThreadPane`, `head`).
 *
 * ⚠ СТРОКИ МОЖЕТ НЕ БЫТЬ — И ЭТО НЕ ПОВОД ГАДАТЬ. Приход по прямой ссылке и
 * переход из «Разбора диалогов» открывают диалог, которого в левой колонке
 * нет; тогда identity спросит сама карточка, когда приедет деталь. Молча
 * пропустить лучше, чем сходить не за тем клиентом.
 *
 * ⚠ ПРАВО СПРАШИВАЕМ ТО ЖЕ, ЧТО И КАРТОЧКА (`ClientCardPane`: `canManage =
 * can("conversations:manage")`). Ручка требует его на сервере, и без права
 * предзагрузка приносила бы наблюдателю 403 на каждое наведение — то есть
 * шум в журнале ровно там, где человек всё равно ничего не увидит.
 *
 * Ключ и запрос — слово в слово как у `useClientIdentity` (`card/clientApi`),
 * включая `staleTime`. Разойдись они — карточка ходила бы на сервер поверх
 * уже привезённого ответа, и заметить это можно было бы только замером;
 * сторож `DialogPreload0709` считает настоящие запросы именно поэтому.
 */
function предзагрузитьЛичность(convId: string): void {
  if (!useSessionStore.getState().permissions.includes("conversations:manage")) return;
  const clientId = cachedConversationRow(convId)?.client.id;
  if (!clientId) return;
  void queryClient.prefetchQuery({
    queryKey: [...CLIENTS_ROOT, "identity", clientId],
    queryFn: () => http.get<ClientIdentityDto>(`/clients/${encodeURIComponent(clientId)}/identity`),
    staleTime: 60_000,
  });
}

/**
 * Сколько держать ФОКУС на строке, прежде чем спрашивать сервер.
 *
 * ⚠ ПОЧЕМУ НЕ НОЛЬ, РАЗ «СРАЗУ». У клавиатуры нет проводки мышью, зато есть
 * своя быстрая пробежка: удержанный Tab идёт по строкам с шагом автоповтора
 * ОС — 25–33 мс на macOS, 30–50 мс на Windows. Виртуализатор держит в разметке
 * до двадцати трёх строк (7 видимых + overscan 8 в обе стороны), и порог 0
 * означал бы 46 запросов за полсекунды от одного человека — больше, чем
 * потолок nginx на человека (30 r/s), то есть 503 на его же собственную
 * работу. 60 мс проходят под любым автоповтором и не заметны тому, кто выбрал
 * строку осознанно: осмысленная остановка на строке длится сотни миллисекунд.
 *
 * Ниже наведения мышью втрое: у фокуса нет ложных срабатываний от пролёта
 * курсора, и держать его на одной планке с мышью незачем.
 */
export const ПОРОГ_КЛАВИАТУРЫ_МС = 60;

/** Отложенная предзагрузка: строка, на которой сейчас стоит курсор или фокус. */
let таймер = 0;
let ждём: string | null = null;

/**
 * Курсор встал на строку.
 *
 * Повторный вызов по той же строке ничего не перезапускает: браузер шлёт
 * `pointerenter` один раз на вход, но React перерисовывает строку на каждый
 * кадр WS — и перемонтирование обработчика не должно отодвигать срок.
 */
export function навелись(convId: string): void {
  жду(convId, ПОРОГ_НАВЕДЕНИЯ_МС);
}

/**
 * Строку выбрали клавиатурой — фокус приехал на неё без мыши.
 *
 * ⚠ ЗАЧЕМ ОТДЕЛЬНЫЙ ВХОД, А НЕ ТОТ ЖЕ `навелись`. 150 мс — плата за проводку
 * мышью: курсор пролетает строку за 84 мс, и порог отсекает пролёт. У фокуса
 * пролёта нет — он приходит туда, куда человек его послал, — и ждать этих
 * 150 мс значит дарить серверу фору, которой у клавиатуры и так нет (замер:
 * клик быстрее 150 мс и шаг ↑/↓ платят полный круг, p50 25 мс сервера плюс
 * RTT офиса ~120 мс).
 *
 * СЛОТ ОЖИДАНИЯ ОДИН НА ОБА ВХОДА, и это решение: мышь и клавиатура не
 * выбирают две строки одновременно, а последнее намерение человека обязано
 * отменять предыдущее — иначе уход курсора не гасил бы уже ненужный запрос.
 */
export function выбралиКлавишами(convId: string): void {
  жду(convId, ПОРОГ_КЛАВИАТУРЫ_МС);
}

function жду(convId: string, порог: number): void {
  if (ждём === convId) return;
  увели();
  ждём = convId;
  таймер = window.setTimeout(() => {
    ждём = null;
    таймер = 0;
    предзагрузитьДиалог(convId);
  }, порог);
}

/** Курсор ушёл со строки — отменяем то, чего не успели спросить. */
export function увели(): void {
  if (таймер) window.clearTimeout(таймер);
  таймер = 0;
  ждём = null;
}

/**
 * СОСЕДИ ОТКРЫТОГО ДИАЛОГА — ТЕ, ПО КОМУ ХОДЯТ ↑/↓.
 *
 * ⚠ ЧТО БЫЛО. Грелась ровно одна строка — та, что под курсором. Клавиши,
 * касание, back/forward и кнопки листания в шапке ленты форы не имеют вовсе:
 * первое нажатие ↑ или ↓ всегда платило круг до сервера. Шаг по списку из
 * `hotkeys/dispatch` спрашивает следующего В ТУ ЖЕ СТОРОНУ уже после перехода,
 * то есть выручает вторую стрелку подряд, но не первую.
 *
 * ⚠ ГРАНИЦА — ДВА СОСЕДА, И ЭТО ПОТОЛОК, А НЕ УМОЛЧАНИЕ. Окно из пяти строк
 * стоило бы десяти запросов на каждое открытие диалога при тринадцати
 * диспетчерах за одним офисным NAT; вверх и вниз — ровно те две строки, куда
 * ведёт одно нажатие.
 *
 * ⚠ ГРЕЕМ В ПРОСТОЕ, А НЕ В ТОТ ЖЕ МИГ. Открытие диалога — самый занятый
 * момент: одновременно едут деталь, лента, личность клиента и его история.
 * Четыре запроса соседей, вброшенные в этот же кадр, конкурировали бы с тем,
 * что человек смотрит прямо сейчас. `requestIdleCallback` пропускает их в
 * первую же паузу.
 *
 * ⚠ ДЕДУПЛИКАЦИЯ ПО АКТИВНОМУ ДИАЛОГУ ОБЯЗАТЕЛЬНА. Список перерисовывается на
 * каждый кадр WS (девять живых каналов — десятки событий в минуту), а зовут
 * нас из эффекта, который видит каждую такую перерисовку. Без этой проверки
 * соседи спрашивались бы заново несколько раз в минуту на каждого из
 * тринадцати человек.
 */

/**
 * Отсрочка захода к соседям: столько ждём паузы, дальше идём и без неё.
 *
 * Это `timeout` у `requestIdleCallback` (и весь срок у запасного таймера):
 * простоя может не случиться вовсе, а обещание «сосед готов к первому нажатию»
 * надо выполнить. Пятая доля секунды — заведомо меньше, чем время, за которое
 * человек читает открывшийся диалог и решает идти дальше.
 */
export const ПРОСТОЙ_МС = 200;

/** Вверх и вниз — ровно те две строки, куда ведёт ОДНО нажатие стрелки. */
const СОСЕДЕЙ_ЗА_РАЗ = 2;

/** Активный диалог, для соседей которого уже назначен (или сделан) заход. */
let соседиДля: string | null = null;
let отменитьПростой: (() => void) | null = null;

function вПростое(дело: () => void): () => void {
  // ⚠ `requestIdleCallback` нет в Safari до 16.4 и нет в jsdom. Запасной путь
  // — обычный таймер: он не так точен, но обещание «не в кадр открытия»
  // выполняет, а без него на этих платформах не грелось бы вовсе.
  if (typeof window.requestIdleCallback === "function") {
    const id = window.requestIdleCallback(дело, { timeout: ПРОСТОЙ_МС });
    return () => window.cancelIdleCallback(id);
  }
  const id = window.setTimeout(дело, ПРОСТОЙ_МС);
  return () => window.clearTimeout(id);
}

export function греемСоседей(активный: string, соседи: ReadonlyArray<string | undefined>): void {
  if (соседиДля === активный) return; // кадр WS ничего не перезапускает
  /*
   * Ушли в другой диалог — прежних соседей догонять незачем: человек уже не там,
   * а канал у него общий с тем, что едет прямо сейчас.
   *
   * ⚠ ЗАМОК ЗДЕСЬ ОДИН, И ЭТО НАМЕРЕННО. Второй — проверка «а тот ли ещё диалог»
   * внутри самого захода — недостижим, пока отмена работает: он выглядел бы
   * страховкой, а на деле был бы кодом, который нельзя ни проверить, ни сломать.
   */
  забытьСоседей();

  const цели: string[] = [];
  for (const id of соседи) {
    if (!id || id === активный || цели.includes(id)) continue;
    цели.push(id);
    // Потолок держим ЗДЕСЬ, а не на совести зовущего: обещание «не больше двух»
    // должно жить там же, где оно записано, иначе следующий вызов его обойдёт.
    if (цели.length === СОСЕДЕЙ_ЗА_РАЗ) break;
  }
  // Строки открытого диалога в списке ещё нет (прямая ссылка, «Разбор
  // диалогов») — соседей не знаем. Не отмечаемся, чтобы спросить их, когда
  // список приедет.
  if (!активный || цели.length === 0) return;

  соседиДля = активный;
  отменитьПростой = вПростое(() => {
    отменитьПростой = null;
    if (document.visibilityState === "hidden") {
      // Скрытая вкладка не читает список и по стрелкам не ходит. Отметку при
      // этом СНИМАЕМ: иначе вернувшийся к работе человек остался бы с холодными
      // соседями навсегда — активный диалог тот же, и второго захода не будет.
      соседиДля = null;
      return;
    }
    for (const id of цели) предзагрузитьДиалог(id);
  });
}

/** Забыть назначенный заход к соседям: диалог сменился или колонки больше нет. */
export function забытьСоседей(): void {
  отменитьПростой?.();
  отменитьПростой = null;
  соседиДля = null;
}
