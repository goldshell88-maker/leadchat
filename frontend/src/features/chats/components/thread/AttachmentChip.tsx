import type { AttachmentDto } from "@/shared/api/types";
import { ExternalLink } from "@/shared/ui/ExternalLink";
import { IconLink, IconMapPin, IconPaperclip, IconTag } from "@/shared/ui/Icon";
import "./attachment-chip.css";

/**
 * Вложение, которое не картинка и не голосовое: ссылка, место, объявление.
 *
 * ЧТО БЫЛО. Все три рисовались ОДНОЙ И ТОЙ ЖЕ строкой со скрепкой — значок,
 * имя, размер. Имя при этом чаще всего не своё: Авито своего названия не даёт,
 * и сервер подставляет подпись вида («Ссылка», «Геопозиция», «Объявление» —
 * `_ATTACHMENT_LABELS` в app/integrations/avito/adapter.py). То есть в ленте
 * стояло «📎 Ссылка» и «📎 Геопозиция»: вид вложения назван, а САМОЕ НУЖНОЕ —
 * куда ведёт ссылка и что за место — не показано вовсе. Оператор открывал
 * каждую наугад, в новой вкладке, чтобы понять, стоило ли открывать.
 *
 * Замер боя за 60 дней: ссылок 123, мест 15, объявлений 2. Немного, но каждая
 * из них — то, ради чего клиент и написал.
 *
 * КАК СТАЛО. У каждого вида свой значок и своя пара строк: сверху — ЧТО ЭТО
 * («Ссылка», «Место», «Объявление»), под ним — СУТЬ (домен, адрес, название
 * объявления). Вид виден, не открывая.
 *
 * ⚠ ЧЕГО ЗДЕСЬ НЕТ. Картинок и голосовых: их лента рисует по-своему — снимок
 * открывается во весь экран, у голосового свой проигрыватель (VoicePlayer).
 * Сюда приходит всё остальное, включая незнакомые виды: для них остаётся
 * скрепка с именем и размером, и это не заглушка, а правило — неизвестное
 * вложение обязано выглядеть спокойно, а не поломкой.
 */

type Вид = "link" | "location" | "item" | "file";

/**
 * Подпись, которой сервер называет вложение, когда Авито не дало своего имени
 * (`_ATTACHMENT_LABELS`). Нужна ровно для одного: не печатать «Ссылка» второй
 * раз под нашим же словом «Ссылка». Разъедется — вернётся повтор в подписи, а
 * не поломка.
 */
const ПОДПИСЬ_СЕРВЕРА: Record<Вид, string> = {
  link: "Ссылка",
  location: "Геопозиция",
  item: "Объявление",
  file: "Файл",
};

/**
 * Что стоит на месте сути, когда открыть нечего: адреса Авито не дало или он
 * не той схемы. «Ссылка» здесь написать НЕЛЬЗЯ — этим словом уже подписана
 * строка выше, и чип читался бы как «Ссылка / Ссылка».
 */
const БЕЗ_АДРЕСА = "Адреса нет";

/** Слово, которым вложение называется в ленте. */
const ЧТО_ЭТО: Record<Вид, string> = {
  link: "Ссылка",
  location: "Место",
  item: "Объявление",
  file: "Файл",
};

const ЗНАЧОК: Record<Вид, typeof IconLink> = {
  link: IconLink,
  location: IconMapPin,
  // Ценник — уже готовая фигура набора: объявление и есть товар с ценой.
  item: IconTag,
  file: IconPaperclip,
};

function видВложения(avitoType: string | null | undefined): Вид {
  return avitoType === "link" || avitoType === "location" || avitoType === "item"
    ? avitoType
    : "file";
}

/**
 * Адрес, по которому МОЖНО перейти, или `null`.
 *
 * ⚠ СХЕМУ ПРОВЕРЯЕМ, ХОТЯ АДРЕС И ПРИШЁЛ ОТ АВИТО. В `href` попадает поле из
 * чужого сообщения, а `javascript:` в `href` — это выполнение кода по нажатию
 * оператора, у которого открыта вся консоль. Проверка стоит одной строки;
 * доверие к чужому полю не стоит ничего. Тот же довод и то же решение
 * («нет адреса — не рисуем перехода»), что в shared/lib/внутреннийАдрес.ts.
 */
function разобратьАдрес(url: string | null | undefined): URL | null {
  if (!url) return null;
  try {
    const адрес = new URL(url);
    return адрес.protocol === "http:" || адрес.protocol === "https:" ? адрес : null;
  } catch {
    // Не адрес вовсе — случай обработан здесь же: чип нарисуется без перехода,
    // именем и видом. Молча проглоченного тут нет, есть решение.
    return null;
  }
}

/** «avito.ru» — без `www.`, который ничего не сообщает и съедает место. */
function хост(адрес: URL): string {
  return адрес.hostname.replace(/^www\./, "");
}

/** Хвост адреса под доменом. Пусто — если это корень сайта. */
function хвост(адрес: URL): string | null {
  const строка = `${адрес.pathname}${адрес.search}`;
  if (строка === "" || строка === "/") return null;
  try {
    // Русские адреса Авито приезжают в процентах: `%D1%80%D0%B5%D0%BC%D0%BE%D0%BD%D1%82`
    // читается человеком как шум, «ремонт» — как слово.
    return decodeURI(строка);
  } catch {
    // Битая процентная последовательность — показываем как пришло.
    return строка;
  }
}

/** Мера файла. Тот же вид, что у строки вложения в MessageBubble. */
function размерСтрокой(bytes: number | null | undefined): string | null {
  if (typeof bytes !== "number" || !Number.isFinite(bytes) || bytes <= 0) return null;
  if (bytes < 1024) return `${bytes} Б`;
  if (bytes < 1024 * 1024) return `${Math.round(bytes / 1024)} КБ`;
  return `${(bytes / (1024 * 1024)).toFixed(1)} МБ`;
}

export function AttachmentChip({ attachment }: { attachment: AttachmentDto }) {
  const вид = видВложения(attachment.avito_type);
  const адрес = разобратьАдрес(attachment.url);
  // Имя показываем, только когда оно СВОЁ: подпись вида уже стоит строкой выше.
  const своё = attachment.name && attachment.name !== ПОДПИСЬ_СЕРВЕРА[вид] ? attachment.name : null;

  let суть: string;
  let подробность: string | null = null;
  if (вид === "link") {
    // ⚠ ГЛАВНАЯ СТРОКА У ССЫЛКИ — ДОМЕН, А НЕ НАЗВАНИЕ. Просьба владельца
    // дословно: «у ссылки видно куда». Название, если Авито его дало, уходит
    // строкой ниже: оно объясняет, а решение «открывать ли» принимают по домену.
    суть = адрес ? хост(адрес) : (своё ?? БЕЗ_АДРЕСА);
    подробность = адрес ? (своё ?? хвост(адрес)) : null;
  } else if (вид === "location") {
    // У места Авито обычно присылает адрес именем. Не прислало — говорим
    // ровно то, что знаем, и не выдумываем координат, которых у нас нет.
    суть = своё ?? "Точка на карте";
  } else if (вид === "item") {
    суть = своё ?? (адрес ? хост(адрес) : БЕЗ_АДРЕСА);
  } else {
    суть = attachment.name;
    подробность = размерСтрокой(attachment.size);
  }

  const Фигура = ЗНАЧОК[вид];
  const содержимое = (
    <>
      <span className="att-chip__icon">
        <Фигура size={16} />
      </span>
      <span className="att-chip__text">
        <span className="att-chip__kind">{ЧТО_ЭТО[вид]}</span>
        <span className="att-chip__gist">{суть}</span>
        {подробность && <span className="att-chip__note">{подробность}</span>}
      </span>
    </>
  );

  if (!адрес) {
    // Переходить некуда — и вид это говорит: ни рамки нажатия, ни курсора руки.
    // Подчёркнутый текст без перехода оператор тыкает до раздражения.
    return (
      <span className="att-chip att-chip--flat" data-kind={вид}>
        {содержимое}
      </span>
    );
  }
  // Мимо моста нельзя (проверка 24.09): в настольном приложении `target=_blank`
  // открылся бы внутри окна и подменил рабочий экран.
  return (
    <ExternalLink
      className="att-chip"
      data-kind={вид}
      url={адрес.href}
      // Домена хватает для решения, но полный адрес иногда нужен целиком —
      // например, чтобы понять, ведёт ли ссылка на нужное объявление.
      title={адрес.href}
    >
      {содержимое}
    </ExternalLink>
  );
}
