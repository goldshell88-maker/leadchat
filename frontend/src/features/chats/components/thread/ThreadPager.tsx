import { Button } from "@mantine/core";
import { useNavigate } from "react-router-dom";
import { nextInboxId } from "../../inbox/api";
import { выбралСам } from "../../выборДиалога";

/**
 * КОНВЕЙЕР ОЧЕРЕДИ «ВХОДЯЩИЕ» — «Следующий (N)».
 *
 * ⚠ ШЕВРОНЫ «ПРЕДЫДУЩИЙ/СЛЕДУЮЩИЙ» УБРАНЫ 09.09 ПО ПРОСЬБЕ ВЛАДЕЛЬЦА:
 * «убери эти стрелочки и сделай ... клавиши, чтобы листать диалоги вниз и
 * вверх». Листание переехало на `Mod+↓` / `Mod+↑`, включённые по умолчанию
 * (разбор — в `hotkeys/catalog.ts` у пары `listNext`/`listPrev`), а оба умения
 * кнопок — догрузку страницы на границе загруженного и честное «идти некуда»
 * без съеденного нажатия — забрал `hotkeys/dispatch.ts::шагПоСписку`.
 *
 * ⚠ ВИДИМЫЙ СПОСОБ СМЕНИТЬ ДИАЛОГ НЕ ПРОПАЛ, И ЭТО ВАЖНО: в проекте записано
 * правило «все хоткеи продублированы видимыми элементами UI». Дубль листания —
 * сам список слева: щелчок по строке. Ниже 768px колонки на экране нет, но там
 * есть «Назад к списку», то есть цена правки на телефоне — два касания вместо
 * одного, а не потеря умения. Сами шевроны там и не работали: без кэша списка
 * (а на телефоне при открытом диалоге `ChatListPane` не смонтирован) обе кнопки
 * приходили погашенными.
 *
 * ⚠ КОНВЕЙЕР ОСТАЁТСЯ, И ОН НЕ ШЕВРОН. В очереди у слова «следующий» другой
 * смысл: строки уходят из-под ног (их принимают коллеги), принятый диалог из
 * очереди исчезает — и обычный шаг по списку после приёма сказал бы «идти
 * некуда», хотя ждут ещё сорок человек. `nextInboxId` этот случай знает: он
 * ведёт к первому ждущему, даже когда открытого диалога в очереди уже нет, и
 * обходит очередь кольцом. Плюс число на кнопке — обещание «столько осталось
 * разобрать», ради которого её и рисовали.
 */
export function ThreadPager({
  convId,
  очередь,
  ждётЕщё,
}: {
  convId: string;
  /** Открыты «Входящие»: показываем конвейер очереди. */
  очередь: boolean;
  /** Сколько в очереди ждёт КРОМЕ открытого — число на кнопке. */
  ждётЕщё: number;
}) {
  const navigate = useNavigate();

  // Кнопка, ведущая в никуда, здесь хуже отсутствующей, а её число — обещание
  // «столько осталось разобрать».
  if (!очередь || ждётЕщё <= 0) return null;

  return (
    <div className="thread-pager" role="group" aria-label="Очередь «Входящие»">
      <Button
        className="thread-header__next"
        size="compact-sm"
        variant="subtle"
        onClick={() => {
          const next = nextInboxId(convId);
          // Переход, которого человек попросил сам, — иначе замок
          // недописанного ответа откатит его обратно (выборДиалога).
          if (next) выбралСам(next);
          navigate(next ? `/chats/${next}` : "/chats");
        }}
      >
        Следующий ({ждётЕщё})
      </Button>
    </div>
  );
}
