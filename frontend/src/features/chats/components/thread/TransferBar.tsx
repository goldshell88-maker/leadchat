/**
 * Три ответа на висящее предложение: два у получателя, третий у передавшего.
 * Имя совпадает с хвостом ручки (`/transfer/{kind}`) — одно слово на кнопку,
 * запрос и всплывающее сообщение, чтобы человек связал нажатие с ответом.
 */
type Действие = "accept" | "decline" | "cancel";

/**
 * Исполнитель решения, о котором попросили КНОПКОЙ В УВЕДОМЛЕНИИ.
 *
 * ⚠ ОТДЕЛЬНЫМ КОМПОНЕНТОМ, А НЕ ЭФФЕКТОМ В `TransferBar`, И ЭТО ВЫНУЖДЕННО:
 * полоса выходит из себя пораньше (`if (!offer) return null`), а хук после
 * условного выхода — нарушение порядка хуков. Здесь же он законен, потому что
 * этот компонент вообще рождается только тогда, когда решение принимать
 * ЕСТЬ КОМУ: его рисуют рядом с кнопками получателя.
 *
 * ⚠ ПОЧЕМУ ПРОСЬБА ЖДЁТ ЗДЕСЬ, А НЕ ИСПОЛНЯЕТСЯ В МЕСТЕ НАЖАТИЯ. Нажатие
 * приходит в платформенный слой, когда диалог ещё не открыт: детали нет,
 * прав нет, кэш чужой. Тот же приём, что у закрытия по Ctrl+D — просьба с
 * адресом ЖДЁТ того, кто умеет её исполнить, вместо того чтобы пропасть.
 *
 * Ничего не рисует: он только про поведение. Имя латиницей — иначе
 * `react-hooks/rules-of-hooks` не признает функцию компонентом и запретит в
 * ней хуки (правило смотрит на ЛАТИНСКУЮ прописную).
 */
function TransferDecisionFromNotify({
  convId,
  выполнить,
}: {
  convId: string;
  выполнить: (kind: "accept" | "decline") => void;
}) {
  const nonce = useActionBus((s) => s.transferDecisionNonce);
  const просьба = useActionBus((s) => s.transferDecision);
  // Ноль, а не текущий счётчик: просьбу, сделанную ДО нашего рождения,
  // исполнить обязаны именно мы — ради этого ожидания всё и затевалось.
  const виден = useRef(0);

  useEffect(() => {
    if (nonce === виден.current) return;
    // Чужой адрес или протухшая просьба — не наши, и «видели» их не мы:
    // отметиться значило бы съесть просьбу у той панели, которой она
    // адресована (диалоги открываются в одном экране по очереди).
    if (!просьба || просьба.convId !== convId) return;
    if (Date.now() - просьба.в > ЖИЗНЬ_ПРОСЬБЫ_МС) return;
    виден.current = nonce;
    useActionBus.getState().transferDecisionHandled(просьба);
    выполнить(просьба.kind);
  }, [nonce, просьба, convId, выполнить]);

  return null;
}

const ИТОГ: Record<Действие, string> = {
  accept: "Диалог принят",
  decline: "Вы отказались от диалога",
  cancel: "Передача отменена",
};

/**
 * Полоса предложенной передачи (требование заказчика от 7 августа).
 *
 * «Диалог не считается переданным, если другой сотрудник его не принял».
 * Пока предложение висит, ответственный НЕ меняется — диалог остаётся у
 * передающего, и отвечает клиенту он. Поэтому полоса выглядит по-разному с
 * двух сторон и обе стороны обязаны её видеть:
 *
 * * получателю — «Борис передал вам диалог» и две кнопки. Без них он не
 *   узнает, что от него чего-то ждут: диалог ведь не в его «Моих» и не в
 *   очереди;
 * * передающему — «ждёт подтверждения» с именем и кнопка «Отменить передачу».
 *   Строка не украшение: не видя её, он считает, что передал, перестаёт
 *   следить за диалогом — а диалог по-прежнему его, и клиент ждёт ответа от
 *   него. Кнопка — вторая половина той же мысли (просьба владельца 04.09):
 *   ошибиться адресатом легко, а до неё ошибку нельзя было забрать назад —
 *   оставалось ждать пятнадцать минут чужого отказа или просить коллегу в
 *   мессенджере.
 *
 * Остальным (руководитель смотрит чужой диалог) — та же строка без кнопок:
 * им важно понимать, почему диалог числится за одним, а обсуждают его двое.
 */
// Полосе нужны `transfer` и `id` — оба есть в строке списка, детали не ждём.
export function TransferBar({
  conversation,
  actionable = true,
}: {
  conversation: ConversationDto;
  /**
   * Показывать ли кнопки решения.
   *
   * ⚠ `false` — ДЛЯ ДИАЛОГА, ВЕРНУВШЕГОСЯ В ОЧЕРЕДЬ (боевой случай 28.08).
   * Диалог в очереди ничей, и принимать предложение не у кого: передававший им
   * уже не владеет. Берут такой диалог кнопкой «Принять диалог» полосы очереди
   * — и две кнопки с ОДНОЙ подписью рядом означали бы, что человек нажимает
   * наугад. Плашка остаётся объяснением, откуда взялось предложение.
   */
  actionable?: boolean;
}) {
  const qc = useQueryClient();
  const me = useSessionStore((s) => s.user);
  const [busy, setBusy] = useState<Действие | null>(null);

  const offer = conversation.transfer;
  if (!offer) return null;

  const iAmRecipient = actionable && offer.to.id === me?.id;
  const iAmGiver = offer.by?.id === me?.id;
  /*
   * ОТМЕНА — ТОЛЬКО ПЕРЕДАВШЕМУ (просьба владельца 04.09: «чтобы можно было
   * отменять передачу, если я случайно начал передавать не тому человеку»).
   *
   * Сервер пускает сюда ещё и обладателя `conversations:manage` — руками
   * разобрать чужой затор, — но кнопки ему здесь нет намеренно: рядом с
   * чужой передачей она читается как «убрать эту строку с глаз», а не как
   * «отменить чужое решение». Свою же ошибку человек исправляет тем же
   * жестом, каким её совершил, и в том же месте экрана.
   *
   * `actionable === false` — диалог вернулся в очередь: полоса там уже не
   * управление, а объяснение, откуда взялось предложение (боевой случай
   * 28.08), и третья кнопка в ряду с «Принять диалог» очереди означала бы
   * выбор наугад.
   */
  const iCanCancel = actionable && iAmGiver;

  /**
   * Итог передачи из ответа ручки — в деталь и в строку, без похода за ними.
   *
   * В строку кладём только то, что передача меняет: статус, ответственного и
   * само предложение. `transferred_to_me`, `pinned`, `unread_count` — личные
   * поля смотрящего, и деталь несёт их умолчаниями, а не правдой (сервер
   * считает их только для выдачи списка): переписать ими строку значило бы
   * снять чужую пометку.
   *
   * ⚠ И В ДЕТАЛИ ЭТИ ПОЛЯ ТОЖЕ ДЕРЖИМ ПРЕЖНИМИ (ревью 06.09). `_transfer_reply`
   * собирает деталь без `viewer` — `pinned: false` для всех, — а кнопка
   * закрепления в шапке (`ThreadActions`) читает `conversation.pinned` из
   * детали: ответ целиком снимал бы закрепление на глазах после любого из
   * трёх действий. Прежняя инвалидация детали этого не показывала, потому что
   * `GET /conversations/{id}` считает закрепление по смотрящему.
   */
  const применитьИтог = (ответ: ConversationDetailDto, kind: Действие) => {
    qc.setQueryData<ConversationDetailDto>(qk.conversations.detail(ответ.id), (old) =>
      old
        ? {
            ...ответ,
            pinned: old.pinned,
            transferred_to_me: old.transferred_to_me,
            unread_count: old.unread_count,
          }
        : ответ,
    );
    патчСтрок(
      (r) => r.id === ответ.id,
      (r) => ({
        ...r,
        status: ответ.status,
        status_since: ответ.status_since,
        assignee: ответ.assignee,
        transfer: ответ.transfer ?? null,
      }),
    );
    const яУчастник = (ответ.participants ?? []).some((p) => p.id === me?.id);
    /*
     * Принял — диалог теперь мой. В «Моих» он, как правило, УЖЕ стоит: сервер
     * держит там и предложенные мне передачи (`participants.mine_condition`:
     * `transfer_to_id == me`), а числа над вкладкой считают их тем же условием
     * (`tab_counts`; «не отвечено» — `own_condition`, куда получатель
     * передачи тоже входит). Поэтому числа здесь НЕ двигаем: +1 удваивал бы
     * диалог, который сервер посчитал ещё при предложении, а поправить его
     * было бы некому — перезапроса после принятия нет. Вставка — на случай
     * кэша старше предложения: дубль она не плодит. Пометка «своя» — иначе
     * заморозка порядка отправит строку в хвост (тот же путь, что у принятия
     * из очереди, `принятоУспешно`).
     */
    if (kind === "accept" && ответ.assignee?.id === me?.id) {
      вставитьСтроку(ответ, (f) => строкаВходитВМои(ответ, f));
      пересобратьПорядок(ответ.id);
    }
    /*
     * Отказался — диалог из моих «Моих» уходит: `transfer_to_id` снят,
     * ответственный прежний. Остаётся он только у позванного участника
     * (та же `mine_condition`, третья ветка) — тогда строку держим, но «не
     * отвечено» всё равно −1: долг считается по `own_condition`, куда
     * участники не входят. Без этого строка чужого диалога стояла бы в «Моих»
     * до случайного перезапроса списка — прежняя инвалидация корня это
     * скрывала. Поиск и «показывать закрытые» (`any` на сервере) не трогаем:
     * там диалог остаётся законно.
     */
    if (kind === "decline") {
      const ждал = Boolean(ответ.waiting_since) && STATUS_SHOWS_WAIT.has(ответ.status);
      if (!яУчастник) убратьСтроку(ответ.id, (f) => f.tab === "mine" && !f.q && !f.withClosed);
      сдвинутьСчёт({ mine: яУчастник ? 0 : -1, mine_waiting: ждал ? -1 : 0 });
    }
  };

  const act = async (kind: Действие) => {
    setBusy(kind);
    try {
      const ответ = await http.post<ConversationDetailDto>(
        `/conversations/${encodeURIComponent(conversation.id)}/transfer/${kind}`,
      );
      /*
       * ⚠ ОДИН КРУГ, А НЕ ТРИ (замер 06.09). Здесь стояло: POST → `await`
       * инвалидации детали → `await` инвалидации корня `conversations` — три
       * последовательных круга ≈105 мс + 3×RTT со спиннером на кнопке, а корень
       * накрывал ВСЕ выдачи и деталь разом: 3–4 лишних запроса на одно нажатие.
       *
       * Ручка отвечает деталью диалога целиком (`_transfer_reply` на сервере):
       * кладём её в кэш и правим строку списка сами. Второй стороне (тому, кто
       * передавал или кому передали) кадр `conversation:updated` приходит от
       * сервера — её списки чинятся им, а не нашим перезапросом.
       */
      if (ответ?.id === conversation.id) {
        применитьИтог(ответ, kind);
      } else {
        // Форма ответа не та, что обещана, — честнее спросить, чем угадывать.
        void qc.invalidateQueries({ queryKey: qk.conversations.detail(conversation.id) });
      }
      if (kind !== "cancel") {
        // Решение получателя: карточка с кнопками и строка предложения во
        // «Входящих» больше ни к чему. Убираем на месте, без запросов: одно
        // нажатие — один круг (замер 06.09).
        closeHandoffCard(conversation.id);
        useInboxStore.getState().remove(conversation.id);
        removeInboxRow(conversation.id);
      }
      toast.success(ИТОГ[kind]);
    } catch (e) {
      toast.error(
        "Не получилось",
        e instanceof ApiError ? e.message : "Попробуйте ещё раз",
      );
      // Устаревшее предложение сервер снял при отказе — полоса уйдёт с деталью.
      void qc.invalidateQueries({ queryKey: qk.conversations.detail(conversation.id) });
    } finally {
      setBusy(null);
    }
  };

  return (
    <div className="transfer-bar" role="status" data-mine={iAmRecipient || undefined}>
      <div className="transfer-bar__text">
        <Text fz="sm" fw={500} c="var(--lc-text-1)">
          {/* Отдел в скобках (04.09): решение «принять или отказаться»
              принимают по тому, кто передаёт, и отдел здесь половина ответа.
              «Коллега» — когда сотрудника уже удалили: у такого отдела нет,
              и скобок не появится. */}
          {iAmRecipient
            ? `${подписьСотрудника(offer.by, "Коллега")} передаёт вам диалог`
            : iAmGiver
              ? `Ждёт подтверждения: ${подписьСотрудника(offer.to)}`
              : `${подписьСотрудника(offer.by, "Коллега")} → ${подписьСотрудника(offer.to)}: ждёт подтверждения`}
        </Text>
        {offer.comment && (
          <Text fz="xs" c="var(--lc-text-2)">
            {offer.comment}
          </Text>
        )}
        {/*
          Напоминание про ответственность — только передающему и только пока
          он думает, что уже отдал. Получателю оно ни к чему: ему как раз
          предлагают взять.
        */}
        {iAmGiver && (
          <Text fz="xs" c="var(--lc-text-3)">
            Диалог пока за вами — отвечайте клиенту, если он напишет.
          </Text>
        )}
      </div>

      {iCanCancel && (
        <div className="transfer-bar__actions">
          {/*
            «ОТМЕНИТЬ ПЕРЕДАЧУ» СТОИТ РЯДОМ С «ДИАЛОГ ПОКА ЗА ВАМИ», И ЭТО ОДНА
            МЫСЛЬ, А НЕ ДВЕ. Напоминание объясняет, почему человек всё ещё
            отвечает за диалог; кнопка — единственный способ это состояние
            закончить, не дожидаясь чужого решения. До неё ошибшийся адресатом
            ждал пятнадцать минут или шёл просить коллегу в мессенджере.

            Второстепенная (`variant="default"`), потому что обычный ход
            событий — дождаться ответа коллеги, а не забрать предложение назад.
          */}
          <Button
            size="xs"
            variant="default"
            loading={busy === "cancel"}
            disabled={busy !== null}
            onClick={() => void act("cancel")}
          >
            Отменить передачу
          </Button>
        </div>
      )}

      {iAmRecipient && (
        <div className="transfer-bar__actions">
          {/*
            Кнопка «Принять»/«Отклонить» в браузерном уведомлении просит то же
            самое, что кнопки ниже, и исполняется ТЕМ ЖЕ `act` — вместе со всей
            правкой кэша, строки списка и счётчиков вкладок. Второй путь к этим
            полям разошёлся бы с первым молча.
          */}
          <TransferDecisionFromNotify convId={conversation.id} выполнить={(k) => void act(k)} />
          {/*
            «ПРИНЯТЬ ДИАЛОГ» — ОДНО НАЗВАНИЕ НА ВСЁ ВЗЯТИЕ ОТВЕТСТВЕННОСТИ.

            Одно и то же действие называлось в интерфейсе тремя словами:
            «Принять диалог» в нижней плашке очереди, «Взять в работу» кнопкой
            в правой карточке и просто «Принять» здесь. Человек читал три
            названия и искал между ними разницу — а разницы нет: во всех трёх
            случаях диалог становится его, и сервер пишет в ленту одну и ту же
            запись «Диалог принят: Имя».

            Выбрано «Принять диалог», а не «Взять в работу», по одной
            проверяемой причине: система уже отвечает этими словами. Системная
            запись в ленте, всплывающее «Диалог принят», шпаргалка «Ctrl+R —
            принять диалог» и справка по клавишам говорят «принят». Название
            кнопки обязано совпадать с тем, что человек увидит после нажатия,
            иначе он не свяжет одно с другим.
          */}
          <Button
            size="xs"
            loading={busy === "accept"}
            disabled={busy !== null}
            onClick={() => void act("accept")}
          >
            Принять диалог
          </Button>
          <Button
            size="xs"
            variant="default"
            loading={busy === "decline"}
            disabled={busy !== null}
            onClick={() => void act("decline")}
          >
            Отказаться
          </Button>
        </div>
      )}
    </div>
  );
}
