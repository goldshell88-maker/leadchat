/**
 * Просмотр присланной картинки во весь экран.
 *
 * ⚠ ЗАЧЕМ ЭТО ВООБЩЕ НУЖНО. Клиент чаще всего присылает не «картинку», а
 * ДОКАЗАТЕЛЬСТВО: фотографию экрана с ошибкой, шильдика с моделью, потёка на
 * задней стенке. Оператор по ней ставит диагноз и называет цену. До сих пор
 * такая фотография рисовалась в ленте одним `<img>` со стороной 280 пикселей и
 * `object-fit: cover` — то есть ОБРЕЗАННОЙ по краям, — и открыть её было
 * нельзя ничем: ни нажатием, ни правой кнопкой (в десктопе нет меню браузера).
 * Снимок экрана с текстом ошибки в таком виде нечитаем, и оператору
 * приходилось идти смотреть его в само Авито.
 *
 * ЧТО ЗДЕСЬ ЕСТЬ И ПОЧЕМУ ИМЕННО ЭТО:
 *
 *   • картинка целиком (`contain`), а не обрезанная: у фотографии экрана
 *     важен ровно край, где текст;
 *   • стрелки по снимкам ЭТОГО ЖЕ диалога: клиент присылает их пачкой
 *     («вот экран, вот шильдик, вот разъём»), и закрывать-открывать каждую
 *     значит терять место;
 *   • клавиатура: ← → между снимками, Esc — закрыть. Оператор работает
 *     быстро и мышью пользуется меньше, чем кажется;
 *   • честная ошибка вместо битого значка: ссылки Авито живут не вечно, и
 *     «не открылась» — это не «клиент прислал пустоту»;
 *   • «Скачать» — потому что диагноз иногда показывают мастеру, а мастер
 *     сидит не за этим экраном.
 *
 * ──────────────────────────────── ПРИБЛИЖЕНИЕ (просьба владельца 05.09) ──
 *
 * «Сделай так, чтобы фото можно было увеличивать, приближать и отдалять».
 * Вписанный в экран снимок закрывает половину задачи: шильдик с моделью и
 * серийным номером клиент снимает с полуметра, и на вписанном в 1200 пикселей
 * ширины снимке эти буквы занимают 8–10 пикселей высоты — то есть не читаются
 * вовсе. Без приближения оператор уходит смотреть их в само Авито, то есть
 * выходит из системы, ради которой её и ставили.
 *
 * ⚠ КОЛЕСО БЕЗ Ctrl — ТОЖЕ ПРИБЛИЖЕНИЕ, И ЭТО НЕ ЛЕНЬ. Под просмотрщиком
 * прокручивать нечего: он закрывает экран целиком, лента переписки под ним
 * недосягаема. Потребуй мы Ctrl — первое же движение колеса не сделало бы
 * НИЧЕГО, и человек заключил бы, что приближения здесь нет. Ctrl+колесо ловим
 * тем же обработчиком: щипок на трекпаде macOS и Windows приезжает в браузер
 * именно так, и не перехвати мы его — увеличился бы весь интерфейс, а снимок
 * остался бы прежним.
 *
 * ⚠ ПОТОЛОК 8×, А НЕ «СКОЛЬКО ПОПРОСЯТ». Телефон снимает 3000–4000 пикселей
 * по ширине, экран оператора показывает около 1200 — вписанный снимок это уже
 * примерно 0,3 своего пикселя. Значит 3× возвращает снимку его собственные
 * пиксели один к одному, а 8× даёт двух-с-половиной-кратное увеличение сверх
 * оригинала: дальше растёт не подробность, а размер квадратиков.
 * Двойное нажатие ведёт ровно в 3× — в тот самый «один к одному», где мелкий
 * текст уже читается, а окружение ещё видно.
 *
 * ⚠ ПРИБЛИЖАЕМ К ТОЧКЕ, А НЕ К ЦЕНТРУ ЭКРАНА. Человек наводит курсор на
 * шильдик и крутит колесо; просмотрщик, который приближает к центру, уводит
 * шильдик за край с первого же щелчка, и дальше человек догоняет его
 * перетаскиванием. Вся геометрия сведена к одной функции `удержатьТочку`:
 * она держит на месте точку под курсором (колесо, двойное нажатие) или между
 * пальцами (щипок), а перетаскивание — её же частный случай при том же
 * масштабе.
 *
 * ⚠ СТРЕЛКИ ДЕЛЯТСЯ ПО МАСШТАБУ, И ЭТО ЕДИНСТВЕННОЕ ЧЕСТНОЕ ДЕЛЕНИЕ.
 * ← → уже водят по снимкам диалога, и отнимать их нельзя. Но у вписанного
 * снимка сдвигать нечего — он и так целиком на экране, — а у приближённого,
 * наоборот, некуда девать стрелки. Поэтому: масштаб 100 % — стрелки ходят по
 * снимкам (как ходили), больше 100 % — двигают снимок. Переход между снимками
 * при этом не теряется: рядом есть кнопки ‹ › и клавиша 0, возвращающая
 * исходный вид.
 */
export interface ViewerImage {
  url: string;
  name: string;
}

export function ImageViewer({
  images,
  index,
  onClose,
  onIndex,
}: {
  images: ViewerImage[];
  /** Какой снимок открыт. `null` — просмотрщик закрыт. */
  index: number | null;
  onClose: () => void;
  onIndex: (next: number) => void;
}) {
  const открыт = index !== null && index >= 0 && index < images.length;
  const [сломалась, setСломалась] = useState(false);
  const [вид, setВид] = useState<Вид & { плавно: boolean }>({
    ...ВИД_ИСХОДНЫЙ,
    плавно: false,
  });

  /*
   * ⚠ ТОТ ЖЕ ВИД ЕЩЁ И РЕФОМ. Колесо и `pointermove` приходят десятками в
   * секунду, и каждый следующий обязан считаться от УЖЕ применённого вида.
   * Состояние React к этому моменту может быть на кадр позади (эффекты
   * отложены), и приближение накапливалось бы с ошибкой — заметно как рывки
   * при быстром вращении колеса. Реф пишется синхронно рядом с `setВид`.
   */
  const видRef = useRef<Вид>(ВИД_ИСХОДНЫЙ);
  const корень = useRef<HTMLDivElement | null>(null);
  const картинка = useRef<HTMLImageElement | null>(null);

  const назад = useCallback(() => {
    if (index === null || images.length < 2) return;
    onIndex((index - 1 + images.length) % images.length);
  }, [index, images.length, onIndex]);

  const вперёд = useCallback(() => {
    if (index === null || images.length < 2) return;
    onIndex((index + 1) % images.length);
  }, [index, images.length, onIndex]);

  /*
   * Где лежит вписанный снимок. Мерим `offsetWidth`/`offsetLeft`, а НЕ
   * `getBoundingClientRect`: прямоугольник учитывает наш же `transform`, а во
   * время плавного перехода — его промежуточное значение. Считая центр по
   * нему, мы получали бы «плывущую» точку приближения ровно тогда, когда
   * человек крутит колесо, не дождавшись конца анимации.
   */
  const раскладка = useCallback(() => {
    const el = картинка.current;
    if (!el) return null;
    const ширина = el.offsetWidth;
    const высота = el.offsetHeight;
    if (!ширина || !высота) return null;
    return {
      центрX: el.offsetLeft + ширина / 2,
      центрY: el.offsetTop + высота / 2,
      ширина,
      высота,
    };
  }, []);

  const применить = useCallback(
    (следующий: Вид, плавно: boolean) => {
      const р = раскладка();
      const итог = р
        ? {
            масштаб: следующий.масштаб,
            x: зажатьСдвиг(
              следующий.x,
              р.центрX,
              (р.ширина * следующий.масштаб) / 2,
              window.innerWidth,
            ),
            y: зажатьСдвиг(
              следующий.y,
              р.центрY,
              (р.высота * следующий.масштаб) / 2,
              window.innerHeight,
            ),
          }
        : следующий;
      видRef.current = итог;
      setВид({ ...итог, плавно });
    },
    [раскладка],
  );

  /** Точка экрана — в координаты относительно центра вписанного снимка. */
  const отЦентра = useCallback(
    (экранX: number, экранY: number): Точка => {
      const р = раскладка();
      return р ? { x: экранX - р.центрX, y: экранY - р.центрY } : { x: 0, y: 0 };
    },
    [раскладка],
  );

  const кТочке = useCallback(
    (желаемый: number, экранX: number, экранY: number, плавно: boolean) => {
      const точка = отЦентра(экранX, экранY);
      применить(удержатьТочку(видRef.current, желаемый, точка, точка), плавно);
    },
    [отЦентра, применить],
  );

  /** Кнопки и клавиши целятся в середину экрана: курсора у них нет. */
  const кЦентру = useCallback(
    (желаемый: number) =>
      кТочке(желаемый, window.innerWidth / 2, window.innerHeight / 2, true),
    [кТочке],
  );

  const сброс = useCallback((плавно: boolean) => {
    видRef.current = ВИД_ИСХОДНЫЙ;
    setВид({ ...ВИД_ИСХОДНЫЙ, плавно });
  }, []);

  const сдвинуть = useCallback(
    (dx: number, dy: number) => {
      const в = видRef.current;
      применить({ масштаб: в.масштаб, x: в.x + dx, y: в.y + dy }, true);
    },
    [применить],
  );

  const переключитьПриближение = useCallback(
    (экранX: number, экранY: number) => {
      if (видRef.current.масштаб > МАСШТАБ_ВПИСАН) сброс(true);
      else кТочке(МАСШТАБ_ДВОЙНОГО, экранX, экранY, true);
    },
    [кТочке, сброс],
  );

  /*
   * Новый снимок — новая попытка и ИСХОДНЫЙ ВИД. Без сброса следующий снимок
   * открывался бы приближённым в то место, где случайно стоял предыдущий: у
   * снимков разные пропорции, и «то же место» на другом снимке — это, как
   * правило, пустой угол.
   */
  useEffect(() => {
    setСломалась(false);
    видRef.current = ВИД_ИСХОДНЫЙ;
    setВид({ ...ВИД_ИСХОДНЫЙ, плавно: false });
  }, [index]);

  useEffect(() => {
    if (!открыт) return;
    const наКлавишу = (e: KeyboardEvent) => {
      // Ctrl+= / Cmd+0 — это увеличение САМОГО БРАУЗЕРА, и отнимать его нельзя:
      // им пользуются те, кому мелок весь интерфейс, а не один снимок.
      const сМодификатором = e.ctrlKey || e.metaKey || e.altKey;
      const приближён = видRef.current.масштаб > МАСШТАБ_ВПИСАН;

      if (e.key === "Escape") {
        // Esc закрывает всегда, даже из приближения: «выйти» — самая частая
        // нужда, а из увеличения выводит 0 и кнопка с процентами.
        e.preventDefault();
        onClose();
      } else if (!сМодификатором && (e.key === "+" || e.key === "=")) {
        e.preventDefault();
        кЦентру(видRef.current.масштаб * ШАГ_КНОПКИ);
      } else if (!сМодификатором && (e.key === "-" || e.key === "_")) {
        e.preventDefault();
        кЦентру(видRef.current.масштаб / ШАГ_КНОПКИ);
      } else if (!сМодификатором && e.key === "0") {
        e.preventDefault();
        сброс(true);
      } else if (e.key === "ArrowLeft") {
        e.preventDefault();
        // Стрелка ведёт ВЗГЛЯД, а не снимок: «влево» показывает то, что левее,
        // — как прокрутка. Снимок при этом едет вправо.
        if (приближён) сдвинуть(ШАГ_СТРЕЛКИ, 0);
        else назад();
      } else if (e.key === "ArrowRight") {
        e.preventDefault();
        if (приближён) сдвинуть(-ШАГ_СТРЕЛКИ, 0);
        else вперёд();
      } else if (приближён && (e.key === "ArrowUp" || e.key === "ArrowDown")) {
        // ↑↓ у вписанного снимка не перехватываем: они принадлежат ленте.
        e.preventDefault();
        сдвинуть(0, e.key === "ArrowUp" ? ШАГ_СТРЕЛКИ : -ШАГ_СТРЕЛКИ);
      }
    };
    /*
     * Слушаем в фазе ЗАХВАТА. Лента и композер держат свои сочетания на
     * `window` (Esc закрывает карточку клиента, стрелки ходят по списку
     * диалогов), и без захвата одно нажатие делало бы два дела сразу.
     */
    window.addEventListener("keydown", наКлавишу, true);
    return () => window.removeEventListener("keydown", наКлавишу, true);
  }, [открыт, onClose, назад, вперёд, кЦентру, сброс, сдвинуть]);

  /*
   * ⚠ КОЛЕСО ВЕШАЕТСЯ ВРУЧНУЮ, А НЕ ЧЕРЕЗ `onWheel`. React вешает `wheel` на
   * корень документа ПАССИВНЫМ слушателем, а пассивному `preventDefault`
   * запрещён: браузер его игнорирует и пишет предупреждение в консоль. То есть
   * через `onWheel` мы бы приближали снимок И одновременно давали браузеру
   * увеличить весь интерфейс на Ctrl+колесо.
   */
  useEffect(() => {
    const el = корень.current;
    if (!открыт || сломалась || !el) return;
    const наКолесо = (e: WheelEvent) => {
      e.preventDefault();
      /*
       * `deltaMode` бывает не только в пикселях: Firefox шлёт строки (16px за
       * строку — средняя высота строки интерфейса), страничный режим — экран.
       * Без приведения одно и то же движение колеса давало бы в Firefox
       * приближение в сотни раз слабее.
       */
      const пиксели =
        e.deltaMode === 1
          ? e.deltaY * 16
          : e.deltaMode === 2
            ? e.deltaY * window.innerHeight
            : e.deltaY;
      // Показательная шкала: приближение ощущается одинаковым и на 1×, и на 6×.
      // Потолок множителя — от «инерционных» трекпадов, шлющих delta в тысячах.
      const множитель = зажать(Math.exp(-пиксели / 400), 0.2, 5);
      кТочке(видRef.current.масштаб * множитель, e.clientX, e.clientY, false);
    };
    el.addEventListener("wheel", наКолесо, { passive: false });
    return () => el.removeEventListener("wheel", наКолесо);
  }, [открыт, сломалась, кТочке]);

  /*
   * Окно изменило размер — вписанный снимок стал другим, и прежний сдвиг может
   * открыть под ним пустоту. Пересчитываем границы, ничего не двигая по своей
   * воле.
   */
  useEffect(() => {
    if (!открыт) return;
    const наРазмер = () => применить(видRef.current, false);
    window.addEventListener("resize", наРазмер);
    return () => window.removeEventListener("resize", наРазмер);
  }, [открыт, применить]);

  /*
   * Пальцы и мышь. Держим ВСЕ прижатые указатели: по одному — перетаскивание,
   * по двум — щипок.
   */
  const указатели = useRef(new Map<number, Точка>());
  const жест = useRef<{ середина: Точка; расстояние: number; путь: number } | null>(null);
  const прошлоеКасание = useRef<{ время: number; x: number; y: number } | null>(null);
  const типУказателя = useRef<string>("mouse");

  const свод = () => {
    const точки = [...указатели.current.values()];
    if (точки.length === 0) return null;
    if (точки.length === 1) return { середина: точки[0], расстояние: 0 };
    const [a, b] = точки;
    return {
      середина: { x: (a.x + b.x) / 2, y: (a.y + b.y) / 2 },
      расстояние: Math.hypot(a.x - b.x, a.y - b.y),
    };
  };

  const наУказательВниз = (e: СобытиеУказателя<HTMLImageElement>) => {
    if (e.pointerType === "mouse" && e.button !== 0) return;
    типУказателя.current = e.pointerType || "mouse";
    /*
     * Захват указателя: `pointermove` и `pointerup` продолжают приходить сюда,
     * даже когда палец ушёл за край снимка. Проверка на наличие метода — ради
     * jsdom и старых WebKit; там перетаскивание просто закончится на краю.
     */
    if (typeof e.currentTarget.setPointerCapture === "function") {
      e.currentTarget.setPointerCapture(e.pointerId);
    }
    указатели.current.set(e.pointerId, { x: e.clientX, y: e.clientY });
    const с = свод();
    if (с) жест.current = { середина: с.середина, расстояние: с.расстояние, путь: 0 };
  };

  const наУказательДвижение = (e: СобытиеУказателя<HTMLImageElement>) => {
    if (!указатели.current.has(e.pointerId)) return;
    указатели.current.set(e.pointerId, { x: e.clientX, y: e.clientY });
    const с = свод();
    const ж = жест.current;
    if (!с || !ж) return;
    /*
     * ⚠ ЗДЕСЬ БЫЛ ДОСРОЧНЫЙ ВЫХОД «вписанный снимок тянуть некуда», и он ВРЕДИЛ.
     * Двигать вписанный снимок и так нечем: границы зажимают сдвиг в ноль, а до
     * загрузки размеров обе точки жеста сходятся в центр. Зато выход стоял ДО
     * подсчёта пути — и палец, проехавший 200px по неприближённому снимку,
     * считался стоявшим на месте, то есть КАСАНИЕМ. Следующее касание рядом
     * складывалось с ним в двойное, и снимок приближался сам собой.
     */
    ж.путь += Math.hypot(с.середина.x - ж.середина.x, с.середина.y - ж.середина.y);
    const масштаб =
      с.расстояние > 0 && ж.расстояние > 0
        ? видRef.current.масштаб * (с.расстояние / ж.расстояние)
        : видRef.current.масштаб;
    /*
     * ⚠ ШАГ СЧИТАЕТСЯ ОТ ПРЕДЫДУЩЕГО СОБЫТИЯ, А НЕ ОТ НАЧАЛА ЖЕСТА. Разница
     * видна на границе: у отсчёта от начала жеста уезд пальца на 300px за край
     * создаёт мёртвую зону в те же 300px — палец идёт обратно, а снимок стоит.
     * Это и есть «залипание». От предыдущего события снимок трогается сразу,
     * потому что зажатое значение — уже граница, и следующий шаг уводит от неё.
     * Плавность здесь запрещена: перетаскивание обязано идти за пальцем.
     */
    применить(
      удержатьТочку(
        видRef.current,
        масштаб,
        отЦентра(ж.середина.x, ж.середина.y),
        отЦентра(с.середина.x, с.середина.y),
      ),
      false,
    );
    ж.середина = с.середина;
    ж.расстояние = с.расстояние;
  };

  const наУказательВверх = (e: СобытиеУказателя<HTMLImageElement>) => {
    const ж = жест.current;
    указатели.current.delete(e.pointerId);
    const остаток = свод();
    if (остаток && ж) {
      /*
       * Один палец из двух отпущен. Перезадаём опору по оставшемуся: иначе
       * следующий же `pointermove` посчитает шаг от СЕРЕДИНЫ между пальцами до
       * одного пальца — снимок прыгнул бы на пол-расстояния между ними.
       */
      ж.середина = остаток.середина;
      ж.расстояние = остаток.расстояние;
      return;
    }
    жест.current = null;
    if (!ж) return;

    /*
     * Двойное КАСАНИЕ считаем сами: браузеры синтезируют `dblclick` из тапов не
     * везде и с задержкой в 300мс. Мышиному двойному нажатию это не мешает —
     * его ловит `onDoubleClick`, а сюда мы пускаем только палец.
     */
    if (e.pointerType !== "touch" || ж.путь > ПОРОГ_ДВИЖЕНИЯ) return;
    const п = прошлоеКасание.current;
    const сейчас = Date.now();
    if (
      п &&
      сейчас - п.время < ДВОЙНОЕ_МС &&
      Math.hypot(e.clientX - п.x, e.clientY - п.y) < ДВОЙНОЕ_ПИКСЕЛЕЙ
    ) {
      прошлоеКасание.current = null;
      переключитьПриближение(e.clientX, e.clientY);
    } else {
      прошлоеКасание.current = { время: сейчас, x: e.clientX, y: e.clientY };
    }
  };

  if (!открыт || index === null) return null;
  const снимок = images[index];
  const проценты = Math.round(вид.масштаб * 100);
  const приближён = вид.масштаб > МАСШТАБ_ВПИСАН;

  return (
    <div
      className="imgview"
      ref={корень}
      role="dialog"
      aria-modal="true"
      aria-label={`Просмотр: ${снимок.name}`}
      // Нажатие по тёмному фону закрывает; по самой картинке — нет, иначе
      // промах при попытке разглядеть деталь закрывал бы просмотр.
      onMouseDown={(e) => {
        if (e.target === e.currentTarget) onClose();
      }}
    >
      <header className="imgview__bar">
        <span className="imgview__name" title={снимок.name}>
          {снимок.name}
        </span>
        {images.length > 1 && (
          <span className="imgview__count">
            {index + 1} из {images.length}
          </span>
        )}

        {/*
          ⚠ ВИДИМЫЙ ВЫХОД ИЗ УВЕЛИЧЕНИЯ И ВИДИМЫЙ ВХОД В НЕГО. Про колесо и
          двойное нажатие знают не все, и приближённый снимок без единой
          кнопки — ловушка: человек не понимает, как вернуть прежний вид, и
          закрывает просмотр целиком. Кнопки заодно единственное, что вообще
          сообщает о существовании приближения.
          100 % здесь — «вписан в экран», а не «один к одному по пикселям».
        */}
        {!сломалась && (
          <div className="imgview__zoom">
            <button
              type="button"
              className="imgview__act"
              onClick={() => кЦентру(видRef.current.масштаб / ШАГ_КНОПКИ)}
              // `aria-disabled`, а НЕ `disabled`: настоящий `disabled` отнимает
              // у кнопки фокус ровно в момент нажатия, и фокус уезжает в body —
              // человек с клавиатуры теряет место, дойдя до края шкалы.
              aria-disabled={приближён ? undefined : true}
              aria-label="Отдалить"
              title="Отдалить (−)"
            >
              <IconMinus size={18} />
            </button>
            <button
              type="button"
              className="imgview__act imgview__scale"
              onClick={() => сброс(true)}
              aria-disabled={приближён ? undefined : true}
              title="Вернуть исходный размер (0)"
            >
              <span aria-hidden="true">{проценты} %</span>
              {/* Значение читалке — словами и вслух при каждом изменении. */}
              <span className="lc-visually-hidden" aria-live="polite">
                Масштаб {проценты} процентов, вернуть исходный размер
              </span>
            </button>
            <button
              type="button"
              className="imgview__act"
              onClick={() => кЦентру(видRef.current.масштаб * ШАГ_КНОПКИ)}
              aria-disabled={вид.масштаб >= МАСШТАБ_ПОТОЛОК ? true : undefined}
              aria-label="Приблизить"
              title="Приблизить (+)"
            >
              <IconPlus size={18} />
            </button>
          </div>
        )}

        <ExternalLink
          className="imgview__act"
          url={withApiRoot(снимок.url)}
          download={снимок.name}
          aria-label="Скачать снимок"
          title="Скачать"
        >
          <IconDownload size={18} />
        </ExternalLink>
        <button
          type="button"
          className="imgview__act"
          onClick={onClose}
          aria-label="Закрыть просмотр"
          title="Закрыть (Esc)"
          autoFocus
        >
          <IconX size={18} />
        </button>
      </header>

      {images.length > 1 && (
        <button
          type="button"
          className="imgview__nav imgview__nav--prev"
          onClick={назад}
          aria-label="Предыдущий снимок"
          title="Предыдущий (←)"
        >
          <IconChevronLeft size={28} />
        </button>
      )}

      {сломалась ? (
        <div className="imgview__broken" role="status">
          <p>Снимок не открылся</p>
          {/*
            Причину называем, потому что она РАЗНАЯ и лечится по-разному:
            просроченная ссылка Авито — это не «клиент прислал пустоту», и идти
            надо в Авито, а не переспрашивать клиента.
          */}
          <p className="imgview__broken-why">
            Ссылки Авито живут ограниченное время. Откройте диалог в Авито — там
            снимок на месте.
          </p>
        </div>
      ) : (
        <img
          ref={картинка}
          className={`imgview__img${приближён ? " imgview__img--zoomed" : ""}`}
          src={withApiRoot(снимок.url)}
          alt={снимок.name}
          style={{
            transform: `translate(${вид.x}px, ${вид.y}px) scale(${вид.масштаб})`,
            // Перетаскивание и щипок обязаны идти за пальцем БЕЗ задержки:
            // плавность здесь читается как подтормаживание, а не как красота.
            transition: вид.плавно ? undefined : "none",
          }}
          // Иначе мышь начинает СВОЁ перетаскивание картинки (drag-n-drop
          // браузера), и приближённый снимок перестаёт двигаться на полпути.
          draggable={false}
          onPointerDown={наУказательВниз}
          onPointerMove={наУказательДвижение}
          onPointerUp={наУказательВверх}
          onPointerCancel={наУказательВверх}
          onDoubleClick={(e) => {
            // Палец сюда не пускаем: его двойное касание уже сосчитано выше, и
            // синтезированный браузером `dblclick` вернул бы вид обратно.
            if (типУказателя.current === "touch") return;
            переключитьПриближение(e.clientX, e.clientY);
          }}
          // Размер вписанного снимка известен только после загрузки — до неё
          // границы сдвига считать не по чему.
          onLoad={() => применить(видRef.current, false)}
          onError={() => setСломалась(true)}
        />
      )}

      {images.length > 1 && (
        <button
          type="button"
          className="imgview__nav imgview__nav--next"
          onClick={вперёд}
          aria-label="Следующий снимок"
          title="Следующий (→)"
        >
          <IconChevronRight size={28} />
        </button>
      )}
    </div>
  );
}
