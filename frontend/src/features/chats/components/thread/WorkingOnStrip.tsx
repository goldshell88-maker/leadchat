import { Text } from "@mantine/core";
import type { ConversationDetailDto } from "@/shared/api/types";
import { подписьСотрудника } from "@/shared/lib/подписьСотрудника";
import { useSessionStore } from "@/shared/stores/sessionStore";
import "./working-on.css";

/**
 * Кто ведёт диалог и кто в нём ещё есть — одной строкой под шапкой.
 *
 * ⚠ ПРОСЬБА ВЛАДЕЛЬЦА 03.09, ДОСЛОВНО: «сделай так, чтобы можно было спокойно
 * заходить в чужой диалог, который в работе у другого человека, и он появлялся
 * так же у тебя в „Мои". Сделай только индикацию, что диалог в работе у …
 * Чтобы оба человека понимали, что у кого в работе».
 *
 * ⚠ ПОЧЕМУ ПОД ШАПКОЙ, А НЕ В ПОДВАЛЕ. До сегодняшнего дня единственная
 * надпись «у кого диалог в работе» жила в заслоне над полем ввода — то есть
 * показывалась только тому, кто в этот заслон упёрся, и только в двух ветках
 * подвала из четырёх: в очереди и в режиме заметок её не было. Имя
 * ответственного из шапки убрали 12 августа, а правая карточка на экранах уже
 * 1360 пикселей закрыта по умолчанию. Сняв заслон и не поставив эту строку, мы
 * получили бы экран, на котором ответа «чей это диалог» нет вообще.
 *
 * ⚠ ОДНА СТРОКА НА ОБЕ СТОРОНЫ, А НЕ ДВЕ РАЗНЫЕ. Хозяин и гость смотрят на
 * один и тот же диалог, и понимать они должны одно и то же. Меняется только
 * подлежащее: «в работе у Анны» против «в работе у вас».
 */
export function WorkingOnStrip({ conversation }: { conversation?: ConversationDetailDto }) {
  const myId = useSessionStore((s) => s.user?.id);
  const хозяин = conversation?.assignee ?? null;
  const участники = conversation?.participants ?? [];

  // Закрытый диалог ничей: его ответственный — память о том, кто вёл разговор,
  // а не указание, к кому идти. Правило то же, что у вкладки «Мои».
  if (!хозяин || conversation?.status === "closed") return null;

  const свой = хозяин.id === myId;
  // Отдел в скобках у каждого имени (04.09): строка отвечает на вопрос «чей
  // это диалог», а у заказчика похожие имена в разных отделах — без отдела
  // ответ неполный. Подпись одна на все экраны, чтобы «Иванов (ОКК)» здесь и
  // «Иванов» в списке не прочлись как двое разных.
  const рядом = участники.filter((p) => p.id !== myId).map((p) => подписьСотрудника(p));
  const яЗдесь = участники.some((p) => p.id === myId);

  // Свой диалог, и никого рядом — говорить не о чем: человек и так знает, чей
  // это разговор. Строка появляется ровно тогда, когда есть новость.
  if (свой && рядом.length === 0) return null;

  const кто = свой ? "у вас" : `у ${подписьСотрудника(хозяин)}`;
  const гости =
    рядом.length === 0
      ? яЗдесь && !свой
        ? "здесь же вы"
        : null
      : рядом.length <= 2
        ? `здесь же ${[...(яЗдесь && !свой ? ["вы"] : []), ...рядом].join(", ")}`
        : `здесь же ${рядом[0]} и ещё ${рядом.length - 1}`;

  return (
    <div className="working-on" role="status" data-mine={свой ? "true" : undefined}>
      <Text component="span" fz="xs" c="var(--lc-text-2)">
        В работе {кто}
        {гости ? ` · ${гости}` : ""}
      </Text>
      {/*
        ⚠ КНОПОК ЗДЕСЬ НЕТ, И ЭТО ДВА ОТДЕЛЬНЫХ РЕШЕНИЯ ВЛАДЕЛЬЦА (04.09).

        «Войти в диалог» переехала вниз, в подвал, к полосе вида «Принять
        диалог»: там она стоит НА МЕСТЕ ПОЛЯ ВВОДА, то есть ровно там, куда
        человек тянется, когда хочет ответить, — и заодно объясняет, почему
        поле закрыто.

        «Выйти» снята вовсе: «мне не нужна лишняя кнопка „Выйти", для себя я
        нажму Ctrl+D и выйду — у меня чат пропадёт, а у другого человека он
        останется». Ctrl+D у гостя и означает выход (см. ChatThreadPane).

        Строка осталась тем, чем и была: ответом на вопрос «чей это диалог».
      */}
    </div>
  );
}
