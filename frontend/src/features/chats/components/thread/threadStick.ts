/** На сколько пикселей от низа лента ещё считается «прижатой». */
export const ПОРОГ_НИЗА = 120;

/** Меньшее движение — дрожь, а не намерение человека. */
const ЛЮФТ = 4;

/**
 * Держаться ли низа ленты после этого события прокрутки.
 *
 * ⚠ РАЗБОР ЖАЛОБЫ 30.08: «диалог с большим числом сообщений открывается не в
 * самом конце, а где-то чуть ниже середины».
 *
 * Прежнее правило было в одну строку: «прижаты, если до низа меньше порога».
 * Оно не различало ДВЕ РАЗНЫЕ ПРИЧИНЫ того, что низ отдалился:
 *
 *  • человек пролистал вверх — читает старое, дёргать его вниз нельзя;
 *  • содержимое выросло ВНИЗ, а прокрутка осталась на месте.
 *
 * Второе случается на каждом открытии длинной переписки: строки
 * виртуализированы с оценкой в 64 пикселя, реальные высоты приезжают пачками
 * по мере измерения, и на полусотне строк набегают сотни пикселей. Защёлка
 * гасла сама собой — а вместе с ней замолкали ОБА заслона: цикл прижатия
 * выходил без перепланировки таймера, то есть навсегда, и наблюдатель размера
 * тоже переставал дожимать. Лента оставалась там, куда успела встать, — тем
 * ниже середины, чем длиннее переписка.
 *
 * Теперь причина различается по направлению: вниз ушло содержимое — держимся,
 * вверх ушёл человек — отпускаем. Возврат к низу возвращает защёлку сам.
 */
export function следующаяЗащёлка(
  было: boolean,
  прошлыйTop: number,
  el: { scrollTop: number; scrollHeight: number; clientHeight: number },
): boolean {
  if (el.scrollHeight - el.scrollTop - el.clientHeight < ПОРОГ_НИЗА) return true;
  const ушёлВверх = el.scrollTop < прошлыйTop - ЛЮФТ;
  return ушёлВверх ? false : было;
}
