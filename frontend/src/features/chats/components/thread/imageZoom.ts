/**
 * Геометрия приближения снимка — БЕЗ React и без DOM.
 *
 * ⚠ ПОЧЕМУ ОТДЕЛЬНЫМ ФАЙЛОМ. Здесь единственное место во всём просмотрщике,
 * где можно ошибиться молча: приближение к центру экрана вместо точки под
 * курсором выглядит «почти так же», и заметно оно только на снимке, где
 * человек целился в шильдик. Отрисовкой это не проверить — в jsdom нет
 * раскладки, все прямоугольники нулевые, — а числами проверить можно, и
 * сторож `ImageViewerZoom0509.test.tsx` проверяет именно их.
 *
 * Меняется этот файл по своей причине (математика жеста), а не вместе с
 * разметкой просмотрщика.
 */

/** Точка в координатах экрана либо относительно центра снимка. */
export interface Точка {
  x: number;
  y: number;
}

/** Масштаб и сдвиг снимка. `масштаб: 1` — снимок вписан в экран. */
export interface Вид {
  масштаб: number;
  x: number;
  y: number;
}

export const МАСШТАБ_ВПИСАН = 1;
export const МАСШТАБ_ПОТОЛОК = 8;
/** Куда ведёт двойное нажатие: примерно «один к одному» по пикселям снимка. */
export const МАСШТАБ_ДВОЙНОГО = 3;
export const ВИД_ИСХОДНЫЙ: Вид = { масштаб: МАСШТАБ_ВПИСАН, x: 0, y: 0 };

/** Шаг кнопок «+»/«−» и клавиш: 1,5 — четыре нажатия от края до края (1 → 5,1). */
export const ШАГ_КНОПКИ = 1.5;
/** Шаг стрелок при сдвиге, пикселей экрана. */
export const ШАГ_СТРЕЛКИ = 80;
/** Двойное КАСАНИЕ: два тапа не дальше этого друг от друга и не позже. */
export const ДВОЙНОЕ_МС = 320;
export const ДВОЙНОЕ_ПИКСЕЛЕЙ = 24;
/** Ниже этого пути палец считается стоявшим на месте, а не тянувшим снимок. */
export const ПОРОГ_ДВИЖЕНИЯ = 6;

export const зажать = (значение: number, от: number, до: number) =>
  Math.min(Math.max(значение, от), до);

/**
 * Новый вид, при котором точка снимка остаётся под тем же местом экрана.
 *
 * Положение точки снимка на экране: `экран = центр + сдвиг + масштаб × точка`,
 * где `центр` — середина вписанного снимка (от масштаба не зависит, снимок
 * центрируется раскладкой). Отсюда при переходе `масштаб → следующий`:
 *
 *     сдвиг' = стала − k × (была − сдвиг),   k = следующий / масштаб
 *
 * Одна формула на все три жеста, и это не экономия строк, а защита от
 * расхождения: колесо и щипок обязаны приближать ОДИНАКОВО.
 *   • колесо и двойное нажатие — `была === стала` (точка под курсором стоит);
 *   • щипок — середина между пальцами едет вместе с пальцами;
 *   • перетаскивание — тот же масштаб (k = 1), формула вырождается в
 *     `сдвиг + (стала − была)`.
 *
 * `была`/`стала` — ОТНОСИТЕЛЬНО ЦЕНТРА вписанного снимка, а не левого верхнего
 * угла экрана.
 */
export function удержатьТочку(
  начало: Вид,
  следующийМасштаб: number,
  была: Точка,
  стала: Точка,
): Вид {
  const масштаб = зажать(следующийМасштаб, МАСШТАБ_ВПИСАН, МАСШТАБ_ПОТОЛОК);
  const k = масштаб / начало.масштаб;
  return {
    масштаб,
    x: стала.x - k * (была.x - начало.x),
    y: стала.y - k * (была.y - начало.y),
  };
}

/**
 * Сдвиг по одной оси, зажатый в границы: под снимком не должно проглядывать
 * пустоты, а сам снимок не должен уезжать за край.
 *
 * `центр` — где лежит середина вписанного снимка в координатах экрана (по
 * вертикали это НЕ середина экрана: сверху у просмотрщика поле 48px под
 * полосу с именем, снизу 16px).
 *
 * Снимок мельче окна — сдвиг ровно 0: приближать нечего, и «немного сдвинутый»
 * вписанный снимок выглядел бы поломкой раскладки, а не решением человека.
 */
export function зажатьСдвиг(
  сдвиг: number,
  центр: number,
  половинаСнимка: number,
  окно: number,
): number {
  const наименьший = окно - центр - половинаСнимка;
  const наибольший = половинаСнимка - центр;
  if (наименьший > наибольший) return 0;
  return зажать(сдвиг, наименьший, наибольший);
}
