/**
 * Отказы `play()`, которые НЕ поломка записи, — по имени DOMException.
 *
 * `NotAllowedError` — политика автозапуска: браузер отклоняет `play()` без
 * жеста человека; после ожидания свежей ссылки WebKit может счесть жест
 * истёкшим. Плеер остаётся на паузе с кнопкой «Слушать»: ссылка уже свежая,
 * второе нажатие играет без ожидания.
 *
 * `AbortError` — игру прервали МЫ: `pause()` до того, как запись догрузилась
 * (человек передумал слушать), или смена `src` под ждущим `play()`. Считать
 * это сбоем значило бы перезапросить ссылку и возобновить игру, которую
 * человек только что остановил.
 */
const НЕ_СБОЙ = new Set(["NotAllowedError", "AbortError"]);

function неСбой(причина: unknown): boolean {
  if (typeof причина !== "object" || причина === null) return false;
  const имя = (причина as { name?: unknown }).name;
  return typeof имя === "string" && НЕ_СБОЙ.has(имя);
}

/**
 * Элемент уже признал адрес мёртвым (не открылись даже метаданные). Сравнение
 * через `!= null`, а не `!== null`: jsdom не задаёт `error` вовсе и отдаёт
 * `undefined` — со строгим сравнением каждый плеер в тестах считался бы упавшим.
 */
function упал(el: HTMLAudioElement): boolean {
  return el.error != null;
}

/**
 * ⚠ ГОВОРИТ ТОЛЬКО ОДНА ЗАПИСЬ НА ВСЮ КОНСОЛЬ.
 *
 * Без этого включённое второе голосовое накладывается на первое: в ленте их
 * подряд бывает несколько, и человек, промахнувшийся мимо паузы, слышит два
 * голоса разом и не понимает, который он слушает. Останавливать чужой
 * проигрыватель некому — каждый знает только про себя, поэтому «кто сейчас
 * звучит» живёт здесь, рядом с самим элементом.
 *
 * Это же ограничивает и вред от самозапуска ниже: сколько бы плееров лента ни
 * отрисовала, звучать одновременно они не могут.
 */
let звучит: HTMLAudioElement | null = null;

function занять(el: HTMLAudioElement): void {
  if (звучит && звучит !== el) звучит.pause();
  звучит = el;
}

function освободить(el: HTMLAudioElement): void {
  if (звучит === el) звучит = null;
}

/**
 * «0:07». Минуты не переводятся в часы намеренно: у голосового Авито предел
 * порядка минуты, а «1:05:03» ради небывалого случая делает подпись шире
 * колонки, в которой она живёт.
 */
function времяСтрокой(секунды: number | null): string {
  if (секунды === null || !Number.isFinite(секунды) || секунды < 0) return ДЛИНА_НЕИЗВЕСТНА;
  const целых = Math.floor(секунды);
  return `${Math.floor(целых / 60)}:${String(целых % 60).padStart(2, "0")}`;
}

/** Длительность считаем известной, только если она конечная и положительная. */
function годнаяДлина(значение: number | null | undefined): number | null {
  return typeof значение === "number" && Number.isFinite(значение) && значение > 0 ? значение : null;
}

