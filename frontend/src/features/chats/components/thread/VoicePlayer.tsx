/** Адрес записи и момент, когда его получили — по нему считается свежесть. */
interface Ссылка {
  адрес: string;
  получена: number;
}

export function VoicePlayer({
  url,
  urlUpdatedAt,
  refreshUrl,
  duration,
  transcript,
  transcriptStatus,
  transcriptQueued = true,
}: {
  url: string;
  /**
   * Когда ссылку получили (мс эпохи) — `dataUpdatedAt` запроса. Без метки
   * считаем, что получили при появлении плеера: старение идёт с этого момента.
   */
  urlUpdatedAt?: number;
  /**
   * Спросить у сервера свежую ссылку. Без него плеер играет по той, что дали,
   * и на сбое сразу говорит подпись — обновить её нечем.
   */
  refreshUrl?: () => Promise<string>;
  duration?: number | null;
  /** Текст от нашего Whisper. Пусто — см. `transcriptStatus`. */
  transcript?: string | null;
  /**
   * Отсутствие значения значит «не начинали». Что при этом показать, решает
   * `transcriptQueued`: для входящего это очередь досчёта, для остального —
   * ничего.
   */
  transcriptStatus?: VoiceTranscriptStatus | null;
  /**
   * Ждать ли расшифровку, когда состояния нет. Расшифровывается только речь
   * КЛИЕНТА (воркер: «своё исходящее мы и так знаем текстом»), поэтому под
   * исходящим голосовым обещать «появится сама» нельзя — не появится.
   */
  transcriptQueued?: boolean;
}) {
  const аудио = useRef<HTMLAudioElement>(null);
  const полоса = useRef<HTMLDivElement>(null);

  const [играет, setИграет] = useState(false);
  const [позиция, setПозиция] = useState(0);
  /** Длительность из метаданных самой записи — она точнее заявленной. */
  const [измерено, setИзмерено] = useState<number | null>(null);
  const [тянут, setТянут] = useState(false);
  const [сбой, setСбой] = useState<string | null>(null);
  /** Ждём свежую ссылку: кнопка занята, второе нажатие ничего не начинает. */
  const [ждём, setЖдём] = useState(false);

  /*
   * Адрес живёт в своём состоянии, а не берётся из пропа напрямую, потому что
   * свежую ссылку плеер добывает САМ и обязан начать играть по ней в ту же
   * секунду — раньше, чем родитель перечитает кэш и передаст её пропом. Когда
   * проп всё же догоняет, адрес уже тот же, и `<audio src>` не трогается: иначе
   * повторная установка того же `src` перезапускала бы загрузку под самой
   * игрой.
   */
  const [ссылка, setСсылка] = useState<Ссылка>(() => ({
    адрес: url,
    получена: urlUpdatedAt ?? Date.now(),
  }));
  useEffect(() => {
    setСсылка((прежняя) => {
      const получена = urlUpdatedAt ?? Date.now();
      // Своя ссылка не старше той, что знает родитель, — остаёмся при своей.
      if (прежняя.адрес === url && прежняя.получена >= получена) return прежняя;
      return { адрес: url, получена };
    });
  }, [url, urlUpdatedAt]);

  /**
   * Хочет ли человек слушать прямо сейчас. Сбой `<audio>` без этого желания
   * (метаданные по мёртвой ссылке при появлении пузыря) плеер не лечит:
   * лечение — это игра, а играть без нажатия нельзя. Нажмут — перезапросим.
   */
  const хотятСлушать = useRef(false);
  /**
   * Один автоматический повтор на одно нажатие. Три состояния, а не флаг,
   * потому что об одном сбое `<audio>` сообщает дважды — событием `error` и
   * отказом обещания `play()`, — и второе сообщение обязано увидеть «повтор
   * идёт», а не «повтора не было» и не «повтор был».
   */
  const повтор = useRef<"не было" | "идёт" | "был">("не было");

  const всего = измерено ?? годнаяДлина(duration);
  const доля = всего ? Math.min(1, Math.max(0, позиция / всего)) : 0;

  /*
   * ⚠ САМА ЗАПИСЬ НЕ ИГРАЕТ (05.09), И `autoPlay` ЗАПРЕЩЁН ОТДЕЛЬНО.
   *
   * Утром 05.09 здесь стоял `play()` при появлении, и это было верно:
   * проигрыватель появлялся ТОЛЬКО после нажатия на «Голосовое сообщение», то
   * есть человек уже сказал «хочу послушать», и требовать второго нажатия
   * значило просить два действия там, где он выразил желание одним.
   *
   * С вечера 05.09 запись открывается сама, как только сообщение попало на
   * экран (просьба владельца). Основание самозапуска исчезло вместе с
   * нажатием: диалог с тремя голосовыми заговорил бы всеми тремя разом, а
   * голосовые как раз и идут сериями. В открытом кабинете это громче любой
   * ошибки вёрстки. Атрибут `autoPlay` запрещён и сам по себе: он включает
   * запись при ЛЮБОМ появлении элемента, и почему она заиграла — из кода не
   * видно.
   *
   * Довод про `NotAllowedError` из тех же дней остался и нужен теперь в
   * `играть()` (см. `НЕ_СБОЙ`): перед игрой плеер бывает ждёт свежую ссылку,
   * и отказ политики автозапуска после ожидания — не поломка, а пауза с
   * кнопкой «Слушать».
   *
   * Остановка при размонтировании обязательна. Оторванный от документа
   * `<audio>` продолжает играть, и человек слышал бы голос без единого плеера
   * на экране — остановить его было бы нечем.
   */
  useEffect(() => {
    const el = аудио.current;
    if (!el) return;
    return () => {
      el.pause();
      освободить(el);
    };
  }, []);

  function перемотать(к: number): void {
    const el = аудио.current;
    if (!el || всего === null) return;
    const цель = Math.min(всего, Math.max(0, к));
    el.currentTime = цель;
    setПозиция(цель);
  }

  /**
   * Доля полосы под указателем. `null` — когда мерить нечего: у скрытого
   * элемента (свёрнутая вкладка, `display: none`) ширина ноль, и деление на
   * неё дало бы `Infinity`, то есть перемотку в конец от любого нажатия.
   */
  function доляПодУказателем(clientX: number): number | null {
    const el = полоса.current;
    if (!el) return null;
    const рамка = el.getBoundingClientRect();
    if (рамка.width <= 0) return null;
    return Math.min(1, Math.max(0, (clientX - рамка.left) / рамка.width));
  }

  /**
   * Спросить свежую ссылку и поставить её в `<audio>` ДО возврата.
   *
   * ⚠ `flushSync` ЗДЕСЬ НЕ ПРИХОТЬ. Обновление состояния из обещания React
   * откладывает, а `play()` вызывается сразу за этой функцией: без
   * принудительного кадра он ушёл бы по СТАРОМУ адресу, и вся починка
   * состояла бы из перезапроса, которым не воспользовались. Та же ссылка в
   * ответе — сеть, а не срок: тогда `load()` даёт вторую честную попытку.
   */
  async function обновитьСсылку(el: HTMLAudioElement): Promise<void> {
    if (!refreshUrl) return;
    // С элемента, а не из замыкания: к повтору после предварительного
    // перезапроса замыкание ещё помнит адрес, которого в `<audio>` давно нет.
    const была = el.getAttribute("src");
    setЖдём(true);
    try {
      const адрес = await refreshUrl();
      // Плеер могли закрыть, пока ждали ответа.
      if (аудио.current !== el) return;
      flushSync(() => setСсылка({ адрес, получена: Date.now() }));
      if (адрес === была) el.load();
    } finally {
      setЖдём(false);
    }
  }

  /**
   * Подпись и нормальная пауза. После отказа `play()` браузер не обязан
   * возвращать `paused` в `true`: без этого следующее нажатие ушло бы в
   * `pause()` вместо новой попытки, и человек жал бы дважды.
   */
  function сдаться(el: HTMLAudioElement): void {
    повтор.current = "был";
    if (!el.paused) el.pause();
    setСбой(НЕ_ОТКРЫЛАСЬ);
  }

  /** `play()`, который бросает только настоящий сбой — см. `НЕ_СБОЙ`. */
  async function играть(el: HTMLAudioElement): Promise<void> {
    try {
      await el.play();
    } catch (причина) {
      if (неСбой(причина)) return;
      throw причина;
    }
  }

  /**
   * Запись не открылась: ОДИН перезапрос ссылки и повтор — без участия
   * человека. Не помогло — подпись. Сюда приходят и `error` элемента, и отказ
   * `play()`; на одном сбое они бывают оба, и второй ничего не начинает.
   */
  async function неОткрылась(): Promise<void> {
    if (повтор.current === "идёт") return;
    const el = аудио.current;
    if (!el) return;
    if (повтор.current === "был" || !refreshUrl) {
      сдаться(el);
      return;
    }
    повтор.current = "идёт";
    try {
      await обновитьСсылку(el);
      // «Был» ставится ДО игры: отказ этой попытки обязан кончиться подписью.
      повтор.current = "был";
      if (аудио.current !== el) return;
      await играть(el);
    } catch {
      сдаться(el);
    }
  }

  async function включить(el: HTMLAudioElement): Promise<void> {
    хотятСлушать.current = true;
    повтор.current = "не было";
    if (сбой) setСбой(null);
    try {
      /*
       * Ссылка старше порога — сначала свежая, потом игра: `<audio>` по
       * мёртвой ссылке падает, и человек пишет клиенту «аудио не грузит». Уже
       * упавший элемент (`error` при загрузке метаданных) лечится тем же:
       * нажимать `play()` по адресу, который элемент сам признал мёртвым, —
       * заведомо получить отказ.
       */
      const протухла = Date.now() - ссылка.получена > ПОРОГ_СВЕЖЕСТИ_МС;
      if (refreshUrl && (протухла || упал(el))) {
        await обновитьСсылку(el);
        if (аудио.current !== el) return;
      } else if (сбой || упал(el)) {
        // Обновить нечем (или незачем): вторая честная попытка по той же
        // ссылке стоит одного `load()` — сорваться могла и сеть.
        el.load();
      }
      await играть(el);
    } catch {
      await неОткрылась();
    }
  }

  function переключить(): void {
    const el = аудио.current;
    if (!el) return;
    if (!el.paused) {
      el.pause();
      return;
    }
    // Свежая ссылка уже в пути: второе нажатие начало бы вторую игру.
    if (ждём) return;
    void включить(el);
  }

  return (
    <div className="voice-player" data-dragging={тянут ? "true" : undefined}>
      {/*
       * Субтитров у речи клиента нет и взяться им неоткуда: это запись из
       * мессенджера, а не наш материал.
       */}
      <audio
        ref={аудио}
        src={withApiRoot(ссылка.адрес)}
        preload="metadata"
        onLoadedMetadata={(e) => setИзмерено(годнаяДлина(e.currentTarget.duration))}
        onTimeUpdate={(e) => {
          // Пока тянут ползунок, время ведёт палец: иначе кадр из `timeupdate`
          // возвращал бы ползунок назад под самой рукой.
          if (!тянут) setПозиция(e.currentTarget.currentTime);
        }}
        onPlay={(e) => {
          // Смена `src` под повтором даёт `pause`, который гасит желание
          // слушать; игра, начатая следом, обязана его вернуть.
          хотятСлушать.current = true;
          setИграет(true);
          занять(e.currentTarget);
        }}
        onPause={(e) => {
          хотятСлушать.current = false;
          setИграет(false);
          освободить(e.currentTarget);
        }}
        onEnded={(e) => {
          хотятСлушать.current = false;
          setИграет(false);
          освободить(e.currentTarget);
        }}
        onError={() => {
          if (хотятСлушать.current) void неОткрылась();
        }}
      />

      <button
        type="button"
        className="voice-player__play"
        // Подпись меняется вместе с делом кнопки: «Слушать» на паузе — это
        // ЧТО ПРОИЗОЙДЁТ, а не что происходит сейчас.
        aria-label={играет ? "Пауза" : "Слушать"}
        aria-busy={ждём || undefined}
        onClick={переключить}
      >
        {играет ? <IconPause size={18} /> : <IconPlay size={18} />}
      </button>

      <div className="voice-player__meter">
        <div
          ref={полоса}
          className="voice-player__track"
          role="slider"
          tabIndex={0}
          aria-label="Перемотка записи"
          aria-valuemin={0}
          /* Длина ещё не приехала — ползунок ни к чему не ведёт, и врать
             границами нельзя: `aria-valuemax={0}` читалось бы как «запись
             нулевой длины». */
          aria-valuemax={всего === null ? undefined : Math.round(всего)}
          aria-valuenow={всего === null ? undefined : Math.round(позиция)}
          aria-valuetext={
            всего === null
              ? "Длительность записи пока неизвестна"
              : `${времяСтрокой(позиция)} из ${времяСтрокой(всего)}`
          }
          aria-disabled={всего === null ? true : undefined}
          style={{ "--voice-pos": `${доля * 100}%` } as CSSProperties}
          onPointerDown={(e) => {
            if (e.button !== 0 || всего === null) return;
            const д = доляПодУказателем(e.clientX);
            if (д === null) return;
            setТянут(true);
            /*
             * Захват указателя, а не слушатели на `window`: с захватом
             * `pointermove` и `pointerup` приходят сюда, даже когда палец
             * ушёл за пределы полосы, и снимать слушатели не надо. Проверка
             * на наличие — ради jsdom и старых WebKit, где метода нет; там
             * перетаскивание просто закончится на краю полосы.
             */
            if (typeof e.currentTarget.setPointerCapture === "function") {
              e.currentTarget.setPointerCapture(e.pointerId);
            }
            перемотать(д * всего);
          }}
          onPointerMove={(e) => {
            if (!тянут || всего === null) return;
            const д = доляПодУказателем(e.clientX);
            if (д !== null) перемотать(д * всего);
          }}
          onPointerUp={() => setТянут(false)}
          onPointerCancel={() => setТянут(false)}
          onKeyDown={(e) => {
            if (всего === null) return;
            // Считаем от ЖИВОГО времени элемента, а не от состояния: `timeupdate`
            // приходит четыре раза в секунду, и стрелка, нажатая между кадрами,
            // прыгала бы от устаревшей отметки.
            const сейчас = аудио.current?.currentTime ?? позиция;
            let цель: number | null = null;
            if (e.key === "ArrowRight" || e.key === "ArrowUp") цель = сейчас + ШАГ;
            else if (e.key === "ArrowLeft" || e.key === "ArrowDown") цель = сейчас - ШАГ;
            else if (e.key === "Home") цель = 0;
            else if (e.key === "End") цель = всего;
            if (цель === null) return;
            // Без этого стрелка прокручивает саму ленту переписки, и диалог
            // уезжает из-под руки ровно в момент перемотки.
            e.preventDefault();
            перемотать(цель);
          }}
        >
          <span className="voice-player__bar">
            <span className="voice-player__fill" />
            <span className="voice-player__knob" />
          </span>
        </div>

        <p className="voice-player__time">
          {`${времяСтрокой(позиция)} / ${времяСтрокой(всего)}`}
        </p>
      </div>

      {/* Молчащий плеер человек читает как поломку системы. Подпись стоит
          только после того, как свежая ссылка спрошена и не помогла. */}
      {сбой && (
        <p className="voice-player__error" role="status">
          {сбой}
        </p>
      )}

      <Расшифровка текст={transcript} состояние={transcriptStatus} вОчереди={transcriptQueued} />
    </div>
  );
}

/**
 * Машинная расшифровка под проигрывателем.
 *
 * ⚠ ПОДПИСЬ ОБЯЗАТЕЛЬНА И СТОИТ ПЕРЕД ТЕКСТОМ. Без неё строка читается как
 * слова клиента, и ошибка распознавания в адресе или в номере уходит дальше
 * уже как факт: диспетчер диктует её мастеру вслух. «Может ошибаться» — это не
 * оговорка юриста, а инструкция: сомневаешься — переслушай, запись рядом.
 */
function Расшифровка({
  текст,
  состояние,
  вОчереди,
}: {
  текст?: string | null;
  состояние?: VoiceTranscriptStatus | null;
  вОчереди: boolean;
}) {
  // ⚠ ПОДПИСЬ «может ошибаться» — ТОЛЬКО НАД НАСТОЯЩИМ ТЕКСТОМ. Над строкой
  // «расшифровать не удалось» предупреждать не о чем: ошибаться там нечему, а
  // лишняя строка в пузыре стоит места, которого в 280 пикселях нет.
  if (состояние !== "done") {
    const подпись = состояние ? ПОДПИСИ[состояние] : вОчереди ? В_ОЧЕРЕДИ : null;
    if (!подпись) return null;
    return (
      <p className="voice-player__transcript-note" role="status">
        {подпись}
      </p>
    );
  }

  const слова = (текст ?? "").trim();

  return (
    <div className="voice-player__transcript">
      <p className="voice-player__transcript-mark">
        <IconBot size={12} /> Машинная расшифровка — может ошибаться
      </p>
      <p className="voice-player__transcript-text" data-empty={слова ? undefined : "true"}>
        {слова || НИ_СЛОВА}
      </p>
    </div>
  );
}
