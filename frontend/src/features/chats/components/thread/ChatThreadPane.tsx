/**
 * Высота одной строки ленты, px — ИЗМЕРЕННАЯ, одна на всю панель.
 *
 * Отсюда её берут двое: виртуализатор (`estimateSize` — по ней он считает
 * суммарную высоту до того, как что-либо измерено) и скелет (по ней он рисует
 * место, которое займёт содержимое). Разбор самого числа — у виртуализатора
 * ниже: медиана строки 73,5, среднее 77,0, и важна здесь именно СУММА.
 *
 * ⚠ ДЕРЖАТЬ ИХ ПОРОЗНЬ НЕЛЬЗЯ, И ЭТО УЖЕ ЛОВИЛОСЬ. Скелет жил своим ритмом
 * 64 px (пузырь 52 + зазор 12) против 76 у содержимого: пять строк скелета
 * занимали 332 px, а те же пять строк переписки — 380. Пятьдесят пикселей
 * лента отыгрывала рывком в момент, когда приходил ответ сервера, — ровно тот
 * «диалог собирается на глазах», против которого писалась шапка по строке
 * списка.
 */
export const ВЫСОТА_СТРОКИ = 76;

/**
 * Зазор перед пузырём — тот же `--lc-space-2`, что у `.msg` сверху.
 * В JS он нужен затем, чтобы `зазор + высота пузыря` давало ровно
 * `ВЫСОТА_СТРОКИ`: два числа рядом проверяются вычитанием, а не верой.
 */
const ЗАЗОР_СТРОКИ = 8;

function ThreadSkeleton() {
  /*
   * ЧЕТЫРЕ ПУЗЫРЯ, А НЕ ПЯТЬ, И ШИРИНЫ РАЗНЫЕ (11 §2.2).
   *
   * Четыре — потому что медианный диалог ровно такой длины (тот же замер, что
   * дал 76 px на строку). Скелет обещает место под содержимое; пообещать
   * больше, чем придёт, — это тот же рывок, только в другую сторону.
   */
  const widths = [46, 58, 38, 62];
  return (
    <div className="thread-skeleton" aria-hidden="true">
      {widths.map((w, i) => (
        <span
          key={i}
          className="thread-skeleton__bubble"
          style={{
            width: `${w}%`,
            height: `${ВЫСОТА_СТРОКИ - ЗАЗОР_СТРОКИ}px`,
            alignSelf: i % 2 ? "flex-end" : "flex-start",
          }}
        />
      ))}
    </div>
  );
}

