import { localDayKey } from "@/shared/lib/formatTime";
import { bubbleText } from "@/shared/lib/messagePreview";

/**
 * ЛЕНТА — ЭТО ПЕРЕПИСКА. ЖУРНАЛ СТАТУСОВ — ЭТО ЖУРНАЛ.
 *
 * ЧТО БЫЛО (разбор живого экрана владельцем, 12 августа). В открытом диалоге
 * подряд стояли двенадцать служебных плашек — «Диалог принят: Ольга»,
 * «Диалог возвращён во «Входящие»: Ольга», «Диалог отклонён: Пётр», «Отказ
 * отменён: Пётр» и так далее, — и они вытеснили сообщения клиента за нижний
 * край экрана. Человек открывал диалог и видел не то, о чём его спрашивают, а
 * историю нажатий своих коллег. Каждая плашка по отдельности честная; беда
 * ровно в том, что их двенадцать, и в ленте они весят столько же, сколько
 * слова клиента.
 *
 * ЧТО ДЕЛАЕМ. Подряд идущие служебные записи собираются в ОДНУ строку
 * «История статусов: 12 событий», которая разворачивается по нажатию.
 * Одиночная запись остаётся как была: «Диалог передан: Борис → Ольга» —
 * это ответ на вопрос «почему диалог у меня», и прятать его за нажатие
 * значило бы менять шум на загадку.
 *
 * СЛУЖЕБНЫЕ СООБЩЕНИЯ АВИТО СЮДА НЕ ПОПАДАЮТ. «Заказ отменён», «Клиент
 * оставил отзыв» — это чужое действие, о котором оператор может не знать
 * ниоткуда больше, и читать его надо сразу, а не после нажатия. Признак —
 * `sender_type === "avito"`, тот же, по которому их отличает MessageBubble.
 */

/** Наша системная запись — журнал, а не переписка (слова Авито сюда не входят). */
export function isStatusLogMessage(msg: MessageDto): boolean {
  return msg.direction === "system" && msg.sender_type !== "avito";
}

/**
 * «Ждал N» из служебной записи вырезается ПРИ ПОКАЗЕ (пункт 4 перекройки).
 *
 * Сервер дописывает ожидание в текст записи о принятии
 * (`app/services/inbox.py`, `format_wait`): получается «Диалог принят: Ольга.
 * Ждал 7 мин». Это МЕТРИКА ДИАЛОГА, а не событие: сколько клиент ждёт, видно
 * в чипе статуса в шапке и в строке списка, причём там значение живое и
 * тикает, а здесь — застывшее число, которое к тому же спорит с шапкой
 * («Ждал 7 мин» рядом с «ждёт 40 мин» — два разных ответа на один вопрос).
 *
 * ПОЧЕМУ НЕ НА СЕРВЕРЕ. Записи, накопленные до этой правки, лежат в базе с
 * хвостом навсегда — их не перепишешь, а показывать их надо уже сегодня.
 * Серверную половину (перестать дописывать) правит владелец `app/**`.
 *
 * Хвост срезается ТОЛЬКО в конце строки и только если он похож на то, что
 * печатает `format_wait` («7 мин», «2 ч 30 мин», «3 дн 4 ч», «45 с»). Текст
 * клиента через эту функцию не проходит вовсе, но подстраховка нужна и здесь:
 * фраза «Причина: клиент ждал ответа» — законный хвост записи об отказе, и
 * резать её нельзя.
 */
const WAITED_TAIL = /\.\s*Ждал\s+\d+\s*(?:с|мин|ч|дн)(?:\s+\d+\s*(?:мин|ч))?\s*$/u;

export function stripWaited(body: string): string {
  return body.replace(WAITED_TAIL, "");
}

/**
 * Вид события — ровно настолько, насколько нужно для гашения пар.
 *
 * РАЗБОР ТЕКСТА, ПОТОМУ ЧТО БОЛЬШЕ НЕЧЕГО РАЗБИРАТЬ. В `MessageOut` нет поля
 * с видом события: служебная запись приезжает готовой строкой, собранной на
 * сервере (`convs.add_system_message`). Заводить это поле — правка `app/**`,
 * которую делает другой человек.
 *
 * ОТКАЗ БЕЗОПАСЕН. Не узнали текст — это `other`: событие остаётся в группе,
 * просто не гасится парой. То есть если сервер завтра перепишет формулировку,
 * лента не сломается и ничего не потеряет — она лишь перестанет схлопывать
 * пары, и группа честно покажет все двенадцать строк.
 */
export type ThreadEventKind = "claimed" | "released" | "declined" | "undeclined" | "other";

/*
 * ГРАНИЦА СЛОВА ЗДЕСЬ — `(?![а-яё])`, А НЕ `\b`. НЕ МЕНЯТЬ ОБРАТНО.
 *
 * `\b` в JavaScript определён через `\w`, то есть [A-Za-z0-9_]: кириллица в
 * него не входит вовсе. Из-за этого `/^Диалог принят\b/` НЕ совпадает с
 * «Диалог принят: Ольга» — между «т» и «:» обе стороны считаются несловесными,
 * границы нет. Написано было именно так, тесты гашения пар падали все три, и
 * поймано это было тестом, а не чтением: выглядит правило совершенно
 * правдоподобно.
 */
const NOT_LETTER = "(?![а-яёА-ЯЁ])";

export function eventKind(body: string): ThreadEventKind {
  const text = body.trim();
  // «Диалог принят: Иван», «Диалог взят в работу: Иван», «Диалог распределён: Иван»
  if (new RegExp(`^Диалог (?:принят|взят в работу|распределён)${NOT_LETTER}`, "u").test(text)) {
    return "claimed";
  }
  // «Диалог возвращён во «Входящие»: Иван», «Диалог возвращён в «Новые». Иван»
  if (new RegExp(`^Диалог возвращён${NOT_LETTER}`, "u").test(text)) return "released";
  if (new RegExp(`^Диалог отклонён${NOT_LETTER}`, "u").test(text)) return "declined";
  if (new RegExp(`^Отказ отменён${NOT_LETTER}`, "u").test(text)) return "undeclined";
  return "other";
}

const OPPOSITE: Record<ThreadEventKind, ThreadEventKind | null> = {
  claimed: "released",
  released: "claimed",
  declined: "undeclined",
  undeclined: "declined",
  other: null,
};

export interface ThreadEvent {
  msg: MessageDto;
  /** Текст записи без метрики «Ждал N». */
  text: string;
  kind: ThreadEventKind;
  /**
   * Погашено соседним противоположным событием: принял и через минуту вернул,
   * отказался и передумал. Такая пара ничего не изменила, и в развёрнутом
   * списке она показывается приглушённо, с пометкой «отменено».
   */
  cancelled: boolean;
}

export type ThreadRow =
  | { kind: "message"; key: string; msg: MessageDto; prev: MessageDto | null }
  | { kind: "events"; key: string; events: ThreadEvent[]; prev: MessageDto | null };

/**
 * Гашение соседних противоположных пар.
 *
 * ПОЧЕМУ ПРИЗНАК — СОСЕДСТВО, А НЕ ВРЕМЯ. Владелец описал случай как «принят →
 * возвращён через минуту», но минута здесь следствие, а не причина. Соседство
 * в журнале означает, что МЕЖДУ этими двумя событиями не случилось ничего:
 * ни сообщения клиенту, ни ответа, ни другого решения. Пара, между которой
 * оператор два часа переписывался с клиентом, соседней не окажется — между
 * ними лягут сообщения, и это будут две разные группы.
 *
 * Каждое событие гасится не более одного раза: три подряд «принят → возвращён
 * → принят» дают одну погашенную пару и одно живое принятие, а не полторы
 * пары. Идём слева направо, потому что журнал читается слева направо.
 */
function markCancelled(events: ThreadEvent[]): void {
  for (let i = 0; i + 1 < events.length; i += 1) {
    const a = events[i];
    const b = events[i + 1];
    if (a.cancelled || b.cancelled) continue;
    if (OPPOSITE[a.kind] === b.kind) {
      a.cancelled = true;
      b.cancelled = true;
    }
  }
}

/**
 * Лента → строки для отрисовки: настоящие сообщения по одному, служебные
 * записи — сериями.
 *
 * `prev` у каждой строки — ПРЕДЫДУЩЕЕ СООБЩЕНИЕ ЛЕНТЫ, а не предыдущая строка.
 * Так дата-разделитель и схлопывание подписей автора (MessageBubble) считают
 * ровно то же, что считали до группировки: свернули мы служебные записи или
 * нет, соседство сообщений в ленте от этого не меняется.
 *
 * СЕРИЯ НЕ ПЕРЕСЕКАЕТ ГРАНИЦУ СУТОК. Иначе внутрь группы попал бы
 * дата-разделитель, и лента потеряла бы день: «История статусов: 4 события»
 * молча съела бы переход через полночь.
 */
export function buildThreadRows(messages: MessageDto[]): ThreadRow[] {
  const rows: ThreadRow[] = [];
  let i = 0;
  while (i < messages.length) {
    const msg = messages[i];
    const prev = i > 0 ? messages[i - 1] : null;

    if (!isStatusLogMessage(msg)) {
      rows.push({ kind: "message", key: msg.id, msg, prev });
      i += 1;
      continue;
    }

    const day = localDayKey(msg.created_at);
    let end = i;
    while (
      end < messages.length &&
      isStatusLogMessage(messages[end]) &&
      localDayKey(messages[end].created_at) === day
    ) {
      end += 1;
    }

    // Одиночная запись остаётся обычным чипом: прятать «Диалог передан:
    // Борис → Ольга» за нажатие — менять шум на загадку.
    if (end - i === 1) {
      rows.push({ kind: "message", key: msg.id, msg, prev });
      i += 1;
      continue;
    }

    const events: ThreadEvent[] = messages.slice(i, end).map((m) => {
      // Текст берётся тем же способом, что и в пузыре (`bubbleText`): иначе о
      // записи с пустым телом группа и лента сказали бы разное.
      const text = stripWaited(bubbleText(m));
      return { msg: m, text, kind: eventKind(text), cancelled: false };
    });
    markCancelled(events);
    // Ключ — id первой записи серии: он стабилен между перерисовками, а
    // порядковый номер поехал бы при дозагрузке истории вверх.
    rows.push({ kind: "events", key: `events:${msg.id}`, events, prev });
    i = end;
  }
  return rows;
}
