import { localDayKey } from "@/shared/lib/formatTime";
import { isAvitoSystemMessage } from "@/shared/lib/messagePreview";
import type { ThreadRow } from "./threadEvents";

/**
 * ЧТО СЧИТАЕТСЯ ОДНОЙ СЕРИЕЙ В ЛЕНТЕ — ОДИН МОДУЛЬ НА ВСЕХ.
 *
 * Границу серии в ленте считают ДВА места: схлопывание подписи автора
 * (`MessageBubble`, с 6 августа) и коллаж из подряд идущих снимков
 * (`PhotoCollage`, 05.09). Правило у них обязано быть одно: разъедься эти два
 * ответа, и на экране выйдет спор с самим собой — подписи схлопнуты в одну
 * группу, а снимки разорваны на две, или наоборот. Поэтому и `kindOf`, и окно
 * серии, и сама проверка «тот же автор» живут здесь, а компоненты их зовут.
 *
 * Модуль чистый (.ts, без React) намеренно: правило проверяется без отрисовки,
 * и его можно звать из панели ленты, где никаких пузырей ещё нет.
 */

export type BubbleKind = "in" | "out" | "bot" | "note" | "system";

export function kindOf(msg: MessageDto): BubbleKind {
  if (msg.direction === "system") return "system";
  // Исторические служебные записи Авито лежат как обычные слова клиента
  // (загрузка истории поднимала их до правки 17.08). Узнаём по приставке —
  // иначе «Пользователь создал чат, но пока ничего не написал» читается как
  // реплика человека, и оператор отвечает на сообщение, которого не было.
  if (isAvitoSystemMessage(msg)) return "system";
  if (msg.direction === "note") return "note";
  if (msg.direction === "in") return "in";
  // Вопрос системы об адресе (`('out','system')`, workers/address_ask.py) —
  // раскладка пузыря как у бота: клиенту говорил не человек.
  return msg.sender_type === "bot" || msg.sender_type === "system" ? "bot" : "out";
}

/**
 * Пауза, после которой это уже другой заход в диалог, а не продолжение.
 *
 * Пять минут выбраны для подписей автора (docs/17): оператор отвечает
 * очередями по три-четыре сообщения, и повторять его имя у каждого — четыре
 * одинаковые строки, которые надо взглядом пропустить. Число переехало сюда
 * без изменения: коллаж берёт ТО ЖЕ окно, потому что вопрос у них общий.
 */
export const ОКНО_СЕРИИ_MS = 5 * 60_000;

/** Сообщения из разных суток: между ними встаёт дата-разделитель. */
export function сменаДня(prev: MessageDto | null, msg: MessageDto): boolean {
  return !prev || localDayKey(prev.created_at) !== localDayKey(msg.created_at);
}

/**
 * Продолжение серии одного автора: тот же тип пузыря, тот же человек, те же
 * сутки и пауза меньше окна. Четыре границы, каждая — отдельное решение;
 * охраняются `messageGrouping.test.tsx`.
 */
export function тотЖеАвтор(prev: MessageDto | null, msg: MessageDto): boolean {
  return (
    prev !== null &&
    !сменаДня(prev, msg) &&
    kindOf(prev) === kindOf(msg) &&
    (prev.sender?.id ?? null) === (msg.sender?.id ?? null) &&
    Date.parse(msg.created_at) - Date.parse(prev.created_at) < ОКНО_СЕРИИ_MS
  );
}

/* ─────────────────────────── коллаж из снимков (просьба владельца 05.09) ─── */

/**
 * ⚠ КОЛЛАЖ СОБИРАЕТСЯ ИЗ СОСЕДНИХ СООБЩЕНИЙ, А НЕ ИЗ ВЛОЖЕНИЙ ОДНОГО.
 *
 * ЗАМЕР ПО БОЮ ЗА 60 ДНЕЙ. Вложений в одном сообщении ВСЕГДА ровно одно:
 * 10 857 сообщений с вложением, ни одного с двумя. То есть коллаж внутри
 * сообщения не сработал бы ни разу — Авито так не присылает.
 *
 * А присылает оно фотографии ПОДРЯД ИДУЩИМИ СООБЩЕНИЯМИ: серий по 2 — 1414,
 * по 3 — 583, по 4 — 244, по 5 — 123, по 6 — 57, по 7 — 19. Каждая давала
 * столько же пузырей: семь снимков — семь пузырей по 280 px, почти два экрана
 * на один вопрос клиента «вот что у меня сломалось». Дальше по ленте оператор
 * листал вслепую.
 *
 * ЧТО ДОЛЖНО БЫЛО ПОПАСТЬ В СЕРИЮ И НЕ ПОПАЛО — РАЗБОР ПО ПУНКТАМ. У пузыря
 * есть признаки, которые нельзя молча потерять при склейке, и каждый из них
 * решён отказом от склейки, а не подгонкой:
 *
 *   • ошибка доставки — сообщение с `failed` в серию НЕ ИДЁТ: у него своя
 *     судьба (крест, «Повторить», «Удалить»), и одна кнопка на семь снимков
 *     не сказала бы, какой именно не ушёл. Заодно и `pending`: «отправляется»
 *     — тоже состояние ОДНОГО сообщения;
 *   • ответ на сообщение — с цитатой не склеиваем: цитата стоит в шапке
 *     пузыря и отвечает на вопрос «на что это ответ», а у серии такого
 *     единого ответа нет;
 *   • заметка — не склеивается вовсе: у каждой своя подпись автора и своя
 *     кнопка «Удалить», и обе именные;
 *   • время и отметка доставки — остаются у серии одни (см. `PhotoCollage`):
 *     это единственные два признака, у которых общий ответ честен.
 */
export interface Снимок {
  msg: MessageDto;
  att: AttachmentDto;
}

export type FeedRow =
  | ThreadRow
  | { kind: "shots"; key: string; shots: Снимок[]; prev: MessageDto | null };

/**
 * Годится ли сообщение в плитку коллажа — и каким вложением.
 *
 * `null` значит «остаётся обычным пузырём»; поводов ровно столько, сколько
 * перечислено в шапке, и добавлять сюда новый можно только вместе с доводом,
 * что именно теряется без отказа.
 */
function снимокСообщения(msg: MessageDto): AttachmentDto | null {
  const kind = kindOf(msg);
  // Заметка и системная запись — не переписка, склеивать их нечем и незачем.
  if (kind !== "in" && kind !== "out") return null;
  if (msg.attachments.length !== 1) return null;
  const att = msg.attachments[0];
  // Без ссылки плитку не из чего сделать: голосовое и часть файлов Авито
  // отдаёт идентификатором, за содержимым надо идти отдельным запросом.
  if (att.kind !== "image" || !att.url) return null;
  // Подпись под снимком — это уже слова, и терять их в сетке нельзя.
  if ((msg.body ?? "").trim() !== "") return null;
  if (msg.reply_to_id) return null;
  if (msg.delivery_status !== "delivered") return null;
  return att;
}

/** Колонок в сетке: 2 при 2–4 снимках, 3 при 5 и больше (просьба владельца). */
export function колонок(снимков: number): 2 | 3 {
  return снимков >= 5 ? 3 : 2;
}

/**
 * Строки ленты → те же строки, но подряд идущие снимки собраны в коллаж.
 *
 * Проход отдельный, ПОСЛЕ `buildThreadRows`, а не внутри него: та функция
 * отвечает на другой вопрос — «журнал статусов это или переписка», — и
 * смешивать в ней два правила значит завести файл, который меняется по двум
 * причинам сразу.
 *
 * ОДИНОЧНЫЙ СНИМОК ОСТАЁТСЯ ПУЗЫРЁМ. Серия начинается с двух: один снимок в
 * сетке 2×1 выглядел бы обрезанным вдвое и потерял бы пропорции, ради которых
 * место под него резервируют (правка 03.09).
 */
export function собратьСерииСнимков(rows: ThreadRow[]): FeedRow[] {
  const out: FeedRow[] = [];
  let i = 0;
  while (i < rows.length) {
    const row = rows[i];
    const att = row.kind === "message" ? снимокСообщения(row.msg) : null;
    if (row.kind !== "message" || !att) {
      out.push(row);
      i += 1;
      continue;
    }

    const shots: Снимок[] = [{ msg: row.msg, att }];
    let end = i + 1;
    while (end < rows.length) {
      const next = rows[end];
      if (next.kind !== "message") break;
      const следующий = снимокСообщения(next.msg);
      if (!следующий) break;
      // Сравниваем с ПОСЛЕДНИМ снимком серии, а не с первым: иначе серия из
      // семи снимков рвалась бы на пятой минуте от её начала, хотя между
      // соседними снимками проходят секунды.
      if (!тотЖеАвтор(shots[shots.length - 1].msg, next.msg)) break;
      shots.push({ msg: next.msg, att: следующий });
      end += 1;
    }

    if (shots.length < 2) {
      out.push(row);
      i += 1;
      continue;
    }
    // Ключ — id первого снимка: он стабилен между перерисовками, а порядковый
    // номер поехал бы при дозагрузке истории вверх (так же, как у журнала).
    out.push({ kind: "shots", key: `shots:${row.msg.id}`, shots, prev: row.prev });
    i = end;
  }
  return out;
}

/**
 * Есть ли в строке это сообщение — для перехода по цитате и подсветки.
 *
 * ⚠ БЕЗ ЭТОГО ПЕРЕХОД ПО ЦИТАТЕ ЛОМАЕТСЯ МОЛЧА. Панель искала строку по
 * `row.msg.id`, а у коллажа своего `msg` нет вовсе: ответ на снимок,
 * попавший в серию, не находил бы ничего и не прокручивал никуда.
 * Свёрнутый журнал целью перехода не бывает — на служебную запись не отвечают.
 */
export function строкаПро(row: FeedRow, messageId: string): boolean {
  if (row.kind === "message") return row.msg.id === messageId;
  if (row.kind === "shots") return row.shots.some((s) => s.msg.id === messageId);
  return false;
}
