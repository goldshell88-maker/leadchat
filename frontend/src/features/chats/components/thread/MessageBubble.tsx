function formatSize(bytes: number): string {
  if (bytes < 1024) return `${bytes} Б`;
  if (bytes < 1024 * 1024) return `${Math.round(bytes / 1024)} КБ`;
  return `${(bytes / (1024 * 1024)).toFixed(1)} МБ`;
}

/**
 * Статус доставки: часы → галочка → крест (docs/16 §4.4).
 *
 * Галочка ОДНА. В макете нарисованы две, как в мессенджерах, но вторая
 * означает «клиент прочитал», а Авито этого не сообщает — API отдаёт только
 * факт доставки. Двойная галочка показывала бы оператору знание, которого у
 * системы нет, и он решал бы «прочитал, но молчит» там, где на деле
 * «возможно, ещё не открыл».
 *
 * У ЗАМЕТКИ ГАЛОЧКИ НЕТ, И ЭТО НЕ ЗАБЫВЧИВОСТЬ. Заметку никуда не доставляют —
 * её видят только свои, — поэтому «Доставлено» рядом с ней было бы обещанием
 * про клиента, которого никто не давал. Заметке нужны ровно два состояния:
 * «сохраняется» и «не сохранилась»; второе — единственное, ради чего на этот
 * значок вообще смотрят.
 */
export function DeliveryStatusIcon({
  status,
  note = false,
}: {
  status: MessageDto["delivery_status"];
  note?: boolean;
}) {
  if (status === "pending") {
    return (
      <i className="msg__status" aria-label={note ? "Сохраняется" : "Отправляется"}>
        <IconClock size={13} />
      </i>
    );
  }
  if (status === "dismissed") {
    /*
     * Снятое с учёта: тот же крестик, но приглушённый. Красным он означал бы
     * «сделай что-нибудь», а делать уже нечего — человек решение принял.
     */
    return (
      <i className="msg__status" aria-label="Не отправлено, снято">
        <IconXCircle size={13} />
      </i>
    );
  }
  if (status === "failed") {
    return (
      <i
        className="msg__status msg__status--failed"
        aria-label={note ? "Не сохранилась" : "Не доставлено"}
      >
        <IconXCircle size={13} />
      </i>
    );
  }
  if (note) return null;
  return (
    <i className="msg__status" aria-label="Доставлено">
      <IconCheck size={13} />
    </i>
  );
}

/**
 * Вложения в пузыре.
 *
 * ТРИ СЛУЧАЯ, И ТРЕТИЙ ВАЖНЕЕ ВСЕГО (#29). Картинка со ссылкой — показываем.
 * Файл со ссылкой — строка со скрепкой. А вот вложение БЕЗ ссылки Авито
 * отдаёт регулярно: голосовое приходит идентификатором, за содержимым надо
 * идти отдельным запросом. Раньше такое рисовалось как `<img src=undefined>`
 * и «📎 undefined · NaN Б» — оператор видел поломку там, где клиент прислал
 * голосовое. Теперь это спокойная строка, по которой видно, что вложение
 * есть, но открыть его негде.
 *
 * ⚠ ТРЕТИЙ СЛУЧАЙ ПЕРЕСТАЛ БЫТЬ ПРО ГОЛОСОВОЕ (07.09). У голосового давно
 * своя ветка с проигрывателем, а «вложение без ссылки» досталось видео и
 * файлам: у них Авито не даёт НИЧЕГО — `content` пуст у всех 130 видео и всех
 * 22 файлов за 30 дней, ни ссылки, ни идентификатора, ни имени, ни размера.
 * Дозагрузить неоткуда: метода в каталоге нет, шесть угаданных путей дали 404
 * на том же токене, на котором `getVoiceFiles` отвечает.
 */
/**
 * Голосовое сообщение: строка превращается в проигрыватель по нажатию.
 *
 * ⚠ ПОЧЕМУ НЕ СРАЗУ ПРОИГРЫВАТЕЛЬ. Ссылку на запись Авито отдаёт ТОЛЬКО
 * отдельным запросом и ненадолго. Рисовать плеер сразу значило бы дёргать
 * Авито на каждое открытие диалога — за все голосовые в переписке разом, в том
 * числе те, которые никто слушать не станет. Нажали — спросили.
 */
function VoiceAttachment({ msg, name }: { msg: MessageDto; name: string }) {
  /*
   * ⚠ ЗАПИСЬ ОТКРЫВАЕТСЯ САМА, БЕЗ НАЖАТИЯ (просьба владельца 05.09: «всё так
   * же нужно нажимать на „Голосовое сообщение", я хочу чтобы он сразу
   * отображался»).
   *
   * ПОЧЕМУ РАНЬШЕ БЫЛО ПО НАЖАТИЮ. Ссылку на запись Авито отдаёт ТОЛЬКО
   * отдельным запросом и ненадолго. Рисовать проигрыватель сразу означало бы
   * дёргать Авито за все голосовые переписки разом — в том числе за те,
   * которые никто слушать не станет.
   *
   * ПОЧЕМУ ТЕПЕРЬ МОЖНО. Лента виртуализована: на экране живут только видимые
   * сообщения, поэтому «сразу» здесь значит «когда сообщение попало на экран»,
   * а не «за всю историю». Замер боя: голосовых 597 за 60 дней на все диалоги,
   * то есть около десяти в сутки на всю смену — открытие диалога с двумя
   * записями стоит двух запросов.
   *
   * Ответ кладём в общий кэш по идентификатору сообщения: прокрутка туда-сюда
   * не спрашивает Авито заново.
   *
   * ⚠ ССЫЛКА ЗДЕСЬ — ДЛЯ МЕТАДАННЫХ, А НЕ ДЛЯ ИГРЫ (06.09). Пузырь появляется
   * на экране, а «Слушать» нажимают и через полчаса; подписанная ссылка
   * files.avito.ru к тому времени мертва (скриншот владельца: оператор пишет
   * клиенту «аудио не грузит»). Поэтому проигрыватель получает ещё момент
   * получения ссылки и способ спросить свежую — и делает это сам перед игрой
   * и один раз на сбое. Сама запись у Авито живёт ≥29 дней (замер 06.09),
   * протухает только подпись.
   */
  const queryClient = useQueryClient();
  const ключ = ["voice-url", msg.id];
  const запись = useQuery({
    queryKey: ключ,
    queryFn: () => voiceUrl(msg.id),
    // Четыре минуты — срок, после которого прокрутка туда-сюда спросит ссылку
    // заново сама; перед игрой она проверяется отдельно и строже (порог в
    // проигрывателе).
    staleTime: 4 * 60_000,
    // Повторять нечего: если Авито не дало ссылку, оно не даст её и через
    // секунду, а человек увидит три одинаковых ожидания вместо одного ответа.
    retry: false,
  });

  if (запись.data?.url) {
    /*
     * ⚠ РАСШИФРОВКА ЕДЕТ ВМЕСТЕ С СООБЩЕНИЕМ И КАДРОМ `message:transcript`, А
     * НЕ ОТДЕЛЬНЫМ ЗАПРОСОМ. Её считает воркер своим Whisper на сервере
     * (решение владельца 05.09: «давай свой Whisper» — ни одна запись не
     * покидает машину), и результат лежит в той же строке сообщения. Значит и
     * приезжает он тем же ответом, что и сам пузырь, а досчитанный позже —
     * кадром в тот же кэш ленты (`patchMessageTranscript`): спрашивать текст
     * вторым запросом значило бы завести второй источник правды.
     */
    return (
      <VoicePlayer
        url={запись.data.url}
        urlUpdatedAt={запись.dataUpdatedAt}
        // Через кэш, а не мимо него: свежую ссылку получает и этот пузырь, и
        // тот же пузырь после прокрутки туда-сюда. `staleTime: 0` — иначе
        // `fetchQuery` вернёт из кэша ровно ту ссылку, которую просят заменить.
        refreshUrl={async () => {
          const свежая = await queryClient.fetchQuery({
            queryKey: ключ,
            queryFn: () => voiceUrl(msg.id),
            staleTime: 0,
            retry: false,
          });
          return свежая.url;
        }}
        transcript={msg.voice_transcript}
        transcriptStatus={msg.voice_transcript_status}
        // Расшифровывается только речь клиента: под своим исходящим голосовым
        // обещать «появится сама» нельзя.
        transcriptQueued={msg.direction === "in"}
      />
    );
  }

  if (запись.isPending) {
    /*
     * Место занимается заранее и ровно того размера, что у проигрывателя:
     * иначе лента дёргается в момент, когда запись приехала, — а голосовые
     * идут сериями по две-три подряд.
     */
    return (
      <span className="msg__voice-wait" role="status" aria-label={`${name}: загружается`}>
        <IconClock size={13} /> {name}
      </span>
    );
  }

  return (
    <span className="msg__file">
      <button
        type="button"
        className="msg__voice-btn"
        onClick={() => void запись.refetch()}
        disabled={запись.isFetching}
      >
        <IconPlay size={12} /> {name}
      </button>
      <span className="msg__voice-error">
        {" · "}
        {запись.error instanceof ApiError ? запись.error.message : "Не удалось получить запись"}
      </span>
    </span>
  );
}

function Attachments({
  msg,
  onOpenImage,
}: {
  msg: MessageDto;
  /** Открыть снимок во весь экран. Нет — картинка остаётся просто картинкой. */
  onOpenImage?: (mediaId: string) => void;
}) {
  if (msg.attachments.length === 0) return null;
  return (
    <span className="msg__attachments">
      {msg.attachments.map((a) => {
        const suffix = a.size ? ` · ${formatSize(a.size)}` : "";
        if (a.avito_type === "voice") {
          return <VoiceAttachment key={a.media_id} msg={msg} name={a.name} />;
        }
        /*
         * ⚠ ССЫЛКА, МЕСТО И ОБЪЯВЛЕНИЕ — СВОИМ ВИДОМ (05.09). Все три рисовались
         * одинаковой строкой со скрепкой, то есть человек не мог отличить
         * присланную ссылку от точки на карте, не открыв. За 60 дней их 140.
         */
        if (a.avito_type === "link" || a.avito_type === "location" || a.avito_type === "item") {
          return <AttachmentChip key={a.media_id} attachment={a} />;
        }
        if (!a.url) {
          /*
           * ⚠ ЭТА ВЕТКА СТАНОВИТСЯ БОЕВОЙ ВПЕРВЫЕ, А НЕ «ЧИНИТСЯ» (07.09).
           *
           * Замер по боевой базе: вложений без ссылки 747, но 731 из них
           * голосовые (уходят выше, в проигрыватель), а остальные 16 —
           * геопозиции и объявления (уходят в `AttachmentChip`). Сюда за всю
           * историю не пришло НИ ОДНО: 0 из 377 471 записи. Значит и вид этой
           * строки никем не проверен — его и доводим.
           *
           * ЧТО ЗДЕСЬ БУДЕТ. Видео и файл, у которых показать нечего. Жалоба
           * владельца дословно: «такое ощущение, что клиент сам пишет» — пока
           * подпись про них ехала телом сообщения, она и была абзацем в пузыре
           * клиента, неотличимым от его слов.
           *
           * СЛОВА — ТОЛЬКО СЕРВЕРНЫЕ. Список подписей живёт на сервере
           * (`_ATTACHMENT_LABELS`, `_CONTENT_FREE_KINDS`); второго его
           * экземпляра здесь нет намеренно — разъехавшись, они дали бы два
           * разных ответа об одном сообщении. Служебность показывает не второе
           * слово, а ФОРМА: пунктирная рамка, скрепка, отсутствие перехода.
           *
           * ⚠ СКРЫТАЯ ПОДПИСЬ — РАДИ СКРИНРИДЕРА, И БЕЗ НЕЁ ФОРМА НЕ РАБОТАЕТ.
           * Рамку и скрепку он не произносит: содержимое пузыря читается
           * подряд, и «Видео — посмотреть можно только в приложении Авито»
           * звучит ровно как фраза человека. Отдельным узлом, а не `aria-label`
           * на `span`: имя от `aria-label` берут только элементы с ролью,
           * поддерживающей называние, а у `span` роли нет вовсе.
           */
          return (
            <span key={a.media_id} className="msg__file msg__file--unavailable">
              <IconPaperclip size={14} />
              {/* Текст одним узлом: скрытая подпись отдельным элементом флекса
                  получила бы свой зазор — пустое место внутри рамки. */}
              <span>
                <span className="lc-visually-hidden">Вложение, открыть нельзя. </span>
                {a.name}
                {suffix}
              </span>
            </span>
          );
        }
        if (a.kind === "image") {
          /*
           * ⚠ СНИМОК — КНОПКА, А НЕ КАРТИНКА (28.08).
           *
           * Клиент присылает не «картинку», а ДОКАЗАТЕЛЬСТВО: фотографию
           * экрана с ошибкой, шильдика с моделью, потёка на задней стенке. По
           * ней оператор ставит диагноз и называет цену. Здесь стоял голый
           * `<img>` со стороной 280 пикселей: открыть его было нельзя ничем —
           * ни нажатием, ни правой кнопкой (в десктопе меню браузера нет), — и
           * текст ошибки на таком снимке нечитаем. Оператор шёл смотреть его в
           * само Авито, то есть выходил из системы, ради которой её и ставили.
           *
           * `<button>`, а не `<div onClick>`: снимок обязан открываться и с
           * клавиатуры, и читаться скринридером как действие.
           */
          /*
           * ⚠ ПРОПОРЦИИ СТАВЯТСЯ НА ОБЁРТКУ, А НЕ НА САМ `img`, И ЭТО ЗАМЕР.
           *
           * Пузырь `.msg__bubble` — flex-элемент с shrink-to-fit: у
           * незагруженной картинки нулевая внутренняя ширина, пузырь
           * схлопывается до 80 px, и `100%` внутри него равно 48. Место
           * резервируется в шесть раз меньше нужного (проверено: строка 76 px
           * вместо 262,5). Определённая ширина у ОБЁРТКИ снимает это: пузырь
           * подстраивается под неё.
           *
           * У старых сообщений размеров нет — там разметка остаётся прежней,
           * и это правильно: выдуманная пропорция хуже отсутствующей.
           */
          const пропорция =
            a.width && a.height ? ({ "--ar": `${a.width / a.height}` } as CSSProperties) : undefined;
          const снимок = (
            <img
              className="msg__image"
              src={withApiRoot(a.url)}
              alt={a.name}
              loading="lazy"
              /* Мимо главного потока: снимок в ленте иначе даёт рывок
                 прокрутки ровно в момент, когда его дорисовали. */
              decoding="async"
              /*
               * Ссылки Авито живут не вечно. Без этого место снимка занимал
               * значок битой картинки — «клиент прислал пустоту», хотя он
               * прислал фотографию, а просрочилась ссылка.
               */
              /*
               * ⚠ НАСТОЯЩАЯ ПРОПОРЦИЯ ПОБЕЖДАЕТ ЗАЯВЛЕННУЮ (05.09, третья
               * жалоба владельца на «лишний фон» вокруг снимка).
               *
               * Место под картинку резервируется заранее по размерам, которые
               * дал сервер (`--ar`), — иначе лента прыгает под курсором. Но
               * если эти размеры не совпадают с настоящими (Авито отдаёт их
               * для превью, а поворот из EXIF не учитывает), коробка получает
               * ЧУЖУЮ форму, и картинка вписывается в неё с тёмными полями по
               * бокам. Снять поля пузыря было мало: полосы рисовала сама
               * коробка.
               *
               * Как только картинка загрузилась, её собственные размеры
               * известны точно — и коробка берёт их. Совпали с заявленными —
               * ничего не двигается; разошлись — форма чинится один раз, и
               * это лучше, чем полосы навсегда.
               */
              onLoad={(e) => {
                const img = e.currentTarget;
                const box = img.closest(".msg__image-wrap") as HTMLElement | null;
                if (!box || !img.naturalWidth || !img.naturalHeight) return;
                box.style.setProperty("--ar", String(img.naturalWidth / img.naturalHeight));
              }}
              onError={(e) => {
                e.currentTarget.closest(".msg__image-wrap")?.setAttribute("data-broken", "true");
              }}
            />
          );
          if (!onOpenImage) {
            return (
              <span key={a.media_id} className="msg__image-wrap" style={пропорция}>
                {снимок}
                <span className="msg__image-broken">Снимок не открылся</span>
              </span>
            );
          }
          return (
            <button
              key={a.media_id}
              type="button"
              className="msg__image-wrap msg__image-wrap--clickable"
              style={пропорция}
              onClick={() => onOpenImage(a.media_id)}
              aria-label={`Открыть снимок: ${a.name}`}
              title="Открыть во весь экран"
            >
              {снимок}
              <span className="msg__image-broken">Снимок не открылся</span>
            </button>
          );
        }
        return (
          <ExternalLink key={a.media_id} className="msg__file" url={withApiRoot(a.url)}>
            <IconPaperclip size={14} /> {a.name}
            {suffix}
          </ExternalLink>
        );
      })}
    </span>
  );
}

