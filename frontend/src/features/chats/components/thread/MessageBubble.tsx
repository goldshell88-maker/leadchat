/**
 * Три исхода — СЛОВАМИ СЕРВЕРА, а не своими (`clients.CANDIDATE_DECISIONS`).
 * `replace` — «это его основной телефон», номер встаёт в поле карточки и
 * затирает прежний; `add` — «телефон его, но основной другой», карточка
 * показывает номер вторым; `reject` — «это не телефон» или «не его».
 */
type Decision = "replace" | "add" | "reject";

interface ResolveResult {
  phone: string | null;
  candidate: PhoneCandidateDto;
  /** Другие карточки с этим же номером — повод предложить объединение. */
  twins: ClientCardRef[];
}

/**
 * Личность клиента ГЛАЗАМИ ЛЕНТЫ.
 *
 * `ClientIdentityDto` в карточке поля `phone_candidates` не объявляет, хотя
 * сервер его шлёт (`clients.identity_view`). Расширяем здесь, а не правим тип
 * в карточке, по границе работ: карточка сейчас в чужих руках, а ждать чужой
 * правки, чтобы показать номер в пузыре, значит не показать его вовсе. Когда
 * тип личности объявит поле у себя, это расширение и приведение ниже уйдут —
 * общий запрос и общий кэш от этого не меняются.
 */
type IdentityWithCandidates = ClientIdentityDto & {
  phone_candidates?: PhoneCandidateDto[];
};

/** Чем кончился разговор про один найденный номер — ПАМЯТЬ ЭКРАНА. */
type Outcome = { kind: "decided"; decision: Decision } | { kind: "gone"; text: string };

/** Подпись тоста и строка на месте предложения — по существу решения. */
const DONE_TITLE: Record<Decision, string> = {
  replace: "Телефон в карточке",
  add: "Телефон добавлен вторым",
  reject: "Номер отклонён",
};
const DONE_NOTE: Record<Decision, string> = {
  replace: "в карточке",
  add: "добавлен вторым номером",
  reject: "отклонён — это не его телефон",
};

/**
 * Сброс кэша после решения по номеру.
 *
 * ПРЕФИКС `["clients"]` НЕ ВЫДУМАН ЗДЕСЬ: карточка объявляет свои ключи с тем
 * же первым элементом (`card/clientApi.ts`) ровно затем, чтобы один сброс
 * накрывал и личность, и подсказки объединения, и историю клиента. Диалоги
 * сбрасываются рядом, потому что телефон виден и в детали (`conversation
 * .client`), и в строке списка: оставь их нетронутыми — в одном окне окажется
 * два разных ответа про один номер.
 */
function useIdentityRefresh() {
  const qc = useQueryClient();
  return () =>
    Promise.all([
      qc.invalidateQueries({ queryKey: ["clients"] }),
      qc.invalidateQueries({ queryKey: qk.conversations.root }),
    ]);
}

function useResolveCandidate(clientId: string) {
  const refresh = useIdentityRefresh();
  return useMutation({
    mutationFn: ({ id, decision }: { id: string; decision: Decision }) =>
      http.post<ResolveResult>(
        `/clients/${encodeURIComponent(clientId)}/phone-candidates/${encodeURIComponent(id)}/resolve`,
        { decision },
      ),
    onSuccess: refresh,
  });
}

/**
 * Строка под текстом: что нашли и что с этим можно сделать.
 *
 * ПОЧЕМУ ДЕЙСТВИЕ ЖИВЁТ ЗДЕСЬ, А НЕ ВНУТРИ ПОДСВЕЧЕННОГО НОМЕРА. Кнопку
 * тянуло поставить прямо в текст — это ближе к глазу. Нельзя: номер из
 * переписки копируют мышью, чтобы позвонить, и любой лишний узел внутри абзаца
 * уезжает в буфер обмена вместе с текстом. Внутри абзаца остаётся только
 * обёртка над теми же символами, всё остальное — отдельной строкой.
 *
 * ОДНО НАЖАТИЕ, ПОКА ВЫБИРАТЬ НЕ ИЗ ЧЕГО. Карточка пуста — «В карточку» и
 * всё; так номер и попадает в карточку в большинстве случаев, потому что
 * автозапись по умолчанию выключена. Карточка занята ДРУГИМ номером — тихо
 * ничего не делать нельзя (оператор нажал бы и решил, что записалось), и
 * молча затирать чужой номер нельзя тем более: показываем ровно три действия,
 * какие знает сервер.
 */
function PhoneOffer({
  clientId,
  candidate,
  cardPhone,
  known,
  outcome,
  onOutcome,
}: {
  clientId: string;
  candidate: PhoneCandidateDto;
  /** Что стоит в карточке сейчас; `null` — номера нет вовсе. */
  cardPhone: string | null;
  /** Этот номер карточке уже известен — основным или вторым. */
  known: boolean;
  outcome: Outcome | null;
  onOutcome: (o: Outcome) => void;
}) {
  const resolve = useResolveCandidate(clientId);
  const refresh = useIdentityRefresh();
  const [error, setError] = useState<string | null>(null);
  /*
   * Показываем канонический вид, а подсвечен в тексте — исходный. Это не
   * рассинхрон, а единственный способ проверить нашу же догадку: рядом стоят
   * «+7(900)1112240» из сообщения и «+7 900 111-22-40», который уедет в
   * карточку и в набиратель.
   */
  const shown = formatPhone(candidate.phone);

  const decide = (decision: Decision) => {
    setError(null);
    resolve.mutate(
      { id: candidate.id, decision },
      {
        onSuccess: (result) => {
          onOutcome({ kind: "decided", decision });
          toast.success(
            DONE_TITLE[decision],
            result.twins.length > 0
              ? "Этот номер есть и в другой карточке — предложение объединить ждёт в карточке клиента"
              : undefined,
          );
        },
        onError: (e) => {
          const api = e instanceof ApiError ? e : null;
          /*
           * 409 «решение уже принято» и 404 «кандидата нет» — не сбой, а
           * новость: пока оператор читал переписку, по номеру решили в
           * карточке или в соседней вкладке. Строка обязана СМЕНИТЬ вид, а не
           * предлагать нажать ещё раз то, чего больше нет; карточку заодно
           * освежаем — там номер, возможно, уже стоит.
           */
          if (api && (api.status === 409 || api.status === 404)) {
            onOutcome({ kind: "gone", text: api.message });
            void refresh();
            return;
          }
          /*
           * Всё остальное — связь или сервер. Текст сервера показывается как
           * есть (01 §1.3): он говорит, что делать, а «Ошибка» не говорит
           * ничего. Кнопки остаются на месте: повторить есть чем.
           */
          setError(api ? api.message : "Не получилось. Попробуйте ещё раз.");
        },
      },
    );
  };

  if (outcome) {
    return (
      <span className="msg__phone-note">
        <IconPhone size={13} /> {shown} —{" "}
        {outcome.kind === "decided" ? DONE_NOTE[outcome.decision] : outcome.text}
      </span>
    );
  }

  /*
   * Номер уже в карточке — предлагать нечего, и предложение здесь было бы
   * работой ради работы. Подсветка при этом остаётся: она отвечает на другой
   * вопрос — «где человек это написал», — и ответ верен по-прежнему.
   */
  if (known) {
    return (
      <span className="msg__phone-note">
        <IconPhone size={13} /> {shown} — уже в карточке
      </span>
    );
  }

  return (
    <span className="msg__phone-offer">
      <IconPhone size={13} />
      <span className="msg__phone-offer__value">{shown}</span>
      {cardPhone ? (
        <>
          <span className="msg__phone-offer__busy">в карточке другой: {formatPhone(cardPhone)}</span>
          {/* Слова кнопок — те же, какими действия названы у владельца и на
              сервере. Перевести их по дороге значило бы завести четвёртое
              понимание тех же трёх действий. */}
          <button
            type="button"
            className="msg__phone-action"
            aria-label={`Заменить телефон в карточке на ${shown}`}
            disabled={resolve.isPending}
            onClick={() => decide("replace")}
          >
            Заменить
          </button>
          <button
            type="button"
            className="msg__phone-action"
            aria-label={`Добавить ${shown} вторым номером`}
            disabled={resolve.isPending}
            onClick={() => decide("add")}
          >
            Добавить
          </button>
          <button
            type="button"
            className="msg__phone-action"
            aria-label={`Отклонить ${shown} — это не его телефон`}
            disabled={resolve.isPending}
            onClick={() => decide("reject")}
          >
            Отклонить
          </button>
        </>
      ) : (
        <button
          type="button"
          className="msg__phone-action msg__phone-action--main"
          aria-label={`В карточку: ${shown}`}
          disabled={resolve.isPending}
          onClick={() => decide("replace")}
        >
          В карточку
        </button>
      )}
      {error && <span className="msg__phone-error">{error}</span>}
    </span>
  );
}

/**
 * Текст ВХОДЯЩЕГО сообщения: с подсветкой найденного номера и действием к нему.
 *
 * ОТКУДА БЕРЁТСЯ ПОДСВЕТКА. Не из разбора на фронте — правила защиты от ложных
 * срабатываний живут на сервере (`app/services/phone_parse.py`), и вторая их
 * копия разошлась бы молча (подробности — в шапке `shared/lib/phoneHighlight`).
 * Сервер отдаёт кандидата с `message_id` и с `raw` — записью номера ровно
 * такой, какой её набрал человек, — и пузырь ищет эту запись в своём тексте
 * подстрокой. Нет кандидата — нет подсветки.
 *
 * ЗАПРОС ОДИН НА ВЕСЬ ЭКРАН, ХОТЯ ЗОВЁТСЯ ИЗ КАЖДОГО ПУЗЫРЯ. Ключ ответа —
 * КЛИЕНТ (`card/clientApi.ts`), поэтому двадцать видимых сообщений подписаны на
 * одну запись кэша и на один запрос; ту же запись читает карточка клиента,
 * когда открыта. Ценой этому — свежесть: ответ считается годным минуту, и
 * предложение по только что пришедшему сообщению может появиться не в тот же
 * миг, а после ближайшего обновления личности. Размен сознательный: запрос на
 * каждый пузырь при прокрутке ленты стоил бы дороже минуты ожидания.
 */
function IncomingText({
  msg,
  clientId,
  body,
  className,
}: {
  msg: MessageDto;
  clientId: string;
  body: string;
  className: string;
}) {
  const { can } = usePermissions();
  /*
   * Право то же, каким телефон правят руками (`conversations:manage`): ручка
   * личности его требует, а решение по кандидату — тем более. Подсветка без
   * права нажать рассказала бы о находке и не дала бы её забрать, а запрос
   * без права ловил бы 403 на каждом входящем.
   *
   * ВТОРОЕ УСЛОВИЕ ПРО ИДЕНТИФИКАТОР. Пока деталь диалога не приехала, в
   * `clientId` лежит идентификатор ДИАЛОГА — запасное значение из
   * `ChatThreadPane`, которого хватает аватару для цвета. Личность по нему
   * ответила бы 404, поэтому ждём настоящий идентификатор клиента.
   */
  const enabled = can("conversations:manage") && clientId !== msg.conversation_id;
  const identity = useClientIdentity(clientId, enabled);
  const data = identity.data as IdentityWithCandidates | undefined;

  /*
   * ПАМЯТЬ О ПРИНЯТЫХ РЕШЕНИЯХ ЖИВЁТ ЗДЕСЬ, И БЕЗ НЕЁ НЕ ОБОЙТИСЬ. Сервер
   * отдаёт только ОЖИДАЮЩИХ кандидатов: нажатие — и номер из ответа исчезает.
   * Строка вместе с подсветкой пропала бы в тот же миг, и на месте нажатой
   * кнопки не осталось бы ничего — ровно то ощущение «нажал, и куда-то делось»,
   * ради которого эта правка и делается. Память недолгая, до перерисовки
   * пузыря лентой, и это честно: вопрос закрыт, номер живёт в карточке.
   */
  const [outcomes, setOutcomes] = useState<
    Array<{ candidate: PhoneCandidateDto; outcome: Outcome }>
  >([]);

  const rows = useMemo(() => {
    const decided = new Set(outcomes.map((o) => o.candidate.id));
    const all: Array<{ candidate: PhoneCandidateDto; outcome: Outcome | null }> = [
      ...outcomes,
      ...candidatesInMessage(data?.phone_candidates, msg.id)
        .filter((c) => !decided.has(c.id))
        .map((candidate) => ({ candidate, outcome: null })),
    ];
    // Порядок — по месту в тексте: строки под сообщением обязаны читаться
    // сверху вниз в том же порядке, в каком номера стоят в самой фразе.
    const at = (c: PhoneCandidateDto) => {
      const i = body.indexOf(c.raw);
      return i < 0 ? Number.MAX_SAFE_INTEGER : i;
    };
    return all.sort((a, b) => at(a.candidate) - at(b.candidate));
  }, [outcomes, data, msg.id, body]);

  const parts = useMemo(
    () => splitPhones(body, rows.map((r) => r.candidate.raw)),
    [body, rows],
  );

  const cardPhone = data?.phone ?? null;
  const phones = data?.phones ?? [];

  return (
    <>
      <p className={className}>
        {parts.map((part, i) =>
          part.phone ? (
            <mark key={i} className="msg__phone">
              {part.text}
            </mark>
          ) : (
            <Fragment key={i}>{part.text}</Fragment>
          ),
        )}
      </p>
      {rows.map(({ candidate, outcome }) => (
        <PhoneOffer
          key={candidate.id}
          clientId={clientId}
          candidate={candidate}
          cardPhone={cardPhone}
          known={candidate.phone === cardPhone || phones.some((p) => p.value === candidate.phone)}
          outcome={outcome}
          onOutcome={(o) =>
            setOutcomes((prev) => [
              ...prev.filter((p) => p.candidate.id !== candidate.id),
              { candidate, outcome: o },
            ])
          }
        />
      ))}
    </>
  );
}

/**
 * Пузыри 5 типов (docs/16 §4.4): in — карточка слева с аватаром клиента, out —
 * градиент primary справа, bot — фиолетовая рамка, note — жёлтая вставка во
 * всю ширину «видно только сотрудникам», system — серый чип по центру (наша
 * запись и служебное сообщение Авито — один и тот же чип, разные подписи).
 * Подпись автора и аватар — только у ПЕРВОГО сообщения в серии одного
 * человека (docs/17): подряд идущие схлопываются.
 * Дата-разделитель не отдельная строка виртуализатора — рендерится здесь,
 * когда день сообщения отличается от предыдущего (03 §4.2).
 */
function MessageBubbleView({
  msg,
  prev,
  clientId,
  clientName,
  clientAvatarUrl,
  onOpenImage,
  onRetry,
  onDismiss,
  onReply,
  onGoToQuoted,
  onDiscard,
  onDeleteNote,
}: {
  msg: MessageDto;
  prev: MessageDto | null;
  clientId: string;
  clientName: string;
  clientAvatarUrl?: string | null;
  /** Открыть снимок во весь экран (просмотрщик живёт у панели ленты). */
  onOpenImage?: (mediaId: string) => void;
  /** Не передан — кнопки «Повторить» нет (роли без `messages:send`, 03 §5.2). */
  onRetry?: (msg: MessageDto) => void;
  /** «Снять» у серверного неотправленного: метка гаснет, сообщение остаётся. */
  onDismiss?: (msg: MessageDto) => void;
  /**
   * Ответить на это сообщение. Не передан — кнопки нет (роли без права
   * отправки; отвечать им не на что).
   */
  onReply?: (msg: MessageDto) => void;
  /** Перейти к цитируемому сообщению в ленте. */
  onGoToQuoted?: (messageId: string) => void;
  /** Удаление заметки автором (17.08); показывается только на своих заметках. */
  onDeleteNote?: (msg: MessageDto) => void;
  /**
   * «Удалить» рядом с «Повторить» (04 §5.3) — только у локальных строк
   * офлайн-очереди: серверное сообщение не выбрасывают, у него свои ретраи.
   */
  onDiscard?: (msg: MessageDto) => void;
}) {
  const kind = kindOf(msg);
  /** Сообщение из одной фотографии и без единого слова. */
  const толькоСнимок =
    !msg.body?.trim() &&
    msg.attachments.length === 1 &&
    msg.attachments[0]?.kind === "image" &&
    Boolean(msg.attachments[0]?.url) &&
    kind !== "note";
  const showDivider = сменаДня(prev, msg);

  /**
   * Служебное сообщение самого Авито — ТА ЖЕ манера, что у наших системных
   * записей, плюс подпись об источнике. Третьего вида подачи заводить не стали
   * намеренно: и «Статус: Новый → В работе. Иванов», и слова Авито — это не
   * переписка, и в ленте они обязаны читаться одинаково тихо, иначе серый чип
   * перестаёт означать «читать не срочно».
   *
   * А подпись всё же нужна: за нашей записью стоит наша же работа, за словами
   * Авито — чужое действие, о котором оператор может ничего не знать. Без
   * подписи «Заказ отменён» выглядит как строка, которую написали мы сами.
   *
   * Вид сообщения (тип от Авито) НЕ переводится в слова: перечня видов у нас
   * нет, и выдуманная подпись хуже отсутствующей. Показываем текст как пришёл.
   */
  const isAvitoSystem = kind === "system" && isAvitoSystemMessage(msg);

  /**
   * Подряд идущие сообщения одного автора схлопываются: подпись и аватар
   * рисуются только у первого (UX-аудит, docs/17).
   *
   * Оператор отвечает очередями по три-четыре сообщения, и до сих пор его имя
   * повторялось у каждого — четыре одинаковые строки подряд, которые надо
   * взглядом пропустить, чтобы добраться до текста. Разделяем по пятиминутному
   * окну: если пауза больше, это уже другой заход в диалог, и напомнить, кто
   * писал, уместно.
   *
   * ⚠ САМО ПРАВИЛО ПЕРЕЕХАЛО В `messageSeries.ts` (05.09) И НЕ ИЗМЕНИЛОСЬ. Ту
   * же границу серии считает коллаж из снимков; двумя копиями они разъехались
   * бы на первой правке, и на экране вышел бы спор с самим собой — подписи
   * схлопнуты в одну группу, а снимки разорваны на две.
   */
  const sameAuthor = тотЖеАвтор(prev, msg);

  /*
   * СХЛОПЫВАНИЕ ДОДЕЛАНО ГЕОМЕТРИЕЙ (13.08). Подпись и аватар убрали 6 августа, а
   * вертикальный зазор остался прежним: `.msg { padding: 3px 0 }` — 6px и внутри
   * серии, и на её границе. Убрали признаки группы, не дав взамен того, что группу
   * показывает. Четыре сообщения подряд перестали повторять имя, но так и не стали
   * читаться одним блоком.
   *
   * ⚠ ЭТО НЕ `sameAuthor`, И РАЗНИЦА СУЩЕСТВЕННА. У заметки подпись рисуется ВСЕГДА
   * (ниже, `kind === "note"`) — она не схлопывается вовсе. Дай ей класс продолжения
   * по одному лишь `sameAuthor`, и две заметки подряд сядут вплотную, сохранив по
   * полной подписи в каждой: плотность группы без единого признака группы. Класс
   * обязан идти от того, ЧТО ПОДПИСЬ ДЕЙСТВИТЕЛЬНО УБРАНА, а не от того, что автор
   * совпал.
   *
   * Сами границы серии (автор, тип пузыря, сутки, пятиминутное окно) не трогаем и не
   * дублируем: они посчитаны выше один раз и охраняются messageGrouping.test.tsx.
   */
  const collapsed = sameAuthor && kind !== "note";
  /*
   * Текст пузыря берётся из ОБЩЕГО модуля, а не считается здесь (правка 8).
   *
   * Здесь стояло `msg.body?.trim() || (attachments.length ? "" : "…")`, а в
   * строке списка — `|| "Вложение"`. Об одном и том же сообщении система
   * говорила разное: в списке «Вложение», в ленте «…». Так выглядело
   * 00000000-0811-… от 11 августа — входящее, у которого сервер не разобрал
   * нетекстовый вид и сохранил пустым.
   *
   * Корень вылечен на сервере, но записи, накопленные ДО правки, так и лежат с
   * `body=null`, и до дозагрузки истории лента обязана называть их честно.
   */
  /*
   * «Ждал N» из служебной записи вырезается ПРИ ПОКАЗЕ (пункт 4 перекройки).
   *
   * Сервер дописывает ожидание в текст записи о принятии: «Диалог принят:
   * Ольга. Ждал 7 мин». Это метрика ДИАЛОГА, а не событие — и живёт она в
   * чипе статуса в шапке, где тикает. В ленте застывшее число ещё и спорит с
   * шапкой: «Ждал 7 мин» рядом с «ждёт 40 мин» — два разных ответа на один
   * вопрос, и оператор верит тому, что ближе к глазу.
   *
   * Серия таких записей проходит мимо этой строки — её собирает
   * SystemEventGroup, и там хвост режет та же самая `stripWaited`.
   */
  const body = isStatusLogMessage(msg) ? stripWaited(bubbleText(msg)) : bubbleText(msg);
  /*
   * Подпись-заглушка — не слова клиента, и выглядеть должна иначе.
   *
   * Без этого «Сообщение неподдерживаемого вида — откройте диалог в Авито»
   * читается как фраза, которую написал человек на том конце, — и оператор
   * отвечает на неё.
   *
   * ⚠ В БОЮ ЭТО СРАВНЕНИЕ НЕ СРАБАТЫВАЛО НИ РАЗУ, И ВОТ ЗАМЕР (07.09). Строк
   * с таким телом 0 из 377 471 — и 0 даже по приставке «Сообщение
   * неподдерживаемого вида», которой сервер метит незнакомый вид. Текст этот в
   * базе не лежит вовсе: его СЧИТАЕТ фронт (`bubbleText`), когда у сообщения
   * нет ни слов, ни вложений. Таких записей 40, и все 40 до единой —
   * служебные записи Авито (`direction=system`, 28.03–24.08), а их рисует
   * ветка выше, где этого класса нет.
   *
   * ПОЧЕМУ ВСЁ-ТАКИ ОСТАЁТСЯ. Пузырь собирается не только из свежего ответа
   * сервера: та же строка приезжает кадром `message:new` и лежит в кэше
   * десктопа с прошлых версий. Пузырь без единого слова читается как пустой, а
   * не как «показать нечего», и цена страховки — одно сравнение строк.
   *
   * ⚠ ЧЕГО ОН НЕ ЛОВИТ, И ЭТО ГЛАВНОЕ. Подписи «Видео», «Файл», «Клиент звонил
   * через приложение Авито» — НАСТОЯЩЕЕ тело записи (3279 строк), этой строке
   * они не равны и равны не будут. Ловить их списком слов здесь нельзя: список
   * живёт на сервере, второй его экземпляр на фронте разъедется с первым.
   * Служебность таких сообщений показывает вложение без ссылки (`Attachments`
   * выше), а не совпадение текста.
   */
  const unsupported = body === UNSUPPORTED_MESSAGE_TEXT;

  /*
   * ЗАМЕТКА ТОЖЕ ОТПРАВЛЯЕТСЯ — И ТОЖЕ МОЖЕТ НЕ ДОЙТИ.
   *
   * Крест, «Повторить» и «Удалить» рисовались только у `kind === "out"`, а
   * внутренняя заметка приходит сюда с `direction === "note"` (см.
   * `buildTempMessage` в useSendMessage). Значит провалившаяся заметка
   * выглядела ровно как сохранённая: жёлтая плашка, имя автора, время — и ни
   * следа ошибки. Оператор писал «клиент просил перезвонить после 18:00, скидку
   * не обещать», запрос падал, и заметки не оставалось нигде: ни у него, ни у
   * сменщика, который назавтра пообещает скидку. Молчаливая потеря хуже видимой
   * ошибки — с ошибкой человек хотя бы напишет второй раз.
   *
   * Путь отправки у заметки тот же и ретрай тот же (`useRetryMessage` зовёт
   * `sendNote`), поэтому и разговор о неудаче обязан быть тот же — иначе кнопка
   * «Повторить» есть в коде, но её некому нажать.
   */
  const isNote = kind === "note";
  // У реплики бота состояние показываем только при сбое: красную метку «ответ
  // не дошёл» ставит и она, а снять её без кнопок у пузыря было нечем.
  const showsDelivery =
    kind === "out" ||
    isNote ||
    (kind === "bot" && msg.sender_type === "bot" && msg.delivery_status === "failed");
  /*
   * Слова об ошибке — по существу случившегося. Заметка не «не доставлена»
   * (доставлять её некому), она НЕ СОХРАНИЛАСЬ. Разница не косметическая:
   * прочитав у заметки «не доставлено», оператор решит, что до клиента не дошло
   * сообщение, и пойдёт разбираться не с тем — а пропала запись для своих.
   */
  const failedLead = isNote
    ? "Заметка не сохранилась"
    : msg.delivery_error
      ? "Не доставлено"
      : "Не отправилось";
  const failedText = msg.delivery_error ? `${failedLead}: ${msg.delivery_error}` : failedLead;

  return (
    <>
      {showDivider && <DayDivider msg={msg} />}

      {kind === "system" ? (
        <div className="msg msg--system" role="listitem">
          <span
            className={
              isAvitoSystem
                ? "msg__system-text msg__system-text--avito"
                : "msg__system-text"
            }
          >
            {isAvitoSystem && (
              <span className="msg__system-source">
                <IconInfo size={12} /> Сообщение Авито
              </span>
            )}
            {body} · {formatClock(msg.created_at)}
          </span>
        </div>
      ) : (
        <div
          className={`msg msg--${kind}${collapsed ? " msg--cont" : ""}`}
          role="listitem"
        >
          {kind === "in" &&
            (sameAuthor ? (
              // Место аватара сохраняем пустым: без него пузыри группы
              // съезжают влево и лесенка ломается.
              <div className="msg__avatar msg__avatar--placeholder" aria-hidden="true" />
            ) : (
              <div className="msg__avatar">
                <ClientAvatar clientId={clientId} name={clientName} src={clientAvatarUrl} size={32} />
              </div>
            ))}
          {/*
            ⚠ СНИМОК БЕЗ СЛОВ — БЕЗ ПУЗЫРЯ (просьба владельца 05.09: «можно
            чтобы нормально отображалось и не было лишнего фона»).
            
            У сообщения из одной фотографии пузырь не несёт ничего: подложка,
            поля и тень обрамляют картинку, у которой и так есть свои края и
            свои скругления. На экране это читается как рамка вокруг рамки —
            особенно на снимке экрана телефона, где по бокам своя тёмная
            полоса. Замер: поля пузыря отнимают у картинки 32 пикселя ширины и
            добавляют 24 высоты на каждое такое сообщение, а их 10 120 за 60
            дней.
            
            Условие узкое: ровно одно вложение-картинка и НИ СЛОВА текста.
            Появилась подпись — вернулся пузырь: слова обязаны лежать на
            подложке, иначе их не прочесть на светлой фотографии.
          */}
          <div className="msg__bubble" data-media={толькоСнимок || undefined}>
            {kind === "out" && !sameAuthor && (
              // Отдел в скобках у автора исходящего (04.09): в ленте, где
              // подряд отвечают двое из разных отделов, имя одно не говорит,
              // кто именно писал клиенту.
              <span className="msg__author">{подписьСотрудника(msg.sender, "Оператор")}</span>
            )}
            {kind === "bot" && !sameAuthor && (
              <span className="msg__author">
                <IconBot size={13} /> {msg.sender_type === "system" ? "Система" : "Бот"}
              </span>
            )}
            {kind === "note" && (
              <span className="msg__author">
                <IconNote size={13} /> Заметка · {подписьСотрудника(msg.sender, "Сотрудник")} ·
                видно только сотрудникам
                {onDeleteNote && (
                  <>
                    {" · "}
                    <button
                      type="button"
                      className="msg__retry"
                      onClick={() => onDeleteNote(msg)}
                      aria-label="Удалить заметку"
                    >
                      Удалить
                    </button>
                  </>
                )}
              </span>
            )}
            {/*
              ВХОДЯЩЕЕ РИСУЕТСЯ ДРУГИМ КОДОМ, И ЭТО НЕ УКРАШЕНИЕ. Только у него
              бывает найденный телефон, и только ему нужен запрос личности
              клиента; звать его из каждого пузыря ленты — включая свои,
              заметки и служебные записи Авито — значило бы платить за то, чего
              там не бывает.
            */}
            {/*
              ⚠ ЦИТАТА — В ШАПКЕ ПУЗЫРЯ, НАД ТЕКСТОМ. Так её читают первой:
              «на что это ответ» — вопрос, который возникает ДО самого ответа,
              а не после. Внизу она превратилась бы в сноску, которую замечают,
              уже перечитав ответ во второй раз.

              У ВХОДЯЩИХ ЕЁ НЕ БЫВАЕТ, и это не пробел разбора: у Авито
              цитирования в API нет (90 800 вебхуков, 153 492 сообщения
              содержимого, полный перечень полей верхнего уровня — ни одного
              признака). Показываем только то, на что ответили МЫ.
            */}
            {msg.reply_to_id && (
              <button
                type="button"
                className="msg__quote"
                onClick={() => onGoToQuoted?.(msg.reply_to_id as string)}
                title={onGoToQuoted ? "Перейти к сообщению" : undefined}
              >
                {msg.reply_to ? (
                  <>
                    <span className="msg__quote-who">
                      {msg.reply_to.direction === "in" ? clientName : "Вы"}
                    </span>
                    <span className="msg__quote-text lc-truncate">
                      {msg.reply_to.has_attachments && !msg.reply_to.body
                        ? "Вложение"
                        : msg.reply_to.body}
                      {msg.reply_to.truncated && "…"}
                    </span>
                  </>
                ) : (
                  /* Связь есть, показывать нечего: сообщение удалили. Пустота
                     здесь выглядела бы ответом в никуда. */
                  <span className="msg__quote-text msg__quote-text--gone">
                    Сообщение удалено
                  </span>
                )}
              </button>
            )}
            {body &&
              (kind === "in" ? (
                <IncomingText
                  msg={msg}
                  clientId={clientId}
                  body={body}
                  className={unsupported ? "msg__text msg__text--unsupported" : "msg__text"}
                />
              ) : (
                <p className={unsupported ? "msg__text msg__text--unsupported" : "msg__text"}>
                  {body}
                </p>
              ))}
            <Attachments msg={msg} onOpenImage={onOpenImage} />
            <span className="msg__meta">
              {/*
                «Ответить» живёт В СТРОКЕ С ЧАСАМИ, а не всплывающей панелью.
                Панель поверх пузыря перекрывает соседнее сообщение — то самое,
                которое человек и читает, решая, отвечать ли. Здесь место уже
                есть, и кнопка проявляется по наведению, не занимая внимания
                постоянно.
              */}
              {onReply && !isNote && (
                <button
                  type="button"
                  className="msg__reply-btn"
                  onClick={() => onReply(msg)}
                  aria-label="Ответить на это сообщение"
                  title="Ответить на это сообщение"
                >
                  Ответить
                </button>
              )}
              {formatClock(msg.created_at)}
              {showsDelivery && <DeliveryStatusIcon status={msg.delivery_status} note={isNote} />}
            </span>
            {showsDelivery && msg.delivery_status === "dismissed" && (
              <span className="msg__failed-note msg__failed-note--dismissed">
                Не отправлено · снято
              </span>
            )}
            {kind === "bot" && msg.sender_type === "system" && msg.delivery_status === "dismissed" && (
              // Вопрос системы, который не дошёл: долга нет
              // (`services/messages.py::undelivered_status`), кнопок нет — повторять
              // его некому. Подпись нужна наблюдателю: иначе в ленте вопрос «есть»,
              // а клиент его не видел. Пузырь бота при `dismissed` — как раньше.
              <span className="msg__failed-note msg__failed-note--dismissed">
                Не доставлено{msg.delivery_error ? ` · ${msg.delivery_error}` : ""}
              </span>
            )}
            {showsDelivery && msg.delivery_status === "failed" && (
              <span className="msg__failed-note">
                {failedText}
                {onRetry && (
                  <>
                    {" · "}
                    <button type="button" className="msg__retry" onClick={() => onRetry(msg)}>
                      Повторить
                    </button>
                  </>
                )}
                {/*
                  ⚠ «СНЯТЬ» — ЕДИНСТВЕННЫЙ ВЫХОД, КОГДА ПОВТОР НЕ ПОМОГАЕТ
                  (жалоба владельца 08.09: «статус „не отправлено“ не
                  пропадает»). Красную метку диалога держит само наличие
                  неотправленного, и снять её можно было только удачным
                  повтором. А повтор помогает не всегда: канал отвалился,
                  диалог закрылся, текст устарел. Живой случай: оператор не
                  стал повторять, набрал тот же текст заново и отправил новым
                  сообщением — оно ушло, а метка осталась навсегда.

                  Кнопка показывается только у СЕРВЕРНОГО сообщения: у
                  местного (POST не дошёл) рядом стоит «Удалить», и два
                  действия с одним смыслом путали бы.
                */}
                {onDismiss && !isLocalTempMessage(msg) && (
                  <>
                    {" · "}
                    <button type="button" className="msg__retry" onClick={() => onDismiss(msg)}>
                      Снять
                    </button>
                  </>
                )}
                {onDiscard && isLocalTempMessage(msg) && (
                  <>
                    {" · "}
                    <button type="button" className="msg__retry" onClick={() => onDiscard(msg)}>
                      Удалить
                    </button>
                  </>
                )}
              </span>
            )}
          </div>
        </div>
      )}
    </>
  );
}

/**
 * ⚠ ПУЗЫРЬ ПЕРЕРИСОВЫВАЕТСЯ ТОЛЬКО КОГДА ИЗМЕНИЛСЯ САМ.
 *
 * До этой обёртки любое состояние панели ленты перерисовывало ВСЕ
 * отрисованные пузыри — а их до тридцати четырёх при девяти-десяти видимых
 * (`overscan`). Пузырь тяжёлый: цитата, вложения, кандидаты в телефоны,
 * меню действий.
 *
 * ⚠ БЕЗ СТАБИЛЬНЫХ КОЛБЭКОВ ЭТА ОБЁРТКА БЕСПОЛЕЗНА. `onRetry`, `onDiscard` и
 * `onDeleteNote` зависели от ОБЪЕКТОВ мутаций, а те пересоздаются на каждом
 * рендере; пропс всегда «изменялся». Стабилизация сделана в `ChatThreadPane`,
 * и порядок здесь обязателен — сначала она, потом это.
 *
 * Сравнение поверхностное, по умолчанию: `msg` и `prev` приходят из кэша
 * запросов и меняют ссылку только при настоящем изменении. Своё сравнение
 * писать НЕЛЬЗЯ: у строк офлайн-очереди меняется `delivery_status`, и
 * сравнение «по msg.id» пропустило бы смену галочки на крестик.
 */
export const MessageBubble = memo(MessageBubbleView);
