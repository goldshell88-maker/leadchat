/**
 * Часы города клиента: «23:40». Тикают сами, пока карточка открыта.
 *
 * ЗАЧЕМ ВООБЩЕ ЧАСЫ. Требование владельца от 11 августа: «хочу, чтобы после
 * установления города показывалось время города, по которому пишет клиент».
 * Смысл ровно один — чтобы диспетчер не набрал номер в три ночи. В России
 * одиннадцать часовых поясов, и от Керчи до Петропавловска девять часов
 * разницы: без подсказки это считают в уме и ошибаются.
 *
 * ПОЧЕМУ СЧИТАЕМ ЗДЕСЬ, А НЕ БЕРЁМ ГОТОВОЕ ВРЕМЯ С СЕРВЕРА. Сервер отдаёт
 * IANA-имя пояса, а не время: время, посчитанное на сервере, замерзает на
 * момент ответа, и открытая полдня карточка показывала бы утро вечером.
 *
 * ПОЧЕМУ 20 СЕКУНД, А НЕ МИНУТА. Минутный интервал не выровнен по границе
 * минуты, и в худшем случае показанное время отстаёт на неё целиком —
 * «23:59» в полночь. Двадцать секунд ограничивают отставание третью минуты и
 * ничего не стоят: один setState на карточку.
 */
function useCityClock(tz: string | null | undefined): string | null {
  const [now, setNow] = useState(() => Date.now());
  useEffect(() => {
    if (!tz) return;
    const id = window.setInterval(() => setNow(Date.now()), 20_000);
    return () => window.clearInterval(id);
  }, [tz]);
  return useMemo(() => {
    if (!tz) return null;
    try {
      return new Intl.DateTimeFormat("ru-RU", {
        timeZone: tz,
        hour: "2-digit",
        minute: "2-digit",
      }).format(new Date(now));
    } catch {
      // Незнакомое движку имя пояса — молчим и показываем один город.
      // Intl бросает RangeError, и уронить им карточку клиента было бы
      // худшим из возможных исходов: без карточки оператор не видит телефон.
      return null;
    }
  }, [tz, now]);
}

/**
 * ОДНА серая строка под названием объявления: «12 000 ₽ · Керчь · 23:40 у клиента».
 *
 * БЫЛО ТРИ СТРОКИ, СТАЛО ДВЕ (правка 9). Цена жила в одной строке с названием,
 * город — в отдельной под ним, и блок «Объявление» занимал столько же места,
 * сколько личность клиента. Оператор смотрит сюда раз за диалог — понять, о
 * какой технике речь и не ночь ли у клиента; трёх строк это не стоит.
 *
 * Отдельный компонент, а не кусок разметки: у него свой таймер, а хук нельзя
 * звать после ранних `return` карточки.
 *
 * ПУСТЫЕ ЧАСТИ ПРОСТО ВЫПАДАЮТ. «Цена: — · Город: —» приучает не читать эту
 * строку, и тогда она не сработает там, где нужна. Пояса нет (город не в
 * справочнике) — показываем город без времени: угаданный час хуже
 * отсутствующего.
 */
function ItemFactsLine({ item }: { item: ItemRef }) {
  const clock = useCityClock(item.city_tz);
  const city = item.city_name ?? item.city_slug;
  const parts = [item.price, city, clock ? `${clock} у клиента` : null].filter(
    Boolean,
  );
  if (parts.length === 0) return null;
  return (
    <Text fz="sm" c="var(--lc-text-2)">
      {/* Незнакомый справочнику город показывается своим слагом («kerch-2»):
          это читаемо и сразу видно, что справочник надо пополнить. Регион — в
          подсказке у всей строки: вешать его на отдельный span значило бы
          собирать строку из кусков ради атрибута, который читают мышью. */}
      <span title={item.city_region ?? undefined}>{parts.join(" · ")}</span>
    </Text>
  );
}

/**
 * Мера доверия к тому, что эта карточка — ОДИН человек (требование владельца 6
 * от 11 августа: «не связываются клиенты, если один и тот же пишет на разные
 * аккаунты»).
 *
 * ЧТО НА САМОМ ДЕЛЕ ПРОИСХОДИТ. Связываются, и связывались всегда: карточка
 * клиента ключуется парой «канал + `author_id` Авито» БЕЗ нашего аккаунта, и
 * одно и то же число, пришедшее с двух наших аккаунтов, попадает в одну
 * строку. Владелец видел не отсутствие механизма, а его невидимость.
 *
 * ПОЧЕМУ ПОКАЗАТЬ ЭТО ФАКТОМ НЕЛЬЗЯ. Авито нигде не обещает, что `author_id`
 * общий для разных аккаунтов: в спецификации у `Chat.users[].id` написано
 * ровно «Обратите внимание на хэширование», и больше ничего. Если
 * идентификатор свой у каждого аккаунта, совпадение чисел — это столкновение
 * двух РАЗНЫХ людей, и в карточку съезжаются чужая переписка и чужой телефон.
 *
 * ПОЧЕМУ ЭТО СТОИТ ПОД ТЕЛЕФОНОМ, А НЕ В КОНЦЕ БЛОКА. Худшее последствие
 * ошибочной склейки — не перепутанный список диалогов, а ЗВОНОК НЕ ТОМУ
 * ЧЕЛОВЕКУ: номер в карточке мог прийти с другого канала. Предупреждение
 * обязано стоять там, где принимают решение звонить.
 *
 * ЭТО ПРО АВТОМАТИКУ, А НЕ ПРО РУЧНОЕ ОБЪЕДИНЕНИЕ. Ручное живёт рядом, в
 * `ClientMergePanel`, и говорит своими словами: связь, установленную человеком,
 * нельзя объяснять словами «совпал идентификатор Авито».
 */
function ClientLinkNote({ client }: { client: ClientRef }) {
  // Поля нет вовсе — так выглядит ответ сервера до этой выкатки и старый кадр
  // WS. Молчим: «связей не найдено» и «не спрашивали» — разные вещи.
  if (!client.link_confidence) return null;
  const confirmed = client.link_confidence === "confirmed";
  return (
    <div className="card-field">
      <Text
        fz="sm"
        fw={500}
        c={confirmed ? "var(--lc-text-1)" : "var(--lc-warning-text)"}
      >
        {confirmed
          ? "Этот же человек писал и на другой наш канал"
          : "Возможно, этот же человек писал и на другой наш канал"}
      </Text>
      <Text fz="xs" c="var(--lc-text-3)">
        {confirmed
          ? "Подтверждено: с обоих каналов пришёл один и тот же телефон."
          : "Совпал только идентификатор Авито, а Авито не обещает, что он общий для разных аккаунтов."}
      </Text>
      {/* Единственный сигнал ЛОЖНОЙ склейки, который у нас сегодня есть, — и
          он говорит громче самой склейки: «возможно, тот же» человек читается
          как «скорее всего, тот же», а несовпавший номер — это довод против.

          Рисуется по своему полю, не глядя на уверенность, хотя сервер обе
          отметки разом сегодня не ставит (`_apply_phone_evidence`: совпадение
          снимает спор, а после `confirmed` спор уже не заводится — второй
          номер у одного человека в ремонте техники обычное дело, «звоните
          жене»). Это не описание существующего состояния, а отказ повторять
          правило сервера на клиенте: разъедутся они молча, и потеряется
          именно предупреждение. */}
      {client.link_phone_conflict && (
        <Text fz="xs" fw={500} c="var(--lc-warning-text)">
          Телефоны с разных каналов не совпали — проверьте, тот ли это человек,
          прежде чем звонить.
        </Text>
      )}
    </div>
  );
}

/**
 * «Писал ещё на канал: Тимофей» — строка в блоке «Клиент».
 *
 * ЗАЧЕМ. Сервер считал историю клиента с самого начала (`client_history`,
 * `client_conversations_count`) и не показывал её нигде — дефект аудита
 * SCEN-14. Диспетчер видел список прошлых диалогов и не понимал, что часть из
 * них пришла на ДРУГОЙ наш аккаунт: у заказчика их девять, и названы они по
 * людям («Тимофей», «Дамир»).
 *
 * ПЕРЕЧИСЛЯЮТСЯ ТОЛЬКО ЧУЖИЕ КАНАЛЫ, БЕЗ ТЕКУЩЕГО. Иначе строку пришлось бы
 * читать вместе с шапкой ленты, чтобы понять, какой из перечисленных открыт
 * сейчас; слово «ещё» отвечает на это само.
 *
 * НЕТ ВТОРОГО КАНАЛА — НЕТ И СТРОКИ. «Каналы: Тимофей» у каждого второго
 * клиента приучает пролистывать это место, и тогда строка не сработает там,
 * где она нужна.
 *
 * СВОДКИ МОЖЕТ НЕ БЫТЬ: ответ сервера до этой выкатки её не несёт, а карточка
 * обязана пережить рассинхрон фронта и бэкенда между выкатками.
 */
function OtherChannelsLine({
  summary,
  currentAccountId,
}: {
  summary: ClientHistorySummary | undefined;
  currentAccountId: string;
}) {
  const others = (summary?.channels ?? []).filter(
    (c) => c.id !== currentAccountId,
  );
  if (others.length === 0) return null;
  return (
    <Text fz="sm" c="var(--lc-text-1)">
      {others.length === 1 ? "Писал ещё на канал: " : "Писал ещё на каналы: "}
      {others.map((c) => c.title).join(", ")}
    </Text>
  );
}

/** Телефон подсвечивается на 2 с в момент появления (11 §2.4, WS conversation:updated). */
function usePhoneHighlight(phone: string | null | undefined): boolean {
  const prev = useRef<string | null | undefined>(phone);
  const [hot, setHot] = useState(false);
  useEffect(() => {
    const appeared = !prev.current && Boolean(phone);
    prev.current = phone;
    if (!appeared) return;
    setHot(true);
    const t = window.setTimeout(() => setHot(false), 2000);
    return () => window.clearTimeout(t);
  }, [phone]);
  return hot;
}

