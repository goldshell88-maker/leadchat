/**
 * Телефон клиента ГЛАЗАМИ, а не одиннадцатью цифрами подряд (дефект аудита 17).
 *
 * ЧТО БЫЛО. Карточка и шапка ленты показывали ровно то, что лежит в базе:
 * «+79125550177». Клиент в том же диалоге писал свой номер по-человечески —
 * «+7 912 555-01-77», — и диспетчер сверял одиннадцать слипшихся цифр с
 * читаемыми глазами, а потом ещё и диктовал их мастеру вслух. Ошибка в одной
 * цифре здесь стоит выезда не по адресу.
 *
 * ФОРМАТИРУЕТСЯ ТОЛЬКО ЗНАКОМАЯ ФОРМА, всё остальное отдаётся как пришло.
 * Сервер нормализует номер к `+7XXXXXXXXXX` (`extract_phone`,
 * app/services/inbound.py: 10–11 цифр → `+7` + десять). Но обещание нормализации
 * живёт на сервере, а не в типе, и если завтра туда попадёт городской номер,
 * иностранный или мусор из ручного ввода — нарезать его по русской маске
 * значило бы ПОКАЗАТЬ НЕ ТОТ НОМЕР. Молча вернуть исходную строку хуже не
 * делает: было нечитаемо — останется нечитаемо.
 *
 * КОПИРУЕТСЯ И ЗВОНИТСЯ ПО-ПРЕЖНЕМУ ИСХОДНОЕ ЗНАЧЕНИЕ (см. ClientCardPane):
 * `tel:` и буфер обмена уезжают в набиратель, CRM и мессенджер, а туда пробелы
 * и дефисы лучше не носить. Пробел — только для глаз.
 */

/** `+7` и ровно десять цифр — единственная форма, которую мы умеем разбирать. */
const RU_E164 = /^\+7(\d{3})(\d{3})(\d{2})(\d{2})$/;

export function formatPhone(phone: string): string {
  const m = RU_E164.exec(phone.trim());
  return m ? `+7 ${m[1]} ${m[2]}-${m[3]}-${m[4]}` : phone;
}
