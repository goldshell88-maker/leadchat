import { useEffect, useRef, useState } from "react";
import { Text, TextInput } from "@mantine/core";
import { ApiError } from "@/shared/api/http";
import { toast } from "@/shared/ui/toast";
import { useSetClientName } from "./clientApi";
import "./client-card.css";

/**
 * Имя клиента — РЕДАКТИРУЕМЫМ полем (требование заказчика от 13 августа).
 *
 * ЧТО БЫЛО. Имя приходило только из профиля Авито и печаталось строкой. А профиль
 * человек заводил один раз и мог назвать как угодно: «Ак», «Продам всё», пусто. В
 * разговоре диспетчер узнаёт настоящее имя — и деть его было некуда, кроме заметки,
 * которую не видно ни в списке чатов, ни в заявке.
 *
 * ПОЧЕМУ ССЫЛКА, А НЕ ВСЕГДА ОТКРЫТОЕ ПОЛЕ — как у телефона: пустой инпут в карточке
 * читается как незаполненная форма и просит, чтобы в него что-то ввели, плюс ловит
 * случайные нажатия при прокрутке.
 *
 * ⚠ ПУСТОЕ ЗНАЧЕНИЕ РАЗРЕШЕНО, И ЭТО НЕ НЕДОСМОТР. «Ак» хуже, чем ничего: под пустым
 * именем карточка честно показывает «Клиент». Кнопка «Сохранить» здесь НЕ выключается
 * на пустом поле — в отличие от телефона, где пустая строка не значит ничего.
 */
export function ClientNameField({
  clientId,
  convId,
  name,
  fallback,
  editable,
  showName,
  className,
}: {
  clientId: string;
  convId: string | null;
  name: string | null;
  /** Что показать вместо имени, когда его нет, — «Клиент». */
  fallback: string;
  editable: boolean;
  /**
   * Печатать ли САМО ИМЯ рядом с кнопкой.
   *
   * ⚠ ПО УМОЛЧАНИЮ НЕТ, И ЭТО ЧУЖОЕ РЕШЕНИЕ, КОТОРОЕ МЫ НЕ ОТМЕНЯЕМ. Правка 10
   * убрала имя из карточки: на широком экране оно уже стоит в шапке ленты, в
   * трёхстах пикселях отсюда, и печатать его дважды — тот самый дубль, из-за
   * которого всю карточку и переделывали. Кнопка «изменить имя» дублем не
   * является: это действие, а не повтор значения.
   *
   * Ниже 768px карточка ложится поверх шапки, имени на экране не остаётся
   * вовсе — там оно печатается (`showName`), и ровно за это отвечает
   * `isMobile` в `ClientCardPane`.
   */
  showName?: boolean;
  /** Класс на обёртку: шапка ленты и карточка набирают имя по-разному. */
  className?: string;
}) {
  const [editing, setEditing] = useState(false);
  const [value, setValue] = useState("");
  const [error, setError] = useState<string | null>(null);
  const inputRef = useRef<HTMLInputElement>(null);
  /** Escape закрыл поле — уход фокуса после него сохранять не должен. */
  const отменено = useRef(false);
  const save = useSetClientName(clientId, convId);

  useEffect(() => {
    if (editing) inputRef.current?.focus();
  }, [editing]);

  const open = () => {
    setValue(name ?? "");
    setError(null);
    отменено.current = false;
    setEditing(true);
  };

  const submit = () => {
    save.mutate(value.trim(), {
      onSuccess: (result) => {
        setEditing(false);
        // Молчим, когда ничего не изменилось: тост на повторное «Сохранить» с тем же
        // текстом приучает не читать тосты.
        if (result.changed) toast.success(result.name ? "Имя сохранено" : "Имя очищено");
      },
      onError: (e) => {
        // Текст сервера показывается как есть (01 §1.3): он говорит, что не так,
        // а «Ошибка сохранения» не говорит ничего.
        setError(e instanceof ApiError ? e.message : "Не получилось сохранить. Попробуйте ещё раз.");
      },
    });
  };

  if (editing) {
    return (
      <div className="card-name-edit">
        <TextInput
          ref={inputRef}
          size="xs"
          value={value}
          error={error}
          placeholder="Как зовут клиента"
          aria-label="Имя клиента"
          onChange={(e) => {
            setValue(e.currentTarget.value);
            setError(null);
          }}
          onKeyDown={(e) => {
            if (e.key === "Enter") {
              e.preventDefault();
              submit();
            }
            // Escape закрывает ПОЛЕ, а не карточку: без остановки всплытия тот же
            // Escape уводил бы из диалога, и набранное пропадало бы вместе с экраном.
            if (e.key === "Escape") {
              e.preventDefault();
              e.stopPropagation();
              отменено.current = true;
              setEditing(false);
            }
          }}
          onBlur={() => {
            // Escape уже закрыл поле — сохранять нечего и незачем.
            if (отменено.current) {
              отменено.current = false;
              return;
            }
            if (value.trim() === (name ?? "").trim()) {
              setEditing(false); // ничего не меняли — молча закрываем
              return;
            }
            submit();
          }}
        />
        {/*
          ⚠ КНОПОК ЗДЕСЬ БОЛЬШЕ НЕТ (28.08, просьба владельца: «убери кнопку
          сохранить, это лишнее нажатие»).

          Правка имени — одно короткое поле, и подтверждать её вторым нажатием
          незачем: Enter сохраняет, уход из поля сохраняет, Escape отменяет.
          Это те же три жеста, которыми человек и так пользуется, — просто
          теперь им не нужно искать кнопку глазами.

          ⚠ УХОД ИЗ ПОЛЯ СОХРАНЯЕТ, А НЕ ОТМЕНЯЕТ. Обратное поведение молча
          теряло бы набранное: человек вписал имя, отвлёкся на ленту — и всё
          пропало без единого слова. Потерять работу тише, чем сохранить
          лишнее, нельзя: лишнее видно и правится, потерянное — нет.
        */}
        {error === null && (
          <span className="card-name-edit__hint">Enter — сохранить · Esc — отменить</span>
        )}
      </div>
    );
  }

  // Ни имени, ни правки — рисовать нечего. Пустой блок оставлял бы в карточке
  // необъяснимый отступ у наблюдателя, которому правка не положена.
  if (!showName && !editable) return null;

  /*
   * ⚠ САМО ИМЯ И ЕСТЬ КНОПКА (28.08, просьба владельца: «изменять имя без
   * кнопки изменить, а просто наводя на поле имени»).
   *
   * Здесь стояла отдельная ссылка «изменить» рядом со значением. Она отнимала
   * место в шапке и в карточке, а главное — заставляла целиться в мелкий текст
   * сбоку вместо того, чтобы нажать на то, что правишь. Теперь наведение
   * подсвечивает само имя, нажатие открывает поле.
   *
   * Пустое имя тоже нажимается: под ним стоит «Клиент», и без этого вписать
   * имя было бы негде. Подпись для скринридера говорит разное в двух случаях —
   * «изменить» и «вписать» — потому что действия разные.
   *
   * Без права правки имя остаётся обычным текстом: наведение на неактивный
   * элемент обещает действие, которого не будет.
   */
  if (!editable) {
    return (
      <div className={className ? `card-name ${className}` : "card-name"}>
        {showName && <Text className="card-section__name">{name ?? fallback}</Text>}
      </div>
    );
  }

  return (
    <div className={className ? `card-name ${className}` : "card-name"}>
      <button
        type="button"
        className="card-name__trigger"
        onClick={open}
        /*
         * ⚠ ПОЛНОЕ ИМЯ В ПОДСКАЗКЕ (разбор дизайна 28.08). В шапке ленты имя
         * теперь обрезается многоточием — иначе длинное название канала-клиента
         * разгоняло шапку на две строки и съедало переписку. Обрезка без
         * способа прочитать целиком — тупик, поэтому подсказка называет имя, а
         * приглашение нажать идёт следом.
         */
        title={name ? `${name} — нажмите, чтобы изменить` : "Нажмите, чтобы вписать имя"}
        aria-label={name ? `Изменить имя клиента: ${name}` : "Вписать имя клиента"}
      >
        {/*
          ⚠ БЕЗ ЗНАЧКА КАРАНДАША (28.08, уточнение владельца: «изменить без
          карандаша, просто тык по полю»). Здесь он был и появлялся при
          наведении. Значок рядом с именем сдвигал строку и читался как второй
          элемент — а имя и так подсвечивается под курсором, этого достаточно,
          чтобы понять, что сюда можно нажать.
        */}
        <span className="card-section__name">{name ?? fallback}</span>
      </button>
    </div>
  );
}
