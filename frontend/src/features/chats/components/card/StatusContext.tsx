import { zonedTimeTitle } from "@/shared/lib/formatTime";
import { formatMoscow } from "@/shared/lib/moscowTime";

/**
 * Строка под полем «Статус»: «Уже 12 мин», «В очереди 3 мин» (docs/38 §5).
 *
 * ЗАЧЕМ ОНА. Статус отвечает на вопрос «что с диалогом», но не на «сколько это
 * длится». Ответ у системы есть — `status_since` и `offered_at` — и до docs/38
 * не показывался нигде: чтобы узнать, что диалог висит «в работе» вторые
 * сутки, надо было открыть журнал.
 *
 * ОНА НЕ ПОВТОРЯЕТ НИ СТАТУС, НИ ОТВЕТСТВЕННОГО (правка 10 от 12 августа).
 *
 * Было: «Ничей» и «В работе у вас · 12 мин». Прямо над этой строкой стоит поле
 * «Статус» со словом «В работе», а прямо под ней — поле «Ответственный» со
 * словом «Вы» или «Без ответственного». То есть три строки подряд говорили
 * одно и то же трижды, причём разными словами: «Ничей» сверху и «Без
 * ответственного» снизу — это одно значение, показанное дважды, и читатель
 * ищет между ними разницу, которой нет.
 *
 * Осталось только то, чего в соседних полях НЕТ: длительность и дата закрытия.
 * Глаголы «В очереди» и «Закрыт» — не повтор статуса, а то, без чего число или
 * дата рядом не читаются: «12 авг» само по себе не факт.
 *
 * ДЛИТЕЛЬНОСТЬ СЧИТАЕТСЯ ОТ `status_since`, А НЕ ОТ `updated_at`. Второй
 * двигает любое сообщение, любая заметка, любое обогащение карточки клиента —
 * строка на нём показывала бы время с последнего сообщения. Это другая
 * величина, и выглядела бы она так же правдоподобно.
 *
 * «СЕЙЧАС» ПРИХОДИТ СНАРУЖИ. Посчитай мы `Date.now()` внутри — значение
 * замёрзло бы на первой отрисовке, и «12 мин» висело бы, пока оператор сидит в
 * диалоге час. Ровно этой ошибкой болел счётчик ожидания в шапке ленты, пока
 * ему не завели тикающие часы.
 */
export function StatusContext({
  conversation,
  now,
}: {
  conversation: ConversationDetailDto;
  now: number;
}) {
  // `meId` отсюда ушёл вместе с веткой «Отложен»: он был нужен ровно ей —
  // согласовать глагол («отложили вы» / «отложил Иванов»).
  const ctx = contextText(conversation, now);
  if (!ctx) return null;
  return (
    /*
     * ПОДПИСЬ К МОМЕНТУ — ИСПОЛНЕНИЕ УЖЕ ЗАПИСАННОГО ПРАВИЛА (`formatTime.ts`):
     * «лечится не сменой пояса, а ПОДПИСЬЮ, где названы ОБА пояса сразу».
     *
     * Найдено проверкой боя 14 августа: в одном диалоге «Ход диалога» печатал
     * «Закрыт 12 авг, 13:08» по Москве, а лента сообщений в двух сантиметрах
     * от него — местное время. Ни одно из двух чисел не подписано, и человек
     * во Владивостоке видит на одном экране два времени одного события,
     * расходящиеся на шесть часов, без единого слова о том, почему.
     *
     * Пояс при этом НЕ меняется: московская отчётность — записанное решение
     * (`moscowTime.ts`), и «Закрыт» относится к ней. Меняется только то, что
     * теперь можно навести и прочитать оба.
     */
    <Text fz="xs" c="var(--lc-text-3)" title={zonedTimeTitle(ctx.at)}>
      {ctx.text}
    </Text>
  );
}

/** «12 мин», «3 ч 20 мин», «2 дн 4 ч» — те же ступени, что у `inbox.format_wait`
 *  на сервере. Второй формат длительности в продукте завести нельзя: «12 мин» в
 *  одном месте и «12 минут» в другом читаются как две разные величины. */
function humanDuration(fromIso: string | null | undefined, now: number): string | null {
  if (!fromIso) return null;
  const started = Date.parse(fromIso);
  if (Number.isNaN(started)) return null;
  const seconds = Math.floor((now - started) / 1000);
  if (seconds < 60) return null; // меньше минуты — «0 мин» хуже, чем ничего
  const minutes = Math.floor(seconds / 60);
  if (minutes < 60) return `${minutes} мин`;
  const hours = Math.floor(minutes / 60);
  const restMin = minutes % 60;
  if (hours < 24) return restMin ? `${hours} ч ${restMin} мин` : `${hours} ч`;
  const days = Math.floor(hours / 24);
  const restHours = hours % 24;
  return restHours ? `${days} дн ${restHours} ч` : `${days} дн`;
}

/**
 * Строка контекста и — ОТДЕЛЬНО — момент, о котором она говорит.
 *
 * Момент возвращается рядом с текстом, а не вычисляется вторым разом снаружи:
 * подпись обязана относиться ровно к тому времени, которое напечатано. Две
 * копии условия «это ветка закрытого» разъехались бы при первой же новой
 * ветке, и подсказка стала бы врать молча — хуже, чем её отсутствие.
 *
 * `at: null` — строка есть, а печатного момента в ней нет (длительности вроде
 * «Уже 12 мин» считаются от «сейчас» и подписи не требуют).
 */
function contextText(
  conv: ConversationDetailDto,
  now: number,
): { text: string; at: string | null } | null {
  const since = humanDuration(conv.status_since, now);

  switch (conv.status) {
    case "new": {
      // У ничьего диалога важно не «сколько он новый», а сколько КЛИЕНТ ждёт
      // в очереди: по этому числу решают, брать ли его сейчас. Считается от
      // `offered_at` — той же отметки, по которой очередь и сортируется.
      //
      // ДИАЛОГА НЕТ В ОЧЕРЕДИ — СТРОКИ НЕТ ВОВСЕ. Раньше здесь стояло «Ничей»,
      // но соседнее поле «Ответственный» говорит ровно это же и своими
      // словами; см. разбор наверху файла.
      if (!conv.in_inbox) return null;
      const waiting = humanDuration(conv.offered_at, now);
      return { text: waiting ? `В очереди ${waiting}` : "В очереди", at: null };
    }
    case "in_progress":
    case "waiting_client":
      // Только длительность: «в работе» и «ждём ответа» уже написаны в поле
      // «Статус» строкой выше, а кто держит диалог — в поле «Ответственный»
      // строкой ниже. Меньше минуты — строки нет: «0 мин» хуже пустоты.
      return since ? { text: `Уже ${since}`, at: null } : null;
    // ЗДЕСЬ БЫЛА ВЕТКА `snoozed`: «Вернётся 14 авг 10:00 по Москве · отложил
    // Иванов · перезвонит после отпуска». Снята 12 августа вместе со всей
    // отложкой — решением владельца.
    case "closed": {
      // У закрытого длительность не нужна — нужно КОГДА.
      //
      // ИТОГА ЗДЕСЬ НЕТ, И ТЕПЕРЬ ЕГО НЕТ НИГДЕ. Сперва (правка 9 от
      // 12 августа) он ушёл отсюда в пользу блока «Чем закончилось» — два
      // показа одного значения в трёх строках друг от друга. В тот же день
      // владелец отказался от исхода целиком, и блока тоже не стало.
      //
      // ДАТЫ НЕТ — СТРОКИ НЕТ ВОВСЕ. Голое «Закрыт» слово в слово повторяло бы
      // само поле «Статус» строкой выше и не добавляло ни одного факта. Пустая
      // строка честнее: у диалога, заведённого до появления `status_since`,
      // даты закрытия мы действительно не знаем.
      if (!conv.status_since) return null;
      return { text: `Закрыт ${formatMoscow(conv.status_since)}`, at: conv.status_since };
    }
    default:
      return null;
  }
}
