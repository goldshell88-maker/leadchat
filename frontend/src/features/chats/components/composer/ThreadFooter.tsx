import { usePermissions } from "@/shared/auth/usePermissions";
import { useSessionStore } from "@/shared/stores/sessionStore";
import { useInboxStore } from "@/shared/stores/inboxStore";
import { useChatUiStore } from "@/shared/stores/chatUiStore";
import { участникиИзвестны, чужойЖивой, яУчастник } from "../../lib/participation";
import { ForeignDialogBar } from "./ForeignDialogBar";
import { InboxClaimedBanner, InboxDecisionBar } from "../../inbox/InboxDecisionBar";
import { TransferBar } from "../thread/TransferBar";
import { useIsQueued } from "../../inbox/useIsQueued";
import { Composer } from "./Composer";
import "./composer.css";

/**
 * Низ панели выбирается одной функцией (03 §5.3, 11 §2.5):
 *  - admin/manager (`messages:send`) — полный композер;
 *  - head (`notes:write` без `messages:send`) — плашка «Режим просмотра» +
 *    композер ТОЛЬКО заметок (⚡ и 📎 скрыты);
 *  - observer — ничего: лента идёт до низа.
 *
 * Очередь «Входящие» (7.1) добавляет ветку ВНУТРИ права `messages:send`: пока
 * диалог не принят, вместо поля ввода — «Принять диалог» / «Отклонить», а если
 * его успел забрать коллега — плашка с его именем. Руководителя и наблюдателя
 * это не касается: принимать они не могут, и низ их панели не меняется вовсе.
 *
 * НИЖНЯЯ ПЛАШКА — ЕДИНСТВЕННОЕ МЕСТО ПЕРВИЧНОГО ДЕЙСТВИЯ (перекройка от 12
 * августа). До неё «принять» предлагалось в трёх местах сразу: здесь, кнопкой
 * «Взять в работу» в правой карточке и селектом «Статус» там же. Три способа
 * сделать одно и то же — это не свобода, а лишний выбор перед каждым
 * диалогом, и названия у них расходились («Принять диалог» против «Взять в
 * работу»).
 *
 * Правило теперь простое и проверяется сторожем `ThreadFooterClaim.test.tsx`:
 * пока диалог ждёт решения, внизу стоит «Принять диалог» и поля ввода нет
 * вовсе; как только он принят, плашка ПРЕВРАЩАЕТСЯ в поле ввода — то есть
 * место одно, и оно же показывает, что произошло.
 */
export function ThreadFooter({
  convId,
  conversation,
  detailFailed = false,
}: {
  convId: string;
  /*
   * Строка списка ГОДИТСЯ здесь наравне с деталью, и тип это признаёт.
   *
   * Низ панели читает у диалога ровно три поля — `transfer`, `status` и
   * данные клиента для подстановок, — и все три есть в строке списка. А
   * требуя деталь, он ждал отдельного запроса и всё это время не знал ни
   * статуса, ни передачи: над ЗАКРЫТЫМ диалогом стояло живое поле ввода,
   * оператор писал в него и получал 422 (жалоба владельца 22.08 про задержку
   * при открытии — это её вторая половина).
   */
  conversation?: ConversationDto;
  /**
   * Деталь диалога НЕ ЗАГРУЗИЛАСЬ — это третье состояние, и без него низ
   * панели врал. `conversation` необязателен с самого начала, но заведён он
   * был под ЗАГРУЗКУ: пусто сейчас, приедет через мгновение. Отказ выглядит
   * ровно так же — `undefined`, — и композер вставал над мёртвым диалогом.
   */
  detailFailed?: boolean;
}) {
  const { can } = usePermissions();
  const myId = useSessionStore((s) => s.user?.id) ?? null;
  const claimedNotice = useInboxStore((s) => s.claimedNotice);
  const queued = useIsQueued(convId, conversation);
  /*
   * Есть ли в этом диалоге неотправленный текст. Нужен ровно затем, чтобы
   * фоновые кадры не забирали поле ввода из-под набора (разбор — ниже, в
   * ветке очереди).
   */
  const естьНабранное = useChatUiStore(
    (s) => (s.drafts[convId]?.text ?? "").trim().length > 0,
  );

  /*
   * ⚠ ПРОВЕРКА БОЯ 14 АВГУСТА: открываем `/chats/not-a-uuid`, деталь падает с
   * 400 — и внизу стоит РАБОЧЕЕ поле ввода. Текст набирается, кнопка «Отправить»
   * живая (её `disabled` смотрит только на длину текста и вложения, про диалог
   * не знает вовсе), нажатие рисует пузырь сообщения, сервер отвечает отказом,
   * текст возвращается в поле. Ни одного слова о том, что писать некуда.
   *
   * Шапка ленты это состояние различала честно («Не получилось загрузить
   * диалог»), а низ панели ту же развилку просто не делал. Теперь делает —
   * и раньше всех прочих веток: без детали неизвестно ни право писать в этот
   * диалог, ни его статус, ни очередь, поэтому любая ветка ниже была бы
   * догадкой.
   */
  if (detailFailed) {
    return (
      <footer className="composer composer--blocked" aria-label="Панель отправки">
        <Text fz="sm" c="var(--lc-text-2)">
          Диалог недоступен — писать некуда.
        </Text>
      </footer>
    );
  }

  // Предложение передачи показывается ВЫШЕ всего остального и всем ролям:
  // получателю — с кнопками, передающему — как напоминание, что диалог всё
  // ещё за ним, руководителю — как объяснение, почему диалог числится за
  // одним, а обсуждают его двое.
  const transferBar = conversation?.transfer ? (
    <TransferBar conversation={conversation} />
  ) : null;

  if (can("messages:send")) {
    // Диалог забрали, пока оператор его читал (7.1 п.4) — нажимать больше не во что.
    if (claimedNotice?.convId === convId) {
      return <InboxClaimedBanner convId={convId} by={claimedNotice.by} />;
    }
    /*
     * ⚠ ОЧЕРЕДЬ ВАЖНЕЕ ПРЕДЛОЖЕНИЯ, И ПОРЯДОК ЗДЕСЬ БЫЛ ОБРАТНЫЙ (боевой
     * случай 28.08).
     *
     * Диалог в очереди — ничей: его берут кнопкой «Принять». Диалог с висящим
     * предложением — чей-то, и там нужен композер. Состояния взаимно
     * исключающие, но одновременно они всё-таки случались: возврат в очередь
     * не снимал предложение (починено в `inbox.return_to_queue`), и диалог
     * оказывался И в очереди, И с предложением.
     *
     * Тогда эта ветка выигрывала у очереди, кнопки «Принять» не было вовсе, и
     * диалог становился неберущимся: «его нельзя было принять и пришлось
     * закрывать». Владелец закрывал руками и искал заново.
     *
     * Теперь очередь спрашивается ПЕРВОЙ, а плашка остаётся над ней —
     * объяснением, откуда взялось предложение. Это второй замок: первый
     * (снятие предложения при возврате) уже не даёт такому состоянию
     * появиться, но строки, застрявшие до выкатки, живут в базе.
     */
    // Признак очереди — только слово сервера (см. useIsQueued); у диалогов до
    // 7.1 его нет вовсе, и они ведут себя ровно как раньше.
    if (queued) {
      return (
        <>
          {/* Без кнопок: принимать предложение не у кого — диалог ничей.
              Берут его «Принять диалог» полосы очереди ниже. */}
          {conversation?.transfer ? (
            <TransferBar conversation={conversation} actionable={false} />
          ) : null}
          <InboxDecisionBar convId={convId} />
          {/*
            ⚠ НЕДОПИСАННЫЙ ОТВЕТ ОСТАВЛЯЕТ ПОЛЕ ВВОДА НА МЕСТЕ (30.08).

            В очередь диалог возвращает не человек, а сервер: протух ключ
            присутствия, три минуты без пинга, свёрнутая вкладка, которой
            браузер придержал таймеры. Кадр `inbox:new` приезжает посреди
            набора, и раньше эта ветка молча забирала поле ввода: набранное
            исчезало с экрана, фокус падал на страницу, а дальше любая
            клавиша работала уже как команда — так и уезжали ответы не тем
            людям.

            Опасности в оставленном поле нет: отправка сама закрепит диалог
            за отправителем («ответил — значит принял», services/messages.py),
            ровно как кнопка «Принять» рядом. Пустой черновик поле не держит —
            там терять нечего, и панель решения остаётся одна, как задумано.
          */}
          {естьНабранное ? <Composer convId={convId} conversation={conversation} /> : null}
        </>
      );
    }
    if (transferBar) {
      // Полоса не ЗАМЕНЯЕТ поле ввода: пока предложение висит, диалог остаётся
      // за передающим, и он обязан иметь возможность ответить клиенту. Отними
      // мы у него композер — вышло бы ровно то, чего требование избегает:
      // диалог формально его, а написать нечем.
      return (
        <>
          {transferBar}
          <Composer convId={convId} conversation={conversation} />
        </>
      );
    }
    /*
     * ⚠ ЧУЖОЙ РАБОЧИЙ ДИАЛОГ: ВМЕСТО ПОЛЯ — «ВОЙТИ В ДИАЛОГ» (просьба владельца
     * 04.09: «кнопку войти в диалог сделай по аналогии, как сделано „Принять
     * диалог", с такой же защитой от написания текста, как и было раньше»).
     *
     * Разбор устройства — в шапке `ForeignDialogBar`. Здесь важны две границы.
     *
     * ⚠ ПЕРВАЯ: ПОКА УЧАСТНИКИ НЕИЗВЕСТНЫ, ЗАСЛОНА НЕТ. Строка списка их не
     * везёт вовсе, и деталь приезжает вторым запросом. Считай мы «нет поля
     * participants» за «меня там нет», вошедший на полсекунды терял бы поле
     * ввода при каждом открытии своего же диалога.
     *
     * ⚠ ВТОРАЯ: НЕДОПИСАННЫЙ ОТВЕТ ЗАСЛОН НЕ ТРОГАЕТ — тот же довод, что у
     * очереди выше. Кадр о смене ответственного приезжает посреди набора, и
     * подмена поля полосой унесла бы набранное вместе с фокусом.
     */
    /*
     * ⚠ ПЕРЕДАННЫЙ МНЕ ДИАЛОГ ЗАСЛОНА НЕ ВИДИТ НИКОГДА (обратная связь
     * сотрудника 05.09: «когда тебе передают диалог, нужно сделать 2 действия
     * вместо одного, чтобы его принять»).
     *
     * Разбор. Пока предложение висит, ответственный ещё ПРЕЖНИЙ — то есть
     * формально диалог чужой, и заслон по общему правилу верен. Но человеку
     * его сюда ПОЗВАЛИ: он пришёл принимать, а не заглянул. Требовать от него
     * сперва «войти», а потом «принять» — это спрашивать разрешения войти у
     * того, кто сам открыл дверь.
     *
     * Ветка `transferBar` выше и так возвращает композер, поэтому в бою этого
     * не видно; условие записано ЯВНО и застраховано сторожем, потому что
     * порядок веток здесь уже менялся дважды (28.08 очередь и предложение
     * поменялись местами), и следующая перестановка тихо вернула бы два
     * нажатия.
     */
    const мнеПередают =
      Boolean(conversation?.transferred_to_me) ||
      Boolean(myId && conversation?.transfer?.to?.id === myId);
    const заслон =
      !мнеПередают &&
      участникиИзвестны(conversation) &&
      чужойЖивой(conversation, myId) &&
      !яУчастник(conversation, myId) &&
      !естьНабранное;
    if (заслон) {
      return <ForeignDialogBar convId={convId} conversation={conversation} />;
    }
    return <Composer convId={convId} conversation={conversation} />;
  }

  if (can("notes:write")) {
    return (
      <>
        {transferBar}
        <div className="read-only-banner" role="status">
          <IconEye size={14} /> Режим просмотра — назначьте менеджера или передайте диалог
        </div>
        <Composer convId={convId} conversation={conversation} noteOnly />
      </>
    );
  }

  return transferBar;
}
