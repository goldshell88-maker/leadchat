import { Button, Text } from "@mantine/core";
import type { ConversationDto } from "@/shared/api/types";
import { подписьСотрудника } from "@/shared/lib/подписьСотрудника";
import { useEnterDialog } from "../../hooks/useConversationActions";
import "./composer.css";

/**
 * Чужой рабочий диалог: вместо поля ввода — полоса «Войти в диалог».
 *
 * ⚠ ПРОСЬБА ВЛАДЕЛЬЦА 04.09, ДОСЛОВНО: «кнопку „Войти в диалог" сделай по
 * аналогии, как сделано „Принять диалог", с такой же защитой от написания
 * текста, как и было раньше».
 *
 * ⚠ ЧТО ЗДЕСЬ БЫЛО И ПОЧЕМУ ВЕРНУЛОСЬ. До 03.09 тут стоял `ForeignDialogGuard`
 * с кнопкой «Всё равно написать»; 03.09 его сняли целиком — вход в чужой
 * диалог стал молчаливым и происходил САМ, от одного открытия экрана. Цена
 * выяснилась назавтра: диалог попадал в «Мои» без единого нажатия, и «Закрыть»
 * в этом списке закрывало разговор клиенту. Заслон возвращается, но действие в
 * нём теперь ОДНО и честное: войти.
 *
 * ⚠ ФОРМА — КАК У ОЧЕРЕДИ, И ЭТО НЕ ПОДРАЖАНИЕ. Полоса «Принять диалог» решает
 * ровно ту же задачу: диалог, в котором пока нельзя писать, и одно нажатие,
 * которое это меняет. Одинаковые задачи обязаны выглядеть одинаково — иначе
 * человек каждый раз заново разбирается, что от него хотят внизу экрана.
 *
 * ⚠ ПОЧЕМУ ПРЕДУПРЕЖДЕНИЕ ОСТАЛОСЬ СЛОВАМИ. Сообщение в Авито уходит клиенту
 * мгновенно и не отзывается. Это и есть причина, по которой поле закрыто, — и
 * называть её надо там же, где стоит запрет.
 */
export function ForeignDialogBar({
  convId,
  conversation,
}: {
  convId: string;
  conversation?: ConversationDto;
}) {
  const войти = useEnterDialog(convId);
  const хозяин = conversation?.assignee;

  return (
    <footer className="foreign-bar" aria-label="Диалог ведёт коллега">
      <Text fz="sm" c="var(--lc-text-2)" className="foreign-bar__hint">
        Диалог ведёт {подписьСотрудника(хозяин, "коллега")}. Клиент получит сообщение сразу, и
        отозвать его в Авито нельзя — поэтому поле ввода открывается нажатием.
      </Text>
      <div className="foreign-bar__actions">
        <Button
          color="lp"
          size="sm"
          loading={войти.isPending}
          disabled={войти.isPending}
          onClick={() => войти.mutate()}
        >
          Войти в диалог
        </Button>
      </div>
    </footer>
  );
}
