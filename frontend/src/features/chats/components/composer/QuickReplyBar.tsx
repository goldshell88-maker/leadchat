import { useEffect, useMemo, useState, type RefObject } from "react";
import { skipToken, useQuery } from "@tanstack/react-query";
import { подобрать, подходит } from "@/features/templates/rankByContext";
import { useTemplates } from "@/features/templates/useTemplates";
import { qk } from "@/shared/api/queryKeys";
import type { MessageDto, MessagesPage, TemplateDto } from "@/shared/api/types";
import "./composer.css";

/**
 * Быстрые ответы: короткий список подходящих, а не свалка всех.
 *
 * ⚠ ЧТО БЫЛО НЕ ТАК. Первая редакция показывала ВСЕ заготовки разом — «по
 * факту он вываливает все ответы, которые были». У диспетчера их полтора
 * десятка: полоса занимала три ряда над полем, и найти в ней нужную было не
 * быстрее, чем набрать руками. Список обязан быть коротким, иначе это не
 * подсказка, а второй экран.
 *
 * ⚠ ТОЛЬКО ВО ВРЕМЯ НАБОРА, И ЭТО ВТОРАЯ РЕДАКЦИЯ ПРАВИЛА (28.08, вечер).
 *
 * Сперва полоса показывалась и над ПУСТЫМ полем — подбирая ответы к последним
 * словам клиента. Владелец увидел это в работе и сказал прямо: «сейчас они
 * перекрывают диалоги, когда открываешь диалог… условно пишу „Здра" — только
 * тогда появляются подсказки».
 *
 * И он прав: над пустым полем подсказка никого не спрашивали — человек только
 * что открыл диалог и читает переписку, а ему на неё кладут список. Подсказка
 * уместна ровно тогда, когда её позвали: с первых букв ответа.
 *
 * Порядок при этом всё равно считается по словам КЛИЕНТА (`подобрать`): среди
 * подошедших под набранное первыми идут те, что ближе к его беде.
 *
 * ⚠ ENTER НЕ ТРОГАЕМ. Он отправляет сообщение, и перехватить его ради вставки
 * заготовки значит однажды отправить клиенту не то. Выбор — нажатием или
 * стрелками с Tab: обе в поле ввода не заняты.
 *
 * ⚠ КЛАВИШИ СЛУШАЕМ У САМОГО ПОЛЯ, А НЕ У ОКНА (разбор дизайна 28.08).
 *
 * Первая редакция вешала `keydown` на `window` в фазе ПЕРЕХВАТА — то есть
 * раньше любого обработчика цели, на всей странице. Последствия шире, чем
 * задумано: Tab из поиска по диалогам, из карточки клиента, из шапки — вместо
 * перевода фокуса вставлял заготовку в черновик; ↑ и ↓ переставали двигать
 * каретку в самом поле ввода; сочетания вроде Alt+↑ гасились вместе с
 * обычными. Полоса же почти всегда видна, так что и перехват был почти
 * всегда.
 *
 * Слушаем поле ввода, обычным всплытием: за пределами композера клавиши
 * работают как везде. Модификаторы пропускаем — они не наши.
 *
 * ⚠ У КАЖДОГО СВОИ (решение владельца). Общими заготовки не делаем: они
 * отражают манеру конкретного человека, и чужая фраза в своей ленте читается
 * как чужой голос. Список тот же, что у пикера, — «свои личные + все общие».
 */

/** Больше пяти строк — это уже не подсказка, а список. */
const МАКСИМУМ = 5;

/**
 * С какой буквы начинаем подсказывать.
 *
 * Одна буква совпадает почти со всем и превращает подсказку в помеху на первом
 * же нажатии. Две — это уже намерение: «Зд», «вы», «це».
 */
const МИНИМУМ = 2;
/** Сколько последних реплик клиента берём в расчёт. */
const РЕПЛИК = 3;

/**
 * Последние слова клиента — из УЖЕ ЗАГРУЖЕННОЙ ленты, без своего запроса.
 *
 * `enabled: false` означает «ничего не грузи, но подпишись на этот кэш»: ленту
 * держит панель диалога, а нам нужно лишь читать её и перерисовываться, когда
 * клиент напишет ещё раз. Свой запрос был бы вторым за теми же данными.
 *
 * Берём НЕСКОЛЬКО ПОСЛЕДНИХ, а не весь диалог: клиент начал с «здравствуйте,
 * ремонт телевизора», а спрашивает сейчас про цену — подсказывать надо про цену.
 */
function useClientSaid(convId: string, enabled: boolean): string[] {
  const { data } = useQuery<{ pages: MessagesPage[] }>({
    queryKey: qk.messages.list(convId),
    // `skipToken`, а не `enabled: false`: оба не грузят, но `enabled` без
    // `queryFn` — это ключ вообще без загрузчика, и react-query честно ругается
    // в консоль на каждый диалог. `skipToken` говорит то же самое словами,
    // которые библиотека понимает: «подписка есть, похода за данными нет».
    queryFn: skipToken,
  });
  return useMemo(() => {
    if (!enabled || !data) return [];
    const все: MessageDto[] = data.pages.flatMap((p) => p.items);
    return все
      .filter((m) => m.direction === "in" && (m.body ?? "").trim())
      .slice(-РЕПЛИК)
      .map((m) => m.body as string);
  }, [data, enabled]);
}

export function QuickReplyBar({
  convId,
  visible,
  typed,
  fieldRef,
  onPick,
  onActive,
}: {
  convId: string;
  /** Показывать ли вообще: это ответ клиенту, а не заметка. */
  visible: boolean;
  /**
   * ПОСЛЕДНЕЕ НАБРАННОЕ СЛОВО — не всё поле.
   *
   * Подсказка работает как автодополнение: слово и есть запрос, и выбор его
   * ЗАМЕНЯЕТ. Передавай мы всё поле, «Здра» + «Здравствуйте, чем помочь?»
   * склеилось бы в «Здра Здравствуйте, чем помочь?» — ровно то, на что
   * пожаловался владелец: «подсказки дописывают в начале слова».
   */
  typed: string;
  /**
   * Поле ввода композера: на нём и только на нём слушаются ↑ ↓ и Tab.
   *
   * Прежняя редакция слушала окно в фазе перехвата — и крала Tab у всей
   * страницы. Ref, а не глобальный слушатель: границы подсказки совпадают с
   * границами поля, к которому она относится.
   */
  fieldRef?: RefObject<HTMLTextAreaElement | null>;
  /**
   * Что вставит Tab прямо сейчас — чтобы поле могло дорисовать продолжение
   * серым (просьба владельца 28.08: «чтобы быстрые сообщения сами
   * автоматически заполнялись»).
   *
   * Отдаём ИМЕННО выбранную строку, а не первую подошедшую: человек ходит по
   * списку стрелками, и призрак в поле обязан показывать то же, что подсветка
   * в списке. Разойдись они — Tab вставил бы не то, что человек видит.
   */
  onActive?: (t: TemplateDto | null) => void;
  onPick: (t: TemplateDto) => void;
}) {
  const набрано = typed.trim();
  const clientSaid = useClientSaid(convId, visible);
  const { data } = useTemplates("all", visible);
  const все = useMemo(() => data?.items ?? [], [data]);

  const items = useMemo(() => {
    /*
     * Пусто или одна буква — молчим. Ничего не подошло — тоже молчим, а не
     * показываем «похожее», которого не просили: подсказка, висящая над каждым
     * словом, — это помеха.
     *
     * Порядок среди подошедших — по словам клиента: он только что описал беду,
     * и ответ на неё должен стоять первым.
     */
    if (!visible || набрано.length < МИНИМУМ) return [];
    const подошли = все.filter((t) => подходит(t, набрано));
    return подобрать(подошли, clientSaid).slice(0, МАКСИМУМ);
  }, [visible, набрано, все, clientSaid]);

  const [активная, setАктивная] = useState(0);
  /*
   * ⚠ СБРОС ПО СОСТАВУ СПИСКА, А НЕ ПО ЕГО ДЛИНЕ (разбор 03.09).
   *
   * Здесь стояло `[набрано, items.length]`. Длина — слабый признак: клиент
   * присылает новое сообщение, порядок пересчитывается под его слова, а строк
   * остаётся столько же. Метка при этом стоит на прежнем НОМЕРЕ — то есть уже
   * на другой заготовке, и Tab вставляет клиенту не то, что человек видит
   * подсвеченным.
   *
   * Ключ по идентификаторам ловит и перестановку, и подмену состава.
   */
  const состав = items.map((t) => t.id).join(",");
  useEffect(() => setАктивная(0), [набрано, состав]);

  // Поле дорисовывает продолжение выбранной строки. `null` — дорисовывать
  // нечего: список пуст или полоса скрыта.
  const выбранная = items[активная] ?? items[0] ?? null;
  useEffect(() => {
    onActive?.(выбранная);
  }, [выбранная, onActive]);

  useEffect(() => {
    const поле = fieldRef?.current;
    if (items.length === 0 || поле === null || поле === undefined) return;
    const наКлавишу = (e: KeyboardEvent) => {
      // Сочетания с модификаторами не наши: Alt+↑ и Cmd+↓ ходят по тексту и по
      // странице, и гасить их ради подсказки нельзя.
      if (e.ctrlKey || e.metaKey || e.altKey) return;
      if (e.key === "ArrowDown") {
        e.preventDefault();
        setАктивная((i) => (i + 1) % items.length);
      } else if (e.key === "ArrowUp") {
        e.preventDefault();
        setАктивная((i) => (i - 1 + items.length) % items.length);
      } else if (e.key === "Tab" && !e.shiftKey) {
        // Tab свободен: в поле ввода он уводит фокус, а здесь делает то, ради
        // чего человек и смотрит на список. Shift+Tab не трогаем — это уход
        // назад, единственный способ выбраться из поля клавиатурой.
        e.preventDefault();
        onPick(items[активная] ?? items[0]);
      }
    };
    поле.addEventListener("keydown", наКлавишу);
    return () => поле.removeEventListener("keydown", наКлавишу);
  }, [items, активная, onPick, fieldRef]);

  if (!visible || items.length === 0) return null;

  return (
    <div className="quick-replies" role="listbox" aria-label="Быстрые ответы">
      {items.map((t, i) => (
        <button
          key={t.id}
          type="button"
          role="option"
          aria-selected={i === активная}
          className="quick-replies__item"
          data-active={i === активная || undefined}
          onMouseEnter={() => setАктивная(i)}
          onClick={() => onPick(t)}
        >
          <span className="quick-replies__title">{t.title}</span>
          {/* Начало текста — чтобы различать похожие заготовки, не открывая их. */}
          <span className="quick-replies__preview">{t.body}</span>
        </button>
      ))}
      <div className="quick-replies__hint" aria-hidden="true">
        <kbd>↑↓</kbd> — выбрать · <kbd>Tab</kbd> — вставить
      </div>
    </div>
  );
}
