/**
 * Стоит ли каретка в живом поле ввода прямо сейчас.
 *
 * `document.body` — это «нигде»: браузер возвращает его, когда фокуса нет
 * вовсе или когда сфокусированный элемент только что удалили из документа.
 * Именно последнее и происходит при перемонтировании самого композера, и там
 * фокус вернуть НАДО.
 */
function activeElementЖивое(el: Element | null): boolean {
  if (!el || el === document.body) return false;
  const tag = el.tagName.toLowerCase();
  return tag === "input" || tag === "textarea" || tag === "select" || (el as HTMLElement).isContentEditable;
}

/**
 * ⚠ У СНИМКА ЭКРАНА ИЗ БУФЕРА ИМЕНИ НЕТ, А ЧИП ПОКАЗЫВАЕТ ИМЯ.
 *
 * Windows кладёт в буфер файл с ПУСТЫМ именем, Chrome — «image.png» на каждый
 * снимок подряд. И то и другое видно в панели вложений и в подписи кнопки
 * «Убрать вложение …»: три снимка в одном сообщении назывались бы одинаково
 * (или никак), и убрать лишний было бы не по чему.
 *
 * ⚠ НАСТОЯЩЕЕ ИМЯ СОХРАНЯЕМ. Файл, скопированный в проводнике, приезжает тем
 * же путём и со своим именем («счёт-1024.png»); заменить его датой значило бы
 * стереть то единственное, по чему человек его узнаёт.
 */
function снимкуИмя(file: File): File {
  const своё = file.name !== "" && file.name.toLowerCase() !== "image.png";
  if (своё) return file;
  const сейчас = new Date();
  const дв = (n: number) => String(n).padStart(2, "0");
  const дата =
    `${сейчас.getFullYear()}-${дв(сейчас.getMonth() + 1)}-${дв(сейчас.getDate())}` +
    ` ${дв(сейчас.getHours())}-${дв(сейчас.getMinutes())}-${дв(сейчас.getSeconds())}`;
  // Двоеточие в имени файла запрещено в Windows — время через дефисы.
  const имя = `Снимок экрана ${дата}.${РАСШИРЕНИЕ[file.type] ?? "png"}`;
  return new File([file], имя, { type: file.type, lastModified: file.lastModified });
}

/**
 * Картинки из буфера обмена или из перетаскивания.
 *
 * `items` — запасной путь, а не украшение: часть браузеров отдаёт снимок
 * экрана только там, а `files` в том же событии пуст. Ошибиться здесь дорого:
 * пустой список означает «картинок нет» и уводит вставку в обычную ветку —
 * человек нажимает Ctrl+V и не получает ничего.
 */
function картинкиИз(dt: DataTransfer | null): File[] {
  if (!dt) return [];
  const прямые = Array.from(dt.files ?? []);
  const все = прямые.length
    ? прямые
    : Array.from(dt.items ?? [])
        .filter((i) => i.kind === "file")
        .map((i) => i.getAsFile())
        .filter((f): f is File => f !== null);
  return все.filter((f) => f.type.startsWith("image/")).map((f) => снимкуИмя(f));
}

/**
 * Тащат ли файл, а не выделенный текст.
 *
 * Перетаскивание текста ВНУТРИ поля — законная и частая правка набранного:
 * перехвати мы его, кусок ответа пропадал бы при переносе. У файлов в
 * `types` всегда есть «Files», у текста — только «text/plain» и «text/html».
 */
function тащатФайл(dt: DataTransfer | null): boolean {
  return Array.from(dt?.types ?? []).includes("Files");
}

