import type { ConversationDto } from "@/shared/api/types";

/**
 * Строки в заданном порядке: содержимое свежее, очередь — прежняя.
 *
 * ⚠ ЗАЧЕМ ЭТО ВООБЩЕ НУЖНО (разбор 30.08). Список живой: любой кадр с новым
 * сообщением двигает строку наверх, и порядок пересчитывается под уже
 * занесённой рукой. Оператор целится в «Ольгу», в этот миг пишет другой
 * клиент — строки разъезжаются, и щелчок попадает в соседа. Открывается чужая
 * переписка, каретка встаёт в её поле ввода, и человек, не заметив подмены,
 * дописывает ответ не тому. Тот же вред, что от клавиш, только руками.
 *
 * ПОЧЕМУ ЗАМОРОЗКА, А НЕ АНИМАЦИЯ ПЕРЕЕЗДА. Плавный переезд показывает, что
 * строка уехала, но не мешает ей уехать: попасть по движущейся цели всё равно
 * нельзя. Порядок держим ровно пока курсор над колонкой; ушёл — список встаёт
 * как надо сам, без всякого действия.
 *
 * ЗАМОРАЖИВАЕТСЯ ТОЛЬКО ПОРЯДОК, содержимое строк живое. Диалоги, появившиеся
 * пока курсор над колонкой, встают в КОНЕЦ: втискивать их между замороженных
 * значило бы двигать всё, что ниже, — то есть ровно то, от чего заморозка и
 * заведена.
 *
 * Вынесено из компонента ради проверки: ошибка в перестановке не видна глазом,
 * а стоит открытого не того диалога.
 */
export function поПлану(
  свежие: ConversationDto[],
  план: string[] | null,
  свои: ReadonlySet<string> = ПУСТО,
): ConversationDto[] {
  if (!план) return свежие;
  const известна = new Set(план);
  const изПлана = new Map(свежие.map((r) => [r.id, r]));
  const out: ConversationDto[] = [];

  /*
   * ⚠ ВЗЯТЫЕ МНОЮ СТРОКИ ВСТАЮТ НА СВОЁ МЕСТО, А НЕ В КОНЕЦ (жалоба владельца
   * 02.09, повторная: «беру пачку диалогов, они сначала появляются в самом
   * низу списка, потом через пару секунд переезжают наверх»).
   *
   * ⚠ ПОЧЕМУ ПРЕЖНЯЯ ПРАВКА НЕ ПОМОГЛА. Утром я сбрасывал план в момент
   * взятия — и это верно, но недостаточно: строка приезжает с сервера через
   * секунду-две, а к тому времени заморозка взводится заново, уже без неё. Для
   * нового плана строка снова «незнакомая» и снова падает в хвост.
   *
   * Теперь взятые мною помнятся отдельно и ставятся туда, где они стоят в
   * НАСТОЯЩЕМ порядке: перед первой знакомой строкой, которая идёт за ними.
   * Чужие новые строки по-прежнему уходят в конец — ради этого заморозка и
   * заведена: они не должны сдвигать всё под занесённой рукой.
   */
  const своиПеред = new Map<string, ConversationDto[]>();
  const своиВКонец: ConversationDto[] = [];
  for (let i = 0; i < свежие.length; i++) {
    const строка = свежие[i];
    if (известна.has(строка.id) || !свои.has(строка.id)) continue;
    const следующая = свежие.slice(i + 1).find((r) => известна.has(r.id));
    if (следующая) {
      const якорь = своиПеред.get(следующая.id) ?? [];
      якорь.push(строка);
      своиПеред.set(следующая.id, якорь);
    } else {
      своиВКонец.push(строка);
    }
  }

  for (const id of план) {
    for (const своя of своиПеред.get(id) ?? []) {
      out.push(своя);
      изПлана.delete(своя.id);
    }
    const строка = изПлана.get(id);
    if (строка) {
      out.push(строка);
      изПлана.delete(id);
    }
  }
  for (const своя of своиВКонец) {
    if (изПлана.delete(своя.id)) out.push(своя);
  }
  for (const новая of изПлана.values()) out.push(новая);
  return out;
}

const ПУСТО: ReadonlySet<string> = new Set();

/* -------------------------------------------------------------------------- *
 *  Своя отправка обязана поднять строку СРАЗУ
 * -------------------------------------------------------------------------- */

/**
 * ⚠ ЖАЛОБА ВЛАДЕЛЬЦА 02.09: «когда отвечаешь клиенту, не сразу чат уходит вверх».
 *
 * Это оборотная сторона заморозки выше, и обе жалобы верны одновременно.
 * Заморозка держит порядок четыре секунды после наведения на колонку — а
 * диспетчер работает так: щёлкнул диалог в списке, тут же ответил. Отправка
 * попадает ровно в это окно, и собственный ответ не двигает строку наверх до
 * истечения секунд.
 *
 * ⚠ ПОЧЕМУ ЗАМОРОЗКУ НЕ СНИМАЕМ, А ПЕРЕСОБИРАЕМ. Снять — значит вернуть беду
 * 30.08: сразу после ответа диспетчер целится в следующую строку, и чужое
 * сообщение уводит её из-под руки. Разница между двумя случаями не в том,
 * двигать список или нет, а в том, ЧЬЁ действие его двигает. Своё — видно
 * сразу; чужое — ждёт, пока рука опустится.
 *
 * Поэтому сигнал не «разморозить», а «пересчитать отсчёт от нынешнего
 * порядка»: строка уезжает наверх немедленно, и с этого нового порядка
 * заморозка продолжает защищать.
 */
let поколениеПорядка = 0;
const слушателиПорядка = new Set<() => void>();

const моиСвои = new Set<string>();

/**
 * Своё действие: порядок обязан встать заново, не дожидаясь конца заморозки.
 *
 * `conversationId` передают там, где диалог ТОЛЬКО ЧТО ПОЯВИЛСЯ у человека —
 * взят из очереди, передан ему. Такой строки в списке ещё нет: она приедет с
 * сервера через секунду-две, и без этой пометки заморозка встретит её как
 * чужую новую и отправит в хвост.
 */
export function пересобратьПорядок(conversationId?: string): void {
  if (conversationId) моиСвои.add(conversationId);
  поколениеПорядка += 1;
  for (const слушатель of слушателиПорядка) слушатель();
}

/** Строки, которые взял сам человек: их место — по порядку, а не в хвосте. */
export function свои(): ReadonlySet<string> {
  return моиСвои;
}

/**
 * Строка доехала и попала в план — она больше не новая, и помнить её незачем.
 * Без этого пометка жила бы вечно и однажды пустила бы в середину списка
 * строку, которую человек брал полчаса назад.
 */
export function забытьСвои(план: readonly string[]): void {
  for (const id of план) моиСвои.delete(id);
}

export function подписатьсяНаПорядок(слушатель: () => void): () => void {
  слушателиПорядка.add(слушатель);
  return () => {
    слушателиПорядка.delete(слушатель);
  };
}

export function поколениеПересборки(): number {
  return поколениеПорядка;
}
