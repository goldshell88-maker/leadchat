import type { Waiting } from "@/shared/lib/waiting";
import { WAIT_LATE_MIN, WAIT_WARN_MIN } from "@/shared/lib/waiting";
import "./wait-gauge.css";

/**
 * Ячейка времени в строке списка — она же шкала срочности (редизайн, TOKENS §9).
 *
 * ЗАЧЕМ ШКАЛА, А НЕ ПРОСТО ЦИФРА. Диспетчер разбирает список сверху вниз и
 * решает по строке, брать её сейчас или нет. Цифру «12 мин» надо прочитать;
 * заливку, растущую снизу вверх, видно боковым зрением, ещё до чтения. На
 * пятой минуте — треть ячейки, на пятнадцатой — вся: срочность становится
 * формой, а не текстом.
 *
 * ПОЧЕМУ ОДНО ЧИСЛО, А НЕ ДВА. Раньше строка показывала время последнего
 * сообщения И отдельно ожидание — два числа рядом, из которых одно почти
 * всегда лишнее. Если ждёт клиент, «14:32» не значит ничего: важно, сколько
 * он ждёт. Если ответили мы — ожидания нет, и время сообщения на месте.
 *
 * ПОРОГИ те же, что и везде в продукте (`shared/lib/waiting.ts`): пять минут
 * и пятнадцать. Пятнадцать минут молчания на Авито означают, что клиент уже
 * пишет конкуренту.
 */
/**
 * Подпись для шкалы — КОРОЧЕ, чем в чипе.
 *
 * В чипе «ждёт 25 мин» есть место на слова, в ячейке шириной 48px его нет:
 * «365 дн» переносится на две строки и перекрикивает имя клиента, ради
 * которого строка и существует. Здесь нужна не фраза, а число с единицей.
 */
function short(minutes: number): string {
  if (minutes < 60) return `${minutes}м`;
  const hours = Math.floor(minutes / 60);
  if (hours < 24) return `${hours}ч`;
  const days = Math.floor(hours / 24);
  // Дальше недели точность не нужна: и «8 дней», и «год» означают одно —
  // клиент давно ушёл. Потолок не даёт ячейке распухнуть.
  return days > 99 ? "99+д" : `${days}д`;
}

export function WaitGauge({
  waiting,
  time,
  sinceMinutes,
  timeTitle,
  escalated,
}: {
  /** Сколько ждёт клиент. `null` — ответили мы, ждать некому. */
  waiting: Waiting | null;
  /** Время последнего сообщения — запасной вид, когда возраст неизвестен. */
  time: string | null;
  /**
   * Сколько минут прошло с последнего события в строке.
   *
   * ⚠ ЖАЛОБА ВЛАДЕЛЬЦА 02.09 СО СКРИНШОТОМ: «то, что вот так рвётся, — это
   * нормально?». В колонке чередовались ДВЕ РАЗНЫЕ ЕДИНИЦЫ: у ждущих оранжевый
   * счётчик «22м», у отвеченных и закрытых — часы «12:39». Сравнить их взглядом
   * нельзя, и список читался как сломанный.
   *
   * Порядок при этом был верен — проверено на боевых данных: столбец сортировки
   * шёл строго по убыванию (03:03, 03:03, 03:02, 03:01, 02:59, 02:53…), а в
   * ячейке рядом стояли то счётчики, то часы. То есть рвался не список, а
   * чтение.
   *
   * Теперь единица одна: возраст строки. Отличие «ждут нас» от «ответили»
   * несёт ЦВЕТ и заливка, а не смена единицы измерения. Точные часы никуда не
   * делись — они в подсказке (`timeTitle`), причём сразу в двух поясах.
   */
  sinceMinutes?: number | null;
  /**
   * Расшифровка этого времени в обоих поясах — «21:24 у вас · 14:24 по
   * Москве» (дефект 19). В ячейке шириной 48px пояс не подписать, а
   * неподписанное время сотрудник сверяет с московским из «Разбора диалогов»
   * в уме. Подсказка снимает вычитание, не отнимая у ячейки ни пикселя.
   */
  timeTitle?: string;
  /** От диалога отказались все, кому он доступен. */
  escalated?: boolean;
}) {
  /*
   * ОТКАЗАЛИСЬ ВСЕ — но красным слепком это больше не рисуется.
   *
   * Было: вся ячейка заливалась красным во всю высоту, а если срока ожидания
   * нет — в ней стояло «—». На светлой теме это выглядело как алая заплата
   * поперёк строки, перекрывала соседний чип и читалась поломкой вёрстки, а не
   * состоянием диалога. И само «—» не значило ничего: человек видел тревожный
   * цвет и прочерк вместо ответа на вопрос «сколько ждут».
   *
   * Теперь: если срок ожидания известен — обычная шкала «поздно», красная
   * цифрой, а не полем. Если неизвестен — ячейка молчит: про «никто не берёт»
   * уже сказано чипом в той же строке, и повторять это красным прямоугольником
   * значит кричать дважды.
   */
  if (escalated && waiting) {
    return (
      <span
        className="wait-gauge"
        data-level="lost"
        title={`Отказались все — клиент ждёт ${waiting.text}`}
        aria-label={`Никто не ведёт, ждёт ${waiting.text}`}
      >
        <span className="wait-gauge__value lc-num">{short(waiting.minutes)}</span>
      </span>
    );
  }

  if (!waiting) {
    /*
     * Ответили мы (или диалог закрыт). Ячейка приглушённая: строка не требует
     * внимания, и подсвечивать её было бы обманом.
     *
     * ⚠ НО ЕДИНИЦА ТА ЖЕ, ЧТО У ЖДУЩИХ. Пока здесь стояли часы, колонка
     * чередовала «22м» и «12:39», и порядок нельзя было прочитать взглядом —
     * см. `sinceMinutes`. Часы остаются запасным видом на случай, если возраст
     * посчитать не из чего.
     */
    /*
     * ⚠ ГРАНИЦА В СУТКИ, А НЕ «ВСЕГДА ОТНОСИТЕЛЬНО».
     *
     * Рвался список у строк, отличающихся МИНУТАМИ: рядом стояли «22м» и
     * «12:39», и сравнить их взглядом было нельзя. Всё, что моложе суток, —
     * ровно этот случай, и там нужна одна мера.
     *
     * Дальше суток дата полезнее счётчика: «5 авг» говорит больше, чем «6д», а
     * спутать её с соседними минутами невозможно — такие строки лежат внизу
     * списка, отсортированного по свежести, и с верхними не чередуются.
     * Проверка «обычная переписка выглядит как раньше» это и стерегла.
     */
    const СУТКИ_В_МИНУТАХ = 24 * 60;
    const возраст =
      sinceMinutes != null && sinceMinutes < СУТКИ_В_МИНУТАХ ? short(sinceMinutes) : time;
    return (
      <span className="wait-gauge" data-level="idle" title={timeTitle}>
        <span className="wait-gauge__time lc-num">{возраст ?? ""}</span>
      </span>
    );
  }

  // Заливка линейна и упирается в потолок на пятнадцатой минуте: дальше
  // расти некуда, «час» и «три часа» одинаково означают «уже поздно».
  const ratio = Math.min(waiting.minutes / WAIT_LATE_MIN, 1);
  const level =
    waiting.minutes >= WAIT_LATE_MIN ? "late" : waiting.minutes >= WAIT_WARN_MIN ? "warn" : "calm";

  return (
    <span
      className="wait-gauge"
      data-level={level}
      title={`Клиент ждёт ответа ${waiting.text}`}
      aria-label={`Ждёт ${waiting.text}`}
    >
      {/* До пяти минут заливки нет вовсе: свежее обращение — норма, и
          закрашивать его значит приучить не смотреть на цвет. */}
      {level !== "calm" && (
        <span
          className="wait-gauge__fill"
          style={{ transform: `scaleY(${Math.round(ratio * 100) / 100})` }}
        />
      )}
      <span className="wait-gauge__value lc-num">{short(waiting.minutes)}</span>
    </span>
  );
}
