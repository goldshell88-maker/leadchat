const NEGATIVE_TAG = "негатив";

/**
 * Превью строки списка со `sender_type`.
 *
 * Поле приходит в каждой строке (`conversations.conversation_out`), но в
 * `types.ts` не объявлено: файл в этой работе принадлежит другому воркеру.
 * Локальное расширение честнее приведения к `any` — видно ровно одно поле и
 * видно, что оно необязательное: строки из кэша прошлой версии его не несут.
 * Кадр `message:new` (`applyWsEvent.applyNewMessage`) с 18.09 поле кладёт —
 * иначе вопрос системы об адресе до перезагрузки подписывался «Вы:».
 */
type PreviewMessage = NonNullable<ConversationDto["last_message"]> & {
  sender_type?: string;
};

/**
 * Служебная запись АВИТО в превью (дефект 12).
 *
 * `direction === "system"` одного недостаточно: тем же признаком помечена наша
 * собственная запись «Статус: Новый → В работе. Иванов», и она приезжает в
 * строку живым кадром `message:new` после каждой смены статуса. Подписать её
 * «Авито» значило бы приписать площадке наши же слова. Отсюда проверка
 * `sender_type`, а отсутствие поля читается как «не Авито» — тише и безопаснее.
 */
function avitoNotice(row: ConversationDto): PreviewMessage | null {
  const lm = row.last_message as PreviewMessage | null;
  // По отправителю (новые записи) ИЛИ по приставке (исторические, поднятые
  // загрузкой истории до правки 17.08) — см. isAvitoSystemMessage.
  return lm && isAvitoSystemMessage(lm) ? lm : null;
}

function previewText(row: ConversationDto): string {
  const lm = row.last_message;
  if (!lm) return "Сообщений пока нет";
  /*
   * ⚠ ИМЯ ВЛОЖЕНИЯ ВПЕРЁД «ВЛОЖЕНИЯ» (07.09). С переездом служебной подписи из
   * тела во вложение тело у видео, файлов и звонков стало пустым, и строка
   * списка сказала бы про них голое «Вложение» — то есть потеряла бы ровно ту
   * мысль, ради которой подпись и существует. Сервер отдаёт имя первого
   * вложения тем же ответом (`services/conversations.py::_first_attachment_name`);
   * своего словаря слов здесь нет намеренно — разъехавшись с серверным, он
   * показывал бы в списке не то, что в ленте.
   */
  const body = lm.body?.trim() || lm.attachment_name?.trim() || "Вложение";
  if (avitoNotice(row)) {
    // «Авито:» — тем же приёмом, что и «Вы:»: одно слово о том, чей это голос.
    // Без него «Клиент оформил заказ, ожидает подтверждения» читается как
    // фраза, которую написал сам клиент.
    return `Авито: ${body}`;
  }
  if (lm.direction !== "out") return body;
  // Вопрос системы об адресе (`('out','system')`, workers/address_ask.py): «Вы:»
  // приписало бы оператору слова, которых он не писал.
  return `${(lm as PreviewMessage).sender_type === "system" ? "Система" : "Вы"}: ${body}`;
}

/**
 * Срочность полосой слева (docs/16 §4.3). Берётся ПЕРВОЕ подходящее: полоса
 * одна, а поводов может совпасть несколько.
 *
 * НЕПРОЧИТАННЫЕ ПОЛОСУ НЕ ПОЛУЧАЮТ (UX-аудит, docs/17 §Т8). Раньше получали —
 * и полоса теряла смысл: непрочитанное есть у большинства строк, а признак,
 * который стоит почти у всех, перестаёт быть признаком. Непрочитанное и так
 * заявлено дважды — жирным именем и синим счётчиком. Полоса остаётся за тем,
 * что требует вмешательства прямо сейчас: брошенный клиент, недовольный,
 * ждущий в очереди.
 *
 * Поля здесь только настоящие. В брифе есть «приоритет» отдельным свойством,
 * но в API его нет и придумывать его на фронте нельзя: это была бы шкала,
 * которую никто не заполняет и которая всегда показывает одно значение.
 * Срочность выводится из того, что система знает сама.
 */
function urgency(
  row: ConversationDto,
): "undelivered" | "escalated" | "negative" | "waiting" | "none" {
  // Неотправленный ответ идёт ПЕРВЫМ, вперёд эскалации и негатива (#26).
  // Остальные поводы говорят «клиенту нужно внимание»; этот говорит «система
  // не сделала того, что человек уже считает сделанным». Пока он не разобран,
  // оператор уверен, что ответил, — и не ответит.
  if (row.undelivered) return "undelivered";
  if (row.escalated) return "escalated";
  if (row.tags.includes(NEGATIVE_TAG)) return "negative";
  if (row.in_inbox) return "waiting";
  return "none";
}

/**
 * Карточка диалога в левой колонке (docs/16 §4.3, макет — 11 §2.1).
 *
 * Высота фиксированная: список виртуализирован, и `ROW_HEIGHT` в
 * `ChatListPane` обязан совпадать с суммой отступов и строк отсюда. Если
 * менять плотность — менять в обоих местах, иначе строки наедут друг на друга
 * или между ними появятся дыры.
 *
 * У СТРОКИ РОВНО ОДНО ДЕЙСТВИЕ — ОТКРЫТЬ ДИАЛОГ.
 *
 * Здесь была ещё ховер-иконка «Передать диалог» — четвёртое по счёту место
 * одного и того же действия: те же слова стояли иконкой в шапке ленты,
 * кнопкой в правой карточке и пунктом меню. Разбор живого экрана владельцем
 * (12 августа) показал, чем это кончается: человек не помнит, какая из
 * четырёх кнопок «настоящая», и проверяет результат после каждой. Действие
 * оставлено ровно в одном месте — в открытом диалоге, где видно, КОМУ и
 * ЗАЧЕМ передают; передавать по превью в списке всё равно нельзя.
 *
 * Разметка при этом осталась `div` с вложенной кнопкой: внешний узел несёт
 * `data-*` состояния строки и полосу срочности (`::before`), а внутренний —
 * область нажатия и рамку фокуса внутри карточки. Второго действия в нём
 * больше нет и заводить его тут не надо.
 */
