import { useEffect, useRef } from "react";
import { useNavigate } from "react-router-dom";
import { useChatUiStore } from "@/shared/stores/chatUiStore";

/**
 * «Человек выбрал диалог сам» — и замок, который держит всё остальное.
 *
 * ⚠ ЗАЧЕМ ЭТО ЗАВЕДЕНО (жалоба владельца, третий заход 31.08). Диалоги
 * перелетают: «начинаю писать клиенту, и диалог может внезапно перескочить».
 * Механизмы закрывались по одному — клавиши, кадры сокета, подмена поля ввода,
 * пересортировка списка, — и каждый раз жалоба возвращалась. Значит перебор
 * механизмов проигрывает: их больше, чем мы находим за раз.
 *
 * Поэтому правило переворачивается. Вместо «запретим ещё один путь» — «уйти с
 * НЕДОПИСАННОГО ответа можно только по осознанному выбору человека». Кто бы ни
 * дёрнул переход, если это не отмеченный выбор и в поле лежит набранное, экран
 * возвращается назад, а попытка пишется в журнал — с ней и найдём виновника,
 * которого не нашли чтением.
 *
 * ЧТО СЧИТАЕТСЯ ВЫБОРОМ: клик по строке списка, кнопка «Следующий» в очереди,
 * приём диалога, переход по уведомлению, ссылка из другого раздела. Каждый
 * такой путь помечает намерение сам — одной строкой рядом с `navigate`.
 *
 * ЧЕГО ЗАМОК НЕ ДЕЛАЕТ. Он не мешает уходить с пустого поля: там терять нечего,
 * и держать человека значило бы мешать работе. Он не запрещает переходы вовсе —
 * только те, которых человек не просил.
 */

/** Сколько живёт отметка выбора: перехода в пределах одного кадра хватает. */
const ЖИВЁТ_МС = 3000;

let выбранный: { id: string; когда: number } | null = null;

/**
 * Пометить выбор по АДРЕСУ, а не по идентификатору.
 *
 * ⚠ ЗАВЕДЕНО ПОСЛЕ СОБСТВЕННОЙ РЕГРЕССИИ (31.08). Замок откатывал переходы по
 * уведомлениям: человек жал «Клиент ждёт ответа», видел нужный диалог один
 * кадр — и оказывался обратно, а в консоли замок обвинял собственный откат.
 * Причина: путь перехода забыли пометить. Ссылок на диалог в приложении
 * больше, чем мест, где о метке помнят, поэтому помечать надо там, где адрес
 * уже собран, — одной строкой и без разбора идентификатора на месте вызова.
 */
export function выбралСамПоАдресу(to: string): void {
  const m = /^\/chats\/([^/?#]+)/.exec(to);
  if (m) выбралСам(decodeURIComponent(m[1]));
}

/** Пометить: этот переход человек сделал сам. */
export function выбралСам(convId: string): void {
  выбранный = { id: convId, когда: Date.now() };
}

/** Был ли переход к этому диалогу осознанным выбором. */
export function этоВыбор(convId: string | null | undefined): boolean {
  if (!convId || !выбранный) return false;
  if (выбранный.id !== convId) return false;
  return Date.now() - выбранный.когда <= ЖИВЁТ_МС;
}

/** Только для тестов: забыть отметку. */
export function забытьВыбор(): void {
  выбранный = null;
}

/**
 * Замок: с недописанного ответа уводит только человек.
 *
 * Вынесен из `ChatsPage` отдельным хуком не ради красоты, а ради проверяемости:
 * правило здесь одно и важное, и сторожить его надо прямо, а не через отрисовку
 * всего экрана чатов с его лентой, карточкой и списком.
 */
/*
 * ⚠ ИМЯ ЛАТИНСКОЕ, И ЭТО НЕ ПРИХОТЬ — то же соглашение, что у `LiveNow` в
 * «Диалогах бота». Правило `react-hooks/rules-of-hooks` узнаёт хук по
 * латинскому `use…`; для кириллического продолжения оно перестаёт считать
 * функцию хуком, и вызовы внутри читаются как хуки вне компонента.
 */
export function useDialogPin(id: string | undefined): void {
  const navigate = useNavigate();
  const прежний = useRef<string | null>(null);

  useEffect(() => {
    const было = прежний.current;
    if (было && id && было !== id && !этоВыбор(id)) {
      const набрано = (useChatUiStore.getState().drafts[было]?.text ?? "").trim();
      if (набрано) {
        // Журнал — половина смысла замка: он называет виновника, которого не
        // видно в коде. Читается в консоли у того, у кого перелетело.
        console.warn("[чат] диалог сменился сам, откатываю", { было, стало: id });
        navigate(`/chats/${было}`, { replace: true });
        return;
      }
    }
    прежний.current = id ?? null;
  }, [id, navigate]);
}
