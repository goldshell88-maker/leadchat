import { useLayoutEffect, useState } from "react";

import {
  RAIL_WIDTH_COLLAPSED,
  RAIL_WIDTH_EXPANDED,
  useRailExpanded,
} from "@/shared/stores/railStore";

/**
 * ШИРИНА, ДОСТУПНАЯ РАБОЧЕМУ МЕСТУ, — ТА ЖЕ ВЕЛИЧИНА, КОТОРУЮ МЕРЯЕТ CSS.
 *
 * ЗАЧЕМ ЭТО ВООБЩЕ ЕСТЬ. Раскладку чатов читают два слоя: CSS решает, как
 * выглядят колонки, React — рисовать ли карточку клиента оверлеем и кнопку
 * «Клиент». Пока оба слоя спрашивали `matchMedia`, они спрашивали про ОКНО, а
 * колонкам достаётся окно за вычетом левой рельсы — 218 пикселей при
 * развёрнутой (умолчание) и 72 при свёрнутой. Замер 08.09: при окне 1440 на
 * ленту оставалось 478 пикселей вместо объявленного минимума 616.
 *
 * CSS перешёл на контейнерный запрос по `.lc-main` (`app-layout.css`), но
 * прочитать контейнерный запрос React не может — у него нет для этого ничего.
 * Поэтому здесь наблюдатель размера на том же прямоугольнике: content-box у
 * `.lc-main` и border-box у `.chats-page` — это один и тот же прямоугольник,
 * потому что у `.lc-main` нет полей, а `.chats-page` растягивается по
 * поперечной оси её колонки. Слои меряют не одинаковое число, а один предмет.
 *
 * ⚠ ЗАЧЕМ ОЦЕНКА ДО ЗАМЕРА. Первый кадр рисуется ДО того, как элемент попал в
 * документ, и наблюдателю ещё нечего наблюдать. Оценка «окно минус рельса»
 * даёт тот же ответ, что и замер, всюду, кроме ширины полосы прокрутки, а
 * замер приходит в `useLayoutEffect` — то есть ДО показа кадра, а не после
 * него. Поэтому подмены на глазах не бывает: сначала подставили оценку, до
 * первой отрисовки заменили измеренным.
 *
 * ⚠ ЗАМКНУТОГО КРУГА ЗДЕСЬ НЕТ. Ширина `.chats-page` задаётся её колонкой, а
 * не содержимым (`flex: 1` в колонке `.lc-main`), поэтому решение, принятое по
 * замеру, на сам замер не влияет: убрали карточку из потока — ширина места не
 * шелохнулась. Ровно по этой причине контейнер объявлен на `.lc-main`, у
 * которой нет полей: контейнер, меняющий собственные поля, менял бы и то, что
 * измеряет.
 */
export function useWorkspaceWidth(место: HTMLElement | null): number {
  const рельса = useRailExpanded() ? RAIL_WIDTH_EXPANDED : RAIL_WIDTH_COLLAPSED;
  const [измерено, setИзмерено] = useState<number | null>(null);

  useLayoutEffect(() => {
    if (!место) {
      setИзмерено(null);
      return;
    }

    const снять = () => {
      const ширина = место.getBoundingClientRect().width;
      // Ноль означает «раскладки нет»: элемент вне документа или это jsdom,
      // который не считает раскладку вовсе. Оценка по окну честнее нуля —
      // ноль объявил бы телефоном любой экран.
      setИзмерено(ширина > 0 ? ширина : null);
    };

    снять();

    if (typeof ResizeObserver === "undefined") return;
    const наблюдатель = new ResizeObserver(снять);
    наблюдатель.observe(место);
    return () => наблюдатель.disconnect();
  }, [место]);

  return измерено ?? Math.max(0, window.innerWidth - рельса);
}
