/**
 * Подсказка «ниже ещё есть» — чистая арифметика без React.
 *
 * ЖИВЁТ ОТДЕЛЬНО ОТ ОКНА по требованию горячей замены: файл, где рядом с
 * компонентами лежит обычная функция, Vite перезагружает целиком вместо
 * горячей замены (`react-refresh/only-export-components`). Для окна справки
 * это мелочь, но правило одно на весь фронт, и держать его выборочно нельзя.
 */

/** Размеры прокручиваемого блока — ровно то, что нужно для ответа «есть ли ещё». */
export interface ScrollBox {
  scrollTop: number;
  clientHeight: number;
  scrollHeight: number;
}

/**
 * Осталось ли что-то НИЖЕ видимой части списка.
 *
 * Вынесено отдельной функцией не ради красоты: в jsdom у элементов нет
 * размеров (`scrollHeight` всегда 0), и проверить это на отрисованном окне
 * тестом невозможно — он зеленел бы всегда. Здесь же считается чистая
 * арифметика, и её можно сломать в тесте.
 *
 * Допуск в один пиксель — не суеверие: при масштабе экрана 125% (обычное дело
 * на ноутбуке 1440×900) высоты приходят дробными, и разность в 0.5px держала
 * бы затемнение зажжённым на самом конце списка. То есть подсказка «ниже ещё
 * есть» висела бы там, где ниже уже ничего нет.
 */
export function hasMoreBelow(box: ScrollBox | null): boolean {
  if (!box) return false;
  return box.scrollHeight - box.scrollTop - box.clientHeight > 1;
}
