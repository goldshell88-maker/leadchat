/**
 * ЕДИНЫЙ РЕЕСТР ДЕЙСТВИЙ И ИХ СОЧЕТАНИЙ. Один источник на справку в окне, блок в
 * профиле, экран переназначения и сам обработчик клавиш.
 *
 * ЧТО ЗДЕСЬ БЫЛО ДО 13 АВГУСТА. Список строк вида `{ keys: "Ctrl + R", what: "…" }` —
 * подпись для человека и ничего больше. Сравнить её с событием было нельзя, поэтому
 * обработчик держал свою, отдельную лестницу `if`, и совпадали они только на честном
 * слове. В шапке файла это признавалось прямо: «полного соответствия тестом не
 * проверить, пока обработчики не объявлены данными». Заказчик попросил
 * переназначение — и объявить их данными пришлось.
 *
 * ТЕПЕРЬ ЭТО ИСТОЧНИК ПРАВДЫ ДЛЯ ОБРАБОТЧИКА: расхождение справки и поведения стало
 * невозможным, оба читают эту таблицу.
 *
 * ПОРЯДОК — ПО ЧАСТОТЕ, а не по алфавиту: сверху то, что жмут каждую минуту.
 * Пометка «как в Jivo» не украшение: она снимает главный страх переезда.
 *
 * ПРАВО (`need`) — ЧТОБЫ НЕ УЧИТЬ НЕВОЗМОЖНОМУ (FUNC-35). Шпаргалка одна на все
 * роли, и наблюдатель читал в ней «Ctrl+R — принять диалог». Он нажимает, не
 * происходит ничего — и решает, что приложение сломано.
 */

