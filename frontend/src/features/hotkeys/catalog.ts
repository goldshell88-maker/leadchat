export function firesWhileTyping(action: HotkeyAction, binding: Binding): boolean {
  if (!action.allowInInput) return false;
  if (binding === "Escape") return true;
  return binding.includes("+");
}

/** Строка справки: подпись сочетаний плюс объяснение. */
export interface Hotkey {
  /** Ключ строки: подписи сочетаний повторяются («выключено» у многих). */
  id: ActionId;
  keys: string;
  what: string;
  need?: Permission;
}

// Один пустой массив на всех — чтобы `useMemo` и сравнения ссылок не считали
// каждый вызов новым значением.
const ПУСТО: readonly Binding[] = [];

/**
 * Какие сочетания ДЕЙСТВУЮТ у этого человека прямо сейчас.
 *
 * ⚠ ОДНА РЕАЛИЗАЦИЯ НА ОДИН СМЫСЛ. До 02.09 строка `bindings[a.id] ?? a.defaults`
 * стояла в четырёх местах: разбор нажатия, шпаргалка, заслон клавиши приёма и
 * экран настройки. Пока правило было одно, это сходило с рук; с появлением
 * «выключено по умолчанию» четыре копии разъехались бы на первой же правке — и
 * разъезд выглядел бы как «в справке одно, а работает другое».
 *
 * Порядок ответа: личная настройка (включая ПУСТОЙ список — это «выключил
 * сам»), иначе умолчание, а у выключенных по умолчанию — ничего.
 */
export function действующие(
  a: HotkeyAction,
  bindings: Readonly<Record<string, readonly Binding[]>> = {},
): readonly Binding[] {
  const свои = bindings[a.id];
  if (свои) return свои;
  return a.offByDefault ? ПУСТО : a.defaults;
}

/**
 * Подпись для действия, у которого сочетаний нет.
 *
 * ⚠ ПУСТОЙ СПИСОК — ЭТО «ВЫКЛЮЧЕНО», А НЕ «НЕИЗВЕСТНО» (просьба владельца
 * 02.09: «сделать возможность отдельно выключать комбинации клавиш»).
 *
 * Разбор нажатия и так молчит на пустом списке (`dispatch.actionFor`:
 * `bindings[a.id] ?? a.defaults`, а `[].includes(...)` ложь), поэтому выключение
 * не потребовало ни новой схемы, ни нового поля. Но в шпаргалке пустая ячейка
 * читается как «не знаем» — а человек обязан видеть, что ЭТО ОН выключил, иначе
 * он будет искать поломку там, где её нет.
 */
const ВЫКЛЮЧЕНО = "выключено";

/** Реестр → строки справки, с учётом личных переназначений. */
export function hotkeyRows(bindings: Readonly<Record<string, readonly Binding[]>> = {}): Hotkey[] {
  const rows: Hotkey[] = [];
  for (const a of ACTIONS) {
    const свои = действующие(a, bindings);
    const keys = свои.length ? formatBindings(свои) : ВЫКЛЮЧЕНО;
    if (a.pairWithPrev && rows.length > 0) {
      const прежняя = rows[rows.length - 1];
      /*
       * Пара («следующий/предыдущий») показывается одной строкой. Если одну
       * половину выключили, приписывать «/ выключено» к другой значило бы
       * сказать неправду про обе: половина-то работает. Показываем ту, что
       * осталась; выключены обе — так и пишем.
       */
      if (свои.length) {
        прежняя.keys = прежняя.keys === ВЫКЛЮЧЕНО ? keys : `${прежняя.keys} / ${keys}`;
      }
      continue;
    }
    rows.push({ id: a.id, keys, what: a.what, need: a.need });
  }
  return rows;
}

/** Что показывать человеку с этим набором прав (FUNC-35). */
export function hotkeysFor(
  can: (p: Permission) => boolean,
  bindings?: Readonly<Record<string, readonly Binding[]>>,
): ReadonlyArray<Hotkey> {
  return hotkeyRows(bindings).filter((h) => !h.need || can(h.need));
}

/** Как действие называется в редакторе клавиш, тосте и для экранного диктора. */
export function actionLabel(a: HotkeyAction): string {
  return a.editorLabel ?? a.what;
}

/** Действия, которые человек вправе переназначить. */
export function assignableActions(): readonly HotkeyAction[] {
  return ACTIONS.filter((a) => !a.fixed);
}
