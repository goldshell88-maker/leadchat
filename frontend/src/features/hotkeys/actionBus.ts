import { create } from "zustand";

/**
 * Шина действий (UX-аудит, docs/17 §Т7).
 *
 * Устроена как шина фокуса и по той же причине: обработчик клавиш — обычный
 * слушатель `keydown` на окне, хуки в нём вызывать нельзя, а «принять»,
 * «отклонить» и «закрыть» живут мутациями внутри компонентов. Клавиша
 * поднимает счётчик, владелец мутации на него подписан и делает работу.
 *
 * Зачем это вообще. Принятие и закрытие — единственные действия, которые
 * оператор совершает РОВНО ПО РАЗУ на каждый диалог, то есть чаще всего
 * остального. При этом до сих пор они были доступны только мышью, а клавиши
 * были розданы редкому: режиму заметки и переключению вкладок. В Jivo, откуда
 * переезжает команда, принятие — Ctrl+Space, решение — Ctrl+D; человек
 * приходит с этой привычкой и упирается в мышь.
 *
 * Счётчик, а не булев флаг: два принятия подряд обязаны быть двумя событиями,
 * иначе второе потеряется.
 *
 * ⚠ У ЗАКРЫТИЯ СЧЁТЧИКА МАЛО — НУЖЕН АДРЕС (жалоба владельца 07.09: «не
 * всегда получается быстро закрывать диалоги через комбинацию клавиш, иногда
 * она слетает и приходится снова кликать на диалог»).
 *
 * Закрытие — единственное действие, после которого человек СРАЗУ оказывается
 * в другом диалоге: панель ленты пересоздаётся под новый `convId`
 * (`<ThreadView key={convId} />`), а её обработчик запоминает номер просьбы
 * НА МОМЕНТ СВОЕГО РОЖДЕНИЯ. Нажатие, попавшее в промежуток между уходом
 * старой панели и рождением новой, поднимало счётчик — и новая панель
 * считала его уже виденным. Клавиша срабатывала «через раз», и человек шёл
 * за мышью.
 *
 * Адрес снимает и это, и вторую беду: просьба, сделанная для диалога, чья
 * карточка ещё не приехала с сервера, теперь ЖДЁТ данных вместо того, чтобы
 * молча пропасть. Обработчик берётся за неё, когда узнаёт, что закрывать.
 *
 * ⚠ И ПРОСЬБА ОБЯЗАНА СНИМАТЬСЯ, КОГДА ЕЁ ИСПОЛНИЛИ (бой 08.09: 69 отказов
 * 403 за три часа, из них 62 за одну минуту — по 4 запроса в секунду в один и
 * тот же диалог).
 *
 * Отметка «эту просьбу я уже сделал» жила ССЫЛКОЙ ВНУТРИ ПАНЕЛИ, а панель
 * рождается заново на каждый диалог (`<ThreadView key={convId} />`). Круг
 * замыкался так: закрытие уводит человека к следующему диалогу ещё до ответа
 * сервера, сервер отказывает, отказ возвращает человека назад — панель
 * рождается второй раз, отметки в ней уже нет, а просьба всё ещё висит в шине
 * с прежним адресом. Она исполняется снова, снова получает отказ и снова
 * возвращает человека. Выход из круга был один: чтобы отказ перестал быть
 * отказом. В бою круг оборвался тем, что коллега принял диалог, — и 63-я
 * попытка ЗАКРЫЛА живой разговор, который он взял за 32 мс до этого.
 *
 * Поэтому просьба здесь — не счётчик, а предмет: ровно один на всю программу,
 * и панель, взявшаяся за него, снимает его с шины (`closeHandled`). Сравнение
 * идёт ПО САМОМУ ПРЕДМЕТУ, а не по номеру: пока панель решала, человек мог
 * попросить снова — снять чужую, более свежую просьбу мы не имеем права.
 *
 * ⚠ ШИНОЙ ПОЛЬЗУЮТСЯ НЕ ТОЛЬКО КЛАВИШИ (07.09). Кнопки «Принять» и
 * «Отклонить» ВНУТРИ браузерного уведомления просят ровно то же, что кнопки
 * на экране, и обязаны идти тем же путём: у передачи это не один POST, а
 * ещё и правка кэша детали, строки списка и счётчиков вкладок
 * (`TransferBar::применитьИтог`, шесть разобранных боевых случаев). Второй
 * путь к тем же полям разошёлся бы с первым на первой правке — этот класс
 * дефектов мы ловили уже трижды.
 */
/**
 * Просьба закрыть диалог. `null` — просьбы нет: ни одной не делали, либо
 * последнюю уже исполнили.
 *
 * `в` — время просьбы, по нему её признают протухшей (тот же довод, что у
 * `transferDecision` ниже): панель, которой она адресована, может не родиться
 * вовсе, и просьба висела бы вечно, чтобы через час выстрелить в спину — сама
 * закрыть диалог, который человек всего лишь открыл посмотреть.
 */
export interface ПросьбаЗакрыть {
  convId: string;
  в: number;
}

interface ActionState {
  claimNonce: number;
  declineNonce: number;
  closeRequest: ПросьбаЗакрыть | null;
  transferNonce: number;
  transferDecisionNonce: number;
  /**
   * Решение по передаче, о котором попросили извне экрана (кнопка в
   * уведомлении). Адрес обязателен по той же причине, что у закрытия:
   * просьбу делают ДО перехода в диалог, и панель, которая её исполнит,
   * родится позже. `в` — время просьбы: панель не берётся за протухшую,
   * иначе оставленная без исполнителя просьба выстрелила бы по СЛЕДУЮЩЕЙ
   * передаче в том же диалоге, которой человек не видел.
   */
  transferDecision: { convId: string; kind: "accept" | "decline"; в: number } | null;
  requestClaim(): void;
  requestDecline(): void;
  requestClose(convId: string): void;
  /** Снять просьбу с шины — её исполнили или признали протухшей. */
  closeHandled(req: ПросьбаЗакрыть): void;
  requestTransfer(): void;
  requestTransferDecision(convId: string, kind: "accept" | "decline"): void;
  /**
   * Снять решение с шины — его исполнили. Иначе новая передача того же
   * диалога в пределах ЖИЗНЬ_ПРОСЬБЫ_МС рождала панель, которая исполняла
   * старое решение ещё раз — по предложению, которого человек не видел.
   */
  transferDecisionHandled(req: ActionState["transferDecision"]): void;
}

export const useActionBus = create<ActionState>()((set) => ({
  claimNonce: 0,
  declineNonce: 0,
  closeRequest: null,
  transferNonce: 0,
  transferDecisionNonce: 0,
  transferDecision: null,
  requestClaim: () => set((s) => ({ claimNonce: s.claimNonce + 1 })),
  requestDecline: () => set((s) => ({ declineNonce: s.declineNonce + 1 })),
  // Каждое нажатие — НОВЫЙ предмет, даже если диалог тот же и та же
  // миллисекунда: два закрытия подряд обязаны быть двумя событиями.
  requestClose: (convId) => set({ closeRequest: { convId, в: Date.now() } }),
  closeHandled: (req) => set((s) => (s.closeRequest === req ? { closeRequest: null } : {})),
  requestTransfer: () => set((s) => ({ transferNonce: s.transferNonce + 1 })),
  requestTransferDecision: (convId, kind) =>
    set((s) => ({
      transferDecisionNonce: s.transferDecisionNonce + 1,
      transferDecision: { convId, kind, в: Date.now() },
    })),
  transferDecisionHandled: (req) =>
    set((s) => (s.transferDecision === req ? { transferDecision: null } : {})),
}));

/**
 * Сколько живёт непринятая просьба — решение по передаче из уведомления и
 * просьба закрыть диалог.
 *
 * ⚠ СРОК ЗДЕСЬ НЕ ДЛЯ ПОРЯДКА, А ПРОТИВ ВЫСТРЕЛА В СПИНУ. Панель передачи
 * рождается, только пока предложение висит. Нажали «Принять» в уведомлении
 * через минуту после того, как передачу отменили, — панели нет, и просьба
 * осталась бы в шине навсегда. Тому же диалогу через час предлагают передачу
 * снова, панель рождается — и принимает её САМА, без человека. Полторы
 * минуты с запасом покрывают переход и загрузку детали (в бою p50 перехода
 * 60 мс) и не покрывают ничего сверх того.
 */
export const ЖИЗНЬ_ПРОСЬБЫ_МС = 90_000;

export function requestClaim(): void {
  useActionBus.getState().requestClaim();
}

export function requestDecline(): void {
  useActionBus.getState().requestDecline();
}

export function requestClose(convId: string): void {
  useActionBus.getState().requestClose(convId);
}

export function requestTransfer(): void {
  useActionBus.getState().requestTransfer();
}

export function requestTransferDecision(convId: string, kind: "accept" | "decline"): void {
  useActionBus.getState().requestTransferDecision(convId, kind);
}
