import { useSessionStore } from "@/shared/stores/sessionStore";
import { formatBindings } from "./binding";
import { ACTIONS, действующие, type ActionId } from "./catalog";

/**
 * Действующее сочетание для подписи в интерфейсе — или пустая строка, если
 * сочетания нет.
 *
 * ⚠ ЗАЧЕМ ЭТО ПОЯВИЛОСЬ (аудит 08.09, H-06). Приложение обещало «Ctrl+K» в
 * ЧЕТЫРЁХ местах — в подсказке значка поиска, в его `aria-label`, на пустом
 * экране ленты и значком прямо в поле поиска, — а действие `search` объявлено
 * `offByDefault: true` (catalog.ts). То есть по умолчанию сочетание не
 * привязано ни к чему и НЕ РАБОТАЕТ. Человек читает подпись, жмёт и делает
 * единственный доступный вывод: сломалось.
 *
 * ⚠ И ВТОРАЯ ПОЛОВИНА БЕДЫ, МЕНЕЕ ЗАМЕТНАЯ. Сочетания переназначаются
 * (`/settings/profile`, вкладка «Интерфейс»). Зашитая строка «Ctrl+K» врала бы
 * и тому, кто включил поиск на другую клавишу: подпись показывала бы чужое
 * сочетание. Спрашивать надо у того же источника, у которого спрашивает разбор
 * нажатия, — иначе подпись и поведение разъедутся на первой же правке.
 *
 * Пустую строку возвращаем НАМЕРЕННО, а не слово «выключено»: в шпаргалке
 * (`hotkeyRows`) человек ищет, что он выключил, и там «выключено» — ответ на
 * его вопрос. В подсказке значка это был бы шум: ему предлагают нажать мышью,
 * а не рассказывают про клавиатуру.
 */
/*
 * ⚠ ИМЯ ХУКА ЛАТИНИЦЕЙ, И ЭТО НЕ ВКУСОВЩИНА. Правило `react-hooks/rules-of-hooks`
 * узнаёт хук по образцу `^use[A-Z0-9]`, а он ASCII-only: `useСочетание` с
 * кириллической «С» правило хуком НЕ считает и валит прогон линтера словами
 * «вызов хука вне компонента». Проверено здесь же 08.09. Обычные функции рядом
 * (`сПодписью`) остаются по-русски — на них правило не смотрит.
 */
export function useShortcutLabel(id: ActionId): string {
  const bindings = useSessionStore((s) => s.hotkeys);
  const действие = ACTIONS.find((a) => a.id === id);
  if (!действие) return "";
  return formatBindings(действующие(действие, bindings));
}

/** «Поиск по диалогам — Ctrl + K», а без сочетания — просто «Поиск по диалогам». */
export function сПодписью(текст: string, сочетание: string): string {
  return сочетание ? `${текст} — ${сочетание}` : текст;
}
