/**
 * Зажатая стрелка листания едет по списку не чаще шага в `HELD_STEP_MS`.
 *
 * Браузер шлёт автоповтор до тридцати раз в секунду, и каждый шаг открывает
 * диалог: при таком темпе личная планка nginx кончалась за секунды (разбор — в
 * `features/chats/keyboardStepping.ts`). Шесть-семь диалогов в секунду глаз ещё
 * успевает читать, а отдельные нажатия не притормаживаются вовсе: ограничен
 * только автоповтор.
 */
const HELD_STEP_MS = 150;
const LIST_STEPS: ReadonlySet<ActionId> = new Set<ActionId>([
  "listNext",
  "listPrev",
  "unreadNext",
  "unreadPrev",
]);
let lastListStepAt = -Infinity;

function heldStepTooSoon(e: KeyboardEvent, id: ActionId): boolean {
  if (!LIST_STEPS.has(id)) return false;
  const now = performance.now();
  if (e.repeat && now - lastListStepAt < HELD_STEP_MS) return true;
  lastListStepAt = now;
  return false;
}

/**
 * Реестр горячих клавиш рабочего места — КАНОН 10 §5.1. Одна точка регистрации:
 * конфликты видны в коде (Ctrl+K живёт в useGlobalHotkeys — он нужен и вне /chats).
 *
 * | Ctrl+↓ / Ctrl+↑ | следующий/предыдущий диалог (включено по умолчанию)|
 * | Alt+↓ / Alt+↑ | следующий/предыдущий диалог С НЕПРОЧИТАННЫМИ         |
 * | Alt+0         | очередь «Входящие» (отдельный ресурс, не вкладка)    |
 * | Alt+1..4      | Мои / Все / Новые / Закрытые (последние два — фильтр) |
 * | Enter         | открыть выбранный диалог, фокус в композер           |
 * | Ctrl+Enter    | отправить сообщение (привычка из Jivo/Telegram)      |
 * | Ctrl+R        | принять диалог (как в Jivo)                          |
 * | Ctrl+D        | отметить решённым (как в Jivo)                       |
 * | Ctrl+T        | передать диалог (как в Jivo)                         |
 * | J/K, ↓/↑      | то же листание, если человек назначил их себе сам    |
 * | Ctrl+Backspace| отклонить диалог (своё: в Jivo отказа нет)           |
 * | Ctrl+Shift+N  | режим заметки                                        |
 * | Esc           | «луковица»: оверлей карточки → режим заметки → поиск |
 *
 * Все хоткеи продублированы видимыми элементами UI — клавиатура ускоряет,
 * но ничего не прячет.
 *
 * ⚠ У ЛИСТАНИЯ ЭТОТ ДУБЛЬ — САМ СПИСОК СЛЕВА, А НЕ КНОПКА В ШАПКЕ (09.09).
 * Шевроны «предыдущий/следующий» владелец велел убрать, и правило не нарушено:
 * сменить диалог мышью по-прежнему можно щелчком по строке, а ниже 768px — по
 * «Назад к списку» и строке. Цена там два касания вместо одного; сами шевроны
 * на телефоне и не работали (без кэша списка обе кнопки приходили погашенными).
 */

/**
 * Что открывают Alt+1..4 — ровно то же, что четыре бывшие вкладки.
 *
 * Вкладок в ряду теперь две («Мои», «Все»), состояние переехало в фильтр
 * «Статус». Но клавиши осталось четыре и делают они прежнее: у людей,
 * привыкших к Alt+3 как к «новым», не должно ничего сломаться от того, что мы
 * переставили кнопки. Alt+3 и Alt+4 просто ставят вкладку «Все» с нужным
 * статусом — это и есть то же самое множество диалогов.
 */
/**
 * Диалоги в порядке отрисовки — из кэша ТОЙ выдачи, что сейчас на экране
 * (UX-аудит, docs/17 §Т7).
 *
 * Раньше здесь всегда читался кэш обычного списка, даже когда открыта очередь.
 * Стрелки и J/K во «Входящих» ходили по остаткам прошлой выдачи и молча
 * уносили оператора в диалог, которого на экране нет, — клавиатурой очередь
 * было не разобрать вовсе.
 *
 * ⚠ САМ РАСЧЁТ ПЕРЕЕХАЛ В `chats/списокНаЭкране` (05.09), и это не уборка.
 * Кнопки «предыдущий/следующий» в шапке ленты листают ТОТ ЖЕ список, что и
 * клавиши; две копии «кто следующий» на одном экране в этом проекте уже
 * расходились трижды — разбор в шапке того модуля.
 */
function cachedRows() {
  return строкиНаЭкране();
}

function isTypingTarget(target: EventTarget | null): boolean {
  const el = target as HTMLElement | null;
  if (!el || !el.tagName) return false;
  const tag = el.tagName.toLowerCase();
  return tag === "input" || tag === "textarea" || tag === "select" || el.isContentEditable;
}

/**
 * Общий разбор для обоих хуков: найти действие в таблице и выполнить.
 *
 * ⚠ `preventDefault` ТОЛЬКО КОГДА ДЕЙСТВИЕ ДЕЙСТВИТЕЛЬНО СРАБОТАЛО. Прежний код
 * местами гасил событие до проверки «а есть ли что делать», местами после, и это
 * было видно на стрелках: при пустом списке ↓ переставала двигать курсор в поле.
 * Теперь правило одно — не сделали ничего, значит клавиша чужая.
 *
 * Esc — исключение: он не гасится никогда. Это договор с браузером («отменить»),
 * и перехватывать его, ничего не сделав, значит отнимать у человека выход.
 */
/**
 * Открыт ли поверх экрана свой слой — окно, ящик, поповер быстрых ответов.
 *
 * ⚠ ЗАЧЕМ. В `dispatch.луковица()` написано «меню и модальные окна гасят
 * событие раньше, до нас оно не доходит». Это неправда: Mantine закрывает окно
 * из своего обработчика и распространение НЕ останавливает, а наши слушатели
 * висят на `window`. Значит один Esc над открытым окном срабатывал ДВАЖДЫ:
 * закрывал окно и следом снимал слой под ним — карточку клиента, режим
 * заметки или поисковый запрос. Оператор жал «передумал» над окном «Передать
 * диалог», а вместе с окном терял ещё и открытую карточку.
 *
 * Правило шире одного Esc и потому надёжнее: пока сверху лежит чужой слой,
 * экранные сочетания молчат ВСЕ. Иначе Ctrl+D поверх открытого окна закрывает
 * диалог, до которого человек в этот момент даже не может дотянуться мышью.
 *
 * Признак — `role="dialog"`/`"alertdialog"` в документе. Его ставит и Mantine
 * своим окнам, и наш поповер быстрых ответов (`TemplatePickerPopover`).
 * Держать вместо этого свой счётчик открытых окон значило бы просить каждое
 * новое окно о нём помнить — а забытое окно вернуло бы дефект молча.
 */
function слойСверху(): boolean {
  return document.querySelector('[role="dialog"], [role="alertdialog"]') !== null;
}

/**
 * Есть ли в открытом диалоге НЕОТПРАВЛЕННЫЙ текст.
 *
 * ⚠ ЭТО ЗАМОК НА ВЕСЬ РАЗБОР ЖАЛОБЫ 30.08. Пока в поле лежит набранное,
 * КЛАВИАТУРА диалог не меняет — ни шагом по списку, ни переходом к следующему
 * в очереди. Мышь по-прежнему может: осознанный клик по другому клиенту — это
 * выбор человека, а нажатие Ctrl+↓ посреди слова выбором не было.
 *
 * Проверяется именно набранное, а не «стоит ли курсор в поле». Оператор мог
 * дописать ответ, щёлкнуть в ленту, чтобы перечитать вопрос клиента, и нажать
 * стрелку — текст всё это время цел, и терять его так же обидно.
 *
 * Пустой черновик не держит ничего: разбирать очередь с клавиатуры (просьба
 * владельца 22.08) и уходить к следующему, передумав отвечать, можно как
 * раньше.
 */
function держитНабранное(action: HotkeyAction): boolean {
  if (!МЕНЯЮТ_ОТКРЫТЫЙ_ДИАЛОГ.has(action.id)) return false;
  const { activeConversationId, drafts } = useChatUiStore.getState();
  if (!activeConversationId) return false;
  return (drafts[activeConversationId]?.text ?? "").trim().length > 0;
}

function handle(e: KeyboardEvent, ctx: RunContext, scope: "global" | "chats"): void {
  if (слойСверху()) return;
  // Личные сочетания читаются из стора НА КАЖДОЕ нажатие, а не замыкаются в эффекте:
  // человек может переназначить клавишу и тут же ею воспользоваться, не перезагружая
  // страницу. Чтение из zustand — это доступ к полю, платить за него нечем.
  const action = actionFor(e, isTypingTarget(e.target), useSessionStore.getState().hotkeys);
  if (!action) return;
  // Зажатая клавиша не повторяет то, что меняет состояние диалога (29.08).
  // Браузер шлёт `keydown` десятки раз в секунду, пока клавишу держат.
  if (e.repeat && БЕЗ_АВТОПОВТОРА.has(action.id)) return;
  // Набранное держит диалог: клавиша не уносит человека из недописанного ответа.
  if (держитНабранное(action)) return;
  const global = GLOBAL_ACTIONS.has(action.id);
  if (scope === "global" ? !global : global) return;
  // Приём уже обработан заслоном на перехвате — второй раз не зовём.
  if (ГАСИМ_ДАЖЕ_ВПУСТУЮ.has(action.id)) return;
  if (heldStepTooSoon(e, action.id)) {
    e.preventDefault();
    return;
  }
  const сделано = runAction(action.id, ctx);
  // Ctrl+R не должен доставаться браузеру даже впустую: «перезагрузить вместо
  // принять» стоит человеку набранного текста (разбор — в catalog.ts).
  const гасим = сделано || ГАСИМ_ДАЖЕ_ВПУСТУЮ.has(action.id);
  if (гасим && action.id !== "escape") e.preventDefault();
}

/**
 * Заслон клавиши приёма — ОТДЕЛЬНЫМ ХУКОМ И НА ВЕСЬ ПРИЛОЖЕНИЕ.
 *
 * ⚠ ПОЧЕМУ ВЫНЕСЕН (жалоба владельца 31.08, третий раз: «Ctrl+R так и
 * перезагружает мне страницу»). Заслон был, работал и доехал в боевую сборку —
 * но жил внутри `useChatHotkeys`, а тот монтируется ТОЛЬКО на экране чатов.
 * Стоило открыть настройки, статистику или разбор диалогов — и клавиша снова
 * доставалась браузеру со всеми последствиями: перезагрузка рабочего места,
 * потерянный набранный ответ.
 *
 * Теперь он висит в раскладке приложения, то есть везде. Это заодно и есть
 * просьба «принимать диалоги из любой вкладки, не заходя во Входящие»: с
 * любого экрана клавиша берёт следующего ждущего и открывает его.
 */
/**
 * Идёт ли прямо сейчас запись нового сочетания в настройках.
 *
 * ⚠ ЗАВЕДЕНО ПОСЛЕ СОБСТВЕННОЙ РЕГРЕССИИ 31.08. Заслон клавиши приёма стал
 * глобальным — и переназначение сочетания превратилось в ловушку: человек
 * жмёт «изменить» у строки «Принять диалог», нажимает Ctrl+R, чтобы задать
 * его, — а заслон честно ПРИНИМАЕТ живой диалог и уносит человека из настроек
 * в чужую переписку.
 *
 * Пока редактор ждёт нажатия, клавиши не выполняются: он их записывает.
 */
let идётЗапись = false;

/** Настройки сообщают, что ждут нажатия (и что перестали ждать). */
export function записьСочетания(включена: boolean): void {
  идётЗапись = включена;
}

export function useClaimKeyGuard(): void {
  const navigate = useNavigate();

  useEffect(() => {
    const ctx: RunContext = { navigate, rows: cachedRows, can: () => true };
    const наПерехвате = (e: KeyboardEvent) => {
      const нажато = bindingOf(e);
      if (!нажато) return;
      const приём = ACTIONS.find((a) => a.id === "claim");
      if (!приём || !действующие(приём, useSessionStore.getState().hotkeys).includes(нажато)) {
        return;
      }
      // Голое сочетание при наборе — клавиша поля, как у всех действий
      // (`firesWhileTyping`), а поверх окна — клавиша окна. Приём у четырёх
      // сотрудников стоит на Tab: заслон, гасивший его везде, в поле пароля
      // забирал из очереди чужой диалог вместо перехода к следующему полю.
      if (isTypingTarget(e.target) && !firesWhileTyping(приём, нажато)) return;
      if (слойСверху() && !нажато.includes("+")) return;
      // Сначала гасим — потом решаем, что делать. Обратный порядок и был бедой.
      e.preventDefault();
      // Настройки ждут нажатия — оно принадлежит им, а не приёму диалога.
      if (идётЗапись) return;
      if (e.repeat) return; // зажатую клавишу не повторяем (29.08)
      if (слойСверху()) return; // поверх окна принимать нечего, но и грузиться незачем
      runAction("claim", ctx);
    };
    window.addEventListener("keydown", наПерехвате, true);
    return () => window.removeEventListener("keydown", наПерехвате, true);
  }, [navigate]);

}

export function useChatHotkeys(): void {
  const navigate = useNavigate();

  useEffect(() => {
    const ctx: RunContext = { navigate, rows: cachedRows, can: () => true };
    const onKeyDown = (e: KeyboardEvent) => handle(e, ctx, "chats");
    window.addEventListener("keydown", onKeyDown);
    return () => window.removeEventListener("keydown", onKeyDown);
  }, [navigate]);
}

/**
 * Ctrl+K и «?» — глобально (11 §8.4): внутри /chats фокусирует поле поиска, с любого
 * другого экрана переводит в /chats и фокусирует его же.
 *
 * Отдельный хук, потому что монтируется в раскладке приложения, а не на экране
 * чатов, — и именно точка монтирования и есть сегодняшняя «область действия».
 */
export function useGlobalHotkeys(): void {
  const navigate = useNavigate();

  useEffect(() => {
    const ctx: RunContext = { navigate, rows: cachedRows, can: () => true };
    const onKeyDown = (e: KeyboardEvent) => handle(e, ctx, "global");
    window.addEventListener("keydown", onKeyDown);
    return () => window.removeEventListener("keydown", onKeyDown);
  }, [navigate]);
}
