/**
 * Разбор «/команды» прямо в поле ввода — как в Jivo.
 *
 * ⚠ ЧТО БЫЛО НЕ ТАК (слова владельца: «он так и неудобный, сделай точный и
 * продуманный аналог, который был сделан на Jivo»).
 *
 * Прежний вызов работал так: «/» открывало попап, попап забирал фокус в СВОЁ
 * поле поиска, и человек набирал запрос второй раз — первый раз он уже нажал
 * «/» в сообщении. Две строки ввода на одну мысль, и ни одна из них не видна
 * там, где человек смотрит.
 *
 * В Jivo строка одна и живёт в самом сообщении: набрал «/цена» — под полем
 * отфильтровался список, стрелки водят метку, Enter подставляет текст ВМЕСТО
 * набранной команды. Поле ввода при этом не теряет фокус ни на миг.
 *
 * ⚠ КОМАНДА НАЧИНАЕТСЯ ТОЛЬКО С НАЧАЛА СТРОКИ ИЛИ ПОСЛЕ ПРОБЕЛА. Косая черта
 * посреди слова — обычный знак, и им пишут живые вещи: «ул. Testoвая 5/2»,
 * «и/или», «09:00/18:00». Открывайся список на каждой из них — он мешал бы
 * ровно тем, кто быстро печатает адрес.
 *
 * ⚠ ПЕРЕВОД СТРОКИ КОМАНДУ ОБРЫВАЕТ. Команда — это одна строка; иначе «/» в
 * первом абзаце считался бы началом команды до конца сообщения.
 */

export interface Команда {
  /** Позиция самой «/» в тексте. */
  от: number;
  /** Набранное после «/» до каретки. */
  запрос: string;
}

/**
 * Сколько букв после «/» ещё считаем командой.
 *
 * Названия заготовок в бою — до 28 знаков («Территориально не подходит»), так
 * что предел щедрый. Он не про поиск, а про то, чтобы забытая открытой
 * команда не тянулась через всё сообщение.
 */
const ПРЕДЕЛ = 60;

/**
 * Команда под кареткой — или `null`, если её там нет.
 *
 * `caret` — позиция каретки (`selectionStart`). Смотрим НАЗАД от неё: то, что
 * человек написал справа от каретки, к текущей команде не относится.
 */
export function найтиКоманду(text: string, caret: number): Команда | null {
  const позиция = Math.max(0, Math.min(caret, text.length));
  for (let i = позиция - 1; i >= 0 && позиция - i <= ПРЕДЕЛ + 1; i--) {
    const знак = text[i];
    if (знак === "\n") return null; // команда живёт в одной строке
    if (знак !== "/") continue;
    // Начало строки или пробел перед «/» — только тогда это команда.
    const перед = i === 0 ? "" : text[i - 1];
    if (перед !== "" && !/\s/u.test(перед)) return null;
    return { от: i, запрос: text.slice(i + 1, позиция) };
  }
  return null;
}
