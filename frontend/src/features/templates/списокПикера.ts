/**
 * ЧТО и В КАКОМ ПОРЯДКЕ показывает пикер быстрых ответов.
 *
 * ⚠ ОДИН ИСТОЧНИК НА ДВА МЕСТА. Список нужен сразу двоим: попапу — чтобы его
 * нарисовать, и полю ввода — чтобы знать, сколько в нём строк, и водить по ним
 * метку стрелками. Посчитай каждый по-своему — метка поедет мимо строки, и
 * человек вставит клиенту не то, на что смотрел. Этот класс ошибки в LeadChat
 * уже разбирали: два пути считали одно поле по-разному.
 */

import type { TemplateDto } from "@/shared/api/types";
import { содержит } from "./поиск";

export interface Группа {
  key: string;
  label: string;
  items: TemplateDto[];
}

/**
 * Сколько ходовых поднимаем наверх отдельной группой.
 *
 * ⚠ ЗАМЕР БОЯ 03.09. Пикер сортировал строго по алфавиту и выбрасывал
 * частоту, которую сам же копит: «Здравствуйте» с 586 применениями стояло
 * 32-й строкой из 64, а в окно помещается пять. То есть до самой ходовой
 * заготовки надо было прокрутить шесть экранов — при том, что верхние восемь
 * заготовок дают 57 % всех вставок.
 *
 * Пять, а не двадцать: смысл группы в том, чтобы её было видно целиком.
 */
export const ХОДОВЫХ = 5;

/**
 * Ходовые — ОТДЕЛЬНОЙ группой и БЕЗ ДУБЛЕЙ в папках.
 *
 * ⚠ ПОЧЕМУ НЕ ДУБЛИРОВАТЬ, ХОТЯ ТАК ДЕЛАЮТ СОСЕДИ. Строки в списке — цели для
 * стрелок и Enter, и порядок обхода считается по плоскому списку. Появись
 * заготовка дважды — метка подсветила бы обе строки разом, а `indexOf` вернул
 * бы первую: человек стоит на одной, Enter вставляет другую.
 *
 * Цена решения честная: заготовка, поднятая наверх, исчезает из своей папки, и
 * мышечная память «Здравствуйте лежит в Открытии» перестаёт работать. Но
 * искать её теперь и не нужно — она первая, а поиск находит её в любом случае.
 */
function ходовые(items: TemplateDto[]): TemplateDto[] {
  return items
    .filter((t) => (t.used_count ?? 0) > 0)
    .slice()
    .sort((a, b) => (b.used_count ?? 0) - (a.used_count ?? 0))
    .slice(0, ХОДОВЫХ);
}

/** Группировка «ОБЩИЕ · Папка» / «МОИ · Папка» (11 §3.1). */
function поПапкам(items: TemplateDto[]): Группа[] {
  const map = new Map<string, Группа>();
  for (const t of items) {
    const scope = t.owner_id === null ? "ОБЩИЕ" : "МОИ";
    const key = `${scope}|${t.folder ?? ""}`;
    const label = t.folder ? `${scope} · ${t.folder}` : scope;
    const group = map.get(key);
    if (group) group.items.push(t);
    else map.set(key, { key, label, items: [t] });
  }
  // Общие идут первыми (в макете 11 §3.1 — ОБЩИЕ, затем МОИ).
  return Array.from(map.values()).sort((a, b) => {
    const sa = a.label.startsWith("ОБЩИЕ") ? 0 : 1;
    const sb = b.label.startsWith("ОБЩИЕ") ? 0 : 1;
    return sa === sb ? a.label.localeCompare(b.label, "ru") : sa - sb;
  });
}

/**
 * Подходит ли заготовка под запрос.
 *
 * ⚠ ТЕ ЖЕ ПРАВИЛА СРАВНЕНИЯ, ЧТО У ПОЛОСЫ ПОДСКАЗОК. Два поиска по одним
 * данным, работающие по-разному, — это когда «еще» находит заготовку в одном
 * месте и не находит в другом. Правила живут в `features/templates/поиск`, и
 * папка тоже ищется: набрал «Открытие» — нашлись заготовки этой папки, хотя
 * раньше не находилось ничего, а папка при этом нарисована в списке.
 */
export function подходитПикеру(t: TemplateDto, q: string): boolean {
  return содержит(t.title, q) || содержит(t.body, q) || содержит(t.folder ?? "", q);
}

/**
 * Готовый список пикера: группы для отрисовки и плоский порядок для стрелок.
 *
 * ⚠ ГРУППА «ЧАСТЫЕ» — ТОЛЬКО ПРИ ПРОСМОТРЕ, НЕ ПРИ ПОИСКЕ. Человек, который
 * набрал запрос, уже сказал, что ему нужно; поднимать поверх его слов
 * что-то своё значит спорить с ним. При пустом запросе он именно
 * ПРОСМАТРИВАЕТ — вот там частота и отвечает на вопрос «с чего начать».
 */
export function подготовить(
  items: readonly TemplateDto[],
  query: string,
): { groups: Группа[]; ordered: TemplateDto[] } {
  const flat = items.filter((t) => подходитПикеру(t, query));
  const groups = (() => {
    if (query.trim()) return поПапкам(flat);
    const верх = ходовые(flat);
    if (верх.length === 0) return поПапкам(flat);
    const поднятые = new Set(верх.map((t) => t.id));
    return [
      { key: "часто", label: "ЧАСТЫЕ", items: верх },
      ...поПапкам(flat.filter((t) => !поднятые.has(t.id))),
    ];
  })();
  return { groups, ordered: groups.flatMap((g) => g.items) };
}
