/**
 * Как сравниваются буквы при поиске заготовок. ОДНА функция на все места.
 *
 * ⚠ ЗАМЕР БОЯ 03.09. Сравнение шло буквально, и «ё» ломала подсказку молча.
 * Диспетчер набирает так, как привык, — «еще», «все», — а заготовка записана
 * правильно: «Вам помощь ещё требуется?», «У вас всё в наличии уже есть?».
 * Подсказка не появлялась вовсе.
 *
 * Насколько это часто: за тридцать суток в исходящих «еще требуется» — 373
 * раза против «ещё требуется» 73; «все в наличии» — 197 против 4. То есть в
 * подавляющем большинстве случаев человек набирал вариант, по которому
 * подсказка молчала.
 *
 * Есть и прямой след промаха: отправленное «Вам помощь еще Вам помощь ещё
 * требуется?» — пять раз за месяц. Человек набрал «еще», подсказка не
 * ответила, он полез в пикер, а тот дописал заготовку к набранному.
 *
 * ⚠ НОРМАЛИЗУЕМ ТОЛЬКО СРАВНЕНИЕ, А НЕ ТЕКСТ. В отправляемом клиенту
 * сообщении «ё» остаётся на месте: правило про буквы поиска не имеет права
 * менять то, что человек прочитает.
 */

/**
 * Привести строку к виду, в котором её сравнивают: нижний регистр, «ё» как
 * «е», лишние пробелы схлопнуты.
 *
 * ⚠ ПРИМЕНЯТЬ К ОБЕИМ СТОРОНАМ СРАВНЕНИЯ. Нормализуй только запрос — и поиск
 * сломается в другую сторону: набранное «ещё» перестанет находить заготовку,
 * записанную через «е».
 */
export function длясравнения(s: string): string {
  return s.toLowerCase().replace(/ё/g, "е").replace(/\s+/gu, " ").trim();
}

/** Содержит ли `текст` подстроку `запрос` по правилам сравнения выше. */
export function содержит(текст: string, запрос: string): boolean {
  const q = длясравнения(запрос);
  return q ? длясравнения(текст).includes(q) : true;
}
