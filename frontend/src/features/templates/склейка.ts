/**
 * Как заготовка встаёт в уже набранный текст.
 *
 * ⚠ ЗАМЕР БОЯ 03.09, И ОН ПРО ЖИВЫХ КЛИЕНТОВ. Тело заготовки вставлялось как
 * есть — с заглавной буквы, — куда бы его ни поставили. Диспетчер набирает
 * «Хорошо, », жмёт заготовку и получает «Хорошо, Когда вам будет удобно меня
 * принять?». За тридцать суток таких сообщений ушло 386, из них 90 за один
 * день; конкретно эта фраза с заглавной отправлена 84 раза против 50 раз
 * правильной. Отозвать сообщение в Авито нечем.
 *
 * Скачок начался ровно 28 августа, когда завели 39 общих заготовок: чем больше
 * ими пользуются, тем чаще видно этот шов.
 */

/**
 * Первое слово — аббревиатура вроде «ТВ» или «СМС»?
 *
 * ⚠ ЕДИНСТВЕННОЕ ИСКЛЮЧЕНИЕ, КОТОРОЕ МОЖНО ОПРЕДЕЛИТЬ НАДЁЖНО. Имя собственное
 * («Авито», «Иван») от обычного начала предложения ничем не отличается — в
 * тексте они выглядят одинаково, и угадывать здесь значит иногда портить
 * название бренда. Аббревиатура же видна по форме: две и больше заглавных
 * подряд. В нынешних 39 общих заготовках имён собственных нет ни одного, а
 * появятся — исключение придётся расширять руками, и это честнее догадки.
 */
function аббревиатура(тело: string): boolean {
  const первое = тело.trimStart().split(/[^\p{L}]/u)[0] ?? "";
  return первое.length >= 2 && первое === первое.toUpperCase() && /\p{Lu}/u.test(первое);
}

/**
 * Продолжаем ли мы начатое предложение — то есть надо ли понизить регистр.
 *
 * `before` — текст ПЕРЕД местом вставки, уже вместе с пробелом-стыком.
 */
export function продолжаетПредложение(before: string): boolean {
  const хвост = before.trimEnd();
  if (!хвост) return false; // начало сообщения — заглавная верна
  if (/\n\s*$/u.test(before)) return false; // новая строка — тоже начало
  /*
   * ⚠ ОДНО УСЛОВИЕ, А НЕ ДВА, И ЭТО ПРОВЕРЕНО ДИВЕРСИЕЙ. Здесь стояла ещё
   * отдельная проверка «кончилось ли предложение» по /[.!?…]/. Она не делала
   * НИЧЕГО: точка, восклицательный знак и закрывающая кавычка и так не входят
   * в набор ниже, то есть отсекались следующей же строкой. Снял её — ни один
   * тест не покраснел, и это был честный ответ: код был мёртвый.
   *
   * Правило простое: фраза продолжается, если перед вставкой стоит буква,
   * цифра или знак, которым предложение не кончают.
   */
  return /[\p{L}\p{N},;:—–-]$/u.test(хвост);
}

/**
 * Тело заготовки, подогнанное под место вставки.
 *
 * Понижаем ТОЛЬКО первую букву и только когда фраза продолжается: всё
 * остальное в тексте заготовки — её собственное, и трогать его нельзя.
 */
export function подогнатьРегистр(before: string, тело: string): string {
  if (!тело || !продолжаетПредложение(before) || аббревиатура(тело)) return тело;
  const первая = тело[0];
  const строчная = первая.toLowerCase();
  // Не буква (цифра, кавычка, эмодзи) — менять нечего.
  return первая === строчная ? тело : строчная + тело.slice(1);
}
