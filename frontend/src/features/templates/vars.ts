/**
 * Подстановка переменных шаблона (01 §7, 11 §3.1) — делает ФРОНТ при вставке,
 * бэкенд хранит body как есть.
 *
 *   {имя}        → имя клиента; нет имени → «Клиент» (10 §7.2: клиента без имени
 *                  так и называем — плейсхолдер менеджеру дописывать нечего)
 *   {менеджер}   → full_name текущего пользователя
 *   {объявление} → item.title диалога
 *
 * Переменная без значения (нет объявления) остаётся плейсхолдером — менеджер
 * видит, что надо дописать (11 §3.1).
 */

export interface TemplateVars {
  clientName?: string | null;
  managerName?: string | null;
  itemTitle?: string | null;
}

/** Клиент без имени: единый фолбэк интерфейса (11 §2.4). */
export const CLIENT_FALLBACK = "Клиент";

const PATTERN = /\{(имя|менеджер|объявление)\}/g;

export function applyTemplateVars(body: string, vars: TemplateVars): string {
  return body.replace(PATTERN, (match, name: string) => {
    switch (name) {
      case "имя":
        return vars.clientName?.trim() || CLIENT_FALLBACK;
      case "менеджер":
        return vars.managerName?.trim() || match;
      case "объявление":
        return vars.itemTitle?.trim() || match;
      default:
        return match;
    }
  });
}

/** Остались ли неподставленные переменные — подсветить менеджеру (11 §3.1). */
export function hasUnresolvedVars(text: string): boolean {
  PATTERN.lastIndex = 0;
  return PATTERN.test(text);
}

/** Кусок текста для показа: обычные буквы или подстановка целиком. */
export interface КусокТекста {
  текст: string;
  подстановка: boolean;
}

/**
 * Разобрать текст на обычные куски и подстановки — чтобы список быстрых
 * ответов мог показать `{имя}` не таким же серым, как остальные слова.
 *
 * ⚠ ЗАЧЕМ ЭТО ВООБЩЕ. В списке настроек текст заготовки — сплошная строка, и
 * подстановка в ней ничем не выделена. А заготовка с незакрытой переменной
 * уходит клиенту в Авито как есть, отозвать сообщение там нечем: разница между
 * «Здравствуйте, Пётр!» и «Здравствуйте, {имя}!» видна только тому, кто знает,
 * куда смотреть.
 *
 * ⚠ ОБРАЗЕЦ ТОТ ЖЕ, ЧТО У ПОДСТАНОВКИ, И ЭТО ГЛАВНОЕ ЗДЕСЬ. Заведи подсветке
 * свой список имён — и через месяц он разойдётся с тем, что подставляется на
 * самом деле: `{телефон}` горел бы жёлтым как переменная, а в сообщение уехал
 * бы фигурными скобками. Класс ошибки в LeadChat уже разбирали: два пути
 * считали одно поле по-разному.
 *
 * ⚠ СВОЙ ЭКЗЕМПЛЯР ОБРАЗЦА, А НЕ ОБЩИЙ. У `PATTERN` флаг `g`, то есть он
 * помнит `lastIndex` между вызовами: перебор поверх общего экземпляра начал бы
 * читать строку не с начала, попади он между вызовами `hasUnresolvedVars`.
 */
export function разобратьПодстановки(text: string): КусокТекста[] {
  const образец = new RegExp(PATTERN.source, "g");
  const куски: КусокТекста[] = [];
  let от = 0;
  for (let m = образец.exec(text); m; m = образец.exec(text)) {
    if (m.index > от) куски.push({ текст: text.slice(от, m.index), подстановка: false });
    куски.push({ текст: m[0], подстановка: true });
    от = m.index + m[0].length;
  }
  if (от < text.length) куски.push({ текст: text.slice(от), подстановка: false });
  return куски;
}
