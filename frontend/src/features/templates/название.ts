/**
 * Название заготовки, когда человек его не написал.
 *
 * ⚠ ЗАМЕР БОЯ 03.09: «Название» обязательно, и 25 личных заготовок из 26
 * ПОВТОРЯЮТ ТЕЛО слово в слово. То есть поле не несёт смысла — оно несёт
 * работу: чтобы сохранить фразу, человек обязан придумать ей ярлык, а он
 * придумывает ровно то же самое ещё раз. Личные заготовки за всё время завели
 * два человека из пятидесяти семи; лишний обязательный шаг стоит на пути ровно
 * там, где люди отваливаются.
 *
 * ⚠ ПОЧЕМУ НЕ УБРАТЬ КОЛОНКУ СОВСЕМ. Название — это то, что видно в списке и по
 * чему ищут: «Территориально не подходит» читается с одного взгляда, а первая
 * строка длинного текста — нет. Тем, кто ярлыки пишет, поле остаётся.
 */

/** Дальше этого названию в списке всё равно не поместиться (колонка 190 px). */
const ПРЕДЕЛ = 40;

/**
 * Название по тексту: первая строка, обрезанная по границе слова.
 *
 * ⚠ РЕЖЕМ ПО СЛОВУ, А НЕ ПО БУКВЕ. «Здравствуйте! Подскажите, какая мод…» —
 * читается; «…какая моде» — выглядит как опечатка в самом названии.
 */
export function названиеПоТексту(body: string): string {
  const первая = body.trim().split("\n")[0]?.trim() ?? "";
  if (!первая) return "";
  if (первая.length <= ПРЕДЕЛ) return первая;
  const кусок = первая.slice(0, ПРЕДЕЛ);
  const пробел = кусок.lastIndexOf(" ");
  // Одно слово длиннее предела — режем как есть, иначе название стало бы пустым.
  const основа = пробел > ПРЕДЕЛ / 2 ? кусок.slice(0, пробел) : кусок;
  return основа.replace(/[\s,;:.!?-]+$/u, "") + "…";
}
