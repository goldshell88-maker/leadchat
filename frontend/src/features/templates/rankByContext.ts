import type { TemplateDto } from "@/shared/api/types";
import { содержит } from "./поиск";

/**
 * Подбор быстрых ответов ПО ТОМУ, ЧТО ПИШЕТ КЛИЕНТ.
 *
 * ⚠ ЗАЧЕМ. Просьба владельца дословно: «он должен понимать, что человек
 * пытается написать, и исходя из его сообщений выдавать варианты». Плоский
 * список заготовок этого не делает: у диспетчера их полтора десятка, нужная
 * стоит третьей с конца, и пока её ищешь глазами — быстрее набрать руками.
 *
 * ⚠ ПОЧЕМУ БЕЗ МОДЕЛИ. Подбор обязан быть мгновенным: полоса живёт над пустым
 * полем, и человек смотрит на неё доли секунды. Поход к модели — это сотни
 * миллисекунд, деньги за каждый диалог и зависимость от чужой доступности ради
 * задачи «отсортировать пятнадцать строк». Сравнение слов даёт тот же ответ
 * здесь и сейчас, а главное — оно ОБЪЯСНИМО: видно, почему заготовка всплыла.
 *
 * ⚠ ПОЧЕМУ СРАВНЕНИЕ ПО НАЧАЛУ СЛОВА. Русский язык склоняет: клиент пишет
 * «телевизора», в заготовке «телевизор», и точное совпадение их не свяжет.
 * Полноценная лемматизация — это словарь на мегабайты в бандле ради
 * сортировки; общее начало в пять букв ловит падежи («телевизор/телевизора/
 * телевизору») и почти не даёт ложных склеек на словах такой длины.
 *
 * ⚠ ПОРЯДОК СОХРАНЯЕТСЯ ПРИ РАВНОМ СЧЁТЕ. Заготовки, ничем не отличающиеся по
 * подходящести, обязаны стоять там же, где стояли: иначе полоса перетасовыва-
 * ется на каждое сообщение клиента, и мышечная память диспетчера не работает.
 */

/** Слова, которые есть в любом сообщении и потому ничего не различают. */
const ШУМ = new Set([
  "здравствуйте",
  "добрый",
  "день",
  "вечер",
  "утро",
  "привет",
  "пожалуйста",
  "спасибо",
  "нужно",
  "надо",
  "можно",
  "хочу",
  "есть",
  "быть",
  "этот",
  "такой",
  "который",
  "когда",
  "сколько",
  "почему",
  "меня",
  "вас",
  "вам",
  "мне",
  "или",
  "как",
  "что",
  "для",
]);

/** Ниже этой длины слово не несёт темы: предлоги, союзы, обрывки. */
const МИН_ДЛИНА = 4;
/** По скольким первым буквам считаем слова одинаковыми (падежи, число). */
const КОРЕНЬ = 5;

function корни(текст: string): Set<string> {
  const out = new Set<string>();
  for (const слово of текст.toLowerCase().split(/[^\p{L}\p{N}]+/u)) {
    if (слово.length < МИН_ДЛИНА || ШУМ.has(слово)) continue;
    out.add(слово.slice(0, КОРЕНЬ));
  }
  return out;
}

/**
 * Насколько заготовка подходит к словам клиента. 0 — ничем не связана.
 *
 * Название весит больше тела: его пишут как ярлык темы («Выезд сегодня»), и
 * совпадение по нему точнее, чем случайное слово в середине длинного текста.
 */
export function оценить(t: TemplateDto, темы: Set<string>): number {
  if (темы.size === 0) return 0;
  let счёт = 0;
  for (const к of корни(t.title)) if (темы.has(к)) счёт += 3;
  for (const к of корни(t.body)) if (темы.has(к)) счёт += 1;
  return счёт;
}

/**
 * Отсортировать заготовки под последние слова клиента.
 *
 * `реплики` — тексты ВХОДЯЩИХ сообщений, свежие первыми. Берём несколько
 * последних, а не весь диалог: клиент начал с «здравствуйте, ремонт телевизора»,
 * а спрашивает сейчас про цену — и подсказывать надо про цену.
 */
export function подобрать(items: TemplateDto[], реплики: string[]): TemplateDto[] {
  const темы = корни(реплики.join(" "));
  /*
   * ⚠ ПОПУЛЯРНОСТЬ РЕШАЕТ ПРИ РАВНОМ СЧЁТЕ (просьба владельца 29.08: «сделай
   * популярность ответов, когда пишешь для быстрых ответов»).
   *
   * Порядок правил именно такой, и это не мелочь:
   *
   *   1. СМЫСЛ ВАЖНЕЕ ЧАСТОТЫ. Клиент написал про стиральную машину — ответ
   *      про неё обязан стоять выше «Здравствуйте», сколько бы раз последнее
   *      ни применяли. Иначе самая ходовая заготовка навсегда займёт первую
   *      строку и подсказка перестанет отвечать на вопрос клиента.
   *   2. ПРИ РАВНОМ СМЫСЛЕ — ЧАСТОТА. Тридцать девять общих заготовок плюс
   *      личные, а показывается пять: какие пять, должен решать живой сигнал,
   *      а не алфавит.
   *   3. ПРИ РАВНОЙ ЧАСТОТЕ — ПРЕЖНИЙ ПОРЯДОК. Заготовки, не отличающиеся
   *      ничем, обязаны стоять там же, где стояли: иначе список перетасовыва-
   *      ется на каждое сообщение клиента, и мышечная память не работает.
   *
   * `?? 0` обязателен: сборка фронта переживает сервер, который поля ещё не
   * присылает, и без него сортировка сравнивала бы undefined.
   */
  const частота = (t: TemplateDto) => t.used_count ?? 0;
  if (темы.size === 0) {
    return items
      .map((t, i) => ({ t, i }))
      .sort((a, b) => частота(b.t) - частота(a.t) || a.i - b.i)
      .map((x) => x.t);
  }
  return items
    .map((t, i) => ({ t, i, счёт: оценить(t, темы) }))
    .sort((a, b) => b.счёт - a.счёт || частота(b.t) - частота(a.t) || a.i - b.i)
    .map((x) => x.t);
}


/**
 * Подходит ли заготовка под НАБРАННОЕ человеком — для подсказки во время ввода.
 *
 * Здесь правила другие, чем при подборе по словам клиента, и это не небрежность.
 * Клиент пишет о своей беде целыми фразами — там нужна тема. Оператор набирает
 * НАЧАЛО того, что хочет сказать, и часто это две-три буквы: «выез», «цен».
 * Поэтому сравниваем по вхождению подстроки, без отсечения коротких слов, и
 * ищем в названии и в тексте сразу.
 */
export function подходит(t: TemplateDto, набрано: string): boolean {
  /*
   * ⚠ СРАВНЕНИЕ ЧЕРЕЗ `содержит`, А НЕ ЧЕРЕЗ `includes` (замер боя 03.09).
   *
   * Буквальное сравнение молча ломала «ё». Диспетчер набирает «еще» — а
   * заготовка записана «Вам помощь ещё требуется?», и подсказка не
   * появляется вовсе. За тридцать суток в исходящих «еще требуется» 373 раза
   * против «ещё требуется» 73; «все в наличии» — 197 против 4.
   */
  return содержит(t.title, набрано) || содержит(t.body, набрано);
}
