import type { DeltaCard, StatsCards, StatsSummary } from "@/shared/api/types";
import { EM_DASH, formatDuration, formatHourRange, formatNumber, formatPercent } from "../lib/format";
import { StatCard } from "./StatCard";

/**
 * Карточка «В очереди» добавлена в ответ `/stats/summary`
 * позже описания в `shared/api/types.ts`. Тип расширяется здесь, а не там:
 * общий файл контрактов правят параллельно другие ветки, и правка в нём
 * означала бы конфликт на слиянии. Поля необязательные — старый сервер
 * (выкатка идёт по частям) просто не пришлёт их, и экран не сломается.
 */
export type SummaryPayload = StatsSummary & {
  cards?: Partial<StatsCards> & { queue_now?: DeltaCard };
  /** Период захватывает сегодня → карточки «за период» посчитаны живьём (STATS-04). */
  period_live?: boolean;
  /** Действующие рабочие часы — они настраиваются, а не зашиты (FUNC-42). */
  work_hours?: { start_hour: number; end_hour: number };
};

/**
 * «10:00–20:00» из действующих настроек.
 *
 * В подсказке FRT это окно было НАПЕЧАТАНО ЧИСЛАМИ прямо в разметке, хотя оно
 * настраивается (#41): смени владелец часы на 09:00–21:00 — цифра под
 * подписью считалась бы по новым часам, а подпись обещала бы старые, и
 * отличить одно от другого читателю было бы нечем. Сервер не прислал часы
 * (старая версия) — подпись обходится без чисел, но не врёт.
 */
function workHoursLabel(hours: SummaryPayload["work_hours"]): string {
  const range = formatHourRange(hours);
  return range ? `в рабочие часы ${range}` : "в рабочие часы";
}

/**
 * Карточки экрана статистики (11 §6.1, состав — 06 §4.1).
 *
 * РАЗДЕЛЕНЫ НА ДВЕ ГРУППЫ, И ЭТО НЕ ОФОРМЛЕНИЕ (аудит 7 августа, docs/19).
 *
 * Величины здесь двух разных природ: «Новые диалоги» — сколько их пришло ЗА
 * ВЫБРАННЫЙ ПЕРИОД, а «В работе» — сколько их ПРЯМО СЕЙЧАС, безотносительно
 * периода. Стоя в одном ряду, они читаются как сравнимые, и глаз честно
 * пытается их сложить.
 *
 * Пока цифры согласованы, подмена незаметна. Стоит им разойтись — а они
 * расходятся всегда, когда период не «сегодня», — руководитель видит рядом
 * «0 новых за месяц» и «35 735 в работе» и не понимает, чему верить. Отчёт,
 * который однажды показался противоречивым, перестают открывать; вернуть
 * доверие дороже, чем не потерять его.
 *
 * Подписи «сейчас» мелким шрифтом под значением для этого мало: она объясняет
 * КАЖДУЮ карточку по отдельности, а проблема — в соседстве. Поэтому 4 сентября
 * их сняли все четыре, а разницу отдали ФОРМЕ: «за период» — карточки на
 * поднятой поверхности, «прямо сейчас» — плоская полоса без неё.
 *
 * ⚠ ГРУПП ДВЕ, А НЕ ТРИ. «Качество работы за период» стояло третьим рядом и
 * делило пополам величины ОДНОЙ природы: и «Новые диалоги», и «Первый ответ»
 * посчитаны по одному и тому же периоду. Граница между рядами читается как
 * «это с этим не сравнивай», и стоять она обязана ровно там, где такое
 * сравнение и правда запрещено, — иначе перестают верить и ей.
 *
 * Формулировки тултипов — из словаря метрик 06 §1 (нормативные).
 */
/**
 * Подсказка «В работе» говорит, что посчитано (проверка 24.09).
 *
 * Здесь было «взятые кем-то из сотрудников», а в числе лежали и диалоги без
 * ответственного — на бою 51 из 305: их никто не ведёт, и ни на одном экране
 * они не видны как чья-то работа. Число карточки остаётся полным (оно входит
 * в сумму открытых), а ничьи названы рядом.
 */
function inProgressTooltip(unassigned: number | undefined): string {
  const nobody =
    unassigned && unassigned > 0 ? ` Из них без ответственного: ${formatNumber(unassigned)} — их не ведёт никто.` : "";
  return `Диалоги в статусе «В работе», ещё не закрытые.${nobody} Снимок на сейчас — с прошлым периодом не сравнивается`;
}

export function SummaryCards({ summary }: { summary: SummaryPayload }) {
  // Ответ мог прийти без части карточек (расширяемый контракт 06 §4.1) — не падаем.
  const cards = summary.cards ?? {};
  const frt = cards.frt_operator;
  const bot = cards.bot_closed;
  const phones = cards.phones_collected;
  const repeat = cards.repeat_contacts;
  const waiting = cards.waiting_now;

  return (
    <>
      <div className="stats-group">
        {/*
          Свежесть подписана У ГРУППЫ, а не одной меткой на весь экран.
          «Данные на 10:05» в шапке относится к витрине статистики, а карточки
          этой группы читаются из неё не всегда: период, захватывающий сегодня,
          сервер считает живьём (STATS-04). Пока подпись была одна на всё,
          она объясняла экран наполовину — и как раз ту половину, где
          «Закрыто» могло обогнать «Новые диалоги».
        */}
        <h2 className="stats-group__title">
          За период
          <span className="stats-group__hint">
            {summary.period_live === false ? "по витрине статистики" : "на момент открытия страницы"}
          </span>
        </h2>
        <div className="stats-cards" role="list" aria-label="Метрики за выбранный период">
          <StatCard
            metricId="conversations_new"
            title="Новые диалоги"
            value={formatNumber(cards.conversations_new?.value)}
            deltaPct={cards.conversations_new?.delta_pct}
            prevLabel={formatNumber(cards.conversations_new?.prev)}
            tooltip="Диалоги, где первое сообщение клиента пришло в выбранный период"
          />
          {/*
            «ОТВЕЧЕНО» — СВОЕЙ КАРТОЧКОЙ, А НЕ СТРОКОЙ В ЧУЖОЙ ПОДСКАЗКЕ.
            Число жило внутри тултипа «Первого ответа», то есть показывалось
            только тому, кто навёл мышь на соседнюю величину. В таблице по
            людям это отдельная колонка, и спрашивают его первым: «сколько
            пришло и на сколько ответили» — один вопрос из двух чисел.
            Дельты у него нет: сервер сравнивает с прошлым периодом медиану
            ответа, а не счётчик ответивших, и рисовать стрелку не из чего.
          */}
          <StatCard
            metricId="answered"
            title="Отвечено"
            value={formatNumber(frt?.answered)}
            deltaPct={null}
            caption={frt ? `без ответа ${formatNumber(frt.unanswered)}` : undefined}
            /*
              ⚠ ПОРЯДОК «БОЛЬШЕ/МЕНЬШЕ» ЗДЕСЬ НЕ ОБЕЩАЕТСЯ, И ЭТО ВАЖНО. Первая
              редакция подписи говорила «поэтому её итог меньше». Без фильтров
              это верно, а под сужением по сотруднику — нет: карточка считает
              по ТЕКУЩЕМУ ответственному (`s.assignee_id`), а колонка — по
              АВТОРУ ПЕРВОГО ОТВЕТА, кому бы диалог ни принадлежал сейчас. По
              замеру боя через двух и более исполнителей проходит 34 %
              диалогов, так что у отдающего диалоги колонка легко окажется
              больше карточки — и обещанный порядок превратил бы объяснимое
              расхождение в улику против отчёта.
            */
            tooltip="Диалоги периода, в которых оператор ответил клиенту хотя бы раз — считая ответы, отправленные из приложения Авито, а не из LeadChat. Колонка «Ответил первым» в таблице ниже считает иначе: только те диалоги, у которых известен автор первого ответа"
          />
          <StatCard
            metricId="conversations_closed"
            title="Закрыто"
            value={formatNumber(cards.conversations_closed?.value)}
            deltaPct={cards.conversations_closed?.delta_pct}
            prevLabel={formatNumber(cards.conversations_closed?.prev)}
            tooltip="Диалоги, переведённые в статус «Закрыт» в выбранный период"
          />
          <StatCard
            metricId="frt_operator"
            title="Первый ответ (медиана)"
            value={formatDuration(frt?.median_sec)}
            deltaPct={frt?.delta_pct}
            prevLabel={formatDuration(frt?.prev_median_sec)}
            tooltip={
              frt
                ? `Медиана ${formatDuration(frt.median_sec)} · среднее ${formatDuration(frt.avg_sec)}. ` +
                  `Считая только ${workHoursLabel(summary.work_hours)}: медиана ${formatDuration(frt.median_biz_sec)} · среднее ${formatDuration(frt.avg_biz_sec)}.`
                : "Нет данных за период"
            }
          />
          <StatCard
            metricId="bot_closed"
            title="Закрыто ботом"
            value={formatPercent(bot?.pct)}
            deltaPct={bot?.delta_pct}
            deltaUnit="пп"
            tooltip={
              bot
                ? `${formatNumber(bot.closed_by_bot)} из ${formatNumber(bot.closed_total)} закрытых диалогов бот довёл без оператора`
                : "Нет данных за период"
            }
          />
          <StatCard
            metricId="phones_collected"
            title="Телефонов"
            value={formatNumber(phones?.value)}
            deltaPct={phones?.delta_pct}
            prevLabel={formatNumber(phones?.prev)}
            tooltip={
              phones
                ? `Бот ${formatNumber(phones.by_source?.bot ?? 0)} · из текста ${formatNumber(phones.by_source?.regex ?? 0)} · вручную ${formatNumber(phones.by_source?.manual ?? 0)}`
                : "Нет данных за период"
            }
          />
          <StatCard
            metricId="repeat_contacts"
            title="Повторные"
            value={formatNumber(repeat?.reopened)}
            deltaPct={null}
            caption={
              /*
               * ⚠ «БЫЛО» ЧИТАЛОСЬ КАК ПРОДОЛЖЕНИЕ ТОЙ ЖЕ ФРАЗЫ ПРО ТЕХ ЖЕ ЛЮДЕЙ.
               * Найдено проверкой боя 14 августа: «4 вернулись · было 0». Счёт
               * верный — ноль относится к ПРОШЛОМУ периоду равной длины, — но без
               * слова «период» строка выглядит противоречием сама с собой: четверо
               * вернулись, а было ноль. Отчёт, который однажды показался
               * противоречивым, перестают открывать.
               *
               * Стрелка `delta` здесь погашена намеренно, значит единственный
               * носитель смысла «прошлый период» — эти самые слова.
               */
              repeat && typeof repeat.prev_reopened === "number"
                ? `↩ вернулись · за прошлый период ${formatNumber(repeat.prev_reopened)}`
                : "↩ вернулись"
            }
            tooltip={
              repeat
                ? `Реоткрытых диалогов ${formatNumber(repeat.reopened)}; уникальных клиентов, обратившихся повторно, — ${formatNumber(repeat.repeat_clients)}`
                : EM_DASH
            }
          />
        </div>
      </div>

      <div className="stats-group">
        <h2 className="stats-group__title">
          Прямо сейчас
          <span className="stats-group__hint">не зависит от выбранного периода</span>
        </h2>
        {/*
          ПОЛОСА, А НЕ РЯД КАРТОЧЕК, И ЭТО ТА ЖЕ МЫСЛЬ, ЧТО НАПИСАНА ВЫШЕ.
          Пока снимок стоял такими же карточками, как итоги периода, разделяла
          их одна подпись над рядом; форма говорила обратное — «это сравнимо,
          складывай». Плоская полоса без поднятой поверхности отвечает за то же
          сама, и подписи «сейчас» под каждым из четырёх значений (их было
          четыре штуки на одну мысль) стали не нужны.
        */}
        <div className="stats-now" role="list" aria-label="Состояние на текущий момент">
          <StatCard
            flat
            metricId="in_progress_now"
            title="В работе"
            value={formatNumber(cards.in_progress_now?.value)}
            deltaPct={null}
            tooltip={inProgressTooltip(cards.in_progress_now?.unassigned)}
          />
          <StatCard
            flat
            metricId="waiting_now"
            title="Ждут ответа"
            value={formatNumber(waiting?.value)}
            deltaPct={null}
            accent={waiting && waiting.value > 0 ? "warning" : undefined}
            tooltip="Диалоги в работе, где клиент написал и ответа ещё не получил — та же отметка, по которой в чатах горит «ждёт 12 мин»"
          />
          {/*
            Очередь — ОТДЕЛЬНАЯ величина, а не значение под подписью «Ждут
            ответа». Раньше её число стояло там, и получалось, что руководитель
            видел неразобранную очередь под видом невыполненной работы
            диспетчеров (STATS-01). Убрать её вовсе тоже нельзя: длина очереди —
            первое, на что смотрят утром.
          */}
          <StatCard
            flat
            metricId="queue_now"
            title="В очереди"
            value={formatNumber(cards.queue_now?.value)}
            deltaPct={null}
            tooltip="Диалоги, которых ещё никто не взял — то же число, что на вкладке «Входящие» в чатах"
          />
          {/*
            «ЖДУТ КЛИЕНТА» — СВОЕЙ ЯЧЕЙКОЙ (docs/38 §6.1).

            Без неё диалог, переведённый в «Ждёт клиента», не попадал бы НИ В
            ОДНУ величину этой группы: «В работе» считает только `in_progress`.
            Руководитель увидел бы, что открытых диалогов стало меньше, хотя их
            столько же, — а по этой цифре решают, звать ли смену.

            Рядом стояла «Отложено» — снята 12 августа решением владельца вместе
            со всей отложкой. Сумма группы от этого не пострадала: четыре числа
            по-прежнему дают все открытые диалоги, и это проверяет охранный тест
            на PostgreSQL.
          */}
          <StatCard
            flat
            metricId="waiting_client_now"
            title="Ждут клиента"
            value={formatNumber(cards.waiting_client_now?.value)}
            deltaPct={null}
            tooltip="Диалоги, где ход за клиентом: мы ответили и ждём его решения"
          />
        </div>
      </div>
    </>
  );
}
