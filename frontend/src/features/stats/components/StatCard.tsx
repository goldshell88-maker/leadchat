import type { ReactNode } from "react";
import { Text, Tooltip } from "@mantine/core";
import { deltaArrow, deltaHint, deltaTone } from "../lib/delta";
import { formatDelta } from "../lib/format";

/**
 * Карточка-метрика (11 §6.1/6.2). Значение уже отформатировано вызывающим —
 * карточка отвечает только за подачу: дельта к прошлому периоду со стрелкой и
 * СЕМАНТИЧЕСКИМ цветом (для времени ответа снижение — зелёное), тултип-расшифровка,
 * акцент warning у «Ждут ответа» > 0.
 */
export interface StatCardProps {
  /** Идентификатор метрики — по нему решается инвертированная семантика дельты. */
  metricId: string;
  title: string;
  value: string;
  /** null → дельты нет вовсе (snapshot-метрики «сейчас»). */
  deltaPct?: number | null;
  /** Проценты сравниваются в процентных пунктах (06 §4.1). */
  deltaUnit?: "%" | "пп";
  /**
   * Значение прошлого периода, УЖЕ отформатированное вызывающим. Показывается
   * вместо процента, когда процент перестал что-либо значить (см. ПОТОЛОК ниже).
   * Форматирует вызывающий: только он знает, число это, время или доля.
   */
  prevLabel?: string;
  /** Подпись под значением вместо дельты («↩ вернулись», «без ответа 52»). */
  caption?: ReactNode;
  tooltip?: ReactNode;
  accent?: "warning";
  /**
   * ПЛОСКАЯ ПОДАЧА — ДЛЯ ВЕЛИЧИН «ПРЯМО СЕЙЧАС».
   *
   * Снимок и итог за период складывать нельзя, и различаться они обязаны
   * ФОРМОЙ, а не одной подписью над рядом: карточка на поднятой поверхности
   * против плоской ячейки общей полосы. Подписи «сейчас» под каждым значением
   * для этого мало — она объясняет одну величину, а вопрос рождается от
   * соседства четырёх (аудит 7 августа, docs/19).
   */
  flat?: boolean;
}

/**
 * С какого процента вместо него показываем само прошлое значение.
 *
 * ⚠ ЧЕТЫРЁХЗНАЧНЫЙ ПРОЦЕНТ — НЕ СВЕДЕНИЕ, А ШУМ (аудит 08.09, M-02: карточка
 * показывала «+190 775 %»). Формула верна, врёт основание: период выбирают
 * произвольный, до 366 дней, а прошлый сервер берёт той же длины вплотную
 * перед ним. У широкого выбора он попадает во время, когда системы ещё не
 * было. Замер по бою 08.09: за 2023–2025 в базе 28 диалогов (Авито отдал
 * старые чаты при подключении аккаунтов), за 2026 — 33 403. Отсюда шесть
 * знаков в процентах.
 *
 * ⚠ ПОЧЕМУ НЕ ПОРОГ НА СЕРВЕРЕ. Через ту же `delta_pct` проходят не только
 * счётчики, но и медиана первого ответа. Порог «сравнивать от 20» убил бы
 * законную дельту у медианы в 12 секунд. Здесь же решает тот, кто знает, ЧТО
 * показывает, и ничего не выбрасывается: вместо потерявшего смысл процента
 * человек видит прошлое значение и сравнивает сам.
 *
 * 1000 % — одиннадцатикратный рост. Выше этого отношение в голове уже не
 * удержать, и полезен только знаменатель.
 */
const ПОТОЛОК_ПРОЦЕНТА = 1000;

export function StatCard({
  metricId,
  title,
  value,
  deltaPct,
  deltaUnit = "%",
  prevLabel,
  caption,
  tooltip,
  accent,
  flat,
}: StatCardProps) {
  const числоЕсть = typeof deltaPct === "number" && Number.isFinite(deltaPct);
  /*
   * Потолок только у процентов: дельта процентной метрики считается в
   * процентных пунктах и больше сотни быть не может по построению.
   */
  const внеШкалы =
    числоЕсть &&
    deltaUnit === "%" &&
    Math.abs(deltaPct) >= ПОТОЛОК_ПРОЦЕНТА &&
    Boolean(prevLabel);
  const hasDelta = числоЕсть && !внеШкалы;
  const tone = deltaTone(metricId, deltaPct);
  const hint = deltaHint(metricId, deltaPct);
  const arrow = deltaArrow(deltaPct);

  /*
   * Пустая подпись держит ряд ровным: у карточек «за период» дельта есть не у
   * всех, и без распорки в 16 пикселей соседи по ряду выходят разной высоты.
   * В плоской полосе распорка не нужна — там подписи нет ни у одной величины,
   * и пустая строка была бы просто дырой под числом.
   */
  /*
   * Вне шкалы подпись занята основанием: место под дельтой одно, и показывать
   * там «без ответа 52» вместо «было 8» значило бы менять тему разговора ровно
   * в тот момент, когда человек ищет, с чем сравнивают.
   *
   * ⚠ РАСПОРКА НИЖЕ — НЕРАЗРЫВНЫЙ ПРОБЕЛ, А НЕ ОБЫЧНЫЙ. Обычный схлопнется, и
   * ряд карточек снова поедет по высоте.
   */
  const подпись = внеШкалы
    ? `было ${prevLabel}`
    : hasDelta
      ? null
      : (caption ?? (flat ? null : " "));

  const card = (
    <article
      className={flat ? "stat-card stat-card--flat" : "stat-card"}
      data-accent={accent}
      data-metric={metricId}
    >
      <Text component="h3" className="stat-card__title" fz="xs" c="var(--lc-text-3)">
        {title}
      </Text>
      <span className="stat-card__value">{value}</span>
      {hasDelta && (
        <span className="stat-card__delta" data-tone={tone}>
          {arrow && <span aria-hidden="true">{arrow}</span>} {formatDelta(deltaPct, deltaUnit)}
          {hint ? ` (${hint})` : ""} <span className="stat-card__delta-tail">к пред.</span>
        </span>
      )}
      {подпись !== null && <span className="stat-card__caption">{подпись}</span>}
    </article>
  );

  if (!tooltip) return card;
  return (
    <Tooltip label={tooltip} multiline w={260} withArrow position="bottom" events={{ hover: true, focus: true, touch: true }}>
      {card}
    </Tooltip>
  );
}
