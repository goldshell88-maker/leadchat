/**
 * ГЕОМЕТРИЯ ПОДПИСЕЙ ОСИ X — отдельно от компонента.
 *
 * Здесь живёт один вопрос: какие точки ряда подписать, чтобы подписи не
 * налезли друг на друга и не срезались о край. Он меняется по своей причине
 * (формат подписи, размеры поля построения) и проверяется числами, без
 * отрисовки, — поэтому и лежит отдельно от React-компонента, который рисует
 * столбики, линию, сетку и тултип.
 *
 * Отступы повторяют `MetricChart` (12/12/28/48), а ШИРИНА поля приходит
 * параметром: система координат графика считается по фактической ширине блока
 * (правка 08.09), и постоянного числа у неё больше нет.
 */

/**
 * Ширина поля построения при ЗАПАСНОЙ ширине графика: 720 − левый 48 − правый 12.
 *
 * ⚠ ЭТО УМОЛЧАНИЕ, А НЕ ЕДИНСТВЕННОЕ ЗНАЧЕНИЕ (правка 08.09). Система
 * координат графика больше не постоянная: `viewBox` считается по фактической
 * ширине блока, иначе картинка тянулась целиком вместе с кеглем подписей (при
 * окне 1181 подпись рисовалась в 8,7 пикселя — замер в stats.css у
 * `.stats-chart__svg`). Поэтому поле построения приходит сюда параметром, а
 * это число остаётся тем, чем было: запасом на случай, когда ширину ещё не
 * померили — до первого кадра и в сторожах, где мерить нечем.
 *
 * 48 и 12 — те же отступы, что в `PAD` у MetricChart; совпадение стережёт
 * ChartViewBox0809.
 */
export const PLOT_W = 720 - 48 - 12;

/**
 * Ширина подписи оси в единицах viewBox — оценка, и намеренно с запасом.
 *
 * Мерить настоящую ширину текста в SVG можно только после отрисовки
 * (`getComputedTextLength`), то есть уже когда подписи наложились. Оценка по
 * длине строки дешевле и для решения «влезет или нет» достаточна: «7 авг» —
 * пять знаков, «8 авг 14:00» — одиннадцать.
 */
export function labelWidth(sample: string): number {
  return Math.max(30, sample.length * 6.5);
}

/**
 * Сколько единиц viewBox приходится на шаг между соседними точками.
 *
 * Ровно та же арифметика, по которой ставятся сами подписи: `cx(i)` считает
 * колонку как `PLOT_W / n`, поэтому и зазор между подписями меряется по
 * `PLOT_W / n`. Здесь стояло `PLOT_W / (n - 1)` — оценка ЗАВЫШЕННАЯ, и
 * тем сильнее, чем меньше точек: при двух точках она обещала 660 единиц
 * зазора там, где на экране 330. Проверка «влезет ли» шла по числу, которого
 * на графике нет.
 */
export function perPoint(count: number, поле = PLOT_W): number {
  return count > 0 ? поле / count : поле;
}

/**
 * Во сколько ширин подписи должен укладываться шаг сетки.
 *
 * ⚠ ПОЛТОРЫ, А НЕ ОДНА, И ЭТО НЕ ЗАПАС «НА ВСЯКИЙ СЛУЧАЙ». Крайние подписи
 * прижимаются внутрь поля (`textAnchor` ниже: иначе половина даты уезжает за
 * край viewBox и срезается). Прижатая влево первая подпись стоит НЕ по центру
 * своей точки, а вся справа от неё — то есть съезжает внутрь на полширины и
 * лезет на соседку.
 *
 * ЗАМЕР В БРАУЗЕРЕ (стенд `?screen=chart`, неделя по часам, 168 точек,
 * `getComputedTextLength`): при шаге в одну ширину первая подпись «16 авг.,
 * 00:00» занимала 49,9…134,2, вторая — 102,6…185,9. Тридцать одна единица
 * внахлёст, и на экране это читалось «16 авг., 007:00, 00:00» — та самая
 * жалоба, только уже слева.
 *
 * Арифметика: прижатая подпись занимает [cx, cx+W], соседка по центру —
 * [cx₁−W/2, cx₁+W/2]; не пересекаются они при cx₁−cx ≥ 1,5W. Сетка
 * равномерная, поэтому требование к крайнему шагу становится требованием ко
 * всем. Плата — на неделе по часам пять подписей вместо восьми; восемь всё
 * равно не помещались.
 */
export const EDGE_LABEL_FACTOR = 1.5;

/**
 * Какие точки подписывать по оси X.
 *
 * ЧТО БЫЛО. Последняя подпись добавлялась БЕЗУСЛОВНО поверх равномерной сетки:
 * `out.add(count - 1)` в конце. Если она попадала близко к предыдущей — а при
 * 30 днях (пресет по умолчанию) это происходит всегда, — подписи налезали друг
 * на друга и читались как «7 авг8 авг». Правая дата на графике самая нужная:
 * она отвечает на вопрос «а по какой день данные».
 *
 * ЧТО СТАЛО. Последняя точка по-прежнему подписывается всегда, но если она
 * слишком близко к соседке, вытесняет её, а не пририсовывается рядом.
 * Сравнение нестрогое: при двух точках иначе потеряется первая.
 */
export function labelIndexes(count: number, max = 8, sample = "00 ммм", поле = PLOT_W): Set<number> {
  const out = new Set<number>();
  if (count === 0) return out;
  /*
   * ⚠ СКОЛЬКО ПОДПИСЕЙ ВЛЕЗЕТ, А НЕ СКОЛЬКО ХОЧЕТСЯ (жалоба владельца 22.08:
   * «идёт наслоение»).
   *
   * Восемь подписей были потолком независимо от их длины, и проверялся только
   * зазор ПОСЛЕДНЕЙ подписи с соседкой — равномерная сетка не проверялась
   * вовсе. На неделе по часам это 168 точек: шаг 21, между подписями 83
   * единицы viewBox, а «16 авг., 06:00» занимает 91. Подписи налезали, и
   * читалось «21:0017 авг., 18:0018 авг.» — ровно то, что на скриншоте.
   *
   * Считаем от ширины подписи и ширины поля: сколько влезает, столько и
   * ставим. Минимум две — с одной подписью ось перестаёт быть осью.
   */
  const влезает = Math.max(2, Math.floor(поле / (EDGE_LABEL_FACTOR * labelWidth(sample))));
  const потолок = Math.min(max, влезает);
  const step = Math.max(1, Math.ceil(count / потолок));
  for (let i = 0; i < count; i += step) out.add(i);

  const last = count - 1;
  if (!out.has(last)) {
    const previous = Math.max(...out);
    const нужно = EDGE_LABEL_FACTOR * labelWidth(sample);
    if ((last - previous) * perPoint(count, поле) < нужно) out.delete(previous);
    out.add(last);
  }
  return out;
}
