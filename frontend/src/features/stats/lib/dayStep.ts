/**
 * Шаг по суткам на почасовом графике (просьба владельца 22.08: «сделай так,
 * чтобы можно было выбирать день»).
 *
 * Неделя по часам — 168 столбиков: общая форма видна, а «что было позавчера в
 * обед» из неё уже не вычитать. Стрелки ставят период в ОДНИ сутки и шагают по
 * ним, не трогая ни метрику, ни группировку.
 *
 * Правило вынесено из разметки отдельным модулем не ради красоты: оно
 * отвечает на два вопроса сразу — «куда ведёт стрелка» и «горит ли она», — и
 * ответы обязаны сходиться. Разъедься они, кнопка гасилась бы не на том дне,
 * на котором перестаёт работать, и человек получил бы либо живую кнопку без
 * последствий, либо погашенную там, где идти ещё есть куда.
 */

import { daysInPeriod, shiftDate, type Period } from "@/shared/lib/period";

/**
 * Какой день показать по нажатию стрелки. `null` — идти некуда.
 *
 * ПЕРВОЕ НАЖАТИЕ ИЗ МНОГОДНЕВНОГО ПЕРИОДА — ЭТО ВХОД В РЕЖИМ ДНЯ, А НЕ ШАГ.
 * Считать шаг от конца периода было ошибкой в обе стороны: «‹» из недели
 * уводило сразу в позавчера, перепрыгнув последний день периода, а «›»
 * упиралось в завтра и не делало ничего. Человек при этом видит подпись
 * «16 – 22 авг.» и ждёт, что стрелка покажет ему один из этих дней, — с
 * последнего и начинаем.
 *
 * `today` — московская дата (06 §0.1), а не локальная: сутки статистики
 * московские, и «завтра» у сотрудника из Владивостока наступает не раньше,
 * чем у сервера.
 */
export function dayStepTarget(period: Period, delta: number, today: string): string | null {
  const one = daysInPeriod(period) === 1;
  const target = one ? shiftDate(period.dateFrom, delta) : period.dateTo;
  // Вперёд дальше сегодняшнего дня идти некуда: пустой график завтрашних суток
  // отвечает на вопрос, которого никто не задавал.
  if (target > today) return null;
  return target;
}

/** Стрелка «вперёд» никуда не ведёт — показанный день и есть сегодняшний. */
export function dayForwardBlocked(period: Period, today: string): boolean {
  return dayStepTarget(period, 1, today) === null;
}
