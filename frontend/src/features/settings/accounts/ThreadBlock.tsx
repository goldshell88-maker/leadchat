import { Button, Skeleton, Switch, Text } from "@mantine/core";
import { useMutation, useQuery, useQueryClient } from "@tanstack/react-query";
import { showToast } from "@/shared/ui/toast";
import {
  fetchThreadSettings,
  saveThreadSettings,
  threadSettingsKey,
  type ThreadSettings,
} from "./api";

/**
 * «Служебные записи Авито» — один переключатель показа в ленте переписки.
 *
 * ТРЕБОВАНИЕ ВЛАДЕЛЬЦА ОТ 14 АВГУСТА, дословно: «сделай так, чтобы можно было
 * отключить все системные сообщения в диалоге, которые отправляет Авито, так
 * как в самой Jivo их нет».
 *
 * ⚠ ПОЧЕМУ ЭТОТ ФАЙЛ ПОЯВИЛСЯ ОТДЕЛЬНОЙ ПРАВКОЙ. Настройку завели и научили
 * ленту её слушать в тот же день — а записать значение было НЕЧЕМ: ни ручки на
 * сервере, ни экрана. Просьба оказалась выполнена наполовину, и обнаружилось
 * это уже после выкатки: код готов, выключателя нет, и человек, пришедший его
 * искать, решил бы, что правка не доехала.
 *
 * ⚠ ВИДОВ СЛУЖЕБНЫХ ЗАПИСЕЙ ДВА, И ОДИН ИЗ НИХ АВИТО НЕ ПОМЕЧАЕТ ВОВСЕ. Тот,
 * что приходит конвертом с признаком системности, виден серым чипом. А
 * «Ассистент Авито ответил» и «Пользователь создал чат» приезжают ОБЫЧНЫМИ
 * сообщениями клиента с приставкой в тексте — признака системности внутри
 * переписки Авито не ставит никогда. Выключатель гасит оба.
 *
 * ПРЯЧЕТ, А НЕ УДАЛЯЕТ, и подпись говорит это прямо. Записи остаются в базе,
 * приезжают в выгрузку и в «Разбор диалогов», а обратное переключение
 * возвращает их целиком. Иначе выключатель показа читался бы как потеря
 * переписки — а за частью этих записей стоит действие клиента.
 *
 * ПРАВО — `settings:manage`, то есть администратор; блок живёт на том же
 * экране, что и «Телефоны в переписке», и по той же причине: своего раздела
 * ради одного тумблера заводить незачем, его бы не нашли.
 */
export function ThreadBlock() {
  const qc = useQueryClient();
  const q = useQuery({ queryKey: threadSettingsKey, queryFn: fetchThreadSettings });

  /*
   * Сохранение сразу, без кнопки «Сохранить» — по тому же доводу, что у
   * соседнего блока: тумблер здесь законченное решение, а всё остальное на
   * этой странице применяется немедленно. Тумблер, ждущий кнопки среди
   * немедленных действий, читается как уже сохранённый.
   */
  const save = useMutation({
    mutationFn: saveThreadSettings,
    onSuccess: (data) => {
      qc.setQueryData(threadSettingsKey, data);
      // Лента у открытых диалогов собрана с прежним фильтром — просим её
      // перечитать, иначе настройка «применилась», а на экране всё по-старому
      // до перезагрузки страницы.
      void qc.invalidateQueries({ queryKey: ["messages"] });
      showToast({ title: "Сохранено", color: "lp" });
    },
    onError: () =>
      showToast({
        title: "Настройка не сохранилась",
        // Положение тумблера берётся из ответа сервера, а не из своей памяти,
        // поэтому после неудачи он остаётся в прежнем положении сам.
        message: "Проверьте соединение и переключите ещё раз",
        color: "red",
      }),
  });

  if (q.isPending) {
    return (
      <section className="accounts-page__block">
        <Skeleton height={18} width={240} radius="var(--lc-radius-sm)" />
        <Skeleton height={34} width={340} radius="var(--lc-radius-sm)" />
      </section>
    );
  }

  if (q.isError) {
    return (
      <section className="accounts-page__block">
        <Text fz="sm" c="var(--lc-danger-text)" role="alert">
          Настройка показа служебных записей не загрузилась. Сама она при этом не
          изменилась — лента работает так, как её настроили в прошлый раз
        </Text>
        <Button variant="outline" size="xs" onClick={() => void q.refetch()}>
          Повторить
        </Button>
      </section>
    );
  }

  const value: ThreadSettings = q.data;

  return (
    <section className="accounts-page__block" aria-labelledby="thread-settings-title">
      <Text id="thread-settings-title" fw={600} fz="md" c="var(--lc-text-1)">
        Служебные записи Авито
      </Text>

      <Switch
        checked={value.avito_system_hidden}
        disabled={save.isPending}
        onChange={(e) => save.mutate({ avito_system_hidden: e.currentTarget.checked })}
        label="Не показывать служебные записи Авито в ленте"
        // Подпись меняется вместе с тумблером: статичная продолжала бы
        // описывать выключенный режим после включения.
        description={
          value.avito_system_hidden
            ? "«Пользователь создал чат», «Ассистент Авито ответил» и подобные записи в переписке не видны"
            : "Переписка показывается целиком, вместе со служебными записями Авито"
        }
      />

      <Text fz="xs" c="var(--lc-text-3)">
        Записи только прячутся: они остаются в базе, в выгрузке и в «Разборе диалогов»,
        и вернутся, если переключатель снять. Настройка общая — лента меняется у всех
        сотрудников сразу.
      </Text>
    </section>
  );
}
