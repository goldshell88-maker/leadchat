import type { ReactNode } from "react";
import { Button, Text } from "@mantine/core";
import type { AvitoAccountDto, ChannelHealthState } from "@/shared/api/types";
import { MSK_TIME_ZONE, formatDate, formatInZone, zonedTimeTitle } from "@/shared/lib/formatTime";
import { IconAlert, IconCheck, IconXCircle } from "@/shared/ui/Icon";

/**
 * ДВЕ СТРОКИ СОСТОЯНИЯ КАРТОЧКИ КАНАЛА: токен и приём обращений.
 *
 * ПРАВИЛО, РАДИ КОТОРОГО ФАЙЛ НАПИСАН: жёлтым и красным помечается ТОЛЬКО то,
 * что требует действия человека. Штатное поведение — суточный токен, который
 * перевыпускается сам, и тишина на редком канале — нейтрально. Индикатор,
 * который горит всегда, не значит ничего; хуже того, он приучает не смотреть и
 * туда, где однажды загорится настоящая поломка.
 *
 * ЧТО БЫЛО ЗДЕСЬ ДО 12 АВГУСТА. Обе строки экран считал сам, каждую по одному
 * числу, и обе врали:
 *
 * * «⚠️ Токен истекает через 23 ч» — жёлтая строка со знаком тревоги при
 *   остатке 23 часа из 24, то есть на всех каналах и почти всё время. Люди
 *   читали её как аварию и жали «Обновить токен» руками каждый день, хотя
 *   суточный токен по постоянным `client_id`/`client_secret` перевыпускается
 *   планировщиком сам, за два часа до срока;
 * * «Webhook: ⚠️ событий нет 16 ч» — тревога по АБСОЛЮТНОМУ времени тишины.
 *   На канале с пятью обращениями за неделю она горела вечно, а соседний с
 *   дневным потоком показывал «✓ в порядке». Разница между ними не в
 *   исправности, а в потоке клиентов. И объясняла эта строка тишину пропавшей
 *   подпиской, ни разу эту подписку не спросив.
 *
 * ТЕПЕРЬ РЕШАЕТ СЕРВЕР (`app/services/channel_health.py`), а экран рисует
 * `state` и `message`. Иначе правило «когда пугать человека» жило бы в двух
 * местах и разъехалось бы на первой же правке; а половины входных данных —
 * получалось ли автообновление, что ответил Авито на сверку подписки, каков
 * обычный ритм канала — у экрана нет и быть не может.
 *
 * ПОЭТОМУ ЖЕ ЗДЕСЬ НЕ ЧИТАЮТСЯ ОСТАЛЬНЫЕ ПОЛЯ ОТВЕТА (тишина в минутах, ритм,
 * порог, время сверки): в `message` они уже сведены в русскую фразу. Стоит
 * фронту взять оттуда хоть одно число — и он немедленно начнёт считать по нему
 * своё правило, то самое, из-за которого экран горел жёлтым круглосуточно.
 */

/** Как выглядит каждое из четырёх состояний. */
interface Look {
  color: string;
  /** Знак тревоги — ТОЛЬКО там, где нужно действие: иначе он обесценивается. */
  Icon?: typeof IconAlert;
  /** Живая область для тех, кто экран не видит; у штатных строк её нет. */
  role?: "status" | "alert";
  bold?: boolean;
}

const LOOK: Record<ChannelHealthState, Look> = {
  // Штатно и спокойно — тем же серым, что «Подключён 05.08.2026» ниже.
  ok: { color: "var(--lc-text-2)" },
  // Тихо, но для этого канала это норма. Тоже нейтрально и БЕЗ значка: разницу
  // между «события идут» и «сейчас тихо» человек читает словами, а знак тревоги
  // здесь означал бы, что редкий канал сломан просто потому, что редкий.
  quiet: { color: "var(--lc-text-2)" },
  warning: { color: "var(--lc-warning-text)", Icon: IconAlert, role: "status", bold: true },
  critical: { color: "var(--lc-danger-text)", Icon: IconXCircle, role: "alert", bold: true },
};

/**
 * Одна строка состояния: цвет, знак, текст сервера и кнопка починки.
 *
 * Кнопка появляется, только когда сервер назвал действие (`action`). У
 * штатного состояния действия нет — и кнопки нет: «Обновить токен» рядом с
 * нормальной строкой люди нажимали каждый день, приняв её за аварию. Для
 * администратора она переехала в меню «…» внизу карточки — туда, где и место
 * обслуживанию, которое почти никогда не нужно.
 */
function HealthLine({
  state,
  message,
  headline,
  detail,
  title,
  icon,
  action,
  onAction,
  busy,
  canManage,
  children,
  kind,
}: {
  state: ChannelHealthState;
  /**
   * Полная фраза сервера. С 13.08 — ЗАПАСНОЙ путь: она не укорочена и рисуется
   * целиком, если сервер ещё не умеет присылать `headline`.
   */
  message: string;
  /** Одна фраза: что случилось и чем грозит. Пусто — сервер старый. */
  headline?: string;
  /** Числа, ритм канала, время сверки, причина отказа. Может не быть вовсе. */
  detail?: string;
  title?: string;
  /** Значок вместо положенного состоянию; спокойная галочка «всё идёт». */
  icon?: ReactNode;
  /** Подпись кнопки; `null` — действия не требуется. */
  action: string | null;
  onAction?: () => void;
  busy?: boolean;
  canManage: boolean;
  children?: ReactNode;
  /**
   * Про что эта строка — токен или приём событий.
   *
   * ⚠ НУЖНО РАСКЛАДКЕ, А НЕ СТИЛЮ (04.09). Свёрнутая строка канала — сетка, и
   * каждой колонке нужен постоянный жилец: иначе у канала без одной из строк
   * состояния соседние колонки съезжают, и список «едет». По этому признаку
   * сетка и раздаёт им колонки.
   */
  kind: "token" | "webhook";
}) {
  const look = LOOK[state];
  const { Icon } = look;
  const mark = icon ?? (Icon ? <Icon size={14} /> : null);
  return (
    <div className="account-card__health" data-kind={kind}>
      <Text
        fz="sm"
        fw={look.bold ? 600 : undefined}
        c={look.color}
        role={look.role}
        /*
         * ⚠ В ПОДСКАЗКЕ — И ПОЯСНЕНИЕ ТОЖЕ (28.08).
         *
         * В свёрнутой строке списка пояснение спрятано: тридцать каналов по
         * три-четыре линии каждый читались как свалка, и владелец попросил
         * «чтобы всё было написано в одном поле». Спрятать, не оставив способа
         * прочитать, — это потеря: у затянувшейся тишины в пояснении лежит
         * ровно та причина, ради которой на страницу и зашли.
         *
         * Поэтому наведение показывает полный текст. В раскрытой карточке
         * пояснение видно и так, и повтор в подсказке там не мешает.
         */
        title={[title, detail].filter(Boolean).join("\n\n") || undefined}
        className="account-card__health-line"
      >
        {mark}
        {/*
          ДВЕ ЧАСТИ ФРАЗЫ, ЗАГОЛОВОК ОБЯЗАТЕЛЕН, ДЕТАЛЬ — НЕТ (разбор интерфейса 13.08).

          Янтарный абзац выходил на пять-шесть строк в колонке карточки: 190 знаков у
          затянувшейся тишины. Такую строку читают боковым зрением, а прочитать её так
          нельзя. Делит СЕРВЕР и присылает обе части готовыми — разбирать `message`
          здесь запрещено (см. начало файла), и регуляркой это было бы то же нарушение
          другим способом.

          ⚠ ОТКАТ НА `message` — НЕ ПЕРЕСТРАХОВКА, А УСЛОВИЕ ВЫКАТКИ. Сервер и фронт
          выкатываются порознь. Пока сервер старый, `headline` не приходит вовсе, и
          строка обязана остаться прежней и полной — тем же приёмом, которым ниже
          держится «старый сервер без состояния».
        */}
        {/* Текст — в своём узле, а не голым текстовым потоком: только так он может
            переноситься ВНУТРИ себя, оставаясь на одной строке со значком. */}
        <span className="account-card__health-text">{headline || message}</span>
      </Text>
      {detail && (
        /*
          Деталь — тем же видом, что и «Последний раз обновился сам …» ниже: 12-й
          кегль, --lc-text-3. Третьего вида здесь не заводим, и раскрытия тоже: деталь
          короткая (60-120 знаков), сама по себе полезна, а прятать её за клик в
          колонке шириной 280 значит менять пять строк текста на лишнее состояние.

          ⚠ ЖИВАЯ ОБЛАСТЬ ОСТАЁТСЯ НА ЗАГОЛОВКЕ, и это осознанно. Заголовок написан
          так, чтобы не врать в одиночку, — значит объявления одного его достаточно.
          Тот же выбор уже сделан для заметки об автообновлении: она тоже вне `role`.
        */
        <Text fz="xs" c="var(--lc-text-3)" className="account-card__health-detail">
          {detail}
        </Text>
      )}
      {children}
      {action !== null &&
        (canManage ? (
          <Button variant="subtle" size="compact-xs" loading={busy} onClick={onAction}>
            {action}
          </Button>
        ) : (
          /* Руководитель видит состояние канала, но не управляет им (11 §4.1).
             Без этой строки он ищет кнопку, которой у него нет и не будет.

             ⚠ РАНЬШЕ ЗДЕСЬ СТОЯЛО «Это делает администратор.», и держалось это на
             хвосте серверной фразы: та кончалась словами «Нажмите «Обновить токен»»,
             и «это» относилось к «нажмите». 13.08 хвосты сняли — кнопка с той же
             подписью стоит вплотную справа и дублировать её в тексте незачем, —
             и местоимению стало не к чему отнестись.

             Теперь строка собирается из подписи того же действия и самодостаточна:
             она называет и ЧТО надо сделать, и КТО это делает. Заодно исчезла
             вторая беда прежнего вида: руководитель узнавал, что нужно чьё-то
             вмешательство, только из хвоста фразы, а хвост говорил «нажмите» —
             то есть звал нажать того, кому нажимать нечем. */
          <Text fz="xs" c="var(--lc-text-3)">
            {action} может администратор.
          </Text>
        ))}
    </div>
  );
}

/** «13.08 в 04:07» — тот же вид, что у строк сервера (`_day_clock`). */
function dayClock(iso: string): string {
  // Время МОСКОВСКОЕ, как и внутри серверных фраз. Два часовых пояса в одном
  // абзаце («обновится в 16:07» рядом с «обновилось в 19:07») читаются как
  // расхождение, а не как забота о часах сотрудника; свои часы он получает
  // подсказкой по наведению (`zonedTimeTitle`).
  const stamp = formatInZone(iso, MSK_TIME_ZONE);
  return stamp ? stamp.replace(" ", " в ") : "";
}

/**
 * ЗАЧЕМ ЭТО ПОЯСНЕНИЕ ВООБЩЕ ЕСТЬ. Слово «токен» на карточке читают как «ключ,
 * который однажды придётся где-то взять и вписать». Отсюда и ежедневные
 * нажатия: человек думает, что срок кончается у ЕГО ключей. Ключи постоянные;
 * суточный — только выданный по ним access-токен, и берёт его сервис.
 */
const TOKEN_HINT =
  "client_id и client_secret постоянные, менять их не нужно. Авито выдаёт по ним " +
  "access-токен на 24 часа, сервис перевыпускает его сам.";

/**
 * Строка «Токен …» — три состояния вместо вечного жёлтого.
 *
 * НОРМА — нейтрально, без значка: «Токен активен. Обновится автоматически
 * 13.08 в 16:07», и рядом — когда обновление в последний раз получилось. Это
 * ответ на вопрос, ради которого и жали кнопку: работает ли автоматика вообще.
 *
 * ВНИМАНИЕ — жёлтое, со знаком: автообновление уже должно было пройти и не
 * прошло либо последняя попытка вернула ошибку. АВАРИЯ — красное: токен истёк
 * (ответы клиентам не уходят прямо сейчас) или обновление не проходит подряд.
 */
export function TokenLine({
  account,
  onRefresh,
  busy,
  canManage,
}: {
  account: AvitoAccountDto;
  onRefresh: () => void;
  busy: boolean;
  canManage: boolean;
}) {
  const token = account.token;

  /*
   * СТАРЫЙ СЕРВЕР — НЕЙТРАЛЬНАЯ СТРОКА, И ТОЛЬКО.
   *
   * Сборка без `token` знает о токене ровно одно: дату. Показываем её фактом,
   * тем же серым, что и всё штатное. Соблазн «посчитать самим, раз даты
   * хватает» — это и есть отменённое правило «меньше двух суток — жёлтым»:
   * оно горело круглосуточно, потому что токен живёт сутки.
   */
  if (!token) {
    return (
      <div className="account-card__health" data-kind="token">
        <Text fz="sm" c="var(--lc-text-2)" title={TOKEN_HINT} className="account-card__health-line">
          {account.token_expires_at
            ? `Токен активен, до ${formatDate(account.token_expires_at)}`
            : "Токен активен."}
        </Text>
      </div>
    );
  }

  return (
    <HealthLine
      kind="token"
      state={token.state}
      message={token.message}
      headline={token.headline}
      detail={token.detail}
      title={TOKEN_HINT}
      action={token.action === "refresh_token" ? "Обновить токен" : null}
      onAction={onRefresh}
      busy={busy}
      canManage={canManage}
    >
      {/* Доказательство того, что автоматика работает, — только у штатной
          строки. У жёлтой и красной сервер уже объяснил, что именно пошло не
          так, и «зато позавчера получилось» читается там издевательством. */}
      {token.state === "ok" && token.last_refresh_at && (
        <Text
          fz="xs"
          c="var(--lc-text-3)"
          title={zonedTimeTitle(token.last_refresh_at)}
          className="account-card__health-note"
        >
          Последний раз обновился сам {dayClock(token.last_refresh_at)}
        </Text>
      )}
    </HealthLine>
  );
}

/**
 * Строка приёма обращений — бывшая «Webhook: …».
 *
 * СЛОВА «WEBHOOK» В НЕЙ БОЛЬШЕ НЕТ. Строку читает владелец бизнеса, а не
 * интегратор; сервер и так присылает готовую фразу по-русски («События
 * приходят, последнее в 19:58», «Подписку на события забрала другая система:
 * обращения от клиентов к нам не приходят вовсе»), и латинская подпись перед
 * ней только требовала перевода.
 *
 * У ВЫКЛЮЧЕННОГО КАНАЛА СТРОКИ НЕТ, пока сервер не поднял тревогу. «Событий
 * нет» у намеренно выключенного канала — шум, а шум приучает не читать это
 * место. Исключение ровно одно, и оно жёлтое: подписку на стороне Авито снять
 * не удалось, то есть человек думает, что откатился, а сообщения по-прежнему
 * идут к нам.
 */
export function WebhookLine({
  account,
  onRewebhook,
  busy,
  canManage,
}: {
  account: AvitoAccountDto;
  onRewebhook: () => void;
  busy: boolean;
  canManage: boolean;
}) {
  const { webhook } = account;
  const state = webhook.state;

  // Старый сервер: состояния нет — молчим совсем. Прежний экран собирал эту
  // строку из `status` и `last_event_at` сам и получал «✓ в порядке» рядом с
  // «⚠ вебхук молчит»; одно из двух всегда было неправдой.
  if (!state || !webhook.message) return null;

  const alarm = state === "warning" || state === "critical";
  if (account.status === "disabled" && !alarm) return null;

  return (
    <HealthLine
      kind="webhook"
      state={state}
      message={webhook.message}
      headline={webhook.headline}
      detail={webhook.detail}
      // «События идут» стоит подтвердить спокойным знаком: в ряду строк, где у
      // тревоги знак есть, его отсутствие читается как недосказанность.
      icon={state === "ok" ? <IconCheck size={14} /> : undefined}
      action={webhook.action === "rewebhook" ? "Обновить подписку" : null}
      onAction={onRewebhook}
      busy={busy}
      canManage={canManage}
    />
  );
}
