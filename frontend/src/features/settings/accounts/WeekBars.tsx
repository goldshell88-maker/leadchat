import { Text, Tooltip } from "@mantine/core";
import { moscowDayOfWeek } from "@/shared/lib/moscowTime";
import type { AccountStatsDto } from "@/shared/api/types";
import "./week-bars.css";

/**
 * Неделя канала в карточке канала (просьба заказчика от 7 августа, как в Jivo).
 *
 * ЗАЧЕМ ЗДЕСЬ, А НЕ В СТАТИСТИКЕ. Раздел статистики отвечает на вопрос «как
 * сработали», и туда идут за отчётом. Вопрос «какой канал приносит обращения,
 * а какой мы теряем» задаётся в другой момент — когда смотришь на список
 * каналов. Ответ, лежащий за двумя фильтрами в другом разделе, на этот вопрос
 * не отвечает: за ним не пойдут.
 *
 * ДВА ЧИСЛА, А НЕ ОДНО. «899 обращений» без второго числа звучит хорошо при
 * любом качестве работы. Пара «всего / без ответа» сразу говорит, чем канал
 * болен: мало обращений или мало ответов. Это разные беды с разными
 * лекарствами — в первом случае вопрос к объявлениям, во втором к людям.
 *
 * ПОЧЕМУ СТОЛБИКИ, А НЕ ГРАФИК. Число говорит «сколько», форма — «ровно ли».
 * Провал в среду при том же итоге за неделю виден только формой, и объясняется
 * он обычно чем-то за пределами системы: выходной, отпуск, сломанный канал.
 * Осей и подписей у столбиков нет намеренно: точные значения здесь не читают,
 * читают силуэт, а оси на полоске в тридцать пикселей — это шум.
 */

const DAY_LABEL = ["вс", "пн", "вт", "ср", "чт", "пт", "сб"];

/**
 * Подписи дней для тултипов: последний столбик — сегодня.
 *
 * ⚠ СЕГОДНЯ — ПО МОСКВЕ, А НЕ ПО ЧАСАМ КОМПЬЮТЕРА (находка 23.08 №21). Столбики
 * приходят с сервера, а он строит семь слотов от МОСКОВСКОЙ даты. Подписи же
 * считались от `new Date().getDay()` — то есть от часов браузера. У оператора
 * восточнее Москвы после полуночи по местному (но ещё вчера по Москве) вся
 * неделя подписана со сдвигом на день: «вторник» стоит под столбиком
 * понедельника, и разговор о провале в среду идёт про четверг.
 */
function dayNames(count: number): string[] {
  const today = moscowDayOfWeek();
  return Array.from({ length: count }, (_, i) => DAY_LABEL[(today - (count - 1 - i) + 7 * 2) % 7]);
}

function plural(n: number, one: string, few: string, many: string): string {
  const mod10 = n % 10;
  const mod100 = n % 100;
  if (mod10 === 1 && mod100 !== 11) return one;
  if (mod10 >= 2 && mod10 <= 4 && (mod100 < 12 || mod100 > 14)) return few;
  return many;
}

/** «часа» / «45 мин» / «3 ч» — на сколько сводка может отставать. */
function staleLabel(minutes: number): string {
  if (minutes < 60) return `${minutes} мин`;
  const hours = Math.round(minutes / 60);
  return hours === 1 ? "часа" : `${hours} ч`;
}

export function WeekBars({ stats }: { stats: AccountStatsDto }) {
  const peak = Math.max(...stats.daily, 1);
  const labels = dayNames(stats.daily.length);
  // Доля без ответа — она решает, тревожный ли цвет у второго числа. Порог в
  // десятую часть не выдуман: на девяти каналах и тринадцати диспетчерах
  // единичные пропуски неизбежны и тревоги не стоят, а каждый десятый — это
  // уже система.
  const missedShare = stats.total > 0 ? stats.missed / stats.total : 0;
  const alarming = stats.missed > 0 && missedShare >= 0.1;
  /*
   * НАСКОЛЬКО СВОДКА МОЖЕТ ОТСТАВАТЬ — величина с сервера, а не наша догадка
   * (`AccountStatsOut.stale_minutes`, app/api/routes/avito_connect.py).
   *
   * Ответ сервера до этой выкатки поля не несёт, и в этом окне `undefined`
   * значит «не знаем», а не «не отстаёт»: считать отставание нулевым — ровно
   * та ошибка, которую мы здесь и чиним. Поэтому падаем на час, то есть на шаг
   * обновления материализованного вида.
   */
  const stale = typeof stats.stale_minutes === "number" ? stats.stale_minutes : 60;

  if (stats.total === 0) {
    /*
     * ПУСТАЯ НЕДЕЛЯ — НЕ ФАКТ, А ПОКАЗАНИЕ ОТСТАЮЩЕГО ПРИБОРА (дефект аудита 6).
     *
     * Здесь стояло «За неделю обращений не было» — утверждение о мире. А
     * сводка считается по ЧАСОВОМУ материализованному виду и отстаёт: на
     * стенде карточка писала «обращений не было» ровно в тот час, когда в
     * «Чатах» лежал сегодняшний диалог этого же канала («Машинка не сливает
     * воду», 19:57), вебхук показывал событие сегодня, а статистика — семь
     * новых диалогов за месяц. Оговорки про отставание не было нигде.
     *
     * Цена ошибки несимметрична, поэтому и правка такая. «Канал молчит» — это
     * повод идти проверять объявления и подписку, то есть звать администратора
     * из-за того, что просто не прошёл час. А второй строкой сказано, где
     * лежит живой ответ: очередь «Входящие» считается по самим диалогам и не
     * отстаёт.
     */
    const оговорка = `Сводка отстаёт до ${staleLabel(stale)} — самые свежие обращения сюда ещё не попали, их видно в «Чатах».`;
    return (
      <div className="week-bars__empty">
        <Text fz="xs" c="var(--lc-text-3)">
          Обращений за неделю не видно
        </Text>
        {/* ⚠ ПОДСКАЗКА ОБЯЗАТЕЛЬНА: в свёрнутой строке оговорка обрезается до
            одной линии (иначе ряд пустого канала выходил вдвое выше соседних —
            139 px против 70), и прочесть её целиком можно только наведением
            либо раскрыв строку. Тот же приём, что у объяснения выключенного
            канала. */}
        <Text fz="xs" c="var(--lc-text-3)" title={оговорка}>
          {оговорка}
        </Text>
      </div>
    );
  }

  return (
    <div className="week-bars">
      <div
        className="week-bars__chart"
        role="img"
        aria-label={`Обращения по дням недели, всего ${stats.total}`}
      >
        {stats.daily.map((value, i) => (
          <Tooltip key={i} label={`${labels[i]}: ${value}`} withArrow openDelay={200}>
            <span className="week-bars__bar" data-empty={value === 0 || undefined}>
              {/* Минимум в два пикселя у ненулевого дня: столбик высотой ноль
                  неотличим от дня без обращений, а это разные вещи. */}
              <span
                className="week-bars__fill"
                style={{ height: value === 0 ? "2px" : `${Math.max(2, (value / peak) * 100)}%` }}
              />
            </span>
          </Tooltip>
        ))}
      </div>

      <div className="week-bars__numbers">
        {/*
          ⚠ ПЕРВАЯ ЛИНИЯ НЕ ПЕРЕНОСИТСЯ (макет 04.09, п. 5). Три числа стояли
          одним переносящимся рядом: у канала с «512 обращений за неделю · 61
          без ответа» ряд ломался пополам, ряд поднимался на строку выше
          соседей, и список шёл волной. Теперь линий ровно две, первая обрезается
          многоточием, а целиком фраза остаётся подсказкой — высота ряда у всех
          тридцати пяти каналов одна.
        */}
        <div className="week-bars__line">
          {/* ⚠ КЕГЛЬ И ВЕС — В week-bars.css, А НЕ ЗДЕСЬ. Число и подпись стояли
              на соседних ступенях шкалы (14 и 12) и весили почти одинаково,
              хотя ради числа на страницу и заходят. Разбор — у
              `.week-bars__total`; размер задан токеном там же, где остальная
              геометрия этого блока. */}
          <Text span c="var(--lc-text-1)" className="lc-num week-bars__total">
            {stats.total}
          </Text>{" "}
          {/* Та же оговорка, что и у пустой недели, но здесь она тише: число,
              отставшее на час, вводит в заблуждение куда слабее, чем «обращений
              не было». Поэтому подсказкой по наведению, а не строкой. */}
          <Text
            span
            className="week-bars__caption"
            c="var(--lc-text-3)"
            title={`${stats.total} ${plural(stats.total, "обращение", "обращения", "обращений")} за неделю. Сводка отстаёт до ${staleLabel(stale)}: обращения последнего часа сюда ещё не попали`}
          >
            {plural(stats.total, "обращение", "обращения", "обращений")} за неделю
          </Text>
        </div>
        {stats.missed > 0 && (
          <Tooltip
            label="Обращения, на которые никто ни разу не ответил"
            withArrow
            openDelay={200}
          >
            {/* Точка-разделитель ушла вместе с общим рядом: второй линии
                отделять себя от первой нечем и незачем. */}
            <Text
              fz="xs"
              className="week-bars__missed"
              data-alarming={alarming || undefined}
            >
              <span className="lc-num">{stats.missed}</span> без ответа
            </Text>
          </Tooltip>
        )}
      </div>
    </div>
  );
}
