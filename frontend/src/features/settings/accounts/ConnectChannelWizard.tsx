import { useEffect, useState } from "react";
import { Alert, Button, Modal, PasswordInput, Stack, Text, TextInput } from "@mantine/core";
import { useMutation, useQuery } from "@tanstack/react-query";
import { queryClient } from "@/app/queryClient";
import { qk } from "@/shared/api/queryKeys";
import { ApiError, http, request } from "@/shared/api/http";
import { showToast } from "@/shared/ui/toast";
import "./connect-wizard.css";

/**
 * Подключение аккаунта Авито — ДВА ПОЛЯ И КНОПКА.
 *
 * РЕШЕНИЕ ЗАКАЗЧИКА: «давай так, чтобы для привязки нам был нужен только
 * Client Secret и ID». До этого подключение шло через согласие: человек уходил
 * на Авито, входил под учётной записью аккаунта, разрешал доступ, возвращался.
 *
 * ПОЧЕМУ ТАК МОЖНО. У Авито есть вход `client_credentials`, и все нужные методы
 * мессенджера его принимают — проверено по официальной спецификации (docs/26).
 * Пара ключей сама по себе даёт доступ к тому аккаунту, которому принадлежит.
 *
 * ПОЧЕМУ ТАК ЛУЧШЕ ИМЕННО ЗДЕСЬ. Аккаунтов девять, пароли от них у разных
 * людей, и владелец системы их у себя не держит. «Пришлите ключи» — просьба,
 * которую можно выполнить, не отдавая пароль; «пришлите пароль» — нельзя.
 * Заодно исчезли адрес возврата, страница согласия и возврат с ошибкой, по
 * которой ничего не понять.
 *
 * ЧЕГО ЗДЕСЬ НЕТ. Выбора типа канала: он у нас ровно один — Авито. И шага
 * настройки общего приложения: теперь ключи у каждого аккаунта свои, и общих
 * настраивать больше незачем.
 */

interface AccountDto {
  id: string;
  title: string;
  avito_user_id: number;
  /** Завели новый канал или обновили ключи у уже подключённого. */
  created?: boolean;
}

interface AvitoAppDto {
  api_base: string;
  auth_url: string;
  live: boolean;
  client_id: string;
  secret_set: boolean;
}

export function ConnectChannelWizard({
  opened,
  onClose,
}: {
  opened: boolean;
  onClose: () => void;
}) {
  const [clientId, setClientId] = useState("");
  const [secret, setSecret] = useState("");
  // Код источника заявки («В95»). То же поле, что в карточке канала, —
  // `lead_origin`, а НЕ лид-центр `lead_src_key`: два разных поля с похожими
  // именами, и первая редакция карточки на этом уже спотыкалась.
  const [источник, setИсточник] = useState("");
  /*
   * ⚠ ЧУЖАЯ ПОДПИСКА: СЕРВЕР ПРОСИТ ПОДТВЕРДИТЬ — ЗНАЧИТ НУЖНО ЧЕМ (28.08).
   *
   * Авито держит на аккаунт РОВНО ОДНУ подписку на события, и подключение
   * вытесняет ту, что стоит сейчас. Сервер честно отказывает 409 с
   * `reason: subscription_taken` и просит прислать `takeover_confirmed`.
   *
   * А интерфейс показывал этот отказ обычным красным тостом — с фразой
   * «Подтвердите, что канал нужно забрать» и БЕЗ единого способа подтвердить.
   * Тупик: человек читает требование, которое некуда исполнить, жмёт
   * «Подключить» снова, получает тот же тост вторым экземпляром — ровно то,
   * что на снимке от владельца.
   *
   * Держим адреса чужих подписок: по ним видно, чья она, и решение «забирать
   * или нет» перестаёт быть слепым.
   */
  const [перехват, setПерехват] = useState<string[] | null>(null);

  useEffect(() => {
    if (opened) {
      setClientId("");
      setSecret("");
      // ⚠ ИСТОЧНИК СБРАСЫВАЕТСЯ ВМЕСТЕ С КЛЮЧАМИ. Поле добавлено 27.08, а в этот
      // сброс не попало — и второй подключаемый аккаунт получал код источника
      // первого: окно закрыли, открыли снова, ключи стёрлись, а «В95» осталось
      // в поле и молча уехало на сервер. Заявки нового канала ушли бы с чужим
      // кодом, и заметили бы это в лид-центре, а не здесь.
      setИсточник("");
      // И согласие на перехват: оно дано про ТЕ ключи и ТУ чужую подписку.
      // Пережив закрытие окна, оно уезжало с ключами другого аккаунта и молча
      // снимало его подписку, которую человек не видел (проверка 24.09).
      setПерехват(null);
    }
  }, [opened]);

  /*
   * КУДА СМОТРИТ СИСТЕМА — здесь, а не в отдельной настройке.
   *
   * Пока не выданы боевые ключи, система работает на встроенном имитаторе, и
   * он принимает ЛЮБЫЕ ключи: подключение проходит, карточка зелёная, а
   * настоящих обращений не будет никогда. Заказчик на это и наткнулся —
   * подключил и увидел данные имитатора вместо своего аккаунта.
   *
   * Поэтому режим показан прямо в окне подключения, до кнопки: это первое, что
   * человек должен знать, нажимая «Подключить».
   */
  const app = useQuery({
    queryKey: ["avito-app"],
    queryFn: () => http.get<AvitoAppDto>("/avito/app"),
    enabled: opened,
  });

  /*
   * Переключение идёт своей ручкой, а не сохранением настроек приложения.
   *
   * Раньше здесь стоял `PUT /avito/app`, который требует пару ключей
   * приложения, — а их у нас нет и не будет: каналы подключаются СВОИМИ
   * ключами. Чтобы запрос прошёл, в поля подставлялась строка "unused". Это
   * враньё в данных: кто-нибудь однажды прочитает "unused" как настоящий
   * Client ID и будет долго искать, почему Авито его не принимает.
   */
  const goLive = useMutation({
    mutationFn: () =>
      request<AvitoAppDto>("/avito/app/mode", { method: "POST", body: { live: true } }),
    onSuccess: () => {
      void app.refetch();
      showToast({ title: "Переключено на настоящий Авито", color: "lp" });
    },
    onError: (e) =>
      showToast({
        title: "Не переключилось",
        message: e instanceof ApiError ? e.message : "Попробуйте ещё раз",
        color: "red",
      }),
  });

  const connect = useMutation({
    mutationFn: (забрать?: boolean) =>
      http.post<AccountDto>("/avito-accounts/connect", {
        client_id: clientId.trim(),
        client_secret: secret.trim(),
        // Пустую строку не шлём: у уже подключённого аккаунта повторное
        // подключение ключами не должно стирать проставленный код.
        ...(источник.trim() ? { lead_origin: источник.trim() } : {}),
        // Поле шлём ТОЛЬКО после осознанного нажатия и ровно на один запрос:
        // согласие про это подключение, а не про аккаунт навсегда.
        ...(забрать ? { takeover_confirmed: true } : {}),
      }),
    onSuccess: (account) => {
      setПерехват(null);
      void queryClient.invalidateQueries({ queryKey: qk.accounts });
      onClose();
      /*
       * РАЗНЫЕ ИСХОДЫ — РАЗНЫЕ СЛОВА.
       *
       * Если ключи принадлежат уже подключённому аккаунту, система обновляет
       * существующий канал, а не заводит новый. Пока оба исхода показывались
       * одним зелёным тостом, это читалось как успех: человек подключал
       * «второй» аккаунт, видел «подключён» и чужое название, а список
       * каналов не рос. Отсюда «я могу подключить только 1 аккаунт».
       *
       * Причина не в системе: при входе по ключам пара принадлежит ТОМУ
       * аккаунту, где заведено приложение. Значит на каждый аккаунт Авито
       * нужны свои ключи — и сказать об этом надо ровно здесь, в момент,
       * когда человек столкнулся.
       */
      if (account.created === false) {
        showToast({
          title: "Это тот же аккаунт, что уже подключён",
          message:
            `Ключи принадлежат каналу «${account.title}» — они обновлены, новый канал не появился. ` +
            "Для другого аккаунта Авито нужны его собственные Client ID и Client Secret, " +
            "созданные в его кабинете разработчика.",
          color: "yellow",
          autoClose: false,
        });
        return;
      }
      showToast({
        title: `Аккаунт «${account.title}» подключён`,
        message: "Новые обращения по его объявлениям пойдут в «Чаты»",
        color: "lp",
      });
    },
    onError: (e) => {
      /*
       * Чужая подписка — не отказ, а ВОПРОС. Показываем его в самом окне, где
       * есть кнопка, а не тостом, где её нет: тост с требованием «подтвердите»
       * и без способа подтвердить — тупик, из которого человек выходит только
       * повторным нажатием и вторым таким же тостом.
       */
      const детали = e instanceof ApiError ? (e.details as Record<string, unknown> | undefined) : undefined;
      if (детали?.reason === "subscription_taken") {
        const адреса = Array.isArray(детали.subscriptions) ? (детали.subscriptions as string[]) : [];
        setПерехват(адреса);
        return;
      }
      // Сервер уже написал причину человеческими словами и назвал, чего не
      // хватает (не те ключи / нет прав на мессенджер / Авито недоступен).
      // Переписывать её здесь значило бы завести второе место для одного
      // правила и однажды разойтись с ним.
      showToast({
        title: "Не подключилось",
        message: e instanceof ApiError ? e.message : "Попробуйте ещё раз",
        color: "red",
        autoClose: false,
      });
    },
  });

  const ready = clientId.trim().length > 0 && secret.trim().length > 0;

  return (
    <Modal
      opened={opened}
      onClose={onClose}
      centered
      size={520}
      className="wizard"
      title="Подключить аккаунт Авито"
    >
      <Stack gap="var(--lc-space-4)">
        <Text fz="sm" c="var(--lc-text-2)">
          Нужны два значения из кабинета разработчика Авито того аккаунта, который
          подключаете. Пароль от аккаунта не требуется — если ключей у вас нет, попросите их
          у того, кто ведёт этот аккаунт.
        </Text>

        <TextInput
          label="Client ID"
          placeholder="из кабинета разработчика Авито"
          value={clientId}
          onChange={(e) => {
            setClientId(e.currentTarget.value);
            setПерехват(null);
          }}
          data-autofocus
        />
        <PasswordInput
          label="Client Secret"
          value={secret}
          onChange={(e) => {
            setSecret(e.currentTarget.value);
            setПерехват(null);
          }}
        />
        {/* Источник здесь, а не только в карточке канала (просьба владельца
            27.08). Между подключением и правкой источника аккаунт уже живой:
            первое обращение может прийти в ту же секунду, и заявка по нему
            ушла бы без кода — молча. Поле необязательное: не знаешь код
            сейчас — проставишь в карточке потом. */}
        <TextInput
          label="Источник"
          placeholder="В95 — можно проставить и позже, в карточке канала"
          value={источник}
          onChange={(e) => setИсточник(e.currentTarget.value)}
        />

        {/* Имитатор принимает любые ключи и отдаёт свои выдуманные данные.
            Подключение при этом выглядит удавшимся — и это худший вид
            поломки: система уверяет, что работает, а обращения не придут. */}
        {app.data && !app.data.live && (
          <Alert color="yellow" variant="light" title="Система смотрит на встроенный имитатор">
            <Text fz="sm">
              Он примет любые ключи и покажет выдуманный аккаунт — настоящих обращений не
              будет. Переключите на настоящий Авито перед подключением.
            </Text>
            <Button
              mt="var(--lc-space-2)"
              size="compact-sm"
              loading={goLive.isPending}
              onClick={() => goLive.mutate()}
            >
              Переключить на настоящий Авито
            </Button>
          </Alert>
        )}

        {/* Права названы здесь, а не в справке: это единственное, что человек
            должен был отметить при создании приложения, и единственная ошибка,
            которую он не заметит — ключи примут, а работать не будет. */}
        <Alert variant="light" title="Приложению нужны права">
          <Text fz="sm">
            <code>messenger:read</code>, <code>messenger:write</code>, <code>user:read</code>
          </Text>
          <Text fz="xs" c="var(--lc-text-3)" mt="var(--lc-space-1)">
            Без них Авито примет ключи, но переписку не отдаст.
          </Text>
        </Alert>

        {/*
          ЧУЖАЯ ПОДПИСКА — ВОПРОС В ОКНЕ, А НЕ ОТКАЗ В ТОСТЕ.
          Авито держит на аккаунт ровно одну подписку, и подключение вытесняет
          ту, что стоит сейчас: у владельца это работающий Jivo на боевом
          канале. Тринадцать диспетчеров перестают получать обращения в ту же
          секунду. Поэтому вопрос стоит рядом с кнопкой, называет адреса чужих
          подписок (по ним видно, чья она) и требует отдельного нажатия.
        */}
        {перехват !== null && (
          <Alert variant="light" color="orange" title="Канал уже кем-то занят">
            <Text fz="sm">
              На этом аккаунте Авито уже стоит подписка на события — сейчас его обслуживает другая
              система (обычно это Jivo). Авито держит на аккаунт ровно одну подписку: если забрать
              канал, та система перестанет получать обращения от клиентов в ту же секунду.
            </Text>
            {перехват.length > 0 && (
              <Text fz="xs" c="var(--lc-text-3)" mt="var(--lc-space-1)" component="div">
                Чужие подписки:
                <ul className="wizard__subs">
                  {перехват.map((адрес) => (
                    <li key={адрес}>{адрес}</li>
                  ))}
                </ul>
              </Text>
            )}
          </Alert>
        )}

        <div className="wizard__foot">
          <Button variant="default" onClick={onClose} disabled={connect.isPending}>
            Отмена
          </Button>
          {перехват !== null ? (
            <Button
              color="orange"
              loading={connect.isPending}
              disabled={!ready || app.data?.live === false}
              onClick={() => connect.mutate(true)}
            >
              Забрать канал себе
            </Button>
          ) : (
            <Button
              loading={connect.isPending}
              disabled={!ready || app.data?.live === false}
              title={
                app.data?.live === false
                  ? "Сначала переключите систему на настоящий Авито"
                  : undefined
              }
              onClick={() => connect.mutate(undefined)}
            >
              Подключить
            </Button>
          )}
        </div>
      </Stack>
    </Modal>
  );
}
