import type { CSSProperties } from "react";
import { useEffect, useRef, useState } from "react";
import { TextInput } from "@mantine/core";

/**
 * Поле «ключевые слова через запятую».
 *
 * ⚠ ЗАЧЕМ ОТДЕЛЬНЫЙ КОМПОНЕНТ, А НЕ ДВА ПОЛЯ НА МЕСТЕ (28.08).
 *
 * Оба места — «Меню» и условие «текст содержит» — были написаны одинаково и
 * ломались одинаково: значение бралось производным (`value.join(", ")`), а
 * onChange на каждой букве разбирал набранное в массив. В ту секунду, когда
 * человек печатает ЗАПЯТУЮ, разбор даёт ["да", ""], `filter(Boolean)`
 * выбрасывает пустой хвост, массив остаётся прежним — и React возвращает поле
 * к «да». Запятая и пробел за ней стираются на лету, следующие буквы
 * дописываются к предыдущему слову: «телевизор, тв, плазма» превращается в
 * «телевизортвплазма».
 *
 * Возразить некому. Проверка редактора ловит только пустой список
 * (validation.ts), схема сервера у ключей разрешает любую строку, а движок
 * сравнивает ключ целиком (`app/bots/steps.py`: `needle in answer`) — «данет» в
 * ответе клиента не встретится никогда. Бот сохраняется, включается, и все
 * ветки меню оказываются мёртвыми: клиент пишет «телевизор», совпадения нет,
 * разговор уходит в on_no_match. По виду сценария это не понять.
 *
 * ЧИНИТСЯ ЧЕРНОВИКОМ. На экране живёт то, что набрали, — со всеми запятыми и
 * пробелами. Модель обновляется на каждой букве (ничего не теряется, если
 * сохранить не уходя из поля), но обратно в поле мы это НЕ подставляем, пока
 * значение снаружи совпадает с разбором нашего же черновика: иначе курсор
 * прыгал бы на каждую лишнюю запятую.
 */
function разобрать(строка: string): string[] {
  return строка
    .split(",")
    .map((s) => s.trim())
    .filter(Boolean);
}

/** Разделитель слепка: в ключевых словах его быть не может — запятая их делит. */
const СЛЕПОК = ",";

export function KeywordsInput({
  value,
  onChange,
  label,
  ariaLabel,
  style,
}: {
  value: string[];
  onChange: (next: string[]) => void;
  label?: string;
  ariaLabel: string;
  style?: CSSProperties;
}) {
  const [черновик, setЧерновик] = useState(() => value.join(", "));
  const свой = useRef<string | null>(null);
  const ключ = value.join(СЛЕПОК);

  useEffect(() => {
    // Наше же эхо — черновик не трогаем. Пришло чужое (переключили шаг,
    // подгрузился сценарий) — показываем то, что действительно в модели.
    if (свой.current !== null && разобрать(свой.current).join(СЛЕПОК) === ключ) return;
    setЧерновик(value.join(", "));
    свой.current = null;
    // `ключ` — строковый слепок массива: сравнение по ссылке бесполезно, новый
    // массив приезжает на каждый ход редактора.
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [ключ]);

  return (
    <TextInput
      label={label}
      aria-label={ariaLabel}
      value={черновик}
      onChange={(e) => {
        const набрано = e.currentTarget.value;
        свой.current = набрано;
        setЧерновик(набрано);
        onChange(разобрать(набрано));
      }}
      size="sm"
      style={style}
    />
  );
}
