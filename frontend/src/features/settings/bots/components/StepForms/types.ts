import type { BotStep } from "@/shared/api/types";

/**
 * Общий контракт формы шага. Форма — управляемый компонент: она никогда не
 * лезет в стор сама, а отдаёт наверх целый новый шаг (`onChange`), потому что
 * правка одного поля может задевать соседние (смена валидатора, вариантов меню).
 */
export interface StepFormProps<T extends BotStep> {
  step: T;
  /** id всех шагов сценария — источник для Select'ов переходов (02 §5.1). */
  stepIds: string[];
  /** Переменные, доступные для вставки в тексты этого шага (02 §5.1). */
  vars: string[];
  onChange: (next: T) => void;
}
