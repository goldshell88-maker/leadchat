import type { BotCreateInput } from "@/shared/api/types";

/**
 * Тело POST /bots для кнопки «Создать бота» (01 §8.3).
 *
 * СЦЕНАРИЙ И БАЗУ ЗНАНИЙ КЛАДЁТ СЕРВЕР (проверка 24.09). Здесь жила своя копия
 * «Первичного приёма», и она разошлась с серверной (`app/bots/scenarios/
 * primary_intake.json`): через сутки молчания клиента бот закрывал диалог сам,
 * хотя владелец автозакрытие отменил, а дожима через 20 минут не было вовсе.
 * База знаний с выдуманными ценами — туда же: сервер оставляет её пустой, и
 * валидатор напоминает заполнить её перед включением.
 */
export function newBotInput(name = "Новый бот"): BotCreateInput {
  return {
    name,
    // Новый бот выключен: сначала прогон в песочнице, потом включение (02 §5.3).
    is_enabled: false,
    // И даже включённый начинает подсказкой: сперва видно, ЧТО он пишет, и лишь потом
    // ему отдают слово. Переключение — руками, в редакторе.
    // Новый бот думает нашим Claude и молчит в клиента: оба переключателя — «как было».
    ai_provider: "claude",
    mode: "suggest",
    schedule: { always: true },
  };
}
