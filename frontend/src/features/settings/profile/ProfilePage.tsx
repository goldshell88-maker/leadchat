import { useState, type KeyboardEvent as ReactKeyboardEvent } from "react";
import { Text, Title } from "@mantine/core";
import { PresenceBlock } from "@/features/presence/PresenceBlock";
import { usePermissions, type Role } from "@/shared/auth/usePermissions";
import { useSessionStore } from "@/shared/stores/sessionStore";
import { UserAvatar } from "@/shared/ui/UserAvatar";
import { AboutAppBlock } from "./AboutAppBlock";
import { AppearanceBlock } from "./AppearanceBlock";
import { ChangePasswordForm } from "./ChangePasswordForm";
import { BrowserAlertsBlock } from "./BrowserAlertsBlock";
import { ToastsBlock } from "./ToastsBlock";
import { HotkeysBlock } from "./HotkeysBlock";
import { ContactAdminForm } from "./ContactAdminForm";
import { MyChannelsBlock } from "./MyChannelsBlock";
import { OwnNameField } from "./OwnNameField";
import { PageHeader } from "@/shared/ui/PageHeader";
import "./profile.css";

const ROLE_LABELS: Record<Role, string> = {
  admin: "Администратор",
  head: "Руководитель",
  manager: "Менеджер",
  observer: "Наблюдатель",
};

const ROLE_HINTS: Record<Role, string> = {
  admin: "полный доступ, включая аккаунты Авито и команду",
  head: "видит все диалоги, передаёт их и пишет заметки — отвечать клиенту не может",
  manager: "отвечает клиентам, ведёт свои диалоги и передаёт их коллегам",
  observer: "только чтение диалогов",
};

/**
 * `/settings/profile` (11 §4.3): профиль, своё состояние «на месте / отошёл»,
 * личные быстрые ответы (кроме наблюдателя — `templates:own`), внешний
 * вид/звук.
 *
 * ПРО ПАРОЛЬ. Форма смены СВОЕГО пароля стоит в карточке «Доступ и пароль»
 * (05.09, дефект аудита FUNC-82 закрыт). До этого дня ручка на сервере
 * существовала, была покрыта тестами и умела всё нужное — а вызвать её из
 * интерфейса было нечем: грепом по `src` она встречалась только в комментарии,
 * который сам это и объяснял. Смена пароля на тринадцать человек означала
 * переписку с администратором на полдня, то есть пароли не меняли вовсе.
 *
 * Состояние присутствия приехало сюда из меню аватара 11 августа (требование
 * владельца №9): это настройка человека о себе, и жить ей среди остальных
 * настроек профиля, а не в выпадающем списке, о котором половина смены не
 * знает. В меню осталась строка-признак без переключения.
 *
 * ⚠ ЭКРАН ПЕРЕСОБРАН 05.09. Владелец посмотрел прошлую правку и сказал: «вкладка
 * профиль так и не переработана». Он был прав: правили кегли заголовков, а
 * раскладка осталась прежней — одна колонка из восьми одинаковых серых блоков
 * с чертами между ними, где имя человека, версия приложения и переключатель
 * «на месте / отошёл» весили ровно поровну.
 *
 * Ярусов теперь три, и у каждого своя роль:
 *   ШАПКА (`.prof-hero`) — кто я и в каком я состоянии. Над вкладками, значит
 *   видна с обеих. Единственный обведённый элемент здесь — присутствие: то,
 *   что меняют каждый день.
 *   КАРТОЧКИ (`.prof-card`) — настройки. Заголовок отделён от контрола линией,
 *   от 1200 пикселей идут в две колонки.
 *   СПРАВКА (`.prof-card--ref`) — роль, пароль, версия. Без рамки, последней:
 *   её читают один раз, а места занимала столько же, сколько переключатели.
 */
export function ProfilePage() {
  const user = useSessionStore((s) => s.user);
  const { can } = usePermissions();
  const [activeId, setActiveId] = useState("account");

  if (!user) return null;

  /*
   * ВКЛАДКИ СОБИРАЮТСЯ ПО ФАКТУ СОДЕРЖИМОГО, а не статическим списком.
   *
   * Быстрые ответы есть не у всех — наблюдателю право `templates:own` не
   * выдаётся. Статический список дал бы ему пустую вкладку: заголовок, за
   * которым ничего нет, читается как поломка.
   *
   * ПОЧЕМУ ИМЕННО ТАКОЕ ДЕЛЕНИЕ. Форма письма администратору и «Мои
   * каналы» ОБЯЗАНЫ жить на одной вкладке: пустой список каналов отправляет
   * писать администратору, а сама форма ссылается на список. Развести их —
   * сделать обе подсказки враньём. Указания «выше»/«ниже» из обеих подсказок
   * убраны 05.09: в две колонки они врут, форма теперь названа по имени.
   *
   * ⚠ ДВЕ КОЛОНКИ ВЕРНУЛИСЬ, И НЕ ТЕ, ЧТО ЛОМАЛИ ПРОКРУТКУ. Прежняя плотная
   * раскладка была многоколоночной (`columns`): она режет поток на колонки
   * ВНУТРИ контейнера прокрутки, и высота содержимого переставала считаться —
   * вертикальная прокрутка раздела пропадала. Здесь обычный CSS Grid: каждая
   * карточка — отдельная ячейка, высота строки считается по самой высокой,
   * прокрутка остаётся у `.settings-section`, как и была. Проверено стендом на
   * 375/768/1024/1440/2560.
   */
  const tabs = [
    {
      id: "account",
      label: "Учётная запись",
      render: () => (
        <div className="prof-grid">
          {/*
            КАНАЛЫ ПЕРВЫМИ, ФОРМА ВТОРОЙ. Порядок был обратный, и держался он на
            подписи пустого списка: «напишите администратору формой выше».
            В две колонки такое указание врёт — форма стоит не выше, а справа, —
            поэтому подпись переписана на имя формы, а не на её место
            (MyChannelsBlock.tsx). Каналы наверху ещё и потому, что это ответ на
            вопрос, с которым сюда приходят («почему коллега видит диалог, а я
            нет»), а форма — редкое действие.
          */}
          <MyChannelsBlock />

          {/* Письмо администратору (14 §2.2). Роль не проверяем: пишут все. */}
          <ContactAdminForm />

          {/*
            СПРАВКА, А НЕ НАСТРОЙКА, И ВЫГЛЯДИТ ОНА ТЕПЕРЬ ИНАЧЕ.

            Роль и подсказка про пароль лежали в одном блоке с аватаром, то есть
            занимали столько же места и весили столько же, сколько «Оформление»
            или «Мои каналы». Читают их один раз за всё время работы. Здесь они
            вместе с «О приложении» стоят последними и без рамки — на полотне
            (`.prof-card--ref`).

            Роль показана и в шапке пилюлей: там ответ на «кто я», здесь — что
            это означает. Дублированием это не считается ровно потому, что
            вопросы разные.
          */}
          <section className="lc-card prof-card prof-card--ref">
            <div className="prof-card__head">
              <Title order={2} fz="var(--lc-fz-section)" c="var(--lc-text-1)">
                Доступ и пароль
              </Title>
              <Text component="p" fz="sm" c="var(--lc-text-3)">
                Что вам разрешено в системе и кто меняет пароль
              </Text>
            </div>
            <Text fz="sm" c="var(--lc-text-2)">
              <b>{ROLE_LABELS[user.role]}</b> — {ROLE_HINTS[user.role]}
            </Text>
            {/*
              ПОДСКАЗКА ПРО ПАРОЛЬ ЗАВИСИТ ОТ ТОГО, КТО СМОТРИТ.
              Здесь стоял один текст на всех: «Пароль меняет администратор —
              напишите ему формой ниже». Администратор, открыв свой профиль,
              читал под собственной ролью «Администратор» предложение написать
              администратору — то есть самому себе, формой, которая кладёт
              письмо в его же центр уведомлений.

              Спрашиваем ПРАВО, а не роль: набор прав приходит с сервера
              (`GET /auth/me`), и матрицу «роль → права» фронт не повторяет
              намеренно (shared/auth/usePermissions.ts). Кто заводит и
              сбрасывает пароли сотрудникам — тот и владеет `users:manage`.

              ФОРМА СМЕНЫ СВОЕГО ПАРОЛЯ ТЕПЕРЬ ЕСТЬ (05.09) — она ниже, а
              разбор в её собственной шапке. Здесь остаётся только различие:
              СВОЙ пароль человек меняет сам, ЧУЖИЕ сбрасывает администратор в
              разделе «Команда». Раньше обе подсказки говорили «меняет
              кто-то другой», и это было правдой ровно до появления формы.
            */}
            {/*
              ⚠ ТЕКСТ ИЗМЕНИЛСЯ, ПОТОМУ ЧТО ИЗМЕНИЛАСЬ ПРАВДА (05.09). Обе
              прежние подсказки говорили «свой пароль меняет кто-то другой» — и
              были верны ровно до сегодня, пока формы не существовало. Теперь
              она стоит ниже, и оставить прежний текст значило бы врать человеку
              о его же возможностях.

              Про администратора строка осталась, но говорит о ЧУЖИХ паролях:
              сбрасывать их по-прежнему ему, в разделе «Команда».
            */}
            <Text fz="sm" c="var(--lc-text-3)">
              {can("users:manage")
                ? "Пароли сотрудникам задаёте и сбрасываете вы сами — в разделе «Команда». Свой меняется здесь."
                : "Свой пароль меняется здесь. Забыли текущий — напишите администратору формой «Написать администратору» на этой вкладке."}
            </Text>
            <ChangePasswordForm />
          </section>

          {/* Только в приложении для Windows (04 §6.3); в браузере вернёт null. */}
          <AboutAppBlock />
        </div>
      ),
    },
    {
      id: "interface",
      label: "Интерфейс",
      render: () => (
        <div className="prof-grid">
          <AppearanceBlock />
          {/*
            Рядом со звуком, а не в отдельной вкладке: это два ответа на один вопрос —
            «как я узнаю о новом сообщении». Звук работает, пока вкладка открыта;
            уведомление — когда она скрыта.
          */}
          <BrowserAlertsBlock />
          {/* Здесь же, а не отдельной вкладкой: это третий ответ на тот же
              вопрос «как я узнаю о новом» — звук, уведомление браузера и
              всплывашка в углу. */}
          <ToastsBlock />
          {/* Единственная карточка во всю ширину: внутри таблица из девятнадцати
              строк в три столбца, и в половине ширины она переносит подписи
              действий по словам. */}
          <HotkeysBlock />
        </div>
      ),
    },
    /*
     * ⚠ ВКЛАДКИ «БЫСТРЫЕ ОТВЕТЫ» ЗДЕСЬ БОЛЬШЕ НЕТ (разбор 03.09), И ЭТО НЕ
     * ПОТЕРЯ, А КОНЕЦ ДВОЕНИЯ.
     *
     * Личные быстрые ответы жили в двух местах сразу и читали ОДИН кэш: эта
     * вкладка и вкладка «Мои» в разделе `/settings/templates`. Дефект был
     * записан в шапке `TemplatesManager` как TPL-06, там же назван и честный
     * выход: убрать вкладку отсюда и открыть раздел по праву `templates:own`,
     * чтобы человек нашёл быстрые ответы там, где их называют.
     *
     * Раздел теперь открыт всем, у кого есть свои заготовки, и сам решает, что
     * показать: администратору — общие и личные, диспетчеру — только его.
     */
  ];

  const active = tabs.find((t) => t.id === activeId) ?? tabs[0];

  /*
   * ВКЛАДКИ ХОДЯТ СТРЕЛКАМИ, И У НИХ ЕСТЬ ПАНЕЛЬ (доступность).
   *
   * Роли `tablist`/`tab` стояли, а остального набора не было: панель под ними
   * не имела `role="tabpanel"` и ни на кого не ссылалась, `aria-controls` не
   * было, и все три вкладки собирали фокус по Tab подряд. Для программы чтения
   * с экрана это разъехавшееся обещание: объявлено «вкладка 2 из 3», а
   * содержимое вкладки — просто следующий кусок страницы, никак с ней не
   * связанный; понять, что оно поменялось от нажатия, нельзя.
   *
   * Делаем по образцу WAI-ARIA: внутри полосы ходят стрелками (с закольцовкой),
   * Tab уводит сразу в содержимое, панель подписана активной вкладкой.
   * Тот же приём — в списке быстрых ответов, чтобы в разделе был один способ.
   */
  const onTabKeyDown = (e: ReactKeyboardEvent<HTMLButtonElement>) => {
    const step = e.key === "ArrowRight" ? 1 : e.key === "ArrowLeft" ? -1 : 0;
    if (step === 0) return;
    e.preventDefault();
    const i = tabs.findIndex((t) => t.id === activeId);
    const next = tabs[(i + step + tabs.length) % tabs.length];
    if (!next) return;
    setActiveId(next.id);
    document.getElementById(`profile-tab-${next.id}`)?.focus();
  };

  return (
    <div className="settings-section">
      <PageHeader title="Профиль" description="Ваши данные, каналы и личные настройки" />

      {/*
        ШАПКА — ЛИЦО ЭКРАНА, И ОНА СТОИТ НАД ВКЛАДКАМИ, А НЕ ВНУТРИ ОДНОЙ ИЗ НИХ.

        Было: аватар 40 px внутри такого же серого блока, что и «Мои каналы»,
        имя ступенью текста, а «на месте / отошёл» — третьим блоком сверху, то
        есть под вкладкой «Учётная запись». Переключился на «Интерфейс» — и
        состояния на экране нет вовсе, хотя меняют его по нескольку раз в смену,
        а всё остальное здесь трогают раз в полгода.

        Стало: кто я (аватар 64, имя, роль пилюлей, почта) и в каком я состоянии
        — в одном ярусе над вкладками. Состояние видно и меняется с любой
        вкладки, а по крупному аватару с именем экран узнаётся с первого взгляда.
      */}
      <section className="prof-hero" aria-label="Кто вы в системе">
        <div className="prof-hero__id">
          <UserAvatar name={user.full_name} size={64} />
          <div className="prof-hero__who">
            <OwnNameField name={user.full_name} />
            <p className="prof-hero__meta">
              <span className="prof-hero__role">{ROLE_LABELS[user.role]}</span>
              <span className="prof-hero__mail">{user.email}</span>
            </p>
          </div>
        </div>
        <PresenceBlock />
      </section>

      <div className="lc-tabs" role="tablist" aria-label="Разделы профиля">
        {tabs.map((t) => (
          <button
            key={t.id}
            type="button"
            role="tab"
            id={`profile-tab-${t.id}`}
            aria-controls="profile-tabpanel"
            className="lc-tabs__tab"
            aria-selected={t.id === activeId}
            tabIndex={t.id === activeId ? 0 : -1}
            data-active={t.id === activeId || undefined}
            onKeyDown={onTabKeyDown}
            onClick={() => setActiveId(t.id)}
          >
            {t.label}
          </button>
        ))}
      </div>

      <div
        className="profile-tabpanel"
        id="profile-tabpanel"
        role="tabpanel"
        aria-labelledby={`profile-tab-${active?.id ?? activeId}`}
      >
        {active?.render()}
      </div>
    </div>
  );
}
