import { Button, Text, Title } from "@mantine/core";
import { requestHotkeysHelp } from "@/features/hotkeys/focusBus";
import { HotkeysEditor } from "./HotkeysEditor";

/**
 * Горячие клавиши в настройках — теперь ссылкой на общую справку, а не второй
 * её копией.
 *
 * ЗАЧЕМ ЗДЕСЬ ВООБЩЕ ЧТО-ТО ОСТАЛОСЬ. Сам список переехал в окно, которое
 * открывается по «?» из любого места, — вспоминают сочетание посреди работы,
 * а не сидя в настройках. Но человек, который о клавише «?» не знает, пойдёт
 * искать сочетания именно сюда: настройки — то место, где ищут «что тут
 * вообще есть». Пустое место здесь означало бы, что функция исчезла.
 *
 * Список НЕ дублируется: кнопка открывает то же самое окно. Две копии
 * перечня разошлись бы на первой правке, а расхождение хуже отсутствия —
 * шпаргалка, обещающая несуществующее сочетание, заставляет решить, что
 * сломалось приложение.
 */
export function HotkeysBlock() {
  return (
    /*
     * ⚠ ЕДИНСТВЕННАЯ КАРТОЧКА ВО ВСЮ ШИРИНУ (`--wide`). Внутри таблица из
     * девятнадцати строк в три столбца: действие, сочетание, кнопка с
     * переключателем. В половине сетки (454 px на окне 1200) столбец действий
     * получает около 180 и переносит подписи по словам — «Принять / следующий
     * диалог» в две строки девятнадцать раз подряд.
     */
    <section className="lc-card prof-card prof-card--wide">
      <div className="prof-card__head">
        <Title order={2} fz="var(--lc-fz-section)" c="var(--lc-text-1)">
          Горячие клавиши
        </Title>
        <Text component="p" fz="sm" c="var(--lc-text-3)">
          Какие сочетания включены у вас и как их переназначить
        </Text>
      </div>
      <Text fz="sm" c="var(--lc-text-2)">
        Основные сочетания совпадают с Jivo — переучиваться не нужно. Всё то же самое
        по-прежнему можно сделать мышью.
      </Text>
      <Button
        variant="default"
        size="xs"
        style={{ alignSelf: "flex-start" }}
        onClick={() => requestHotkeysHelp()}
      >
        Показать сочетания
      </Button>
      <Text fz="xs" c="var(--lc-text-3)">
        Или нажмите «?» в любом месте программы
      </Text>

      {/*
        ПЕРЕНАЗНАЧЕНИЕ — ЗДЕСЬ, А НЕ В ОКНЕ СПРАВКИ (требование заказчика 13 августа).
        Окно открывается посреди работы, чтобы ВСПОМНИТЬ сочетание; настраивают их
        один раз и осознанно. Смешай оба — и человек, заглянувший подсмотреть клавишу,
        случайно её переназначит.
      */}
      <HotkeysEditor />
    </section>
  );
}
