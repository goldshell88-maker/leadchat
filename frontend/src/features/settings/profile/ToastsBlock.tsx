import { useState } from "react";
import { Switch, Text, Title } from "@mantine/core";
import { setToastsMuted, toastsMuted } from "@/shared/ui/toast";

/**
 * Всплывающие уведомления — выключатель.
 *
 * ⚠ ПРОСЬБА ВЛАДЕЛЬЦА 28.08 дословно: «сделай так, чтобы все уведомления можно
 * было отключить визуально, и появлялись только в колокольчике».
 *
 * ПОЧЕМУ НАСТРОЙКА ЭТОГО УСТРОЙСТВА, А НЕ ЧЕЛОВЕКА. Всплывашка — свойство
 * ЭКРАНА: на большом мониторе она не мешает, на ноутбуке закрывает половину
 * переписки, и один диспетчер работает и там и там. Поэтому она живёт в
 * браузере, как и выбор темы, а не уезжает на сервер вслед за человеком.
 *
 * ⚠ ЧЕСТНАЯ ГРАНИЦА, И ОНА НАЗВАНА ВСЛУХ ПРЯМО НА ЭКРАНЕ. Отказ вашего же
 * действия — «сообщение не ушло», «состояние не сохранилось» — не глушится
 * никогда. Это единственная обратная связь на нажатую кнопку: спрячь её, и
 * человек уйдёт уверенный, что клиенту ответили, а клиент останется без
 * ответа. В колокольчике таких сообщений нет — он про события системы, а не
 * про судьбу нажатия.
 */
export function ToastsBlock() {
  const [muted, setMuted] = useState(toastsMuted);

  return (
    <section className="lc-card prof-card">
      {/*
        ⚠ ЗАГОЛОВОК БЫЛ h4 НА 13 ПИКСЕЛЕЙ СРЕДИ СОСЕДЕЙ-h2 (разбор 05.09).
        Блок стоит четвёртым на вкладке «Интерфейс», между «Уведомлениями
        браузера» и «Горячими клавишами», — и назывался тише, чем собственная
        подпись под ним (13 против 14). Читалось это не как блок, а как
        примечание к предыдущему, то есть выключатель всплывашек выглядел
        частью настроек браузерных уведомлений — противоположной настройкой.
        Для программы чтения с экрана было хуже: h4 без h3 над ним — провал в
        иерархии, «подраздел неизвестно чего».
      */}
      <div className="prof-card__head">
        <Title order={2} fz="var(--lc-fz-section)" c="var(--lc-text-1)">
          Всплывающие уведомления
        </Title>
        <Text component="p" fz="sm" c="var(--lc-text-3)">
          Показывать новости о работе в углу экрана или только в колокольчике
        </Text>
      </div>
      <Text fz="sm" c="var(--lc-text-2)">
        Новости о работе — «диалог принят коллегой», «история загружена» — показываются
        всплывашкой в углу. Выключите, и они останутся только в колокольчике.
      </Text>
      <Switch
        checked={!muted}
        onChange={(e) => {
          const выкл = !e.currentTarget.checked;
          setToastsMuted(выкл);
          setMuted(выкл);
        }}
        label={muted ? "Выключены — только колокольчик" : "Показывать всплывашки"}
      />
      <Text fz="xs" c="var(--lc-text-3)" mt="var(--lc-space-2)">
        Сообщения об ошибке вашего действия — «сообщение не ушло», «не сохранилось» —
        показываются всегда: их нет в колокольчике, и пропустить их нельзя.
      </Text>
      <Text fz="xs" c="var(--lc-text-3)" mt={4}>
        Настройка этого браузера. На другом компьютере выставляется отдельно.
      </Text>
    </section>
  );
}
