import { useState } from "react";
import { Button, PasswordInput, Text } from "@mantine/core";
import { ApiError, http } from "@/shared/api/http";
import { toast } from "@/shared/ui/toast";

/**
 * Смена СВОЕГО пароля.
 *
 * ⚠ РУЧКА НА СЕРВЕРЕ ЖИЛА БЕЗ ЕДИНОГО ПОТРЕБИТЕЛЯ. `POST /auth/change-password`
 * написан, покрыт тестами и умеет всё нужное — спрашивает текущий пароль и
 * обрывает остальные сессии. А формы во фронте не было ни одной: грепом по
 * `src` эта строка встречалась только в комментарии профиля, который сам себя и
 * объяснял. Дефект аудита FUNC-82.
 *
 * Цена: на тринадцать человек «смена пароля» означала переписку с
 * администратором на полдня — то есть пароли не меняли вовсе. И серверный отказ
 * «Свой пароль меняют в профиле — с вводом текущего» указывал в пустоту: в
 * профиле менять было нечем.
 *
 * ⚠ ТЕКУЩИЙ ПАРОЛЬ СПРАШИВАЕТСЯ, И ЭТО НЕ ФОРМАЛЬНОСТЬ. Сессия живёт долго, а
 * незапертый ноутбук в офисе — обычное дело: без проверки любой, кто подошёл к
 * чужому столу, запер бы коллегу из системы. Правило держит сервер, здесь оно
 * лишь показано человеку.
 */
export function ChangePasswordForm() {
  const [текущий, setТекущий] = useState("");
  const [новый, setНовый] = useState("");
  const [идёт, setИдёт] = useState(false);
  const [ошибка, setОшибка] = useState<string | null>(null);

  /*
   * Десять знаков — это правило СЕРВЕРА (app/schemas/auth.py: min_length=10), и
   * повторено оно здесь ровно затем, чтобы человек узнал о нём до отправки, а
   * не отказом. Расходиться им нельзя: смягчи мы проверку — получим отказ,
   * которого человек не ждал; ужесточи — запретим пароль, который сервер
   * принимает.
   */
  const МИНИМУМ = 10;
  const коротко = новый.length > 0 && новый.length < МИНИМУМ;
  const можно = текущий.length > 0 && новый.length >= МИНИМУМ && !идёт;

  const отправить = async () => {
    setИдёт(true);
    setОшибка(null);
    try {
      await http.post("/auth/change-password", {
        current_password: текущий,
        new_password: новый,
      });
      setТекущий("");
      setНовый("");
      /*
       * Про обрыв чужих сессий говорим ВСЛУХ. Человек, сменивший пароль из-за
       * подозрения, должен знать, что тот, кто уже был внутри, выброшен, —
       * иначе он продолжит считать, что беда не устранена. А тот, кто менял
       * пароль «просто так», иначе удивится, почему на телефоне разлогинило.
       */
      toast.success("Пароль изменён. Остальные ваши сеансы завершены");
    } catch (e) {
      /*
       * Причину показываем словами сервера, а не своими: он различает
       * «неверный текущий» и «новый совпадает со старым», и эти два случая
       * лечатся по-разному. Своё «не получилось» стёрло бы разницу.
       */
      setОшибка(e instanceof ApiError ? e.message : "Не получилось сменить пароль");
    } finally {
      setИдёт(false);
    }
  };

  return (
    <form
      className="prof-pass"
      onSubmit={(e) => {
        e.preventDefault();
        if (можно) void отправить();
      }}
    >
      <PasswordInput
        size="sm"
        label="Текущий пароль"
        autoComplete="current-password"
        value={текущий}
        onChange={(e) => {
          setТекущий(e.currentTarget.value);
          setОшибка(null);
        }}
      />
      <PasswordInput
        size="sm"
        label="Новый пароль"
        description={`Не короче ${МИНИМУМ} знаков`}
        autoComplete="new-password"
        value={новый}
        error={коротко ? `Коротко: нужно хотя бы ${МИНИМУМ} знаков` : undefined}
        onChange={(e) => {
          setНовый(e.currentTarget.value);
          setОшибка(null);
        }}
      />
      {ошибка && (
        <Text fz="sm" c="var(--lc-danger-text)" role="alert">
          {ошибка}
        </Text>
      )}
      <Button type="submit" size="sm" loading={идёт} disabled={!можно}>
        Сменить пароль
      </Button>
    </form>
  );
}
