import { useEffect, useState } from "react";
import { useMutation, useQuery, useQueryClient } from "@tanstack/react-query";
import { Button, NumberInput, Skeleton, Switch, Text } from "@mantine/core";
import { ApiError, http } from "@/shared/api/http";
import { toast } from "@/shared/ui/toast";

/**
 * Рабочие часы для «скорости первого ответа» (#41).
 *
 * ЗАЧЕМ ЭТО ЗДЕСЬ, А НЕ В СТАТИСТИКЕ. Настройка управленческая и меняется
 * ровно тогда же, когда меняются смены, — то есть рядом с распределением
 * диалогов, а не среди графиков. В статистике её искал бы тот, кто смотрит
 * отчёт; менять её будет тот, кто расставляет людей.
 *
 * ЧТО ЭТО ЗА ЧИСЛО. Скорость ответа считается только по времени внутри окна:
 * ночная пауза в неё не входит. Пока окно было зашито в код как 10–20, при
 * двенадцатичасовых сменах цифра льстила ночной: клиенту, написавшему в 20:05
 * и отвеченному в 10:05 утра, засчитывалось пять минут вместо четырнадцати
 * часов.
 *
 * ПОЧЕМУ ПРЕДУПРЕЖДЕНИЕ ПРО ЧАС. Отчёты после сохранения выглядят так же и
 * меняются не сразу — витрина пересчитывается раз в час. Не сказать об этом
 * значит получить человека, который решит, что настройка не сработала, и
 * поменяет её ещё раз.
 *
 * ПОЧЕМУ ПОЯС НАЗВАН ЯВНО (DIST-02). Сервер считает окно по Europe/Moscow
 * (app/services/stats.py), а всё остальное время в интерфейсе показывается по
 * поясу браузера. У заказчика смены во Владивостоке и Москве одновременно, и
 * «с 10 до 20» без пояса каждый читает по-своему: владивостокский руководитель
 * ставит окно под свою смену и получает цифры, посчитанные по чужой.
 */

interface WorkHours {
  start_hour: number;
  end_hour: number;
}

const KEY = ["settings", "work-hours"];

/** Часы по умолчанию — их же показывает сервер новой установке. */
const DEFAULT_START = 10;
const DEFAULT_END = 20;

/**
 * Круглосуточное окно — 0:00–24:00 (правка владельца 22.08).
 *
 * ПОЧЕМУ 24, А НЕ 0. Пара проверяется как «начало < конец», и при потолке 23 у
 * обоих концов максимум составлял 0–23, то есть двадцать три часа: последний
 * час суток выпадал из расчёта всегда. А 0–0 и 23–0 сервер отвергает как
 * вырожденное окно — и правильно отвергает: такое окно на боевой системе уже
 * обнуляло скорость первого ответа у ВСЕХ менеджеров. 24 значит «до конца
 * суток» и проходит проверку непустого окна честно.
 *
 * ПОЧЕМУ ОТДЕЛЬНЫМ ПЕРЕКЛЮЧАТЕЛЕМ. Круглосуточная работа — это решение, а не
 * подобранная пара чисел. Человек, которому нужно «считать всегда», не обязан
 * догадываться, что для этого надо написать 24 в поле «До».
 */
const ROUND_START = 0;
const ROUND_END = 24;

function isRoundClock(start: unknown, end: unknown): boolean {
  return start === ROUND_START && end === ROUND_END;
}

/**
 * Окно задано, если конец строго позже начала.
 *
 * Ровно то же правило, что на сервере (`app_settings.work_window_is_set`) и в
 * расчёте метрик (`stats.business_seconds_between`, SQL-функция
 * `business_seconds_between`, миграция 0029). Здесь оно нужно ДВАЖДЫ — для
 * набранного в полях и для приехавшего с сервера, — и оба раза должно значить
 * одно и то же.
 */
function windowIsSet(start: unknown, end: unknown): boolean {
  return typeof start === "number" && typeof end === "number" && start < end;
}

/**
 * «0:00–0:00» — как назвать окно в объяснении.
 *
 * Часы приходят `unknown` не по небрежности: зовут эту функцию и для ответа
 * сервера (там поле может не приехать вовсе), и для НАБРАННОГО в полях, где
 * очищенное поле — пустая строка. Приведение типом (`as WorkHours`) сделало бы
 * ровно то, от чего защищает `part`: пропустило бы пустоту как час.
 */
function describeWindow(hours: { start_hour: unknown; end_hour: unknown } | undefined): string {
  if (!hours) return "";
  if (isRoundClock(hours.start_hour, hours.end_hour)) return "круглосуточно";
  const part = (v: unknown) => (typeof v === "number" ? `${v}:00` : "—");
  return `${part(hours.start_hour)}–${part(hours.end_hour)}`;
}

/**
 * «14 часов», «2 часа», «21 час» — форму слова решает последняя пара цифр.
 *
 * Диапазон здесь 0–24, и на нём нужны все три формы: 1 и 21 дают «час», 2–4 и
 * 22–24 — «часа», 11–14 — «часов» вопреки последней цифре. Написать одну форму
 * («часов») было бы проще, но «21 часов» в рабочем интерфейсе читается как
 * недоделка, а не как экономия.
 */
function hoursWord(n: number): string {
  const lastTwo = n % 100;
  const last = n % 10;
  if (lastTwo >= 11 && lastTwo <= 14) return "часов";
  if (last === 1) return "час";
  if (last >= 2 && last <= 4) return "часа";
  return "часов";
}

/** Часы суток для полосы: клетка `h` — это час [h, h+1). */
const BAND_HOURS = Array.from({ length: 24 }, (_, h) => h);

/** Отметки шкалы под полосой; 24 стоит отдельно — это граница суток. */
const RULER_MARKS = [0, 3, 6, 9, 12, 15, 18, 21];

export function WorkHoursBlock() {
  const qc = useQueryClient();
  const q = useQuery({
    queryKey: KEY,
    queryFn: () => http.get<WorkHours>("/settings/work-hours"),
  });

  /** `""` — поле очищено руками (DIST-03), см. `onChange` ниже. */
  const [start, setStart] = useState<number | "">(DEFAULT_START);
  const [end, setEnd] = useState<number | "">(DEFAULT_END);

  /*
   * ФОРМА НАПОЛНЯЕТСЯ ГОДНЫМ ОКНОМ, А НЕ ЛЮБЫМ.
   *
   * Как и в соседнем блоке, форма наполняется из ответа один раз на загрузку и
   * не синхронизируется постоянно — иначе набранное в поле пропадало бы при
   * фоновом перезапросе. Берём только числа: ответ без поля (старая версия
   * сервера, обрезанный прокси) обнулил бы поле в пустоту, и человек сохранил
   * бы пустоту поверх рабочего значения, ничего не заметив.
   *
   * А ВОТ ВЫРОЖДЕННОЕ ОКНО В ПОЛЯ НЕ КЛАДЁТСЯ, И ЭТО ВЫХОД ИЗ ЛОВУШКИ. На
   * боевой системе сохранено 0:00–0:00. Раньше эти нули приезжали в поля как
   * есть, и получалась комната без двери: значения невалидны, красная строка
   * под ними, кнопка «Сохранить часы» погашена — а погашена она была И потому,
   * что окно негодное, И потому, что «ничего не меняли». Поправить настройку
   * через интерфейс становилось нельзя вовсе; единственным выходом оставалась
   * правка в базе руками.
   *
   * Теперь в поля подставляется осмысленное предложение (10–20, то же, что
   * видит новая установка), а рядом честно написано, что именно лежит в базе и
   * почему предложено другое. Подмена сразу делает форму «изменённой», поэтому
   * кнопка живая с первого взгляда — до всякой правки. Молча сохранять это
   * предложение нельзя: окно решает, как считается скорость первого ответа у
   * тринадцати диспетчеров, и менять его вправе человек, а не экран.
   */
  useEffect(() => {
    if (!q.data) return;
    const s = typeof q.data.start_hour === "number" ? q.data.start_hour : DEFAULT_START;
    const e = typeof q.data.end_hour === "number" ? q.data.end_hour : DEFAULT_END;
    if (windowIsSet(s, e)) {
      setStart(s);
      setEnd(e);
      return;
    }
    setStart(DEFAULT_START);
    setEnd(DEFAULT_END);
  }, [q.data]);

  const save = useMutation({
    mutationFn: (body: WorkHours) => http.patch<WorkHours>("/settings/work-hours", body),
    onSuccess: (data) => {
      qc.setQueryData(KEY, data);
      toast.success("Рабочие часы сохранены", "Отчёты пересчитаются в течение часа");
    },
    onError: (e) =>
      toast.error(
        "Не сохранилось",
        e instanceof ApiError
          ? e.message
          : "Проверьте соединение и нажмите «Сохранить часы» ещё раз",
      ),
  });

  const bothFilled = typeof start === "number" && typeof end === "number";
  /*
   * ОКНО ОБЯЗАНО БЫТЬ НЕПУСТЫМ, И ЭТО ТЕПЕРЬ ЗАПРЕТ, А НЕ ПРЕДУПРЕЖДЕНИЕ.
   *
   * Здесь стояло жёлтое «конец не позже начала — рабочих часов не останется»,
   * и кнопка «Сохранить часы» при этом работала. На боевой системе так и
   * сохранили 0:00–0:00. Дальше окно нулевой длины даёт ноль рабочих секунд
   * на любом интервале, и медиана «первый ответ в рабочее время» стала нулём
   * у ВСЕХ менеджеров — отчёт, по которому оценивают тринадцать диспетчеров,
   * показывал ноль независимо от их работы и выглядел совершенно обычно.
   *
   * Предупреждение эту беду не остановило и остановить не могло: человек,
   * который правит две цифры, читает подсказку под ними в последнюю очередь.
   * Сервер такое больше не принимает (`app_settings._assert_work_window`);
   * кнопка гаснет здесь, чтобы отказ не приходил тостом после нажатия.
   */
  const hoursValid = windowIsSet(start, end);
  const dirty =
    Boolean(q.data) && bothFilled && (start !== q.data?.start_hour || end !== q.data?.end_hour);
  /*
   * В БАЗЕ ЛЕЖИТ ОКНО, КОТОРОГО НЕ БЫВАЕТ.
   *
   * Второе полуслагаемое ловушки было в `dirty`: он сравнивает поля с ответом
   * сервера, и при сохранённом 0:00–0:00 «ничего не менялось» означало
   * погашенную кнопку ровно тогда, когда чинить надо срочно.
   *
   * ЧТО ЭТО РАСПИРАЕТ ТЕПЕРЬ. Отдельного «разрешить сохранение, раз в базе
   * мусор» здесь нет намеренно: выход даёт ПОДСТАНОВКА выше. Она кладёт в поля
   * 10–20 вместо негодного окна, и форма от этого сразу считается изменённой —
   * кнопка живая с первого взгляда. Отдельная оговорка `|| storedWindowBroken`
   * тут стояла и была мёртвой веткой: чтобы она что-то решала, подставленное
   * должно совпасть с сохранённым, а сохранённое при этом быть негодным —
   * то есть 10–20 должно быть одновременно и годным, и нет. Проверено
   * ломанием: подмена условия на прежнее `!dirty || !hoursValid` не роняла ни
   * одного теста, потому что ронять было нечего.
   *
   * Признак же нужен для объяснения под полями — там он и используется.
   */
  const storedWindowBroken =
    Boolean(q.data) && !windowIsSet(q.data?.start_hour, q.data?.end_hour);
  const canSave = hoursValid && dirty;

  /*
   * ЗАГРУЗКА И ОШИБКА ВИДНЫ (DIST-01).
   *
   * Блок не показывал ни того, ни другого: пока запрос летел — и если он падал
   * с 403, 500 или обрывом сети, — в полях стояли зашитые 10 и 20. Выглядит это
   * ТОЧНО ТАК ЖЕ, как сохранённые значения: администратор смотрит на «С 10:00
   * До 20:00», видит своё окно и уходит. А в базе там могло стоять 8–22, и вся
   * скорость ответа считалась по чужому окну — молча, без единого признака.
   *
   * Хуже того, сохранить эту выдумку было можно: `dirty` сравнивался с
   * `q.data`, но стоило тронуть любое поле — и поверх настоящих часов уезжали
   * бы подставные. Теперь до ответа сервера показываем заглушку, а на ошибке —
   * причину и кнопку повтора; полей, которые нечем наполнить, на экране нет.
   */
  if (q.isPending) {
    return (
      <div className="dist__block">
        <Skeleton height={20} width={160} radius="var(--lc-radius-sm)" />
        <Skeleton height={14} width="70%" radius="var(--lc-radius-sm)" mt="var(--lc-space-2)" />
        <Skeleton height={38} width={260} radius="var(--lc-radius-sm)" mt="var(--lc-space-3)" />
      </div>
    );
  }

  if (q.isError) {
    return (
      <div className="dist__block">
        <Text fz="var(--lc-fz-section)" fw={600} c="var(--lc-text-1)">
          Рабочие часы
        </Text>
        <Text fz="sm" c="var(--lc-danger-text)" mt="var(--lc-space-2)" role="alert">
          Рабочие часы не загрузились — показать нечего. Нажмите «Повторить»
        </Text>
        <Button
          variant="outline"
          size="xs"
          mt="var(--lc-space-3)"
          onClick={() => void q.refetch()}
        >
          Повторить
        </Button>
      </div>
    );
  }

  /*
   * Полоса закрашивается по НАБРАННОМУ, а не по сохранённому: она подпись к
   * тому, что человек видит в полях прямо сейчас. Пустое поле и вывернутая
   * пара (20–8) дают полосу без единой клетки — это и есть отказ, показанный
   * формой, а не только красной строкой ниже.
   */
  const bandStart = typeof start === "number" ? start : -1;
  const bandEnd = typeof end === "number" ? end : -1;

  /*
   * ДЛИНА ОКНА СЧИТАЕТСЯ ЗДЕСЬ, А НЕ В ГОЛОВЕ ЧИТАЮЩЕГО.
   *
   * Полоса показывает сдвиг, но длину с неё считают по клеткам — а на телефоне
   * клетка 11 px, и считать нечем (замер 05.09). При этом длина и есть предмет
   * настройки: скорость первого ответа делится на рабочие секунды.
   *
   * `null` — пока поле пустое: длины у ненабранного окна нет, и показывать
   * вместо неё ноль значило бы объявить сломанным то, что просто набирается.
   * А вот вывернутая пара (20–8) даёт честный ноль: рабочих часов в таком окне
   * действительно не остаётся.
   */
  const windowHours =
    typeof start === "number" && typeof end === "number" ? Math.max(0, end - start) : null;

  return (
    <div className="dist__block">
      <div className="dist__hhead">
        <Text fz="var(--lc-fz-section)" fw={600} c="var(--lc-text-1)">
          Рабочие часы
        </Text>
        {/* Пояс — плашкой у заголовка, а не оговоркой в конце фразы: см.
            .dist__tz в distribution.css. */}
        <span className="dist__tz">по московскому времени, UTC+3</span>
      </div>
      <Text fz="sm" c="var(--lc-text-2)" mb="var(--lc-space-3)">
        Окно, по которому считается скорость первого ответа. Время вне окна в
        расчёт не идёт: ночная пауза не портит цифру, но и не украшает её.
      </Text>

      <Switch
        size="sm"
        mb="var(--lc-space-3)"
        label="Круглосуточно"
        description="Считать скорость ответа всё время, без ночной паузы"
        checked={isRoundClock(start, end)}
        onChange={(e) => {
          if (e.currentTarget.checked) {
            setStart(ROUND_START);
            setEnd(ROUND_END);
          } else {
            setStart(DEFAULT_START);
            setEnd(DEFAULT_END);
          }
        }}
      />

      <div className="dist__hours">
        {/*
          Подписи «С» и «До» глазу хватает — они стоят рядом и читаются парой.
          Скринридер же зачитывает поле в отрыве от соседа: «С, поле ввода» не
          говорит ни о чём. Поэтому у поля есть ещё и полное имя, а видимая
          подпись остаётся короткой.
        */}
        <NumberInput
          size="xs"
          label="С"
          aria-label="Начало рабочего дня, час по Москве"
          suffix=":00"
          min={0}
          max={23}
          allowDecimal={false}
          disabled={isRoundClock(start, end)}
          value={start}
          // Пустое поле остаётся пустым (DIST-03): было `: 0`, и стёртая «10»
          // мгновенно превращалась в «0», а следующая цифра дописывалась к
          // нулю — «08» вместо «8».
          onChange={(v) => setStart(v === "" ? "" : typeof v === "number" ? v : Number(v))}
        />
        <NumberInput
          size="xs"
          label="До"
          aria-label="Конец рабочего дня, час по Москве"
          suffix=":00"
          min={0}
          // 24 — «до конца суток»; ниже потолок делал круглосуточное окно
          // недостижимым (максимум 0–23, двадцать три часа).
          max={24}
          allowDecimal={false}
          disabled={isRoundClock(start, end)}
          value={end}
          onChange={(v) => setEnd(v === "" ? "" : typeof v === "number" ? v : Number(v))}
        />
      </div>

      {/*
        Длина окна — единственный показатель этого экрана, и набран он как
        показатель: число крупно, подпись под ним мелко. Читалке с экрана он
        нужен ТЕМ БОЛЕЕ (полоса ниже от неё скрыта), поэтому строка обычная, а
        не декоративная.
      */}
      <div className="dist__len">
        <span className="dist__len-num" data-empty={windowHours === 0 ? "" : undefined}>
          {windowHours ?? "—"}
        </span>
        <span className="dist__len-cap">
          {windowHours === null ? "часов в сутках" : `${hoursWord(windowHours)} в сутках`}
        </span>
      </div>

      {/*
        Полоса СКРЫТА ОТ ЧИТАЛКИ С ЭКРАНА намеренно: она ничего не добавляет к
        двум полям выше, а озвученные подряд двадцать четыре безымянные клетки
        — это шум вместо настройки. Глазу же она говорит то, чего числа не
        говорят: длину смены и её сдвиг внутри суток.
      */}
      <div className="dist__shape" aria-hidden="true">
        <div className="dist__band">
          {BAND_HOURS.map((h) => (
            <span
              key={h}
              className="dist__cell"
              data-on={h >= bandStart && h < bandEnd ? "" : undefined}
              data-tick={h % 3 === 2 ? "" : undefined}
            />
          ))}
        </div>
        <div className="dist__ruler">
          {RULER_MARKS.map((h) => (
            <span key={h}>{h}</span>
          ))}
          <span className="dist__ruler-end">24</span>
        </div>
      </div>

      {/*
        ПОЧЕМУ В ПОЛЯХ НЕ ТО, ЧТО В БАЗЕ, — СКАЗАНО ВСЛУХ И С ЧИСЛАМИ.
        Молча подставить 10–20 значит соврать: человек уйдёт уверенным, что
        окно у него такое, а отчёты продолжат считаться по вырожденному до
        первого нажатия «Сохранить часы». Поэтому здесь и старое значение, и
        предложенное, и прямое указание, что делать.
      */}
      {storedWindowBroken && (
        /*
         * ⚠ ПРЕДУПРЕЖДЕНИЕ ГОВОРИЛО НЕПРАВДУ ПРО РАСЧЁТ, И ЭТО ВИДНО РЯДОМ.
         * Стояло: «скорость первого ответа по нему считаться не может», — а
         * статистика её показывает (проверка боя 14 августа: 3 м 1 с при
         * сохранённом 0:00–0:00). Сервер при вырожденном окне НЕ отказывается
         * считать, а считает по календарю (`stats.py`, запасной вариант): ноль
         * означал бы «ответили мгновенно», и это была бы ложь похуже.
         *
         * Так что беда не в том, что цифры нет, а в том, что она равна обычной
         * скорости ответа — и ночное ожидание попадает в расчёт. Об этом и
         * говорим.
         */
        <Text fz="xs" c="var(--lc-warning-text)" mt="var(--lc-space-2)" role="alert">
          Сохранённое окно {describeWindow(q.data)} нерабочее: в нём ноль часов,
          поэтому скорость первого ответа считается по календарю — колонка
          «в рабочие часы» просто повторяет обычную, и ночное ожидание входит в
          расчёт. В полях — предложение {DEFAULT_START}:00–{DEFAULT_END}:00;
          поправьте, если смены другие, и нажмите «Сохранить часы».
        </Text>
      )}

      {!bothFilled && (
        <Text fz="xs" c="var(--lc-warning-text)" mt="var(--lc-space-2)" role="status">
          Впишите оба часа — иначе сохранять нечего.
        </Text>
      )}

      {bothFilled && !hoursValid && (
        <Text fz="xs" c="var(--lc-danger-text)" mt="var(--lc-space-2)" role="alert">
          Конец должен быть позже начала — иначе рабочих часов не останется
          вовсе, и скорость первого ответа обнулится у всех. Сохранить такое
          окно нельзя.
        </Text>
      )}

      <div className="dist__actions">
        <Button
          size="xs"
          disabled={!canSave}
          loading={save.isPending}
          onClick={() => {
            // Проверка типов здесь повторяет `hoursValid` не по небрежности:
            // компилятор не переносит сужение через вызов функции, а отправка
            // пустой строки в поле часа — ровно та ошибка, от которой пустое
            // поле и защищают. Пусть лучше условие стоит дважды, чем `as`.
            if (!hoursValid || typeof start !== "number" || typeof end !== "number") return;
            save.mutate({ start_hour: start, end_hour: end });
          }}
        >
          {/*
            «Сохранить ЧАСЫ», а не просто «Сохранить». На экране теперь две
            кнопки сохранения — у распределения и здесь, — и одинаковые надписи
            означают выбор вслепую: человек жмёт ближайшую и не понимает,
            почему изменение не применилось. Скринридер зачитал бы их и вовсе
            неотличимо.
          */}
          Сохранить часы
        </Button>
        {dirty && (
          /*
           * ⚠ СТРОКА ВРАЛА ПРО АВТОРСТВО. «Есть несохранённые изменения» на
           * первом же заходе — а человек ничего не менял: поля разошлись с
           * базой из-за ПОДСТАНОВКИ 10–20 вместо вырожденного окна. Он ищет,
           * что натворил, и не находит.
           *
           * Поэтому текст называет факт, а не поступок: поля и база разошлись.
           *
           * ⚠ А ТЕПЕРЬ ЕЩЁ И ПРЕДМЕТ, ЧИСЛАМИ. Один факт «что-то не сохранено»
           * не отвечает на вопрос, ЧТО именно уедет по кнопке. Человек, который
           * отвлёкся на смену и вернулся к экрану через час, читал прежнюю
           * строку и шёл сверять поля с памятью. Пара «8:00–22:00 вместо
           * 10:00–20:00» отвечает на это сразу и не требует помнить, что было.
           */
          <Text fz="xs" c="var(--lc-warning-text)">
            <span>
              {storedWindowBroken
                ? "Поля отличаются от сохранённого"
                : "Есть несохранённые изменения"}
            </span>
            <span className="dist__num">
              : окно {describeWindow({ start_hour: start, end_hour: end })} вместо{" "}
              {describeWindow(q.data)}
            </span>
          </Text>
        )}
      </div>

      <Text fz="xs" c="var(--lc-text-3)" mt="var(--lc-space-3)">
        Отчёты пересчитываются раз в час — новые цифры появятся не мгновенно.
      </Text>
    </div>
  );
}
