import { Button, Group, Text } from "@mantine/core";
import { plural } from "@/shared/lib/plural";

/**
 * Подвал таблицы настроек: счётчик и, ЕСЛИ СТРАНИЦА НЕ ОДНА, кнопки «Назад» и
 * «Вперёд».
 *
 * ЗАЧЕМ ОТДЕЛЬНЫЙ КОМПОНЕНТ И ПОЧЕМУ КНОПКИ НЕ ВСЕГДА. Раньше подвал печатался
 * всегда, когда строк больше нуля: у команды из тринадцати человек внизу висело
 * «1–13 из 13» и две заведомо мёртвые кнопки, обе с `disabled` (страница —
 * пятьдесят строк, и второй никогда не будет). Мёртвый орган управления
 * читается как поломка: «почему кнопки не нажимаются». То же самое стояло в
 * журнале аудита — отсюда общий компонент, а не две одинаковые правки, которые
 * потом разъедутся.
 *
 * ВТОРАЯ ПОЛОВИНА БЕДЫ БЫЛА ОБРАТНОЙ. Подвал жил ВНУТРИ ветки с непустым
 * списком, поэтому опустевшая вторая страница (отключили последних сотрудников
 * при снятой галочке «показывать отключённых») оставалась без единой кнопки:
 * «Назад» нет, вернуться некуда, спасает только перезагрузка. Поэтому подвал
 * рисуется и при пустой выдаче — но только если человек не на первой странице:
 * там о пустоте уже сказало пустое состояние, и «0 сотрудников» под ним лишнее.
 *
 * СЧЁТ СКЛОНЯЕТСЯ. Подпись собиралась как `${noun}: ${total}` с существительным
 * в родительном множественного — «Сотрудников: 1», «Записей: 1». На стенде это
 * видно с первого взгляда: в команде один человек, и подвал пишет
 * «Сотрудников: 1». Форма выбирается по числу тем же хелпером, что и во всём
 * остальном продукте (shared/lib/plural.ts), а не отдельным правилом здесь.
 */
export function Pager({
  offset,
  shown,
  total,
  pageSize,
  noun,
  onOffset,
}: {
  offset: number;
  /** Сколько строк на текущей странице. */
  shown: number;
  total: number;
  pageSize: number;
  /** Три формы существительного: «сотрудник / сотрудника / сотрудников». */
  noun: readonly [one: string, few: string, many: string];
  onOffset(next: number): void;
}) {
  // Первая страница и она же единственная — показывать нечего.
  if (shown === 0 && offset === 0) return null;

  const hasPages = total > pageSize || offset > 0;

  const label =
    shown === 0
      ? "На этой странице пусто"
      : hasPages
        ? `${offset + 1}–${offset + shown} из ${total}`
        : `${total} ${plural(total, noun[0], noun[1], noun[2])}`;

  return (
    <Group justify="space-between" mt="var(--lc-space-3)">
      {/* Цифры моноширинные: «1–50 из 120» и «51–100 из 120» при листании
          иначе меняют ширину подписи и дёргают её на месте. */}
      <Text fz="xs" c="var(--lc-text-3)" className="team-pager__count">
        {label}
      </Text>
      {hasPages && (
        <Group gap="var(--lc-space-2)">
          <Button
            size="xs"
            variant="default"
            disabled={offset === 0}
            onClick={() => onOffset(Math.max(0, offset - pageSize))}
          >
            Назад
          </Button>
          <Button
            size="xs"
            variant="default"
            disabled={offset + shown >= total}
            onClick={() => onOffset(offset + pageSize)}
          >
            Вперёд
          </Button>
        </Group>
      )}
    </Group>
  );
}
