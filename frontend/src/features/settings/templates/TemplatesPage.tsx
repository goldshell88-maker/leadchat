import { PageHeader } from "@/shared/ui/PageHeader";
import { usePermissions } from "@/shared/auth/usePermissions";
import { TemplatesManager } from "@/features/templates/TemplatesManager";

/**
 * `/settings/templates` (11 §3.2) — общие быстрые ответы (A, H по праву
 * `templates:shared`) и вкладка «Мои» с личными того же пользователя.
 */
export function TemplatesPage() {
  const { can } = usePermissions();
  /*
   * ⚠ ПОДПИСЬ ОБЯЗАНА СОВПАДАТЬ С ТЕМ, ЧТО ЧЕЛОВЕК ВИДИТ. Диспетчеру раздел
   * показывает только его собственные заготовки (`personalOnly`), и обещать
   * ему «общие видит вся команда» значит рассказывать про экран, которого у
   * него нет.
   */
  const общие = can("templates:shared");
  return (
    <div className="settings-section">
      {/* Про переменные здесь больше не пишем: их список и так стоит в самом
          редакторе шаблона, где им и место — рядом с полем, куда их вставляют.
          Описание страницы отвечает на другой вопрос: что это за раздел. */}
      {/* Словарь (10 §7.2): «шаблон» разрешён только как ИМЯ раздела, а сама
          вещь называется быстрым ответом. Здесь было «Общие шаблоны видит вся
          команда» — то есть в подзаголовке одно слово, в кнопке рядом другое. */}
      <PageHeader
        title="Быстрые ответы"
        description={
          общие
            ? "Общие видит вся команда, личные — только вы. В диалоге вставляются по «/»"
            : "Эти быстрые ответы видите только вы. В диалоге вставляются по «/» или кнопкой с молнией над полем ввода"
        }
      />
      <TemplatesManager personalOnly={!общие} />
    </div>
  );
}
