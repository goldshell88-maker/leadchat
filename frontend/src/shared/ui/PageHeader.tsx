import type { ReactNode } from "react";
import { Text, Title } from "@mantine/core";
import "./page-header.css";

/**
 * Шапка страницы: заголовок, описание одной строкой, слот действий справа.
 *
 * ЗАЧЕМ. Шесть страниц настроек называли себя по-разному: `order` 1 или 2,
 * кегль 20, 18 или 16, у одной жирность 600, у остальных нет, у одной
 * «Настройки · Аккаунты Авито», у соседней просто «Боты». Переходя между
 * разделами, человек видел, как заголовок прыгает в размере и весе, — и это
 * читается не как разные страницы, а как разное качество сборки.
 *
 * Иерархия заголовков тоже была нарушена: `order={2}` без единицы выше — для
 * скринридера это «подраздел неизвестно чего».
 *
 * КАНОН: `h1`, кегль из токена `--lc-fz-page`, вес 600, описание — одна
 * строка без точки в конце. Точка в конце короткой подписи заставляет читать
 * её как предложение, а это подпись.
 *
 * ЧИСЛА ЗДЕСЬ БОЛЬШЕ НЕТ, И ЭТО ПОЧИНКА. Комментарий обещал «20px», а правило
 * читало `--lc-fz-page` — то есть 28. Разошлись они молча и надолго: разбор
 * 12 августа померил на живом экране 28 и был прав, а следующий читатель кода
 * поверил бы комментарию. Одно значение — одно место, и это место `lc-vars`.
 *
 * ПОЛЬЗУЮТСЯ ЭТИМ ВСЕ РАЗДЕЛЫ. 12 августа сюда переведены «Статистика»
 * (называла себя 20-м кеглем), «Разбор диалогов» и «Что нового» (24-м): три
 * размера на одно и то же место в иерархии, и у разбора вдобавок своя копия
 * этой самой раскладки под именем `.dt__head`.
 *
 * Исключение из канона одно и осознанное: редактор бота, где заголовок —
 * редактируемое поле, а не текст.
 */
export function PageHeader({
  title,
  description,
  actions,
}: {
  title: string;
  /** Одна строка: чем страница занимается. Без точки в конце. */
  description?: string;
  /** Правый слот: кнопки страницы. */
  actions?: ReactNode;
}) {
  return (
    <header className="page-header">
      <div className="page-header__text">
        <Title order={1} className="page-header__title">
          {title}
        </Title>
        {description ? (
          <Text component="p" className="page-header__description">
            {description}
          </Text>
        ) : null}
      </div>
      {actions ? <div className="page-header__actions">{actions}</div> : null}
    </header>
  );
}
