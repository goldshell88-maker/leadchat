/**
 * Одно место, где ошибка превращается в человеческое сообщение (18.08).
 *
 * ЗАЧЕМ. По экрану было рассыпано полсотни заготовок «Попробуйте ещё раз» —
 * они показывались на ЛЮБУЮ ошибку и врали о причине: 500 читался как «нет
 * прав», истёкшая сессия — как «сервер занят». Боевой случай: удаление
 * заметки падало пятисоткой, а человек читал «удалить можно только свою
 * заметку» и искал виноватого в себе.
 *
 * ЧТО ПОКАЗЫВАЕМ ТЕПЕРЬ, ТРЕМЯ ЧАСТЯМИ:
 *   1. ГДЕ — короткое имя действия, которое не удалось («Удаление заметки»);
 *   2. ЧТО — слова сервера, как есть: он единственный знает причину;
 *   3. КОД обращения (`request_id`) — по нему строка находится в журнале
 *      сервера за секунду. Без него разбор начинается с «а когда это было?».
 *
 * Сеть отдельно: если запрос не доехал вовсе, сервер ничего не сказал, и
 * честный ответ — «нет связи с сервером», а не выдуманная причина.
 */
import { ApiError } from "@/shared/api/http";

/** Человеческие названия кодов, которые сервер отдаёт машинными словами. */
const CODE_LABELS: Record<string, string> = {
  forbidden: "нет прав на это действие",
  not_found: "объект не найден — возможно, его уже удалили",
  conflict: "состояние изменилось: обновите страницу",
  already_claimed: "диалог уже взял коллега",
  validation_error: "сервер не принял значение",
  unauthorized: "сессия истекла — войдите заново",
  rate_limited: "слишком часто: подождите несколько секунд",
  internal_error: "внутренняя ошибка сервера",
};

export interface ErrorToastInput {
  /** Что не получилось, словами человека: «Удаление заметки», «Смена статуса». */
  where: string;
  /** Ошибка как есть — ApiError, Error или что угодно. */
  error: unknown;
  /** Подсказка, если сервер промолчал (сеть, неизвестная ошибка). */
  fallback?: string;
}

export interface ErrorToastOut {
  title: string;
  message: string;
  color: "red";
  /** Долгие тосты закрываются рукой: код обращения надо успеть переписать. */
  autoClose: false;
}

export function describeError({ where, error, fallback }: ErrorToastInput): ErrorToastOut {
  if (error instanceof ApiError) {
    const причина =
      error.message?.trim() || CODE_LABELS[error.code] || `ошибка сервера (${error.status})`;
    const код = error.requestId ? ` · код ${error.requestId}` : "";
    return { title: `Не получилось: ${where}`, message: `${причина}${код}`, color: "red", autoClose: false };
  }
  // Сеть/оффлайн: запрос не доехал, сервер причины не называл — не выдумываем.
  const сеть = typeof navigator !== "undefined" && navigator.onLine === false;
  const message = сеть
    ? "нет интернета — проверьте связь, изменения не сохранены"
    : fallback || "нет связи с сервером — попробуйте ещё раз";
  return { title: `Не получилось: ${where}`, message, color: "red", autoClose: false };
}
