import { useEffect, useState } from "react";
import { Button, Text } from "@mantine/core";
import { Link } from "react-router-dom";
import { usePermissions } from "@/shared/auth/usePermissions";
import { useSessionStore } from "@/shared/stores/sessionStore";
import { IconBell } from "./Icon";
import "./ПредложитьУведомления.css";

/**
 * Полоса «включите уведомления» в рабочем месте.
 *
 * ЗАЧЕМ ОНА ВООБЩЕ ПОЯВИЛАСЬ. Разрешение на системные уведомления спрашивает
 * ровно одно место — переключатель в /settings/profile. Пока человек туда не
 * зашёл, `Notification.permission` остаётся `default`, и весь код показа —
 * рабочий, проверенный, с честным заслоном по фокусу — не показывает ничего.
 * Жалоба «уведомления не работают» у большинства людей означает именно это: не
 * поломку показа, а невыданное разрешение. В настройки профиля диспетчер за
 * смену не заходит ни разу: у него список, лента и CRM в соседнем окне.
 *
 * ЦЕНА МОЛЧАНИЯ (замер боя 05.09): 1357 новых диалогов и 625 возвратов в
 * сутки, каналы открыты 30–33 операторам каждый, за неделю 11 739 взятий из
 * очереди. Каждое такое взятие — гонка, и выигрывает её тот, кто раньше узнал.
 *
 * ⚠ РАЗРЕШЕНИЕ СПРАШИВАЕТСЯ ТОЛЬКО ИЗ ЖЕСТА ЧЕЛОВЕКА, И ВТОРОЙ ПОПЫТКИ НЕ
 * БУДЕТ. Браузер требует нажатия и запоминает отказ навсегда — снять его можно
 * только в настройках сайта. Поэтому здесь именно полоса с кнопкой, а не вызов
 * `requestPermission()` при входе: выскочивший сам по себе запрос закрывают не
 * глядя, и это «не глядя» стоит человеку уведомлений до конца работы в этом
 * браузере. По той же причине `requestPermission()` стоит первым действием
 * обработчика: любое ожидание перед ним съедает признак пользовательского
 * жеста, и Chromium отклоняет запрос молча.
 *
 * КОМУ ПОКАЗЫВАЕМ. Только тем, у кого есть `messages:send`, — то есть тем, кто
 * отвечает клиенту. Руководителю и наблюдателю уведомление о новом диалоге
 * пользы не несёт, а полоса в рабочем месте у них была бы просто шумом.
 *
 * ЗАКРЫВАЕТСЯ НАСОВСЕМ И У КАЖДОГО СВОЙ. Отказ лежит в браузере под ключом с
 * id человека: на общем компьютере смены закрытая полоса одного диспетчера не
 * должна прятать её от следующего, который сядет за ту же машину и тот же
 * профиль браузера. Сервер про этот отказ не знает намеренно — заводить ради
 * галочки колонку, ручку и миграцию дороже, чем показать полосу ещё раз тому,
 * кто пересел за другой компьютер (так же решено для «Что нового»,
 * features/updates/seen.ts).
 */

type Разрешение = NotificationPermission | "unsupported";

function текущееРазрешение(): Разрешение {
  if (typeof Notification === "undefined") return "unsupported";
  return Notification.permission;
}

function ключОтказа(userId: string): string {
  return `lc-notify-nudge-off:${userId}`;
}

function отказывался(userId: string | undefined): boolean {
  if (!userId) return false;
  try {
    return localStorage.getItem(ключОтказа(userId)) === "1";
  } catch {
    // Приватное окно без хранилища: считаем, что не отказывался. Показать
    // полосу лишний раз безобиднее, чем спрятать её у того, кто её ждёт.
    return false;
  }
}

/*
 * ⚠ ИМЯ КОМПОНЕНТА ЛАТИНИЦЕЙ, ХОТЯ ФАЙЛ НАЗВАН ПО-РУССКИ, — ЭТО НЕ
 * НЕПОСЛЕДОВАТЕЛЬНОСТЬ. `react-hooks/rules-of-hooks` узнаёт компонент по
 * `/^[A-Z]/`, то есть по ЛАТИНСКОЙ прописной: с русским именем правило считает
 * функцию обычной и запрещает в ней хуки — семь ошибок линтера на пустом месте.
 * Отключать правило ради имени нельзя: оно ловит настоящие поломки порядка
 * хуков. В проекте так уже сделано — `useAutoAway` в `автоОтошёл.ts`,
 * `useDialogPin` в `выборДиалога.ts`: русское имя у файла, латинское у того,
 * что разбирает инструмент.
 */
export function NotifyNudge() {
  const { can } = usePermissions();
  const userId = useSessionStore((s) => s.user?.id);
  const [разрешение, setРазрешение] = useState<Разрешение>(текущееРазрешение);
  const [спрашиваем, setСпрашиваем] = useState(false);
  // Читаем отказ сразу при первом рендере, а не в эффекте: эффект отработал бы
  // после первого кадра, и человек, закрывший полосу вчера, каждое утро видел
  // бы её мигание при открытии рабочего места.
  const [скрыт, setСкрыт] = useState(() => отказывался(useSessionStore.getState().user?.id));

  // Сменился человек за тем же браузером — отказ надо перечитать под его id.
  useEffect(() => {
    setСкрыт(отказывался(userId));
  }, [userId]);

  // Разрешение могли выдать в /settings/profile или снять в настройках сайта,
  // не перезагружая вкладку. Рабочее место при этом остаётся смонтированным,
  // и без пересмотра полоса висела бы поверх уже выданного разрешения.
  useEffect(() => {
    const сверить = () => setРазрешение(текущееРазрешение());
    document.addEventListener("visibilitychange", сверить);
    return () => document.removeEventListener("visibilitychange", сверить);
  }, []);

  const включить = async () => {
    if (typeof Notification === "undefined") return;
    setСпрашиваем(true);
    try {
      setРазрешение(await Notification.requestPermission());
    } catch {
      // Приватное окно Firefox и старые Safari бросают вместо отказа.
      setРазрешение(текущееРазрешение());
    } finally {
      setСпрашиваем(false);
    }
  };

  const большеНеПредлагать = () => {
    setСкрыт(true);
    if (!userId) return;
    try {
      localStorage.setItem(ключОтказа(userId), "1");
    } catch {
      // Без хранилища просто не запомним — полоса вернётся после перезагрузки.
    }
  };

  /*
   * ⚠ ЗАПРЕТ ТОЖЕ ПОКАЗЫВАЕМ, И ЭТО ПРАВКА ПО ЖИВОЙ ЖАЛОБЕ (07.09, «уведомления
   * в Chrome не работают»).
   *
   * Здесь стояло `разрешение !== "default"` — то есть при ЗАПРЕТЕ полоса
   * исчезала совсем. Довод был верный ровно наполовину: кнопка «Включить» при
   * запрете и правда обман, браузер второй раз не спросит. Но из «кнопка не
   * поможет» не следует «человеку не о чем знать», а вышло именно это: у того,
   * кто однажды нажал «Блокировать» — или чей Chrome отклонил запрос САМ, в
   * режиме тихих запросов, даже не показав его, — на экране не остаётся ни
   * объяснения, ни следа. Уведомлений нет, причина невидима, и человек
   * говорит «не работает приложение».
   *
   * Поэтому при запрете полоса остаётся, но вместо кнопки — ссылка на
   * /settings/profile, где лежит разбор по шагам. Второй копии инструкции
   * здесь нет намеренно: два текста про одно разъедутся на первой же правке,
   * а Chrome свои настройки уже один раз переставлял (замок -> ползунки).
   */
  const запрещено = разрешение === "denied";
  if ((разрешение !== "default" && !запрещено) || скрыт || !can("messages:send")) return null;

  return (
    <div
      className="lc-notify-nudge"
      data-denied={запрещено || undefined}
      role="status"
      aria-label="Уведомления браузера не включены"
    >
      <IconBell className="lc-notify-nudge__icon" size={20} />
      <div className="lc-notify-nudge__text">
        <Text fz="sm" c="var(--lc-text-1)">
          {запрещено
            ? "Браузер запретил уведомления — о новом клиенте вы не узнаете"
            : "Не пропускайте клиента, пока смотрите в CRM"}
        </Text>
        <Text fz="xs" c="var(--lc-text-3)">
          {запрещено
            ? "Снять запрет можно только в настройках самого браузера — отсюда он второй раз не спросит."
            : "Браузер подскажет о новом диалоге, когда окно LeadChat закрыто другим. Пока смотрите в LeadChat — ничего не всплывает."}
        </Text>
      </div>
      {запрещено ? (
        // Ссылка, а не кнопка: кнопка обещала бы действие, которого браузер не
        // даст. Разбор по шагам — там же, где он был всегда, и в одном экземпляре.
        <Button size="xs" variant="light" component={Link} to="/settings/profile">
          Как включить
        </Button>
      ) : (
        <Button size="xs" loading={спрашиваем} onClick={() => void включить()}>
          Включить уведомления
        </Button>
      )}
      <Button size="xs" variant="subtle" color="gray" onClick={большеНеПредлагать}>
        Больше не предлагать
      </Button>
    </div>
  );
}
