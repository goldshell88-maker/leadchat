/**
 * Схлопывание перезапросов списка диалогов (жалобы владельца 22.08).
 *
 * ЗАЧЕМ. Обработчики событий звали `invalidateQueries` по спискам на КАЖДОЕ
 * изменение: смену статуса, принятие диалога из очереди, возврат в очередь,
 * передачу. Строка к этому моменту УЖЕ поправлена локально
 * (`patchRowEverywhere`), и перезапрос нужен ровно для одного: диалог мог
 * переехать между вкладками.
 *
 * На одном событии это незаметно. На пачке — нет: пятьдесят закрытий давали
 * пятьдесят PATCH плюс пятьдесят полных перезапросов тяжёлого списка. А в
 * смену из тринадцати диспетчеров кадры `inbox:claimed` приходят КАЖДОМУ на
 * каждое чужое нажатие — то есть список перезапрашивался у всех и всё время.
 * Отсюда разом три жалобы: «зависания страницы», «диалог визуально пропадает»
 * и три тоста «Статус не изменился» (часть запросов упиралась в лимит nginx —
 * 30 в секунду на адрес — и возвращалась 429).
 *
 * ПОЧЕМУ ХВОСТ, А НЕ ГОЛОВА. Перезапрос по первому событию пачки показал бы
 * список в середине правок и всё равно потребовал бы второго в конце. Нужен
 * ровно последний — он один отражает итог.
 *
 * ПОЧЕМУ ЗАДЕРЖКА ЗАМЕТНОЙ НЕ БУДЕТ. Строки правятся сразу, до всякого
 * перезапроса: человек видит изменение мгновенно. Полсекунды ждёт только
 * сверка с сервером, и ждёт она в фоне.
 *
 * ⚠ ЭФФЕКТ ЖИВЁТ ЗДЕСЬ, А НЕ ПРИХОДИТ КОЛБЭКОМ. Таймер один на модуль, и
 * колбэком его можно было бы незаметно подменить: следующий вызов отменяет
 * предыдущий вместе с его работой. Пока все звавшие делали одно и то же, это
 * сходило с рук ровно до первого, кто позвал бы с другим намерением.
 */

import { queryClient } from "@/app/queryClient";
import { CONVERSATIONS_LIST_KEY, qk } from "@/shared/api/queryKeys";

/**
 * Хвост пачки.
 *
 * ⚠ БЫЛО ПОЛСЕКУНДЫ, СТАЛО ПЯТАЯ ЧАСТЬ (просьба владельца 04.09: «можешь ещё
 * сильнее ускорить, чтобы не было задержек вообще»). Прежний довод — «дольше
 * человек уже замечает» — верен только сверху: снизу порог никто не проверял,
 * а он и есть задержка на КАЖДОЕ чужое событие.
 *
 * Двести миллисекунд, а не ноль: схлопывание должно остаться схлопыванием.
 * Пачка кадров об одном диалоге (сообщение, отметка, смена статуса) приходит
 * за десятки миллисекунд и по-прежнему склеивается в один перезапрос.
 *
 * Цена измерена, а не прикинута: nginx пускает 30 запросов в секунду с адреса
 * (1800 в минуту), офис за одним адресом тратит сейчас около 17 в минуту на
 * восьмерых. Даже троекратный рост — три процента бюджета.
 */
export const LIST_REFETCH_DELAY_MS = 200;

/**
 * ⚠ ПОТОЛОК ОЖИДАНИЯ. БЕЗ НЕГО СХЛОПЫВАНИЕ ГОЛОДАЕТ (28.08, жалоба оператора).
 *
 * Таймер сбрасывался КАЖДЫМ вызовом, а кадр `inbox:claimed` приходит всем
 * тринадцати диспетчерам на каждое чужое «Принять». В живую смену события идут
 * чаще, чем раз в полсекунды, — и перезапрос не наступал ВООБЩЕ, пока поток не
 * стихнет. Жалоба дословно: «взял 4 диалога, по статистике в работе 14, а вижу
 * 10; подгрузились спустя 3 минуты». Три минуты — это не задержка списка, это
 * время до первой паузы в потоке.
 *
 * Три секунды выбраны так: перезапросов не больше двадцати в минуту на вкладку
 * (лимит nginx — тридцать запросов в секунду на адрес, то есть запас
 * стократный), а человек не ждёт дольше трёх секунд ни при какой нагрузке.
 */
export const LIST_REFETCH_MAX_WAIT_MS = 3_000;

let таймер: ReturnType<typeof setTimeout> | null = null;
/** Когда началась текущая пачка — от неё считается потолок. */
let началоПачки = 0;

/**
 * Окно для ОДНИХ ЧИСЕЛ, без списка (аудит 06.09).
 *
 * Числа над «Моими» с 06.09 двигаются дельтой из кадра (`tabCounts`), и
 * сервер про них спрашивают только там, где дельту честно не вывести: строка
 * старого кэша без `waiting_since`. Такие кадры идут пачкой (утренний наплыв,
 * выгрузка истории), и один запрос на окно достаточен: он спрашивает ИТОГ, а
 * не каждый шаг. Три секунды — тот же потолок, что у списка: дольше человек
 * ждать не должен, чаще — снова тот поток, который дал 344 ответа 429 в сутки.
 */
export const COUNTS_REFETCH_WINDOW_MS = 3_000;
let таймерЧисел: ReturnType<typeof setTimeout> | null = null;

/**
 * Попросить перезапрос списков диалогов. Подряд идущие просьбы схлопываются.
 *
 * ⚠ КЛЮЧ — СПИСКИ, А НЕ КОРЕНЬ `["conversations"]`. Корень накрывает и
 * `["conversations","detail",id]`, то есть каждый такой вызов вдобавок
 * перезапрашивал ОТКРЫТУЮ деталь — второй запрос на ровном месте и лишняя
 * перерисовка шапки. Деталь во всех этих местах уже поправлена в кэше
 * (`setQueryData` рядом с вызовом), спрашивать сервер о ней незачем.
 *
 * `refetchType: "active"` — не жадность, а условие бесшовности: react-query
 * держит прежние данные, пока идёт перезапрос, поэтому список не мигает
 * пустотой (скелет `ChatListPane` висит на `isPending`, а он на перезапросе
 * не поднимается). Неактивные ключи просто помечаются протухшими.
 */
/**
 * Числа над вкладкой и строки списка едут ВМЕСТЕ (жалоба владельца 03.09:
 * «очень долго обновляется вкладка/поля/индикаторы»).
 *
 * ⚠ ЧТО БЫЛО. У счётчика был СВОЙ схлопыватель с окном в пятнадцать секунд
 * (`освежитьСчёт`), а у списка — этот, с полусекундой и потолком в три. Число
 * и строки, из которых оно сложено, обновлялись по разным часам: список
 * перестраивался за полсекунды, а «Мои 49» держались старыми ещё четырнадцать.
 * Хуже того, СВОЁ нажатие счётчика не касалось вовсе — `refetchListsNow`
 * сбрасывал только ключ списка, а счётчик живёт под соседним ключом.
 *
 * ⚠ ПОЧЕМУ ОКНО В 15 СЕКУНД ВООБЩЕ ПОЯВИЛОСЬ И ПОЧЕМУ ЕГО МОЖНО СНЯТЬ. Его
 * поставили 02.09 по замеру: ручку счётчика звали 82,6 раза в минуту. Замер
 * 03.09 показывает 9,1 раза в минуту на восьмерых работающих — в девять раз
 * меньше. Сама ручка стоит один запрос в частичный индекс (0,7 мс на боевой
 * базе), а nginx пускает тридцать запросов в секунду с адреса при нынешних
 * двух. Дорого было не считать, а спрашивать часто; теперь и это не дорого.
 *
 * Ключи сбрасываются одним таймером, поэтому число физически не может быть
 * старше строк.
 */
function сбросить(): void {
  // Числа едут вместе со списком — отдельное окно чисел больше не нужно.
  if (таймерЧисел !== null) {
    clearTimeout(таймерЧисел);
    таймерЧисел = null;
  }
  void queryClient.invalidateQueries({
    queryKey: CONVERSATIONS_LIST_KEY,
    refetchType: "active",
  });
  void queryClient.invalidateQueries({ queryKey: qk.conversations.counts });
}

/**
 * Попросить перезапрос ОДНИХ чисел — один на окно `COUNTS_REFETCH_WINDOW_MS`.
 *
 * Повторные просьбы внутри окна ничего не двигают: хвост окна спросит итог.
 * Пока ждёт перезапрос списка, просьба тоже лишняя — он спросит и числа.
 */
export function scheduleCountsRefetch(): void {
  if (таймер !== null || таймерЧисел !== null) return;
  таймерЧисел = setTimeout(() => {
    таймерЧисел = null;
    void queryClient.invalidateQueries({ queryKey: qk.conversations.counts });
  }, COUNTS_REFETCH_WINDOW_MS);
}

/**
 * Как часто числа сверяются с сервером, даже когда дельта посчиталась.
 *
 * ⚠ ЗАЧЕМ СВЕРКА, ЕСЛИ ДЕЛЬТА ЧЕСТНА (жалоба владельца 07.09: «ответил
 * клиенту, а диалог так и висит в неотвеченных»).
 *
 * До 06.09 число сверялось с сервером после КАЖДОГО кадра — дорого (54–57 %
 * трафика), но самоисправлялось за секунды. Теперь оно двигается дельтой по
 * паре строк ДО и ПОСЛЕ патча, и у дельты есть слепое пятно: строку берут из
 * кэша, а вариантов кэша столько, сколько наборов фильтров человек открывал.
 * Варианты грузятся с сервера в разное время и между собой РАСХОДЯТСЯ; ошибись
 * дельта хоть раз — число останется неверным до смены статуса, хозяина или
 * тихой сверки, то есть до двух минут, а в худшем случае и дольше.
 *
 * Ошибку дельты нельзя доказать отсутствующей: слепых пятен у неё столько,
 * сколько путей приводит строку в кэш. Поэтому здесь стоит не заплатка под
 * найденный случай, а потолок расхождения: раз в полминуты число спрашивают у
 * сервера независимо от того, сошлась дельта или нет. Мгновенная реакция
 * остаётся у дельты, правда — за сервером.
 *
 * Цена посчитана: 13 человек × 2 запроса в минуту = 26 в минуту против 250–356
 * до 06.09. Это возврат к верности числа, а не к прежнему потоку.
 */
export const COUNTS_RECONCILE_MS = 30_000;
let таймерСверки: ReturnType<typeof setTimeout> | null = null;

/** Поставить редкую сверку чисел с сервером. Повторные просьбы схлопываются. */
export function scheduleCountsReconcile(): void {
  if (таймерСверки !== null) return;
  таймерСверки = setTimeout(() => {
    таймерСверки = null;
    void queryClient.invalidateQueries({ queryKey: qk.conversations.counts });
  }, COUNTS_RECONCILE_MS);
}

export function scheduleListRefetch(): void {
  const сейчас = Date.now();
  if (таймер === null) началоПачки = сейчас;
  else clearTimeout(таймер);
  // Обычно — полсекунды после ПОСЛЕДНЕГО события. Но не позже, чем через
  // `LIST_REFETCH_MAX_WAIT_MS` после ПЕРВОГО: иначе непрерывный поток кадров
  // отодвигает перезапрос бесконечно, и список отстаёт от счётчиков минутами.
  const осталосьДоПотолка = Math.max(0, LIST_REFETCH_MAX_WAIT_MS - (сейчас - началоПачки));
  таймер = setTimeout(() => {
    таймер = null;
    сбросить();
  }, Math.min(LIST_REFETCH_DELAY_MS, осталосьДоПотолка));
}

/**
 * Перезапросить СЕЙЧАС, минуя схлопывание.
 *
 * Для действий, которые человек совершил САМ и результат которых ждёт глазами:
 * принял диалог — он обязан появиться в «Моих» немедленно, а не в хвосте чужой
 * пачки. Схлопывание защищает от ЧУЖИХ событий, а не от собственных нажатий.
 */
export function refetchListsNow(): void {
  if (таймер !== null) {
    clearTimeout(таймер);
    таймер = null;
  }
  сбросить();
}

/** Сброс между тестами: модульное состояние иначе течёт из теста в тест. */
export function __resetListRefetch(): void {
  if (таймер !== null) clearTimeout(таймер);
  таймер = null;
  началоПачки = 0;
  if (таймерЧисел !== null) clearTimeout(таймерЧисел);
  таймерЧисел = null;
  // Сверка живёт своим таймером и переживала бы соседний тест, спрашивая
  // сервер в чужом окне.
  if (таймерСверки !== null) clearTimeout(таймерСверки);
  таймерСверки = null;
}
