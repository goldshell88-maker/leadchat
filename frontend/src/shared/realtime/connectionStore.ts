import { create } from "zustand";

/**
 * WS-соединение (03 §1.1/§2.2): status для баннера «нет соединения» (11 §8.1),
 * lastEventAt — максимальный ts принятого события, точка отсчёта догона (01 §11.7).
 * Не персистится.
 */
export type ConnectionStatus = "idle" | "connecting" | "open" | "reconnecting";

interface ConnectionState {
  status: ConnectionStatus;
  lastEventAt: string | null;
  /**
   * Когда связь ВОЗВРАЩАЛАСЬ — метки времени за последнее окно.
   *
   * ⚠ ЗАЧЕМ СЧИТАТЬ ВОЗВРАТЫ (разбор 03.09). Сотрудник сообщил: «сайт работал
   * в пять раз медленнее». Сервер в ту минуту отвечал за 25 мс по медиане, а у
   * него самого сокет оборвался и вернулся шесть раз за час — то есть медленно
   * было в его канале, а не в службе.
   *
   * Узнать это по экрану он не мог. Полоса «нет соединения» показывается на
   * время переподключения и гаснет через две секунды после возврата: при
   * обрыве в одну секунду человек видит короткую вспышку. Шесть вспышек за час
   * читаются как «сайт тормозит», а не как «мой интернет рвётся», — и жалоба
   * уходит на службу.
   */
  reconnects: number[];
  /**
   * Когда пришёл последний СОДЕРЖАТЕЛЬНЫЙ кадр (не pong), по локальным часам.
   *
   * ⚠ ПОЧЕМУ НЕ `lastEventAt`. Там серверный `ts` из самого кадра, и он пуст
   * всё тихое утро: по нему не отличить «событий не было» от «связь молчит».
   * А различать надо: сокет бывает жив по всем признакам и при этом не
   * приносить ничего — тогда экран тихо стареет, и человеку остаётся F5.
   */
  lastFrameAt: number;
}

/** Дольше этого окна возвраты не помним: речь о «сейчас», а не о смене. */
export const ОКНО_ОБРЫВОВ_МС = 10 * 60_000;

export const useConnectionStore = create<ConnectionState>()(() => ({
  status: "idle",
  lastEventAt: null,
  reconnects: [],
  lastFrameAt: 0,
}));

/**
 * Отметить возврат связи. Зовётся ТОЛЬКО когда сокет вернулся, а не открылся впервые.
 *
 * ⚠ ОКНО ЗДЕСЬ НЕ ПРИМЕНЯЕТСЯ, И ЭТО ПРОВЕРЕНО ДИВЕРСИЕЙ. Метки стареют, пока
 * лежат, поэтому отсекать старые обязан ЧИТАТЕЛЬ — и он это делает. Такой же
 * отбор при записи ничего не менял: убрал его — ни один тест не покраснел,
 * потому что читатель всё равно фильтрует. Два места, решающих одно, однажды
 * разъезжаются; окно решает одно.
 *
 * Роста без предела нет: за смену возвратов единицы, вкладку перезагружают.
 */
export function отметитьВозвратСвязи(сейчас = Date.now()): void {
  useConnectionStore.setState((s) => ({ reconnects: [...s.reconnects, сейчас] }));
}
