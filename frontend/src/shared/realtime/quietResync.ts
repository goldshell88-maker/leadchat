/**
 * ТИХАЯ СВЕРКА С СЕРВЕРОМ — ВМЕСТО F5.
 *
 * ⚠ ПРОСЬБА ВЛАДЕЛЬЦА 28.08 дословно: «иногда приходится обновлять страницу,
 * так как что-то не проставилось, не прошло и т.д. Сделай бесшовное обновление
 * страницы, чтобы это было незаметно».
 *
 * ЧТО УЖЕ БЫЛО И ПОЧЕМУ НЕ ХВАТАЛО. Догон после ОБРЫВА написан давно и
 * подробно (`catchUpAfterReconnect`): сокет вернулся — забираем дифф или
 * перезапрашиваем открытые экраны. Но он держится на допущении «сокет жив,
 * значит кэш верен», а это неправда. Кадр теряется и без обрыва:
 *
 *   • публикация в Pub/Sub — «отправил и забыл», подтверждения доставки нет;
 *   • кадр мог уехать без нужного поля — за один сегодняшний день таких
 *     нашлось три (шкала ожидания, `in_inbox` при закрытии, имя поля у провала
 *     доставки), и каждый оставлял на экране вчерашнюю правду;
 *   • вкладка была скрыта, браузер придержал таймеры, а `refetchOnWindowFocus`
 *     у нас выключен намеренно (03 §2.4: «реальное время само приносит
 *     изменения»). С 31.08 скрытая вкладка сверяется наравне с открытой: у
 *     неё видны счётчик в заголовке и бейдж очереди, а кадр, потерянный при
 *     свёрнутой вкладке, иначе не чинился никогда.
 *
 * Во всех трёх случаях человеку остаётся F5 — и он его жмёт, теряя черновик и
 * место в ленте.
 *
 * ⚠ ПОЧЕМУ ЭТО НЕЗАМЕТНО. `invalidateQueries` с `refetchType: "active"` не
 * снимает данные с экрана: react-query держит прежние, пока идёт запрос, и
 * подменяет их готовыми. Ни скелета, ни мигания, ни прыжка прокрутки — в
 * отличие от перезагрузки страницы, которая всё это делает и вдобавок теряет
 * набранное.
 *
 * ⚠ ПОЧЕМУ НЕ `refetchOnWindowFocus: true` ГЛОБАЛЬНО. Он срабатывает на каждый
 * возврат фокуса — то есть десятки раз за смену, включая переключение между
 * окнами. Здесь же есть пол в двадцать секунд и один общий проход, а не
 * россыпь перезапросов на каждое касание мыши.
 */

/** Не чаще одного раза в столько: возврат во вкладку бывает и раз в секунду. */
const НЕ_ЧАЩЕ_МС = 20_000;

/**
 * Свой, короткий пол ДЛЯ ВОЗВРАТА ВО ВКЛАДКУ.
 *
 * ⚠ ШАПКА ВЫШЕ ОБЕЩАЛА ЗАЩИТУ, КОТОРОЙ В КОДЕ НЕ БЫЛО (разбор 03.09). Строка
 * «здесь есть пол в двадцать секунд» верна только для таймера: возврат звал
 * сверку с `force`, то есть в обход пола вообще. А диспетчер работает в двух
 * окнах — LeadChat и само Авито — и щёлкает между ними постоянно. Одна сверка
 * на экране чатов это 12–17 запросов; при перещёлкивании раз в три секунды
 * получалась их непрерывная очередь.
 *
 * Семь секунд выбраны так, чтобы просьба владельца от 28.08 осталась в силе:
 * вернулся человек — видит свежее, а не «минуту старого». Ставить сюда
 * двадцать секунд нельзя, это вернуло бы ровно ту жалобу.
 */
const ПОЛ_ПУЛЬСА_МС = 5_000;
let последнийПульс = 0;

/**
 * ПУЛЬС — два запроса вместо пятнадцати (жалоба владельца 03.09: «сделай, чтобы
 * весь сайт обновлялся в фоне», и она же про «максимально быстро»).
 *
 * ⚠ ЧТО БЫЛО. Возврат во вкладку звал ПОЛНУЮ сверку: 12–17 запросов на экране
 * чатов. Диспетчер работает в двух окнах — LeadChat и само Авито — и щёлкает
 * между ними постоянно; тринадцать человек сидят за ОДНИМ офисным адресом, а
 * nginx считает предел на адрес. Залп в тринадцать вкладок по пятнадцать
 * запросов — это почти двести штук разом при пропуске шестьдесят: лишнее
 * получает 429, а на 429 клиент не переспрашивает. То есть частые возвраты не
 * ускоряли обновление, а теряли его.
 *
 * ⚠ ЧТО ИМЕННО ЧЕЛОВЕК ВИДИТ СРАЗУ. Вернувшись, он смотрит на числа: «Мои» и
 * бейдж очереди. Это ровно два запроса, и оба дешёвые (счётчик — один SQL в
 * частичный индекс, 0,7 мс на боевой базе). Остальное — переписка, карточка,
 * настройки — обновляется кадрами и тяжёлой сверкой по своему сроку.
 */
function пульс(): void {
  const сейчас = Date.now();
  if (сейчас - последнийПульс < ПОЛ_ПУЛЬСА_МС) return;
  последнийПульс = сейчас;
  void queryClient.invalidateQueries({ queryKey: qk.conversations.counts });
  void refreshInboxCount();
}

/**
 * Пол сверки в работе. Две минуты выбраны так: пропущенный кадр живёт на
 * экране не дольше этого, а тринадцать вкладок дают меньше одного запроса
 * списка в секунду на всех — при лимите nginx в тридцать на адрес.
 */
const РАЗ_В_МС = 2 * 60_000;

let последняя = 0;
let таймер: ReturnType<typeof setInterval> | undefined;
let сторожТишины: ReturnType<typeof setInterval> | undefined;

/** Сверить открытые экраны с сервером. Молча и без снятия данных с экрана. */
export function resyncNow(force = false): void {
  const сейчас = Date.now();
  if (!force && сейчас - последняя < НЕ_ЧАЩЕ_МС) return;
  последняя = сейчас;

  /*
   * ⚠ СНАЧАЛА ДОСДАЁМ ОТМЕТКИ ПРОЧТЕНИЯ, ПОТОМ СПРАШИВАЕМ СЕРВЕР (аудит 30.08).
   *
   * Сверка тянет счётчики непрочитанного, а `seedFromRows` объявлен «сервер —
   * истина» и перезаписывает их целиком. Если `POST /read` не дошёл (обрыв
   * туннеля, 429, 500 — всё, что мимо коротких ретраев транспорта), сверка
   * вернёт прежнее непрочитанное и снова сделает жирным диалог, в который
   * оператор смотрит. Досылка после перезапроса опоздала бы ровно на один цикл.
   */
  void досдатьМаркеры();

  /*
   * ⚠ СНАЧАЛА СВОРАЧИВАЕМ ЛЕНТЫ К ХВОСТУ, ПОТОМ ПЕРЕЗАПРАШИВАЕМ. Иначе сверка
   * заменяет ленту прокрученного вверх диалога одним СТАРЫМ куском: полный
   * перезапрос бесконечного запроса идёт только вперёд, а вперёд у ленты
   * ничего нет. Разбор — в `applyWsEvent.свернутьЛентыКХвосту`.
   */
  свернутьЛентыКХвосту();

  /*
   * ⚠ СВЕРЯЕМ КЛЮЧИ ЧАТОВ, А НЕ ВСЁ ПОДРЯД (аудит 06.09).
   *
   * ЧТО БЫЛО. С 31.08 здесь стоял сплошной `invalidateQueries({ refetchType:
   * "active" })` — «всё, у чего есть наблюдатель». Довод был про F5: карточка
   * клиента, шаблоны, каналы не сверялись никогда. Но три беды того дня, ради
   * которых сверку заводили, все были про кадры ЧАТОВ (шкала ожидания,
   * `in_inbox` при закрытии, имя поля у провала доставки); шаблоны и
   * настройки правят на их же экранах, где мутация сбрасывает ключ сама.
   *
   * ЦЕНА замерена 06.09: на экране чатов живут 10–17 активных запросов,
   * включая шаблоны со `staleTime` пять минут, — и все они шли раз в две
   * минуты с каждой из 11–13 вкладок за одним офисным адресом, складываясь в
   * тот же поток, что дал 344 ответа 429 в сутки. Сверять здесь есть смысл
   * ровно то, что живёт на кадрах сокета и стареет без них: строки списка,
   * числа над вкладкой, очередь и открытая лента. Остальное обновляется по
   * своему `staleTime` при следующем открытии экрана.
   *
   * `refetchType: "active"` везде: ключ без наблюдателя помечается
   * устаревшим и оживёт при открытии. Ленту берём ОДНУ — открытую: закрытые
   * ленты наблюдателя не имеют, и корень `messages` дал бы то же самое, но
   * прямым адресом честнее.
   */
  void queryClient.invalidateQueries({ queryKey: CONVERSATIONS_LIST_KEY, refetchType: "active" });
  void queryClient.invalidateQueries({ queryKey: qk.conversations.counts, refetchType: "active" });
  void queryClient.invalidateQueries({ queryKey: qk.inbox.list, refetchType: "active" });
  const { activeConversationId } = useChatUiStore.getState();
  if (activeConversationId) {
    void queryClient.invalidateQueries({
      queryKey: qk.messages.list(activeConversationId),
      refetchType: "active",
    });
    // Шапка, подвал и полоса передачи открытого диалога рисуются по детали:
    // без неё потерянный кадр держал, например, «Войти в диалог» вместо
    // «Принять» до ухода из диалога. Один запрос раз в две минуты.
    void queryClient.invalidateQueries({
      queryKey: qk.conversations.detail(activeConversationId),
      refetchType: "active",
    });
  }

  /*
   * Счётчик очереди — отдельно и всегда: он живёт дольше открытого списка
   * (висит на вкладке, в заголовке браузера и в рейке), и наблюдателя у него
   * может не быть вовсе.
   */
  void refreshInboxCount();
}

/**
 * Сколько сокет может молчать, прежде чем мы спросим сами.
 *
 * ⚠ ЗАЧЕМ ВООБЩЕ. Сокет бывает жив по всем признакам — открыт, pong'и ходят —
 * и при этом не приносит ничего: подписка на сервере потерялась, кадр не дошёл,
 * событие проглотил обрыв туннеля. Экран в этом случае тихо стареет, и человеку
 * остаётся перезагрузка страницы, ради отмены которой всё это и написано.
 *
 * Девяносто секунд — по замеру, а не по вкусу: типичный промежуток между
 * пачками событий в работе около пятидесяти секунд, то есть порог почти вдвое
 * выше обычного и стреляет на аномалии, а не в работе. Цена — два дешёвых
 * запроса на вкладку.
 */
const ТИШИНА_СОКЕТА_МС = 90_000;

function наВозвратВкладки(): void {
  if (typeof document === "undefined" || document.visibilityState !== "visible") return;
  /*
   * Вернулся человек — сразу освежаем ЧИСЛА (два запроса), а полную сверку
   * зовём по обычному сроку. Раньше здесь стояла полная сверка с обходом пола:
   * пятнадцать запросов на каждое переключение окна, тринадцать вкладок за
   * одним адресом.
   */
  пульс();
  resyncNow();
}

/** Включить тихую сверку. Возвращает функцию выключения. */
export function startQuietResync(): () => void {
  // Новый сеанс — новый отсчёт: пороги не должны тянуться из прошлого
  // входа и глушить первую же сверку.
  последняя = 0;
  последнийПульс = 0;
  if (typeof document !== "undefined") {
    document.addEventListener("visibilitychange", наВозвратВкладки);
  }
  clearInterval(таймер);
  /*
   * ⚠ РАЗБРОС ПЕРЕД СВЕРКОЙ (03.09). После выкатки все тринадцать вкладок
   * перезапускаются разом и дальше идут в такт: их периодические сверки
   * складываются в один залп по 12–17 запросов каждая, а nginx считает предел
   * на АДРЕС, и офис за одним NAT. Случайная доля секунды разводит фазы, и
   * ничего больше от неё не требуется.
   */
  const разброс = () => Math.floor(Math.random() * 8_000);
  /*
   * ⚠ ПУЛЬС ПО ФОКУСУ ОКНА, А НЕ ТОЛЬКО ПО ВИДИМОСТИ (03.09). У диспетчера два
   * монитора: окно LeadChat видно постоянно, `visibilitychange` не приходит
   * НИКОГДА, и возврат к нему мышью ничего не освежал. Пол пульса тот же.
   */
  if (typeof window !== "undefined") {
    window.addEventListener("focus", пульс);
  }
  clearInterval(сторожТишины);
  сторожТишины = setInterval(() => {
    const { status, lastFrameAt } = useConnectionStore.getState();
    if (status !== "open" || lastFrameAt === 0) return;
    if (Date.now() - lastFrameAt < ТИШИНА_СОКЕТА_МС) return;
    пульс();
  }, 15_000);
  таймер = setInterval(() => {
    setTimeout(() => {
    /*
     * ⚠ СКРЫТУЮ ВКЛАДКУ СВЕРЯЕМ ТОЖЕ (просьба владельца 31.08: «обновляться
     * должно всё, даже если вкладка свёрнута»).
     *
     * Здесь стоял пропуск: «смотреть на неё некому, вернётся — сверим по
     * возврату». Довод неверен дважды. Во-первых, у свёрнутой вкладки видно
     * главное: счётчик в заголовке браузера, бейдж очереди и звук нового
     * обращения — а они как раз и держатся на данных, которые мы не сверяли.
     * Во-вторых, кадр, потерянный при свёрнутой вкладке, не чинился НИКОГДА:
     * сверка по возврату случается, только если человек вернётся, а он может
     * работать в соседнем окне Авито полсмены.
     *
     * Цена мала: браузер и так придерживает таймеры скрытой вкладки (обычно до
     * одного раза в минуту), медианы ручек 26–150 мс, а `refetchType: "active"`
     * тянет только то, что смонтировано.
     *
     * Закрытую вкладку сверять нечем и незачем: там нет ни кода, ни устаревших
     * данных — при следующем открытии всё загрузится заново.
     */
      resyncNow();
    }, разброс());
  }, РАЗ_В_МС);

  return () => {
    if (typeof document !== "undefined") {
      document.removeEventListener("visibilitychange", наВозвратВкладки);
    }
    if (typeof window !== "undefined") {
      window.removeEventListener("focus", пульс);
    }
    clearInterval(таймер);
    таймер = undefined;
    clearInterval(сторожТишины);
    сторожТишины = undefined;
    последняя = 0;
    последнийПульс = 0;
  };
}
