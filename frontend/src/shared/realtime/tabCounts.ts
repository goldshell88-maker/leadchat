import { queryClient } from "@/app/queryClient";
import { qk } from "@/shared/api/queryKeys";
import type { ConversationDto, TabCounts } from "@/shared/api/types";
import { STATUS_SHOWS_WAIT } from "@/shared/lib/conversationStatus";

/**
 * Числа над «Моими» двигаются ДЕЛЬТАМИ ИЗ КАДРА, а не перезапросом (аудит 06.09).
 *
 * ЗАМЕР (api-журнал 16,6 ч, nginx 24 ч). `GET /conversations/counts` — 55–60
 * тыс. в сутки, `GET /conversations` — 52–56 тыс.; вместе 54–57 % ВСЕГО
 * трафика, в пик 47 запросов на человека в минуту. Источник один: каждый
 * широковещательный кадр (`message:new` всем — 1 126 сообщений в час,
 * `conversation:updated`, `inbox:claimed/released`, `assigned`, плюс личный
 * кадр на `POST /read`) заказывал у КАЖДОЙ из 11–13 вкладок список плюс
 * числа. Вкладки били в одно окно, nginx (30 запросов в секунду на адрес)
 * отдавал 344 ответа 429 в сутки — все с офисного адреса, — а react-query 4xx
 * не повторяет: «Не получилось загрузить» на ленте и сорванное «Принять».
 *
 * ПОЧЕМУ ДЕЛЬТА ЧЕСТНА. Сервер считает числа двумя предикатами
 * (`services/conversations.py::tab_counts`): «на руках» — условие вкладки
 * «Мои» без закрытых; «не отвечено» — из них те, за кого я ОТВЕЧАЮ
 * (`own_condition`: ответственный или получатель передачи), в статусе из
 * `STATUS_SHOWS_WAIT` и с якорем ожидания. Кадр `message:new` везёт
 * канонический `waiting_since` (`inbound.py`, `messages.py` — с 28.08), а
 * строка в кэше знает статус и хозяина. Значит «ждал → не ждёт» и обратно
 * видно по паре строк ДО и ПОСЛЕ патча — ровно то, что посчитал бы сервер.
 *
 * ⚠ ГДЕ ДЕЛЬТУ ВЫВЕСТИ НЕЛЬЗЯ — НЕ ГАДАЕМ. Строка из старого кэша без поля
 * `waiting_since` (в типе отсутствие ≠ `null`) — это «не знаем», и тогда
 * `null` отсюда означает «спроси сервер»; спрашивают его одним отложенным
 * запросом на окно (`listRefetch.scheduleCountsRefetch`), а не списком.
 * «На руках» дельтой не двигается вовсе: его меняют только статус и хозяин,
 * а их смена и так ведёт к перезапросу списка вместе с числами.
 */

/** Ждёт ли клиент в этой строке — тем же правилом, что `_waiting_condition`. */
function ждёт(row: ConversationDto): boolean | null {
  if (row.waiting_since === undefined) return null; // строка старого кэша — не знаем
  return row.waiting_since !== null && STATUS_SHOWS_WAIT.has(row.status);
}

/**
 * Отвечаю ли я за строку — `own_condition`: ответственный или тот, кому
 * предложена ещё не принятая передача (`transfer_to_id`; в строке это
 * `transfer.to`). Флаг ⚑ `transferred_to_me` сюда не входит: он значит
 * «назначен мне и ещё не открыт», то есть ответственный уже я.
 */
function отвечаю(row: ConversationDto, я: string): boolean {
  return row.assignee?.id === я || row.transfer?.to.id === я;
}

/**
 * Переключилось ли у строки «клиент ждёт» — и `null`, когда не узнать.
 *
 * ⚠ ЭТО НЕ ТО ЖЕ, ЧТО ДЕЛЬТА НИЖЕ, И ПУТАТЬ ИХ НЕЛЬЗЯ. Дельта считает МОЙ
 * долг: чужой диалог ей безразличен, потому что в числе «не отвечено» его нет.
 * А членство строки в срезе «ждут ответа» от хозяина не зависит вовсе — срез
 * работает и на вкладке «Все» (`waiting_only` на сервере). Взять здесь дельту
 * значило бы: свой отвеченный из среза уходит, чужой остаётся.
 */
export function ожиданиеПереключилось(
  было: ConversationDto,
  стало: ConversationDto,
): boolean | null {
  const б = ждёт(было);
  const с = ждёт(стало);
  if (б === null || с === null) return null;
  return б !== с;
}

/**
 * На сколько сдвинуть «не отвечено» после патча строки: −1, 0, +1 — или
 * `null`, когда по строке этого не узнать (см. шапку).
 */
export function дельтаНеОтвечено(
  было: ConversationDto,
  стало: ConversationDto,
  я: string | undefined,
): number | null {
  if (я === undefined) return null;
  const ждалУМеня = отвечаю(было, я) ? ждёт(было) : false;
  const ждётУМеня = отвечаю(стало, я) ? ждёт(стало) : false;
  if (ждалУМеня === null || ждётУМеня === null) return null;
  return Number(ждётУМеня) - Number(ждалУМеня);
}

/**
 * Сдвинуть числа в кэше. Кэша нет — записывать нечего: первый же наблюдатель
 * спросит сервер сам, и подменять его ответ выдуманным нулём нельзя.
 *
 * ⚠ ЕДИНСТВЕННЫЙ ХОЗЯИН СЧЁТА НАД ВКЛАДКАМИ. 06.09 в двух ветках одного
 * этапа завелись две одинаковые функции — здесь и `listCache.сдвинутьЧислаМоих`.
 * Разошлись бы они на первой же правке (Math.max, поля, порядок), и числа
 * зависели бы от того, чей путь сработал: кадр WS или своё действие. Вторая
 * снята, все зовут эту.
 */
export function сдвинутьСчёт(дельта: Partial<TabCounts>): void {
  queryClient.setQueryData<TabCounts>(qk.conversations.counts, (old) => {
    if (!old) return old;
    return {
      mine: Math.max(0, old.mine + (дельта.mine ?? 0)),
      mine_waiting: Math.max(0, old.mine_waiting + (дельта.mine_waiting ?? 0)),
    };
  });
}
