import { useMediaQuery } from "@mantine/hooks";
import { create } from "zustand";
import { persist } from "zustand/middleware";

import { MOBILE_QUERY } from "@/shared/lib/breakpoints";

/**
 * Развёрнута ли левая панель.
 *
 * ПОЧЕМУ ОТДЕЛЬНОЕ ХРАНИЛИЩЕ, А НЕ ПОЛЕ В `chatUiStore`. То состояние
 * сбрасывается при смене роли и пользователя (`resetForRole`) — и правильно
 * делает: у другого человека другие вкладки и другая очередь. Ширина панели к
 * роли отношения не имеет: это привычка глаз и разрешение монитора. Диспетчер,
 * работающий на ноутбуке 1366px, свернул панель один раз — и она обязана
 * остаться свёрнутой завтра, даже если за тем же компьютером посидел
 * администратор.
 *
 * ПОЧЕМУ РАЗВЁРНУТА ПО УМОЛЧАНИЮ. Свёрнутая панель — это четыре безымянных
 * значка; что за ними, узнаёшь наведением. Команда переезжает с Jivo, где
 * разделы подписаны словами, и первое впечатление важнее одной строки экрана.
 * Кому тесно — сворачивает, и решение запоминается.
 */

interface RailState {
  expanded: boolean;
  toggle(): void;
  set(expanded: boolean): void;
}

export const useRailStore = create<RailState>()(
  persist(
    (set) => ({
      expanded: true,
      toggle: () => set((s) => ({ expanded: !s.expanded })),
      set: (expanded) => set({ expanded }),
    }),
    { name: "leadchat-rail" },
  ),
);

/** Ширина панели в пикселях — одно число на CSS и на раскладку каркаса. */
export const RAIL_WIDTH_EXPANDED = 218;
export const RAIL_WIDTH_COLLAPSED = 72;

/**
 * Развёрнута ли панель ПРЯМО СЕЙЧАС — с поправкой на ширину окна.
 *
 * Сохранённый выбор сделан для монитора; на экране в 390 пикселей панель в
 * 218 съела бы больше половины ширины, а работа здесь — переписка, которой
 * эта ширина и нужна. Ответ нужен в двух местах — каркас задаёт ширину
 * столбца, панель прячет подписи, — и оба обязаны получить его из одной
 * функции: разложи это по двум правилам, и они разойдутся.
 *
 * ПОЧЕМУ ЗДЕСЬ, А НЕ В `AppRail.tsx`, ГДЕ ЭТА ФУНКЦИЯ ЖИЛА РАНЬШЕ. Она нужна
 * И панели, И каркасу, то есть пересекает границу файла с компонентами. У
 * Vite горячая перезагрузка `.tsx` заменяет модуль целиком: панель получает
 * новую копию функции, а каркас продолжает держать старую — и два места,
 * которым положено отвечать одинаково, начинают отвечать по-разному. Ровно
 * такую вторую копию модуля мы уже ловили сегодня у хранилища Zustand, где
 * одна оказалась заполненной, а вторая пустой. В обычном `.ts` этого не
 * происходит, и ширина остаётся одним ответом на двоих.
 */
export function useRailExpanded(): boolean {
  const stored = useRailStore((s) => s.expanded);
  const isMobile = useMediaQuery(MOBILE_QUERY, false, { getInitialValueInEffect: false });
  return stored && !isMobile;
}
