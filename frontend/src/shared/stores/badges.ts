import { selectInboxCount, useInboxStore } from "./inboxStore";
import { selectTotalUnread, useUnreadStore } from "./unreadStore";

/**
 * Два бейджа приложения в одном месте (7.1 п.5): непрочитанные и очередь.
 *
 * Величины РАЗНЫЕ и складывать их нельзя. Непрочитанное — «мне написали, я не
 * прочитал», работа уже моя. Очередь — «диалог ничей и ждёт, чтобы его взяли»,
 * и работой он станет, только если я нажму «Принять». Одно число на двоих
 * означало бы, что оператор видит «7» и не знает, семь ли это его переписок или
 * семь брошенных клиентов.
 *
 * Механизм переиспользован целиком: то же место (заголовок вкладки), та же
 * подписка на стор, тот же формат. Новое здесь ровно одно — вторая величина
 * рядом с первой. Бейдж на иконке «Чаты» второго механизма не требует вовсе:
 * рейка читает счётчики селекторами, как читала непрочитанные.
 */

export interface Badges {
  /**
   * Непрочитанные сообщения В МОИХ ЖИВЫХ ДИАЛОГАХ.
   *
   * Раньше здесь было написано «во всех диалогах», и код это подтверждал:
   * суммировалось содержимое стора целиком. 12 августа выяснилось, чем это
   * оборачивается — «(10)» в заголовке вкладки появлялось и пропадало от смены
   * фильтра, потому что стор хранит всё пролистанное, включая чужое и
   * закрытое. Определение и код теперь совпадают, а почему именно так —
   * в `stores/unreadStore.ts::selectMineUnread`.
   */
  unread: number;
  /** Диалогов ждёт МОЕГО решения во «Входящих» (7.1). */
  queue: number;
}

export function readBadges(): Badges {
  return {
    unread: selectTotalUnread(useUnreadStore.getState()),
    queue: selectInboxCount(useInboxStore.getState()),
  };
}

/**
 * Заголовок вкладки браузера.
 *
 * `(N)` — непрочитанные, ровно как было (11 §2.6, DESIGN 3.3): без очереди
 * строка совпадает с прежней до символа, и ничего не «поехало».
 * `[N]` — очередь. Скобки разные намеренно: в свёрнутой вкладке видно шесть-семь
 * символов, и различать два числа приходится по форме, а не по позиции.
 * Очередь стоит первой — клиент, которого ещё никто не взял, срочнее
 * непрочитанного в диалоге, где оператор уже есть.
 */
export function formatDocumentTitle(
  { unread, queue }: Badges,
  section: string | null = currentSection,
): string {
  const parts: string[] = [];
  if (queue > 0) parts.push(`[${queue}]`);
  if (unread > 0) parts.push(`(${unread})`);
  // Раздел — ПОСЛЕ бейджей и ПЕРЕД именем продукта: в свёрнутой вкладке видно
  // шесть-семь символов, и числа обязаны уцелеть первыми; а из десятка вкладок
  // «Статистика · LeadChat» находится глазами, «LeadChat» ×10 — нет.
  const name = section ? `${section} · LeadChat` : "LeadChat";
  return parts.length > 0 ? `${parts.join(" ")} ${name}` : name;
}

/*
 * РАЗДЕЛ В ЗАГОЛОВКЕ ВКЛАДКИ (п. 16 отчёта тестирования, 15 августа).
 *
 * `document.title` всю жизнь был «LeadChat» на каждом экране: у диспетчера
 * рядом живут Авито, лид-центр и почта, и вкладку «Разбор диалогов» среди них
 * было не найти иначе как перебором. Название раздела сообщает сюда
 * `AppLayout` — единственное место, которое знает текущий путь.
 *
 * Модульная переменная, а не аргумент подписчика: подписка в `App.tsx`
 * пересобирает заголовок по ИЗМЕНЕНИЮ БЕЙДЖЕЙ, а раздел меняется навигацией —
 * это два независимых источника одного заголовка, и встреча им назначена
 * здесь. Порядок «[очередь] (непрочитанные) …» — записанное решение выше, и
 * раздел его не трогает.
 */
let currentSection: string | null = null;
let reapplyTitle: (() => void) | null = null;

export function setDocumentSection(section: string | null): void {
  if (section === currentSection) return;
  currentSection = section;
  reapplyTitle?.();
}

/**
 * Подпись иконки «Чаты» в рейке.
 *
 * Сами кружки на значке — `aria-hidden`: это два числа в углах эмодзи, и
 * скринридер прочитал бы их как «2 3». Поэтому величины называются словами и
 * разными: «в очереди» — клиент ждёт, чтобы его взяли, «непрочитанных» — работа
 * уже моя. Порядок тот же, что в заголовке вкладки, — очередь первой.
 */
export function formatChatsRailLabel({ unread, queue }: Badges): string {
  const parts: string[] = [];
  if (queue > 0) parts.push(`в очереди: ${queue}`);
  if (unread > 0) parts.push(`непрочитанных: ${unread}`);
  return parts.length > 0 ? `Чаты — ${parts.join(", ")}` : "Чаты";
}

/**
 * Подписка на оба счётчика без React — для `document.title`. Возвращает
 * отписку; сразу отдаёт текущее значение, чтобы вызывающему не писать это
 * руками. `apply` зовётся только при реальном изменении пары: сообщения идут
 * потоком, а перезапись `document.title` тем же значением дёргает вкладку.
 */
export function subscribeBadges(apply: (b: Badges) => void): () => void {
  let prev = readBadges();
  apply(prev);
  const push = () => {
    const next = readBadges();
    if (next.unread === prev.unread && next.queue === prev.queue) return;
    prev = next;
    apply(next);
  };
  const offUnread = useUnreadStore.subscribe(push);
  const offInbox = useInboxStore.subscribe(push);
  // Смена раздела перерисовывает заголовок с ТЕМИ ЖЕ числами: значения не
  // изменились, но строка собирается заново — уже с новым разделом.
  reapplyTitle = () => apply(prev);
  return () => {
    offUnread();
    offInbox();
    reapplyTitle = null;
  };
}
