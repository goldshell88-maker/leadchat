/**
 * Подпись сотрудника: имя и отдел в скобках — «Зуев Денис (Чатер)».
 *
 * ⚠ ПРОСЬБА ВЛАДЕЛЬЦА 04.09, ДОСЛОВНО: «нужно сделать так, чтобы везде
 * аккуратно в скобочках подписывались (Чатер) (ОКК) и т.д.». Отдел лежит в
 * `users.department` с 7.4, но виден был ровно в одном месте — колонкой на
 * вкладке «Команда». Во всех рабочих экранах человек был одним именем, а
 * имена у заказчика похожие: в списке тринадцать человек, часть из которых
 * ведёт один и тот же тип обращений из разных отделов.
 *
 * ⚠ ОДНА ФУНКЦИЯ НА ВСЕ ЭКРАНЫ — И ЭТО ГЛАВНОЕ В НЕЙ. Разъедься подпись по
 * местам показа — получим «Иванов (ОКК)» в шапке ленты и «Иванов» в списке, а
 * человек прочтёт это как ДВУХ РАЗНЫХ ИВАНОВЫХ и пойдёт выяснять, кто из них
 * ведёт диалог. Тем же классом дефекта здесь уже ловились: два пути считали
 * одно поле по-разному (`dva-puti-raznyi-schet`).
 *
 * ⚠ ПУСТОЙ ОТДЕЛ СКОБОК НЕ ДАЁТ. Замер боя: поле свободное, заполнено НЕ У
 * ВСЕХ. «Иванов ()» читается как сломанный экран, а не как «отдел не указан».
 *
 * ⚠ ЛИШНИЕ ПРОБЕЛЫ СХЛОПЫВАЮТСЯ. На бою рядом живут «Диспетчер МНЧ» и
 * «Диспетчер  МНЧ» с двумя пробелами: человек читает их как один отдел, и
 * подпись обязана выглядеть одинаково. Сервер чистит это же значение у себя
 * (`app/services/user_ref.py`) — здесь чистка повторена НЕ по недосмотру:
 * фронт и бэкенд выкатываются порознь, старая сборка сервера про неё не
 * знает, а вторым путём отдел приезжает ещё и собственным полем строки
 * («Команда», кандидат на канал, «Разбор диалогов»).
 *
 * ⚠ ЧТО РЕЖЕТСЯ ПЕРВЫМ ПРИ НЕХВАТКЕ ШИРИНЫ — ОТДЕЛ, А НЕ ИМЯ. Поэтому отдел
 * стоит в ХВОСТЕ подписи: в узких местах строка обрезается многоточием с
 * конца (`lc-truncate`, `dt__ell`), и первым исчезает именно он. Обратный
 * порядок дал бы «(ОКК) Ольга Ков…» — то есть отдел ценой имени, а имя тут
 * главное: отдел лишь уточняет, кто из двух похожих, и без него строка
 * остаётся рабочей. Полная подпись при этом остаётся в `title`/`aria-label`,
 * так что наведение и озвучка её всё равно дают.
 *
 * ⚠ ГДЕ ПОДПИСЬ НЕ СТАВИТСЯ, И ЭТО РЕШЕНИЕ, А НЕ ПРОПУСК:
 *
 * * «Команда» (`TeamMembersTab`) — отдел стоит там СВОЕЙ КОЛОНКОЙ и правится в
 *   ней же. Скобки рядом были бы вторым показом одного значения, а колонка
 *   ещё и редактируемая: показать «Иванов (ОКК)» и хранить «ОКК» значит
 *   подсунуть человеку правку, которой он не делал.
 * * СВОЁ ИМЯ — «Вы» в карточке, «у вас» в шапке, своя учётка в рельсе и в
 *   профиле. Свой отдел человек знает; скобки там только съедают ширину.
 *   Исключение одно и оно осознанное: АВТОР РЕПЛИКИ в ленте подписан отделом
 *   и когда это ты — иначе твои реплики и реплики коллеги подписаны
 *   по-разному, а лента читается как один список.
 * * АВАТАРКА (`UserAvatar`) берёт инициалы из имени: «О.К.(ОКК)» — не инициалы.
 * * ЖИВАЯ ЛЕНТА (`features/feed`) — строки там собирает справочник имён по id,
 *   и часть источников (зрители диалога) отдела не везёт вовсе. Отдел у
 *   половины строк и его отсутствие у другой половины хуже, чем ровное
 *   отсутствие: читается как «у этих отдела нет».
 * * СТРОКА ЗРИТЕЛЕЙ (`ConversationViewers`) — по той же причине: список едет
 *   из присутствия в Redis, где отдела нет.
 * * ВЫГРУЗКА CSV «Разбора» — колонка «Оператор» уходит в Excel, и скобки
 *   сломали бы фильтр по точному имени. Отдел там имеет смысл добавлять
 *   отдельным столбцом, а не в имя.
 */

/** Всё, что подписи нужно от человека. Шире `UserRef` — берёт и строки таблиц. */
export interface ЧеловекСОтделом {
  full_name?: string | null;
  department?: string | null;
}

/** «Диспетчер  МНЧ» → «Диспетчер МНЧ»; пусто и пробелы → пустая строка. */
function отдел(значение: string | null | undefined): string {
  return (значение ?? "").replace(/\s+/g, " ").trim();
}

/**
 * Имя с отделом в скобках. Нет имени — возвращается `запасное`, БЕЗ скобок:
 * «Коллега (ОКК)» обещало бы, что мы знаем, кто это, — а мы не знаем.
 *
 * `запасное` нужно вызывающим, у которых человека может не быть вовсе:
 * «Оператор» у реплики без автора, «Коллега» у передачи от удалённого
 * сотрудника.
 */
export function подписьСотрудника(
  человек: ЧеловекСОтделом | null | undefined,
  запасное = "",
): string {
  const имя = (человек?.full_name ?? "").trim();
  if (!имя) return запасное;
  const где = отдел(человек?.department);
  return где ? `${имя} (${где})` : имя;
}
