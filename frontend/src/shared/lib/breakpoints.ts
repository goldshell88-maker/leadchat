/**
 * Пороги раскладки рабочего места — ОДНО место на весь фронт.
 *
 * Их два, и оба живут сразу в трёх слоях: запрос в CSS решает, как выглядят
 * колонки, React — рисовать ли оверлей и кнопку, а комментарии в сторе
 * объясняют, откуда взялось состояние. Раньше числа стояли в каждом слое своей
 * копией, и правка одного давала состояние, которого не бывает: CSS уже
 * показал две колонки, а React всё ещё считает раскладку трёхколоночной —
 * карточка и в потоке, и в оверлее одновременно.
 *
 * Менять порог здесь и в `chats-page.css` (запросы CSS не умеют читать
 * TypeScript). Расхождение ловится тестом.
 *
 * ⚠ ДВЕ РАЗНЫЕ ЛИНЕЙКИ, И ЭТО НЕ НЕДОСМОТР (правка 08.09).
 *
 * `NARROW_MAX` меряется по РАБОЧЕМУ МЕСТУ — окну за вычетом левой рельсы.
 * `MOBILE_MAX` меряется по ОКНУ. Причина у разницы одна и та же: порог обязан
 * стоять там, где стоит решение, которое он принимает.
 *
 *   • Узкая раскладка решает судьбу трёх колонок, а колонки живут внутри
 *     рабочего места. Рельса развёрнута по умолчанию и забирает 218 пикселей
 *     (`shared/stores/railStore.ts`), поэтому окно — не та величина.
 *   • Порог телефона решает судьбу САМОЙ рельсы: `useRailExpanded` сворачивает
 *     её по `MOBILE_QUERY`. Считай его от места — и получишь круг, где ширина
 *     рельсы зависит от ширины места, а место от рельсы. По окну этот круг
 *     разомкнут, и все пять копий порога 767 (`app-layout.css`,
 *     `client-card.css`, `platform.css`, стор, здесь) остаются согласованными.
 */

/**
 * Ниже этого карточка клиента уезжает в оверлей по кнопке «Клиент».
 *
 * ⚠ ЧИСЛО МЕРЯЕТСЯ ПО ШИРИНЕ РАБОЧЕГО МЕСТА, А НЕ ОКНА. Расчёт ниже был верен
 * с самого начала — неверной была величина, которую в него подставляли:
 *   1360 − 340 (список) − 340 (карточка) − 64 (зазоры) = 616px — три колонки
 *   1359 − 340 − 64 = 955px — две колонки, лента дышит
 * Слева от «минус» стоит ширина, доступная КОЛОНКАМ, а её раньше брали равной
 * ширине окна. При развёрнутой рельсе колонкам достаётся на 218 пикселей
 * меньше: замер 08.09 на стенде — при окне 1440 ленте оставалось 478 пикселей
 * вместо объявленных 616, а на 1360 и вовсе 398.
 *
 * Прежний порог 1020 оставлял три колонки на всём диапазоне 1021–1359, где
 * ленте доставалось 400–530: имя клиента обрезалось, телефон переносился в
 * четыре строки. Ровно это и происходило снова, только на других окнах.
 */
export const NARROW_MAX = 1359;

/** Ниже этого — стек из двух экранов: список и лента по отдельности. */
export const MOBILE_MAX = 767;

/**
 * Узко ли рабочему месту при такой его ширине.
 *
 * Отдельная функция, а не сравнение по месту вызова: сравнение — часть порога,
 * и знак «меньше или равно» обязан быть один на весь фронт. Ошибись здесь на
 * единицу, и React с CSS разойдутся ровно на одном пикселе — том самом, где
 * карточка оказывается и в потоке, и в оверлее.
 */
export function узкоеМесто(ширинаМеста: number): boolean {
  return ширинаМеста <= NARROW_MAX;
}

/**
 * ⚠ `NARROW_QUERY` БОЛЬШЕ НЕТ, И ЭТО НАМЕРЕННО. Медиазапрос по ширине окна —
 * ровно тот инструмент, который не умеет вычесть рельсу; оставь его здесь
 * рядом с `узкоеМесто`, и следующая правка снова возьмёт его как более
 * привычный. Узкую раскладку определяет `features/chats/ширинаМеста.ts`.
 */
export const MOBILE_QUERY = `(max-width: ${MOBILE_MAX}px)`;
