/** Куда уводит адрес: внутрь приложения или наружу. */
export function внутреннийАдрес(to: string): boolean {
  // Обратный слэш браузер приравнивает к прямому: `/\evil.example` уходит
  // наружу, оставаясь похожим на внутренний путь. Отсюда и вся брешь.
  const адрес = to.replaceAll("\\", "/");
  // Абсолютный адрес со схемой (`https://…`, `javascript:…`) — не наш путь.
  if (/^[a-z][a-z0-9+.-]*:/i.test(адрес)) return false;
  // `//host` — адрес без схемы, тоже наружу.
  if (адрес.startsWith("//")) return false;
  return адрес.startsWith("/");
}

/**
 * Адрес перехода или `null`, если он уводит наружу.
 *
 * Возвращаем `null`, а не «безопасный» `/`: молча увести человека не туда, куда
 * он нажал, — это второй способ соврать. Вызывающий решает сам, что делать с
 * отказом, и обычно правильный ответ — не рисовать такую ссылку вовсе.
 */
export function толькоВнутренний(to: string): string | null {
  return внутреннийАдрес(to) ? to : null;
}
