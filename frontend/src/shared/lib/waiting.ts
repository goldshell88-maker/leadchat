/**
 * Сколько клиент ждёт ответа — ОДНА метрика на весь интерфейс.
 *
 * ЧТО ЗДЕСЬ ПРОИЗОШЛО 12 АВГУСТА. На одном экране ожидание было показано пятью
 * способами и тремя разными числами одновременно: «ждёт 2 ч» в шапке ленты,
 * оранжевая шкала «7ч» в строке списка, «в очереди 7 ч 11 мин» в карточке,
 * «Диалог ждёт в очереди» нижней плашкой и «Ждал 6 ч 41 мин» в системной
 * записи. Два часа и семь часов одиннадцать минут про один диалог — это уже не
 * дубль, а подорванное доверие ко всем числам продукта разом: диспетчер,
 * поймавший систему на таком, перестаёт верить и правильным цифрам тоже.
 * Независимо то же нашёл аудит (CHATS-07 / FUNC-14).
 *
 * КАК ЧИНИТСЯ. Считать перестаёт клиент. Сервер отдаёт ГОТОВЫЙ ЯКОРЬ
 * `waiting_since` — момент, с которого клиент ждёт нашего ответа (определение и
 * все «почему не так» — в `app/services/conversation_status.py:waiting_since`).
 * Здесь остаётся только оформление: сколько прошло, как это назвать и каким
 * цветом. Выбирать, ОТ ЧЕГО считать, интерфейсу больше нечем — а именно этот
 * выбор и расходился в пяти местах.
 *
 * ПОЧЕМУ СЕРВЕР НЕ ШЛЁТ ГОТОВУЮ ПОДПИСЬ. Она замерзает на времени ответа:
 * оператор сидит в диалоге сорок минут и всё это время видит «ждёт 1 мин».
 * Тикать обязан клиент — но тикать ОДНИМ способом и от ОДНОГО момента.
 *
 * ПОРОГИ. До пяти минут ничего не показываем: свежее обращение — это норма, и
 * счётчик у каждой строки превратился бы в шум, на который перестают смотреть.
 * После пяти — предупреждение, после пятнадцати — тревога: пятнадцать минут
 * молчания на Авито означают, что клиент уже пишет конкуренту.
 */

import type { ConversationStatus } from "./conversationStatus";
import { STATUS_SHOWS_WAIT } from "./conversationStatus";

export const WAIT_WARN_MIN = 5;
export const WAIT_LATE_MIN = 15;

export type WaitLevel = "calm" | "warn" | "late";

export interface Waiting {
  minutes: number;
  /** Готовая подпись: «7 мин», «2 ч», «3 дн». */
  text: string;
  level: WaitLevel;
}

/** Всё, что метрике нужно знать о диалоге. Строка списка, деталь и кадр WS. */
export interface WaitingSource {
  /**
   * Каноническое поле сервера: момент, с которого клиент ждёт. `null` — не
   * ждёт. `undefined` — строка старая (кэш прошлой версии, офлайн-снимок
   * десктопа), поля в ней нет вовсе, и тогда работает запасной расчёт.
   */
  waiting_since?: string | null;
  status?: string;
  /** Только для запасного расчёта — см. :func:`waitingFor`. */
  unread_count?: number;
  /** Только для запасного расчёта — см. :func:`waitingFor`. */
  last_message_at?: string | null;
}

function humanize(minutes: number): string {
  if (minutes < 60) return `${minutes} мин`;
  if (minutes < 60 * 24) return `${Math.floor(minutes / 60)} ч`;
  return `${Math.floor(minutes / (60 * 24))} дн`;
}

function level(minutes: number): WaitLevel {
  if (minutes >= WAIT_LATE_MIN) return "late";
  if (minutes >= WAIT_WARN_MIN) return "warn";
  return "calm";
}

/**
 * Оформление ожидания по готовой метке времени — ЕДИНСТВЕННЫЙ форматтер.
 *
 * `now` передаётся снаружи НАМЕРЕННО: иначе значение, вычисленное внутри
 * useMemo, замерзает на момент первой отрисовки и «ждёт 1 мин» висит, пока
 * оператор сидит в диалоге двадцать минут. Тикающие часы держит вызывающий —
 * один на список, а не сорок на строку.
 *
 * Сам по себе выбор метки не делает и делать не должен: кто передаст сюда
 * `offered_at` или `last_message_at`, тот и вернёт на экран разнобой, ради
 * устранения которого написан весь этот файл. Точка входа для диалога —
 * :func:`waitingFor`.
 */
export function waitingSince(iso: string | null | undefined, now: number): Waiting | null {
  if (!iso) return null;
  const started = Date.parse(iso);
  if (Number.isNaN(started)) return null;
  const minutes = Math.floor((now - started) / 60_000);
  if (minutes < 1) return null;
  return { minutes, text: humanize(minutes), level: level(minutes) };
}

/**
 * СКОЛЬКО КЛИЕНТ ЖДЁТ. Одна точка входа для всех пяти мест на экране.
 *
 * Годится и строке списка, и шапке ленты, и карточке, и нижней плашке: форма
 * диалога везде одна, а разными были только самодельные расчёты поверх неё.
 *
 * СТАТУС ПРОВЕРЯЕТСЯ ЗДЕСЬ ЕЩЁ РАЗ, ХОТЯ СЕРВЕР ЕГО УЖЕ УЧЁЛ, — и это не
 * перестраховка. Кадр `conversation:updated` патчит строку списка полями,
 * которые изменились: закрытие диалога приезжает статусом, а `waiting_since`
 * в патче может и не быть. Без этой проверки закрытый диалог продолжал бы
 * показывать «ждёт 3 ч» до следующей полной загрузки списка — ровно дефект №3
 * (docs/33 §3), из-за которого оператор открывал строку, требующую внимания, и
 * находил закрытое обращение. Список статусов общий с сервером
 * (`STATUS_SHOWS_WAIT`), его разъезд ловит `tests/unit/test_conversation_status.py`.
 *
 * ЗАПАСНОЙ РАСЧЁТ — ТОЛЬКО ДЛЯ СТРОК БЕЗ ПОЛЯ. В кэше и в офлайн-снимке
 * десктопа лежат строки, записанные ДО этой выкатки, и они переживут её. Для
 * них остаётся прежний признак «есть непрочитанные» — он завышает ожидание
 * (`last_message_at` двигают наши же исходящие и заметки), но молча погасить
 * тревогу хуже, чем показать лишнюю. Как только строка обновится с сервера,
 * заработает канонический путь. Отличаем по `undefined`, а НЕ по `null`:
 * `null` — это ответ сервера «не ждёт», и подменять его догадкой нельзя.
 */
/**
 * ЖДЁТ ЛИ КЛИЕНТ НАШЕГО ОТВЕТА — ПРЕДИКАТ, ОТДЕЛЬНЫЙ ОТ ПОДПИСИ.
 *
 * ⚠ ЗАЧЕМ ОТДЕЛЬНО, ЕСЛИ ЕСТЬ `waitingFor`. Тот отвечает на вопрос «что
 * написать в ячейке», и у него есть правило показа: моложе минуты — `null`,
 * потому что «ждёт 0 мин» это шум. Но `null` там означает «нечего писать», а
 * НЕ «никто не ждёт», и разница стоила дефекта.
 *
 * ЧТО ЛОМАЛОСЬ. Строка списка выводила «мяч у клиента» (то есть «мы ответили,
 * можно не смотреть» — приглушённое имя, погашенный аватар) из отсутствия
 * подписи. Клиент, написавший ПОЛМИНУТЫ НАЗАД, подписи не имел — и его диалог
 * рисовался как сделанный. Причём список отсортирован по свежести, так что
 * такая строка стоит ПЕРВОЙ: самый срочный диалог смены выглядел закрытым
 * вопросом ровно те шестьдесят секунд, когда на него надо кинуться.
 *
 * Здесь правило одно и оно про факт: поле сервера `waiting_since` непусто.
 * Зеркало серверного `_waiting_condition`, и обе стороны собраны из одного и
 * того же списка статусов.
 *
 * Запасной путь для строк без поля — тот же, что у `waitingFor`: непрочитанные.
 */
export function ждётНас(row: WaitingSource): boolean {
  if (row.status && !STATUS_SHOWS_WAIT.has(row.status as ConversationStatus)) return false;
  if (row.waiting_since !== undefined) return row.waiting_since !== null;
  return (row.unread_count ?? 0) > 0;
}

export function waitingFor(row: WaitingSource, now: number): Waiting | null {
  if (row.status && !STATUS_SHOWS_WAIT.has(row.status as ConversationStatus)) return null;
  if (row.waiting_since !== undefined) return waitingSince(row.waiting_since, now);
  if (!row.unread_count || row.unread_count <= 0) return null;
  return waitingSince(row.last_message_at, now);
}

/**
 * Прежнее имя расчёта для строки списка. Оставлено, чтобы правка не потребовала
 * одновременной переделки всех мест показа; ведёт в :func:`waitingFor` и
 * никакой своей логики не имеет — вторая логика здесь и была бедой.
 *
 * @deprecated Зовите `waitingFor`: он не только про строку списка.
 */
export const waitingForRow = waitingFor;
