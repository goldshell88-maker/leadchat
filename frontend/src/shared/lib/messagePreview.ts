/**
 * Слова о содержимом сообщения — В ОДНОМ МЕСТЕ.
 *
 * ЧТО БЫЛО. 11 августа с боевого аккаунта приехало сообщение
 * 00000000-0811-4000-8000-000000000001: `direction=in`, `sender_type=client`,
 * `body=null`, `attachments=[]`. Запись есть, показать нечего — и каждое место
 * придумывало ответ само:
 *
 *   лента (`MessageBubble`)        → «…»
 *   строка списка (`ConversationListItem`) → «Вложение»
 *   всплывающее уведомление (`platform/toast`) → «Вложение»
 *
 * Диспетчер видел в списке «Вложение», открывал диалог и находил там «…».
 * Двенадцать раз за день это читается как «программа сломалась», хотя сломан
 * был разбор: сервер не знал нетекстовых видов Авито и сохранял пустую запись
 * (`app/integrations/avito/adapter.py`, `_fallback_body`).
 *
 * Корень вылечен на сервере — с 12 августа запись без тела И без вложений не
 * сохраняется вовсе. Этот модуль закрывает вторую половину: слова больше не
 * сочиняются в каждом месте заново. Он нужен и после серверной правки — для
 * записей, накопленных ДО неё: у них в базе по-прежнему `body=null`, и лента
 * обязана назвать их теми же словами, какими сервер называет новые.
 *
 * Функции две, потому что мест ДВА, и они разные: в пузыре ленты вложение
 * рисуется само (картинкой или строкой со скрепкой), а в строке списка и в
 * тосте, кроме одной строки текста, нет ничего.
 */

/**
 * Тот же текст, что кладёт сервер (`adapter.py::UNSUPPORTED_MESSAGE_TEXT`).
 *
 * Пара держится тестом `tests/unit/test_avito_empty_message.py::
 * test_unsupported_text_matches_frontend`: разъехавшись, они дадут ровно ту
 * беду, ради которой всё это писалось, — два разных ответа об одном сообщении.
 */
export const UNSUPPORTED_MESSAGE_TEXT = "Сообщение неподдерживаемого вида — откройте диалог в Авито";

/**
 * Приставка, которой Авито метит свои служебные записи.
 *
 * ⚠ ЗАЧЕМ ПРИЗНАК ПО ТЕКСТУ, ЕСЛИ ЕСТЬ ПРИЗНАК ПО ОТПРАВИТЕЛЮ. С 17 августа
 * сервер разбирает такие записи отдельной веткой и кладёт их как системные
 * (`direction: "system", sender_type: "avito"`) — новые метятся верно, и
 * трогать это не надо. Но в базе лежат 29 записей ПРЕЖНЕЙ поры, поднятых
 * загрузкой истории: у них `direction: "in", sender_type: "client"`, и лента
 * рисовала их обычными словами клиента. «Пользователь создал чат, но пока
 * ничего не написал» выглядело как реплика человека — оператор отвечал на
 * сообщение, которого никто не писал.
 *
 * Переписывать историю в базе ради этого нельзя (данные клиентов правим только
 * по делу), поэтому лента узнаёт такие записи по приставке. Признак ровно тот
 * же, по которому их узнаёт сервер (`services/conversations.py`).
 */
export const AVITO_SYSTEM_PREFIX = "[Системное сообщение]";

/** Служебная запись Авито — по отправителю (новые) или по приставке (исторические). */
export function isAvitoSystemMessage(msg: {
  direction?: string | null;
  sender_type?: string | null;
  body?: string | null;
}): boolean {
  if (msg.direction === "system" && msg.sender_type === "avito") return true;
  return (msg.body ?? "").startsWith(AVITO_SYSTEM_PREFIX);
}

/** Общее слово, когда известно только то, что тела нет. */
const SOME_ATTACHMENT = "Вложение";

type AttachmentLike = { name?: string | null };

export type MessageTextSource = {
  body?: string | null;
  /**
   * НЕОБЯЗАТЕЛЬНОЕ — и это не небрежность, а правда о данных.
   * `ConversationDto.last_message` несёт только `body`, `direction` и время;
   * вложений в нём нет (`services/conversations.py`, чужая зона).
   */
  attachments?: AttachmentLike[] | null;
};

function trimmedBody(msg: MessageTextSource): string {
  return msg.body?.trim() ?? "";
}

/**
 * Текст пузыря в ленте. Пустая строка — законный ответ: значит, говорить будут
 * сами вложения, и подпись рядом с ними была бы вторым таким же словом.
 */
export function bubbleText(msg: MessageTextSource): string {
  const body = trimmedBody(msg);
  if (body) return body;
  return msg.attachments && msg.attachments.length > 0 ? "" : UNSUPPORTED_MESSAGE_TEXT;
}

/**
 * Одна строка о сообщении — всюду, где пузыря нет и вложение нарисовать негде.
 *
 * ⚠ СТРОКУ СПИСКА ЭТА ФУНКЦИЯ НЕ РИСУЕТ, ХОТЯ ЗДЕСЬ ТАК И БЫЛО НАПИСАНО
 * (проверено 07.09). У `ConversationListItem` своя `previewText`, и она
 * смотрит ровно в одно поле — `last_message.body`: вложений в строке списка
 * нет вовсе (`LastMessageRef` — это `body`, `direction`, `created_at`).
 * Единственный потребитель отсюда — всплывающее уведомление десктопа
 * (`platform/toast.ts`). Обещание «превью списка» было тем самым враньём
 * комментария, по которому чинят не то место.
 *
 * ⚠ ЧТО ЭТО ЗНАЧИТ ПРИ ПЕРЕЕЗДЕ ПОДПИСИ ИЗ ТЕЛА ВО ВЛОЖЕНИЕ. Тост назовёт
 * вложение его именем — словами сервера, целиком: «Видео — посмотреть можно
 * только в приложении Авито». Резать их здесь нечем и незачем — короткого
 * имени вида сервер отдельным полем пока не отдаёт, а второй список подписей
 * на фронте разъехался бы с серверным. Замер длин имён по бою: 95-я доля —
 * 19 знаков, самое длинное за всю историю — 120 (адрес геопозиции).
 *
 * Про случай «поле `attachments` не пришло вовсе»: считаем, что вложение есть.
 * Пустое тело возможно ровно там, где оно есть, — сервер с 12 августа не
 * сохраняет запись, у которой нет ни тела, ни вложений. Исключение —
 * накопленное до правки; такие записи чинятся дозагрузкой истории, а до неё
 * честнее сказать «Вложение», чем «неподдерживаемый вид», которого мы в этом
 * месте не проверяли.
 */
export function previewText(msg: MessageTextSource): string {
  const body = trimmedBody(msg);
  if (body) return body;
  if (msg.attachments === undefined || msg.attachments === null) return SOME_ATTACHMENT;
  const first = msg.attachments[0]?.name?.trim();
  if (first) return first;
  return msg.attachments.length > 0 ? SOME_ATTACHMENT : UNSUPPORTED_MESSAGE_TEXT;
}
