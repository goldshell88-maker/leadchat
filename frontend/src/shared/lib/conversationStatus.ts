/**
 * Единственный словарь статусов диалога на фронте (docs/38 §0–§1).
 *
 * ПОЧЕМУ ЭТОТ ФАЙЛ ЕСТЬ. К одиннадцатому августа состав словаря был записан в
 * интерфейсе семь раз: фильтр списка чатов (во множественном числе), селект в
 * карточке клиента, колонка и фильтр в «Разборе диалогов», тип строки таблицы,
 * общий тип — объявленный ДВАЖДЫ, — и своя копия семантики вкладок в прогреве
 * кэша десктопа. Ни одна не выводилась из остальных, и подписи уже разъехались:
 * в одном месте «Новые», в другом «Новый».
 *
 * ПРАВИЛО СОПРОВОЖДЕНИЯ. Новое значение — правка ДВУХ файлов (этого и
 * `app/services/conversation_status.py`) и двух тестов. Пришлось тронуть
 * третий — где-то осталась копия. Разъезд с сервером ловит охранный тест
 * `tests/unit/test_conversation_status.py`: он читает этот файл текстом и
 * сравнивает `STATUS_ORDER` с серверным `STATUSES`. Приём в проекте уже
 * применён к списку сортируемых колонок (`features/table/api.ts`).
 */

export type ConversationStatus = "new" | "in_progress" | "waiting_client" | "closed";

/**
 * Порядок — жизненный путь диалога, он же порядок пунктов во всех фильтрах.
 * Алфавит здесь был бы случайным, а частотность — непостоянной.
 *
 * ЗНАЧЕНИЙ ЧЕТЫРЕ, А НЕ ПЯТЬ: `snoozed` («Отложен») снят 12 августа решением
 * владельца вместе со всей отложкой. Серверная половина — `STATUSES` в
 * `app/services/conversation_status.py`, там же записано, что колонки отложки
 * в базе остались и функцию можно вернуть правкой кода.
 *
 * ЭТОТ МАССИВ СВЕРЯЕТСЯ С СЕРВЕРОМ ПОСТРОЧНО. Не переписывайте его в одну
 * строку и не собирайте из `Object.keys` — охранный тест читает файл текстом,
 * потому что запрашивать словарь у сервера ради отрисовки фильтра значило бы
 * лишний раунд-трип на каждом открытии страницы.
 */
export const STATUS_ORDER: readonly ConversationStatus[] = [
  "new",
  "in_progress",
  "waiting_client",
  "closed",
];

/** Подпись в единственном числе — поле «Статус», колонка таблицы, чип. */
export const STATUS_LABEL: Record<ConversationStatus, string> = {
  new: "Новый",
  in_progress: "В работе",
  waiting_client: "Ждёт клиента",
  closed: "Закрыт",
};

/**
 * Подпись срезом — фильтры и вкладки: пункт означает множество диалогов, а не
 * один. «Статус: Новые» и «Статус: Новый» читаются по-разному, и до docs/38 в
 * списке чатов стояло первое, а в «Разборе диалогов» — второе.
 */
export const STATUS_LABEL_PLURAL: Record<ConversationStatus, string> = {
  new: "Новые",
  in_progress: "В работе",
  waiting_client: "Ждут клиента",
  closed: "Закрытые",
};

/**
 * При каких статусах на экране вообще показывается счётчик «клиент ждёт».
 *
 * `closed` ожидание ГАСИТ — на сервере это делает `clear_awaiting`,
 * здесь то же правило повторено для интерфейса. Пока его не было, закрытый
 * диалог с непрочитанным показывал шкалу «ждёт 3 ч» в списке и «ждёт 3 ч» в
 * шапке ленты: обе считались мимо статуса (дефект №3, docs/33 §3). Оператор
 * видел строку, требующую внимания, открывал — и находил закрытый диалог.
 *
 * Серверная половина правила — `STATUS_SHOWS_WAIT` в
 * `app/services/conversation_status.py`; сверяются тем же охранным тестом.
 */
export const STATUS_SHOWS_WAIT: ReadonlySet<ConversationStatus> = new Set<ConversationStatus>([
  "new",
  "in_progress",
  "waiting_client",
]);

/**
 * Каким статусам рисуется чип в строке списка.
 *
 * `new` и `in_progress` — это 95 % строк, и чип на каждой превратился бы в
 * шум, на который перестают смотреть. Рисуется ровно то, что ОБЪЯСНЯЕТ,
 * почему строка выглядит непривычно: мы ждём клиента, диалог закрыт.
 * Третьим здесь был чип «Отложен» — снят 12 августа вместе со статусом.
 */
export const STATUS_SHOWS_CHIP: ReadonlySet<ConversationStatus> = new Set<ConversationStatus>([
  "waiting_client",
  "closed",
]);

/**
 * Подпись незнакомого кода — САМИМ КОДОМ, а не пустотой.
 *
 * Нужна в окне выката: между релизом фронта и релизом бэкенда (порядок именно
 * такой, docs/38) клиент может получить значение, которого ещё не знает. Строка
 * `waiting_client` латиницей некрасива, но она хотя бы говорит правду; пустая
 * ячейка вместо статуса — это потерянная строка отчёта.
 */
export function statusLabel(status: string): string {
  return STATUS_LABEL[status as ConversationStatus] ?? status;
}

// ЗДЕСЬ ЖИЛА `statusLabelPlural` — подпись статуса во множественном числе для
// снятых бейджей вкладок. Снята 23.08: потребителей ноль. Словарь
// `STATUS_LABEL_PLURAL` и `STATUS_OPTIONS_PLURAL` остаются — их читает «Разбор
// диалогов».


/** Пункты для `Select` — собираются из словаря, а не выписываются рядом. */
export const STATUS_OPTIONS: Array<{ value: ConversationStatus; label: string }> =
  STATUS_ORDER.map((value) => ({ value, label: STATUS_LABEL[value] }));

export const STATUS_OPTIONS_PLURAL: Array<{ value: ConversationStatus; label: string }> =
  STATUS_ORDER.map((value) => ({ value, label: STATUS_LABEL_PLURAL[value] }));
