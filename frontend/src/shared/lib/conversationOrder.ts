import type { ConversationDto } from "@/shared/api/types";

/**
 * ПОРЯДОК СПИСКА ДИАЛОГОВ — ОДИН НА ВСЁ ПРИЛОЖЕНИЕ.
 *
 * Зеркало серверного `ORDER BY` из `app/services/conversations.list_conversations`:
 *
 *   1) закреплённые смотрящим — выше всех;
 *   2) `last_message_at` УБЫВАЮЩЕ, строки без сообщений — в конец;
 *   3) `id` — полный ключ.
 *
 * ЗАЧЕМ ОТДЕЛЬНЫЙ ФАЙЛ. Порядок на фронте считался в ДВУХ местах и
 * по-разному: список приходил в серверном порядке, а локальные правки кэша
 * (новое сообщение, патч строки, закрепление) пересортировывали его своим
 * компаратором — «непрочитанные сверху, затем свежее сверху». Пока событий не
 * было, список выглядел одним образом; после первого же входящего он
 * перестраивался в другой — закреплённые уезжали вниз, а прочитанные и
 * непрочитанные менялись местами. Оператор видел, как список «сам себя
 * перетасовывает», и терял строку, на которую вёл палец.
 *
 * Пер-юзерного `unread_count` в ключах нет намеренно, и это главное отличие
 * от прежнего компаратора. Сервер сортировать по нему не может физически: в
 * ответ он попадает уже ПОСЛЕ выборки (`read_markers.apply_unread_counts`), а
 * `ORDER BY` отрабатывает до `LIMIT`. Оставь мы этот ключ на клиенте — две
 * копии порядка снова разъехались бы, только теперь молча.
 *
 * ТАЙБРЕЙКЕР ПО `id` НЕ УКРАШЕНИЕ. Служебные события Авито приходят пачками с
 * одинаковой секундой, и без третьего ключа порядок внутри пачки зависел бы
 * от того, в каком порядке строки легли в массив, — то есть менялся бы после
 * каждой локальной правки.
 */

/** «Закреплено» отсутствующим полем не бывает: старая строка кэша — не закреплена. */
function pinRank(row: ConversationDto): number {
  return row.pinned ? 0 : 1;
}

export function compareConversationRows(a: ConversationDto, b: ConversationDto): number {
  const pa = pinRank(a);
  const pb = pinRank(b);
  if (pa !== pb) return pa - pb;

  // Пустое `last_message_at` — диалог без сообщений; его место в конце, а не
  // в начале, куда его отправило бы сравнение строк с пустой (`"" < "2026…"`).
  const ta = a.last_message_at ?? "";
  const tb = b.last_message_at ?? "";
  if (ta !== tb) {
    if (!ta) return 1;
    if (!tb) return -1;
    return ta < tb ? 1 : -1;
  }

  if (a.id === b.id) return 0;
  return a.id < b.id ? -1 : 1;
}
