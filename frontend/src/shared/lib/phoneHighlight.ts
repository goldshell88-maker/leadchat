/**
 * НАЙДЕННЫЙ ТЕЛЕФОН ВНУТРИ ТЕКСТА СООБЩЕНИЯ: ГДЕ ОН ЛЕЖИТ, А НЕ ЕСТЬ ЛИ ОН ТАМ.
 *
 * ЧЕГО ЗДЕСЬ НЕТ НАМЕРЕННО — РАЗБОРА. Правила, по которым цепочка цифр
 * считается телефоном, живут на сервере (`app/services/phone_parse.py`) и взяты
 * из боевых диалогов: цифры, приклеенные к слову, — не номер («код входной
 * двери 37ключ2580»); в цепочке ровно 10 или 11 цифр («8-900-111-22-40-77» —
 * неизвестно что); знак номера слева отменяет находку («заказ№89001112240»).
 * Повторить их в TypeScript означало бы завести ВТОРОЙ источник правды, и
 * разошёлся бы он молча, в одну из двух сторон, и обе плохие: подсветка
 * пообещала бы номер там, где сервер его не нашёл, — оператор диктует мастеру
 * чужой телефон; или промолчала бы там, где нашёл, — а автозапись по умолчанию
 * ВЫКЛЮЧЕНА, и путь «нажать в пузыре» для номера основной, а не запасной.
 *
 * ПОЭТОМУ ГРАНИЦА ПРОВЕДЕНА ТАК. Сервер отдаёт кандидата с полем `raw` — номер
 * ровно в той записи, какой его набрал человек («+7(900)1112240»), — и
 * `message_id`. Фронту остаётся арифметика: где эта запись стоит в тексте. Нет
 * кандидата — нет подсветки, и выдумать её здесь не из чего по устройству.
 *
 * ГЛАВНОЕ СВОЙСТВО РАЗРЕЗКИ: КУСКИ СКЛЕИВАЮТСЯ ОБРАТНО В ИСХОДНЫЙ ТЕКСТ, знак
 * в знак. Ни одного добавленного символа, ни одного потерянного. Это не
 * педантизм: номер из переписки копируют мышью, чтобы позвонить, — и если
 * подсветка вставит в текст хоть что-нибудь своё (пробел, перенос, значок), в
 * буфер обмена уедет не то, что написал клиент. Свойство закреплено тестом.
 */

/**
 * Распознанный номер, ЖДУЩИЙ решения оператора (`clients.candidate_view`).
 *
 * ОБЪЯВЛЕН ЗДЕСЬ, А НЕ РЯДОМ С `ClientIdentityDto` В КАРТОЧКЕ, по одной
 * прозаичной причине: карточка этих полей пока не объявляет, а сервер их шлёт,
 * и ждать чужой правки, чтобы показать номер в пузыре, значило бы не показать
 * его вовсе. Когда тип личности объявит их у себя, это объявление уедет туда.
 */
export interface PhoneCandidateDto {
  id: string;
  /** Канонический вид, `+7XXXXXXXXXX`, — им звонят и по нему ищут двойников. */
  phone: string;
  /**
   * Как номер написан в сообщении. Не украшение: оператор обязан иметь
   * возможность сверить нашу догадку с тем, что человек набрал на самом деле,
   * — и это же поле показывает, ЧТО подсвечивать в тексте.
   */
  raw: string;
  conversation_id: string;
  /** Сообщение, из которого номер вычитан. `null` — у записей до правки. */
  message_id: string | null;
  message_at: string | null;
  detected_at: string | null;
  /** `voice` — из расшифровки голосового: подсвечивать в пузыре нечего, тело пусто. */
  source: "inbound" | "rescan" | "voice";
  status: "pending" | "accepted" | "rejected";
}

/** Кусок текста сообщения: обычный или тот, что надо подсветить. */
export interface TextPart {
  text: string;
  phone: boolean;
}

/**
 * Кандидаты ИМЕННО ЭТОГО сообщения и только ждущие решения.
 *
 * Сервер и так шлёт одни ожидающие, но проверка стоит строки: приедь сюда
 * когда-нибудь отклонённый — пузырь предложил бы вписать номер, про который
 * оператор уже сказал «это не он», и предложение вернулось бы после каждого
 * пересчёта истории.
 */
export function candidatesInMessage(
  candidates: readonly PhoneCandidateDto[] | undefined,
  messageId: string,
): PhoneCandidateDto[] {
  if (!candidates) return [];
  return candidates.filter((c) => c.message_id === messageId && c.status === "pending");
}

/**
 * Текст сообщения — кусками, где куски `raw` помечены к подсветке.
 *
 * ПОИСК ПОДСТРОКОЙ, А НЕ РЕГУЛЯРКОЙ. В `raw` живут `+`, скобки и точки —
 * знаки, значащие в регулярном выражении. Собранный из них шаблон либо упал
 * бы, либо, что хуже, совпал бы не с тем: `+7(900)1112240` как выражение
 * означает «единица или больше семёрок, дальше одна из цифр 9, 1, 5…».
 *
 * Перекрытия отбрасываются: если два кандидата указывают на пересекающиеся
 * места (один номер записан внутри другого), берётся первый по порядку —
 * подсветить один и тот же символ дважды нельзя, а рвать текст на части ради
 * этого нельзя тем более (см. свойство склейки в шапке файла).
 */
export function splitPhones(text: string, raws: readonly string[]): TextPart[] {
  const spans: Array<[number, number]> = [];
  for (const raw of raws) {
    // Пустая запись — не «совпадение в каждой позиции», а отсутствие данных:
    // без этой проверки цикл ниже не кончится никогда.
    if (!raw) continue;
    for (let from = 0; ; ) {
      const at = text.indexOf(raw, from);
      if (at < 0) break;
      spans.push([at, at + raw.length]);
      from = at + raw.length;
    }
  }
  if (spans.length === 0) return [{ text, phone: false }];

  spans.sort((a, b) => a[0] - b[0] || b[1] - a[1]);
  const parts: TextPart[] = [];
  let cursor = 0;
  for (const [start, end] of spans) {
    if (start < cursor) continue;
    if (start > cursor) parts.push({ text: text.slice(cursor, start), phone: false });
    parts.push({ text: text.slice(start, end), phone: true });
    cursor = end;
  }
  if (cursor < text.length) parts.push({ text: text.slice(cursor), phone: false });
  return parts;
}
