/**
 * Перезагрузка вкладки и уход на рабочее место — ОДНИМ объектом на всё
 * приложение.
 *
 * ПОЧЕМУ ОБЪЕКТ, А НЕ ДВЕ ФУНКЦИИ. jsdom не умеет ни `location.reload()`, ни
 * `location.assign()` — он бросает «Not implemented: navigation». Проверить,
 * что кнопка действительно перезагружает страницу, иначе нечем: подменить
 * `window.location` в тесте не выйдет (свойство неконфигурируемо), а «просто
 * поверить» нельзя — кнопка «Обновить» в двух местах сразу, и обе точки
 * ведут в прод, где ошибка стоит потерянной смены. Тест подменяет поля этого
 * объекта (`vi.spyOn(pageActions, "reload")`), поэтому вызывать их надо
 * ЧЕРЕЗ объект: `pageActions.reload()`, а не деструктурировать.
 *
 * ПОЧЕМУ ЗДЕСЬ, А НЕ В `app/ErrorBoundary`. Раньше объект жил внутри экрана
 * отказа, и это читалось как «перезагрузка — часть аварийного экрана». Теперь
 * перезагрузку просит и мирный баннер «Вышло обновление» из `platform/`, а
 * платформенному слою незачем тянуть за собой аварийный экран со всеми его
 * зависимостями. `ErrorBoundary` объект реэкспортирует — тесты и старые
 * импорты продолжают работать и указывают на ТУ ЖЕ ссылку.
 */
export const pageActions = {
  reload: () => window.location.reload(),
  goHome: () => window.location.assign("/chats"),
};
