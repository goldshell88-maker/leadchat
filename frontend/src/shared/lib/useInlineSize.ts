/**
 * ШИРИНА САМОГО БЛОКА — ТО ЖЕ ЧИСЛО, ЧТО ВИДИТ `@container` В CSS.
 *
 * ЗАЧЕМ. Пороги раскладки в проекте писались медиазапросами по ширине ОКНА, а
 * содержимому окно не достаётся целиком: слева стоит рельса приложения, и по
 * умолчанию она развёрнута (218px, `railStore`; свёрнутая — 72). Разницы в
 * 146px хватает, чтобы порог включился там, где на него нет места: раздел
 * «Команда» получал справку о ролях и горизонтальную прокрутку таблицы
 * одновременно, от роста окна на два пикселя (замер 08.09 — в team.css).
 *
 * В CSS это лечится контейнерным запросом (приём принят в проекте 07.09, см.
 * `settings/bots/bots.css` у `.sandbox-drawer__body`). Но `@container` не
 * умеет менять ТЕГИ, а React не умеет читать CSS, и там, где разметка зависит
 * от той же ширины, второй слой обязан мерить ТУ ЖЕ величину — иначе слои
 * разъезжаются и получается состояние, которого не бывает: CSS уже поставил
 * справку в колонку сбоку, а React всё ещё рисует свёртку.
 *
 * Отсюда этот хук: он отдаёт ширину наблюдаемого блока в пикселях, и она
 * сравнивается с тем же числом, что стоит в `@container`.
 *
 * ⚠ ЧТО ОБЯЗАН СОБЛЮСТИ ВЫЗЫВАЮЩИЙ. `@container` спрашивает ширину
 * СОДЕРЖИМОГО контейнера, а `getBoundingClientRect` отдаёт внешнюю рамку.
 * Совпадают они, только когда у наблюдаемого блока нет своих полей и рамки, —
 * поэтому наблюдать надо тот самый блок, чью ширину делит раскладка
 * (`.team-members__layout`, `.stats-chart__plot`), а не карточку с padding
 * вокруг него.
 *
 * ⚠ И ВТОРОЕ: у наблюдаемого блока ширина не должна зависеть от его же
 * содержимого, иначе замер и раскладка гоняются друг за другом. У обоих
 * нынешних вызывающих она задана снаружи (блочный элемент растягивается по
 * родителю), а `container-type: inline-size` в CSS это ещё и гарантирует.
 */
import { useCallback, useRef, useState } from "react";

/**
 * Ширина блока и ссылка-обработчик, которую надо повесить на него же.
 *
 * `null` — «ещё не мерили»: до первого замера, а также там, где мерить нечем
 * (jsdom в сторожах, браузер без `ResizeObserver`). Решение по `null`
 * принимает вызывающий, и принимать его надо в пользу ПРЕЖНЕГО вида: замер
 * появится через мгновение, а мигание раскладкой человек уже увидит.
 */
export function useInlineSize(): [(el: HTMLElement | null) => void, number | null] {
  const [width, setWidth] = useState<number | null>(null);
  const наблюдатель = useRef<ResizeObserver | null>(null);

  /*
   * Ссылка-функция, а не `useRef`: блок появляется и исчезает вместе с веткой
   * разметки (пока едут данные — скелетон, при ошибке — плашка), и наблюдателя
   * надо переподключать. `useCallback` с пустым списком держит одну и ту же
   * функцию — иначе React отцеплял бы и цеплял наблюдателя на каждый рендер.
   *
   * Замер прямо здесь, в фазе фиксации: он вызывает перерисовку ДО кадра, и
   * первое, что человек видит, — уже верная раскладка.
   */
  const ref = useCallback((el: HTMLElement | null) => {
    наблюдатель.current?.disconnect();
    наблюдатель.current = null;
    // Прежнее число намеренно не сбрасываем: блок мог уйти на перерисовку, и
    // `null` на один кадр вернул бы раскладку по умолчанию — то самое мигание.
    if (!el) return;
    setWidth(Math.round(el.getBoundingClientRect().width));
    if (typeof ResizeObserver !== "function") return;
    наблюдатель.current = new ResizeObserver((записи) => {
      const запись = записи[0];
      if (!запись) return;
      // `contentRect` — коробка СОДЕРЖИМОГО, ровно та, о которой спрашивает
      // `@container`.
      setWidth(Math.round(запись.contentRect.width));
    });
    наблюдатель.current.observe(el);
  }, []);

  return [ref, width];
}
