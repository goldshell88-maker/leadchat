import type { AccountRef, AvitoAccountDto, MyChannelDto } from "@/shared/api/types";

/**
 * Подпись канала в СПИСКАХ ВЫБОРА: название и источник рядом.
 *
 * ⚠ ПРОСЬБА ВЛАДЕЛЬЦА 03.09: «нужно, чтобы источник также прописывался рядом с
 * аккаунтами». Показан был список фильтра «Канал»: два десятка строк вида
 * «Александр КП», «Александр МНЧ», «Анатолий БТ» — по ним не отличить, какой
 * источник за каким каналом, а отвечает диспетчер именно от источника.
 *
 * ⚠ У ЭТОГО ЕСТЬ ИСТОРИЯ, И ОНА ОБЪЯСНЯЕТ, ПОЧЕМУ ПОДПИСЬ, А НЕ НАЗВАНИЕ.
 * Раньше владелец вписывал источник прямо в НАЗВАНИЕ канала: «ПАРТ 7 ИСТ С78».
 * 19 августа поля вынесли из названия и показали чипом в шапке чата — название
 * для этого не предназначено, оно же уходит в отчёты и уведомления. Но в
 * списках выбора шапки нет, и там источник снова стало неоткуда взять.
 * Поэтому он приписывается к подписи ПРИ ОТОБРАЖЕНИИ, а в самом названии
 * канала по-прежнему его нет.
 *
 * ⚠ ТОЛЬКО ИСТОЧНИК, БЕЗ НОМЕРА ПАРТНЁРА. В шапке чата рядом стоят оба, но
 * там места больше. Номер партнёра у большинства каналов один и тот же (7), то
 * есть в списке он ничего не различает — а различать и есть работа подписи.
 *
 * Источник не заполнен (служебный канал, только что подключённый) — подпись
 * остаётся прежней: висящая точка без значения хуже её отсутствия.
 */
export function подписьКанала(
  account: Pick<AvitoAccountDto | AccountRef | MyChannelDto, "title" | "lead_origin">,
): string {
  const источник = (account.lead_origin ?? "").trim();
  return источник ? `${account.title} · ${источник}` : account.title;
}
