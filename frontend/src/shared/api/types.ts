/** Важность (14 §4): красная плашка / жёлтая строка / серая строка. */
export type NotificationSeverity = "critical" | "warning" | "info";

/**
 * Каталог событий 14 §2 — ключи серверного реестра `services/notifications.KINDS`.
 * Союз с «хвостом» `(string & {})`: подсказки в редакторе остаются, а новый вид,
 * появившийся на бэкенде раньше фронта, не ломает типизацию и рисуется общим видом.
 */
export type KnownNotificationKind =
  // 2.1 системные — получатели все администраторы
  | "account.needs_reauth"
  | "inbound.stalled"
  | "backup.failed"
  | "scheduler.down"
  // Присылает внешний наблюдатель со второго сервера через POST /internal/notify:
  // «изнутри всё хорошо» о недоступности снаружи сказать некому.
  | "system.unreachable"
  | "queue.backlog"
  | "delivery.failures"
  | "disk.space"
  | "cert.expiring"
  | "ai.unavailable"
  // Автообъединение карточек само ушло в тень после откатов людей (12.09)
  | "client_merge.autostopped"
  // Воронка адресов: доля адресов, дошедших до карточки, упала за неделю (18.09)
  | "address.funnel_dropped"
  // Лестница политик правил адреса: понижение/отключение и повышение (20.09)
  | "address.rule_degraded"
  | "address.rule_promoted"
  // 2.2 обращения сотрудников — получатели все администраторы
  | "support.password_reset"
  | "support.message"
  | "auth.account_locked"
  // 2.3 рабочие события — руководитель и ответственный менеджер
  | "conversation.negative"
  | "conversation.no_reply"
  | "conversation.reopened"
  | "conversation.assigned"
  | "conversation.invited";

export type NotificationKind = KnownNotificationKind | (string & {});

