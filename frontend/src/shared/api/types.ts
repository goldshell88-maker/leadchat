/** Element of GET /conversations items (01 §5.1). */
export interface ConversationDto {
  id: string;
  status: ConversationStatus;
  /**
   * Когда диалог вошёл в НЫНЕШНИЙ статус (docs/38 §2). Отсюда считается
   * длительность в строке контекста — «В работе у Иванова · 12 мин».
   *
   * НЕ `updated_at`: тот двигает любое сообщение, любая заметка, любое
   * обогащение карточки клиента, и строка на нём показывала бы время с
   * последнего сообщения — другую величину, и показывала бы правдоподобно.
   *
   * Необязательное и nullable: строки из кэша прошлой версии поля не несут, а
   * `null` законен у диалогов, не менявших статуса с миграции. И то и другое
   * рисуется как статус БЕЗ длительности — прочерк честнее выдуманного нуля.
   */
  status_since?: string | null;
  /**
   * КАНОНИЧЕСКОЕ ОЖИДАНИЕ: момент, с которого клиент ждёт нашего ответа.
   * `null` — не ждёт (мы ответили, клиент ещё не писал или диалог закрыт).
   *
   * ⚠ ПОЛЕ НЕОБЯЗАТЕЛЬНОЕ, И РАЗНИЦА МЕЖДУ `null` И ОТСУТСТВИЕМ ЗНАЧАЩАЯ.
   * `null` — это ответ сервера «не ждёт». Отсутствие означает строку из
   * старого кэша или офлайн-снимка десктопа, записанную до появления поля; для
   * неё `waitingFor` уходит в запасной расчёт, а приглушение строки не
   * применяется вовсе (`ConversationListItem`, «мяч у клиента»). Подменять
   * отсутствие догадкой нельзя — молча погашенная тревога хуже лишней.
   *
   * Сервер кладёт поле в строку списка с 12 августа; в описании типа его до
   * сих пор не было, хотя `shared/lib/waiting.ts` читал его всё это время.
   */
  waiting_since?: string | null;
  channel: "avito";
  account: AccountRef;
  client: ClientRef;
  assignee: UserRef | null;
  item: ItemRef | null;
  last_message: LastMessageRef | null;
  unread_count: number;
  /**
   * Ответ оператора не дошёл до клиента (#26).
   *
   * Признак ДИАЛОГА, а не сообщения: красный крест виден только в открытой
   * ленте, а решение «идти дальше или вернуться» человек принимает по левому
   * списку. Там строка выглядела успешно отвеченной — «Вы: перезвоню в течение
   * часа», ничего красного, — и оператор уходил к следующему клиенту.
   *
   * Необязательное: строки, пришедшие из кэша прошлой версии, поля не несут, и
   * отсутствие обязано читаться как «всё доставлено», а не как «не знаем».
   */
  undelivered?: boolean;
  /* Здесь были `outcome` и `outcome_amount` — результат обращения и сумма
     заказа (#37). Сервер их больше не отдаёт: окно «Чем закончилось» снято
     12 августа решением владельца. Колонки в базе остались. */
  bot_active: boolean;
  tags: string[];
  transferred_to_me: boolean;
  last_message_at: string | null;
  /**
   * Закреплено ЛИЧНО смотрящим (требование от 7 августа).
   *
   * Не свойство диалога, а отношение человека к нему: у одного и того же
   * диалога значение разное для разных людей. Поэтому поле приходит в каждой
   * строке, а не хранится где-то рядом с диалогом.
   */
  pinned?: boolean;

  /* --- очередь «Входящие» (7.1, 15 §2.1) --------------------------------- *
   *
   * Все поля НЕОБЯЗАТЕЛЬНЫЕ, и это принципиально: строка очереди
   * (`services.inbox.inbox_item`) — это обычный `ConversationOut` плюс поля
   * ожидания, а обычный список и деталь их не несут вовсе. Диалоги, заведённые
   * до очереди, приходят без них и ведут себя ровно как раньше («кто ответил,
   * тот и ведёт»). Отсутствие поля НИКОГДА не означает «в очереди» — только
   * `in_inbox === true` означает.
   */

  /**
   * Диалог ждёт решения оператора. Приходит в патчах строки
   * (`queue_patch`/`claimed_patch`, 01 §11.3) и в элементах `GET /inbox`.
   * `false` — уже занят: у остальных двенадцати кнопка «Принять» гаснет.
   */
  in_inbox?: boolean | null;
  /** Когда диалог встал в очередь, ISO. По нему очередь сортируется (FIFO). */
  offered_at?: string | null;
  /** Сколько уже ждёт, секунды (только строки `GET /inbox`). */
  waiting_seconds?: number | null;
  /** То же по-русски, готовым текстом от сервера («12 мин»). */
  waiting_human?: string | null;
  /** Сколько операторов уже отказались — растёт к «никто не берёт». */
  declined_count?: number;
  /** Отказались ВСЕ, кому диалог доступен: клиент брошен, нужен разбор. */
  escalated?: boolean;
  /** Кто вынул диалог из очереди. Передача (01 §5.5) этот факт не переписывает. */
  claimed_by?: UserRef | null;
  claimed_at?: string | null;
  /**
   * Предложение передачи, ждущее ответа. `null` — предложения нет.
   *
   * Пока оно висит, `assignee` остаётся ПРЕЖНИМ: диалог числится за
   * передающим, и отвечает клиенту он. Это не деталь реализации, а суть
   * требования — ответственность не может повиснуть в воздухе между двумя
   * людьми, пока один думает, что отдал, а другой не знает, что получил.
   */
  transfer?: TransferOffer | null;
}

