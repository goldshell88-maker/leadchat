export interface ClientRef {
  id: string;
  /** Вебхук Авито v3 не несёт имени — для нового чата оно null, пока его не обогатит reconciliation/backfill. */
  name: string | null;
  /**
   * Идентификатор клиента НА АВИТО (`author_id` мессенджера), а не наш uuid.
   *
   * Показывается в блоке «Клиент на Авито» с кнопкой копирования: это
   * единственное, чем клиента можно назвать в кабинете Авито и в разговоре с
   * их поддержкой. Необязательное — старые кадры WS его не несут.
   */
  external_id?: string | null;
  /**
   * Ссылка на публичный профиль клиента. СЕГОДНЯ ВСЕГДА null.
   *
   * Авито даёт только числовой идентификатор мессенджера, а публичный профиль
   * живёт по другому, непрозрачному ключу; сопоставления между ними нет ни в
   * документации, ни в наших данных (docs/32 §7). Собранная по догадке ссылка
   * ведёт в 404. Интерфейс рисует ссылку ТОЛЬКО при непустом значении —
   * подтвердится формат, и фронт трогать не придётся.
   */
  profile_url?: string | null;
  /**
   * Спрашивали ли мы у Авито ссылку на профиль этого клиента.
   *
   * Отличает «ещё не знаем» от «Авито не дал», и подсказка в карточке обязана
   * говорить об этом разное: первое пройдёт само через секунду после открытия
   * диалога, второе не пройдёт никогда.
   */
  profile_checked?: boolean;
  phone: string | null;
  /**
   * Фото клиента — ссылка на CDN Авито из его публичного профиля.
   *
   * null законен: обогащение ещё не сходило, профиль без картинки или строка
   * из кэша прошлой версии. Интерфейс в этом случае рисует инициалы — и он же
   * откатывается на них, когда ссылка протухла (onError у img).
   */
  avatar_url?: string | null;
  avito_rating: number | null;
  /**
   * Клиент помечен как нежелательный (чёрный список).
   *
   * Его сообщения приходят и сохраняются — пометка убирает только требование
   * внимания: диалог не встаёт в очередь и не звенит.
   */
  blocked?: boolean;
  /** «Пишет каждый день, ничего не заказывает» — объяснение для того, кто
   *  наткнётся на пометку через полгода. */
  blocked_reason?: string | null;
  /**
   * Клиент писал не только в этот канал — и насколько мы в этом уверены
   * (требование владельца 6 от 11 августа).
   *
   * `null` (или поля нет вовсе, как в старых кадрах WS) — межканальной
   * склейки у карточки нет.
   *
   * `assumed` — карточка собрала диалоги с РАЗНЫХ аккаунтов Авито только
   * потому, что у них совпал `author_id`. Авито нигде не обещает, что этот
   * идентификатор общий для разных аккаунтов (в спецификации у
   * `Chat.users[].id` стоит «Обратите внимание на хэширование», и всё).
   * Значит за одной карточкой МОГУТ стоять два разных человека, и показывать
   * это как факт нельзя ни словом, ни оформлением.
   *
   * `confirmed` — с другого канала пришёл тот же номер телефона. Совпадение и
   * идентификатора, и номера у двух посторонних неправдоподобно, поэтому это
   * уже факт.
   */
  link_confidence?: "assumed" | "confirmed" | null;
  /**
   * Телефоны, пришедшие с разных каналов, НЕ СОВПАЛИ — довод за то, что
   * склеены разные люди. Единственный сигнал ложной склейки, который у нас
   * сегодня есть; интерфейс обязан показать его громче самой склейки.
   */
  link_phone_conflict?: boolean;
}

export interface ItemRef {
  title: string;
  url: string | null;
  price: string | null;
  /**
   * Город объявления (требование владельца от 11 августа: «непонятно, на какое
   * объявление пишет клиент, из-за этого я не знаю город»).
   *
   * Города Авито не отдаёт ни в вебхуке, ни в карточке чата — он вычитан из
   * САМОЙ ССЫЛКИ на объявление (`avito.ru/moskva/...`), сервером, чистой
   * функцией. Поэтому все четыре поля необязательные и любое может быть null:
   * ссылки может не быть вовсе, домен может оказаться чужим, а слаг —
   * незнакомым справочнику.
   *
   * `city_slug` приходит даже когда справочник города не знает: интерфейс
   * показывает сам слаг, и сразу видно, что справочник надо пополнить.
   */
  city_slug?: string | null;
  city_name?: string | null;
  city_region?: string | null;
  /**
   * IANA-имя часового пояса (`Europe/Moscow`) — НЕ время и НЕ смещение.
   *
   * Время у клиента считает браузер по этому имени, поэтому оно ИДЁТ, а не
   * замирает на момент ответа сервера, и переход на другое смещение случится
   * сам. Пусто — время не показываем вовсе: угаданный час стоит звонка
   * клиенту в три ночи, а пустое место не стоит ничего.
   */
  city_tz?: string | null;
}

