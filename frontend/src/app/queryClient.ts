import { QueryClient } from "@tanstack/react-query";
import { ApiError, TIMEOUT_ERROR } from "@/shared/api/http";

/**
 * Сколько раз переспрашивать после отказа. Значение прежнее (03 §2.4) — здесь
 * оно вынесено в имя только затем, чтобы правило ниже читалось словами.
 */
const RETRIES = 2;

/**
 * ТАЙМАУТ ПЕРЕСПРАШИВАТЬ НЕЛЬЗЯ (ACC-06, DIALOGS-13).
 *
 * `http.ts` теперь отбивает молчащий сервер через двадцать секунд — иначе
 * экран висел бы в загрузке вечно. Но с общим `retry: 2` лечение выходило
 * дороже болезни: три попытки по двадцать секунд — это МИНУТА скелетона
 * вместо вечности, и человек всё равно не понимает, что происходит.
 *
 * Смысл повтора в том, что вторая попытка может пройти там, где первая
 * споткнулась о мгновенную беду (перезапуск контейнера на выкате — секунды).
 * Запрос, провисевший двадцать секунд, споткнулся не об это: сервер жив,
 * соединение принято, ответа нет. Повтор здесь только оттягивает разговор.
 *
 * Все прочие отказы переспрашиваются как раньше — правило сужает поведение
 * ровно в одной точке.
 */
const isTimeout = (error: unknown) => error instanceof ApiError && error.code === TIMEOUT_ERROR;

/**
 * ОТКАЗ «ТЫ НЕПРАВ» ПЕРЕСПРАШИВАТЬ БЕССМЫСЛЕННО — И ЭТО ВИДНО СНАРУЖИ.
 *
 * Найдено проверкой боя 14 августа: открываем `/chats/not-a-uuid`, и во вкладке
 * «Сеть» лежат ТРИ одинаковых запроса с 400. Тройка бралась отсюда: правило
 * выше переспрашивает всё, кроме таймаута, а 4xx значит «запрос составлен не
 * так» — второй такой же запрос составлен ровно так же и получит тот же ответ.
 * Человек за это платит тройным ожиданием перед сообщением об ошибке.
 *
 * ПОЧЕМУ ВЕСЬ ДИАПАЗОН, А НЕ СПИСОК КОДОВ. 401 и 403 лечатся входом и правами,
 * 404 и 410 — тем, что сущности нет; ни одно из этого не проходит само за
 * секунду. Отдельно про 429: у него свой протокол с `Retry-After` (01 §1.3), и
 * сроки там не секундные — дневной лимит выгрузки (`/stats`) или окно поддержки.
 * Повтор через секунду в закрытую дверь — ровно то, от чего лимит и поставлен;
 * тот же довод записан в `http.ts` у `RETRY_STATUSES`. Секундный отказ nginx
 * по частоте сюда доходит, только если не помогло и ожидание по `Retry-After`
 * в самом `http.ts` (`sendPatiently`).
 *
 * 5xx остаётся повторяемым: перезапуск контейнера на выкате — это секунды, и
 * вторая попытка честно может пройти там, где первая споткнулась.
 */
const isClientFault = (error: unknown) =>
  error instanceof ApiError && error.status >= 400 && error.status < 500;

/**
 * Правило повторов целиком, отдельной функцией — чтобы его можно было
 * проверить сторожем, не поднимая сеть и экран (`queryRetry.test.ts`).
 * Внутри `new QueryClient({...})` оно было недостижимо для теста, и обе
 * оговорки выше держались на честном слове.
 */
export function shouldRetryQuery(failureCount: number, error: unknown): boolean {
  return !isTimeout(error) && !isClientFault(error) && failureCount < RETRIES;
}

// Defaults per 03 §2.4. Realtime (later sprints) delivers changes itself,
// so aggressive refetching is unnecessary.
export const queryClient = new QueryClient({
  defaultOptions: {
    queries: {
      staleTime: 30_000,
      gcTime: 30 * 60_000,
      retry: shouldRetryQuery,
      refetchOnWindowFocus: false,
    },
  },
});
