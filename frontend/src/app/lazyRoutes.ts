/**
 * Чанки ленивых разделов — одной картой «путь маршрута → import()».
 *
 * ЗАЧЕМ КАРТА, А НЕ `import()` ПРЯМО В `router.tsx` (жалоба владельца 06.09:
 * «задержки»). Переход в ленивый раздел не давал человеку никакого отклика:
 * `lazy` намеренно оставляет прежний экран на месте, пока едет чанк (довод у
 * `/dialogs` в router.tsx), а сам чанк начинал ехать только ПОСЛЕ нажатия. На
 * медленной сети нажатие «ничего не делало» секунду-две. Круг до сервера
 * никуда не денется, зато его можно сдвинуть в прошлое: человек наводит мышь
 * на пункт раньше, чем нажимает, и это время у нас есть даром — то же
 * решение, что у строк списка диалогов (`features/chats/предзагрузка.ts`).
 *
 * Для этого рельсе и меню настроек нужен ТОТ ЖЕ `import()`, что стоит на
 * маршруте. Два `import("...")` одного модуля браузер склеит сам, но стоит
 * путям разойтись на букву — предзагрузка потянет соседний файл, а переход
 * по-прежнему будет ждать свой, и заметить это можно только замером сети.
 * Одна карта — один источник: маршрут и пункт меню зовут одну и ту же строку.
 *
 * ⚠ КЛЮЧ — ПУТЬ МАРШРУТА, КАК ОН ЗАПИСАН В `router.tsx`, включая параметры
 * (`/settings/bots/:id`). Сторож `NavPending0609` сверяет карту с картой
 * маршрутов в обе стороны: лишний ключ здесь или ленивый маршрут мимо карты —
 * красный прогон.
 */
export const routeChunks = {
  "/invite/:token": () => import("@/features/auth/InvitePage"),
  "/dialogs": () => import("@/features/table/TablePage"),
  "/bot-dialogs": () => import("@/features/bot-dialogs/BotDialogsPage"),
  "/updates": () => import("@/features/updates/UpdatesPage"),
  "/ui-kit": () => import("@/features/uikit/UiKitPage"),
  "/notifications": () => import("@/features/notifications/NotificationsPage"),
  "/feed": () => import("@/features/feed/FeedPage"),
  "/stats": () => import("@/features/stats/StatsPage"),
  "/settings/profile": () => import("@/features/settings/profile/ProfilePage"),
  "/settings/accounts": () => import("@/features/settings/accounts/AccountsPage"),
  "/settings/accounts/operators": () => import("@/features/settings/accounts/OperatorsGridPage"),
  "/settings/templates": () => import("@/features/settings/templates/TemplatesPage"),
  "/settings/bots": () => import("@/features/settings/bots/BotsPage"),
  "/settings/bots/:id": () => import("@/features/settings/bots/BotEditor"),
  "/settings/leadbot": () => import("@/features/settings/leadbot/LeadbotTab"),
  "/settings/leads": () => import("@/features/settings/leads/LeadsTab"),
  "/settings/distribution": () => import("@/features/settings/distribution/DistributionTab"),
  "/settings/apis": () => import("@/features/settings/apis/ApisPage"),
  "/settings/team": () => import("@/features/settings/team/TeamPage"),
};

export type LazyRoutePath = keyof typeof routeChunks;
type ChunkOf<P extends LazyRoutePath> = Awaited<ReturnType<(typeof routeChunks)[P]>>;

/** Что уже спросили: и то, что ещё едет, и то, что приехало. */
const requested = new Map<LazyRoutePath, Promise<unknown>>();

/**
 * Промис чанка — один на путь, сколько бы раз ни спросили.
 *
 * Им пользуется и `lazy` маршрута, и предзагрузка по наведению: если человек
 * навёл мышь, а потом нажал, переход ждёт ТОТ ЖЕ промис, а не заводит второй.
 */
export function loadChunk<P extends LazyRoutePath>(path: P): Promise<ChunkOf<P>> {
  const known = requested.get(path);
  if (known) return known as Promise<ChunkOf<P>>;
  const chunk = routeChunks[path]() as Promise<ChunkOf<P>>;
  requested.set(path, chunk);
  /*
   * ⚠ ОТКАЗ НЕ ЗАПОМИНАЕМ. После выкатки старый чанк исчезает с сервера, и
   * `import()` во вкладке, открытой до выкатки, отдаёт 404 — это отклонённый
   * промис (разбор у `errorElement` в router.tsx). Останься он в карте —
   * нажатие на пункт получало бы тот же отказ из кэша, не сходив в сеть ещё
   * раз, и человек читал бы «раздел сломан» там, где сеть просто моргнула.
   */
  chunk.catch(() => requested.delete(path));
  return chunk;
}

/**
 * Предзагрузка по намерению: только положить чанк в кэш браузера. Ничего не
 * рисует и никуда не переходит; не нажали — файл просто лежит в кэше.
 */
export function preloadRoute(path: LazyRoutePath): void {
  loadChunk(path).catch((e: unknown) => {
    // Экран отказа покажет сам переход, если чанка не окажется и по нажатию;
    // здесь предзагрузка оставляет след и не поднимает тревогу раньше времени.
    console.warn(`[lazyRoutes] раздел ${path} не предзагрузился:`, e);
  });
}

/**
 * Обработчики для пункта меню: наведение мышью И фокус с клавиатуры — оба
 * предшествуют нажатию, и с клавиатуры пункт выбирают не реже, чем мышью
 * (сочетания в `features/hotkeys`). Повторное наведение стоит ноль: промис
 * уже в карте.
 */
export function preloadOnHover(path: LazyRoutePath) {
  const preload = () => preloadRoute(path);
  return { onPointerEnter: preload, onFocus: preload };
}

/** Забыть спрошенное — для сторожей, которые считают вызовы `import()`. */
export function forgetChunks(): void {
  requested.clear();
}

/**
 * Пауза между чанками там, где холостых промежутков браузер не обещает:
 * `requestIdleCallback` нет в Safari до 17. Это НЕ имитация простоя — простоя
 * мы там не видим и видеть не можем; 300 мс лишь разводят чанки во времени,
 * чтобы очередь не превращалась в залп.
 */
export const ЗАПАСНАЯ_ПАУЗА_МС = 300;

type Отмена = () => void;

/**
 * Один холостой промежуток.
 *
 * ⚠ БЕЗ `timeout`. С ним браузер ОБЯЗАН выполнить дело по истечении срока —
 * даже посреди работы человека, то есть ровно тогда, когда предзагрузке
 * встревать нельзя. Нет простоя — нет и прогрева: это не потеря, а условие.
 */
function вПростое(дело: () => void): Отмена {
  if (typeof window.requestIdleCallback === "function") {
    const id = window.requestIdleCallback(() => дело());
    return () => window.cancelIdleCallback(id);
  }
  const id = window.setTimeout(дело, ЗАПАСНАЯ_ПАУЗА_МС);
  return () => window.clearTimeout(id);
}

/**
 * Прогрев разделов В ПРОСТОЕ: очередь путей, по одному чанку за раз.
 *
 * ЗАЧЕМ, ЕСЛИ ЕСТЬ `preloadOnHover`. Наведение — не единственный способ
 * попасть в раздел, а у остальных форы нет вовсе: переход клавишами, касание
 * на планшете, back/forward, `navigate()` из кода и прямая ссылка платят круг
 * до сервера целиком (RTT офиса ~120 мс поверх самого чанка). Плюс после
 * выкатки старые чанки исчезают с сервера (nginx `try_files … =404`, контейнер
 * пересоздаётся): вкладка, открытая до выкатки, ловит 404 на ПЕРВОМ же
 * переходе и аварийно перезагружается — прогретый заранее чанк снимает и это.
 *
 * ⚠ ЧЕГО ЭТА ОЧЕРЕДЬ ДЕЛАТЬ НЕ ИМЕЕТ ПРАВА — мешать работе. Тринадцать
 * диспетчеров сидят за одним офисным NAT, а всех ленивых чанков ~120 КБ
 * сжатыми: выданные залпом, они отняли бы канал у того, что человек делает
 * прямо сейчас. Отсюда четыре правила:
 *  - шаг живёт в холостом промежутке браузера (`вПростое`, без `timeout`);
 *  - следующий чанк спрашивается, только когда предыдущий отъехал;
 *  - скрытая вкладка не греет ничего, а свёрнутая посреди прогрева замирает
 *    и продолжает по возвращении;
 *  - уже спрошенное пропускается, слот достаётся следующему.
 *
 * Возвращает отмену, и звать её обязан вызвавший (у каркаса — очистка
 * эффекта): без этого очередь переживёт экран, который её завёл.
 */
export function предзагрузитьВПростое(пути: readonly LazyRoutePath[]): Отмена {
  /*
   * Копия, а не сам список: очередь расходуется `shift`, а звать её могут с
   * заново собранным массивом каждый раз. Отсеивать здесь уже спрошенное
   * незачем — это делает `шаг` в момент выдачи, и делает шире: путь могли
   * согреть наведением уже после того, как очередь встала.
   */
  const очередь = [...пути];
  let жива = true;
  let отменитьШаг: Отмена | null = null;
  /*
   * ⚠ «ЧАНК В ПУТИ» — ОТДЕЛЬНЫМ ПРИЗНАКОМ, А НЕ ПО `отменитьШаг` (разбор
   * 07.09). Пока чанк едет, запланированного шага нет — и до этого признака
   * `запланировать` считало такое состояние свободным. Хватало вернуться во
   * вкладку, не дождавшись чанка: `наВидимость` заводила второй шаг поверх
   * едущего, и в канал уходили два чанка разом. На офисном круге окно узкое,
   * а на медленном канале чанк едет секундами — переключился в CRM и обратно,
   * и залп, которого эта очередь и создана не допускать.
   */
  let едет = false;

  const стоп = () => {
    if (!жива) return;
    жива = false;
    отменитьШаг?.();
    отменитьШаг = null;
    document.removeEventListener("visibilitychange", наВидимость);
  };

  const запланировать = () => {
    if (!жива || отменитьШаг || едет) return;
    if (очередь.length === 0) {
      стоп();
      return;
    }
    отменитьШаг = вПростое(шаг);
  };

  const шаг = () => {
    отменитьШаг = null;
    if (!жива) return;
    /*
     * ⚠ ВИДИМОСТЬ СПРАШИВАЕТСЯ В МОМЕНТ ЗАГРУЗКИ, а не при постановке в
     * очередь: между тем и другим вкладку успевают свернуть, а запасной таймер
     * в фоновой вкладке срабатывает (в отличие от холостых промежутков).
     * Скрытая вкладка не отменяет очередь, а замирает: канал офиса общий, и
     * фоновая вкладка тянула бы чанки у той, в которой работают. Разбудит её
     * `наВидимость` — фора нужна к первому переходу, а он будет по возвращении.
     */
    if (document.visibilityState !== "visible") return;
    // Пока ждали простоя, путь могли согреть наведением — тогда слот
    // достаётся следующему, а не тратится на промис, который уже в карте.
    let путь = очередь.shift();
    while (путь !== undefined && requested.has(путь)) путь = очередь.shift();
    if (путь === undefined) {
      стоп();
      return;
    }
    едет = true;
    void loadChunk(путь)
      .catch((e: unknown) => {
        // Тот же довод, что у `preloadRoute`: экран отказа покажет сам переход,
        // если чанка не окажется и по нажатию.
        console.warn(`[lazyRoutes] раздел ${путь} не прогрелся в простое:`, e);
      })
      .finally(() => {
        едет = false;
        запланировать();
      });
  };

  const наВидимость = () => {
    if (жива && document.visibilityState === "visible") запланировать();
  };

  document.addEventListener("visibilitychange", наВидимость);
  запланировать();
  return стоп;
}
