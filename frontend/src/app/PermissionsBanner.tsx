import { useEffect, useState } from "react";
import { Button } from "@mantine/core";
import { useQuery } from "@tanstack/react-query";
import { http } from "@/shared/api/http";
import type { MeResponse } from "@/shared/api/types";
import { useSessionStore } from "@/shared/stores/sessionStore";

/**
 * «У МЕНЯ ОТНЯЛИ ПРАВА» — А НА САМОМ ДЕЛЕ НЕ ОТВЕТИЛ ОДИН ЗАПРОС
 * (аудит SHELL-04, сценарий SCEN-01).
 *
 * ЧТО БЫЛО. Вход и старт вкладки кончаются запросом «кто я»
 * (`GET /auth/me`) — он приносит роль и список прав. Если запрос не удался
 * (сетевой всплеск, 502 в секунду перезапуска `api`), в `catch` выставляется
 * `permissions: []`, а человек остаётся ЗАЛОГИНЕННЫМ. Повторной попытки не
 * было нигде, сообщения — тоже нигде.
 *
 * Как это выглядит с рабочего места. Оболочка рисуется как у роли без
 * доступа: в рельсе пропадают «Разбор диалогов» и «Статистика», в настройках
 * исчезают вкладки, в диалоге нет кнопок. Ни одной строки о том, что
 * случилось. Руководитель читает это единственным доступным способом —
 * «администратор что-то со мной сделал», — звонит и разбирается полчаса.
 * Лечилось перезагрузкой вкладки, но догадаться до неё можно только зная
 * устройство.
 *
 * ПОЧЕМУ ПУСТОЙ СПИСОК — НАДЁЖНЫЙ ПРИЗНАК БЕДЫ, А НЕ РОЛИ. Сервер не знает
 * ролей без прав: у самой урезанной, `observer`, есть `conversations:read`
 * (app/core/rbac.py, `ROLE_PERMISSIONS`). Значит «человек есть, прав ноль» не
 * бывает в природе и означает ровно одно — ответ «кто я» до нас не доехал.
 * Заводить ради этого ещё одно поле в хранилище сессии не нужно: признак уже
 * есть, он просто никем не читался.
 *
 * ЧТО ЗДЕСЬ. Три вещи, и все обязательны:
 *   1) сказать словами, что это сбой связи, а не отзыв доступа;
 *   2) починиться самим — повторить «кто я» и записать права на место;
 *   3) дать кнопку, когда автоматические попытки кончились.
 */

/**
 * Сколько ждать, прежде чем считать пустые права бедой.
 *
 * Пауза не косметическая. Обычный вход проходит через то же состояние:
 * `applySession` сперва кладёт пользователя, и лишь потом — ответ «кто я».
 * Между этими двумя тактами прав нет ни у кого, и без выдержки полоса
 * мигала бы при КАЖДОМ входе, обучая на неё не смотреть. Полторы секунды —
 * заведомо больше обычного ответа `/auth/me` (десятки миллисекунд) и заведомо
 * меньше того, что человек примет за «так и надо».
 */
const GRACE_MS = 1500;

/** Человек есть, прав ноль — и это состояние держится дольше выдержки. */
function usePermissionsLost(): boolean {
  const empty = useSessionStore((s) => Boolean(s.user) && s.permissions.length === 0);
  const [held, setHeld] = useState(false);

  useEffect(() => {
    if (!empty) {
      setHeld(false);
      return;
    }
    const timer = window.setTimeout(() => setHeld(true), GRACE_MS);
    return () => window.clearTimeout(timer);
  }, [empty]);

  return empty && held;
}

export function PermissionsBanner() {
  const lost = usePermissionsLost();

  /*
   * Починка идёт тем же механизмом, что и все запросы экрана: повторы и паузы
   * между ними уже описаны в `queryClient`, и свой цикл повторов рядом с ним
   * разошёлся бы с общим правилом при первой же правке.
   *
   * `staleTime: 0` — ответ этого запроса нельзя переиспользовать: он нужен
   * ровно в тот момент, когда прав нет, и каждый раз заново.
   */
  const q = useQuery({
    queryKey: ["auth-me-recovery"],
    queryFn: async () => {
      const me = await http.get<MeResponse>("/auth/me");
      // Та же запись, что при входе и старте вкладки: своя копия здесь теряла
      // личные сочетания клавиш — они остались бы пустыми до перезагрузки.
      useSessionStore.getState().applyMe(me);
      return me;
    },
    enabled: lost,
    staleTime: 0,
    gcTime: 0,
  });

  if (!lost) return null;

  return (
    <div className="lc-perm-banner" role="alert">
      {q.isError ? (
        <>
          {/*
            Главное здесь — вторая половина фразы. Первое объяснение, которое
            приходит в голову человеку с исчезнувшими разделами, — «мне
            урезали доступ»; пока оно не опровергнуто прямо, всё остальное
            читается как подтверждение.
          */}
          <span>
            Не удалось получить ваши права — часть разделов сейчас скрыта. Это сбой связи, доступ у
            вас не отбирали.
          </span>
          <Button size="compact-xs" variant="white" onClick={() => void q.refetch()}>
            Повторить
          </Button>
        </>
      ) : (
        <span>Восстанавливаем ваши права — часть разделов пока скрыта…</span>
      )}
    </div>
  );
}
