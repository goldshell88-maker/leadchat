import { useEffect } from "react";
import { Text, Tooltip } from "@mantine/core";
import { useConnectionStore, ОКНО_ОБРЫВОВ_МС } from "@/shared/realtime/connectionStore";
import { useQuery } from "@tanstack/react-query";
import { noticeServerVersion } from "@/platform/buildVersion";
import { fetchHealth } from "@/shared/api/http";
import { qk } from "@/shared/api/queryKeys";

/**
 * Состояние связи с сервером: `/api/health` раз в 30 секунд.
 *
 * ВЫНЕСЕНО ИЗ `AppLayout` РАДИ ОДНОЙ ВЕЩИ, И ОНА ВАЖНЕЕ ОПРЯТНОСТИ. Показ
 * связи переехал внутрь всплывающего окна сотрудника (макет от 12 августа), а
 * окно закрыто по умолчанию — то есть компонент не смонтирован. Опрос вместе
 * с ним умер бы, а на нём висит НЕ ТОЛЬКО точка: тем же ответом приходит
 * версия сборки, и по ней замечается расхождение вкладки с сервером
 * (SHELL-02). Полоса «Вышло обновление» перестала бы появляться вовсе — тихо,
 * без единой ошибки в консоли.
 *
 * Поэтому опрос теперь живёт отдельным всегда смонтированным наблюдателем
 * (`ServerVersionWatch`), а показ берёт готовое из кэша: ключ у запроса один,
 * и второго похода в сеть не возникает.
 */

type HealthState = "online" | "connecting" | "degraded" | "offline";

function useServerHealth(): { state: HealthState; version: string | undefined } {
  const q = useQuery({
    queryKey: qk.health,
    queryFn: fetchHealth,
    refetchInterval: 30_000,
    /*
     * ⚠ В ФОНЕ НЕ СТУЧИМ (замер боя 27.08). Здесь стояло
     * `refetchIntervalInBackground: true`, и проба уходила каждые тридцать
     * секунд даже в свёрнутой вкладке — круглосуточно. За сутки с одного офиса
     * это 3944 запроса из 11 092, то есть треть всего, что приложение просит у
     * сервера; ночью, когда в системе никого, оно продолжало стучать по 180 раз
     * в час.
     *
     * Показывает эта проба состояние связи В ШАПКЕ — то есть ровно то, чего не
     * видно, пока вкладка скрыта. При возврате react-query перезапросит сам, и
     * индикатор обновится раньше, чем человек успеет посмотреть на него.
     *
     * Байтов проба почти не стоит (0,22 МБ за сутки), но жалоба владельца была
     * не про объём: постоянный фоновый стук держит радиомодуль включённым и
     * читается как «сайт грузит интернет».
     */
    staleTime: 0,
    retry: 0,
  });

  const state: HealthState = q.isError
    ? "offline"
    : q.isPending
      ? "connecting"
      : q.data.status === "ok"
        ? "online"
        : "degraded";

  return { state, version: q.data?.version };
}

/**
 * Ничего не рисует — только держит опрос живым и сверяет версию сборки.
 * Монтируется в каркасе один раз.
 */
export function ServerVersionWatch() {
  const { version } = useServerHealth();
  /*
   * Пустую версию (ошибка запроса, первая загрузка) не отсеиваем здесь:
   * `noticeServerVersion` сама не трогает состояние полосы, когда версии не
   * знает. Проверка в двух местах разошлась бы при первой же правке.
   */
  useEffect(() => {
    noticeServerVersion(version);
  }, [version]);
  return null;
}

/**
 * Со скольких возвратов подряд говорим «связь нестабильна».
 *
 * ⚠ ТРИ, А НЕ ОДИН. Одиночный обрыв бывает у всех и лечится сам за секунду —
 * писать о нём значит пугать без повода. Три возврата за десять минут это уже
 * не случайность, а свойство канала: живые обновления не доезжают, каждое
 * действие ждёт переподключения, и работа ощущается вязкой.
 */
const ОБРЫВОВ_ДЛЯ_ТРЕВОГИ = 3;

export function ConnectionIndicator() {
  const { state, version } = useServerHealth();
  /*
   * ⚠ ТОЧКА ЗНАЛА ТОЛЬКО ПРО HTTP, И ЭТО СТОИЛО ЛОЖНОЙ ЖАЛОБЫ (разбор 03.09).
   *
   * Состояние бралось из опроса `/api/health` раз в 30 секунд. У сотрудника
   * рвался ЖИВОЙ КАНАЛ — шесть раз за час, — а опрос здоровья при этом
   * проходил: точка светилась зелёным «На связи», обновления не приезжали, и
   * человек сделал единственный доступный ему вывод — «сайт стал в пять раз
   * медленнее». Сервер в те минуты отвечал за 25 мс по медиане.
   *
   * Теперь точка знает про оба канала и называет вещи своими именами.
   */
  const обрывов = useConnectionStore(
    (s) => s.reconnects.filter((t) => Date.now() - t <= ОКНО_ОБРЫВОВ_МС).length,
  );
  const нестабильна = state === "online" && обрывов >= ОБРЫВОВ_ДЛЯ_ТРЕВОГИ;

  /*
   * СЛОВА ПРО СВЯЗЬ, А НЕ ПРО ЧЕЛОВЕКА. Здесь стояло «В сети» — ровно то же,
   * чем в любой переписке называют состояние СОБЕСЕДНИКА. Рядом в том же окне
   * живёт «отошёл», и получалось так: диспетчер поставил себе «отошёл», а
   * строка ниже показывает зелёное «В сети». Человек читает это как
   * «состояние не сохранилось» и ставит «отошёл» заново — либо, наоборот,
   * верит строке и ждёт обращений, которых автораздача ему уже не даёт.
   *
   * Два разных смысла обязаны называться разными словами. Здесь — только про
   * канал до сервера; про себя человек читает выше, у своего имени.
   */
  const label = нестабильна
    ? "Связь нестабильна"
    : state === "online"
      ? "На связи"
      : state === "connecting"
        ? "Подключение…"
        : state === "degraded"
          ? "Сбой на сервере"
          : "Нет соединения";

  return (
    <Tooltip
      label={
        нестабильна
          ? `Соединение обрывалось ${обрывов} раз за последние десять минут. Сервер отвечает — проверьте свой интернет`
          : state === "online"
            ? `Сервер отвечает · v${version ?? "?"}`
            : label
      }
    >
      <div className="lc-conn" role="status" aria-label={`Связь с сервером: ${label}`}>
        <span
          className="lc-conn__dot"
          data-state={нестабильна ? "unstable" : state}
          aria-hidden="true"
        />
        {/*
          ⚠ КЛАСС `lc-conn__label` УБРАН — ОН НИЧЕГО НЕ ЗНАЧИЛ (проверка 05.09).
          Комментарий на его месте обещал, что слово прячется на узких экранах,
          а правила для этого класса не было ни в одном файле фронта: грепом он
          встречался ровно один раз — здесь, в разметке. Обещание было ложным с
          того дня, как связь переехала внутрь окна сотрудника: окно шириной 288
          пикселей одинаково на телефоне и на мониторе, прятать в нём нечего и
          незачем. Комментарий, описывающий несуществующее поведение, врёт
          следующему читателю убедительнее, чем отсутствие комментария.
        */}
        <Text fz="xs" c="var(--lc-text-3)">
          {label}
        </Text>
      </div>
    </Tooltip>
  );
}
