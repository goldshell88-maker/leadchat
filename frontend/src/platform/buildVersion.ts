import { isDesktopBuild } from "./bridge";
import { useUpdateStore } from "./updateStore";

/**
 * «ВКЛАДКА РАБОТАЕТ НА СТАРОЙ СБОРКЕ» — распознавание ДО поломки (SHELL-02).
 *
 * ЧТО БЫЛО. После каждой выкатки вкладка, открытая до неё, ломалась на первом
 * же переходе в ленивый раздел: `/assets` отдаётся с `Cache-Control: immutable`
 * и `try_files $uri =404` (docker/nginx/templates/leadchat.conf.template), так
 * что старый чанк с сервера исчезает и `import()` приносит 404 вместо кода.
 * Экран отказа это чинит — но постфактум: человек уже нажал «Статистика», уже
 * ничего не увидел, и вкладка перезагружается у него под руками. А пока он
 * никуда не переходит, вкладка молча остаётся на старом коде: старые запросы,
 * старый разбор кадров WS, старые тексты. С 8 августа выкатки идут в рабочий
 * день, на живой переписке — «узнаем, когда сломается» перестало годиться.
 *
 * ОТКУДА БЕРЁТСЯ НОМЕР. Он УЖЕ собирается в бандл, ничего заводить не пришлось:
 *  - `docker/Dockerfile.web` объявляет `ARG VITE_APP_VERSION`, а vite инлайнит
 *    `VITE_*` прямо в код на этапе сборки (рантайм-конфига у SPA нет, 05 §4);
 *  - CI подставляет туда короткий SHA — тот же тег, которым помечается образ
 *    api (`.github/workflows/deploy.yml`, шаг meta: один `tag` на оба образа);
 *  - api отдаёт свой тег в `GET /api/health` полем `version`
 *    (`app/core/config.py`: `APP_VERSION` либо `IMAGE_TAG`, а `deploy.sh`
 *    прописывает в `.env` именно выкаченный тег).
 * Значит «версия в бандле ≠ версия из /api/health» — это ровно «на сервере
 * лежит другая сборка фронта». Отдельной ручки, отдельного файла версии и
 * отдельного опроса не нужно: `/api/health` шапка и так дёргает раз в 30 с.
 *
 * ЧЕГО ЗДЕСЬ СОЗНАТЕЛЬНО НЕТ. Сравнения «больше/меньше». Тег — это SHA, он не
 * упорядочен; да и откат (`deploy.sh` умеет возвращать предыдущий тег) — это
 * тоже «вкладка не совпадает с сервером», и лечится он тем же самым действием.
 */

/** Версия ЭТОГО бандла. Пусто — сборка без тега (локальный `npm run dev`). */
export const BUILD_VERSION = ((import.meta.env.VITE_APP_VERSION as string | undefined) ?? "").trim();

/**
 * `dev` — не версия, а заглушка: она стоит умолчанием и в `Dockerfile.web`
 * (`ARG VITE_APP_VERSION="dev"`), и в `.env.example` (`APP_VERSION=dev`).
 * Сравнивать с ней — верный способ повесить на стенде вечный баннер, который
 * не гасится перезагрузкой (после неё версия бандла та же самая).
 */
const PLACEHOLDER = "dev";

/**
 * «prod» — ИМЯ ТЕГА, А НЕ ВЕРСИЯ (боевой случай 30.08). Контейнер, поднятый
 * без APP_VERSION, представляется в /api/health словом «prod» — ровно это
 * делал откатный путь выкатки, поднимавший образы без передачи номера. Слово
 * не совпадает ни с одним номером сборки, и полоса «Вышло обновление» горела
 * вечно: перезагрузка приносила тот же самый несовпадающий ответ. Откат
 * починен отдельно (ship.sh теперь передаёт номер возвращаемой сборки), но
 * фронт обязан быть терпим к любому серверу, который version'ом не владеет.
 */
const НЕ_ВЕРСИИ = new Set([PLACEHOLDER, "prod"]);

/**
 * Расходится ли сборка вкладки с той, что лежит на сервере.
 *
 * В десктопной сборке — всегда `false`, и это не перестраховка: фронт там
 * живёт внутри приложения (origin `tauri://localhost`, 04 §1.1), с сервера он
 * не перезагружается вовсе, а обновляется отдельным каналом с собственными
 * версиями (`platform/tauri/updater.ts`). Совпасть с тегом api эти номера не
 * обязаны никогда — без этой проверки у десктопа висел бы баннер, кнопка
 * которого ничего не чинит.
 */
export function isStaleTab(serverVersion: string | null | undefined): boolean {
  if (isDesktopBuild()) return false;
  const server = (serverVersion ?? "").trim();
  if (!server || !BUILD_VERSION) return false;
  if (НЕ_ВЕРСИИ.has(server) || НЕ_ВЕРСИИ.has(BUILD_VERSION)) return false;
  return server !== BUILD_VERSION;
}

/**
 * Принять версию из очередного `/api/health` и обновить состояние полосы.
 *
 * Гасить умеет тоже: если версии снова совпали (откат выкатки, пока человек не
 * успел нажать «Обновить»), полоса уходит сама — предлагать перезагрузку ради
 * той же самой сборки нечестно.
 *
 * А ВОТ «ВЕРСИЯ НЕ ПРИШЛА» — НЕ ПОВОД ГАСИТЬ, и это главная строка функции.
 * Выкатка перезапускает api: `/api/health` несколько секунд отвечает отказом
 * либо ответом без поля. Ровно в эти секунды полоса и поднимается — и «раз не
 * знаем, снимем» погасило бы её в тот единственный момент, когда она правда.
 * Оператор увидел бы мигание вместо предложения обновиться.
 *
 * Проверка стоит ЗДЕСЬ, а не у места вызова, намеренно: место вызова одно
 * сегодня, но функция публичная, и второй вызыватель обязан получить то же
 * поведение, не переписывая его у себя.
 */
export function noticeServerVersion(serverVersion: string | null | undefined): void {
  const server = (serverVersion ?? "").trim();
  if (!server) return;
  useUpdateStore.getState().announceBuild(isStaleTab(server) ? server : null);
}
