/**
 * «Человек сейчас смотрит на LeadChat?» и «эта ли вкладка оповещает?» — два
 * вопроса, на которые обязаны отвечать ОДИНАКОВО обе платформы и все вкладки
 * одного человека.
 *
 * ⚠ ПЕРВЫЙ ВОПРОС ВЕБ-МОСТ СЧИТАЛ НЕВЕРНО (07.09). Заслон показа стоял по
 * видимости вкладки (`visibilityState === "visible"`), и диспетчер, у которого
 * поверх LeadChat открыта CRM, считался «смотрящим»: вкладка видима, окно
 * чужое — уведомление не показывалось никогда, ровно в том случае, ради
 * которого уведомления и нужны. Десктопный мост считал по фокусу с самого
 * начала (`tauri/notifier.ts::currentEnv`), тихая сверка — тоже
 * (`quietResync.ts`, довод про два монитора). Здесь третья копия предиката не
 * заводится: обе платформы зовут `наЭкранеЛи`.
 *
 * Второй вопрос — про вкладки. Тег склейки (`bridge.ts::дополнитьСклейкой`)
 * схлопывает окна ОДНОГО вида события, но каждая вкладка всё равно создаёт
 * своё уведомление, а у диспетчера их 11–13 за смену. Поэтому вкладки
 * договариваются между собой, и оповещает ровно одна.
 */

/** Окно видимо И в фокусе. Без документа (SSR, прогон вне jsdom) — «на экране». */
export function наЭкранеЛи(): boolean {
  if (typeof document === "undefined") return true;
  // Свёрнутое/скрытое окно отдаёт visibilityState=hidden, потеря фокуса — hasFocus()=false.
  const виден = document.visibilityState === "visible";
  return виден && (typeof document.hasFocus !== "function" || document.hasFocus());
}

/* -------------------------------------------------------------------------- *
 *  Выборы оповещающей вкладки
 * -------------------------------------------------------------------------- */

/**
 * ПОЧЕМУ «ПОСЛЕДНЯЯ БЫВШАЯ НА ЭКРАНЕ», А НЕ `navigator.locks`.
 *
 * Web Locks дал бы жизнеспособность даром: замок сам освобождается при закрытии
 * вкладки. Но выбирает он произвольную вкладку — ту, что попросила первой, а
 * клик по уведомлению открывает диалог ИМЕННО В ТОЙ вкладке, которая его
 * показала (`web.ts`, `note.onclick`). Человек, вернувшись, оказался бы в
 * вкладке, которую последний раз видел час назад, потеряв открытые в рабочей
 * фильтры и позицию списка. Кроме того, замок держится и у замороженной
 * вкладки — та не покажет ничего, и уведомления пропали бы совсем.
 *
 * Поэтому оповещает вкладка, у которой предикат «на экране» был истинным
 * ПОСЛЕДНИМ: это ровно та, куда человек вернётся. Одновременно на экране может
 * быть только одна вкладка (фокус в системе один), поэтому сравнение времён
 * даёт одного победителя без переговоров.
 */
const ИМЯ_КАНАЛА = "lc-уведомления-выборы";

/**
 * Пульс и срок жизни записи о соседе. ⚠ 25 с выбраны не «на глаз»: у скрытой
 * вкладки Chromium прореживает таймеры до одного срабатывания в минуту, и срок
 * жизни обязан пережить два прореженных такта — иначе живого соседа объявят
 * мёртвым, и уведомление покажут обе вкладки.
 */
const ПУЛЬС_МС = 25_000;
const ЖИЗНЬ_ЗАПИСИ_МС = 150_000;

type Сообщение =
  | { тип: "я" | "привет"; id: string; наЭкранеВ: number }
  | { тип: "ухожу"; id: string };

interface ЗаписьСоседа {
  /** Когда сосед последний раз был на экране; 0 — не был ни разу. */
  наЭкранеВ: number;
  /** Когда мы последний раз слышали соседа — по этому полю он и «жив». */
  услышано: number;
}

export interface Выборы {
  /** Показывать ли уведомление из ЭТОЙ вкладки. */
  оповещает(): boolean;
  /** Снять слушатели и закрыть канал (выход из приложения, тесты). */
  остановить(): void;
}

export interface НастройкиВыборов {
  /** Имя канала — своё у каждого прогона теста, чтобы вкладки не путались. */
  имя?: string;
  /**
   * Подмена предиката «на экране». Нужна тестам: две «вкладки» живут в одном
   * документе jsdom, и настоящий `document.hasFocus()` у них общий.
   */
  наЭкране?: () => boolean;
}

export function создатьВыборы(настройки: НастройкиВыборов = {}): Выборы {
  const наЭкране = настройки.наЭкране ?? наЭкранеЛи;
  const я = `${Date.now().toString(36)}-${Math.random().toString(36).slice(2, 8)}`;
  const соседи = new Map<string, ЗаписьСоседа>();
  let наЭкранеВ = наЭкране() ? Date.now() : 0;

  let канал: BroadcastChannel | null = null;
  try {
    канал = typeof BroadcastChannel === "function" ? new BroadcastChannel(настройки.имя ?? ИМЯ_КАНАЛА) : null;
  } catch (e) {
    // Приватное окно, запрет политикой, чужая среда — канала нет, и это не
    // повод молчать: без него вкладка считает себя единственной (см. `оповещает`).
    console.warn("[уведомления] канал вкладок недоступен, оповещаю всегда:", e);
    канал = null;
  }

  const послать = (m: Сообщение) => {
    if (!канал) return;
    try {
      канал.postMessage(m);
    } catch (e) {
      console.warn("[уведомления] сообщение соседним вкладкам не ушло:", m.тип, e);
    }
  };

  if (канал) {
    канал.onmessage = (e: MessageEvent<Сообщение>) => {
      const m = e.data;
      if (!m || typeof m.id !== "string" || m.id === я) return;
      if (m.тип === "ухожу") {
        соседи.delete(m.id);
        return;
      }
      соседи.set(m.id, { наЭкранеВ: Number(m.наЭкранеВ) || 0, услышано: Date.now() });
      // На «привет» отвечаем состоянием: новая вкладка обязана узнать поле
      // сразу, а не через пульс — до первого уведомления может быть секунда.
      if (m.тип === "привет") послать({ тип: "я", id: я, наЭкранеВ });
    };
  }

  const отметиться = () => {
    if (наЭкране()) наЭкранеВ = Date.now();
    послать({ тип: "я", id: я, наЭкранеВ });
  };

  const наСобытие = () => {
    // Интересен только переход НА экран: он и есть «был последним».
    if (!наЭкране()) return;
    наЭкранеВ = Date.now();
    послать({ тип: "я", id: я, наЭкранеВ });
  };

  /**
   * Заморозка — это уход. Замороженная вкладка не выполняет ничего, показать
   * уведомление не может, а её запись у соседей осталась бы самой свежей и
   * заперла бы их. `resume` возвращает вкладку в поле.
   */
  const наЗаморозку = () => послать({ тип: "ухожу", id: я });
  const наПробуждение = () => отметиться();
  const наЗакрытие = () => послать({ тип: "ухожу", id: я });

  const естьОкно = typeof window !== "undefined";
  if (естьОкно) {
    window.addEventListener("focus", наСобытие);
    window.addEventListener("pagehide", наЗакрытие);
  }
  if (typeof document !== "undefined") {
    document.addEventListener("visibilitychange", наСобытие);
    document.addEventListener("freeze", наЗаморозку);
    document.addEventListener("resume", наПробуждение);
  }

  const пульс = естьОкно ? setInterval(отметиться, ПУЛЬС_МС) : null;
  послать({ тип: "привет", id: я, наЭкранеВ });

  return {
    оповещает() {
      // Канала нет — договариваться не с кем. Молчать в этом случае значит
      // потерять уведомления вовсе, а показать лишнее — всего лишь повтор.
      if (!канал) return true;
      if (наЭкране()) наЭкранеВ = Date.now();

      const сейчас = Date.now();
      for (const [id, с] of соседи) {
        if (сейчас - с.услышано > ЖИЗНЬ_ЗАПИСИ_МС) соседи.delete(id);
      }
      for (const [id, с] of соседи) {
        if (с.наЭкранеВ > наЭкранеВ) return false;
        // Ничья бывает только у вкладок, не бывших на экране ни разу (обе с
        // нулём): решаем по id — правило одно у всех, значит победитель один.
        if (с.наЭкранеВ === наЭкранеВ && id < я) return false;
      }
      return true;
    },

    остановить() {
      if (пульс !== null) clearInterval(пульс);
      if (естьОкно) {
        window.removeEventListener("focus", наСобытие);
        window.removeEventListener("pagehide", наЗакрытие);
      }
      if (typeof document !== "undefined") {
        document.removeEventListener("visibilitychange", наСобытие);
        document.removeEventListener("freeze", наЗаморозку);
        document.removeEventListener("resume", наПробуждение);
      }
      послать({ тип: "ухожу", id: я });
      канал?.close();
      канал = null;
    },
  };
}

let выборы: Выборы | null = null;

/**
 * Выборы на всё приложение. Ленивые: первое же уведомление их поднимет, но
 * `initPlatform` заводит их раньше — чтобы к первому событию вкладки уже
 * познакомились и первое уведомление не показали две сразу.
 */
export function этаВкладкаОповещает(): boolean {
  выборы ??= создатьВыборы();
  return выборы.оповещает();
}

/** Поднять выборы заранее; возвращает отписку для `teardown` платформы. */
export function запуститьВыборы(): () => void {
  выборы ??= создатьВыборы();
  return () => __сброситьВыборы();
}

/** Только для тестов: закрыть канал и забыть соседей. */
export function __сброситьВыборы(): void {
  выборы?.остановить();
  выборы = null;
}
