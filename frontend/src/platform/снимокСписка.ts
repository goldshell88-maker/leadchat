import type { ConversationTab } from "@/shared/api/queryKeys";
import { BUILD_VERSION } from "./buildVersion";
import type { ConversationDto, TabCounts } from "@/shared/api/types";

/**
 * Снимок списка диалогов для ВЕБА поверх IndexedDB — веб-двойник десктопного
 * SQLite-кэша (04 §5.4 шаг 1).
 *
 * ЗАЧЕМ. В десктопе `warmupFromCache` кладёт до 200 строк в кэш TanStack ещё до
 * первого ответа сервера; в вебе `convCache.warmup()` возвращал null, и человек
 * на КАЖДОМ открытии вкладки видел скелет, пока идёт `GET /conversations`
 * (замер 06.09: p50 39 мс, p95 114 мс сервера плюс ~120 мс круга офисного
 * канала). У диспетчера 11–13 вкладок за смену — этот скелет он видит
 * десятки раз в день, и всё это время экран не говорит ничего.
 *
 * Снимок — проекция сервера ТОЛЬКО ДЛЯ ЧТЕНИЯ: он кладётся в кэш протухшим
 * (`updatedAt: 0`), поэтому первый же ответ API его перезаписывает. Ни одного
 * лишнего запроса снимок не добавляет — он лишь заполняет первый кадр тем, что
 * и так будет запрошено.
 *
 * Проводка та же, что у десктопа: `installCachePersist` → `convCache.persist`
 * на запись, `warmupFromCache` → `convCache.warmup` на чтение. Второго пути
 * записи здесь нет намеренно — разъехавшиеся пути дают два разных ответа на
 * один вопрос (класс дефекта «два пути считают одно поле по-разному»).
 */

const БАЗА = "leadchat";
const ВЕРСИЯ = 1;
const ХРАНИЛИЩЕ = "снимок-списка";
/** Запись всегда одна: снимок — это «последнее, что человек видел», а не история. */
const КЛЮЧ = "текущий";

/** CACHE_DIALOGS из 04 §5.1 — тот же потолок, что у десктопа. */
export const МАКС_СТРОК = 200;

/**
 * Потолок на размер снимка.
 *
 * 200 строк весят 50–100 КБ, и порог взят с пятикратным запасом: он ловит не
 * норму, а вырождение — диалог с гигантским текстом последнего сообщения,
 * который иначе рос бы вместе с перепиской. Считаем в ЗНАКАХ (`JSON.stringify`
 * возвращает UTF-16), а не в байтах: точная мера здесь не нужна, нужен
 * заведомый верхний край.
 */
export const МАКС_ЗНАКОВ = 512_000;

/**
 * Сколько снимок годен — ДВЕНАДЦАТЬ ЧАСОВ. Порог выбран рассуждением, не замером.
 *
 * Внутри смены и через перезагрузку вкладки снимок всегда свежий, и ради этого
 * он и заводится. А после ночи он ЛЖЁТ: клиенты Авито пишут круглосуточно,
 * за ночь очередь оборачивается целиком — вчерашние вечерние диалоги закрыты,
 * взяты ночной сменой или переданы. Показать их как сегодняшний список значит
 * дать человеку кликнуть по чужому диалогу и увидеть, как список под пальцем
 * перерисовывается ответом сервера. Пустой список честнее: он не обещает ничего.
 *
 * Двенадцать часов = вечер (21:00) → утро (09:00). Дольше — уже «не работал
 * сутки», и там снимок вреден.
 */
export const СРОК_ГОДНОСТИ_МС = 12 * 60 * 60 * 1000;

/**
 * Дедлайн чтения при старте.
 *
 * ⚠ БЕЗ НЕГО МОЛЧАЩАЯ БАЗА = СКЕЛЕТ НАВСЕГДА. `warmupFromCache` ждут внутри
 * `sessionStore.bootstrap()`, а до конца bootstrap на экране висит скелет
 * оболочки — ровно тот довод, по которому в `http.ts` стоит потолок на
 * `POST /auth/refresh`. `indexedDB.open` умеет не отвечать вовсе: соседняя
 * вкладка держит базу прошлой версии (`onblocked`), профиль повреждён, диск
 * занят. Снимок — ускорение, и ускорение, которое умеет подвесить старт,
 * не имеет права существовать.
 *
 * 300 мс: чтение одной записи стоит единицы миллисекунд, и всё, что дольше,
 * уже проиграло тому самому серверу, ради опережения которого снимок и живёт.
 */
export const ДЕДЛАЙН_ЧТЕНИЯ_МС = 300;

/**
 * Что лежит в базе.
 *
 * `ownerId` отвечает на «чей это список»: компьютер сменный, за одним столом
 * работает смена, и чужой список на своём экране — это чужая переписка.
 *
 * ⚠ `build` — ВЕРСИЯ СБОРКИ, И БЕЗ НЕЁ СНИМОК ПЕРЕЖИВАЕТ ВЫКАТКУ (найдено
 * ревью 07.09). Срок годности 12 часов длиннее промежутка между выкатками, а
 * `разобрать` проверяет только `id` строки — значит на следующее утро после
 * любой выкатки, сменившей форму строки списка, первый кадр у КАЖДОГО из
 * тринадцати человек рисовался бы строками предыдущей сборки. Это не редкий
 * край, это все и каждый день после выкатки. `ВЕРСИЯ` ниже — версия схемы
 * IndexedDB, она от переименования поля в DTO не поднимется.
 *
 * ⚠ ПОЛЯ `role` ЗДЕСЬ БОЛЬШЕ НЕТ. Комментарий обещал, что оно даёт вкладку по
 * умолчанию, — неправда: вкладку берёт живой стор сессии
 * (`warmup.ts::defaultTabForRole(user?.role)`), а записанное в снимок значение
 * не читал никто. Диверсия ревьюера подменила его на «наблюдателя» — ни один
 * сторож не покраснел.
 */
export interface ЗаписьСнимка {
  ownerId: string;
  /** Версия сборки, которая снимок положила (`BUILD_VERSION`). */
  build: string;
  /** Вкладка, на которой снимок собран, — для понимания, чем он был. */
  tab: ConversationTab;
  dialogs: ConversationDto[];
  /** Числа над вкладкой «Мои»; null — сервер их ещё не присылал. */
  counts: TabCounts | null;
  savedAt: string;
}

/**
 * Открыть базу.
 *
 * Любой отказ означает «как раньше», а не ошибку на экране: приватное окно,
 * запрет хранилища политикой, переполненный диск, повреждённый профиль. Ни один
 * из этих случаев не мешает работать — он лишь возвращает веб к прежнему
 * поведению «скелет до ответа сервера».
 */
function открыть(): Promise<IDBDatabase | null> {
  return new Promise((resolve) => {
    try {
      if (typeof indexedDB === "undefined" || indexedDB === null) {
        resolve(null);
        return;
      }
      const req = indexedDB.open(БАЗА, ВЕРСИЯ);
      req.onupgradeneeded = () => {
        const db = req.result;
        if (!db.objectStoreNames.contains(ХРАНИЛИЩЕ)) db.createObjectStore(ХРАНИЛИЩЕ);
      };
      req.onsuccess = () => resolve(req.result);
      req.onerror = () => resolve(null);
      // Соседняя вкладка держит прошлую версию: ждать её мы не вправе (см. дедлайн).
      req.onblocked = () => resolve(null);
    } catch {
      // Firefox в приватном окне бросает синхронно прямо из open().
      resolve(null);
    }
  });
}

/** Обещание с потолком ожидания: не ответили за срок — работаем без снимка. */
function сДедлайном<T>(работа: Promise<T>, мс: number, запасной: T): Promise<T> {
  return new Promise((resolve) => {
    const таймер = setTimeout(() => resolve(запасной), мс);
    const конец = (v: T) => {
      clearTimeout(таймер);
      resolve(v);
    };
    работа.then(конец, () => конец(запасной));
  });
}

/**
 * Строка из хранилища — это ДАННЫЕ, а не обещание. Её мог записать прошлый
 * выпуск фронта (поля переименованы, `role` ещё не было), её мог испортить
 * оборванный сеанс. Пропускаем только то, на что можно опереться.
 */
function разобрать(сырое: unknown): ЗаписьСнимка | null {
  if (!сырое || typeof сырое !== "object") return null;
  const з = сырое as Partial<ЗаписьСнимка>;
  if (typeof з.ownerId !== "string" || з.ownerId.length === 0) return null;
  if (typeof з.build !== "string") return null;
  if (typeof з.savedAt !== "string") return null;
  if (!Array.isArray(з.dialogs) || з.dialogs.length === 0) return null;
  const годные = з.dialogs.filter((d): d is ConversationDto => Boolean(d && typeof d.id === "string"));
  if (годные.length === 0) return null;
  return {
    ownerId: з.ownerId,
    build: з.build,
    tab: typeof з.tab === "string" ? з.tab : "all",
    dialogs: годные,
    counts: з.counts ?? null,
    savedAt: з.savedAt,
  };
}

async function достатьЗапись(): Promise<unknown> {
  const db = await открыть();
  if (!db) return null;
  try {
    return await new Promise<unknown>((resolve) => {
      const tx = db.transaction(ХРАНИЛИЩЕ, "readonly");
      const req = tx.objectStore(ХРАНИЛИЩЕ).get(КЛЮЧ);
      req.onsuccess = () => resolve(req.result ?? null);
      req.onerror = () => resolve(null);
      tx.onabort = () => resolve(null);
    });
  } catch {
    // Хранилища нет (база создана прошлой версией без него) — снимка тоже нет.
    return null;
  } finally {
    db.close();
  }
}

/**
 * Прочитать снимок. Возвращает null и когда базы нет, и когда снимок протух:
 * оба случая для вызывающего одинаковы — рисовать нечего.
 *
 * Проверка «чей снимок» здесь НЕ делается: текущего пользователя знает
 * `warmupFromCache`, и держать это знание в двух местах значит завести второй
 * ответ на тот же вопрос.
 */
export async function прочитатьСнимок(сейчас: number = Date.now()): Promise<ЗаписьСнимка | null> {
  const сырое = await сДедлайном<unknown>(достатьЗапись(), ДЕДЛАЙН_ЧТЕНИЯ_МС, null);
  const запись = разобрать(сырое);
  if (!запись) return null;
  const возраст = сейчас - Date.parse(запись.savedAt);
  // NaN (мусор вместо даты) даёт false у обоих сравнений — такую запись не показываем.
  if (!(возраст >= 0 && возраст <= СРОК_ГОДНОСТИ_МС)) return null;
  /*
   * ⚠ ЧУЖАЯ СБОРКА — ЧУЖАЯ ФОРМА СТРОКИ. Срок годности (12 ч) длиннее
   * промежутка между выкатками, а разбор проверяет только `id`: без этой
   * строки первый кадр после каждой выкатки рисовался бы строками предыдущей
   * сборки — у всех тринадцати человек.
   *
   * Сравнение простое равенство, а не «непустое и равное»: в бою версия есть
   * всегда (её подставляет сборка), а в разработке и тестах её нет ни у кого —
   * и пустая равна пустой, то есть снимок своей же сборки читается. Требуй мы
   * непустоты, снимок в разработке не работал бы никогда и до боя доехал бы
   * непроверенным.
   */
  if (запись.build !== BUILD_VERSION) return null;
  return запись;
}

/** Подрезать снимок до потолков: сначала строки, потом размер. */
export function подрезать(dialogs: ConversationDto[]): ConversationDto[] {
  let строки = dialogs.slice(0, МАКС_СТРОК);
  // Половинным делением, а не по одной: восемь замеров вместо двухсот, и они
  // идут на КАЖДУЮ запись снимка.
  while (строки.length > 1 && JSON.stringify(строки).length > МАКС_ЗНАКОВ) {
    строки = строки.slice(0, Math.floor(строки.length / 2));
  }
  return строки;
}

export async function сохранитьСнимок(запись: ЗаписьСнимка): Promise<void> {
  const dialogs = подрезать(запись.dialogs);
  if (dialogs.length === 0) return;
  const db = await открыть();
  if (!db) return;
  try {
    await new Promise<void>((resolve) => {
      const tx = db.transaction(ХРАНИЛИЩЕ, "readwrite");
      tx.objectStore(ХРАНИЛИЩЕ).put({ ...запись, dialogs }, КЛЮЧ);
      tx.oncomplete = () => resolve();
      tx.onerror = () => resolve();
      // Кончилось место — снимок просто не обновится, работать это не мешает.
      tx.onabort = () => resolve();
    });
  } catch {
    // Хранилища нет — писать некуда; следующее открытие вкладки создаст базу.
  } finally {
    db.close();
  }
}

/**
 * Стереть снимок.
 *
 * ⚠ ЗОВЁТСЯ ПРИ ВЫХОДЕ И ПРИ ОТЗЫВЕ СЕССИИ (`sessionStore.wipeLocalCache`).
 * Тот же довод, что у десктопного `cache_clear`: за одним столом работает
 * смена, и список диалогов ушедшего — это его переписка, а не общее имущество.
 * Проверка `ownerId` при чтении — второй замок, а не замена этому.
 */
export async function стеретьСнимок(): Promise<void> {
  const db = await открыть();
  if (!db) return;
  try {
    await new Promise<void>((resolve) => {
      const tx = db.transaction(ХРАНИЛИЩЕ, "readwrite");
      tx.objectStore(ХРАНИЛИЩЕ).delete(КЛЮЧ);
      tx.oncomplete = () => resolve();
      tx.onerror = () => resolve();
      tx.onabort = () => resolve();
    });
  } catch {
    // Хранилища нет — стирать нечего.
  } finally {
    db.close();
  }
}
