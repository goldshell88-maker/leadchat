import { isTauri, type NotifyRequest } from "./bridge";

/**
 * Веб-сторона сервис-воркера (`public/sw.js`, 07.09): показ уведомления с
 * кнопками и приём нажатия обратно во вкладку.
 *
 * Модуль намеренно тонкий и знает ровно три вещи, потому что решение «показывать
 * ли и что» принимает веб-мост, а «что делать с нажатием» — платформенный слой.
 * Здесь только то, чего ни тот ни другой сделать не могут: разговор с воркером.
 *
 * ⚠ ОТКАЗ ЛЮБОГО ШАГА — НЕ АВАРИЯ. Воркер может не встать (старый браузер,
 * приватное окно, запрет политикой домена, наш же промах в конфиге nginx), и
 * тогда уведомления показываются по-старому, без кнопок. Поэтому каждая функция
 * здесь возвращает «не смог» вместо исключения: уведомления — удобство, а не
 * условие работы, и ронять из-за них рабочее место нельзя.
 */

/** Регистрируем по корню: воркер должен видеть все вкладки приложения. */
const ПУТЬ_ВОРКЕРА = "/sw.js";

/** Иконка — та, что реально лежит в public/ (в вебе других картинок нет). */
const ИКОНКА = "/favicon.svg";

/** Метка отправителя, обязана совпадать с `КАНАЛ` в `public/sw.js`. */
const КАНАЛ = "leadchat-sw";

type Кнопка = { action: string; title: string };

/**
 * ⚠ ВРЕМЕННЫЙ МОСТ К ОБЩЕМУ СТЫКУ. Поля склейки (`tag`, `requireInteraction`,
 * `actions`) по договорённости 07.09 живут в самом `NotifyRequest`, но
 * дописывает их веб-мост — соседний файл, который правит другой человек.
 * Пересечение ниже держит этот модуль собираемым при любом порядке выкладки и
 * обнуляется само, как только поля приедут: типы у них те же.
 */
type ЗапросПоказа = NotifyRequest & {
  tag?: string;
  requireInteraction?: boolean;
  actions?: Кнопка[];
};

/**
 * ⚠ КНОПОК НЕТ В ТИПАХ БРАУЗЕРА, И ЭТО НЕ ПРОБЕЛ TypeScript. `NotificationOptions`
 * в lib.dom описывает `new Notification`, у которого кнопок не бывает вовсе;
 * `actions` существует только у `registration.showNotification`. Стандарт
 * разделяет их намеренно, типы следом. Отсюда собственный тип с одним лишним
 * полем — вместо `any` на весь вызов.
 */
interface ОпцииСКнопками extends NotificationOptions {
  actions?: Кнопка[];
}

let регистрация: ServiceWorkerRegistration | null = null;

/**
 * Поставить воркер. Возвращает регистрацию либо null — «работаем без него».
 *
 * Повторный вызов безопасен: браузер по одной паре (адрес скрипта, область)
 * возвращает уже существующую регистрацию, а не ставит вторую.
 */
export async function включитьВоркер(): Promise<ServiceWorkerRegistration | null> {
  /*
   * ⚠ ТОЛЬКО ВЕБ. У десктопной сборки свой мост уведомлений (`platform/tauri`),
   * и тосты там рисует Rust через Action Center — с кнопкой «Ответить», которой
   * в браузере не бывает. Поставить сюда ещё и воркер значило бы показывать по
   * два уведомления на одно событие: сборка одна и та же, отличает её только
   * этот признак.
   */
  if (isTauri()) return null;
  // Ни navigator, ни serviceWorker не гарантированы: их нет в тестовой среде,
  // нет в небезопасном контексте (http без localhost) и нет в приватном окне
  // части браузеров.
  if (typeof navigator === "undefined" || !("serviceWorker" in navigator)) return null;

  try {
    регистрация = await navigator.serviceWorker.register(ПУТЬ_ВОРКЕРА);
    return регистрация;
  } catch (e) {
    /*
     * ⚠ САМЫЙ ВЕРОЯТНЫЙ ОТКАЗ — НАШ СОБСТВЕННЫЙ, И ОН МОЛЧАЛИВЫЙ. Браузер не
     * регистрирует воркер, отданный с чужим Content-Type, а до 07.09 /sw.js
     * попадал под SPA-fallback nginx и приезжал как text/html (проверено
     * curl'ом на бою: 200, text/html, 14 103 байта — это index.html). Отдельный
     * `location = /sw.js` в шаблоне лечит именно это, а здесь остаётся честная
     * запись в консоль: приложение живёт, кнопок в уведомлении нет.
     */
    console.warn("[sw] воркер не зарегистрирован — уведомления останутся без кнопок:", e);
    return null;
  }
}

/**
 * Показать уведомление через воркер. `false` — воркера нет, показывай сам.
 *
 * Судим по регистрации, полученной `включитьВоркер`, и НЕ ждём
 * `navigator.serviceWorker.ready`: это обещание не отклоняется никогда, и на
 * машине без воркера ожидание висело бы вечно — а уведомление нужно сейчас.
 */
export async function показатьЧерезВоркер(n: NotifyRequest): Promise<boolean> {
  if (!регистрация) return false;

  const з = n as ЗапросПоказа;
  const опции: ОпцииСКнопками = {
    body: з.body,
    icon: ИКОНКА,
    /*
     * Ключ склейки. Браузер заменяет прежнее уведомление с тем же тегом вместо
     * того, чтобы класть рядом второе.
     *
     * ⚠ БЕЗ НЕГО ВКЛЮЧЕНИЕ РАЗРЕШЕНИЯ ДАЁТ ЛАВИНУ. В бою 05.09 за сутки 1357
     * новых диалогов и 625 возвратов — около двух тысяч постановок в очередь, и
     * каждая видна 30–33 операторам канала. Каждая СКРЫТАЯ вкладка человека
     * показала бы своё уведомление на каждое из них.
     *
     * `renotify` намеренно не ставим: с ним замена звенит заново, то есть
     * склейка гасит только картинку, но не шум. Звук у нас и так свой, во
     * вкладке.
     */
    tag: з.tag,
    // Не гасить само — для передачи диалога: 119 предложений за 30 дней, редко
    // и дорого, пропустить нельзя.
    requireInteraction: з.requireInteraction,
    silent: з.silent,
    actions: з.actions,
    // Воркер живёт отдельно от вкладки и её состояния не видит: адрес возврата
    // надо положить в само уведомление.
    data: { conversationId: з.conversationId ?? null },
  };

  try {
    await регистрация.showNotification(з.title, опции);
    return true;
  } catch (e) {
    /*
     * Штатный случай, а не поломка: регистрация уже есть, а рабочий экземпляр
     * воркера ещё ставится — показ в эти первые миллисекунды отклоняется.
     * Отвечаем «не смог», и мост покажет обычное уведомление без кнопок.
     */
    console.warn("[sw] показ через воркер не удался, показываем обычным способом:", e);
    return false;
  }
}

/**
 * Закрыть показанные уведомления с этим тегом. Нужно карточке передачи: она
 * висит до нажатия, а решение могли принять в самом приложении или с другого
 * устройства — тогда её кнопки уже ничего не делают.
 */
export async function закрытьПоТегу(tag: string): Promise<void> {
  if (!регистрация) return;
  try {
    for (const n of await регистрация.getNotifications({ tag })) n.close();
  } catch (e) {
    console.warn("[sw] не удалось закрыть уведомление:", e);
  }
}

/** Подписаться на нажатие в уведомлении. Возвращает отписку. */
export function приДействииИзУведомления(
  cb: (a: { action: string; conversationId: string | null }) => void,
): () => void {
  if (typeof navigator === "undefined" || !("serviceWorker" in navigator)) return () => {};

  const слушатель = (e: MessageEvent) => {
    const письмо = e.data as { source?: unknown; action?: unknown; conversationId?: unknown } | null;
    // Отбор по метке — договор с `public/sw.js`, а не перестраховка: этим же
    // каналом пользуются чужие библиотеки, и чужое письмо разбирать нечем.
    if (!письмо || письмо.source !== КАНАЛ) return;
    cb({
      action: typeof письмо.action === "string" ? письмо.action : "open",
      conversationId: typeof письмо.conversationId === "string" ? письмо.conversationId : null,
    });
  };

  navigator.serviceWorker.addEventListener("message", слушатель);
  return () => navigator.serviceWorker.removeEventListener("message", слушатель);
}
