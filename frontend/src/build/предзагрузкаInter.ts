import type { Plugin } from "vite";

/**
 * Два подмножества Inter, которые браузер скачивает НА САМОМ ДЕЛЕ.
 *
 * `@fontsource-variable/inter/wght.css` объявляет семь `@font-face`, но
 * `unicode-range` оставляет от них два: латиницу и кириллицу (main.tsx).
 * Расширенные (`latin-ext`, `cyrillic-ext`) в интерфейсе не встречаются — за
 * ними одними 111 КБ, и предзагрузить их значило бы отнять полосу у того, что
 * человек действительно увидит.
 */
const ПОДМНОЖЕСТВА_INTER = ["cyrillic", "latin"] as const;

/**
 * Предзагрузка шрифта интерфейса (замер 06.09).
 *
 * ЧТО БЫЛО. Про шрифт браузер узнаёт только из `@font-face` — то есть после
 * того, как скачает и разберёт обязательный CSS (296 КБ сырых). До этого текст
 * рисуется подстановкой (`font-display: swap`), а потом перерисовывается
 * настоящим: у команды на Windows подмена идёт на Segoe UI с другими
 * метриками, то есть перерисовывается не только начертание, но и ширины.
 *
 * ЧТО ЗДЕСЬ. Оба нужных файла названы прямо в разметке, и браузер начинает их
 * качать вместе с CSS, а не после него. Байты те же самые: эти два подмножества
 * скачиваются в любом случае, меняется только очерёдность.
 *
 * ⚠ ПОЧЕМУ ХУКОМ, А НЕ СТРОКОЙ В index.html. Имена файлов содержат хеш
 * содержимого и меняются от сборки к сборке. Вписанное руками имя пережило бы
 * ровно одно обновление шрифта, после чего браузер молча качал бы мимо кэша
 * файл, которого нет, — и предзагрузка превратилась бы в лишний 404.
 *
 * Кириллица идёт первой: интерфейс русский, и первым нужным глифом будет её.
 */
export function предзагрузитьInter(): Plugin {
  let base = "/";

  return {
    name: "lc-preload-inter",
    // В dev шрифт отдаётся из node_modules без хеша и без конкуренции за
    // полосу — предзагружать там нечего.
    apply: "build",
    configResolved(config) {
      base = config.base;
    },
    transformIndexHtml: {
      order: "post",
      handler(html, ctx) {
        // Собранных имён нет — значит это не сборка (dev-сервер, вызов из теста).
        if (!ctx.bundle) return html;

        const файлы = ПОДМНОЖЕСТВА_INTER.map((подмножество) => {
          const маска = new RegExp(`(^|/)inter-${подмножество}-wght-normal-[\\w-]+\\.woff2$`);
          const найдено = Object.keys(ctx.bundle!).filter((имя) => маска.test(имя));
          /*
            Молчать здесь нельзя: пропавший файл означает, что шрифт сменили
            или подключили иначе, — и предзагрузка тихо перестала бы работать,
            оставив в разметке правдоподобную пустоту. Пусть падает сборка.
          */
          if (найдено.length !== 1) {
            throw new Error(
              `lc-preload-inter: подмножество ${подмножество} не найдено в сборке ` +
                `(совпадений ${найдено.length}). Шрифт заменили или перестали импортировать ` +
                `@fontsource-variable/inter/wght.css в src/main.tsx?`,
            );
          }
          return найдено[0];
        });

        return {
          html,
          tags: файлы.map((файл) => ({
            tag: "link",
            attrs: {
              rel: "preload",
              as: "font",
              type: "font/woff2",
              // Без crossorigin браузер скачал бы файл дважды: шрифты идут
              // анонимным CORS-запросом, и предзагрузка без него не совпадает
              // с настоящей загрузкой по ключу кэша.
              crossorigin: "",
              href: base + файл,
            },
            injectTo: "head" as const,
          })),
        };
      },
    },
  };
}

