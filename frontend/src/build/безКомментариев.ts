import type { Plugin } from "vite";

/**
 * Комментарии разметки не уезжают в браузер (просьба владельца 08.09).
 *
 * ЧТО БЫЛО. `index.html` объясняет сам себя подробно: почему тема ставится до
 * первой отрисовки, почему встроенный скрипт синхронный, откуда берётся ширина
 * рельсы у каркаса, почему классы именно те. Всё это — доводы для того, кто
 * будет править файл, и в репозитории им место. Но Vite копирует разметку как
 * есть, и каждый человек, открывший исходный код страницы, получал полтора
 * десятка абзацев внутренней переписки: пути к файлам, имена сторожей,
 * ссылки на разборы.
 *
 * Владелец, открыв «просмотр кода», назвал это «мусорными надписями» — и по
 * делу: странице они не нужны, а весят и рассказывают лишнее.
 *
 * ⚠ УДАЛЯЕМ В СБОРКЕ, А НЕ В ИСХОДНИКЕ. Соблазн стереть их в самом
 * `index.html` велик и дёшев, но тогда следующий человек, правящий встроенный
 * скрипт, не узнает ни про хеш CSP, ни про то, почему скрипт синхронный, —
 * и снимет то, на чём держится отсутствие вспышки чужой темы. Комментарий
 * дороже байтов, которые он стоит, — но только там, где его читают.
 *
 * ⚠ ЧТО ЗДЕСЬ НЕ ТРОГАЕТСЯ, И ЭТО ВАЖНЕЕ САМОЙ ПРАВКИ. Встроенный скрипт
 * разрешён в CSP ПО ХЕШУ СОДЕРЖИМОГО (`security-headers.conf`, сторож
 * `CspInlineHash0109`). Изменись он на один пробел — браузер откажется его
 * выполнять, и у всех вернётся вспышка чужой темы. Поэтому убираются только
 * комментарии РАЗМЕТКИ (`<!-- … -->`), а содержимое `<script>` и `<style>`
 * не разбирается вовсе: внутри них такой последовательности нет.
 */
const КОММЕНТАРИЙ = /<!--(?!\[if)[\s\S]*?-->/g;

/**
 * Встроенные стили тоже объясняют себя — и тоже уезжают в браузер целиком.
 *
 * ⚠ ИХ СНИМАТЬ БЕЗОПАСНО, А СКРИПТ — НЕТ, И РАЗНИЦА ПРИНЦИПИАЛЬНАЯ.
 * `style-src` разрешает встроенные стили целиком (`'unsafe-inline'`), поэтому
 * содержимое стилей ничем не подписано и правится свободно. Скрипт же
 * разрешён ПО ХЕШУ: тронь его хоть на пробел — браузер откажется его
 * выполнять, и у всех вернётся вспышка чужой темы. Поэтому комментарии из
 * скрипта вынесены в разметку руками (см. index.html), а не снимаются здесь.
 */
const СТИЛЬ = /(<style[^>]*>)([\s\S]*?)(<\/style>)/gi;
const CSS_КОММЕНТАРИЙ = /\/\*[\s\S]*?\*\//g;

export function безКомментариев(): Plugin {
  return {
    name: "leadchat-без-комментариев",
    // `apply: "build"` — в разработке комментарии остаются: там их и читают,
    // открыв исходник страницы рядом с редактором.
    apply: "build",
    transformIndexHtml: {
      order: "post",
      handler(html) {
        return html
          .replace(КОММЕНТАРИЙ, "")
          .replace(СТИЛЬ, (_, открыл, тело, закрыл) =>
            открыл + тело.replace(CSS_КОММЕНТАРИЙ, "").replace(/\n{3,}/g, "\n\n") + закрыл,
          )
          .replace(/\n{3,}/g, "\n\n");
      },
    },
  };
}
