/// <reference types="vitest/config" />
import { defineConfig, loadEnv } from "vite";
import react from "@vitejs/plugin-react";

/*
 * Плагин лежит отдельным файлом, а не здесь, ради проверки: импорт самого
 * `vite.config.ts` тащит в прогон esbuild, а он в jsdom не заводится
 * («TextEncoder ... incorrectly false»). Отдельный модуль берёт из vite
 * только тип, то есть в рантайм не приносит ничего.
 */
import { предзагрузитьInter } from "./src/build/предзагрузкаInter";
import { безКомментариев } from "./src/build/безКомментариев";

/**
 * Per docs/03-FRONTEND.md: alias "@" -> /src, dev proxy /api -> FastAPI on :8000 (ws for future WS hub).
 *
 * Режим `desktop` (04 §1.1) — ТОТ ЖЕ бандл, отличий ровно два:
 *  - VITE_API_BASE абсолютный: origin в Tauri — `tauri://localhost`, относительный /api туда не ходит;
 *  - VITE_IS_DESKTOP=1 — флаг десктоп-сборки для платформенного слоя.
 * Ничего Tauri-специфичного в конфиг не добавляется: пакеты `@tauri-apps/*` фронт
 * не импортирует вовсе (см. src/platform/tauri/ipc.ts) — веб-бандл чист по построению,
 * а сам платформенный чанк подключается динамическим импортом (03 §7).
 */
const DESKTOP_API_BASE = "https://chat.partner-lead-centre.ru";

export default defineConfig(({ mode }) => {
  const isDesktop = mode === "desktop";
  // envDir "." — корень фронта; @types/node в проекте нет, поэтому без process.cwd().
  const env = loadEnv(mode, ".", "VITE_");

  return {
    plugins: [react(), предзагрузитьInter(), безКомментариев()],
    resolve: { alias: { "@": "/src" } },
    server: {
      proxy: {
        "/api": { target: "http://localhost:8000", ws: true },
      },
    },
    build: {
      target: "es2022",
      /*
       * ⚠ КАРТЫ КОДА НЕ СОБИРАЕМ: ИХ НЕ ЧИТАЕТ НИКТО (чистка 08.09).
       *
       * Стояло `true`, и сборка клала рядом с каждым файлом карту — сорок
       * файлов, около семи мегабайт, которые пеклись в образ и уезжали на
       * сервер. Наружу они не отдаются: nginx отвечает на `/assets/*.map`
       * четырёхсотчетвёркой (`leadchat.conf.template`). Комментарий там же
       * объяснял это так: «они уезжают в Sentry из CI» — и вот это оказалось
       * неправдой. Ни в `.github/workflows`, ни в Dockerfile, ни в скриптах
       * `deploy/` нет ни одного вызова `sentry-cli`; карты не уезжают никуда.
       *
       * То есть сборка тратила время и место на файлы, которые нельзя
       * получить и некому прочитать. Появится загрузка в Sentry — вернуть
       * надо будет `"hidden"`: карты собираются, а хвост `sourceMappingURL`
       * в код не пишется (аудит 08.09, S-04).
       *
       * Разработку это не задевает: `vite dev` отдаёт карты всегда, мимо
       * этой настройки.
       */
      sourcemap: false,
      rollupOptions: {
        output: {
          /*
           * Ядро вынесено из главного файла отдельными частями.
           *
           * ЗАЧЕМ. Главный файл весил 691 КБ (218 КБ сжатых) — это всё, что
           * браузер обязан скачать и разобрать ДО первой отрисовки. Экраны
           * уже загружаются по мере надобности (редактор ботов, статистика,
           * распределение), но библиотека интерфейса и графики лежали в
           * общей куче вместе с нашим кодом.
           *
           * Дело не только в объёме. Наш код меняется каждый день, а Mantine
           * и React — раз в несколько месяцев. Лежа в одном файле, они
           * пересобираются вместе: любая правка кнопки заставляет команду
           * заново качать всю библиотеку. Разделив их, мы отдаём браузеру
           * возможность держать неизменную часть в кэше — со второго дня
           * работы человек скачивает только то, что мы действительно
           * изменили.
           *
           * Дробить мельче смысла нет: каждая часть — отдельный запрос, и на
           * плохой связи десять мелких файлов хуже двух крупных.
           */
          manualChunks: {
            react: ["react", "react-dom", "react-router-dom"],
            // ⚠ БЕЗ "@mantine/dates", И ЭТО ЗАМЕР, А НЕ ВКУС. Календарь нужен
            // четырём ЛЕНИВЫМ экранам (статистика, лиды, распределение, лид-бот),
            // а список выше затаскивал его вместе с dayjs в общий чанк, который
            // грузится всем и сразу: 50 902 сырых, 14 504 сжатых байта на первом
            // открытии у человека, который в статистику не заходит. Rollup сам
            // соберёт для этих четырёх общий кусок.
            mantine: ["@mantine/core", "@mantine/hooks", "@mantine/notifications"],
            data: ["@tanstack/react-query", "@tanstack/react-virtual", "zustand"],
          },
        },
      },
    },
    // define — только для десктоп-сборки; веб и тесты остаются нетронутыми.
    ...(isDesktop
      ? {
          define: {
            "import.meta.env.VITE_API_BASE": JSON.stringify(env.VITE_API_BASE || DESKTOP_API_BASE),
            "import.meta.env.VITE_IS_DESKTOP": JSON.stringify("1"),
          },
        }
      : null),
    test: {
      environment: "jsdom",
      setupFiles: ["./src/test/setup.ts"],
      css: false,
      // Ожидание одной проверки — с запасом над `asyncUtilTimeout` (5 с, см.
      // src/test/setup.ts): тест, который честно ждёт пять секунд, не должен
      // упасть по СВОЕМУ таймауту раньше, чем по ожиданию элемента. Иначе
      // отказ выглядит как «тест завис», а не «элемент не появился».
      testTimeout: 15_000,
    },
  };
});
